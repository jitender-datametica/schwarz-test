CREATE OR REPLACE VIEW FE_MSTR_NFMD.MV_ID30_LATEST_WB AS
SELECT YEAR_ID,
       WEEK_ID,
       MANDANT_ID,
       AKTION_ID,
       SKU_ID,
       NULL       AS INITAL_DECISON_DATE,  -- Deprecated, will be removed
       CREATED_AT AS UPDATED_DATE,
       MARKDOWN_DECISION
FROM CORE.TS_ID30_MSI_INSERTS
    QUALIFY RANK() OVER (PARTITION BY YEAR_ID, WEEK_ID, MANDANT_ID, AKTION_ID, SKU_ID ORDER BY CREATED_AT DESC) = 1;