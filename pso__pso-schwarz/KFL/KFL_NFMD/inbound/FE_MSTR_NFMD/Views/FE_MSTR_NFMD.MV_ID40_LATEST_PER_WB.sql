CREATE OR REPLACE VIEW FE_MSTR_NFMD.MV_ID40_LATEST_PER_WB AS
WITH LATEST AS (
SELECT
	AKTION_ID,
	SKU_ID,
	WUP_ID,
	MIN(CREATED_AT) AS INITAL_DECISON_DATE,
	MAX(CREATED_AT) UPDATED_DATE
FROM
	CORE.TS_ID40_PERC_WBS
GROUP BY
	AKTION_ID,
	SKU_ID,
	WUP_ID)
SELECT
	DISTINCT YEAR_ID,
	WEEK_ID,
	MANDANT_ID,
	sc.AKTION_ID,
	sc.SKU_ID,
	sc.WUP_ID,
	INITAL_DECISON_DATE,
	UPDATED_DATE,
	MANUAL_MARKDOWN_PERCENTAGE,
	MANUAL_MARKDOWN_DATE
FROM
	CORE.TS_ID40_PERC_WBS sc
JOIN LATEST l ON
	(sc.AKTION_ID = l.AKTION_ID
	AND sc.SKU_ID = l.SKU_ID
	AND sc.WUP_ID = l.WUP_ID
	AND sc.CREATED_AT = l.UPDATED_DATE);
