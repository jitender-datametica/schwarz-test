CREATE OR REPLACE VIEW FE_MSTR_NFMD.MV_LATEST_ACTIVE_CLUSTER AS
SELECT MANDANT_ID, ARTICLE_CLUSTER_ID, TRUE AS CLUSTER_ACTIVE_FLAG
FROM CORE.TS_ACTIVE_ARTICE_CLUSTER_WBS
    QUALIFY RANK() OVER (PARTITION BY MANDANT_ID ORDER BY CREATED_AT DESC) = 1;