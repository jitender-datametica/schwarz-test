CREATE OR REPLACE PROCEDURE DBP_MACRO.M_SSM_WUP_PROZESS_WERBEVERTEILUNG
(
 P_MANDANT_ID NUMBER
,P_WUP_ID NUMBER
,P_NB_ID NUMBER
,P_SSM_PROZESS_ID NUMBER
,P_DAT VARCHAR
,P_WERT NUMBER
)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
MERGE INTO DBP_DATA.SSM_WUP_PROZESS_WERBEVERTEILUNG AS target
USING
(
 SELECT
  :P_MANDANT_ID	 			AS MANDANT_ID
 ,:P_WUP_ID 				AS WUP_ID
 ,:P_NB_ID 					AS NB_ID
 ,:P_SSM_PROZESS_ID 		AS SSM_PROZESS_ID
 ,:P_DAT 					AS DAT
 ,:P_WERT 					AS WERT
) AS source
  ON  target.MANDANT_ID 	= source.MANDANT_ID
  AND target.WUP_ID     	= source.WUP_ID
  AND target.NB_ID     		= source.NB_ID
  AND target.SSM_PROZESS_ID	= source.SSM_PROZESS_ID
  AND target.DAT			= source.DAT
	
WHEN MATCHED THEN UPDATE SET
target.WERT = source.WERT

WHEN NOT MATCHED THEN INSERT
(
  MANDANT_ID
 ,WUP_ID
 ,NB_ID 
 ,SSM_PROZESS_ID
 ,DAT
 ,WERT
)
VALUES
(
  source.MANDANT_ID
 ,source.WUP_ID
 ,source.NB_ID
 ,source.SSM_PROZESS_ID
 ,source.DAT
 ,source.WERT
);
COMMIT;
RETURN 'UPDATE/INSERT SUCCESSFUL';
END;
$$;