CREATE OR REPLACE PROCEDURE DBP_MACRO.M_UPS_TS_WBS_REFMARKT (
    P_MANDANT_ID FLOAT,
    P_WUP_ID FLOAT,
    P_NB_ID FLOAT,
    P_WUP_CONCAT_REF VARCHAR(50),
    P_REF_FAKTOR_FALLBACK FLOAT,
    P_WUP_VZ_CONCAT_FALLBACK VARCHAR(50),
    P_FIXAMOUNT_SHARE_ALG_500 FLOAT,
    P_FIXAMOUNT_SHARE_ALG_120 FLOAT,
    P_ESTIMATION_FG FLOAT,
    P_ADJUSTMENT_FG FLOAT)
RETURNS VARCHAR
LANGUAGE SQL
AS $$

DECLARE
dummy float;

BEGIN
        
-- Wenn Eintrag vorhanden loeschen 
    DELETE FROM DBP_MSI_DATA.TS_WBS_REFMARKT 
        WHERE MANDANT_ID = :P_MANDANT_ID 
            AND WUP_ID = :P_WUP_ID
            AND NB_ID = :P_NB_ID;

-- Eintrag einfügen 
    INSERT INTO DBP_MSI_DATA.TS_WBS_REFMARKT (MANDANT_ID, WUP_ID, NB_ID, WUP_ID_REF, NB_ID_REF, REF_FAKTOR_FALLBACK, MANDANT_ID_VZ_FALLBACK, WUP_ID_VZ_FALLBACK, NB_ID_VZ_FALLBACK, FIXAMOUNT_SHARE_ALG_500, FIXAMOUNT_SHARE_ALG_120, ESTIMATION_FG, ADJUSTMENT_ID)
        VALUES (:P_MANDANT_ID, :P_WUP_ID, :P_NB_ID, TO_NUMBER(SPLIT_PART(:P_WUP_CONCAT_REF,':',1)), TO_NUMBER(SPLIT_PART(:P_WUP_CONCAT_REF,':',2)), :P_REF_FAKTOR_FALLBACK, TO_NUMBER(SPLIT_PART(:P_WUP_VZ_CONCAT_FALLBACK,':',1)), TO_NUMBER(SPLIT_PART(:P_WUP_VZ_CONCAT_FALLBACK,':',2)), TO_NUMBER(SPLIT_PART(:P_WUP_VZ_CONCAT_FALLBACK,':',3)), :P_FIXAMOUNT_SHARE_ALG_500, :P_FIXAMOUNT_SHARE_ALG_120, :P_ESTIMATION_FG, :P_ADJUSTMENT_FG);
    COMMIT;
    RETURN 'Referenzmarkt gespeichert.';
END;
$$;