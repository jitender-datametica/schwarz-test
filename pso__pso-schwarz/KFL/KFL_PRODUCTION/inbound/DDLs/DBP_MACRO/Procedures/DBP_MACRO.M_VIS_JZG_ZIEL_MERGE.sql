CREATE OR REPLACE PROCEDURE DBP_MACRO.M_VIS_JZG_ZIEL_MERGE (
	P_MANDANT_ID NUMBER,
	P_NB_ID NUMBER,
	P_WUP_ID NUMBER,
	P_WRG_ID VARCHAR(3),
	P_GJ NUMBER,
	P_METRIK_ID NUMBER,
	P_TYP_ID NUMBER,
	P_LEVEL_ID NUMBER,
	P_WERT_EINGABE FLOAT,
	P_KOMMENTAR_EINGABE VARCHAR(16777216)
) 
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER /* OWNER does not work */ 
AS $$
  
DECLARE
	v_ergebnis VARCHAR DEFAULT 'Merge';
  
BEGIN
	MERGE INTO DBP_MSI_VIEW_VIS.TS_VIS_JZG_ZIEL_EINGABE trgt USING (
		SELECT
		  :P_MANDANT_ID AS MANDANT_ID
		, :P_NB_ID AS NB_ID
		, :P_WUP_ID AS WUP_ID
		, :P_WRG_ID AS WRG_ID
		, :P_GJ AS GJ 
		, :P_METRIK_ID AS METRIK_ID
		, :P_TYP_ID AS TYP_ID
		, :P_LEVEL_ID AS LEVEL_ID
		, :P_WERT_EINGABE AS WERT_EINGABE
		, :P_KOMMENTAR_EINGABE AS KOMMENTAR_EINGABE
	) srce
	ON  trgt.MANDANT_ID = srce.MANDANT_ID
	AND trgt.WUP_ID = srce.WUP_ID
	AND trgt.WRG_ID = srce.WRG_ID
	AND trgt.GJ = srce.GJ
	AND trgt.METRIK_ID = srce.METRIK_ID
	AND trgt.TYP_ID = srce.TYP_ID
	AND trgt.LEVEL_ID = srce.LEVEL_ID
  
	WHEN MATCHED THEN UPDATE 
		SET 
		  trgt.WERT_EINGABE = srce.WERT_EINGABE
		, trgt.KOMMENTAR_EINGABE = srce.KOMMENTAR_EINGABE
		, trgt.ZEITSTEMPEL = CURRENT_TIMESTAMP()
 
	WHEN NOT MATCHED THEN INSERT (
		  trgt.MANDANT_ID
		, trgt.NB_ID
		, trgt.WUP_ID
		, trgt.WRG_ID
		, trgt.GJ
		, trgt.METRIK_ID
		, trgt.TYP_ID
		, trgt.LEVEL_ID
		, trgt.WERT_EINGABE
		, trgt.KOMMENTAR_EINGABE
		, trgt.ZEITSTEMPEL
	)
	VALUES (
		  srce.MANDANT_ID
		, srce.NB_ID
		, srce.WUP_ID
		, srce.WRG_ID
		, srce.GJ
		, srce.METRIK_ID
		, srce.TYP_ID
		, srce.LEVEL_ID
		, COALESCE(srce.WERT_EINGABE, NULL)
		, COALESCE(srce.KOMMENTAR_EINGABE,'')
		, CURRENT_TIMESTAMP()
	);
COMMIT; 
  
v_ergebnis := 'JZG '  || v_ergebnis || ' done' ;
RETURN v_ergebnis; 
  
END;
$$;