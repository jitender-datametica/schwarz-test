CREATE OR REPLACE PROCEDURE DBP_MACRO.M_VIS_LEERGUT_WERT_EINGABE (
	P_MANDANT_ID NUMBER,
	P_WUP_ID NUMBER,
    P_NB_ID NUMBER,
	P_DAT VARCHAR,
    P_WRG_ID VARCHAR(3),
	P_BETRAG_LEERGUT_ZAEHLUNG FLOAT
) 
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER /* OWNER does not work */ 
AS $$ 

/*
	SQL MERGE Leergut :  TS Eingabe Zählung
	2025-03-20 muellerpatri : initiale Erstellung [AP0228745]
*/ 

DECLARE
	v_ergebnis VARCHAR DEFAULT 'Leergut merged'; 

BEGIN

MERGE INTO DBP_MSI_DATA.TS_WUP_DAT_LEERGUT trgt USING (
	SELECT :P_MANDANT_ID AS MANDANT_ID
		, :P_WUP_ID AS WUP_ID
        , :P_NB_ID AS NB_ID
        , :P_DAT AS DAT
		, :P_WRG_ID AS WRG_ID	
		, :P_BETRAG_LEERGUT_ZAEHLUNG AS BETRAG_LEERGUT_ZAEHLUNG
	) srce
	ON trgt.MANDANT_ID = srce.MANDANT_ID AND trgt.WUP_ID = srce.WUP_ID AND trgt.DAT = srce.DAT AND trgt.WRG_ID = srce.WRG_ID

WHEN MATCHED THEN UPDATE 
	SET trgt.BETRAG_LEERGUT_ZAEHLUNG = srce.BETRAG_LEERGUT_ZAEHLUNG
		, trgt.TD_UPDATE = CURRENT_TIMESTAMP() 

WHEN NOT MATCHED THEN INSERT (
	  trgt.MANDANT_ID
	, trgt.WUP_ID
    , trgt.NB_ID
    , trgt.DAT
	, trgt.WRG_ID	
	, trgt.BETRAG_LEERGUT_ZAEHLUNG
    , trgt.BETRAG_LEERGUT_INVENTUR
    , trgt.TD_UPDATE
    , trgt.TD_INSERT
	)
	VALUES (
	  srce.MANDANT_ID
	, srce.WUP_ID
    , srce.NB_ID
    , srce.DAT
	, srce.WRG_ID
	, COALESCE(srce.BETRAG_LEERGUT_ZAEHLUNG, NULL)
    , null
    , null
	, CURRENT_TIMESTAMP()
	); 

COMMIT; 

RETURN v_ergebnis; 

END;
$$;