CREATE OR REPLACE PROCEDURE DBP_MACRO.M_VIS_WUP
(
 P_MANDANT_ID NUMBER
,P_WUP_ID NUMBER
,P_DAT_VON VARCHAR
,P_DAT_EROEFFNUNG VARCHAR
,P_DAT_BIS VARCHAR
,P_UEBERNAHME_VON VARCHAR
,P_KUNDENFAKTOR NUMBER
,P_UMSATZ_EA_EUR NUMBER
,P_UMSATZ_EA_LAND NUMBER
,P_UMSATZ_ERWARTUNG_EUR NUMBER
,P_DAT_WIEDEREROEFFNUNG VARCHAR
,P_EINWOHNER_ANZAHL NUMBER
)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
 DECLARE
	SERV_NOT_UPDATED EXCEPTION(-20001,'NOT_UPDATED! DATUM VON/ ERFÖFFUNGSDATUM/ SCHLIßUNGSDATUM - AUSSER REICHWEITE');
    var_currentDate DATE;
	var_datvon DATE;
	var_dateroe DATE;
	var_datbis DATE;
 BEGIN
 
 SELECT CURRENT_DATE - 5    INTO :var_currentDate;
 SELECT DAT_VON             INTO :var_datvon         FROM DBP_DATA.WUP WHERE MANDANT_ID = :P_MANDANT_ID AND WUP_ID = :P_WUP_ID;
 SELECT DAT_EROEFFNUNG      INTO :var_dateroe        FROM DBP_DATA.WUP WHERE MANDANT_ID = :P_MANDANT_ID AND WUP_ID = :P_WUP_ID;
 SELECT DAT_BIS             INTO :var_datbis         FROM DBP_DATA.WUP WHERE MANDANT_ID = :P_MANDANT_ID AND WUP_ID = :P_WUP_ID;
 
 CASE WHEN 
	(
	 (	 (TO_DATE(P_DAT_VON) = TO_DATE(:var_datvon))
	 OR  ((TO_DATE(P_DAT_VON) != TO_DATE(:var_datvon)) AND (TO_DATE(P_DAT_VON) BETWEEN TO_DATE(:var_currentdate) AND ('2090-12-31'))) 
	 )
	AND
	 (	 (TO_DATE(P_DAT_EROEFFNUNG) = TO_DATE(:var_dateroe))
	 OR  ((TO_DATE(P_DAT_EROEFFNUNG) != TO_DATE(:var_dateroe)) AND (TO_DATE(P_DAT_EROEFFNUNG) BETWEEN TO_DATE(:var_currentdate) AND ('2090-12-31'))) 
	 )
	AND
	 (	 (TO_DATE(P_DAT_BIS) = TO_DATE(:var_datbis))
	 OR  ((TO_DATE(P_DAT_BIS) != TO_DATE(:var_datbis)) AND (TO_DATE(P_DAT_BIS) BETWEEN TO_DATE(:var_currentdate) AND ('9999-12-31'))) 
	 )	
    )
 THEN
   UPDATE DBP_DATA.WUP
   SET
     DAT_VON =              :P_DAT_VON
    ,DAT_EROEFFNUNG =       :P_DAT_EROEFFNUNG
    ,DAT_BIS =              :P_DAT_BIS
    ,UEBERNAHME_VON =       :P_UEBERNAHME_VON
    ,KUNDENFAKTOR =         :P_KUNDENFAKTOR
    ,UMSATZ_EA_EUR =        :P_UMSATZ_EA_EUR
    ,UMSATZ_EA_LAND =       :P_UMSATZ_EA_LAND
    ,UMSATZ_ERWARTUNG_EUR = :P_UMSATZ_ERWARTUNG_EUR
    ,DAT_WIEDEREROEFFNUNG = :P_DAT_WIEDEREROEFFNUNG
    ,EINWOHNER_ANZAHL =     :P_EINWOHNER_ANZAHL
    WHERE
        MANDANT_ID =        :P_MANDANT_ID
    AND WUP_ID =            :P_WUP_ID;
   COMMIT;
   RETURN 'WUP_is_updated';
   
 ELSE
   RAISE SERV_NOT_UPDATED;
   RETURN 'WUP_not_updated';
 END CASE;   
 END;
$$;
