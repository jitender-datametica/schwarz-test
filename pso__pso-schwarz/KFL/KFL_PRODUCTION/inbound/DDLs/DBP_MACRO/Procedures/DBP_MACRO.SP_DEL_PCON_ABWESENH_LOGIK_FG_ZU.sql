CREATE OR REPLACE PROCEDURE DBP_MACRO.SP_DEL_PCON_ABWESENH_LOGIK_FG_ZU(
	P_MANDANT_ID FLOAT,
	P_ABWESENHEIT_ID VARCHAR,
	P_KJMO_BIS FLOAT,
	P_KJMO_VON FLOAT,
	P_LOGIK_KZ VARCHAR ,
	P_LANGZEIT_ABWESEND_FG FLOAT,
	P_PFLEGE_FG FLOAT ,
	P_BESCHAEFTIGUNGS_VERBOT_FG FLOAT,
	P_KRANKHEIT_UNFALL_FG FLOAT ,
	P_SONSTIGE_ABWESENHEIT_FG FLOAT,
	P_FREIGESTELLT_FG FLOAT,
	P_MUTTERSCHUTZ_FG FLOAT ,
	P_ELTERNZEIT_FG FLOAT ,
	P_LOESCHEN_FG FLOAT
	)
   RETURNS STRING
   LANGUAGE JAVASCRIPT
   EXECUTE AS OWNER
   AS
   $$
   // Vorhandener Datensatz loeschen 
   
   if(P_LOESCHEN_FG == "1") {
	   var sql_stmt = 	
		`DELETE FROM dbp_data.pcon_abwesenh_logik_fg_zu
			Where KJMO_BIS = ? 
				AND KJMO_VON = ?
				AND LOGIK_KZ = ?
				AND LANGZEIT_ABWESEND_FG = ?
				AND PFLEGE_FG = ?
				AND BESCHAEFTIGUNGS_VERBOT_FG = ?
				AND KRANKHEIT_UNFALL_FG = ?
				AND SONSTIGE_ABWESENHEIT_FG = ?
				AND FREIGESTELLT_FG = ?
				AND MUTTERSCHUTZ_FG = ?
				AND ELTERNZEIT_FG = ? 
				AND MANDANT_ID = ?
				AND ABWESENHEIT_ID = ? `;
			
		snowflake.createStatement({
			sqlText : sql_stmt,
			binds : [P_KJMO_BIS,P_KJMO_VON,P_LOGIK_KZ,P_LANGZEIT_ABWESEND_FG, P_PFLEGE_FG, P_BESCHAEFTIGUNGS_VERBOT_FG, P_KRANKHEIT_UNFALL_FG,
					 P_SONSTIGE_ABWESENHEIT_FG,P_FREIGESTELLT_FG, P_MUTTERSCHUTZ_FG, P_ELTERNZEIT_FG, P_MANDANT_ID,P_ABWESENHEIT_ID]
		}).execute();	
	}
	
	var sql_commit = `COMMIT;`
   snowflake.createStatement({
	   sqlText : sql_commit
	}).execute();
   	
   $$;