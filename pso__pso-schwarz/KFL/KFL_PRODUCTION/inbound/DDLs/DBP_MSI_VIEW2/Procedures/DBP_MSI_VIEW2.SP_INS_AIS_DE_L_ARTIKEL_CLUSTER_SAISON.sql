CREATE OR REPLACE PROCEDURE DBP_MSI_VIEW2.SP_INS_AIS_DE_L_ARTIKEL_CLUSTER_SAISON(
    P_CLUSTER_DESC VARCHAR
)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS OWNER
AS  
$$
BEGIN
    INSERT INTO DBP_MSI_VIEW2.TS_AIS_DE_L_EK_SAISON (ek_saison_id, ek_saison_bez)
    SELECT COALESCE(MAX(ek_saison_id),0)+1,
    :P_CLUSTER_DESC
    FROM DBP_MSI_VIEW2.TS_AIS_DE_L_EK_SAISON;

    COMMIT;

    RETURN 'Neues Cluster angelegt';

END;
$$;