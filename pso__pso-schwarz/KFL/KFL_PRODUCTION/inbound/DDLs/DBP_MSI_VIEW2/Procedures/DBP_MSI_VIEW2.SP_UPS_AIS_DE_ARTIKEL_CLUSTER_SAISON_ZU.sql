CREATE OR REPLACE PROCEDURE DBP_MSI_VIEW2.SP_UPS_AIS_DE_ARTIKEL_CLUSTER_SAISON_ZU(
    P_CLUSTER_ID NUMBER,
    P_DAT_VON VARCHAR,
    P_DAT_BIS VARCHAR,
    P_KL_ARTIKELLISTE VARCHAR(5120),
    P_LOESCHEN NUMBER
)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS OWNER
AS  
$$
BEGIN

DELETE FROM DBP_MSI_VIEW2.TS_AIS_DE_EK_SAISON_ART_ZU 
WHERE ek_saison_id = :P_CLUSTER_ID 
AND DAT_GUELTIG_VON = :P_DAT_VON
AND DAT_GUELTIG_BIS = :P_DAT_BIS;

IF (:P_LOESCHEN = 0) THEN
INSERT INTO DBP_MSI_VIEW2.TS_AIS_DE_EK_SAISON_ART_ZU  (
    ART_ID,
    MANDANT_ID,
    ek_saison_id,
    DAT_GUELTIG_VON,
    DAT_GUELTIG_BIS,
    KL_ART_ID_LISTE_TXT
)
SELECT DISTINCT 
    ART_ID,
    MANDANT_ID,
    :P_CLUSTER_ID,
    :P_DAT_VON,
    :P_DAT_BIS,
    :P_KL_ARTIKELLISTE
FROM DBP_VIEW.V_ART
WHERE KL_ART_ID IN ( SELECT table1.value FROM TABLE(split_to_table(:P_KL_ARTIKELLISTE, ';')) AS table1 )
AND MANDANT_ID = 1
;
END IF;

COMMIT;
RETURN 'geänderte Zuordnung gespeichert';

END;
$$;