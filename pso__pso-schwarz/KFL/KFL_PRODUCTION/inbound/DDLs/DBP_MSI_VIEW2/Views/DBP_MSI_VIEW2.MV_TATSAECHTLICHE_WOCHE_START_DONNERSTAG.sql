CREATE OR REPLACE VIEW DBP_MSI_VIEW2.MV_TATSAECHTLICHE_WOCHE_START_DONNERSTAG
(
dat
,dat_vj
,kjwo
,kjwo_vj
,akt_wo)
AS
SELECT
dat+3,
dat_vj+3,
CASE 
WHEN dat + 3 IN 
('2022-1-2', '2022-1-1','2021-12-31','2021-12-30','2021-12-26','2021-12-25','2021-12-24','2021-12-23','2021-1-3','2021-1-2','2021-1-1','2020-12-31','2020-12-27','2020-12-26','2020-12-25','2020-12-24')  
THEN kjwo-1
WHEN dat + 3 IN ('2023-12-27') THEN kjwo + 1
ELSE kjwo END AS kjwo,
CASE 
WHEN dat+3 IN 
('2022-1-2', '2022-1-1','2021-12-31','2021-12-30','2021-12-26','2021-12-25','2021-12-24','2021-12-23','2021-1-3','2021-1-2','2021-1-1','2020-12-31','2020-12-27','2020-12-26','2020-12-25','2020-12-24')
THEN kjwo_vj-1
WHEN dat + 3 IN ('2023-12-27') THEN kjwo_vj + 1
ELSE kjwo_vj END AS kjwo_vj,
CASE 
WHEN dat + 3 IN
('2022-1-2', '2022-1-1','2021-12-31','2021-12-30','2021-12-26','2021-12-25','2021-12-24','2021-12-23','2021-1-3','2021-1-2','2021-1-1','2020-12-31','2020-12-27','2020-12-26','2020-12-25','2020-12-24')
THEN akt_wo-1
WHEN dat + 3 IN ('2023-12-27') THEN akt_wo + 1
ELSE akt_wo END AS akt_wo
FROM dbp_view.v_tag;