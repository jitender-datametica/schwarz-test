CREATE OR REPLACE VIEW DBP_MSI_VIEW3.MV_EMPFAENGER
(
	EMPFAENGER_ID,
	AKTUELL_WUP_ID,
	IS_AKT_WUP_ID_FG,
	NB_ID,
	MANDANT_ID_EMPFAENGER,
	DAT_VON,
	EMPFAENGER_BEZ,
	DAT_BIS,
	BUCHUNGSKREIS_ID,
	VERKAUFSORGANISATION_ID,
	WUP_TYP_ID,
	BREITENGRAD,
	LAENGENGRAD,
	VKL_ID,
	VS_ID
) AS-- 2015.09.01. SROM0404: INC0480245, ERWEITERUNG UM GASTRO-BETRIEBE (NB_ID = 2)
--                       LAENGENGRAD UND BREITENGRAD AUCH GLEICH MITGENOMMEN
-- 2020-11-13 NWAG2310: + VKL_ID + VS_ID
-- 2023-02-07, dknop, ID 0 nochmal als -1 duplizieren damit zB Einträge mit WEMPF "DPL" im Bericht 06.01 angezeigt werden (INC6065771)
-- ID 0 nochmal als -1 duplizieren damit zB Einträge mit WEMPF "DPL" im Bericht 06.01 angezeigt werden (INC6065771)
--2024-08-01,AP0204035, SPEC0254614,dknop, adding aktuell_wup_id logic
--2025-10-06, INC11561998, nw, switching to full outer join with GP table
SELECT
COALESCE(W.WUP_ID, G.GP_ID) AS WUP_ID,
COALESCE(W.AKTUELL_WUP_ID, G.GP_ID) AS AKTUELL_WUP_ID,
CASE WHEN aktuell_wup_id = wup_id THEN 1 ELSE 0 END AS IS_AKT_WUP_ID_FG,
COALESCE(W.NB_ID,-111) AS NB_ID,
COALESCE(W.MANDANT_ID, G.MANDANT_ID) AS MANDANT_ID,
COALESCE(W.DAT_VON, G.DAT_VON) AS DAT_VON,
CASE WHEN W.NB_ID = -1 THEN '---' ELSE COALESCE(W.WUP_STANDORT, G.GP_NAME) END AS EMPFAENGER_BEZ,
COALESCE(W.DAT_BIS, G.DAT_BIS) AS DAT_BIS,
COALESCE(W.BUCHUNGSKREIS_ID,-1),
COALESCE(W.VERKAUFSORGANISATION_ID,G.EINKAUFSORGANISATION_ID::VARCHAR(4)),
COALESCE(W.WUP_TYP_ID,-1),
COALESCE(W.BREITENGRAD, G.BREITENGRAD),
COALESCE(W.LAENGENGRAD, G.LAENGENGRAD),
COALESCE(W.VKL_ID,-1) AS VKL_ID,
COALESCE(W.VS_ID,-1) AS VS_ID
FROM DBP_VIEW.V_GP G
--show columns in DBP_VIEW.V_GP 
FULL OUTER JOIN DBP_VIEW.V_WUP W ON G.MANDANT_ID=W.MANDANT_ID AND G.GP_ID=W.WUP_ID
WHERE (NB_ID IN (2, 0, -111) AND WUP_ID > 0)
   OR (NB_ID = -1 AND WUP_ID = 0)
   OR W.NB_ID IS NULL

UNION ALL
-- ID 0 nochmal als -1 duplizieren damit zB Einträge mit WEMPF "DPL" im Bericht 06.01 angezeigt werden (INC6065771)
SELECT
-1 AS WUP_ID,
-1 AS AKTUELL_WUP_ID,
1 AS IS_AKT_WUP_ID_FG,
NB_ID,
MANDANT_ID,
DAT_VON,
CASE WHEN NB_ID = -1 THEN '---' ELSE WUP_STANDORT END AS EMPFAENGER_BEZ,
DAT_BIS,
BUCHUNGSKREIS_ID,
VERKAUFSORGANISATION_ID,
WUP_TYP_ID,
BREITENGRAD,
LAENGENGRAD,
VKL_ID,
VS_ID
FROM DBP_VIEW.V_WUP
WHERE NB_ID = -1 AND WUP_ID = 0;