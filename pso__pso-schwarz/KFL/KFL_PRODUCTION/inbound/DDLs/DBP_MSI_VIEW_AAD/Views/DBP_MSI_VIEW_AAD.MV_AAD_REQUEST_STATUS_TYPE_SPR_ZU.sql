CREATE OR REPLACE VIEW DBP_MSI_VIEW_AAD.MV_AAD_REQUEST_STATUS_TYPE_SPR_ZU AS 
-- 30.06.2023 staeblern Erstellen Sprachtabelle aad_request_status_type_spr_zu
SELECT 
v01.request_status_type_id
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.REQUEST_STATUS_TYPE_DESCR END),'N/A') AS REQUEST_STATUS_TYPE_DESCR                      
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.REQUEST_STATUS_TYPE_DESCR END),'N/A') AS REQUEST_STATUS_TYPE_DESCR_DE                
,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.REQUEST_STATUS_TYPE_DESCR END), REQUEST_STATUS_TYPE_DESCR_DE) AS REQUEST_STATUS_TYPE_DESCR_CZ
,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.REQUEST_STATUS_TYPE_DESCR END), REQUEST_STATUS_TYPE_DESCR_DE) AS REQUEST_STATUS_TYPE_DESCR_SK
,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.REQUEST_STATUS_TYPE_DESCR END), REQUEST_STATUS_TYPE_DESCR_DE) AS REQUEST_STATUS_TYPE_DESCR_HR
,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.REQUEST_STATUS_TYPE_DESCR END), REQUEST_STATUS_TYPE_DESCR_DE) AS REQUEST_STATUS_TYPE_DESCR_PL
,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.REQUEST_STATUS_TYPE_DESCR END), REQUEST_STATUS_TYPE_DESCR_DE) AS REQUEST_STATUS_TYPE_DESCR_RO
,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.REQUEST_STATUS_TYPE_DESCR END), REQUEST_STATUS_TYPE_DESCR_DE) AS REQUEST_STATUS_TYPE_DESCR_BG
FROM dbp_view.v_aad_request_status_type_spr_zu v01
GROUP BY 
v01.request_status_type_id
UNION 
SELECT 0 AS request_status_type_id
,'' AS REQUEST_STATUS_TYPE_DESCR                      
,'' AS REQUEST_STATUS_TYPE_DESCR_DE                
,'' AS REQUEST_STATUS_TYPE_DESCR_CZ
,'' AS REQUEST_STATUS_TYPE_DESCR_SK
,'' AS REQUEST_STATUS_TYPE_DESCR_HR
,'' AS REQUEST_STATUS_TYPE_DESCR_PL
,'' AS REQUEST_STATUS_TYPE_DESCR_RO
,'' AS REQUEST_STATUS_TYPE_DESCR_BG
 ;