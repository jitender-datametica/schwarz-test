CREATE OR REPLACE VIEW DBP_MSI_VIEW_AAD.MV_AAD_SCENARIO_SPR_ZU AS
--20.06.2023 snik: SPEC0200569 AAD Scenario Sprachtabelle
   SELECT
    v01.SCENARIO_ID
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.SCENARIO_DESCR END),'N/A') AS SCENARIO_DESCR                      
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.SCENARIO_DESCR END),'N/A') AS SCENARIO_DESCR_DE                
   ,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.SCENARIO_DESCR END), SCENARIO_DESCR_DE) AS SCENARIO_DESCR_CZ
   ,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.SCENARIO_DESCR END), SCENARIO_DESCR_DE) AS SCENARIO_DESCR_SK
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.SCENARIO_DESCR END), SCENARIO_DESCR_DE) AS SCENARIO_DESCR_HR
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.SCENARIO_DESCR END), SCENARIO_DESCR_DE) AS SCENARIO_DESCR_PL
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.SCENARIO_DESCR END), SCENARIO_DESCR_DE) AS SCENARIO_DESCR_RO
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.SCENARIO_DESCR END), SCENARIO_DESCR_DE) AS SCENARIO_DESCR_BG
FROM DBP_VIEW.V_AAD_SCENARIO_SPR_ZU v01
GROUP BY v01.SCENARIO_ID;