CREATE OR REPLACE VIEW DBP_MSI_VIEW_AIS_INT.MV_L_REGION(
	MANDANT_ID,
	REGION_ID,
	VS_ID_ALT,
	REGION_KBEZ,
	REGION_BEZ
) AS SELECT
	MANDANT_ID,
	WUP_CLUSTER_ID AS REGION_ID,
	WUP_CLUSTER_ID - 100 AS VS_ID_ALT,
	WUP_CLUSTER_BEZ AS REGION_KBEZ,
	WUP_CLUSTER_DESCR AS REGION_BEZ
FROM DBP_VIEW.V_TS_SCM_L_WUP_CLUSTER
WHERE WUP_CLUSTER_ID IN (101,102,103,106,107,108) AND MANDANT_ID = 1

UNION ALL

SELECT
	MANDANT_ID,
	VS_ID AS REGION_ID,
	VS_ID AS VS_ID_ALT,
	VS_BEZ AS REGION_KBEZ,
	VS_BEZ AS REGION_BEZ
FROM DBP_VIEW.V_VS
WHERE MANDANT_ID <> 1;