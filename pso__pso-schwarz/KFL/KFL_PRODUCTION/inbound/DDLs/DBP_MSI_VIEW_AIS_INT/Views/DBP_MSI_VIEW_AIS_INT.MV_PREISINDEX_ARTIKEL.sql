create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_AIS_INT.MV_PREISINDEX_ARTIKEL(
	MANDANT_ID,
	DAT_ERFASS,
	ART_ID,
	WRG_ID,
	BETRAG_UMSATZ_ART,
	FAKTOR_GEWICHTUNG_UMSATZ,
	PREIS_ART_GEWICHTET_VORKALK,
	PREIS_ART_GEWICHTET_NACHKALK,
	PREIS_ART_VORKALK,
	PREIS_ART_NACHKALK,
	MKW_CD,
	KUKLA_ID,
	DAT_GUELTIG_VON,
	DAT_GUELTIG_BIS,
	DAT_VORKALK,
	DAT_NACHKALK,
	PREIS_KUKLA_ART_DURCHSCHNITT,
	PREIS_KUKLA_ART_GEWICHTET,
	PROZ_SCHWELLENWERT,
	TEURER_VK_FLAG,
	BILLIGER_VK_FLAG,
	GLEICH_VK_FLAG,
	TEURER_NK_FLAG,
	BILLIGER_NK_FLAG,
	GLEICH_NK_FLAG,
	DIFF_VK,
	DIFF_VK_PROZ,
	DIFF_NK,
	DIFF_NK_PROZ
) as
SELECT 
    mandant_id, 
    dat_erfass,
    art_id, 
    wrg_id,
    
    betrag_umsatz_art,
    faktor_gewichtung_umsatz,
    preis_art_gewichtet_vorkalk,
    preis_art_gewichtet_nachkalk,
    preis_art_vorkalk,
    preis_art_nachkalk,
    mkw_cd,
    
    kukla_id,
    dat_gueltig_von,
    dat_gueltig_bis,
    dat_vorkalk,
    dat_nachkalk,
    preis_kukla_art_durchschnitt,
    preis_kukla_art_gewichtet,
    proz_schwellenwert,
    
    CASE WHEN  preis_art_vorkalk > preis_kukla_art_durchschnitt THEN 'X' ELSE '' END AS  teurer_vk_flag,
    CASE WHEN  preis_art_vorkalk < preis_kukla_art_durchschnitt THEN 'X' ELSE '' END AS  billiger_vk_flag,
    CASE WHEN  preis_art_vorkalk = preis_kukla_art_durchschnitt THEN 'X' ELSE '' END AS  gleich_vk_flag,
    CASE WHEN  preis_art_nachkalk > preis_kukla_art_durchschnitt THEN 'X' ELSE '' END AS  teurer_nk_flag,
    CASE WHEN  preis_art_nachkalk < preis_kukla_art_durchschnitt THEN 'X' ELSE '' END AS  billiger_nk_flag,
    CASE WHEN  preis_art_nachkalk = preis_kukla_art_durchschnitt THEN 'X' ELSE '' END AS  gleich_nk_flag,
    preis_art_vorkalk - preis_kukla_art_durchschnitt AS diff_vk,
    CASE WHEN preis_art_vorkalk = 0 OR preis_art_vorkalk IS NULL THEN 0 ELSE (preis_art_vorkalk - preis_kukla_art_durchschnitt) / preis_art_vorkalk END  AS diff_vk_proz,
    preis_art_nachkalk - preis_kukla_art_durchschnitt AS diff_nk,
    CASE WHEN preis_art_nachkalk = 0 OR preis_art_nachkalk IS NULL THEN 0 ELSE (preis_art_nachkalk - preis_kukla_art_durchschnitt) / preis_art_nachkalk END  AS diff_nk_proz   
    
FROM dbp_data.preisindex_kukla_Art;
