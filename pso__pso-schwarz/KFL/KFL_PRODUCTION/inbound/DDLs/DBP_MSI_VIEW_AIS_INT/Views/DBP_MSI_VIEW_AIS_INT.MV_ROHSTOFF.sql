create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_AIS_INT.MV_ROHSTOFF(
	ROHSTOFF_NR,
	ROHSTOFF_CLUSTER_ID,
	ROHSTOFF_BASIS_EINH_NAME,
	ROHSTOFF_BEZ,
	ROHSTOFF_KFL_BEZ,
	ROHSTOFFKATEGORIE,
	ROHSTOFF_BESCHREIBUNG_TXT,
	ROHSTOFF_QUALITAET_TXT,
	ROHSTOFF_HERKUNFTSORT_NAME,
	ROHSTOFF_LIEFERORT_NAME,
	ROHSTOFF_QUELL_BEZ
) as
SELECT
 v01.ROHSTOFF_NR 
 
,v02.ROHSTOFF_CLUSTER_ID
,v01.ROHSTOFF_BASIS_EINH_NAME
,v01.ROHSTOFF_BEZ
,v02.ROHSTOFF_KFL_BEZ
,v02.ROHSTOFF_KATEGORIE_KFL_NAME AS ROHSTOFFKATEGORIE
,v01.ROHSTOFF_BESCHREIBUNG_TXT
,TRIM (v02.ROHSTOFF_QUALITAET_TXT) AS ROHSTOFF_QUALITAET_TXT
,v01.ROHSTOFF_HERKUNFTSORT_NAME
,v01.ROHSTOFF_LIEFERORT_NAME

,v02.ROHSTOFF_QUELL_BEZ
FROM DBP_DATA.ROHSTOFF v01
LEFT JOIN DBP_MSI_DATA.TS_ROHSTOFF_MONITORING_ANZEIGE v02
ON v01.ROHSTOFF_NR = v02.ROHSTOFF_NR
WHERE CURRENT_DATE BETWEEN v02.DAT_ANZEIGE_VON AND DAT_ANZEIGE_BIS
GROUP BY ALL
ORDER BY ROHSTOFF_NR;
