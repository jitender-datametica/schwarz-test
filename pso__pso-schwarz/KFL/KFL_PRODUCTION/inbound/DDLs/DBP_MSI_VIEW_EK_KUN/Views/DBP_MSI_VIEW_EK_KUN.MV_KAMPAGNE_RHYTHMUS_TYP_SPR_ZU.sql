CREATE OR REPLACE VIEW DBP_MSI_VIEW_EK_KUN.MV_KAMPAGNE_RHYTHMUS_TYP_SPR_ZU
(
 MANDANT_ID
,KAMPAGNE_RHYTHMUS_TYP_ID
,KAMPAGNE_RHYTHMUS_TYP_BEZ_EN
,KAMPAGNE_RHYTHMUS_TYP_BEZ
,KAMPAGNE_RHYTHMUS_TYP_BEZ_CZ
,KAMPAGNE_RHYTHMUS_TYP_BEZ_SK
,KAMPAGNE_RHYTHMUS_TYP_BEZ_HR
,KAMPAGNE_RHYTHMUS_TYP_BEZ_PL
,KAMPAGNE_RHYTHMUS_TYP_BEZ_RO
,KAMPAGNE_RHYTHMUS_TYP_BEZ_BG
)
AS
SELECT
 MANDANT_ID
,KAMPAGNE_RHYTHMUS_TYP_ID
, MAX(CASE WHEN spr_id =  24           THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_EN      --EN
, COALESCE(MAX(CASE WHEN spr_id = 22   THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ        --DE (Standard)
, COALESCE(MAX(CASE WHEN spr_id = 124  THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_CZ    -- CZ
, COALESCE(MAX(CASE WHEN spr_id = 108  THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_SK    -- SK
, COALESCE(MAX(CASE WHEN spr_id = 65   THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_HR    -- HR
, COALESCE(MAX(CASE WHEN spr_id = 90   THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_PL    -- PL
, COALESCE(MAX(CASE WHEN spr_id = 95   THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_RO    -- RO
, COALESCE(MAX(CASE WHEN spr_id = 18   THEN KAMPAGNE_RHYTHMUS_TYP_BEZ END), KAMPAGNE_RHYTHMUS_TYP_BEZ_EN) AS KAMPAGNE_RHYTHMUS_TYP_BEZ_BG    -- BG

FROM DBP_VIEW.V_KAMPAGNE_RHYTHMUS_TYP_SPR_ZU
GROUP BY  
 MANDANT_ID
,KAMPAGNE_RHYTHMUS_TYP_ID;
