CREATE OR REPLACE VIEW DBP_MSI_VIEW_EK_KUN.MV_KAMPAGNE_VORLAGE_MO_SUM
(
	MANDANT_ID,
	KAMPAGNE_ID,
	KJMO,
	NACHRICHT_VORLAGE_ID,
	KOMMUNIKATIONSKANAL_ID,
	MESSAGE_TITEL,
	MESSAGE_NAME_ID,
	MESSAGE_NAME,
	NACHRICHT_SUBVORLAGE_NAME_LISTE_TXT,
	VARIATION,
	KAMPAGNE_NAME,
	DAT_KAMPAGNE_VON,
	KJ_KAMPAGNE_VON,
	KJWO_KAMPAGNE_VON,
	KJMO_KAMPAGNE_VON,
	KAMPAGNE_RHYTHMUS_TYP_ID,
	KAMPAGNE_VERSION_NR,
	NACHRICHT_VORLAGE_TITEL_TXT,
	NACHRICHT_VORLAGE_TXT,
	MESSAGE_CONTENT,
	NACHRICHT_VORLAGE_URL_TXT,
	URL,
	NACHRICHT_VORLAGE_BILD_ID,
	PICTURE,
	ANZ_KAMPAGNE_KUNDE_GESAMT,
	MEMBER_COUNT_EMAIL,
	MEMBER_COUNT_PUSH,
	MEMBER_COUNT_SMS,
	ANZ_KUNDE_GESENDET,
	SENT_EMAIL,
	SENT_SMS,
	SENT_PUSH,
	RATE_KUNDE_GESENDET,
	CLICK_SENT_RATE_EMAIL,
	CLICK_SENT_RATE_PUSH,
	ANZ_KUNDE_BLOCKIERT,
	BLOCKED_EMAIL,
	RATE_KUNDE_BLOCKIERT,
	RATE_BLOCKED_EMAIL,
	ANZ_KUNDE_ZUGESTELLT,
	DELIVERED_EMAIL,
	RATE_KUNDE_ZUGESTELLT,
	DELIVERED_RATE_EMAIL,
	DELIVERED_RATE_PUSH,
	ANZ_KUNDE_BOUNCED_SOFT,
	ANZ_KUNDE_BOUNCED_HARD,
	HARD_BOUNCE_EMAIL,
	SOFT_BOUNCE_EMAIL,
	SOFT_BOUNCE_RATE_PROVIDER,
	HARD_BOUNCE_RATE_PROVIDER,
	HARD_BOUNCE_RATE_EMAIL,
	SOFT_BOUNCE_RATE_EMAIL,
	ANZ_KUNDE_GEOEFFNET,
	OPENED_EMAIL,
	OPENED_SMS,
	OPENED_PUSH,
	RATE_KUNDE_GEOEFFNET_ZUGESTELLT,
	OPENED_RATE_EMAIL,
	OPENED_RATE_PUSH,
	ANZ_KUNDE_GEKLICKT,
	CLICKS_EMAIL,
	CLICKS_PUSH,
	RATE_KUNDE_GEKLICKT_GESENDET,
	RATE_KUNDE_GEKLICKT_GEOEFFNET,
	CLICK_RATE_EMAIL,
	CLICK_RATE_PUSH,
	RATE_KUNDE_GEKLICKT_ZUGESTELLT,
	ANZ_KUNDE_SPAM,
	SPAM_EMAIL,
	RATE_KUNDE_SPAM,
	SPAM_RATE_EMAIL,
	ANZ_KUNDE_ABGEMELDET,
	UNSUBSCRIBE_EMAIL,
	RATE_KUNDE_ABGEMELDET,
	UNSUBSCRIBE_RATE_EMAIL
) 
AS
SELECT
 v01.MANDANT_ID
,v01.KAMPAGNE_ID
,v01.KJMO
,v01.NACHRICHT_VORLAGE_ID
,v01.KOMMUNIKATIONSKANAL_ID
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID IN (1, 2) THEN CAST(v01.NACHRICHT_VORLAGE_TITEL_TXT AS VARCHAR(4000)) ELSE '' END AS MESSAGE_TITEL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID IN (1) THEN CAST(v01.NACHRICHT_VORLAGE_ID AS VARCHAR (4000)) ELSE '' END AS MESSAGE_NAME_ID
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID IN (1) THEN CAST(v02.NACHRICHT_VORLAGE_NAME AS VARCHAR (4000)) ELSE '' END AS MESSAGE_NAME
,v01.NACHRICHT_SUBVORLAGE_NAME_LISTE_TXT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN CAST(v01.NACHRICHT_SUBVORLAGE_NAME_LISTE_TXT AS VARCHAR(4000)) ELSE '' END AS VARIATION
,v01.KAMPAGNE_NAME
,v01.DAT_KAMPAGNE_VON
,YEAR (v01.DAT_KAMPAGNE_VON) AS KJ_KAMPAGNE_VON
,YEAR (v01.DAT_KAMPAGNE_VON) || LPAD(WEEK (DAT_KAMPAGNE_VON),2,0) AS KJWO_KAMPAGNE_VON
,YEAR (v01.DAT_KAMPAGNE_VON) || LPAD(MONTH (DAT_KAMPAGNE_VON),2,0) AS KJMO_KAMPAGNE_VON 
,v01.KAMPAGNE_RHYTHMUS_TYP_ID
,v01.KAMPAGNE_VERSION_NR
,v01.NACHRICHT_VORLAGE_TITEL_TXT
,v01.NACHRICHT_VORLAGE_TXT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID IN (2, 3) THEN CAST(v01.NACHRICHT_VORLAGE_TXT AS VARCHAR(4000)) ELSE '' END AS MESSAGE_CONTENT
,v01.NACHRICHT_VORLAGE_URL_TXT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.NACHRICHT_VORLAGE_URL_TXT ELSE '' END AS URL
,v01.NACHRICHT_VORLAGE_BILD_ID
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.NACHRICHT_VORLAGE_BILD_ID ELSE '' END AS PICTURE
,v01.ANZ_KAMPAGNE_KUNDE_GESAMT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KAMPAGNE_KUNDE_GESAMT ELSE 0 END AS MEMBER_COUNT_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.ANZ_KAMPAGNE_KUNDE_GESAMT ELSE 0 END AS MEMBER_COUNT_PUSH
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 3 THEN v01.ANZ_KAMPAGNE_KUNDE_GESAMT ELSE 0 END AS MEMBER_COUNT_SMS
,v01.ANZ_KUNDE_GESENDET
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_GESENDET ELSE 0 END AS SENT_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 3 THEN v01.ANZ_KUNDE_GESENDET ELSE 0 END AS SENT_SMS
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.ANZ_KUNDE_GESENDET ELSE 0 END AS SENT_PUSH
,v01.RATE_KUNDE_GESENDET
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_GESENDET ELSE 0 END AS CLICK_SENT_RATE_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.RATE_KUNDE_GESENDET ELSE 0 END AS CLICK_SENT_RATE_PUSH
,v01.ANZ_KUNDE_BLOCKIERT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_BLOCKIERT ELSE 0 END AS BLOCKED_EMAIL
,v01.RATE_KUNDE_BLOCKIERT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_BLOCKIERT ELSE 0 END AS RATE_BLOCKED_EMAIL
,v01.ANZ_KUNDE_ZUGESTELLT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_ZUGESTELLT ELSE 0 END AS DELIVERED_EMAIL
,v01.RATE_KUNDE_ZUGESTELLT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_ZUGESTELLT ELSE 0 END AS DELIVERED_RATE_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.RATE_KUNDE_ZUGESTELLT ELSE 0 END AS DELIVERED_RATE_PUSH
,v01.ANZ_KUNDE_BOUNCED_SOFT
,v01.ANZ_KUNDE_BOUNCED_HARD
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_BOUNCED_HARD ELSE 0 END AS HARD_BOUNCE_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_BOUNCED_SOFT ELSE 0 END AS SOFT_BOUNCE_EMAIL
,v01.RATE_KUNDE_BOUNCED_SOFT AS SOFT_BOUNCE_RATE_PROVIDER
,v01.RATE_KUNDE_BOUNCED_HARD AS HARD_BOUNCE_RATE_PROVIDER
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_BOUNCED_HARD ELSE 0 END AS HARD_BOUNCE_RATE_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_BOUNCED_SOFT ELSE 0 END AS SOFT_BOUNCE_RATE_EMAIL
,v01.ANZ_KUNDE_GEOEFFNET
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_GEOEFFNET ELSE 0 END AS OPENED_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 3 THEN v01.ANZ_KUNDE_GEOEFFNET ELSE 0 END AS OPENED_SMS
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.ANZ_KUNDE_GEOEFFNET ELSE 0 END AS OPENED_PUSH
,v01.RATE_KUNDE_GEOEFFNET_ZUGESTELLT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_GEOEFFNET_ZUGESTELLT ELSE 0 END AS OPENED_RATE_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.RATE_KUNDE_GEOEFFNET_ZUGESTELLT ELSE 0 END AS OPENED_RATE_PUSH
,v01.ANZ_KUNDE_GEKLICKT
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_GEKLICKT ELSE 0 END AS CLICKS_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.ANZ_KUNDE_GEKLICKT ELSE 0 END AS CLICKS_PUSH
,v01.RATE_KUNDE_GEKLICKT_GESENDET
,v01.RATE_KUNDE_GEKLICKT_GEOEFFNET
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_GEKLICKT_GEOEFFNET ELSE 0 END AS CLICK_RATE_EMAIL
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 2 THEN v01.RATE_KUNDE_GEKLICKT_GEOEFFNET ELSE 0 END AS CLICK_RATE_PUSH
,v01.RATE_KUNDE_GEKLICKT_ZUGESTELLT
,v01.ANZ_KUNDE_SPAM
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_SPAM ELSE 0 END AS SPAM_EMAIL
,v01.RATE_KUNDE_SPAM
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_SPAM ELSE 0 END AS SPAM_RATE_EMAIL
,v01.ANZ_KUNDE_ABGEMELDET
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.ANZ_KUNDE_ABGEMELDET ELSE 0 END AS UNSUBSCRIBE_EMAIL
,v01.RATE_KUNDE_ABGEMELDET
,CASE WHEN v01.KOMMUNIKATIONSKANAL_ID = 1 THEN v01.RATE_KUNDE_ABGEMELDET ELSE 0 END AS UNSUBSCRIBE_RATE_EMAIL

FROM DBP_MSI_DATA.KAMPAGNE_VORLAGE_MO_SUM v01
LEFT JOIN DBP_DATA.KAMPAGNE_NACHRICHT_VORLAGE v02
ON v01.MANDANT_ID = v02.MANDANT_ID
AND v01.KOMMUNIKATIONSKANAL_ID = v02.KOMMUNIKATIONSKANAL_ID
AND v01.NACHRICHT_VORLAGE_ID = v02.NACHRICHT_VORLAGE_ID;