create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_EK_KUN.MV_VS(
	MANDANT_ID,
	VS_ID,
	VS_BEZ
) as
SELECT 
v01.mandant_id
,v01.vs_id
,v01.vs_bez
FROM DBP_DATA.VS v01

WHERE MANDANT_ID <> 1


UNION ALL

SELECT
 DISTINCT MANDANT_ID
,CASE WHEN v01.WUP_CLUSTER_ID IN (102, 107) THEN 1
      WHEN v01.WUP_CLUSTER_ID IN (101, 103) THEN 2
      WHEN v01.WUP_CLUSTER_ID IN (106, 108) THEN 3
      END AS VS_ID  
,CASE WHEN v01.WUP_CLUSTER_ID IN (102, 107) THEN 'Süd'
      WHEN v01.WUP_CLUSTER_ID IN (101, 103) THEN 'Ost'
      WHEN v01.WUP_CLUSTER_ID IN (106, 108) THEN 'West'
      END AS VS_BEZ
FROM DBP_DATA.TS_SCM_WUP_CLUSTER_ZU v01
WHERE v01.MANDANT_ID = 1
AND v01.NB_ID = 0
;
