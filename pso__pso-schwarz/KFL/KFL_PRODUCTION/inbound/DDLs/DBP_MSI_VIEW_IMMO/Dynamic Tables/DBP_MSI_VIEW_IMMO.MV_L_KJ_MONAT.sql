CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMMO.MV_L_KJ_MONAT(
	KJMO,
	KJMO_VJ,
	GJMO,
	KJQU,
	KJ,
	GJ,
	AKT_GJ,
	AKT_MO,
	AKT_MO_KOMPLETT,
	AKT_KJQU,
	AKT_KJQU_KOMPLETT,
	AKT_KJ,
	AKT_KJ_KOMPLETT,
	MO_KJ,
	MIN_DAT,
	MAX_DAT,
	KJMO_VM,
	AKT_BUCHUNGS_SCHLUSS,
	KJMO_BEZ,
	KJMO_BEZ_KURZ,
	KJMO_KURZ_BEZ,
	KJMO_BUCHUNGSSCHLUSS
) TARGET_LAG = '1 hour, 30 minutes' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMMO
 AS
SELECT
    KJMO,
    KJMO_VJ,
    GJMO,
    KJQU,
    KJ,
    GJ,
    AKT_GJ,
    AKT_MO,
    AKT_MO_KOMPLETT,
    AKT_KJQU,
    AKT_KJQU_KOMPLETT,
    AKT_KJ,
    AKT_KJ_KOMPLETT,
    MO_KJ,
    MIN_DAT,
    MAX_DAT,
    TO_NUMBER(
        TO_VARCHAR(
            ADD_MONTHS(TO_DATE(TO_CHAR(kjmo), 'YYYYMM'), -1),
            'YYYYMM'
        )
    ) AS KJMO_VM,
    V1.AKT_BUCHUNGS_SCHLUSS,
    CASE
        WHEN MO_ID = 3
        AND SPR_ID = 22 THEN 'März'
        ELSE V2.MO_BEZ
    END AS KJMO_BEZ,
    SUBSTR(V2.MO_BEZ, 0, 3) || ' ' || SUBSTR (KJ, 3, 2) AS KJMO_BEZ_KURZ,
    CASE
        WHEN MO_ID = 3
        AND SPR_ID = 22 THEN 'Mrz'
        ELSE SUBSTR(V2.MO_BEZ, 0, 3)
    END AS KJMO_KURZ_BEZ,
    V1.BUCHUNGS_SCHLUSS_AKT
FROM
    DBP_VIEW.V_MONAT
    LEFT JOIN DBP_VIEW.V_L_BUCHUNGSSTATUS_KER V1 ON V1.KJ_KER_MO_ID = KJMO
    LEFT JOIN DBP_VIEW.V_MONAT_SPR_ZU V2 ON V2.MO_ID = MO_KJ
WHERE
    V2.SPR_ID = 22;