CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMMO.MV_L_MIETVERTRAG_UMSATZ_KONZ_HILF(
	MANDANT_ID,
	MV_INTRENO,
	BRANCHE_ID,
	MAN_VERMIETUNGSAUFTRAG_ID,
	ANLASS_ZWVERMIETUNG_ID,
	VERTRAGSART_ID,
	MIETVERTRAG_NR,
	MV_OBJEKT_NR,
	PARTNER_ID,
	ANSCHLUSS_MIETVERTRAG,
	MV_OPTION,
	DAT_KUEND_EINGANG_BIS,
	DAT_KUEND_BERECHNET_ZUM,
	KUEND_PARTEI,
	KUEND_FRIST,
	DAT_MIET_BEGINN,
	DAT_MIET_ENDE,
	RESTLAUFZEIT_MONATE,
	MV_AKT_GUELTIG_FG,
	UNBEFRISTET_FG,
	MIETVERTRAG_NR_ALT
) TARGET_LAG = '1 hour, 30 minutes' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMMO
 AS

   SELECT V1.MANDANT_ID ,
       V1.MV_INTRENO ,
       V1.BRANCHE_ID ,
       V1.MAN_VERMIETUNGSAUFTRAG_ID ,
       V1.ANLASS_ZWVERMIETUNG_ID ,
       V1.VERTRAGSART_ID ,
       V1.MIETVERTRAG_NR ,
       V1.MV_OBJEKT_NR ,
       V1.PARTNER_ID ,
       V1.ANSCHLUSS_MIETVERTRAG ,
       V1.MV_OPTION ,
       V1.DAT_KUEND_EINGANG_BIS ,
       V1.DAT_KUEND_BERECHNET_ZUM ,
       V1.KUEND_PARTEI ,
       V1.KUEND_FRIST ,
       V1.DAT_MIET_BEGINN ,
       V1.DAT_MIET_ENDE ,
       (CASE
            WHEN CURRENT_DATE BETWEEN DAT_MIET_BEGINN AND DAT_MIET_ENDE THEN ((TRUNC((DAT_MIET_ENDE- "CURRENT_DATE")/30))+0.5)
            ELSE 0
        END) AS RESTLAUFZEIT_MONATE ,
       (CASE
            WHEN CURRENT_DATE BETWEEN DAT_MIET_BEGINN AND DAT_MIET_ENDE THEN 1
            ELSE 0
        END) AS MV_AKT_GUELTIG_FG ,
       (CASE
            WHEN (DAT_MIET_ENDE IS NULL
                  OR DAT_MIET_ENDE = TO_DATE('9999-12-31','YYYY-MM-DD')) THEN 1
            ELSE 0
        END) AS UNBEFRISTET_FG ,
       V1.MIETVERTRAG_NR_ALT --,v2.miet_fg

FROM DBP_VIEW.V_IMMO_MIETVERTRAG_PER V1
LEFT JOIN
  (SELECT DISTINCT V3.MV_INTRENO ,
                   V3.MANDANT_ID --,v3.miet_fg

   FROM DBP_MSI_VIEW_IMMO.MV_MIETVERTRAG_MIETSICHERHEIT AS V3
   WHERE V3.DAT_RUECKGABE IS NULL
     OR V3.DAT_RUECKGABE> CURRENT_DATE ) AS V2 ON V1.MANDANT_ID=V2.MANDANT_ID
AND V1.MV_INTRENO=V2.MV_INTRENO
WHERE V1.MV_INTRENO NOT IN
    (SELECT DISTINCT V112.MINIMAL_MV_INTRENO
     FROM
       (SELECT DISTINCT MANDANT_ID ,
                        MIETVERTRAG_NR ,
                        COUNT(MV_INTRENO) AS ANZAHL_MV_INTRENOS ,
                        MIN(MV_INTRENO) AS MINIMAL_MV_INTRENO
        FROM DBP_VIEW.V_IMMO_MIETVERTRAG_PER
        GROUP BY 1 ,
                 2
        HAVING ANZAHL_MV_INTRENOS>2) AS V112)
UNION ALL
SELECT V1.MANDANT_ID ,
       V1.MV_INTRENO ,
       V1.BRANCHE_ID ,
       V1.MAN_VERMIETUNGSAUFTRAG_ID ,
       V1.ANLASS_ZWVERMIETUNG_ID ,
       V1.VERTRAGSART_ID ,
       V16.MIETVERTRAG_NR ,
       V1.MV_OBJEKT_NR ,
       V1.PARTNER_ID ,
       V1.ANSCHLUSS_MIETVERTRAG ,
       V1.MV_OPTION ,
       V1.DAT_KUEND_EINGANG_BIS ,
       V1.DAT_KUEND_BERECHNET_ZUM ,
       V1.KUEND_PARTEI ,
       V1.KUEND_FRIST ,
       V1.DAT_MIET_BEGINN ,
       V1.DAT_MIET_ENDE ,
       (CASE
            WHEN CURRENT_DATE BETWEEN DAT_MIET_BEGINN AND DAT_MIET_ENDE THEN ((TRUNC((DAT_MIET_ENDE- "CURRENT_DATE")/30))+0.5)
            ELSE 0
        END) AS RESTLAUFZEIT_MONATE ,
       (CASE
            WHEN CURRENT_DATE BETWEEN DAT_MIET_BEGINN AND DAT_MIET_ENDE THEN 1
            ELSE 0
        END) AS MV_AKT_GUELTIG_FG ,
       (CASE
            WHEN (DAT_MIET_ENDE IS NULL
                  OR DAT_MIET_ENDE = TO_DATE('9999-12-31','YYYY-MM-DD')) THEN 1
            ELSE 0
        END) AS UNBEFRISTET_FG ,
       V1.MIETVERTRAG_NR_ALT --,v2.miet_fg

FROM DBP_VIEW.V_IMMO_MIETVERTRAG_PER V1
LEFT JOIN
  (SELECT DISTINCT V3.MV_INTRENO ,
                   V3.MANDANT_ID --,v3.miet_fg

   FROM DBP_MSI_VIEW_IMMO.MV_MIETVERTRAG_MIETSICHERHEIT AS V3
   WHERE V3.DAT_RUECKGABE IS NULL
     OR V3.DAT_RUECKGABE> CURRENT_DATE ) AS V2 ON V1.MANDANT_ID=V2.MANDANT_ID
AND V1.MV_INTRENO=V2.MV_INTRENO
INNER JOIN
  (SELECT DISTINCT V1.MANDANT_ID ,
                   V1.MV_INTRENO ,
                   V2.MIETVERTRAG_NR
   FROM DBP_VIEW.V_IMMO_MIETVERTRAG_PER AS V1
   JOIN
     (SELECT DISTINCT MANDANT_ID ,
                      MV_INTRENO ,
                      MIETVERTRAG_NR ,
                      MIETVERTRAG_NR_ALT
      FROM DBP_VIEW.V_IMMO_MIETVERTRAG_PER) AS V2 ON V1.MIETVERTRAG_NR=V2.MIETVERTRAG_NR_ALT
   AND V1.MANDANT_ID=V2.MANDANT_ID) AS V16 ON V16.MANDANT_ID=V1.MANDANT_ID
AND V16.MV_INTRENO=V1.MV_INTRENO
WHERE V1.MV_INTRENO NOT IN
    (SELECT DISTINCT V112.MINIMAL_MV_INTRENO
     FROM
       (SELECT DISTINCT MANDANT_ID ,
                        MIETVERTRAG_NR ,
                        COUNT(MV_INTRENO) AS ANZAHL_MV_INTRENOS ,
                        MIN(MV_INTRENO) AS MINIMAL_MV_INTRENO
        FROM DBP_VIEW.V_IMMO_MIETVERTRAG_PER
        GROUP BY 1 ,
                 2
        HAVING ANZAHL_MV_INTRENOS>2) AS V112)
UNION ALL --dummy contract per mandant

SELECT MANDANT_ID ,
       '' AS MV_INTRENO ,
       0 AS BRANCHE_ID ,
       0 AS MAN_VERMIETUNGSAUFTRAG_ID ,
       0 AS ANLASS_ZWVERMIETUNG_ID ,
       0 AS VERTRAGSART_ID ,
       '' AS MIETVERTRAG_NR ,
       '' AS MV_OBJEKT_NR ,
       '' AS PARTNER_ID ,
       '' AS ANSCHLUSS_MIETVERTRAG ,
       '' AS MV_OPTION ,
       CAST ('9999-12-31' AS VARCHAR) AS DAT_KUEND_EINGANG_BIS ,
            CAST ('9999-12-31' AS VARCHAR) AS DAT_KUEND_BERECHNET_ZUM ,
                 '' AS KUEND_PARTEI ,
                 '' AS KUEND_FRIST ,
                 CAST ('1900-01-01' AS VARCHAR) AS DAT_MIET_BEGINN ,
                      CAST ('9999-12-31' AS VARCHAR) AS DAT_MIET_ENDE ,
                           0 AS RESTLAUFZEIT_MONATE ,
                           1 AS MV_AKT_GUELTIG_FG ,
                           0 AS UNBEFRISTET_FG ,
                           '' AS MIETVERTRAG_NR_ALT --,1 AS miet_fg

FROM DBP_VIEW.V_MANDANT;