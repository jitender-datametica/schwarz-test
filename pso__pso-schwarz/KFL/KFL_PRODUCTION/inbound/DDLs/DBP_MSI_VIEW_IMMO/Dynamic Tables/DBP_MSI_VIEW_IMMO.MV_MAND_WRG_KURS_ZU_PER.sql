CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMMO.MV_MAND_WRG_KURS_ZU_PER(
	MANDANT_ID,
	WRG_ID,
	WRG_TYP_ID,
	KURS,
	UMRECHNUNGSKURS,
	KURS_DAT_VON,
	KURS_DAT_BIS
) TARGET_LAG = '1 hour, 30 minutes' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMMO
 AS

   --Copy of VIEW dbe_msi_view_ivs.mv_mandant_wrg_kurs_zu_per

SELECT MWT.MANDANT_ID ,
       MWT.WRG_ID ,
       MWT.WRG_TYP_ID ,
       CASE
           WHEN WRG_TYP_ID = 0 THEN LW.UMRECHNUNGSKURS
           ELSE 1.0000000
       END AS KURS ,
       TRUNC(1/ KURS) AS UMRECHNUNGSKURS ,
       TO_DATE('1900-01-01','YYYY-MM-DD') KURS_DAT_VON ,
       TO_DATE('9999-12-31','YYYY-MM-DD') KURS_DAT_BIS
FROM DBP_VIEW.V_MANDANT_WRG_TYP_ZU MWT
INNER JOIN DBP_VIEW.V_MANDANT M ON MWT.MANDANT_ID = M.MANDANT_ID
INNER JOIN DBP_VIEW.V_KURS LW ON LW.VON_WRG_ID = M.DEFAULT_WRG
AND LW.NACH_WRG_ID = 'EUR'
AND LW.KURSTYP_ID = 3
AND LW.DAT_BIS = TO_DATE('9999-12-31','YYYY-MM-DD');