CREATE OR REPLACE VIEW DBP_MSI_VIEW_LBS.MV_GP(
	MANDANT_ID,
	GP_ID,
	EINKAUFSORGANISATION_ID,
	DAT_VON,
	DAT_BIS,
	ANLIEFERUNG_ID,
	GP_NAME,
	GP_STRASSE,
	GP_PLZ,
	GP_ORT,
	LAND_ID,
	HGP_ID,
	ZEK_ID,
	LIEFERZEIT,
	ZAHLUNGSZIEL_ID,
	AGB_ID,
	ISO_ID,
	EIGENVERPACKUNG_ID,
	EIGENMARKE_ID,
	AUDIT_ID,
	AUDIT_DAT,
	HERST_FG,
	ZAHLART_ID,
	RETOUR_SPERR_FG,
	SYSTEM_ID,
	GP_BRANCHE_ID,
	WEWA_FG,
	LOESCH_FG,
	REGION_ID,
	MIN_PAL_FAKTOR_LKW,
	GLN_BBNR,
	GLN_BSNR,
	GLN_BUBKZ,
	BREITENGRAD,
	LAENGENGRAD,
	GP_NAME_LAT,
	IVN,
	ISD_FG,
	MARKANT_ID,
	SAP_REGION_ID
) AS SELECT
    V01.MANDANT_ID,
    V01.GP_ID,
    V01.EINKAUFSORGANISATION_ID,
    V01.DAT_VON,
    V01.DAT_BIS,
    V01.ANLIEFERUNG_ID,
    V01.GP_NAME,
    V01.GP_STRASSE,
    V01.GP_PLZ,
    V01.GP_ORT,
    V01.LAND_ID,
    V01.HGP_ID,
    V01.ZEK_ID,
    V01.LIEFERZEIT,
    V01.ZAHLUNGSZIEL_ID,
    V01.AGB_ID,
    V01.ISO_ID,
    V01.EIGENVERPACKUNG_ID,
    V01.EIGENMARKE_ID,
    V01.AUDIT_ID,
    V01.AUDIT_DAT,
    V01.HERST_FG,
    V01.ZAHLART_ID,
    V01.RETOUR_SPERR_FG,
    V01.SYSTEM_ID,
    V01.GP_BRANCHE_ID,
    V01.WEWA_FG,
    V01.LOESCH_FG,
    V01.REGION_ID,
    V01.MIN_PAL_FAKTOR_LKW,
    V01.GLN_BBNR,
    V01.GLN_BSNR,
    V01.GLN_BUBKZ,
    V01.BREITENGRAD,
    V01.LAENGENGRAD,
    V01.GP_NAME_LAT,
    V01.IVN,
    V01.ISD_FG,
    V01.MARKANT_ID,
    V02.SAP_REGION_ID
FROM dbp_view.v_gp V01

JOIN dbp_view.v_region V02
    ON V01.MANDANT_ID = V02.MANDANT_ID
    AND V01.LAND_ID = V02.LAND_ID
    AND V01.REGION_ID = V02.REGION_ID

WHERE V01.GP_ID NOT BETWEEN 10000 AND 999999;