CREATE OR REPLACE VIEW DBP_MSI_VIEW_LOG.MV_HYDRA_LEISTUNG(
	MANDANT_ID,
	BUCHUNGSKREIS_ID_HYDRA,
	PRODUKTIVITAETSSCHL_HYDRA,
	LAGERNUMMER_ID,
	TRANSPORT_GV_ID,
	BELEGART_ID_HYDRA,
	WG_VERKETT_LIEF,
	ARTIKELSORTIMENT_ID,
	DAT,
	MENGE_1,
	DAUER_1,
	MENGE_2,
	DAUER_2,
	MENGE_3,
	DAUER_3,
	MENGE_4,
	DAUER_4,
	ABRECHNUNG_FG,
	ABRECHNUNG_FG_S,
	ABRECHNUNG_FG_DESC
) AS
-- 2022-10-07, AP0145540, SPEC0169641, initial, dknop
-- 2022-11-29, AP0145540, SPEC0169641, adding artikelsortiment_id, dknop
-- 2024-10-17, nwag, move ts to msi_data
SELECT
 hl.MANDANT_ID
,hl.BUCHUNGSKREIS_ID_HYDRA
,hl.PRODUKTIVITAETSSCHL_HYDRA
,hl.LAGERNUMMER_ID
,hl.TRANSPORT_GV_ID
,hl.BELEGART_ID_HYDRA
,hl.WG_VERKETT_LIEF
,COALESCE(art_sort.ARTIKELSORTIMENT_ID, '-1')
,hl.DAT
,hl.MENGE_1
,hl.DAUER_1
,hl.MENGE_2
,hl.DAUER_2
,hl.MENGE_3
,hl.DAUER_3
,hl.MENGE_4
,hl.DAUER_4
,hl.ABRECHNUNG_FG
,CASE WHEN hl.ABRECHNUNG_FG=1 THEN 'X' ELSE '' END AS ABRECHNUNG_FG_S
,CASE WHEN hl.ABRECHNUNG_FG=1 THEN 'Rechnungslauf abgeschlossen (Hydra)' ELSE 'Rechnungslauf noch offen (Hydra)' END AS ABRECHNUNG_FG_DESC

FROM dbp_view.v_HYDRA_LEISTUNG hl
LEFT JOIN DBP_MSI_V_VIEW.V_TS_LAGERNUMMER_SORTIERUNG_SCM  art_sort
    ON  hl.lagernummer_id = art_sort.lagernummer_id 
    AND hl.mandant_id = art_sort.mandant_id;