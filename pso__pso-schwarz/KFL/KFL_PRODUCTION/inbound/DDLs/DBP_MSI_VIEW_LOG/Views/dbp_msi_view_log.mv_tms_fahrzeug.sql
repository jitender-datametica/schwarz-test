CREATE OR REPLACE VIEW DBP_MSI_VIEW_LOG.MV_TMS_FAHRZEUG(
	TMS_FAHRZEUGTYP_ID,
	TMS_TREIBSTOFF_ID
) AS
--AP0230823_SPEC0266004, initial, dknop
--2025-01-29, nwag, prio KTMS_DE > KTMS_FLW_DE
SELECT
	TMS_FAHRZEUGTYP_ID,
	TMS_TREIBSTOFF_ID
FROM DBP_VIEW.V_TMS_FAHRZEUG t0
JOIN dbp_view.v_l_system s
  ON t0.system_id = s.system_id
QUALIFY ROW_NUMBER() OVER (PARTITION BY TMS_FAHRZEUGTYP_ID, TMS_TREIBSTOFF_ID ORDER BY CASE WHEN LEFT(KL_SYSTEM_BEZ,3)  <> 'FLW' THEN 0 ELSE 1 END) = 1
;