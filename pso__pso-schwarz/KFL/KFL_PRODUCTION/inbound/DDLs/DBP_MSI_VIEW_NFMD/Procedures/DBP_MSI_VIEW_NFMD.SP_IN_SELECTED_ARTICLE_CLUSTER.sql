CREATE OR REPLACE PROCEDURE DBP_MSI_VIEW_NFMD.SP_IN_SELECTED_ARTICLE_CLUSTER(
    "P_MANDANT_ID" NUMBER, 
    "P_ARTICLE_CLUSTER_ID" NUMBER, 
    "P_USER_ID" VARCHAR(255))
RETURNS STRING
LANGUAGE SQL
COMMENT='Selected Article Cluster'
EXECUTE AS OWNER
AS $$ 
BEGIN
INSERT INTO DBP_MSI_VIEW_NFMD.TS_NFMD_SELECTED_ARTICLE_CLUSTER
(MANDANT_ID, ARTICLE_CLUSTER_ID, DWH_CREATED_TMSP, USER_ID )
VALUES(:P_MANDANT_ID,:P_ARTICLE_CLUSTER_ID,CURRENT_TIMESTAMP::TIMESTAMP_NTZ,:P_USER_ID);

COMMIT;
RETURN 'Artikelcluster ausgewaehlt';
END;
$$;