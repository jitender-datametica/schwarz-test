CREATE OR REPLACE VIEW DBP_MSI_VIEW_SCM.MV_WG_SCM_BEREICH_ZU(
	MANDANT_ID,
	WG_ID,
	SCM_BEREICH_ID
) AS
--AP0182383, SPEC0207712, knop, initial
SELECT
 wg.MANDANT_ID
,wg.wg_id
,COALESCE(scm.WG_HIERARCHIE_MUTTER_ID,-1) AS scm_bereich_id
FROM dbp_view.v_wg_per wg
LEFT JOIN dbp_view.v_WG_HIERARCHIE_ZU_PER scm
ON wg.mandant_id=scm.mandant_id
AND wg.wg_id=scm.WG_HIERARCHIE_ID
AND scm.ARTHIERTYP_ID=12
WHERE wg.dat_bis='9999-12-31'
AND wg.arthiertyp_id=2
GROUP BY wg.MANDANT_ID,wg.WG_ID,COALESCE(scm.WG_HIERARCHIE_MUTTER_ID,-1) ;