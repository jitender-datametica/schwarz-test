CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_KMR_COMPETITOR_STORE_CUSTOMER_REVIEW(
	MANDANT_ID,
	SYSTEM_NAME,
    COMPETITOR_STORE_ID,
	DAT,
	COMPETITOR_REVIEW_RATING,
	COMPETITOR_REVIEW_NMBR,
    COMPETITOR_REVIEW_ID,
	COMPETITOR_REVIEW_TMSP
) AS
/*	KMR Google : Wettbewerber Bewertungen
	2024-02-27 : Review
    2025-05-06 muellerpatri : Änderung von SID auf ID
*/
SELECT
  	RSR.MANDANT_ID
	, RSR.EXT_SYSTEM_NAME           AS SYSTEM_NAME
	, EXT_STORE_ID                  AS COMPETITOR_STORE_ID
	, TO_DATE(RSR.REVIEW_TMSP)      AS DAT
	, RSR.REVIEW_RATING             AS COMPETITOR_REVIEW_RATING
	, 1::INTEGER                    AS COMPETITOR_REVIEW_NMBR
	, RSR.EXT_CUSTOMER_REVIEW_ID    AS COMPETITOR_REVIEW_ID
	, RSR.REVIEW_TMSP               AS COMPETITOR_REVIEW_TMSP
FROM DBP_VIEW.V_RETAIL_STORE_CUSTOMER_REVIEW RSR
 
INNER JOIN DBP_VIEW.V_RETAIL_COMPANY RCO 
ON RCO.EXT_RETAIL_COMPANY_ID = RSR.EXT_RETAIL_COMPANY_ID AND RCO.EXT_SYSTEM_NAME = RSR.EXT_SYSTEM_NAME 
 
WHERE RCO.COMPETITOR_FG = 1;