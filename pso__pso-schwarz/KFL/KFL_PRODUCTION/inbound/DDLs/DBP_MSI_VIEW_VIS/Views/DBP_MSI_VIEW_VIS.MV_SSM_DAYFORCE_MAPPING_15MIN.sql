CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_SSM_DAYFORCE_MAPPING_15MIN(
        MANDANT_ID,
        NB_ID,
        WUP_ID,
        WUP_BEREICH_ID,
        WUP_ABT_ID,
        DAYFORCE_MINIMAL_MAPPING,
        DAYFORCE_XREFCODE,
        DAT,
        ZEIT_STUNDE,
        ZEIT_15MIN,
        WERT_GESAMT,
        WERT_MINIMAL,
        WERT_AUFGABE,
        WERT_TREIBER,
        WERT_TREIBER_FAKTOR,
        WERT_DIFF_FAKTOR,
        WERT_XREF_FAKTOR,
        SUM_MINIMAL,
        SUM_FAKTOR,
        XFAKTOR,
        WERT_DIFF_OHNE,
        WERT_XREF_OHNE,
        SUM_OHNE
)
AS
    -- FAKT/AGGREGAT - MAPPING DAYFORCE/XREF PRO WUP/BEREICH/ABT/TAG/15MIN
    -- 2020-10-30 SSCH0611 : INITIAL (AP0052955_SPEC0067085)
    -- 2023-10-11 muellerpatri: Adding Mandant-Join (AP0164780)
    -- 2024-06-20 muellerpatri : Filialumgliederung + Review [P1760-DWH]

SELECT
    SSM.MANDANT_ID
    , SSM.NB_ID
    , WUP.AKTUELL_WUP_ID AS WUP_ID
    , SSM.WUP_BEREICH_ID
    , SSM.WUP_ABT_ID
    , SSM.DAYFORCE_MINIMAL_MAPPING
    , SSM.DAYFORCE_XREFCODE
    , SSM.DAT
    , SSM.ZEIT_STUNDE
    , SSM.ZEIT_15MIN
    , SSM.WERT_GESAMT  -- NO FILTER - REFERENCE
    , SSM.WERT_MINIMAL -- FILTER 3 - MINIMAL
    , SSM.WERT_AUFGABE -- FILTER 2 - AUFGABE
    , SSM.WERT_TREIBER -- FILTER 1 - DYN. TREIBER
    , SSM.WERT_TREIBER * SWC.SSM_UMSATZ_FAKTOR              AS WERT_TREIBER_FAKTOR -- TREIBER (INKL. UMSATZFAKTOR)
    , CASE WHEN 
            CASE WHEN SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
                THEN 1 
                ELSE 0 
            END 
            * SUM(SSM.WERT_MINIMAL) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) 
            > CASE WHEN SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
                THEN 1 
                ELSE 0 
            END 
            * SUM(SSM.WERT_AUFGABE + WERT_TREIBER_FAKTOR) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) 
                THEN 
                    CASE WHEN  SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
                        THEN 1 
                        ELSE 0
                    END 
            * SUM(SSM.WERT_MINIMAL) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) 
            - CASE WHEN SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
                THEN 1 
                ELSE 0
            END 
            * SUM(SSM.WERT_AUFGABE + WERT_TREIBER_FAKTOR) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) 
    ELSE 0.0000 END  AS WERT_DIFF_FAKTOR
    , WERT_AUFGABE + WERT_TREIBER_FAKTOR + WERT_DIFF_FAKTOR AS WERT_XREF_FAKTOR    -- WERT XREFCODE (INKL. UMSATZFAKTOR)
    , CASE WHEN SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
        THEN 1 
        ELSE 0
    END 
    * SUM(SSM.WERT_MINIMAL) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
    AS SUM_MINIMAL -- MINIMAL PRO DF_MIN_MAPPING
    ,  CASE WHEN SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
        THEN 1 
        ELSE 0
    END 
    * SUM(SSM.WERT_AUFGABE + WERT_TREIBER_FAKTOR) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
    AS SUM_FAKTOR -- TREIBER/AUFGABE PRO DF_MIN_MAPPING
    , CASE WHEN SSM.DAYFORCE_XREFCODE =  MAX(SSM.DAYFORCE_XREFCODE) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN)
        THEN 1 
        ELSE 0
    END AS XFAKTOR -- FILTERUNG AUF XREFCODE MIT MINIMAL 
    , CASE WHEN SUM_MINIMAL > XFAKTOR * SUM(SSM.WERT_AUFGABE + SSM.WERT_TREIBER) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) 
        THEN SUM_MINIMAL - XFAKTOR * SUM(SSM.WERT_AUFGABE + SSM.WERT_TREIBER) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) 
        ELSE 0.0000 
    END  AS WERT_DIFF_OHNE
    , WERT_AUFGABE + WERT_TREIBER + WERT_DIFF_OHNE AS WERT_XREF_OHNE      -- WERT XREFCODE OHNE UMSATZFAKTOR
    , XFAKTOR * SUM(SSM.WERT_AUFGABE + SSM.WERT_TREIBER) OVER (PARTITION BY SSM.MANDANT_ID, SSM.NB_ID, WUP.AKTUELL_WUP_ID, SSM.WUP_BEREICH_ID, SSM.WUP_ABT_ID, SSM.DAYFORCE_MINIMAL_MAPPING, SSM.DAT, SSM.ZEIT_STUNDE, SSM.ZEIT_15MIN) AS SUM_OHNE -- TREIBER/AUFGABE PRO DF_MIN_MAPPING

FROM ( -- SUBSELECT, AGGREGATION PRO BEREICH/ABT/XREFCODE/15MIN
    SELECT
        SWTS.MANDANT_ID
        , SWTS.NB_ID
        , SWTS.WUP_ID
        , SWTS.WUP_BEREICH_ID
        , SWTS.WUP_ABT_ID
        , LSP.DAYFORCE_XREFCODE
        , LSP.DAYFORCE_MINIMAL_MAPPING
        , OEFFNUNG_LADEN_THEKEN_FG
        , SWTS.DAT
        , SWTS.ZEIT_STUNDE
        , SWTS.ZEIT_15MIN
        , SUM(CASE LSP.SSM_AUFWAND_TYP_ID WHEN 1 THEN SWTS.WERT ELSE 0.0000 END)           AS WERT_TREIBER -- NUR DYNAMISCHE TREIBER
        , SUM(CASE LSP.SSM_AUFWAND_TYP_ID WHEN 2 THEN SWTS.WERT ELSE 0.0000 END)           AS WERT_AUFGABE -- NUR AUFGABE
        , SUM(CASE LSP.SSM_AUFWAND_TYP_ID WHEN 3 THEN SWTS.WERT ELSE 0.0000 END)           AS WERT_MINIMAL -- NUR MINIMAL
        , SUM(SWTS.WERT)                                                                   AS WERT_GESAMT  -- WERT UNGEFILTERT
        , SUM(CASE LSP.SSM_AUFWAND_TYP_ID WHEN 1 THEN SWTS.WERT_GERUNDET ELSE 0.0000 END ) AS WERT_GERUNDET_TREIBER -- NUR DYNAMISCHE TREIBER
        , SUM(CASE LSP.SSM_AUFWAND_TYP_ID WHEN 2 THEN SWTS.WERT_GERUNDET ELSE 0.0000 END ) AS WERT_GERUNDET_AUFGABE -- NUR AUFGABE
        , SUM(CASE LSP.SSM_AUFWAND_TYP_ID WHEN 3 THEN SWTS.WERT_GERUNDET ELSE 0.0000 END ) AS WERT_GERUNDET_MINIMAL -- NUR MINIMAL
        , SUM(SWTS.WERT_GERUNDET)                                                          AS WERT_GERUNDET_GESAMT  -- WERT UNGEFILTERT

    FROM DBP_VIEW.V_SSM_WUP_TAG_STUNDE  SWTS

    JOIN DBP_VIEW.V_L_SSM_PROZESS  LSP
    ON SWTS.SSM_PROZESS_ID = LSP.SSM_PROZESS_ID AND SWTS.MANDANT_ID = LSP.MANDANT_ID AND LSP.DAT_BIS= '9999-12-31'

    GROUP BY
        SWTS.MANDANT_ID
        , SWTS.NB_ID
        , SWTS.WUP_ID
        , SWTS.WUP_BEREICH_ID
        , SWTS.WUP_ABT_ID
        , LSP.DAYFORCE_XREFCODE
        , LSP.DAYFORCE_MINIMAL_MAPPING
        , OEFFNUNG_LADEN_THEKEN_FG
        , SWTS.DAT
        , SWTS.ZEIT_STUNDE
        , SWTS.ZEIT_15MIN
) SSM

JOIN ( -- SSM_WUPCAL
    SELECT
    WC1.MANDANT_ID,
    WC1.WUP_ID,
    WC1.DAT,
    WC1.SSM_UMSATZ_FAKTOR
    FROM DBP_MSI_VIEW_VIS.MV_SSM_WUPCAL WC1
) SWC
ON SSM.MANDANT_ID = SWC.MANDANT_ID AND SSM.WUP_ID = SWC.WUP_ID
AND SSM.DAT = SWC.DAT

INNER JOIN dbp_view.v_wup WUP
ON SSM.MANDANT_ID = WUP.MANDANT_ID AND SSM.WUP_ID = WUP.WUP_ID

;