CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_VIS_TAG_UMSATZ_STUNDEN_BEREICH(
	MANDANT_ID,
	NB_ID,
	WUP_ID,
	WRG_ID,
	DAT,
	HR_OBJEKT_BEREICH_ID,
	UMS_NETTO,
	UMS_NETTO_WVJ,
	UMS_NETTO_KVJ,
	STUNDEN_NETTO,
	STUNDEN_NETTO_PLAN,
	STUNDEN_SOLL_FIX,
	STUNDEN_SOLL_DYN,
	STUNDEN_SOLL
) AS 
 
/*	FAKT : UMSATZ UND STUNDEN (IST, PLAN, SOLL) PRO FILIALE/BEREICH UND TAG
	NETTOLEISTUNG BEREICH : PROJEKTION UMSATZ/STUNDEN AUF FILIALE/BEREICH (SHR)
	2018.0809 SSCH0611 : INITIAL - INTERNATIONALE STRUKTUR
	2018.0816 AWOL2209 : MAPPING ABT_ID ZU HR_OBJEKT_BEREICH_ID AUF HWG_ID GEAENDERT.
	2018.0912 SSCH0611 : ERWEITERUNG SSM (SOLLSTUNDEN) 
	2018.1113 SSCH0611 : WG-REFRESH - NEUE STRUKTUR MAPPING UEBER ABTEILUNG - BUGFIX/FILTER
	2019.0119 SSCH0611 : ANPASSUNG SUMME (SAP TIME + PEP) 
	2019.0125 SSCH0611 : FILTER UMSATZ (KASSE) REMOVED + INT STRUKTUR (SSM_ABT)
	2019.0520 SSCH0611 : UMSTELLUNG AUF NETTOSTUNDEN_BEREICH (EXTERNE STUNDEN), BEREICH -1 ERGAENZT
	2019.0520 SSCH0611 : STUNDEN_TYP_FG (0=IST, 1=PLAN) 
                         QUELLE_ID (1= GFOS ORACLE, 2=SAP TIME, 3=DAYFORCE, 4=PEP, 5=GFOS EXCEL, 7=UPLOAD SHAREPOINT, 9=TRANSACTION FRONTEND)
	2019.0703 SSCH0611 : SONSTIGE (EXTERNE) STUNDEN - UPDATE
	2019.0828 SSCH0611 : SWITCH QUELLE_ID (5 GFOS EXCEL > 1 GFOS ORACLE) > STICHTAG 01.09.2019
	2019.1011 SSCH0611 : UPDATE BEREICH (KASSE/THEKE ETC.), MAPPING HWG > OWG
	2019.1125 SSCH0611 : UPDATE MAPPING SSM (THEKE)
	2020-11-13 SSCH0611 : REMOVED SSM_WUP_TAG_STUNDE PART (TABLE CHANGED), 3 Dummy Metriken
	2024-06-17 ssch0611 : Filter: Generell Filiale + ZF. Review + Historie/GFOS angepasst. 
	2024-07-31 muellerpatri : Entfernen von Filter auf hr_objekt_bereich = 11
	2024-08-22 ssch0611 : Filialumgliederung + Review [P1760-DWH]
*/
 
SELECT
  VIS.MANDANT_ID
, VIS.NB_ID
, WUP.aktuell_wup_id AS WUP_ID
, VIS.WRG_ID
, VIS.DAT
, VIS.HR_OBJEKT_BEREICH_ID
, VIS.UMS_NETTO
, VIS.UMS_NETTO_WVJ
, VIS.UMS_NETTO_KVJ
, NSB.STUNDEN_NETTO
, NSB.STUNDEN_NETTO_PLAN
, 0.00 AS STUNDEN_SOLL_FIX 
, 0.00 AS STUNDEN_SOLL_DYN 
, 0.00 AS STUNDEN_SOLL 
FROM ( 
	SELECT /* PART I - Umsatz Filiale */
	  vis00.MANDANT_ID
	, vis00.NB_ID
	, vis00.WUP_ID
	, vis00.WRG_ID
	, vis00.DAT
	, hob00.hr_objekt_bereich_id
	, SUM(UMS_NETTO)     AS UMS_NETTO
	, SUM(UMS_NETTO_WVJ) AS UMS_NETTO_WVJ
	, SUM(UMS_NETTO_KVJ) AS UMS_NETTO_KVJ
	FROM DBP_MSI_V_VIEW.V_VIS_TAG_UMSATZ_KUNDE_WUP vis00
	CROSS JOIN (
		SELECT DISTINCT hr_objekt_bereich_id 
		FROM dbp_view.v_l_org_einheit_bereich
		WHERE hr_objekt_bereich_id IN (-1,10,60)
	) hob00
	WHERE vis00.NB_ID IN (-1, 0) AND vis00.AKT_GJ BETWEEN -1 AND 1
	GROUP BY vis00.MANDANT_ID, vis00.NB_ID, vis00.WUP_ID, vis00.WRG_ID, vis00.DAT, hob00.HR_OBJEKT_BEREICH_ID
	UNION ALL 
	SELECT /* PART II - Umsatz Bereich/OWG */
	  vis01.MANDANT_ID
	, vis01.NB_ID
	, vis01.WUP_ID
	, vis01.WRG_ID
	, vis01.DAT
	, ware.HR_OBJEKT_BEREICH_ID
	, SUM(UMS_NETTO) UMS_NETTO
	, SUM(UMS_NETTO_WVJ) UMS_NETTO_WVJ
	, SUM(UMS_NETTO_KVJ) UMS_NETTO_KVJ
	FROM DBP_MSI_V_VIEW.V_VIS_TAG_UMSATZ_WG vis01
	JOIN ( -- Internationales Mapping OWG auf hr_objekt_bereich_id
		SELECT DISTINCT OWG.HR_OBJEKT_BEREICH_ID, WG.OWG_ID, WG.WG_ID
		FROM DBP_VIEW.V_WG_PER  WG
		INNER JOIN DBP_VIEW.V_OWG_PER OWG
		ON OWG.OWG_ID = WG.OWG_ID AND OWG.DAT_BIS = '9999-12-31' AND OWG.ARTHIERTYP_ID = 2
	) ware
	ON ware.WG_ID = vis01.WG_ID
	WHERE vis01.NB_ID IN (-1, 0)
	GROUP BY vis01.MANDANT_ID, vis01.NB_ID, vis01.WUP_ID, vis01.WRG_ID, vis01.DAT, ware.HR_OBJEKT_BEREICH_ID
) VIS
LEFT JOIN ( 
	SELECT DISTINCT /* PART III - NETTOSTUNDEN BEREICH (IST, PLAN) */
	  NSB.MANDANT_ID
	, NSB.NB_ID
	, NSB.WUP_ID
	, NSB.DAT
	, NSB.HR_OBJEKT_BEREICH_ID
	 /* Quelle 1 (GFOS ORACLE) ab 2019-09-01, daher Filter/Case auf QUELLE 5 (GFOS EXCEL) entfernt  */
	, SUM(CASE WHEN STUNDEN_TYP_FG = 0 THEN STUNDEN ELSE 0.00 END) AS STUNDEN_NETTO
	, SUM(CASE WHEN STUNDEN_TYP_FG = 1 THEN STUNDEN ELSE 0.00 END) AS STUNDEN_NETTO_PLAN
	FROM DBP_VIEW.V_NETTOSTUNDEN_BEREICH  NSB
	GROUP BY NSB.MANDANT_ID, NSB.NB_ID, NSB.WUP_ID, NSB.DAT, NSB.HR_OBJEKT_BEREICH_ID
) NSB
ON NSB.WUP_ID = VIS.WUP_ID AND NSB.MANDANT_ID = VIS.MANDANT_ID AND NSB.DAT = VIS.DAT
AND NSB.HR_OBJEKT_BEREICH_ID = VIS.HR_OBJEKT_BEREICH_ID
 
JOIN DBP_VIEW.V_WUP WUP
ON WUP.WUP_ID = VIS.WUP_ID AND WUP.MANDANT_ID = VIS.MANDANT_ID
;