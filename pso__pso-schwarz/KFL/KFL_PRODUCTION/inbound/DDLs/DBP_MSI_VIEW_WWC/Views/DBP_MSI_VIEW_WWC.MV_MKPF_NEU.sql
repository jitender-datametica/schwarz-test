CREATE OR REPLACE view DBP_MSI_VIEW_WWC.MV_MKPF_NEU as
SELECT
    V01.MANDANT_ID,
    TO_VARCHAR(V01.LAGERBEW_BELEG_ID, 'FM0000000000') AS MBLNR,
    TO_VARCHAR(V01.LAGERBEW_BELEG_ID),
    V01.KJ AS MJAHR,
    V01.VORGANGSART_ID AS VGART,
    V01.DAT_BUCH AS BUDAT,
    V01.BELEG_USER_NAME AS USNAM,
    V01.REF_LAGERBEW_BELEG_ID AS XBLNR,
    V01.DAT_BELEG AS BLDAT,
    V01.DAT_ERFASST AS CPUDT,
    CAST(
        to_char(V01.DAT_ERFASST, 'YYYY-MM-DD ') || CASE
            WHEN V01.ZEIT_ERFASST IS NULL THEN '00:00:00'
            ELSE TO_CHAR(V01.ZEIT_ERFASST, '00:00:00')
        END AS TIMESTAMP_NTZ
    ) AS CPUDT_CPUTM,
    CAST(
        to_char(V01.DAT_ERFASST, 'YYYY-MM-DD ') || CASE
            WHEN V01.ZEIT_ERFASST IS NULL THEN '00:00:00'
            ELSE TO_CHAR(V01.ZEIT_ERFASST, '00:00:00')
        END AS TIMESTAMP_NTZ
    ) AS CPUDT_CPUTM_STR,
    V01.BELEGART_ID AS BLART,
    V01.BELEGKOPFTEXT AS BKTXT,
    V01.WAREN_BEGL_SCHEIN_ID AS XABLN,
    V01.TRANSAKTION_CODE AS TCODE2,
    0 AS AKT_FG
FROM
    DBP_VIEW.V_LAGERBEW V01
    LEFT OUTER JOIN DBP_VIEW.V_LAGERBEW_DELTA B ON V01.MANDANT_ID = B.MANDANT_ID
    AND V01.LAGERBEW_BELEG_ID = B.LAGERBEW_BELEG_ID
    AND V01.KJ = B.KJ
    AND V01.DAT_BUCH = B.DAT_BUCH
WHERE
    B.MANDANT_ID IS NULL
UNION
ALL
SELECT
    MANDANT_ID,
    TO_VARCHAR(LAGERBEW_BELEG_ID, 'FM0000000000') AS MBLNR,
    TO_VARCHAR(LAGERBEW_BELEG_ID),
    KJ AS MJAHR,
    VORGANGSART_ID AS VGART,
    DAT_BUCH AS BUDAT,
    BELEG_USER_NAME AS USNAM,
    REF_LAGERBEW_BELEG_ID AS XBLNR,
    DAT_BELEG AS BLDAT,
    DAT_ERFASST AS CPUDT,
    CAST(
        to_char(DAT_ERFASST, 'YYYY-MM-DD ') || CASE
            WHEN ZEIT_ERFASST IS NULL THEN '00:00:00'
            ELSE TO_CHAR(ZEIT_ERFASST, '00:00:00')
        END AS TIMESTAMP_NTZ
    ) AS CPUDT_CPUTM,
    CAST(
        to_char(DAT_ERFASST, 'YYYY-MM-DD ') || CASE
            WHEN ZEIT_ERFASST IS NULL THEN '00:00:00'
            ELSE TO_CHAR(ZEIT_ERFASST, '00:00:00')
        END AS TIMESTAMP_NTZ
    ) AS CPUDT_CPUTM_STR,
    BELEGART_ID AS BLART,
    BELEGKOPFTEXT AS BKTXT,
    WAREN_BEGL_SCHEIN_ID AS XABLN,
    TRANSAKTION_CODE AS TCODE2,
    1 AS AKT_FG
FROM
    DBP_VIEW.V_LAGERBEW_DELTA
    ;