create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_ZB.V_DIM_PROJEKTTERMIN_SPR_ZU(
	PROJEKTTERMIN_CD,
	PROJEKTTERMIN_BEZ,
	PROJEKTTERMIN_BEZ_DE,
	PROJEKTTERMIN_BEZ_CZ,
	PROJEKTTERMIN_BEZ_SK,
	PROJEKTTERMIN_BEZ_HR,
	PROJEKTTERMIN_BEZ_PL,
	PROJEKTTERMIN_BEZ_RO,
	PROJEKTTERMIN_BEZ_BG
) as 
SELECT 
--MANDANT_ID
PROJEKTTERMIN_CD
,COALESCE(MAX(CASE WHEN SPR_ID =  22  THEN PROJEKTTERMIN_BEZ END),'N/A') AS PROJEKTTERMIN_BEZ                       
,COALESCE(MAX(CASE WHEN SPR_ID =  22  THEN PROJEKTTERMIN_BEZ END),'N/A') AS PROJEKTTERMIN_BEZ_DE                 
,COALESCE(MAX(CASE WHEN SPR_ID = 124 THEN PROJEKTTERMIN_BEZ END),  PROJEKTTERMIN_BEZ_DE ) AS PROJEKTTERMIN_BEZ_CZ    
,COALESCE(MAX(CASE WHEN SPR_ID = 108 THEN PROJEKTTERMIN_BEZ END),  PROJEKTTERMIN_BEZ_DE ) AS PROJEKTTERMIN_BEZ_SK    
,COALESCE(MAX(CASE WHEN SPR_ID =  65  THEN PROJEKTTERMIN_BEZ END), PROJEKTTERMIN_BEZ_DE ) AS PROJEKTTERMIN_BEZ_HR     
,COALESCE(MAX(CASE WHEN SPR_ID =  90  THEN PROJEKTTERMIN_BEZ END), PROJEKTTERMIN_BEZ_DE ) AS PROJEKTTERMIN_BEZ_PL     
,COALESCE(MAX(CASE WHEN SPR_ID =  95  THEN PROJEKTTERMIN_BEZ END), PROJEKTTERMIN_BEZ_DE ) AS PROJEKTTERMIN_BEZ_RO     
,COALESCE(MAX(CASE WHEN SPR_ID =  18  THEN PROJEKTTERMIN_BEZ END), PROJEKTTERMIN_BEZ_DE ) AS PROJEKTTERMIN_BEZ_BG    
FROM 
DBP_DATA.PROJEKTTERMIN_SPR_ZU
GROUP BY 1
;
