create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_ZB.V_GEWERK_SPR_ZU(
	MANDANT_ID,
	GEWERK_ID,
	GEWERK_BEZ,
	GEWERK_BEZ_DE,
	GEWERK_BEZ_CZ,
	GEWERK_BEZ_SK,
	GEWERK_BEZ_HR,
	GEWERK_BEZ_PL,
	GEWERK_BEZ_RO,
	GEWERK_BEZ_BG
) as 
SELECT 
MANDANT_ID
,GEWERK_ID
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id =  22  THEN GEWERK_BEZ END),'N/A') 
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ                       
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id =  22  THEN GEWERK_BEZ END),'N/A')
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_DE                 
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id = 124 THEN GEWERK_BEZ END), GEWERK_BEZ_DE )
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_CZ    
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id = 108 THEN GEWERK_BEZ END), GEWERK_BEZ_DE )
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_SK    
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id =  65  THEN GEWERK_BEZ END), GEWERK_BEZ_DE )
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_HR     
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id =  90  THEN GEWERK_BEZ END), GEWERK_BEZ_DE )
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_PL     
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id =  95  THEN GEWERK_BEZ END), GEWERK_BEZ_DE )
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_RO     
,CASE WHEN GEWERK_ID < 8 THEN COALESCE(MAX(CASE WHEN spr_id =  18  THEN GEWERK_BEZ END), GEWERK_BEZ_DE )
WHEN GEWERK_ID = 8 THEN 'Baukostenzuschüsse' 
WHEN  GEWERK_ID = 9 THEN 'Förderungen' ELSE NULL END AS GEWERK_BEZ_BG    
FROM 
DBP_DATA.GEWERK_SPR_ZU
GROUP BY 1,2
;
