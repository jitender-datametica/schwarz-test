CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW_WWC.MV_ART_AKTIV_KZ_ZU(
	MANDANT_ID,
	ART_ID,
	AKTIV_KZ
) AS
   SELECT
   V01.MANDANT_ID, V01.ART_ID, COALESCE(V03.AKTIV_KZ, 'K.A.') AS AKTIV_KZ
   FROM DBP_VIEW.V_ART V01
   LEFT OUTER JOIN
   (
   SELECT
   V02.MANDANT_ID, V02.ART_ID, CASE
   WHEN SUM(V02.ANZAHL_MARKT_LISTUNG) = 0 THEN ' '
   WHEN SUM(V02.ANZAHL_MARKT_LISTUNG) > 0 THEN 'X'
   END AS AKTIV_KZ

   FROM DBP_VIEW.V_STERNCHEN_LOGIK V02

   --WHERE V02.MANDANT_ID <> 1

   GROUP BY 1, 2
   )
   V03
   ON V01.MANDANT_ID = V03.MANDANT_ID
   AND V01.ART_ID = V03.ART_ID

   --WHERE V01.MANDANT_ID <> 1

   GROUP BY 1, 2, 3;