CREATE OR REPLACE VOLATILE TABLE _WEEK AS
(
SELECT MANDANT_ID,
       MAX(KJWO_UPDATE) AS KJWO
FROM DBP_DATA.SORTIMENT_LEISTUNG
GROUP BY 1
);

CREATE OR REPLACE VOLATILE TABLE _WEEK_PREV AS
(
SELECT A.MANDANT_ID,
       A.KJWO_UPDATE AS KJWO
FROM DBP_DATA.SORTIMENT_LEISTUNG A
JOIN DBP_DATA.WOCHE B 
  ON A.KJWO_UPDATE=B.KJWO 
  WHERE B.AKT_WO = (SELECT AKT_WO - 1 AS AKT_WO FROM DBP_DATA.WOCHE WHERE KJWO = (SELECT MAX(KJWO_UPDATE) AS KJWO FROM DBP_DATA.SORTIMENT_LEISTUNG))
  GROUP BY 1,2
);

CREATE OR REPLACE VOLATILE TABLE _MONAT AS (
SELECT X.MANDANT_ID,X.KJMO FROM 
(SELECT 
MANDANT_ID,
KJMO,
DENSE_RANK() OVER (PARTITION BY MANDANT_ID ORDER BY KJMO DESC) AS AKT_WO
FROM DBP_DATA.ART_NIELSEN_FAKTEN_KJMO
WHERE MANDANT_ID > 1
GROUP BY 1,2 ) X
WHERE AKT_WO BETWEEN 1 AND 12
);

CREATE OR REPLACE VOLATILE TABLE _RUN_CNT AS
(
SELECT COALESCE(MAX(RUN_CNT),0)+1 AS RUN_CNT
FROM DBP_ETL_PROCESS.MAT_TEST
WHERE KJWO = (SELECT MAX(KJWO_UPDATE) AS KJWO FROM DBP_DATA.SORTIMENT_LEISTUNG)
);

create or replace volatile table _art_nielsen as
(
 select * from dbp_data.art_nielsen where DAT_BIS='9999-12-31'
) ;

create or replace volatile table _ART_MATCHING_NIELSEN_PER_KMO as
