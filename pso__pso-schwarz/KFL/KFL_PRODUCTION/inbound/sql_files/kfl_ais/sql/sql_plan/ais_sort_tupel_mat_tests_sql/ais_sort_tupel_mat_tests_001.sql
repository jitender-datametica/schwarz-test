CREATE OR REPLACE VOLATILE TABLE _TUPEL_MAT_TEST_1 AS 
(
 SELECT 
 Q_MANDANT_ID
,Q_A500_KJWO_UPDATE
,Q_A425_KJMO
,Q_ANZAHL_KL
,P_ANZAHL_KL
,(Q_ANZAHL_KL - P_ANZAHL_KL) AS DIFFERENZ_KL 
FROM
(
    SELECT
    A.MANDANT_ID AS Q_MANDANT_ID
   ,A500_KJWO_UPDATE AS Q_A500_KJWO_UPDATE
   ,A425_KJMO AS Q_A425_KJMO
   ,SUM(CASE WHEN ART_ID IS NULL THEN 0 ELSE 1 END) AS Q_ANZAHL_KL
    FROM DBP_ETL_PROCESS.TUPEL_MAT_ETL A
   JOIN _WEEK B
   ON A.MANDANT_ID = B.MANDANT_ID AND 
      A.A500_KJWO_UPDATE = B.KJWO
    GROUP BY 1,2,3
) QU
JOIN 
(
   SELECT
   A.MANDANT_ID AS P_MANDANT_ID
  ,A500_KJWO_UPDATE AS P_A500_KJWO_UPDATE
  ,A425_KJMO AS P_A425_KJMO
  ,SUM(CASE WHEN ART_ID IS NULL THEN 0 ELSE 1 END) AS P_ANZAHL_KL
   FROM DBP_ETL_PROCESS.TUPEL_MAT_ETL A
   JOIN _WEEK_PREV B
    ON A.MANDANT_ID = B.MANDANT_ID AND 
      A.A500_KJWO_UPDATE = B.KJWO
   GROUP BY 1,2,3
) PRO
ON PRO.P_MANDANT_ID = QU.Q_MANDANT_ID
WHERE ABS(DIFFERENZ_KL)>1000
ORDER BY QU.Q_MANDANT_ID
);

