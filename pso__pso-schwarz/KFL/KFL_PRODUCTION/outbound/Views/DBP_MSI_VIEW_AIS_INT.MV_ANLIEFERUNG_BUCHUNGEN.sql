FROM kfl_production_dbp_view.v_anlieferung_management AS V1
 INNER JOIN kfl_production_dbp_view.v_anlieferung_management_det AS V2 ON V1.anlieferung_id = V2.anlieferung_id AND V1.mandant_id
    = V2.mandant_id
 LEFT JOIN kfl_production_dbp_view.v_besch_best AS V3 ON V2.best_beleg_id = V3.best_beleg_id AND V2.mandant_id = V3.mandant_id;