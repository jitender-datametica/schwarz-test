CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_ims.mv_monat (kjmo, kjmo_vj, gjmo, gjmo_vj, kjqu, gjqu, kj, gj,
akt_mo, akt_mo_komplett, akt_gjqu, akt_gjqu_komplett, akt_kjqu, akt_kjqu_komplett, akt_gj, akt_gj_komplett, akt_kj,
akt_kj_komplett, mo_gj, mo_kj, min_dat, max_dat, kjmo_vm) AS SELECT kjmo,
 kjmo_vj,
 gjmo,
 gjmo_vj,
 kjqu,
 gjqu,
 kj,
 gj,
 akt_mo,
 akt_mo_komplett,
 akt_gjqu,
 akt_gjqu_komplett,
 akt_kjqu,
 akt_kjqu_komplett,
 akt_gj,
 akt_gj_komplett,
 akt_kj,
 akt_kj_komplett,
 mo_gj,
 mo_kj,
 min_dat,
 max_dat,
 ROUND(CAST(FORMAT_DATE('%Y%m', DATE_ADD(PARSE_DATE('%Y%m', CAST(kjmo AS STRING)), INTERVAL - 1 MONTH)) AS BIGNUMERIC),
  0) AS kjmo_vm
FROM kfl_production_dbp_view.v_monat;