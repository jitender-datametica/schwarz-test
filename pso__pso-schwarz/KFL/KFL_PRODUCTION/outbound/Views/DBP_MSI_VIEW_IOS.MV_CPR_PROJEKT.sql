CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_ios.mv_cpr_projekt AS SELECT PR.projekt_id,
 PR.projekt_id AS projekt_id_lfd_nr,
 PR.cpr_ext_id AS projekt_nr,
 SUBSTR(PR.cpr_ext_id, 14, 2) AS projekt_nr_endung,
 TRIM(PR.techn_platz_id) AS techn_platz_id,
 2 AS techn_platz_ebene_id,
  CASE
  WHEN SUBSTR(PR.massnahme_id, 1, 5) = 'ZPPM_'
  THEN SUBSTR(PR.massnahme_id, 6, LENGTH(PR.massnahme_id) - 5)
  ELSE PR.massnahme_id
  END AS massnahme_kz,
 PR.massnahme_id,
 PR.cpr_kategorie_id,
 PR.projekt_anlass_id,
 PR.projektart_id,
 CAST(NULL AS STRING) AS cpr_projekt_gruppe_id,
 PR.dat_freigabe,
 SU.cpr_suchfeld,
 PR.mandant_id,
 COALESCE(V01.aktuell_wup_id, PR.wup_id) AS wup_id,
 PR.cpr_filialtyp_bez,
 PR.cpr_standort,
 PR.cpr_plz,
 PR.cpr_str,
 PR.cpr_vs,
 PR.cpr_vw,
 PR.region_id,
 PR.land_id,
 PR.markt_typ_ea,
 PR.markt_typ_vp,
 COALESCE(PR.kbl_nl_bez, PR.land_id) AS kbl_nl_bez,
 PR.cpr_betreuer_name,
 PR.objekt_planer_name,
 PR.plan_verantw_kz,
 PR.cpr_general_planer,
 PR.cpr_objekt_steurer AS cpr_projekt_steurer,
 PR_SPR.cpr_projekt_langtext,
 PR.pl_be_name,
 PR.pl_vertrieb_name,
 PR.pl_elektro,
 PR.pl_hls,
 COALESCE(PR.gj, 0) AS gj,
 PR.betrag_proj_kosten,
 COALESCE(PR.expansion_merkmal, '') AS expansion_merkmal,
 PR.expansion_auftrag_id,
 PR.cpr_auftraggeber_name,
 COALESCE(PR.investor_eigenobj, ' ') AS investor_eigenobj,
 PR.investor_name,
 PR.cpr_generalunternehmer_name,
 PR.leiter_eroeff_abn_name,
 PR.leiter_rohger_abn_name,
 PR.cpr_systemstatus1_id,
 PR.cpr_systemstatus2_id,
 PR.cpr_systemstatus3_id,
 PR.bauleiter_name,
 PR.bearbeit_ea_soa_name,
 PR.fach_ing_name,
 PR.ges_grund_flaeche_bez,
 PR.gu_ladenbau_name,
 PR.kaelte_lief_name,
 PR.log_massn,
 PR.pl_einrichtung_name,
 PR.statiker_name,
 PR.plan_verantwortl_name,
 PR.cpr_bl_projekt_bau_einr_name,
 PR.cpr_gen_ueb_name,
 PR.cpr_gen_unt_haust_name,
 PR.cpr_arch_ph_14_name,
 PR.cpr_arch_phase_58_name,
 PR.cpr_fachpl_name,
 PR.cpr_fachpl_kaelt_name,
 PR.cpr_fachpl_sonst_name,
 PR.cpr_gutachter_name,
 PR.cpr_vermesser_name,
 PR.cpr_fachin_tga_name,
 PR.cpr_qual_sich_bau_name,
 PR.cpr_qual_sich_haust_name,
 PR.cpr_gj_ber,
 PR.cpr_eig_proj,
 PR.cpr_gu_ausbau AS cpr_gen_unt_ausb_name,
 PR.einbau_kkv,
 DATE(NULL) AS dat_eroeffnung,
 DATE(NULL) AS dat_teil_oeffentl,
  CASE
  WHEN PR.kbl_nl_bez IS NOT NULL
  THEN TRIM(PR.land_id) || ' / Region  ' || TRIM(PR.kbl_nl_bez)
  ELSE TRIM(PR.land_id) || ' / Region  '
  END AS land_nl
FROM kfl_production_dbp_view.v_cpr_projekt_per AS PR
 INNER JOIN kfl_production_dbp_view.v_cpr_projekt_spr_zu_per AS PR_SPR ON PR.projekt_id = PR_SPR.projekt_id AND PR.dat_bis
    = PR_SPR.dat_bis
 LEFT JOIN kfl_production_dbp_view.v_l_cpr_suchfeld AS SU ON PR.cpr_suchfeld_id = SU.cpr_suchfeld_id
 LEFT JOIN kfl_production_dbp_view.v_wup AS V01 ON PR.wup_id = V01.wup_id AND PR.mandant_id = V01.mandant_id
WHERE PR.dat_bis = DATE '9999-12-31';