CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_ivs.mv_l_mietvertrag_hist (mietvertrag_id, mandant_id, dat_bis,
dat_von, debitor_werbung_id, debitor_miete_id, vertragart_id, konzessionaer_id, vermieter_id, vertrag_status_fg,
dat_vertrag_beginn, dat_vertrag_ende, dat_kuendbar_zum, dat_kuendigung, kuendigung_frist, kuend_frist_bez,
betrag_kaution, nebenkosten_betrag, nebenkosten_abschlag, sonderregelung_fg, wrg_id, mietindex_prozent, dat_mietindex,
mietauftrag_id, mietvertrag_option, mietvertrag_nr) AS SELECT mietvertrag_id,
 mandant_id,
 dat_bis,
 dat_von,
 debitor_werbung_id,
 debitor_miete_id,
 vertragart_id,
 konzessionaer_id,
 vermieter_id,
 vertrag_status_fg,
 dat_vertrag_beginn,
 dat_vertrag_ende,
 dat_kuendbar_zum,
 dat_kuendigung,
 kuendigung_frist,
 kuend_frist_bez,
 betrag_kaution,
 nebenkosten_betrag,
 nebenkosten_abschlag,
 sonderregelung_fg,
 wrg_id,
 mietindex_prozent,
 dat_mietindex,
 mietauftrag_id,
 mietvertrag_option,
 mietvertrag_nr
FROM kfl_production_dbp_view.v_ivs_mietvertrag_per
WHERE (mandant_id, mietvertrag_id, dat_von) IN (SELECT (mandant_id, mietvertrag_id, MAX(dat_von))
   FROM kfl_production_dbp_view.v_ivs_mietvertrag_per
   GROUP BY mandant_id,
    mietvertrag_id)
UNION ALL
SELECT '0' AS mietvertrag_id,
 mandant_id,
 CAST('1900-01-01' AS DATE) AS dat_von,
 CAST('9999-12-31' AS DATE) AS dat_bis,
 0 AS debitor_werbung_id,
 0 AS debitor_miete_id,
 SUBSTR('000', 1, 3) AS vertragart_id,
 '0' AS konzessionaer_id,
  mandant_id * - 1 AS vermieter_id,
 SUBSTR('0', 1, 1) AS vertrag_status_fg,
 CAST('1900-01-01' AS DATE) AS dat_vertrag_beginn,
 CAST('9999-12-31' AS DATE) AS dat_vertrag_ende,
 CAST('9999-12-31' AS DATE) AS dat_kuendbar_zum,
 CAST('9999-12-31' AS DATE) AS dat_kuendigung,
 0 AS kuendigung_frist,
 '' AS kuend_frist_bez,
 0 AS betrag_kaution,
 0 AS nebenkosten_betrag,
 0 AS nebenkosten_abschlag,
 0 AS sonderregelung_fg,
 wrg_id,
 0 AS mietindex_prozent,
 CAST('1900-01-01' AS DATE) AS dat_mietindex,
 0 AS mietauftrag_id,
 '' AS mietvertrag_option,
 '0' AS mietauftrag_nr
FROM kfl_production_dbp_view.v_mandant_wrg_typ_zu AS MWT
WHERE wrg_id = 'EUR';