CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_vis.mv_markt_lagerbuch_art AS WITH LABU AS (SELECT mandant_id,
   nb_id,
   wup_id,
   art_id,
   dat_lagerbuch,
   MIN(betrag_vk_brutto) AS betrag_vk_brutto_min,
   AVG(betrag_vk_brutto) AS betrag_vk_brutto_avg,
   MAX(betrag_vk_brutto) AS betrag_vk_brutto_max,
   COUNT(DISTINCT stellplatz_nr) AS anzahl_stellplatz,
   COUNT(DISTINCT markt_lagerbereich_id) AS anzahl_lagerbereich,
   COUNT(DISTINCT dat_mhd) AS anzahl_mhd,
   1 AS anzahl_artikel,
   SUM(menge_lagerbestand_stellplatz) AS menge_stellplatz_sum,
   MAX(menge_lagerbestand_gesamt) AS menge_lagerbestand,
   MAX(menge_filialbestand) AS menge_filialbestand,
   MAX(menge_opt_bestand) AS menge_opt_bestand,
   AVG(rate_verraeumung) AS rate_verraeum_avg,
   SUM(IF(rate_verraeumung = 0.00, 1, 0)) AS rate_verraeum_000_sum,
   SUM(IF(rate_verraeumung BETWEEN 0.01 AND 49.99, 1, 0)) AS rate_verraeum_001_sum,
   SUM(IF(rate_verraeumung BETWEEN 50.00 AND 79.99, 1, 0)) AS rate_verraeum_050_sum,
   SUM(IF(rate_verraeumung BETWEEN 80.00 AND 99.99, 1, 0)) AS rate_verraeum_080_sum,
   SUM(IF(rate_verraeumung = 100.00, 1, 0)) AS rate_verraeum_100_sum
  FROM kfl_production_dbp_view.v_markt_lagerbuch AS LABU
  GROUP BY mandant_id,
   nb_id,
   wup_id,
   art_id,
   dat_lagerbuch,
   anzahl_artikel), PRIO AS (SELECT mandant_id,
   nb_id,
   wup_id,
   art_id,
   dat_lagerbuch,
   MIN(IF(verraeumung_prio_grund_id NOT IN ('50', '55'), betrag_vk_brutto, NULL)) AS betrag_vk_brutto_ohne_min,
   AVG(IF(verraeumung_prio_grund_id NOT IN ('50', '55'), betrag_vk_brutto, NULL)) AS betrag_vk_brutto_ohne_avg,
   MAX(IF(verraeumung_prio_grund_id NOT IN ('50', '55'), betrag_vk_brutto, NULL)) AS betrag_vk_brutto_ohne_max,
   SUM(IF(verraeumung_prio_grund_id = '00', 1, 0)) AS verraeum_grund_00_sum,
   SUM(IF(verraeumung_prio_grund_id = '01', 1, 0)) AS verraeum_grund_01_sum,
   SUM(IF(verraeumung_prio_grund_id = '02', 1, 0)) AS verraeum_grund_02_sum,
   SUM(IF(verraeumung_prio_grund_id = '04', 1, 0)) AS verraeum_grund_04_sum,
   SUM(IF(verraeumung_prio_grund_id = '05', 1, 0)) AS verraeum_grund_05_sum,
   SUM(IF(verraeumung_prio_grund_id = '06', 1, 0)) AS verraeum_grund_06_sum,
   SUM(IF(verraeumung_prio_grund_id = '12', 1, 0)) AS verraeum_grund_12_sum,
   SUM(IF(verraeumung_prio_grund_id = '13', 1, 0)) AS verraeum_grund_13_sum,
   SUM(IF(verraeumung_prio_grund_id = '50', 1, 0)) AS verraeum_grund_50_sum,
   SUM(IF(verraeumung_prio_grund_id = '55', 1, 0)) AS verraeum_grund_55_sum,
   SUM(IF(verraeumung_prio_grund_id = '60', 1, 0)) AS verraeum_grund_60_sum,
   SUM(IF(verraeumung_prio_grund_id = '70', 1, 0)) AS verraeum_grund_70_sum,
   SUM(IF(verraeumung_prio_grund_id = '80', 1, 0)) AS verraeum_grund_80_sum,
               IF(SUM(IF(verraeumung_prio_grund_id = '00', 1, 0)) > 0, '00 ', '') || IF(SUM(IF(verraeumung_prio_grund_id
                     = '01', 1, 0)) > 0, '01 ', '') || IF(SUM(IF(verraeumung_prio_grund_id = '02', 1, 0)) > 0, '02 ', ''
               ) || IF(SUM(IF(verraeumung_prio_grund_id = '04', 1, 0)) > 0, '04 ', '') || IF(SUM(IF(verraeumung_prio_grund_id
                  = '05', 1, 0)) > 0, '05 ', '') || IF(SUM(IF(verraeumung_prio_grund_id = '06', 1, 0)) > 0, '06 ', '')
          || IF(SUM(IF(verraeumung_prio_grund_id = '12', 1, 0)) > 0, '12 ', '') || IF(SUM(IF(verraeumung_prio_grund_id =
              '13', 1, 0)) > 0, '13 ', '') || IF(SUM(IF(verraeumung_prio_grund_id = '50', 1, 0)) > 0, '50 ', '') || IF(SUM(IF(verraeumung_prio_grund_id
             = '55', 1, 0)) > 0, '55 ', '') || IF(SUM(IF(verraeumung_prio_grund_id = '60', 1, 0)) > 0, '60 ', '') || IF(SUM(IF(verraeumung_prio_grund_id
           = '70', 1, 0)) > 0, '70 ', '') || IF(SUM(IF(verraeumung_prio_grund_id = '80', 1, 0)) > 0, '80 ', '') AS
   verraeum_gruende_sum
  FROM kfl_production_dbp_view.v_markt_lagerbuch_verraeum_prio_grund_zu
  GROUP BY mandant_id,
   nb_id,
   wup_id,
   art_id,
   dat_lagerbuch) (SELECT t2.mandant_id,
   t2.nb_id,
   t2.wup_id,
   t2.art_id,
   t2.dat_lagerbuch AS dat,
   KRS.nach_wrg_id AS wrg_id,
    t2.betrag_vk_brutto_min * KRS.umrechnungskurs AS betrag_vk_brutto_min,
    t2.betrag_vk_brutto_avg * KRS.umrechnungskurs AS betrag_vk_brutto_avg,
    t2.betrag_vk_brutto_max * KRS.umrechnungskurs AS betrag_vk_brutto_max,
    t6.betrag_vk_brutto_ohne_min * KRS.umrechnungskurs AS betrag_vk_brutto_ohne_min,
    t6.betrag_vk_brutto_ohne_avg * KRS.umrechnungskurs AS betrag_vk_brutto_ohne_avg,
    t6.betrag_vk_brutto_ohne_max * KRS.umrechnungskurs AS betrag_vk_brutto_ohne_max,
   t2.anzahl_stellplatz,
   t2.anzahl_lagerbereich,
   t2.anzahl_mhd,
   t2.anzahl_artikel,
   t2.menge_stellplatz_sum,
   t2.menge_lagerbestand,
   t2.menge_filialbestand,
   t2.menge_opt_bestand,
   t2.rate_verraeum_avg,
   t2.rate_verraeum_000_sum,
   t2.rate_verraeum_001_sum,
   t2.rate_verraeum_050_sum,
   t2.rate_verraeum_080_sum,
   t2.rate_verraeum_100_sum,
   t6.verraeum_grund_00_sum,
   t6.verraeum_grund_01_sum,
   t6.verraeum_grund_02_sum,
   t6.verraeum_grund_04_sum,
   t6.verraeum_grund_05_sum,
   t6.verraeum_grund_06_sum,
   t6.verraeum_grund_12_sum,
   t6.verraeum_grund_13_sum,
   t6.verraeum_grund_50_sum,
   t6.verraeum_grund_55_sum,
   t6.verraeum_grund_60_sum,
   t6.verraeum_grund_70_sum,
   t6.verraeum_grund_80_sum,
   t6.verraeum_gruende_sum
  FROM LABU AS t2
   INNER JOIN PRIO AS t6 ON t2.mandant_id = t6.mandant_id AND t2.wup_id = t6.wup_id AND t2.art_id = t6.art_id AND t2.dat_lagerbuch
      = t6.dat_lagerbuch
   INNER JOIN kfl_production_dbp_view.v_mandant_wrg_zu_per AS WRG ON t2.mandant_id = WRG.mandant_id AND t2.dat_lagerbuch
     BETWEEN WRG.dat_von AND WRG.dat_bis
   INNER JOIN kfl_production_dbp_msi_view_vis.mv_kurs_umrechnung AS KRS ON WRG.wrg_id = KRS.von_wrg_id);