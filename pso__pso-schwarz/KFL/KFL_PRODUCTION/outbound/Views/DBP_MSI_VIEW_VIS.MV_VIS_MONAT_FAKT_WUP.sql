CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_vis.mv_vis_monat_fakt_wup (mandant_id, nb_id, wup_id, wrg_id, kjmo,
mo_kj, ums_netto, ums_netto_kvj, ums_netto_kvvj, ums_netto_plan, ums_netto_plan_extern, ums_netto_plan_x, anz_kunde,
anz_kunde_kvj, anz_kunde_kvvj, anz_offen, anz_offen_kvj, anz_offen_kvvj, pers_std, pers_std_kvj, pers_std_plan,
pers_kosten, pers_kosten_kvj, pers_kosten_plan, pers_k_ohne, pers_k_ohne_kvj, pers_k_ohne_plan, rohertrag, rohertrag_kvj
, rohertrag_plan, pers_auq, pers_auq_kvj, pers_fluq, pers_fluq_kvj, nl_ist, nl_plan) AS SELECT VIS.mandant_id,
 VIS.nb_id,
 WUP.aktuell_wup_id AS wup_id,
 VIS.wrg_id,
 VIS.kjmo,
 VIS.mo_kj,
 VIS.ums_netto,
 VIS.ums_netto_kvj,
 VIS.ums_netto_kvvj,
 VIS.ums_netto_plan,
 VIS.ums_netto_plan_extern,
 IF(VIS.ums_netto_plan_extern <> 0, VIS.ums_netto_plan_extern, VIS.ums_netto_plan) AS ums_netto_plan_x,
 VIS.anz_kunde,
 VIS.anz_kunde_kvj,
 VIS.anz_kunde_kvvj,
 VIS.anz_offen,
 VIS.anz_offen_kvj,
 VIS.anz_offen_kvvj,
 VIS.pers_std,
 VIS.pers_std_kvj,
 VIS.pers_std_plan,
 VIS.pers_kosten,
 VIS.pers_kosten_kvj,
 VIS.pers_kosten_plan,
 VIS.pers_k_ohne,
 VIS.pers_k_ohne_kvj,
 VIS.pers_k_ohne_plan,
 VIS.rohertrag,
 VIS.rohertrag_kvj,
 VIS.rohertrag_plan,
 VIS.pers_auq,
 VIS.pers_auq_kvj,
 VIS.pers_fluq,
 VIS.pers_fluq_kvj,
  VIS.ums_netto / IF(VIS.pers_std = 0, NULL, VIS.pers_std) AS nl_ist,
  VIS.ums_netto_plan / IF(VIS.pers_std_plan = 0, NULL, VIS.pers_std_plan) AS nl_plan
FROM kfl_production_dbp_msi_v_view.v_vis_monat_ums_kunde_pers_wup AS VIS
 INNER JOIN kfl_production_dbp_view.v_wup AS WUP ON VIS.mandant_id = WUP.mandant_id AND VIS.wup_id = WUP.wup_id;