 SUM(0) AS sum_artikel_markt
FROM kfl_production_dbp_msi_data.vis_tag_fwws_wg AS V01
 INNER JOIN kfl_production_dbp_view.v_wup AS WUP ON V01.mandant_id = WUP.mandant_id AND V01.wup_id = WUP.wup_id
GROUP BY V01.mandant_id,
 V01.nb_id,
 wup_id,
 V01.bezugsweg_id,
 V01.arthiertyp_id,
 V01.abt_id,
 V01.wg_id,
 V01.dat,
 V01.kjwo,
 V01.kjmo,
 V01.gj,
 V01.akt_tag,
 V01.dispomerkmal;