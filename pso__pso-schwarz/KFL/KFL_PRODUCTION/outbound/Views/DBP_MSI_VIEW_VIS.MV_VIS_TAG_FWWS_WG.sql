CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_vis.mv_vis_tag_fwws_wg (mandant_id, nb_id, wup_id, bezugsweg_id,
arthiertyp_id, abt_id, wg_id, dat, kjwo, kjmo, gj, akt_tag, dispomerkmal, anz_artikel_autodispo,
anz_artikel_markt_gelistet_okd, anz_artikel_markt_gelistet, anz_artikel_exc209, anz_artikel_exc214,
anz_artikel_autodispo_dm12, sum_artikel_autodispo, sum_artikel_markt_gelistet_okd, sum_artikel_markt_gelistet,
anz_artikel_markt, sum_artikel_markt) AS SELECT V01.mandant_id,
 V01.nb_id,
 WUP.aktuell_wup_id AS wup_id,
 V01.bezugsweg_id,
 V01.arthiertyp_id,
 V01.abt_id,
 V01.wg_id,
 V01.dat,
 V01.kjwo,
 V01.kjmo,
 V01.gj,
 V01.akt_tag,
 V01.dispomerkmal,
 SUM(CAST(V01.anz_artikel_autodispo AS BIGNUMERIC)) AS anz_artikel_autodispo,
 SUM(V01.anz_artikel_markt_gelistet_okd) AS anz_artikel_markt_gelistet_okd,
 SUM(V01.anz_artikel_markt_gelistet) AS anz_artikel_markt_gelistet,
 SUM(V01.anz_artikel_exc209) AS anz_artikel_exc209,
 SUM(V01.anz_artikel_exc214) AS anz_artikel_exc214,
