CREATE OR REPLACE PROCEDURE dbp_macro.m_update_sparte_standort(IN SPARTE_ID FLOAT64, IN MANDANT_ID FLOAT64, IN STANDORT_ID FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;
BEGIN TRANSACTION;
SET sql_stmt  =  '''UPDATE dbp_data.ims_standort SET  sparte_id = CAST(@SPARTE_ID AS INT64)  WHERE mandant_id = @MANDANT_ID AND standort_id = CASE WHEN LENGTH(CAST(@STANDORT_ID AS STRING)) < 4    THEN TRIM(CAST(@STANDORT_ID_1 AS STRING FORMAT "0000")) ELSE CAST(@STANDORT_ID_1_2 AS STRING)   END''';

EXECUTE IMMEDIATE (sql_stmt) USING SPARTE_ID AS SPARTE_ID,  MANDANT_ID AS MANDANT_ID,  STANDORT_ID AS STANDORT_ID,  STANDORT_ID AS STANDORT_ID_1,  STANDORT_ID AS STANDORT_ID_1_2;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;

