CREATE OR REPLACE VIEW FE_MSTR_AI_REPORTING.V_BAK_AGG_ITEM_STORE_DAY_MODEL_PREDICTION(
	CLIENT_ID
	,MODEL_SID
	,MODEL_RUN_DT
	,LOC_SID
	,ITEM_SID
	,PREDICTION_DT
	,SCORE_TYPE_SID
	,SCORE_MEAS
	,MODEL_AREA_CD
	,MODEL_GROUP_CD
	,DWH_LOAD_ID
	,DWH_CREATED
	,DWH_UPDATED
	,ASPECT_ID
	,MEAS_COUNT
) AS
    /* Version: 1.2
    ** Author:  Stefan Sockel
    ** Date:    2022-03-30
    ** Changes: Change ASPECT_ID to 1 (BGES)
    */
SELECT 
    SC.CLIENT_ID
	,SC.MODEL_SID
	,SC.MODEL_RUN_DT
	,SC.LOC_SID
	,SC.ITEM_SID
	,SC.PREDICTION_DT
	,SC.SCORE_TYPE_SID
	,SC.SCORE_MEAS
	,SC.MODEL_AREA_CD
	,SC.MODEL_GROUP_CD
	,SC.DWH_LOAD_ID
	,SC.DWH_CREATED
	,SC.DWH_UPDATED 
    ,1
    ,1
FROM 
    P_LEW_CORE.T_ITEM_STORE_DAY_MODEL_SCORE AS SC
WHERE
    SC.MODEL_SID = 2 
AND SC.SCORE_TYPE_SID IN (5,6,7)
AND (DAYNAME(SC.MODEL_RUN_DT) IN('Wed','Fri') OR SC.MODEL_RUN_DT = '2025-05-22');
 