CREATE OR REPLACE VIEW FE_MSTR_AI_REPORTING.V_SOD_AGG_ITEM_STORE_DAY_MODEL_ANOMALY(
	CLIENT_ID
	, MODEL_SID
	, MODEL_RUN_DT
	, LOC_SID
	, ITEM_SID
	, PREDICTION_DT
	, SCORE_TYPE_SID
	, SCORE_MEAS
	, MODEL_AREA_CD
	, MODEL_GROUP_CD
	, DWH_LOAD_ID
	, DWH_CREATED
	, DWH_UPDATED
	, ASPECT_ID
	, MEAS_COUNT
) AS
    /* Version: 1.0
    ** Author:  Stefan Sockel
    ** Date:    2022-11-09
    ** Changes: Initial version
    */
SELECT 
    SC.CLIENT_ID
	,SC.MODEL_SID
	,SC.MODEL_RUN_DT
	,SC.LOC_SID
	,SC.ITEM_SID
	,SC.PREDICTION_DT
	,SC.SCORE_TYPE_SID
	,SC.SCORE_MEAS
	,SC.MODEL_AREA_CD
	,SC.MODEL_GROUP_CD
	,SC.DWH_LOAD_ID
	,SC.DWH_CREATED
	,SC.DWH_UPDATED 
    ,2
    ,1
FROM 
    "P_LEW_CORE"."T_ITEM_STORE_DAY_MODEL_SCORE" AS SC
INNER JOIN
      (
      SELECT 
        ROW_NUMBER() OVER (PARTITION BY PREDICTION_DT ORDER BY MODEL_RUN_DT DESC) AS RN
        ,MODEL_RUN_DT
        ,PREDICTION_DT
      FROM 
        "P_LEW_CORE"."T_ITEM_STORE_DAY_MODEL_SCORE"
      GROUP BY MODEL_RUN_DT,PREDICTION_DT
      ) RW
ON 
    SC.MODEL_RUN_DT = RW.MODEL_RUN_DT AND SC.PREDICTION_DT = RW.PREDICTION_DT
WHERE
    RW.RN = 1 
;