CREATE OR REPLACE VIEW FE_MSTR_TOOLBOX_SPIEGEL.V_AGG_SPACEMAN_SECTION_STORE_AISLE_PAS_FTS(
   INT_ORG_SID
 , SPACEMAN_SECTION_SID
 , SECTION_WIDTH_MEAS
 , SHELF_WIDTH_MEAS
 , MAX_POTENTIAL_CONTACT_DISTANCE
 , MAX_POTENTIAL_CONTACT_DISTANCE_5
 , AVG_KOLLI
 , CNT_CASES
 , CNT_ITEM
 , SECTION_SELECTION_ID
 , METRIC_SYSTEM_ID
 , PAS_TYPE
 , HIGHER_MEAS
 , SHELF_METER
 , CLIENT_ID
 , MOVE_TO_STORE_ID
 , AISLE
) AS
SELECT 
    INT_ORG_SID
  , KPI.SPACEMAN_SECTION_SID
  , KPI.SECTION_WIDTH_MEAS
  , KPI.SHELF_WIDTH_MEAS
  , KPI.MAX_POTENTIAL_CONTACT_DISTANCE
  , KPI.MAX_POTENTIAL_CONTACT_DISTANCE_5
  , KPI.AVG_KOLLI
  , KPI.CNT_CASES
  , KPI.CNT_ITEM
  , KPI.SECTION_SELECTION_ID
  , KPI.METRIC_SYSTEM_ID
  , KPI.PAS_TYPE
  , KPI.HIGHER_MEAS
  , KPI.SHELF_METER
  , STORE.CLIENT_ID
  , STORE.MOVE_TO_STORE_ID
  , SSA.AISLE
FROM FE_MSTR_TOOLBOX_SPIEGEL.V_AGG_SPACEMAN_SECTION_PAS_FTS KPI

INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_SPACEMAN_SECTION_STORE SECSTORE

 ON KPI.SPACEMAN_SECTION_SID = SECSTORE.SPACEMAN_SECTION_SID
INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_ORG_STORE_MERGE_VGES STORE

 ON SECSTORE.LOC_SID_STORE = STORE.STORE_ID
INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_SPACEMAN_SECTION_STORE_AISLE SSA

 ON SECSTORE.SPACEMAN_SECTION_SID = SSA.SPACEMAN_SECTION_SID 
 AND STORE.MOVE_TO_STORE_ID = SSA.MOVE_TO_STORE_ID
 ;
