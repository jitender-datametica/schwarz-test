CREATE OR REPLACE VIEW FE_MSTR_TOOLBOX_SPIEGEL.V_MAT_REF_RECONSTRUCTION_WEEK(
	STORAGE_TEST_EXEC_SID
	,ORIG_STORE_NR
	,TEST_WEEK
	,RECONSTRUCTION_WEEK_FG
	,EXCLUDED_WEEK_FG
    ,COMPENSATION_WEEK_FG
) AS
SELECT TR.STORAGE_TEST_EXEC_SID 
    ,TR.ORIG_STORE_NR
    ,TR.TEST_WEEK
	,MAX(CASE WHEN TR.TEST_WEEK = PA.RECONSTRUCTIN_WEEK_LIST_GRAPH THEN 1 ELSE 0 END) AS RECONSTRUCTION_WEEK_FG
	,MAX(CASE WHEN TR.TEST_WEEK = PA.EXCLUDED_WEEK_LIST_GRAPH THEN 1 ELSE 0 END) AS EXCLUDED_WEEK_FG
	,CASE WHEN TR.TEST_WEEK = PA.TEST_WEEK_COMP THEN 1 ELSE 0 END AS COMPENSATION_WEEK_FG
FROM 
(SELECT 
TR.STORAGE_TEST_EXEC_SID 
    ,GRP.ORIG_STORE_NR
    ,GRP.TEST_WEEK
FROM P_LEW_CORE.T_STORAGE_TEST_RESULT TR
INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_STORAGE_TEST_EXECUTION_EXT EXT
        ON TR.STORAGE_TEST_EXEC_SID = EXT.STORAGE_TEST_EXEC_SID
INNER JOIN (
SELECT   STORAGE_TEST_RESULT_GRP_SID
		,storage_test_result_grp_type_cd 
		,loc.src_orig_store_nr AS orig_store_nr
		,test_week
	FROM p_lew_core.t_storage_test_result_group grp
	INNER JOIN p_lew_core.t_location  loc 
	       ON loc.loc_sid = grp.loc_sid_store
	WHERE UPPER(storage_test_result_grp_type_cd) = UPPER( 'Store')
 )grp 
ON grp.storage_test_result_grp_sid = tr.storage_test_result_grp_sid
)tr
INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_STORAGE_TEST_RESULT_PARAMETER_GRAPH pa
        ON tr.storage_test_exec_sid= pa.storage_test_exec_sid
	   AND tr.orig_store_nr= pa.orig_store_nr

 GROUP BY 1,2,3,6;