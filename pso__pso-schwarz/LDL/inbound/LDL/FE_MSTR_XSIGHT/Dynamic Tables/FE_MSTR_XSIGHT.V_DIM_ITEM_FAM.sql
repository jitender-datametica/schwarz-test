CREATE
	OR REPLACE DYNAMIC TABLE FE_MSTR_XSIGHT.V_DIM_ITEM_FAM (
	ITEM_FAM_GRP_CD,
	ITEM_FAM_GRP_NAME,
	ITEM_FAM_GRP_NAME_EN,
	ITEM_FAM_GRP_NAME2,
	ITEM_FAM_GRP_NAME2_EN
	) TARGET_LAG = '90 MINUTES' REFRESH_MODE = AUTO INITIALIZE = ON_CREATE WAREHOUSE = WH_LDL_%%environmentAbbreviation%%_DYNAMIC_TABLE_XSIGHT CLUSTER BY (
	ITEM_FAM_GRP_CD
	) AS

SELECT DISTINCT COALESCE(ITEM_FAM_GRP_CD,'-1') AS ITEM_FAM_GRP_CD
    ,MAX(COALESCE(ITEM_FAM_GRP_NAME_DE,'N/A')) AS ITEM_FAM_GRP_NAME
    ,MAX(COALESCE(ITEM_FAM_GRP_NAME_EN,'N/A')) AS ITEM_FAM_GRP_NAME_EN
    ,MAX(COALESCE(ITEM_FAM_GRP_CD,'-1') || ' ' || COALESCE(ITEM_FAM_GRP_NAME_DE,'N/A')) AS ITEM_FAM_GRP_NAME2
    ,MAX(COALESCE(ITEM_FAM_GRP_CD,'-1') || ' ' || COALESCE(ITEM_FAM_GRP_NAME_EN,'N/A')) AS ITEM_FAM_GRP_NAME2_EN
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_PRODUCT
GROUP BY
ITEM_FAM_GRP_CD;