CREATE
	OR REPLACE DYNAMIC TABLE FE_MSTR_XSIGHT.V_DIM_ITEM_GRP (
	ITEM_GRP_INT_CD
    ,ITEM_GRP_INT_NAME_EN
    ,ITEM_GRP_INT_NAME
	,ITEM_GRP_NAME2
    ,ITEM_GRP_NAME2_EN
	) TARGET_LAG = '90 MINUTES' REFRESH_MODE = AUTO INITIALIZE = ON_CREATE WAREHOUSE = WH_LDL_%%environmentAbbreviation%%_DYNAMIC_TABLE_XSIGHT CLUSTER BY (
	ITEM_GRP_INT_CD
	) AS

SELECT DISTINCT COALESCE(ITEM_GRP_INT_CD,'-1') AS ITEM_GRP_INT_CD
    ,MAX(COALESCE(ITEM_GRP_INT_NAME_EN,'N/A')) AS ITEM_GRP_INT_NAME_EN
    ,MAX(COALESCE(ITEM_GRP_INT_NAME_DE,'N/A')) AS ITEM_GRP_INT_NAME
	,MAX((ITEM_GRP_INT_CD ||' '|| ITEM_GRP_INT_NAME_DE)) AS ITEM_GRP_NAME2
    ,MAX((ITEM_GRP_INT_CD ||' '||ITEM_GRP_INT_NAME_EN)) AS ITEM_GRP_NAME2_EN
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_PRODUCT
GROUP BY
ITEM_GRP_INT_CD;