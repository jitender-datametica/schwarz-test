CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_DIM_BENCHMARK_CHANNEL (
	CHANNEL_NAME
	,DATA_PROVIDER_NAME
	,DATA_SRC_NAME
	,COUNTRY_CD
	,DATA_SRC_SEGMENT_NAME
	,CHANNEL_SID
	,BENCHMARK_CHANNEL_FG
	) AS

SELECT CH.MARKET_RESEARCH_CHANNEL_NAME
	,BCH.MARKET_RESEARCH_DATA_PROVIDER_NAME
	,BCH.MARKET_RESEARCH_DATA_SRC_NAME
	,BCH.MARKET_RESEARCH_COUNTRY_CD
	,BCH.MARKET_RESEARCH_DATA_SRC_SEGMENT_NAME
	,BCH.MARKET_RESEARCH_CHANNEL_SID
	,BCH.DEFAULT_BENCHMARK_CHANNEL_FG
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_BENCHMARK_CHANNEL BCH
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_CHANNEL CH ON BCH.MARKET_RESEARCH_DATA_PROVIDER_NAME = CH.MARKET_RESEARCH_DATA_PROVIDER_NAME
	AND BCH.MARKET_RESEARCH_DATA_SRC_NAME = CH.MARKET_RESEARCH_DATA_SRC_NAME
	AND BCH.MARKET_RESEARCH_CHANNEL_SID = CH.MARKET_RESEARCH_CHANNEL_SID;