CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_DIM_PERIOD (
	PERIOD_SID
	,PERIOD_SID_PY
	,PERIOD_NAME_PY
	,CALENDAR_NAME
	,PERIOD_NAME
	,PERIOD_TYPE_CD
	) AS

SELECT DISTINCT BP.MARKET_RESEARCH_PERIOD_SID AS PERIOD_SID
	,PYBP.MARKET_RESEARCH_PERIOD_SID AS PERIOD_SID_PY
	,PYBP.MARKET_RESEARCH_PERIOD_NAME AS PERIOD_NAME_PY
	,BP.MARKET_RESEARCH_CALENDAR_NAME AS CALENDAR_NAME
	,BP.MARKET_RESEARCH_PERIOD_NAME AS PERIOD_NAME
	,BP.MARKET_RESEARCH_PERIOD_TYPE_CD AS PERIOD_TYPE_CD
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD BP
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION PR --GET NIELSEN PERIOD
	ON BP.MARKET_RESEARCH_PERIOD_SID = PR.REL_MARKET_RESEARCH_PERIOD_SID
	AND PR.MARKET_RESEARCH_PERIOD_REL_TYPE_CD = 'src_to_bc'
JOIN P_LEW_CORE_AC.V_LOCAL_MARKET_RESEARCH_PERIOD LP --GET LOCAL PERIOD BY COUNTRY AND SRC_SEGMENT
	ON LP.MARKET_RESEARCH_PERIOD_SID = PR.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION PYPR --GET PREVIOUS YEAR BUSINESS PERIOD
	ON BP.MARKET_RESEARCH_PERIOD_SID = PYPR.MARKET_RESEARCH_PERIOD_SID
	AND PYPR.MARKET_RESEARCH_PERIOD_REL_TYPE_CD = 'prev_year'
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD PYBP ON PYPR.REL_MARKET_RESEARCH_PERIOD_SID = PYBP.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION PRPYLP --GET PREVIOS YEAR NIELSEN PERIOD
	ON PYPR.REL_MARKET_RESEARCH_PERIOD_SID = PRPYLP.REL_MARKET_RESEARCH_PERIOD_SID
	AND PRPYLP.MARKET_RESEARCH_PERIOD_REL_TYPE_CD = 'src_to_bc'
JOIN P_LEW_CORE_AC.V_LOCAL_MARKET_RESEARCH_PERIOD PYLP --GET PREVIOS YEAR LOCAL PERIOD BY COUNTRY AND SRC_SEGMENT
	ON PYLP.MARKET_RESEARCH_PERIOD_SID = PRPYLP.MARKET_RESEARCH_PERIOD_SID;