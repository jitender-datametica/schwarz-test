CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_FACT_PRODUCT_EVALUATION (
	MARKET_RESEARCH_PROD_SID
	,IM_SORTIMENT_MARKE
	,IM_SORTIMENT_EM
	,REGIONAL_SAISONAL
	,ANDERE_VERPACKUNGSGR_M_EM
	,AKTIONSARTIKEL_IN_OUT
	,VORSCHLAG_NIS_MARKE
	,VORSCHLAG_NIS_EIGENMARKE
	,VORSCHLAG_NIS_AKTION_IN_OUT
	,VORSCHLAG_NIS_AKTION_PV
	,NICHT_ERHAELTLICH
	) AS

SELECT I.MARKET_RESEARCH_PROD_SID
	,CASE 
		WHEN E.IM_SORTIMENT_MARKE = 1
			THEN 1
		ELSE 0
		END AS IM_SORTIMENT_MARKE
	,CASE 
		WHEN E.IM_SORTIMENT_EM = 1
			THEN 1
		ELSE 0
		END AS IM_SORTIMENT_EM
	,CASE 
		WHEN E.REGIONAL_SAISONAL = 1
			THEN 1
		ELSE 0
		END AS REGIONAL_SAISONAL
	,CASE 
		WHEN E.ANDERE_VERPACKUNGSGR_M_EM = 1
			THEN 1
		ELSE 0
		END AS ANDERE_VERPACKUNGSGR_M_EM
	,CASE 
		WHEN E.AKTIONSARTIKEL_IN_OUT = 1
			THEN 1
		ELSE 0
		END AS AKTIONSARTIKEL_IN_OUT
	,CASE 
		WHEN E.VORSCHLAG_NIS_MARKE = 1
			THEN 1
		ELSE 0
		END AS VORSCHLAG_NIS_MARKE
	,CASE 
		WHEN E.VORSCHLAG_NIS_EIGENMARKE = 1
			THEN 1
		ELSE 0
		END AS VORSCHLAG_NIS_EIGENMARKE
	,CASE 
		WHEN E.VORSCHLAG_NIS_AKTION_IN_OUT = 1
			THEN 1
		ELSE 0
		END AS VORSCHLAG_NIS_AKTION_IN_OUT
	,CASE 
		WHEN E.VORSCHLAG_NIS_AKTION_PV = 1
			THEN 1
		ELSE 0
		END AS VORSCHLAG_NIS_AKTION_PV
	,CASE 
		WHEN E.NICHT_ERHAELTLICH = 1
			THEN 1
		ELSE 0
		END AS NICHT_ERHAELTLICH
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_PRODUCT I
LEFT OUTER JOIN FE_MSTR_XSIGHT.T_FACT_PRODUCT_EVALUATION E ON I.MARKET_RESEARCH_PROD_SID = E.MARKET_RESEARCH_PROD_SID;