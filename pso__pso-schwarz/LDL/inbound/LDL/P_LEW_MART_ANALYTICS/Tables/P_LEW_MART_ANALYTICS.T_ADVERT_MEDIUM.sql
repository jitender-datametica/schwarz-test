CREATE TABLE P_LEW_MART_ANALYTICS.T_ADVERT_MEDIUM (
	CLIENT_ID NUMBER(38,0) NOT NULL,
	ADV_MEDIUM_SID NUMBER(38,0) NOT NULL,
