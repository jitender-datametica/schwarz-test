CREATE TABLE P_LEW_MART_ANALYTICS.T_ADVERT_WEEK (
	CLIENT_ID NUMBER(38,0) NOT NULL,
	ADV_WEEK_ID NUMBER(38,0) NOT NULL,
	ADV_WEEK_DESCR VARCHAR(50) NOT NULL COLLATE 'en-ci',
	ADV_WEEK_YEAR_NUM NUMBER(38,0) NOT NULL,
	ADV_WEEK_WEEK_NUM NUMBER(38,0) NOT NULL,
	ADV_WEEK_START_DT DATE NOT NULL,
	ADV_WEEK_END_DT DATE NOT NULL,
	DWH_CREATED TIMESTAMP_NTZ(9) NOT NULL,
	DWH_UPDATED TIMESTAMP_NTZ(9) NOT NULL,
	unique (CLIENT_ID, ADV_WEEK_ID)
);