CREATE OR REPLACE VIEW P_LEW_MART_ANALYTICS.V_FTM_CURRENCY 
(
    CLIENT_ID
    , COUNTRY_CODE
    , CURR_TOT_ID
    , CURRENCY_CODE
    , CURRENCY_DESC
    , LOCAL_CURRENCY_FG
    , TO_CURRENCY_CODE
    , RATE_CURRENCY_EXCHANGE
) AS
   SELECT
   RCRR.CLIENT_ID 
   , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
   , RCRR.CURR_TOT_ID
   , RCRR.CURRENCY_ISO_CD AS CURRENCY_CODE
   , RCRR.CURRENCY_DESC
   , RCRR.LOCAL_CURRENCY_FG
   , RCRR.TO_CURRENCY_ISO_CD AS TO_CURRENCY_CODE
   , RCRR.RATE_CURRENCY_EXCHANGE

  FROM P_LEW_MART_MSI_AC.V_REF_CURRENCY AS RCRR
  INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY AS RCTRY
    ON RCRR.COUNTRY_ID = RCTRY.COUNTRY_ID
;