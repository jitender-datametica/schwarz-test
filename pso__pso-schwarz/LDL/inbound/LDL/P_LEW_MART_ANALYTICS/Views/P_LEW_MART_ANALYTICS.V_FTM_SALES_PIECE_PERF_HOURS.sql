 CREATE OR REPLACE VIEW P_LEW_MART_ANALYTICS.V_FTM_SALES_PIECE_PERF_HOURS
(
    CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
    , WORK_TIME_TOTAL_HR
    , PIECE_PERFORMANCE
) 
AS
SELECT 
    SDPP.CLIENT_ID
    , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
    , SDPP.dwh_cal_dt DAT_FORMDATE
    , TAG.CY_WEEK AS CY_WEEK
    , SDPP.loc_sid_store AS STORE_ID
    , SDPP.src_orig_store_nr AS ORIG_STORE_NR
    , SDPP.WORK_TIME_TOTAL_HR
    , SDPP.PIECE_PERFORMANCE
FROM P_LEW_BIL_AC.V_AGG_STORE_DAY_PIECE_PERF AS SDPP

INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY AS TAG
    ON TAG.DAT_CALENDAR = SDPP.dwh_cal_dt

INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY AS RCTRY
    ON SDPP.CLIENT_ID = RCTRY.COUNTRY_ID
    
WHERE SDPP.currency_iso_cd = 'EUR'
;