CREATE OR REPLACE VIEW P_LEW_MART_ANALYTICS.V_MAT_FTM_TURNOVER(
	CLIENT_ID
	, COUNTRY_CODE
	, DAT_FORMDATE
	, CY_WEEK
	, STORE_ID
	, ORIG_STORE_NR
	, ITEM_ID
	, ORIG_ITEM_NR
	, ITEMGROUP_INT_ID
	, SUBITEMGROUP_ID
	, ITEM_TYPE
	, SALES_NET_VAL
	, SALES_PIECES_EJR
	, BUYING_VAL
	, SALES_BASED_MARGIN
	, SALES_BASED_MARGIN_PCT
    , DWH_UPDATED
) AS
/*
#----------------------------------------------------------------------------
# 22-08-2024 SNIK1809 - NEW setup
# 09-01-2025 SNIK1809 - Updated Buying with LDL_PRODUCTION.P_LEW_MART_LEAD.T_ITM_ORIG_ITEM
#----------------------------------------------------------------------------
*/

WITH A_SALES AS(
    SELECT
      A.CLIENT_ID
    , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
    , A.DAT_FORMDATE
    , TAG.CY_WEEK
    , A.STORE_ID
    , A.ORIG_STORE_NR
    , A.ITEM_ID
    , ART_INFO.ORIG_ITEM_NR
    , UWG_INFO.ITEMGROUP_INT_ID
    , ART_INFO.SUBITEMGROUP_ID
    , CASE WHEN ART_INFO.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
    , A.VAL_RTL_NET_EJR_ASIS + A.VAL_RETURN_NET_EJR_ASIS AS SALES_NET_VAL
    , A.QTY_PIECE_EJR_ASIS + A.QTY_WEIGHT_EJR_ASIS + A.QTY_RETURN_EJR_ASIS AS SALES_PIECES_EJR
    , '0' AS BUYING_VAL
    , '0' AS SALES_BASED_MARGIN
    , '0' AS SALES_BASED_MARGIN_PCT
    , PR.DWH_UPDATED AS DWH_UPDATED

    FROM P_LEW_MART_LEAD.V_AGG_STORE_DAY_ITEM_EJR_ASIS A
    
    INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY AS RCTRY
        ON A.CLIENT_ID = RCTRY.COUNTRY_ID
    
    INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY AS TAG
        ON TAG.DAT_CALENDAR = A.DAT_FORMDATE
    	
    INNER JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM AS ART_INFO
        ON ART_INFO.CLIENT_ID = A.CLIENT_ID
        AND ART_INFO.ITEM_ID = A.ITEM_ID
        AND ART_INFO.DAT_VALID_FROM <= A.DAT_FORMDATE
        
    INNER JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP AS UWG_INFO
        ON UWG_INFO.SUBITEMGROUP_ID = ART_INFO.SUBITEMGROUP_ID 

        INNER JOIN P_LEW_MART_MSI_AC.V_ORG_STORE_SKEY AS FIL
        ON FIL.CLIENT_ID = A.CLIENT_ID
        AND FIL.STORE_ID = A.STORE_ID

    -- NEW RECORDS + UPDATED OLD RECORDS WILL BE SEEN AS RESULT
    INNER JOIN (SELECT CLIENT_ID, LOC_SID, ITEM_SID,  MAX(DWH_UPDATED) AS DWH_UPDATED
				   FROM P_LEW_CORE_AC.V_POS_RECEIPTLINE
				   WHERE DWH_UPDATED >= DATEADD(WEEK, -10, CURRENT_DATE )
				   GROUP BY CLIENT_ID, LOC_SID, ITEM_SID
				) AS PR
     ON PR.CLIENT_ID = A.CLIENT_ID
    AND PR.ITEM_SID = A.ITEM_ID
    AND PR.LOC_SID = A.STORE_ID

    WHERE A.CURRENCY_ISO_CD = 'EUR' AND A.DAT_FORMDATE >= DATEADD(WEEK, -10, CURRENT_DATE )
)

, B_BUYING AS (
    SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN/ SALES_NET_VAL_B AS SALES_BASED_MARGIN_PCT
    , DWH_UPDATED
    
    FROM (
      (SELECT
          A.CLIENT_ID
        , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
        , A.DWH_CAL_DT AS DAT_FORMDATE
        , TAG.CY_WEEK
        , A.ST_LOC_SID AS STORE_ID
        , FIL.ORIG_STORE_NR
	    , ART_INFO2.ITEM_ID
        , A.ORIG_ITEM_NR
        , UWG_INFO.ITEMGROUP_INT_ID
        , ART_INFO.SUBITEMGROUP_ID
        , CASE WHEN ART_INFO2.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
        , FIL.WH_ID
        , '0' AS SALES_NET_VAL
        , '0' AS SALES_PIECES_EJR 
        , COUNT(ART_INFO2.ITEM_ID) OVER (PARTITION BY A.CLIENT_ID,A.ORIG_ITEM_NR,A.DWH_CAL_DT,A.ST_LOC_SID) AS CNT_ITM
        , A.SALES_BUYING_DIFF AS BUYING_VAL
       , A.SALES_NET_VAL/CNT_ITM AS SALES_NET_VAL_B
       , A.SALES_BUYING_DIFF/CNT_ITM AS SALES_BASED_MARGIN
       , A.SALES_BUYING_DIFF*CNT_ITM/A.SALES_NET_VAL AS SALES_BASED_MARGIN_PCT
       , ADJ.DWH_UPDATED AS DWH_UPDATED

        FROM P_LEW_MART_LEAD.V_AGG_AVG_BUY_PRICE_STR_DAY_ITM A
        
        INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY AS RCTRY
            ON A.CLIENT_ID = RCTRY.COUNTRY_ID
        
        INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY AS TAG
            ON TAG.DAT_CALENDAR = A.DWH_CAL_DT
        
        INNER JOIN P_LEW_MART_MSI_AC.V_ORG_STORE_SKEY AS FIL
            ON FIL.CLIENT_ID = A.CLIENT_ID
            AND FIL.STORE_ID = A.ST_LOC_SID
            
        INNER JOIN P_LEW_MART_LEAD.T_ITM_ORIG_ITEM AS ART_INFO
            ON ART_INFO.CLIENT_ID = A.CLIENT_ID
            AND ART_INFO.ORIG_ITEM_NR = A.ORIG_ITEM_NR
            AND ART_INFO.DAT_VALID_FROM = A.DAT_VALID_FROM
            
        INNER JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM AS ART_INFO2
            ON ART_INFO.CLIENT_ID = ART_INFO2.CLIENT_ID
            AND ART_INFO.ORIG_ITEM_NR  = ART_INFO2.ORIG_ITEM_NR            
           
        INNER JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP AS UWG_INFO
            ON UWG_INFO.SUBITEMGROUP_ID = ART_INFO.SUBITEMGROUP_ID

        	-- NEW RECORDS + UPDATED OLD RECORDS WILL BE SEEN AS RESULT
        INNER JOIN (
                    SELECT   MOVI.CLIENT_ID
                           , LOC_SID_WH
                           , I.ITEM_SID
                           , OSM.MOVE_TO_ST_LOC_SID AS ST_LOC_SID
                           , I.SRC_ORIG_ITEM_NR AS ORIG_ITEM_NR
        			       , MAX(COALESCE(DAT_ADJUSTMENT_RCV,ENTRY_DT)) AS DWH_UPDATED
                    FROM P_LEW_BIL_AC.V_MOV_ITEM_RECEIVE_WH MOVI
                    INNER JOIN P_LEW_CORE_AC.V_WAWI_ORG_ALL_STORE_MERGE_ACT AS OSM
                            ON MOVI.CLIENT_ID = OSM.CLIENT_ID
                           AND MOVI.LOC_SID_WH = OSM.WH_LOC_SID 
                           AND ASPECT_ID = 1
                    INNER JOIN P_LEW_CORE_AC.V_ITEM I
                            ON I.ITEM_SID = MOVI.ITEM_SID
            		WHERE COALESCE(DAT_ADJUSTMENT_RCV,ENTRY_DT) >= DATEADD(WEEK, -10, CURRENT_DATE )           
                    GROUP BY MOVI.CLIENT_ID, LOC_SID_WH, OSM.MOVE_TO_ST_LOC_SID, I.SRC_ORIG_ITEM_NR, I.ITEM_SID) AS ADJ
               ON ADJ.CLIENT_ID = A.CLIENT_ID
              AND ADJ.ORIG_ITEM_NR = A.ORIG_ITEM_NR
              AND ADJ.ST_LOC_SID = A.ST_LOC_SID 
              AND ADJ.ITEM_SID = ART_INFO2.ITEM_ID

        WHERE A.CURRENCY_ISO_CD = 'EUR' AND A.DWH_CAL_DT >= DATEADD(WEEK, -10, CURRENT_DATE )

        )

        UNION ALL

	( SELECT
          A.CLIENT_ID
        , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
        , A.DWH_CAL_DT AS DAT_FORMDATE
        , TAG.CY_WEEK
        , A.ST_LOC_SID AS STORE_ID
        , FIL.ORIG_STORE_NR
	    , ART_INFO2.ITEM_ID
        , A.ORIG_ITEM_NR
        , UWG_INFO.ITEMGROUP_INT_ID
        , ART_INFO.SUBITEMGROUP_ID
        , CASE WHEN ART_INFO2.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
        , FIL.WH_ID
        , '0' AS SALES_NET_VAL
        , '0' AS SALES_PIECES_EJR 
        , COUNT(ART_INFO2.ITEM_ID) OVER (PARTITION BY A.CLIENT_ID,A.ORIG_ITEM_NR,A.DWH_CAL_DT,A.ST_LOC_SID) AS CNT_ITM
        , A.SALES_BUYING_DIFF AS BUYING_VAL
       , A.SALES_NET_VAL/CNT_ITM AS SALES_NET_VAL_B
       , A.SALES_BUYING_DIFF/CNT_ITM AS SALES_BASED_MARGIN
       , A.SALES_BUYING_DIFF*CNT_ITM/A.SALES_NET_VAL AS SALES_BASED_MARGIN_PCT
	   , PR.DWH_UPDATED AS DWH_UPDATED

        FROM P_LEW_MART_LEAD.V_AGG_AVG_BUY_PRICE_STR_DAY_ITM A
        
        INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY AS RCTRY
            ON A.CLIENT_ID = RCTRY.COUNTRY_ID
        
        INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY AS TAG
            ON TAG.DAT_CALENDAR = A.DWH_CAL_DT
        
        INNER JOIN P_LEW_MART_MSI_AC.V_ORG_STORE_SKEY AS FIL
            ON FIL.CLIENT_ID = A.CLIENT_ID
            AND FIL.STORE_ID = A.ST_LOC_SID
            
        INNER JOIN P_LEW_MART_LEAD.T_ITM_ORIG_ITEM AS ART_INFO
            ON ART_INFO.CLIENT_ID = A.CLIENT_ID
            AND ART_INFO.ORIG_ITEM_NR = A.ORIG_ITEM_NR
            AND ART_INFO.DAT_VALID_FROM = A.DAT_VALID_FROM
            
        INNER JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM AS ART_INFO2
            ON ART_INFO.CLIENT_ID = ART_INFO2.CLIENT_ID
            AND ART_INFO.ORIG_ITEM_NR  = ART_INFO2.ORIG_ITEM_NR            
           
        INNER JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP AS UWG_INFO
            ON UWG_INFO.SUBITEMGROUP_ID = ART_INFO.SUBITEMGROUP_ID 

  -- NEW RECORDS + UPDATED OLD RECORDS WILL BE SEEN AS RESULT
        INNER JOIN (SELECT  R.CLIENT_ID
                           ,LOC_SID
                           , I.ITEM_SID
                           , I.SRC_ORIG_ITEM_NR AS ORIG_ITEM_NR
                           , MAX(R.DWH_UPDATED) AS DWH_UPDATED
					   FROM P_LEW_CORE_AC.V_POS_RECEIPTLINE R
                    INNER JOIN P_LEW_CORE_AC.V_ITEM I
                            ON I.ITEM_SID = R.ITEM_SID
					   WHERE R.DWH_UPDATED >= DATEADD(WEEK, -10, CURRENT_DATE )
                    GROUP BY R.CLIENT_ID, LOC_SID, I.SRC_ORIG_ITEM_NR, I.ITEM_SID
					) AS PR
                ON PR.CLIENT_ID = A.CLIENT_ID
               AND PR.ORIG_ITEM_NR = A.ORIG_ITEM_NR
               AND PR.LOC_SID = A.ST_LOC_SID  
               AND PR.ITEM_SID = ART_INFO2.ITEM_ID
               
         WHERE A.CURRENCY_ISO_CD = 'EUR' AND A.DWH_CAL_DT >= DATEADD(WEEK, -10, CURRENT_DATE)
	) 

   )
)
SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN_PCT
    , DWH_UPDATED
FROM(
    SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN_PCT
    , DWH_UPDATED
    FROM A_SALES

    UNION ALL
    
    SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN_PCT
    , DWH_UPDATED
    FROM B_BUYING
)
;