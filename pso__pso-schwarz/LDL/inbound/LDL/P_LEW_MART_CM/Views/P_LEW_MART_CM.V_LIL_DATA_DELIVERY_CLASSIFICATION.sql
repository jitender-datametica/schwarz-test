CREATE OR REPLACE VIEW P_LEW_MART_CM.V_LIL_DATA_DELIVERY_CLASSIFICATION
(
    CLIENT_ID
  , PERIOD_ID
  , YEAR_ID
  , PERIOD_TYPE_ID
  , DSC_NR
  , LFL_ID
  , PP_LFL_ID
  , PY_LFL_ID
)
AS
SELECT
      C.CLIENT_ID AS CLIENT_ID
    , DD.SRC_PERIOD_NR          AS PERIOD_ID
    , DD.PERIOD_YEAR            AS YEAR_ID
    , DD.PERIOD_TYPE_ID         AS PERIOD_TYPE_ID
    , DD.DSC_NR                 AS DSC_NR
    , DD.LFL_ID                 AS LFL_ID
    , PPDD.LFL_ID               AS PP_LFL_ID
    , PYDD.LFL_ID               AS PY_LFL_ID
FROM P_LEW_CORE_AC.V_LIL_DATA_DELIVERY_CLASSIFICATION AS DD
INNER JOIN P_LEW_MART_CM_AC.V_LIL_CLIENT AS C
ON DD.SRC_REGION_CD = C.COUNTRY_ISO_CD
INNER JOIN P_LEW_MART_CM.V_LIL_PERIOD AS P
ON DD.SRC_PERIOD_NR = P.PER_ID
LEFT OUTER JOIN P_LEW_CORE_AC.V_LIL_DATA_DELIVERY_CLASSIFICATION AS PPDD
ON P.PP_PER_ID=PPDD.SRC_PERIOD_NR
AND DD.SRC_REGION_CD = PPDD.SRC_REGION_CD
LEFT OUTER JOIN P_LEW_CORE_AC.V_LIL_DATA_DELIVERY_CLASSIFICATION AS PYDD
ON P.PY_PER_ID=PYDD.SRC_PERIOD_NR
AND DD.SRC_REGION_CD = PYDD.SRC_REGION_CD
;