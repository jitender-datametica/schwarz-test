CREATE OR REPLACE VIEW P_LEW_MART_CM.V_LIL_META_FILE_CONTENT
(
      CLIENT_ID
    , FILE_ID
    , REGION_ID
    , PERIOD_ID
    , SRC_ASSORT_PARENT_CAT_CD
    , DWH_CREATED
    , DWH_UPDATED
)
AS
   SELECT
      CON.CLIENT_ID                  AS CLIENT_ID
    , CON.FILE_ID                  AS FILE_ID
    , REG.REGION_ID                AS REGION_ID
    , PER.PERIOD_ID                AS PERIOD_ID
    , CON.SRC_ASSORT_PARENT_CAT_CD AS SRC_ASSORT_PARENT_CAT_CD
    , CON.DWH_CREATED              AS DWH_CREATED
    , CON.DWH_UPDATED              AS DWH_UPDATED
  FROM P_LEW_PROCESS_MSTR_AC.V_LIL_FILE_CONTENT AS CON
  INNER JOIN P_LEW_PROCESS_MSTR_AC.V_LIL_REGION AS REG
  ON REG.REGION_SID = CON.REGION_SID
  INNER JOIN P_LEW_PROCESS_MSTR_AC.V_LIL_PERIOD AS PER
  ON PER.PERIOD_SID = CON.PERIOD_SID
;
