CREATE OR REPLACE VIEW P_LEW_MART_LEAD.V_ACC_PRICE_LABEL_REPAIR_STATE(
  CLIENT_ID
 , MOVE_TO_STORE_ID
 , WH_ID
 , ASPECT_ID
 , PRICE_LABEL_PRODUCER_NAME
 , ELECTRONIC_PRICE_LABEL_TYPE_CD
 , ELECTRONIC_PRICE_LABEL_TYPE_CD_FE
 , DAT_FORMDATE
 , REPAIR_START_DT
 , REPAIR_END_DT
 , PRICE_LABEL_WARRANTY_STATUS_CD
 , PRICE_LABEL_REPAIR_RESULT_CD
 , PRICE_LABEL_REPAIR_ORIGIN_NAME
 , DEFECT_TXT
 , NET_PRICE
 , DEFECTPRICE
 , DEFECTPRICE_CUR
 , WH_DEFECTPRICE_CUR
 , CLIENT_DEFECTPRICE_CUR
 , INT_DEFECTPRICE_CUR
 , CURR_ISO_CD
 , PRICE_LABEL_SID
 , WH_LABEL_CNT
 , CLIENT_LABEL_CNT
 , INT_LABEL_CNT
 , DEFECT_COUNT
 , WH_DEFECT_COUNT
 , CLIENT_DEFECT_COUNT
 , INT_DEFECT_COUNT
 , NOTDEFECT_COUNT
 , WH_NOTDEFECT_COUNT
 , CLIENT_NOTDEFECT_COUNT
 , INT_NOTDEFECT_COUNT
 , WARRANTY_COUNT
 , WH_WARRANTY_COUNT
 , CLIENT_WARRANTY_COUNT
 , INT_WARRANTY_COUNT
) AS

 WITH SDAY AS 
 (
	SELECT DATEADD(DAY, -1*SEQ4(), CURRENT_DATE()) AS DAT_FORMDATE, DAYNAME(DAT_FORMDATE) AS DAT_NAME
	FROM TABLE(GENERATOR(ROWCOUNT => (100000) ))
	WHERE (UPPER(DAT_NAME) = 'SUN' OR DAT_FORMDATE = CURRENT_DATE-1)
	AND DAT_FORMDATE>= '2023-11-01'
 )

, CUR AS
(
	SELECT
	  A.CLIENT_ID
	 ,A.ACTIVE_FROM_DT
	 ,A.ACTIVE_TO_DT
	 ,A.DWH_VALID_FROM
	 ,A.DWH_VALID_TO
	 ,A.CURR_CD_FROM		AS CURR_CD_FROM_LOC
	 ,A.CURR_CD_TO			AS CURR_CD_TO_LOC
	 ,EURUSD.CURR_CD_FROM	AS CURR_CD_FROM_USD_EUR
	 ,EURUSD.CURR_CD_TO		AS CURR_CD_TO_USD_EUR
	 ,A.EXCHANGE_RATE		AS EXCNG_EUR_LOCCUR
	 ,EURUSD.EXCHANGE_RATE	AS EXCNG_USD_EUR
	FROM P_LEW_CORE_AC.V_EXCHANGE_RATE_KNOWN_HIST A
	INNER JOIN
	 (
	  SELECT 
	    CUR1.CLIENT_ID
	   ,CUR1.CURR_CD_FROM
	   ,CUR1.CURR_CD_TO
	   ,CUR1.EXCHANGE_RATE	
	  FROM P_LEW_CORE_AC.V_EXCHANGE_RATE_KNOWN_HIST AS CUR1
	  
	  INNER JOIN P_LEW_CORE_AC.V_EXCHANGE_RATE_TYPE AS CY1
	   ON  CY1.CLIENT_ID       = CUR1.CLIENT_ID
	   AND CY1.X_RATE_TYPE_SID = CUR1.X_RATE_TYPE_SID
	   AND CY1.SRC_KURST       = '@BEWE'
	  
	  WHERE  CUR1.CLIENT_ID = 33
	   AND CURRENT_DATE BETWEEN CUR1.ACTIVE_FROM_DT AND CUR1.ACTIVE_TO_DT
	   AND CURRENT_DATE BETWEEN CUR1.DWH_VALID_FROM AND CUR1.DWH_VALID_TO
	   AND CURR_CD_FROM = 'EUR'
	 )	EURUSD
	 ON A.CURR_CD_FROM = EURUSD.CURR_CD_FROM
	INNER JOIN P_LEW_CORE_AC.V_EXCHANGE_RATE_TYPE AS CY
	 ON  CY.CLIENT_ID       = A.CLIENT_ID
	 AND CY.X_RATE_TYPE_SID = A.X_RATE_TYPE_SID
	 AND CY.SRC_KURST       = '@BEWE'
	
	WHERE CURRENT_DATE BETWEEN A.ACTIVE_FROM_DT AND a.ACTIVE_TO_DT
	 AND CURRENT_DATE BETWEEN A.DWH_VALID_FROM AND A.DWH_VALID_TO
)
, LBL AS
 (
	SELECT DISTINCT
	 PLC.CLIENT_ID
	,PLC.MOVE_TO_STORE_ID
	,PLC.WH_ID
	,PLC.ASPECT_ID
	,PLRS.PRICE_LABEL_SID
	,PLRS.PRICE_LABEL_PRODUCER_NAME
	,PL.ELECTRONIC_PRICE_LABEL_TYPE_CD
	,PL.ELECTRONIC_PRICE_LABEL_TYPE_CD_FE
	,PLRS.REPAIR_START_DT
	,PLRS.REPAIR_END_DT
	,PLRS.PRICE_LABEL_WARRANTY_STATUS_CD
	,PLRS.PRICE_LABEL_REPAIR_RESULT_CD
	,PLRS.PRICE_LABEL_REPAIR_ORIGIN_NAME
	,PLRS.DEFECT_TXT

	
	/*DEFECT_LABELS:*/
	,CASE WHEN 
	/* IMAGOTAG DEFECT_LABELS:*/
		(	PLRS.PRICE_LABEL_PRODUCER_NAME = 'Imagotag'
		AND PLRS.PRICE_LABEL_REPAIR_RESULT_CD = 'Recycling' 
		AND PLRS.PRICE_LABEL_WARRANTY_STATUS_CD IN ( 'Excluded Warranty','Out of Warranty'))
	OR
	/* SOLUM DEFECT_LABELS:*/
		(	PLRS.PRICE_LABEL_PRODUCER_NAME = 'Solum'
		AND PLRS.PRICE_LABEL_REPAIR_ORIGIN_NAME = 'Customer'
		AND PLRS.DEFECT_TXT = 'DAMAGE')
	THEN 1 ELSE 0 END AS DEFECT_COUNT
	
	/*NOTDEFECT_LABELS:*/
	,CASE WHEN 
	/* IMAGOTAG NOTDEFECT_LABELS:*/
		(	PLRS.PRICE_LABEL_PRODUCER_NAME = 'Imagotag'
		AND PLRS.PRICE_LABEL_REPAIR_RESULT_CD = 'Returned functional')
	OR
	/* SOLUM NOTDEFECT_LABELS:*/
		(	PLRS.PRICE_LABEL_PRODUCER_NAME = 'Solum'
		AND PLRS.PRICE_LABEL_REPAIR_ORIGIN_NAME = 'Customer'
		AND PLRS.DEFECT_TXT = 'NDF')
	THEN 1 ELSE 0 END AS NOTDEFECT_COUNT
	
	/*WARRANTY_LABELS:*/
	,CASE WHEN 
	/* IMAGOTAG WARRANTY_LABELS:*/
		(	PLRS.PRICE_LABEL_PRODUCER_NAME = 'Imagotag'
		AND PLRS.PRICE_LABEL_WARRANTY_STATUS_CD = 'In Warranty'
		AND PLRS.PRICE_LABEL_REPAIR_RESULT_CD IN ('Replace','Credit note','Credit Note'))
	OR
	/* SOLUM WARRANTY_LABELS:*/
		(	PLRS.PRICE_LABEL_PRODUCER_NAME = 'Solum'
		AND PLRS.PRICE_LABEL_REPAIR_ORIGIN_NAME = 'Solum')
	THEN 1 ELSE 0 END AS WARRANTY_COUNT

    ,DEFECT_COUNT * PLPH.NET_PRICE AS DEFECTPRICE
    ,PLPH.NET_PRICE
    ,CAST(DEFECTPRICE * CUR.EXCNG_EUR_LOCCUR / CUR.EXCNG_USD_EUR AS DECIMAL(18,4)) AS DEFECTPRICE_CUR
    ,PLPH.CURR_ISO_CD
	
	FROM P_LEW_CORE_AC.V_PRICE_LABEL_REPAIR_STATE PLRS
	
	INNER JOIN P_LEW_MART_LEAD_AC.V_PRICE_LABEL PL
	ON PLRS.PRICE_LABEL_SID = PL.PRICE_LABEL_SID
	
	INNER JOIN P_LEW_CORE_AC.V_PRICE_LABEL_PRICE_HIST PLPH
	ON PL.ELECTRONIC_PRICE_LABEL_TYPE_CD = PLPH.ELECTRONIC_PRICE_LABEL_TYPE_CD
	AND PL.PRICE_LABEL_PRODUCER_NAME = PLPH.PRICE_LABEL_PRODUCER_NAME
	
	INNER JOIN P_LEW_MART_LEAD.V_PRICE_LABEL_STORE PLC
	ON PLRS.PRICE_LABEL_SID = PLC.PRICE_LABEL_SID
	AND PLRS.REPAIR_START_DT BETWEEN PLC.DWH_VALID_FROM AND PLC.DWH_VALID_TO

    INNER JOIN CUR
    ON  CUR.CLIENT_ID = PLC.CLIENT_ID
     
 )

 SELECT DISTINCT
     LBL.CLIENT_ID
   , LBL.MOVE_TO_STORE_ID
   , LBL.WH_ID
   , LBL.ASPECT_ID
   , LBL.PRICE_LABEL_PRODUCER_NAME
   , LBL.ELECTRONIC_PRICE_LABEL_TYPE_CD	
   , LBL.ELECTRONIC_PRICE_LABEL_TYPE_CD_FE
   , SDAY.DAT_FORMDATE
   , LBL.REPAIR_START_DT
   , LBL.REPAIR_END_DT
   , LBL.PRICE_LABEL_WARRANTY_STATUS_CD
   , LBL.PRICE_LABEL_REPAIR_RESULT_CD
   , LBL.PRICE_LABEL_REPAIR_ORIGIN_NAME
   , LBL.DEFECT_TXT
   , NET_PRICE
   , DEFECTPRICE
   , DEFECTPRICE_CUR
   , SUM(DEFECTPRICE_CUR) OVER (PARTITION BY CLIENT_ID,WH_ID,DAT_FORMDATE)	AS WH_DEFECTPRICE_CUR
   , SUM(DEFECTPRICE_CUR) OVER (PARTITION BY CLIENT_ID,DAT_FORMDATE)		AS CLIENT_DEFECTPRICE_CUR
   , SUM(DEFECTPRICE_CUR) OVER (PARTITION BY DAT_FORMDATE) 					AS INT_DEFECTPRICE_CUR
   , CURR_ISO_CD
   , LBL.PRICE_LABEL_SID
   , COUNT(LBL.PRICE_LABEL_SID) OVER (PARTITION BY CLIENT_ID,WH_ID,DAT_FORMDATE)AS WH_LABEL_CNT
   , COUNT(LBL.PRICE_LABEL_SID) OVER (PARTITION BY CLIENT_ID,DAT_FORMDATE) 		AS CLIENT_LABEL_CNT
   , COUNT(LBL.PRICE_LABEL_SID) OVER (PARTITION BY DAT_FORMDATE) 				AS INT_LABEL_CNT
   , LBL.DEFECT_COUNT
   , SUM(LBL.DEFECT_COUNT) OVER (PARTITION BY CLIENT_ID,WH_ID,DAT_FORMDATE) 	AS WH_DEFECT_COUNT
   , SUM(LBL.DEFECT_COUNT) OVER (PARTITION BY CLIENT_ID,DAT_FORMDATE)           AS CLIENT_DEFECT_COUNT
   , SUM(LBL.DEFECT_COUNT) OVER (PARTITION BY DAT_FORMDATE) 					AS INT_DEFECT_COUNT
   , LBL.NOTDEFECT_COUNT
   , SUM(LBL.NOTDEFECT_COUNT) OVER (PARTITION BY CLIENT_ID,WH_ID,DAT_FORMDATE)	AS WH_NOTDEFECT_COUNT
   , SUM(LBL.NOTDEFECT_COUNT) OVER (PARTITION BY CLIENT_ID,DAT_FORMDATE)		AS CLIENT_NOTDEFECT_COUNT
   , SUM(LBL.NOTDEFECT_COUNT) OVER (PARTITION BY DAT_FORMDATE) 					AS INT_NOTDEFECT_COUNT
   , LBL.WARRANTY_COUNT
   , SUM(LBL.WARRANTY_COUNT) OVER (PARTITION BY CLIENT_ID,WH_ID,DAT_FORMDATE)	AS WH_WARRANTY_COUNT
   , SUM(LBL.WARRANTY_COUNT) OVER (PARTITION BY CLIENT_ID,DAT_FORMDATE)			AS CLIENT_WARRANTY_COUNT
   , SUM(LBL.WARRANTY_COUNT) OVER (PARTITION BY DAT_FORMDATE) 					AS INT_WARRANTY_COUNT
 
 FROM SDAY
 JOIN LBL
 WHERE
 SDAY.DAT_FORMDATE >= LBL.REPAIR_START_DT
;