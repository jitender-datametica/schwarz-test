CREATE OR REPLACE VIEW P_LEW_MART_MSI.V_AGG_INT_DAY_ROC
/*
#----------------------------------------------------------------------------
# History:
#  1.0  18.07.2022    Oliver Haus         Initial DDL deployment - RWL aggregated values for Cockpits
#  1.1  10.07.2023    Chetana Patil       Added logic for RWL_WEIGHTED_VJ  
#----------------------------------------------------------------------------
*/
(
	INT_ID
  , CLIENT_ID
  ,	DAT_FORMDATE
  ,	CURRENCY_ISO_CD
  ,	QTY_PIECE_STC_WH
  ,	RWL_NOMINATOR
  ,	RWL_WEIGHTED
  , RWL_WEIGHTED_VJ
) COMMENT='Aggregated View on International-Level for RWL in Cockpits'
 AS
	 WITH VORJAHRESWERTE AS (
	   SELECT 
	   WH.INT_ID
	 , V02.CAL_DT AS DAT_FORMDATE
	 , V01.CURRENCY_ISO_CD
	 , SUM(V01.RWL_NOMINATOR)/SUM(V01.QTY_PIECE_EP_WH) AS RWL_WEIGHTED_VJ
	   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC V01
	   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE WH
	   ON V01.CLIENT_ID = WH.CLIENT_ID AND V01.WH_ID = WH.WH_ID
	   JOIN  P_LEW_MART_LEAD_AC.V_DIM_CAL_DAY V02
	   ON V01.DAT_FORMDATE = V02.CAL_DT_PREV_1Y
	   WHERE V01.FLAGS_COMBINED = '0000' 
	   AND WH.ASPECT_ID = 1
	   GROUP BY 
	   WH.INT_ID
	 , V02.CAL_DT
	 , V01.CURRENCY_ISO_CD)
	 
	, BASE AS (  
	   SELECT 
	   WH.INT_ID
	 , ROC.DAT_FORMDATE
	 , ROC.CURRENCY_ISO_CD
	 , SUM(ROC.QTY_PIECE_EP_WH) AS QTY_PIECE_STC_WH
	 , SUM(ROC.RWL_NOMINATOR) AS RWL_NOMINATOR
	 , SUM(ROC.RWL_NOMINATOR)/SUM(ROC.QTY_PIECE_EP_WH) AS RWL_WEIGHTED
	   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC ROC
	   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE WH
	   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
	   WHERE FLAGS_COMBINED = '0000'
	   AND WH.ASPECT_ID = 1
	   GROUP BY 
	   WH.INT_ID
	 , ROC.DAT_FORMDATE
	 , ROC.CURRENCY_ISO_CD)
	 
    SELECT   
	   COALESCE(BASE.INT_ID,VJ.INT_ID) AS INT_ID
	 , WH.CLIENT_ID
	 , COALESCE(BASE.DAT_FORMDATE, VJ.DAT_FORMDATE) AS DAT_FORMDATE
	 , COALESCE(BASE.CURRENCY_ISO_CD, VJ.CURRENCY_ISO_CD) AS CURRENCY_ISO_CD
	 , BASE.QTY_PIECE_STC_WH -- ON LEVEL INT
	 , BASE.RWL_NOMINATOR -- ON LEVEL INT
	 , BASE.RWL_WEIGHTED -- ON LEVEL INT 
	 , VJ.RWL_WEIGHTED_VJ -- ON LEVEL INT
	FROM BASE 
	FULL OUTER JOIN VORJAHRESWERTE VJ
	ON  BASE.INT_ID = VJ.INT_ID
	AND BASE.CURRENCY_ISO_CD = VJ.CURRENCY_ISO_CD
	AND BASE.DAT_FORMDATE = VJ.DAT_FORMDATE
	JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE WH 
	ON BASE.INT_ID = WH.INT_ID
;