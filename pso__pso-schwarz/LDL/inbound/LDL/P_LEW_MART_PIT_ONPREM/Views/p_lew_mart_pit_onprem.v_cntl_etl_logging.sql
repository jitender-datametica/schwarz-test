CREATE OR REPLACE VIEW P_LEW_MART_PIT_ONPREM.V_CNTL_ETL_LOGGING
AS
SELECT
      lg.RUN_ID_SEQ 
    , lg.RUN_TS
    , lg.RUN_DAY_ID
    , lg.RUN_CLUSTERING_DESC
    , lg.APPLICATION_NAME
    , lg.MODULE_NAME
    , lg.COMPONENT_NAME
    , lg.START_RUN_TS
    , lg.END_RUN_TS
    , lg.RUN_TIME_MIN
    , lg.RUN_TIME_SEC
    , lg.QUERY_TAG
    , lg.SF_USER
    , lg.SF_WAREHOUSE
    , lg.SF_ROLE
    , lg.SF_DATABASE
    , lg.SF_SCHEMA
    , lg.SF_SESSION
    , lg.SF_CLIENT
    , lg.RUN_LDESC
    , lg.RECORD_PROCESSED_NR
    , lg.START_PROCESSIG_FLAG
    , lg.END_PROCESSIG_FLAG
    , lg.MODULE_LEVEL_FLAG
    , lg.COMPONENT_LEVEL_FLAG
    , lg.COMPLETED_RUN_FLAG
    , (DENSE_RANK () OVER (ORDER BY lg.RUN_ID_SEQ DESC) -1 ) * (-1) MOVING_RUN_ID_FROM_CURRENT
FROM P_LEW_MART_PIT_ONPREM.T_CNTL_ETL_LOGGING lg
WHERE TRUE     
    AND lg.DELETED_FG = 0;