CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_HIVE_DIM_ITEM(
	COUNTRY  
	, ITEMNO  
	, ITEMDESC  
	, ITEMGROUPNO  
	, ITEMGROUPDESC  
	, SUBGROUPNO  
	, SUBGROUPDESC  
	, FAMILYNO  
	, FAMILYDESC  
	, TAX_RATE  
	, IS_WEIGHTED  
	, IS_SALE_WITHDRAWN  
	, SOURCE_EXTRACTION_TMSP  
	, SNFLK_INSERT_TMSP  
	, SNFLK_UPDATE_TMSP
) AS
SELECT *
FROM "CORE"."T_HIVE_ITEM"
QUALIFY SNFLK_INSERT_TMSP = MAX(SNFLK_INSERT_TMSP) OVER (PARTITION BY country,itemno) 
;
