	** Date: 	2023-05-24
	** Changes:	Initial version
	*/
SELECT DIC_AREA_ID
	,DIC_ACTIVE
	,MOD_DATE
	,DIC_AREA_NR
	,DIC_AREA_WH
	,COUNTRY
	,DIC_AREA_NAME
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_DIC_AREA_NEW

UNION ALL

SELECT da.DIC_AREA_ID
	,da.DIC_ACTIVE
	,da.MOD_DATE
	,da.DIC_AREA_NR
	,w.WARE_ID AS DIC_AREA_WH
	,da.COUNTRY
	,da.DIC_AREA_NAME
	,da.SOURCE_EXTRACTION_TMSP
	,da.SNFLK_INSERT_TMSP
	,da.SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_DIC_AREA da
JOIN CORE.T_ORACLE_V_DIM_WAREHOUSE w ON da.country = w.country
WHERE da.country NOT IN (
		SELECT DISTINCT country
		FROM CORE.T_ORACLE_V_DIC_AREA_NEW
		);