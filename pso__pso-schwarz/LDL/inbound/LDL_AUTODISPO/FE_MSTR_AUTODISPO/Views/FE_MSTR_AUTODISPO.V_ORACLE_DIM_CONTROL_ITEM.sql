CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_DIM_CONTROL_ITEM(
	COUNTRY
	, ITEM_NR
	, PARAM_NAME
	, SOURCE_EXTRACTION_TMSP
	, SNFLK_INSERT_TMSP
	, SNFLK_UPDATE_TMSP
) AS
    /* Version: 1.0
	** Author:	Dominik Pfarr
	** Date: 	2023-10-24
	** Changes:	initial version
	*/
SELECT COUNTRY
	,PARAM_VALUE ITEM_NR
    ,PARAM_NAME
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP 
FROM CORE.T_ORACLE_V_DD_PARAMETER
WHERE param_name = 'CONTROL_ITEM';