CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_DIM_COUNTRY(
	  COUNTRY
	, SOURCE_FLAG
	, ADL_ACTIVE_FLAG
) AS

    /* Version:   1.1
    ** Author:    Dominik Pfarr
    ** Date:      2023-03-22
    ** Changes:   adding flags
    */
SELECT COUNTRY
	,MAX(SOURCE_FLAG) AS SOURCE_FLAG
	,MAX(ADL_ACTIVE_FLAG) AS ADL_ACTIVE_FLAG
FROM FE_MSTR_AUTODISPO.V_ORACLE_DIM_WAREHOUSE
GROUP BY COUNTRY;