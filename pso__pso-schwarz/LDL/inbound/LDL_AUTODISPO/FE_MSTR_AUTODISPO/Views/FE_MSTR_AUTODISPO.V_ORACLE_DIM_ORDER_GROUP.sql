CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_DIM_ORDER_GROUP(
	COUNTRY
	,DOG_WH
	,DOG_NAME
	,DOG_ITEM
	,DOG_ACTIVE
	,MOD_DATE
	,DOG_CALCULATIONMETHOD
	,DOG_STORE
	,SOURCE_EXTRACTION_TMSP
	
) AS    /* Version:   1.2
    ** Author:    Dominik Pfarr
    ** Date:      2024-05-22
    ** Changes:   non historicized version using qualify statement to support also old table structure
    */
SELECT 
COUNTRY
	,DOG_WH AS WH
	,DOG_NAME
	,DOG_ITEM
	,DOG_ACTIVE
	,MOD_DATE
	,DOG_CALCULATIONMETHOD
	,DOG_STORE AS STORE
	,SOURCE_EXTRACTION_TMSP
	
FROM CORE.T_ORACLE_V_DIM_ORDER_GROUP
QUALIFY  ROW_NUMBER() OVER (PARTITION BY COUNTRY, DOG_ITEM, DOG_STORE ORDER BY mod_date DESC) =1;