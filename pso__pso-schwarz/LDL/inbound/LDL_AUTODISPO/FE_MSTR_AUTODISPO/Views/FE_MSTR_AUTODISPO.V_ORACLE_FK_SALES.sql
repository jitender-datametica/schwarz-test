CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_FK_SALES(
	 MOD_DATE
	,SALES_QUANTITY
	,DATE
	,SALES_VALUE
	,SALES_PRICE
	,SALES_RECEIPT_NR
	,DELETED
	,ITEM_NR
	,STORE
	,COUNTRY
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
) AS
    /* Version:   1.2
    ** Author:    Dominik Pfarr
    ** Date:      2024-03-12
    ** Changes:   switch to new date_ column
    */	

SELECT MOD_DATE
	,SALES_QUANTITY
	,DATE_ AS DATE
	,SALES_VALUE
	,SALES_PRICE
	,SALES_RECEIPT_NR
	,DELETED
	,SALES_ITEM_NR AS ITEM_NR
	,SALES_STORE_NR AS STORE
	,COUNTRY
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_FK_SALES
WHERE DELETED = 0;