CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_FK_STORE_TREND(
	COUNTRY
	, FST_STORETREND_ID
	, FST_TRENDTYPE
	, FST_WH
	, FST_STORE
	, FST_ORDERAREA
	, FST_ARTICLEGROUP
	, FST_GROUP_NR
	, FST_SUBGROUP_NR
	, FST_ARTICLE
	, FST_PERCENT
	, FST_DATEFROM
	, FST_DATETO
	, DATE_FROM
	, DATE_TO
	, MOD_DATE
	, SCENARIO
	, FST_SCENARIO
	, STORE_INFO
	, ARTICLE_INFO
	, SOURCE_EXTRACTION_TMSP
	, SNFLK_INSERT_TMSP
	, SNFLK_UPDATE_TMSP
) AS
    /* Version:   1.4
    ** Author:    Dominik Pfarr
    ** Date:      2023-07-31
    ** Changes:   adding fst_scenario for cross-checking purposes
    */	
    
SELECT s.COUNTRY
	,FST_STORETREND_ID
	,FST_TRENDTYPE
	,FST_WH
	,FST_STORE
	,FST_CALCULATIONMETHOD
	,FST_ARTICLEGROUP
	,FST_GROUP_NR
	,FST_SUBGROUP_NR
	,FST_ARTICLE
	,FST_PERCENT
	,FST_DATEFROM
	,FST_DATETO
	,DATEADD(DAY, FST_DATEFROM - 365.25 * (4712) - 2, '0000-01-01')::DATE DATE_FROM
	,DATEADD(DAY, FST_DATETO - 365.25 * (4712) - 2, '0000-01-01')::DATE DATE_TO
	,s.MOD_DATE
	,CONCAT (
		CASE WHEN (
					fst_store IS NULL
					AND FST_WH IS NULL
					) THEN 'Country' WHEN (FST_WH IS NULL) THEN 'Store' ELSE 'Warehouse' END
		,' & '
		,CASE WHEN (
					FST_CALCULATIONMETHOD IS NULL
					AND FST_ARTICLEGROUP IS NULL
					AND FST_GROUP_NR IS NULL
					AND FST_SUBGROUP_NR IS NULL
					AND FST_ARTICLE IS NULL
					) THEN 'All items' WHEN (FST_CALCULATIONMETHOD IS NOT NULL) THEN 'Calculation Method' WHEN (FST_ARTICLEGROUP IS NOT NULL) THEN 'Family' WHEN (FST_GROUP_NR IS NOT NULL) THEN 'Group' WHEN (FST_SUBGROUP_NR IS NOT NULL) THEN 'Subgroup' ELSE 'Item' END
		) AS SCENARIO
    ,FST_SCENARIO
	,CASE WHEN (
				fst_store IS NULL
				AND FST_WH IS NULL
				) THEN ('all') 
          WHEN (FST_WH IS NULL) THEN CONCAT (
					'STO '
					,fst_store
					) 
          ELSE CONCAT (
				'WH '
				,fst_wh
				) END AS store_info
	,CASE WHEN (
				FST_CALCULATIONMETHOD IS NULL
				AND FST_ARTICLEGROUP IS NULL
				AND FST_GROUP_NR IS NULL
				AND FST_SUBGROUP_NR IS NULL
				AND FST_ARTICLE IS NULL
				) THEN ('all') 
          WHEN (FST_CALCULATIONMETHOD IS NOT NULL) THEN CONCAT (
					'CM '
					,LEFT(cm.CALCULATIONMETHOD_NAME, 7)
					) 
          WHEN (FST_GROUP_NR IS NOT NULL) THEN CONCAT (
					'GRP '
					,FST_GROUP_NR
					) 
          WHEN (FST_ARTICLEGROUP IS NOT NULL) THEN CONCAT (
					'FAM '
					,FST_ARTICLEGROUP
					) 
         
          WHEN (FST_SUBGROUP_NR IS NOT NULL) THEN CONCAT (
					'SUB '
					,FST_SUBGROUP_NR
					) 
          ELSE CONCAT (
				'ITM '
				,FST_ARTICLE
				) END AS article_info
	,s.SOURCE_EXTRACTION_TMSP
	,s.SNFLK_INSERT_TMSP
	,s.SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_FK_STORE_TREND_NEW s
LEFT JOIN CORE.T_ORACLE_V_DIC_CALCULATIONMETHOD cm ON s.country = cm.country
	AND s.FST_CALCULATIONMETHOD = cm.CALCULATIONMETHOD;