CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_FK_TRUCKFILLING(
	COUNTRY
	, STORE_NR
	, TRF_DELIVERYDATE_ID
	, DATE
	, STORECALCULATION_ID
	, ORDER_TYPE
	, TRF_PALETTECOUNT
	, MOD_DATE
	, SOURCE_EXTRACTION_TMSP
	, SNFLK_INSERT_TMSP
	, SNFLK_UPDATE_TMSP
) AS
    /* Version: 1.1
	** Author:	Dominik Pfarr
	** Date: 	2024-03-14
	** Changes:	adding order type
	*/
SELECT COUNTRY
	,TRF_STORE_NR AS STORE_NR
	,TRF_DELIVERYDATE_ID
	,TRF_DELIVERYDATE AS DATE
	,TRF_STORECALCULATION_ID AS STORECALCULATION_ID
    ,'TRUCKFILLING'::VARCHAR(16777216) AS ORDER_TYPE
	,TRF_PALETTECOUNT
	,MOD_DATE
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_FK_TRUCKFILLING;