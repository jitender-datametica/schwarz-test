CREATE OR REPLACE PROCEDURE FE_MSTR_BCBI.P_INSERT_WAWI_MANUAL_EXTRACTION_ENTRY
(
P_CLIENT_ID NUMBER(38,0)
,P_SYSTEM_KEY NUMBER(38,0)
,P_WH_ID NUMBER(38,0)
,P_DAYEND_DATE DATE
,P_ENTRY_FROM VARCHAR(255)
,P_REASON VARCHAR(255)
)
RETURNS TEXT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
    IF (:P_DAYEND_DATE >= '2022-03-1'
    
        AND NOT EXISTS (SELECT 1 FROM FE_MSTR_BCBI.TS_WAWI_MANUAL_EXTRACTION
        WHERE  CLIENT_ID    = :P_CLIENT_ID
        AND    SYSTEM_KEY   = :P_SYSTEM_KEY
        AND    WH_ID        = :P_WH_ID
        AND    DAYEND_DATE  = :P_DAYEND_DATE
        AND    EXTRACTED_FG=0)
        
        AND EXISTS (SELECT 1 FROM FE_MSTR_BCBI.V_L_SOURCE_SYSTEM_WAWI_MANUAL_EXTRACTION
        WHERE   CLIENT_ID   = :P_CLIENT_ID
        AND     WH_ID       = :P_WH_ID
        AND     SYSTEM_KEY  = :P_SYSTEM_KEY))
    THEN 
        INSERT INTO FE_MSTR_BCBI.TS_WAWI_MANUAL_EXTRACTION
		SELECT
			:P_CLIENT_ID
			,:P_SYSTEM_KEY
			,:P_WH_ID
			,:P_DAYEND_DATE
			,:P_ENTRY_FROM
			,:P_REASON
			,0
			,CURRENT_TIMESTAMP()
			,NULL
		;
    END IF;
COMMIT;
END;
$$
;