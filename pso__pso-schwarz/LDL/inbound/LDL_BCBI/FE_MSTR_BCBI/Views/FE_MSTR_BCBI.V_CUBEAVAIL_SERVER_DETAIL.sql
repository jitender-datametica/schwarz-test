CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_CUBEAVAIL_SERVER_DETAIL AS
WITH CUBEAVAIL AS (
	SELECT
		DISTINCT T.JOB_ID
		,EXP.DAY AS DAY
		,calweek.WEEK_OF_YEAR AS WEEK
		,calweek.CY_WEEK_SHORT_NAME AS WEEK_NAME
		,calweek.CY_WEEK AS WEEK_ID
		,EXP.MONTH_OF_YEAR AS MONTH
		,EXP.MONTH_OF_YEAR_NAME AS MONTH_NAME
		,EXP.CY_MONTH AS MONTH_ID
		,EXP.CY AS YEAR
		,EXP.BUS_YEAR AS BUS_YEAR
		,EXP.ZONE
		,EXP.PROJECT_ID
		,EXP.PROJECT_NAME
		,EXP.CUBE_ID
		,EXP.CUBE_NAME
		,EXP.SUBCUBE_ID
		,EXP.SUBCUBE_NAME
		,T.CUBEACTIONID
		,CASE
			WHEN T.CUBEACTIONID IN (65536, 131073) THEN 'Cubing Server'
			ELSE 'Copy Server'
		END AS CUBEACTION
		,EXP.ISERVER_ID
		,EXP.ISERVER_NAME
		,EXP.FIRST_SOLUTION_ID
		,EXP.FIRST_SOLUTION_NAME
		,EXP.SEC_SOLUTION_ID
		,EXP.SEC_SOLUTION_NAME
		,T.STARTTIME AS START_TIME
		,T.FINISHTIME AS END_TIME
		,T.JOB_DURATION_MIN
		,T.ERROR_ID
		,T.ERROR_DESC
		,T.RESULT_ROWS
		,T.SQL_PASSES
		,CASE
			WHEN START_TIME IS NULL
			AND END_TIME IS NULL THEN 'Nicht Gestartet'
			WHEN START_TIME IS NOT NULL
			AND END_TIME IS NULL
			AND T.ERROR_ID = 0 THEN 'Gestartet'
			WHEN START_TIME IS NOT NULL
			AND T.ERROR_ID = 1 THEN 'Abgebrochen'
			WHEN START_TIME IS NOT NULL
			AND END_TIME IS NOT NULL
			AND T.ERROR_ID = 0 THEN 'Durchgelaufen'
		END AS CUBING_STATUS
		,CASE
			WHEN CUBING_STATUS = 'Durchgelaufen' THEN CASE
				WHEN (
					EXP.ZONE = 'EU'
					AND TIME(END_TIME) BETWEEN TO_TIME('07:31:00')
					AND TO_TIME('13:00:00')
				)
				OR (
					EXP.ZONE = 'US'
					AND TIME(END_TIME) BETWEEN TO_TIME('13:30:00')
					AND TO_TIME('18:00:00')
				) THEN 'VVTA'
				WHEN(
					EXP.ZONE = 'EU'
					AND TIME(END_TIME) BETWEEN TO_TIME('13:00:00')
					AND TO_TIME('22:00:00')
				)
				OR (
					EXP.ZONE = 'US'
					AND TIME(END_TIME) BETWEEN TO_TIME('18:00:00')
					AND TO_TIME('22:00:00')
				) THEN 'NVTA'
				WHEN(
					EXP.ZONE = 'EU'
					AND TIME(END_TIME) BETWEEN TO_TIME('04:00:00')
					AND TO_TIME('07:31:00')
				)
				OR (
					EXP.ZONE = 'US'
					AND TIME(END_TIME) BETWEEN TO_TIME('10:20:00')
					AND TO_TIME('13:30:00')
				) THEN 'VTA'
			END
			WHEN CUBING_STATUS = 'Gestartet'
			AND (
				(
					EXP.ZONE = 'EU'
					AND CURRENT_TIME > TO_TIME('07:31:00')
				)
				OR (
					EXP.ZONE = 'US'
					AND CURRENT_TIME > TO_TIME('13:30:00')
				)
			) THEN 'NVTA'
			ELSE ''
		END AS VTA_STATUS
	FROM
		FE_MSTR_BCBI.V_CUBEAVAIL_EXPECTED AS EXP
		LEFT JOIN (
			SELECT
				*
			FROM
				FE_MSTR_BCBI.V_CUBEAVAIL
			WHERE
				TIME(FINISHTIME) BETWEEN TO_TIME('04:00:00')
				AND TO_TIME('22:31:00')
		) T ON T.ZONE = EXP.ZONE
		AND Date(T.STARTTIME) = EXP.DAY
		AND T.REPORT_ID = EXP.SUBCUBE_ID
		AND T.SERVERMACHINE = EXP.ISERVER_NAME
		LEFT JOIN FE_MSTR_BCBI.T_DIM_CAL_WEEK AS calweek ON EXP.CY_WEEK = calweek.CY_WEEK
)
SELECT
	DISTINCT JOB_ID
	,DAY
	,WEEK
	,WEEK_NAME
	,WEEK_ID
	,MONTH
	,MONTH_NAME
	,MONTH_ID
	,YEAR
	,BUS_YEAR
	,ZONE
	,PROJECT_ID
	,PROJECT_NAME
	,CUBE_ID
	,CUBE_NAME
	,SUBCUBE_ID
	,SUBCUBE_NAME
	,CUBEACTIONID
	,CUBEACTION
	,ISERVER_ID
	,ISERVER_NAME
	,FIRST_SOLUTION_ID
	,FIRST_SOLUTION_NAME
	,SEC_SOLUTION_ID
	,SEC_SOLUTION_NAME
	,START_TIME
	,END_TIME
	,JOB_DURATION_MIN
	,ERROR_ID
	,ERROR_DESC
	,RESULT_ROWS
	,SQL_PASSES
	,CUBING_STATUS
	,VTA_STATUS
FROM
	CUBEAVAIL
WHERE
	(
		ZONE
		,DAY
		,PROJECT_NAME
		,CUBE_NAME
		,SUBCUBE_NAME
		,ISERVER_NAME
		,END_TIME
	) IN (
		SELECT
			DISTINCT ZONE
			,DAY
			,PROJECT_NAME
			,CUBE_NAME
			,SUBCUBE_NAME
			,ISERVER_NAME
			,END_TIME
		FROM
			(
				SELECT
					ZONE
					,DAY
					,PROJECT_NAME
					,CUBE_NAME
					,SUBCUBE_NAME
					,ISERVER_NAME
					,ERROR_ID
					,MIN(START_TIME) AS START_TIME
					,MIN(END_TIME) AS END_TIME
				FROM
					CUBEAVAIL
				WHERE
					ERROR_ID != 1
				GROUP BY
					ZONE
					,DAY
					,PROJECT_NAME
					,CUBE_NAME
					,SUBCUBE_NAME
					,ISERVER_NAME
					,ERROR_ID
			)
	);