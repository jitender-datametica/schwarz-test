CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_DATAAVAIL_STORE_FIRST_TRANSFER AS 
SELECT CLIENT_ID, WH_ID, ORIG_STORE_NR, SYSTEM_KEY, DAT_DAYEND
, MIN(TIMESTAMP_LOAD_BCBI) AS first_trans_date
FROM (SELECT lsp.CLIENT_ID, wh.WH_ID, lsp.ORIG_STORE_NR, lsp.SYSTEM_KEY, lsp.DAT_DAYEND, TO_DATE(lsp.TIMESTAMP_LOAD_BCBI) AS TIMESTAMP_LOAD_BCBI
    , SUM(CASE WHEN lsp.mail_rows IS NULL THEN 1 ELSE 0 END) AS missing_total
    FROM FE_MSTR_BCBI.T_WAWI_SYS_LOAD_STATUS_PRESENT lsp 
    INNER JOIN (SELECT DISTINCT SRC_WH_ID AS WH_ID, LOC_SID_WH, DWH_VALID_FROM, DWH_VALID_TO FROM FE_MSTR_BCBI.T_WAREHOUSE) wh --to get SRC_WH_ID (as WH_ID)
        ON lsp.wh_loc_sid = wh.loc_sid_wh
        AND lsp.dat_dayend BETWEEN wh.DWH_VALID_FROM AND wh.DWH_VALID_TO 
    INNER JOIN FE_MSTR_BCBI.V_DATAAVAIL_STORE_EXPECTED_LIST AS ex
        ON  lsp.CLIENT_ID     = ex.CLIENT_ID 
        AND wh.WH_ID          = ex.WH_ID 
        AND lsp.SYSTEM_KEY    = ex.SYSTEM_KEY 
        AND lsp.INTERFACE_KEY = ex.INTERFACE_KEY
        AND lsp.DAT_DAYEND    = ex.DAT_OPEN 
    WHERE lsp.system_key IN (2, 13) -- 2-EJR and 13-TXJ
    AND lsp.DAT_DAYEND < TO_DATE(lsp.TIMESTAMP_LOAD_BCBI)
    AND ex.is_mandatory = 1
    AND lsp.DAT_DAYEND >= '2022-04-23' --to skip first 30 day in lsp table, which are just used for calculation of is_prev_missing. min(TIMESTAMP_LOAD_BCBI) is '2022-04-24' in T_WAWI_SYS_LOAD_STATUS_PRESENT
    GROUP BY lsp.CLIENT_ID, wh.WH_ID, lsp.ORIG_STORE_NR, lsp.SYSTEM_KEY, lsp.DAT_DAYEND, lsp.TIMESTAMP_LOAD_BCBI
    HAVING missing_total = 0  
)
GROUP BY CLIENT_ID, WH_ID, SYSTEM_KEY, ORIG_STORE_NR, DAT_DAYEND
;