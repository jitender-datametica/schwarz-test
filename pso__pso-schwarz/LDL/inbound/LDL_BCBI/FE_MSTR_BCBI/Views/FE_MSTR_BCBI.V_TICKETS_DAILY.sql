CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_TICKETS_DAILY AS 
SELECT
    CASE WHEN TASK_TYPE = 'Spezifikation'
        THEN REPLACE(CONCAT(TASK_TYPE,'_',OPENED_AT),' ','_')--left(Betreff, 35),erstellt_am),' ','_') as ID,
        ELSE REPLACE(CONCAT(TASK_TYPE,'_',FIRST_ASSIGNMENT_GROUP,'_',OPENED_AT),' ','_') --left(Betreff, 35),erstellt_am),' ','_') as ID,
    END AS ID
    ,LOCATION AS COUNTRY_TICKET_ID
    ,SUBJECT
    ,STATE AS STATUS_
    ,TASK_TYPE AS TYPE
    ,SOLUTION
    ,AFFECTED_CI  AS CI
    ,PRIORITY
    ,ASSIGNMENT_GROUP AS ASSIGNED_TO_GROUP
    ,ASSIGNMENT_GROUP_HISTORY 
    ,FIRST_ASSIGNMENT_GROUP AS OPENED_BY_GROUP
    ,OPENED_AT AS CREATED_ON
    ,UPDATED_AT AS CHANGED_ON
    ,UPLOAD_DATE
FROM FE_MSTR_BCBI.t_tickets_daily;