CREATE OR REPLACE VIEW ETL.V_FACT_TURNOVER_FULLDATES (
       CAL_DT
     , BUS_YEAR
     , INT_ORG_SID
     , INT_ORG_TYPE_CD
     , COUNTRY_ORG_CD
     , CURR_CD
) AS
WITH
INT_ORG_YEARS AS
(
    SELECT  
          F.INT_ORG_SID
        , D1.BUS_YEAR
        , F.INT_ORG_TYPE_CD
        , FIRST_VALUE(MIN_BY(F.COUNTRY_ORG_CD, BUS_DT)) OVER (PARTITION BY INT_ORG_SID ORDER BY D1.BUS_YEAR)  AS COUNTRY_ORG_CD
        , F.CURR_CD        
     FROM ETL.T_TCACHE_FACT_RETAIL_BY_STORE_DAY AS F -- 2023-05-05, 4000 EUR TURNOVER -> PY_TURNOVER 2024-05-05
     JOIN CORE_DIM.T_DIM_CALENDAR_DATE D1
       ON D1.CAL_DT = F.BUS_DT
      AND F.BUS_DT <= CURRENT_DATE 
    GROUP BY 
          F.INT_ORG_SID
        , D1.BUS_YEAR
        , F.INT_ORG_TYPE_CD
        , F.CURR_CD    
)
,INT_ORG_YEARS_EXTENDED AS
(
     
    SELECT 
         INT_ORG_SID
       , BUS_YEAR
       , INT_ORG_TYPE_CD
       , COUNTRY_ORG_CD
       , CURR_CD        
    FROM INT_ORG_YEARS
    UNION 
    SELECT 
         INT_ORG_SID
       , BUS_YEAR + 1
       , INT_ORG_TYPE_CD
       , COUNTRY_ORG_CD
       , CURR_CD        
    FROM INT_ORG_YEARS
)
SELECT 
     D2.CAL_DT
    ,D2.BUS_YEAR
    ,IOYE.INT_ORG_SID
    ,IOYE.INT_ORG_TYPE_CD
    ,IOYE.COUNTRY_ORG_CD
    ,IOYE.CURR_CD         
FROM INT_ORG_YEARS_EXTENDED IOYE
JOIN CORE_DIM.T_DIM_CALENDAR_DATE D2
  ON D2.BUS_YEAR = IOYE.BUS_YEAR
WHERE D2.CAL_DT <= CURRENT_DATE 
; 