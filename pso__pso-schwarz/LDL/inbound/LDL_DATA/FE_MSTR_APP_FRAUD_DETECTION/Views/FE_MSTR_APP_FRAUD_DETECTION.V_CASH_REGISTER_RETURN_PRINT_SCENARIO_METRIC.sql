WITH CTE_CLS_REL_CASH_REGISTER
(
CASH_REGISTER_EVENT_SID,SCENARIO_ID,CUST_SID,CUST_IDENT_TYPE_CD,CASH_REGISTER_EVENT_NR,CASHIER_NR
,BUS_DT,STORE_SID,COUNTRY_ORG_CD,REL_CASH_REGISTER_EVENT_SID,REL_BUS_DT, CASH_REGISTER_EVENT_REL_TYPE_CD
)
AS
(
SELECT DISTINCT
MAX( 
DECODE(REL.CASH_REGISTER_EVENT_REL_TYPE_CD,'SUCCESSOR',REL.REL_CASH_REGISTER_EVENT_SID,0)) 
OVER (PARTITION BY REL.CASH_REGISTER_EVENT_SID)   AS CASH_REGISTER_EVENT_SID_OW
,CLS.SCENARIO_ID
,CLS.CUST_SID
,CLS.CUST_IDENT_TYPE_CD 
,RIGHT(CASH_REGISTER_EVENT_SID_OW,10)::NUMBER AS CASH_REGISTER_EVENT_NR
,CLS.CASHIER_NR
,CLS.BUS_DT
,CLS.STORE_SID
,CLS.COUNTRY_ORG_CD
,DECODE(REL.CASH_REGISTER_EVENT_REL_TYPE_CD,'SELF',REL.CASH_REGISTER_EVENT_SID,REL.REL_CASH_REGISTER_EVENT_SID) AS REL_CASH_REGISTER_EVENT_SID
,REL.REL_BUS_DT AS REL_BUS_DT
,REL.CASH_REGISTER_EVENT_REL_TYPE_CD AS CASH_REGISTER_EVENT_REL_TYPE_CD
FROM CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_RELATIONSHIP REL
INNER JOIN CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_CLASSIFICATION CLS
ON REL.BUS_DT = CLS.BUS_DT
AND REL.COUNTRY_ORG_CD = CLS.COUNTRY_ORG_CD
AND REL.CASH_REGISTER_EVENT_SID = CLS.CASH_REGISTER_EVENT_SID
WHERE CLS.SCENARIO_ID IN  (6,60100,60200,60300)
AND REL.CASH_REGISTER_EVENT_REL_TYPE_CD IN ('SELF','SUCCESSOR','EVENT_AROUND_LOGOFF', 'SUCC_ALL_NPI_EVENTS') 
UNION ALL
SELECT DISTINCT
MAX( 
DECODE(REL.CASH_REGISTER_EVENT_REL_TYPE_CD,'SELF',0,REL.REL_CASH_REGISTER_EVENT_SID)) 
OVER (PARTITION BY REL.CASH_REGISTER_EVENT_SID)   AS CASH_REGISTER_EVENT_SID_OW
,CLS.SCENARIO_ID
,CLS.CUST_SID
,CLS.CUST_IDENT_TYPE_CD 
,RIGHT(CASH_REGISTER_EVENT_SID_OW,10)::NUMBER AS CASH_REGISTER_EVENT_NR
,CLS.CASHIER_NR
,CLS.BUS_DT
,CLS.STORE_SID
,CLS.COUNTRY_ORG_CD
,DECODE(REL.CASH_REGISTER_EVENT_REL_TYPE_CD,'SELF',REL.CASH_REGISTER_EVENT_SID,REL.REL_CASH_REGISTER_EVENT_SID) AS REL_CASH_REGISTER_EVENT_SID
,REL.REL_BUS_DT AS REL_BUS_DT
,REL.CASH_REGISTER_EVENT_REL_TYPE_CD AS CASH_REGISTER_EVENT_REL_TYPE_CD
FROM CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_RELATIONSHIP REL
INNER JOIN CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_CLASSIFICATION CLS
ON REL.BUS_DT = CLS.BUS_DT
AND REL.COUNTRY_ORG_CD = CLS.COUNTRY_ORG_CD
AND REL.CASH_REGISTER_EVENT_SID = CLS.CASH_REGISTER_EVENT_SID
WHERE CLS.SCENARIO_ID IN  (12,120100,120200,120300,120400,120600,120700,120900,120800)
AND REL.CASH_REGISTER_EVENT_REL_TYPE_CD IN ('SELF','ORIGINAL') 
UNION ALL
SELECT 
CLS.CASH_REGISTER_EVENT_SID 
,CLS.SCENARIO_ID
,CLS.CUST_SID
,CLS.CUST_IDENT_TYPE_CD 
,CLS.CASH_REGISTER_EVENT_NR 
,CLS.CASHIER_NR
,CLS.BUS_DT
,CLS.STORE_SID
,CLS.COUNTRY_ORG_CD
,REL.REL_CASH_REGISTER_EVENT_SID
,REL.REL_BUS_DT AS REL_BUS_DT
,REL.CASH_REGISTER_EVENT_REL_TYPE_CD AS CASH_REGISTER_EVENT_REL_TYPE_CD
FROM CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_RELATIONSHIP REL
INNER JOIN CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_CLASSIFICATION CLS
ON REL.BUS_DT = CLS.BUS_DT
AND REL.COUNTRY_ORG_CD = CLS.COUNTRY_ORG_CD
AND REL.CASH_REGISTER_EVENT_SID = CLS.CASH_REGISTER_EVENT_SID
WHERE CLS.SCENARIO_ID NOT IN  (6,60100,60200,60300,12,120100,120200,120300,120400,120600,120700,120800,120900)
)
SELECT  
S.SCENARIO_ID 
,M.METRIC_ID 
,EC.CUST_SID
,EC.CUST_IDENT_TYPE_CD
,EC.CASH_REGISTER_EVENT_SID::VARCHAR(100) 
,EC.CASH_REGISTER_EVENT_NR
,EC.CASHIER_NR
,EC.BUS_DT
,EC.STORE_SID
,CR_RETURN_PRINT.CASH_REGISTER_EVENT_SID::VARCHAR(100)  AS REL_CASH_REGISTER_EVENT_SID
,CR_RETURN_PRINT.CASH_REGISTER_EVENT_NR AS REL_CASH_REGISTER_EVENT_NR 
,CR_RETURN_PRINT.CASHIER_NR AS REL_CASHIER_NR
,CR_RETURN_PRINT.CASH_REGISTER_EVENT_LINE_SEQ AS CASH_REGISTER_EVENT_LINE_SEQ
,999   AS CASH_REGISTER_EVENT_LINE_SEQ_DBL
,CR_RETURN_PRINT.EVENT_AUTH_BY_NR
,CR_RETURN_PRINT.LINE_AUTH_BY_NR
,CR_RETURN_PRINT.EVENT_AUTH_BY_NR
,CR_RETURN_PRINT.PARENT_LINE_SEQ
,CR_RETURN_PRINT.RETAIL_EVENT_LINE_SCENARIO_ID
,TO_CHAR(CR_RETURN_PRINT.EVENT_START_TMSP,'HH24:MI:SS') AS EVENT_START_TMSP
,TO_CHAR(CR_RETURN_PRINT.EVENT_END_TMSP,'HH24:MI:SS') AS  EVENT_END_TMSP
,TO_CHAR(CR_RETURN_PRINT.ORIG_BUS_DT,'DD.MM.YYYY') AS EVENT_LINE_START_TMSP
,TO_CHAR(CR_RETURN_PRINT.EVENT_END_TMSP,'HH24:MI:SS') AS EVENT_LINE_END_TMSP
,CR_RETURN_PRINT.BUS_DT AS REL_BUS_DT
,CR_RETURN_PRINT.STORE_SID AS REL_STORE_SID
,CR_RETURN_PRINT.STORE_NR AS STORE_NR
,CR_RETURN_PRINT.COUNTRY_ORG_CD AS COUNTRY_ORG_CD 
,CR_RETURN_PRINT.CASH_REGISTER_NR AS CASH_REGISTER_NR
,CR_RETURN_PRINT.PROD_RETAIL_LINE_TYPE_CD AS PROD_RETAIL_LINE_TYPE_CD
,CR_RETURN_PRINT.PROD_VARIANT_SID AS PROD_VARIANT_SID
,(CR_RETURN_PRINT.CASH_REGISTER_EVENT_NR * 10000 + CR_RETURN_PRINT.CASH_REGISTER_EVENT_LINE_SEQ)  AS LOCAL_PROD_NR
,CR_RETURN_PRINT.PROD_VARIANT_INPUT_NR
,CR_RETURN_PRINT.PROD_VARIANT_INPUT_NR_TYPE_CD
,CR_RETURN_PRINT.ORIG_CASH_REGISTER_EVENT_NR AS DISPLAYED_PROD_VARIANT_NAME_TITLE  
,'Rückgabegrund:'||PR.PROD_RETURN_REASON_DESCR  AS DISPLAYED_PROD_VARIANT_NAME 
,CR_RETURN_PRINT.PROD_ENTRY_METHOD_CD
,CR_RETURN_PRINT.PRICE_ENTRY_METHOD_CD
,CR_RETURN_PRINT.PAYM_LINE_TYPE_CD
,CR_RETURN_PRINT.PAYM_TYPE_ID
,CR_RETURN_PRINT.FRAUD_DETECTION_RELEVANT_FG
,CR_RETURN_PRINT.PROD_RETURN_REASON_SID
,CR_RETURN_PRINT.RETURN_TXT
,CR_RETURN_PRINT.PARENT_RETAIL_EVENT_SID
,CR_RETURN_PRINT.UNIT_PRICE
,CR_RETURN_PRINT.PROD_VARIANT_CNT
,CR_RETURN_PRINT.PROD_VARIANT_QTY
,CR_RETURN_PRINT.BASE_GROSS_VAL
,CR_RETURN_PRINT.RETAIL_LINE_GROSS_VAL
,CR_RETURN_PRINT.RETAIL_LINE_VAT_VAL
,CR_RETURN_PRINT.LOCAL_PAYM_VAL
,CR_RETURN_PRINT.TAX_LINE_GROSS_VAL AS TXN_GROSS_VAL
,CR_RETURN_PRINT.TAX_LINE_VAL AS TXN_VAT_VAL
,CR_RETURN_PRINT.TAX_PCT
,CR_RETURN_PRINT.CASH_REGISTER_EVENT_SEQ
,CR_RETURN_PRINT.DWH_CREATED_TMSP
,CR_RETURN_PRINT.DWH_UPDATED_TMSP
,CR_RETURN_PRINT.DWH_LOAD_ID
,CR_RETURN_PRINT.DWH_NODE_CD
,CR_RETURN_PRINT.ORIG_COUNTRY_ORG_CD
,CR_RETURN_PRINT.ORIG_STORE_NR
,CR_RETURN_PRINT.ORIG_BUS_DT
,CR_RETURN_PRINT.ORIG_CASH_REGISTER_NR
,CR_RETURN_PRINT.ORIG_CASH_REGISTER_EVENT_NR
,CR_RETURN_PRINT.ORIG_CASH_REGISTER_EVENT_NR::VARCHAR(100) AS ORIG_CASH_REGISTER_EVENT_SID
,CR_RETURN_PRINT.ORIG_CASH_REGISTER_NR
FROM CTE_CLS_REL_CASH_REGISTER EC
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO S
ON EC.SCENARIO_ID = S.SCENARIO_ID 
AND S.SCENARIO_GRP_ID = 2
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC M
ON M.SCENARIO_ID = S.SCENARIO_ID 
INNER JOIN CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_PRINT CR_RETURN_PRINT
ON CR_RETURN_PRINT.COUNTRY_ORG_CD = EC.COUNTRY_ORG_CD
AND CR_RETURN_PRINT.CASH_REGISTER_EVENT_SID = EC.REL_CASH_REGISTER_EVENT_SID
AND CR_RETURN_PRINT.RETAIL_EVENT_LINE_SCENARIO_ID  IN (141,142)
INNER JOIN CORE_REL.T_PRODUCT_RETURN_REASON PR
ON CR_RETURN_PRINT.PROD_RETURN_REASON_SID = PR.PROD_RETURN_REASON_SID
AND PR.LANG_CD = 'DE'
WHERE EC.CASH_REGISTER_EVENT_REL_TYPE_CD  IN ( 'SELF','RETURN_SAME_ORIGINAL')
;