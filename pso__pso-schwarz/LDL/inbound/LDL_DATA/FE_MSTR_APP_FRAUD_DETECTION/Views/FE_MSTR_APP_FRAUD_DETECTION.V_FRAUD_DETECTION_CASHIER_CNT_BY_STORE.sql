CREATE OR REPLACE VIEW FE_MSTR_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_CASHIER_CNT_BY_STORE(
STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE STORE WHERE THE RELATED CASH REGISTER EVENT HAPPENED.',
CASHIER_CNT COMMENT 'THE NUMBER OF CASHIERS WORKED ON ANALYSIS PERIOD'
) COMMENT = 'Cashier Count per Store for last 9 weeks'
AS 
WITH CTE_MIN_ANALYSIS_DT(ANALYSIS_PERIOD_START_DT)
AS
(
SELECT MIN(ORD.ANALYSIS_PERIOD_START_DT) AS ANALYSIS_PERIOD_START_DT
FROM CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_ORDER ORD
WHERE ORD.ORDER_PARAMETER_STATUS_CD = 'RV'
)
SELECT 
MAIN.INT_ORG_SID AS STORE_SID 
,COUNT(DISTINCT MAIN.CASHIER_NR) AS CASHIER_CNT
FROM CORE_APP_FRAUD_DETECTION.T_STATISTICS_BY_STORE_HOUR_CASHIER MAIN
INNER JOIN CTE_MIN_ANALYSIS_DT DT
ON  MAIN.BUS_DT >= DT.ANALYSIS_PERIOD_START_DT
GROUP BY MAIN.INT_ORG_SID;