CREATE OR REPLACE VIEW FE_MSTR_GF_LEAD.V_FACT_REAL_ESTATE_STATUS_BY_DAY(
	REAL_ESTATE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE REAL ESTATE OBJECT.',
	STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR A STORE.',
	COUNTRY_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE RELATED COUNTRY ORGANIZATION.',
	COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY FOR WHICH THIS COUNTRY ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	REPORTING_COUNTRY_CD COMMENT 'THE CODE WHICH IDENTIFIES THE REPORTING COUNTRY IN WHICH THE INTERNAL ORGANIZATION IS LOCATED.',
	CAL_DT COMMENT 'THE DAY REPRESENTED AS A CALENDAR DATE OF THE FORM YYYY-MM-DD. YYYY IS THE CALENDAR YEAR, MM (BETWEEN 1 AND 12) THE CALENDAR MONTH AND DD THE DAY OF THE CALENDAR MONTH (BETWEEN 1 AND 31). ',
	REAL_ESTATE_STATUS_CD COMMENT 'THE CODE IDENTIFYING THE LIFECYCLE STATUS FOR REAL ESTATE OBJECTS. (THIS IS THE BUSINESS LIFECYCLE, SO IT MIGHT DIFFER FROM THE STATUS CODE SHOWN IN THE SOURCE SYSTEM.)',
	OPEN_STORE_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING IS OPEN, OTHERWISE VALUE 0.',
    OPEN_STORE_PY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS OPEN ONE YEAR AGO, OTHERWISE VALUE 0.',
    OPEN_STORE_PPY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS OPEN TWO YEARS AGO, OTHERWISE VALUE 0.',
	CLOSED_STORE_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING IS CLOSED, OTHERWISE VALUE 0.',
	CLOSED_STORE_PY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS CLOSED ONE YEAR AGO, OTHERWISE VALUE 0.',
	CLOSED_STORE_PPY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS CLOSED TWO YEARS AGO, OTHERWISE VALUE 0.',
	STORE_UNDER_CONTRACT_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING IS UNDER CONTRACT, REGARDLESS IF THERE IS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	STORE_UNDER_CONTRACT_PY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS UNDER CONTRACT ONE YEAR AGO, REGARDLESS IF THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	STORE_UNDER_CONTRACT_PPY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS UNDER CONTRACT TWO YEARS AGO, REGARDLESS IF THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	STORE_TO_BE_BUILT_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS UNDER CONTRACT AND THERE IS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	STORE_TO_BE_BUILT_PY_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING WAS UNDER CONTRACT ONE YEAR AGO AND THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	STORE_TO_BE_BUILT_PPY_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING WAS UNDER CONTRACT TWO YEARS AGO AND THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	CANCEL_TERM_STORE_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS FINALLY SETTLED (TERMINATED) OR THERE IS NO INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	OWN_STORE_TO_BE_BUILT_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS UNDER CONTRACT, PRIVATELY OWNED AND THERE IS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.',
	OWN_OPEN_STORE_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS OPEN AND PRIVATELY OWNED, OTHERWISE VALUE 0.',
	OWNERSHIP_TYPE_CD COMMENT 'THE CODE IDENTIFYING THE OWNERSHIP OF A REAL ESTATE OBJECT, I.E. IF IT HAS BEEN BOUGHT OR IF IT IS RENTED.',
	OPEN_DT COMMENT 'THE DATE WHEN THE INTERNAL ORGANIZATION HAS STARTED ITS REGULAR OPERATION. (THIS DATE MAY BE DIFFERENT FROM THE PLANNED OPENING DATE.)',
	CLOSE_DT COMMENT 'THE DATE WHEN THIS REAL ESTATE OBJECT WAS CLOSED.',
	DAYS_SINCE_OPENING COMMENT 'THE COUNT OF DAYS SINCE STORE OPENING.',
	DAYS_SINCE_CLOSURE COMMENT 'THE COUNT OF DAYS SINCE STORE CLOSURE.',
	SALES_AREA_MEAS COMMENT 'THE SPACE WHICH CAN BE USED FOR SALES, IN THE UNIT INDICATED BY THE UNIT OF MEASURE CODE (E.G. M2).',
	TOTAL_SUBLET_AREA_MEAS COMMENT 'THE TOTAL SPACE WHICH CAN BE SUBLET, IN THE UNIT INDICATED BY THE UNIT OF MEASURE CODE (E.G. M2).',
	RENTED_SUBLET_AREA_MEAS COMMENT 'THE SPACE WHICH IS CURRENTLY RENTED OUT, IN THE UNIT INDICATED BY THE UNIT OF MEASURE CODE.'
) AS
SELECT
    main.REAL_ESTATE_SID
    , main.STORE_SID
   	, main.COUNTRY_ORG_SID
    , main.COUNTRY_ORG_CD
	, main.REPORTING_COUNTRY_CD
	, main.CAL_DT
    , main.REAL_ESTATE_STATUS_CD
	, main.OPEN_STORE_CNT
	, main.OPEN_STORE_PY_CNT
	, main.OPEN_STORE_PPY_CNT
    , main.CLOSED_STORE_CNT
	, main.CLOSED_STORE_PY_CNT
	, main.CLOSED_STORE_PPY_CNT
	, main.STORE_UNDER_CONTRACT_CNT
	, main.STORE_UNDER_CONTRACT_PY_CNT
	, main.STORE_UNDER_CONTRACT_PPY_CNT
	, main.STORE_TO_BE_BUILT_CNT
	, main.STORE_TO_BE_BUILT_PY_CNT
	, main.STORE_TO_BE_BUILT_PPY_CNT
	, main.CANCEL_TERM_STORE_CNT
	, main.OWN_STORE_TO_BE_BUILT_CNT
	, main.OWN_OPEN_STORE_CNT
	, main.OWNERSHIP_TYPE_CD	
    , main.OPEN_DT
    , main.CLOSE_DT
    , main.DAYS_SINCE_OPENING
    , main.DAYS_SINCE_CLOSURE
    , main.SALES_AREA_MEAS
    , main.TOTAL_SUBLET_AREA_MEAS
    , main.RENTED_SUBLET_AREA_MEAS
FROM CORE_DIM.V_FACT_REAL_ESTATE_STATUS_BY_DAY main
;