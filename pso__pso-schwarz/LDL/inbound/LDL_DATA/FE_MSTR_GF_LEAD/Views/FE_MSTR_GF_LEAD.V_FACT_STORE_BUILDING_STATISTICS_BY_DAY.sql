CREATE OR REPLACE VIEW FE_MSTR_GF_LEAD.V_FACT_STORE_BUILDING_STATISTICS_BY_DAY(
	REAL_ESTATE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE REAL ESTATE OBJECT.',
	COUNTRY_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE RELATED COUNTRY ORGANIZATION.',
	COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY FOR WHICH THIS COUNTRY ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	REPORTING_COUNTRY_CD COMMENT 'THE CODE WHICH IDENTIFIES THE REPORTING COUNTRY IN WHICH THE INTERNAL ORGANIZATION IS LOCATED.',
	CAL_DT COMMENT 'THE DAY REPRESENTED AS A CALENDAR DATE OF THE FORM YYYY-MM-DD. YYYY IS THE CALENDAR YEAR, MM (BETWEEN 1 AND 12) THE CALENDAR MONTH AND DD THE DAY OF THE CALENDAR MONTH (BETWEEN 1 AND 31). ',
	OPENED_STORE_BLD_CNT COMMENT 'THE OPEN STORES COUNT ON THE GIVEN DAY (KPI 1202501)',
	OPENED_STORE_BLD_PY_CNT COMMENT 'THE OPEN STORES COUNT ON THE SAME CALENDAR DATE ONE YEAR AGO (KPI 1202501)',
	OPENED_STORE_BLD_PPY_CNT COMMENT 'THE OPEN STORES COUNT ON THE SAME CALENDAR DATE TWO YEARS AGO (KPI 1202501)',
	RELOC_STORE_BLD_CNT COMMENT 'THE RELOCATED STORES COUNT ON THE GIVEN DAY (KPI 1202502)',
	RELOC_STORE_BLD_PY_CNT COMMENT 'THE RELOCATED STORES COUNT ON THE SAME CALENDAR DATE ONE YEAR AGO (KPI 1202502)',
	RELOC_STORE_BLD_PPY_CNT COMMENT 'THE RELOCATED STORES COUNT ON THE SAME CALENDAR DATE TWO YEARS AGO (KPI 1202502)',
	REPLACED_STORE_BLD_CNT COMMENT 'THE REPLACED STORES COUNT ON THE GIVEN DAY (KPI 1202512)',
	REPLACED_STORE_BLD_PY_CNT COMMENT 'THE REPLACED STORES COUNT ON THE SAME CALENDAR DATE ONE YEAR AGO (KPI 1202512)',
	REPLACED_STORE_BLD_PPY_CNT COMMENT 'THE REPLACED STORES COUNT ON THE SAME CALENDAR DATE TWO YEARS AGO (KPI 1202512)',
	CLOSED_STORE_BLD_CNT COMMENT 'THE CLOSED STORES COUNT ON THE GIVEN DAY (KPI 1204501)',
	CLOSED_STORE_BLD_PY_CNT COMMENT 'THE CLOSED STORES COUNT ON THE SAME CALENDAR DATE ONE YEAR AGO (KPI 1204501)',
	CLOSED_STORE_BLD_PPY_CNT COMMENT 'THE CLOSED STORES COUNT ON THE SAME CALENDAR DATE TWO YEARS AGO (KPI 1204501)',
	BLD_CONTRACT_CNT COMMENT 'THE COUNT OF BUILDING CONTRACTS SIGNED ON THE GIVEN DAY (KPI 1201503)',
	BLD_CONTRACT_PY_CNT COMMENT 'THE COUNT OF BUILDING CONTRACTS SIGNED ON THE SAME CALENDAR DATE ONE YEAR AGO (KPI 1201503)',
	BLD_CONTRACT_PPY_CNT COMMENT 'THE COUNT OF BUILDING CONTRACTS SIGNED ON THE SAME CALENDAR DATE TWO YEARS AGO (KPI 1201503)'
) AS
SELECT
     MAIN.REAL_ESTATE_SID AS REAL_ESTATE_SID
	,MAIN.COUNTRY_ORG_SID AS COUNTRY_ORG_SID
    ,MAIN.COUNTRY_ORG_CD  AS COUNTRY_ORG_CD
    ,MAIN.REPORTING_COUNTRY_CD  AS REPORTING_COUNTRY_CD
    ,MAIN.CAL_DT  AS CAL_DT
    ,MAIN.OPENED_STORE_BLD_CNT AS OPENED_STORE_BLD_CNT
	,MAIN.OPENED_STORE_BLD_PY_CNT AS OPENED_STORE_BLD_PY_CNT
	,MAIN.OPENED_STORE_BLD_PPY_CNT AS OPENED_STORE_BLD_PPY_CNT
	,MAIN.RELOC_STORE_BLD_CNT AS RELOC_STORE_BLD_CNT
	,MAIN.RELOC_STORE_BLD_PY_CNT AS RELOC_STORE_BLD_PY_CNT
	,MAIN.RELOC_STORE_BLD_PPY_CNT AS RELOC_STORE_BLD_PPY_CNT
	,MAIN.REPLACED_STORE_BLD_CNT AS REPLACED_STORE_BLD_CNT
	,MAIN.REPLACED_STORE_BLD_PY_CNT AS REPLACED_STORE_BLD_PY_CNT
	,MAIN.REPLACED_STORE_BLD_PPY_CNT AS REPLACED_STORE_BLD_PPY_CNT
	,MAIN.CLOSED_STORE_BLD_CNT AS CLOSED_STORE_BLD_CNT
	,MAIN.CLOSED_STORE_BLD_PY_CNT AS CLOSED_STORE_BLD_PY_CNT
	,MAIN.CLOSED_STORE_BLD_PPY_CNT AS CLOSED_STORE_BLD_PPY_CNT
	,MAIN.BLD_CONTRACT_CNT AS BLD_CONTRACT_CNT
	,MAIN.BLD_CONTRACT_PY_CNT AS BLD_CONTRACT_PY_CNT
	,MAIN.BLD_CONTRACT_PPY_CNT AS BLD_CONTRACT_PPY_CNT
	FROM CORE_DIM.V_FACT_STORE_BUILDING_STATISTICS_BY_DAY MAIN
	;