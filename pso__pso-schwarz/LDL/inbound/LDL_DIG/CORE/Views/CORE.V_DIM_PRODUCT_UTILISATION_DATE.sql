CREATE OR REPLACE VIEW CORE.V_DIM_PRODUCT_UTILISATION_DATE(
	PROD_SID
    ,PROD_NR
	,IS_CATALOG_PROD_FG
    ,ASSORTMENT_PLAN_PERIOD_NR
    ,MIN_DELIVERY_DATE
	,MAX_DELIVERY_DATE
    ,PROMO_DUR_WEEK_CNT
    ,CALCULATED_UTILISATION
    ,CORRECT_UTILISATION
    ,CORRECT_UTILISATION_DATE_ONLY
    ,CORRECT_UTILISATION_WEEK
    ,WEEKS_UNTIL_UTILISATION
    ,CALCULATED_INFORMATION_CONCEPT
    ,CORRECT_INFORMATION_CONCEPT
    ,USED_DELIVERY_UTILISATION_DATE
) AS


WITH 
CTE_PU AS
(
    SELECT
         PROD_SID
        ,UTIL_ACTION_CD
        ,EXCEPTION_UTIL_DT
    FROM
        CORE.T_FACT_PRODUCT_UTILISATION
    WHERE
        DWH_VALID_FG = TRUE
),

CTE_SWD AS -- total stock count per PROD_SID
(
    SELECT
        DIM_PV.PROD_SID AS PROD_SID
        ,SUM(TOTAL_STOCK_CNT) AS TOTAL_STOCK_CNT
    FROM
        CORE.T_FACT_STOCK_WAREHOUSE_DAILY SWD
    INNER JOIN
        CORE.T_DIM_PRODUCT_VARIANT DIM_PV
        ON DIM_PV.PROD_VARIANT_SID = SWD.PROD_VARIANT_SID
        AND DIM_PV.DWH_VALID_FG = TRUE
    WHERE
        ACTIVE_FG = TRUE
    GROUP BY
        PROD_SID
),

MAX_LT AS
(
    SELECT 
        PROD_SID
        ,MAX(TGT_PROD_RECEIVE_CY_WEEK) AS TGT_PROD_RECEIVE_CY_WEEK_MAX
    FROM
        CORE.T_DIM_SALES_PROMOTION
    WHERE 
        DWH_VALID_FG
        AND LOWER(SALE_PROMO_STATUS_CD) <> 'canceled'
        AND IS_REPEATED_FG = FALSE
    GROUP BY
        PROD_SID
),

MAX_IAN AS
(
    SELECT 
	    T1.PROD_SID
        ,MAX(AMC_IAN_NR) AS AMC_IAN_NR
        ,MAX(T1.ASSORTMENT_PLAN_PERIOD_NR) AS ASSORTMENT_PLAN_PERIOD_NR
        ,MIN(C2.CAL_DT) AS MIN_DELIVERY_DT_IAN
	    ,MAX(C1.CAL_DT) AS MAX_DELIVERY_DT_IAN
        ,MAX(PROMO_DUR_WEEK_CNT) AS PROMO_DUR_WEEK_CNT_IAN
	FROM CORE.T_DIM_SALES_PROMOTION T1
		INNER JOIN CORE.T_DIM_CAL_DAY C1 ON C1.CY_WEEK = T1.TGT_PROD_RECEIVE_CY_WEEK  AND C1.DAY_OF_WEEK = 5
        INNER JOIN CORE.T_DIM_CAL_DAY C2 ON C2.CY_WEEK = T1.FIRST_DELIVERY_CY_WEEK AND C2.DAY_OF_WEEK = 5
        LEFT JOIN MAX_LT T2 ON T1.PROD_SID = T2.PROD_SID 
	WHERE 
            IS_REPEATED_FG = FALSE
        AND LOWER(T1.SALE_PROMO_STATUS_CD) <> 'canceled'
        AND T1.DWH_VALID_FG
        AND TGT_PROD_RECEIVE_CY_WEEK_MAX = TGT_PROD_RECEIVE_CY_WEEK
	GROUP BY T1.PROD_SID
),
    
MAX_BATCH AS
(
    SELECT 
	    T2.PROD_SID
        ,MAX(AMC_IAN_NR) AS AMC_IAN_NR
        ,MAX(T2.ASSORTMENT_PLAN_PERIOD_NR) AS ASSORTMENT_PLAN_PERIOD_NR
        ,MIN(C2.CAL_DT) AS MIN_DELIVERY_DT_BATCH
	    ,MAX(C1.CAL_DT) AS MAX_DELIVERY_DT_BATCH
        ,MAX(PROMO_DUR_WEEK_CNT) AS PROMO_DUR_WEEK_CNT_BATCH
	FROM CORE.T_DIM_SALES_PROMOTION T2
		INNER JOIN CORE.T_DIM_CAL_DAY C1 ON C1.CY_WEEK = T2.TGT_PROD_RECEIVE_CY_WEEK AND C1.DAY_OF_WEEK = 5
   		INNER JOIN CORE.T_DIM_CAL_DAY C2 ON C2.CY_WEEK = T2.FIRST_DELIVERY_CY_WEEK AND C2.DAY_OF_WEEK = 5
        LEFT JOIN MAX_LT T3 ON T3.PROD_SID = T2.PROD_SID 
	WHERE 
            IS_REPEATED_FG = FALSE
        AND LOWER(T2.SALE_PROMO_STATUS_CD) <> 'canceled'
        AND T2.DWH_VALID_FG
        AND TGT_PROD_RECEIVE_CY_WEEK_MAX = TGT_PROD_RECEIVE_CY_WEEK
	GROUP BY T2.PROD_SID
),

SALES_PROMOTION_TEMP AS -- use only promotions which are not in the future. use the promotion with the largets AMC_IAN_NR for each product
(
    SELECT
         DIM_SP.PROD_SID
        ,IS_CATALOG_PROD_FG
        ,DIM_SP.ASSORTMENT_PLAN_PERIOD_NR
        ,DIM_SP.AMC_IAN_NR
        ,CAL_W.CY_WEEK_BEGIN_DT AS TGT_PROD_RECEIVE_CY_WEEK_DT
        ,'BATCH' AS Source
    FROM
        CORE.T_DIM_SALES_PROMOTION DIM_SP
    INNER JOIN
        CORE.T_DIM_CAL_WEEK CAL_W
        ON
            CAL_W.CY_WEEK = TGT_PROD_RECEIVE_CY_WEEK
    INNER JOIN 
        MAX_BATCH BATCH
        ON DIM_SP.PROD_SID = BATCH.PROD_SID
    WHERE
        DWH_VALID_FG = TRUE
        AND LOWER(SALE_PROMO_STATUS_CD) <> 'canceled'
        AND IS_REPEATED_FG = FALSE

    UNION

    SELECT
         DIM_SP.PROD_SID
        ,IS_CATALOG_PROD_FG
        ,DIM_SP.ASSORTMENT_PLAN_PERIOD_NR
        ,DIM_SP.AMC_IAN_NR
        ,CAL_W.CY_WEEK_BEGIN_DT AS TGT_PROD_RECEIVE_CY_WEEK_DT
        ,'IAN' AS Source
    FROM
        CORE.T_DIM_SALES_PROMOTION DIM_SP
    INNER JOIN
        CORE.T_DIM_CAL_WEEK CAL_W
        ON
        CAL_W.CY_WEEK = TGT_PROD_RECEIVE_CY_WEEK
    INNER JOIN 
        MAX_IAN IAN
        ON DIM_SP.PROD_SID = IAN.PROD_SID
        AND IAN.PROD_SID NOT IN (SELECT DISTINCT PROD_SID FROM MAX_BATCH)
    WHERE
        DWH_VALID_FG = TRUE
        AND LOWER(SALE_PROMO_STATUS_CD) <> 'canceled'
        AND IS_REPEATED_FG = FALSE
),

SALES_PROMOTION AS -- use the (prefiltered) promotion with the largest date
(
    SELECT
         PROD_SID
        ,Source
        ,IS_CATALOG_PROD_FG
        ,ASSORTMENT_PLAN_PERIOD_NR
        ,AMC_IAN_NR
        ,TGT_PROD_RECEIVE_CY_WEEK_DT
    FROM (
        SELECT
             PROD_SID
             ,Source
            ,IS_CATALOG_PROD_FG
            ,ASSORTMENT_PLAN_PERIOD_NR
            ,AMC_IAN_NR
            ,MAX(TGT_PROD_RECEIVE_CY_WEEK_DT) OVER(PARTITION BY (PROD_SID)) AS TGT_PROD_RECEIVE_CY_WEEK_DT
            ,ROW_NUMBER() OVER(PARTITION BY (PROD_SID) ORDER BY TGT_PROD_RECEIVE_CY_WEEK_DT DESC) AS ROW_NO
        FROM
            SALES_PROMOTION_TEMP
        )
    WHERE
        ROW_NO = 1
)

SELECT
     DIM_P.PROD_SID
     ,DIM_P.PROD_NR
     ,SP.IS_CATALOG_PROD_FG
     ,SP.ASSORTMENT_PLAN_PERIOD_NR

    ,CASE 
        WHEN SP.ASSORTMENT_PLAN_PERIOD_NR IS NOT NULL THEN MIN_DELIVERY_DT_BATCH
        ELSE MIN_DELIVERY_DT_IAN
    END AS MIN_DELIVERY_DATE
    ,CASE 
        WHEN SP.ASSORTMENT_PLAN_PERIOD_NR IS NOT NULL THEN MAX_DELIVERY_DT_BATCH
        ELSE MAX_DELIVERY_DT_IAN
    END AS MAX_DELIVERY_DATE
    ,CASE 
        WHEN SP.ASSORTMENT_PLAN_PERIOD_NR IS NOT NULL THEN PROMO_DUR_WEEK_CNT_BATCH
        ELSE PROMO_DUR_WEEK_CNT_IAN
    END AS PROMO_DUR_WEEK_CNT

    ,CASE
	    WHEN UPPER(UTIL_ACTION_CD) = 'VERWERTUNG' THEN 'bereits in Verwertung'
        WHEN MAX_DELIVERY_DATE IS NULL THEN 'kein LT'
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND MIN_DELIVERY_DATE < '2022-09-16'::DATE THEN TO_VARCHAR(DATEADD(MONTH, 16, MIN_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND MAX_DELIVERY_DATE < '2022-09-16'::DATE THEN TO_VARCHAR(DATEADD(WEEK, 26, MAX_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND SP.ASSORTMENT_PLAN_PERIOD_NR IN ('2110','2107','2104','2101','2010','2007','2004','2001','1910','1907','1904','1901') THEN TO_VARCHAR(DATEADD(MONTH, 16, MIN_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND SP.ASSORTMENT_PLAN_PERIOD_NR IN ('2110','2107','2104','2101','2010','2007','2004','2001','1910','1907','1904','1901') THEN TO_VARCHAR(DATEADD(WEEK, 26, MAX_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROMO_DUR_WEEK_CNT IS NULL OR PROMO_DUR_WEEK_CNT = '0' THEN 'Sortiment, keine Verwertung'
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND PROMO_DUR_WEEK_CNT <= '12' THEN TO_VARCHAR(DATEADD(WEEK, 15, MIN_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND PROMO_DUR_WEEK_CNT <= '12' THEN TO_VARCHAR(DATEADD(WEEK, 15, MAX_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND PROMO_DUR_WEEK_CNT > '12' AND PROMO_DUR_WEEK_CNT <= '26' THEN TO_VARCHAR(DATEADD(WEEK, 29, MIN_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND PROMO_DUR_WEEK_CNT > '12' AND PROMO_DUR_WEEK_CNT <= '26' THEN TO_VARCHAR(DATEADD(WEEK, 29, MAX_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND PROMO_DUR_WEEK_CNT > '26' THEN TO_VARCHAR(DATEADD(WEEK, 55, MIN_DELIVERY_DATE), 'DD.MM.YYYY')
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND PROMO_DUR_WEEK_CNT > '26' THEN TO_VARCHAR(DATEADD(WEEK, 55, MAX_DELIVERY_DATE), 'DD.MM.YYYY')
        ELSE 'kein LT'
    END ::VARCHAR(40) AS CALCULATED_UTILISATION

    ,CASE
        WHEN UPPER(UTIL_ACTION_CD) = 'AUSLISTUNG NACHDISPO' THEN TO_VARCHAR(EXCEPTION_UTIL_DT, 'DD.MM.YYYY')
        WHEN UPPER(UTIL_ACTION_CD) = 'AUSNAHME VWK' THEN TO_VARCHAR(EXCEPTION_UTIL_DT, 'DD.MM.YYYY')
        WHEN TRY_TO_DATE(EXCEPTION_UTIL_DT)::VARCHAR(40) > CALCULATED_UTILISATION::VARCHAR(40) THEN TO_VARCHAR(EXCEPTION_UTIL_DT, 'DD.MM.YYYY')
        ELSE CALCULATED_UTILISATION
    END ::VARCHAR(40) AS CORRECT_UTILISATION

    ,TRY_TO_DATE(CORRECT_UTILISATION, 'DD.MM.YYYY') AS CORRECT_UTILISATION_DATE_ONLY
    ,DCW.CY_WEEK_NAME                 AS CORRECT_UTILISATION_WEEK
    ,FLOOR(DATEDIFF(DAY, CURRENT_DATE(), CORRECT_UTILISATION_DATE_ONLY) / 7) AS WEEKS_UNTIL_UTILISATION
    
    ,CASE
    	WHEN UPPER(UTIL_ACTION_CD) = 'VERWERTUNG' THEN 'bereits in Verwertung'
        WHEN MAX_DELIVERY_DATE IS NULL THEN 'kein LT'
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND MIN_DELIVERY_DATE < '2022-09-16' THEN 'Altes Konzept Festlistung'
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND MAX_DELIVERY_DATE < '2022-09-16' THEN 'Altes Konzept Aktion'
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND SP.ASSORTMENT_PLAN_PERIOD_NR IN ('2110','2107','2104','2101','2010','2007','2004','2001','1910','1907','1904','1901') THEN 'Altes Konzept Festlistung'
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND SP.ASSORTMENT_PLAN_PERIOD_NR IN ('2110','2107','2104','2101','2010','2007','2004','2001','1910','1907','1904','1901') THEN 'Altes Konzept Aktion'
        WHEN PROMO_DUR_WEEK_CNT IS NULL OR PROMO_DUR_WEEK_CNT = '0' THEN 'Sortiment, keine Verwertung'
        WHEN PROMO_DUR_WEEK_CNT <= '12' AND PROD_PROMO_CLASS_CD = 'FS' THEN 'Neues Konzept Festlistung 12 Wochen'
        WHEN PROMO_DUR_WEEK_CNT <= '12' AND PROD_PROMO_CLASS_CD != 'FS' THEN 'Neues Konzept Aktion 12 Wochen'
        WHEN PROMO_DUR_WEEK_CNT > '12' AND PROMO_DUR_WEEK_CNT <= '26' AND PROD_PROMO_CLASS_CD = 'FS' THEN 'Neues Konzept Festlistung 26 Wochen'
        WHEN PROMO_DUR_WEEK_CNT > '12' AND PROMO_DUR_WEEK_CNT <= '26' AND PROD_PROMO_CLASS_CD != 'FS' THEN 'Neues Konzept Aktion 26 Wochen'
        WHEN PROMO_DUR_WEEK_CNT > '26' AND PROD_PROMO_CLASS_CD = 'FS' THEN 'Neues Konzept Festlistung 52 Wochen'
        WHEN PROMO_DUR_WEEK_CNT > '26' AND PROD_PROMO_CLASS_CD != 'FS' THEN 'Neues Konzept Aktion 52 Wochen'
        ELSE 'kein LT'
    END ::VARCHAR(40) AS CALCULATED_INFORMATION_CONCEPT

    ,CASE 
        WHEN UPPER(UTIL_ACTION_CD) = 'AUSLISTUNG NACHDISPO' THEN 'Ausnahme ohne Auslistung'
        WHEN UPPER(UTIL_ACTION_CD) = 'AUSNAHME VWK' THEN 'Ausnahme ohne Auslistung'        
        WHEN LENGTH(CALCULATED_UTILISATION) = '10' THEN
            CASE 
                WHEN EXCEPTION_UTIL_DT::VARCHAR(40) > CALCULATED_UTILISATION::VARCHAR(40) THEN 'Ausnahme ohne Auslistung'
                ELSE CALCULATED_INFORMATION_CONCEPT
            END
            ELSE CALCULATED_INFORMATION_CONCEPT
    END ::VARCHAR(40) AS CORRECT_INFORMATION_CONCEPT

    ,CASE
	    WHEN UPPER(UTIL_ACTION_CD) = 'VERWERTUNG' THEN 'bereits in Verwertung'
        WHEN MAX_DELIVERY_DATE IS NULL THEN 'kein LT'
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND MIN_DELIVERY_DATE < '2022-09-16'::DATE THEN CONCAT ( YEAR(MIN_DELIVERY_DATE),  ' KW ', WEEK(MIN_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND MAX_DELIVERY_DATE < '2022-09-16'::DATE THEN CONCAT ( YEAR(MAX_DELIVERY_DATE),  ' KW ', WEEK(MAX_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND SP.ASSORTMENT_PLAN_PERIOD_NR IN ('2110','2107','2104','2101','2010','2007','2004','2001','1910','1907','1904','1901') THEN CONCAT ( YEAR(MIN_DELIVERY_DATE),  ' KW ', WEEK(MIN_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND SP.ASSORTMENT_PLAN_PERIOD_NR IN ('2110','2107','2104','2101','2010','2007','2004','2001','1910','1907','1904','1901') THEN CONCAT ( YEAR(MAX_DELIVERY_DATE),  ' KW ', WEEK(MAX_DELIVERY_DATE))
        WHEN PROMO_DUR_WEEK_CNT IS NULL OR PROMO_DUR_WEEK_CNT = '0' THEN 'Sortiment, keine Verwertung'
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND PROMO_DUR_WEEK_CNT <= '12' THEN CONCAT ( YEAR(MIN_DELIVERY_DATE),  ' KW ', WEEK(MIN_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND PROMO_DUR_WEEK_CNT <= '12' THEN CONCAT ( YEAR(MAX_DELIVERY_DATE),  ' KW ', WEEK(MAX_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND PROMO_DUR_WEEK_CNT > '12' AND PROMO_DUR_WEEK_CNT <= '26' THEN CONCAT ( YEAR(MIN_DELIVERY_DATE),  ' KW ', WEEK(MIN_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND PROMO_DUR_WEEK_CNT > '12' AND PROMO_DUR_WEEK_CNT <= '26' THEN CONCAT ( YEAR(MAX_DELIVERY_DATE),  ' KW ', WEEK(MAX_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD = 'FS' AND PROMO_DUR_WEEK_CNT > '26' THEN CONCAT ( YEAR(MIN_DELIVERY_DATE),  ' KW ', WEEK(MIN_DELIVERY_DATE))
        WHEN PROD_PROMO_CLASS_CD != 'FS' AND PROMO_DUR_WEEK_CNT > '26' THEN CONCAT ( YEAR(MAX_DELIVERY_DATE),  ' KW ', WEEK(MAX_DELIVERY_DATE))
        ELSE 'kein LT'
    END ::VARCHAR(40) AS USED_DELIVERY_UTILISATION_DATE

FROM
    CORE.T_DIM_PRODUCT DIM_P
LEFT JOIN
    CTE_PU FACT_PU
    ON
        DIM_P.PROD_SID = FACT_PU.PROD_SID
LEFT JOIN
    SALES_PROMOTION SP
    ON
        SP.PROD_SID = DIM_P.PROD_SID
LEFT JOIN 
    MAX_IAN IAN
    ON DIM_P.PROD_SID = IAN.PROD_SID
LEFT JOIN 
    MAX_BATCH BATCH
    ON DIM_P.PROD_SID = BATCH.PROD_SID
LEFT JOIN
    CORE.T_DIM_CAL_DAY DCD
    ON CORRECT_UTILISATION_DATE_ONLY = DCD.CAL_DT
LEFT JOIN
    CORE.T_DIM_CAL_WEEK DCW
    ON DCD.CY_WEEK = DCW.CY_WEEK
WHERE
    DIM_P.DWH_VALID_FG = TRUE
    AND DIM_P.PROD_SID IN ( -- only show products which currently have a stock greater than 0
        SELECT PROD_SID FROM CTE_SWD WHERE TOTAL_STOCK_CNT > 0
    )
;