CREATE OR REPLACE VIEW CORE.V_DIM_TRAVEL_OFFER_OPERATOR(
	TRAV_OFFER_OPERATOR_CD,
	TRAV_OFFER_OPERATOR_DESCR
) COMMENT='A regular view to fetch the distinct offer operator codes from travel booking fact'
 AS
SELECT DISTINCT OFFER_OPERATOR_CD AS TRAV_OFFER_OPERATOR_CD,
       NULL AS TRAV_OFFER_OPERATOR_DESCR
FROM CORE.T_FACT_TRAVEL_BOOKING;