CREATE OR REPLACE VIEW CORE.V_DIM_TRAVEL_OFFER_TYPE(
	TRAV_OFFER_TYPE_LVL1_NAME,
	TRAV_OFFER_TYPE_LVL2_NAME,
    TRAV_OFFER_TYPE_LVL3_NAME,
    TRAV_OFFER_TYPE_LVL4_NAME 
) COMMENT='A regular view to fetch the categorization of offer (4 levels of hierarchy)'
 AS
SELECT DISTINCT TRAV_OFFER_TYPE_LVL1_NAME,TRAV_OFFER_TYPE_LVL2_NAME,
TRAV_OFFER_TYPE_LVL3_NAME,TRAV_OFFER_TYPE_LVL4_NAME
FROM CORE.T_DIM_TRAVEL_OFFER;