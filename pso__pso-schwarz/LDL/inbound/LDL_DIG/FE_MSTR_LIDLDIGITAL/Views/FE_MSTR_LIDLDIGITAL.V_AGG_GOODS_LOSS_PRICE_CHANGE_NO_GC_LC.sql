CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_AGG_GOODS_LOSS_PRICE_CHANGE_NO_GC_LC
AS SELECT
     CASE WHEN BUSINESS_EVENT_TYPE_CD = '' THEN '-1' ELSE IFNULL(BUSINESS_EVENT_TYPE_CD, '-1') END AS BUSINESS_EVENT_TYPE_CD
    ,CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD
    ,EVENT_DT AS EVENT_DATE
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
    ,IFNULL(PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID    
    ,CASE WHEN DELIVERY_SRC_TYPE_CD = '' THEN '-1' ELSE IFNULL(DELIVERY_SRC_TYPE_CD, '-1') END AS DELIVERY_SRC_TYPE_CD
    ,CASE WHEN PROFIT_LOSS_REASON_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_CD, '-1') END AS PROFIT_LOSS_REASON_CD
    ,CASE WHEN GOODS_LOSS_ORIGIN_TYPE_CD = '' THEN '-1' ELSE IFNULL(GOODS_LOSS_ORIGIN_TYPE_CD, '-1') END AS GOODS_LOSS_ORIGIN_TYPE_CD
    ,IFNULL(NATIONAL_ACCT_SID, '-1') AS NATIONAL_ACCOUNT_SID
    ,NATIONAL_ACCT_NR AS NATIONAL_ACCOUNT_NR
    ,PROD_QTY AS PROD_QTY
    ,TGT_PRICE_NET_LOCAL_VAL AS TGT_PRICE_NET_LOCAL_VAL
    ,TGT_PRICE_NET_EUR_VAL AS TGT_PRICE_NET_EUR_VAL
    ,ACTUAL_PRICE_NET_LOCAL_VAL AS ACTUAL_PRICE_NET_LOCAL_VAL
    ,ACTUAL_PRICE_NET_EUR_VAL AS ACTUAL_PRICE_NET_EUR_VAL
    ,IVP_PRICE_NET_LOCAL_VAL AS IVP_PRICE_NET_LOCAL_VAL
    ,IVP_PRICE_NET_EUR_VAL AS IVP_PRICE_NET_EUR_VAL
    ,PC_LOSSES_NET_LOCAL_VAL AS PC_LOSSES_NET_LOCAL_VAL
    ,PC_LOSSES_NET_EUR_VAL AS PC_LOSSES_NET_EUR_VAL
    ,TRANSFER_MARGIN_NET_LOCAL_VAL AS TRANSFER_MARGIN_NET_LOCAL_VAL
    ,TRANSFER_MARGIN_NET_EUR_VAL AS TRANSFER_MARGIN_NET_EUR_VAL
    ,CORRECTION_COGS_NET_LOCAL_VAL AS CORRECTION_COGS_NET_LOCAL_VAL
    ,CORRECTION_COGS_NET_EUR_VAL AS CORRECTION_COGS_NET_EUR_VAL
FROM
    lec_share.v_agg_goods_loss_summary
WHERE
    GOODS_LOSS_ORIGIN_TYPE_CD = 'PC'
;
