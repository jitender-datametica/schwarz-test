CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_AGG_STOCK_WAREHOUSE_DAILY_ALLOCATED(
	WH_SID
	,PROD_VARIANT_SID
	,CAL_DT
	,ACTIVE_FG
	,BLOCKED_STOCK_CNT_ALLOCATED
	,BLOCKED_STOCK_VAL_ALLOCATED
	,BLOCKED_STOCK_RETURN_CNT_ALLOCATED
	,BLOCKED_STOCK_RETURN_VAL_ALLOCATED
	,UNRESTRICTED_STOCK_CNT_ALLOCATED
	,UNRESTRICTED_STOCK_VAL_ALLOCATED
	,RESTRICTED_STOCK_CNT_ALLOCATED
	,RESTRICTED_STOCK_VAL_ALLOCATED
	,IN_TRANSFER_CNT_ALLOCATED
	,IN_TRANSFER_VAL_ALLOCATED
	,IN_TRANSIT_CNT_ALLOCATED
	,IN_TRANSIT_VAL_ALLOCATED
	,IN_QTY_INSPECTION_CNT_ALLOCATED
	,IN_QTY_INSPECTION_VAL_ALLOCATED
	,AVAIL_TO_PROMISE_CNT_ALLOCATED
	,AVAIL_TO_PROMISE_VAL_ALLOCATED
	,AVAIL_TO_SELL_CNT_ALLOCATED
	,AVAIL_TO_SELL_VAL_ALLOCATED
	,RECEIV_ON_DOCK_CNT_ALLOCATED
	,RECEIV_ON_DOCK_VAL_ALLOCATED
	,TOTAL_STOCK_CNT_ALLOCATED
	,TOTAL_STOCK_VAL_ALLOCATED
    ,WH_ALLOC_ENTITY_CD
    ,WH_ALLOC_ENTITY_COUNTRY_CD
	,PROD_SID
	,DISTRIBUTION_PCT
	,ALLOC_PROMO_CLASS_CD
	,SUPPLIER_SID
	,CURR_CD
	,EKP_PRICE_VAL
	,GC_LC_CD
) AS SELECT
     IFNULL(AGG_SWD.WH_SID , -1) AS WH_SID
	,IFNULL(AGG_SWD.PROD_VARIANT_SID , -1) AS PROD_VARIANT_SID
    ,AGG_SWD.CAL_DT AS CAL_DT
    ,AGG_SWD.ACTIVE_FG AS ACTIVE_FG

    ,AGG_SWD.BLOCKED_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT AS BLOCKED_STOCK_CNT_ALLOCATED
    ,AGG_SWD.BLOCKED_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS BLOCKED_STOCK_VAL_ALLOCATED
    ,AGG_SWD.BLOCKED_STOCK_RETURN_CNT * FACT_SWAD.DISTRIBUTION_PCT AS BLOCKED_STOCK_RETURN_CNT_ALLOCATED
    ,AGG_SWD.BLOCKED_STOCK_RETURN_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS BLOCKED_STOCK_RETURN_VAL_ALLOCATED
    ,AGG_SWD.UNRESTRICTED_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT AS UNRESTRICTED_STOCK_CNT_ALLOCATED
    ,AGG_SWD.UNRESTRICTED_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS UNRESTRICTED_STOCK_VAL_ALLOCATED
    ,AGG_SWD.RESTRICTED_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT AS RESTRICTED_STOCK_CNT_ALLOCATED
    ,AGG_SWD.RESTRICTED_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS RESTRICTED_STOCK_VAL_ALLOCATED
    ,AGG_SWD.IN_TRANSFER_CNT * FACT_SWAD.DISTRIBUTION_PCT AS IN_TRANSFER_CNT_ALLOCATED
    ,AGG_SWD.IN_TRANSFER_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS IN_TRANSFER_VAL_ALLOCATED
    ,AGG_SWD.IN_TRANSIT_CNT * FACT_SWAD.DISTRIBUTION_PCT AS IN_TRANSIT_CNT_ALLOCATED
    ,AGG_SWD.IN_TRANSIT_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS IN_TRANSIT_VAL_ALLOCATED
    ,AGG_SWD.IN_QTY_INSPECTION_CNT * FACT_SWAD.DISTRIBUTION_PCT AS IN_QTY_INSPECTION_CNT_ALLOCATED
    ,AGG_SWD.IN_QTY_INSPECTION_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS IN_QTY_INSPECTION_VAL_ALLOCATED
    ,AGG_SWD.AVAIL_TO_PROMISE_CNT * FACT_SWAD.DISTRIBUTION_PCT AS AVAIL_TO_PROMISE_CNT_ALLOCATED
    ,AGG_SWD.AVAIL_TO_PROMISE_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS AVAIL_TO_PROMISE_VAL_ALLOCATED
    ,AGG_SWD.AVAIL_TO_SELL_CNT * FACT_SWAD.DISTRIBUTION_PCT AS AVAIL_TO_SELL_CNT_ALLOCATED
    ,AGG_SWD.AVAIL_TO_SELL_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS AVAIL_TO_SELL_VAL_ALLOCATED
    ,AGG_SWD.RECEIV_ON_DOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT AS RECEIV_ON_DOCK_CNT_ALLOCATED
    ,AGG_SWD.RECEIV_ON_DOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS RECEIV_ON_DOCK_VAL_ALLOCATED
    ,AGG_SWD.TOTAL_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT AS TOTAL_STOCK_CNT_ALLOCATED
    ,AGG_SWD.TOTAL_STOCK_CNT * FACT_SWAD.DISTRIBUTION_PCT * FACT_PPS.PRICE_VAL AS TOTAL_STOCK_VAL_ALLOCATED

    ,IFNULL(FACT_SWAD.WH_ALLOC_ENTITY_CD, '-1') AS WH_ALLOC_ENTITY_CD
    ,IFNULL(DIM_WAE.WH_ALLOC_ENTITY_COUNTRY_CD, '-1') AS WH_ALLOC_ENTITY_COUNTRY_CD
	,IFNULL(FACT_SWAD.PROD_SID , -1) AS PROD_SID
    ,FACT_SWAD.DISTRIBUTION_PCT AS DISTRIBUTION_PCT
    ,CASE WHEN FACT_SWAD.ALLOC_PROMO_CLASS_CD = '' THEN '-1' ELSE IFNULL(FACT_SWAD.ALLOC_PROMO_CLASS_CD, '-1') END AS ALLOC_PROMO_CLASS_CD

	,IFNULL(FACT_PPS.SUPPLIER_SID , -1) AS SUPPLIER_SID
    ,CASE WHEN FACT_PPS.CURR_CD = '' THEN '-1' ELSE IFNULL(FACT_PPS.CURR_CD, '-1') END AS CURR_CD
    ,FACT_PPS.PRICE_VAL AS EKP_PRICE_VAL
    ,'GC' AS GC_LC_CD
FROM
    lec_share.v_fact_stock_warehouse_daily AS AGG_SWD
INNER JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_VARIANT AS DIM_PV
    ON
        DIM_PV.PROD_VARIANT_SID = AGG_SWD.PROD_VARIANT_SID
INNER JOIN
    lec_share.v_fact_stock_warehouse_allocation_daily AS FACT_SWAD
    ON 
        FACT_SWAD.WH_SID = AGG_SWD.WH_SID
        AND FACT_SWAD.PROD_SID = DIM_PV.PROD_SID
        AND FACT_SWAD.CAL_DT = AGG_SWD.CAL_DT
INNER JOIN
    lec_share.v_dim_warehouse_allocation_entity DIM_WAE
    ON
        FACT_SWAD.WH_ALLOC_ENTITY_CD = DIM_WAE.WH_ALLOC_ENTITY_CD
LEFT JOIN
    lec_share.v_fact_product_price_supplier FACT_PPS
    ON
        FACT_PPS.SUPPLIER_SID = DIM_PV.MAIN_SUPPLIER_SID
        AND FACT_PPS.PROD_VARIANT_SID = DIM_PV.PROD_VARIANT_SID
        AND AGG_SWD.CAL_DT BETWEEN FACT_PPS.ACTIVE_FROM_TMSP AND FACT_PPS.ACTIVE_TO_TMSP
        AND FACT_PPS.WSHOP_CD = 'DE' -- DE buys all articles, see NBI-5097 (we could also use INT with the same result)
        AND FACT_PPS.PRICE_TYPE_CD = 'EKP'
        AND FACT_PPS.CURR_CD = 'EUR'

WHERE
    AGG_SWD.CAL_DT >= '2022-05-19'::DATE -- from 2022-05-19 and later, daily distribution percentages exist
    AND (AGG_SWD.ACTIVE_FG=1
        OR (AGG_SWD.CAL_DT BETWEEN DATE_TRUNC('month',ADD_MONTHS(CURRENT_DATE,-24)) AND LAST_DAY(ADD_MONTHS(CURRENT_DATE,-1),'month')
            AND AGG_SWD.CAL_DT=LAST_DAY(AGG_SWD.CAL_DT,'month')))

