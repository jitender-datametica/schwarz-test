CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_ADDRESS(
	ADDR_SID
	,ADDR_NR
	,ZIP_CD
    ,MSTR_ZIP_CD
	,COUNTRY_NAME
	,CITY_NAME
	,STREET_NAME
	,HOUSE_NR
	,DISTRICT_NAME
	,POST_BOX_NR
	,ADDR_SUFFIX
	,COMPANY_NAME
	,ADDR_LON
	,ADDR_LAT
	,ADDR_TYPE_CD
) AS 
SELECT
ADDR_SID
,ADDR_NR
,ZIP_CD
       ,CASE 
           WHEN COUNTRY_NAME = 'CZ' THEN REPLACE(ZIP_CD, ' ', '') -- REMOVING SPACES FROM CZECH
           WHEN COUNTRY_NAME = 'SK' THEN REPLACE(ZIP_CD, ' ', '') -- REMOVING SPACES FROM SLOVAKIA
           WHEN COUNTRY_NAME = 'NL' THEN LEFT(ZIP_CD, LEN(ZIP_CD) - 3) -- REMOVING LAST 3 LETTERS FROM NETHERLANDS
           ELSE ZIP_CD
       END AS MSTR_ZIP_CD -- THIS COLUMN IS CREATED BECAUSE MSTR DOESNT ACCEPTS THE FORMAT FROM SOURCE FOR THOSE COUNTRIES 
,COUNTRY_NAME
,CITY_NAME
,STREET_NAME
,HOUSE_NR
,DISTRICT_NAME
,POST_BOX_NR
,ADDR_SUFFIX
,COMPANY_NAME
,ADDR_LON
,ADDR_LAT
,ADDR_TYPE_CD
FROM
lec_share.v_dim_address
WHERE DWH_VALID_FG = 'TRUE'
UNION ALL
    SELECT 
         '-1' -- ADDR_SID
        ,''   -- ,ADDR_NR
        ,''   -- ,ZIP_CD
        ,''   -- ,MSTR_ZIP_CD
        ,''   -- ,COUNTRY_NAME
        ,''   -- ,CITY_NAME
        ,''   -- ,STREET_NAME
        ,''   -- ,HOUSE_NR
        ,''   -- ,DISTRICT_NAME
        ,''   -- ,POST_BOX_NR
        ,''   -- ,ADDR_SUFFIX
        ,''   -- ,COMPANY_NAME
        ,0    -- ,ADDR_LON
        ,0    -- ,ADDR_LAT
        ,'-1' -- ,ADDR_TYPE_CD
;