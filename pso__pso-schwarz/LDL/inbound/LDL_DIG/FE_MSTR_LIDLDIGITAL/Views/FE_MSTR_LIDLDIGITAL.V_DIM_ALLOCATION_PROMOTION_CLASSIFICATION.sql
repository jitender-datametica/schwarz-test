CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_ALLOCATION_PROMOTION_CLASSIFICATION
AS SELECT
     ALLOC_PROMO_CLASS_CD AS ALLOC_PROMO_CLASS_CD
    ,ALLOC_PROMO_CLASS_DESCR AS ALLOC_PROMO_CLASS_DESCR 
FROM
    lec_share.v_dim_allocation_promotion_classification
UNION ALL
    SELECT
         '-1' -- ALLOC_PROMO_CLASS_CD
        ,'' -- ALLOC_PROMO_CLASS_DESCR
;
