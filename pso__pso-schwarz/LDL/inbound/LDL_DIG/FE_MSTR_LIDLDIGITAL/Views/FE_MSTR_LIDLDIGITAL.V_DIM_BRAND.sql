CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_BRAND
(
     BRAND_SID
    ,BRAND_NR
    ,BRAND_NAME
    ,BRAND_CLASS_CD
)
AS SELECT
     BRAND_SID
    ,BRAND_NR
    ,BRAND_NAME
    ,CASE WHEN BRAND_CLASS_CD = '' THEN '-1' ELSE IFNULL(BRAND_CLASS_CD, '-1') END
FROM
    lec_share.v_dim_brand
WHERE DWH_VALID_FG = TRUE
UNION ALL
    SELECT '-1', '', '', '-1'
;