CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_BRAND_CLASSIFICATION
(
    BRAND_CLASS_CD
	,BRAND_CLASS_DESCR
    ,BRAND_CLASS_DESCR_DBR
) 
AS SELECT
     BRAND_CLASS_CD
    ,BRAND_CLASS_DESCR
    ,BRAND_CLASS_DESCR AS BRAND_CLASS_DESCR_DBR

FROM lec_share.v_dim_brand_classification
UNION ALL
    SELECT '-1', '', 'Sonst'
;