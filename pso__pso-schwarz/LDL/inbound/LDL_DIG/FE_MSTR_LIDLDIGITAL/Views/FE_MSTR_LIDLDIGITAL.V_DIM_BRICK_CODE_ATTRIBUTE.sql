CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_BRICK_CODE_ATTRIBUTE
AS SELECT
     CASE WHEN ATTR_CD = '' THEN '-1' ELSE IFNULL(ATTR_CD, '-1') END AS ATTR_CD
    ,ATTR_DESCR AS ATTR_DESCR
    ,IS_CUSTOM_FG AS IS_CUSTOM_FG 
FROM
    lec_share.v_dim_brick_code_attribute
UNION ALL
    SELECT
         '-1' -- ATTR_CD
        ,'' -- ATTR_DESCR
        ,FALSE -- IS_CUSTOM_FG
;
