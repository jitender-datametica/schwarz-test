CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_BRICK_CODE_VALUE
AS SELECT
     CASE WHEN VALUE_CD = '' THEN '-1' ELSE IFNULL(VALUE_CD, '-1') END AS VALUE_CD
    ,VALUE_DESCR AS VALUE_DESCR
    ,IS_CUSTOM_FG AS IS_CUSTOM_FG 
FROM
    lec_share.v_dim_brick_code_value
UNION ALL
    SELECT
         '-1' -- VALUE_CD
        ,'' -- VALUE_DESCR
        ,FALSE -- IS_CUSTOM_FG
;
