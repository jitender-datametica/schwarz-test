CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CAL_DAY
AS SELECT
     CAL_DT AS CAL_DT
    ,CY AS CY
    ,BUS_YEAR AS BUS_YEAR
    ,CY_MONTH AS CY_MONTH
    ,MONTH_OF_YEAR AS MONTH_OF_YEAR
    ,MONTH_OF_BUS_YEAR AS MONTH_OF_BUS_YEAR
    ,MONTH_OF_YEAR_SHORT_NAME AS MONTH_OF_YEAR_SHORT_NAME
    ,MONTH_OF_YEAR_SHORT_NAME_DE AS MONTH_OF_YEAR_SHORT_NAME_DE
    ,MONTH_OF_YEAR_SHORT_NAME_EN AS MONTH_OF_YEAR_SHORT_NAME_EN
    ,MONTH_OF_YEAR_NAME AS MONTH_OF_YEAR_NAME
    ,MONTH_OF_YEAR_NAME_DE AS MONTH_OF_YEAR_NAME_DE
    ,MONTH_OF_YEAR_NAME_EN AS MONTH_OF_YEAR_NAME_EN
    ,DAY_OF_MONTH AS DAY_OF_MONTH
    ,CY_WEEK AS CY_WEEK
    ,WEEK_OF_YEAR AS WEEK_OF_YEAR
    ,DAY_OF_WEEK AS DAY_OF_WEEK
    ,DAY_OF_WEEK_SHORT_NAME AS DAY_OF_WEEK_SHORT_NAME
    ,DAY_OF_WEEK_SHORT_NAME_DE AS DAY_OF_WEEK_SHORT_NAME_DE
    ,DAY_OF_WEEK_SHORT_NAME_EN AS DAY_OF_WEEK_SHORT_NAME_EN
    ,DAY_OF_WEEK_NAME AS DAY_OF_WEEK_NAME
    ,DAY_OF_WEEK_NAME_DE AS DAY_OF_WEEK_NAME_DE
    ,DAY_OF_WEEK_NAME_EN AS DAY_OF_WEEK_NAME_EN
    ,TO_VARCHAR(CAL_DT, 'dd.mm.YYYY') || ' ' || DAY_OF_WEEK_NAME_DE AS DAY_STRING_DE
    ,TO_VARCHAR(CAL_DT, 'dd.mm.YYYY') || ' ' || DAY_OF_WEEK_NAME_EN AS DAY_STRING_EN
    ,DAY_OF_CY AS DAY_OF_CY
    ,DAY_OF_BUS_YEAR AS DAY_OF_BUS_YEAR
    ,CAL_DT_PREV_1D AS CAL_DT_PREV_1D
    ,CAL_DT_PREV_1W AS CAL_DT_PREV_1W
    ,CAL_DT_PREV_1M AS CAL_DT_PREV_1M
    ,CAL_DT_PREV_1Y AS CAL_DT_PREV_1Y
    ,CAL_DT_PREV_2Y AS CAL_DT_PREV_2Y
    ,CAL_DT_PREV_3Y AS CAL_DT_PREV_3Y
    ,CAL_DT_PREV_4Y AS CAL_DT_PREV_4Y
    ,CAL_DT_PREV_5Y AS CAL_DT_PREV_5Y
    ,CAL_DT_SWDAY_PREV_1M AS CAL_DT_SWDAY_PREV_1M
    ,CAL_DT_SWDAY_PREV_1Y AS CAL_DT_SWDAY_PREV_1Y
    ,CAL_DT_SWDAY_PREV_2Y AS CAL_DT_SWDAY_PREV_2Y
    ,CAL_DT_SWDAY_PREV_3Y AS CAL_DT_SWDAY_PREV_3Y
    ,CAL_DT_SWDAY_PREV_4Y AS CAL_DT_SWDAY_PREV_4Y
    ,CAL_DT_SWDAY_PREV_5Y AS CAL_DT_SWDAY_PREV_5Y
    ,FIRST_DAY_OF_WEEK_FG AS FIRST_DAY_OF_WEEK_FG
    ,LAST_DAY_OF_WEEK_FG AS LAST_DAY_OF_WEEK_FG
    ,FIRST_DAY_OF_MONTH_FG AS FIRST_DAY_OF_MONTH_FG
    ,LAST_DAY_OF_MONTH_FG AS LAST_DAY_OF_MONTH_FG
    ,FIRST_DAY_OF_CY_FG AS FIRST_DAY_OF_CY_FG
    ,LAST_DAY_OF_CY_FG AS LAST_DAY_OF_CY_FG
    ,FIRST_DAY_OF_BUS_YEAR_FG AS FIRST_DAY_OF_BUS_YEAR_FG
    ,LAST_DAY_OF_BUS_YEAR_FG AS LAST_DAY_OF_BUS_YEAR_FG
    ,CAL_DT_OFFSET AS CAL_DT_OFFSET
    ,CY_WEEK_OFFSET AS CY_WEEK_OFFSET
    ,CY_MONTH_OFFSET AS CY_MONTH_OFFSET
    ,CY_OFFSET AS CY_OFFSET
    ,BUS_YEAR_OFFSET AS BUS_YEAR_OFFSET
    ,CY_QUARTER AS CY_QUARTER
FROM
    lec_share.v_dim_cal_day
WHERE 
    CAL_DT != TO_DATE('1900-01-01') -- some date core tables contain a dummy entry, which is removed here so we can add our own dummy value
UNION ALL
    SELECT
         TO_DATE('1900-01-01')-- CAL_DT
        ,'-1' -- CY
        ,'-1' -- BUS_YEAR
        ,'-1' -- CY_MONTH
        ,'-1' -- MONTH_OF_YEAR
        ,'-1' -- MONTH_OF_BUS_YEAR
        ,'' -- MONTH_OF_YEAR_SHORT_NAME
        ,'' -- MONTH_OF_YEAR_SHORT_NAME_DE
        ,'' -- MONTH_OF_YEAR_SHORT_NAME_EN
        ,'' -- MONTH_OF_YEAR_NAME
        ,'' -- MONTH_OF_YEAR_NAME_DE
        ,'' -- MONTH_OF_YEAR_NAME_EN
        ,'-1' -- DAY_OF_MONTH
        ,'-1' -- CY_WEEK
        ,'-1' -- WEEK_OF_YEAR
        ,'-1' -- DAY_OF_WEEK
        ,'' -- DAY_OF_WEEK_SHORT_NAME
        ,'' -- DAY_OF_WEEK_SHORT_NAME_DE
        ,'' -- DAY_OF_WEEK_SHORT_NAME_EN
        ,'' -- DAY_OF_WEEK_NAME
        ,'' -- DAY_OF_WEEK_NAME_DE
        ,'' -- DAY_OF_WEEK_NAME_EN
        ,'' -- DAY_STRING_DE
        ,'' -- DAY_STRING_EN
        ,'-1' -- DAY_OF_CY
        ,'-1' -- DAY_OF_BUS_YEAR
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_1D
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_1W
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_1M
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_1Y
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_2Y
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_3Y
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_4Y
        ,TO_DATE('1900-01-01') -- CAL_DT_PREV_5Y
        ,TO_DATE('1900-01-01') -- CAL_DT_SWDAY_PREV_1M
        ,TO_DATE('1900-01-01') -- CAL_DT_SWDAY_PREV_1Y
        ,TO_DATE('1900-01-01') -- CAL_DT_SWDAY_PREV_2Y
        ,TO_DATE('1900-01-01') -- CAL_DT_SWDAY_PREV_3Y
        ,TO_DATE('1900-01-01') -- CAL_DT_SWDAY_PREV_4Y
        ,TO_DATE('1900-01-01') -- CAL_DT_SWDAY_PREV_5Y
        ,FALSE -- FIRST_DAY_OF_WEEK_FG
        ,FALSE -- LAST_DAY_OF_WEEK_FG
        ,FALSE -- FIRST_DAY_OF_MONTH_FG
        ,FALSE -- LAST_DAY_OF_MONTH_FG
        ,FALSE -- FIRST_DAY_OF_CY_FG
        ,FALSE -- LAST_DAY_OF_CY_FG
        ,FALSE -- FIRST_DAY_OF_BUS_YEAR_FG
        ,FALSE -- LAST_DAY_OF_BUS_YEAR_FG
        ,'999' -- CAL_DT_OFFSET
        ,'999' -- CY_WEEK_OFFSET
        ,'999' -- CY_MONTH_OFFSET
        ,'999' -- CY_OFFSET
        ,'999' -- BUS_YEAR_OFFSET
        ,'-1' -- CY_QUARTER
;