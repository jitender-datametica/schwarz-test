CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CAL_MONTH
AS SELECT
     CY_MONTH AS CY_MONTH
    ,CY AS CY
    ,BUS_YEAR AS BUS_YEAR
    ,MONTH_OF_YEAR AS MONTH_OF_YEAR
    ,MONTH_OF_BUS_YEAR AS MONTH_OF_BUS_YEAR
    ,MONTH_OF_YEAR_SHORT_NAME AS MONTH_OF_YEAR_SHORT_NAME
    ,MONTH_OF_YEAR_SHORT_NAME_DE AS MONTH_OF_YEAR_SHORT_NAME_DE
    ,MONTH_OF_YEAR_SHORT_NAME_EN AS MONTH_OF_YEAR_SHORT_NAME_EN
    ,MONTH_OF_YEAR_NAME AS MONTH_OF_YEAR_NAME
    ,MONTH_OF_YEAR_NAME_DE AS MONTH_OF_YEAR_NAME_DE
    ,MONTH_OF_YEAR_NAME_EN AS MONTH_OF_YEAR_NAME_EN
    ,CY_MONTH_BEGIN_DT AS CY_MONTH_BEGIN_DT
    ,CY_MONTH_END_DT AS CY_MONTH_END_DT
    ,CY_MONTH_DAY_CNT AS CY_MONTH_DAY_CNT
    ,CY_MONTH_PREV_1M AS CY_MONTH_PREV_1M
    ,CY_MONTH_PREV_1Y AS CY_MONTH_PREV_1Y
    ,CY_MONTH_PREV_2Y AS CY_MONTH_PREV_2Y
    ,CY_MONTH_PREV_3Y AS CY_MONTH_PREV_3Y
    ,CY_MONTH_PREV_4Y AS CY_MONTH_PREV_4Y
    ,CY_MONTH_PREV_5Y AS CY_MONTH_PREV_5Y
    ,CY_MONTH_OFFSET AS CY_MONTH_OFFSET
    ,CY_OFFSET AS CY_OFFSET
    ,BUS_YEAR_OFFSET AS BUS_YEAR_OFFSET
FROM
    lec_share.v_dim_cal_month
WHERE 
    CY_MONTH != '-1' -- some date core tables contain a -1 dummy entry, which is removed here so we can add our own dummy value
UNION ALL
    SELECT
             '-1' -- CY_MONTH
            ,'-1' -- CY
            ,'-1' -- BUS_YEAR
            ,'-1' -- MONTH_OF_YEAR
            ,'-1' -- MONTH_OF_BUS_YEAR
            ,'' -- MONTH_OF_YEAR_SHORT_NAME
            ,'' -- MONTH_OF_YEAR_SHORT_NAME_DE
            ,'' -- MONTH_OF_YEAR_SHORT_NAME_EN
            ,'' -- MONTH_OF_YEAR_NAME
            ,'' -- MONTH_OF_YEAR_NAME_DE
            ,'' -- MONTH_OF_YEAR_NAME_EN
            ,TO_DATE('1900-01-01') -- CY_MONTH_BEGIN_DT
            ,TO_DATE('1900-01-01') -- CY_MONTH_END_DT
            ,'0' -- CY_MONTH_DAY_CNT
            ,'-1' -- CY_MONTH_PREV_1M
            ,'-1' -- CY_MONTH_PREV_1Y
            ,'-1' -- CY_MONTH_PREV_2Y
            ,'-1' -- CY_MONTH_PREV_3Y
            ,'-1' -- CY_MONTH_PREV_4Y
            ,'-1' -- CY_MONTH_PREV_5Y
            ,'999' -- CY_MONTH_OFFSET
            ,'999' -- CY_OFFSET
            ,'999' -- BUS_YEAR_OFFSET
;