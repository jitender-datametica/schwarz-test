    ,CC_GROUP_LVL3_NAME_DE AS CC_GROUP_LVL3_NAME_DE
    ,CASE WHEN CC_GROUP_LVL2_NR = '' THEN '-1' ELSE IFNULL(CC_GROUP_LVL2_NR, '-1') END AS CC_GROUP_LVL2_NR
    ,CC_GROUP_LVL2_NAME_EN AS CC_GROUP_LVL2_NAME_EN
    ,CC_GROUP_LVL2_NAME_DE AS CC_GROUP_LVL2_NAME_DE
    ,CASE WHEN CC_GROUP_LVL1_NR = '' THEN '-1' ELSE IFNULL(CC_GROUP_LVL1_NR, '-1') END AS CC_GROUP_LVL1_NR
    ,CC_GROUP_LVL1_NAME_EN AS CC_GROUP_LVL1_NAME_EN
    ,CC_GROUP_LVL1_NAME_DE AS CC_GROUP_LVL1_NAME_DE
