CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_COUPON
AS SELECT
     COUPON_ID AS COUPON_ID
    ,CASE WHEN COUPON_CD = '' THEN '-1' ELSE IFNULL(COUPON_CD, '-1') END AS COUPON_CD
    ,CASE WHEN COUPON_PROMO_CD = '' THEN '-1' ELSE IFNULL(COUPON_PROMO_CD, '-1') END AS COUPON_PROMO_CD
    ,COUPON_PROMO_NAME AS COUPON_PROMO_NAME
    ,CONVERT_TIMEZONE('Europe/Berlin', COUPON_VALID_FROM_TMSP)::TIMESTAMP_NTZ AS COUPON_VALID_FROM_TMSP
    ,CONVERT_TIMEZONE('Europe/Berlin', COUPON_VALID_TO_TMSP)::TIMESTAMP_NTZ AS COUPON_VALID_TO_TMSP
    ,CASE WHEN COUPON_TYPE_CD = '' THEN '-1' ELSE IFNULL(COUPON_TYPE_CD, '-1') END AS COUPON_TYPE_CD
    ,CASE WHEN COUPON_DISCOUNT_TYPE_CD = '' THEN '-1' ELSE IFNULL(COUPON_DISCOUNT_TYPE_CD, '-1') END AS COUPON_DISCOUNT_TYPE_CD
    ,COUPON_MAX_REDEMPTION_CNT AS COUPON_MAX_REDEMPTION_CNT
    ,CASE WHEN PROD_FOOD_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_FOOD_CLASS_CD, '-1') END AS PROD_FOOD_CLASS_CD
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
    ,DISCOUNT_SHIP_FG AS DISCOUNT_SHIP_FG
    ,COUPON_DISCOUNT_PCT AS COUPON_DISCOUNT_PCT
    ,COUPON_DISCOUNT_GROSS_LOCAL_VAL AS COUPON_DISCOUNT_GROSS_LOCAL_VAL
FROM
    lec_share.v_dim_coupon
UNION ALL
    SELECT
        '-1'   -- COUPON_ID   
        ,'-1' -- COUPON_CD
        ,'-1' -- COUPON_PROMO_CD
        ,'-1' -- COUPON_PROMO_NAME
        ,CAST('1900-01-01' AS TIMESTAMP_NTZ) -- COUPON_VALID_FROM_TMSP
        ,CAST('2999-01-01' AS TIMESTAMP_NTZ) -- COUPON_VALID_TO_TMSP
        ,'-1' -- COUPON_TYPE_CD
        ,'-1' -- COUPON_DISCOUNT_TYPE_CD
        ,'0' -- COUPON_MAX_REDEMPTION_CNT
        ,'-1' -- PROD_FOOD_CLASS_CD
        ,'-1' -- CURR_CD,
        ,FALSE -- DISCOUNT_SHIP_FG,
        ,'0' -- COUPON_DISCOUNT_PCT,
        ,'0' -- COUPON_DISCOUNT_GROSS_LOCAL_VAL
;
