CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_COUPON_TYPE
AS SELECT
     CASE WHEN COUPON_TYPE_CD = '' THEN '-1' ELSE IFNULL(COUPON_TYPE_CD, '-1') END AS COUPON_TYPE_CD
    ,COUPON_TYPE_DESCR AS COUPON_TYPE_DESCR 
FROM
    lec_share.v_dim_coupon_type
UNION ALL
    SELECT
         '-1' -- COUPON_TYPE_CD
        ,'' -- COUPON_TYPE_DESCR
;
