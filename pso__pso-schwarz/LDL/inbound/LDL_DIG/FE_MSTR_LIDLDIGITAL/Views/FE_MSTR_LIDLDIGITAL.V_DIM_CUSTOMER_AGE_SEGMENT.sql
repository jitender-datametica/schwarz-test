CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CUSTOMER_AGE_SEGMENT
AS SELECT
     CASE WHEN CUST_AGE_SEGM_CD = '' THEN '-1' ELSE IFNULL(CUST_AGE_SEGM_CD, '-1') END AS CUST_AGE_SEGM_CD
    ,CASE WHEN CUST_AGE_SEGM_TYPE_CD = '' THEN '-1' ELSE IFNULL(CUST_AGE_SEGM_TYPE_CD, '-1') END AS CUST_AGE_SEGM_TYPE_CD
    ,CUST_AGE_SEGM_DESCR AS CUST_AGE_SEGM_DESCR
    ,CUST_AGE_SEGM_START_YEAR AS CUST_AGE_SEGM_START_YEAR
    ,CUST_AGE_SEGM_END_YEAR AS CUST_AGE_SEGM_END_YEAR 
FROM
    lec_share.v_dim_customer_age_segment
UNION ALL
    SELECT
         '-1' -- CUST_AGE_SEGM_CD
        ,'-1' -- CUST_AGE_SEGM_TYPE_CD
        ,'' -- CUST_AGE_SEGM_DESCR
        ,'-1' -- CUST_AGE_SEGM_START_YEAR
        ,'-1' -- CUST_AGE_SEGM_END_YEAR
;
