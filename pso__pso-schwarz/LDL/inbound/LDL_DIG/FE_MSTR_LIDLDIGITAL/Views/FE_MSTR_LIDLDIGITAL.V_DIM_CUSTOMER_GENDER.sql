CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CUSTOMER_GENDER
AS SELECT
     CASE WHEN CUST_GENDER_CD = '' THEN '-1' ELSE IFNULL(CUST_GENDER_CD, '-1') END AS CUST_GENDER_CD
    ,CUST_GENDER_DESCR AS CUST_GENDER_DESCR 
FROM
    lec_share.v_dim_customer_gender
UNION ALL
    SELECT
         '-1' -- CUST_GENDER_CD
        ,'' -- CUST_GENDER_DESCR
;
