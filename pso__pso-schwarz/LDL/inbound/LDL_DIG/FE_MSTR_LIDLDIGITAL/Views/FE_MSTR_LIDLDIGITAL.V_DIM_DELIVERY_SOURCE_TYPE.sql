CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_DELIVERY_SOURCE_TYPE
(
    DELIVERY_SRC_TYPE_CD
    ,DELIVERY_SRC_TYPE_DESCR
    ,DELIVERY_SRC_TYPE_GRP
    ,DELIVERY_SRC_TYPE_DESCR_DBR
)
AS SELECT
     DELIVERY_SRC_TYPE_CD
    ,DELIVERY_SRC_TYPE_DESCR
    ,DELIVERY_SRC_TYPE_DESCR
    ,CASE WHEN DELIVERY_SRC_TYPE_CD = 'DIG' THEN 'Sonst' 
    WHEN DELIVERY_SRC_TYPE_CD = 'LAG' THEN 'Lager'
    WHEN DELIVERY_SRC_TYPE_CD = 'STR' THEN 'Strecke'
    WHEN DELIVERY_SRC_TYPE_CD = 'Sonst' THEN 'Sonst'
    ELSE '-1'
    END AS DELIVERY_SRC_TYPE_DESCR_DBR

FROM lec_share.v_dim_delivery_source_type
UNION ALL
    SELECT '-1', '', '', 'Sonst'
;