CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_INTERNAL_COMPANY_PARTNER(
    INTERNAL_COMPANY_PARTNER_SID
    ,INTERNAL_COMPANY_PARTNER_NR
    ,INTERNAL_COMPANY_PARTNER_NAME
) AS
SELECT
     INTERNAL_COMPANY_PARTNER_SID    
    ,CASE WHEN INTERNAL_COMPANY_PARTNER_NR = '' THEN '-1' ELSE IFNULL(INTERNAL_COMPANY_PARTNER_NR, '-1') END  AS INTERNAL_COMPANY_PARTNER_NR
    ,INTERNAL_COMPANY_PARTNER_NAME
FROM
    lec_share.v_dim_internal_company_partner
WHERE
    DWH_VALID_FG = TRUE
UNION ALL
    SELECT '-1', '-1', '-1'
;