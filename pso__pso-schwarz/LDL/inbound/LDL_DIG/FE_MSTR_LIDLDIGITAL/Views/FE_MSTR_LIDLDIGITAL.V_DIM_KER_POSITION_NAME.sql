CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_KER_POSITION_NAME
AS SELECT DISTINCT
	FISCAL_YEAR
	, PROFIT_LOSS_POSITION_NR 				AS KER_POSITION_NR
    , PROFIT_LOSS_POSITION_NAME 			AS KER_POSITION_NAME
    , PROFIT_LOSS_POSITION_DISPLAY_ORDER_NR AS KER_POSITION_DISPLAY_ORDER_NR
FROM
    lec_share.v_rel_cost_element_group_profit_loss_position
UNION ALL
    SELECT 
   	'-1' 		-- FISCAL_YEAR  
    , '-1'		-- KER_POSITION_NR
    , '-1'		-- KER_POSITION_NAME
    , '1000'	-- KER_POSITION_DISPLAY_ORDER_NR
;