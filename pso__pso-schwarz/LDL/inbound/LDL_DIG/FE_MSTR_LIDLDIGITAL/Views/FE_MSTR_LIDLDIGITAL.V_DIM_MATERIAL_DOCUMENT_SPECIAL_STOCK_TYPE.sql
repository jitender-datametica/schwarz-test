CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_MATERIAL_DOCUMENT_SPECIAL_STOCK_TYPE
AS SELECT
     CASE WHEN MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD = '' THEN '-1' ELSE IFNULL(MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD, '-1') END AS MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD
    ,MATERIAL_DOC_SPECIAL_STOCK_TYPE_DESCR AS MATERIAL_DOC_SPECIAL_STOCK_TYPE_DESCR 
FROM
    lec_share.v_dim_material_document_special_stock_type
UNION ALL
    SELECT
         '-1' -- MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD
        ,'' -- MATERIAL_DOC_SPECIAL_STOCK_TYPE_DESCR
;
