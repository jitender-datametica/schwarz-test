CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PACKAGING_MATERIAL_COMPONENT
(
     PACK_MATERIAL_NR
    ,PACK_COMPOS_GROUP_NAME
    ,PACK_COMPOS_TYPE_NAME
    ,LDPCR_COMPOS_KG
    ,LDPE_COMPOS_KG
    ,PP_COMPOS_KG
    ,PE_COMPOS_KG
    ,THERMO_ECO_COMPOS_KG
    ,PAPER_COMPOS_KG
    ,CORRUGATED_CARDBOARD_KG
)
AS SELECT
     PACK_MATERIAL_NR
    ,PACK_COMPOS_GROUP_NAME
    ,PACK_COMPOS_TYPE_NAME
    ,LDPCR_COMPOS_KG
    ,LDPE_COMPOS_KG
    ,PP_COMPOS_KG
    ,PE_COMPOS_KG
    ,THERMO_ECO_COMPOS_KG
    ,PAPER_COMPOS_KG
    ,CORRUGATED_CARDBOARD_KG
FROM
    lec_share.v_dim_packaging_material_component
WHERE
    DWH_VALID_FG = TRUE
UNION ALL
    SELECT
         '-1' -- PACK_MATERIAL_NR
        ,'' -- PACK_COMPOS_GROUP_NAME
        ,'' -- PACK_COMPOS_TYPE_NAME
        ,'0' -- LDPCR_COMPOS_KG
        ,'0' -- LDPE_COMPOS_KG
        ,'0' -- PP_COMPOS_KG
        ,'0' -- PE_COMPOS_KG
        ,'0' -- THERMO_ECO_COMPOS_KG
        ,'0' -- PAPER_COMPOS_KG
        ,'0' -- CORRUGATED_CARDBOARD_KG
;