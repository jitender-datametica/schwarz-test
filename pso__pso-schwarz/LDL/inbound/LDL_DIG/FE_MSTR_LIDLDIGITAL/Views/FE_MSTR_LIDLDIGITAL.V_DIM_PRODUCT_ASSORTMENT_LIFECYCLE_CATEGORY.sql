CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_ASSORTMENT_LIFECYCLE_CATEGORY
AS SELECT
     CASE WHEN PROD_ASSORTMENT_LIFECYCLE_CAT_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_LIFECYCLE_CAT_CD, '-1') END AS PROD_ASSORTMENT_LIFECYCLE_CAT_CD
    ,PROD_ASSORTMENT_LIFECYCLE_CAT_DESCR AS PROD_ASSORTMENT_LIFECYCLE_CAT_DESCR
    ,CASE WHEN PROD_ASSORTMENT_LIFECYCLE_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_LIFECYCLE_CD, '-1') END AS PROD_ASSORTMENT_LIFECYCLE_CD 
FROM
    lec_share.v_dim_product_assortment_lifecycle_category
UNION ALL
    SELECT
         '-1' -- PROD_ASSORTMENT_LIFECYCLE_CAT_CD
        ,'' -- PROD_ASSORTMENT_LIFECYCLE_CAT_DESCR
        ,'-1' -- PROD_ASSORTMENT_LIFECYCLE_CD
;
