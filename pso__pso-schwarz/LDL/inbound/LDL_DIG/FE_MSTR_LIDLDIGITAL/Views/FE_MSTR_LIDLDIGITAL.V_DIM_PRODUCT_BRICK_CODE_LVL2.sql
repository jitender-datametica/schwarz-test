CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_BRICK_CODE_LVL2
AS SELECT
     CASE WHEN PROD_GS1_LVL2_BRICK_CD = '' THEN '-1' ELSE IFNULL(PROD_GS1_LVL2_BRICK_CD, '-1') END AS PROD_GS1_LVL2_BRICK_CD
    ,PROD_GS1_LVL2_BRICK_DESCR AS PROD_GS1_LVL2_BRICK_DESCR
    ,CASE WHEN PROD_GS1_LVL1_BRICK_CD = '' THEN '-1' ELSE IFNULL(PROD_GS1_LVL1_BRICK_CD, '-1') END AS PROD_GS1_LVL1_BRICK_CD
    ,PROD_GS1_LVL1_BRICK_DESCR AS PROD_GS1_LVL1_BRICK_DESCR
FROM
    lec_share.v_dim_product_brick_code_lvl2
WHERE
    DWH_VALID_FG = TRUE
UNION ALL
    SELECT
         '-1' -- PROD_GS1_LVL2_BRICK_CD
        ,'' -- PROD_GS1_LVL2_BRICK_DESCR
        ,'-1' -- PROD_GS1_LVL1_BRICK_CD
        ,'' -- PROD_GS1_LVL1_BRICK_DESCR
;
