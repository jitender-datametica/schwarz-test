CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.v_dim_product_category_of_need (
     CATEGORY_OF_NEED_CD
   , CATEGORY_OF_NEED_NAME
   , WORLD_OF_NEED_CD
   , DWH_CREATED_TMSP
   , DWH_UPDATED_TMSP
   , DWH_SRC_FILE_NAME
   , SRC_FILE_TMSP
 
) AS SELECT
     CATEGORY_OF_NEED_CD
   , CATEGORY_OF_NEED_NAME
   , WORLD_OF_NEED_CD
   , DWH_CREATED_TMSP
   , DWH_UPDATED_TMSP
   , DWH_SRC_FILE_NAME
   , SRC_FILE_TMSP
FROM LEC_SHARE.v_dim_product_category_of_need
UNION ALL
    SELECT
          '-1' -- CATEGORY_OF_NEED_CD   
        , ''   -- CATEGORY_OF_NEED_NAME
        , '-1' -- WORLD_OF_NEED_CD
        , CAST('1900-01-01' AS TIMESTAMP_NTZ) -- DWH_CREATED_TMSP
        , CAST('1900-01-01' AS TIMESTAMP_NTZ) -- DWH_UPDATED_TMSP
        , ''   -- DWH_SRC_FILE_NAME
        , CAST('1900-01-01' AS TIMESTAMP_NTZ) -- SRC_FILE_TMSP
;