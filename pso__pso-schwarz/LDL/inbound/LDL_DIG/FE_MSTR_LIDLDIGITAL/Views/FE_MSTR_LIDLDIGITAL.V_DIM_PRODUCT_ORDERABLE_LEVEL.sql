CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_ORDERABLE_LEVEL
AS SELECT
     CASE WHEN PROD_ORDERABLE_LVL_CD = '' THEN '-1' ELSE IFNULL(PROD_ORDERABLE_LVL_CD, '-1') END AS PROD_ORDERABLE_LVL_CD
    ,PROD_ORDERABLE_LVL_DESCR AS PROD_ORDERABLE_LVL_DESCR 
FROM
    lec_share.v_dim_product_orderable_level
UNION
    SELECT
         '-1' -- PROD_ORDERABLE_LVL_CD
        ,'' -- PROD_ORDERABLE_LVL_DESCR
;
