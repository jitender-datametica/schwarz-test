CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PROFIT_LOSS_REASON
AS SELECT
     CASE WHEN PROFIT_LOSS_REASON_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_CD, '-1') END AS PROFIT_LOSS_REASON_CD
    ,PROFIT_LOSS_REASON_NAME AS PROFIT_LOSS_REASON_NAME
    ,CASE WHEN PROFIT_LOSS_REASON_GROUP_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_GROUP_CD, '-1') END AS PROFIT_LOSS_REASON_GROUP_CD
    ,PROFIT_LOSS_REASON_GROUP_NAME AS PROFIT_LOSS_REASON_GROUP_NAME
    ,PROFIT_LOSS_TYPE_NAME AS PROFIT_LOSS_TYPE_NAME 
FROM
    lec_share.v_dim_profit_loss_reason
UNION ALL
    SELECT
         '-1' -- PROFIT_LOSS_REASON_CD
        ,'' -- PROFIT_LOSS_REASON_NAME
        ,'-1' -- PROFIT_LOSS_REASON_GROUP_CD
        ,'' -- PROFIT_LOSS_REASON_GROUP_NAME
        ,'' -- PROFIT_LOSS_TYPE_NAME
;
