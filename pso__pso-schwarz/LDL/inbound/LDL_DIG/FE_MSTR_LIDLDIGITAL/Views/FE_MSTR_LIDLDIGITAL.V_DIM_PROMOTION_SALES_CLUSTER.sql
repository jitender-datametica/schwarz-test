CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PROMOTION_SALES_CLUSTER
AS SELECT
     IFNULL(PROMO_SALE_CLUSTER_CD, '-1') AS PROMO_SALE_CLUSTER_CD
    ,PROMO_SALE_CLUSTER_DESCR AS PROMO_SALE_CLUSTER_DESCR
    ,LAST_WEEK_NR AS LAST_WEEK_NR 
FROM
    lec_share.v_dim_promotion_sales_cluster
UNION ALL
    SELECT
         '-1' -- PROMO_SALE_CLUSTER_CD
        ,'-1' -- PROMO_SALE_CLUSTER_DESCR
        ,'0' -- LAST_WEEK_NR
;
