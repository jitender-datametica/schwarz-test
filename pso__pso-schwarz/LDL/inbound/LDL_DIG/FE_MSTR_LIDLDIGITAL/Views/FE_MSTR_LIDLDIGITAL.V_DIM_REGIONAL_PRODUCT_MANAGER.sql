CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_REGIONAL_PRODUCT_MANAGER(
    WSHOP_CD
    , REG_PROD_MANAGER_CD
    , REG_PROD_MANAGER_NAME
    , REG_PROD_MANAGER_TEAM_LEAD_NAME
) AS SELECT
    WSHOP_CD
    , REG_PROD_MANAGER_CD
    , REG_PROD_MANAGER_NAME
    , REG_PROD_MANAGER_TEAM_LEAD_NAME
FROM lec_share.v_dim_regional_product_manager
UNION ALL
SELECT 
	'-1'     -- WSHOP_CD
    , '-1'   -- REG_PROD_MANAGER_CD
	, ''     -- REG_PROD_MANAGER_NAME
	, ''     -- REG_PROD_MANAGER_TEAM_LEAD_NAME
;