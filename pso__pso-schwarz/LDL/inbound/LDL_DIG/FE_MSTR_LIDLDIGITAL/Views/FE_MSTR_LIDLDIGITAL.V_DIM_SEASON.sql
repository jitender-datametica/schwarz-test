CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_SEASON
(
     SEASON_NR
    ,SEASON_START_MON_DT_NR
    ,SEASON_END_MON_DT_NR
    ,SEASON_NAME
)
