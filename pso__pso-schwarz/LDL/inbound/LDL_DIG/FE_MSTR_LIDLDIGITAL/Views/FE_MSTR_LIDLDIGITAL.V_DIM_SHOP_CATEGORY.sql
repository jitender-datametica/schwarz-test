CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_SHOP_CATEGORY
(
     SHOP_CAT_SID
    ,SHOP_CAT_CD
    ,SHOP_CAT_NAME
    ,SHOP_CAT_LVL1_SID
    ,SHOP_CAT_LVL2_SID
    ,SHOP_CAT_LVL3_SID
    ,SHOP_CAT_LVL4_SID
)
AS SELECT
     SHOP_CAT_SID
	,IFNULL(SHOP_CAT_CD, '-1')
    ,SHOP_CAT_NAME
	,IFNULL(SHOP_CAT_LVL1_SID, '-1')
	,IFNULL(SHOP_CAT_LVL2_SID, '-1')
	,IFNULL(SHOP_CAT_LVL3_SID, '-1')
	,IFNULL(SHOP_CAT_LVL4_SID, '-1')
FROM lec_share.v_dim_shop_category
WHERE DWH_VALID_FG = TRUE
UNION ALL
    SELECT
    
         '-1' -- SHOP_CAT_SID
        ,'-1' -- ,SHOP_CAT_CD
        ,''   -- ,SHOP_CAT_NAME
        ,'-1' -- ,SHOP_CAT_LVL1_SID
        ,'-1' -- ,SHOP_CAT_LVL2_SID
        ,'-1' -- ,SHOP_CAT_LVL3_SID
        ,'-1' -- ,SHOP_CAT_LVL4_SID
;