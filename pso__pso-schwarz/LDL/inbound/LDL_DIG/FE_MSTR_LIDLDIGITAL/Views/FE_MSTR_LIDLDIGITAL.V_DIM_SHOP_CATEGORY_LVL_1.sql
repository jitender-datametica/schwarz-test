CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_SHOP_CATEGORY_LVL_1
(
     SHOP_CAT_LVL1_SID
    ,SHOP_CAT_LVL1_CD
    ,SHOP_CAT_LVL1_NAME
)
AS SELECT
     SHOP_CAT_LVL1_SID
    ,IFNULL(SHOP_CAT_LVL1_CD, '-1')
    ,SHOP_CAT_LVL1_NAME
FROM lec_share.v_dim_shop_category_lvl_1
WHERE DWH_VALID_FG = TRUE
UNION ALL
    SELECT '-1', '-1', ''
;