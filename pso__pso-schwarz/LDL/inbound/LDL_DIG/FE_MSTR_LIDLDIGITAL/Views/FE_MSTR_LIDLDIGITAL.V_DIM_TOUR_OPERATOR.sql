CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TOUR_OPERATOR
(
     TOUR_OPERATOR_CD
    ,TOUR_OPERATOR_NAME
    ,TOUR_OPERATOR_TYPE_CD
    ,TOUR_OPERATOR_CONTRACT_TYPE_CD
)
AS SELECT
     TOUR_OPERATOR_CD
    ,TOUR_OPERATOR_NAME
    ,CASE WHEN TOUR_OPERATOR_TYPE_CD = '' THEN '-1' ELSE IFNULL(TOUR_OPERATOR_TYPE_CD, '-1') END
    ,CASE WHEN TOUR_OPERATOR_CONTRACT_TYPE_CD = '' THEN '-1' ELSE IFNULL(TOUR_OPERATOR_CONTRACT_TYPE_CD , '-1') END
FROM lec_share.v_dim_tour_operator
UNION ALL
    SELECT '-1', '', '-1', '-1'
;