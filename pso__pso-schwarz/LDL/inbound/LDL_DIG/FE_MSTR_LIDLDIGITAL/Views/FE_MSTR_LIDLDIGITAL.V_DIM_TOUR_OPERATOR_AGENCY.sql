CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TOUR_OPERATOR_AGENCY
(
     TOUR_OPERATOR_AGENCY_CD
    ,TOUR_OPERATOR_CD
)
AS SELECT
     TOUR_OPERATOR_AGENCY_CD
    ,CASE WHEN TOUR_OPERATOR_CD = '' THEN '-1' ELSE IFNULL(TOUR_OPERATOR_CD, '-1') END
FROM lec_share.v_dim_tour_operator_agency
UNION ALL
    SELECT '-1', '-1'
;