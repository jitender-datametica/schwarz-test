CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TRAVEL_BOOKING_NUMBER
(
     BOOKING_NR  
    ,BOOKING_DT
    ,TRAVEL_START_DT
    ,TRAVEL_END_DT
    ,CANCEL_DT   
)
AS SELECT DISTINCT
     BOOKING_NR  
    ,BOOKING_DT
    ,TRAVEL_START_DT
    ,TRAVEL_END_DT
    ,CANCEL_DT
    FROM lec_share.v_fact_travel_booking
WHERE
    DWH_VALID_FG=TRUE
UNION ALL
    SELECT '-1', TO_DATE('1900-01-01'), TO_DATE('1900-01-01'), TO_DATE('1900-01-01'), TO_DATE('1900-01-01')
;
