CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TRAVEL_BOOKING_ROOM_TYPE
(
     TRAV_BOOKING_ROOM_TYPE_CD
    ,TRAV_BOOKING_ROOM_TYPE_DESCR
    ,TRAV_BOOKING_ROOM_TYPE_GROUP_CD
)
AS SELECT
     TRAV_BOOKING_ROOM_TYPE_CD
    ,TRAV_BOOKING_ROOM_TYPE_DESCR
    ,CASE WHEN TRAV_BOOKING_ROOM_TYPE_GROUP_CD = '' THEN '-1' ELSE IFNULL(TRAV_BOOKING_ROOM_TYPE_GROUP_CD, '-1') END
FROM lec_share.v_dim_travel_booking_room_type
UNION ALL
    SELECT '-1', '', '-1'
;