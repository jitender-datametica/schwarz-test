CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TRAVEL_COST_CENTER
(
     TRAV_COST_CENTER_CD
    ,TRAV_SOURCE_MARKET_CD
    ,TRAV_COST_CENTER_DESCR
)
AS SELECT
     TRAV_COST_CENTER_CD
    ,CASE WHEN TRAV_SOURCE_MARKET_CD = '' THEN '-1' ELSE IFNULL(TRAV_SOURCE_MARKET_CD, '-1') END
    ,TRAV_COST_CENTER_DESCR
FROM lec_share.v_dim_travel_cost_center
UNION ALL
    SELECT '-1', '-1', ''
;