CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_WEBSHOP
(
     WSHOP_CD
    ,WSHOP_NAME_DE
    ,WSHOP_NAME_EN
    ,WSHOP_DISPLAY_ORDER_NR
    ,COUNTRY_CD
)
AS SELECT
     WSHOP_CD
    ,WSHOP_NAME_DE
    ,WSHOP_NAME_EN
    ,WSHOP_DISPLAY_ORDER_NR
    ,CASE WHEN COUNTRY_CD = '' THEN '-1' ELSE IFNULL(COUNTRY_CD, '-1') END
FROM lec_share.v_dim_webshop
UNION ALL
    SELECT '-1', '', '', 1000, '-1'
;