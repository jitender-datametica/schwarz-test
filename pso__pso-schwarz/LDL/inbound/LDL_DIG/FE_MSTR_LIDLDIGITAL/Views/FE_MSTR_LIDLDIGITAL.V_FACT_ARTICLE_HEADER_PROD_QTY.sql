CREATE OR REPLACE  VIEW FE_MSTR_LIDLDIGITAL.V_FACT_ARTICLE_HEADER_PROD_QTY
(
PROD_VARIANT_SID
,CUST_ORDER_SID
,CUST_ORDER_DT
,WSHOP_CD 
,PROD_QTY
)
AS
SELECT
COL_FACT_2.PROD_VARIANT_SID
,IFNULL(COL_FACT.CUST_ORDER_SID , -1)
,COL_FACT.CUST_ORDER_DT
,CASE WHEN COL_FACT.WSHOP_CD = '' THEN '-1' ELSE IFNULL(COL_FACT.WSHOP_CD , '-1') END
,SUM(COL_FACT.PROD_QTY)
FROM
lec_share.v_fact_customer_order_line COL_FACT
JOIN
lec_share.v_fact_customer_order_line COL_FACT_2
ON
COL_FACT.CUST_ORDER_SID = COL_FACT_2.CUST_ORDER_SID AND COL_FACT.CUST_ORDER_POS_NR = COL_FACT_2.BUNDLE_HEADER_POS_NR
WHERE
COL_FACT.IS_BUNDLE_HEADER_FG = 1
AND COL_FACT_2.IS_BUNDLE_HEADER_FG = 0 
GROUP BY
COL_FACT_2.PROD_VARIANT_SID
,COL_FACT.CUST_ORDER_SID 
,COL_FACT.CUST_ORDER_DT  
,COL_FACT.WSHOP_CD
;