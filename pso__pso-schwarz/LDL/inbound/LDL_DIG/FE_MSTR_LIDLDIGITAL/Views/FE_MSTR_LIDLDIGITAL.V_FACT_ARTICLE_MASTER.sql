CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_ARTICLE_MASTER
/*
	Used for Artikelstamm dossier.
	MSTR does not join the 5 tables with full outer join.
	In order to not lose any data, this view is created.
*/
AS SELECT
	 COALESCE(FACT_PA.WSHOP_CD, REL_PVA.WSHOP_CD, FACT_PPC.WSHOP_CD, FACT_PPSIGV.WSHOP_CD, FACT_PPS.WSHOP_CD) AS WSHOP_CD
	,FACT_PA.CAL_DT AS CAL_DT_PRODUCT_AVAILABILITY
	,COALESCE(FACT_PA.PROD_VARIANT_SID, REL_PVA.PROD_VARIANT_SID, FACT_PPC.PROD_VARIANT_SID, FACT_PPSIGV.PROD_VARIANT_SID, FACT_PPS.PROD_VARIANT_SID) AS PROD_VARIANT_SID
	,COALESCE(FACT_PA.PROD_VARIANT_NR, REL_PVA.PROD_VARIANT_NR) AS PROD_VARIANT_NR
	,FACT_PA.IS_ORDERABLE_FG AS IS_ORDERABLE_FG
	,FACT_PA.IS_VISIBLE_FG AS IS_VISIBLE_FG
    ,IFF(FACT_PA.IS_REPLENISHMENT_CONSIDERED_FG IS NULL, NULL, IFF(FACT_PA.IS_REPLENISHMENT_CONSIDERED_FG, 'YES', 'NO'))  AS IS_REPLENISHMENT_CONSIDERED_FG
	,FACT_PA.IS_AVAIL_IN_STORE_FG AS IS_AVAIL_IN_STORE_FG
	,FACT_PA.IS_IN_STOCK_FG AS IS_IN_STOCK_FG
	,FACT_PA.AVAIL_LVL AS AVAIL_LVL
	,FACT_PA.PROD_ORDERABLE_LVL_CD AS PROD_ORDERABLE_LVL_CD
	,FACT_PA.SRC_CATALOG_NAME AS SRC_CATALOG_NAME
	,FACT_PA.IS_IN_PROMO_FG AS IS_IN_PROMO_FG
	,FACT_PA.MAX_ORDER_QTY AS MAX_ORDER_QTY
	,FACT_PA.TOTAL_STOCK_QTY AS TOTAL_STOCK_QTY
	,FACT_PA.LOCALE_NAME AS LOCALE_NAME
    ,FACT_PA.IS_LEGACY_FG AS IS_LEGACY_FG
    ,FACT_PA.IS_SOLD_OUT_FG AS IS_SOLD_OUT_FG

	,REL_PVA.REG_PROD_VARIANT_NAME AS REG_PROD_VARIANT_NAME
	,REL_PVA.REG_PROD_VARIANT_DESCR AS REG_PROD_VARIANT_DESCR
	,IFNULL(REL_PVA.PROD_SID, '-1') AS PROD_SID
	,IFNULL(REL_PVA.PROD_NR, '-1') AS PROD_NR
	,REL_PVA.REG_PROD_NAME AS REG_PROD_NAME
	,REL_PVA.PROD_TGT_DELIVERY_TIME AS PROD_TGT_DELIVERY_TIME
	,IFNULL(REL_PVA.TAX_CLASS_CD, '-1') AS TAX_CLASS_CD
	,REL_PVA.MATERIAL_POS_TYPE_CD AS MATERIAL_POS_TYPE_CD
	,REL_PVA.DELIVERY_SRC_TYPE_CD AS DELIVERY_SRC_TYPE_CD
	,IFNULL(REL_PVA.SHOP_CAT_SID, '-1') AS SHOP_CAT_SID
	,REL_PVA.SHOP_CAT_NAME AS SHOP_CAT_NAME
	,IFNULL(REL_PVA.SHOP_CAT_LVL4_SID, '-1') AS SHOP_CAT_LVL4_SID
	,REL_PVA.SHOP_CAT_LVL4_NAME AS SHOP_CAT_LVL4_NAME
	,IFNULL(REL_PVA.SHOP_CAT_LVL3_SID, '-1') AS SHOP_CAT_LVL3_SID
	,REL_PVA.SHOP_CAT_LVL3_NAME AS SHOP_CAT_LVL3_NAME
	,IFNULL(REL_PVA.SHOP_CAT_LVL2_SID, '-1') AS SHOP_CAT_LVL2_SID
	,REL_PVA.SHOP_CAT_LVL2_NAME AS SHOP_CAT_LVL2_NAME
	,IFNULL(REL_PVA.SHOP_CAT_LVL1_SID, '-1') AS SHOP_CAT_LVL1_SID
	,REL_PVA.SHOP_CAT_LVL1_NAME AS SHOP_CAT_LVL1_NAME
	,IFNULL(REL_PVA.PROD_ONLINE_STATUS_CD, '-1') AS PROD_ONLINE_STATUS_CD
	,IFNULL(REL_PVA.PROD_LISTING_STATUS_CD, '-1') AS PROD_LISTING_STATUS_CD

    ,FACT_PPC.TAX_CLASS_PCT AS TAX_CLASS_PCT
	,IFNULL(FACT_PPC.CURR_CD, '-1') AS PRODUCT_PRICING_CONDITION_CURR_CD
	,FACT_PPC.VKP_PRICE_GROSS_VAL AS VKP_PRICE_GROSS_VAL
	,FACT_PPC.VKP_PRICE_NET_VAL AS VKP_PRICE_NET_VAL -- a similar column also exists coming from FACT_PPSIGV
	,FACT_PPC.AKP_PRICE_GROSS_VAL AS AKP_PRICE_GROSS_VAL -- a similar column also exists coming from FACT_PPSIGV
	,FACT_PPC.AKP_PRICE_NET_VAL AS AKP_PRICE_NET_VAL
	,FACT_PPC.UVP_PRICE_GROSS_VAL AS UVP_PRICE_GROSS_VAL
	,FACT_PPC.STP_PRICE_GROSS_VAL AS STP_PRICE_GROSS_VAL
	,FACT_PPC.VKZ1_PRICE_GROSS_VAL AS VKZ1_PRICE_GROSS_VAL
	,FACT_PPC.VKZ2_PRICE_GROSS_VAL AS VKZ2_PRICE_GROSS_VAL
	,FACT_PPC.IVP_PRICE_GROSS_VAL AS IVP_PRICE_GROSS_VAL
	,FACT_PPC.ZVP_PRICE_GROSS_VAL AS ZVP_PRICE_GROSS_VAL

-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
	,IFNULL(FACT_PPC.VKP_CURR_CD, '-1') AS VKP_CURR_CD
	,FACT_PPC.VKP_PRICE_GROSS_LOCAL_VAL AS VKP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.VKP_PRICE_GROSS_EUR_VAL AS VKP_PRICE_GROSS_EUR_VAL
	,FACT_PPC.VKP_PRICE_NET_LOCAL_VAL AS VKP_PRICE_NET_LOCAL_VAL
	,FACT_PPC.VKP_PRICE_NET_EUR_VAL AS VKP_PRICE_NET_EUR_VAL
	,IFNULL(FACT_PPC.AKP_CURR_CD, '-1') AS AKP_CURR_CD
	,FACT_PPC.AKP_PRICE_GROSS_LOCAL_VAL AS AKP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.AKP_PRICE_GROSS_EUR_VAL AS AKP_PRICE_GROSS_EUR_VAL
	,FACT_PPC.AKP_PRICE_NET_LOCAL_VAL AS AKP_PRICE_NET_LOCAL_VAL
	,FACT_PPC.AKP_PRICE_NET_EUR_VAL AS AKP_PRICE_NET_EUR_VAL
	,IFNULL(FACT_PPC.UVP_CURR_CD, '-1') AS UVP_CURR_CD
	,FACT_PPC.UVP_PRICE_GROSS_LOCAL_VAL AS UVP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.UVP_PRICE_GROSS_EUR_VAL AS UVP_PRICE_GROSS_EUR_VAL
	,IFNULL(FACT_PPC.STP_CURR_CD, '-1') AS STP_CURR_CD
	,FACT_PPC.STP_PRICE_GROSS_LOCAL_VAL AS STP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.STP_PRICE_GROSS_EUR_VAL AS STP_PRICE_GROSS_EUR_VAL
	,IFNULL(FACT_PPC.VKZ1_CURR_CD, '-1') AS VKZ1_CURR_CD
	,FACT_PPC.VKZ1_PRICE_GROSS_LOCAL_VAL AS VKZ1_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.VKZ1_PRICE_GROSS_EUR_VAL AS VKZ1_PRICE_GROSS_EUR_VAL
	,IFNULL(FACT_PPC.VKZ2_CURR_CD, '-1') AS VKZ2_CURR_CD
	,FACT_PPC.VKZ2_PRICE_GROSS_LOCAL_VAL AS VKZ2_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.VKZ2_PRICE_GROSS_EUR_VAL AS VKZ2_PRICE_GROSS_EUR_VAL
	,IFNULL(FACT_PPC.IVP_CURR_CD, '-1') AS IVP_GROSS_CURR_CD
	,FACT_PPC.IVP_PRICE_GROSS_LOCAL_VAL AS IVP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.IVP_PRICE_GROSS_EUR_VAL AS IVP_PRICE_GROSS_EUR_VAL
	,IFNULL(FACT_PPC.ZVP_CURR_CD, '-1') AS ZVP_CURR_CD
	,FACT_PPC.ZVP_PRICE_GROSS_LOCAL_VAL AS ZVP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPC.ZVP_PRICE_GROSS_EUR_VAL AS ZVP_PRICE_GROSS_EUR_VAL
-- end section

	,FACT_PPSIGV.CAL_DT AS CAL_DT_PRODUCT_PRICE_SALE_IVP_GLD_VKP
	,IFNULL(FACT_PPSIGV.CURR_CD, '-1') AS GLD_CURR_CD
	,FACT_PPSIGV.GLD_PRICE_NET_VAL AS GLD_PRICE_NET_VAL
	,IFNULL(FACT_PPSIGV.CURR_CD, '-1') AS IVP_NET_CURR_CD
	,FACT_PPSIGV.IVP_PRICE_NET_VAL AS IVP_PRICE_NET_VAL
	,IFNULL(FACT_PPSIGV.CURR_CD, '-1') AS LAST_VKP_CURR_CD
	,FACT_PPSIGV.VKP_PRICE_NET_VAL AS LAST_VKP_PRICE_NET_VAL
	,FACT_PPSIGV.VKP_PRICE_GROSS_VAL AS LAST_VKP_PRICE_GROSS_VAL

	,IFNULL(FACT_PPS.SUPPLIER_SID, '-1') AS SUPPLIER_SID
	,IFF(COALESCE(FACT_PPC.GC_LC_CD, FACT_PPSIGV.GC_LC_CD, FACT_PPS.GC_LC_CD) = 'GC', FACT_PPS.EKP_PRICE_VAL, NULL) AS EKP_PRICE_VAL -- data for this column is only available for GC. because FACT_PPS contains additional columns that we always want to see (SUPPLIER_SID), we cannot filter in the join, so we do it here (NBI-5555)
	,IFF(COALESCE(FACT_PPC.GC_LC_CD, FACT_PPSIGV.GC_LC_CD, FACT_PPS.GC_LC_CD) = 'GC', FACT_PPS.FKZ_PRICE_VAL, NULL) AS FKZ_PRICE_VAL -- data for this column is only available for GC. because FACT_PPS contains additional columns that we always want to see (SUPPLIER_SID), we cannot filter in the join, so we do it here (NBI-5555)
	
-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
	,FACT_PPS.EKP_PRICE_EUR_VAL AS EKP_PRICE_EUR_VAL
	,FACT_PPS.FKZ_PRICE_EUR_VAL AS FKZ_PRICE_EUR_VAL
-- end section
	
	,COALESCE(FACT_PPC.GC_LC_CD, FACT_PPSIGV.GC_LC_CD, FACT_PPS.GC_LC_CD,'GC') AS GC_LC_CD

-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
	,FACT_PPSIGV.GLD_PRICE_NET_EUR_VAL AS GLD_PRICE_NET_EUR_VAL
	,FACT_PPSIGV.GLD_PRICE_NET_LOCAL_VAL AS GLD_PRICE_NET_LOCAL_VAL
	,FACT_PPSIGV.IVP_PRICE_NET_EUR_VAL AS IVP_PRICE_NET_EUR_VAL
	,FACT_PPSIGV.IVP_PRICE_NET_LOCAL_VAL AS IVP_PRICE_NET_LOCAL_VAL
	,FACT_PPSIGV.VKP_PRICE_NET_LOCAL_VAL AS LAST_VKP_PRICE_NET_LOCAL_VAL
	,FACT_PPSIGV.VKP_PRICE_NET_EUR_VAL AS LAST_VKP_PRICE_NET_EUR_VAL
	,FACT_PPSIGV.VKP_PRICE_GROSS_LOCAL_VAL AS LAST_VKP_PRICE_GROSS_LOCAL_VAL
	,FACT_PPSIGV.VKP_PRICE_GROSS_EUR_VAL AS LAST_VKP_PRICE_GROSS_EUR_VAL
-- end section

FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_AVAILABILITY_ACTIVE FACT_PA
FULL OUTER JOIN
    FE_MSTR_LIDLDIGITAL.V_REL_PRODUCT_VARIANT_REGIONAL REL_PVA
    ON
        REL_PVA.PROD_VARIANT_SID = FACT_PA.PROD_VARIANT_SID
        AND REL_PVA.WSHOP_CD = FACT_PA.WSHOP_CD
FULL OUTER JOIN
    FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICING_CONDITION FACT_PPC
    ON 
        FACT_PPC.PROD_VARIANT_SID = COALESCE(FACT_PA.PROD_VARIANT_SID, REL_PVA.PROD_VARIANT_SID)
        AND FACT_PPC.WSHOP_CD = COALESCE(FACT_PA.WSHOP_CD, REL_PVA.WSHOP_CD)
FULL OUTER JOIN
	FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_SALE_IVP_GLD_VKP FACT_PPSIGV
    ON 
        FACT_PPSIGV.PROD_VARIANT_SID = COALESCE(FACT_PA.PROD_VARIANT_SID, REL_PVA.PROD_VARIANT_SID, FACT_PPC.PROD_VARIANT_SID)
        AND FACT_PPSIGV.WSHOP_CD = COALESCE(FACT_PA.WSHOP_CD, REL_PVA.WSHOP_CD, FACT_PPC.WSHOP_CD)
		AND FACT_PPSIGV.GC_LC_CD = FACT_PPC.GC_LC_CD
FULL OUTER JOIN
	FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_SUPPLIER FACT_PPS
	ON
        FACT_PPS.PROD_VARIANT_SID = COALESCE(FACT_PA.PROD_VARIANT_SID, REL_PVA.PROD_VARIANT_SID, FACT_PPC.PROD_VARIANT_SID, FACT_PPSIGV.PROD_VARIANT_SID)
        AND FACT_PPS.WSHOP_CD = COALESCE(FACT_PA.WSHOP_CD, REL_PVA.WSHOP_CD, FACT_PPC.WSHOP_CD, FACT_PPSIGV.WSHOP_CD)
	--	AND FACT_PPS.GC_LC_CD = COALESCE(FACT_PPC.GC_LC_CD, FACT_PPSIGV.GC_LC_CD) -- FACT_PPS contains data that we always want to see (SUPPLIER_SID) and prices we only want to see if GC_LC_CD = 'GC'. To achieve this, we filter the prices above. (NBI-5555)
;