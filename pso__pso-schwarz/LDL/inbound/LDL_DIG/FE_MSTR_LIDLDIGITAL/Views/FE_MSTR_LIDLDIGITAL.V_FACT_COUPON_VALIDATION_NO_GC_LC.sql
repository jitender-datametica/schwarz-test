CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_COUPON_VALIDATION_NO_GC_LC
AS 
WITH COL_GROUPED AS(
    SELECT 
        MAX( cust_order_dt )      AS cust_order_dt
        , cust_order_sid
        , prod_variant_sid
    FROM lec_share.v_fact_customer_order_line  
    GROUP BY 
        CUST_ORDER_SID
        , PROD_VARIANT_SID
)
SELECT
     FACT_CP.COUPON_VALIDATION_NR AS COUPON_VALIDATION_NR
    ,IFNULL(FACT_CP.CUST_ORDER_SID, '-1') AS CUST_ORDER_SID
    ,IFNULL(FACT_CP.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,IFNULL(FACT_CP.COUPON_ID, '-1') AS COUPON_ID
    ,CASE WHEN FACT_CP.COUPON_CD = '' THEN '-1' ELSE IFNULL(FACT_CP.COUPON_CD, '-1') END AS COUPON_CD
    ,CASE WHEN FACT_CP.COUPON_PROMO_CD = '' THEN '-1' ELSE IFNULL(FACT_CP.COUPON_PROMO_CD, '-1') END AS COUPON_PROMO_CD
    ,CASE WHEN FACT_CP.PROFIT_LOSS_REASON_CD = '' THEN '-1' ELSE IFNULL(FACT_CP.PROFIT_LOSS_REASON_CD, '-1') END AS PROFIT_LOSS_REASON_CD
    ,CASE WHEN FACT_CP.CURR_CD = '' THEN '-1' ELSE IFNULL(FACT_CP.CURR_CD, '-1') END AS CURR_CD
    ,CASE WHEN FACT_CP.WSHOP_CD = '' THEN '-1' ELSE IFNULL(FACT_CP.WSHOP_CD, '-1') END AS WSHOP_CD
    ,FACT_CP.PROD_QTY AS PROD_QTY
    ,CONVERT_TIMEZONE('Europe/Berlin', FACT_CP.COUPON_VALIDATION_TMSP)::TIMESTAMP_NTZ AS COUPON_VALIDATION_TMSP
    ,FACT_CP.COUPON_SHIP_GROSS_LOCAL_VAL AS COUPON_SHIP_GROSS_LOCAL_VAL
    ,FACT_CP.COUPON_SHIP_GROSS_LOCAL_VAL / FACT_CER.EXCHANGE_RATE AS COUPON_SHIP_GROSS_EUR_VAL
    ,FACT_CP.COUPON_ITEM_GROSS_LOCAL_VAL AS COUPON_ITEM_GROSS_LOCAL_VAL
    ,FACT_CP.COUPON_ITEM_GROSS_LOCAL_VAL / FACT_CER.EXCHANGE_RATE AS COUPON_ITEM_GROSS_EUR_VAL
    ,FACT_CP.COUPON_POS_GROSS_LOCAL_VAL AS COUPON_POS_GROSS_LOCAL_VAL
    ,FACT_CP.COUPON_POS_GROSS_LOCAL_VAL / FACT_CER.EXCHANGE_RATE AS COUPON_POS_GROSS_EUR_VAL
FROM
    lec_share.v_fact_coupon_validation FACT_CP
INNER JOIN
    COL_GROUPED  FACT_COL
    ON
        FACT_CP.CUST_ORDER_SID = FACT_COL.CUST_ORDER_SID
        AND FACT_CP.PROD_VARIANT_SID = FACT_COL.PROD_VARIANT_SID
INNER JOIN 
    lec_share.v_fact_currency_exchange_rate FACT_CER
    ON 
        FACT_CP.CURR_CD = FACT_CER.FROM_CURR_CD
        AND FACT_COL.CUST_ORDER_DT BETWEEN FACT_CER.ACTIVE_FROM_DT AND FACT_CER.ACTIVE_TO_DT 
        AND FACT_CER.TO_CURR_CD = 'EUR'
INNER JOIN
    lec_share.v_dim_currency_exchange_rate_type DIM_CERT
    ON
        DIM_CERT.CURR_EXCHANGE_RATE_TYPE_CD = FACT_CER.CURR_EXCHANGE_RATE_TYPE_CD
        AND DIM_CERT.IS_GENERAL_USED_FG
;
