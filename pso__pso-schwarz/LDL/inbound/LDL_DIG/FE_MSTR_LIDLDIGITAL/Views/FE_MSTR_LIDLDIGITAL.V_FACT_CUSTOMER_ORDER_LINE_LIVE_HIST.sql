CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_ORDER_LINE_LIVE_HIST
(
WSHOP_CD
,CUST_ORDER_NR
,CUST_ORDER_CREATE_DT
,CUST_ORDER_CREATE_TM
,CUST_ORDER_DT
,PROD_VARIANT_SID
,PROD_QTY
,PROD_PRICE_NET_LOCAL_VAL
,PROD_PRICE_NET_EUR_VAL
,IS_BUNDLE_HEADER_FG
,IS_PART_OF_BUNDLE_HEADER_CNT_FG
,IS_PART_OF_BUNDLE_POS_CNT_FG
,VERSION_DT
)
AS
SELECT
    CUST_ORD.WSHOP_CD AS WSHOP_CD
	,CUST_ORD.CUST_ORDER_NR AS CUST_ORDER_NR
	,DATE(CUST_ORD.CUST_ORDER_CREATE_TMSP) AS CUST_ORDER_CREATE_DT
	,CUST_ORD.CUST_ORDER_CREATE_TMSP ::TIME(6) AS CUST_ORDER_CREATE_TM
	,CUST_ORD.CUST_ORDER_DT AS CUST_ORDER_DT
	,IFNULL(PROD_VAR_REG.PROD_VARIANT_SID, -1) AS PROD_VARIANT_SID
	,CUST_ORD.PROD_QTY AS PROD_QTY
	,CUST_ORD.PROD_PRICE_NET_LOCAL_VAL AS PROD_PRICE_NET_LOCAL_VAL
	,SUM(CUST_ORD.PROD_PRICE_NET_LOCAL_VAL / EX.EXCHANGE_RATE) AS PROD_PRICE_NET_EUR_VAL
	,CUST_ORD.IS_BUNDLE_HEADER_FG AS IS_BUNDLE_HEADER_FG
	,CUST_ORD.IS_PART_OF_BUNDLE_HEADER_CNT_FG AS IS_PART_OF_BUNDLE_HEADER_CNT_FG
	,CUST_ORD.IS_PART_OF_BUNDLE_POS_CNT_FG AS IS_PART_OF_BUNDLE_POS_CNT_FG
    ,CUST_ORD.CUST_ORDER_DT AS VERSION_DT
FROM lec_share.v_fact_customer_order_line AS CUST_ORD
    LEFT JOIN lec_share.v_rel_product_variant_regional AS PROD_VAR_REG
        ON (CUST_ORD.PROD_VARIANT_SID = PROD_VAR_REG.PROD_VARIANT_SID
        AND CUST_ORD.WSHOP_CD = PROD_VAR_REG.WSHOP_CD)
        AND PROD_VAR_REG.DWH_VALID_FG
    LEFT JOIN lec_share.v_fact_currency_exchange_rate AS EX       
        ON CUST_ORD.CUST_ORDER_DT BETWEEN EX.ACTIVE_FROM_DT AND EX.ACTIVE_TO_DT 
        AND CUST_ORD.CURR_CD = EX.FROM_CURR_CD 
        AND EX.TO_CURR_CD = 'EUR'
        AND EX.CURR_EXCHANGE_RATE_TYPE_CD = 'F'
WHERE IS_PART_OF_BUNDLE_HEADER_CNT_FG
GROUP BY ALL
;