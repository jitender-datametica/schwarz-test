CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_ORDER_LINE_LIVE_MASTER(
	WSHOP_CD
    ,CUST_ORDER_NR
    ,CUST_ORDER_CREATE_HOUR
	,PROD_VARIANT_SID
    ,VERSION_DT
    ,LT_RELATIVE_DT
    ,PROD_PRICE_NET_EUR_VAL_TODAY
	,PROD_PRICE_NET_EUR_VAL_AVG_BY
	,PROD_PRICE_NET_EUR_VAL_SDWLY
    ,PROD_QTY_TODAY
) AS
SELECT
    WSHOP_CD
    ,CUST_ORDER_NR
    ,CUST_ORDER_CREATE_HOUR
    ,PROD_VARIANT_SID
    ,VERSION_DT
    ,LT_RELATIVE_DT
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'TODAY' THEN PROD_PRICE_NET_EUR_VAL ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_TODAY
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'BY' THEN PROD_PRICE_NET_EUR_VAL/COUNT_BY_DAYS ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_AVG_BY
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'SDWLY' THEN PROD_PRICE_NET_EUR_VAL ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_SDWLY
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'TODAY' THEN PROD_QTY ELSE NULL END) AS PROD_QTY_TODAY
FROM
    (SELECT
        WSHOP_CD
        ,CUST_ORDER_NR
        ,HOUR(CUST_ORDER_CREATE_TM) AS CUST_ORDER_CREATE_HOUR
        ,PROD_VARIANT_SID
        ,CUST_ORDER_DT
        ,VERSION_DT
        ,CASE
            WHEN CUST_ORDER_DT = VERSION_DT THEN 'TODAY'                          -- Today
            WHEN CUST_ORDER_DT = DATEADD(DAY, - 1, VERSION_DT) THEN 'BY'          -- Business year to date excluding today                
            ELSE 'SDWLY' END AS LT_RELATIVE_DT                                    -- Same day of the week last year
        ,PROD_PRICE_NET_EUR_VAL
        ,PROD_QTY
        ,(SELECT COUNT(DISTINCT INCL_CAL_DT) - 1 FROM FE_MSTR_LIDLDIGITAL.V_CAL_CUM_BUSINESS_YEAR_TO_DATE WHERE CAL_DT = VERSION_DT) AS COUNT_BY_DAYS        -- Support column to calculate Average sales for the Business year to date
    FROM FE_MSTR_LIDLDIGITAL.T_FACT_CUSTOMER_ORDER_LINE_LIVE
    WHERE IS_PART_OF_BUNDLE_HEADER_CNT_FG = 'TRUE' 
    )
GROUP BY
     WSHOP_CD
    ,CUST_ORDER_NR
    ,CUST_ORDER_CREATE_HOUR
    ,PROD_VARIANT_SID
    ,VERSION_DT
    ,LT_RELATIVE_DT    
;