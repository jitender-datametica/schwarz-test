CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_ORDER_LINE_RETURN_NO_GC_LC
/*
    Table T_FACT_CUSTOMER_ORDER_LINE_RETURN has been replaced with T_FACT_CUSTOMER_RETURN_LINE.
    This view currently still uses the old name and the old column names so that no changes in MSTR need to be made.
*/
AS
SELECT 
     COLR_FACT.WSHOP_CD AS WSHOP_CD
    ,IFNULL(COLR_FACT.CUST_ORDER_RETURN_SID , -1) AS CUST_ORDER_RETURN_SID
    ,COLR_FACT.CUST_ORDER_RETURN_NR AS CUST_ORDER_RETURN_NR
    ,COLR_FACT.CUST_ORDER_RETURN_POS_NR AS CUST_ORDER_RETURN_POS_NR
    ,IFNULL(COLR_FACT.CUST_ORDER_SID , -1) AS CUST_ORDER_SID
    ,COLR_FACT.CUST_ORDER_NR AS CUST_ORDER_NR
    ,COLR_FACT.CUST_ORDER_POS_NR AS CUST_ORDER_POS_NR
    ,CONVERT_TIMEZONE('Europe/Berlin', COLR_FACT.CUST_ORDER_RETURN_CREATE_TMSP)::TIMESTAMP_NTZ AS CUST_ORDER_RETURN_CREATE_TMSP
    ,CONVERT_TIMEZONE('Europe/Berlin', COLR_FACT.CUST_ORDER_CREATE_TMSP)::TIMESTAMP_NTZ AS CUST_ORDER_CREATE_TMSP
    ,TO_TIME(COLR_FACT.CUST_ORDER_RETURN_CREATE_TMSP) AS CUST_ORDER_RETURN_TM
    ,TO_TIME(COLR_FACT.CUST_ORDER_RETURN_CREATE_TMSP) AS CUST_ORDER_RETURN_CREATE_TIME
    ,TO_DATE(COLR_FACT.CUST_ORDER_RETURN_CREATE_TMSP) AS CUST_ORDER_RETURN_CREATE_DATE
    ,IFNULL(COLR_FACT.PROD_VARIANT_SID , -1) AS PROD_VARIANT_SID
    ,COLR_FACT.CUST_ORDER_DT AS CUST_ORDER_DT
    ,COLR_FACT.CUST_ORDER_RETURN_DT AS CUST_ORDER_RETURN_DT
    ,IFNULL(COLR_FACT.CUST_SID , -1) AS CUST_SID
    ,COLR_FACT.PROD_QTY AS RETURN_PROD_QTY
    ,CASE WHEN COLR_FACT.CURR_CD = '' THEN '-1' ELSE IFNULL(COLR_FACT.CURR_CD , '-1') END AS CURR_CD
    ,CASE WHEN CER_FACT.TO_CURR_CD = '' THEN '-1' ELSE IFNULL(CER_FACT.TO_CURR_CD , '-1') END AS TO_CURR_CD
    ,CER_FACT.EXCHANGE_RATE AS EXCHANGE_RATE
    ,CASE WHEN CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD = '' THEN '-1' ELSE IFNULL(CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD , '-1') END AS CURR_EXCHANGE_RATE_TYPE_CD
    ,CER_FACT.ACTIVE_FROM_DT AS ACTIVE_FROM_DT
    ,CER_FACT.ACTIVE_TO_DT AS ACTIVE_TO_DT
    ,CER_FACT.ACTIVE_FG AS ACTIVE_FG
    ,COLR_FACT.PROD_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_PRICE_NET_EUR_VAL
    ,COLR_FACT.PROD_PRICE_NET_LOCAL_VAL AS PROD_PRICE_NET_LOCAL_VAL
    ,COLR_FACT.PROD_PRICE_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_PRICE_GROSS_EUR_VAL
    ,COLR_FACT.PROD_PRICE_GROSS_LOCAL_VAL AS PROD_PRICE_GROSS_LOCAL_VAL
    ,COLR_FACT.PROD_PRICE_VAT_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_PRICE_VAT_EUR_VAL
    ,COLR_FACT.PROD_PRICE_VAT_LOCAL_VAL AS PROD_PRICE_VAT_LOCAL_VAL
    ,COLR_FACT.PROD_COUPON_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_COUPON_NET_EUR_VAL
    ,COLR_FACT.PROD_COUPON_NET_LOCAL_VAL AS PROD_COUPON_NET_LOCAL_VAL
    ,COLR_FACT.PROD_COUPON_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_COUPON_GROSS_EUR_VAL
    ,COLR_FACT.PROD_COUPON_GROSS_LOCAL_VAL AS PROD_COUPON_GROSS_LOCAL_VAL
    ,COLR_FACT.PROD_COUPON_VAT_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_COUPON_VAT_EUR_VAL
    ,COLR_FACT.PROD_COUPON_VAT_LOCAL_VAL AS PROD_COUPON_VAT_LOCAL_VAL
    ,COLR_FACT.DELIVERY_COST_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_COST_NET_EUR_VAL
    ,COLR_FACT.DELIVERY_COST_NET_LOCAL_VAL AS DELIVERY_COST_NET_LOCAL_VAL
    ,COLR_FACT.DELIVERY_COST_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_COST_GROSS_EUR_VAL
    ,COLR_FACT.DELIVERY_COST_GROSS_LOCAL_VAL AS DELIVERY_COST_GROSS_LOCAL_VAL
    ,COLR_FACT.DELIVERY_COST_VAT_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_COST_VAT_EUR_VAL
    ,COLR_FACT.DELIVERY_COST_VAT_LOCAL_VAL AS DELIVERY_COST_VAT_LOCAL_VAL
    ,COLR_FACT.DELIVERY_COUPON_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_COUPON_NET_EUR_VAL
    ,COLR_FACT.DELIVERY_COUPON_NET_LOCAL_VAL AS DELIVERY_COUPON_NET_LOCAL_VAL
    ,COLR_FACT.DELIVERY_COUPON_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_COUPON_GROSS_EUR_VAL
    ,COLR_FACT.DELIVERY_COUPON_GROSS_LOCAL_VAL AS DELIVERY_COUPON_GROSS_LOCAL_VAL
    ,COLR_FACT.DELIVERY_COUPON_VAT_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_COUPON_VAT_EUR_VAL
    ,COLR_FACT.DELIVERY_COUPON_VAT_LOCAL_VAL AS DELIVERY_COUPON_VAT_LOCAL_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_PAUSHAL_NET_EUR_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_NET_LOCAL_VAL AS DELIVERY_PAUSHAL_NET_LOCAL_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_PAUSHAL_GROSS_EUR_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_GROSS_LOCAL_VAL AS DELIVERY_PAUSHAL_GROSS_LOCAL_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_VAT_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_PAUSHAL_VAT_EUR_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_VAT_LOCAL_VAL AS DELIVERY_PAUSHAL_VAT_LOCAL_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_COUPON_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_PAUSHAL_COUPON_NET_EUR_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_COUPON_NET_LOCAL_VAL AS DELIVERY_PAUSHAL_COUPON_NET_LOCAL_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_PAUSHAL_COUPON_GROSS_EUR_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL AS DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_COUPON_VAT_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_DELIVERY_PAUSHAL_COUPON_VAT_EUR_VAL
    ,COLR_FACT.DELIVERY_PAUSHAL_COUPON_VAT_LOCAL_VAL AS DELIVERY_PAUSHAL_COUPON_VAT_LOCAL_VAL
    ,COLR_FACT.IVP_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS IVP_PRICE_NET_EUR_VAL
    ,COLR_FACT.IVP_PRICE_NET_LOCAL_VAL AS IVP_PRICE_NET_LOCAL_VAL
    ,COLR_FACT.GLD_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS GLD_PRICE_NET_EUR_VAL
    ,COLR_FACT.GLD_PRICE_NET_LOCAL_VAL AS GLD_PRICE_NET_LOCAL_VAL
    ,COLR_FACT.IVP_ORIGINAL_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS IVP_ORIGINAL_PRICE_NET_EUR_VAL
    ,COLR_FACT.IVP_ORIGINAL_PRICE_NET_LOCAL_VAL AS IVP_ORIGINAL_PRICE_NET_LOCAL_VAL
    ,COLR_FACT.DROPSHIPMENT_ORDER_FG AS DROPSHIPMENT_ORDER_FG
    ,CASE WHEN COLR_FACT.CUST_ORDER_TYPE_CD = '' THEN '-1' ELSE IFNULL(COLR_FACT.CUST_ORDER_TYPE_CD , '-1') END AS CUST_ORDER_TYPE_CD
    ,NULL::VARCHAR(5) AS SALES_CHANNEL_TYPE_CD -- TODO: check if this column can be removed from the view
    ,CASE WHEN COLR_FACT.CUST_PAYM_METHOD_CD = '' THEN '-1' ELSE IFNULL(COLR_FACT.CUST_PAYM_METHOD_CD , '-1') END AS CUST_PAYM_METHOD_CD
    ,IFNULL(COLR_FACT.DELIVERY_ADDR_SID , -1) AS DELIVERY_ADDR_SID
    ,IFNULL(COLR_FACT.BILLING_ADDR_SID , -1) AS BILLING_ADDR_SID
    ,CASE WHEN COLR_FACT.PROD_RETURN_REASON_CD = '' THEN '-1' ELSE IFNULL(COLR_FACT.PROD_RETURN_REASON_CD , '-1') END AS PROD_RETURN_REASON_CD
    ,IFNULL(COLR_FACT.PROD_SID , -1) AS PROD_SID
    ,CASE WHEN COLR_FACT.ORDER_RETURN_REASON_CD = '' THEN '-1' ELSE IFNULL(COLR_FACT.ORDER_RETURN_REASON_CD , '-1') END AS ORDER_RETURN_REASON_CD

    ,COL_FACT.WH_SID AS WH_SID
    ,COLR_FACT.RETURN_WH_SID
    ,colr_fact.add_services_net_local_val / cer_fact.exchange_rate 						    AS add_services_net_eur_val
	,colr_fact.add_services_net_local_val 													AS add_services_net_local_val
	,colr_fact.add_services_gross_local_val / cer_fact.exchange_rate 						AS add_services_gross_eur_val
	,colr_fact.add_services_gross_local_val 												AS add_services_gross_local_val
	,colr_fact.add_services_vat_local_val / cer_fact.exchange_rate 						    AS add_services_vat_eur_val
	,colr_fact.add_services_vat_local_val 													AS add_services_vat_local_val
    ,colr_fact.dist_channel_cd																	AS dist_channel_cd
	,colr_fact.dist_country_cd																	AS dist_country_cd
	,colr_fact.dist_channel_type_cd 																AS dist_channel_type_cd
FROM
    lec_share.v_fact_customer_return_line COLR_FACT
LEFT JOIN lec_share.v_fact_customer_order_line COL_FACT
    ON COL_FACT.CUST_ORDER_SID = COLR_FACT.CUST_ORDER_SID
        AND COL_FACT.CUST_ORDER_POS_NR = COLR_FACT.CUST_ORDER_POS_NR
INNER JOIN
    lec_share.v_fact_currency_exchange_rate CER_FACT
    ON
        COLR_FACT.CURR_CD = CER_FACT.FROM_CURR_CD
        AND COLR_FACT.CUST_ORDER_DT BETWEEN CER_FACT.ACTIVE_FROM_DT AND CER_FACT.ACTIVE_TO_DT 
		AND CER_FACT.TO_CURR_CD = 'EUR'
INNER JOIN
    lec_share.v_dim_currency_exchange_rate_type CERT_DIM
    ON
        CERT_DIM.CURR_EXCHANGE_RATE_TYPE_CD = CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD
        AND CERT_DIM.IS_GENERAL_USED_FG

/* WHERE CONDITION */

INNER JOIN
    lec_share.v_dim_cal_day CAL_DIM
    ON CAL_DIM.CAL_DT = COLR_FACT.CUST_ORDER_RETURN_DT
    AND CAL_DIM.BUS_YEAR >= 2020
;
