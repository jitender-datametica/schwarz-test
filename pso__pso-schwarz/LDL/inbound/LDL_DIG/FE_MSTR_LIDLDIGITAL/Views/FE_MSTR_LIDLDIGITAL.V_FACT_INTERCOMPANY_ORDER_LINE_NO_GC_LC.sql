CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_INTERCOMPANY_ORDER_LINE_NO_GC_LC(
	DIST_CHANNEL_CD
    ,DIST_COUNTRY_CD
    ,IC_ORDER_SID
    ,IC_ORDER_CREATE_TMSP
    ,IC_ORDER_DT
    ,IC_ORDER_TM
    ,IC_ORDER_CREATE_TIME
    ,IC_ORDER_CREATE_DATE
    ,PROD_VARIANT_SID
    ,PROD_SID
    ,CUST_SID
    ,IC_ORDER_NR
    ,IC_ORDER_POS_NR
    ,PROD_QTY
    ,DELIVERY_ADDR_SID
    ,CURR_CD
    ,EXCHANGE_RATE
    ,CURR_EXCHANGE_RATE_TYPE_CD
    ,CURR_EXCHANGE_RATE_ACTIVE_FROM_DT
    ,CURR_EXCHANGE_RATE_ACTIVE_TO_DT
    ,CURR_EXCHANGE_RATE_ACTIVE_FG
    ,IVP_PRICE_NET_EUR_VAL
    ,IVP_PRICE_NET_LOCAL_VAL
    ,COGS_PRICE_NET_EUR_VAL
    ,COGS_PRICE_NET_LOCAL_VAL
    ,IS_ORDER_CANCEL_FG
    ,CUST_ORDER_PERFORM_DT
    ,CUST_DELIVERY_TGT_DT
    ,WH_SID
    ,WH_CD
    ,PROD_VARIANT_NR
    ,PROD_NR
) AS 
SELECT 
     ICOL_FACT.DIST_CHANNEL_CD AS DIST_CHANNEL_CD
    ,ICOL_FACT.DIST_COUNTRY_CD AS DIST_COUNTRY_CD
    ,IFNULL(ICOL_FACT.IC_ORDER_SID , -1) AS IC_ORDER_SID
    ,CONVERT_TIMEZONE('Europe/Berlin', ICOL_FACT.IC_ORDER_CREATE_TMSP)::TIMESTAMP_NTZ AS IC_ORDER_CREATE_TMSP
    ,ICOL_FACT.IC_ORDER_DT AS IC_ORDER_DT
    ,TO_TIME(ICOL_FACT.IC_ORDER_CREATE_TMSP) AS IC_ORDER_TM
    ,TO_TIME(ICOL_FACT.IC_ORDER_CREATE_TMSP) AS IC_ORDER_CREATE_TIME
    ,TO_DATE(ICOL_FACT.IC_ORDER_CREATE_TMSP) AS IC_ORDER_CREATE_DATE
    ,IFNULL(ICOL_FACT.PROD_VARIANT_SID , -1) AS PROD_VARIANT_SID
    ,IFNULL(ICOL_FACT.PROD_SID , -1) AS PROD_SID
    ,IFNULL(ICOL_FACT.CUST_SID , -1) AS CUST_SID
    ,ICOL_FACT.IC_ORDER_NR AS IC_ORDER_NR
    ,ICOL_FACT.IC_ORDER_POS_NR AS IC_ORDER_POS_NR
    ,ICOL_FACT.PROD_QTY AS PROD_QTY
    ,IFNULL(ICOL_FACT.DELIVERY_ADDR_SID , -1) AS DELIVERY_ADDR_SID
    ,CASE WHEN ICOL_FACT.CURR_CD  = '' THEN '-1' ELSE IFNULL(ICOL_FACT.CURR_CD  , '-1') END AS CURR_CD
    ,CER_FACT.EXCHANGE_RATE AS EXCHANGE_RATE
    ,CASE WHEN CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD = '' THEN '-1' ELSE IFNULL(CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD , '-1') END AS CURR_EXCHANGE_RATE_TYPE_CD
    ,CER_FACT.ACTIVE_FROM_DT AS CURR_EXCHANGE_RATE_ACTIVE_FROM_DT
    ,CER_FACT.ACTIVE_TO_DT AS CURR_EXCHANGE_RATE_ACTIVE_TO_DT
    ,CER_FACT.ACTIVE_FG AS CURR_EXCHANGE_RATE_ACTIVE_FG
    ,ICOL_FACT.IVP_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS IVP_PRICE_NET_EUR_VAL
    ,ICOL_FACT.IVP_PRICE_NET_LOCAL_VAL AS IVP_PRICE_NET_LOCAL_VAL
    ,ICOL_FACT.COGS_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS COGS_PRICE_NET_EUR_VAL
    ,ICOL_FACT.COGS_PRICE_NET_LOCAL_VAL AS COGS_PRICE_NET_LOCAL_VAL
    ,ICOL_FACT.IS_ORDER_CANCEL_FG AS IS_ORDER_CANCEL_FG
    ,ICOL_FACT.CUST_ORDER_PERFORM_DT AS CUST_ORDER_PERFORM_DT
    ,ICOL_FACT.CUST_DELIVERY_TGT_DT AS CUST_DELIVERY_TGT_DT
    ,IFNULL(ICOL_FACT.WH_SID , -1) AS WH_SID
    ,CASE WHEN ICOL_FACT.WH_CD = '' THEN '-1' ELSE IFNULL(ICOL_FACT.WH_CD , '-1') END AS WH_CD
    ,ICOL_FACT.PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,ICOL_FACT.PROD_NR AS PROD_NR
FROM
    lec_share.v_fact_intercompany_order_line ICOL_FACT                                                                        --PARKSIDE
INNER JOIN
    lec_share.v_fact_currency_exchange_rate CER_FACT
    ON
        ICOL_FACT.CURR_CD = CER_FACT.FROM_CURR_CD                                                                        --PARKSIDE
    AND ICOL_FACT.IC_ORDER_DT BETWEEN CER_FACT.ACTIVE_FROM_DT AND CER_FACT.ACTIVE_TO_DT
    AND CER_FACT.TO_CURR_CD = 'EUR'
INNER JOIN
    lec_share.v_dim_currency_exchange_rate_type CERT
    ON
        CERT.CURR_EXCHANGE_RATE_TYPE_CD = CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD
    AND CERT.IS_GENERAL_USED_FG
INNER JOIN
    lec_share.v_dim_cal_day CAL_DIM
    ON CAL_DIM.CAL_DT = ICOL_FACT.IC_ORDER_DT                                                                            --PARKSIDE
WHERE
    CAL_DIM.BUS_YEAR_OFFSET IN ( '0' , '-1' , '-2' )
;