CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_SALE_IVP_GLD_VKP_NO_GC_LC
/*
    This view is referenced in V_FACT_ARTICLE_MASTER.
*/
AS 
SELECT
     WSHOP_CD AS WSHOP_CD
    ,CAL_DT AS CAL_DT
    ,IFNULL(PROD_VARIANT_SID , -1) AS PROD_VARIANT_SID
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD , '-1') END AS CURR_CD
    ,GLD_PRICE_NET_EUR_VAL
    ,GLD_PRICE_NET_LOCAL_VAL
    ,IVP_PRICE_NET_EUR_VAL
    ,IVP_PRICE_NET_LOCAL_VAL
    ,VKP_PRICE_NET_EUR_VAL
    ,VKP_PRICE_NET_LOCAL_VAL
    ,VKP_PRICE_GROSS_EUR_VAL
    ,VKP_PRICE_GROSS_LOCAL_VAL
    ,FIRST_VALID_PRICE_FG
FROM
    lec_share.v_fact_product_price_sale_ivp_gld_vkp
WHERE
    DWH_VALID_FG = 'TRUE'
;