CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_STOCK_AGE
AS SELECT
     CAL_DT AS CAL_DT
    ,PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,ACTIVE_FG AS ACTIVE_FG
    ,CASE WHEN PROD_STOCK_AGE_CLUSTER_CD = '' THEN '-1' ELSE IFNULL(PROD_STOCK_AGE_CLUSTER_CD, '-1') END AS PROD_STOCK_AGE_CLUSTER_CD
    ,REF_BOOKING_DT AS REF_BOOKING_DT
    ,FIRST_INBOUND_DT AS FIRST_INBOUND_DT
    ,DELTA_DAY_CNT AS DELTA_DAY_CNT 
FROM
    lec_share.v_fact_product_stock_age
;
