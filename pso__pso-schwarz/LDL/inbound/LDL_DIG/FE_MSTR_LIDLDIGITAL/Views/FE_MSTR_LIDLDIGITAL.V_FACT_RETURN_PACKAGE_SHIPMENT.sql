CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_RETURN_PACKAGE_SHIPMENT (
    WSHOP_CD
    , BUS_YEAR
    , MONTH_OF_BUS_YEAR
    , CUST_ORDER_RETURN_DT
    , CUST_ORDER_SID
    , CUST_ORDER_POS_NR
    , CUST_ORDER_RETURN_SID
    , CUST_ORDER_RETURN_POS_NR
    , PROD_VARIANT_SID
    , PROD_VARIANT_NR
    , BUNDLE_COMPONENT_PROD_VARIANT_SID
    , BUNDLE_HEADER_PROD_VARIANT_SID
    , PACK_SIZE_HANDLE_GROUP_CD
    , RETURN_PACK_SID
    , RETURN_SHIP_COST_NET_EUR_VAL)
AS SELECT
      WSHOP_CD
    , BUS_YEAR
    , MONTH_OF_BUS_YEAR
    , CUST_ORDER_RETURN_DT
    , IFNULL(CUST_ORDER_SID,'-1') 
    , CUST_ORDER_POS_NR
    , CUST_ORDER_RETURN_SID
    , CUST_ORDER_RETURN_POS_NR
    , COALESCE(BUNDLE_HEADER_PROD_VARIANT_SID,PROD_VARIANT_SID,'-1')
    , IFNULL(PROD_VARIANT_NR,'-1')
    , IFNULL(PROD_VARIANT_SID,'-1')
    , IFNULL(BUNDLE_HEADER_PROD_VARIANT_SID,'-1')
    , PACK_SIZE_HANDLE_GROUP_CD
    , IFNULL(RETURN_PACK_SID,'-1')
    , RETURN_SHIP_COST_NET_EUR_VAL
FROM
    lec_share.v_fact_return_package_shipment_core_view
WHERE 
        CUST_ORDER_RETURN_DT >= '2022-03-01' --limit not needed data
    AND CUST_ORDER_RETURN_DT <= LAST_DAY( ADD_MONTHS( CURRENT_DATE(), -1 ) )
    ;