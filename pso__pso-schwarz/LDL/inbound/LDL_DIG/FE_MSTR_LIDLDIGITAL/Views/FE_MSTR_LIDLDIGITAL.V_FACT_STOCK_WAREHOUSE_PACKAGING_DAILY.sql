CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_STOCK_WAREHOUSE_PACKAGING_DAILY
AS SELECT
     WH_SID AS WH_SID
    ,STORAGE_LOC_CD AS STORAGE_LOC_CD
    ,CASE WHEN PACK_MATERIAL_NR = '' THEN '-1' ELSE IFNULL(PACK_MATERIAL_NR, '-1') END AS PACK_MATERIAL_NR
    ,CAL_DT AS CAL_DT
    ,ACTIVE_FG AS ACTIVE_FG
    ,BLOCKED_STOCK_CNT AS BLOCKED_STOCK_CNT
    ,UNRESTRICTED_STOCK_CNT AS UNRESTRICTED_STOCK_CNT
    ,RESTRICTED_STOCK_CNT AS RESTRICTED_STOCK_CNT
    ,IN_TRANSFER_CNT AS IN_TRANSFER_CNT
    ,IN_QTY_INSPECTION_CNT AS IN_QTY_INSPECTION_CNT 
FROM
    lec_share.v_fact_stock_warehouse_packaging_daily
;
