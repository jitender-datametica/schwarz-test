CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_TRAVEL_BOOKING
(
     TRAV_BOOKING_SID
    ,DWH_VALID_FROM_TMSP
    ,DWH_VALID_TO_TMSP
    ,DWH_VALID_FG
    ,BOOKING_NR
    ,TRAV_OFFER_SID
    ,PROCESS_NR
    ,CUST_SID
    ,TRAV_COST_CENTER_CD
    ,TRAV_BOOKING_CHANNEL_CD
    ,CUST_BOOKING_REF_SID
    ,CUST_BOOKING_REF_LINK
    ,TRAV_BOOKING_SVC_TYPE_CD
    ,TOUR_OPERATOR_CD
    ,BOOKING_DT
    ,TRAVEL_START_DT
    ,TRAVEL_END_DT
    ,DURATION_OF_TRAVEL
    ,PREBOOKING_DAYS
    ,CURR_TRAV_BOOKING_STATUS_CD
    ,CANCEL_DT
    ,CHILD_CNT
    ,PASSENGER_CNT
    ,CURR_CD
    ,INIT_BOOKING_SVC_PRICE_VAL
    ,INIT_BOOKING_SVC_PROVISION_VAL
    ,CURR_BOOKING_SVC_PRICE_VAL
    ,CURR_BOOKING_SVC_PROVISION_VAL
    ,CANCEL_PRICE_VAL
    ,CANCEL_PROVISION_VAL
    ,TRAV_BOOKING_COUPON_CD
    ,COUPON_PRICE_VAL
    ,IS_FLIGHT_SVC_AVAIL_FG
    ,FLIGHT_SVC_CD
    ,DEPARTURE_AIRPORT_CD
    ,ARRIVAL_AIRPORT_CD
    ,DESTINATION_COUNTRY_CD
    ,DESTINATION_REGION_NAME
    ,CRUISE_REGION_NAME
    ,TRAV_BOOKING_ROOM_TYPE_CD
    ,TRAV_BOOKING_FOOD_PACK_TYPE_CD
    ,IS_HOTEL_SVC_AVAIL_FG
    ,HOTEL_SVC_CD
    ,HOTEL_GIATA_NR
    ,HOTEL_CITY_NAME
    ,IS_MISC_SVC_AVAIL_FG
    ,CURR_TRAV_BOOKING_SVC_STATUS_CD
	,INIT_TRAV_BOOKING_SVC_STATUS_CD
    ,TRAV_BOOKING_DIST_SYS_CD
    ,TOUR_OPERATOR_AGENCY_CD
    ,OFFER_OPERATOR_CD
    ,TRAV_BOOKING_COUPON_CUST_CD
)
AS SELECT
     TRAV_BOOKING_SID
    ,DWH_VALID_FROM_TMSP
    ,DWH_VALID_TO_TMSP
    ,DWH_VALID_FG
    ,BOOKING_NR
    ,IFNULL(TRAV_OFFER_SID , '-1')
    ,PROCESS_NR
    ,IFNULL(CUST_SID , '-1')
    ,CASE WHEN TRAV_COST_CENTER_CD = '' THEN '-1' ELSE IFNULL(TRAV_COST_CENTER_CD , '-1') END
    ,CASE WHEN TRAV_BOOKING_CHANNEL_CD = '' THEN '-1' ELSE IFNULL(TRAV_BOOKING_CHANNEL_CD , '-1') END
    ,IFNULL(CUST_BOOKING_REF_SID , '-1')
    ,CUST_BOOKING_REF_LINK
    ,CASE WHEN TRAV_BOOKING_SVC_TYPE_CD = '' THEN '-1' ELSE IFNULL(TRAV_BOOKING_SVC_TYPE_CD , '-1') END
    ,CASE WHEN TOUR_OPERATOR_CD = '' THEN '-1' ELSE IFNULL(TOUR_OPERATOR_CD , '-1') END
    ,BOOKING_DT
    ,TRAVEL_START_DT
    ,TRAVEL_END_DT
    ,DATEDIFF(DAY, TRAVEL_START_DT,TRAVEL_END_DT) DURATION_OF_TRAVEL
    ,DATEDIFF(DAY, BOOKING_DT,TRAVEL_START_DT) PREBOOKING_DAYS
    ,CASE WHEN CURR_TRAV_BOOKING_STATUS_CD = '' THEN '' ELSE IFNULL(CURR_TRAV_BOOKING_STATUS_CD , '') END
    ,CANCEL_DT
    ,CHILD_CNT
    ,PASSENGER_CNT
    ,CASE WHEN CURR_CD = '' THEN '' ELSE IFNULL(CURR_CD , '') END
    ,INIT_BOOKING_SVC_PRICE_VAL
    ,INIT_BOOKING_SVC_PROVISION_VAL
    ,CURR_BOOKING_SVC_PRICE_VAL
    ,CURR_BOOKING_SVC_PROVISION_VAL
    ,CANCEL_PRICE_VAL
    ,CANCEL_PROVISION_VAL
    ,CASE WHEN TRAV_BOOKING_COUPON_CD = '' THEN '' ELSE IFNULL(TRAV_BOOKING_COUPON_CD , '') END
    ,COUPON_PRICE_VAL 
    ,IS_FLIGHT_SVC_AVAIL_FG
    ,CASE WHEN FLIGHT_SVC_CD = '' THEN '' ELSE IFNULL(FLIGHT_SVC_CD , '') END
    ,CASE WHEN DEPARTURE_AIRPORT_CD = '' THEN '' ELSE IFNULL(DEPARTURE_AIRPORT_CD , '') END
    ,CASE WHEN ARRIVAL_AIRPORT_CD = '' THEN '' ELSE IFNULL(ARRIVAL_AIRPORT_CD , '') END
    ,CASE WHEN DESTINATION_COUNTRY_CD = '' THEN '' ELSE IFNULL(DESTINATION_COUNTRY_CD , '') END
    ,DESTINATION_REGION_NAME
    ,CRUISE_REGION_NAME
    ,CASE WHEN TRAV_BOOKING_ROOM_TYPE_CD = '' THEN '-1' ELSE IFNULL(TRAV_BOOKING_ROOM_TYPE_CD , '-1') END
    ,CASE WHEN TRAV_BOOKING_FOOD_PACK_TYPE_CD = '' THEN '-1' ELSE IFNULL(TRAV_BOOKING_FOOD_PACK_TYPE_CD , '-1') END
    ,IS_HOTEL_SVC_AVAIL_FG
    ,CASE WHEN HOTEL_SVC_CD = '' THEN '' ELSE IFNULL(HOTEL_SVC_CD , '') END
    ,HOTEL_GIATA_NR
    ,HOTEL_CITY_NAME
    ,IS_MISC_SVC_AVAIL_FG
    ,CASE WHEN CURR_TRAV_BOOKING_SVC_STATUS_CD = '' THEN '-1' ELSE IFNULL(CURR_TRAV_BOOKING_SVC_STATUS_CD , '-1') END
	,CASE WHEN INIT_TRAV_BOOKING_SVC_STATUS_CD = '' THEN '-1' ELSE IFNULL(INIT_TRAV_BOOKING_SVC_STATUS_CD , '-1') END
    ,CASE WHEN TRAV_BOOKING_DIST_SYS_CD = '' THEN '-1' ELSE IFNULL(TRAV_BOOKING_DIST_SYS_CD , '-1') END
    ,CASE WHEN TOUR_OPERATOR_AGENCY_CD = '' THEN '-1' ELSE IFNULL(TOUR_OPERATOR_AGENCY_CD , '-1') END
    ,CASE WHEN OFFER_OPERATOR_CD = '' THEN '-1' ELSE IFNULL(OFFER_OPERATOR_CD , '-1') END
    ,CASE WHEN TRAV_BOOKING_COUPON_CUST_CD = '' THEN '' ELSE IFNULL(TRAV_BOOKING_COUPON_CUST_CD , '') END
FROM lec_share.v_fact_travel_booking
WHERE
    DWH_VALID_FG=TRUE;
