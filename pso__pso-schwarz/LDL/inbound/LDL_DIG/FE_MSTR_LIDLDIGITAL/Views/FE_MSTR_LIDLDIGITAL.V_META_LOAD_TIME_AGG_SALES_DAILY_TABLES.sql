CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_META_LOAD_TIME_AGG_SALES_DAILY_TABLES(
	AGG_TABLE_NAME
	,MAX_DWH_UPDATED_TMSP
) AS SELECT
    'T_AGG_SALES_DAILY'
    ,CONVERT_TIMEZONE('Europe/Berlin', MAX(DWH_UPDATED_TMSP))::TIMESTAMP_NTZ AS MAX_DWH_UPDATED_TMSP
FROM
    lec_share.v_agg_sales_daily

UNION ALL

SELECT
    'T_AGG_PRODUCT_SALES_DAILY'
    ,CONVERT_TIMEZONE('Europe/Berlin', MAX(DWH_UPDATED_TMSP))::TIMESTAMP_NTZ AS MAX_DWH_UPDATED_TMSP
FROM
    lec_share.v_agg_product_sales_daily

UNION ALL

SELECT
    'T_AGG_PRODUCT_VARIANT_SALES_DAILY'
    ,CONVERT_TIMEZONE('Europe/Berlin', MAX(DWH_UPDATED_TMSP))::TIMESTAMP_NTZ AS MAX_DWH_UPDATED_TMSP
FROM
    lec_share.v_agg_product_variant_sales_daily
;