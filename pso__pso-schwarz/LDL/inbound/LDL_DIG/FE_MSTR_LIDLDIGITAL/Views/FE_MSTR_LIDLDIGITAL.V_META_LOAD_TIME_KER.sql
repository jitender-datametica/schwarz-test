CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_META_LOAD_TIME_KER(
	ACCT_DATA_SRC_NAME
    ,FISCAL_PERIOD
    ,FISCAL_YEAR
    ,CURRENT_FISCAL_PERIOD
    ,IS_CURRENT_FISCAL_PERIOD_AND_YEAR_CD
    ,PREVIOUS_FISCAL_PERIOD
    ,IS_PREVIOUS_FISCAL_PERIOD_AND_YEAR_CD
    ,MAX_DWH_UPDATED_TMSP     
) AS SELECT
    'IST SAP' AS ACCT_DATA_SRC_NAME
    ,FISCAL_PERIOD_NR AS FISCAL_PERIOD
    ,FISCAL_YEAR AS FISCAL_YEAR
    ,DECODE(MONTH(CURRENT_DATE())-2,-1,11,0,12,MONTH(CURRENT_DATE())-2) AS CURRENT_FISCAL_PERIOD
    ,CASE WHEN Decode(MONTH(CURRENT_DATE())-2,-1,11,0,12,MONTH(CURRENT_DATE())-2)= FISCAL_PERIOD 
        AND DECODE(MONTH(CURRENT_DATE())-2,-1,YEAR(CURRENT_DATE())-1,0,YEAR(CURRENT_DATE())-1,YEAR(CURRENT_DATE()))= FISCAL_YEAR
        THEN 1
        ELSE 0
        END AS IS_CURRENT_FISCAL_PERIOD_AND_YEAR_CD
    ,DECODE(MONTH(CURRENT_DATE())-3,-2,10,-1,11,0,12,MONTH(CURRENT_DATE())-3) AS PREVIOUS_FISCAL_PERIOD
    ,CASE WHEN DECODE(MONTH(CURRENT_DATE())-3,-2,10,-1,11,0,12,MONTH(CURRENT_DATE())-3)= FISCAL_PERIOD 
        AND DECODE(MONTH(CURRENT_DATE())-3,-2,YEAR(CURRENT_DATE())-1,-1,YEAR(CURRENT_DATE())-1,0,YEAR(CURRENT_DATE())-1,YEAR(CURRENT_DATE()))= FISCAL_YEAR
        THEN 1
        ELSE 0
        END AS IS_PREVIOUS_FISCAL_PERIOD_AND_YEAR_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', MAX(DWH_UPDATED_TMSP))::TIMESTAMP_NTZ AS MAX_DWH_UPDATED_TMSP
FROM
    lec_share.v_fact_accounting_document_line
GROUP BY ACCT_DATA_SRC_NAME, FISCAL_PERIOD, FISCAL_YEAR,CURRENT_FISCAL_PERIOD, IS_CURRENT_FISCAL_PERIOD_AND_YEAR_CD, PREVIOUS_FISCAL_PERIOD, IS_PREVIOUS_FISCAL_PERIOD_AND_YEAR_CD
    
UNION

SELECT
    'EXT' AS ACCT_DATA_SRC_NAME
    ,FISCAL_PERIOD AS FISCAL_PERIOD
    ,FISCAL_YEAR AS FISCAL_YEAR
    ,DECODE(MONTH(CURRENT_DATE())-2,-1,11,0,12,MONTH(CURRENT_DATE())-2) AS CURRENT_FISCAL_PERIOD
    ,CASE WHEN DECODE(MONTH(CURRENT_DATE())-2,-1,11,0,12,MONTH(CURRENT_DATE())-2)= FISCAL_PERIOD 
        AND DECODE(MONTH(CURRENT_DATE())-2,-1,YEAR(CURRENT_DATE())-1,0,YEAR(CURRENT_DATE())-1,YEAR(CURRENT_DATE()))= FISCAL_YEAR
        THEN 1
        ELSE 0
        END AS IS_CURRENT_FISCAL_PERIOD_AND_YEAR_CD
    ,DECODE(MONTH(CURRENT_DATE())-3,-2,10,-1,11,0,12,MONTH(CURRENT_DATE())-3) AS PREVIOUS_FISCAL_PERIOD
    ,CASE WHEN DECODE(MONTH(CURRENT_DATE())-3,-2,10,-1,11,0,12,MONTH(CURRENT_DATE())-3)= FISCAL_PERIOD 
        AND DECODE(MONTH(CURRENT_DATE())-3,-2,YEAR(CURRENT_DATE())-1,-1,YEAR(CURRENT_DATE())-1,0,YEAR(CURRENT_DATE())-1,YEAR(CURRENT_DATE()))= FISCAL_YEAR
        THEN 1
        ELSE 0
        END AS IS_PREVIOUS_FISCAL_PERIOD_AND_YEAR_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', MAX(DWH_UPDATED_TMSP))::TIMESTAMP_NTZ AS MAX_DWH_UPDATED_TMSP
FROM
    lec_share.v_agg_financial_period_summary
WHERE ACCT_DATA_SRC_NAME='EXT'
GROUP BY ACCT_DATA_SRC_NAME, FISCAL_PERIOD, FISCAL_YEAR,CURRENT_FISCAL_PERIOD, IS_CURRENT_FISCAL_PERIOD_AND_YEAR_CD, PREVIOUS_FISCAL_PERIOD, IS_PREVIOUS_FISCAL_PERIOD_AND_YEAR_CD
;