CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_META_LOAD_TIME_LAGER_COCKPIT(
	WH_SID
	,WH_CD
	,MAX_SRC_FILE_TMSP
	,MAX_DWH_UPDATED_TMSP
) AS
SELECT
WH_SID
,WH_CD
,CONVERT_TIMEZONE('Europe/Berlin', MIN(MAX_SRC_FILE_TMSP))::TIMESTAMP_NTZ  AS MAX_SRC_FILE_TMSP
,CONVERT_TIMEZONE('Europe/Berlin', MAX(MAX_DWH_UPDATED_TMSP))::TIMESTAMP_NTZ  AS MAX_DWH_UPDATED_TMSP
FROM (
   SELECT 
    WH_SID
    ,WH_CD
    ,MAX(SRC_FILE_TMSP) AS MAX_SRC_FILE_TMSP
    ,MAX(DWH_UPDATED_TMSP) AS MAX_DWH_UPDATED_TMSP
    FROM lec_share.v_fact_warehouse_order_line_process_status
    GROUP BY WH_CD, WH_SID

UNION 
    
    SELECT
    WH_SID
    ,WH_CD
    ,MAX(SRC_FILE_TMSP) AS MAX_SRC_FILE_TMSP
    ,MAX(DWH_UPDATED_TMSP) AS MAX_DWH_UPDATED_TMSP
    FROM lec_share.v_fact_warehouse_processing 
    GROUP BY WH_CD, WH_SID

UNION 
    
    SELECT
    WH_SID
    ,WH_CD
    ,MAX(SRC_FILE_TMSP) AS MAX_SRC_FILE_TMSP
    ,MAX(DWH_UPDATED_TMSP) AS MAX_DWH_UPDATED_TMSP
    FROM lec_share.v_fact_warehouse_order_line
    GROUP BY WH_CD, WH_SID
        )
GROUP BY 
WH_CD
,WH_SID
;