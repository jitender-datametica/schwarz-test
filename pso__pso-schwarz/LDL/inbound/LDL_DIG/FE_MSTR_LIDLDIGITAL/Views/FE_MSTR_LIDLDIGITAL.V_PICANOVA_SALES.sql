CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_PICANOVA_SALES
( 
     SKU
    ,CLIENT
    ,CLIENT_SORT
    ,DOCTYPE
    ,ORDERDATEKEY
    ,REVENUEBEFOREDISCOUNT
    ,COUPONVALUE
    ,ORDERNUMBER
    ,PAYMENTMETHOD
    ,PROCESSOR
    ,QUANTITY
    ,VOUCHERCAMPAIGNID
    ,CLIENTPRODUCT
    ,COMMISSIONNET
    ,DISCOUNTCODEID
    ,COUPONCODE
    ,VOUCHERCAMPAIGNNAME
)
AS SELECT 
     SKU AS SKU -- product
    ,DECODE(LENGTH(NVL(CLIENT,'')),0,'Sonstiges',CLIENT) AS CLIENTX -- Webshop
    ,DECODE(CLIENTX,'DE','0','Sonstiges','Z',CLIENT) AS CLIENT_SORT -- Webshop Sortierung
    ,DECODE(LOWER(DOCTYPE),'order','order','') AS DOCTYPE -- Belegart
    ,TRY_TO_DATE(ORDERDATEKEY, 'dd.mm.yyyy')  AS ORDERDATEKEY -- Bestelldatum
    ,TRY_TO_NUMBER(DECODE(LOWER(PROD_TYPE),'shipping','','coupon','','fullrefund','','partrefund','',REVENUENETBEFOREDISCOUNT),38,5) AS REVENUENETBEFOREDISCOUNT --NettoWert
    ,ABS(TRY_TO_NUMBER(DECODE(LOWER(PROD_TYPE),'coupon',REVENUENETBEFOREDISCOUNT,''),38,5)) AS COUPONVALUE --Gutscheinwert 
    ,(DECODE(LOWER(PROD_TYPE),'shipping','','coupon','','fullrefund','','partrefund','',ORDERNUMBER)) AS ORDERNUMBER --Bestellnummer 
    ,PAYMENTMETHOD AS PAYMENTMETHOD --Zahlungsart
    ,LEFT(PROCESSOR,8) AS PROCESSOR --Geschaeftspartner
    ,TRY_TO_NUMBER(DECODE(LOWER(PROD_TYPE),'shipping','','coupon','','fullrefund','','partrefund','',QUANTITY),38,5) AS QUANTITY --Bestellmenge 
    ,VOUCHERCAMPAIGNID AS VOUCHERCAMPAIGNID -- GutscheinKampagneID
    ,PLATFORM AS CLIENTPRODUCT -- Client Product
    ,TRY_TO_NUMBER(COMMISSIONNET,38,5) AS COMMISSIONNET -- Provision_Netto
    ,DISCOUNTCODEID -- Discount
    ,MAX(TRIM(COUPONCODE)) OVER (PARTITION BY ORDERNUMBER,ORDERDATEKEY) AS COUPONCODE -- Gutscheincode
    ,MAX(TRIM(VOUCHERCAMPAIGNNAME)) OVER (PARTITION BY ORDERNUMBER,ORDERDATEKEY) AS VOUCHERCAMPAIGNNAME -- GutscheinKampagne
FROM
    FE_MSTR_LIDLDIGITAL.T_PICANOVA_SALES
;
