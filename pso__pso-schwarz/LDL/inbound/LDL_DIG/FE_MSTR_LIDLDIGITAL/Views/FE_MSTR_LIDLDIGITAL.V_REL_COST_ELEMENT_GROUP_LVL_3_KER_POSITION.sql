CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_COST_ELEMENT_GROUP_LVL_3_KER_POSITION AS
SELECT
	FISCAL_YEAR
	, CE_GROUP_LVL3_NR
    , CE_GROUP_LVL3_NAME_DE
    , PROFIT_LOSS_POSITION_NR 		AS KER_POSITION_NR
    , PROFIT_LOSS_POSITION_NAME 	AS KER_POSITION_NAME
FROM 
	lec_share.v_rel_cost_element_group_profit_loss_position
UNION ALL
    SELECT
	'-1' 	-- FISCAL_YEAR    
    ,'-1' 	-- CE_GROUP_LVL3_NR
    ,'' 	-- CE_GROUP_LVL3_NAME_DE
    ,'-1' 	-- KER_POSITION_NR
    ,''		-- KER_POSITION_NAME;
	;