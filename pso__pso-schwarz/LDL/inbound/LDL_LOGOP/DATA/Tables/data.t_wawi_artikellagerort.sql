CREATE TABLE DATA.t_wawi_artikellagerort (
    client_id           NUMBER(38,0)    NOT NULL    COMMENT 'Client id - calculated based on the country code',
    wawi_instanz_kzl    VARCHAR(3)      NOT NULL    COMMENT 'Country code',
    wh_nr               NUMBER(38,0)    NOT NULL    COMMENT 'Warehouse number',
    artikelnr           VARCHAR(18)     NOT NULL    COMMENT 'Indication of the complete article number. ARTIKEL.Artikelnr',
    kartlagerortnr      NUMBER(38,0)    NULL        COMMENT 'Storage location for boxes / single packages. LAGERORT.Lagertortnr',
    lagerplatzkarton    NUMBER(38,0)    NULL        COMMENT 'Storage bin number for boxes / single packages. LAGERORT.Lagertortnr, BEREICHE_SETZLISTE.Von_Lagerplatz/Bis_Lagerplatz',
    pallagerortnr       NUMBER(38,0)    NULL        COMMENT 'Storage location for Euro pallets. LAGERORT.Lagertortnr, BEREICHE_SETZLISTE.Lagertortnr',
    lagerplatzpalette   NUMBER(38,0)    NULL        COMMENT 'Storage bin number for Euro pallets. LAGERORT.Lagertortnr, BEREICHE_SETZLISTE.Von_Lagerplatz/Bis_Lagerplatz',
    dueslagerortnr      NUMBER(38,0)    NULL        COMMENT 'Storage location for Düsseldorf pallets. LAGERORT.Lagertortnr, BEREICHE_SETZLISTE.Lagertortnr',
    lagerplatzduesseld  NUMBER(38,0)    NULL        COMMENT 'Storage bin number for Düsseldorf pallets. LAGERORT.Lagertortnr, BEREICHE_SETZLISTE.Von_Lagerplatz/Bis_Lagerplatz',
    datum               TIMESTAMP_NTZ(9) NULL       COMMENT 'Last modification date',
    bediener            VARCHAR(8)      NULL        COMMENT 'Last editor',
    invfig_karton       VARCHAR(1)      NULL        COMMENT 'Inventory flag for boxes / single packages',
    invfig_palette      VARCHAR(1)      NULL        COMMENT 'Inventory flag for Euro pallets',
    invfig_duesseld     VARCHAR(1)      NULL        COMMENT 'Inventory flag for Düsseldorf pallets',
    scn                 NUMBER(38,0)    NULL,
    dwh_load_id         NUMBER(38,0)    NOT NULL    COMMENT 'Load id',
    dwh_created         TIMESTAMP_NTZ(9) NOT NULL   COMMENT 'Record created at',
    dwh_updated         TIMESTAMP_NTZ(9) NOT NULL   COMMENT 'Record updated at',
    dwh_valid_from      DATE            NOT NULL    COMMENT 'Valid from date',
    dwh_valid_to        DATE            NOT NULL    COMMENT 'Valid to date',
    deleted_fg          BOOLEAN         NOT NULL    COMMENT 'Flag if record is deleted',
    PRIMARY KEY (client_id, wh_nr, artikelnr, dwh_valid_from)
) COMMENT='WAWI - WHWAWIADM.ARTIKELLAGERORT';