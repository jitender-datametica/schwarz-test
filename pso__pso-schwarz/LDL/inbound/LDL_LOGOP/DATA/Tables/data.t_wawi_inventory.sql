CREATE TABLE DATA.T_WAWI_INVENTORY (
	CLIENT_ID NUMBER(38,0) NOT NULL COMMENT 'Client id - calculated based on the country code',
	WH_NR NUMBER(38,0) NOT NULL COMMENT 'Warehouse number',
	WAWI_INSTANZ_KZL VARCHAR(3) NOT NULL COMMENT 'Country code',
	INVENTORYNUM NUMBER(38,0) NOT NULL COMMENT 'Number of the Inventory - filled in by the application automatically',
	DESCRIPTION VARCHAR(25) COMMENT 'Name of the inventory typed in by the user during the inventory generation',
	DAYENDDATE TIMESTAMP_NTZ(9) COMMENT 'Inventorydate typed in by the user during the inventory generation',
	READONLY VARCHAR(1) COMMENT 'Shows if the inventory was already posted or not T if posted, F if not posted',
	C72_TYPE VARCHAR(1) COMMENT 'P = partial; Z = Full but not activated; F = Full and activated',
	INVENTSKELETON TIMESTAMP_NTZ(9) COMMENT 'Timestamp of the inventory generation',
	ADDUNALOCSLOTS TIMESTAMP_NTZ(9) COMMENT 'Timestamp adding items without slots',
	ADDAISLEDESCR TIMESTAMP_NTZ(9) COMMENT 'Timestamp adding aisle description from BEREICHE_SETZLISTE',
	DELOLDITEMS TIMESTAMP_NTZ(9) COMMENT 'Timestamp after deleting items with status >12',
	UPDPRICES TIMESTAMP_NTZ(9) COMMENT 'Timestamp of the last price updates',
	UPDEXPFIGURES TIMESTAMP_NTZ(9) COMMENT 'Timestamp of the last update of expected stock',
	UPDONTHERAMP TIMESTAMP_NTZ(9) COMMENT 'Timestamp of the last update of the rampstock',
	ADDOLDCASESZS TIMESTAMP_NTZ(9),
	DELOLDCASESZS TIMESTAMP_NTZ(9),
	MOD_USER VARCHAR(8) COMMENT 'Last moduser of inventory',
	MOD_DATE TIMESTAMP_NTZ(9) COMMENT 'last moddate of inventory',
	YNDINVENTORY NUMBER(38,0) COMMENT 'Indicates if the inventory is a YE or not',
	EVALINVENTORY NUMBER(38,0) COMMENT 'Indicates if the inventory is a evaluation inventory or not',
	DATEPOSTED TIMESTAMP_NTZ(9) COMMENT 'Timestamp of the posting of the inventory',
	WHNR NUMBER(38,0) NOT NULL COMMENT 'Number of the WH from UMGEBUNG',
	CHECKDAT TIMESTAMP_NTZ(9) COMMENT 'The timestamp of the T72_INVENTORY.C72_CHECKVALUE check',
	CHECKVALUE NUMBER(38,0) COMMENT 'Indicates whether the check for equality between T1001.C1001_PIECEQTY_CAL and T1001.C1001_PIECEQTY_REAL was successful or not',
	UPDEXPFIGURES_SSI TIMESTAMP_NTZ(9) COMMENT 'The timestamp of the the ssi expected figures update',
	UPDEXPFIGURES_LPV TIMESTAMP_NTZ(9) COMMENT 'The timestamp of the lpv expected figures update',
	MANUAL_LPV NUMBER(38,0) COMMENT 'Indicates whether a year end full inventory is in LPV manual mode, 0 = LPV manual mode is disabled, 1 = LPV manual mode is enabled, null = not relevant for the specific inventory',
	AREA_BY_AREA NUMBER(38,0) COMMENT 'Indicates if an item of the inventory is from ewm(1) or not(0)',
	SCN NUMBER(38,0),
	DWH_LOAD_ID NUMBER(38,0) NOT NULL COMMENT 'Load id',
	DWH_CREATED TIMESTAMP_NTZ(9) NOT NULL COMMENT 'Record created at',
	DWH_UPDATED TIMESTAMP_NTZ(9) NOT NULL COMMENT 'Record updated at',
	DWH_VALID_FROM DATE NOT NULL COMMENT 'Valid from date',
	DWH_VALID_TO DATE NOT NULL COMMENT 'Valid to date',
	DELETED_FG BOOLEAN NOT NULL COMMENT 'Flag if record is deleted',
	PRIMARY KEY (CLIENT_ID, WHNR, INVENTORYNUM, DWH_VALID_FROM)
)COMMENT='WAWI - WHWAWIADM.T72_INVENTORY table'
;