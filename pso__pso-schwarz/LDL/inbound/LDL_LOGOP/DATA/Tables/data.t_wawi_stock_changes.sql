CREATE TABLE DATA.t_wawi_stock_changes (
client_id 				NUMBER(38,0) 	NOT NULL 		COMMENT 'Client id - calculated based on the country code', 
wawi_instanz_kzl 		VARCHAR(3)		NOT NULL 		COMMENT 'Country code',
wh_nr 					NUMBER(38,0)  	NOT NULL 		COMMENT 'Warehouse number',
c1003_id 				NUMBER(38,0)	NOT NULL		COMMENT 'Unique ID, which is assigned automatically',
sscc 					NUMBER(38,0)	NULL			COMMENT 'ID from the T1010_SSCC table',
stock_area 				NUMBER(38,0)	NULL			COMMENT 'Sender ID from the T1000_STOCK_AREA table',
rcv_stock_area 			NUMBER(38,0)	NULL			COMMENT 'Recipient ID from the T1000_STOCK_AREA table',
corrid 					NUMBER(38,0)	NULL			COMMENT 'ID from the T1002_STOCK_CORRECTION table',
formdate 				TIMESTAMP		NULL			COMMENT 'Document date',
itemnr 					VARCHAR(18)		NULL			COMMENT 'Item number from the ARTICLE table',
pieceqty 				NUMBER(38,3)	NULL			COMMENT 'Difference quantity. Always refers to the C1003_STOCK_AREA column. A + value increases C1003_STOCK_AREA and a - value decreases C1003_RCV_STOCK_AREA. A - value increases the posting in reverse.',
formno 					VARCHAR(20)		NULL			COMMENT 'Document number',
formtype 				NUMBER(38,0)	NULL			COMMENT 'Document type',
dayend_status 			NUMBER(38,0)	NULL			COMMENT 'TA status: 0 = not posted. 1 = TA snapshot. 2 = posted.',
dayend_date 			TIMESTAMP		NULL			COMMENT 'Daily closing date',
moduser 				VARCHAR(30)		NULL			COMMENT 'Last processor',
moddate 				TIMESTAMP		NULL			COMMENT 'Date of change',
scn 					NUMBER(38,0)	NULL			COMMENT '',
dwh_load_id    			NUMBER(38,0) 	NOT NULL 		COMMENT 'Load id',
dwh_created    			TIMESTAMP 		NOT NULL 		COMMENT 'Record created at',
dwh_updated    			TIMESTAMP 		NOT NULL 		COMMENT 'Record updated at',
dwh_valid_from 			DATE 			NOT NULL 		COMMENT 'Valid from date',
dwh_valid_to   			DATE 			NOT NULL 		COMMENT 'Valid to date',
deleted_fg     			BOOLEAN 		NOT NULL 		COMMENT 'Flag if record is deleted',
PRIMARY KEY (client_id, wh_nr, c1003_id, dwh_valid_from)
) COMMENT = 'WAWI - WHWAWIADM.T1003_STOCK_CHANGES. Detailed table of released stock changes from table T1002_STOCK_CORRECTION. These stock changes are taken into account during a DAY run.';
