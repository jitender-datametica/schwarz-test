CREATE DYNAMIC TABLE DATA.t_wawi_stock_value_act
 TARGET_LAG = '1 hour' 
 REFRESH_MODE = INCREMENTAL
 INITIALIZE = ON_CREATE 
 WAREHOUSE = WH_LDL_LOGOP_%%environmentAbbreviation%%_DYNAMIC_TABLE_DATA
 CLUSTER BY (CLIENT_ID, WH_NR, DATE(CAL_DT)) AS
SELECT 
    CLIENT_ID,
    WAWI_INSTANZ_KZL,
    WH_NR,
    ID,
    STOCK_AREA,
    CAL_DT,
    ITEMNR,
    PIECEQTY_CAL,
    PIECEQTY_REAL,
    PIECEQTY_EWMCALC,
    PIECEQTY_NF_UNDER,
    PIECEQTY_NF_OVER,
    PIECEQTY_NF_NONREC,
    PIECEQTY_NF_ZERODEL,
    PIECEQTY_NF_SPS_OVER,
    PIECEQTY_NF_SPS_UNDER,
    SCN,
    DWH_CREATED,
    DWH_UPDATED
FROM 
    DATA.T_WAWI_STOCK_VALUE
WHERE 
    CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
    AND DELETED_FG = 0
    AND STOCK_AREA = 2
    AND PIECEQTY_REAL IS NOT NULL
    AND CAL_DT >= '2025-03-01';