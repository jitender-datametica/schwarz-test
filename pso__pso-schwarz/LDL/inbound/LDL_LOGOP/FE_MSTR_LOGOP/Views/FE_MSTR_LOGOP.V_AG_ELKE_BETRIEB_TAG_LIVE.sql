        DATA.T_SAPEWM_NFEMPLOYEEPERFORMANCE
		INNER JOIN DATA.T_CAL_CALENDARDAY CAL
		ON CREATED_DATE = CAL.CAL_DT
	WHERE YEAR(DATEADD(MONTH, -2, CURRENT_DATE)) = CAL.BUSYEAR
