CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_AG_ELKE_STAMMDATEN_WH(
  LANDESKUERZEL
 ,CLIENT_ID
 ,GESELLSCHAFT_NR
 ,GESELLSCHAFTSKUERZEL
 ,GESELLSCHAFT
 ,GESELLSCHAFTSTYP
) AS
SELECT
   LANDESKUERZEL
 , CASE 
		WHEN  LANDESKUERZEL = 'INT'	THEN 0
		WHEN  LANDESKUERZEL = 'AT'	THEN 1
		WHEN  LANDESKUERZEL = 'BE'	THEN 2
		WHEN  LANDESKUERZEL = 'BG'	THEN 3
		WHEN  LANDESKUERZEL = 'CH'	THEN 4
		WHEN  LANDESKUERZEL = 'CY'	THEN 5
		WHEN  LANDESKUERZEL = 'CZ'	THEN 6
		WHEN  LANDESKUERZEL = 'DK'	THEN 8
		WHEN  LANDESKUERZEL = 'ES'	THEN 10
		WHEN  LANDESKUERZEL = 'FI'	THEN 11
		WHEN  LANDESKUERZEL = 'FR'	THEN 12
		WHEN  LANDESKUERZEL = 'GB'	THEN 13
		WHEN  LANDESKUERZEL = 'GR'	THEN 14
		WHEN  LANDESKUERZEL = 'HR'	THEN 15
		WHEN  LANDESKUERZEL = 'HU'	THEN 16
		WHEN  LANDESKUERZEL = 'IE'	THEN 17
		WHEN  LANDESKUERZEL = 'IT'	THEN 18
		WHEN  LANDESKUERZEL = 'LT'	THEN 19
		WHEN  LANDESKUERZEL = 'LV'	THEN 20
		WHEN  LANDESKUERZEL = 'NI'	THEN 21
		WHEN  LANDESKUERZEL = 'NL'	THEN 22
		WHEN  LANDESKUERZEL = 'DE'	THEN 23
		WHEN  LANDESKUERZEL = 'PL'	THEN 24
		WHEN  LANDESKUERZEL = 'PT'	THEN 25
		WHEN  LANDESKUERZEL = 'RO'	THEN 26
		WHEN  LANDESKUERZEL = 'SE'	THEN 27
		WHEN  LANDESKUERZEL = 'SI'	THEN 28
		WHEN  LANDESKUERZEL = 'SK'	THEN 29
		WHEN  LANDESKUERZEL = 'CS'	THEN 31
		WHEN  LANDESKUERZEL = 'MT'	THEN 32
		WHEN  LANDESKUERZEL = 'US'	THEN 33
		WHEN  LANDESKUERZEL = 'RS'	THEN 34
		ELSE NULL
   END AS CLIENT_ID  
 , GESELLSCHAFTSNUMMER AS GESELLSCHAFT_NR
 , GESELLSCHAFTSKUERZEL
    ,CASE 
		WHEN GESELLSCHAFTSNUMMER = -9998 THEN 'AT'
		WHEN GESELLSCHAFTSNUMMER = -9997 THEN 'BE'
		WHEN GESELLSCHAFTSNUMMER = -9996 THEN 'BG'
		WHEN GESELLSCHAFTSNUMMER = -9995 THEN 'CH'
		WHEN GESELLSCHAFTSNUMMER = -9994 THEN 'CS'
		WHEN GESELLSCHAFTSNUMMER = -9993 THEN 'CY'
		WHEN GESELLSCHAFTSNUMMER = -9992 THEN 'CZ'
		WHEN GESELLSCHAFTSNUMMER = -9991 THEN 'DE'
		WHEN GESELLSCHAFTSNUMMER = -9990 THEN 'DK'
		WHEN GESELLSCHAFTSNUMMER = -9989 THEN 'EE'
		WHEN GESELLSCHAFTSNUMMER = -9988 THEN 'ES'
		WHEN GESELLSCHAFTSNUMMER = -9987 THEN 'FI'
		WHEN GESELLSCHAFTSNUMMER = -9986 THEN 'FR'
		WHEN GESELLSCHAFTSNUMMER = -9985 THEN 'GB'
		WHEN GESELLSCHAFTSNUMMER = -9984 THEN 'GR'
		WHEN GESELLSCHAFTSNUMMER = -9983 THEN 'HR'
		WHEN GESELLSCHAFTSNUMMER = -9982 THEN 'HU'
		WHEN GESELLSCHAFTSNUMMER = -9981 THEN 'IE'
		WHEN GESELLSCHAFTSNUMMER = -9980 THEN 'IT'
		WHEN GESELLSCHAFTSNUMMER = -9979 THEN 'LT'
		WHEN GESELLSCHAFTSNUMMER = -9978 THEN 'LV'
		WHEN GESELLSCHAFTSNUMMER = -9977 THEN 'MT'
		WHEN GESELLSCHAFTSNUMMER = -9976 THEN 'NI'
		WHEN GESELLSCHAFTSNUMMER = -9975 THEN 'NL'
		WHEN GESELLSCHAFTSNUMMER = -9974 THEN 'PL'
		WHEN GESELLSCHAFTSNUMMER = -9973 THEN 'PT'
		WHEN GESELLSCHAFTSNUMMER = -9972 THEN 'RO'
		WHEN GESELLSCHAFTSNUMMER = -9971 THEN 'RS'
		WHEN GESELLSCHAFTSNUMMER = -9970 THEN 'SE'
		WHEN GESELLSCHAFTSNUMMER = -9969 THEN 'SI'
		WHEN GESELLSCHAFTSNUMMER = -9968 THEN 'SK'
		WHEN GESELLSCHAFTSNUMMER = -9967 THEN 'US'
		WHEN GESELLSCHAFTSNUMMER = -10000 THEN 'INT'                                   
        ELSE GESELLSCHAFTSNAME                                                           
    END AS GESELLSCHAFT
 , GESELLSCHAFTSTYP
FROM DATA.T_AG_ELKE_STAMMDATEN
;