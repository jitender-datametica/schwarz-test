SELECT
  CLIENT_ID
, LIDL_COUNTRY
, SOURCE_SYSTEM
, WH_ID
, CY_WEEK
, SUM(PALLETS_TOTAL) AS PALLETS_TOTAL_WK
, SUM(PALLET_STORES) AS PALLET_STORES_WK
, SUM(PALLET_NON_STORES) AS PALLET_NON_STORES_WK
, SUM(COUNT_TRUCKS_TOTAL) AS COUNT_TRUCKS_TOTAL_WK
, SUM(COUNT_TRUCKS_STORE_DELIVERY) AS COUNT_TRUCKS_STORE_DELIVERY_WK
, SUM(COUNT_TRUCKS_NON_STORE_DELIVERY) AS COUNT_TRUCKS_NON_STORE_DELIVERY_WK
, SUM(COUNT_SHIFTS_TOTAL) AS COUNT_SHIFTS_TOTAL_WK
, SUM(COUNT_SHIFTS_STORE_DELIVERY) AS COUNT_SHIFTS_STORE_DELIVERY_WK
, SUM(COUNT_SHIFTS_NON_STORE_DELIVERY) AS COUNT_SHIFTS_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_SEC) AS USE_TIME_IN_SEC_WK
, SUM(USE_TIME_IN_MIN) AS USE_TIME_IN_MIN_WK
, SUM(USE_TIME_IN_HR) AS USE_TIME_IN_HR_WK
, SUM(USE_TIME_IN_SEC_STORE_DELIVERY) AS USE_TIME_IN_SEC_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_MIN_STORE_DELIVERY) AS USE_TIME_IN_MIN_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_HR_STORE_DELIVERY) AS USE_TIME_IN_HR_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_SEC_NON_STORE_DELIVERY) AS USE_TIME_IN_SEC_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_MIN_NON_STORE_DELIVERY) AS USE_TIME_IN_MIN_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_HR_NON_STORE_DELIVERY) AS USE_TIME_IN_HR_NON_STORE_DELIVERY_WK
, SUM(KILOMETER) AS KILOMETER_WK
, SUM(KILOMETER_STORE_DELIVERY) AS KILOMETER_STORE_DELIVERY_WK
, SUM(KILOMETER_NON_STORE_DELIVERY) AS KILOMETER_NON_STORE_DELIVERY_WK
, SUM(DV_DIESEL_TOTAL) AS DV_DIESEL_TOTAL_WK
, SUM(DV_DIESEL_STORE_DELIVERY) AS DV_DIESEL_STORE_DELIVERY_WK
, SUM(DV_DIESEL_NON_STORE_DELIVERY) AS DV_DIESEL_NON_STORE_DELIVERY_WK
, SUM(DV_LNG_TOTAL) AS DV_LNG_TOTAL_WK
, SUM(DV_LNG_STORE_DELIVERY) AS DV_LNG_STORE_DELIVERY_WK
, SUM(DV_LNG_NON_STORE_DELIVERY) AS DV_LNG_NON_STORE_DELIVERY_WK
, SUM(DV_CNG_TOTAL) AS DV_CNG_TOTAL_WK
, SUM(DV_CNG_STORE_DELIVERY) AS DV_CNG_STORE_DELIVERY_WK
, SUM(DV_CNG_NON_STORE_DELIVERY) AS DV_CNG_NON_STORE_DELIVERY_WK
, SUM(DV_ELEKTRO_TOTAL) AS DV_ELEKTRO_TOTAL_WK
, SUM(DV_ELEKTRO_STORE_DELIVERY) AS DV_ELEKTRO_STORE_DELIVERY_WK
, SUM(DV_ELEKTRO_NON_STORE_DELIVERY) AS DV_ELEKTRO_NON_STORE_DELIVERY_WK
, SUM(DV_WASSERSTOFF_TOTAL) AS DV_WASSERSTOFF_TOTAL_WK
, SUM(DV_WASSERSTOFF_STORE_DELIVERY) AS DV_WASSERSTOFF_STORE_DELIVERY_WK
, SUM(DV_WASSERSTOFF_NON_STORE_DELIVERY) AS DV_WASSERSTOFF_NON_STORE_DELIVERY_WK
, SUM(COUNT_TOURS_TOTAL) AS COUNT_TOURS_TOTAL_WK
, SUM(COUNT_TOURS_STORE_DELIVERY) AS COUNT_TOURS_STORE_DELIVERY_WK
, SUM(COUNT_TOURS_NON_STORE_DELIVERY) AS COUNT_TOURS_NON_STORE_DELIVERY_WK
, ZEROIFNULL(COUNT_TOURS_TOTAL_WK / NULLIFZERO(COUNT_SHIFTS_TOTAL_WK)) AS TOURS_PER_SHIFT_TOTAL_WK
, ZEROIFNULL(COUNT_TOURS_STORE_DELIVERY_WK / NULLIFZERO(COUNT_SHIFTS_STORE_DELIVERY_WK)) AS TOURS_PER_SHIFT_STORE_DELIVERY_WK
, ZEROIFNULL(COUNT_TOURS_NON_STORE_DELIVERY_WK / NULLIFZERO(COUNT_SHIFTS_NON_STORE_DELIVERY_WK)) AS TOURS_PER_SHIFT_NON_STORE_DELIVERY_WK
, SUM(PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY) AS PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY_WK
, SUM(PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY) AS PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY_WK
, ZEROIFNULL(PALLETS_TOTAL_WK / NULLIFZERO(COUNT_SHIFTS_TOTAL_WK)) AS PALLETS_PER_SHIFT_TOTAL_WK
, ZEROIFNULL(PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY_WK / NULLIFZERO(COUNT_SHIFTS_STORE_DELIVERY_WK)) AS PALLETS_PER_SHIFT_STORE_DELIVERY_WK
, ZEROIFNULL(PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY_WK / NULLIFZERO(COUNT_SHIFTS_NON_STORE_DELIVERY_WK)) AS PALLETS_PER_SHIFT_NON_STORE_DELIVERY_WK
, SUM(TOTAL_NUM_PALLETS_PLANNED) AS TOTAL_NUM_PALLETS_PLANNED_WK
, SUM(TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES) AS TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES_WK
, SUM(TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES) AS TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES_WK
, SUM(TOTAL_NUM_PALLETS_CAPACITY) AS TOTAL_NUM_PALLETS_CAPACITY_WK
, SUM(TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_STORE_DELIVERIES) AS TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_STORE_DELIVERIES_WK
, SUM(TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_NON_STORE_DELIVERIES) AS TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_NON_STORE_DELIVERIES_WK
, ZEROIFNULL(TOTAL_NUM_PALLETS_PLANNED_WK / NULLIFZERO(TOTAL_NUM_PALLETS_CAPACITY_WK) *100) AS UTILIZATION_PERCENT_TOTAL_WK
, ZEROIFNULL(TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES_WK / NULLIFZERO(TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_STORE_DELIVERIES_WK) *100) AS UTILIZATION_PERCENT_STORE_DELIVERY_WK
, ZEROIFNULL(TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES_WK / NULLIFZERO(TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_NON_STORE_DELIVERIES_WK) *100) AS UTILIZATION_PERCENT_NON_STORE_DELIVERY_WK
, ZEROIFNULL(KILOMETER_WK / NULLIFZERO(TOTAL_NUM_PALLETS_PLANNED_WK)) AS KM_PER_PALLET_TOTAL_WK
, ZEROIFNULL(KILOMETER_STORE_DELIVERY_WK / NULLIFZERO(TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES_WK)) AS KM_PER_PALLET_STORE_DELIVERY_WK
, ZEROIFNULL(KILOMETER_NON_STORE_DELIVERY_WK / NULLIFZERO(TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES_WK)) AS KM_PER_PALLET_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_SEC_PER_SHIFT) AS USE_TIME_IN_SEC_PER_SHIFT_WK
, SUM(USE_TIME_IN_MIN_PER_SHIFT) AS USE_TIME_IN_MIN_PER_SHIFT_WK
, SUM(USE_TIME_IN_HR_PER_SHIFT) AS USE_TIME_IN_HR_PER_SHIFT_WK
, SUM(USE_TIME_IN_SEC_PER_SHIFT_STORE_DELIVERY) AS USE_TIME_IN_SEC_PER_SHIFT_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_MIN_PER_SHIFT_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_SHIFT_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_HR_PER_SHIFT_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_SHIFT_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_SEC_PER_SHIFT_NON_STORE_DELIVERY) AS USE_TIME_IN_SEC_PER_SHIFT_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_MIN_PER_SHIFT_NON_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_SHIFT_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_HR_PER_SHIFT_NON_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_SHIFT_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_SEC_PER_TRUCK) AS USE_TIME_IN_SEC_PER_TRUCK_WK
, SUM(USE_TIME_IN_MIN_PER_TRUCK) AS USE_TIME_IN_MIN_PER_TRUCK_WK
, SUM(USE_TIME_IN_HR_PER_TRUCK) AS USE_TIME_IN_HR_PER_TRUCK_WK
, SUM(USE_TIME_IN_SEC_PER_TRUCK_STORE_DELIVERY) AS USE_TIME_IN_SEC_PER_TRUCK_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_MIN_PER_TRUCK_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_TRUCK_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_HR_PER_TRUCK_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_TRUCK_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_SEC_PER_TRUCK_NON_STORE_DELIVERY) AS USE_TIME_IN_SEC_PER_TRUCK_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_MIN_PER_TRUCK_NON_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_TRUCK_NON_STORE_DELIVERY_WK
, SUM(USE_TIME_IN_HR_PER_TRUCK_NON_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_TRUCK_NON_STORE_DELIVERY_WK
, ZEROIFNULL((COUNT_SHIFTS_TOTAL_WK / NULLIFZERO(COUNT_TRUCKS_TOTAL_WK)-1)*100) AS SHARE_DOUBLE_SHIFTS_WK
, ZEROIFNULL((COUNT_SHIFTS_STORE_DELIVERY_WK / NULLIFZERO(COUNT_TRUCKS_STORE_DELIVERY_WK)-1)*100) AS SHARE_DOUBLE_SHIFTS_STORE_DELIVERY_WK
, ZEROIFNULL((COUNT_SHIFTS_NON_STORE_DELIVERY_WK / NULLIFZERO(COUNT_TRUCKS_NON_STORE_DELIVERY_WK)-1)*100) AS SHARE_DOUBLE_SHIFTS_NON_STORE_DELIVERY_WK
, SUM(TOTALNUMPALLETSWITHISDELIVERYTOEXTERNALWAREHOUSEPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISDELIVERYTOEXTERNALWAREHOUSEPLANNEDEXCLDUMMY_WK
, SUM(TOTALNUMPALLETSWITHISDELIVERYTOINTERNALWAREHOUSEPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISDELIVERYTOINTERNALWAREHOUSEPLANNEDEXCLDUMMY_WK
, SUM(TOTALNUMPALLETSWITHISDELIVERYTONONFOODWAREHOUSEPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISDELIVERYTONONFOODWAREHOUSEPLANNEDEXCLDUMMY_WK
, SUM(TOTALNUMPALLETSWITHISSTOCKTRANSFERPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISSTOCKTRANSFERPLANNEDEXCLDUMMY_WK
, SUM(TOTALNUMPALLETSWITHISRECEIVINGCROSSDOCKINGPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISRECEIVINGCROSSDOCKINGPLANNEDEXCLDUMMY_WK
, SUM(TOTALNUMPALLETSWITHISPICKINGCROSSDOCKINGPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISPICKINGCROSSDOCKINGPLANNEDEXCLDUMMY_WK
FROM FE_MSTR_LOGOP.V_QUINTIQ_REPORTEDKPI_SSBI SSBI
INNER JOIN DATA.T_CAL_CALENDARDAY CAL
    ON CAL.CAL_DT = SSBI.DELIVERY_DT
GROUP BY
  CLIENT_ID
, LIDL_COUNTRY
, SOURCE_SYSTEM
, WH_ID
, CY_WEEK
;