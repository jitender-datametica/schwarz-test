CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_QUINTIQ_DIMACHANGELOG(
   CLIENT_ID COMMENT 'CLIENT ID - CALCULATED BASED ON THE COUNTRY CODE' 
 , LIDL_COUNTRY COMMENT 'COUNTRY CODE. ORIGINAL FIELD NAME BIC_ZMLILA' 
 , SOURCE_SYSTEM COMMENT 'SOURCE SYSTEM' 
 , WH_ID COMMENT 'WAREHOUSE ID' 
 , CHANGED_ATTR COMMENT 'THE ATTRIBUTE THAT WAS CHANGED' 
 , CHANGE_TMSP COMMENT 'TIME WHEN THE OK BUTTON WAS PRESSED TO TRIGGER THE CHANGE' 
 , CHANGE_ID COMMENT 'COMBINATION OF ADDRESSFROM  TO  RESOURCETYPE AND TIMEPROFILE' 
 , NEW_VAL COMMENT 'THE NEW VALUE OF THE ATTRIBUTE' 
 , OLD_VAL COMMENT 'THE OLD VALUE OF THE ATTRIBUTE' 
 , USER_NR COMMENT 'EMPLOYEE NUMBER OF THE USER THAT MADE THE CHANGE' 
 , CHANGEDOBJECT COMMENT 'THE NAME OF THE OBJECT THAT WAS CHANGED (STAGINGDIMACELL OR STAGINGTOLLCELL)' 
 , DATASETNAME COMMENT 'THE NAME OF THE DATASET WHERE THIS CHANGE OCCURED' 
 , REASON COMMENT 'The given reason for this DiMa change'
 , DWH_LOAD_ID COMMENT 'LOAD ID' 
 , DWH_CREATED COMMENT 'RECORD CREATED AT' 
 , DWH_UPDATED COMMENT 'RECORD UPDATED AT' 
 , DWH_VALID_FROM COMMENT 'VALID FROM DATE' 
 , DWH_VALID_TO COMMENT 'VALID TO DATE' 
 , DELETED_FG COMMENT 'FLAG IF RECORD IS DELETED'
) COMMENT='QUINTIQ - PREPARED VIEW ON RAW DATA'
 AS 
SELECT
   CLIENT_ID
 , LIDL_COUNTRY
 , SOURCE_SYSTEM
 , WH_ID
 , CHANGED_ATTR
 , CHANGE_TMSP
 , CHANGE_ID
 , NEW_VAL
 , OLD_VAL
 , USER_NR
 , CHANGEDOBJECT
 , DATASETNAME
 , REASON
 , DWH_LOAD_ID
 , DWH_CREATED
 , DWH_UPDATED
 , DWH_VALID_FROM
 , DWH_VALID_TO
 , DELETED_FG
FROM DATA.T_QUINTIQ_DIMACHANGELOG;