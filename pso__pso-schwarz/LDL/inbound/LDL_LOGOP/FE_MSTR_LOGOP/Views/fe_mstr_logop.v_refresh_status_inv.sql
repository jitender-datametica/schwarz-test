CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_REFRESH_STATUS_INV(
	CLIENT_ID COMMENT 'Client id - calculated based on the country code',
	WH_ID COMMENT 'Warehouse id',
	INV_DWH_UPDATED COMMENT 'Latest update for T073 table per warehouse',
	INV_DWH_UPDATED_GLB COMMENT 'Latest refresh for T073 table per warehouse',
	INV_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T073 table per warehouse (in days)',
	INH_DWH_UPDATED COMMENT 'Latest update for T072 table per warehouse',
	INH_DWH_UPDATED_GLB COMMENT 'Latest refresh for T072 table per warehouse',
	INH_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T072 table per warehouse (in days)',
	STC_DWH_UPDATED COMMENT 'Latest update for T067 table per warehouse',
	STC_DWH_UPDATED_GLB COMMENT 'Latest refresh for T067 table per warehouse',
	STC_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T067 table per warehouse (in days)',
	DA_DWH_UPDATED COMMENT 'Latest update for SAPEWM Difference Analyzer per warehouse',
	DA_DWH_UPDATED_GLB COMMENT 'Latest refresh for SAPEWM Difference Analyzer per warehouse',
	DA_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for SAPEWM Difference Analyzer per warehouse (in days)',
	ACC_DWH_UPDATED COMMENT 'Latest update for T090 table per warehouse',
	ACC_DWH_UPDATED_GLB COMMENT 'Latest refresh for T090 table per warehouse',
	ACC_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T090 table per warehouse (in days)',
	BSD_DWH_UPDATED COMMENT 'Latest update for Bestandartikel table per warehouse',
	BSD_DWH_UPDATED_GLB COMMENT 'Latest refresh for Bestandartikel table per warehouse',
	BSD_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for Bestandartikel table per warehouse (in days)',
	SV_DWH_UPDATED COMMENT 'Latest update for T1001 table per warehouse',
	SV_DWH_UPDATED_GLB COMMENT 'Latest refresh for T1001 table per warehouse',
	SV_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T1001 table per warehouse (in days)',
	MI_DWH_UPDATED COMMENT 'Latest update for T178 table per warehouse',
	MI_DWH_UPDATED_GLB COMMENT 'Latest refresh for T178 table per warehouse',
	MI_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T178 table per warehouse (in days)',
	IS_DWH_UPDATED COMMENT 'Latest update for T117 table per warehouse',
	IS_DWH_UPDATED_GLB COMMENT 'Latest refresh for T117 table per warehouse',
	IS_UPDATE_STATUS COMMENT 'Time between Current Date and latest update for T117 table per warehouse (in days)'
) AS
WITH 

rwh AS (
SELECT
CLIENT_ID,
WH_ID
FROM FE_MSTR_LOGOP.V_REF_WH
),

t073 AS (
SELECT DISTINCT 
CLIENT_ID, 
CASE 
   WHEN CLIENT_ID=13 AND WH_ID = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_ID = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_ID = 20 THEN 22 ELSE WH_ID
   END AS WH_ID, 
MAX(MOD_DATE) OVER (PARTITION BY CLIENT_ID, WH_ID) AS INV_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS INV_DWH_UPDATED_GLB,
DATEDIFF('DAY', INV_DWH_UPDATED_GLB, CURRENT_DATE) AS INV_UPDATE_STATUS
FROM DATA.T_WAWI_INVENTORYDET
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
),

t072 AS (
SELECT DISTINCT 
CLIENT_ID, 
CASE 
   WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
   END AS WH_ID, 
MAX(MOD_DATE) OVER (PARTITION BY CLIENT_ID, WH_NR) AS INH_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_NR) AS INH_DWH_UPDATED_GLB,
DATEDIFF('DAY', INH_DWH_UPDATED_GLB, CURRENT_DATE) AS INH_UPDATE_STATUS
FROM DATA.T_WAWI_INVENTORY
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
),

t067 AS (
SELECT DISTINCT 
CLIENT_ID, 
CASE 
   WHEN CLIENT_ID=13 AND WH_ID = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_ID = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_ID = 20 THEN 22 ELSE WH_ID
   END AS WH_ID, 
MAX(MOD_DATE) OVER (PARTITION BY CLIENT_ID, WH_ID) AS STC_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS STC_DWH_UPDATED_GLB,
DATEDIFF('DAY', STC_DWH_UPDATED_GLB, CURRENT_DATE) AS STC_UPDATE_STATUS
FROM DATA.T_WAWI_STOCK_CORR
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
),

tEWMDA AS (
SELECT DISTINCT 
CLIENT_ID, 
WH_ID,
TO_TIMESTAMP(POSTED_DATE || ' ' || POSTED_TIME) AS POSTED_DATE_TMSP,
MAX(POSTED_DATE_TMSP) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DA_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DA_DWH_UPDATED_GLB,
DATEDIFF('DAY', DA_DWH_UPDATED_GLB, CURRENT_DATE) AS DA_UPDATE_STATUS
FROM DATA.T_SAPEWM_DIFFERENCEANALYZER
),

t090 AS (
SELECT DISTINCT
CLIENT_ID,
CASE 
   WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
   END AS WH_ID,
MAX(FORM_DT) OVER (PARTITION BY CLIENT_ID, WH_NR) AS ACC_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_NR) AS ACC_DWH_UPDATED_GLB,
DATEDIFF('DAY', ACC_DWH_UPDATED_GLB, CURRENT_DATE) AS ACC_UPDATE_STATUS
FROM DATA.T_WAWI_WHACCOUNT
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
AND FORM_TYPE IN (10, 11, 12, 40, 41, 44, 45, 46, 54, 55, 65, 80, 81, 130, 131, 135, 138, 140, 141, 145, 148, 150, 151, 160, 161)
AND DAY_END_DT BETWEEN '2024-03-01' AND CURRENT_DATE
),

bstd AS (
SELECT DISTINCT
CLIENT_ID,
CASE 
   WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
   END AS WH_ID,
MAX(DATUM) OVER (PARTITION BY CLIENT_ID, WH_NR) AS BSD_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_NR) AS BSD_DWH_UPDATED_GLB,
DATEDIFF('DAY', BSD_DWH_UPDATED_GLB, CURRENT_DATE) AS BSD_UPDATE_STATUS
FROM DATA.T_WAWI_BESTANDARTIKEL_ACT
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
),

t1001 AS (
SELECT DISTINCT
CLIENT_ID,
CASE 
   WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
   END AS WH_ID,
MAX(CAL_DT) OVER (PARTITION BY CLIENT_ID, WH_NR) AS SV_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_NR) AS SV_DWH_UPDATED_GLB,
DATEDIFF('DAY', SV_DWH_UPDATED_GLB, CURRENT_DATE) AS SV_UPDATE_STATUS
FROM DATA.T_WAWI_STOCK_VALUE
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
AND STOCK_AREA = 2
),

t178 AS (
SELECT DISTINCT
CLIENT_ID,
CASE 
   WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
   WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
   WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
   END AS WH_ID,
MAX(INS_DATE) OVER (PARTITION BY CLIENT_ID, WH_NR) AS MI_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_NR) AS MI_DWH_UPDATED_GLB,
DATEDIFF('DAY', MI_DWH_UPDATED_GLB, CURRENT_DATE) AS MI_UPDATE_STATUS
FROM DATA.T_WAWI_MISSING_ITEMS
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
AND MISSING_UNTIL IS NULL
AND STATUS < 40
),

t117 AS (
SELECT DISTINCT
CLIENT_ID,
CASE 
   WHEN CLIENT_ID=13 AND WAREHOUSENO = 600 THEN 60
   WHEN CLIENT_ID=18 AND WAREHOUSENO = 20 THEN 4
   WHEN CLIENT_ID=21 AND WAREHOUSENO = 20 THEN 22 ELSE WAREHOUSENO
   END AS WH_ID,
MAX(UPDATEDON) OVER (PARTITION BY CLIENT_ID, WAREHOUSENO) AS IS_DWH_UPDATED,
MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WAREHOUSENO) AS IS_DWH_UPDATED_GLB,
DATEDIFF('DAY', IS_DWH_UPDATED_GLB, CURRENT_DATE) AS IS_UPDATE_STATUS
FROM DATA.T_WAWI_ITEMSTATUS
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
--AND STATUS IN (1,2,3,4,13,14)
)

SELECT
a.CLIENT_ID
,a.WH_ID 
,b.INV_DWH_UPDATED
,b.INV_DWH_UPDATED_GLB 
,b.INV_UPDATE_STATUS
,c.INH_DWH_UPDATED
,c.INH_DWH_UPDATED_GLB 
,c.INH_UPDATE_STATUS 
,d.STC_DWH_UPDATED
,d.STC_DWH_UPDATED_GLB 
,d.STC_UPDATE_STATUS 
,e.DA_DWH_UPDATED
,e.DA_DWH_UPDATED_GLB
,e.DA_UPDATE_STATUS 
,f.ACC_DWH_UPDATED
,f.ACC_DWH_UPDATED_GLB 
,f.ACC_UPDATE_STATUS 
,g.BSD_DWH_UPDATED
,g.BSD_DWH_UPDATED_GLB 
,g.BSD_UPDATE_STATUS 
,h.SV_DWH_UPDATED
,h.SV_DWH_UPDATED_GLB
,h.SV_UPDATE_STATUS 
,i.MI_DWH_UPDATED
,i.MI_DWH_UPDATED_GLB
,i.MI_UPDATE_STATUS 
,j.IS_DWH_UPDATED
,j.IS_DWH_UPDATED_GLB
,j.IS_UPDATE_STATUS
FROM rwh a
LEFT JOIN t073 b ON
a.CLIENT_ID = b.CLIENT_ID
AND a.WH_ID = b.WH_ID
LEFT JOIN t072 c ON
a.CLIENT_ID = c.CLIENT_ID
AND a.WH_ID = c.WH_ID 
LEFT JOIN t067 d ON
a.CLIENT_ID = d.CLIENT_ID
AND a.WH_ID = d.WH_ID 
LEFT JOIN tEWMDA e ON
a.CLIENT_ID = e.CLIENT_ID
AND a.WH_ID = e.WH_ID 
LEFT JOIN t090 f ON
a.CLIENT_ID = f.CLIENT_ID
AND a.WH_ID = f.WH_ID
LEFT JOIN bstd g ON
a.CLIENT_ID = g.CLIENT_ID
AND a.WH_ID = g.WH_ID
LEFT JOIN t1001 h ON
a.CLIENT_ID = h.CLIENT_ID
AND a.WH_ID = h.WH_ID
LEFT JOIN t178 i ON
a.CLIENT_ID = i.CLIENT_ID
AND a.WH_ID = i.WH_ID
LEFT JOIN t117 j ON
a.CLIENT_ID = j.CLIENT_ID
AND a.WH_ID = j.WH_ID
;