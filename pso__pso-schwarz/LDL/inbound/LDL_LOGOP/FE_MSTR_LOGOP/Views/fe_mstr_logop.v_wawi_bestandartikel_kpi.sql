CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_WAWI_BESTANDARTIKEL_KPI(
    CLIENT_ID,
    WH_ID,
    ARTIKELNR,
	BEZ_LANG,
	BEZ_KURZ,
	DEUTSCHTEXT,
	ARTGRUPNR,
    ARTGRUPBEZ,
    ARTGRUPBEZ_EN,
    LPTYP,
    LPTYP_EN,
    AUTODISPO_FLG,
    WGI,
    WGI_EN,
    MENGE,
	RETAIL_PRICE,
    STATUS,
	BESTAND_DT,
    MISSING_UNTIL,
    WAMAS_REASON,
    DWH_VALID_FROM,
    DWH_VALID_TO,
    DWH_UPDATED,
    DELETED_FG,
    MISSING_FG
) COMMENT='WAWI - based on BESTANDARTIKEL table'
AS SELECT
	bes.CLIENT_ID
    ,bes.WH_ID
    ,bes.ARTIKELNR
	,lar.BEZ_LANG
	,lar.BEZ_KURZ
	,lar.DEUTSCHTEXT
	,lar.ARTGRUPNR
	,lar.ARTGRUPBEZ
	,lar.ARTGRUPBEZ_EN
	,lar.LPTYP
	,lar.LPTYP_EN
	,lar.AUTODISPO_FLG
	,lar.WGI
	,lar.WGI_EN
    ,bes.MENGE
	,bes.RETAIL_PRICE
    ,bes.STATUS
	,bes.DATUM AS BESTAND_DT
    ,bes.MISSING_UNTIL
    ,bes.WAMAS_REASON
    ,bes.DWH_VALID_FROM
    ,bes.DWH_VALID_TO
    ,bes.DWH_UPDATED
    ,bes.DELETED_FG
    ,bes.MISSING_FG
FROM FE_MSTR_LOGOP.V_WAWI_BESTANDARTIKEL bes
INNER JOIN FE_MSTR_LOGOP.V_LU_WAWI_ARTIKEL lar
	ON lar.client_id = bes.client_id
	AND lar.artikelnr = bes.artikelnr
;