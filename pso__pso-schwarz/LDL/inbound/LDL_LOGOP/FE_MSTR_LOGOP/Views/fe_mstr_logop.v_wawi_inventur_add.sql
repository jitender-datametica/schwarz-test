CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_WAWI_INVENTUR_ADD(
    CLIENT_ID COMMENT 'Client id - calculated based on the country code',
    WH_ID COMMENT 'Warehouse id',
    ARTIKELNR COMMENT 'Item nr',
	FORM_NR COMMENT 'T067 Form nr',
    REPORTED_DATE COMMENT 'T067 = T072 Date',
    REASON_ID COMMENT 'T067 Reason id',
	REASON_DESC COMMENT 'T067 Reason for inventory change',
	CHARGE COMMENT 'T067 Charge',
	MOD_USER COMMENT 'T067 User who made changes',
    PIECE_QTY COMMENT 'T067 Piece quantity',
    PIECE_QTY_NEG COMMENT 'T067 Summe negierte Piece QTY auf Ebene „C067 Itemnumber“ und „C076 Formdate“ mit Filter„C067 Reason ID“ = 3',
    PIECE_QTY_POS COMMENT 'T067 Summe Piece QTY auf Ebene der „C067 Itemnumber“ und „C076 Formdate“ mit Filter „C067 Reason ID“ = 4',
    INVENTORYNUM COMMENT 'T073 Inventory nr',
    INVENTORYDESC COMMENT 'T073 Inventory desc',
    INVENTORYTYPE COMMENT 'T072 Inventory type',
    EXP_QTY COMMENT 'T073 INV Expected Qty. (PC)',
    GES_QTY COMMENT 'T073 INV Counted Qty. (PC)',
    DIFF_QTY COMMENT 'T073 INV Difference Qty.',
    DWH_LOAD_ID COMMENT 'Load id',
    DWH_CREATED COMMENT 'Record created at',
    DWH_UPDATED COMMENT 'Record updated at',
    DWH_VALID_FROM COMMENT 'Valid from date',
    DWH_VALID_TO COMMENT 'Valid to date',
    DELETED_FG COMMENT 'Flag if record is deleted'
) AS
WITH 
-- Stock Corrections Reference
lustock AS (
    SELECT
        CLIENT_ID,
        CASE 
            WHEN CLIENT_ID=13 AND WH_ID = 600 THEN 60
            WHEN CLIENT_ID=18 AND WH_ID = 20 THEN 4
            WHEN CLIENT_ID=21 AND WH_ID = 20 THEN 22 ELSE WH_ID
            END AS WH_ID,
        ITEM_NR AS ARTIKELNR,
		FORM_NR,
        FORM_DATE AS T067_FORM_DATE,
        REASON_ID AS T067_REASON_ID,
		REASON_DESC AS T067_REASON_DESC,
		CHARGE AS T067_CHARGE,
		MOD_USER AS T067_MOD_USER,
        (CASE_QTY*DECIMAL_CASE)+PIECE_QTY AS T067_PIECE_QTY,
        CASE WHEN REASON_ID IN (1,2,3) THEN T067_PIECE_QTY ELSE 0 END AS T067_PIECE_QTY_NEG,
        CASE WHEN REASON_ID = 4 THEN T067_PIECE_QTY ELSE 0 END AS T067_PIECE_QTY_POS,
        DWH_LOAD_ID,
        DWH_CREATED,
        MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED,
        DWH_VALID_FROM,
        DWH_VALID_TO,
        DELETED_FG
    FROM "DATA".T_WAWI_STOCK_CORR
    WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
      AND DELETED_FG = 'FALSE'
	  AND T067_FORM_DATE > '2024-03-01'
      --AND SCN <> 0 
),
-- Inventory Details Reference
luinvdet AS (
	SELECT
	CLIENT_ID
	,WH_ID
	,ARTIKELNR
    ,FORM_NR
	,INVENTORYNUM
	,INVENTORYTYPE	
	,T072_DATE
	,T073_EXP_QTY 
	,T073_GES_QTY
	,T073_DIFF_QTY
	,DWH_LOAD_ID
	,DWH_CREATED
	,DWH_UPDATED
	,DWH_VALID_FROM
	,DWH_VALID_TO
	,DELETED_FG
FROM FE_MSTR_LOGOP.V_WAWI_INVENTORYDET
)
SELECT
    lui.CLIENT_ID,
    lui.WH_ID,
    lui.ARTIKELNR,
	lui.FORM_NR,
    lui.T072_DATE AS REPORTED_DATE,
    NULL AS REASON_ID,
	NULL AS REASON_DESC,
	NULL AS CHARGE,
	NULL AS MOD_USER,
    NULL AS PIECE_QTY,
    NULL AS PIECE_QTY_NEG,
    NULL AS PIECE_QTY_POS,
    lui.INVENTORYNUM,
    CONCAT('INV', ' ', TO_VARCHAR(lui.INVENTORYNUM)) AS INVENTORYDESC,
    lui.INVENTORYTYPE,
    lui.T073_EXP_QTY AS EXP_QTY,
    lui.T073_GES_QTY AS GES_QTY,
    lui.T073_DIFF_QTY AS DIFF_QTY,
    lui.DWH_LOAD_ID,
    lui.DWH_CREATED,
    lui.DWH_UPDATED,
    lui.DWH_VALID_FROM,
    lui.DWH_VALID_TO,
    lui.DELETED_FG
FROM luinvdet lui
UNION
SELECT
    lus.CLIENT_ID,
    lus.WH_ID,
    lus.ARTIKELNR,
	lus.FORM_NR,
    lus.T067_FORM_DATE AS REPORTED_DATE,
    lus.T067_REASON_ID AS REASON_ID,
	lus.T067_REASON_DESC AS REASON_DESC,
	lus.T067_CHARGE AS CHARGE,
	lus.T067_MOD_USER AS MOD_USER,
    lus.T067_PIECE_QTY AS PIECE_QTY,
    lus.T067_PIECE_QTY_NEG AS PIECE_QTY_NEG,
    lus.T067_PIECE_QTY_POS AS PIECE_QTY_POS,
    NULL AS INVENTORYNUM,
    NULL AS INVENTORYDESC,
    NULL AS INVENTORYTYPE,
    NULL AS EXP_QTY,
    NULL AS GES_QTY,
    NULL AS DIFF_QTY,
    lus.DWH_LOAD_ID,
    lus.DWH_CREATED,
    lus.DWH_UPDATED,
    lus.DWH_VALID_FROM,
    lus.DWH_VALID_TO,
    lus.DELETED_FG
FROM lustock lus
;