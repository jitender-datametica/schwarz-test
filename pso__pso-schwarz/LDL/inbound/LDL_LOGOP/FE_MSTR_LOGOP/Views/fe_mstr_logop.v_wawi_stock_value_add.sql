CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_WAWI_STOCK_VALUE_ADD(
	CLIENT_ID COMMENT 'Client id - calculated based on the country code',
	WH_ID COMMENT 'Warehouse id',
	ARTIKELNR COMMENT 'Item nr',
	REPORTED_DATE COMMENT 'T1001 Date',
	PIECEQTY_CAL COMMENT 'Stock Expected',
	PIECEQTY_REAL COMMENT 'Stock Counted',
	PIECEQTY_DIFF COMMENT 'Stock Difference',
	RETAIL_PRICE COMMENT 'Retail Price from Bestandartikel',
	DWH_LOAD_ID COMMENT 'Load id',
	DWH_CREATED COMMENT 'Record created at',
	DWH_UPDATED COMMENT 'Record updated at',
	DWH_VALID_FROM COMMENT 'Valid from date',
	DWH_VALID_TO COMMENT 'Valid to date',
	DELETED_FG COMMENT 'Flag if record is deleted'
) AS
WITH vastock AS (
	SELECT
	  vas.CLIENT_ID
	 ,vas.WH_NR 
	 ,vas.ITEMNR
	 ,vas.CAL_DT
	 ,vas.PIECEQTY_CAL
	 ,vas.PIECEQTY_REAL
	 ,bes.RETAIL_PRICE
	 ,vas.DWH_LOAD_ID
	 ,vas.DWH_CREATED
     ,vas.DWH_UPDATED
	 ,vas.DWH_VALID_FROM
	 ,vas.DWH_VALID_TO
	 ,vas.DELETED_FG
FROM DATA.T_WAWI_STOCK_VALUE vas
INNER JOIN DATA.T_WAWI_BESTANDARTIKEL_ACT bes
		ON bes.CLIENT_ID = vas.CLIENT_ID
		AND bes.WH_NR = vas.WH_NR
		AND bes.ARTIKELNR = vas.ITEMNR
	WHERE CURRENT_DATE BETWEEN vas.DWH_VALID_FROM AND vas.DWH_VALID_TO
		AND vas.DELETED_FG = 0
		AND vas.CAL_DT >= DATEADD(DAY, -28, CURRENT_DATE())
		AND vas.STOCK_AREA = 2		
	)
SELECT
	  CLIENT_ID
	 ,CASE 
            WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
            WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
            WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
            END AS 
         WH_ID
	 ,ITEMNR AS ARTIKELNR
	 ,DATE_TRUNC('Day',CAL_DT) AS REPORTED_DATE
	 ,ZEROIFNULL(PIECEQTY_CAL)
	 ,ZEROIFNULL(PIECEQTY_REAL)
	 ,ZEROIFNULL(PIECEQTY_CAL)-ZEROIFNULL(PIECEQTY_REAL) AS PIECEQTY_DIFF
	 ,RETAIL_PRICE
	 ,DWH_LOAD_ID
	 ,DWH_CREATED
     ,MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED
	 ,DWH_VALID_FROM
	 ,DWH_VALID_TO
	 ,DELETED_FG
FROM vastock 
;