CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_ZFM_BOOKING_QUOTA(
	CLIENT_ID COMMENT 'Client id - calculated based on the country code',
	WH_ID COMMENT 'Warehouse ID. Subset of Warehouse Number (lagernummer)',
	BOOKING_DATE COMMENT 'Date of booking',
	COUNT_PAL_EWM_REC COMMENT 'Number of Pallets for EWM_ZFM Received',
	COUNT_PAL_EWM_DEC COMMENT 'Number of Pallets for EWM_ZFM Declined',
	COUNT_EP_ZFM COMMENT 'Number of Pallets for ZFM',
	COUNT_DD_ZFM COMMENT 'Number of Pallets for ZFM',
	COUNT_BOOKING_GR_ZFM COMMENT 'Count of signed out bookings ZFM',
	COUNT_BOOKING_GR_WAWI COMMENT 'Count of signed out bookings WAWI',
	COUNT_EP_WAWI COMMENT 'Number of Pallets for ZFM from WAWI',
	COUNT_DD_WAWI COMMENT 'Number of Pallets for ZFM from WAWI',
	WAWI_PALLETS COMMENT 'Calculation for WAWI Pallets',
	EWM_PALLETS COMMENT 'Calculation for EWM Pallets',
	BOOKING_TRUCKS COMMENT 'Calculation for EWM Pallets'
) AS
WITH ZFM_PALLETS AS
(SELECT 
	b.client_id
	,b.wh_id
	,b.booking_date
	,SUM(CASE WHEN b.deleted = FALSE THEN bo.ep_count ELSE 0 END) AS COUNT_EP_ZFM
	,SUM(CASE WHEN b.deleted = FALSE THEN bo.dd_count ELSE 0 END)/2 AS COUNT_DD_ZFM
	,COUNT(DISTINCT CASE WHEN b.deleted = FALSE THEN b.booking_id ELSE NULL END ) AS count_booking_GR
	 FROM "DATA".t_zfm_bookings b
	 LEFT JOIN "DATA".T_ZFM_BOOKINGORDERS bo
	 ON b.client_id = bo.client_id
	 AND b.booking_id = bo.booking_id
	 WHERE b.deleted_fg = FALSE 
	 AND CURRENT_DATE BETWEEN b.dwh_valid_from AND b.dwh_valid_to
	 AND bo.deleted_fg = FALSE 
	 AND CURRENT_DATE BETWEEN bo.dwh_valid_from AND bo.dwh_valid_to
	 GROUP BY ALL)
, RECEIVED AS (
SELECT
client_id,
wh_id,
confirmed_date AS BOOKING_DATE,
--NLENR,
COUNT(TANUM) AS COUNT_PAL_EWM_REC
FROM DATA.T_SAPEWM_WAREHOUSETASK
WHERE tostat = 'C' AND TRART = 5 AND DOCNO LIKE '41%'
GROUP BY ALL)
,DECLINED AS (
SELECT
client_id,
wh_id,
confirmed_date AS BOOKING_DATE,
--VLENR,
COUNT(TANUM) AS COUNT_PAL_EWM_DEC
FROM DATA.T_SAPEWM_WAREHOUSETASK
WHERE tostat = 'C' AND TRART = 6 AND DOCNO LIKE '41%' AND EXCCODE LIKE 'Z%'
GROUP BY ALL)
,EWM_PALLETS AS 
(SELECT REC.CLIENT_ID,REC.WH_ID, REC.BOOKING_DATE, REC.COUNT_PAL_EWM_REC, DEC.COUNT_PAL_EWM_DEC
FROM RECEIVED REC
JOIN DECLINED DEC 
ON rec.client_id = DEC.client_id
AND rec.wh_id = DEC.wh_id
AND rec.BOOKING_DATE = DEC.BOOKING_DATE
GROUP BY ALL)
,WAWI_PALLETS AS 
(SELECT
CLIENT_ID,
WH_NR AS WH_ID,
DATE(MOD_DATE) AS BOOKING_Date,
COUNT(DISTINCT CASE WHEN task_status = 99 THEN task_id ELSE NULL END) AS COUNT_BOOKING_GR,
SUM(CASE WHEN task_status = 99 THEN pal_eu_goods ELSE 0 END) AS count_ep_wawi,
SUM(CASE WHEN task_status = 99 THEN pal_dd_goods ELSE 0 END)/2 AS count_dd_wawi
FROM "DATA".T_WAWI_GINTASKS
WHERE deleted_fg = FALSE 
AND CURRENT_DATE BETWEEN dwh_valid_from AND dwh_valid_to
GROUP BY ALL)
,EWM_BOOKINGS AS
(WITH BASE AS(
SELECT -- Step 1 
client_id,
wh_id,
confirmed_date AS BOOKING_DATE,
NLENR,
docno
FROM DATA.T_SAPEWM_WAREHOUSETASK
WHERE tostat = 'C' AND TRART IN (5,6) AND DOCNO LIKE '41%'
GROUP BY ALL
MINUS 
SELECT -- Step 2
client_id,
wh_id,
confirmed_date AS BOOKING_DATE,
VLENR,
docno
FROM DATA.T_SAPEWM_WAREHOUSETASK 
WHERE tostat = 'C' AND TRART = 6 AND DOCNO LIKE '41%'
AND EXCCODE LIKE 'Z%'
GROUP BY ALL)
SELECT COUNT(DISTINCT tu_num_ext) AS COUNT_BOOKING_GR_EWM, a.client_id, a.wh_id, a.booking_date FROM BASE A 
LEFT JOIN DATA.T_SAPEWM_INBOUNDDELIVERYHEADER B -- Step 3 = (Step 1 – Step 2) + Inboundeliveryheader
ON a.client_id = b.client_id 
AND a.wh_id = b.Wh_id 
AND a.DOCNO =  b.docno_h
GROUP BY 
a.client_id,
a.wh_id,
a.booking_date)
SELECT
 ZFM.CLIENT_ID
,ZFM.WH_ID
,ZFM.BOOKING_DATE
,EWM.COUNT_PAL_EWM_REC
,EWM.COUNT_PAL_EWM_DEC
,ZFM.COUNT_EP_ZFM
,ZFM.COUNT_DD_ZFM
,ZFM.COUNT_BOOKING_GR
,WAWI.COUNT_BOOKING_GR
,WAWI.COUNT_EP_WAWI
,WAWI.COUNT_DD_WAWI
,ZEROIFNULL((ZFM.COUNT_EP_ZFM + ZFM.COUNT_DD_ZFM) / NULLIF((WAWI.COUNT_EP_WAWI + WAWI.COUNT_DD_WAWI),0))
,ZEROIFNULL((ZFM.COUNT_EP_ZFM + ZFM.COUNT_DD_ZFM) / NULLIF((EWM.COUNT_PAL_EWM_REC - EWM.COUNT_PAL_EWM_DEC),0))
,IFF(WAWI.COUNT_BOOKING_GR IS NOT NULL, ZFM.COUNT_BOOKING_GR / NULLIF(WAWI.COUNT_BOOKING_GR, 0), IFF(EWMB.COUNT_BOOKING_GR_EWM IS NOT NULL, ZFM.COUNT_BOOKING_GR / NULLIF(EWMB.COUNT_BOOKING_GR_EWM, 0), NULL))
FROM ZFM_PALLETS ZFM
LEFT JOIN EWM_PALLETS EWM
ON ZFM.CLIENT_ID = EWM.CLIENT_ID 
AND ZFM.BOOKING_DATE = EWM.BOOKING_DATE 
AND ZFM.WH_ID = EWM.WH_ID
LEFT JOIN WAWI_PALLETS WAWI
ON ZFM.CLIENT_ID = WAWI.CLIENT_ID 
AND ZFM.BOOKING_DATE = WAWI.BOOKING_DATE 
AND ZFM.WH_ID = WAWI.WH_ID
LEFT JOIN EWM_BOOKINGS EWMB
ON ZFM.CLIENT_ID = EWMB.CLIENT_ID 
AND ZFM.BOOKING_DATE = EWMB.BOOKING_DATE 
AND ZFM.WH_ID = EWMB.WH_ID;