	ITEMPROPID NUMBER(38,0) NOT NULL,
	DAYWHID NUMBER(38,0) NOT NULL,
	LORRYNO NUMBER(38,0) NOT NULL,
	VERSIONID NUMBER(38,0) NOT NULL,
	CORRTYPEID NUMBER(38,0),
	ELMSTATUS NUMBER(38,0),
	CHANGEDATE DATE,
	CHANGEUSER NUMBER(38,0),
	ORDER_REFERENCE VARCHAR(250),
	WAWIPURCHASEORDERID VARCHAR(250),
	ORDER_NUMBER NUMBER(38,0),
	ORDER_POSITION NUMBER(38,0),
	ORDERQUANTITY NUMBER(38,10),
	DWH_CREATED_TMSP TIMESTAMP_LTZ(9) NOT NULL COMMENT 'The point in time when this record was created in the data warehouse.',
	DWH_UPDATED_TMSP TIMESTAMP_LTZ(9) NOT NULL COMMENT 'The point in time when this record was created or last updated.',
