CREATE OR REPLACE VIEW FE_MSTR_SCM.V_BUSYEAR_MONTH_WEEK(
	 LAND
	,CLIENT_ID
	,BA_NR
	,IAN
	,BUSYEAR
	,START_MONTH
	,END_MONTH
	,CAL_MONTH
	,CY_MONTH_SEQ
	,CAL_WEEK
) AS
 (
SELECT
    LAND
    ,CLIENT.CLIENT_ID
	,BA_NR
	,IAN
	,BUSYEAR
	,START_MONTH
	,END_MONTH
	,CY_MONTH
	,CY_MONTH_SEQUENCE
	,CY_WEEK
FROM
       CORE_REL.V_BUSYEAR_MONTH_WEEK CAL
    INNER JOIN CORE.V_CLIENT CLIENT ON (CAL.LAND=CLIENT.COUNTRY_CD)
   )
;