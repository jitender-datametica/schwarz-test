CREATE OR REPLACE VIEW FE_MSTR_APOLLO_KAUFLAND.V_FACT_KFL_GTP_ITEM_ADVERTISE_DAY
(
 LOB_CD
,KFL_CLIENT_ID
,KFL_GTP_NR
,KFL_GTP_SUBSIDIARY_TYPE_ID
,KFL_ITEM_NR
,CAL_WEEK
,KFL_ADV_PERIOD_TYPE_ID
,CURR_CD
,ADV_DT
,KFL_ADV_WEEK
,KFL_ADJUST_ADV_SALES_7_QTY
,KFL_ADV_STOCK_QTY
,KFL_GTP_CNT
,LDL_ADJUST_ADV_SALES_7_QTY
,LDL_ADV_STOCK_QTY
,LDL_GTP_CNT
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
)
AS
SELECT
 LOB_CD
,KFL_CLIENT_ID
,KFL_GTP_NR
,KFL_GTP_SUBSIDIARY_TYPE_ID
,CASE WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID = 1 THEN (KFL_ITEM_NR / 100)::INTEGER
      WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID > 1 THEN (KFL_ITEM_NR / 10)::INTEGER
      WHEN lob_cd = 'LDL' THEN (KFL_ITEM_NR / 100)::INTEGER ELSE NULL
      END AS KFL_ITEM_NR
,CAL_WEEK
,KFL_ADV_PERIOD_TYPE_ID
,CURR_CD
,ADV_DT
,KFL_ADV_WEEK
,KFL_ADJUST_ADV_SALES_7_QTY
,KFL_ADV_STOCK_QTY
,KFL_GTP_CNT
,LDL_ADJUST_ADV_SALES_7_QTY
,LDL_ADV_STOCK_QTY
,LDL_GTP_CNT
--AP0219535/SPEC0270105 neue Spalte für Posten KZ aufgenommen / sschuecke 26.09.2024
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
FROM CORE.T_FACT_KFL_GTP_ITEM_ADVERTISE_DAY;