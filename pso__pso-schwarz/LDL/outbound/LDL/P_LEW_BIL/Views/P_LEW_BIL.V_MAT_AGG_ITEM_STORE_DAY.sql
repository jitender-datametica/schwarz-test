CREATE OR REPLACE VIEW ldl_p_lew_bil.v_mat_agg_item_store_day (client_id, loc_sid_store, src_orig_store_nr, src_wh_id,
dwh_cal_dt, cy_month, item_sid, retail_val, retail_net_val, qty_act, diff_inv_stc_calc_cnt, diff_inv_stc_calc_val,
diff_inv_stc_calc_net_val, diff_inv_return_qty, diff_inv_return_val, diff_inv_return_net_val, abs_val, net_abs_val,
pr_diff_del_val, pr_diff_net_del_val, pr_diff_return_val, pr_diff_net_return_val, pv_val, net_pv_val, claim_val,
claim_net_val, retail_fa_val, retail_net_fa_val, return_fa_val, return_net_fa_val, qty_piece_fa, qty_return_fa,
diff_inv_stc_calc_cnt_fa, diff_inv_stc_calc_val_fa, diff_inv_stc_calc_net_val_fa, diff_inv_return_fa_qty,
diff_inv_return_fa_val, diff_inv_return_net_fa_val, abs_fa_val, net_abs_fa_val, pr_diff_fa_del_val,
pr_diff_net_fa_del_val, pr_diff_fa_return_val, pr_diff_net_fa_return_val, pv_fa_val, net_pv_fa_val, claim_fa_val,
claim_net_fa_val, dwh_updated) AS SELECT COALESCE(rtl_inv.client_id, RTRN.client_id) AS client_id,
 COALESCE(rtl_inv.loc_sid_store, RTRN.loc_sid_store) AS loc_sid_store,
 COALESCE(rtl_inv.src_orig_store_nr, RTRN.src_orig_store_nr) AS src_orig_store_nr,
 COALESCE(rtl_inv.src_wh_id, RTRN.src_wh_id) AS src_wh_id,
 COALESCE(rtl_inv.dwh_cal_dt, RTRN.dwh_cal_dt) AS dwh_cal_dt,
 COALESCE(rtl_inv.cy_month, RTRN.cy_month) AS cy_month,
 COALESCE(rtl_inv.item_sid, RTRN.item_sid) AS item_sid,
 COALESCE(rtl_inv.retail_val, 0) AS retail_val,
 COALESCE(rtl_inv.retail_net_val, 0) AS retail_net_val,
 COALESCE(rtl_inv.qty_act, 0) AS qty_act,
 COALESCE(rtl_inv.diff_inv_stc_calc_cnt, 0) AS diff_inv_stc_calc_cnt,
 COALESCE(rtl_inv.diff_inv_stc_calc_val, 0) AS diff_inv_stc_calc_val,
 COALESCE(rtl_inv.diff_inv_stc_calc_net_val, 0) AS diff_inv_stc_calc_net_val,
 COALESCE(RTRN.ship_qty, 0) AS diff_inv_return_qty,
 COALESCE(RTRN.gross_val, 0) AS diff_inv_return_val,
 COALESCE(RTRN.sales_net_val, 0) AS diff_inv_return_net_val,
 0 AS abs_val,
 0 AS net_abs_val,
 0 AS pr_diff_del_val,
 0 AS pr_diff_net_del_val,
 0 AS pr_diff_return_val,
 0 AS pr_diff_net_return_val,
 0 AS pv_val,
 0 AS net_pv_val,
 0 AS claim_val,
 0 AS claim_net_val,
 0 AS retail_fa_val,
 0 AS retail_net_fa_val,
 0 AS return_fa_val,
 0 AS return_net_fa_val,
 0 AS qty_piece_fa,
 0 AS qty_return_fa,
 0 AS diff_inv_stc_calc_cnt_fa,
 0 AS diff_inv_stc_calc_val_fa,
 0 AS diff_inv_stc_calc_net_val_fa,
 0 AS diff_inv_return_fa_qty,
 0 AS diff_inv_return_fa_val,
 0 AS diff_inv_return_net_fa_val,
 0 AS abs_fa_val,
 0 AS net_abs_fa_val,
 0 AS pr_diff_fa_del_val,
 0 AS pr_diff_net_fa_del_val,
 0 AS pr_diff_fa_return_val,
 0 AS pr_diff_net_fa_return_val,
 0 AS pv_fa_val,
 0 AS net_pv_fa_val,
 0 AS claim_fa_val,
 0 AS claim_net_fa_val,
 CURRENT_TIMESTAMP() AS dwh_updated
FROM (SELECT COALESCE(RTL.client_id, INV.client_id) AS client_id,
   COALESCE(RTL.loc_sid_store, INV.loc_sid_store) AS loc_sid_store,
   COALESCE(RTL.src_orig_store_nr, INV.src_orig_store_nr) AS src_orig_store_nr,
   COALESCE(RTL.src_wh_id, INV.src_wh_id) AS src_wh_id,
   COALESCE(RTL.dwh_cal_dt, INV.dwh_cal_dt) AS dwh_cal_dt,
   COALESCE(RTL.cy_month, INV.cy_month) AS cy_month,
   COALESCE(RTL.item_sid, INV.item_sid) AS item_sid,
   COALESCE(RTL.retail_val, 0) AS retail_val,
   COALESCE(RTL.retail_net_val, 0) AS retail_net_val,
   COALESCE(RTL.qty_act, 0) AS qty_act,
   COALESCE(INV.inv_diff_total_piece, 0) AS diff_inv_stc_calc_cnt,
   COALESCE(INV.inv_diff_total_val, 0) AS diff_inv_stc_calc_val,
   COALESCE(INV.inv_diff_total_net_val, 0) AS diff_inv_stc_calc_net_val
  FROM ldl_p_lew_bil.t_agg_sales_retail_item_store_day AS RTL
   FULL JOIN ldl_p_lew_bil.t_agg_inv_item_store_day AS INV ON RTL.client_id = INV.client_id AND RTL.loc_sid_store = INV
        .loc_sid_store AND RTL.item_sid = INV.item_sid AND RTL.dwh_cal_dt = INV.dwh_cal_dt AND RTL.src_wh_id = INV.src_wh_id
     ) AS rtl_inv
 FULL JOIN ldl_p_lew_bil.t_agg_inv_return_item_store_day AS RTRN ON rtl_inv.client_id = RTRN.client_id AND rtl_inv.loc_sid_store
       = RTRN.loc_sid_store AND rtl_inv.item_sid = RTRN.item_sid AND rtl_inv.dwh_cal_dt = RTRN.dwh_cal_dt AND rtl_inv.src_wh_id
    = RTRN.src_wh_id;