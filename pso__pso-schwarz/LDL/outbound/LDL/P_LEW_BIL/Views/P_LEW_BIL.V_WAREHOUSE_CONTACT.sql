CREATE OR REPLACE VIEW ldl_p_lew_bil.v_warehouse_contact AS SELECT LCTN.client_id,
 LCTN.loc_sid_wh,
 LCTN.src_wh_id,
 LCTN.addr_sid,
 ADDR.lang_sid,
 ADDR.country_pol_sid,
 ADDR.lang_cd,
 ADDR.country_pol_cd,
 ADDR.name1,
 ADDR.name2,
 ADDR.name3,
 ADDR.sort1,
 ADDR.street,
 ADDR.house_number1,
 ADDR.house_number2,
 ADDR.city,
 ADDR.postbox,
 ADDR.zip_code,
 ADDR.phone_number,
 ADDR.fax_number,
 LCTN.dwh_valid_from,
 LCTN.dwh_valid_to,
 LCTN.dwh_actual_fg,
 LCTN.active_fg,
 LCTN.active_future_fg,
 LCTN.global_loc_id_length,
 LCTN.global_loc_type_cd,
   ADDR.street || ' ' || ADDR.house_number1 AS street_number
FROM ldl_p_lew_bil.v_warehouse AS LCTN
 INNER JOIN ldl_p_lew_core_ac.v_address AS ADDR ON LCTN.addr_sid = ADDR.addr_sid AND LCTN.client_id = ADDR.client_id;