    PRIMARY KEY: probably use -client_id */
CREATE OR REPLACE VIEW ldl_p_lew_mart_pit_onprem.v_pit_item AS SELECT client_id,
 dwh_cal_dt,
 cy_year,
 cy_month,
 iso_year_week,
 adv_week_id,
 lang_sid,
 weekday_nr,
 weekday_descr,
 weekday_sdescr,
 dwh_cal_dt_ldescr,
 cy_month_descr,
 item_sid,
 item_mstr_sid,
 item_fam_grp_sid AS uwg_af_sid,
 brand_sid,
 sub_item_grp_sid AS uwg_sid,
 item_grp_int_sid AS wgi_sid,
 orig_item_nr,
 item_descr_int,
 item_descr AS item_descr_loc,
 item_variant_descr_int,
 item_variant_descr AS item_variant_descr_loc,
 src_familygrp_id AS uwg_af_id,
 src_familygrp_cd AS uwg_af_cd,
 src_familygrp_cd AS uwg_af_desc,
 item_fam_grp_name AS uwg_af_desc_int,
 item_fam_grp_descr AS uwg_af_desc_loc,
 src_subitemgrp_id AS uwg_id,
 src_subitemgrp_cd AS uwg_cd,
 sub_item_grp_name AS uwg_desc_int,
 src_itemgrp_int_id AS wgi_id,
 src_itemgrp_int_cd AS wgi_cd,
 item_grp_int_name AS wgi_desc_int,
 item_grp_int_descr AS wgi_desc_loc,
 brand_name_int,
 brand_descr,
 buying_list_type_id,
 buying_list_type_descr,
 buying_list_type_group_id,
 buying_list_type_group_descr,
 listing_type_id,
 listing_type_descr,
 listing_type_group_id,
 listing_type_group_descr,
 listing_fg,
 action_type_id,
 marke_em_descr,
 case_size,
 marke_fg,
 em_fg
FROM ldl_p_lew_mart_pit_onprem.v_pit_item_client_day_current AS ITM
WHERE client_id IN (SELECT DISTINCT client_id
   FROM ldl_p_lew_mart_pit_onprem.t_pit_clients)
UNION ALL
SELECT client_id,
 DATE '9999-12-31' AS dwh_cal_dt,
 - 2 AS cy_year,
 - 2 AS cy_month,
 - 2 AS iso_year_week,
 - 2 AS adv_week_id,
 - 2 AS lang_sid,
 - 2 AS weekday_nr,
 'TOT' AS weekday_descr,
 'TT' AS weekday_sdescr,
 'TOT' AS dwh_cal_dt_ldescr,
 'TOT' AS cy_month_descr,
 - 2 AS item_sid,
   - 2 * 100 + client_id AS item_mstr_sid,
 - 2 AS uwg_af_sid,
 - 2 AS brand_sid,
 - 2 AS uwg_sid,
 - 2 AS wgi_sid,
 - 2 AS orig_item_nr,
 'TOT' AS item_descr_int,
 'TOT' AS item_descr_loc,
 'TOT' AS item_variant_descr_int,
 'TOT' AS item_variant_descr_loc,
 - 2 AS uwg_af_id,
 'TOT' AS uwg_af_cd,
 'TOT' AS uwg_af_desc,
 'TOT' AS uwg_af_desc_int,
 'TOT' AS uwg_af_desc_loc,
 - 2 AS uwg_id,
 'TOT' AS uwg_cd,
 'TOT' AS uwg_desc_int,
 - 2 AS wgi_id,
 'TOT' AS wgi_cd,
 'TOT' AS wgi_desc_int,
 'TOT' AS wgi_desc_loc,
 'TOT' AS brand_name_int,
 'TOT' AS brand_descr,
 - 2 AS buying_list_type_id,
 'TOT' AS buying_list_type_descr,
 - 2 AS buying_list_type_group_id,
 'TOT' AS buying_list_type_group_descr,
 - 2 AS listing_type_id,
 'TOT' AS listing_type_descr,
 - 2 AS listing_type_group_id,
 'TOT' AS listing_type_group_descr,
 0 AS listing_fg,
 - 2 AS action_type_id,
 'TOT' AS marke_em_descr,
 - 2 AS case_size,
 0 AS marke_fg,
 0 AS em_fg
FROM (SELECT DISTINCT client_id
  FROM ldl_p_lew_mart_pit_onprem.t_pit_clients) AS Clients;