CREATE OR REPLACE VIEW ldl_p_lew_precore.v_location_map_key AS SELECT LOC.client_id,
 LOC.loc_sid,
 LOC.src_werks,
 LOC.src_orig_store_nr,
 LOC.src_orig_wh_nr,
 LOC.src_store_id,
 LOC.src_wh_id,
 LOC.loc_name,
 LOC.loc_name2,
 LOC.loc_sid_successor_act,
 LOC.country_pol_sid,
 LOC.country_pol_cd,
 LOC.wh_store_mark,
 LOC.wh_store_label,
 LOC.storetype_mark,
 LOC.storetype_label,
 LOC.customer_cd,
 LOC.global_loc_ctry_cd,
 LOC.global_loc_id,
 LOC.global_loc_id_length,
 LOC.global_loc_type_cd,
 LOC.opening_dt,
 LOC.real_opening_dt,
 LOC.closing_dt,
 LOC.longitude,
 LOC.latitude,
 LOC.sap_creation_wrf1_dt,
 LOC.dwh_load_id,
 LOC.dwh_created,
 LOC.dwh_updated
FROM ldl_p_lew_core_ac.v_location AS LOC
 INNER JOIN ldl_p_lew_core_ac.v_location_hist AS LOC_HIST ON LOC.loc_sid = LOC_HIST.loc_sid
WHERE LOC.wh_store_label = 'Store'
 AND CURRENT_DATE BETWEEN LOC_HIST.dwh_valid_from AND LOC_HIST.dwh_valid_to;