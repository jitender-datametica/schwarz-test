-- Report month
 SELECT X.business_year,
 X.booking_month,
 X.warehouse_nr,
 X.cost_center,
 X.hours_external_lj,
 X.hours_external_vj
FROM (SELECT COALESCE(LJ.business_year, VJ.business_year + 1) AS business_year,
   COALESCE(LJ.booking_month, VJ.booking_month + 100) AS booking_month,
    CASE
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '10'
    THEN 1
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '20'
    THEN 2
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '30'
    THEN 3
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '31'
    THEN 3
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '40'
    THEN 4
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '41'
    THEN 4
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '50'
    THEN 5
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '60'
    THEN 6
    WHEN SUBSTR(COALESCE(LJ.cost_center, VJ.cost_center), 1, 2) = '90'
    THEN 9
    ELSE 99
    END AS warehouse_nr,
   COALESCE(LJ.cost_center, VJ.cost_center) AS cost_center,
   CAST(SUM(LJ.hours_external) AS BIGNUMERIC) AS hours_external_lj,
   CAST(SUM(VJ.hours_external) AS BIGNUMERIC) AS hours_external_vj
  FROM (SELECT CASE
      WHEN ROUND(CAST(RIGHT(cy_month, 2) AS BIGNUMERIC), 0) <= 2
      THEN ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0) - 1
      ELSE ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0)
      END AS business_year,
     ROUND(CAST(cy_month AS BIGNUMERIC), 0) AS booking_month,
     cost_center,
     CAST(SUM(hours_external) AS BIGNUMERIC) AS hours_external
    FROM ldl_s_conl_workbench.t_i_wh_hours_external
    WHERE RIGHT(cost_center, 4) IN ('9648', '9668') -- was ('9628','9648','9668','9698')

     AND CASE
       WHEN ROUND(CAST(RIGHT(cy_month, 2) AS BIGNUMERIC), 0) <= 2
       THEN ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0) - 1
       ELSE ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0)
       END = (SELECT MAX(CASE
          WHEN ROUND(CAST(RIGHT(TRIM(CAST(cy_month AS STRING)), 2) AS BIGNUMERIC), 0) <= 2
          THEN ROUND(CAST(TRUNC(CAST(ROUND(CAST(LEFT(TRIM(CAST(cy_month AS STRING)), 4) AS BIGNUMERIC), 0) - 1 AS
              BIGNUMERIC)) AS BIGNUMERIC), 0)
          ELSE ROUND(CAST(TRUNC(CAST(ROUND(CAST(LEFT(TRIM(CAST(cy_month AS STRING)), 4) AS BIGNUMERIC), 0) AS BIGNUMERIC
              )) AS BIGNUMERIC), 0)
          END) AS max_year
       FROM ldl_s_conl_workbench.v_hr_po_lead_base
       WHERE RIGHT(TRIM(cost_center), 4) IN ('9648', '9668'))
    GROUP BY
     /* MSC-ERROR - MSCEWI2041 - TRUNC FUNCTION WAS ADDED TO ENSURE INTEGER. MAY NEED CHANGES IF NOT NUMERIC OR STRING. ** */
     business_year,
     booking_month,
     cost_center) AS LJ
   FULL JOIN (SELECT CASE
      WHEN ROUND(CAST(RIGHT(cy_month, 2) AS BIGNUMERIC), 0) <= 2
      THEN ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0) - 1
      ELSE ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0)
      END AS business_year,
     ROUND(CAST(cy_month AS BIGNUMERIC), 0) AS booking_month,
     cost_center,
     CAST(SUM(hours_external) AS BIGNUMERIC) AS hours_external
    FROM ldl_s_conl_workbench.t_i_wh_hours_external
    WHERE RIGHT(cost_center, 4) IN ('9648', '9668') -- was ('9628','9648','9668','9698')

     AND CASE
       WHEN ROUND(CAST(RIGHT(cy_month, 2) AS BIGNUMERIC), 0) <= 2
       THEN ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0) - 1
       ELSE ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0)
       END = (SELECT MAX(CASE
           WHEN ROUND(CAST(RIGHT(TRIM(CAST(cy_month AS STRING)), 2) AS BIGNUMERIC), 0) <= 2
           THEN ROUND(CAST(TRUNC(CAST(ROUND(CAST(LEFT(TRIM(CAST(cy_month AS STRING)), 4) AS BIGNUMERIC), 0) - 1 AS
               BIGNUMERIC)) AS BIGNUMERIC), 0)
           ELSE ROUND(CAST(TRUNC(CAST(ROUND(CAST(LEFT(TRIM(CAST(cy_month AS STRING)), 4) AS BIGNUMERIC), 0) AS
               BIGNUMERIC)) AS BIGNUMERIC), 0)
           END) - 1
       FROM ldl_s_conl_workbench.v_hr_po_lead_base
       WHERE RIGHT(TRIM(cost_center), 4) IN ('9648', '9668'))
    GROUP BY
     /* MSC-ERROR - MSCEWI2041 - TRUNC FUNCTION WAS ADDED TO ENSURE INTEGER. MAY NEED CHANGES IF NOT NUMERIC OR STRING. ** */
     business_year,
     booking_month,
     cost_center) AS VJ ON LJ.business_year = VJ.business_year + 1 AND LJ.booking_month = VJ.booking_month + 100 AND LJ
     .cost_center = VJ.cost_center
  GROUP BY business_year,
   booking_month,
   warehouse_nr,
   cost_center) AS X
 INNER JOIN (SELECT MAX(CASE
     WHEN ROUND(CAST(RIGHT(cy_month, 2) AS BIGNUMERIC), 0) <= 2
     THEN ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0) - 1
     ELSE ROUND(CAST(TRUNC(CAST(LEFT(cy_month, 4) AS BIGNUMERIC)) AS BIGNUMERIC), 0)
     END) AS business_year,
   MAX(ROUND(CAST(cy_month AS BIGNUMERIC), 0)) AS max_month
  FROM ldl_s_conl_workbench.t_i_wh_hours_external
  WHERE RIGHT(TRIM(cost_center), 4) IN ('9648', '9668')) AS RPM ON X.business_year = RPM.business_year AND X.booking_month
    <= RPM.max_month;