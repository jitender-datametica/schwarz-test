  FROM ldl_dig_fe_mstr_lidldigital.v_fact_goods_movement
  WHERE (wh_leave_actual_tmsp, cust_order_sid, cust_order_pos_nr) IN (SELECT (MAX(wh_leave_actual_tmsp), cust_order_sid
       , cust_order_pos_nr)
     FROM ldl_dig_fe_mstr_lidldigital.v_fact_goods_movement
     GROUP BY cust_order_sid,
      cust_order_pos_nr)) (SELECT FACT_SOL.supplier_order_nr,
   FACT_SOL.supplier_order_pos_nr,
   FACT_SOL.supplier_order_type_cd,
   FACT_SOL.prod_variant_sid,
   FACT_COL.prod_variant_nr,
   FACT_SOL.supplier_order_dt,
   FACT_SOL.supplier_sid,
   FACT_SOL.cust_order_sid,
   FACT_SOL.cust_order_nr,
   FACT_SOL.cust_order_pos_nr,
   FACT_SOL.prod_qty,
   FACT_SOL.supplier_order_cancel_dt,
   FACT_COL.wshop_cd,
   FACT_COL.cust_order_create_tmsp,
   FACT_COL.cust_order_dt,
   FACT_COL.cust_order_tm,
   FACT_COL.cust_order_create_time,
   FACT_COL.cust_order_create_date,
   FACT_COL.prod_sid,
   FACT_COL.article_set,
   FACT_COL.prod_sale_type_cd,
   FACT_COL.cust_sid,
   FACT_COL.is_bundle_header_fg,
   FACT_COL.bundle_header_pos_nr,
   FACT_COL.delivery_addr_sid,
   FACT_COL.delivery_cust_sid,
   FACT_COL.is_blocked_delivery_fg,
   FACT_COL.delivery_blocked_reason_cd,
   FACT_COL.is_order_cancel_fg,
   FACT_COL.cust_paym_method_cd,
   FACT_COL.sales_channel_type_cd,
   FACT_COL.order_cancel_reason_cd,
   FACT_COL.cust_order_type_cd,
   FACT_COL.cust_order_perform_dt,
   FACT_COL.cust_delivery_tgt_dt,
   FACT_COL.wh_sid,
   FACT_COL.wh_cd,
   FACT_COL.product_assortiment_type_cd,
   FACT_COL.dropshipment_order_fg,
   FACT_COL.is_part_of_bundle_header_cnt_fg,
   FACT_COL.is_part_of_bundle_pos_cnt_fg,
   FACT_GM.delivery_order_sid,
   FACT_GM.delivery_order_nr,
   FACT_GM.delivery_order_pos_nr,
   FACT_GM.goods_mov_cat_cd,
   FACT_GM.goods_mov_cat_group_cd,
   FACT_GM.goods_mov_actual_tmsp,
   FACT_GM.delivery_prod_qty,
   FACT_GM.delivery_type_cd,
   FACT_GM.delivery_route_cd,
   FACT_GM.recipient_country_cd,
   FACT_GM.stock_placement_cd,
   FACT_GM.stock_removal_cd,
   FACT_GM.storage_loc_cd,
   FACT_GM.wh_leave_actual_tmsp,
   FACT_GM.wh_leave_actual_dt,
   FACT_GM.wh_leave_tgt_tmsp,
   FACT_GM.wh_leave_tgt_dt,
   FACT_GM.order_item_category_cd,
   FACT_GM.wh_arrive_actual_dt,
   FACT_GM.sale_doc_type_cd,
   FACT_GM.delivery_tgt_dt,
   ldl_dig_fe_mstr_lidldigital.f_count_working_days(FACT_SOL.supplier_order_dt, FACT_GM.wh_leave_actual_dt) AS
   supplier_order_to_wh_leave_in_days,
   ldl_dig_fe_mstr_lidldigital.f_count_working_days(FACT_COL.cust_delivery_tgt_dt, FACT_GM.wh_leave_actual_dt)-1 AS cust_delivery_tg_to_wh_leave_in_days,
   ldl_dig_fe_mstr_lidldigital.f_count_working_days(FACT_GM.delivery_tgt_dt, FACT_GM.wh_leave_actual_dt) AS
   delivery_tg_to_wh_leave_in_days
  FROM ldl_dig_fe_mstr_lidldigital.v_fact_supplier_order_line AS FACT_SOL
   LEFT JOIN ldl_dig_fe_mstr_lidldigital.v_fact_customer_order_line AS FACT_COL ON FACT_SOL.cust_order_sid = FACT_COL.cust_order_sid
       AND FACT_SOL.cust_order_pos_nr = FACT_COL.cust_order_pos_nr AND FACT_COL.gc_lc_cd = 'GC'
   LEFT JOIN CTE AS FACT_GM ON FACT_SOL.supplier_order_nr = FACT_GM.supplier_order_nr AND FACT_SOL.supplier_order_pos_nr
      = FACT_GM.supplier_order_pos_nr);
      
