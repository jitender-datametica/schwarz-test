CREATE TABLE IF NOT EXISTS ldl_logop_data.t_wawi_inventory (
client_id BIGNUMERIC(38,0) NOT NULL OPTIONS(description='Client id - calculated based on the country code'),
wh_nr BIGNUMERIC(38,0) NOT NULL OPTIONS(description='Warehouse number'),
wawi_instanz_kzl STRING(3) NOT NULL OPTIONS(description='Country code'),
inventorynum BIGNUMERIC(38,0) NOT NULL
OPTIONS(description='Number of the Inventory - filled in by the application automatically'),
description STRING(25) OPTIONS(description='Name of the inventory typed in by the user during the inventory generation'),
dayenddate DATETIME OPTIONS(description='Inventorydate typed in by the user during the inventory generation'),
readonly STRING(1) OPTIONS(description='Shows if the inventory was already posted or not T if posted, F if not posted'),
c72_type STRING(1) OPTIONS(description='P = partial; Z = Full but not activated; F = Full and activated'),
inventskeleton DATETIME OPTIONS(description='Timestamp of the inventory generation'),
addunalocslots DATETIME OPTIONS(description='Timestamp adding items without slots'),
addaisledescr DATETIME OPTIONS(description='Timestamp adding aisle description from BEREICHE_SETZLISTE'),
delolditems DATETIME OPTIONS(description='Timestamp after deleting items with status >12'),
updprices DATETIME OPTIONS(description='Timestamp of the last price updates'),
updexpfigures DATETIME OPTIONS(description='Timestamp of the last update of expected stock'),
updontheramp DATETIME OPTIONS(description='Timestamp of the last update of the rampstock'),
addoldcaseszs DATETIME,
deloldcaseszs DATETIME,
mod_user STRING(8) OPTIONS(description='Last moduser of inventory'),
mod_date DATETIME OPTIONS(description='last moddate of inventory'),
yndinventory BIGNUMERIC(38,0) OPTIONS(description='Indicates if the inventory is a YE or not'),
evalinventory BIGNUMERIC(38,0) OPTIONS(description='Indicates if the inventory is a evaluation inventory or not'),
dateposted DATETIME OPTIONS(description='Timestamp of the posting of the inventory'),
whnr BIGNUMERIC(38,0) NOT NULL OPTIONS(description='Number of the WH from UMGEBUNG'),
checkdat DATETIME OPTIONS(description='The timestamp of the T72_INVENTORY.C72_CHECKVALUE check'),
checkvalue BIGNUMERIC(38,0)
OPTIONS(description='Indicates whether the check for equality between T1001.C1001_PIECEQTY_CAL and T1001.C1001_PIECEQTY_REAL was successful or not'),
updexpfigures_ssi DATETIME OPTIONS(description='The timestamp of the the ssi expected figures update'),
updexpfigures_lpv DATETIME OPTIONS(description='The timestamp of the lpv expected figures update'),
manual_lpv BIGNUMERIC(38,0)
OPTIONS(description='Indicates whether a year end full inventory is in LPV manual mode, 0 = LPV manual mode is disabled, 1 = LPV manual mode is enabled, null = not relevant for the specific inventory'),
area_by_area BIGNUMERIC(38,0) OPTIONS(description='Indicates if an item of the inventory is from ewm(1) or not(0)'),
scn BIGNUMERIC(38,0),
dwh_load_id BIGNUMERIC(38,0) NOT NULL OPTIONS(description='Load id'),
dwh_created DATETIME NOT NULL OPTIONS(description='Record created at'),
dwh_updated DATETIME NOT NULL OPTIONS(description='Record updated at'),
dwh_valid_from DATE NOT NULL OPTIONS(description='Valid from date'),
dwh_valid_to DATE NOT NULL OPTIONS(description='Valid to date'),
deleted_fg BOOL NOT NULL OPTIONS(description='Flag if record is deleted'),
PRIMARY KEY (client_id, whnr, inventorynum, dwh_valid_from) NOT ENFORCED
) OPTIONS(description='WAWI - WHWAWIADM.T72_INVENTORY table');