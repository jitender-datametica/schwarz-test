CREATE OR REPLACE VIEW ldl_score_core_rel.v_calendar_ytd AS WITH TIMERANGE AS (SELECT DATE_SUB(DATE_ADD(DATE(CAST(EXTRACT(YEAR FROM CURRENT_DATE) - 10 AS STRING)
       || '-01-01'), INTERVAL ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1) DAY), INTERVAL 1 DAY) AS cal_dt
  FROM UNNEST(GENERATE_ARRAY(0, 364*12)) AS SEQ) (SELECT a.cal_dt,
   b.cal_dt AS incl_cal_dt
  FROM TIMERANGE AS a
   INNER JOIN TIMERANGE AS b ON EXTRACT(YEAR FROM a.cal_dt) = EXTRACT(YEAR FROM b.cal_dt) AND a.cal_dt >= b.cal_dt);