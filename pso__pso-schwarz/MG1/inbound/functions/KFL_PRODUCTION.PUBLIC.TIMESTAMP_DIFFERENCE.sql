CREATE OR REPLACE FUNCTION KFL_PRODUCTION.PUBLIC.TIMESTAMP_DIFFERENCE("DATE1" TIMESTAMP_NTZ(9), "DATE2" TIMESTAMP_NTZ(9), "INPUT_PART" VARCHAR(16777216))
RETURNS VARCHAR(16777216)
LANGUAGE SQL
AS '
   DECODE(INPUT_PART,
           ''YEAR'',             TO_VARCHAR(DATEDIFF(YEAR, DATE2, DATE1)),
           ''DAY'',              TO_VARCHAR(TRUNC(DATEDIFF(SECONDS, DATE2, DATE1)/(86400))),
           ''DAY TO HOUR'',      TO_VARCHAR(TRUNC(DATEDIFF(SECONDS, DATE2, DATE1)/(86400))) || '' '' || PUBLIC.TIMES_DIFFERENCE(LEAST(DATE1,DATE2), GREATEST(DATE1, DATE2), ''HOUR''),
           ''DAY TO MINUTE'',    TO_VARCHAR(TRUNC(DATEDIFF(SECONDS, DATE2, DATE1)/(86400))) || '' '' || PUBLIC.TIMES_DIFFERENCE(LEAST(DATE1,DATE2), GREATEST(DATE1, DATE2), ''MINUTE''),
           ''DAY TO SECOND'',    TO_VARCHAR(TRUNC(DATEDIFF(SECONDS, DATE2, DATE1)/(86400))) || '' '' || PUBLIC.TIMES_DIFFERENCE(LEAST(DATE1,DATE2), GREATEST(DATE1, DATE2), ''SECOND''),
           ''HOUR'',             TO_VARCHAR(DATEDIFF(HOUR, DATE2, DATE1)),
           ''HOUR TO MINUTE'',   TO_VARCHAR(DATEDIFF(HOUR, DATE2, DATE1)) || '':'' || SPLIT_PART(PUBLIC.TIMES_DIFFERENCE(LEAST(DATE1,DATE2), GREATEST(DATE1, DATE2), ''MINUTE''), '':'', 2),
           ''HOUR TO SECOND'',   TO_VARCHAR(DATEDIFF(HOUR, DATE2, DATE1)) || '':'' || SUBSTR(PUBLIC.TIMES_DIFFERENCE(LEAST(DATE1,DATE2), GREATEST(DATE1, DATE2), ''SECOND''), -5),
           ''MINUTE'',           TO_VARCHAR(DATEDIFF(MINUTE, DATE2, DATE1)),
           ''MINUTE TO SECOND'', TO_VARCHAR( TRUNC(DATEDIFF(SECONDS, DATE2, DATE1)/60), ''FM9900'') || '':'' || SUBSTR(PUBLIC.TIMES_DIFFERENCE(LEAST(DATE1,DATE2), GREATEST(DATE1, DATE2), ''SECOND''), -2),
           ''SECOND'',           TO_VARCHAR(DATEDIFF(SECOND, DATE2, DATE1), ''9999'')
            )
';