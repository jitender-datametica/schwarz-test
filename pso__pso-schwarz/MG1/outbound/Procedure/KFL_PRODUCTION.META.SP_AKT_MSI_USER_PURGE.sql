CREATE OR REPLACE PROCEDURE KFL_PRODUCTION_META.SP_AKT_MSI_USER_PURGE(OUT out_param STRING)
BEGIN
DECLARE sql_purge STRING;
DECLARE statement_purge STRING;
DECLARE result_purge STRING;
--
SET sql_purge  =  '''DELETE FROM KFL_PRODUCTION_DBP_MSI_DATA.AKT_MSI_USER WHERE SESSION_ID IN (SELECT DISTINCT T1.SESSION_ID   FROM KFL_PRODUCTION_DBP_MSI_DATA.AKT_MSI_USER AS T1    INNER JOIN ACCOUNT_USAGE.QUERY_HISTORY AS T2 ON T1.SESSION_ID = T2.SESSION_ID   WHERE DATE(T2.START_TIME) = CURRENT_DATE    AND T2.END_TIME < DATETIME_ADD(CURRENT_TIMESTAMP(), INTERVAL - 1 HOUR));''';
SET statement_purge  =  sql_purge;

EXECUTE IMMEDIATE (statement_purge);
SET out_param  =  result_purge;
SELECT out_param;
RETURN;
END;
