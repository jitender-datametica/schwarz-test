 LKP_WRG = b.WRG_ID,
 LKP_UMRECHNUNGSKURS = 1 / CAST(b.UMRECHNUNGSKURS AS FLOAT64) FROM (SELECT *
  FROM KFL_PRODUCTION_DBP_DATA.MANDANT_WRG_ZU_PER
  WHERE CURRENT_DATE BETWEEN DAT_VON AND DAT_BIS
   AND VON_WRG_ID IS NOT NULL) AS b
WHERE KMO_ARTBEW_BON.MANDANT_ID = b.MANDANT_ID AND KMO_ARTBEW_BON.LKP_WRG = b.VON_WRG_ID;


UPDATE KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_BON SET
 LKP_MWST = b.MWST FROM (SELECT A.MANDANT_ID,
   B.DAT,
   A.MWST_ID,
   A.MWST
  FROM KFL_PRODUCTION_DBP_DATA.MWST_PER AS A
   INNER JOIN `_TAGE` AS B ON B.DAT BETWEEN A.DAT_VON AND A.DAT_BIS
  WHERE A.MANDANT_ID IN (3, 5, 6, 8)) AS b
WHERE KMO_ARTBEW_BON.MANDANT_ID = b.MANDANT_ID AND KMO_ARTBEW_BON.DAT_BOOKING = b.DAT AND KMO_ARTBEW_BON.LKP_MWST_ID = b
  .MWST_ID;


