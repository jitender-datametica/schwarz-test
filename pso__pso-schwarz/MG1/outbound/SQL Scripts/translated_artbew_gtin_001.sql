 LKP_MWST_ID = b.MWST_ID FROM KFL_PRODUCTION_DBP_DATA.ART_PER AS b
WHERE KMO_ARTBEW_BON.DAT_BOOKING BETWEEN b.DAT_VON AND b.DAT_BIS AND KMO_ARTBEW_BON.MANDANT_ID = b.MANDANT_ID AND
   KMO_ARTBEW_BON.LKP_ART_ID = b.ART_ID AND KMO_ARTBEW_BON.LKP_MWST_ID <> b.MWST_ID;


