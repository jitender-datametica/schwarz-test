   FROM KFL_PRODUCTION_DBP_DATA.MANDANT_WRG_ZU_PER
   WHERE WRG_ID <> VON_WRG_ID
    AND CURRENT_DATE BETWEEN DAT_VON AND DAT_BIS) AS y ON l.MANDANT_ID = y.MANDANT_ID AND l.LKP_WRG = y.WRG_ID);



