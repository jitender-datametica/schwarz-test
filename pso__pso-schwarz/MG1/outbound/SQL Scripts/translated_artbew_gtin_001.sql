  l.MANDANT_ID,
   CASE
   WHEN l.AKTION_ID <> ''
   THEN 1002
   ELSE 1001
   END AS BEWART_ID,
  - 1 AS GP_ID,
  l.LKP_NB_ID AS NB_ID,
  l.LKP_ART_ID AS ART_ID,
  l.DAT_BOOKING AS DAT,
