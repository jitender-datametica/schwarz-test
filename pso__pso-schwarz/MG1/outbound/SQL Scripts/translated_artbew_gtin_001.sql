  ROUND(CAST(l.UMSATZ_BRUTTO_ * CASE
       WHEN y.CONV_FG = 1
       THEN l.LKP_UMRECHNUNGSKURS
       ELSE 1
       END / (1 + l.LKP_MWST / 100) AS NUMERIC), 4) AS UMSATZ_NETTO,
