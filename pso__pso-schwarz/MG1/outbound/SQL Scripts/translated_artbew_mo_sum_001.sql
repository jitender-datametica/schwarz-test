CREATE OR REPLACE TEMPORARY TABLE _ARTBEW_AGG_MONAT (
DAT DATE NOT NULL,
MANDANT_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID INTEGER NOT NULL,
KJMO INTEGER NOT NULL
);


INSERT INTO `_ARTBEW_AGG_MONAT` (DAT, MANDANT_ID, WUP_ID, NB_ID, KJMO)
(SELECT C.DAT,
  A.MANDANT_ID,
  A.WUP_ID,
  A.NB_ID,
  C.KJMO
 FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_AGG_WT AS A
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS B ON A.DAT = B.DAT
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS C ON B.KJMO = C.KJMO
 GROUP BY A.MANDANT_ID,
  A.WUP_ID,
  A.NB_ID,
  C.DAT,
  C.KJMO);


DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_MO_SUM
WHERE (MANDANT_ID, WUP_ID, NB_ID, KJMO) IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, KJMO)
   FROM `_ARTBEW_AGG_MONAT`) AND (KJMO, MANDANT_ID) IN (SELECT (KJMO, MANDANT_ID)
   FROM `_ARTBEW_AGG_MONAT`);


