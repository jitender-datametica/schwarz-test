CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_TAGE` AS
SELECT DAT
FROM KFL_PRODUCTION_DBP_DATA.TAG
WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 4 DAY) AND (DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY))
GROUP BY DAT;




CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_SNAPSHOT1` AS
SELECT A.BON_ID,
 A.BON_ZEILE,
 A.KL_ART_ID,
 A.EAN_KASSE,
 A.WG_ID,
 A.MENGE,
 A.EINH_ID,
 A.UMSATZ_BRUTTO,
 A.MWST_ID,
 A.ERFASSUNG_ID,
 A.AKTION_ID,
 A.MANDANT_ID,
 A.WUP_ID,
 A.TALON_ID,
 A.START_BON_ZEILE,
 A.BON_NR_EXTERN,
 A.KPOS_ERFASSUNG_ID,
 A.UMSATZ_BRUTTO_NORM,
 A.VK_BRUTTO_OBB,
 A.BON_VORGANG_ID,
 A.BARCODE_STRING,
 A.BON_DAT,
 A.TD_INSERT,
 A.TD_UPDATE,
 A.BARCODE_LEERGUT,
 A.ZEILENSTORNO_FG,
 X.KASSE_TYP_ID
FROM KFL_PRODUCTION_DBP_ODS.ODS_BON_KOPF AS X
 INNER JOIN KFL_PRODUCTION_DBP_ODS.ODS_BON_VERKAUF AS A ON X.MANDANT_ID = A.MANDANT_ID AND X.WUP_ID = A.WUP_ID AND X.BON_ID
     = A.BON_ID AND X.BON_DAT = A.BON_DAT
WHERE X.BON_DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 4 DAY) AND (DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY))
 AND X.KASSE_TYP_ID IN (1, 8, 9)
 AND A.MENGE > 0
 AND A.EINH_ID NOT IN ('LGB', 'PND', 'LGK', 'LGF');


CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_ARTBEW` AS
SELECT *
FROM KFL_PRODUCTION_DBP_DATA.ARTBEW
WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 4 DAY) AND (DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY));


CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_ERGEBNIS` AS
SELECT A.MANDANT_ID,
 A.WUP_ID,
 0 AS NB_ID,
  CASE
  WHEN A.AKTION_ID NOT IN ('0', '0000000000', '')
  THEN 1002
  ELSE 1001
  END AS BEWART_ID,
 CAST(NULL AS BIGNUMERIC) AS GP_ID,
 B.ART_ID,
 A.BON_DAT AS DAT,
 A.AKTION_ID,
 0 AS PROMO_FG,
 A.KASSE_TYP_ID,
 COALESCE(CASE
   WHEN TRIM(A.BARCODE_STRING) = ''
   THEN CAST(A.EAN_KASSE AS BIGNUMERIC)
   WHEN LENGTH(A.BARCODE_STRING) > 26
   THEN CAST(- 9999 AS BIGNUMERIC)
   WHEN ROUND(SAFE_CAST(A.BARCODE_STRING AS BIGNUMERIC), 0) IS NOT NULL
   THEN CAST(ROUND(CAST(A.BARCODE_STRING AS BIGNUMERIC), 0) AS BIGNUMERIC)
   ELSE CAST(A.EAN_KASSE AS BIGNUMERIC)
   END, A.EAN_KASSE) AS GTIN_KASSE,
 SUM(CASE
   WHEN A.ERFASSUNG_ID = 'SC'
   THEN 1
   ELSE 0
   END) AS VORGANG_SCANNED,
 SUM(CASE
   WHEN A.ERFASSUNG_ID = 'KE'
   THEN 1
   ELSE 0
   END) AS VORGANG_KEYED,
 SUM(CASE
   WHEN A.ERFASSUNG_ID = 'SC' AND (A.EINH_ID = 'ST' AND A.MENGE <> 1 OR A.EINH_ID = 'KGM')
   THEN 1
   ELSE 0
   END) AS VORGANG_SCANNED_EINZELN,
 SUM(CASE
   WHEN A.ERFASSUNG_ID = 'KE' AND (A.EINH_ID = 'ST' AND A.MENGE <> 1 OR A.EINH_ID = 'KGM')
   THEN 1
   ELSE 0
   END) AS VORGANG_KEYED_EINZELN,
 COUNT(DISTINCT A.BON_ID) AS ANZAHL_BON,
 SUM(CASE
   WHEN A.EINH_ID = 'KGM'
   THEN 1
   ELSE A.MENGE
   END) AS ANZAHL_REGISTRIERT
FROM DEFAULTSCHEMA.`_SNAPSHOT1` AS A
 INNER JOIN KFL_PRODUCTION_DBP_DATA.ART AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.KL_ART_ID = B.KL_ART_ID AND B.DAT_BIS
   = DATE '9999-12-31'
GROUP BY A.MANDANT_ID,
 A.WUP_ID,
 NB_ID,
 BEWART_ID,
 GP_ID,
 B.ART_ID,
 DAT,
 A.AKTION_ID,
 PROMO_FG,
 A.KASSE_TYP_ID,
 GTIN_KASSE;


UPDATE DEFAULTSCHEMA.`_ERGEBNIS` SET
 PROMO_FG = t1.PROMO_FG FROM (SELECT MANDANT_ID,
   WUP_ID,
   ART_ID,
   AKTION_ID,
   EAN_KASSE,
   DAT,
   PROMO_FG
  FROM DEFAULTSCHEMA.`_ARTBEW`
  WHERE PROMO_FG = 1
  GROUP BY MANDANT_ID,
   WUP_ID,
   DAT,
   ART_ID,
   AKTION_ID,
   PROMO_FG,
   EAN_KASSE) AS t1
WHERE `_ERGEBNIS`.MANDANT_ID = t1.MANDANT_ID AND `_ERGEBNIS`.WUP_ID = t1.WUP_ID AND `_ERGEBNIS`.ART_ID = t1.ART_ID AND
    `_ERGEBNIS`.AKTION_ID = t1.AKTION_ID AND `_ERGEBNIS`.GTIN_KASSE = t1.EAN_KASSE AND `_ERGEBNIS`.DAT = t1.DAT;


UPDATE DEFAULTSCHEMA.`_ERGEBNIS` SET
 GP_ID = t0.GP_ID FROM (SELECT MANDANT_ID,
   WUP_ID,
   ART_ID,
   DAT,
   MAX(GP_ID) AS GP_ID
  FROM DEFAULTSCHEMA.`_ARTBEW`
  GROUP BY MANDANT_ID,
   WUP_ID,
   DAT,
   ART_ID) AS t0
WHERE `_ERGEBNIS`.MANDANT_ID = t0.MANDANT_ID AND `_ERGEBNIS`.WUP_ID = t0.WUP_ID AND `_ERGEBNIS`.ART_ID = t0.ART_ID AND
  `_ERGEBNIS`.DAT = t0.DAT;


UPDATE DEFAULTSCHEMA.`_ERGEBNIS` AS `_ERGEBNIS0` SET
 GP_ID = b.GP_ID FROM (SELECT a.MANDANT_ID,
   a.WUP_ID,
   a.ART_ID,
   a.DAT,
   MAX(B.GP_ID) AS GP_ID
  FROM (SELECT *
    FROM DEFAULTSCHEMA.`_ERGEBNIS`
    WHERE GP_ID IS NULL) AS a
   INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_GP_NM_ZU_PER AS B ON a.MANDANT_ID = B.MANDANT_ID AND a.WUP_ID = B.WUP_ID AND a
      .ART_ID = B.ART_ID AND a.DAT BETWEEN B.DAT_VON AND B.DAT_BIS
  GROUP BY a.MANDANT_ID,
   a.WUP_ID,
   a.ART_ID,
   a.DAT) AS b
WHERE `_ERGEBNIS0`.MANDANT_ID = b.MANDANT_ID AND `_ERGEBNIS0`.WUP_ID = b.WUP_ID AND `_ERGEBNIS0`.ART_ID = b.ART_ID AND
   `_ERGEBNIS0`.DAT = b.DAT AND `_ERGEBNIS0`.GP_ID IS NULL;


DELETE FROM DEFAULTSCHEMA.`_ERGEBNIS`
WHERE GP_ID IS NULL;


DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_SCANNING
WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 4 DAY) AND (DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY));


INSERT INTO KFL_PRODUCTION_DBP_DATA.ARTBEW_SCANNING (WUP_ID, MANDANT_ID, BEWART_ID, GP_ID, NB_ID, ART_ID, DAT, AKTION_ID
 , PROMO_FG, GTIN_KASSE, KASSE_TYP_ID, VORGANG_SCANNED, VORGANG_KEYED, VORGANG_SCANNED_EINZELN, VORGANG_KEYED_EINZELN,
 ANZAHL_BON, ANZAHL_REGISTRIERT)
(SELECT WUP_ID,
  MANDANT_ID,
  BEWART_ID,
  CAST(GP_ID AS INTEGER) AS GP_ID,
  NB_ID,
  ART_ID,
  DAT,
  AKTION_ID,
  CAST(PROMO_FG AS INTEGER) AS PROMO_FG,
  CAST(GTIN_KASSE AS INTEGER) AS GTIN_KASSE,
  KASSE_TYP_ID,
  VORGANG_SCANNED,
  VORGANG_KEYED,
  VORGANG_SCANNED_EINZELN,
  VORGANG_KEYED_EINZELN,
  ANZAHL_BON,
  CAST(ANZAHL_REGISTRIERT AS INTEGER) AS ANZAHL_REGISTRIERT
 FROM DEFAULTSCHEMA.`_ERGEBNIS`);