(SELECT t3.MANDANT_ID,
  t3.ART_ID,
  t0.LIFNR AS GP_ID_,
   CASE
   WHEN t0.WERKS IS NULL
   THEN - 1
   ELSE t0.WERKS
   END AS WUP_ID_,
   CASE
   WHEN t0.WERKS IS NULL OR t0.WERKS = - 1
   THEN NULL
   ELSE wp.NB_ID
   END AS NB_ID_,
