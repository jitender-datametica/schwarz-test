UPDATE KFL_PRODUCTION_DBP_DATA.ART_GP_ZU_PER AS ART_GP_ZU_PER0 SET
 DAT_BIS = dt1.DAT_BIS,
 TD_UPDATE = CURRENT_TIMESTAMP() FROM (SELECT MANDANT_ID,
   ART_ID,
   DAT_VON,
    CASE
    WHEN (SUM(ROUND(CAST(FORMAT_DATE('%Y%m%d', DAT_VON) AS BIGNUMERIC), 0)) OVER (PARTITION BY MANDANT_ID, ART_ID
        ORDER BY DAT_VON IS NULL, DAT_VON ROWS BETWEEN 1 PRECEDING AND CURRENT ROW)) - ROUND(CAST(FORMAT_DATE('%Y%m%d', DAT_VON) AS BIGNUMERIC)
       , 0) = 0
    THEN PARSE_DATE('%F', '9999-12-31')
    ELSE DATE_ADD(DATE(CAST((SUM(ROUND(CAST(FORMAT_DATE('%Y%m%d', DAT_VON) AS BIGNUMERIC), 0)) OVER (PARTITION BY
            MANDANT_ID, ART_ID ORDER BY DAT_VON IS NULL, DAT_VON ROWS BETWEEN 1 PRECEDING AND CURRENT ROW)) - ROUND(CAST(FORMAT_DATE('%Y%m%d', DAT_VON) AS BIGNUMERIC)
         , 0) AS STRING)), INTERVAL - 1 DAY)
    END AS DAT_BIS
  FROM (SELECT MANDANT_ID,
     ART_ID,
     DAT_VON
    FROM KFL_PRODUCTION_DBP_DATA.ART_GP_ZU_PER
    WHERE MANDANT_ID = 1
    GROUP BY DAT_VON,
     MANDANT_ID,
     ART_ID) AS t1) AS dt1
WHERE ART_GP_ZU_PER0.MANDANT_ID = dt1.MANDANT_ID AND ART_GP_ZU_PER0.ART_ID = dt1.ART_ID AND ART_GP_ZU_PER0.DAT_VON = dt1
   .DAT_VON AND ART_GP_ZU_PER0.DAT_BIS <> dt1.DAT_BIS;


