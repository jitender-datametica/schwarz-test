  MENGE_BEST_BME,
  T.ENDLIEF_FG,
  T.DAT_BEST_BELEG,
  T.WRG_ID,
  T.EK_NETTO,
  la.GP_ID,
  la.BESTELLART_ID,
  T.KOMPONENTENMENGE,
  T.MENGE_BEST_KOLLI,
  T.LOESCH_FG,
  T.SELBSTABHOL_FG
