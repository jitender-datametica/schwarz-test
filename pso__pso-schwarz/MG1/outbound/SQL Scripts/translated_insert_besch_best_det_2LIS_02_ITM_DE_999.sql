    AUSG_MENGE_EINH_ID,
    DAT_VON,
    DAT_BIS
   FROM KFL_PRODUCTION_DBP_DATA.ART_VORSCHLAGSWERT_PER
   WHERE MANDANT_ID = 1) AS av ON T.ART_ID = av.ART_ID AND la.DAT_BEST_BELEG BETWEEN av.DAT_VON AND av.DAT_BIS
  LEFT JOIN (SELECT ART_ID,
    ALTNV_MENGE_EINH_ID,
    DAT_VON,
    DAT_BIS,
    UMRECH_FAKTOR
   FROM KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER
   WHERE MANDANT_ID = 1) AS aukolli_alternativ ON T.ART_ID = aukolli_alternativ.ART_ID AND av.AUSG_MENGE_EINH_ID =
     aukolli_alternativ.ALTNV_MENGE_EINH_ID AND la.DAT_BEST_BELEG BETWEEN aukolli_alternativ.DAT_VON AND
    aukolli_alternativ.DAT_BIS);


