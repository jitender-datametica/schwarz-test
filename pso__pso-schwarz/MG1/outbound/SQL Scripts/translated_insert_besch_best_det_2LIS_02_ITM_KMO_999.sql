UPDATE KFL_PRODUCTION_DBP_ETL.KMO_EKPO SET
 EK_NETTO = a.EK_EFFEKTIVPREIS,
 GP_ID = a.GP_ID,
 WRG_ID = a.WRG_ID FROM (SELECT A.MANDANT_ID,
   A.WUP_ID,
   A.NB_ID,
   A.ART_ID,
   Z.GP_ID,
   M.DEFAULT_WRG AS WRG_ID,
   COALESCE(COALESCE(MA.FAKTOR_EK_EFFEKTIVPREIS, MS.FAKTOR_EK_EFFEKTIVPREIS), COALESCE(E.EK_NETTO, EE.EK_NETTO), 0.0000
    ) AS EK_EFFEKTIVPREIS
  FROM KFL_PRODUCTION_DBP_ETL.KMO_EKPO AS A
   INNER JOIN KFL_PRODUCTION_DBP_DATA.MANDANT AS M ON A.MANDANT_ID = M.MANDANT_ID
   LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_GP_NM_ZU_PER AS Z ON A.MANDANT_ID = Z.MANDANT_ID AND A.WUP_ID = Z.WUP_ID AND A
      .ART_ID = Z.ART_ID AND CURRENT_DATE BETWEEN Z.DAT_VON AND Z.DAT_BIS
   LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_GP_WUP_ZU_PER AS E ON Z.MANDANT_ID = E.MANDANT_ID AND Z.VZ_WUP_ID = E.WUP_ID
        AND Z.ART_ID = E.ART_ID AND Z.GP_ID = E.GP_ID AND CURRENT_DATE BETWEEN E.DAT_VON AND E.DAT_BIS AND MOD(Z.BQ_FINDUNG_ID
       , 2) = 1 AND Z.BQ_FINDUNG_ID <> 25
   LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_GP_WUP_ZU_PER AS EE ON Z.MANDANT_ID = EE.MANDANT_ID AND - 1 = EE.WUP_ID AND Z.ART_ID
         = EE.ART_ID AND Z.GP_ID = EE.GP_ID AND CURRENT_DATE BETWEEN EE.DAT_VON AND EE.DAT_BIS AND MOD(Z.BQ_FINDUNG_ID,
      2) = 0
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.ART_WUP_MAN_SP_BESCH_BEST_TMP AS MS ON A.MANDANT_ID = MS.MANDANT_ID AND A.ART_ID =
       MS.ART_ID AND MS.WUP_ID = 0 AND Z.BQ_FINDUNG_ID = 27
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.ART_WUP_MAN_SP_BESCH_BEST_TMP AS MA ON A.MANDANT_ID = MA.MANDANT_ID AND A.ART_ID =
       MA.ART_ID AND A.WUP_ID = MA.WUP_ID AND Z.BQ_FINDUNG_ID = 26
  WHERE A.MANDANT_ID > 1
  GROUP BY A.MANDANT_ID,
   A.WUP_ID,
   A.NB_ID,
   A.ART_ID,
   Z.GP_ID,
   WRG_ID,
   EK_EFFEKTIVPREIS) AS a
WHERE KMO_EKPO.MANDANT_ID = a.MANDANT_ID AND KMO_EKPO.WUP_ID = a.WUP_ID AND KMO_EKPO.NB_ID = a.NB_ID AND KMO_EKPO.ART_ID
   = a.ART_ID;


