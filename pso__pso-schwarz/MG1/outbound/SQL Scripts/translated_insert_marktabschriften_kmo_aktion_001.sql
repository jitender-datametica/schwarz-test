DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.MARKTABSCHRIFT_AKTION_TMP;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.MARKTABSCHRIFT_AKTION_TMP (
WUP_ID INTEGER,
NB_ID SMALLINT,
AKTION_ID STRING,
MANDANT_ID BIGNUMERIC,
DAT DATE,
ART_ID INTEGER,
MENGE_ABSCHRIFT NUMERIC(18,3),
VK_AKTION_BRUTTO NUMERIC(9,3),
VK_VOR_AKTION_BRUTTO NUMERIC(9,2),
MWST_ID BIGNUMERIC,
ABSCHRIFTBETRAG_NETTO NUMERIC(18,4),
ABSCHRIFTBETRAG_BRUTTO NUMERIC(18,2),
WRG_ID STRING,
VK_AKTION_NETTO NUMERIC(9,4),
VK_VOR_AKTION_NETTO NUMERIC(9,4),
AKTION_RELEVANT_FG BIGNUMERIC
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.MARKTABSCHRIFT_AKTION_TMP (WUP_ID, NB_ID, AKTION_ID, MANDANT_ID, DAT, ART_ID,
 MENGE_ABSCHRIFT, VK_AKTION_BRUTTO, VK_VOR_AKTION_BRUTTO, MWST_ID, ABSCHRIFTBETRAG_NETTO, ABSCHRIFTBETRAG_BRUTTO, WRG_ID
 , VK_AKTION_NETTO, VK_VOR_AKTION_NETTO, AKTION_RELEVANT_FG)
(SELECT CAST(A.WUP_ID AS INTEGER) AS WUP_ID,
  CAST(A.NB_ID AS SMALLINT) AS NB_ID,
  B.AKTION_ID,
  A.MANDANT_ID,
  A.DAT,
  CAST(A.ART_ID AS INTEGER) AS ART_ID,
  CAST(SUM(A.MENGE) AS NUMERIC) AS MENGE_ABSCHRIFT,
  B.VK_AKTION_BRUTTO,
  B.VK_VOR_AKTION_BRUTTO,
  C.MWST_ID,
  0 AS ABSCHRIFTBETRAG_NETTO,
  0 AS ABSCHRIFTBETRAG_BRUTTO,
  A.WRG AS WRG_ID,
  0 AS VK_AKTION_NETTO,
  0 AS VK_VOR_AKTION_NETTO,
  B.AKTION_RELEVANT_FG
 FROM KFL_PRODUCTION_DBP_DATA.ARTBEW AS A
  INNER JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.MARKTABSCHRIFTEN_STAMM AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B
       .WUP_ID AND A.NB_ID = B.NB_ID AND A.ART_ID = B.ART_ID AND A.DAT = B.DAT
  INNER JOIN KFL_PRODUCTION_DBP_DATA.ART AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.ART_ID = C.ART_ID
 WHERE A.MANDANT_ID > 1
  AND A.DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 45 DAY) AND (CURRENT_DATE)
  AND A.BEWART_ID = 1002
 GROUP BY A.WUP_ID,
  A.NB_ID,
  B.AKTION_ID,
  A.MANDANT_ID,
  A.DAT,
  A.ART_ID,
  B.VK_AKTION_BRUTTO,
  B.VK_VOR_AKTION_BRUTTO,
  C.MWST_ID,
  ABSCHRIFTBETRAG_NETTO,
  ABSCHRIFTBETRAG_BRUTTO,
  WRG_ID,
  B.AKTION_RELEVANT_FG);


UPDATE KFL_PRODUCTION_DBP_ETL.MARKTABSCHRIFT_AKTION_TMP SET
 ABSCHRIFTBETRAG_BRUTTO = (MARKTABSCHRIFT_AKTION_TMP.VK_VOR_AKTION_BRUTTO - MARKTABSCHRIFT_AKTION_TMP.VK_AKTION_BRUTTO)
  * MARKTABSCHRIFT_AKTION_TMP.MENGE_ABSCHRIFT
WHERE TRUE;


UPDATE KFL_PRODUCTION_DBP_ETL.MARKTABSCHRIFT_AKTION_TMP SET
 ABSCHRIFTBETRAG_NETTO = (ROUND(CAST(MARKTABSCHRIFT_AKTION_TMP.VK_VOR_AKTION_BRUTTO / (1.00 + dt1.MWST_ / 100.00) AS NUMERIC)
     , 2) - ROUND(CAST(MARKTABSCHRIFT_AKTION_TMP.VK_AKTION_BRUTTO / (1.00 + dt1.MWST_ / 100.00) AS NUMERIC), 2)) *
  MARKTABSCHRIFT_AKTION_TMP.MENGE_ABSCHRIFT,
 VK_AKTION_NETTO = MARKTABSCHRIFT_AKTION_TMP.VK_AKTION_BRUTTO / (1.00 + dt1.MWST_ / 100.00),
 VK_VOR_AKTION_NETTO = MARKTABSCHRIFT_AKTION_TMP.VK_VOR_AKTION_BRUTTO / (1.00 + dt1.MWST_ / 100.00) FROM (SELECT
   MANDANT_ID AS MANDANT_ID_,
   MWST_ID AS MWST_ID_,
   DAT_VON AS DAT_VON_,
   MWST AS MWST_,
   DAT_BIS AS DAT_BIS_
  FROM KFL_PRODUCTION_DBP_DATA.MWST_PER
  WHERE MANDANT_ID > 1) AS dt1
WHERE MARKTABSCHRIFT_AKTION_TMP.DAT BETWEEN dt1.DAT_VON_ AND dt1.DAT_BIS_ AND MARKTABSCHRIFT_AKTION_TMP.MWST_ID = dt1.MWST_ID_
    AND MARKTABSCHRIFT_AKTION_TMP.MANDANT_ID = dt1.MANDANT_ID_;


DELETE FROM KFL_PRODUCTION_DBP_DATA.MARKTABSCHRIFTEN_KMO_AKTION
WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 45 DAY) AND (CURRENT_DATE);


INSERT INTO KFL_PRODUCTION_DBP_DATA.MARKTABSCHRIFTEN_KMO_AKTION (WUP_ID, NB_ID, AKTION_ID, MANDANT_ID, DAT, ART_ID,
 MENGE_ABSCHRIFT, ABSCHRIFTBETRAG_NETTO, ABSCHRIFTBETRAG_BRUTTO, WRG_ID, VK_AKTION_NETTO, VK_VOR_AKTION_NETTO,
 AKTION_RELEVANT_FG)
(SELECT WUP_ID,
  NB_ID,
  AKTION_ID,
  MANDANT_ID,
  DAT,
  ART_ID,
  MENGE_ABSCHRIFT,
  ABSCHRIFTBETRAG_NETTO,
  ABSCHRIFTBETRAG_BRUTTO,
  WRG_ID,
  VK_AKTION_NETTO,
  VK_VOR_AKTION_NETTO,
  AKTION_RELEVANT_FG
 FROM KFL_PRODUCTION_DBP_ETL.MARKTABSCHRIFT_AKTION_TMP);


CREATE OR REPLACE TABLE DEFAULTSCHEMA._upd_${TRANSIENT_TABLE_SUFFIX} AS
SELECT A.MANDANT_ID,
 A.WUP_ID,
 A.ART_ID,
 A.DAT,
 A.MENGE_ABSCHRIFT,
 A.VK_AKTION_NETTO,
 b.VK_AKTION_NETTO_FAKTURA,
 A.VK_VOR_AKTION_NETTO,
 b.VK_VOR_AKTION_NETTO_FAKTURA
FROM KFL_PRODUCTION_DBP_DATA.MARKTABSCHRIFTEN_KMO_AKTION AS A
 INNER JOIN (SELECT t0.MANDANT_ID,
   t0.ART_ID,
   t0.WUP_ID,
   t0.DAT_FAKTURA_SAP,
   ROUND(t0.VK_AKTION_BRUTTO / (1.00 + B.MWST / 100.00), 2) AS VK_AKTION_NETTO_FAKTURA,
   ROUND(t0.VK_VOR_AKTION_BRUTTO / (1.00 + B.MWST / 100.00), 2) AS VK_VOR_AKTION_NETTO_FAKTURA
  FROM (SELECT MANDANT_ID,
     ART_ID,
     WUP_ID,
     DAT_FAKTURA_SAP,
     VK_AKTION_BRUTTO,
     VK_VOR_AKTION_BRUTTO,
     AKTION_ID,
     MAX(SAP_MWST_ID) AS SAP_MWST_ID
    FROM KFL_PRODUCTION_DBP_DATA.BESCH_FAKTURA_DET_KMO
    GROUP BY MANDANT_ID,
     DAT_FAKTURA_SAP,
     ART_ID,
     WUP_ID,
     AKTION_ID,
     VK_AKTION_BRUTTO,
     VK_VOR_AKTION_BRUTTO) AS t0
   INNER JOIN KFL_PRODUCTION_DBP_DATA.MWST_PER AS B ON t0.MANDANT_ID = B.MANDANT_ID AND t0.SAP_MWST_ID = B.SAP_MWST_ID
    AND t0.DAT_FAKTURA_SAP BETWEEN B.DAT_VON AND B.DAT_BIS
  WHERE t0.AKTION_ID <> ''
   AND t0.DAT_FAKTURA_SAP BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 45 DAY) AND (CURRENT_DATE)
  GROUP BY t0.MANDANT_ID,
   t0.ART_ID,
   t0.WUP_ID,
   t0.DAT_FAKTURA_SAP,
   VK_AKTION_NETTO_FAKTURA,
   VK_VOR_AKTION_NETTO_FAKTURA) AS b ON A.MANDANT_ID = b.MANDANT_ID AND A.ART_ID = b.ART_ID AND A.WUP_ID = b.WUP_ID AND
   A.DAT = b.DAT_FAKTURA_SAP
WHERE A.DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 45 DAY) AND (CURRENT_DATE)
 AND A.AKTION_RELEVANT_FG = 1
 AND (A.VK_AKTION_NETTO <> b.VK_AKTION_NETTO_FAKTURA OR A.VK_VOR_AKTION_NETTO <> b.VK_VOR_AKTION_NETTO_FAKTURA);


UPDATE KFL_PRODUCTION_DBP_DATA.MARKTABSCHRIFTEN_KMO_AKTION SET
 VK_AKTION_NETTO = b.VK_AKTION_NETTO_FAKTURA,
 VK_VOR_AKTION_NETTO = b.VK_VOR_AKTION_NETTO_FAKTURA,
 ABSCHRIFTBETRAG_NETTO = CAST((b.VK_VOR_AKTION_NETTO_FAKTURA - b.VK_AKTION_NETTO_FAKTURA) * b.MENGE_ABSCHRIFT AS NUMERIC)
 FROM DEFAULTSCHEMA._upd_${TRANSIENT_TABLE_SUFFIX} AS b
WHERE MARKTABSCHRIFTEN_KMO_AKTION.MANDANT_ID = b.MANDANT_ID AND MARKTABSCHRIFTEN_KMO_AKTION.WUP_ID = b.WUP_ID AND
    MARKTABSCHRIFTEN_KMO_AKTION.ART_ID = b.ART_ID AND MARKTABSCHRIFTEN_KMO_AKTION.DAT = b.DAT AND
  MARKTABSCHRIFTEN_KMO_AKTION.AKTION_RELEVANT_FG = 1;