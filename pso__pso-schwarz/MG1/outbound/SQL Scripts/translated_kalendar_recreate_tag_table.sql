INSERT INTO KFL_PRODUCTION_DBP_DATA.TAG (DAT, KJMO, KJMO_VJ, KJMO_VVJ, WTAG_ID, KJWO, KJWO_VJ, KJWO_VVJ, GJWO, GJWO_VJ,
 WO_DAT_VON, WO_DAT_BIS, GJMO, GJMO_VJ, KJQU, GJQU, KJ, GJ, KJTAG_ID, GJTAG_ID, KJWO_KL, KJWO_KL_DAT_VON,
 KJWO_KL_DAT_BIS, GJWO_KL, GJWO_KL_DAT_VON, GJWO_KL_DAT_BIS, DAT_VJ, DAT_VVJ, AKT_TAG, AKT_MO, AKT_MO_KOMPLETT, AKT_WO,
 AKT_WO_KOMPLETT, AKT_GJWO_KL, AKT_GJWO_KL_KOMPLETT, AKT_KJWO_KL, AKT_KJWO_KL_KOMPLETT, AKT_GJQU, AKT_GJQU_KOMPLETT,
 AKT_KJQU, AKT_KJQU_KOMPLETT, AKT_GJ, AKT_GJ_KOMPLETT, AKT_KJ, AKT_KJ_KOMPLETT, MO_GJ, MO_KJ, PJWO, GJHJ, AKT_GJHJ,
 AKT_GJHJ_KOMPLETT, DAT_VJ_KT)
(SELECT T0.DAT,
  T0.KJMO,
  T0.KJMO_VJ,
     (EXTRACT(YEAR FROM DATE(SUBSTR(CAST(T0.KJMO AS STRING), 1, 6))) - 2) * 100 + EXTRACT(MONTH FROM DATE(SUBSTR(CAST(T0.KJMO AS STRING)
      , 1, 6))) AS KJMO_VVJ,
  T0.WTAG_ID,
  T0.KJWO,
  T0.KJWO_VJ,
  CAST((ROUND(CAST(SUBSTR(SUBSTR(CAST(T0.KJWO_VJ AS STRING), 1, 10), 1, 4) AS BIGNUMERIC), 0) - 1) * 100 + ROUND(CAST(SUBSTR(SUBSTR(CAST(T0.KJWO_VJ AS STRING)
        , 1, 10), 5, 2) AS BIGNUMERIC), 0) AS INTEGER) AS KJWO_VVJ,
  T0.GJWO,
  T0.GJWO_VJ,
  T0.WO_DAT_VON,
  T0.WO_DAT_BIS,
  T0.GJMO,
  T0.GJMO_VJ,
  T0.KJQU,
  T0.GJQU,
  T0.KJ,
  T0.GJ,
  T0.KJTAG_ID,
  T0.GJTAG_ID,
  T0.KJWO_KL,
  T0.KJWO_KL_DAT_VON,
  T0.KJWO_KL_DAT_BIS,
  T0.GJWO_KL,
  T0.GJWO_KL_DAT_VON,
  T0.GJWO_KL_DAT_BIS,
  T0.DAT_VJ,
  DATE_SUB(T0.DAT, INTERVAL 728 DAY) AS DAT_VVJ,
   T0.AKT_TAG - T1.AKT_TAG AS AKT_TAG,
   T0.AKT_MO - T1.AKT_MO AS AKT_MO,
   T0.AKT_MO - T1.AKT_MO_KOMPLETT AS AKT_MO_KOMPLETT,
   T0.AKT_WO - T1.AKT_WO AS AKT_WO,
   T0.AKT_WO - T1.AKT_WO_KOMPLETT AS AKT_WO_KOMPLETT,
   T0.AKT_GJWO_KL - T1.AKT_GJWO_KL AS AKT_GJWO_KL,
   T0.AKT_GJWO_KL - T1.AKT_GJWO_KL_KOMPLETT AS AKT_GJWO_KL_KOMPLETT,
   T0.AKT_KJWO_KL - T1.AKT_KJWO_KL AS AKT_KJWO_KL,
   T0.AKT_KJWO_KL - T1.AKT_KJWO_KL_KOMPLETT AS AKT_KJWO_KL_KOMPLETT,
   T0.AKT_GJQU - T1.AKT_GJQU AS AKT_GJQU,
   T0.AKT_GJQU - T1.AKT_GJQU_KOMPLETT AS AKT_GJQU_KOMPLETT,
   T0.AKT_KJQU - T1.AKT_KJQU AS AKT_KJQU,
   T0.AKT_KJQU - T1.AKT_KJQU_KOMPLETT AS AKT_KJQU_KOMPLETT,
   T0.AKT_GJ - T1.AKT_GJ AS AKT_GJ,
   T0.AKT_GJ - T1.AKT_GJ_KOMPLETT AS AKT_GJ_KOMPLETT,
   T0.AKT_KJ - T1.AKT_KJ AS AKT_KJ,
   T0.AKT_KJ - T1.AKT_KJ_KOMPLETT AS AKT_KJ_KOMPLETT,
  T0.MO_GJ,
  T0.MO_KJ,
  T0.PJWO,
  T0.GJHJ,
   T0.AKT_GJHJ - T1.AKT_GJHJ AS AKT_GJHJ,
   T0.AKT_GJHJ - T1.AKT_GJHJ_KOMPLETT AS AKT_GJHJ_KOMPLETT,
   (SAFE.PARSE_DATE('%F', CONCAT(EXTRACT(YEAR FROM T0.DAT) - 1, '-', EXTRACT(MONTH FROM T0.DAT), '-', EXTRACT(DAY FROM
      T0.DAT)))) AS DAT_VJ_KT
 FROM KFL_PRODUCTION_DBP_ETL_PROCESS.TAG_MASTER AS T0
  INNER JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.TAG_MASTER AS T1 ON T0.DAT <= DATE_ADD(T1.DAT, INTERVAL 3650 DAY)
 WHERE T1.DAT = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY));


UPDATE KFL_PRODUCTION_DBP_DATA.TAG AS TAG0 SET
 KJWO_VVJ = CAST(b.KJWO_NEU AS INTEGER) FROM (SELECT a.KJWO,
    SUBSTR(CAST(CAST(FLOOR(a.KJWO / 100) AS INTEGER) + 1 AS STRING), 1, 4) || '01' AS KJWO_NEU
  FROM (SELECT KJWO_VVJ AS KJWO
    FROM KFL_PRODUCTION_DBP_DATA.TAG
    WHERE DAT >= DATE '2000-01-01'
    GROUP BY KJWO) AS a
   LEFT JOIN KFL_PRODUCTION_DBP_DATA.TAG AS B ON a.KJWO = B.KJWO
  WHERE B.DAT IS NULL
  GROUP BY a.KJWO,
   KJWO_NEU) AS b
WHERE TAG0.KJWO_VVJ = b.KJWO;


