      END AS DAT_BIS_
    FROM
      _ART_GP_NM_ZU_PER_TMP2 AS _ART_GP_NM_ZU_PER_TMP2_0
    GROUP BY 1, 2, 3, 4
) AS DT1 WHERE _art_gp_nm_zu_per_tmp2.MANDANT_ID = DT1.MANDANT_ID
