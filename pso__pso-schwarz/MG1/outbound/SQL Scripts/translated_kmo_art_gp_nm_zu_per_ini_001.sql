DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.ART_GP_NM_ZU_PER_DAT_RELEVANT;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.ART_GP_NM_ZU_PER_DAT_RELEVANT (
DAT_RELEVANT DATE NOT NULL,
DAT_AUSSTIEG DATE NOT NULL
);


DELETE FROM KFL_PRODUCTION_DBP_ETL_PROCESS.METADATA_KMO_BQ_FINDUNG
WHERE ENDE IS NULL;


INSERT INTO KFL_PRODUCTION_DBP_ETL.ART_GP_NM_ZU_PER_DAT_RELEVANT (DAT_RELEVANT, DAT_AUSSTIEG)
(SELECT MIN(DAT) AS DAT_RELEVANT,
  MAX(DAT) AS DAT_AUSSTIEG
 FROM KFL_PRODUCTION_DBP_DATA.TAG
 WHERE DAT BETWEEN (SELECT DATE_ADD(MAX(SNAPSHOT_DATUM), INTERVAL 1 DAY)
    FROM KFL_PRODUCTION_DBP_ETL_PROCESS.METADATA_KMO_BQ_FINDUNG) AND (DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)));