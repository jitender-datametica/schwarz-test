INSERT INTO `_HAUPTLIEFERANT` (DAT_RELEVANT, MANDANT_ID, WUP_ID, NB_ID, ART_ID, GP_ID)
(SELECT b.DAT_RELEVANT,
  A.MANDANT_ID,
  - 1 AS WUP_ID,
  - 1 AS NB_ID,
  CAST(A.ART_ID AS INTEGER) AS ART_ID,
  CAST(MAX(b.GP_ID) AS INTEGER) AS GP_ID
 FROM KFL_PRODUCTION_DBP_DATA.ART_GP_NM_ZU_PER AS A
  INNER JOIN (SELECT t1.DAT_RELEVANT,
    t1.MANDANT_ID,
    t1.ART_ID,
    t1.GP_ID
   FROM (SELECT R.DAT_RELEVANT,
      A0.MANDANT_ID,
      A0.ART_ID,
      A0.GP_ID,
      COUNT(*) AS z0
     FROM KFL_PRODUCTION_DBP_DATA.ART_GP_NM_ZU_PER AS A0
      INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_ART_WUP_EK_DATUM_RELEVANT AS R ON TRUE
     WHERE A0.GP_ID <> - 1
      AND A0.MANDANT_ID > 1
      AND R.DAT_RELEVANT BETWEEN A0.DAT_VON AND A0.DAT_BIS
     GROUP BY A0.MANDANT_ID,
      A0.ART_ID,
      A0.GP_ID,
      R.DAT_RELEVANT) AS t1
   QUALIFY (RANK() OVER (PARTITION BY CAST(t1.MANDANT_ID AS STRING), CAST(t1.ART_ID AS STRING) ORDER BY t1.z0 IS NULL
         DESC, t1.z0 DESC)) = 1) AS b ON A.MANDANT_ID = b.MANDANT_ID AND A.ART_ID = b.ART_ID AND b.DAT_RELEVANT BETWEEN
    A.DAT_VON AND A.DAT_BIS
 GROUP BY A.MANDANT_ID,
  A.ART_ID,
  b.DAT_RELEVANT);


