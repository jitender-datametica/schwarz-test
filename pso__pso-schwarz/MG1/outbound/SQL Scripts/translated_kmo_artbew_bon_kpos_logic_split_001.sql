CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_BON_DELTA_MAIN (
MANDANT_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
DAT_BOOKING DATE NOT NULL,
XML_NAME STRING(255)
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_BON_DELTA_MAIN (MANDANT_ID, WUP_ID, DAT_BOOKING, XML_NAME)
(SELECT T.MANDANT_ID,
  T.WUP_ID,
  T.DAT_BOOKING,
  B.XML_NAME
 FROM KFL_PRODUCTION_DBP_ODS.ODS_BON_TRANSACTION AS T
  INNER JOIN KFL_PRODUCTION_DBP_ODS.BON_LOAD_STATUS AS B ON T.DATEI_NAME = B.XML_NAME AND B.ARTBEW_FG = 0
 WHERE T.MANDANT_ID > 1
  AND TRIM(T.KASSENSYSTEM_NAME) = 'KPOS'
  AND B.PARSEBON_TIME <= CAST(TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 10 MINUTE) AS DATETIME)
  AND DATE(T.BON_BOOKING) <= DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
 GROUP BY T.WUP_ID,
  T.MANDANT_ID,
  T.DAT_BOOKING,
  B.XML_NAME);