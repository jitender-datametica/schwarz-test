INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_WG_SUM_TMP (MANDANT_ID, NB_ID, ARTHIERTYP_ID, WG_ID, DAT, WUP_ID,
 BEWART_ID, KJMO, UMSATZ_BRUTTO, UMSATZ_NETTO, UMSATZ_WRG, UMSATZ_BRUTTO_KONZ, UMSATZ_NETTO_KONZ, QUELLE, MENGE)
(SELECT MANDANT_ID,
  NB_ID,
  ARTHIERTYP_ID,
  WG_ID,
  DAT,
  WUP_ID,
  BEWART_ID,
  CAST(KJMO AS INTEGER) AS KJMO,
  SUM(UMSATZ_BRUTTO),
  SUM(UMSATZ_NETTO),
  UMSATZ_WRG,
  SUM(UMSATZ_BRUTTO_KONZ),
  SUM(UMSATZ_NETTO_KONZ),
  QUELLE,
  SUM(MENGE)
 FROM (SELECT Z.MANDANT_ID,
    Z.WUP_ID,
    Z.LKP_WG_ID AS WG_ID,
    1001 AS BEWART_ID,
    Z.DAT_BOOKING AS DAT,
    Z.LKP_NB_ID AS NB_ID,
    2 AS ARTHIERTYP_ID,
    Z.LKP_WRG AS UMSATZ_WRG,
    ROUND(CAST(FORMAT_DATE('%Y%m', Z.DAT_BOOKING) AS BIGNUMERIC), 0) AS KJMO,
    1 AS QUELLE,
    SUM(ROUND(CAST(Z.UMSATZ_BRUTTO * CASE
         WHEN y.CONV_FG = 1
         THEN Z.LKP_UMRECHNUNGSKURS
         ELSE 1
         END AS NUMERIC), 8)) AS UMSATZ_BRUTTO,
    CAST(SUM(ROUND(CAST(Z.UMSATZ_BRUTTO * CASE
           WHEN y.CONV_FG = 1
           THEN Z.LKP_UMRECHNUNGSKURS
           ELSE 1
           END AS NUMERIC), 8)) / (1 + Z.LKP_MWST / 100) AS NUMERIC) AS UMSATZ_NETTO,
    0 AS UMSATZ_BRUTTO_KONZ,
    0 AS UMSATZ_NETTO_KONZ,
    SUM(Z.MENGE) AS MENGE
   FROM KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_BON AS Z
    LEFT JOIN (SELECT MANDANT_ID,
      WRG_ID,
      DAT_VON,
      DAT_BIS,
      TD_UPDATE,
      TD_INSERT,
      VON_WRG_ID,
      UMRECHNUNGSKURS,
      1 AS CONV_FG
     FROM KFL_PRODUCTION_DBP_DATA.MANDANT_WRG_ZU_PER AS A
     WHERE WRG_ID <> VON_WRG_ID
      AND CURRENT_DATE BETWEEN DAT_VON AND DAT_BIS) AS y ON Z.MANDANT_ID = y.MANDANT_ID AND Z.LKP_WRG = y.WRG_ID
    LEFT JOIN (SELECT MANDANT_ID,
      BON_ID,
      DAT_BOOKING,
      BON_ZEILE,
      SUM(UMSATZ_BRUTTO) AS PROMOTION_BRUTTO
     FROM KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_BON_PROMOTION
     GROUP BY MANDANT_ID,
      BON_ID,
      DAT_BOOKING,
      BON_ZEILE) AS p ON Z.MANDANT_ID = p.MANDANT_ID AND Z.BON_ID = p.BON_ID AND Z.DAT_BOOKING = p.DAT_BOOKING AND Z.BON_ZEILE
       = p.BON_ZEILE
   GROUP BY Z.MANDANT_ID,
    Z.WUP_ID,
    Z.LKP_WG_ID,
    Z.DAT_BOOKING,
    Z.LKP_POSTEN_ID,
    Z.LKP_NB_ID,
    Z.LKP_MWST,
    Z.LKP_WRG) AS a
 GROUP BY MANDANT_ID,
  WUP_ID,
  WG_ID,
  BEWART_ID,
  DAT,
  NB_ID,
  ARTHIERTYP_ID,
  UMSATZ_WRG,
  KJMO,
  QUELLE);


UPDATE KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_WG_SUM_TMP SET
 UMSATZ_BRUTTO_KONZ = ROUND(CAST(KMO_ARTBEW_WG_SUM_TMP.UMSATZ_BRUTTO * K.UMRECHNUNGSKURS AS NUMERIC), 4),
 UMSATZ_NETTO_KONZ = ROUND(CAST(KMO_ARTBEW_WG_SUM_TMP.UMSATZ_NETTO * K.UMRECHNUNGSKURS AS NUMERIC), 4) FROM
 KFL_PRODUCTION_DBP_DATA.KURS AS K
WHERE KMO_ARTBEW_WG_SUM_TMP.UMSATZ_WRG = K.VON_WRG_ID AND KMO_ARTBEW_WG_SUM_TMP.DAT BETWEEN K.DAT_VON AND K.DAT_BIS AND
   K.NACH_WRG_ID = 'EUR' AND K.KURSTYP_ID = 3;


