DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_PAYBACK_TMP;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_PAYBACK_TMP LIKE KFL_PRODUCTION_DBP_DATA.ARTBEW;


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_PAYBACK_TMP (MANDANT_ID, WUP_ID, NB_ID, DAT, BEWART_ID, GP_ID, ART_ID, AKTION_ID, PROMO_FG, EAN_KASSE, EINKAUFSORGANISATION_ID, HERST_ID, MWST_ID, MENGE, WRG, UMSATZ_NETTO, DIFF_UMSATZ_NETTO_KONZ, UMSATZ_MWST_BETRAG, DIFF_UMSATZ_MWST_BETRAG_KONZ, EK_BRUTTO, DIFF_EK_BRUTTO_KONZ, EK_NETTO, DIFF_EK_NETTO_KONZ, EK_NETTONETTO, DIFF_EK_NETTONETTO_KONZ, EK_KAL_BASIS, DIFF_EK_KAL_BASIS_KONZ, EK_MEP, DIFF_EK_MEP_KONZ, EK_MEP_VOR_FWU, EK_MEP_VOR_FWU_KONZ, EINSTANDSPREIS, DIFF_EINSTANDSPREIS_KONZ, LOGKOSTENZUSCHLAG, DIFF_LOGKOSTENZUSCHLAG_KONZ, BEZUGSWEG_ID, EK_NETTO_BNK, DIFF_EK_NETTO_BNK_KONZ, EK_NETTO_BNK_SACHK, DIFF_EK_NETTO_BNK_SACHK_KONZ, POSTEN_ID, BQ_FINDUNG_ID, EK_GLD, DIFF_EK_GLD_KONZ, BONUSBASIS, BONUSBASIS_KONZ)
  SELECT
      T1.MANDANT_ID,
      T1.WUP_ID,
      T1.NB_ID,
      T1.DAT_BUCH AS DAT,
      1010 AS BEWART_ID,
      -1 AS GP_ID,
      T1.ART_ID,
      '          ' AS AKTION_ID,
      0 AS PROMO_FG,
      0 AS EAN_KASSE,
      T3.EINKAUFSORGANISATION_ID,
      -1 AS HERST_ID,
      T4.MWST_ID,
      0 AS MENGE,
      T1.WRG_ID AS WRG,
      T1.BETRAG_FI_BELEG_SUM AS UMSATZ_NETTO,
      0 AS DIFF_UMSATZ_NETTO_KONZ,
      0 AS UMSATZ_MWST_BETRAG,
      0 AS DIFF_UMSATZ_MWST_BETRAG_KONZ,
      T5.ZERO_ENC AS EK_BRUTTO,
      T5.ZERO_ENC AS DIFF_EK_BRUTTO_KONZ,
      T5.ZERO_ENC AS EK_NETTO,
      T5.ZERO_ENC AS DIFF_EK_NETTO_KONZ,
      T5.ZERO_ENC AS EK_NETTONETTO,
      T5.ZERO_ENC AS DIFF_EK_NETTONETTO_KONZ,
      T5.ZERO_ENC AS EK_KAL_BASIS,
      T5.ZERO_ENC AS DIFF_EK_KAL_BASIS_KONZ,
      T5.ZERO_ENC AS EK_MEP,
      T5.ZERO_ENC AS DIFF_EK_MEP_KONZ,
      0 AS EK_MEP_VOR_FWU,
      0 AS EK_MEP_VOR_FWU_KONZ,
      T5.ZERO_ENC AS EINSTANDSPREIS,
      T5.ZERO_ENC AS DIFF_EINSTANDSPREIS_KONZ,
      0 AS LOGKOSTENZUSCHLAG,
      0 AS DIFF_LOGKOSTENZUSCHLAG_KONZ,
      1 AS BEZUGSWEG_ID,
      T5.ZERO_ENC AS EK_NETTO_BNK,
      T5.ZERO_ENC AS DIFF_EK_NETTO_BNK_KONZ,
      T5.ZERO_ENC AS EK_NETTO_BNK_SACHK,
      T5.ZERO_ENC AS DIFF_EK_NETTO_BNK_SACHK_KONZ,
      substr(substr(CAST(0 as STRING), 1, 16777216), 1, 2) AS POSTEN_ID,
      25 AS BQ_FINDUNG_ID,
      0 AS EK_GLD,
      0 AS DIFF_EK_GLD_KONZ,
      0 AS BONUSBASIS,
      0 AS BONUSBASIS_KONZ
    FROM
      KFL_PRODUCTION_DBP_ETL_PROCESS.IN_FI_BELEG_DET_AGG_PAYBACK AS T1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.L_EINKAUFSORGANISATION AS T3 ON T1.MANDANT_ID = T3.MANDANT_ID
      INNER JOIN (
        SELECT
            MWST_PER.MANDANT_ID,
            max(MWST_PER.MWST_ID) AS MWST_ID
          FROM
            KFL_PRODUCTION_DBP_DATA.MWST_PER
          WHERE MWST_PER.DAT_BIS = PARSE_DATE('%Y%m%d', '99991231')
           AND MWST_PER.MWST = 0
          GROUP BY 1
      ) AS T4 ON T1.MANDANT_ID = T4.MANDANT_ID
      INNER JOIN (
        SELECT
            MANDANT.MANDANT_ID,
            0 AS ZERO_ENC
          FROM
            KFL_PRODUCTION_DBP_DATA.MANDANT
      ) AS T5 ON T1.MANDANT_ID = T5.MANDANT_ID
       AND (CAST(T1.VERARBEITET_FG as INT64)>> 2)&1 = 0
;




