UPDATE KFL_PRODUCTION_DBP_ETL_PROCESS.IN_FI_BELEG_DET_AGG_PAYBACK AS t
SET
  VERARBEITET_FG = CAST(t.VERARBEITET_FG AS INT64) | (1 << 0)  -- artbew_wg_sum-verarbeitung
WHERE EXISTS (
  SELECT 1
  FROM KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_PAYBACK_TMP AS s
  WHERE t.MANDANT_ID = s.MANDANT_ID
    AND t.WUP_ID       = s.WUP_ID
    AND t.DAT_BUCH     = s.DAT
);



