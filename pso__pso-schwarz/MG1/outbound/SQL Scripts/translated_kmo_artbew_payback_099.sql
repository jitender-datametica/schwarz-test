DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW
WHERE BEWART_ID = 1010 AND (MANDANT_ID, WUP_ID, NB_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
   FROM KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_PAYBACK_TMP);



