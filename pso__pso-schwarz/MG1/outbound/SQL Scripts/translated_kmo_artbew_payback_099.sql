INSERT INTO KFL_PRODUCTION_DBP_ETL_PROCESS.UAPC_ARTBEW_DELTA (MANDANT_ID, WUP_ID, DAT, ROW_ID, PROCESSED_AT, TD_INSERT,
 TD_UPDATE)
(SELECT MANDANT_ID,
  WUP_ID,
  DAT,
    (ROW_NUMBER() OVER (ORDER BY MANDANT_ID IS NULL, MANDANT_ID, WUP_ID IS NULL, WUP_ID, DAT IS NULL, DAT)) + COALESCE((SELECT
      MAX(ROW_ID)
     FROM KFL_PRODUCTION_DBP_ETL_PROCESS.UAPC_ARTBEW_DELTA), 0) AS ROW_ID,
  CAST(NULL AS TIMESTAMP) AS PROCESSED_AT,
  CURRENT_TIMESTAMP() AS TD_INSERT,
  CURRENT_TIMESTAMP() AS TD_UPDATE
 FROM KFL_PRODUCTION_DBP_ETL.KMO_ARTBEW_PAYBACK_TMP
 WHERE (MANDANT_ID, WUP_ID, DAT, DATE(CURRENT_TIMESTAMP())) NOT IN (SELECT (MANDANT_ID, WUP_ID, DAT, DATE(TD_INSERT))
    FROM KFL_PRODUCTION_DBP_ETL_PROCESS.UAPC_ARTBEW_DELTA)
 GROUP BY MANDANT_ID,
  WUP_ID,
  DAT);

-- 2. Verarbeitung Payback (PL) fuers VIS

DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP LIKE KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM;



INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP (MANDANT_ID, NB_ID, ARTHIERTYP_ID, WG_ID, DAT, WUP_ID, BEWART_ID, KJMO, UMSATZ_BRUTTO, UMSATZ_NETTO, UMSATZ_WRG, UMSATZ_BRUTTO_KONZ, UMSATZ_NETTO_KONZ, QUELLE, MENGE)
  SELECT
      T1.MANDANT_ID,
      T1.NB_ID,
      T2.ARTHIERTYP_ID,
      T2.WG_ID,
      T1.DAT_BUCH AS DAT,
      T1.WUP_ID,
      1010 AS BEWART_ID,        /*Payback aus FI*/
      --,t1.dat_buch /100 + 190000 as kjmo
      round(CAST(FORMAT_DATE('%Y%m', T1.DAT_BUCH)AS NUMERIC), 0) AS KJMO,
      T1.BETRAG_FI_BELEG_SUM AS UMSATZ_BRUTTO,
      T1.BETRAG_FI_BELEG_SUM AS UMSATZ_NETTO,
      T1.WRG_ID AS UMSATZ_WRG,
      T1.BETRAG_FI_BELEG_SUM AS UMSATZ_BRUTTO_KONZ,
      T1.BETRAG_FI_BELEG_SUM AS UMSATZ_NETTO_KONZ,
      10 AS QUELLE,  /*Payback aus FI*/
      0 AS MENGE
    FROM
      KFL_PRODUCTION_DBP_ETL_PROCESS.IN_FI_BELEG_DET_AGG_PAYBACK AS T1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER AS T2 ON T1.MANDANT_ID = T2.MANDANT_ID
       AND T1.ART_ID = T2.ART_ID
       AND T2.DAT_BIS = PARSE_DATE('%Y%m%d', '99991231')
       AND T2.ARTHIERTYP_ID = 2
       AND (CAST(T1.VERARBEITET_FG as INT64)>> 1)&1 = 0
;


UPDATE KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP SET
 UMSATZ_BRUTTO_KONZ = ROUND(CAST(KMO_WPUUMS_PAYBACK_TMP.UMSATZ_BRUTTO * K.UMRECHNUNGSKURS AS NUMERIC), 4),
 UMSATZ_NETTO_KONZ = ROUND(CAST(KMO_WPUUMS_PAYBACK_TMP.UMSATZ_NETTO * K.UMRECHNUNGSKURS AS NUMERIC), 4) FROM
 KFL_PRODUCTION_DBP_DATA.KURS AS K
WHERE KMO_WPUUMS_PAYBACK_TMP.UMSATZ_WRG = K.VON_WRG_ID AND KMO_WPUUMS_PAYBACK_TMP.DAT BETWEEN K.DAT_VON AND K.DAT_BIS
  AND K.NACH_WRG_ID = 'EUR' AND K.KURSTYP_ID = 3;


DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM
WHERE BEWART_ID = 1010 AND (MANDANT_ID, WUP_ID, NB_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
    FROM KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP) AND QUELLE = 10   -- Daten in der Zieltabelle stammen aus der Payback aus FI
    ;


INSERT INTO KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM (MANDANT_ID, WUP_ID, WG_ID, BEWART_ID, DAT, NB_ID, ARTHIERTYP_ID, UMSATZ_BRUTTO, UMSATZ_NETTO, UMSATZ_WRG, UMSATZ_BRUTTO_KONZ, UMSATZ_NETTO_KONZ, KJMO, MENGE, QUELLE, UMRECHNUNGSKURS_HIST)
  SELECT
      A.MANDANT_ID,
      A.WUP_ID,
      A.WG_ID,
      A.BEWART_ID,
      A.DAT,
      A.NB_ID,
      A.ARTHIERTYP_ID,
      A.UMSATZ_BRUTTO,
      A.UMSATZ_NETTO,
      A.UMSATZ_WRG,
      A.UMSATZ_BRUTTO_KONZ,
      A.UMSATZ_NETTO_KONZ,
      A.KJMO,
      A.MENGE,
      A.QUELLE,
      K.UMRECHNUNGSKURS AS UMRECHNUNGSKURS_HIST
    FROM
      KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP AS A
      LEFT OUTER JOIN KFL_PRODUCTION_DBP_DATA.KURS AS K ON A.UMSATZ_WRG = K.VON_WRG_ID
       AND A.DAT BETWEEN K.DAT_VON AND K.DAT_BIS
       AND K.NACH_WRG_ID = 'EUR'
       AND K.KURSTYP_ID = 3
;


UPDATE KFL_PRODUCTION_DBP_ETL_PROCESS.IN_FI_BELEG_DET_AGG_PAYBACK AS t
SET
  VERARBEITET_FG = CAST(t.VERARBEITET_FG AS INT64) | (1 << 1)  -- artbew_wg_sum-verarbeitung
WHERE EXISTS (
  SELECT 1
  FROM KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_PAYBACK_TMP AS s
  WHERE t.MANDANT_ID = s.MANDANT_ID
    AND t.WUP_ID       = s.WUP_ID
    AND t.DAT_BUCH     = s.DAT
);



