DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.KMO_MARM_ANR;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.KMO_MARM_ANR (
MATNR INTEGER NOT NULL,
MANDANT_ID INTEGER NOT NULL,
ALTNV_MENGE_EINH_ID STRING(3) COLLATE 'und:ci' NOT NULL,
BRUTTOGEW NUMERIC(18,3) NOT NULL,
GEW_EINH_ID STRING(3) COLLATE 'und:ci' NOT NULL,
UMRECH_FAKTOR FLOAT64 NOT NULL,
DAT_VON DATE NOT NULL,
DAT_BIS DATE NOT NULL,
LAENGE NUMERIC(18,3) NOT NULL,
BREITE NUMERIC(18,3) NOT NULL,
HOEHE NUMERIC(18,3) NOT NULL,
UMREN INTEGER,
UMREZ INTEGER,
TD_INSERT TIMESTAMP
);


CREATE TEMPORARY TABLE IF NOT EXISTS _DUP_CHECK AS
SELECT A.MATNR,
 A.MATNR_CHAR,
 A.QUELLSYSTEM,
 A.MEINH,
 A.BRGEW,
 A.GEWEI,
 A.UMREZ,
 A.UMREN,
 A.LAENGE,
 A.BREITE,
 A.HOEHE,
 A.BEZUGSDATUM,
 A.MANDANT_ID,
 A.TD_INSERT
FROM KFL_PRODUCTION_DBP_ETL.KMO_MARM AS A
 INNER JOIN (SELECT MANDANT_ID,
   MATNR_CHAR,
   MEINH
  FROM KFL_PRODUCTION_DBP_ETL.KMO_MARM
  GROUP BY MATNR_CHAR,
   MEINH,
   MANDANT_ID
  HAVING COUNT(*) > 1) AS b ON A.MANDANT_ID = b.MANDANT_ID AND A.MATNR_CHAR = b.MATNR_CHAR AND A.MEINH = b.MEINH
QUALIFY (ROW_NUMBER() OVER (PARTITION BY CAST(A.MANDANT_ID AS STRING), A.MATNR_CHAR, A.MEINH ORDER BY A.MANDANT_ID
      IS NULL, A.MANDANT_ID, A.MATNR_CHAR IS NULL, A.MATNR_CHAR, A.MEINH IS NULL, A.MEINH, A.BEZUGSDATUM IS NULL DESC, A
      .BEZUGSDATUM DESC)) = 1;


DELETE FROM KFL_PRODUCTION_DBP_ETL.KMO_MARM
WHERE (MANDANT_ID, MATNR_CHAR, MEINH) IN (SELECT (MANDANT_ID, MATNR_CHAR, MEINH)
  FROM `_DUP_CHECK`);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_MARM
(SELECT *
 FROM `_DUP_CHECK`);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_MARM_ANR (MATNR, MANDANT_ID, ALTNV_MENGE_EINH_ID, BRUTTOGEW, GEW_EINH_ID,
 UMRECH_FAKTOR, DAT_VON, DAT_BIS, LAENGE, BREITE, HOEHE, UMREN, UMREZ)
(SELECT MATNR,
  CAST(MANDANT_ID AS INTEGER) AS MANDANT_ID,
  COALESCE(SUBSTR(MEINH, 1, 3), '-1') AS ALTNV_MENGE_EINH_ID,
  COALESCE(BRGEW, 0) AS BRUTTOGEW,
  COALESCE(SUBSTR(GEWEI, 1, 3), '-1') AS GEW_EINH_ID,
  COALESCE(CAST(CAST(UMREN AS FLOAT64) / UMREZ AS FLOAT64), 1) AS UMRECH_FAKTOR,
  DATE_SUB(BEZUGSDATUM, INTERVAL 1 DAY),
  PARSE_DATE('%Y%m%d', '99991231') AS DAT_BIS,
  COALESCE(LAENGE, 0) AS LAENGE,
  COALESCE(BREITE, 0) AS BREITE,
  COALESCE(HOEHE, 0) AS HOEHE,
  CAST(UMREN AS INTEGER) AS UMRECH_NENNER,
  CAST(UMREZ AS INTEGER) AS UMRECH_ZAEHLER
 FROM KFL_PRODUCTION_DBP_ETL.KMO_MARM AS M);


DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.ART_UMRECHNUNG_FAKTOR_PER_TMP;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.ART_UMRECHNUNG_FAKTOR_PER_TMP (
ART_ID INTEGER NOT NULL,
MANDANT_ID INTEGER NOT NULL,
ALTNV_MENGE_EINH_ID STRING(3) COLLATE 'und:ci' NOT NULL,
BRUTTOGEW NUMERIC(18,3) NOT NULL,
GEW_EINH_ID STRING(3) COLLATE 'und:ci' NOT NULL,
UMRECH_FAKTOR FLOAT64 NOT NULL,
DAT_VON DATE NOT NULL,
DAT_BIS DATE NOT NULL,
LAENGE NUMERIC(18,3) NOT NULL,
BREITE NUMERIC(18,3) NOT NULL,
HOEHE NUMERIC(18,3) NOT NULL,
UMRECH_NENNER INTEGER,
UMRECH_ZAEHLER INTEGER
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ART_UMRECHNUNG_FAKTOR_PER_TMP (ART_ID, MANDANT_ID, ALTNV_MENGE_EINH_ID, BRUTTOGEW,
 GEW_EINH_ID, UMRECH_FAKTOR, DAT_VON, DAT_BIS, LAENGE, BREITE, HOEHE, UMRECH_NENNER, UMRECH_ZAEHLER)
(SELECT CAST(t0.ART_ID AS INTEGER) AS ART_ID,
  DT1.MANDANT_ID,
  DT1.ALTNV_MENGE_EINH_ID,
  DT1.BRUTTOGEW,
  DT1.GEW_EINH_ID,
  DT1.UMRECH_FAKTOR,
  DT1.DAT_VON,
  DT1.DAT_BIS,
  DT1.LAENGE,
  DT1.BREITE,
  DT1.HOEHE,
  DT1.UMREN,
  DT1.UMREZ
 FROM KFL_PRODUCTION_DBP_ETL.KMO_MARM_ANR AS DT1
  INNER JOIN (SELECT KL_ART_ID,
    ART_ID,
    MANDANT_ID
   FROM KFL_PRODUCTION_DBP_DATA.ART
   QUALIFY (ROW_NUMBER() OVER (PARTITION BY CAST(KL_ART_ID AS STRING), CAST(MANDANT_ID AS STRING) ORDER BY ART_ID
         IS NULL DESC, ART_ID DESC)) = 1) AS t0 ON DT1.MATNR = t0.KL_ART_ID AND DT1.MANDANT_ID = t0.MANDANT_ID);


DELETE FROM KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER
WHERE (MANDANT_ID, ART_ID, ALTNV_MENGE_EINH_ID, DAT_VON) IN (SELECT (CAST(MANDANT_ID AS BIGNUMERIC), CAST(ART_ID AS BIGNUMERIC)
    , ALTNV_MENGE_EINH_ID, DAT_VON)
  FROM KFL_PRODUCTION_DBP_ETL.ART_UMRECHNUNG_FAKTOR_PER_TMP);




INSERT INTO KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER (MANDANT_ID, ALTNV_MENGE_EINH_ID, ART_ID, DAT_VON,
 BRUTTOGEW, UMRECH_FAKTOR, GEW_EINH_ID, DAT_BIS, LAENGE, BREITE, HOEHE, UMRECH_ZAEHLER, UMRECH_NENNER)
(SELECT MANDANT_ID,
  ALTNV_MENGE_EINH_ID,
  ART_ID,
  DAT_VON,
  BRUTTOGEW,
  UMRECH_FAKTOR,
  GEW_EINH_ID,
  DAT_BIS,
  LAENGE,
  BREITE,
  HOEHE,
  UMRECH_ZAEHLER,
  UMRECH_NENNER
 FROM (SELECT DT1.MANDANT_ID,
    DT1.ALTNV_MENGE_EINH_ID,
    DT1.ART_ID,
    DT1.DAT_VON,
    DT1.BRUTTOGEW,
    cast(DT1.UMRECH_FAKTOR as bignumeric) as UMRECH_FAKTOR,
    DT1.GEW_EINH_ID,
    DT1.DAT_BIS,
    DT1.LAENGE,
    DT1.BREITE,
    DT1.HOEHE,
    DT1.UMRECH_ZAEHLER,
    DT1.UMRECH_NENNER
   FROM KFL_PRODUCTION_DBP_ETL.ART_UMRECHNUNG_FAKTOR_PER_TMP AS DT1
    LEFT JOIN (SELECT *
     FROM KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER AS DT3
     WHERE DAT_BIS = PARSE_DATE('%F', '9999-12-31')) AS dt2 ON DT1.MANDANT_ID = dt2.MANDANT_ID AND DT1.ART_ID = dt2.ART_ID
               AND DT1.ALTNV_MENGE_EINH_ID = dt2.ALTNV_MENGE_EINH_ID AND DT1.BRUTTOGEW = dt2.BRUTTOGEW
              --AND CAST(dt1.umrech_faktor AS DECIMAL(18,4)) = CAST(dt2.umrech_faktor AS DECIMAL(18,4))
               AND DT1.GEW_EINH_ID = dt2.GEW_EINH_ID AND DT1.LAENGE = dt2.LAENGE AND DT1.BREITE = dt2.BREITE AND DT1.HOEHE = dt2.HOEHE AND DT1
       .UMRECH_NENNER = dt2.UMRECH_NENNER AND DT1.UMRECH_ZAEHLER = dt2.UMRECH_ZAEHLER
   WHERE dt2.ART_ID IS NULL
   GROUP BY DT1.ART_ID,
    DT1.MANDANT_ID,
    DT1.ALTNV_MENGE_EINH_ID,
    DT1.BRUTTOGEW,
    DT1.GEW_EINH_ID,
    DT1.UMRECH_FAKTOR,
    DT1.DAT_VON,
    DT1.DAT_BIS,
    DT1.LAENGE,
    DT1.BREITE,
    DT1.HOEHE,
    DT1.UMRECH_NENNER,
    DT1.UMRECH_ZAEHLER) AS t3
 WHERE NOT EXISTS (SELECT 1 AS `A11860`
   FROM KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER
   WHERE MANDANT_ID = t3.MANDANT_ID
    AND ALTNV_MENGE_EINH_ID = t3.ALTNV_MENGE_EINH_ID
    AND ART_ID = t3.ART_ID)
 QUALIFY (ROW_NUMBER() OVER (PARTITION BY MANDANT_ID, ALTNV_MENGE_EINH_ID, ART_ID)) = 1);




UPDATE KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER SET DAT_BIS = DT1.DAT_BIS FROM (
  SELECT
      ART_UMRECHNUNG_FAKTOR_PER_0.MANDANT_ID,
      ART_UMRECHNUNG_FAKTOR_PER_0.ART_ID,
      ART_UMRECHNUNG_FAKTOR_PER_0.ALTNV_MENGE_EINH_ID,
      ART_UMRECHNUNG_FAKTOR_PER_0.DAT_VON,
      CASE
        WHEN sum(CAST(format_date('%Y%m%d', DAT_VON) as BIGNUMERIC)) OVER (PARTITION BY MANDANT_ID, ART_ID, ALTNV_MENGE_EINH_ID ORDER BY DAT_VON DESC NULLS FIRST ROWS 1 PRECEDING) - CAST(format_date('%Y%m%d', DAT_VON) as BIGNUMERIC) = NUMERIC '0' THEN parse_date('%Y-%m-%d', '9999-12-31')
        ELSE date_sub(parse_date('%Y%m%d', CAST(sum(CAST(format_date('%Y%m%d', DAT_VON) as BIGNUMERIC)) OVER (PARTITION BY MANDANT_ID, ART_ID, ALTNV_MENGE_EINH_ID ORDER BY DAT_VON DESC NULLS FIRST ROWS 1 PRECEDING) - CAST(format_date('%Y%m%d', DAT_VON) as BIGNUMERIC) as STRING)), interval 1 DAY)
      END AS DAT_BIS
    FROM
      KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER AS ART_UMRECHNUNG_FAKTOR_PER_0
) AS DT1 WHERE ART_UMRECHNUNG_FAKTOR_PER.MANDANT_ID = DT1.MANDANT_ID
 AND ART_UMRECHNUNG_FAKTOR_PER.ART_ID = DT1.ART_ID
 AND ART_UMRECHNUNG_FAKTOR_PER.ALTNV_MENGE_EINH_ID = DT1.ALTNV_MENGE_EINH_ID
 AND ART_UMRECHNUNG_FAKTOR_PER.DAT_BIS <> DT1.DAT_BIS
 AND ART_UMRECHNUNG_FAKTOR_PER.DAT_VON = DT1.DAT_VON
 AND ART_UMRECHNUNG_FAKTOR_PER.MANDANT_ID IN(
  SELECT
      DT1.MANDANT_ID
    FROM
      KFL_PRODUCTION_DBP_ETL.ART_UMRECHNUNG_FAKTOR_PER_TMP
    GROUP BY 1
);


