/*
_------------------------------------------------------------------------------
_ 12.) Stuecklistenaufloesung aus ARTBEW in volatile Tabelle (Fueße)
_------------------------------------------------------------------------------
*/


-- 18.12.2012, -dba-


--


-- Aus der ARTBEW werden zunaechst fuer die relevanten Tage alle betroffenen Kopfartikel ermittelt. Ueber den


-- nachgelagerten JOIN gegen die Komponententabelle STUECKLISTE_DET werden dann die zugehoerigen Fußartikel mit


-- der auf Basismengeneinheit geeichten Menge in die Zwischentabelle STEP01 eingespielt.
















INSERT INTO `_STEP01` (MANDANT_ID, WUP_ID, NB_ID, ART_ID, BEWART_ID, BEWART_DET_ID, PROMO_FG, DAT, WRG, EAN_KASSE, MENGE
 , UMSATZ_NETTO_ALT, UMSATZ_MWST_BETRAG_ALT, UMSATZ_BTO, UMRECHNUNGSKURS, KOPF_ART_ID, KOMPONENTENMENGEN_FAKTOR,
 STUECKLISTE_ID)
(SELECT A.MANDANT_ID,
  CAST(A.WUP_ID AS INTEGER) AS WUP_ID,
  CAST(A.NB_ID AS SMALLINT) AS NB_ID,
  CAST(b.ART_ID AS INTEGER) AS ART_ID,
  CAST(A.BEWART_ID AS INTEGER) AS BEWART_ID,
  CAST(A.BEWART_DET_ID AS INTEGER) AS BEWART_DET_ID,
  CAST(A.PROMO_FG AS INTEGER) AS PROMO_FG,
  A.DAT,
  A.WRG,
  A.EAN_KASSE,
  SUM(CAST(A.MENGE AS FLOAT64)) AS MENGE,
  SUM(CAST(A.UMSATZ_NETTO AS NUMERIC)) AS UMSATZ_NETTO_ALT,
  SUM(CAST(A.UMSATZ_MWST_BETRAG AS NUMERIC)) AS UMSATZ_MWST_BETRAG_ALT,
  SUM(CAST(A.UMSATZ_NETTO + A.UMSATZ_MWST_BETRAG AS NUMERIC)) AS UMSATZ_BTO,
  0 AS UMRECHNUNGSKURS,
  CAST(A.ART_ID AS INTEGER) AS KOPF_ART_ID,
  -- falls eine Komponente mehrfach in der Stueckliste vorhanden ist: Menge aufsummieren 
  ROUND(CAST(SUM(CAST(A.MENGE AS FLOAT64) * CAST(b.KOMPONENTENMENGE AS FLOAT64)) / MAX(COALESCE(C.UMRECH_FAKTOR, 1.0000
       )) AS NUMERIC), 4) AS KOMPONENTENMENGEN_FAKTOR,
  CAST(b.STUECKLISTE_ID AS INTEGER) AS STUECKLISTE_ID
 FROM KFL_PRODUCTION_DBP_DATA.ARTBEW AS A
  INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_DAT AS D ON A.DAT = D.DAT
  INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_ART_GP_WUP_ZU AS Z ON A.MANDANT_ID = Z.MANDANT_ID AND A.ART_ID = Z.ART_ID
        AND A.WUP_ID = Z.WUP_ID AND A.NB_ID = Z.NB_ID AND A.DAT = Z.DAT
  INNER JOIN (SELECT A0.MANDANT_ID,
    A0.STUECKLISTE_ID,
    A0.DAT_VON,
    A0.DAT_BIS,
    A0.ART_ID,
    NULL AS WUP_ID,
    NULL AS NB_ID,
    A0.STUECKLISTE_VERWENDUNG_ID
   FROM KFL_PRODUCTION_DBP_DATA.STUECKLISTE AS A0
    INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_WPUUMS_DAT_MIN AS M ON A0.DAT_BIS >= M.DAT
   WHERE --a.wup_id IS NULL AND
   A0.STUECKLISTE_VERWENDUNG_ID = 3
    AND (A0.MANDANT_ID, A0.ART_ID, A0.STUECKLISTE_ID) IN (SELECT (MANDANT_ID, ART_ID, MAX(STUECKLISTE_ID))
      FROM KFL_PRODUCTION_DBP_DATA.STUECKLISTE
      GROUP BY MANDANT_ID,
       ART_ID)) AS k ON A.MANDANT_ID = k.MANDANT_ID AND A.ART_ID = k.ART_ID AND A.DAT BETWEEN k.DAT_VON AND k.DAT_BIS

  -- Ermittlung Fußartikel
  INNER JOIN (SELECT *
   FROM KFL_PRODUCTION_DBP_DATA.STUECKLISTE_DET
   WHERE STUECKLISTE_TYP_ID = 'M') AS b ON k.MANDANT_ID = b.MANDANT_ID AND k.STUECKLISTE_ID = b.STUECKLISTE_ID AND A.DAT
    BETWEEN b.DAT_VON AND b.DAT_BIS

  -- Ermittlung Umrechnungsfaktor, damit korrekter Bezug zur Basismengeneinheit hergestellt wird.
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER AS C ON b.MANDANT_ID = C.MANDANT_ID AND b.ART_ID = C.ART_ID
       AND b.KOMPONENTENMENGE_EINH_ID = C.ALTNV_MENGE_EINH_ID AND A.DAT BETWEEN C.DAT_VON AND C.DAT_BIS
 WHERE A.MANDANT_ID > 1
  AND A.MENGE <> 0
  AND A.UMSATZ_NETTO <> 0
 GROUP BY A.MANDANT_ID,
  A.WUP_ID,
  A.NB_ID,
  b.ART_ID,
  A.DAT,
  KOPF_ART_ID,
  A.BEWART_ID,
  A.BEWART_DET_ID,
  b.STUECKLISTE_ID,
  A.WRG,
  A.EAN_KASSE,
  A.PROMO_FG);


