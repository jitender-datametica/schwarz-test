 EK_GLD = G.EK_GLD * ARTBEW.MENGE,
 DIFF_EK_GLD_KONZ = G.EK_GLD * ARTBEW.MENGE * G.UMRECHNUNGSKURS FROM KFL_PRODUCTION_DBP_DATA.ART AS A,
 KFL_PRODUCTION_DBP_ETL.TMP_ART_WUP_TAG_GLD AS G
WHERE ARTBEW.DAT = G.DAT AND ARTBEW.MANDANT_ID = G.MANDANT_ID AND ARTBEW.WUP_ID = G.WUP_ID AND ARTBEW.ART_ID = G.ART_ID
    AND ARTBEW.ART_ID > - 1 AND ARTBEW.MANDANT_ID = A.MANDANT_ID AND ARTBEW.ART_ID = A.ART_ID AND A.WG_ART_FG = 0   /*keine WG Erfassartiekel*/;


