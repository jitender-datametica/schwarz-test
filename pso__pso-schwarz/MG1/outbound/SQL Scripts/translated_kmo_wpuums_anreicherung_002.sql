 EK_GLD = ARTBEW.EK_NETTO,
 DIFF_EK_GLD_KONZ = ARTBEW.DIFF_EK_NETTO_KONZ FROM KFL_PRODUCTION_DBP_ETL.GLD_DAT, KFL_PRODUCTION_DBP_DATA.ART AS A
WHERE ARTBEW.DAT = GLD_DAT.DAT AND ARTBEW.MANDANT_ID > 1 AND ARTBEW.MANDANT_ID = A.MANDANT_ID AND ARTBEW.ART_ID = A.ART_ID
     AND ARTBEW.ART_ID > - 1 AND A.WG_ART_FG = 1   /*Warengruppenerfassartikel*/
;





