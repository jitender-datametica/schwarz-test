SELECT MANDANT_ID,
 VON_WRG_ID,
 WRG_ID,
 UMRECHNUNGSKURS,
 DAT_VON,
 DAT_BIS
FROM KFL_PRODUCTION_DBP_DATA.MANDANT_WRG_ZU_PER
WHERE VON_WRG_ID IS NOT NULL
GROUP BY MANDANT_ID,
 WRG_ID,
 DAT_VON,
 DAT_BIS,
 VON_WRG_ID,
 UMRECHNUNGSKURS
ORDER BY 1 NULLS LAST,
 2 NULLS LAST,
 5 NULLS LAST,
 6 NULLS LAST;