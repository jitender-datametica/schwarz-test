CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_KUNDEN_GLEICH (
MANDANT_ID INTEGER,
WUP_ID INTEGER NOT NULL,
NB_ID INTEGER NOT NULL,
DAT DATE NOT NULL,
DAT_GLEICH DATE,
BONANZAHL NUMERIC(18,2)
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.MIS_Q_KUNDEN_GLEICH (MANDANT_ID, WUP_ID, NB_ID, DAT, DAT_GLEICH, BONANZAHL)
(SELECT T1.MANDANT_ID,
  T1.WUP_ID,
  T1.NB_ID,
  T1.DAT,
  T2.DAT_VGL AS DAT_GLEICH,
  T1.BONANZAHL
 FROM KFL_PRODUCTION_DBP_ETL.MIS_Q_KUNDEN AS T1
  INNER JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_KUNDEN AS T2 ON T1.MANDANT_ID = T2.MANDANT_ID AND T1.WUP_ID = T2.WUP_ID AND T1
      .NB_ID = T2.NB_ID AND T1.DAT = T2.DAT AND T1.BONANZAHL = T2.BONANZAHL
 WHERE T1.KUNDEN_FG = 1
  AND T2.KUNDENGLEICH_FG = 1);


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL SET
 PRUEF_GRUND_ID_KUNDE = dt1.PRUEF_GRUND_ID_KUNDE_,
 PRUEF_STATUS_ID_KUNDE = CASE
  WHEN WUPCAL.PRUEF_STATUS_ID_KUNDE IS NULL
  THEN dt1.PRUEF_STATUS_ID_KUNDE_
  ELSE dt1.PRUEF_STATUS_ID_KUNDE_RELOAD_
  END FROM (SELECT t1.MANDANT_ID AS MANDANT_ID_,
   t1.WUP_ID AS WUP_ID_,
   t1.NB_ID AS NB_ID_,
   t1.DAT AS DAT_,
   MAX(CASE
       WHEN T2.WUP_ID IS NULL
       THEN ' '
       ELSE 'D'
       END || CASE
       WHEN T3.WUP_ID IS NULL
       THEN ' '
       ELSE 'G'
       END || ' ') AS PRUEF_GRUND_ID_KUNDE_,
    CASE
    WHEN MAX(CASE
         WHEN T2.WUP_ID IS NULL
         THEN ' '
         ELSE 'D'
         END || CASE
         WHEN T3.WUP_ID IS NULL
         THEN ' '
         ELSE 'G'
         END || ' ') = '   '
    THEN 1
    ELSE 0
    END AS PRUEF_STATUS_ID_KUNDE_,
    CASE
    WHEN MAX(CASE
         WHEN T2.WUP_ID IS NULL
         THEN ' '
         ELSE 'D'
         END || CASE
         WHEN T3.WUP_ID IS NULL
         THEN ' '
         ELSE 'G'
         END || ' ') = '   '
    THEN 2
    ELSE - 1
    END AS PRUEF_STATUS_ID_KUNDE_RELOAD_
  FROM (SELECT *
    FROM KFL_PRODUCTION_DBP_ETL_PROCESS.KUNDENANZ_AGG_WT
    WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 365 DAY) AND (CURRENT_DATE)) AS t1
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_KUNDEN_ABW_AVG AS T2 ON t1.DAT = T2.DAT AND t1.MANDANT_ID = T2.MANDANT_ID AND
      t1.WUP_ID = T2.WUP_ID AND t1.NB_ID = T2.NB_ID
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_KUNDEN_GLEICH AS T3 ON t1.DAT = T3.DAT AND t1.MANDANT_ID = T3.MANDANT_ID AND
      t1.WUP_ID = T3.WUP_ID AND t1.NB_ID = T3.NB_ID
  WHERE t1.CALC_FG = 0
  GROUP BY MANDANT_ID_,
   WUP_ID_,
   NB_ID_,
   DAT_) AS dt1
WHERE WUPCAL.MANDANT_ID = dt1.MANDANT_ID_ AND WUPCAL.WUP_ID = dt1.WUP_ID_ AND WUPCAL.NB_ID = dt1.NB_ID_ AND WUPCAL.DAT =
  dt1.DAT_;