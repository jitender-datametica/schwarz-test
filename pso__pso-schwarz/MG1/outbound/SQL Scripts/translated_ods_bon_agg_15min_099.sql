WUP_ID INTEGER NOT NULL,
WRG_ID STRING(3) NOT NULL,
MANDANT_ID BIGNUMERIC NOT NULL,
KASSENSYSTEM_NAME STRING,
KASSE_NR SMALLINT,
KASSE_TYP_ID BIGNUMERIC,
START_TIME DATETIME NOT NULL,
END_TIME DATETIME NOT NULL
);


