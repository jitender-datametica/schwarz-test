CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_track_it_$TRANSIENT_TABLE_SUFFIX` AS
SELECT T1.MANDANT_ID,
 T1.KASSENSYSTEM_NAME,
 T1.WUP_ID,
 T1.WRG_ID,
 T1.KASSE_NR,
 T1.KASSE_TYP_ID,
 t2.ZEIT_STUNDE,
 t2.ZEIT_MINUTE,
 DATE(T1.START_TIME) AS BON_DAT,
 PARSE_DATETIME('%F %H:%M:%S', CAST(DATE(T1.START_TIME) AS STRING) || ' ' || t2.START_TIME) AS ZEIT_SCHEIBE_START,
 DATETIME_ADD(PARSE_DATETIME('%F %H:%M:%S', CAST(DATE(T1.START_TIME) AS STRING) || ' ' || t2.END_TIME), INTERVAL 1
  SECOND) AS ZEIT_SCHEIBE_ENDE,
 T1.START_TIME,
 T1.END_TIME
FROM KFL_PRODUCTION_DBP_ETL.ODS_BON_SIGN_ON_OFF_TIME AS T1
 INNER JOIN (SELECT ZEIT_STUNDE,
   ZEIT_MINUTE,
       CASE
       WHEN ZEIT_STUNDE < 10
       THEN '0' || TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
       ELSE TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
       END || ':' || CASE
      WHEN ZEIT_MINUTE < 10
      THEN '0' || TRIM(SUBSTR(CAST(ZEIT_MINUTE AS STRING), 1, 39))
      ELSE TRIM(SUBSTR(CAST(ZEIT_MINUTE AS STRING), 1, 39))
      END || ':00' AS START_TIME,
      CASE
      WHEN ZEIT_STUNDE < 10
      THEN '0' || TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
      ELSE TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
      END || ':' || CASE
     WHEN ZEIT_MINUTE = 0
     THEN '14:59'
     WHEN ZEIT_MINUTE = 15
     THEN '29:59'
     WHEN ZEIT_MINUTE = 30
     THEN '44:59'
     WHEN ZEIT_MINUTE = 45
     THEN '59:59'
     ELSE NULL
     END AS END_TIME
  FROM KFL_PRODUCTION_DBP_DATA.ZEIT) AS t2 ON DATETIME_ADD(PARSE_DATETIME('%F %H:%M:%S', CAST(DATE(T1.START_TIME) AS STRING)
       || ' ' || t2.END_TIME), INTERVAL 1 SECOND) >= T1.START_TIME AND PARSE_DATETIME('%F %H:%M:%S', CAST(DATE(T1.START_TIME) AS STRING)
      || ' ' || t2.START_TIME) <= T1.END_TIME;


