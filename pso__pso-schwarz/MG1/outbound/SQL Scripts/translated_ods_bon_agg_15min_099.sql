INSERT INTO KFL_PRODUCTION_DBP_ETL.ODS_BON_SIGN_ON_OFF_TIME (WUP_ID, WRG_ID, MANDANT_ID, KASSENSYSTEM_NAME, KASSE_NR,
 KASSE_TYP_ID, START_TIME, END_TIME)
(SELECT t1.WUP_ID,
  t1.WRG_ID,
  t1.MANDANT_ID,
  t1.KASSENSYSTEM_NAME,
  t1.KASSE_NR,
  t1.KASSE_TYP_ID,
  t1.BON_ENDE AS START_TIME,
  MAX(COALESCE(t2.BON_ENDE, t3.BON_ENDE, PARSE_DATETIME('%F %H:%M:%S', CAST(DATE(t1.BON_ENDE) AS STRING) || ' 23:59:59'
     ))) AS END_TIME
 FROM (SELECT WUP_ID,
    WRG_ID,
    BON_DAT,
    MANDANT_ID,
    KASSENSYSTEM_NAME,
    KASSE_NR,
    KASSE_TYP_ID,
    BON_ENDE,
    BON_NR,
    LAG(BON_NR) OVER (PARTITION BY WUP_ID, CAST(MANDANT_ID AS STRING), KASSE_NR, BON_DAT ORDER BY BON_NR IS NULL DESC,
       BON_NR DESC) AS FOLGEBON,
     CASE
     WHEN (LAG(BON_NR) OVER (PARTITION BY WUP_ID, CAST(MANDANT_ID AS STRING), KASSE_NR, BON_DAT ORDER BY BON_NR IS NULL
         DESC, BON_NR DESC)) IS NULL
     THEN 99999999
     ELSE LAG(BON_NR) OVER (PARTITION BY WUP_ID, CAST(MANDANT_ID AS STRING), KASSE_NR, BON_DAT ORDER BY BON_NR IS NULL
        DESC, BON_NR DESC)
     END AS FOLGE_BON_NR
   FROM KFL_PRODUCTION_DBP_ETL.ODS_BON_SIGN_ON_OFF
   WHERE TRANSACTION_NAME IN ('SignOnTransaction')) AS t1
  LEFT JOIN (SELECT *
   FROM KFL_PRODUCTION_DBP_ETL.ODS_BON_SIGN_ON_OFF
   WHERE TRANSACTION_NAME IN ('SignOffTransaction')) AS t2 ON t1.WUP_ID = t2.WUP_ID AND t1.WRG_ID = t2.WRG_ID AND t1.MANDANT_ID
         = t2.MANDANT_ID AND t1.KASSENSYSTEM_NAME = t2.KASSENSYSTEM_NAME AND t1.KASSE_NR = t2.KASSE_NR AND t2.BON_NR
     BETWEEN t1.BON_NR AND t1.FOLGE_BON_NR AND t1.BON_DAT = t2.BON_DAT
  LEFT JOIN (SELECT *
   FROM KFL_PRODUCTION_DBP_ETL.ODS_BON_SIGN_ON_OFF
   WHERE TRANSACTION_NAME IN ('SignOnTransaction')) AS t3 ON t1.WUP_ID = t3.WUP_ID AND t1.WRG_ID = t3.WRG_ID AND t1.MANDANT_ID
         = t3.MANDANT_ID AND t1.KASSENSYSTEM_NAME = t3.KASSENSYSTEM_NAME AND t1.KASSE_NR = t3.KASSE_NR AND t1.FOLGE_BON_NR
      = t3.BON_NR AND t1.BON_DAT = t3.BON_DAT
 GROUP BY t1.MANDANT_ID,
  t1.WUP_ID,
  t1.WRG_ID,
  t1.KASSENSYSTEM_NAME,
  t1.KASSE_NR,
  t1.KASSE_TYP_ID,
  START_TIME);


