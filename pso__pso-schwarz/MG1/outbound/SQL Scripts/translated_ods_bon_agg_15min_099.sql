CREATE OR REPLACE TABLE DEFAULTSCHEMA._kasse_track_1_${TRANSIENT_TABLE_SUFFIX} AS
SELECT t0.MANDANT_ID,
 t0.WUP_ID,
 t0.DAT,
 t0.KASSE_NR,
 t0.KASSE_TYP_ID,
 t0.DFL,
 COUNT(t0.KASSE_TYP_ID) OVER (PARTITION BY CAST(t0.MANDANT_ID AS STRING), t0.WUP_ID, t0.DAT, t0.KASSE_NR ORDER BY t0.MANDANT_ID
    IS NULL, t0.MANDANT_ID, t0.WUP_ID IS NULL, t0.WUP_ID, t0.DAT IS NULL, t0.DAT, t0.KASSE_NR IS NULL, t0.KASSE_NR
  RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ANZ_KT,
 t0.ANZ_BONS,
 DENSE_RANK() OVER (PARTITION BY CAST(t0.MANDANT_ID AS STRING), t0.WUP_ID, t0.DAT, t0.KASSE_NR ORDER BY t0.ANZ_BONS
    IS NULL DESC, t0.ANZ_BONS DESC) AS RANG_ANZ_BONS,
 DENSE_RANK() OVER (PARTITION BY CAST(t0.MANDANT_ID AS STRING), t0.WUP_ID, t0.DAT, t0.KASSE_NR ORDER BY t0.DFL IS NULL,
    t0.DFL) AS RANG_ANZ_DFL
FROM (SELECT A.MANDANT_ID,
   A.WUP_ID,
   A.DAT,
   A.KASSE_NR,
   A.KASSE_TYP_ID,
   COALESCE(B.DURCHFALLLOGIK_ID, 99) AS DFL,
   SUM(A.BONANZAHL_SUG) AS ANZ_BONS
  FROM KFL_PRODUCTION_DBP_ETL.ODS_BON_AGG_15MIN AS A
   LEFT JOIN KFL_PRODUCTION_DBP_ODS.L_KASSE_TYP AS B ON A.KASSE_TYP_ID = B.KASSE_TYP_ID
  GROUP BY A.MANDANT_ID,
   A.WUP_ID,
   A.DAT,
   A.KASSE_NR,
   A.KASSE_TYP_ID,
   DFL) AS t0;


