          V.TALON_ID <> 0 AND T.KASSENSYSTEM_NAME IN ('KPOS', 'POSITION') AND V.MANDANT_ID > 1
      THEN 0
      ELSE 1
      END AS TRACK_ARTIKEL
    FROM KFL_PRODUCTION_DBP_ODS.ODS_BON_KOPF AS K
