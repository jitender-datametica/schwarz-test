DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.VIS_BON_WUP_BEDIENUNG_TMP;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.VIS_BON_WUP_BEDIENUNG_TMP (
MANDANT_ID INTEGER,
WUP_ID INTEGER,
NB_ID INTEGER,
DAT DATE,
WRG_ID STRING COLLATE 'und:ci',
GJ INTEGER,
AKT_GJ INTEGER,
KJMO INTEGER,
AKT_MO INTEGER,
KJWO INTEGER,
AKT_WO INTEGER,
WTAG_ID INTEGER,
AKT_TAG INTEGER,
ANZ_KUNDE_BED_WURST INTEGER,
ANZ_KUNDE_BED_WURST_WVJ INTEGER,
ANZ_KUNDE_BED_KAESE INTEGER,
ANZ_KUNDE_BED_KAESE_WVJ INTEGER,
ANZ_KUNDE_BED_FLEISCH INTEGER,
ANZ_KUNDE_BED_FLEISCH_WVJ INTEGER,
ANZ_KUNDE_BED_GEFLUEGEL INTEGER,
ANZ_KUNDE_BED_GEFLUEGEL_WVJ INTEGER,
ANZ_KUNDE_BED_FISCH INTEGER,
ANZ_KUNDE_BED_FISCH_WVJ INTEGER,
ANZ_KUNDE_BED_FEINK INTEGER,
ANZ_KUNDE_BED_FEINK_WVJ INTEGER
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_BON_WUP_BEDIENUNG_TMP (MANDANT_ID, WUP_ID, NB_ID, DAT, WRG_ID, GJ, AKT_GJ, KJMO,
 AKT_MO, KJWO, AKT_WO, WTAG_ID, AKT_TAG, ANZ_KUNDE_BED_WURST, ANZ_KUNDE_BED_WURST_WVJ, ANZ_KUNDE_BED_KAESE,
 ANZ_KUNDE_BED_KAESE_WVJ, ANZ_KUNDE_BED_FLEISCH, ANZ_KUNDE_BED_FLEISCH_WVJ, ANZ_KUNDE_BED_GEFLUEGEL,
 ANZ_KUNDE_BED_GEFLUEGEL_WVJ, ANZ_KUNDE_BED_FISCH, ANZ_KUNDE_BED_FISCH_WVJ, ANZ_KUNDE_BED_FEINK, ANZ_KUNDE_BED_FEINK_WVJ
 )
(SELECT D.MANDANT_ID,
  D.WUP_ID,
  D.NB_ID,
  D.DAT,
  COALESCE(M.DEFAULT_WRG, '') AS WRG_ID,
  D.GJ,
  D.AKT_GJ,
  D.KJMO,
  D.AKT_MO,
  D.KJWO,
  D.AKT_WO,
  D.WTAG_ID,
  D.AKT_TAG,
  SUM(COALESCE(W.ANZ_KUNDE * D.AKT_GJ_FG, 0)) AS ANZ_KUNDE_WURST,
  SUM(COALESCE(W.ANZ_KUNDE * D.VJ_WT_1_FG, 0)) AS ANZ_KUNDE_WURST_WVJ,
  SUM(COALESCE(K.ANZ_KUNDE * D.AKT_GJ_FG, 0)) AS ANZ_KUNDE_KAESE,
  SUM(COALESCE(K.ANZ_KUNDE * D.VJ_WT_1_FG, 0)) AS ANZ_KUNDE_KAESE_WVJ,
  SUM(COALESCE(F.ANZ_KUNDE * D.AKT_GJ_FG, 0)) AS ANZ_KUNDE_FLEISCH,
  SUM(COALESCE(F.ANZ_KUNDE * D.VJ_WT_1_FG, 0)) AS ANZ_KUNDE_FLEISCH_WVJ,
  SUM(COALESCE(G.ANZ_KUNDE * D.AKT_GJ_FG, 0)) AS ANZ_KUNDE_GEFLUEGEL,
  SUM(COALESCE(G.ANZ_KUNDE * D.VJ_WT_1_FG, 0)) AS ANZ_KUNDE_GEFLUEGEL_WVJ,
  SUM(COALESCE(S.ANZ_KUNDE * D.AKT_GJ_FG, 0)) AS ANZ_KUNDE_FISCH,
  SUM(COALESCE(S.ANZ_KUNDE * D.VJ_WT_1_FG, 0)) AS ANZ_KUNDE_FISCH_WVJ,
  SUM(COALESCE(E.ANZ_KUNDE * D.AKT_GJ_FG, 0)) AS ANZ_KUNDE_FEINK,
  SUM(COALESCE(E.ANZ_KUNDE * D.VJ_WT_1_FG, 0)) AS ANZ_KUNDE_FEINK_WVJ
 FROM KFL_PRODUCTION_DBP_ETL.DAT_VJ_VERGLEICH AS D
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MANDANT AS M ON D.MANDANT_ID = M.MANDANT_ID
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_BEDIENKONZEPT_ZU AS W ON D.MANDANT_ID = W.MANDANT_ID AND D.WUP_ID = W.WUP_ID
    AND D.JOIN_DAT = W.DAT AND W.BEDIENKONZEPT_ID = 1
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_BEDIENKONZEPT_ZU AS K ON D.MANDANT_ID = K.MANDANT_ID AND D.WUP_ID = K.WUP_ID
    AND D.JOIN_DAT = K.DAT AND K.BEDIENKONZEPT_ID = 2
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_BEDIENKONZEPT_ZU AS F ON D.MANDANT_ID = F.MANDANT_ID AND D.WUP_ID = F.WUP_ID
    AND D.JOIN_DAT = F.DAT AND F.BEDIENKONZEPT_ID = 3
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_BEDIENKONZEPT_ZU AS G ON D.MANDANT_ID = G.MANDANT_ID AND D.WUP_ID = G.WUP_ID
    AND D.JOIN_DAT = G.DAT AND G.BEDIENKONZEPT_ID = 4
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_BEDIENKONZEPT_ZU AS S ON D.MANDANT_ID = S.MANDANT_ID AND D.WUP_ID = S.WUP_ID
    AND D.JOIN_DAT = S.DAT AND S.BEDIENKONZEPT_ID = 5
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_BEDIENKONZEPT_ZU AS E ON D.MANDANT_ID = E.MANDANT_ID AND D.WUP_ID = E.WUP_ID
    AND D.JOIN_DAT = E.DAT AND E.BEDIENKONZEPT_ID = 6
 WHERE COALESCE(W.MANDANT_ID, K.MANDANT_ID, F.MANDANT_ID, G.MANDANT_ID, S.MANDANT_ID, E.MANDANT_ID) IS NOT NULL
 GROUP BY D.MANDANT_ID,
  D.WUP_ID,
  D.NB_ID,
  D.DAT,
  WRG_ID,
  D.GJ,
  D.AKT_GJ,
  D.KJMO,
  D.AKT_MO,
  D.KJWO,
  D.AKT_WO,
  D.WTAG_ID,
  D.AKT_TAG);


UPDATE KFL_PRODUCTION_DBP_ETL.VIS_BON_WUP_BEDIENUNG_TMP SET
 WUP_ID = x1.WUP_ID_ FROM (SELECT T1.MANDANT_ID AS MANDANT_ID_,
   T1.NB_ID AS NB_ID_,
   T2.WUP_ID AS WUP_ID_,
   T1.WUP_ID AS WUP_ID_ALT_
  FROM KFL_PRODUCTION_DBP_DATA.WUP AS T1
   INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP AS T2 ON T1.WUP_ID = T2.WUP_ID_ALT AND T1.NB_ID = T2.NB_ID AND T1.MANDANT_ID =
      T2.MANDANT_ID AND T2.DAT_VON <= CURRENT_DATE) AS x1
WHERE VIS_BON_WUP_BEDIENUNG_TMP.MANDANT_ID = x1.MANDANT_ID_ AND VIS_BON_WUP_BEDIENUNG_TMP.NB_ID = x1.NB_ID_ AND
  VIS_BON_WUP_BEDIENUNG_TMP.WUP_ID = x1.WUP_ID_ALT_;