INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_PERSONAL_WUP_TMP (MANDANT_ID, NB_ID, WUP_ID, GJ, KJMO, PERS_STD, PERS_STD_KVJ,
 PERS_STD_PLAN, ABWESENHEIT_TAGE, ANZ_TAGE, ABWESENHEIT_TAGE_KVJ, ANZ_TAGE_KVJ, PERS_AUSTRITTE, PERS_ANZ,
 PERS_AUSTRITTE_KVJ, PERS_ANZ_KVJ)
(SELECT MANDANT_ID,
  NB_ID,
  WUP_ID,
  GJ,
  KJMO,
  0,
  0,
  0,
  ROUND(CAST(ABWESENHEIT_TAGE AS NUMERIC), 2) AS ERG_ABWESENHEIT_TAGE,
  ROUND(CAST(ANZ_TAGE AS NUMERIC), 2) AS ERG_ANZ_TAGE,
  ROUND(CAST(ABWESENHEIT_TAGE_KVJ AS NUMERIC), 2) AS ERG_ABWESENHEIT_TAGE_KVJ,
  ROUND(CAST(ANZ_TAGE_KVJ AS NUMERIC), 2) AS ERG_ANZ_TAGE_KVJ,
  ROUND(CAST(PERS_AUSTRITTE AS NUMERIC), 2) AS ERG_PERS_AUSTRITTE,
  ROUND(CAST(PERS_ANZ AS NUMERIC), 2) AS ERG_PERS_ANZ,
  ROUND(CAST(PERS_AUSTRITTE_KVJ AS NUMERIC), 2) AS ERG_PERS_AUSTRITTE_KVJ,
  ROUND(CAST(PERS_ANZ_KVJ AS NUMERIC), 2) AS ERG_PERS_ANZ_KVJ
 FROM (SELECT T3.MANDANT_ID,
    T3.NB_ID,
    T3.WUP_ID,
    B.GJ,
    T2.KJMO,
     DATE_DIFF(B.MAX_DAT, B.MIN_DAT, DAY) + 1 AS KALENDERTAGE,
    SUM(CAST(T2.ABWESENHEIT_TAGE_IST AS FLOAT64)) AS ABWESENHEIT_TAGE,
    SUM(IF(CAST(T2.ANZ_KOPF_IST * (DATE_DIFF(B.MAX_DAT, B.MIN_DAT, DAY) + 1) AS FLOAT64) = 0, NULL, CAST(T2.ANZ_KOPF_IST * (DATE_DIFF(B.MAX_DAT, B.MIN_DAT, DAY) + 1) AS FLOAT64)
      )) AS ANZ_TAGE,
    SUM(CAST(T2.ABWESENHEIT_TAGE_VJ AS FLOAT64)) AS ABWESENHEIT_TAGE_KVJ,
    SUM(IF(CAST(T2.ANZ_KOPF_VJ * (DATE_DIFF(B.MAX_DAT, B.MIN_DAT, DAY) + 1) AS FLOAT64) = 0, NULL, CAST(T2.ANZ_KOPF_VJ * (DATE_DIFF(B.MAX_DAT, B.MIN_DAT, DAY) + 1) AS FLOAT64)
      )) AS ANZ_TAGE_KVJ,
    SUM(CAST(T2.SOLL_STUNDEN_MO_AN_IST + T2.SOLL_STUNDEN_MO_AG_IST AS FLOAT64)) AS PERS_AUSTRITTE,
    SUM(IF(CAST(T2.SOLL_STUNDEN_MO_IST AS FLOAT64) = 0, NULL, CAST(T2.SOLL_STUNDEN_MO_IST AS FLOAT64))) AS PERS_ANZ,
    SUM(CAST(T2.SOLL_STUNDEN_MO_AN_VJ + T2.SOLL_STUNDEN_MO_AG_VJ AS FLOAT64)) AS PERS_AUSTRITTE_KVJ,
    SUM(IF(CAST(T2.SOLL_STUNDEN_MO_VJ AS FLOAT64) = 0, NULL, CAST(T2.SOLL_STUNDEN_MO_VJ AS FLOAT64))) AS PERS_ANZ_KVJ
   FROM KFL_PRODUCTION_DBP_DATA.L_ORG_EINHEIT AS T1
    INNER JOIN KFL_PRODUCTION_DBP_DATA.SHR_KENNZAHLEN AS T2 ON T1.HR_OBJEKT_ID = T2.HR_OBJEKT_ID AND T1.MANDANT_ID = T2
       .MANDANT_ID AND T2.SHR_FREIGABE_FG = 1
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP AS T3 ON ROUND(SAFE_CAST(SUBSTR(T1.HR_OBJEKT_BEZ_KURZ, 3, 4) AS BIGNUMERIC),
       0) = T3.WUP_ID AND T2.MANDANT_ID = T3.MANDANT_ID
    INNER JOIN KFL_PRODUCTION_DBP_ETL.VIS_MANDANT AS VM ON T3.MANDANT_ID = VM.MANDANT_ID
    INNER JOIN KFL_PRODUCTION_DBP_DATA.L_MA_VARIABLE AS T4 ON T2.KJMO = T4.KJMO AND T2.MANDANT_ID = T4.MANDANT_ID
    INNER JOIN KFL_PRODUCTION_DBP_DATA.MONAT AS B ON T2.KJMO = B.KJMO
   WHERE T3.NB_ID IN (0, 2, 7, - 1)
    AND (T1.MANDANT_ID = 2 AND T1.HR_OBJEKT_BEZ_KURZ LIKE 'CZ%' OR T1.MANDANT_ID = 3 AND T1.HR_OBJEKT_BEZ_KURZ LIKE
            'PL%' OR T1.MANDANT_ID = 5 AND T1.HR_OBJEKT_BEZ_KURZ LIKE 'SK%' OR T1.MANDANT_ID = 6 AND T1.HR_OBJEKT_BEZ_KURZ
          LIKE 'HR%' OR T1.MANDANT_ID = 7 AND T1.HR_OBJEKT_BEZ_KURZ LIKE 'RO%' OR T1.MANDANT_ID = 8 AND T1.HR_OBJEKT_BEZ_KURZ
        LIKE 'BG%')
   GROUP BY T3.MANDANT_ID,
    T3.NB_ID,
    T3.WUP_ID,
    B.GJ,
    T2.KJMO,
    KALENDERTAGE) AS erg);