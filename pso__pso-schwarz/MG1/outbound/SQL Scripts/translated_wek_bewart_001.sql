DELETE FROM KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ARTBEW_FLAGGING
WHERE (MANDANT_ID, WUP_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, DAT)
  FROM KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ARTBEW_AGG_WT);


INSERT INTO KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ARTBEW_FLAGGING (MANDANT_ID, WUP_ID, ART_ID, DAT, BEWART_ID, MENGE,
 MENGE_SUM, ANTEIL, BEWART_DET_ID)
(SELECT t2.MANDANT_ID,
  t2.WUP_ID,
  t2.ART_ID,
  t2.DAT,
  t2.BEWART_ID,
  t2.MENGE,
  SUM(ABS(t2.MENGE)) OVER (PARTITION BY t2.MANDANT_ID, t2.WUP_ID, t2.ART_ID, t2.DAT RANGE BETWEEN UNBOUNDED PRECEDING
   AND UNBOUNDED FOLLOWING) AS MENGE_SUM,
  IFNULL(CAST(ABS(t2.MENGE) AS FLOAT64) / IF(CAST(SUM(ABS(t2.MENGE)) OVER (PARTITION BY t2.MANDANT_ID, t2.WUP_ID, t2.ART_ID, t2.DAT RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS FLOAT64)
      = 0, NULL, CAST(SUM(ABS(t2.MENGE)) OVER (PARTITION BY t2.MANDANT_ID, t2.WUP_ID, t2.ART_ID, t2.DAT RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS FLOAT64)
     ), 0) AS ANTEIL,
  t2.BEWART_DET_ID
 FROM (SELECT A.MANDANT_ID,
    A.WUP_ID,
    A.ART_ID,
    A.DAT,
    A.BEWART_ID,
    A.BEWART_DET_ID,
    SUM(A.MENGE) AS MENGE
   FROM KFL_PRODUCTION_DBP_DATA.ARTBEW AS A
    INNER JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ARTBEW_AGG_WT AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B.WUP_ID
         AND A.NB_ID = B.NB_ID AND A.DAT = B.DAT
   WHERE A.BEWART_ID IN (1001, 1002)
   GROUP BY A.MANDANT_ID,
    A.WUP_ID,
    A.DAT,
    A.BEWART_ID,
    A.ART_ID,
    A.BEWART_DET_ID
   HAVING MENGE <> 0) AS t2);