UPDATE KFL_PRODUCTION_DBP_DATA.WERBEWOCHE_KL SET
 AKT_KJWO_WW_KOMPLETT = WERBEWOCHE_KL.AKT_KJWO_WW + 1
WHERE AKT_KJWO_WW <= - 1 AND MANDANT_ID IN (7, 2, 6);


UPDATE KFL_PRODUCTION_DBP_DATA.WERBEWOCHE_KL SET
 AKT_KJWO_WW_KOMPLETT = 0
WHERE AKT_KJWO_WW = 1 AND MANDANT_ID IN (7, 2, 6) AND DAT IN (SELECT DAT
   FROM KFL_PRODUCTION_DBP_DATA.TAG
   WHERE DAT = DATE_ADD(CURRENT_DATE, INTERVAL 2 DAY) AND WTAG_ID = 3
    OR DAT = DATE_ADD(CURRENT_DATE, INTERVAL 1 DAY) AND WTAG_ID = 3
    OR DAT = CURRENT_DATE AND WTAG_ID = 3);