CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP AS
(SELECT *
FROM KFL_PRODUCTION_DBP_DATA.WUPCAL
LIMIT 0);


INSERT INTO KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP (MANDANT_ID, WUP_ID, NB_ID, DAT, OFFEN, WERBEWOCHE,
 DATENLIEFERUNG_ARTBEW_WG_SUM, DATENLIEFERUNG_BONANZAHL, DATENLIEFERUNG_MISVIER, DATENLIEFERUNG_ARTBEW,
 DATENLIEFERUNG_QBM_STATUS, BONANZAHL, BONANZAHL_MISVIER)
(SELECT dt1.MANDANT_ID AS `_MANDANT_ID`,
  dt1.WUP_ID AS `_WUP_ID`,
  dt1.NB_ID AS `_NB_ID`,
  dt1.DAT_MISSING AS `_DAT`,
  1 AS `_OFFEN`,
  0 AS `_WERBEWOCHE`,
  0 AS `_DATENLIEFERUNG_ARTBEW_WG_SUM`,
  0 AS `_DATENLIEFERUNG_BONANZAHL`,
  0 AS `_DATENLIEFERUNG_MISVIER`,
  0 AS `_DATENLIEFERUNG_ARTBEW`,
  0 AS `_DATENLIEFERUNG_QBM_STATUS`,
  CAST(CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0
     THEN 0
     ELSE dt1.SOURCE_BONANZAHL / WWZP0.UMSATZ_PRZ * dt1.UMSATZ_PRZ
     END AS BIGNUMERIC) AS INTEGER) AS `_BONANZAHL`,
  0 AS `_BONANZAHL_MISVIER`
 FROM (SELECT t2.MANDANT_ID,
    t2.WUP_ID,
    t2.NB_ID,
    t2.DAT_MISSING,
    t2.MISSING_BONANZAHL,
    t2.SOURCE_BONANZAHL,
    t2.UMSATZ_PRZ,
    t2.DAT_SOURCE
   FROM (SELECT W1.MANDANT_ID,
      W1.WUP_ID,
      W1.NB_ID,
      W1.DAT AS DAT_MISSING,
      W1.BONANZAHL AS MISSING_BONANZAHL,
      W2.BONANZAHL AS SOURCE_BONANZAHL,
      WWZP.UMSATZ_PRZ,
      W2.DAT AS DAT_SOURCE,
      W1.DAT,
      W2.DAT AS DAT0
     FROM KFL_PRODUCTION_DBP_DATA.WUPCAL AS W1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL AS W2 ON W1.MANDANT_ID = W2.MANDANT_ID AND W1.WUP_ID = W2.WUP_ID AND W1.NB_ID = W2.NB_ID
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS T1 ON W1.DAT = T1.DAT AND T1.DAT < CURRENT_DATE AND T1.DAT > PARSE_DATE('%F', '2003-11-23')
      INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER AS WWZP ON W1.MANDANT_ID = WWZP.MANDANT_ID AND W1.WUP_ID = WWZP.WUP_ID AND W1.NB_ID = WWZP.NB_ID AND T1.WTAG_ID = WWZP.WTAG_ID
     WHERE W2.BONANZAHL <> 0
      AND W2.DAT < W1.DAT
      AND W1.DATENLIEFERUNG_BONANZAHL IN (0, 2)
      AND W1.OFFEN = 1
      AND W1.NB_ID IN (0)
      AND WWZP.DAT_BIS = PARSE_DATE('%F', '9999-12-31')
     QUALIFY (ROW_NUMBER() OVER (PARTITION BY W1.MANDANT_ID, W1.WUP_ID, W1.NB_ID, W1.DAT ORDER BY DAT0 IS NULL DESC, DAT0 DESC)) = 1) AS t2) AS dt1
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS T2 ON dt1.DAT_SOURCE = T2.DAT AND T2.DAT < CURRENT_DATE
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER AS WWZP0 ON dt1.MANDANT_ID = WWZP0.MANDANT_ID AND dt1.WUP_ID = WWZP0.WUP_ID AND dt1.NB_ID = WWZP0.NB_ID AND T2.WTAG_ID = WWZP0.WTAG_ID AND WWZP0.DAT_BIS = PARSE_DATE('%F', '9999-12-31'));


DELETE FROM KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP
WHERE (MANDANT_ID, WUP_ID, NB_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL
  WHERE DATENLIEFERUNG_BONANZAHL = 1
   AND BONANZAHL <> 0);


