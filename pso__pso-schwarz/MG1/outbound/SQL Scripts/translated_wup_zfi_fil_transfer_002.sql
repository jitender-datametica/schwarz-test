CREATE OR REPLACE TEMPORARY TABLE _UPD AS
SELECT MANDANT_ID,
 WUP_ID,
 ORIG_WUP_ID,
 AKTUELL_WUP_ID,
 DATE_SUB(DAT_VON, INTERVAL 1 DAY) AS DAT_BIS,
  - 1 * WUP_AENDERUNG_GRUND_ID AS WUP_AENDERUNG_GRUND_ID
FROM KFL_PRODUCTION_DBP_DATA.WUP
WHERE WUP_AENDERUNG_GRUND_ID IN (- 2, - 3)
 AND MANDANT_ID = 1
 AND CURRENT_DATE = DAT_VON;


CREATE OR REPLACE TEMPORARY TABLE _UPD2 AS
SELECT A.MANDANT_ID,
 B.WUP_ID,
 A.ORIG_WUP_ID,
 A.AKTUELL_WUP_ID,
 A.DAT_VON AS DAT_VON_ALT,
 A.DAT_EROEFFNUNG AS DAT_EROEFFNUNG_ALT
FROM KFL_PRODUCTION_DBP_DATA.WUP AS A
 INNER JOIN `_UPD` AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B.ORIG_WUP_ID
WHERE A.WUP_AENDERUNG_GRUND_ID IN (0)
 AND A.MANDANT_ID = 1;


UPDATE KFL_PRODUCTION_DBP_DATA.WUP SET
 DAT_EROEFFNUNG_ALT = b.DAT_EROEFFNUNG_ALT,
 DAT_VON_ALT = b.DAT_VON_ALT FROM `_UPD2` AS b
WHERE WUP.MANDANT_ID = b.MANDANT_ID AND WUP.WUP_ID = b.ORIG_WUP_ID;


UPDATE KFL_PRODUCTION_DBP_DATA.WUP SET
 DAT_BIS = b.DAT_BIS,
 WUP_AENDERUNG_GRUND_ID = b.WUP_AENDERUNG_GRUND_ID FROM `_UPD` AS b
WHERE WUP.MANDANT_ID = b.MANDANT_ID AND WUP.WUP_ID = b.ORIG_WUP_ID AND WUP.AKTUELL_WUP_ID = b.AKTUELL_WUP_ID AND WUP.WUP_AENDERUNG_GRUND_ID
   = 0;


UPDATE KFL_PRODUCTION_DBP_DATA.WUP SET
 AKTUELL_WUP_ID = b.WUP_ID,
 WUP_AENDERUNG_GRUND_ID = 0,
 WUP_ID_ALT = CASE
  WHEN WUP.WUP_AENDERUNG_GRUND_ID = - 2
  THEN b.ORIG_WUP_ID
  ELSE NULL
  END FROM `_UPD` AS b
WHERE WUP.MANDANT_ID = b.MANDANT_ID AND WUP.WUP_ID = b.WUP_ID AND WUP.WUP_AENDERUNG_GRUND_ID IN (- 2, - 3);


