INSERT INTO KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT (MANDANT_ID, WUP_ID, NB_ID, DAT, OFFEN, OFFEN_VON, OFFEN_BIS,
 OFFEN_THEKE_VON, OFFEN_THEKE_BIS)
(SELECT x.MANDANT_ID,
  x.WUP_ID,
  x.NB_ID,
  B.DAT,
  x.OFFEN,
  x.OFFEN_VON_,
  x.OFFEN_BIS_,
  x.OFFEN_THEKE_VON,
  x.OFFEN_THEKE_BIS
 FROM (SELECT MANDANT_ID,
    WUP_ID,
    NB_ID,
    1 AS OFFEN,
    MIN(CASE
      WHEN OFFEN_VON = 240000
      THEN 0
      ELSE OFFEN_VON
      END) AS OFFEN_VON_,
    MAX(CASE
      WHEN OFFEN_BIS = 240000
      THEN 0
      ELSE OFFEN_BIS
      END) AS OFFEN_BIS_,
    MIN(TIME(CAST(CAST(CASE
         WHEN OFFEN_VON = 240000
         THEN 0
         ELSE OFFEN_VON
         END AS STRING FORMAT '000000') AS DATETIME))) AS OFFEN_THEKE_VON,
    MAX(TIME(CAST(CAST(CASE
         WHEN OFFEN_BIS = 240000
         THEN 0
         ELSE OFFEN_BIS
         END AS STRING FORMAT '000000') AS DATETIME))) AS OFFEN_THEKE_BIS
   FROM KFL_PRODUCTION_DBP_DATA.WUPCAL AS A
   GROUP BY MANDANT_ID,
    WUP_ID,
    NB_ID,
    OFFEN) AS x
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS B ON TRUE
 WHERE B.DAT BETWEEN DATE_ADD(CURRENT_DATE, INTERVAL 1 DAY) AND (DATE_ADD(CURRENT_DATE, INTERVAL 90 DAY))
  AND (x.MANDANT_ID, x.WUP_ID, x.NB_ID, B.DAT) NOT IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
    FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT)
 GROUP BY x.MANDANT_ID,
  x.WUP_ID,
  x.NB_ID,
  x.OFFEN,
  x.OFFEN_VON_,
  x.OFFEN_BIS_,
  x.OFFEN_THEKE_VON,
  x.OFFEN_THEKE_BIS,
  B.DAT);


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT SET
 OFFEN_VON = b.OFFEN_VON_,
 OFFEN_BIS = b.OFFEN_BIS_,
 OFFEN_THEKE_VON = b.OFFEN_THEKE_VON,
 OFFEN_THEKE_BIS = b.OFFEN_THEKE_BIS,
 TD_UPDATE = CURRENT_TIMESTAMP() FROM (SELECT t1.DAT,
   t1.WTAG_ID,
   t1.MANDANT_ID,
   t1.WUP_ID,
   t1.OFFEN_VON_,
   t1.OFFEN_BIS_,
   TIME(CAST(CAST(t1.OFFEN_VON_ AS STRING FORMAT '000000') AS DATETIME)) AS OFFEN_THEKE_VON,
   TIME(CAST(CAST(t1.OFFEN_BIS_ AS STRING FORMAT '000000') AS DATETIME)) AS OFFEN_THEKE_BIS
  FROM (SELECT A.DAT,
     A.WTAG_ID,
     B.MANDANT_ID,
     B.WUP_ID,
      CASE
      WHEN B.ZEIT_VON = 240000
      THEN 0
      ELSE B.ZEIT_VON
      END AS OFFEN_VON_,
      CASE
      WHEN B.ZEIT_BIS = 240000
      THEN 0
      ELSE B.ZEIT_BIS
      END AS OFFEN_BIS_
    FROM KFL_PRODUCTION_DBP_DATA.TAG AS A
     INNER JOIN KFL_PRODUCTION_DBP_DATA.VAUS_WUP_OEFFNUNG_ZU_PER AS B ON A.WTAG_ID = B.WUP_OEFFNUNGS_TYP_ID
    WHERE A.DAT BETWEEN DATE_ADD(CURRENT_DATE, INTERVAL 1 DAY) AND (DATE_ADD(CURRENT_DATE, INTERVAL 90 DAY))
    GROUP BY A.DAT,
     A.WTAG_ID,
     B.MANDANT_ID,
     B.WUP_ID,
     OFFEN_VON_,
     OFFEN_BIS_) AS t1) AS b
WHERE WUPCAL_ZUKUNFT.MANDANT_ID = b.MANDANT_ID AND WUPCAL_ZUKUNFT.DAT = b.DAT AND WUPCAL_ZUKUNFT.WUP_ID = b.WUP_ID;


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT SET
 OFFEN = t0.OFFEN,
 TD_UPDATE = CURRENT_TIMESTAMP() FROM (SELECT MANDANT_ID,
   WUP_ID,
   NB_ID,
   DAT,
   MAX(OFFEN) AS OFFEN
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_EREIGNIS_ZU AS WEZ
  GROUP BY DAT,
   WUP_ID,
   NB_ID,
   MANDANT_ID) AS t0
WHERE t0.MANDANT_ID = WUPCAL_ZUKUNFT.MANDANT_ID AND t0.WUP_ID = WUPCAL_ZUKUNFT.WUP_ID AND t0.NB_ID = WUPCAL_ZUKUNFT.NB_ID
    AND t0.DAT = WUPCAL_ZUKUNFT.DAT;


CREATE TEMPORARY TABLE IF NOT EXISTS _AVG_IST AS
SELECT T1.MANDANT_ID,
 T1.WUP_ID,
 T1.WTAG_ID,
 AVG(T1.UMS_NETTO) AS UMSATZ_NETTO
FROM KFL_PRODUCTION_DBP_MSI_DATA.VIS_TAG_UMSATZ_KUNDE_WUP AS T1
 INNER JOIN KFL_PRODUCTION_DBP_DATA.MANDANT AS T2 ON T1.MANDANT_ID = T2.MANDANT_ID AND T1.WRG_ID = T2.DEFAULT_WRG
WHERE T1.AKT_WO BETWEEN - 10 AND (- 1)
GROUP BY T1.MANDANT_ID,
 T1.WUP_ID,
 T1.WTAG_ID;


CREATE TEMPORARY TABLE IF NOT EXISTS _PLAN AS
SELECT T1.MANDANT_ID,
 T1.WUP_ID,
 T1.DAT,
 T2.WTAG_ID,
 T1.WRG_ID,
 COALESCE(T1.UMS_NETTO_PLAN_MAN_MELDESCHLUSS_PLUS2, T1.UMS_NETTO_PLAN_MAN) AS UMSATZ_PLAN_HL
FROM KFL_PRODUCTION_DBP_DATA.WUP_STUNDEN_TAG AS T1
 INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS T2 ON T1.DAT = T2.DAT
WHERE T2.AKT_WO BETWEEN 0 AND 16;


CREATE TEMPORARY TABLE IF NOT EXISTS _UMSATZ_HEBEL AS
SELECT A.MANDANT_ID,
 A.WUP_ID,
 A.DAT,
 A.WRG_ID,
 COALESCE(CAST(A.UMSATZ_PLAN_HL AS BIGNUMERIC) / IF(CAST(B.UMSATZ_NETTO AS BIGNUMERIC) = 0, NULL, CAST(B.UMSATZ_NETTO AS BIGNUMERIC)
    ), 1.0000) AS UMSATZ_HEBEL
FROM `_PLAN` AS A
 INNER JOIN `_AVG_IST` AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B.WUP_ID AND A.WTAG_ID = B.WTAG_ID;


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT SET
 SSM_UMSATZ_FAKTOR = b.UMSATZ_HEBEL,
 TD_UPDATE = CURRENT_TIMESTAMP() FROM `_UMSATZ_HEBEL` AS b
WHERE WUPCAL_ZUKUNFT.MANDANT_ID = b.MANDANT_ID AND WUPCAL_ZUKUNFT.WUP_ID = b.WUP_ID AND WUPCAL_ZUKUNFT.DAT = b.DAT AND
  WUPCAL_ZUKUNFT.DAT > DATE_ADD(CURRENT_DATE, INTERVAL 55 DAY);


