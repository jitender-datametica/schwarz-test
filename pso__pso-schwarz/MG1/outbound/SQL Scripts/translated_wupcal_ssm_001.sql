UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL SET
 OFFEN_VON = b.OFFEN_VON,
 OFFEN_BIS = b.OFFEN_BIS FROM (SELECT A.MANDANT_ID,
   A.WUP_ID,
   A.DAT,
   MAX(C.ZEIT_VON) AS OFFEN_VON,
   MAX(C.ZEIT_BIS) AS OFFEN_BIS
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL AS A
   INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS B ON A.DAT = B.DAT
   INNER JOIN KFL_PRODUCTION_DBP_DATA.VAUS_WUP_OEFFNUNG_ZU_PER AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.WUP_ID = C.WUP_ID
        AND A.DAT BETWEEN C.DAT_VON AND C.DAT_BIS AND B.WTAG_ID = C.WUP_OEFFNUNGS_TYP_ID
  WHERE A.NB_ID = 0
   AND A.OFFEN_VON IS NULL
   AND A.DAT >= DATE '2024-01-01'
   AND A.OFFEN = 1
  GROUP BY A.MANDANT_ID,
   A.WUP_ID,
   A.DAT) AS b
WHERE WUPCAL.MANDANT_ID = b.MANDANT_ID AND WUPCAL.WUP_ID = b.WUP_ID AND WUPCAL.DAT = b.DAT AND WUPCAL.OFFEN_VON IS NULL
  AND WUPCAL.OFFEN = 1 AND WUPCAL.NB_ID = 0;


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT SET
 OFFEN_VON = b.OFFEN_VON,
 OFFEN_BIS = b.OFFEN_BIS FROM (SELECT A.MANDANT_ID,
   A.WUP_ID,
   A.DAT,
   MAX(C.ZEIT_VON) AS OFFEN_VON,
   MAX(C.ZEIT_BIS) AS OFFEN_BIS
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_ZUKUNFT AS A
   INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG AS B ON A.DAT = B.DAT
   INNER JOIN KFL_PRODUCTION_DBP_DATA.VAUS_WUP_OEFFNUNG_ZU_PER AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.WUP_ID = C.WUP_ID
        AND A.DAT BETWEEN C.DAT_VON AND C.DAT_BIS AND B.WTAG_ID = C.WUP_OEFFNUNGS_TYP_ID
  WHERE A.NB_ID = 0
   AND A.OFFEN_VON IS NULL
   AND A.DAT >= DATE '2024-01-01'
   AND A.OFFEN = 1
  GROUP BY A.MANDANT_ID,
   A.WUP_ID,
   A.DAT) AS b
WHERE WUPCAL_ZUKUNFT.MANDANT_ID = b.MANDANT_ID AND WUPCAL_ZUKUNFT.WUP_ID = b.WUP_ID AND WUPCAL_ZUKUNFT.DAT = b.DAT AND
   WUPCAL_ZUKUNFT.OFFEN_VON IS NULL AND WUPCAL_ZUKUNFT.OFFEN = 1 AND WUPCAL_ZUKUNFT.NB_ID = 0;