CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_ETL.MV_ARTBEW_WO_SUM (KJWO, ART_ID, WG_ID, BEWART_ID, MANDANT_ID, WUP_ID,
NB_ID, EK_MEP_UMSATZ, UMSATZ_NETTO, MENGE) AS SELECT KJWO,
 ART_ID,
 WG_ID,
 BEWART_ID,
 MANDANT_ID,
 WUP_ID,
 NB_ID,
 CAST(EK_MEP AS FLOAT64) AS EK_MEP_UMSATZ,
 CAST(UMSATZ_NETTO AS FLOAT64) AS UMSATZ_NETTO,
 CAST(MENGE AS FLOAT64) AS MENGE
FROM KFL_PRODUCTION_DBP_ETL.BF_ARTBEW_WG_ART_WO_SUM_STP_DE
WHERE MANDANT_ID = 1;