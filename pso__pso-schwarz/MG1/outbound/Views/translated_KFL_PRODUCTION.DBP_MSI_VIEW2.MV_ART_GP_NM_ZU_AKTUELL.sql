CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW2.MV_ART_GP_NM_ZU_AKTUELL (ART_ID, AKT_GP_ID, GP_NAME, MANDANT_ID,
ANZ_LIEF) AS SELECT V01.ART_ID,
 V01.GP_ID AS AKT_GP_ID,
 V02.GP_NAME,
 V01.MANDANT_ID,
 COUNT(V01.WUP_ID) AS ANZ_LIEF
FROM KFL_PRODUCTION_DBP_VIEW.V_ART_GP_NM_ZU_PER AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_GP AS V02 ON V01.GP_ID = V02.GP_ID AND V01.MANDANT_ID = V02.MANDANT_ID
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_WUP AS V03 ON V01.MANDANT_ID = V03.MANDANT_ID AND V01.WUP_ID = V03.WUP_ID AND V01
   .NB_ID = V03.NB_ID
WHERE V01.DAT_BIS = DATE '9999-12-31'
 AND V01.MANDANT_ID = 1
 AND V03.NB_ID = 0
 AND CURRENT_DATE BETWEEN V03.DAT_VON AND V03.DAT_BIS
GROUP BY V01.MANDANT_ID,
 V01.ART_ID,
 V01.GP_ID,
 V02.GP_NAME
QUALIFY (ROW_NUMBER() OVER (PARTITION BY CAST(V01.ART_ID AS STRING) ORDER BY ANZ_LIEF IS NULL, ANZ_LIEF)) = 1;