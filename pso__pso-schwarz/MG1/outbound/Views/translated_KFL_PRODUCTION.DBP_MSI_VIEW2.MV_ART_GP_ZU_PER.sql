CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW2.MV_ART_GP_ZU_PER (ART_ID, GP_ID, MANDANT_ID, AKTUELL_FG) AS SELECT
 ART_ID,
 GP_ID,
 MANDANT_ID,
  CASE
  WHEN DAT_BIS = DATE '9999-12-31'
  THEN 'a'
  ELSE 'h'
  END AS AKTUELL_FG
FROM KFL_PRODUCTION_DBP_VIEW.V_ART_GP_ZU_PER
WHERE MANDANT_ID = 1
QUALIFY (SUM(1) OVER (PARTITION BY CAST(ART_ID AS STRING), CAST(GP_ID AS STRING), CAST(MANDANT_ID AS STRING) ORDER BY
      DAT_BIS IS NULL, DAT_BIS ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)) = 1;