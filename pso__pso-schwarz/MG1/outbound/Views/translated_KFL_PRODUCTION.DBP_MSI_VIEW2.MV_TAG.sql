	DAT_VVJ_DATE
) AS
-- KARWOCHE IDENTIFIZIEREN
WITH KAR_WOCHE AS(
SELECT 
DISTINCT V01.DAT, V01.KJWO, V01.AKT_WO
FROM KFL_PRODUCTION_DBP_VIEW.V_TAG  V01
JOIN KFL_PRODUCTION_DBP_VIEW.V_WUPCAL_EREIGNIS_ZU V02
ON V01.DAT = V02.DAT
WHERE V02.MANDANT_ID = 1 
AND V02.EREIGNIS_ID = 5 
AND V02.EREIGNISTYP_ID = 1 
AND V01.DAT >= '2019-01-01') 
-- ZEITRAUM FUER OSTERN DEFINIEREN 
-- KARWOCHE - 10 WOCHEN + 2 WOCHEN 
, OSTER_SAISON_ZEITRAUM AS (
SELECT   V01.DAT, 
V01.AKT_KJ,
V01.KJWO,
DENSE_RANK() OVER (PARTITION BY V01.AKT_KJ ORDER BY V01.DAT ASC) AS SORT_ID_OSTERTAGE
FROM KFL_PRODUCTION_DBP_VIEW.V_TAG V01
JOIN KAR_WOCHE 
ON V01.AKT_WO BETWEEN KAR_WOCHE.AKT_WO -10 AND KAR_WOCHE.AKT_WO + 2)
-- VJ / VVJ DAT ERMITTELN 
, OSTERN_SAISON_VJ_VVJ_FAKTEN AS 
(SELECT 
V01.DAT,
VJ.KJWO AS KJWO_VJ_OSTERN,
VJ.DAT AS DAT_VJ_OSTERN,
VVJ.KJWO AS KJWO_VVJ_OSTERN,
VVJ.DAT AS DAT_VVJ_OSTERN
FROM OSTER_SAISON_ZEITRAUM V01
LEFT JOIN OSTER_SAISON_ZEITRAUM VJ
ON V01.AKT_KJ-1 = VJ.AKT_KJ
AND V01.SORT_ID_OSTERTAGE = VJ.SORT_ID_OSTERTAGE
LEFT JOIN OSTER_SAISON_ZEITRAUM VVJ
ON V01.AKT_KJ-2 = VVJ.AKT_KJ
AND V01.SORT_ID_OSTERTAGE = VVJ.SORT_ID_OSTERTAGE)

   SELECT
   V01.DAT,
   V01.KJMO, 
   V01.KJMO_VJ, 
   V01.WTAG_ID, 
   V01.KJWO, 
   V01.KJWO_VJ, 
   V01.GJWO, 
   V01.GJWO_VJ, 
   V01.WO_DAT_VON, 
   V01.WO_DAT_BIS, 
   V01.GJMO, 
   V01.GJMO_VJ, 
   V01.KJQU, 
   V01.GJQU, 
   V01.KJ, 
   V01.GJ, 
   V01.KJTAG_ID, 
   V01.GJTAG_ID, 
   V01.KJWO_KL, 
   V01.KJWO_KL_DAT_VON, 
   V01.KJWO_KL_DAT_BIS, 
   V01.GJWO_KL, 
   V01.GJWO_KL_DAT_VON, 
   V01.GJWO_KL_DAT_BIS, 
   V01.DAT_VJ, 
   V01.AKT_TAG, 
   V01.AKT_MO, 
   V01.AKT_MO_KOMPLETT, 
   V01.AKT_WO, AKT_WO_KOMPLETT, 
   V01.AKT_GJWO_KL, 
   V01.AKT_GJWO_KL_KOMPLETT, 
   V01.AKT_KJWO_KL, 
   V01.AKT_KJWO_KL_KOMPLETT, 
   V01.AKT_GJQU, 
   V01.AKT_GJQU_KOMPLETT, 
   V01.AKT_KJQU, 
   V01.AKT_KJQU_KOMPLETT, 
   V01.AKT_GJ, 
   V01.AKT_GJ_KOMPLETT, 
   V01.AKT_KJ, 
   V01.AKT_KJ_KOMPLETT, 
   V01.MO_GJ, 
   V01.MO_KJ, 
   V01.DAT_VJ-364, 
   V01.AKT_MO/3, 
   CASE
      WHEN LAST_DAY(V01.DAT) = V01.DAT THEN LAST_DAY(DATETIME_ADD(V01.DAT, INTERVAL -1 MONTH))
      ELSE DATETIME_ADD(V01.DAT, INTERVAL -1 MONTH)
    END, 
   CASE
      WHEN LAST_DAY(V01.DAT) = V01.DAT THEN LAST_DAY(DATETIME_ADD(V01.DAT, INTERVAL -12 MONTH))
      ELSE DATETIME_ADD(V01.DAT, INTERVAL -12 MONTH)
    END,

   V01.DAT_VJ_KT,

   V02.DAT_VJ_OSTERN,
   V02.DAT_VVJ_OSTERN,

   CASE
      WHEN LAST_DAY(V01.DAT_VJ_KT) = V01.DAT_VJ_KT THEN LAST_DAY(DATETIME_ADD(V01.DAT_VJ_KT, INTERVAL -12 MONTH))
      ELSE DATETIME_ADD(V01.DAT_VJ_KT, INTERVAL -12 MONTH)
    END AS DAT_VVJ_KT 
   FROM KFL_PRODUCTION_DBP_VIEW.V_TAG V01
   LEFT JOIN OSTERN_SAISON_VJ_VVJ_FAKTEN V02
   ON V01.DAT = V02.DAT;
