	DAT,
	KJMO,
	KJMO_VJ,
	WTAG_ID,
	KJWO,
	KJWO_VJ,
	GJWO,
	GJWO_VJ,
	WO_DAT_VON,
	WO_DAT_BIS,
	GJMO,
	GJMO_VJ,
	KJQU,
	GJQU,
	KJ,
	GJ,
	KJTAG_ID,
	GJTAG_ID,
	KJWO_KL,
	KJWO_KL_DAT_VON,
	KJWO_KL_DAT_BIS,
	GJWO_KL,
	GJWO_KL_DAT_VON,
	GJWO_KL_DAT_BIS,
	DAT_VJ,
