CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW2.MV_WG_SPR_ZU (WG_ID, SPR_ID, ARTHIERTYP_ID, MANDANT_ID, WG_BEZ,
WG_ID_BEZ) AS SELECT WG_ID,
 SPR_ID,
 ARTHIERTYP_ID,
 MANDANT_ID,
 WG_BEZ,
    CASE
    WHEN WG_ID < 10
    THEN '00' || CAST(WG_ID AS STRING)
    WHEN WG_ID < 100
    THEN '0' || CAST(WG_ID AS STRING)
    ELSE CAST(WG_ID AS STRING)
    END || '  ' || WG_BEZ AS WG_ID_BEZ
FROM KFL_PRODUCTION_DBP_VIEW.V_WG_SPR_ZU
WHERE SPR_ID = 22
 AND ARTHIERTYP_ID = 2
 AND MANDANT_ID = 1
 AND WG_ID >= - 3;