CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW2.MV_WUG_SPR_ZU (MANDANT_ID, WUG_ID, ARTHIERTYP_ID, WG_ID, SPR_ID,
WUG_BEZ, WUG_ID_BEZ) AS SELECT MANDANT_ID,
 WUG_ID,
 ARTHIERTYP_ID,
 WG_ID,
 SPR_ID,
 WUG_BEZ,
 SUBSTR(CAST(SUBSTR(CAST(WUG_ID AS STRING), 1, 10) || '   ' || WUG_BEZ AS STRING), 1, 50) AS WUG_ID_BEZ
FROM KFL_PRODUCTION_DBP_VIEW.V_WUG_SPR_ZU
WHERE SPR_ID = 22
 AND MANDANT_ID = 1
 AND ARTHIERTYP_ID = 2;