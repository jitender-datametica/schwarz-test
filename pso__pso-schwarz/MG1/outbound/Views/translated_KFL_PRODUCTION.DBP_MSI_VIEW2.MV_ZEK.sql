CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW2.MV_ZEK (ZEK_ID, MANDANT_ID, WBL_ID, ZEK_NAME, ZEK_LANG_BEZ,
ZEK_ELTERN_SEC_ID, ZEK_ELTERN_MANDANT_ID) AS SELECT ZEK_ID,
 MANDANT_ID,
 WBL_ID,
 ZEK_NAME,
  CASE
  WHEN ZEK_ID = '-99'
  THEN '-099' || ' ' || ZEK_NAME
  WHEN ZEK_ID = '-2'
  THEN '-002' || ' ' || ZEK_NAME
  WHEN ZEK_ID = '0'
  THEN '000' || ' ' || ZEK_NAME
  ELSE ZEK_ID || ' ' || ZEK_NAME
  END AS ZEK_LANG_BEZ,
 ZEK_ID AS ZEK_ELTERN_SEC_ID,
 MANDANT_ID AS ZEK_ELTERN_MANDANT_ID
FROM KFL_PRODUCTION_DBP_VIEW.V_ZEK
WHERE MANDANT_ID = 1
 AND ZEK_ID <> '-1';