CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_ABT_SPR_ZU (ABT_ID, ABT_BEZ, ABT_BEZ_DE, ABT_BEZ_CZ,
ABT_BEZ_PL, ABT_BEZ_SK, ABT_BEZ_HR, ABT_BEZ_RO, ABT_BEZ_BG) AS SELECT ABT_ID,
 MAX(CASE
   WHEN SPR_ID = 22
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ,
 MAX(CASE
   WHEN SPR_ID = 22
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_DE,
 MAX(CASE
   WHEN SPR_ID = 124
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_CZ,
 MAX(CASE
   WHEN SPR_ID = 90
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_PL,
 MAX(CASE
   WHEN SPR_ID = 108
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_SK,
 MAX(CASE
   WHEN SPR_ID = 65
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_HR,
 MAX(CASE
   WHEN SPR_ID = 95
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_RO,
 MAX(CASE
   WHEN SPR_ID = 18
   THEN ABT_BEZ
   ELSE NULL
   END) AS ABT_BEZ_BG
FROM KFL_PRODUCTION_DBP_VIEW.V_ABT_SPR_ZU
WHERE ARTHIERTYP_ID = 2
GROUP BY ABT_ID;