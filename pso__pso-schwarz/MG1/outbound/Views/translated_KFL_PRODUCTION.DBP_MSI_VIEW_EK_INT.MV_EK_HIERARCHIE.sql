CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_EK_HIERARCHIE (MANDANT_ID, ZEK_ID, ZEK_NAME, WBL_ID,
WBL_NAME, GF_ID, GF_NAME) AS SELECT V01.MANDANT_ID,
 V01.ZEK_ID,
 V01.ZEK_NAME,
 V01.WBL_ID,
 V02.WBL_NAME,
 V02.GF_ID,
 V03.GF_NAME
FROM KFL_PRODUCTION_DBP_VIEW.V_ZEK AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_WBL AS V02 ON V01.MANDANT_ID = V02.MANDANT_ID AND V01.WBL_ID = V02.WBL_ID
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_GF AS V03 ON V02.MANDANT_ID = V03.MANDANT_ID AND V02.GF_ID = V03.GF_ID;