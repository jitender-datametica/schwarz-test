CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_L_LAND (LAND_ID, MANDANT_ID, LAND_SORT_ID) AS SELECT CAST(MANDANT_ID AS BIGNUMERIC)
 AS LAND_ID,
 CAST(MANDANT_ID AS BIGNUMERIC) AS MANDANT_ID,
 CAST(CASE
   WHEN MANDANT_ID = 1
   THEN 2
   WHEN MANDANT_ID = 2
   THEN 4
   WHEN MANDANT_ID = 5
   THEN 5
   WHEN MANDANT_ID = 6
   THEN 6
   WHEN MANDANT_ID = 3
   THEN 7
   WHEN MANDANT_ID = 7
   THEN 8
   WHEN MANDANT_ID = 8
   THEN 9
   WHEN MANDANT_ID = 4
   THEN 10
   ELSE NULL
   END AS BIGNUMERIC) AS LAND_SORT_ID
FROM KFL_PRODUCTION_DBP_VIEW.V_MANDANT AS V01
UNION ALL
SELECT - 1 AS LAND_ID,
 CAST(MANDANT_ID AS BIGNUMERIC) AS MANDANT_ID,
 1 AS LAND_SORT_ID
FROM KFL_PRODUCTION_DBP_VIEW.V_MANDANT AS V02
UNION ALL
SELECT - 2 AS LAND_ID,
 CAST(MANDANT_ID AS BIGNUMERIC) AS MANDANT_ID,
 3 AS LAND_SORT_ID
FROM KFL_PRODUCTION_DBP_VIEW.V_MANDANT AS V03
WHERE MANDANT_ID NOT IN (1);