CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_WUG (MANDANT_ID, ARTHIERTYP_ID, WG_ID, WUG_ID, WGI_ID) AS
SELECT MANDANT_ID,
 ARTHIERTYP_ID,
 WG_ID,
 WUG_ID,
   CASE
   WHEN WG_ID < 0
   THEN '-' || SUBSTR(CAST(WG_ID AS STRING), 1, 3)
   ELSE SUBSTR(CAST(WG_ID AS STRING), 1, 3)
   END || CASE
   WHEN WUG_ID < 0
   THEN '-' || SUBSTR(CAST(WUG_ID AS STRING), 1, 3)
   ELSE SUBSTR(CAST(WUG_ID AS STRING), 1, 3)
   END AS WGI_ID
FROM KFL_PRODUCTION_DBP_VIEW.V_WUG AS V01
WHERE ARTHIERTYP_ID = 2;