CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_WUG_SPR_ZU (MANDANT_ID, ARTHIERTYP_ID, WG_ID, WUG_ID,
WUG_GESPERRT, WUG_BEZ, WUG_BEZ_DE, WUG_BEZ_CZ, WUG_BEZ_SK, WUG_BEZ_HR, WUG_BEZ_PL, WUG_BEZ_RO, WUG_BEZ_BG) AS SELECT V01
 .MANDANT_ID,
 V01.ARTHIERTYP_ID,
 V01.WG_ID,
 V01.WUG_ID,
 MAX(COALESCE(CASE
    WHEN INSTR(UPPER(CASE
        WHEN V01.MANDANT_ID = 1
        THEN 'Gesperrt'
        WHEN V01.MANDANT_ID = 2
        THEN 'BLOKOV\u00c1NO'
        WHEN V01.MANDANT_ID = 3
        THEN 'zablokowane'
        WHEN V01.MANDANT_ID = 5
        THEN 'Blokované'
        WHEN V01.MANDANT_ID = 6
        THEN 'ZATVORENO'
        WHEN V01.MANDANT_ID = 7
        THEN '\u00ceNCHIS'
        WHEN V01.MANDANT_ID = 8
        THEN 'Блокирана'
        ELSE NULL
        END), V02.WUG_BEZ) = 1
    THEN 1
    ELSE NULL
    END, 0)) AS WUG_GESPERRT,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.WUG_BEZ
    ELSE NULL
    END), 'N/A') AS WUG_BEZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.WUG_BEZ
    ELSE NULL
    END), 'N/A') AS WUG_BEZ_DE,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 124
    THEN V02.WUG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WUG_BEZ
     ELSE NULL
     END), 'N/A')) AS WUG_BEZ_CZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 108
    THEN V02.WUG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WUG_BEZ
     ELSE NULL
     END), 'N/A')) AS WUG_BEZ_SK,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 65
    THEN V02.WUG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WUG_BEZ
     ELSE NULL
     END), 'N/A')) AS WUG_BEZ_HR,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 90
    THEN V02.WUG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WUG_BEZ
     ELSE NULL
     END), 'N/A')) AS WUG_BEZ_PL,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 95
    THEN V02.WUG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WUG_BEZ
     ELSE NULL
     END), 'N/A')) AS WUG_BEZ_RO,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 18
    THEN V02.WUG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WUG_BEZ
     ELSE NULL
     END), 'N/A')) AS WUG_BEZ_BG
FROM KFL_PRODUCTION_DBP_VIEW.V_WUG AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_WUG_SPR_ZU AS V02 ON V01.WG_ID = V02.WG_ID AND V01.WUG_ID = V02.WUG_ID
WHERE V01.ARTHIERTYP_ID = 2
 AND V02.ARTHIERTYP_ID = 2
GROUP BY V01.MANDANT_ID,
 V01.ARTHIERTYP_ID,
 V01.WG_ID,
 V01.WUG_ID;