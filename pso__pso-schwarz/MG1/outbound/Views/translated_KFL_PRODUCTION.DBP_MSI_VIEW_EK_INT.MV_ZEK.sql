CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_ZEK (MANDANT_ID, ZEK_ID, WBL_ID, ZEK_ID_LANG, ZEK_NAME,
ZEK_ID_LANG_NAME) AS SELECT MANDANT_ID,
 ZEK_ID,
 WBL_ID,
 -- Anpassung bisherige Logik mit FM000 aufgrund Änderung Spalte zek_id zu Textfeld - AP0172759/SPEC0207789 sschuecke 01.09.2023
  CASE
  WHEN CAST(ROUND(SAFE_CAST(ZEK_ID AS BIGNUMERIC), 0) AS STRING) <> ZEK_ID
  THEN ZEK_ID
  ELSE TRIM(CAST(ROUND(SAFE_CAST(ZEK_ID AS BIGNUMERIC), 0) AS STRING FORMAT '000'))
  END AS ZEK_ID_LANG,
 ZEK_NAME,
    CASE
    WHEN CAST(ROUND(SAFE_CAST(ZEK_ID AS BIGNUMERIC), 0) AS STRING) <> ZEK_ID
    THEN ZEK_ID
    ELSE TRIM(CAST(ROUND(SAFE_CAST(ZEK_ID AS BIGNUMERIC), 0) AS STRING FORMAT '000'))
    END || ' ' || ZEK_NAME AS ZEK_ID_LANG_NAME
FROM KFL_PRODUCTION_DBP_VIEW.V_ZEK AS V01;