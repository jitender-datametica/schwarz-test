BEGIN TRANSACTION;

MERGE INTO CORE_REL.T_INTERNAL_ORGANIZATION TRG
USING
(
	SELECT
		INT_ORG_SID,
        DWH_VALID_FROM_TMSP,
		MIN(OPEN_DT) 
			OVER (PARTITION BY INT_ORG_SID) MIN_OPEN_DT,
		MIN(TO_DATE(PLANNED_OPEN_DT)) 
			OVER (PARTITION BY INT_ORG_SID)		AS MIN_PLANNED_OPEN_DT,
		LAST_VALUE(TO_DATE(CLOSE_DT)) 
			OVER (PARTITION BY INT_ORG_SID ORDER BY CLOSE_DT ASC NULLS LAST) AS MAX_CLOSE_DT
	FROM CORE_REL.T_INTERNAL_ORGANIZATION
	WHERE INT_ORG_TYPE_CD = 'STORE'
) SRC
ON TRG.INT_ORG_SID = SRC.INT_ORG_SID
    AND TRG.DWH_VALID_FROM_TMSP = SRC.DWH_VALID_FROM_TMSP
WHEN MATCHED
		-- at least one of the values from source is not the same as target
		AND  NOT ( EQUAL_NULL( TRG.OPEN_DT , SRC.MIN_OPEN_DT )
					AND EQUAL_NULL( TRG.PLANNED_OPEN_DT , SRC.MIN_PLANNED_OPEN_DT )
					AND EQUAL_NULL( TRG.CLOSE_DT , SRC.MAX_CLOSE_DT )
				)
	THEN 
		UPDATE SET 
			TRG.OPEN_DT = SRC.MIN_OPEN_DT,
			TRG.PLANNED_OPEN_DT = SRC.MIN_PLANNED_OPEN_DT,
			TRG.CLOSE_DT = SRC.MAX_CLOSE_DT
;
COMMIT;
