INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        REAL_ESTATE_KEY_TYPE_CD,
        REAL_ESTATE_NK,
        REAL_ESTATE_NR,
        REAL_ESTATE_NAME,
        REAL_ESTATE_TYPE_CD,
        OWNERSHIP_TYPE_CD,
        OWNERSHIP_RATIO_TYPE_CD,
        OWN_ACQUISITION_FG,
        REAL_ESTATE_USG_TYPE_CD,
        WH_BUILDING_TYPE_CD,
        WH_PURPOSE_CD,
        SHARED_USG_FG,
        CONTRACT_DT,
        PRECONTRACT_DT,
        CONSTRUCTION_START_DT,
        CONSTRUCTION_END_DT,
        OPEN_DT,
        PLANNED_OPEN_DT,
        CLOSE_DT,
        PLANNED_CLOSE_DT,
        PROJECT_CANCEL_DT,
        PROJECT_TERM_DT,
        SALES_AREA_MEAS,
        STORAGE_AREA_MEAS,
        TOTAL_SUBLET_AREA_MEAS,
        RENTED_SUBLET_AREA_MEAS,
        UOM_CD,
        TOTAL_PARKING_SPACE_CNT,
        OWN_PARKING_SPACE_CNT,
        UNDERGROUND_PARKING_SPACE_CNT,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
WITH PROJ_SELECTED AS (
    SELECT * FROM ETL_PROCESS.T_TCACHE_LISY_CDS_PROJECTMILESTONES_SNAP
    WHERE DELETED != 'x'
    AND IGL_ACCOUNTNUMBER is not null
    AND IGL_PROJECTTYPECODE = 285540000 
    AND STARTOFCONSTRUCTION_ACT IS NOT NULL
    AND ENDOFPROJECT_ACT IS NOT NULL
    AND IGL_PROJECTSTATUSCODE = 285540008 -- Completed projects only
    QUALIFY ROW_NUMBER() OVER (PARTITION BY IGL_ACCOUNTNUMBER, STARTOFCONSTRUCTION_ACT ORDER BY ENDOFCONSTRUCTION_ACT DESC, SINKMODIFIEDON DESC) = 1
),
MARKETING_SELECTED AS (
        SELECT *
        , SUM(IGL_AREAQM) OVER (PARTITION BY ACCOUNT_NUMBER) AS TOTAL_AREA_MEAS -- HERE, WE COMPUTE THE TOTAL AREA WITHIN THE STORE THAT CAN BE SUBLET REGARDLESS OF WHETHER OR NOT THIS IS ACTUALLY DONE AND REGARDLESS OF THE TYPE OF AREA
        FROM ETL_PROCESS.T_TCACHE_LISY_CDS_MARKETINGAREA_SNAP
        WHERE IGL_AREATYPECODE = 285540005 -- type "Sublet area"
        AND IGL_ACCOUNTTYPECODE = 285540000 -- account type "Store"
        and ACCOUNT_NUMBER IS NOT NULL
        QUALIFY row_number() over (partition by account_number, igl_areaqm, igl_industrycode, igl_floorcode, igl_rentalincomepa order by sinkmodifiedon desc) = 1 -- THIS ROW MAKES SURE WE GET RID OF DUPLICATES
)
--- THIS IS A NEW CTE WHERE WE TAKE JUST THE SUBLET AREA SO WE FILTER BY IGL_REALISEDBOOL = TRUE
,MARKETING_SUM AS (
        SELECT
            ACCOUNT_NUMBER
            ,IGL_REALISEDBOOL 
            ,TOTAL_AREA_MEAS
            ,SUM(IGL_AREAQM) AS RENTED_AREA_MEAS -- TOTAL SUBLET AREA WITHIN THE STORE REGARDLESS OF ITS TYPE
        FROM MARKETING_SELECTED
        WHERE IGL_REALISEDBOOL = TRUE
        GROUP BY 
            ACCOUNT_NUMBER
            ,IGL_REALISEDBOOL 
            ,TOTAL_AREA_MEAS
)
SELECT
       'RE' AS REAL_ESTATE_KEY_TYPE_CD,
        SRC.IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(SRC.IGL_NUMBER, 3, LENGTH(SRC.IGL_NUMBER)), '0#') AS REAL_ESTATE_NK, -- Use for Keyspace Lookup
        SRC.IGL_NUMBER  AS REAL_ESTATE_NR, -- Target table column
        SRC.ADDRESS1_NAME AS REAL_ESTATE_NAME,
        CASE 
                WHEN SRC.IGL_ACCOUNTTYPECODE = 285540000 THEN 'STORE'
                WHEN SRC.IGL_ACCOUNTTYPECODE = 285540009 THEN 'SPEC'
                ELSE '-1'
        END AS REAL_ESTATE_TYPE_CD,
        CASE 
                WHEN SRC.IGL_PROPERTYTYPECODE = 285540000 THEN 'B'
                WHEN SRC.IGL_PROPERTYTYPECODE = 285540001 THEN 'R'
                WHEN SRC.IGL_PROPERTYTYPECODE = 285540002 THEN 'L'
                ELSE '-1'
        END AS OWNERSHIP_TYPE_CD,
        CASE 
                WHEN SRC.IGL_OWNERSHIPCODE = 285540000 THEN 'F'
                WHEN SRC.IGL_OWNERSHIPCODE = 285540001 THEN 'P'
        END AS OWNERSHIP_RATIO_TYPE_CD,
        SRC.IGL_OWNACQUISITION AS OWN_ACQUISITION_FG,
        CASE 
                WHEN (SRC.IGL_TOTALAREABUILDINGM2CALC >= MRKT.TOTAL_AREA_MEAS AND RENTED_AREA_MEAS > 0) THEN '3PTY' 
                ELSE 'OWN'
        END AS REAL_ESTATE_USG_TYPE_CD,
        NULL AS WH_BUILDING_TYPE_CD,
        NULL AS WH_PURPOSE_CD,
        NULL AS SHARED_USG_FG,
        TO_DATE(SRC.IGL_CONTRACTDATE) AS CONTRACT_DT,
        TO_DATE(SRC.IGL_PRECONTRACTDATE) AS PRECONTRACT_DT,
        PROJ.STARTOFCONSTRUCTION_ACT AS CONSTRUCTION_START_DT,
        PROJ.ENDOFCONSTRUCTION_ACT AS CONSTRUCTION_END_DT,
        TO_DATE(SRC.IGL_NEODATE) AS OPEN_DT,
        TO_DATE(SRC.IGL_EXPECTEDOPENINGDATE) AS PLANNED_OPEN_DT,
        TO_DATE(SRC.IGL_CLOSINGDATE) AS CLOSE_DT,
        TO_DATE(SRC.IGL_EXPECTEDCLOSINGDATE) AS PLANNED_CLOSE_DT,
        TO_DATE(SRC.IGL_NOIMPLEMENTATIONDATE) AS PROJECT_CANCEL_DT,
        IGL_FINALSETTLEMENTDATE AS PROJECT_TERM_DT,
        SRC.IGL_SALESAREA AS SALES_AREA_MEAS,
        SRC.IGL_LSTORAGEAREA AS STORAGE_AREA_MEAS,
        CASE 
                WHEN SRC.IGL_TOTALAREABUILDINGM2CALC >= MRKT.TOTAL_AREA_MEAS THEN MRKT.TOTAL_AREA_MEAS
                ELSE NULL
        END AS TOTAL_SUBLET_AREA_MEAS,
        RENTED_AREA_MEAS AS RENTED_SUBLET_AREA_MEAS,
        'SQMT' AS UOM_CD,
        SRC.IGL_PARKINGTOTAL AS TOTAL_PARKING_SPACE_CNT,
        SRC.IGL_PARKINGLIDL AS OWN_PARKING_SPACE_CNT,
        SRC.IGL_PARKINGDECK AS UNDERGROUND_PARKING_SPACE_CNT,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CASE 
        WHEN RE.REAL_ESTATE_NR IS NOT NULL THEN SRC.SINKMODIFIEDON 
        WHEN IGL_EXPECTEDOPENINGDATE > CURRENT_DATE OR IGL_NEODATE >= CURRENT_DATE THEN SRC.SINKMODIFIEDON
        ELSE NVL(SRC.IGL_NEODATE, SRC.SINKMODIFIEDON)
        END AS DWH_MAPPING_TMSP,
         0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM etl_process.t_${SRC_INPUT_TABLE} SRC
LEFT JOIN 
(SELECT DISTINCT REAL_ESTATE_NR from CORE_REL.T_REAL_ESTATE
 WHERE DWH_NODE_CD = 'LISY') RE
 ON SRC.IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(SRC.IGL_NUMBER, 3, LENGTH(SRC.IGL_NUMBER)), '0#') = RE.REAL_ESTATE_NR
LEFT OUTER JOIN PROJ_SELECTED PROJ
ON PROJ.IGL_ACCOUNTNUMBER = SRC.IGL_NUMBER
LEFT OUTER JOIN MARKETING_SUM MRKT
ON  SRC.IGL_NUMBER = MRKT.ACCOUNT_NUMBER
WHERE SRC.IGL_ACCOUNTTYPECODE IN (285540000, 285540009)  -- Real Estate associated with stores and 'special sale' stores
AND SRC.IGL_NUMBER IS NOT NULL -- (only objects with assigned object number should be kept)
AND SRC.DELETED <> 'x';
