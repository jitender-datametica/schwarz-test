/* Source / Target Dedupe Notes:

We must avoid UPDATEing any rows that already exist (exact duplicates) due to the unnecessary time that would take. 
This will happen due to transactions already loaded by the live processing.
We only need process updates for transactions where values may have changed.

The framework has a method for handling this - the UNHIST mode. 
This mode introduces a MINUS operation when loading to TS however it does not inlucde any predicates for the 
target table, therefore, we would scan the whole of PRODUCT_RETAIL_LINE, not performant. 
Therefore, we are not going to use that method, instead we will embed a custom dedupe operation (which includes predicates) in this post-load script.

Logically, we must exclude any rows in source that pre-exist.. 
We will do that using the country_org_cd, bus_dt cluster keys to avoid a full table scan of the target

*/

