CREATE OR REPLACE TEMPORARY TABLE ETL.VT_${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}_PROCESS
AS SELECT * 
FROM ETL.t_${SRC_INPUT_TABLE} SRC
WHERE LOWER(CONTEXT_COUNTRY) IN (${SRC_COUNTRY_LIST})
AND RECEIPT_TRANSACTIONTYPE_ID BETWEEN '100' AND '399'
QUALIFY Row_Number() OVER (
PARTITION BY
        CONTEXT_COUNTRY
      , ORIG_STORE_NR
      , POS_TERMINAL_ID
      , ORIG_RECEIPT_NR
      , RECEIPT_BUSINESS_DATE
ORDER BY
        RECEIPT_TIMESTAMP_END DESC
      , POSNR
) = 1;

INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        RETAIL_EVENT_SID,
        CASH_REGISTER_EVENT_NR,
        EVENT_START_TMSP,
        EVENT_END_TMSP,
        BUS_DT,
        CASH_REGISTER_TYPE_CD,
        CASH_REGISTER_USG_TYPE_CD,
        CASHIER_NR,
        AUTH_BY_NR,
        CUST_IDENT_TYPE_CD,
        RETAIL_EVENT_TYPE_CD,
        RETAIL_EVENT_SCENARIO_ID,
        OFFLINE_FG,
        CANCEL_FG,
        SUSPEND_FG,
        TRAINING_FG,
        TXN_GROSS_VAL,
        TXN_NET_VAL,
        TXN_VAT_VAL,
        TURNOVER_RELEVANT_FG,
        SERVICE_TM_SEC_MEAS,
        PAYM_TM_SEC_MEAS,
        SCANNED_LINES_CNT,
        KEYED_LINES_CNT,
        RETAIL_EVENT_KEY_TYPE_CD,
        STORE_KEY_TYPE_CD,
        COUNTRY_ORG_KEY_TYPE_CD,
        CUST_KEY_TYPE_CD,
        CONT_RETAIL_EVENT_KEY_TYPE_CD,
        CASH_REGISTER_KEY_TYPE_CD,
        REAL_ESTATE_KEY_TYPE_CD,
        CONTEXT_COUNTRY,
        LIDLPLUS_CUSTOMER_CD,
        ORIG_RECEIPT_NR,
        ORIG_STORE_NR,
        POS_TERMINAL_ID,
        RECEIPT_BUSINESS_DATE,
        RESUMED_TRANS_DATE,
        RESUMED_TRANS_RECEIPT_NR,
        RESUMED_TRANS_STORE_NR,
        RESUMED_TRANS_TERMINAL_ID,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        ((((CAST(TO_CHAR(RECEIPT_BUSINESS_DATE, 'YYYYMMDD') AS NUMBER) * 100
        + ASCII(SUBSTRING(BIC_ZMLILA, 1, 1))) * 100
        + ASCII(SUBSTRING(BIC_ZMLILA, 2, 1))) * 100000000
        + ORIG_STORE_NR) * 10000
        + POS_TERMINAL_ID) * 10000000000
        + ORIG_RECEIPT_NR AS RETAIL_EVENT_SID,

        SRC.ORIG_RECEIPT_NR AS CASH_REGISTER_EVENT_NR,
        SRC.RECEIPT_TIMESTAMP_BEGIN AS EVENT_START_TMSP,
        SRC.RECEIPT_TIMESTAMP_END AS EVENT_END_TMSP,
        SRC.RECEIPT_BUSINESS_DATE AS BUS_DT,
        NULL AS CASH_REGISTER_TYPE_CD,
        NULL AS CASH_REGISTER_USG_TYPE_CD,
        -1 AS CASHIER_NR,
        -1 AS AUTH_BY_NR,
        SRC.LIDLPLUS_IDENT_TYPE_CD AS CUST_IDENT_TYPE_CD,
        CASE WHEN Substring(SRC.RECEIPT_TRANSACTIONTYPE_ID, 2, 1) = '5'
                         THEN 'R' /*RETURN ... 150, 151, 250, 251, 350, 351*/
                         ELSE 'S' /*SALES ... 100, 101, 200, 201, 300, 301*/
        END RETAIL_EVENT_TYPE_CD,
        CAST(SRC.RECEIPT_TRANSACTIONTYPE_ID as NUMBER) AS RETAIL_EVENT_SCENARIO_ID,
        CASE WHEN SRC.OFFLINE_FG = '1'
            THEN TRUE
            ELSE FALSE
        END OFFLINE_FG,
        CASE WHEN Substring(SRC.RECEIPT_TRANSACTIONTYPE_ID, 1, 1) = '2'
                         THEN TRUE /*200, 201, 250, 251*/
                         ELSE FALSE
        END CANCEL_FG,
        CASE WHEN Substring(SRC.RECEIPT_TRANSACTIONTYPE_ID, 1, 1) = '3'
                         THEN TRUE /*300, 301, 350, 351*/
                         ELSE FALSE
        END SUSPEND_FG,
        CASE WHEN SRC.TRAINING_FG = '1'
            THEN TRUE
            ELSE FALSE
        END TRAINING_FG,
        SRC.VAL_RETAIL AS TXN_GROSS_VAL,
        SRC.VAL_RETAIL_NET AS TXN_NET_VAL,
        SRC.VAL_RETAIL - SRC.VAL_RETAIL_NET AS TXN_VAT_VAL,
        CASE WHEN SRC.RECEIPT_TRANSACTIONTYPE_ID IN ('100', '150')
                         THEN TRUE
                         ELSE FALSE
        END TURNOVER_RELEVANT_FG,
        (SRC.DUR_SERVICE_TIME / 1000) AS SERVICE_TM_SEC_MEAS,
        (SRC.DUR_PAY_CHANGE_TIME / 1000) AS PAYM_TM_SEC_MEAS,
        NULL AS SCANNED_LINES_CNT,
        NULL AS KEYED_LINES_CNT,
        'STORE' AS STORE_KEY_TYPE_CD,
        'COUNTRY' AS COUNTRY_ORG_KEY_TYPE_CD,
        'CUST' AS CUST_KEY_TYPE_CD,
        'RET' AS CONT_RETAIL_EVENT_KEY_TYPE_CD,
        'REG' AS CASH_REGISTER_KEY_TYPE_CD,
        'RE' AS REAL_ESTATE_KEY_TYPE_CD,
        SRC.CONTEXT_COUNTRY,
        SRC.LIDLPLUS_CUSTOMER_CD,
        SRC.ORIG_RECEIPT_NR,
        SRC.ORIG_STORE_NR,
        SRC.POS_TERMINAL_ID,
        SRC.RECEIPT_BUSINESS_DATE,
        SRC.RESUMED_TRANS_DATE,
        SRC.RESUMED_TRANS_RECEIPT_NR,
        SRC.RESUMED_TRANS_STORE_NR,
        SRC.RESUMED_TRANS_TERMINAL_ID,
        'EJR' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        current_timestamp AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'EJR' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM ETL.VT_${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}_PROCESS SRC
;

-- Delete those records from source using the PK
DELETE FROM ETL.t_${SRC_INPUT_TABLE} SRC
WHERE EXISTS (SELECT 1 FROM ETL.VT_${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}_PROCESS PROCESS
              WHERE 
                SRC.CONTEXT_COUNTRY=PROCESS.CONTEXT_COUNTRY AND 
                SRC.ORIG_STORE_NR=PROCESS.ORIG_STORE_NR AND
                SRC.POS_TERMINAL_ID=PROCESS.POS_TERMINAL_ID AND 
                SRC.ORIG_RECEIPT_NR=PROCESS.ORIG_RECEIPT_NR AND
                SRC.RECEIPT_BUSINESS_DATE=PROCESS.RECEIPT_BUSINESS_DATE);
