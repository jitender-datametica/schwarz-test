INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        RETAIL_EVENT_SID,
        CASH_REGISTER_EVENT_NR,
        EVENT_START_TMSP,
        EVENT_END_TMSP,
        BUS_DT,
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        CASH_REGISTER_SID,
        CASH_REGISTER_TYPE_CD,
        CASH_REGISTER_USG_TYPE_CD,
        CASHIER_HASH,
        AUTH_BY_HASH,
        CUST_SID,
        CUST_IDENT_TYPE_CD,
        RETAIL_EVENT_TYPE_CD,
        RETAIL_EVENT_SCENARIO_ID,
        OFFLINE_FG,
        CANCEL_FG,
        SUSPEND_FG,
        SUSP_RETAIL_EVENT_SID,
        TRAINING_FG,
        TXN_GROSS_VAL,
        TXN_NET_VAL,
        TXN_VAT_VAL,
        CURR_CD,
        TURNOVER_RELEVANT_FG,
        SERVICE_TM_SEC_MEAS,
        PAYM_TM_SEC_MEAS,
        SCANNED_LINES_CNT,
        KEYED_LINES_CNT,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        SRC.RETAIL_EVENT_SID AS RETAIL_EVENT_SID,
        SRC.ORIG_RECEIPT_NR AS CASH_REGISTER_EVENT_NR,
        SRC.RECEIPT_TIMESTAMP_BEGIN AS EVENT_START_TMSP,
        SRC.RECEIPT_TIMESTAMP_END AS EVENT_END_TMSP,
        SRC.RECEIPT_BUSINESS_DATE AS BUS_DT,
        SRC.STORE_SID AS STORE_SID,
        COUNTRY_ORG_SID AS COUNTRY_ORG_SID,
        COUNTRY_ORG_CD AS COUNTRY_ORG_CD,
        REAL_ESTATE_SID AS REAL_ESTATE_SID, 
        CASH_REGISTER_SID AS CASH_REGISTER_SID,
        POS_TYPE AS CASH_REGISTER_TYPE_CD,
        NULL AS CASH_REGISTER_USG_TYPE_CD,
        checker_hash AS cashier_hash,
        receipt_authority_hash AS auth_by_hash,
        SRC.CUST_SID AS CUST_SID,
        SRC.LIDLPLUS_IDENT_TYPE_CD AS CUST_IDENT_TYPE_CD,
        CASE WHEN Substring(SRC.RECEIPT_TRANSACTIONTYPE_ID, 2, 1) = '5'
                         THEN 'R' /*RETURN ... 150, 151, 250, 251, 350, 351*/
                         ELSE 'S' /*SALES ... 100, 101, 200, 201, 300, 301*/
        END RETAIL_EVENT_TYPE_CD,
        CAST(SRC.RECEIPT_TRANSACTIONTYPE_ID as NUMBER) AS RETAIL_EVENT_SCENARIO_ID,
        CASE WHEN SRC.OFFLINE_FG = '1'
            THEN TRUE
            ELSE FALSE
        END OFFLINE_FG,
        CASE WHEN Substring(SRC.RECEIPT_TRANSACTIONTYPE_ID, 1, 1) = '2'
                         THEN TRUE /*200, 201, 250, 251*/
                         ELSE FALSE
        END CANCEL_FG,
        CASE WHEN Substring(SRC.RECEIPT_TRANSACTIONTYPE_ID, 1, 1) = '3'
                         THEN TRUE /*300, 301, 350, 351*/
                         ELSE FALSE
        END SUSPEND_FG,
        CASE WHEN RESUMED_TRANS_STORE_NR || RESUMED_TRANS_TERMINAL_ID ||
                  RESUMED_TRANS_RECEIPT_NR || RESUMED_TRANS_DATE IS NOT NULL 
             THEN 
                 ((((CAST(TO_CHAR(RESUMED_TRANS_DATE, 'YYYYMMDD') AS NUMBER) * 100
                       + ASCII(SUBSTRING(CONTEXT_COUNTRY, 1, 1))) * 100
                       + ASCII(SUBSTRING(CONTEXT_COUNTRY, 2, 1))) * 100000000
                       + RESUMED_TRANS_STORE_NR) * 10000
                       + RESUMED_TRANS_TERMINAL_ID) * 10000000000
                       + RESUMED_TRANS_RECEIPT_NR
             ELSE NULL 
        END AS SUSP_RETAIL_EVENT_SID,
        CASE WHEN SRC.TRAINING_FG = '1'
            THEN TRUE
            ELSE FALSE
        END TRAINING_FG,
        SRC.VAL_RETAIL AS TXN_GROSS_VAL,
        SRC.VAL_RETAIL_NET AS TXN_NET_VAL,
        SRC.VAL_RETAIL - SRC.VAL_RETAIL_NET AS TXN_VAT_VAL,
        SRC.CURR_CD AS CURR_CD, 
        CASE WHEN SRC.RECEIPT_TRANSACTIONTYPE_ID IN ('100', '150')
                         THEN TRUE
                         ELSE FALSE
        END TURNOVER_RELEVANT_FG,
        (SRC.DUR_SERVICE_TIME / 1000) AS SERVICE_TM_SEC_MEAS,
        (SRC.DUR_PAY_CHANGE_TIME / 1000) AS PAYM_TM_SEC_MEAS,
        SRC.ORIG_CNT_SCANPOS AS SCANNED_LINES_CNT,
        SRC.ORIG_CNT_DIRPOS AS KEYED_LINES_CNT,
        'EJR' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        'T_${SRC_INPUT_TABLE}' AS FILENAME,
        'EJR' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM ETL.T_${SRC_INPUT_TABLE} SRC
WHERE RECEIPT_TRANSACTIONTYPE_ID BETWEEN '100' AND '399'
QUALIFY ROW_NUMBER() OVER (
PARTITION BY
        CONTEXT_COUNTRY
      , ORIG_STORE_NR
      , POS_TERMINAL_ID
      , ORIG_RECEIPT_NR
      , RECEIPT_BUSINESS_DATE
ORDER BY
        RECEIPT_TIMESTAMP_END DESC
      , POSNR
) = 1
;
