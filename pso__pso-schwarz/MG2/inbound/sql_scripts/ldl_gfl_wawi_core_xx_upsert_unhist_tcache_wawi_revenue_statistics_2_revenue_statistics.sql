INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        STAT_DT,
        BUS_DT,
        CURR_STAT_FG,
        CORRECTION_SEQ,
        RECEIPT_NR,
        RECEIPT_LINE_NR,
        STAT_SRC_CD,
        REVENUE_STAT_TYPE_ID,
        RECEIPT_CNT,
        TURNOVER_NET_VAL,
        TURNOVER_GROSS_VAL,
        CURR_CD,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        SRC.STORE_SID,
        SRC.COUNTRY_ORG_SID,
        ORG.COUNTRY_ORG_CD,
        SRC.REAL_ESTATE_SID,
        SRC.STAT_DT,
        SRC.BUS_DT,
        SRC.CURR_STAT_FG,
        SRC.CORRECTION_SEQ,
        SRC.RECEIPT_NR,
        SRC.RECEIPT_LINE_NR,
        SRC.STAT_SRC_CD,
        SRC.REVENUE_STAT_TYPE_ID,
        SRC.RECEIPT_CNT,
        SRC.TURNOVER_NET_VAL,
        SRC.TURNOVER_GROSS_VAL,
        ORG.CURR_CD,
        'WAWI_WH' AS SOURCE_SYSTEM,
        SRC.BUS_DT AS EXTRACTION_DT,
        CURRENT_TIMESTAMP() AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'WAWI_WH' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM ${TEMP_DB}.t_${SRC_INPUT_TABLE}  SRC   
LEFT OUTER JOIN ${TARGET_DB}.T_INTERNAL_ORGANIZATION ORG
ON  SRC.COUNTRY_ORG_SID = ORG.INT_ORG_SID
AND SRC.BUS_DT BETWEEN ORG.DWH_VALID_FROM_TMSP AND ORG.DWH_VALID_TO_TMSP
;
