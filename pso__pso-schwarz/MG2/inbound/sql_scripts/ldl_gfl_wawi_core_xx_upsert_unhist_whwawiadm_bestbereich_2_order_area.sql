INSERT INTO ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
    ORDER_AREA_NR,
    INT_ORG_KEY_TYPE_CD,
    INT_ORG_NK,
    LANG_CD,
    ORDER_AREA_DESCR,
    SOURCE_SYSTEM,
    EXTRACTION_DT,
    DWH_MAPPING_TMSP,
    TF_ERROR_FG,
    DELETED_FG,
    RECORD_ID,
    FILENAME,
    DWH_NODE_CD,
    DWH_LOAD_ID
)
SELECT
    BESTBEREICHNR AS ORDER_AREA_NR,
    'COUNTRY' AS INT_ORG_KEY_TYPE_CD,
    CASE WHEN wawi_instanz_kzl='CS' THEN 'ES' ELSE LEFT(wawi_instanz_kzl,2) END AS INT_ORG_NK,
    'DE' AS LANG_CD,
    BESTBEREICHBEZ AS ORDER_AREA_DESCR,
    'WAWI_HQ' AS SOURCE_SYSTEM,
    CURRENT_DATE AS EXTRACTION_DT,
    CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
    0 AS TF_ERROR_FG,
    0 AS DELETED_FG,
    0 AS RECORD_ID,
    't_${SRC_INPUT_TABLE}' AS FILENAME,
    'WAWI_HQ' AS DWH_NODE_CD,
    '${LOAD_ID}' as DWH_LOAD_ID 
FROM  ${LDL_WAWI_COMMON_SNFLK_CL_DB_NAME}.${SRC_INPUT_TABLE} SRC
WHERE delete_fg IS NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY  INT_ORG_NK,    BESTBEREICHNR  ORDER BY SRC.EXTRACTION_TMSP DESC) = 1 
;
