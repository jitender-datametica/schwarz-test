create or replace view LDL_DATA_PRODUCTION.FE_MSTR_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_ORDER_BY_SALES_COMPANY_ACT_YEAR(
	SALES_COMPANY_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE INTERNAL ORGANIZATION.',
	REVISION_FG_CNT COMMENT 'NUMBER OF AUDITING HAPPENED FOR THE SALES COMPANY',
	ACTIVE_ANALYSIS_FG COMMENT 'CURRENTLY REQUIRED OR NOT',
	ORDER_FREQUENCY_PER_YEAR COMMENT 'MAXIMUM ORDER ALLOWED PER YEAR'
) as  
SELECT 
	ORG.INT_ORG_SID AS SALES_COMPANY_SID, 
	SUM(DECODE(ORD_PARAM.INT_ORG_SID,ORG.INT_ORG_SID,1,0)) AS REVISION_FG_CNT, 
	MAX(DECODE(ORD_PARAM.ORDER_PARAMETER_STATUS_CD,'RV',1,0)) AS ACTIVE_ANALYSIS_FG,
    MAX(MAX_ORDER.PARAM_COUNTRY_VAL_QTY) AS ORDER_FREQUENCY_PER_YEAR
FROM CORE_DIM.T_DIM_INTERNAL_ORGANIZATION ORG
LEFT JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_ORDER ORD_PARAM
ON  ORG.INT_ORG_SID = ORD_PARAM.INT_ORG_SID
AND YEAR(ORD_PARAM.AUDIT_TMSP)= YEAR(CURRENT_DATE()) 
AND ORD_PARAM.ORDER_PARAMETER_STATUS_CD IN ('RV','END')
LEFT JOIN CORE_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_PARAMETER_CURRENT_VALUE MAX_ORDER
ON MAX_ORDER.COUNTRY_ORG_CD = ORG.COUNTRY_ORG_CD
AND MAX_ORDER.PARAM_ID = 133
WHERE ORG.INT_ORG_TYPE_CD = 'COMPANY'
AND ORG.DWH_VALID_FG
AND ORG.IS_SALES_COMPANY_FG
GROUP BY 
ORG.INT_ORG_SID
HAVING REVISION_FG_CNT < NVL(ORDER_FREQUENCY_PER_YEAR,999);