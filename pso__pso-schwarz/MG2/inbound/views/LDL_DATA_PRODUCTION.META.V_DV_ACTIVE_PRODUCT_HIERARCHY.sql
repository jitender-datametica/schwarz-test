create or replace view LDL_DATA_PRODUCTION.META.V_DV_ACTIVE_PRODUCT_HIERARCHY(
	PROD_SID,
	PROD_DWH_VALID_FROM_TMSP,
	PROD_DWH_VALID_TO_TMSP,
	PROD_NR,
	PROD_NAME,
	PROD_DESCR,
	PROD_CREATION_DT,
	PROD_TYPE_CD,
	PROD_TYPE_DESCR,
	ITEM_TYPE_CD,
	ITEM_TYPE_DESCR,
	ITEM_FAM_SID,
	FAM_DWH_VALID_FROM_TMSP,
	FAM_DWH_VALID_TO_TMSP,
	ITEM_FAM_NR,
	ITEM_FAM_NAME,
	SUB_ITEM_GRP_SID,
	SIG_DWH_VALID_FROM_TMSP,
	SIG_DWH_VALID_TO_TMSP,
	SUB_ITEM_GRP_NR,
	SUB_ITEM_GRP_NAME,
	INT_ITEM_GRP_SID,
	IIG_DWH_VALID_FROM_TMSP,
	IIG_DWH_VALID_TO_TMSP,
	INT_ITEM_GRP_NR,
	INT_ITEM_GRP_NAME,
	FAILED_ITEM_FAMILY_CONSISTENT,
	FAILED_SUB_ITEM_GROUP_CONSISTENT,
	FAILED_INT_ITEM_GROUP_CONSISTENT,
	TOTAL
) COMMENT='Active products from core_dim.t_dim_product and related hierarchies (item family, sub item group, international item group)\ninput datasets:\ncore_dim.t_dim_product\ncore_dim.t_dim_item_family\ncore_dim.t_dim_sub_item_group\ncore_dim.t_dim_international_item_group'
 as select prod.prod_sid, prod.dwh_valid_from_tmsp as prod_dwh_valid_from_tmsp, prod.dwh_valid_to_tmsp as prod_dwh_valid_to_tmsp, prod.prod_nr, prod.prod_name, prod.prod_descr, prod.prod_creation_dt, prod.prod_type_cd, prod.prod_type_descr, prod.item_type_cd, prod.item_type_descr, fam.item_fam_sid, fam.dwh_valid_from_tmsp as fam_dwh_valid_from_tmsp, fam.dwh_valid_to_tmsp as fam_dwh_valid_to_tmsp, fam.item_fam_nr, fam.item_fam_name, sig.sub_item_grp_sid, sig.dwh_valid_from_tmsp as sig_dwh_valid_from_tmsp, sig.dwh_valid_to_tmsp as sig_dwh_valid_to_tmsp, sig.sub_item_grp_nr, sig.sub_item_grp_name, iig.int_item_grp_sid, iig.dwh_valid_from_tmsp as iig_dwh_valid_from_tmsp, iig.dwh_valid_to_tmsp as iig_dwh_valid_to_tmsp, iig.int_item_grp_nr, iig.int_item_grp_name, CASE WHEN fam.item_fam_sid = -1 OR fam.item_fam_sid is null THEN 1 ELSE 0 END AS FAILED_ITEM_FAMILY_CONSISTENT, CASE WHEN sig.sub_item_grp_sid = -1 OR sig.sub_item_grp_sid is null THEN 1 ELSE 0 END AS FAILED_SUB_ITEM_GROUP_CONSISTENT, CASE WHEN iig.int_item_grp_sid = -1 OR iig.int_item_grp_sid is null THEN 1 ELSE 0 END AS FAILED_INT_ITEM_GROUP_CONSISTENT, 1 as TOTAL from core_dim.t_dim_product prod left join core_dim.t_dim_item_family fam on prod.item_fam_sid = fam.item_fam_sid and fam.dwh_valid_fg = true left join core_dim.t_dim_sub_item_group sig on fam.sub_item_grp_sid = sig.sub_item_grp_sid and sig.dwh_valid_fg = true left join core_dim.t_dim_international_item_group iig on sig.int_item_grp_sid = iig.int_item_grp_sid and iig.dwh_valid_fg = true where prod.prod_sid <> -1 and prod.dwh_valid_fg = true;