	L10_IDP_ROLE_FULL_NAME,
	L10_WORKFORCE_ID,
	L10_CONTAINER_PURPOSE_TYPE_NAME,
	ROLE_NAME_SEPARATOR
) as 
WITH cte_pre_select_level AS
(
    SELECT
         cont_role.ORG_UNIT_LEVEL_NAME
        ,cont_role.RESSORT_NAME
        ,cont_role.BUSINESS_ROLE_NAME
        ,cont.IDP_CONTAINER_TYPE_CD
        ,cont.CONTAINER_NAME
        ,cont.CONTAINER_NAME_SEPARATOR
        ,cont_role.TECHNICAL_ROLE_GROUP_TYPE_CD
        ,cont_role.TECHNICAL_ROLE_TYPE_CD
        ,cont_role.TECHNICAL_ROLE_NAME
        ,cont_role.ROLE_NAME_SEPARATOR
        ,idp_workf_role.WORKFORCE_ID
        ,CONCAT(
                cont.CONTAINER_NAME
                ,cont.CONTAINER_NAME_SEPARATOR      
                ,cont_role.TECHNICAL_ROLE_NAME
        ) AS IDP_ROLE_FULL_NAME
        ,cont.CONTAINER_PURPOSE_TYPE_NAME
    FROM            META.T_SEC_CONF_COMPONENTS_CONTAINER_ROLE cont_role
    LEFT OUTER JOIN META.T_SEC_CONF_CONTAINER cont
                ON  cont.TECHNICAL_ROLE_TYPE_CD = cont_role.TECHNICAL_ROLE_TYPE_CD
    LEFT OUTER JOIN META.T_SEC_CONF_IDP_ROLE_WORKFORCEID idp_workf_role
            ON  idp_workf_role.IDP_FULL_ROLE_NAME = CONCAT(cont.CONTAINER_NAME, cont.CONTAINER_NAME_SEPARATOR, cont_role.TECHNICAL_ROLE_NAME)
)
,cte_pre_join_level AS
(
    SELECT 
        /* L20 Role Attributes */ 
        cont.ORG_UNIT_LEVEL_NAME
        ,cont.RESSORT_NAME
        ,cont.BUSINESS_ROLE_NAME
        ,CONCAT(cont.ORG_UNIT_LEVEL_NAME, ' - ', cont.RESSORT_NAME, ' - ', cont.BUSINESS_ROLE_NAME) AS FULL_DEPARTMENT_NAME
        ,cont.IDP_CONTAINER_TYPE_CD  AS L20_IDP_CONTAINER_TYPE_CD
        ,cont.CONTAINER_NAME         AS L20_CONTAINER_NAME
        ,cont.TECHNICAL_ROLE_GROUP_TYPE_CD AS L20_TECHNICAL_ROLE_GROUP_TYPE_CD
        ,cont.TECHNICAL_ROLE_TYPE_CD AS L20_TECHNICAL_ROLE_TYPE_CD
        ,cont.TECHNICAL_ROLE_NAME    AS L20_TECHNICAL_ROLE_NAME
        ,cont.IDP_ROLE_FULL_NAME     AS L20_IDP_ROLE_FULL_NAME
        ,cont.WORKFORCE_ID          AS L20_WORKFORCE_ID
        ,cont.CONTAINER_PURPOSE_TYPE_NAME AS L20_CONTAINER_PURPOSE_TYPE_NAME
        ,cont.CONTAINER_NAME_SEPARATOR
        /* L10 Role Attributes */
        ,cont_role.IDP_CONTAINER_TYPE_CD  AS L10_IDP_CONTAINER_TYPE_CD
        ,cont_role.TECHNICAL_ROLE_GROUP_TYPE_CD AS L10_TECHNICAL_ROLE_GROUP_TYPE_CD
        ,cont_role.TECHNICAL_ROLE_TYPE_CD AS L10_TECHNICAL_ROLE_TYPE_CD
        ,cont_role.TECHNICAL_ROLE_NAME    AS L10_TECHNICAL_ROLE_NAME
        ,cont_role.IDP_ROLE_FULL_NAME     AS L10_IDP_ROLE_FULL_NAME
        ,cont_role.WORKFORCE_ID          AS L10_WORKFORCE_ID
        ,cont_role.CONTAINER_PURPOSE_TYPE_NAME AS L10_CONTAINER_PURPOSE_TYPE_NAME
        ,cont_role.ROLE_NAME_SEPARATOR 
    FROM            (    /* L10 Roles Filter */
                        SELECT * 
                        FROM cte_pre_select_level 
                    ) cont_role
    LEFT OUTER JOIN (   /* L20 Container Roles Filter */
                        SELECT * 
                        FROM cte_pre_select_level 
                        WHERE TECHNICAL_ROLE_TYPE_CD IN ('container data', 'container func')
                    ) cont
                ON  cont.ORG_UNIT_LEVEL_NAME = cont_role.ORG_UNIT_LEVEL_NAME
                AND (cont.RESSORT_NAME = cont_role.RESSORT_NAME OR cont_role.RESSORT_NAME = '*')    -- '*' including passthrough roles
                AND (cont.BUSINESS_ROLE_NAME = cont_role.BUSINESS_ROLE_NAME OR cont_role.BUSINESS_ROLE_NAME = '*')  -- '*' including passthrough roles
                AND cont.TECHNICAL_ROLE_GROUP_TYPE_CD = cont_role.TECHNICAL_ROLE_GROUP_TYPE_CD


)

/* func authentification, func acl */
SELECT  
    /* L20 Role Attributes */ 
     ORG_UNIT_LEVEL_NAME
    ,RESSORT_NAME
    ,BUSINESS_ROLE_NAME
    ,FULL_DEPARTMENT_NAME
    ,L20_IDP_CONTAINER_TYPE_CD
    ,L20_CONTAINER_NAME
    ,L20_TECHNICAL_ROLE_GROUP_TYPE_CD
    ,L20_TECHNICAL_ROLE_TYPE_CD
    ,L20_TECHNICAL_ROLE_NAME
    ,L20_IDP_ROLE_FULL_NAME
    ,L20_WORKFORCE_ID
    ,L20_CONTAINER_PURPOSE_TYPE_NAME
    ,CONTAINER_NAME_SEPARATOR
    /* L10 Role Attributes */
    ,L10_IDP_CONTAINER_TYPE_CD
    ,L10_TECHNICAL_ROLE_GROUP_TYPE_CD
    ,L10_TECHNICAL_ROLE_TYPE_CD
    ,L10_TECHNICAL_ROLE_NAME
    ,L10_IDP_ROLE_FULL_NAME
    ,L10_WORKFORCE_ID
    ,L10_CONTAINER_PURPOSE_TYPE_NAME
    ,ROLE_NAME_SEPARATOR
FROM cte_pre_join_level
WHERE L10_TECHNICAL_ROLE_TYPE_CD IN ('func authentification', 'func acl')


