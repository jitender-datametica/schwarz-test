create or replace view LDL_DATA_PRODUCTION.META.V_SEC_CONF_CONTAINER_ROLE_BUNDLING(
	ORG_UNIT_LEVEL_NAME,
	RESSORT_NAME,
	BUSINESS_ROLE_NAME,
	FULL_DEPARTMENT_NAME,
	L20_IDP_CONTAINER_TYPE_CD,
