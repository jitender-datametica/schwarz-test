create or replace view LDL_DATA_PRODUCTION.POLICIES.V_SEC_RAP_COUNTRY_ORG_CD__INT_ORG_SID(
	NAME,
	COUNTRY_ORG_CD,
	INT_ORG_SID
) COMMENT='Security view for the standard use case for a scenario where the COUNTRY_ORG_CD and the INT_ORG_SID columns need to be combined'
 as

    SELECT DISTINCT
         COUNTRY.ROLE_NAME::VARCHAR AS NAME
        ,HIERARCHY.COUNTRY_ORG_CD::VARCHAR AS COUNTRY_ORG_CD
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_CORE_ISO_COUNTRY_CD COUNTRY
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON HIERARCHY.ISO_COUNTRY_CD = COUNTRY.ISO_COUNTRY_CD
  
    UNION ALL

    SELECT DISTINCT
         COMPANY.ROLE_NAME::VARCHAR AS NAME
        ,HIERARCHY.COUNTRY_ORG_CD::VARCHAR AS COUNTRY_ORG_CD
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_CORE_SALES_COMPANY_NR COMPANY 
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON HIERARCHY.SALES_COMPANY_NR = COMPANY.SALES_COMPANY_NR

    UNION ALL

    SELECT DISTINCT 
         ACCTMGR.LOGIN_NAME_EMAIL::VARCHAR AS NAME
        ,HIERARCHY.COUNTRY_ORG_CD::VARCHAR AS COUNTRY_ORG_CD
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_ACCOUNTMANAGER ACCTMGR
    LEFT OUTER JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON ACCTMGR.ACCT_MGR_DISTRICT_NR = HIERARCHY.ACCT_MGR_DISTRICT_NR

    UNION ALL

    SELECT DISTINCT
         SLSMGR.LOGIN_NAME_EMAIL::VARCHAR AS NAME
        ,HIERARCHY.COUNTRY_ORG_CD::VARCHAR AS COUNTRY_VALUE
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_SALESMANAGER SLSMGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY 
        ON SLSMGR.SALES_MGR_DISTRICT_SID = HIERARCHY.SALES_MGR_DISTRICT_SID
    WHERE HIERARCHY.INT_ORG_TYPE_CD = 'STORE'
;