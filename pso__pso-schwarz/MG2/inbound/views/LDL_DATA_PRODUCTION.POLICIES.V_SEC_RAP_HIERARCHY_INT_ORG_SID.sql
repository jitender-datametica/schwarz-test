create or replace view LDL_DATA_PRODUCTION.POLICIES.V_SEC_RAP_HIERARCHY_INT_ORG_SID(
	NAME,
	INT_ORG_SID
) COMMENT='SECURITY VIEW FOR THE ORGANIZATIONAL HIERARCHY TABLE BASED ON THE INT_ORG_SID COLUMN'
 as
    SELECT DISTINCT 
         ROLE_NAME AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_CORE_ISO_COUNTRY_CD COUNTRY
    LEFT JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON COUNTRY.ISO_COUNTRY_CD = HIERARCHY.ISO_COUNTRY_CD
    
    UNION ALL

    SELECT DISTINCT
         ROLE_NAME AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_CORE_SALES_COMPANY_NR POS
    LEFT JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON POS.SALES_COMPANY_NR = HIERARCHY.SALES_COMPANY_NR
   
    UNION ALL
    
    SELECT DISTINCT 
         LOGIN_NAME_EMAIL AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_ACCOUNTMANAGER ACCTMNGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON ACCTMNGR.ACCT_MGR_DISTRICT_SID = HIERARCHY.ACCT_MGR_DISTRICT_SID
   
    UNION ALL
    
    SELECT 
         LOGIN_NAME_EMAIL AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_SALESMANAGER SLSMNGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY HIERARCHY ON SLSMNGR.SALES_MGR_DISTRICT_SID = HIERARCHY.SALES_MGR_DISTRICT_SID
    ;