
TRUNCATE TABLE ldl_data_production_${target_db}.${tgt_target_table};

INSERT INTO ldl_data_production_${temp_db}.${src2tgt_temp_table1}_${src_context_area}
(
        cash_register_event_nr,
        event_start_tmsp,
        event_end_tmsp,
        bus_dt,
        cash_register_type_cd,
        cash_register_usg_type_cd,
        cashier_nr,
        auth_by_nr,
        cust_ident_type_cd,
        retail_event_type_cd,
        retail_event_scenario_id,
        offline_fg,
        cancel_fg,
        suspend_fg,
        training_fg,
        txn_gross_val,
        txn_net_val,
        txn_vat_val,
        turnover_relevant_fg,
        service_tm_sec_meas,
        paym_tm_sec_meas,
        scanned_lines_cnt,
        keyed_lines_cnt,
        retail_event_key_type_cd,
        store_key_type_cd,
        country_org_key_type_cd,
        cust_key_type_cd,
        cont_retail_event_key_type_cd,
        cash_register_key_type_cd,
        cash_register_natural_key,
        real_estate_key_type_cd,
        context_country,
        lidlplus_customer_cd,
        orig_receipt_nr,
        orig_store_nr,
        pos_terminal_id,
        receipt_business_date,
        resumed_trans_date,
        resumed_trans_receipt_nr,
        resumed_trans_store_nr,
        resumed_trans_terminal_id,
        source_system,
        extraction_dt,
        dwh_mapping_tmsp,
        tf_error_fg,
        deleted_fg,
        record_id,
        filename,
        dwh_node_cd,
        dwh_load_id
)
SELECT
    dedup.cash_register_event_nr,
    dedup.event_start_tmsp,
    dedup.event_end_tmsp,
    dedup.bus_dt,
    dedup.cash_register_type_cd,
    dedup.cash_register_usg_type_cd,
    dedup.cashier_nr,
    dedup.auth_by_nr,
    dedup.cust_ident_type_cd,
    dedup.retail_event_type_cd,
    dedup.retail_event_scenario_id,
    dedup.offline_fg,
    dedup.cancel_fg,
    dedup.suspend_fg,
    dedup.training_fg,
    dedup.txn_gross_val,
    dedup.txn_net_val,
    dedup.txn_vat_val,
    dedup.turnover_relevant_fg,
    dedup.service_tm_sec_meas,
    dedup.paym_tm_sec_meas,
    dedup.scanned_lines_cnt,
    dedup.keyed_lines_cnt,
    dedup.retail_event_key_type_cd,
    dedup.store_key_type_cd,
    dedup.country_org_key_type_cd,
    dedup.cust_key_type_cd,
    dedup.cont_retail_event_key_type_cd,
    dedup.cash_register_key_type_cd,
    dedup.cash_register_natural_key,
    dedup.real_estate_key_type_cd,
    dedup.context_country,
    dedup.lidlplus_customer_cd,
    dedup.orig_receipt_nr,
    dedup.orig_store_nr,
    dedup.pos_terminal_id,
    dedup.receipt_business_date,
    dedup.resumed_trans_date,
    dedup.resumed_trans_receipt_nr,
    dedup.resumed_trans_store_nr,
    dedup.resumed_trans_terminal_id,
    dedup.source_system,
    dedup.extraction_dt,
    dedup.dwh_mapping_tmsp,
    dedup.tf_error_fg,
    dedup.deleted_fg,
    dedup.record_id,
    dedup.filename,
    dedup.dwh_node_cd,
    dedup.dwh_load_id
FROM (
    SELECT
        src.orig_receipt_nr AS cash_register_event_nr,
        src.receipt_timestamp_begin AS event_start_tmsp,
        src.receipt_timestamp_end AS event_end_tmsp,
        src.dwh_mapping_dt AS bus_dt,
        NULL AS cash_register_type_cd,
        NULL AS cash_register_usg_type_cd,
        -1 AS cashier_nr,
        -1 AS auth_by_nr,
        src.lidlplus_ident_type_cd AS cust_ident_type_cd,
        CASE 
             WHEN SUBSTR(src.receipt_transactiontype_id, 2, 1) = '5'
             THEN 'R'       /*RETURN ... 150, 151, 250, 251, 350, 351*/
             ELSE 'S'       /*SALES ... 100, 101, 200, 201, 300, 301*/
        END AS retail_event_type_cd,
        SAFE_CAST(src.receipt_transactiontype_id AS INT64) AS retail_event_scenario_id,
        IF(src.offline_fg = '1', TRUE, FALSE) AS offline_fg,
        IF(SUBSTR(src.receipt_transactiontype_id, 1, 1) = '2', TRUE, FALSE) AS cancel_fg,       /*200, 201, 250, 251*/
        IF(SUBSTR(src.receipt_transactiontype_id, 1, 1) = '3', TRUE, FALSE) AS suspend_fg,      /*300, 301, 350, 351*/
        IF(src.training_fg = '1', TRUE, FALSE) AS training_fg,
        src.val_retail AS txn_gross_val,
        src.val_retail_net AS txn_net_val,
        (src.val_retail - src.val_retail_net) AS txn_vat_val,
        IF(src.receipt_transactiontype_id IN ('100', '150'), TRUE, FALSE) AS turnover_relevant_fg,
        src.dur_service_time AS service_tm_sec_meas,
        src.dur_pay_change_time AS paym_tm_sec_meas,
        src.orig_cnt_scanpos AS scanned_lines_cnt,
        src.orig_cnt_dirpos AS keyed_lines_cnt,
        'RET' AS retail_event_key_type_cd,
        'STORE' AS store_key_type_cd,
        'COUNTRY' AS country_org_key_type_cd,
        'CUST' AS cust_key_type_cd,
        'RET' AS cont_retail_event_key_type_cd,
        'DUMMY' AS cash_register_key_type_cd,
        'DUMMY|DUMMY' AS cash_register_natural_key,
        'RE' AS real_estate_key_type_cd,
        src.context_country,
        src.lidlplus_customer_cd,
        src.orig_receipt_nr,
        src.orig_store_nr,
        src.pos_terminal_id,
        src.receipt_business_date,
        src.resumed_trans_date,
        src.resumed_trans_receipt_nr,
        src.resumed_trans_store_nr,
        src.resumed_trans_terminal_id,
        'EJR' AS source_system,
        CURRENT_DATE() AS extraction_dt,
        CURRENT_TIMESTAMP() AS dwh_mapping_tmsp,
        0 AS tf_error_fg,
        0 AS deleted_fg,
        0 AS record_id,
        't_${SRC_INPUT_TABLE}' AS filename,
        'EJR' AS dwh_node_cd,
        '${LOAD_ID}' AS dwh_load_id,
        ROW_NUMBER() OVER (
            PARTITION BY
                src.context_country,
                src.orig_store_nr,
                src.pos_terminal_id,
                src.orig_receipt_nr,
                src.receipt_business_date
            ORDER BY
                src.receipt_timestamp_end DESC,
                src.posnr
        ) AS rn
    FROM ldl_data_production_etl.t_${src_input_table} src
    WHERE src.receipt_transactiontype_id BETWEEN '100' AND '399'
) AS dedup
WHERE dedup.rn = 1
;
