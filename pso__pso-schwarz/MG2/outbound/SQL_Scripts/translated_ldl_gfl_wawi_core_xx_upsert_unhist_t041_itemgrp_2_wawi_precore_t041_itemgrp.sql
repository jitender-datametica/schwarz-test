TRUNCATE TABLE LDL_DATA_PRODUCTION.PO_PREFIX_TARGET_DB_PO_SUFFIX.PO_PREFIX_TGT_TARGET_TABLE_PO_SUFFIX;
INSERT INTO LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC2TGT_TEMP_TABLE1_PO_SUFFIX_PO_PREFIX_SRC_CONTEXT_AREA_PO_SUFFIX (CTRCODE, EXTRACTION_TMSP, ITEMGRPNR, STAFFNR, PRODGRPNR, DESCSHORT, `DESC`, SORTINGTERM, DIFFRCV, MODUSER, MODDATE, GROUP_ID, TEMP_MIN, TEMP_MAX, RCV_COUNT, RCV_DAYS, MMO_DELIVERY_TIME, TRACEABILITY_LEVEL, SCN, SOURCE_SYSTEM, EXTRACTION_DT, DWH_MAPPING_TMSP, TF_ERROR_FG, DELETED_FG, RECORD_ID, FILENAME, DWH_NODE_CD, DWH_LOAD_ID)
  SELECT
      --
      left(SRC.CTRCODE, 2) AS CTRCODE,
      SRC.EXTRACTION_TMSP,
      SRC.C041_ITEMGRPNR,
      SRC.C041_STAFFNR,
      SRC.C041_PRODGRPNR,
      SRC.C041_DESCSHORT,
      SRC.C041_DESC,
      SRC.C041_SORTINGTERM,
      SRC.C041_DIFFRCV,
      SRC.C041_MODUSER,
      SRC.C041_MODDATE,
      SRC.C041_GROUP_ID,
      SRC.C041_TEMP_MIN,
      SRC.C041_TEMP_MAX,
      SRC.C041_RCV_COUNT,
      SRC.C041_RCV_DAYS,
      SRC.C041_MMO_DELIVERY_TIME,
      SRC.C041_TRACEABILITY_LEVEL,
      SRC.SCN,
      --
      'WAWI' AS SOURCE_SYSTEM,
      current_date() AS EXTRACTION_DT,
      current_timestamp() AS DWH_MAPPING_TMSP,
      NUMERIC '0' AS TF_ERROR_FG,
      NUMERIC '0' AS DELETED_FG,
      NUMERIC '0' AS RECORD_ID,
      'po_prefix_SRC_INPUT_TABLE_po_suffix' AS FILENAME,
      'WAWI' AS DWH_NODE_CD,
      'po_prefix_LOAD_ID_po_suffix' AS DWH_LOAD_ID
    FROM
      LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX AS SRC
      INNER JOIN LDL_DATA_PRODUCTION.ETL.WAWI_CONTROL_TABLE AS CTRL ON CTRL.SOURCE_TABLE_NAME = upper('LDL_DATA_PRODUCTION.po_prefix_TEMP_DB_po_suffix.po_prefix_SRC_INPUT_TABLE_po_suffix')
       AND CTRL.SOURCE_STATUS = 'A'
       AND SRC.EXTRACTION_TMSP BETWEEN CTRL.BEGIN_TMSP AND CTRL.END_TMSP
      INNER JOIN (
        SELECT
            A.CTRCODE,
            rank() OVER (ORDER BY if(CASE
              WHEN A.CTRCODE = 'DE' THEN NUMERIC '1'
              WHEN A.CTRCODE NOT IN(
                'BG', 'CY', 'GR'
              ) THEN NUMERIC '2'
              WHEN A.CTRCODE = 'GR' THEN NUMERIC '3'
              WHEN A.CTRCODE IN(
                'BG', 'CY'
              ) THEN NUMERIC '4'
            END IS NULL, 0, 1) DESC, CASE
              WHEN A.CTRCODE = 'DE' THEN NUMERIC '1'
              WHEN A.CTRCODE NOT IN(
                'BG', 'CY', 'GR'
              ) THEN NUMERIC '2'
              WHEN A.CTRCODE = 'GR' THEN NUMERIC '3'
              WHEN A.CTRCODE IN(
                'BG', 'CY'
              ) THEN NUMERIC '4'
            END, if(A.CTRCODE IS NULL, 0, 1) DESC, A.CTRCODE) AS EKS_RANK
          FROM
            (
              SELECT DISTINCT
                  PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX.CTRCODE
                FROM
                  LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX
            ) AS A
      ) AS CSRC ON SRC.CTRCODE = CSRC.CTRCODE
    QUALIFY CSRC.EKS_RANK = min(CSRC.EKS_RANK) OVER (PARTITION BY CTRCODE, SRC.C041_ITEMGRPNR, SRC.C041_PRODGRPNR)
     AND row_number() OVER (PARTITION BY CTRCODE, SRC.C041_ITEMGRPNR, SRC.C041_PRODGRPNR ORDER BY if(SRC.EXTRACTION_TMSP IS NULL, 0, 1), SRC.EXTRACTION_TMSP DESC) = NUMERIC '1'
;
