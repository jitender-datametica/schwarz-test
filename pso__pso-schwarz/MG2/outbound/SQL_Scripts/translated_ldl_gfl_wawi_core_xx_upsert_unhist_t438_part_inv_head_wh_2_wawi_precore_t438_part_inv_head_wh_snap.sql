INSERT INTO LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC2TGT_TEMP_TABLE1_PO_SUFFIX_PO_PREFIX_SRC_CONTEXT_AREA_PO_SUFFIX (CTRCODE, WH_NR, C438_INV_ID, C438_LIST_ID, C438_SIC_ID, C438_INVENTORYDATE, C438_STORENR, C438_STATUS, C438_INV_TYPE, C438_SENT, C438_DIFFVALUE, C438_TURNOVER, C438_RESULT, C438_COLOR, C438_PERIOD_COLOR, C438_STOCK_CALC_DATE, C438_MODUSER, C438_MODDATE, C438_PERIOD_DIFFVALUE, C438_PERIOD_TURNOVER, C438_PERIOD_RANGE_RED, C438_PERIOD_RANGE_YELLOW, C438_POSCOUNT, C438_WHNR, SCN, EXTRACTION_TMSP, SOURCE_SYSTEM, EXTRACTION_DT, DWH_MAPPING_TMSP, TF_ERROR_FG, DELETED_FG, RECORD_ID, FILENAME, DWH_NODE_CD, DWH_LOAD_ID)
  SELECT
      CASE
        WHEN CTRCODE = 'CS' THEN 'ES'
        WHEN CTRCODE = 'NIE' THEN 'NI'
        ELSE CTRCODE
      END AS CTRCODE_CONVERTED,
      WH_NR,
      C438_INV_ID,
      C438_LIST_ID,
      C438_SIC_ID,
      C438_INVENTORYDATE,
      C438_STORENR,
      C438_STATUS,
      C438_INV_TYPE,
      C438_SENT,
      C438_DIFFVALUE,
      C438_TURNOVER,
      C438_RESULT,
      C438_COLOR,
      C438_PERIOD_COLOR,
      C438_STOCK_CALC_DATE,
      C438_MODUSER,
      C438_MODDATE,
      C438_PERIOD_DIFFVALUE,
      C438_PERIOD_TURNOVER,
      C438_PERIOD_RANGE_RED,
      C438_PERIOD_RANGE_YELLOW,
      C438_POSCOUNT,
      C438_WHNR,
      SCN,
      EXTRACTION_TMSP,
      'WAWI' AS SOURCE_SYSTEM,
      current_date() AS EXTRACTION_DT,
      current_timestamp() AS DWH_MAPPING_TMSP,
      NUMERIC '0' AS TF_ERROR_FG,
      NUMERIC '0' AS DELETED_FG,
      NUMERIC '0' AS RECORD_ID,
      'po_prefix_SRC_INPUT_TABLE_po_suffix' AS FILENAME,
      'WAWI_WH' AS DWH_NODE_CD,
      'po_prefix_LOAD_ID_po_suffix' AS DWH_LOAD_ID
    FROM
      LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX AS SRC
      INNER JOIN LDL_DATA_PRODUCTION.ETL.WAWI_CONTROL_TABLE AS CTRL ON true
       AND CTRL.SOURCE_TABLE_NAME = upper('LDL_DATA_PRODUCTION.po_prefix_TEMP_DB_po_suffix.po_prefix_SRC_INPUT_TABLE_po_suffix')
       AND CTRL.SOURCE_STATUS = 'A'
       AND SRC.EXTRACTION_TMSP BETWEEN CTRL.BEGIN_TMSP AND CTRL.END_TMSP
    QUALIFY row_number() OVER (PARTITION BY CTRCODE_CONVERTED, WH_NR, C438_INV_ID ORDER BY if(SRC.EXTRACTION_TMSP IS NULL, 0, 1), SRC.EXTRACTION_TMSP DESC) = NUMERIC '1'
;
