store_to_be_built_ppy_cnt
OPTIONS(description='VALUE 1 IF THE STORE/BUIDLING WAS UNDER CONTRACT TWO YEARS AGO AND THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'),
cancel_term_store_cnt
