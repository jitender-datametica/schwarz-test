create or replace view IDQ_PRODUCTION.DWH.CHECK_RULE_BY_COUNTRY_SUMMARY(
	CHECK_RULE_BY_COUNTRY_SUMMARY_ID,
	CHECK_RULE_BY_COUNTRY_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	REF_RULE_ID,
	REF_FIELD_ID,
	REF_CRITICALITY_ID,
	REF_DIMENSION_ID,
	TEST_RESULT_AMOUNT,
	ERROR_AMOUNT,
	NO_ERROR_AMOUNT,
	SOLVED_ERROR_AMOUNT,
	NEW_ERROR_AMOUNT,
	FLIP_ERROR_AMOUNT,
	EARLIEST_DUE_DATE,
	REF_TIME_EARLIEST_DUE_DAY_ID,
	OVERDUE_AMOUNT,
	REF_STATUS_ID,
	CHECK_RULE_BY_COUNTRY_IS_CURRENT,
	NEWLY_SOLVED_ERROR_AMOUNT,
	EXCLUDE_FLAG
) as
SELECT ROW_NUMBER() OVER (ORDER BY REF_TIME_CALCULATION_DAY_ID) AS CHECK_RULE_BY_COUNTRY_SUMMARY_ID, *
FROM (
	SELECT CRCS.CALCULATION_TIME        AS CHECK_RULE_BY_COUNTRY_CALCULATION_TIME
		  ,CRCS.CALCULATION_DAY_ID        AS REF_TIME_CALCULATION_DAY_ID
		  ,CRCS.SOURCE_SYSTEM_ID          AS REF_SOURCE_SYSTEM_ID
		  ,CRCS.BRANCH_ID                 AS REF_BRANCH_ID
		  ,CRCS.COUNTRY_ID                AS REF_COUNTRY_ID
		  ,CRCS.SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
		  ,CRCS.TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
		  ,CRCS.RULE_ID                   AS REF_RULE_ID
		  ,RR.FIELD_ID                    AS REF_FIELD_ID
		  ,RR.CRITICALITY_ID              AS REF_CRITICALITY_ID
		  ,RR.DIMENSION_ID                AS REF_DIMENSION_ID
		  ,CRCS.TEST_RESULT_AMOUNT        AS TEST_RESULT_AMOUNT
		  ,CRCS.ERROR_AMOUNT              AS ERROR_AMOUNT
		  ,CRCS.NO_ERROR_AMOUNT           AS NO_ERROR_AMOUNT
		  ,CRCS.SOLVED_ERROR_AMOUNT       AS SOLVED_ERROR_AMOUNT
		  ,CRCS.NEW_ERROR_AMOUNT          AS NEW_ERROR_AMOUNT
		  ,CRCS.FLIP_ERROR_AMOUNT         AS FLIP_ERROR_AMOUNT
		  ,CRCS.EARLIEST_DUE_DATE         AS EARLIEST_DUE_DATE
		  ,CRCS.EARLIEST_DUE_DAY_ID       AS REF_TIME_EARLIEST_DUE_DAY_ID
		  ,CRCS.OVERDUE_AMOUNT            AS OVERDUE_AMOUNT
		  ,CRCS.STATUS_ID                 AS REF_STATUS_ID
		  ,1                                AS CHECK_RULE_BY_COUNTRY_IS_CURRENT
		  ,CRCS.NEWLY_SOLVED_ERROR_AMOUNT AS NEWLY_SOLVED_ERROR_AMOUNT
		  ,CASE 
			WHEN RE.EXCLUDE_FLAG IS NOT NULL THEN RE.EXCLUDE_FLAG 
		    ELSE     0				
			END EXCLUDE_FLAG
	FROM idq_results.CHECK_RULE_BY_SCOPE_CURRENT CRCS
	INNER JOIN idq_results.REF_TEST_OBJECT_TYPE_EXTENDED TOTE
		on TOTE.ID = CRCS.TEST_OBJECT_TYPE_ID
	INNER JOIN idq_results.REF_RULE RR
	  ON CRCS.RULE_ID = RR.ID
	LEFT JOIN idq_results.REF_EXCLUDE RE
	  ON TOTE.LEVEL_1_ID=RE.TEST_OBJECT_TYPE_ID and
	  --ON CRCS.TEST_OBJECT_TYPE_ID=RE.TEST_OBJECT_TYPE_ID and
	  CRCS.BRANCH_ID=RE.BRANCH_ID and 
	  CRCS.COUNTRY_ID=RE.COUNTRY_ID and 
	  CRCS.RULE_ID=RE.RULE_ID and 
	  CRCS.SOURCE_SYSTEM_ID=RE.SOURCE_SYSTEM_ID
	  and RE.SOURCE_SYSTEM_PRIMARY_KEY is null and RE.UNDONE_AT is null
	UNION ALL
	SELECT CRCS.CALCULATION_TIME        AS CHECK_RULE_BY_COUNTRY_CALCULATION_TIME
		  ,CRCS.CALCULATION_DAY_ID        AS REF_TIME_CALCULATION_DAY_ID
		  ,CRCS.SOURCE_SYSTEM_ID          AS REF_SOURCE_SYSTEM_ID
		  ,CRCS.BRANCH_ID                 AS REF_BRANCH_ID
		  ,CRCS.COUNTRY_ID                AS REF_COUNTRY_ID
		  ,CRCS.SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
		  ,CRCS.TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
		  ,CRCS.RULE_ID                   AS REF_RULE_ID
		  ,RR.FIELD_ID                    AS REF_FIELD_ID
		  ,RR.CRITICALITY_ID              AS REF_CRITICALITY_ID
		  ,RR.DIMENSION_ID                AS REF_DIMENSION_ID
		  ,CRCS.TEST_RESULT_AMOUNT        AS TEST_RESULT_AMOUNT
		  ,CRCS.ERROR_AMOUNT              AS ERROR_AMOUNT
		  ,CRCS.NO_ERROR_AMOUNT           AS NO_ERROR_AMOUNT
		  ,CRCS.SOLVED_ERROR_AMOUNT       AS SOLVED_ERROR_AMOUNT
		  ,CRCS.NEW_ERROR_AMOUNT          AS NEW_ERROR_AMOUNT
		  ,CRCS.FLIP_ERROR_AMOUNT         AS FLIP_ERROR_AMOUNT
		  ,CRCS.EARLIEST_DUE_DATE         AS EARLIEST_DUE_DATE
		  ,CRCS.EARLIEST_DUE_DAY_ID       AS REF_TIME_EARLIEST_DUE_DAY_ID
		  ,CRCS.OVERDUE_AMOUNT            AS OVERDUE_AMOUNT
		  ,CRCS.STATUS_ID                 AS REF_STATUS_ID
		  ,0                                AS CHECK_RULE_BY_COUNTRY_IS_CURRENT
		  ,CRCS.NEWLY_SOLVED_ERROR_AMOUNT AS NEWLY_SOLVED_ERROR_AMOUNT
		  ,CASE 
			WHEN RE.EXCLUDE_FLAG IS NOT NULL THEN RE.EXCLUDE_FLAG 
		    ELSE     0				
			END EXCLUDE_FLAG
	FROM idq_results.CHECK_RULE_BY_SCOPE_HISTORICAL CRCS
	INNER JOIN idq_results.REF_TEST_OBJECT_TYPE_EXTENDED TOTE
		on TOTE.ID = CRCS.TEST_OBJECT_TYPE_ID
	INNER JOIN idq_results.REF_RULE RR
	  ON CRCS.RULE_ID = RR.ID 
	LEFT JOIN idq_results.REF_EXCLUDE RE
	  ON TOTE.LEVEL_1_ID=RE.TEST_OBJECT_TYPE_ID and
	  --ON CRCS.TEST_OBJECT_TYPE_ID=RE.TEST_OBJECT_TYPE_ID and
	  CRCS.BRANCH_ID=RE.BRANCH_ID and 
	  CRCS.COUNTRY_ID=RE.COUNTRY_ID and 
	  CRCS.RULE_ID=RE.RULE_ID and 
	  CRCS.SOURCE_SYSTEM_ID=RE.SOURCE_SYSTEM_ID
	  and RE.SOURCE_SYSTEM_PRIMARY_KEY is null and RE.UNDONE_AT is null 
) COUNTRY_SUMMARY
;