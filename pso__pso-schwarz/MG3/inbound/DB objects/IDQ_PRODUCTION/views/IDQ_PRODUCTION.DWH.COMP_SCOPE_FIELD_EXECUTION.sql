create or replace view IDQ_PRODUCTION.DWH.COMP_SCOPE_FIELD_EXECUTION(
	COMP_SCOPE_EXECUTION_ID,
	FIELD_DEFINITION_ID,
	EXECUTION_DATE,
	EXECUTION_DAY_ID,
	MATCH_AMOUNT,
	EQUAL_AMOUNT,
	UNEQUAL_AMOUNT,
	LEADING_EMPTY,
	DEPENDENT_EMPTY,
	SCOPE_ID,
	COMP_SCOPE_FIELD_EXECUTION_IS_CURRENT,
	REF_COMP_DEFINITION_ID,
	LEADING_COMP_SCOPE_ID,
	DEPENDENT_COMP_SCOPE_ID,
	LEADING_REF_SOURCE_SYSTEM_TYPE_ID,
	LEADING_REF_SOURCE_SYSTEM_ID,
	LEADING_REF_COUNTRY_ID,
	LEADING_REF_BRANCH_ID,
	LEADING_REF_TEST_OBJECT_TYPE_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_ID,
	DEPENDENT_REF_COUNTRY_ID,
	DEPENDENT_REF_BRANCH_ID,
	DEPENDENT_REF_TEST_OBJECT_TYPE_ID,
	SYNC_SCORE,
	SYNC_SCORE_FAIL,
	SYNC_RATIO
) as

SELECT 
       a.COMP_SCOPE_EXECUTION_ID
      ,a.FIELD_COMP_DEFINITION_ID 				AS FIELD_DEFINITION_ID
      ,a.EXECUTION_DATE
      ,a.EXECUTION_DAY_ID
      ,a.MATCH_AMOUNT
      ,a.EQUAL_AMOUNT
      ,a.UNEQUAL_AMOUNT
      ,a.LEADING_EMPTY
      ,a.DEPENDENT_EMPTY
      ,a.SCOPE_ID
	  ,1                                	AS  COMP_SCOPE_FIELD_EXECUTION_IS_CURRENT
	    ,RCDS.COMP_DEFINITION_ID			AS REF_COMP_DEFINITION_ID,				
		--REMOVED RCDS.LEADING_COMP_SCOPE_ID		AS LEADING_SCOPE_ID,
		RCDS.LEADING_COMP_SCOPE_ID		AS LEADING_COMP_SCOPE_ID,		--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		--REMOVED RCDS.DEPENDENT_COMP_SCOPE_ID		AS DEPENDENT_SCOPE_ID,
		RCDS.DEPENDENT_COMP_SCOPE_ID		AS DEPENDENT_COMP_SCOPE_ID,	--new COLUMN because of name change -- renaming tbd with Sergey & KD
		RSL.SOURCE_SYSTEM_TYPE_ID			AS LEADING_REF_SOURCE_SYSTEM_TYPE_ID,		
		RSL.SOURCE_SYSTEM_ID				AS LEADING_REF_SOURCE_SYSTEM_ID,			
		RSL.COUNTRY_ID					AS LEADING_REF_COUNTRY_ID,				
		RSL.BRANCH_ID						AS LEADING_REF_BRANCH_ID,					
		RSL.TEST_OBJECT_TYPE_ID			AS LEADING_REF_TEST_OBJECT_TYPE_ID,		
		RSD.SOURCE_SYSTEM_TYPE_ID			AS DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,	
		RSD.SOURCE_SYSTEM_ID				AS DEPENDENT_REF_SOURCE_SYSTEM_ID,		
		RSD.COUNTRY_ID					AS DEPENDENT_REF_COUNTRY_ID,				
		RSD.BRANCH_ID						AS DEPENDENT_REF_BRANCH_ID,				
		RSD.TEST_OBJECT_TYPE_ID			AS DEPENDENT_REF_TEST_OBJECT_TYPE_ID	    

		,CASE when (1.0*a.equal_amount)/a.MATCH_AMOUNT > 0.5 then 1 else 0 end as sync_score        
		,CASE when (1.0*a.equal_amount)/a.MATCH_AMOUNT > 0.5 then 0 else 1 end as sync_score_fail 
		,(1.0*a.equal_amount)/a.MATCH_AMOUNT								   as sync_ratio        
  FROM SYSCOMP.COMP_SCOPE_FIELD_EXECUTION_CURRENT a

  join  SYSCOMP.COMP_SCOPE_EXECUTION_CURRENT CSE

  on cse.ID= a.COMP_SCOPE_EXECUTION_ID
	INNER JOIN idq_results.REF_COMP_DEFINITION_SCOPE RCDS
	   ON CSE.COMP_DEFINITION_SCOPE_ID = RCDS.ID
	INNER JOIN idq_results.REF_COMP_SCOPE RSL
	   ON RCDS.LEADING_COMP_SCOPE_ID = RSL.ID
	INNER JOIN idq_results.REF_COMP_SCOPE RSD
	   ON RCDS.DEPENDENT_COMP_SCOPE_ID = RSD.ID
	   
  UNION ALL

SELECT
       aa.COMP_SCOPE_EXECUTION_ID
      ,aa.FIELD_COMP_DEFINITION_ID		AS FIELD_DEFINITION_ID
      ,aa.EXECUTION_DATE
      ,aa.EXECUTION_DAY_ID
      ,aa.MATCH_AMOUNT
      ,aa.EQUAL_AMOUNT
      ,aa.UNEQUAL_AMOUNT
      ,aa.LEADING_EMPTY
      ,aa.DEPENDENT_EMPTY
      ,aa.SCOPE_ID
	  ,0									AS  COMP_SCOPE_FIELD_EXECUTION_IS_CURRENT

	  	,RCDS.COMP_DEFINITION_ID			AS REF_COMP_DEFINITION_ID,				
		--REMOVED RCDS.LEADING_COMP_SCOPE_ID		AS LEADING_SCOPE_ID,
		RCDS.LEADING_COMP_SCOPE_ID		AS LEADING_COMP_SCOPE_ID,			--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		--REMOVED RCDS.DEPENDENT_COMP_SCOPE_ID		AS DEPENDENT_SCOPE_ID, 
		RCDS.DEPENDENT_COMP_SCOPE_ID		AS DEPENDENT_COMP_SCOPE_ID,		--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		RSL.SOURCE_SYSTEM_TYPE_ID			AS LEADING_REF_SOURCE_SYSTEM_TYPE_ID,		
		RSL.SOURCE_SYSTEM_ID				AS LEADING_REF_SOURCE_SYSTEM_ID,			
		RSL.COUNTRY_ID					AS LEADING_REF_COUNTRY_ID,				
		RSL.BRANCH_ID						AS LEADING_REF_BRANCH_ID,					
		RSL.TEST_OBJECT_TYPE_ID			AS LEADING_REF_TEST_OBJECT_TYPE_ID,		
		RSD.SOURCE_SYSTEM_TYPE_ID			AS DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,	
		RSD.SOURCE_SYSTEM_ID				AS DEPENDENT_REF_SOURCE_SYSTEM_ID,		
		RSD.COUNTRY_ID					AS DEPENDENT_REF_COUNTRY_ID,				
		RSD.BRANCH_ID						AS DEPENDENT_REF_BRANCH_ID,				
		RSD.TEST_OBJECT_TYPE_ID			AS DEPENDENT_REF_TEST_OBJECT_TYPE_ID	    
		,CASE when (1.0*aa.equal_amount)/aa.MATCH_AMOUNT > 0.5 then 1 else 0 end as sync_score        
		,CASE when (1.0*aa.equal_amount)/aa.MATCH_AMOUNT > 0.5 then 0 else 1 end as sync_score_fail   																								   
		,(1.0*aa.equal_amount)/aa.MATCH_AMOUNT								     as sync_ratio        
  FROM SYSCOMP.COMP_SCOPE_FIELD_EXECUTION_HISTORICAL aa

    join  SYSCOMP.COMP_SCOPE_EXECUTION_HISTORICAL CSE

  on cse.ID= aa.COMP_SCOPE_EXECUTION_ID
	INNER JOIN idq_results.REF_COMP_DEFINITION_SCOPE RCDS
	   ON CSE.COMP_DEFINITION_SCOPE_ID = RCDS.ID
	INNER JOIN idq_results.REF_COMP_SCOPE RSL
	   ON RCDS.LEADING_COMP_SCOPE_ID = RSL.ID
	INNER JOIN idq_results.REF_COMP_SCOPE RSD
	   ON RCDS.DEPENDENT_COMP_SCOPE_ID = RSD.ID
;