create or replace view IDQ_PRODUCTION.DWH.REF_COMP_CRITICALITY(
	REF_CRITICALITY_ID,
	CRITICALITY_TECHNICAL_NAME,
	PENALTY,
	SLA_IN_DAYS,
	CRITICALITY_NAME,
	CRITICALITY_NAME_DE,
	CRITICALITY_NAME_EN
) as
SELECT ID                  AS REF_CRITICALITY_ID
      ,CRITICALITY		 AS CRITICALITY_TECHNICAL_NAME
      ,PENALTY			 AS PENALTY
      ,SLA_IN_DAYS		 AS SLA_IN_DAYS
      ,NAME_DE			 AS CRITICALITY_NAME
      ,NAME_DE			 AS CRITICALITY_NAME_DE
      ,NAME_EN			 AS CRITICALITY_NAME_EN
FROM idq_results.REF_CRITICALITY
;