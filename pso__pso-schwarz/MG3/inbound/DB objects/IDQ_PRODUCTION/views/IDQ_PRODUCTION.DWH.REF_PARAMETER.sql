create or replace view IDQ_PRODUCTION.DWH.REF_PARAMETER(
	REF_PARAMETER_ID,
	SCOPE,
	REF_BRANCH_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	PARAMETER_TECHNICAL_NAME,
	DEFAULT_VALUE,
	PARAMETER_DESCRIPTION,
	PARAMETER_DESCRIPTION_DE,
	PARAMETER_DESCRIPTION_EN
) as
SELECT ID                     AS REF_PARAMETER_ID
      ,SCOPE                  AS SCOPE
      ,BRANCH_ID              AS REF_BRANCH_ID
      ,SOURCE_SYSTEM_TYPE_ID  AS REF_SOURCE_SYSTEM_TYPE_ID
      ,NAME                   AS PARAMETER_TECHNICAL_NAME
      ,DEFAULT_VALUE          AS DEFAULT_VALUE
      ,DESCRIPTION_DE         AS PARAMETER_DESCRIPTION
      ,DESCRIPTION_DE         AS PARAMETER_DESCRIPTION_DE
      ,DESCRIPTION_EN         AS PARAMETER_DESCRIPTION_EN
FROM idq_results.REF_PARAMETER 
;