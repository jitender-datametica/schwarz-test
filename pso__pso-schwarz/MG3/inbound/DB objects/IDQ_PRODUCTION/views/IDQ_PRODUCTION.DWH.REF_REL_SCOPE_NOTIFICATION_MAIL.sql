create or replace view IDQ_PRODUCTION.DWH.REF_REL_SCOPE_NOTIFICATION_MAIL(
	REF_REL_SCOPE_NOTIFICATION_MAIL_ID,
	REF_SCOPE_ID,
	REF_NOTIFICATION_ID,
	EMAIL,
	FREQUENCY,
	INSERTED_AT,
	REF_SOURCE_SYSTEM_TYPE_ID
) as
SELECT 	rrsnm.ID 				AS REF_REL_SCOPE_NOTIFICATION_MAIL_ID
		,SCOPE_ID 		AS REF_SCOPE_ID
		,NOTIFICATION_ID	AS REF_NOTIFICATION_ID
		,EMAIL			AS EMAIL
		,FREQUENCY		AS FREQUENCY
		,INSERTED_AT		AS INSERTED_AT
        ,rs.SOURCE_SYSTEM_TYPE_ID AS REF_SOURCE_SYSTEM_TYPE_ID
		
FROM idq_results.REF_REL_SCOPE_NOTIFICATION_MAIL rrsnm
join idq_results.ref_scope rs on rs.id = rrsnm.scope_id;