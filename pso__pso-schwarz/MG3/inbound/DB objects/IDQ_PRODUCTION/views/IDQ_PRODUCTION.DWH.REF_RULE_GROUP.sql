create or replace view IDQ_PRODUCTION.DWH.REF_RULE_GROUP(
	REF_RULE_GROUP_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	RULE_GROUP_TECHNICAL_NAME,
	RULE_GROUP_NAME,
	RULE_GROUP_NAME_DE,
	RULE_GROUP_NAME_EN
) as
SELECT ID                      AS REF_RULE_GROUP_ID
      ,SOURCE_SYSTEM_TYPE_ID   AS REF_SOURCE_SYSTEM_TYPE_ID
      ,SHORT_NAME    		     AS RULE_GROUP_TECHNICAL_NAME
      ,NAME_DE  				 AS RULE_GROUP_NAME
      ,NAME_DE				 AS RULE_GROUP_NAME_DE
      ,NAME_ES				 AS RULE_GROUP_NAME_EN
FROM idq_results.REF_RULE_GROUP 
;