create or replace view IDQ_PRODUCTION.DWH.REF_TEST_OBJECT_TYPE(
	REF_TEST_OBJECT_TYPE_ID,
	TEST_OBJECT_TYPE_TECHNICAL_NAME,
	PARENT_ID,
	TEST_OBJECT_TYPE_NAME,
	TEST_OBJECT_TYPE_NAME_DE,
	TEST_OBJECT_TYPE_NAME_EN
) as
SELECT ID               AS REF_TEST_OBJECT_TYPE_ID
      ,TEST_OBJECT_TYPE AS TEST_OBJECT_TYPE_TECHNICAL_NAME
      ,PARENT_ID		  AS PARENT_ID
      ,NAME_DE		  AS TEST_OBJECT_TYPE_NAME
      ,NAME_DE		  AS TEST_OBJECT_TYPE_NAME_DE
      ,NAME_EN		  AS TEST_OBJECT_TYPE_NAME_EN
FROM idq_results.REF_TEST_OBJECT_TYPE
;