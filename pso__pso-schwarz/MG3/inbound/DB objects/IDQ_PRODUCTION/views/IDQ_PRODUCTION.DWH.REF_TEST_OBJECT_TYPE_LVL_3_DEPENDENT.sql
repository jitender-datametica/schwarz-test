create or replace view IDQ_PRODUCTION.DWH.REF_TEST_OBJECT_TYPE_LVL_3_DEPENDENT(
	DEPENDENT_REF_TEST_OBJECT_TYPE_LEVEL_3_ID,
	DEPENDENT_IS_DUMMY,
	DEPENDENT_TEST_OBJECT_TYPE,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_NAME,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_NAME_DE,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_NAME_EN,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_CHANGE_BY,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_LAST_CHANGE,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_FROM_DATE,
	DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_TO_DATE,
	DEPENDENT_REF_TEST_OBJECT_TYPE_LEVEL_2_ID
) as
	SELECT 
  		TOTE.ID                               				AS DEPENDENT_REF_TEST_OBJECT_TYPE_LEVEL_3_ID
        ,case  
			when TOTE.LEVEL_3_ID is null then 1 
			else 0 end 											AS DEPENDENT_IS_DUMMY
        ,TOTE.TEST_OBJECT_TYPE                 				AS DEPENDENT_TEST_OBJECT_TYPE
        ,TOTE.NAME_DE                             			AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_NAME
        ,TOTE.NAME_DE                            				AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_NAME_DE
        ,TOTE.NAME_EN                             			AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_NAME_EN
        ,TOTE.CHANGE_BY                         				AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_CHANGE_BY
        ,TOTE.LAST_CHANGE                        				AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_LAST_CHANGE
        ,TOTE.FROM_DATE                         				AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_FROM_DATE
        ,TOTE.TO_DATE                           				AS DEPENDENT_TEST_OBJECT_TYPE_EXTENDED_TO_DATE
        ,case when 
			TOTE.ID=TOTE.LEVEL_1_ID then TOTE.ID 
			else TOTE.LEVEL_2_ID end 							AS DEPENDENT_REF_TEST_OBJECT_TYPE_LEVEL_2_ID
	FROM idq_results.REF_TEST_OBJECT_TYPE_EXTENDED TOTE
;