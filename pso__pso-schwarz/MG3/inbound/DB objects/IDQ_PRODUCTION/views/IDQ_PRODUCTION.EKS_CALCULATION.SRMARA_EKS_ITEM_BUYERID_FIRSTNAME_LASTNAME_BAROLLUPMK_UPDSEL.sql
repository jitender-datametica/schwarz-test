create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_BUYERID_FIRSTNAME_LASTNAME_BAROLLUPMK_UPDSEL(
	ITEMID,
	BUYERID,
	BUYERIDNEW,
	BUYERFIRSTNAME,
	BUYERFIRSTNAMENEW,
	BUYERLASTNAME,
	BUYERLASTNAMENEW
) as
SELECT DISTINCT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, 
EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID, 
EKS_CALCULATION.srMARA_EKS_ITEM_BuyerID_FirstName_LastName_SKRollup01.BuyerID AS BuyerIDNew, 
EKS_CALCULATION.STMARA_EKS_ITEM.BuyerFirstName, 
                  EKS.EMPLOYEE.FIRSTNAME AS BuyerFirstNameNew, 
                  EKS_CALCULATION.STMARA_EKS_ITEM.BuyerLastName, 
                  EKS.EMPLOYEE.LASTNAME AS BuyerLastNameNew
FROM     EKS_CALCULATION.STMARA_EKS_ITEM INNER JOIN
                  EKS_CALCULATION.srMARA_EKS_ITEM_BuyerID_FirstName_LastName_SKRollup01 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.srMARA_EKS_ITEM_BuyerID_FirstName_LastName_SKRollup01.ITEMID AND 
                  EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = EKS_CALCULATION.srMARA_EKS_ITEM_BuyerID_FirstName_LastName_SKRollup01.BITFLAG INNER JOIN
                  EKS.EMPLOYEE ON EKS_CALCULATION.srMARA_EKS_ITEM_BuyerID_FirstName_LastName_SKRollup01.BuyerID = EKS.EMPLOYEE.EMPLOYEEID
WHERE  (EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 2) AND (EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID IS NULL);