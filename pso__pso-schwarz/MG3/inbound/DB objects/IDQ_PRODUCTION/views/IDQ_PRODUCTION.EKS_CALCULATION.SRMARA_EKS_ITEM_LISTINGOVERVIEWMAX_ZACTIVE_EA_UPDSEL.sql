create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_EA_UPDSEL(
	LISTINGOVERVIEWID,
	LOCATION,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE,
	ZACTIVE,
	ZACTIVENEW
) as
SELECT EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LOCATION,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CR_LOCATIONID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.casesize,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zActive,
         1 AS zActiveNew
  FROM   EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX
         INNER JOIN EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_010
                 ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_010.LISTINGOVERVIEWID
                    AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_010.SUPPLIERNO
                    AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_010.ReceivingCountry
                    AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_010.ITEMID
  WHERE  ( EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zArticleType = 'EA' )  
;