create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZITEM_BA_UPDSEL(
	LISTINGOVERVIEWID,
	LOCATION,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE,
	ZARTICLETYPENEW,
	ZARTICLETYPE,
	ZITEM_BANEW,
	ZITEM_BA
) as
SELECT EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LOCATION,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CR_LOCATIONID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize,
         EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType AS zArticleTypeNew,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zArticleType,
         EKS_CALCULATION.STMARA_EKS_ITEM.zITEM_BA     AS zITEM_BANew,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zITEM_BA
  FROM   EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM
                 ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID
  WHERE  ( EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zArticleType IS NULL );