create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_SK_UPDSEL(
	ITEMID,
	ZLEGACYMATNR,
	ZLEGACYMATKL,
	ZMATKL,
	ZLEGACYMATKLNEW,
	ZMATKLNEW
) as

SELECT
EKS_CALCULATION.stMARA_EKS_ITEM.itemid, 
EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATNR, 
EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL, 
EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL,
EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_SK_010.zLegacyMATKLNew, 
EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_SK_010.zMATKLNew

FROM EKS_CALCULATION.stMARA_EKS_ITEM 
INNER JOIN
EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_SK_010 
ON EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_SK_010.zLegacyMATNR = EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATNR;