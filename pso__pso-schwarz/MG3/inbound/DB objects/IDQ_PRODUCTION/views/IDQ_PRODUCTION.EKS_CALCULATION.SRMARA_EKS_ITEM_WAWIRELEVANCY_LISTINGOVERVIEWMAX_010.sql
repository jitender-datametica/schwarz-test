create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCY_LISTINGOVERVIEWMAX_010(
	LISTINGOVERVIEWID,
	LOCATION,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE
) as
SELECT        MAX(LO.LISTINGOVERVIEWID) AS LISTINGOVERVIEWID, 
              LOC.SHORTSIGN AS LOCATION, 
              S.SUPPLIERNO, 
              LO.CR_LOCATIONID, 
              RC.SHORTSIGN AS RECEIVINGCOUNTRY, 
              LI.ITEMID, 
              BP.CASESIZECalc AS CASESIZE    
FROM                     
              (SELECT SUPPLIERNO, LISTINGOVERVIEWID, CR_LOCATIONID FROM EKS.LISTINGOVERVIEW) AS LO
              INNER JOIN
              (SELECT LISTINGOVERVIEWID, LOCATIONID, CONTRACTLINKID FROM EKS.CONTRACTLINK WHERE STATUSID IN (34, 86)) AS CONTRACTLINK ON LO.LISTINGOVERVIEWID = CONTRACTLINK.LISTINGOVERVIEWID 
              INNER JOIN
              (SELECT SUPPLIERNO FROM EKS.SUPPLIER WHERE SUPPLIERNO <> 10236) AS S ON LO.SUPPLIERNO = S.SUPPLIERNO 
              INNER JOIN
              (SELECT LOCATIONID, SHORTSIGN FROM EKS.LOCATION) AS LOC ON LO.CR_LOCATIONID = LOC.LOCATIONID 
              INNER JOIN
              (SELECT LOCATIONID, SHORTSIGN FROM EKS.LOCATION) AS RC ON CONTRACTLINK.LOCATIONID = RC.LOCATIONID 
              INNER JOIN
              (SELECT CONTRACTLINKID, BASICPRICEID FROM EKS.CONTRACTPRICEREL) AS CPR ON CONTRACTLINK.CONTRACTLINKID = CPR.CONTRACTLINKID 
              INNER JOIN
              (SELECT CASESIZECalc, BASICPRICEID, LISTINGITEMID FROM EKS.BASICPRICE) AS BP ON CPR.BASICPRICEID = BP.BASICPRICEID 
              INNER JOIN
              (SELECT ITEMID,LISTINGITEMID FROM EKS.LISTINGITEM) AS LI ON BP.LISTINGITEMID = LI.LISTINGITEMID 
              INNER JOIN
              (SELECT DISTINCT znegotiatingcountry, ITEMID, itemno FROM EKS_CALCULATION.stmara_eks_item WHERE zrelevantmdm = 1) AS mara ON RC.SHORTSIGN = mara.znegotiatingcountry AND LI.ITEMID = mara.ITEMID
              INNER JOIN (SELECT DISTINCT SUBSTR(wawi_artikelnr,-4,4) as wawi_artikelnr_suffix, EKS_SUPPLIER_NO, EKS_ARTIKEL_NR FROM EKS_CALCULATION.WAWI_MDM_RELEVANT_ARTICLES) AS wawi 
              on BP.CASESIZECalc = wawi.wawi_artikelnr_suffix and LO.SUPPLIERNO = wawi.EKS_SUPPLIER_NO and mara.itemno = wawi.EKS_ARTIKEL_NR
GROUP BY S.SUPPLIERNO, LO.CR_LOCATIONID, LOC.SHORTSIGN, RC.SHORTSIGN, LI.ITEMID, 
                         BP.CASESIZECalc
HAVING        (S.SUPPLIERNO <> 10236);