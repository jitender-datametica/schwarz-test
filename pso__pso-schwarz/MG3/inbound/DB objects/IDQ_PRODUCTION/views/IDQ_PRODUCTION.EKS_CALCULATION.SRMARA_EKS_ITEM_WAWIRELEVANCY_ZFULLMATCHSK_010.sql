create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCY_ZFULLMATCHSK_010(
	ITEMID,
	ITEMNO,
	ZFULLMATCHNEW,
	ZISVALIDCONTRACT
) as
  SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
        EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO,
         1 AS zFullMatchNew,
         xtEKS_BASICINFO_RecCountry.zIsValidContract
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY as xtEKS_BASICINFO_RecCountry
                    ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO = xtEKS_BASICINFO_RecCountry.SK_ITEMNO
  WHERE  ( xtEKS_BASICINFO_RecCountry.zIsValidContract = 1 ) and EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantMDM = 1;