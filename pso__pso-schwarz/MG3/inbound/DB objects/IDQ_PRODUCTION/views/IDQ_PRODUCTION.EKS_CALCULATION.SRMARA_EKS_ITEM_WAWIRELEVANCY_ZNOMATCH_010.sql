create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCY_ZNOMATCH_010(
	ITEMID,
	ITEMNO,
	ZNOMATCHNEW
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.itemid,
         EKS_CALCULATION.STMARA_EKS_ITEM.ItemNo,
         1 AS zNoMatchNew
  FROM   EKS.ITEM
         INNER JOIN EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_ALLTIME
                 ON EKS.ITEM.ITEMID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_ALLTIME.ITEMID
         RIGHT OUTER JOIN EKS_CALCULATION.STMARA_EKS_ITEM
                       ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_ALLTIME.itemid = EKS_CALCULATION.STMARA_EKS_ITEM.itemid
                          AND EKS.ITEM.ITEMNO = EKS_CALCULATION.STMARA_EKS_ITEM.ItemNo
  WHERE  ( EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_ALLTIME.ITEMID IS NULL );