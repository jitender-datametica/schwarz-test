create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_REMOVEDUPLICATEEA_010(
	LISTINGOVERVIEWID,
	ITEMID,
	RECEIVINGCOUNTRY,
	CASESIZE,
	MAXDATE
) as
SELECT        EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, 
                EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid, 
                EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, 
                EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize, 
                 MAX(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL) AS MaxDate
FROM            EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY INNER JOIN
                         EKS.CONTRACTPRICEVALIDITY ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID
WHERE        (EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID IS NULL)
GROUP BY EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize
HAVING        (MIN(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL) <> MAX(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL));