create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZFORCERELEVANT_UPDSEL(
	ITEMID,
	ZFORCERELEVANT,
	ZFORCERELEVANTNEW,
	ITEMNO
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, 
         EKS_CALCULATION.STMARA_EKS_ITEM.zForceRelevant,
         EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ForceRelevant AS zForceRelevantNew,
         EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ITEMNO
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.zSource = EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.zSource
                    AND EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO = EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ITEMNO
  WHERE  ( EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ForceRelevant = 1 )
          OR ( EKS_CALCULATION.STMARA_EKS_ITEM.zForceRelevant <> EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ForceRelevant );