create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZHASVALIDCONTRACTDATE_ZHASVALIDADSFLG_SK_UPDSEL(
	ITEMID,
	ZHASVALIDADSFLG,
	ZHASVALIDADSFLGNEW,
	ADSFLG,
	VALUE,
	ZHASVALIDCONTRACTDATE,
	ZHASVALIDCONTRACTDATENEW,
	ITEM_DATEUNTIL,
	DATE,
	ZARTICLETYPE
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, 
         EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidADSFLG,
         1                    AS zHasValidADSFLGNew,
         SKValidity.ADSFLG,
         EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER.Value,
         EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidContractDate,
         1                    AS zHasValidContractDateNew,
         max(SKValidity.DATEUNTIL) AS ITEM_DATEUNTIL,
         P2.Date,
         EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         LEFT OUTER JOIN (SELECT DISTINCT LISTINGOVERVIEWID,
                                          casesize,
                                          SK_ITEMID,
                                          ReceivingCountry,
                                          SUPPLIERNO,
                                          CONTRACTPRICEVALIDITYID
                          FROM   EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY) AS SKLink
                         LEFT OUTER JOIN EKS.CONTRACTPRICEVALIDITY AS SKValidity
                                      ON SKLink.CONTRACTPRICEVALIDITYID = SKValidity.CONTRACTPRICEVALIDITYID
                         RIGHT OUTER JOIN EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX
                                       ON SKLink.LISTINGOVERVIEWID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID
                                          AND SKLink.casesize = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize
                                          AND SKLink.SK_ITEMID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID
                                          AND SKLink.ReceivingCountry = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry
                                          AND SKLink.SUPPLIERNO = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO
                      ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER
                 ON EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER.ID = 'ADSFLGCHK'
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER AS EKS_ZSM_ArticleParameter_1
                 ON EKS_ZSM_ArticleParameter_1.ID = 'ADSFLGON'
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER AS P2
                 ON P2.ID = 'VALIDITYDATE'
  WHERE  ( ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
           AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType = 'SK' )
           AND ( SKValidity.ADSFLG = EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER.Value )
            OR ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
               AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType = 'SK' )
               AND ( EKS_ZSM_ArticleParameter_1.Value = 0 ) )
         AND SKValidity.DATEUNTIL >= P2.Date
    group by EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidADSFLG, zHasValidADSFLGNew, SKValidity.ADSFLG, EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER.Value, EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidContractDate, zHasValidContractDateNew, P2.Date, EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType;