create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZHASVALIDTIMELINELU_UPDSEL(
	ITEMID,
	ZHASVALIDTIMELINELU,
	ZHASVALIDTIMELINELUNEW,
	LISTINGOVERVIEWID
) as
SELECT distinct  EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, 
        EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidTimelineLU,
         1 AS zHasValidTimelineLUNew,
         max(EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID)
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS.LISTINGITEM
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.LISTINGITEM.ITEMID
         INNER JOIN EKS.LISTINGOVERVIEW
                 ON EKS.LISTINGITEM.LISTINGOVERVIEWID = EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID
         INNER JOIN EKS.CONTRACTLINK
                 ON EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID = EKS.CONTRACTLINK.LISTINGOVERVIEWID
         INNER JOIN EKS.SUPPLIER
                 ON EKS.LISTINGOVERVIEW.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO
         left outer join EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER
                      on EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER.ID = 'DRDATE'
  WHERE  ( EKS.CONTRACTLINK.STATUSID IN ( '34', '86' ) )
         AND ( EKS.LISTINGOVERVIEW.DATEUNTIL >= CAST(EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER.DATE as TIMESTAMP_NTZ(9)) )
         group by EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidTimelineLU ;