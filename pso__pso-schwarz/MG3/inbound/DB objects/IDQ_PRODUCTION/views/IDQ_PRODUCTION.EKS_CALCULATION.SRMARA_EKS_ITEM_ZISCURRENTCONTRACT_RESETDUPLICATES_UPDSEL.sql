create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISCURRENTCONTRACT_RESETDUPLICATES_UPDSEL(
	ZARTICLETYPE,
	ITEMID,
	ZISCURRENTCONTRACT,
	ZHASVALIDCONTRACTDATE,
	ZHASVALIDADSFLG,
	CONTRACTPRICEVALIDITYID,
	CONSTRUCTED,
	ZISCURRENTCONTRACTNEW
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType,
         EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsCurrentContract,
         EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidContractDate,
         EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidADSFLG,
         EKS_CALCULATION.XTEKS_BASICINFO_UNION.CONTRACTPRICEVALIDITYID,
         EKS_CALCULATION.STMARA_EKS_ITEM.Constructed,
         NULL AS zIsCurrentContractNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         LEFT OUTER JOIN EKS_CALCULATION.XTEKS_BASICINFO_UNION
                      ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.XTEKS_BASICINFO_UNION.itemid
  WHERE  ( EKS_CALCULATION.XTEKS_BASICINFO_UNION.CONTRACTPRICEVALIDITYID IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType IN ( 'SK', 'EA' ) )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidADSFLG = 1 )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidContractDate = 1 )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsCurrentContract = 1 ) ;