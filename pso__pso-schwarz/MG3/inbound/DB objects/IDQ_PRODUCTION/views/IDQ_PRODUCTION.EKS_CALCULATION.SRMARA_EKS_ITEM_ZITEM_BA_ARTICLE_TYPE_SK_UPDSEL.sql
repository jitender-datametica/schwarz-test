create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZITEM_BA_ARTICLE_TYPE_SK_UPDSEL(
	ITEMID,
	ITEMNO,
	BITFLAG,
	ZISSKHASBA,
	EXPR1,
	ITEMNOBA,
	""ARTICLE TYPE"",
	ZITEM_BA,
	ZITEM_BANEW
) as 
SELECT stMARA_EKS_ITEM.ITEMID,
         stMARA_EKS_ITEM.ITEMNO,
         stMARA_EKS_ITEM.BITFLAG,
         stMARA_EKS_ITEM.zIsSKhasBA,
         stMARA_EKS_ITEM_1.ITEMID  AS Expr1,
         stMARA_EKS_ITEM_1.ITEMID  AS ItemNoBA,
         stMARA_EKS_ITEM_1.BITFLAG AS ""Article type"",
         stMARA_EKS_ITEM.zITEM_BA,
         stMARA_EKS_ITEM_1.ITEMID  AS zITEM_BANew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM AS stMARA_EKS_ITEM
         INNER JOIN EKS.ITEMSORTING
                 ON stMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM AS stMARA_EKS_ITEM_1
                 ON EKS.ITEMSORTING.SORTITEMID = stMARA_EKS_ITEM_1.ITEMID
  WHERE  ( stMARA_EKS_ITEM.BITFLAG = 4 )
         AND ( stMARA_EKS_ITEM_1.BITFLAG = 2 )
    QUALIFY ROW_NUMBER() OVER (PARTITION BY stMARA_EKS_ITEM.ITEMID ORDER BY zITEM_BANew) = 1;