create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ZZZ_PACK_TYPE_FROMXTZLAX008_CUST4UPDSEL(
	ITEMID,
	ZZZ_PACK_TYPE,
	ZZZ_PACK_TYPENEW
) as
SELECT        STMARA_EKS_ITEM.itemid, STMARA_EKS_ITEM.zZZ_PACK_TYPE, XTZLAX008_CUST4.TargetValue1 AS zZZ_PACK_TYPEnew
FROM            EKS_CALCULATION.STMARA_EKS_ITEM INNER JOIN
                         EKS_CALCULATION.XTZLAX008_CUST4 ON STMARA_EKS_ITEM.zLegacyZZ_PACK_TYPE = XTZLAX008_CUST4.LegacyValue
WHERE        (NOT (XTZLAX008_CUST4.TargetValue IS NULL)) AND (STMARA_EKS_ITEM.zZZ_PACK_TYPE IS NULL) AND (XTZLAX008_CUST4.NotRelevant = 0);