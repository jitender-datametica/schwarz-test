create or replace view IDQ_PRODUCTION.EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_ALLTIME(
	LISTINGOVERVIEWID,
	LOCATION,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE
) as
SELECT        MAX(EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID) AS LISTINGOVERVIEWID, EKS.LOCATION.SHORTSIGN AS LOCATION, EKS.SUPPLIER.SUPPLIERNO, EKS.LISTINGOVERVIEW.CR_LOCATIONID, 
                         stEKS_LOCATION_1.SHORTSIGN AS ReceivingCountry, EKS.LISTINGITEM.ITEMID, EKS.BASICPRICE.CASESIZECalc AS CaseSize
FROM            EKS.LISTINGOVERVIEW INNER JOIN
                         EKS.CONTRACTLINK ON EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID = EKS.CONTRACTLINK.LISTINGOVERVIEWID INNER JOIN
                         EKS.SUPPLIER ON EKS.LISTINGOVERVIEW.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO INNER JOIN
                         EKS.LOCATION ON EKS.LISTINGOVERVIEW.CR_LOCATIONID = EKS.LOCATION.LOCATIONID INNER JOIN
                         EKS.LOCATION AS stEKS_LOCATION_1 ON EKS.CONTRACTLINK.LOCATIONID = stEKS_LOCATION_1.LOCATIONID INNER JOIN
                         EKS.CONTRACTPRICEREL ON EKS.CONTRACTLINK.CONTRACTLINKID = EKS.CONTRACTPRICEREL.CONTRACTLINKID INNER JOIN
                         EKS.BASICPRICE ON EKS.CONTRACTPRICEREL.BASICPRICEID = EKS.BASICPRICE.BASICPRICEID INNER JOIN
                         EKS.LISTINGITEM ON EKS.BASICPRICE.LISTINGITEMID = EKS.LISTINGITEM.LISTINGITEMID
WHERE        (EKS.CONTRACTLINK.STATUSID IN (34, 86))
GROUP BY EKS.SUPPLIER.SUPPLIERNO, EKS.LISTINGOVERVIEW.CR_LOCATIONID, EKS.LOCATION.SHORTSIGN, stEKS_LOCATION_1.SHORTSIGN, EKS.LISTINGITEM.ITEMID, 
                         EKS.BASICPRICE.CASESIZECalc
HAVING        (EKS.SUPPLIER.SUPPLIERNO <> 10236);