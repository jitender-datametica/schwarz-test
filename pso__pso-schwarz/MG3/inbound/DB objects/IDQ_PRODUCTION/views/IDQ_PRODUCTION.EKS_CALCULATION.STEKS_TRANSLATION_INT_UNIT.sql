create or replace view IDQ_PRODUCTION.EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT(
	TRANSLATIONID,
	CHECKID,
	PKID,
	TRANSLATION_FIELDID,
	CRDATE,
	MODDATE,
	CRUSER,
	MODUSER,
	DESCRIPTION
) as 
SELECT        TRANSLATIONID, CHECKID, PKID, TRANSLATION_FIELDID, CRDATE, MODDATE, CRUSER, MODUSER, DESCRIPTION
FROM EKS.TRANSLATION_INT
WHERE (EKS.TRANSLATION_INT.TRANSLATION_FIELDID = 7);