create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_EA_MULTIPLE_COMMODITYCODE_01_SEL(
	EXPR2,
	ITEMID
) as
SELECT COUNT(DISTINCT EKS.ITEMINTRASTAT.INTRASTAT) AS Expr2, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
FROM     EKS_CALCULATION.stMARA_EKS_ITEM INNER JOIN
                  EKS.ITEMINTRASTAT ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMINTRASTAT.ITEMID
GROUP BY EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
HAVING (COUNT(DISTINCT EKS.ITEMINTRASTAT.INTRASTAT) > 1);