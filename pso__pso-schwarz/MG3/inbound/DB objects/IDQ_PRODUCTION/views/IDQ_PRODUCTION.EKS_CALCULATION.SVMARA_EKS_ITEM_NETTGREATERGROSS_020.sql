create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTGREATERGROSS_020(
	ZSOURCE,
	ZACTIVE,
	ZNEGOTIATINGCOUNTRY,
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	DESCRIPTION_INT,
	ZMATKL,
	ARTICLEFAMILY,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	BUYERSHORTSIGN,
	LISTINGOVERVIEWID,
	INTSUPPLIERNO,
	SUPPLIERDESCRIPTION,
	RECEIVINGCOUNTRY,
	CASESIZE,
	CASEGROSSWEIGHT,
	NETWEIGHT,
	TOTAL_CASENETWEIGHT,
	DECIMALCASESIZE,
	ZISCURRENTCONTRACT,
	ZISCURRENTCONTRACTFROMSK,
	ZRELEVANTMDM
) as					  
SELECT DISTINCT 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zSource, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zActive, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
				  EKS.SUPPLIER.INTSUPPLIERNO, 
				  EKS.SUPPLIER.DESCRIPTION AS SupplierDescription, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize, 
				  GW.CASEGROSSWEIGHT AS CASEGROSSWEIGHT, NW.Netweight, NW.Total_CaseNetweight, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM
			FROM     EKS_CALCULATION.stMARA_EKS_ITEM 
			INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID 
				  INNER JOIN
                  EKS.LISTINGITEM ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = EKS.LISTINGITEM.LISTINGOVERVIEWID AND EKS.LISTINGITEM.ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID 
				  INNER JOIN
                  EKS.BASICPRICE ON EKS.BASICPRICE.LISTINGITEMID = EKS.LISTINGITEM.LISTINGITEMID AND EKS.BASICPRICE.BASICPRICEID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.BASICPRICEID 
				  INNER JOIN
                  EKS.SUPPLIER ON EKS.SUPPLIER.SUPPLIERNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO 
				  INNER JOIN
                  EKS_CALCULATION.svMARA_EKS_ITEM_NettGreaterGross_SKCaseGrossWeight AS GW ON EKS.LISTINGITEM.ITEMID = GW.ITEMID AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = GW.LISTINGOVERVIEWID AND 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize = GW.CaseSize AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO = GW.SUPPLIERNO AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry = GW.ReceivingCountry 
				  INNER JOIN
                  EKS_CALCULATION.svMARA_EKS_ITEM_NettGreaterGross_SKNettweight AS NW ON EKS.LISTINGITEM.ITEMID = NW.ITEMID AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = NW.LISTINGOVERVIEWID AND 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize = NW.CaseSize AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO = NW.SUPPLIERNO AND 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry = NW.ReceivingCountry 
				  LEFT OUTER JOIN
                  EKS.LISTINGOVERVIEW AS list ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = list.LISTINGOVERVIEWID 
				  LEFT OUTER JOIN
                  EKS.LOHEADING AS loh ON list.LOHEADINGID = loh.LOHEADINGID LEFT OUTER JOIN
                  EKS.TRANSLATION_INT AS trans_loh ON loh.DESCRIPTIONID = trans_loh.TRANSLATIONID LEFT OUTER JOIN
                  EKS.LOCATEGORY AS loc ON list.LOCATEGORYID = loc.LOCATEGORYID LEFT OUTER JOIN
                  EKS.TRANSLATION_INT AS trans_loc ON loc.DESCRIPTIONID = trans_loc.TRANSLATIONID
			WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) 
			AND (LOWER(IFNULL(trans_loc.DESCRIPTION, '')) NOT LIKE '%filialbelieferung%') 
			AND (LOWER(IFNULL(trans_loh.DESCRIPTION, '')) NOT LIKE '%dezentral%');