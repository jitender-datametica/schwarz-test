create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTWEIGHT_DIFFERENT_PACKCONTENT_SEL_ALL(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	ZZZ_QUANT_PACK_CONT,
	ZZZ_PACK_CONTENT,
	ZZZ_PACK_CONT_UOM,
	PACKAGEPACKAGING,
	EKS_NETTWEIGHT,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
SELECT EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.zNegotiatingCountry AS NegotiatingCountry, 
EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN,
EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName,
EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL,
EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily,
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.ITEMID, 
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.ITEMNO, 
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.zArticleType AS ArticleType, 
EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description, 
EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT, 
EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONTENT, 
EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONT_UOM, 
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.PackagePackaging, 
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.EKS_NETTWEIGHT, 
CASE WHEN (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1 AND stMARA_EKS_ITEM.zIsCurrentContract = 0) 
THEN sk.zRelevantMDM ELSE stMARA_EKS_ITEM.zRelevantMDM END AS zRelevantMDM, 
EKS_CALCULATION.stMARA_EKS_ITEM.zSource, 
EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM    
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030 
INNER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM ON EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_030.ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID 
LEFT OUTER JOIN
(SELECT EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid, MIN(EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM) AS zRelevantMDM
FROM 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry 
INNER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM 
ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
GROUP BY EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid) AS SK 
ON SK.itemid = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) 
AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL <> '74') 
AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID IN
                      (SELECT ITEMID
                       FROM      EKS_CALCULATION.svMARA_EKS_ITEM_EA_ReceivingCountry
                       WHERE   (ReceivingCountry NOT IN ('US', 'LX', 'EW', 'CH')))) OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) 
                  AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL <> '74') AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID IN
                      (SELECT ITEMID
                       FROM      EKS_CALCULATION.svMARA_EKS_ITEM_EA_ReceivingCountry AS svMARA_EKS_ITEM_EA_ReceivingCountry_2
                       WHERE   (ReceivingCountry NOT IN ('US', 'LX', 'EW', 'CH')))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL <> '74') AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID IN
                      (SELECT ITEMID
                       FROM      EKS_CALCULATION.svMARA_EKS_ITEM_EA_ReceivingCountry AS svMARA_EKS_ITEM_EA_ReceivingCountry_1
                       WHERE   (ReceivingCountry NOT IN ('US', 'LX', 'EW', 'CH')))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1);