CREATE OR REPLACE FUNCTION LDL_PRODUCTION.P_LEW_MART_PIT.F_GETADVPERIODID(""PADVWEEKID"" NUMBER(38,0), ""PSTARTDATE"" DATE, ""PENDDATE"" DATE)
RETURNS NUMBER(38,0)
LANGUAGE SQL
AS '
	iff(pStartDate IS NULL OR pEndDate IS NULL OR pStartDate > pEndDate OR pAdvWeekID < 0
		, -1::INTEGER
		,
		TRY_TO_NUMBER(
			TO_CHAR(pAdvWeekID) 			||
			TO_CHAR(pStartDate,''YYMMDD'') 	||
			TO_CHAR(pEndDate,''YYMMDD'')
		)::INTEGER		
	) 
	';