CREATE OR REPLACE FUNCTION LDL_PRODUCTION.P_LEW_MART_PIT.F_GETHISTREJECTREASONID(""P_REJECTDESCR"" VARCHAR(16777216), ""P_REPDATE"" DATE)
RETURNS NUMBER(38,0)
LANGUAGE SQL
AS '
	
	SELECT
		max(
			COALESCE(rej.REJECT_REASON_ID,-1)
		) AS REJECT_REASON_ID
	FROM
		(
			SELECT REJECT_REASON_ID 
			FROM P_LEW_MART_PIT.T_CNTL_DIM_REJECT_REASON
			WHERE TRUE
				AND DELETED_FG 		= 0
				AND UPPER(TRIM(REJECT_REASON_DESCR))	LIKE ''%'' || UPPER(TRIM(p_RejectDescr)) || ''%''
				AND p_RepDate	BETWEEN VALID_FROM_DT AND VALID_TO_DT
			QUALIFY ROW_NUMBER() OVER(PARTITION BY REJECT_REASON_ID, VALID_FROM_DT, DELETED_FG ORDER BY DWH_UPDATED_TS) = 1 
    	)rej
	WHERE TRUE	
		
    ';