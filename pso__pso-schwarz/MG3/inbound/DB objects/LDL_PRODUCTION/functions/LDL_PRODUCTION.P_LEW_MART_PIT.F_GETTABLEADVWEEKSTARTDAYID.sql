CREATE OR REPLACE FUNCTION LDL_PRODUCTION.P_LEW_MART_PIT.F_GETTABLEADVWEEKSTARTDAYID()
RETURNS TABLE (""CLIENT_ID"" NUMBER(38,0), ""COUNTRY_ISO_CD"" VARCHAR(3), ""COUNTRY_DESCR"" VARCHAR, ""LANG_SID"" NUMBER(38,0), ""CURR_SID"" NUMBER(38,0), ""CURR_CD"" VARCHAR, ""CTR_ADV_WEEK_START_WEEKDAY_ID"" NUMBER(38,0))
LANGUAGE SQL
AS '
		SELECT 
			  a.CLIENT_ID
			, a.COUNTRY_ISO_CD
			, a.COUNTRY_DESCR
			, a.LANG_SID
			, a.CURR_SID
			, a.CURR_CD			
			, a.CTR_ADV_WEEK_START_WEEKDAY_ID
		FROM		
		(
		SELECT
			  CLIENT_ID
			, COUNTRY_ISO_CD
			, COUNTRY_DESCR
			, LANG_SID
			, CURR_SID
			, CURR_CD			
			, CTR_ADV_WEEK_START_WEEKDAY_ID
		FROM P_LEW_MART_PIT.T_DIM_CLIENT
		WHERE TRUE 
			AND DELETED_FG 		= 0
			AND CURRENT_FG 		= 1
			AND PIT_COUNTRY_FG	= 1

		QUALIFY ROW_NUMBER() OVER(PARTITION BY CLIENT_ID, VALID_FROM_DT, DELETED_FG ORDER BY DWH_UPDATED_TS) = 1
		) a
    ';