create or replace view PRODUCTION_PRODUCTION.FE_MSTR_BGE_PALETTIERER.V_REL_ALERTS_PRIORITY_TO_PRODUCTION_STOP_FLAG(
	ALERTS_PRIORITY_ID,
	ALERTS_PRODUCTION_STOP_FG
) as
SELECT ALERTS_PRIORITY_ID, ALERTS_PRODUCTION_STOP_FG
FROM FE_MSTR_BGE_PALETTIERER.V_DIM_ALERTS_PRIORITY
cross join
FE_MSTR_BGE_PALETTIERER.V_DIM_PRODUCTION_STOP_FLAG
WHERE (ALERTS_PRIORITY_ID <> 5 OR ALERTS_PRODUCTION_STOP_FG = FALSE)
;