create or replace view SZD_PRODUCTION.FE_MSTR_SERVICE_AND_SUPPORT.V_FACT_TICKET_OPENED_PER_MONTH_TICKET_TYPE_DIVISION_COUNTRY(
	TICKET_TYPE_ID,
	TICKET_TYPE_NAME,
	CY_MONTH,
	TICKET_CREATOR_COUNTRY_BUSINESS_CD,
	TICKET_CREATOR_COUNTRY_BUSINESS_NAME,
	TICKET_CREATOR_DIVISION_CD,
	TICKET_CREATED_CNT,
	TICKET_OPENED_CNT
) as
SELECT 
	TF1.TICKET_TYPE_ID
    , TF1.TICKET_TYPE_NAME
	, TF1.CY_MONTH
    , TD1.COUNTRY_BUSINESS_CD
    , TF1.TICKET_CREATOR_COUNTRY_BUSINESS_NAME
    , TD2.DIVISION_CD
    , TF1.TICKET_CREATED_CNT
    , TF1.TICKET_OPENED_CNT
FROM CORE.T_FACT_TICKET_OPENED_PER_MONTH_TICKET_TYPE_DIVISION_COUNTRY TF1
JOIN CORE.T_DIM_COUNTRY_BUSINESS TD1
ON TF1.TICKET_CREATOR_COUNTRY_BUSINESS_LOCATION_SID=TD1.LOCATION_SID AND TD1.DWH_VALID_TO_TMSP >= '9999-12-31'
JOIN CORE.T_DIM_DIVISION TD2
ON TF1.TICKET_CREATOR_DIVISION_PARTY_SID=TD2.PARTY_SID AND TD2.DWH_VALID_TO_TMSP >= '9999-12-31'
;