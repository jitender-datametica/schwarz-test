create or replace view SZD_PRODUCTION.FE_MSTR_WHOLESALE.V_DIM_PRODUCER(
	PRODUCER_PARTY_SID,
	DWH_VALID_FROM_TMSP,
	DWH_VALID_TO_TMSP,
	DWH_VALID_FG,
	STATUS_CD,
	PRODUCER_NAME,
	EMAIL_TXT,
	PRODUCER_NAME_TXT
) as 
    SELECT 
        PARTY_SID AS PRODUCER_PARTY_SID
        ,DWH_VALID_FROM_TMSP
        ,DWH_VALID_TO_TMSP
        ,DWH_VALID_FG
        ,STATUS_CD
        ,PRODUCER_NAME
        ,EMAIL_TXT
        ,SOURCE_PRODUCER_NAME_ADDRESS_CITY_TXT AS PRODUCER_NAME_TXT
    FROM
        CORE.T_DIM_PRODUCER
    WHERE
        DWH_VALID_FG = 1
;