create or replace view SZD_PRODUCTION.FE_MSTR_WHOLESALE.V_DIM_VENDOR(
	VENDOR_PARTY_SID,
	DWH_VALID_FROM_TMSP,
	DWH_VALID_TO_TMSP,
	DWH_VALID_FG,
	STATUS_CD,
	VENDOR_NAME,
	EMAIL_TXT,
	VENDOR_NAME_TXT
) as 
    SELECT 
        PARTY_SID AS VENDOR_PARTY_SID
        ,DWH_VALID_FROM_TMSP
        ,DWH_VALID_TO_TMSP
        ,DWH_VALID_FG
        ,STATUS_CD
        ,VENDOR_NAME
        ,EMAIL_TXT
        ,SOURCE_VENDOR_NAME_ADDRESS_CITY_TXT AS VENDOR_NAME_TXT
    FROM
        CORE.T_DIM_VENDOR
    WHERE
        DWH_VALID_FG = 1
;