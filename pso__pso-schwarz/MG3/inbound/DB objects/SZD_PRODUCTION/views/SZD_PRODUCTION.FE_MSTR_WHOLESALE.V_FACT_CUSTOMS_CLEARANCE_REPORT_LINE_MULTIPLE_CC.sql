create or replace view SZD_PRODUCTION.FE_MSTR_WHOLESALE.V_FACT_CUSTOMS_CLEARANCE_REPORT_LINE_MULTIPLE_CC(
	CLEARANCE_DT,
	ITEM_POSITION,
	CY_MONTH,
	CONSIGNOR_PARTY_SID,
	IMPORTER_PARTY_SID,
	IMPORTER_NUMBER,
	DECLARANT_PARTY_SID,
	DECLARANT_NUMBER,
	DECLARANT_NAME,
	DECLARANT_AUTHORIZED_FG,
	ORIGIN_COUNTRY_LOCATION_SID,
	ORIGIN_ISO_COUNTRY_CD,
	CUSTOMS_TARIFF_NUMBER_CD,
	CUSTOMS_PRODUCT_NUMBER,
	GOODS_DESCR,
	DUTY_PAID_VAL,
	CURR_CD,
	MULTIPLE_CC_FG,
	CC2_FG,
	CC3_FG,
	CC4_FG,
	OVER_4_CC_FG
) as

SELECT DISTINCT CLEARANCE_DT
	,ITEM_POSITION
	,CY_MONTH
	,CONSIGNOR_PARTY_SID
	,IMPORTER_PARTY_SID
	,IMPORTER_NUMBER
	,DECLARANT_PARTY_SID
	,DECLARANT_NUMBER
	,DECLARANT_NAME
	,DECLARANT_AUTHORIZED_FG
	,ORIGIN_COUNTRY_LOCATION_SID
	,ORIGIN_ISO_COUNTRY_CD
	,CUSTOMS_TARIFF_NUMBER_CD
	,CUSTOMS_PRODUCT_NUMBER
	,GOODS_DESCR
	,DUTY_PAID_VAL
	,CURR_CD
	,CASE 
		WHEN (COUNT(DISTINCT CUSTOMS_TARIFF_NUMBER_CD) OVER (PARTITION BY CUSTOMS_PRODUCT_NUMBER)) > 1
			THEN 1
		ELSE 0
		END AS MULTIPLE_CC_FG
	,CASE 
		WHEN (COUNT(DISTINCT CUSTOMS_TARIFF_NUMBER_CD) OVER (PARTITION BY CUSTOMS_PRODUCT_NUMBER)) = 2
			THEN 1
		ELSE 0
		END AS CC2_FG
	,CASE 
		WHEN (COUNT(DISTINCT CUSTOMS_TARIFF_NUMBER_CD) OVER (PARTITION BY CUSTOMS_PRODUCT_NUMBER)) = 3
			THEN 1
		ELSE 0
		END AS CC3_FG
	,CASE 
		WHEN (COUNT(DISTINCT CUSTOMS_TARIFF_NUMBER_CD) OVER (PARTITION BY CUSTOMS_PRODUCT_NUMBER)) = 4
			THEN 1
		ELSE 0
		END AS CC4_FG
	,CASE 
		WHEN (COUNT(DISTINCT CUSTOMS_TARIFF_NUMBER_CD) OVER (PARTITION BY CUSTOMS_PRODUCT_NUMBER)) > 4
			THEN 1
		ELSE 0
		END AS OVER_4_CC_FG
FROM CORE.T_FACT_CUSTOMS_CLEARANCE_REPORT_LINE
;