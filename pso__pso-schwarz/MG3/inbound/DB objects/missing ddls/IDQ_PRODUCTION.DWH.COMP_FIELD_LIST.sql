create or replace view IDQ_PRODUCTION.DWH.COMP_FIELD_LIST(
	SCOPE_ID,
	REF_COMP_FIELD_DEFINITION_ID,
	COMP_SCOPE_EXECUTION_ID,
	LEADING_TEST_OBJECT_ID,
	DEPENDENT_TEST_OBJECT_ID,
	LEADING_FIELD_VALUE,
	DEPENDENT_FIELD_VALUE,
	FIELD_RESULT_TYPE_ID,
	LEADING_REF_BRANCH_ID,
	LEADING_REF_TEST_OBJECT_TYPE_ID,
	LEADING_REF_COUNTRY_ID,
	LEADING_REF_SOURCE_SYSTEM_TYPE_ID,
	LEADING_REF_SOURCE_SYSTEM_ID,
	DEPENDENT_REF_BRANCH_ID,
	DEPENDENT_REF_TEST_OBJECT_TYPE_ID,
	DEPENDENT_REF_COUNTRY_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_ID
) as

SELECT 
	   a.SCOPE_ID						   AS SCOPE_ID -- clarify naming with Sergey // NEW COLUMN ADDED
	  ,a.COMP_FIELD_DEFINITION_ID        AS REF_COMP_FIELD_DEFINITION_ID
      ,a.COMP_RECORD_EXECUTION_ID        AS COMP_SCOPE_EXECUTION_ID ----- Is it correct?_KD // clarify with Sergey
      ,a.LEADING_TEST_OBJECT_ID          AS LEADING_TEST_OBJECT_ID
      ,a.DEPENDENT_TEST_OBJECT_ID        AS DEPENDENT_TEST_OBJECT_ID
      ,a.LEADING_FIELD_VALUE             AS LEADING_FIELD_VALUE
      ,a.DEPENDENT_FIELD_VALUE           AS DEPENDENT_FIELD_VALUE
      ,a.FIELD_RESULT_TYPE_ID            AS FIELD_RESULT_TYPE_ID
	  ,b.BRANCH_ID				          LEADING_REF_BRANCH_ID							
	  ,b.TEST_OBJECT_TYPE_ID              LEADING_REF_TEST_OBJECT_TYPE_ID               
	  ,b.COUNTRY_ID                       LEADING_REF_COUNTRY_ID                        
	  ,RSS_L.SOURCE_SYSTEM_TYPE_ID      LEADING_REF_SOURCE_SYSTEM_TYPE_ID             
	  ,b.SOURCE_SYSTEM_ID                 LEADING_REF_SOURCE_SYSTEM_ID                  
  	  ,c.BRANCH_ID                        DEPENDENT_REF_BRANCH_ID                       
	  ,c.TEST_OBJECT_TYPE_ID              DEPENDENT_REF_TEST_OBJECT_TYPE_ID             
	  ,c.COUNTRY_ID                       DEPENDENT_REF_COUNTRY_ID                      
	  ,RSS_D.SOURCE_SYSTEM_TYPE_ID      DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID           
	  ,c.SOURCE_SYSTEM_ID                 DEPENDENT_REF_SOURCE_SYSTEM_ID                
	  
  FROM SYSCOMP.COMP_FIELD_LIST a 

	join idq_results.IDQ_TEST_OBJECT b  ---- LEADING
		on a.LEADING_TEST_OBJECT_ID=b.ID
	join idq_results.IDQ_TEST_OBJECT c ----- DEPENDENT
		on a.DEPENDENT_TEST_OBJECT_ID=c.ID
	INNER JOIN idq_results.REF_SOURCE_SYSTEM RSS_L ---- LEADING
		ON b.SOURCE_SYSTEM_ID = RSS_L.ID
	INNER JOIN idq_results.REF_SOURCE_SYSTEM RSS_D ----- DEPENDENT
		ON c.SOURCE_SYSTEM_ID = RSS_D.ID
;
