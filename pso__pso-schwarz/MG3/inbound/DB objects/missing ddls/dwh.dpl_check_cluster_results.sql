create or replace view DWH.DPL_CHECK_CLUSTER_RESULTS(
	DPL_CHECK_CLUSTER_RESULTS_ID,
	DPL_CHECK_EXECUTION_ID,
	IDQ_TEST_OBJECT_ID,
	CLUSTERID,
	GROUPKEY,
	CLUSTERSIZE,
	ROWID,
	LINKID,
	LINKSCORE,
	REF_RULE_ID,
	REF_DPL_CHECK_DEFINITION_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID,
	REF_TEST_OBJECT_TYPE_ID
) as
SELECT  DCCR.ID                       AS DPL_CHECK_CLUSTER_RESULTS_ID
       ,DCCR.DPL_CHECK_EXECUTION_ID	AS DPL_CHECK_EXECUTION_ID
       ,DCCR.TEST_OBJECT_ID			AS IDQ_TEST_OBJECT_ID
       ,DCCR.CLUSTERID				AS CLUSTERID
       ,DCCR.GROUPKEY					AS GROUPKEY
       ,DCCR.CLUSTERSIZE				AS CLUSTERSIZE
       ,DCCR.ROWID				    AS ROWID
       ,DCCR.LINKID					AS LINKID
       ,DCCR.LINKSCORE				AS LINKSCORE
       ,RRDCDR.RULE_ID				AS REF_RULE_ID
       ,DCE.DPL_CHECK_DEFINITION_ID	AS REF_DPL_CHECK_DEFINITION_ID
       ,DCE.SOURCE_SYSTEM_ID			AS REF_SOURCE_SYSTEM_ID
       ,RDCD.SOURCE_SYSTEM_TYPE_ID	AS REF_SOURCE_SYSTEM_TYPE_ID
       ,DCE.COUNTRY_ID				AS REF_COUNTRY_ID
       ,RDCD.BRANCH_ID				AS REF_BRANCH_ID
       ,RDCD.TEST_OBJECT_TYPE_ID		AS REF_TEST_OBJECT_TYPE_ID	
FROM idq_results.DPL_CHECK_CLUSTER_RESULTS DCCR
INNER JOIN idq_results.DPL_CHECK_EXECUTION DCE
  ON DCCR.DPL_CHECK_EXECUTION_ID = DCE.ID
INNER JOIN idq_results.REF_DPL_CHECK_DEFINITION RDCD
  ON DCE.DPL_CHECK_DEFINITION_ID = RDCD.ID
INNER JOIN (SELECT DPL_CHECK_DEFINITION_ID, MAX(RULE_ID) AS RULE_ID FROM idq_results.REF_REL_DPL_CHECK_DEF_RULE GROUP BY DPL_CHECK_DEFINITION_ID ) RRDCDR
  ON DCE.DPL_CHECK_DEFINITION_ID = RRDCDR. DPL_CHECK_DEFINITION_ID
;