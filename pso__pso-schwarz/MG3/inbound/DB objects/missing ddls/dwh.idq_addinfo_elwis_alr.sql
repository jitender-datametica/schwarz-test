create or replace view DWH.IDQ_ADDINFO_ELWIS_ALR(
	IDQ_ADDINFO_ELWIS_ALR_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	IDQ_TEST_OBJECT_ID,
	REF_BRANCH_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	IS_RELEVANT,
	LIEFERANTENNUMMER,
	LIEFERANTENNAME,
	ARTIKELNUMMER,
	ARTIKELBEZEICHNUNG,
	ALTE_ARTIKELNUMMER,
	BERECHTIGUNGSGRUPPE,
	ARTIKELART,
	WARENGRUPPE,
	GRUNDDATEN_STATUS
) as

select ID AS IDQ_ADDINFO_ELWIS_ALR_ID,
SOURCE_SYSTEM_PRIMARY_KEY,
TEST_OBJECT_ID AS IDQ_TEST_OBJECT_ID,
BRANCH_ID AS REF_BRANCH_ID,
SOURCE_SYSTEM_ID AS REF_SOURCE_SYSTEM_ID,
COUNTRY_ID AS REF_COUNTRY_ID,
IS_RELEVANT,
LIEFERANTENNUMMER,
LIEFERANTENNAME,
ARTIKELNUMMER,
ARTIKELBEZEICHNUNG,
ALTE_ARTIKELNUMMER,
BERECHTIGUNGSGRUPPE,
ARTIKELART,
WARENGRUPPE,
GRUNDDATEN_STATUS

from idq_results.IDQ_ADDINFO_ELWIS_ALR as a
inner join dwh.CHECK_TEST_RESULT b on a.TEST_OBJECT_ID=b.IDQ_TEST_OBJECT_ID
where a.IS_RELEVANT=1 and IS_ERROR_DETECTED=1 and REF_SOURCE_SYSTEM_TYPE_ID=8 and BRANCH_ID=1;