create or replace view DWH.REF_SYNC_DISTRIBUTION_LOGIC(
	REF_SYNC_DISTRIBUTION_LOGIC_ID,
	REF_SYNC_REL_FIELD_FIELD_ID,
	REF_COUNTRY_ID,
	REF_SYNC_DISTRIBUTION_LOGIC_TYPE_ID,
	REF_SYNC_REPORT_DEFINITION_ID,
	DISTRIBUTION_LOGIC_DESCRIPTION
) as
SELECT ID                                    AS REF_SYNC_DISTRIBUTION_LOGIC_ID
      ,REF_SYNC_REL_FIELD_FIELD_ID           AS REF_SYNC_REL_FIELD_FIELD_ID
      ,REF_COUNTRY_ID                        AS REF_COUNTRY_ID
      ,REF_SYNC_DISTRIBUTION_LOGIC_TYPE_ID   AS REF_SYNC_DISTRIBUTION_LOGIC_TYPE_ID
      ,REF_SYNC_REPORT_DEFINITION_ID         AS REF_SYNC_REPORT_DEFINITION_ID
      ,DISTRIBUTION_LOGIC_DESCRIPTION        AS DISTRIBUTION_LOGIC_DESCRIPTION
FROM idq_results.REF_SYNC_DISTRIBUTION_LOGIC
;