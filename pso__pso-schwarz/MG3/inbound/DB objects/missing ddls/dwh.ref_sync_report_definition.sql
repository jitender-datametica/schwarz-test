create or replace view DWH.REF_SYNC_REPORT_DEFINITION(
	REF_SYNC_REPORT_DEFINITION_ID,
	SYNC_REPORT_DEFINITION_TECHNICAL_NAME,
	REF_TEST_OBJECT_TYPE_ID,
	LEADING_SYSTEM_ID,
	DEPENDENT_SYSTEM_ID,
	SYNC_REPORT_DEFINITION_NAME,
	SYNC_REPORT_DEFINITION_NAME_DE,
	SYNC_REPORT_DEFINITION_NAME_EN
) as
SELECT ID                  AS REF_SYNC_REPORT_DEFINITION_ID
      ,NAME                AS SYNC_REPORT_DEFINITION_TECHNICAL_NAME
      ,TEST_OBJECT_TYPE_ID AS REF_TEST_OBJECT_TYPE_ID
      ,LEADING_SYSTEM_ID   AS LEADING_SYSTEM_ID
      ,DEPENDENT_SYSTEM_ID AS DEPENDENT_SYSTEM_ID
      ,NAME		         AS SYNC_REPORT_DEFINITION_NAME
      ,NAME		         AS SYNC_REPORT_DEFINITION_NAME_DE
      ,NAME		         AS SYNC_REPORT_DEFINITION_NAME_EN
FROM idq_results.REF_SYNC_REPORT_DEFINITION
;