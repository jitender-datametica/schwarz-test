create or replace view DWH.SYNC_REPORT_TEST_RESULT(
	SYNC_REPORT_TEST_RESULT_ID,
	SYNC_REPORT_RECORD_RESULT_ID,
	REF_SYNC_REL_FIELD_FIELD_ID,
	LEADING_FIELD_VALUE,
	DEPENDENT_FIELD_VALUE,
	IS_ERROR_DETECTED,
	REF_SYNC_RESULT_TYPE_ID,
	EQUALITY_SCORE,
	PENALTY,
	SYNC_REPORT_EXECUTION_ID,
	REF_SYNC_REPORT_DEFINITION_ID,
	REF_TEST_OBJECT_TYPE_ID,
	LEADING_SYSTEM_ID,
	DEPENDENT_SYSTEM_ID,
	SYNC_REPORT_TEST_RESULT_IS_CURRENT
) as
SELECT SRTR.ID                            AS SYNC_REPORT_TEST_RESULT_ID
      ,SRTR.SYNC_REPORT_RECORD_RESULT_ID  AS SYNC_REPORT_RECORD_RESULT_ID
      ,SRTR.SYNC_REL_FIELD_FIELD_ID	    AS REF_SYNC_REL_FIELD_FIELD_ID
      ,SRTR.LEADING_FIELD_VALUE		    AS LEADING_FIELD_VALUE
      ,SRTR.DEPENDENT_FIELD_VALUE		    AS DEPENDENT_FIELD_VALUE
      ,SRTR.IS_ERROR_DETECTED			    AS IS_ERROR_DETECTED
      ,SRTR.REF_SYNC_RESULT_TYPE_ID	    AS REF_SYNC_RESULT_TYPE_ID
      ,SRTR.EQUALITY_SCORE				AS EQUALITY_SCORE
      ,SRTR.PENALTY					    AS PENALTY
      ,SRE.ID                             AS SYNC_REPORT_EXECUTION_ID
      ,SRE.SYNC_REPORT_DEFINITION_ID	    AS REF_SYNC_REPORT_DEFINITION_ID
      ,RSRD.TEST_OBJECT_TYPE_ID           AS REF_TEST_OBJECT_TYPE_ID
      ,RSRD.LEADING_SYSTEM_ID             AS LEADING_SYSTEM_ID
      ,RSRD.DEPENDENT_SYSTEM_ID           AS DEPENDENT_SYSTEM_ID
	  ,SRE.IS_CURRENT                     AS SYNC_REPORT_TEST_RESULT_IS_CURRENT
FROM idq_results.SYNC_REPORT_TEST_RESULT SRTR
INNER JOIN idq_results.SYNC_REPORT_RECORD_RESULT SRRR
  ON SRTR.SYNC_REPORT_RECORD_RESULT_ID = SRRR.ID
INNER JOIN idq_results.SYNC_REPORT_EXECUTION SRE
  ON SRRR.SYNC_REPORT_EXECUTION_ID = SRE.ID
INNER JOIN idq_results.REF_SYNC_REPORT_DEFINITION RSRD
  ON SRE.SYNC_REPORT_DEFINITION_ID = RSRD.ID
;