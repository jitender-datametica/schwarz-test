CREATE OR REPLACE PROCEDURE FE_MSTR_BGE_PALETTIERER.P_ADD_OR_UPDATE_SHIFT_REPORT_MESSAGES (ALERTS_DAY_SHIFT_ID FLOAT, ALERTS_SHIFT_REPORT_AGREEMENT_TXT VARCHAR(16777216), ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT VARCHAR(16777216), ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT VARCHAR(16777216), ALERTS_SHIFT_REPORT_SECURITY_ISSUES VARCHAR(16777216))
RETURNS STRING
LANGUAGE JAVASCRIPT
EXECUTE AS OWNER
AS $$
   var sql_command = "\
    MERGE INTO CORE.T_FACT_ALERTS_SHIFT_REPORT_PER_SHIFT AS TGT1 \
	USING (SELECT ALERTS_DAY_SHIFT_ID, MAX(ALERTS_SHIFT_REPORT_AGREEMENT_TXT) AS ALERTS_SHIFT_REPORT_AGREEMENT_TXT, MAX(ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT) AS ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, MAX(ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT) AS ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, MAX(ALERTS_SHIFT_REPORT_SECURITY_ISSUES) AS ALERTS_SHIFT_REPORT_SECURITY_ISSUES, CURRENT_TIMESTAMP() AS DWH_CREATED_TMSP,CURRENT_TIMESTAMP() AS DWH_UPDATED_TMSP \
	FROM (VALUES (:1,:2,:3,:4,:5,CURRENT_TIMESTAMP(),CURRENT_TIMESTAMP())) AS V1 (ALERTS_DAY_SHIFT_ID, ALERTS_SHIFT_REPORT_AGREEMENT_TXT, ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, ALERTS_SHIFT_REPORT_SECURITY_ISSUES,DWH_CREATED_TMSP, DWH_UPDATED_TMSP) \
	GROUP BY ALERTS_DAY_SHIFT_ID, DWH_CREATED_TMSP, DWH_UPDATED_TMSP) AS SRC1 \
	ON TGT1.ALERTS_DAY_SHIFT_ID = SRC1.ALERTS_DAY_SHIFT_ID \
	WHEN MATCHED THEN \
	UPDATE SET \
	TGT1.ALERTS_SHIFT_REPORT_AGREEMENT_TXT = SRC1.ALERTS_SHIFT_REPORT_AGREEMENT_TXT, \
	TGT1.ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT = SRC1.ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, \
	TGT1.ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT = SRC1.ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, \
	TGT1.ALERTS_SHIFT_REPORT_SECURITY_ISSUES = SRC1.ALERTS_SHIFT_REPORT_SECURITY_ISSUES, \
	TGT1.DWH_UPDATED_TMSP = SRC1.DWH_UPDATED_TMSP \
	WHEN NOT MATCHED THEN \
	INSERT (ALERTS_DAY_SHIFT_ID, ALERTS_SHIFT_REPORT_AGREEMENT_TXT, ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, ALERTS_SHIFT_REPORT_SECURITY_ISSUES, DWH_CREATED_TMSP, DWH_UPDATED_TMSP) \
	VALUES (SRC1.ALERTS_DAY_SHIFT_ID, SRC1.ALERTS_SHIFT_REPORT_AGREEMENT_TXT, SRC1.ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, SRC1.ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, SRC1.ALERTS_SHIFT_REPORT_SECURITY_ISSUES, SRC1.DWH_CREATED_TMSP, SRC1.DWH_UPDATED_TMSP) \
	";
   
	snowflake.execute({sqlText: sql_command,
	binds: [ALERTS_DAY_SHIFT_ID, ALERTS_SHIFT_REPORT_AGREEMENT_TXT, ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, ALERTS_SHIFT_REPORT_SECURITY_ISSUES].map(function(x){return x===undefined?null:x})});  

	var sql_commit ="COMMIT";
	snowflake.execute( {
    sqlText:sql_commit
	});
$$   
;