CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISVALIDBITFLAGUPDSEL"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  ZISVALIDBITFLAG = EKS_CALCULATION.SRMARA_EKS_ITEM_ZISVALIDBITFLAGUPDSEL.ZISVALIDBITFLAGNEW
FROM EKS_CALCULATION.SRMARA_EKS_ITEM_ZISVALIDBITFLAGUPDSEL
WHERE STMARA_EKS_ITEM.itemid = EKS_CALCULATION.SRMARA_EKS_ITEM_ZISVALIDBITFLAGUPDSEL.ITEMID;
END;
';