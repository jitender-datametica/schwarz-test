CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_SKROLLUP_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zNegotiatingCountry = sr.zNegotiatingCountryNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zNegotiatingCountry_SKRollup_UpdSel AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';