CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZZ_PACK_CONTENT_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zZZ_PACK_CONTENT = sr.zZZ_PACK_CONTENTNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_ZZ_PACK_CONTENT_UpdSel AS sr
WHERE EKS_CALCULATION.STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';