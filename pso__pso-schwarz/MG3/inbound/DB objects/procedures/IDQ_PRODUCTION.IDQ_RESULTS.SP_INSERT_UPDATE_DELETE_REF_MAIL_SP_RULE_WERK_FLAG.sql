CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_SP_RULE_WERK_FLAG("REF_MAIL_SP_RULE_WERK_FLAG_ID" NUMBER(38,0), "RULE_ID" NUMBER(38,0), "BRANCH_ID" NUMBER(38,0), "WERK_FLAG" NUMBER(38,0), "WG_FLAG" NUMBER(38,0), "MATART_FLAG" NUMBER(38,0), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE WERK_BRANCH_Comb_exist number(38,0);
BEGIN
WERK_BRANCH_Comb_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_FLAG WHERE RULE_ID = :RULE_ID and BRANCH_ID = :BRANCH_ID and WERK_FLAG = :WERK_FLAG and WG_FLAG = :WG_FLAG and MATART_FLAG = :WERK_FLAG);
   -- Delete from contact table for @REF_MAIL_SP_WERK_MAIL_ID if @DELETE equals 1
    IF (:DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_FLAG WHERE ID = :REF_MAIL_SP_RULE_WERK_FLAG_ID;
    --    RETURN 0;
   -- END IF;

    -- INSERT NEW WERK RULE COMBINATION
    elseIF (:DEL = 0 and :REF_MAIL_SP_RULE_WERK_FLAG_ID = 0 and WERK_BRANCH_Comb_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_FLAG
        (ID, RULE_ID, BRANCH_ID, WERK_FLAG, WG_FLAG, MATART_FLAG) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_FLAG),:RULE_ID, :BRANCH_ID, :WERK_FLAG, :WG_FLAG, :MATART_FLAG);
       -- RETURN 0;
        
  --  END IF;
    --	Merge into REF_MAIL_SP_RULE_WERK_FLAG
    else
    MERGE INTO IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_FLAG AS TARGET
    USING 
    (SELECT :REF_MAIL_SP_RULE_WERK_FLAG_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.WERK_FLAG <> :WERK_FLAG or TARGET.WERK_FLAG <> :WG_FLAG or TARGET.WERK_FLAG <> :MATART_FLAG THEN
            UPDATE SET WERK_FLAG = :WERK_FLAG, WG_FLAG = :WG_FLAG, MATART_FLAG = :MATART_FLAG;
            end if;
            commit;
            return 1;
END';


