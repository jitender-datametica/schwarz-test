CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_SP_WG("REF_MAIL_SP_WG_ID" NUMBER(38,0), "WG" VARCHAR(255), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE WG_exist number(38,0);
BEGIN
WG_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_SP_WG WHERE WG = :WG);
    IF (:DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_MAIL_SP_WG WHERE ID = :REF_MAIL_SP_WG_ID;
      --  RETURN 0;
   -- END IF;
   
    -- INSERT NEW WG
    elseIF (:REF_MAIL_SP_WG_ID = 0 AND :DEL = 0 and WG_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_MAIL_SP_WG
        (ID,WG) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_MAIL_SP_WG),:WG);
        -- RETURN 0;
    --END IF;
else 
    MERGE INTO IDQ_RESULTS.REF_MAIL_SP_WG AS TARGET
    USING 
    (SELECT :REF_MAIL_SP_WG_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.WG <> :WG THEN
            UPDATE SET WG = :WG;

            end if;
            commit;

            return 1;
END';


