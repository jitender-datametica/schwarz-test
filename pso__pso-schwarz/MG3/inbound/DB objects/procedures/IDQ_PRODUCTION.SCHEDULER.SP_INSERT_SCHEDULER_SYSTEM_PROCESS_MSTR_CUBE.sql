CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.SCHEDULER.SP_INSERT_SCHEDULER_SYSTEM_PROCESS_MSTR_CUBE("SYSTEM_PROCESS_ID" NUMBER(38,0), "CUBE_ID" VARCHAR(250))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    let entry_exist INTEGER := null;
    
    SELECT count(1) INTO :entry_exist
    FROM SCHEDULER.SYSTEM_PROCESS_MSTR_CUBE
        WHERE SYSTEM_PROCESS_ID = :SYSTEM_PROCESS_ID
        AND CUBE_ID = :CUBE_ID;
        
    IF (entry_exist > 0) THEN
        -- Cube already exists
        RETURN 0;
    END IF;
    
    INSERT INTO SCHEDULER.SYSTEM_PROCESS_MSTR_CUBE (SYSTEM_PROCESS_ID,CUBE_ID) VALUES (:SYSTEM_PROCESS_ID, :CUBE_ID);
    
    COMMIT;
    
END';