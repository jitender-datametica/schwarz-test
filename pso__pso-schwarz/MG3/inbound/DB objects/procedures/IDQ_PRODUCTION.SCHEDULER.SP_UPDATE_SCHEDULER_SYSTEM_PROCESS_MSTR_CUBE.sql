
CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.SCHEDULER.SP_UPDATE_SCHEDULER_SYSTEM_PROCESS_MSTR_CUBE("ID" NUMBER(38,0), "SYSTEM_PROCESS_ID" NUMBER(38,0), "CUBE_ID" VARCHAR(250), "DEL_FLAG" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    IF (:DEL_FLAG = 1) THEN
        DELETE FROM SCHEDULER.SYSTEM_PROCESS_MSTR_CUBE WHERE ID = :ID;
    END IF;
    UPDATE SCHEDULER.SYSTEM_PROCESS_MSTR_CUBE SET SYSTEM_PROCESS_ID = :SYSTEM_PROCESS_ID, CUBE_ID = :CUBE_ID WHERE ID = :ID;
    COMMIT;
END';
