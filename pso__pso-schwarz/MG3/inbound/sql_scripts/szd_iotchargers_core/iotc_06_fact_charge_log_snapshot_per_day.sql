  BEGIN TRANSACTION;

  DELETE FROM CORE.${TST_PREFIX}T_FACT_CHARGE_LOG_SNAPSHOT_PER_DAY;


  INSERT INTO CORE.${TST_PREFIX}T_FACT_CHARGE_LOG_SNAPSHOT_PER_DAY (REPORT_DT, CHARGER_PROVIDER_SYSTEM_CD, CHARGER_RESOURCE_ITEM_SID, CHARGE_POINT_RESOURCE_ITEM_SID, CHARGING_STATION_OWNER_PARTY_SID, REAL_ESTATE_RESOURCE_ITEM_SID, COUNTRY_LOCATION_SID, DIVISION_PARTY_SID, CHARGE_POINT_PLUGIN_TYPE_CD, CHARGE_POINT_POWER_TYPE_CD, CHARGER_STATION_TYPE_CD, AUTHENTICATION_METHOD_CD, ACTIVE_CHARGER_CNT, ACTIVE_CHARGE_POINT_CNT, DWH_CREATED_TMSP, DWH_UPDATED_TMSP)
  WITH
  TIMEFRAME AS (
      SELECT CAL_DT 
        FROM CORE.T_DIM_CAL_DAY C
      WHERE CAL_DT BETWEEN '2023-01-01' AND CURRENT_DATE
  )
  SELECT TF.CAL_DT AS REPORT_DT,
        COALESCE(CL.CHARGER_PROVIDER_SYSTEM_CD, '-1') AS CHARGER_PROVIDER_SYSTEM_CD,
        COALESCE(CL.CHARGER_RESOURCE_ITEM_SID, -1) AS CHARGER_RESOURCE_ITEM_SID,
        COALESCE(CL.CHARGE_POINT_RESOURCE_ITEM_SID, -1) AS CHARGE_POINT_RESOURCE_ITEM_SID,
        COALESCE(CHG.CHARGING_STATION_OWNER_PARTY_SID, -1) AS CHARGING_STATION_OWNER_PARTY_SID,
        COALESCE(CHG.REAL_ESTATE_RESOURCE_ITEM_SID, -1) AS REAL_ESTATE_RESOURCE_ITEM_SID,
        COALESCE(RES.COUNTRY_LOCATION_SID, -1) AS COUNTRY_LOCATION_SID,
        COALESCE(RES.DIVISION_PARTY_SID, -1) AS DIVISION_PARTY_SID,
        COALESCE(CPO.CHARGE_POINT_PLUGIN_TYPE_CD, '-1') AS CHARGE_POINT_PLUGIN_TYPE_CD,
        COALESCE(CPO.CHARGE_POINT_POWER_TYPE_CD, '-1') AS CHARGE_POINT_POWER_TYPE_CD,
        COALESCE(CHG.CHARGER_STATION_TYPE_CD, '-1') AS CHARGER_STATION_TYPE_CD,
        CASE WHEN UPPER(CPT.CHARGE_POINT_TARIFF_NAME) LIKE 'LIDL%'
              THEN 'LIDL-PLUS'
              WHEN UPPER(CPT.CHARGE_POINT_TARIFF_NAME) LIKE 'KAUFLAND%'
              THEN 'KFL-APP'
              WHEN CL.ROAMING_INTERFACE_CD = 'ENERGISED'
              THEN 'ICR'
              WHEN CL.ROAMING_INTERFACE_CD = 'COMMUNITY'
              THEN CASE WHEN UPPER(EMP.EMP_NAME) = 'VIRTUAL DIRECT PAYMENT PROVIDER'
                        THEN 'ADHOC'
                        ELSE 'RCOM'
                    END
              ELSE '-1'      
          END AS AUTHENTICATION_METHOD,
        CASE WHEN NULLIF(CL.CHARGER_RESOURCE_ITEM_SID, -1) IS NOT NULL THEN 1 ELSE 0 END AS ACTIVE_CHARGER_CNT,
        CASE WHEN NULLIF(CL.CHARGE_POINT_RESOURCE_ITEM_SID , -1) IS NOT NULL THEN 1 ELSE 0 END AS ACTIVE_CHARGE_POINT_CNT,
        CURRENT_TIMESTAMP AS DWH_CREATED_TMSP,
        CURRENT_TIMESTAMP AS DWH_UPDATED_TMSP
    FROM TIMEFRAME TF
    LEFT
    JOIN CORE_REL.T_CHARGE_LOG CL
      ON TO_DATE(CL.START_LOCAL_TMSP) = TF.CAL_DT 
    AND CL.METER_TOTAL_MEAS >= 0 
    AND CL.METER_TOTAL_MEAS < 150000
    AND TIMESTAMPDIFF(SECOND, CL.START_LOCAL_TMSP, CL.END_LOCAL_TMSP) > 0
    LEFT  
    JOIN CORE_REL.T_CHARGE_POINT_TARIFF CPT
      ON CL.CHARGE_POINT_TARIFF_ID = CPT.CHARGE_POINT_TARIFF_ID
    LEFT
    JOIN CORE_REL.T_ELECTRO_MOBILITY_PROVIDER EMP
      ON CL.EMP_PARTY_SID = EMP.PARTY_SID 
    LEFT
    JOIN CORE.T_DIM_CHARGER CHG
      ON CL.CHARGER_RESOURCE_ITEM_SID = CHG.RESOURCE_ITEM_SID 
    AND TF.CAL_DT BETWEEN CHG.DWH_VALID_FROM_TMSP AND CHG.DWH_VALID_TO_TMSP 
    LEFT
    JOIN CORE.T_DIM_REAL_ESTATE RES
      ON CHG.REAL_ESTATE_RESOURCE_ITEM_SID = RES.RESOURCE_ITEM_SID 
    AND TF.CAL_DT BETWEEN RES.DWH_VALID_FROM_TMSP AND RES.DWH_VALID_TO_TMSP 
    LEFT
    JOIN CORE.T_DIM_CHARGE_POINT CPO
      ON CL.CHARGE_POINT_RESOURCE_ITEM_SID = CPO.RESOURCE_ITEM_SID 
    AND TF.CAL_DT BETWEEN CPO.DWH_VALID_FROM_TMSP AND CPO.DWH_VALID_TO_TMSP
  GROUP
      BY ALL
  ;


  COMMIT;
