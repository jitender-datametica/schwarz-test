BEGIN TRANSACTION;

DELETE FROM CORE.${TST_PREFIX}T_FACT_CHARGE_POINT_SNAPSHOT_PER_DAY;

INSERT INTO CORE.${TST_PREFIX}T_FACT_CHARGE_POINT_SNAPSHOT_PER_DAY (REPORT_DT, CHARGER_PROVIDER_SYSTEM_CD, CHARGE_POINT_RESOURCE_ITEM_SID, CHARGER_RESOURCE_ITEM_SID, CHARGING_STATION_OWNER_PARTY_SID, REAL_ESTATE_RESOURCE_ITEM_SID, COUNTRY_LOCATION_SID, DIVISION_PARTY_SID, CHARGE_POINT_PLUGIN_TYPE_CD, CHARGE_POINT_POWER_TYPE_CD, CHARGER_STATION_TYPE_CD, AVAILABLE_CHARGE_POINT_CNT, DWH_CREATED_TMSP, DWH_UPDATED_TMSP)
WITH
TIMEFRAME AS (
    SELECT CAL_DT 
      FROM CORE.T_DIM_CAL_DAY C
     WHERE CAL_DT BETWEEN '2023-01-01' AND CURRENT_DATE
)
SELECT DISTINCT
       TF.CAL_DT AS REPORT_DT,
       COALESCE(CPO.CHARGER_PROVIDER_SYSTEM_CD, '-1') AS CHARGER_PROVIDER_SYSTEM_CD,
       COALESCE(CPO.RESOURCE_ITEM_SID, -1) AS CHARGE_POINT_RESOURCE_ITEM,
       COALESCE(CPO.CHARGER_RESOURCE_ITEM_SID, -1) AS CHARGER_RESOURCE_ITEM_SID,
       COALESCE(CHG.CHARGING_STATION_OWNER_PARTY_SID, -1) AS CHARGING_STATION_OWNER_PARTY_SID,
       COALESCE(CHG.REAL_ESTATE_RESOURCE_ITEM_SID, -1) AS REAL_ESTATE_RESOURCE_ITEM_SID,
       COALESCE(RES.COUNTRY_LOCATION_SID, -1) AS COUNTRY_LOCATION_SID,
       COALESCE(RES.DIVISION_PARTY_SID, -1) AS DIVISION_PARTY_SID,
       COALESCE(CPO.CHARGE_POINT_PLUGIN_TYPE_CD, '-1') AS CHARGE_POINT_PLUGIN_TYPE_CD,
       COALESCE(CPO.CHARGE_POINT_POWER_TYPE_CD, '-1') AS CHARGE_POINT_POWER_TYPE_CD,
       COALESCE(CHG.CHARGER_STATION_TYPE_CD, '-1') AS CHARGER_STATION_TYPE_CD,
       CASE WHEN CPO.RESOURCE_ITEM_SID IS NOT NULL THEN 1 ELSE 0 END AS AVAILABLE_CHARGE_POINT_CNT,
       CURRENT_TIMESTAMP AS DWH_CREATED_TMSP,
       CURRENT_TIMESTAMP AS DWH_UPDATED_TMSP
  FROM TIMEFRAME TF
  LEFT
  JOIN CORE.T_DIM_CHARGE_POINT CPO
    ON TF.CAL_DT BETWEEN CPO.DWH_VALID_FROM_TMSP AND CPO.DWH_VALID_TO_TMSP
   AND CPO.RESOURCE_ITEM_SID != -1
  LEFT
  JOIN CORE.T_DIM_CHARGER CHG
    ON CPO.CHARGER_RESOURCE_ITEM_SID = CHG.RESOURCE_ITEM_SID 
   AND TF.CAL_DT BETWEEN CHG.DWH_VALID_FROM_TMSP AND CHG.DWH_VALID_TO_TMSP
  LEFT
  JOIN CORE.T_DIM_REAL_ESTATE  RES
    ON CHG.REAL_ESTATE_RESOURCE_ITEM_SID  = RES.RESOURCE_ITEM_SID 
   AND TF.CAL_DT BETWEEN RES.DWH_VALID_FROM_TMSP AND RES.DWH_VALID_TO_TMSP
;

COMMIT;
