FIRST_VALUE(V01.LAENGENGRAD) OVER (PARTITION BY V01.mandant_id, aktuell_wup_id1 ORDER BY V01.dat_von DESC NULLS LAST) AS akt_laengengrad,

(1000 + V01.MANDANT_ID * 100 + V01.VS_ID * 10) * -1::INTEGER AS DUMMY

