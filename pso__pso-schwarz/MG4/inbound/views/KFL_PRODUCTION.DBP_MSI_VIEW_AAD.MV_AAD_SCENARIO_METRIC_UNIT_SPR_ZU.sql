create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_AAD.MV_AAD_SCENARIO_METRIC_UNIT_SPR_ZU(
	SCENARIO_METRIC_UNIT_ID,
	SCENARIO_METRIC_UNIT_DESCR,
	SCENARIO_METRIC_UNIT_DESCR_DE,
	SCENARIO_METRIC_UNIT_DESCR_CZ,
	SCENARIO_METRIC_UNIT_DESCR_SK,
	SCENARIO_METRIC_UNIT_DESCR_HR,
	SCENARIO_METRIC_UNIT_DESCR_PL,
	SCENARIO_METRIC_UNIT_DESCR_RO,
	SCENARIO_METRIC_UNIT_DESCR_BG
) as 
-- 30.06.2023 staeblern Erstellen Sprachtabelle AAD_SCENARIO_METRIC_UNIT
SELECT v01.SCENARIO_METRIC_UNIT_ID
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.SCENARIO_METRIC_UNIT_DESCR END),'N/A') AS SCENARIO_METRIC_UNIT_DESCR                      
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.SCENARIO_METRIC_UNIT_DESCR END),'N/A') AS SCENARIO_METRIC_UNIT_DESCR_DE                
,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.SCENARIO_METRIC_UNIT_DESCR END), SCENARIO_METRIC_UNIT_DESCR_DE) AS SCENARIO_METRIC_UNIT_DESCR_CZ
,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.SCENARIO_METRIC_UNIT_DESCR END), SCENARIO_METRIC_UNIT_DESCR_DE) AS SCENARIO_METRIC_UNIT_DESCR_SK
,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.SCENARIO_METRIC_UNIT_DESCR END), SCENARIO_METRIC_UNIT_DESCR_DE) AS SCENARIO_METRIC_UNIT_DESCR_HR
,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.SCENARIO_METRIC_UNIT_DESCR END), SCENARIO_METRIC_UNIT_DESCR_DE) AS SCENARIO_METRIC_UNIT_DESCR_PL
,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.SCENARIO_METRIC_UNIT_DESCR END), SCENARIO_METRIC_UNIT_DESCR_DE) AS SCENARIO_METRIC_UNIT_DESCR_RO
,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.SCENARIO_METRIC_UNIT_DESCR END), SCENARIO_METRIC_UNIT_DESCR_DE) AS SCENARIO_METRIC_UNIT_DESCR_BG

FROM dbp_view.v_AAD_SCENARIO_METRIC_UNIT_SPR_ZU v01
GROUP BY v01.SCENARIO_METRIC_UNIT_ID
;