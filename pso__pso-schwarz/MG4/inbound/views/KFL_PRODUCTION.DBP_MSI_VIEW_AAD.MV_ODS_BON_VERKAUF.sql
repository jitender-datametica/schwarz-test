create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_AAD.MV_ODS_BON_VERKAUF(
	BON_ID,
	BON_ZEILE,
	KL_ART_ID,
	EAN_KASSE,
	WG_ID,
	MENGE,
	EINH_ID,
	UMSATZ_BRUTTO,
	MWST_ID,
	ERFASSUNG_ID,
	AKTION_ID,
	MANDANT_ID,
	WUP_ID,
	TALON_ID,
	START_BON_ZEILE,
	BON_NR_EXTERN,
	KPOS_ERFASSUNG_ID,
	UMSATZ_BRUTTO_NORM,
	VK_BRUTTO_OBB,
	BON_VORGANG_ID,
	BARCODE_STRING,
	BARCODE_LEERGUT,
	BON_DAT
) as


   SELECT 
     v01.BON_ID
   , v01.BON_ZEILE
   , v01.KL_ART_ID
   , v01.EAN_KASSE
   , v01.WG_ID
   , v01.MENGE
   , v01.EINH_ID
   , v01.UMSATZ_BRUTTO
   , v01.MWST_ID
   , v01.ERFASSUNG_ID
   , v01.AKTION_ID
   , v01.MANDANT_ID
   , v02.aktuell_wup_id AS wup_id
   , v01.TALON_ID
   , v01.START_BON_ZEILE
   , v01.BON_NR_EXTERN
   , v01.KPOS_ERFASSUNG_ID
   , v01.UMSATZ_BRUTTO_NORM
   , v01.VK_BRUTTO_OBB
   , v01.BON_VORGANG_ID
   , v01.BARCODE_STRING
   , v01.BARCODE_LEERGUT 
   , v01.BON_DAT
   FROM dbp_v_ods.v_ods_bon_verkauf v01
   
INNER JOIN dbp_view.v_wup v02
ON v01.wup_id = v02.wup_id
AND v01.mandant_id = v02.mandant_id
;