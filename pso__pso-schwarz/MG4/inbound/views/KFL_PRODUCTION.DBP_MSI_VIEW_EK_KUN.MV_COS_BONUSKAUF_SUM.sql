create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_EK_KUN.MV_COS_BONUSKAUF_SUM(
	MANDANT_ID,
	BONUSKAUF_ID,
	KAMPAGNEN_ID,
	COUPON_TYP,
	AKTIONS_TYP,
	ANZ_ZIELGRUPPENGROESSE,
	AUSGESPIELTER_KANAL,
	ANZ_PUNKTE_ZU_ZAHLEND,
	ANZ_AKTIVIERUNGEN_KAUFBAR,
	ANZ_AKTIVIERUNGEN_NICHT_KAUFBAR,
	ANZ_AKTIVIERUNGEN,
	RATE_AKTIVIERUNGSQUOTE,
	ANZ_EINLOESUNGEN_KAUFBAR,
	ANZ_EINLOESUNGEN_NICHT_KAUFBAR,
	ANZ_EINLOESUNGEN,
	RATE_EINLOESEQUOTE,
	ANZ_GESAMT_PUNKTE_EINLOESUNGEN,
	ANZ_UNIQUE_KUNDEN,
	BETRAG_BONUSKAUF_UMSATZ_BRUTTO,
	BETRAG_BONUSKAUF_UMSATZ_NETTO,
	MENGE_PROMO
) as
SELECT
 MANDANT_ID
,BONUSKAUF_ID
,KAMPAGNEN_ID_LISTE_TXT AS KAMPAGNEN_ID
,COUPON_TYP_NAME AS COUPON_TYP
,AKTION_TYP_NAME AS AKTIONS_TYP
,ANZ_ZIELGRUPPENGROESSE
,KANAL_LISTE_TXT AS AUSGESPIELTER_KANAL
,ANZ_PUNKTE_COUPON_BENOETIGT AS ANZ_PUNKTE_ZU_ZAHLEND
,ANZ_AKTIVIERUNGEN_KAUFBAR
,ANZ_AKTIVIERUNGEN_NICHT_KAUFBAR
,ANZ_GESAMT_AKTIVIERUNGEN AS ANZ_AKTIVIERUNGEN
,RATE_AKTIVIERUNGSQUOTE
,ANZ_EINLOESUNGEN_KAUFBAR
,ANZ_EINLOESUNGEN_NICHT_KAUFBAR
,ANZ_GESAMT_EINLOESUNGEN AS ANZ_EINLOESUNGEN
,RATE_EINLOESEQUOTE
,ANZ_GESAMT_PUNKTE_EINLOESUNGEN
,ANZ_UNIQUE_KUNDEN
--,BETRAG_BONUSKAUF_UMSATZ_BRUTTO
--,BETRAG_BONUSKAUF_UMSATZ_BRUTTO_KONZ
--,BETRAG_BONUSKAUF_UMSATZ_NETTO
--,BETRAG_BONUSKAUF_UMSATZ_NETTO_KONZ

,CASE
WHEN v02.wrg_typ_id = 0 AND v01.mandant_id > 1 THEN CAST(v01.BETRAG_BONUSKAUF_UMSATZ_BRUTTO_KONZ AS NUMBER(38,5))
ELSE CAST(v01.BETRAG_BONUSKAUF_UMSATZ_BRUTTO AS NUMBER(38,5)) END BETRAG_BONUSKAUF_UMSATZ_BRUTTO
,CASE
WHEN v02.wrg_typ_id = 0 AND v01.mandant_id > 1 THEN CAST(v01.BETRAG_BONUSKAUF_UMSATZ_NETTO_KONZ AS NUMBER(38,5))
ELSE CAST(v01.BETRAG_BONUSKAUF_UMSATZ_NETTO AS NUMBER(38,5)) END BETRAG_BONUSKAUF_UMSATZ_NETTO

,MENGE_BONUSKAUF_BME AS MENGE_PROMO
FROM DBP_MSI_V_VIEW.V_COS_BONUSKAUF_SUM v01

CROSS JOIN dbp_msi.akt_msi_user_wrg_typ_zu v02
;