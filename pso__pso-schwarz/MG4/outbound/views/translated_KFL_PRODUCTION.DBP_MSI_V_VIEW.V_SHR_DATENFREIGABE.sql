CREATE OR REPLACE VIEW kfl_production_dbp_msi_v_view.v_shr_datenfreigabe(MANDANT_ID, KJMO, DAT, NAT_INT_FG, USER_ID, FREIGABE_UHRZEIT, SHR_FREIGABE_FG, DAT_FREIGABE_KENNZAHLEN) AS SELECT
    SHR_DATENFREIGABE.MANDANT_ID,
    SHR_DATENFREIGABE.KJMO,
    SHR_DATENFREIGABE.DAT,
    SHR_DATENFREIGABE.NAT_INT_FG,
    SHR_DATENFREIGABE.USER_ID,
    time(0, 0, CAST(SHR_DATENFREIGABE.FREIGABE_UHRZEIT / NUMERIC '1000' as INT64)) AS FREIGABE_UHRZEIT,
    SHR_DATENFREIGABE.SHR_FREIGABE_FG,
    SHR_DATENFREIGABE.DAT_FREIGABE_KENNZAHLEN
  FROM
    kfl_production_dbp_msi_data.shr_datenfreigabe
;
