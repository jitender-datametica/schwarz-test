create or replace view BIAID_TOOLS_PROJECTS_PRODUCTION.FE_MSTR_COSTMONITOR.V_IAM_AZURE_INVENTORY_FILE_LOG_LAST(
	INVENTORY_FILE_DATE,
	LOAD_TIMESTAMP,
	STORAGE_ACCOUNT_NAME,
	STORAGE_ACCOUNT_TENANT,
	STORAGE_ACCOUNT_ZONE
) as
with log as (select
  "INVENTORY_FILE_DATE",
  "LOAD_TIMESTAMP",
  "STATUS",
  "STORAGE_ACCOUNT_NAME",
  "STORAGE_ACCOUNT_TENANT",
  "STORAGE_ACCOUNT_ZONE"
from "ETL_PROCESS".T_IAM_AZURE_INVENTORY_FILE_LOG
qualify    row_number() over (
     partition by
      "INVENTORY_FILE_DATE",
      "STORAGE_ACCOUNT_NAME",
      "STORAGE_ACCOUNT_TENANT",
      "STORAGE_ACCOUNT_ZONE"
     order by "LOAD_TIMESTAMP" desc
   ) = 1
)
select
  "INVENTORY_FILE_DATE",
  "LOAD_TIMESTAMP",
  "STORAGE_ACCOUNT_NAME",
  "STORAGE_ACCOUNT_TENANT",
  "STORAGE_ACCOUNT_ZONE"
from log
where status = 'SUCCESS'
qualify
    row_number() over (
     partition by
      "STORAGE_ACCOUNT_NAME",
      "STORAGE_ACCOUNT_TENANT",
      "STORAGE_ACCOUNT_ZONE"
     order by "INVENTORY_FILE_DATE" desc
   ) = 1;