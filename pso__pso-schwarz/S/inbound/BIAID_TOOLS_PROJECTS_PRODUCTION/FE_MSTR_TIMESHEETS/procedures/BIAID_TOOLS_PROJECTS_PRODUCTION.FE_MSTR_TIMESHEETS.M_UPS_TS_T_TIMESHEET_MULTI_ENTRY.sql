CREATE OR REPLACE PROCEDURE BIAID_TOOLS_PROJECTS_PRODUCTION.FE_MSTR_TIMESHEETS.M_UPS_TS_T_TIMESHEET_MULTI_ENTRY("P_ACTUAL_APPROVER_NAME" VARCHAR(100), "P_TIMESHEET_ENTRY_STATUS" VARCHAR(20), "P_PSP_ELEMENT_CD" VARCHAR(50), "P_INTENDED_APPROVER_NAME" VARCHAR(100), "P_MIN_DATE" VARCHAR(16777216), "P_MAX_DATE" VARCHAR(16777216), "P_EXTERNAL_EMPLOYEE_FULL_NAME" VARCHAR(100), "P_EXTERNAL_SUPPLIER_NAME" VARCHAR(100))
RETURNS VARCHAR(16777216)
LANGUAGE SQL
COMMENT='Update T_TIMESHEET_ENTRY (Excel Upload Leistungsnachweis) mit Prüfstatus und Kommentar '
EXECUTE AS OWNER
AS '
DECLARE
dummy NUMBER;

BEGIN

 UPDATE BIAID_TOOLS_PROJECTS_PRODUCTION.FE_MSTR_TIMESHEETS.T_TIMESHEET_ENTRY
 SET
   ACTUAL_APPROVER_NAME				=	:P_ACTUAL_APPROVER_NAME
 , TIMESHEET_ENTRY_STATUS			=	:P_TIMESHEET_ENTRY_STATUS
 WHERE
	 PSP_ELEMENT_CD					=	:P_PSP_ELEMENT_CD
 AND INTENDED_APPROVER_NAME			=	:P_INTENDED_APPROVER_NAME
 AND EXTERNAL_EMPLOYEE_FULL_NAME	=	:P_EXTERNAL_EMPLOYEE_FULL_NAME
 AND EXTERNAL_SUPPLIER_NAME			=	:P_EXTERNAL_SUPPLIER_NAME
 AND TIMESHEET_ENTRY_DT BETWEEN :P_MIN_DATE AND :P_MAX_DATE
 ;

COMMIT;

RETURN ''Update T_TIMESHEET_ENTRY durchgeführt'';
END;
;
';