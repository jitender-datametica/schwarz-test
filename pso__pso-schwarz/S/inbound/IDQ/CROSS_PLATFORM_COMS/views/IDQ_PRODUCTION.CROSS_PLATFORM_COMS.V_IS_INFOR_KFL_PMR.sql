create or replace view IDQ_PRODUCTION.CROSS_PLATFORM_COMS.V_IS_INFOR_KFL_PMR(
	TIMEADDED_IS_INFOR_VIEW
) as
SELECT MIN(MIN_INSERT) as TimeAdded FROM
(
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_EXP_STS
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_EXT_XR
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_TRM_PRD
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_PROD
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_PROD_EXT_XR
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_PRODT
);