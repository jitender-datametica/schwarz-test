create or replace view IDQ_PRODUCTION.DWH.CHECK_DQ_BY_FIELD(
	CHECK_DQ_BY_FIELD_ID,
	REF_FIELD_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	CHECK_DQ_BY_FIELD_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	SCORE,
	TEST_OBJECT_AMOUNT,
	IS_USABLE,
	CHECK_DQ_BY_FIELD_IS_CURRENT
) as
SELECT 1                        AS CHECK_DQ_BY_FIELD_ID
      ,FIELD_ID               AS REF_FIELD_ID
	    ,SOURCE_SYSTEM_ID       AS REF_SOURCE_SYSTEM_ID
      ,BRANCH_ID              AS REF_BRANCH_ID
      ,COUNTRY_ID             AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_TYPE_ID  AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID    AS REF_TEST_OBJECT_TYPE_ID
      ,CALCULATION_TIME       AS CHECK_DQ_BY_FIELD_CALCULATION_TIME
	    ,CALCULATION_DAY_ID     AS REF_TIME_CALCULATION_DAY_ID
      ,SCORE                  AS SCORE
      ,TEST_OBJECT_AMOUNT     AS TEST_OBJECT_AMOUNT
      ,IS_USABLE              AS IS_USABLE
      ,1                        AS CHECK_DQ_BY_FIELD_IS_CURRENT
FROM idq_results.CHECK_DQ_BY_FIELD_CURRENT
UNION ALL
SELECT 1                        AS CHECK_DQ_BY_FIELD_ID
      ,FIELD_ID               AS REF_FIELD_ID
	    ,SOURCE_SYSTEM_ID       AS REF_SOURCE_SYSTEM_ID
      ,BRANCH_ID              AS REF_BRANCH_ID
      ,COUNTRY_ID             AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_TYPE_ID  AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID    AS REF_TEST_OBJECT_TYPE_ID
      ,CALCULATION_TIME       AS CHECK_DQ_BY_FIELD_CALCULATION_TIME
	    ,CALCULATION_DAY_ID     AS REF_TIME_CALCULATION_DAY_ID
      ,SCORE                  AS SCORE
      ,TEST_OBJECT_AMOUNT     AS TEST_OBJECT_AMOUNT
      ,IS_USABLE              AS IS_USABLE
      ,0                        AS CHECK_DQ_BY_FIELD_IS_CURRENT
FROM idq_results.CHECK_DQ_BY_FIELD_HISTORICAL
 ;