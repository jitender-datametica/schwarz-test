create or replace view IDQ_PRODUCTION.DWH.CHECK_HISTORY(
	CHECK_HISTORY_ID,
	CHECK_HISTORY_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	TEST_OBJECT_AMOUNT,
	REL_TEST_OBJECT_AMOUNT,
	CHECK_TEST_OBJECT_AMOUNT,
	AVG_SCORE,
	RULE_AMOUNT,
	FIELD_AMOUNT,
	ERROR_FREE_TO_AMOUNT,
	USABLE_TO_AMOUNT,
	UNUSABLE_TO_AMOUNT,
	ERROR_AMOUNT,
	SOLVED_ERROR_AMOUNT,
	OVERDUE_AMOUNT,
	NEW_ERROR_AMOUNT,
	FLIP_ERROR_AMOUNT,
	NEWLY_SOLVED_ERROR_AMOUNT,
	CHECK_HISTORY_IS_CURRENT
) as
SELECT 1                           AS CHECK_HISTORY_ID
      ,CALCULATION_TIME          AS CHECK_HISTORY_CALCULATION_TIME
      ,CALCULATION_DAY_ID        AS REF_TIME_CALCULATION_DAY_ID
      ,SOURCE_SYSTEM_ID          AS REF_SOURCE_SYSTEM_ID
      ,BRANCH_ID                 AS REF_BRANCH_ID
      ,COUNTRY_ID                AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
      ,TEST_OBJECT_AMOUNT        AS TEST_OBJECT_AMOUNT
      ,REL_TEST_OBJECT_AMOUNT    AS REL_TEST_OBJECT_AMOUNT
      ,CHECK_TEST_OBJECT_AMOUNT  AS CHECK_TEST_OBJECT_AMOUNT
      ,AVG_SCORE                 AS AVG_SCORE
      ,RULE_AMOUNT               AS RULE_AMOUNT
      ,FIELD_AMOUNT              AS FIELD_AMOUNT
      ,ERROR_FREE_TO_AMOUNT      AS ERROR_FREE_TO_AMOUNT
      ,USABLE_TO_AMOUNT          AS USABLE_TO_AMOUNT
      ,UNUSABLE_TO_AMOUNT        AS UNUSABLE_TO_AMOUNT
      ,ERRORS_AMOUNT             AS ERROR_AMOUNT
      ,SOLVED_ERRORS_AMOUNT      AS SOLVED_ERROR_AMOUNT
      ,OVERDUE_AMOUNT            AS OVERDUE_AMOUNT
      ,NEW_ERROR_AMOUNT          AS NEW_ERROR_AMOUNT
      ,FLIP_ERROR_AMOUNT         AS FLIP_ERROR_AMOUNT
      ,NEWLY_SOLVED_ERROR_AMOUNT AS NEWLY_SOLVED_ERROR_AMOUNT
      ,1                           AS CHECK_HISTORY_IS_CURRENT
FROM idq_results.CHECK_HISTORY_CURRENT
UNION ALL
SELECT 1                           AS CHECK_HISTORY_ID
      ,CALCULATION_TIME          AS CHECK_HISTORY_CALCULATION_TIME
      ,CALCULATION_DAY_ID        AS REF_TIME_CALCULATION_DAY_ID
      ,SOURCE_SYSTEM_ID          AS REF_SOURCE_SYSTEM_ID
      ,BRANCH_ID                 AS REF_BRANCH_ID
      ,COUNTRY_ID                AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
      ,TEST_OBJECT_AMOUNT        AS TEST_OBJECT_AMOUNT
      ,REL_TEST_OBJECT_AMOUNT    AS REL_TEST_OBJECT_AMOUNT
      ,CHECK_TEST_OBJECT_AMOUNT  AS CHECK_TEST_OBJECT_AMOUNT
      ,AVG_SCORE                 AS AVG_SCORE
      ,RULE_AMOUNT               AS RULE_AMOUNT
      ,FIELD_AMOUNT              AS FIELD_AMOUNT
      ,ERROR_FREE_TO_AMOUNT      AS ERROR_FREE_TO_AMOUNT
      ,USABLE_TO_AMOUNT          AS USABLE_TO_AMOUNT
      ,UNUSABLE_TO_AMOUNT        AS UNUSABLE_TO_AMOUNT
      ,ERRORS_AMOUNT             AS ERROR_AMOUNT
      ,SOLVED_ERRORS_AMOUNT      AS SOLVED_ERROR_AMOUNT
      ,OVERDUE_AMOUNT            AS OVERDUE_AMOUNT
      ,NEW_ERROR_AMOUNT          AS NEW_ERROR_AMOUNT
      ,FLIP_ERROR_AMOUNT         AS FLIP_ERROR_AMOUNT
      ,NEWLY_SOLVED_ERROR_AMOUNT AS NEWLY_SOLVED_ERROR_AMOUNT
      ,0                           AS CHECK_HISTORY_IS_CURRENT
FROM idq_results.CHECK_HISTORY_HISTORICAL
;