create or replace view IDQ_PRODUCTION.DWH.DPL_CHECK_HISTORY_EXTENDED(
	DPL_CHECK_HISTORY_EXTENDED_ID,
	REF_DPL_CHECK_DEFINITION_ID,
	DPL_CHECK_EXECUTION_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	DPL_CHECK_HISTORY_EXTENDED_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	TOTAL_AMOUNT_FOR_EXECUTION,
	CLUSTER_AMOUNT_TOTAL_FOR_EXECUTION,
	SCOPE_SPECIFIC_CLUSTER_AMOUNT,
	SCOPE_SPECIFIC_DUPLICATE_AMOUNT,
	SCOPE_NON_SPECIFIC_CLUSTER_AMOUNT,
	SCOPE_NON_SPECIFIC_DUPLICATE_AMOUNT,
	DPL_CHECK_HISTORY_EXTENDED_IS_CURRENT
) as
SELECT ID										AS DPL_CHECK_HISTORY_EXTENDED_ID
      ,DPL_CHECK_DEFINITION_ID				AS REF_DPL_CHECK_DEFINITION_ID
      ,DPL_CHECK_EXECUTION_ID					AS DPL_CHECK_EXECUTION_ID
      ,SOURCE_SYSTEM_ID						AS REF_SOURCE_SYSTEM_ID
      ,COUNTRY_ID								AS REF_COUNTRY_ID
      ,BRANCH_ID								AS REF_BRANCH_ID
      ,SOURCE_SYSTEM_TYPE_ID					AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID					AS REF_TEST_OBJECT_TYPE_ID
      ,TEST_TIME								AS DPL_CHECK_HISTORY_EXTENDED_CALCULATION_TIME
	  ,TEST_DAY_ID							AS REF_TIME_CALCULATION_DAY_ID
      ,TOTAL_AMOUNT_FOR_EXECUTION				AS TOTAL_AMOUNT_FOR_EXECUTION
      ,CLUSTER_AMOUNT_TOTAL_FOR_EXECUTION		AS CLUSTER_AMOUNT_TOTAL_FOR_EXECUTION
      ,SCOPE_SPECIFIC_CLUSTER_AMOUNT			AS SCOPE_SPECIFIC_CLUSTER_AMOUNT
      ,SCOPE_SPECIFIC_DUPLICATE_AMOUNT		AS SCOPE_SPECIFIC_DUPLICATE_AMOUNT
      ,SCOPE_NON_SPECIFIC_CLUSTER_AMOUNT		AS SCOPE_NON_SPECIFIC_CLUSTER_AMOUNT
      ,SCOPE_NON_SPECIFIC_DUPLICATE_AMOUNT	AS SCOPE_NON_SPECIFIC_DUPLICATE_AMOUNT
      ,IS_CURRENT								AS DPL_CHECK_HISTORY_EXTENDED_IS_CURRENT
FROM idq_results.DPL_CHECK_HISTORY_EXTENDED
;