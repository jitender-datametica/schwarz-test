create or replace view IDQ_PRODUCTION.DWH.MSTR_CUBE(
	CUBE_ID,
	MSTR_CUBE_ID,
	MSTR_PROJECT_ID,
	MSTR_CUBE_NAME,
	REF_SOURCE_SYSTEM_TYPE_ID
) as
SELECT
    ID                              AS CUBE_ID
	,MSTR_CUBE_ID                   AS MSTR_CUBE_ID
    ,MSTR_PROJECT_ID                AS MSTR_PROJECT_ID
	,MSTR_CUBE_NAME                 AS MSTR_CUBE_NAME
    ,SOURCE_SYSTEM_TYPE_ID          AS REF_SOURCE_SYSTEM_TYPE_ID

FROM SCHEDULER.MSTR_CUBE
;