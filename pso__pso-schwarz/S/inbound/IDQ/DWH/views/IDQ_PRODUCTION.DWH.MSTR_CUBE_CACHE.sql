create or replace view IDQ_PRODUCTION.DWH.MSTR_CUBE_CACHE(
	ID_ENCODED,
	PROJECT_ID,
	CREATOR_NAME,
	CUBE_DEFINITION_ID,
	CUBE_NAME,
	CREATED_TIMESTAMP,
	LAST_UPDATED_TIMESTAMP,
	HAS_DUPLICATE
) as
SELECT MHCC.ID_ENCODED                AS ID_ENCODED,
       MHCC.PROJECT_ID                AS PROJECT_ID,
       MHCC.CREATOR_NAME              AS CREATOR_NAME,
       MHCC.CUBE_DEFINITION_ID        AS CUBE_DEFINITION_ID,
       MHCC.CUBE_NAME                 AS CUBE_NAME,
       MHCC.CREATED_TIMESTAMP         AS CREATED_TIMESTAMP,
       MHCC.LAST_UPDATED_TIMESTAMP    AS LAST_UPDATED_TIMESTAMP,
       CASE
       WHEN  MHCC.CACHE_COUNT > 1
              THEN 1
              ELSE 0
       END as HAS_DUPLICATE
FROM
        idq_results.MSTR_HELPER_CUBE_CACHE MHCC;