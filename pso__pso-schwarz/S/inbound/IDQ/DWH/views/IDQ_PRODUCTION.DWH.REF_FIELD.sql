create or replace view IDQ_PRODUCTION.DWH.REF_FIELD(
	REF_FIELD_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	SOURCE_TABLE,
	FIELD_TECHNICAL_NAME,
	FIELD_NAME,
	FIELD_NAME_DE,
	FIELD_NAME_EN
) as
SELECT ID                      AS REF_FIELD_ID
      ,SOURCE_SYSTEM_TYPE_ID	 AS REF_SOURCE_SYSTEM_TYPE_ID
      ,SOURCE_TABLE			 AS SOURCE_TABLE
      ,TECHNICAL_NAME			 AS FIELD_TECHNICAL_NAME
	  ,NAME_DE				 AS FIELD_NAME
      ,NAME_DE				 AS FIELD_NAME_DE
      ,NAME_EN				 AS FIELD_NAME_EN
FROM idq_results.REF_FIELD
;