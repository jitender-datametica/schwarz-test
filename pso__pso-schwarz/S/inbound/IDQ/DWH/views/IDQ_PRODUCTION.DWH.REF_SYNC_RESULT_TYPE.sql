create or replace view IDQ_PRODUCTION.DWH.REF_SYNC_RESULT_TYPE(
	REF_SYNC_RESULT_TYPE_ID,
	SYNC_RESULT_TYPE_TECHNICAL_NAME,
	SYNC_RESULT_TYPE_NAME,
	SYNC_RESULT_TYPE_NAME_DE,
	SYNC_RESULT_TYPE_NAME_EN
) as
SELECT ID                   AS REF_SYNC_RESULT_TYPE_ID
      ,SYNC_FIELD_RESULT    AS SYNC_RESULT_TYPE_TECHNICAL_NAME
      ,SYNC_FIELD_RESULT	  AS SYNC_RESULT_TYPE_NAME
      ,SYNC_FIELD_RESULT	  AS SYNC_RESULT_TYPE_NAME_DE
      ,SYNC_FIELD_RESULT	  AS SYNC_RESULT_TYPE_NAME_EN
FROM idq_results.REF_SYNC_RESULT_TYPE
;