create or replace view IDQ_PRODUCTION.DWH.RELEVANCE_EXECUTION(
	RELEVANCE_EXECUTION_ID,
	RELEVANCE_EXECUTION_CALCULATION_TIME,
	REF_RELEVANCE_DEFINITION_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_BRANCH_ID,
	REF_TEST_OBJECT_TYPE_ID
) as
SELECT RE.ID                       AS RELEVANCE_EXECUTION_ID
      ,RE.TEST_TIME                AS RELEVANCE_EXECUTION_CALCULATION_TIME
      ,RE.RELEVANCE_DEFINITION_ID  AS REF_RELEVANCE_DEFINITION_ID
      ,RE.SOURCE_SYSTEM_ID         AS REF_SOURCE_SYSTEM_ID
      ,RE.COUNTRY_ID               AS REF_COUNTRY_ID
	  ,RD.SOURCE_SYSTEM_TYPE_ID    AS REF_SOURCE_SYSTEM_TYPE_ID
	  ,RD.BRANCH_ID                AS REF_BRANCH_ID
	  ,RD.TEST_OBJECT_TYPE_ID      AS REF_TEST_OBJECT_TYPE_ID
FROM idq_results.RELEVANCE_EXECUTION  RE
INNER JOIN idq_results.REF_RELEVANCE_DEFINITION RD
  ON RE.RELEVANCE_DEFINITION_ID = RD.ID
;