create or replace view IDQ_PRODUCTION.DWH.RELEVANCE_EXECUTION_PARAMETER(
	RELEVANCE_EXECUTION_PARAMETER_ID,
	RELEVANCE_EXECUTION_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_REL_RULE_MAPPLET_PARAMETER_ID,
	VALUE
) as
SELECT ID                            AS RELEVANCE_EXECUTION_PARAMETER_ID
      ,RELEVANCE_EXECUTION_ID        AS RELEVANCE_EXECUTION_ID
      ,COUNTRY_ID    		           AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_ID              AS REF_SOURCE_SYSTEM_ID
      ,REL_RULE_MAPPLET_PARAMETER_ID AS REF_REL_RULE_MAPPLET_PARAMETER_ID
      ,VALUE    		               AS VALUE
FROM idq_results.RELEVANCE_EXECUTION_PARAMETER
;