create or replace view IDQ_PRODUCTION.DWH.REPORTING_TEST_RESULT(
	REPORTING_TEST_RESULT_ID,
	IDQ_TEST_OBJECT_ID,
	REF_RULE_ID,
	IN_REPORT_INCLUDED,
	FIRST_INCLUDE,
	FIRST_EXCLUDE,
	REF_TIME_FIRST_INCLUDE_DAY_ID,
	REF_TIME_FIRST_EXCLUDE_DAY_ID,
	REF_FIELD_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_TEST_OBJECT_TYPE_ID,
	REF_DIMENSION_ID,
	REF_SOURCE_SYSTEM_ID
) as SELECT ROW_NUMBER() OVER (ORDER BY REF_TIME_FIRST_INCLUDE_DAY_ID, IDQ_TEST_OBJECT_ID,REF_RULE_ID) AS REPORTING_TEST_RESULT_ID, *
FROM (
SELECT
      RTR.TEST_OBJECT_ID			AS IDQ_TEST_OBJECT_ID
      ,RTR.RULE_ID				AS REF_RULE_ID
      ,RTR.IN_REPORT_INCLUDED		AS IN_REPORT_INCLUDED
      ,RTR.FIRST_INCLUDE			AS FIRST_INCLUDE
      ,RTR.FIRST_EXCLUDE			AS FIRST_EXCLUDE
      ,RTR.FIRST_INCLUDE_DAY_ID	AS REF_TIME_FIRST_INCLUDE_DAY_ID
      ,RTR.FIRST_EXCLUDE_DAY_ID	AS REF_TIME_FIRST_EXCLUDE_DAY_ID
      ,RR.FIELD_ID				AS REF_FIELD_ID
      ,RSS.SOURCE_SYSTEM_TYPE_ID	AS REF_SOURCE_SYSTEM_TYPE_ID
      ,ITO.BRANCH_ID				AS REF_BRANCH_ID
      ,ITO.COUNTRY_ID				AS REF_COUNTRY_ID
      ,ITO.TEST_OBJECT_TYPE_ID	AS REF_TEST_OBJECT_TYPE_ID
	  ,RR.DIMENSION_ID			AS REF_DIMENSION_ID
	  ,ITO.SOURCE_SYSTEM_ID		AS REF_SOURCE_SYSTEM_ID
FROM idq_results.REPORTING_TEST_RESULT_CURRENT RTR
INNER JOIN idq_results.REF_RULE RR
  ON RTR.RULE_ID = RR.ID
INNER JOIN idq_results.IDQ_TEST_OBJECT ITO
  ON RTR.TEST_OBJECT_ID = ITO.ID
INNER JOIN idq_results.REF_SOURCE_SYSTEM RSS
  ON ITO.SOURCE_SYSTEM_ID = RSS.ID

 ) REPORTING_TEST_RESULT
;