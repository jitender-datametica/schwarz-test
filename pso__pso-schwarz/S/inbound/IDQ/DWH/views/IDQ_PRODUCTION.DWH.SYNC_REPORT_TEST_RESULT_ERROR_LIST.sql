create or replace view IDQ_PRODUCTION.DWH.SYNC_REPORT_TEST_RESULT_ERROR_LIST(
	LEADING_PRIMARY_KEY,
	SOURCE_TABLE,
	TECHNICAL_NAME,
	NAME_DE,
	IS_ERROR_DETECTED,
	LEADING_FIELD_VALUE,
	DEPENDENT_FIELD_VALUE,
	SYNC_REPORT_EXECUTION_ID,
	DEPENDENT_SOURCE_TABLE,
	DEPENDENT_TECHNICAL_NAME,
	DEPENDENT_FIELD_NAME_DE,
	FUNCTIONAL_FIELD_NAME,
	COUNTRY_ID,
	COUNTRY
) as
SELECT  SRRR.LEADING_PRIMARY_KEY         AS LEADING_PRIMARY_KEY
       ,RF.SOURCE_TABLE                  AS SOURCE_TABLE
	   ,RF.TECHNICAL_NAME                AS TECHNICAL_NAME
	   ,RF.NAME_DE                       AS NAME_DE
	   ,SRTR.IS_ERROR_DETECTED           AS IS_ERROR_DETECTED
	   ,SRTR.LEADING_FIELD_VALUE         AS LEADING_FIELD_VALUE
	   ,SRTR.DEPENDENT_FIELD_VALUE       AS DEPENDENT_FIELD_VALUE
	   ,SRE.ID                           AS SYNC_REPORT_EXECUTION_ID
	   ,RF_DEP.SOURCE_TABLE              AS DEPENDENT_SOURCE_TABLE
	   ,RF_DEP.TECHNICAL_NAME            AS DEPENDENT_TECHNICAL_NAME
	   ,RF_DEP.NAME_DE                   AS DEPENDENT_FIELD_NAME_DE
	   ,RSRFF.FUNCTIONAL_FIELD_NAME      AS FUNCTIONAL_FIELD_NAME
	   ,RC.ID                            AS COUNTRY_ID
	   ,RC.COUNTRY                       AS COUNTRY

FROM            idq_results.REF_SYNC_REPORT_DEFINITION RSRD
     INNER JOIN idq_results.SYNC_REPORT_EXECUTION SRE
	    ON RSRD.ID = SRE.SYNC_REPORT_DEFINITION_ID
	 INNER JOIN idq_results.REF_COUNTRY RC
	    ON SRE.COUNTRY_ID = RC.ID
     INNER JOIN idq_results.REF_SYNC_REL_FIELD_FIELD RSRFF
	   ON RSRD.ID = RSRFF.SYNC_REPORT_DEFINITION_ID
	 INNER JOIN idq_results.REF_FIELD RF
	   ON RSRFF.LEADING_FIELD_ID = RF.ID
	 INNER JOIN idq_results.REF_FIELD RF_DEP
	   ON RSRFF.DEPENDENT_FIELD_ID = RF_DEP.ID
     INNER JOIN idq_results.SYNC_REPORT_TEST_RESULT SRTR
	   ON  RSRFF.ID=SRTR.SYNC_REL_FIELD_FIELD_ID
	 INNER JOIN idq_results.SYNC_REPORT_RECORD_RESULT SRRR
	   ON      SRTR.SYNC_REPORT_RECORD_RESULT_ID = SRRR.ID
	       AND SRE.ID = SRRR.SYNC_REPORT_EXECUTION_ID
WHERE SRE.IS_CURRENT = 1
;