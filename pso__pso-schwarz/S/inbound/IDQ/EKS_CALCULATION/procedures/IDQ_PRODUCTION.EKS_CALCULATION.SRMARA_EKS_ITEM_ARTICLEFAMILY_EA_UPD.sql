CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ARTICLEFAMILY_EA_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  ArticleFamily = sr.ArticleFamilyNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_ArticleFamily_EA_UpdSel AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';