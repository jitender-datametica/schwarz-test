CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_BUYERID_FIRSTNAME_LASTNAME_SKROLLUP_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  BuyerID = sr.BuyerIDNew, BuyerFirstName = sr.BuyerFirstNameNew, BuyerLastName = sr.BuyerLastNameNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_BuyerID_FirstName_LastName_SKRollup_UpdSel AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';