CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_LOCATION_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX 
SET  CR_LOCATIONID = sr.CR_LOCATIONIDNew, LOCATION = sr.LOCATIONNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_LISTINGOVERVIEWMAX_LOCATION_UpdSel AS sr
WHERE 
EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = sr.LISTINGOVERVIEWID
AND
EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.RECEIVINGCOUNTRY = sr.RECEIVINGCOUNTRY
AND
EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = sr.ITEMID
And
EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.Casesize = sr.casesize

;
END;
';