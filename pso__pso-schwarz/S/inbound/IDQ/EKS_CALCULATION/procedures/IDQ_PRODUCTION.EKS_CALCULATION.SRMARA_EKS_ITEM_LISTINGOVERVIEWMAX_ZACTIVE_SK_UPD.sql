CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_SK_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX 
SET  zActive = sr.zActiveNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_LISTINGOVERVIEWMAX_zActive_SK_UpdSel AS sr
WHERE EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = sr.LISTINGOVERVIEWID
AND
EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry = sr.RECEIVINGCOUNTRY
AND
EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = sr.ITEMID;
END;
';