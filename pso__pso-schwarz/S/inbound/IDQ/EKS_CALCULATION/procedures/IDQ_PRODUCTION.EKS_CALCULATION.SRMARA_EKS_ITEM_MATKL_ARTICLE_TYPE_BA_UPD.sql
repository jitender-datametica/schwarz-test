CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_BA_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zMATKL = sr.zMATKLNew, zLegacyMATKL = zLegacyMATKLNEW
FROM EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_BA_UpdSel AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';