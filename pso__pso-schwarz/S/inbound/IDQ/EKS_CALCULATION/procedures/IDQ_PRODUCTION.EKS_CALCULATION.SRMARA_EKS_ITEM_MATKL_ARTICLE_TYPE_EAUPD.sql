CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_EAUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zMATKL = sr.zMATKLNew
FROM EKS_CALCULATION.SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_EAUPDSEL AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';