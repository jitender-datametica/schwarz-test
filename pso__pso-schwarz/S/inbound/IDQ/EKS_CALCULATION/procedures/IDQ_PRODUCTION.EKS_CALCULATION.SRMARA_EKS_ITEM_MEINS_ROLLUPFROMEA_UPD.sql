CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_MEINS_ROLLUPFROMEA_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zMEINS = sr.zMEINSNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_MEINS_RollupFromEA_UpdSel AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';