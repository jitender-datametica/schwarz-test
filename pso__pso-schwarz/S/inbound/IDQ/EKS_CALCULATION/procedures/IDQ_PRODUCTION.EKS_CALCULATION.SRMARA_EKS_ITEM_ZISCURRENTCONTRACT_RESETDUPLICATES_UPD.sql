CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISCURRENTCONTRACT_RESETDUPLICATES_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zIsCurrentContract = sr.zIsCurrentContractNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zIsCurrentContract_ResetDuplicates_UpdSel AS sr
WHERE EKS_CALCULATION.STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';