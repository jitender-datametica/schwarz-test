CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISSKHASBAUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zIsSKhasBA = sr.zIsSKhasBANew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zIsSKhasBAUpdSel AS sr
WHERE EKS_CALCULATION.STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';