CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZLEGACYMATNRUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM 
SET  zLegacyMATNR = sr.zLegacyMATNRNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zLegacyMATNRUpdSel AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';