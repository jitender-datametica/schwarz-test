create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ARTICLEFAMILY_EA_UPDSEL(
	ITEMID,
	LEVEL_1,
	LEVEL_2,
	ARTICLEFAMILY,
	ARTICLEFAMILYNEW
) as
SELECT Distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS.ITEMGRPTIMELINE.SHORTDESC                       AS Level_1,
         stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC                AS Level_2,
         EKS_CALCULATION.STMARA_EKS_ITEM.ArticleFamily,
         --ISNULL(dbo.stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC || N'.' || DSW.dbo.boarj0(dbo.stEKS_ITEMGRPTIMELINE.SHORTDESC, 3), N'') AS ArticleFamilyNew
         IFNULL(stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC
                || '.' || EKS.ITEMGRPTIMELINE.SHORTDESC, '') AS ArticleFamilyNew,
  FROM   EKS.ITEMGRPTIMELINE
         INNER JOIN EKS.ITEMGROUPITEMREL
                 ON EKS.ITEMGRPTIMELINE.ITEMGROUPID = EKS.ITEMGROUPITEMREL.ITEMGROUPID
         INNER JOIN EKS.ITEMGRPTIMELINE as stEKS_ITEMGRPTIMELINE_PARENT
                 ON EKS.ITEMGRPTIMELINE.PARENTID = stEKS_ITEMGRPTIMELINE_PARENT.ITEMGROUPID
         INNER JOIN (SELECT ITEMID, max(MODDATE) as MAX_MODDATE from EKS.ITEMGROUPITEMREL group by  ITEMID) ITEMGROUPITEMREL_MAXMODDATE
                 ON EKS.ITEMGROUPITEMREL.ITEMID = ITEMGROUPITEMREL_MAXMODDATE.ITEMID
                    and
                    EKS.ITEMGROUPITEMREL.MODDATE = ITEMGROUPITEMREL_MAXMODDATE.MAX_MODDATE
         RIGHT OUTER JOIN EKS_CALCULATION.STMARA_EKS_ITEM
                       ON EKS.ITEMGROUPITEMREL.ITEMID = EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID
                          AND current_date() BETWEEN EKS.ITEMGROUPITEMREL.DATEFROM AND EKS.ITEMGROUPITEMREL.DATEUNTIL
                          AND current_date() BETWEEN EKS.ITEMGRPTIMELINE.DATEFROM AND EKS.ITEMGRPTIMELINE.DATEUNTIL
                          AND current_date() BETWEEN stEKS_ITEMGRPTIMELINE_PARENT.DATEFROM AND stEKS_ITEMGRPTIMELINE_PARENT.DATEUNTIL
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0 )
         ;