create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZARTICLETYPEUPDSEL(
	LISTINGOVERVIEWID,
	ITEMID,
	RECEIVINGCOUNTRY,
	CASESIZE,
	ZARTICLETYPE,
	ZARTICLETYPENEW
) as
Select distinct t1.LISTINGOVERVIEWID, t1.itemid, t1.RECEIVINGCOUNTRY, t1.casesize, t1.zarticletype, t2.zarticletype AS zarticletypenew
from EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX t1
LEFT OUTER JOIN
STMARA_EKS_ITEM t2
ON t1.itemid = t2.itemid;