create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_BA_010(
	SORTITEMID,
	ZLEGACYMATKLNEW,
	ZMATKLNEW
) as
SELECT
EKS.ITEMSORTING.SORTITEMID,
MIN(stMARA_EKS_ITEM_1.zMATKL) AS zLegacyMATKLNew,
MIN(stMARA_EKS_ITEM_1.zMATKL) AS zMATKLNew

FROM        EKS.ITEMSORTING INNER JOIN
            EKS_CALCULATION.stMARA_EKS_ITEM AS stMARA_EKS_ITEM_1
            ON EKS.ITEMSORTING.ITEMID = stMARA_EKS_ITEM_1.ITEMID

WHERE     (stMARA_EKS_ITEM_1.BITFLAG IN ('4', '0')) AND (stMARA_EKS_ITEM_1.zMATKL IS NOT NULL)
GROUP BY EKS.ITEMSORTING.SORTITEMID;