create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCE_ZISCURRENTCONTRACT_UPDSEL(
	ITEMID,
	ZISCURRENTCONTRACT,
	ZISCURRENTCONTRACTNEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsCurrentContract,
         1 AS zIsCurrentContractNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = '0' )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsCurrentContract IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantMDM = 1 ) ;