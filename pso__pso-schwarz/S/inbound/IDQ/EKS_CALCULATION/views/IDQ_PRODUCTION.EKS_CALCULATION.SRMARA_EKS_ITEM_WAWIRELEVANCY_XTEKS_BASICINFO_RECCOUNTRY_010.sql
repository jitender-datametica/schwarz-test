create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCY_XTEKS_BASICINFO_RECCOUNTRY_010(
	LISTINGOVERVIEWID,
	CASESIZE,
	ITEMID,
	ITEMNO,
	SK_ITEMID,
	SK_ITEMNO,
	SK_DESCRIPTION_INT,
	BASICPRICEUNIT,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	BASICPRICEID,
	CONTRACTPRICERELID,
	CONTRACTLINKID,
	LOCATIONID,
	CONTRACTPRICEVALIDITYID,
	DECIMALCASESIZE
) as
with cte as(SELECT DISTINCT
                         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID,
                         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize,
                         stMARA_WAWI_zRelevantMDM.ITEMID,
                         /*dbo.stMARA_EKS_ITEM.DESCRIPTION_INT as SK_DESCRIPTION_INT,*/ EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT.DESCRIPTION AS BasicPriceUnit,
                         ReceivingCountry,
                         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO,
                         EKS.BASICPRICE.BASICPRICEID,
                         stMARA_WAWI_zRelevantMDM.zarticletype,
                         EKS.CONTRACTPRICEREL.CONTRACTPRICERELID,
                         EKS.CONTRACTPRICEREL.CONTRACTLINKID,
                         CONTRACTLINK.LOCATIONID,
                         CONTRACTPRICEVALIDITYID,
                         (TRY_CAST(CAST(EKS.BASICPRICE.SUBCASES as NUMBER(15, 2)) * CAST(EKS.BASICPRICE.SUBCASESIZE as NUMBER(15, 2)) as Number(30,4))) AS DecimalCasesize,
                         stMARA_WAWI_zRelevantMDM.zactive
FROM            EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX INNER JOIN
                         EKS.LISTINGITEM ON EKS.LISTINGITEM.LISTINGOVERVIEWID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID AND
                         EKS.LISTINGITEM.ITEMID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID INNER JOIN
                         EKS.BASICPRICE ON EKS.LISTINGITEM.LISTINGITEMID = EKS.BASICPRICE.LISTINGITEMID AND EKS.BASICPRICE.CASESIZECalc = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize INNER JOIN
                         EKS.CONTRACTLINK as CONTRACTLINK ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = CONTRACTLINK.LISTINGOVERVIEWID INNER JOIN
                         EKS.CONTRACTPRICEREL ON CONTRACTLINK.CONTRACTLINKID = EKS.CONTRACTPRICEREL.CONTRACTLINKID AND
                         EKS.BASICPRICE.BASICPRICEID = EKS.CONTRACTPRICEREL.BASICPRICEID INNER JOIN
                         EKS.CONTRACTPRICEVALIDITY ON EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICERELID = EKS.CONTRACTPRICEREL.CONTRACTPRICERELID INNER JOIN
                         EKS.UNIT ON EKS.BASICPRICE.UNITID = EKS.UNIT.UNITID INNER JOIN
                         EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT ON EKS.UNIT.SHORTDESCID = EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT.TRANSLATIONID INNER JOIN
                         EKS.LOCATION ON CONTRACTLINK.LOCATIONID = EKS.LOCATION.LOCATIONID AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry = EKS.LOCATION.SHORTSIGN INNER JOIN
                         EKS_CALCULATION.STMARA_EKS_ITEM as stMARA_WAWI_zRelevantMDM ON stMARA_WAWI_zRelevantMDM.zrelevantmdm = 1 and EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = stMARA_WAWI_zRelevantMDM.ITEMID
                         AND stMARA_WAWI_zRelevantMDM.znegotiatingcountry = ReceivingCountry
                         inner join EKS_CALCULATION.WAWI_MDM_RELEVANT_ARTICLES on
                         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize = right(EKS_CALCULATION.WAWI_MDM_RELEVANT_ARTICLES.WAWI_ARTIKELNR, 4)
                         AND WAWI_MDM_RELEVANT_ARTICLES.EKS_SUPPLIER_NO = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.supplierno
                         and stMARA_WAWI_zRelevantMDM.itemno = WAWI_MDM_RELEVANT_ARTICLES.EKS_ARTIKEL_NR
                         --AND stMARA_WAWI_zRelevantMDM.zactivenew = 1
                         )
    /* get the EAs from the SKs that have a contract*/
    SELECT cte.LISTINGOVERVIEWID, casesize, EKS.ITEM.itemid, EKS.ITEM.ITEMNO, cte.itemid AS SK_ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.itemno AS SK_ITEMNO,
                              EKS_CALCULATION.STMARA_EKS_ITEM.DESCRIPTION_INT AS SK_DESCRIPTION_INT, BasicPriceUnit, ReceivingCountry, SUPPLIERNO, BASICPRICEID, CONTRACTPRICERELID, CONTRACTLINKID, LOCATIONID, CONTRACTPRICEVALIDITYID,
                              DecimalCasesize
     FROM            cte INNER JOIN
                              EKS_CALCULATION.STMARA_EKS_ITEM ON cte.itemid = EKS_CALCULATION.STMARA_EKS_ITEM.itemid INNER JOIN
                              EKS.ITEMSORTING ON EKS.ITEMSORTING.SORTITEMID = cte.ITEMID AND cte.zArticleType = 'SK' INNER JOIN
                              EKS.ITEM ON EKS.ITEMSORTING.itemid = EKS.ITEM.itemid AND EKS.ITEM.bitflag = '0'
UNION ALL
/*get the EAs with a contract*/ SELECT cte.LISTINGOVERVIEWID, casesize, cte.itemid, ITEMNO, NULL AS SK_ITEMID, NULL AS SK_ITEMNO, NULL AS SK_DESCRIPTION_INT, BasicPriceUnit, ReceivingCountry, SUPPLIERNO,
                         BASICPRICEID, CONTRACTPRICERELID, CONTRACTLINKID, LOCATIONID, CONTRACTPRICEVALIDITYID, DecimalCasesize
FROM            cte INNER JOIN
                         EKS_CALCULATION.STMARA_EKS_ITEM ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = cte.itemid
WHERE        cte.zArticleType = 'EA';