create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_ZISVALIDCONTRACT_MAXDATEUNTIL_SK(
	LISTINGOVERVIEWID,
	SK_ITEMID,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	MAXDATEUNTIL
) as
SELECT        EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO,
                         MAX(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL) AS MAXDATEUNTIL
FROM            EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY INNER JOIN
                         EKS.CONTRACTPRICEVALIDITY ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID
GROUP BY EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO
HAVING        (NOT (EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID IS NULL));