create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZARTICLETYPEUPDSEL(
	ITEMID,
	ZARTICLETYPE,
	ZARTICLETYPENEW
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType,
         ( case EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG
             when 0 then 'EA'
             when 2 then 'BA'
             when 4 then 'SK'
           end ) AS zArticleTypeNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType IS NULL ) ;