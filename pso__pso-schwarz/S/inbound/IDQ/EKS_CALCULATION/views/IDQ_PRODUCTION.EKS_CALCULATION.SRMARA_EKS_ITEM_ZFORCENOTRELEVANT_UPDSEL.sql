create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZFORCENOTRELEVANT_UPDSEL(
	ITEMNO,
	ZFORCENOTRELEVANT,
	ZFORCENOTRELEVANTNEW
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO,
         EKS_CALCULATION.STMARA_EKS_ITEM.zForceNotRelevant,
         EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ForceNotRelevant AS zForceNotRelevantNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE
                    ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO = EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ITEMNO
  WHERE  ( EKS_CALCULATION.EKS_ZSM_ARTICLERELEVANCYOVERRIDE.ForceNotRelevant = 1 );