create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISCURRENTCONTRACTFROMSK_RESET_01(
	ITEMID
) as
SELECT EKS.ITEMSORTING.ITEMID
FROM     EKS.ITEMSORTING INNER JOIN
                  EKS_CALCULATION.STMARA_EKS_ITEM AS SK ON EKS.ITEMSORTING.SORTITEMID = SK.ITEMID
WHERE  (SK.zArticleType = 'SK')
GROUP BY EKS.ITEMSORTING.ITEMID
HAVING (MAX(CAST(IFNULL(SK.zIsCurrentContract, IFNULL(SK.zRelevantMDM, 0)) as NUMBER(38,0))) = 0);