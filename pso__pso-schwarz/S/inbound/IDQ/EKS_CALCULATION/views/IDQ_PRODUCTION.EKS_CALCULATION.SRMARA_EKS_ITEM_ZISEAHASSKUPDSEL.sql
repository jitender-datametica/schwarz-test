create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISEAHASSKUPDSEL(
	ITEMID,
	ZISEAHASSK,
	ZISEAHASSKNEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
        EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasSK,
         '1' AS zIsEAhasSKNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS.ITEMSORTING
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM as stEKS_ITEM_PARENT
                 ON EKS.ITEMSORTING.SORTITEMID = stEKS_ITEM_PARENT.ITEMID
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasSK IS NULL )
         AND EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0
         and stEKS_ITEM_PARENT.BITFLAG = 4;