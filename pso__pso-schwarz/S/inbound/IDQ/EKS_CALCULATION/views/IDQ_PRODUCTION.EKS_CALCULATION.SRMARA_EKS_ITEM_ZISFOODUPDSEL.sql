create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISFOODUPDSEL(
	ITEMID,
	ZISFOOD,
	ZISFOODNEW
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
        zIsFood,
         '1' AS zIsFoodNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
  WHERE  ( zLegacyMATKL BETWEEN '20' AND '98' )
         AND ( zLegacyMATKL <> '86' ) ;