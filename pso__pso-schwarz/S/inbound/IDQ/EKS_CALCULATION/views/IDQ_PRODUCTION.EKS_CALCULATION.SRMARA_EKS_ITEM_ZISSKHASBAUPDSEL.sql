create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISSKHASBAUPDSEL(
	ITEMID,
	ZISSKHASBA,
	ZISSKHASBANEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
        EKS_CALCULATION.STMARA_EKS_ITEM.zIsSKhasBA,
         '1' AS zIsSKhasBANew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS.ITEMSORTING
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM as stEKS_ITEM_PARENT
                 ON EKS.ITEMSORTING.SORTITEMID = stEKS_ITEM_PARENT.ITEMID
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsSKhasBA IS NULL )
         AND EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 4
         and stEKS_ITEM_PARENT.BITFLAG = 2;