create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZITEM_BA_ARTICLE_TYPE_EA_02_UPDSEL(
	ITEMID,
	ITEMNO,
	ZISEAHASSKHASBA,
	ZARTICLETYPE,
	ZITEM_BA,
	ZITEM_BANEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasSKhasBA,
         EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType,
         EKS_CALCULATION.STMARA_EKS_ITEM.zITEM_BA,
         max(stMARA_EKS_ITEM_2.ITEMID) AS zITEM_BANew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM
         INNER JOIN EKS.ITEMSORTING
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM AS stMARA_EKS_ITEM_1
                 ON EKS.ITEMSORTING.SORTITEMID = stMARA_EKS_ITEM_1.ITEMID
         INNER JOIN EKS.ITEMSORTING AS stEKS_ITEMSORTING_1
                 ON stMARA_EKS_ITEM_1.ITEMID = stEKS_ITEMSORTING_1.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM AS stMARA_EKS_ITEM_2
                 ON stEKS_ITEMSORTING_1.SORTITEMID = stMARA_EKS_ITEM_2.ITEMID
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0 )
         AND ( stMARA_EKS_ITEM_1.BITFLAG = 4 )
         AND ( stMARA_EKS_ITEM_2.BITFLAG = 2 )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasSKhasBA = 1 )
    group by EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasSKhasBA,
         EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType,
         EKS_CALCULATION.STMARA_EKS_ITEM.zITEM_BA;