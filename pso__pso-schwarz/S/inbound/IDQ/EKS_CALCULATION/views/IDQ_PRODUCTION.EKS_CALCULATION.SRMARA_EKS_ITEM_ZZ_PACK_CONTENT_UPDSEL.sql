create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZZ_PACK_CONTENT_UPDSEL(
	ITEMID,
	ZZZ_PACK_CONTENT,
	ZZZ_PACK_CONTENTNEW
) as
SELECT        STMARA_EKS_ITEM.ITEMID, STMARA_EKS_ITEM.zZZ_PACK_CONTENT, EKS.ITEMDETAIL.VOLUME AS zZZ_PACK_CONTENTNew
FROM            EKS_CALCULATION.STMARA_EKS_ITEM INNER JOIN
                         EKS.ITEMDETAIL ON STMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID;