create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZZ_QUANT_PACK_CONT_ARTICLE_TYPE_EAUPDSEL(
	ITEMID,
	ZZZ_QUANT_PACK_CONT,
	ZZZ_QUANT_PACK_CONTNEW
) as
SELECT        STMARA_EKS_ITEM.itemid, EKS_CALCULATION.STMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT, EKS.ITEMDETAIL.BUNDLEFACT AS zZZ_QUANT_PACK_CONTNew
FROM            stMARA_EKS_ITEM INNER JOIN
                         EKS.ITEMDETAIL ON stMARA_EKS_ITEM.ITEMID = ITEMDETAIL.ITEMID
WHERE        (stMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT IS NULL) AND (stMARA_EKS_ITEM.BITFLAG = '0');