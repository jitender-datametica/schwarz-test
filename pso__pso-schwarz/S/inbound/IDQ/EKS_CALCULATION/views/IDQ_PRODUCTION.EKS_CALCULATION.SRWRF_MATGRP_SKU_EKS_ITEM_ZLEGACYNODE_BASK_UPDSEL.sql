create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRWRF_MATGRP_SKU_EKS_ITEM_ZLEGACYNODE_BASK_UPDSEL(
	ITEMID,
	ZLEGACYNODE,
	ZLEGACYNODENEW
) as
SELECT distinct EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.ITEMID,
         EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE,
         IFNULL(EKS_CALCULATION.srWRF_MATGRP_SKU_EKS_ITEM_zLegacyNODE_01.zLegacyNODE, '') AS zLegacyNODENew
  FROM   EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM
         INNER JOIN EKS_CALCULATION.stMARA_EKS_ITEM
                 ON EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
         LEFT OUTER JOIN EKS_CALCULATION.srWRF_MATGRP_SKU_EKS_ITEM_zLegacyNODE_01
                      ON EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA = EKS_CALCULATION.srWRF_MATGRP_SKU_EKS_ITEM_zLegacyNODE_01.zITEM_BA
  WHERE  ( EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.Constructed IS NULL )
         AND ( EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE IS NULL )
         AND ( EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.BITFLAG IN ( 2, 4 ) );