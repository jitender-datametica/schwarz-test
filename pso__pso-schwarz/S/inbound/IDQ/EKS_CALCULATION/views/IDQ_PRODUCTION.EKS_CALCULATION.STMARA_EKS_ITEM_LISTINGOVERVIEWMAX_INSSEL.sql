create or replace view IDQ_PRODUCTION.EKS_CALCULATION.STMARA_EKS_ITEM_LISTINGOVERVIEWMAX_INSSEL(
	LISTINGOVERVIEWID,
	LOCATION,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE
) as
select
MAX(t1.listingoverviewid) AS LISTINGOVERVIEWID,
'' AS LOCATION,
t3.SUPPLIERNO,
'' AS CR_LOCATIONID,
STEKS_LOCATION_1.SHORTSIGN AS ReceivingCountry,
t7.ITEMID,
t6.casesizecalc as CaseSize
from EKS.LISTINGOVERVIEW t1
INNER JOIN EKS.CONTRACTLINK  t2 ON t1.LISTINGOVERVIEWID = t2.LISTINGOVERVIEWID
INNER JOIN EKS.SUPPLIER t3 ON t1.supplierno = t3.SUPPLIERNO
INNER JOIN EKS.LOCATION t4 ON t1.cr_locationid = t4.locationid
INNER JOIN EKS.LOCATION AS STEKS_LOCATION_1 ON t2.LOCATIONID = STEKS_LOCATION_1.locationid
INNER JOIN EKS.CONTRACTPRICEREL t5 ON t2.contractlinkid = t5.contractlinkid
INNER JOIN EKS.BASICPRICE t6 ON t5.basicpriceid = t6.basicpriceid
INNER JOIN EKS.LISTINGITEM t7 ON t6.listingitemid = t7.listingitemid
LEFT OUTER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER t8 ON t8.id = 'DRDATE'

WHERE (t2.statusid in (34, 86) ) AND t1.dateuntil >= t8.date
GROUP BY t3.supplierno, stEKS_LOCATION_1.shortsign, t7.itemid, t6.casesizecalc
having t3.supplierno <> 10236
;