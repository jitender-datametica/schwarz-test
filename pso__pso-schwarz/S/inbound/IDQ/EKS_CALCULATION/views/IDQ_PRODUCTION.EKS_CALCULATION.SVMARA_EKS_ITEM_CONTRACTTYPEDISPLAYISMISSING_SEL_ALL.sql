create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_CONTRACTTYPEDISPLAYISMISSING_SEL_ALL(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	CONTRACTDESC,
	LUHEADLINE,
	ARTICLEHEADLINE,
	CONTRACTHEADLINE,
	LISTINGOVERVIEWID,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	BA_NUMBER,
	BA_DESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
SELECT DISTINCT
    CASE WHEN st.zNegotiatingCountry = 'NT' THEN 'INT' ELSE st.zNegotiatingCountry END AS NegotiatingCountry,
	st.BuyerSHORTSIGN, st.BuyerFirstName, st.BuyerLastName, st.zMATKL, st.ArticleFamily, st.ITEMID, st.ITEMNO,
                  st.zArticleType AS ArticleType, st.DESCRIPTION_INT AS Description, TR_LC.DESCRIPTION AS ContractDesc,
				  TR_LH.DESCRIPTION AS LuHeadline, TR_VAL.DESCRIPTION AS ArticleHeadline, TR_SP.DESCRIPTION AS ContractHeadline,
                  xt.LISTINGOVERVIEWID, xt.ReceivingCountry,
				  SUPP.INTSUPPLIERNO AS SUPPLIERNO, SUPP.SHORTDESC AS SupplierDescription,
				  st_ba.ITEMNO AS BA_NUMBER, st_ba.DESCRIPTION_INT AS BA_DESCRIPTION, st.zRelevantMDM,
                  st.zSource, st.zActive
FROM     EKS_CALCULATION.stMARA_EKS_ITEM AS st
INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry AS xt ON (CASE WHEN xt.SK_ITEMID IS NULL THEN xt.ITEMID ELSE xt.SK_ITEMID END) = st.ITEMID
				  LEFT OUTER JOIN
                  EKS.CONTRACTPRICEVALIDITY ON xt.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID
				  LEFT OUTER JOIN
                  EKS.VALIDITY AS val ON EKS.CONTRACTPRICEVALIDITY.VALIDITYID = val.VALIDITYID
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT AS TR_VAL ON val.DESCRIPTIONID = TR_VAL.TRANSLATIONID
				  LEFT OUTER JOIN
                  EKS.LISTINGOVERVIEW AS list ON xt.LISTINGOVERVIEWID = list.LISTINGOVERVIEWID
				  LEFT OUTER JOIN
                  EKS.LOCATEGORY AS LC ON list.LOCATEGORYID = LC.LOCATEGORYID
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT AS TR_LC ON LC.DESCRIPTIONID = TR_LC.TRANSLATIONID
				  LEFT OUTER JOIN
                  EKS.LOHEADING AS lh ON list.LOHEADINGID = lh.LOHEADINGID
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT AS TR_LH ON TR_LH.TRANSLATIONID = lh.DESCRIPTIONID
				  LEFT OUTER JOIN
                  EKS.CONTRACTSIGNVALUE AS CSV ON CSV.CONTRACTLINKID = xt.CONTRACTLINKID AND CSV.SIGNSPECID = 1
				  LEFT OUTER JOIN
                  EKS.SIGNSPECVAL AS SP ON SP.SIGNSPECVALID = CSV.SIGNSPECVALID
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT AS TR_SP ON TR_SP.TRANSLATIONID = SP.DESCRIPTIONID
				  LEFT OUTER JOIN
                  EKS.SUPPLIER AS SUPP ON xt.SUPPLIERNO = SUPP.SUPPLIERNO
				  LEFT OUTER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM AS st_ba ON st.zITEM_BA = st_ba.ITEMID
WHERE  (LOWER(st.DESCRIPTION_INT) LIKE '%display%') AND (LOWER(TR_LC.DESCRIPTION) NOT LIKE '%display%' OR
                  LOWER(TR_LH.DESCRIPTION) NOT LIKE '%display%') OR
                  (LOWER(TR_LC.DESCRIPTION) NOT LIKE '%display%') AND (LOWER(TR_LH.DESCRIPTION) LIKE '%display%') OR
                  (LOWER(TR_LC.DESCRIPTION) LIKE '%display%') AND (LOWER(TR_LH.DESCRIPTION) NOT LIKE '%display%') OR
                  (LOWER(TR_LC.DESCRIPTION) NOT LIKE '%display%' OR
                  LOWER(TR_LH.DESCRIPTION) NOT LIKE '%display%') AND (LOWER(TR_VAL.DESCRIPTION) LIKE '%display%') OR
                  (LOWER(TR_LC.DESCRIPTION) NOT LIKE '%display%' OR
                  LOWER(TR_LH.DESCRIPTION) NOT LIKE '%display%') AND (LOWER(TR_SP.DESCRIPTION) LIKE '%display%');