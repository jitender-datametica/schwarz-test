create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DQ_EKS_EASINACTIVEBUYER_SEL_ALL(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION_INT,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
					SELECT DISTINCT
								EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry,
								EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN,
								EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName,
								EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName,
								EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL,
								EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily,
								EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID,
								EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO,
								EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType,
								EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT,
								CASE WHEN (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1 AND
								stMARA_EKS_ITEM.zIsCurrentContract = 0)
								THEN sk.zRelevantMDM ELSE stMARA_EKS_ITEM.zRelevantMDM END AS zRelevantMDM,
								EKS_CALCULATION.stMARA_EKS_ITEM.zSource,
								EKS_CALCULATION.stMARA_EKS_ITEM.zActive
				FROM     EKS_CALCULATION.stMARA_EKS_ITEM LEFT OUTER JOIN
									(SELECT EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid, MIN( EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM) AS zRelevantMDM
									FROM      EKS_CALCULATION.xtEKS_BASICINFO_RecCountry INNER JOIN
														EKS_CALCULATION.stMARA_EKS_ITEM ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
									GROUP BY EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid) AS SK ON SK.itemid = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
				WHERE  (UPPER(EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN) LIKE '%X')
				AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA')
				AND (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1);