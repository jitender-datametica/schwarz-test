create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_GTINCHECKDIGITINVALID_SEL(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	EAN,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
(SELECT DISTINCT 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description, 
                  EKS.ITEMEAN.EAN, 
				  EKS.SUPPLIER.INTSUPPLIERNO AS SupplierNo, 
				  EKS.SUPPLIER.DESCRIPTION AS SupplierDescription, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zSource, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM              EKS_CALCULATION.stMARA_EKS_ITEM INNER JOIN
                  EKS.ITEMEAN ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMEAN.ITEMID AND current_date() BETWEEN EKS.ITEMEAN.DATEFROM AND EKS.ITEMEAN.DATEUNTIL INNER JOIN
                  EKS.ITEMEAN_SUPPLIER ON EKS.ITEMEAN.ITEMEANID = EKS.ITEMEAN_SUPPLIER.ITEMEANID INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM AS BA ON EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA = BA.ITEMID INNER JOIN
                  EKS.ITEMDETAIL ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID LEFT OUTER JOIN
                  EKS.SUPPLIER ON EKS.SUPPLIER.SUPPLIERNO = EKS.ITEMEAN_SUPPLIER.SUPPLIERNO
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) AND (EKS.ITEMDETAIL.TEXT_INT IS NULL) AND (EKS.ITEMDETAIL.TEXT_NAT IS NULL) AND (RIGHT(IFNULL(EKS.ITEMEAN.zEAN_Converted, 'X'), 1) 
                  <> IFNULL(EKS_CALCULATION.STANDARDCHECKDIGIT1(lpad(EKS.ITEMEAN.zEAN_Converted,18,'0')), 'XX'))
);