create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_MESSURES_DIFF_BETW_ARTICLES010(
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE,
	ZNEGOTIATINGCOUNTRY,
	ZITEM_BA,
	ITEMID,
	ITEMNO,
	DESCRIPTION_INT,
	ZMATKL,
	CASESIZE,
	CASEHEIGHT,
	CASEWIDTH,
	CASEDEPTH,
	ZARTICLETYPE,
	BUYERID,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	BUYERSHORTSIGN,
	ARTICLEFAMILY,
	ZISCURRENTCONTRACT,
	SUBCASESIZE,
	BA_ITEMNO,
	LISTINGOVERVIEWID,
	VOLUME,
	RECEIVINGCOUNTRY,
	UNITDESCRIPTION,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION
) as
WITH cte AS (SELECT EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize, 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, 
EKS_CALCULATION.svMARA_EKS_ITEM_BASKEA_Structure_010.BA_ITEMNO, 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID AS itemid, 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID, 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICERELID, EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO, EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry, 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant
	FROM EKS_CALCULATION.xtEKS_BASICINFO_RecCountry 
	INNER JOIN
		EKS_CALCULATION.svMARA_EKS_ITEM_BASKEA_Structure_010 ON EKS_CALCULATION.svMARA_EKS_ITEM_BASKEA_Structure_010.SK_ITEMNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMNO
	 WHERE (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID IS NOT NULL)
		UNION
	SELECT EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize, 
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, 
		   EKS_CALCULATION.svMARA_EKS_ITEM_BASKEA_Structure_010.BA_ITEMNO, EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid, 
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID, 
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICERELID, 
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO,
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry, 
		   EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant
	FROM  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry 
	INNER JOIN EKS_CALCULATION.svMARA_EKS_ITEM_BASKEA_Structure_010 ON EKS_CALCULATION.svMARA_EKS_ITEM_BASKEA_Structure_010.EA_ITEMNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMNO
	WHERE (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID IS NULL))
	SELECT DISTINCT 
		cte.zIsWAWIRelevant AS zRelevantMDM, 
		EKS_CALCULATION.stMARA_EKS_ITEM.zSource, EKS_CALCULATION.stMARA_EKS_ITEM.zActive, 
		EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry, 
		EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA, cte.itemid, 
		EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
		EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT, 
		EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, cte.casesize, 
		EKS.ITEMDIMENSION.CASEHEIGHT, 
		EKS.ITEMDIMENSION.CASEWIDTH, 
		EKS.ITEMDIMENSION.CASEDEPTH, 
		EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
		EKS_CALCULATION.stMARA_EKS_ITEM.BuyerID, 
		EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
		EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, 
		EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, 
		EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, 
		EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract, 
		cte.DecimalCaseSize AS subcasesize, 
		cte.BA_ITEMNO, 
		cte.LISTINGOVERVIEWID, 
			CASE WHEN TR.DESCRIPTION = 'mm' THEN 
			(CAST(EKS.ITEMDIMENSION.CASEDEPTH AS decimal(10, 2)) / 1000 * CAST(EKS.ITEMDIMENSION.CASEWIDTH AS decimal(10, 2)) 
			/ 1000 * CAST(EKS.ITEMDIMENSION.CASEHEIGHT AS decimal(10, 2)) / 1000) WHEN TR.DESCRIPTION = 'cm' THEN (CAST(EKS.ITEMDIMENSION.CASEDEPTH AS decimal(10, 2)) 
			/ 100 * CAST(EKS.ITEMDIMENSION.CASEWIDTH AS decimal(10, 2)) / 100 * CAST(EKS.ITEMDIMENSION.CASEHEIGHT AS decimal(10, 2)) / 100) 
			WHEN TR.DESCRIPTION = 'in' THEN (CAST(EKS.ITEMDIMENSION.CASEDEPTH AS decimal(10, 2)) / 39.37 * CAST(EKS.ITEMDIMENSION.CASEWIDTH AS decimal(10, 2)) 
			/ 39.37 * CAST(EKS.ITEMDIMENSION.CASEHEIGHT AS decimal(10, 2)) / 39.37) WHEN TR.DESCRIPTION = 'm' THEN CAST(EKS.ITEMDIMENSION.CASEDEPTH AS decimal(10, 2)) 
			* CAST(EKS.ITEMDIMENSION.CASEWIDTH AS decimal(10, 2)) * CAST(EKS.ITEMDIMENSION.CASEHEIGHT AS decimal(10, 2)) END AS Volume, 
			cte.ReceivingCountry,
			tr.DESCRIPTION AS unitdescription, 
			EKS.SUPPLIER.INTSUPPLIERNO AS SupplierNo, 
			EKS.SUPPLIER.DESCRIPTION AS SupplierDescription
			FROM     
			EKS_CALCULATION.stMARA_EKS_ITEM 
			INNER JOIN
				cte ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = cte.itemid 
			INNER JOIN
				EKS.ITEMDIMENSION ON cte.CONTRACTPRICEVALIDITYID = EKS.ITEMDIMENSION.CONTRACTPRICEVALIDITYID 
				AND EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMDIMENSION.ITEMID 
				INNER JOIN
							  EKS.UNIT ON EKS.ITEMDIMENSION.CASEUNITID = EKS.UNIT.UNITID 
				INNER JOIN
							  EKS.TRANSLATION_INT_UNIT AS tr ON EKS.UNIT.SHORTDESCID = tr.TRANSLATIONID
				LEFT OUTER JOIN
							  EKS.SUPPLIER ON cte.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO;
