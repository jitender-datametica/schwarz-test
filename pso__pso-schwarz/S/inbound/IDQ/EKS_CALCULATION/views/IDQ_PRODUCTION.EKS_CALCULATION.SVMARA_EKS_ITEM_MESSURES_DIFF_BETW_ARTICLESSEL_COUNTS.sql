create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_MESSURES_DIFF_BETW_ARTICLESSEL_COUNTS(
	LISTINGOVERVIEWID,
	CASEHEIGHT_COUNT,
	CASEWIDTH_COUNT,
	CASEDEPTH_COUNT
) as
SELECT listingoverviewid, COUNT(DISTINCT CASEHEIGHT) AS CASEHEIGHT_Count, COUNT(DISTINCT CASEWIDTH) AS CASEWIDTH_Count, COUNT(DISTINCT CASEDEPTH) AS CASEDEPTH_Count
FROM     EKS_CALCULATION.svMARA_EKS_ITEM_Messures_Diff_BETW_ArticlesSel_ALL
GROUP BY listingoverviewid
HAVING (COUNT(DISTINCT CASEHEIGHT) > 1) OR
                  (COUNT(DISTINCT CASEWIDTH) > 1) OR
                  (COUNT(DISTINCT CASEDEPTH) > 1);