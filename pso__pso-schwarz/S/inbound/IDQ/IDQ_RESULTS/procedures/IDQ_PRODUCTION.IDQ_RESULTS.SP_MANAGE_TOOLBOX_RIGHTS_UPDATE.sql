-- SP_MANAGE_TOOLBOX_RIGHTS_UPDATE (VARCHAR, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER)

CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_MANAGE_TOOLBOX_RIGHTS_UPDATE("MSTR_USER" VARCHAR(1000), "SYSCHECK_EXCLUDE_FLAG" NUMBER(38,0), "SYSCHECK_PARAMETER_FLAG" NUMBER(38,0), "SYSCHECK_ALERTS_FLAG" NUMBER(38,0), "SYSCOMP_EXCLUDE_FLAG" NUMBER(38,0), "SYSCOMP_PARAMETER_FLAG" NUMBER(38,0), "SYSCOMP_ALERTS_FLAG" NUMBER(38,0), "RELEVANCE_EXCLUDE_FLAG" NUMBER(38,0), "RELEVANCE_PARAMETER_FLAG" NUMBER(38,0), "RELEVANCE_ALERTS_FLAG" NUMBER(38,0), "RULE_CATALOG_FLAG" NUMBER(38,0), "TOOLBOX_ADMIN_FLAG" NUMBER(38,0), "MAIL_KFL_EK_NR_FLAG" NUMBER(38,0), "MAIL_SP_FLAG" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    IF (SYSCHECK_EXCLUDE_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET SYSCHECK_EXCLUDE_FLAG = :SYSCHECK_EXCLUDE_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;
    
    IF (SYSCHECK_PARAMETER_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET SYSCHECK_PARAMETER_FLAG = :SYSCHECK_PARAMETER_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (SYSCHECK_ALERTS_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET SYSCHECK_ALERTS_FLAG = :SYSCHECK_ALERTS_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;
    
    IF (SYSCOMP_EXCLUDE_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET SYSCOMP_EXCLUDE_FLAG = :SYSCOMP_EXCLUDE_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

     IF (SYSCOMP_PARAMETER_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET SYSCOMP_PARAMETER_FLAG = :SYSCOMP_PARAMETER_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

     IF (SYSCOMP_ALERTS_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET SYSCOMP_ALERTS_FLAG = :SYSCOMP_ALERTS_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (RELEVANCE_EXCLUDE_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET RELEVANCE_EXCLUDE_FLAG = :RELEVANCE_EXCLUDE_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (RELEVANCE_PARAMETER_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET RELEVANCE_PARAMETER_FLAG = :RELEVANCE_PARAMETER_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (RELEVANCE_ALERTS_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET RELEVANCE_ALERTS_FLAG = :RELEVANCE_ALERTS_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (RULE_CATALOG_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET RULE_CATALOG_FLAG = :RULE_CATALOG_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (RULE_CATALOG_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET RULE_CATALOG_FLAG = :RULE_CATALOG_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (TOOLBOX_ADMIN_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET TOOLBOX_ADMIN_FLAG = :TOOLBOX_ADMIN_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

    IF (MAIL_KFL_EK_NR_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET MAIL_KFL_EK_NR_FLAG = :MAIL_KFL_EK_NR_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;
    IF (MAIL_SP_FLAG is NOT NULL) THEN
	    UPDATE IDQ_RESULTS.REF_TOOLBOX_EXECUTION_RIGHTS 
	    SET MAIL_SP_FLAG = :MAIL_SP_FLAG
	    where MSTR_USER = :MSTR_USER;
	END IF;

commit;
END';