create or replace VIEW IDQ_PRODUCTION.IDQ_RESULTS.V_REF_EXCLUDE_RULE_SET(
	COUNTRY_ID,
	TEST_OBJECT_TYPE_ID,
	SOURCE_SYSTEM_ID,
	RULE_SET
) as
SELECT COUNTRY_ID
      ,TEST_OBJECT_TYPE_ID
	  ,SOURCE_SYSTEM_ID
      ,CASE WHEN TEST_OBJECT_ID is not null then null 
       else CONCAT('|',listagg(/*distinct*/ RULE_ID, '|') WITHIN GROUP (ORDER BY RULE_ID),'|')
       END
FROM IDQ_RESULTS.REF_EXCLUDE AS x
WHERE     RULE_ID IS NOT NULL
      AND SOURCE_SYSTEM_PRIMARY_KEY IS NULL
	  AND SOURCE_SYSTEM_ID IS NOT NULL
      AND COUNTRY_ID IS NOT NULL
	  AND TEST_OBJECT_TYPE_ID IS NOT NULL
	  AND EXCLUDE_FLAG = 1
GROUP BY COUNTRY_ID,TEST_OBJECT_TYPE_ID,SOURCE_SYSTEM_ID,TEST_OBJECT_ID;"