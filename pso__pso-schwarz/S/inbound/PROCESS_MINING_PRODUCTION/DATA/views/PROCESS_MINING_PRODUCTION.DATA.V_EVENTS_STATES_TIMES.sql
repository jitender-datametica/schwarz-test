create or replace view PROCESS_MINING_PRODUCTION.DATA.V_EVENTS_STATES_TIMES(
	U_TASK_NUMBER,
	U_ORDER,
	START_TIMESTAMP,
	EVENT,
	EVENT_LEVEL,
	END_TIMESTAMP,
	DURATION,
	U_ASSIGNMENT_GROUP_NAME,
	STATE_START,
	STATE_END,
	U_ASSIGNED_AT,
	U_ASSIGNMENT_REVOKED_AT
) as /* SELECT RELEVANT INFORMATION FROM SYS_AUDIT*/
WITH T_SYS_AUDIT_STATES AS(
    SELECT /** GATHER ALL STATE EVENTS BESIDES THE FIRST  **/
        TICKETS.NUMBER AS U_TASK_NUMBER,
        T_SYS_AUDIT.SYS_CREATED_ON AS EVENT_TIMESTAMP,
        T_SYS_AUDIT.tablename,
        ROW_NUMBER() OVER (PARTITION BY T_SYS_AUDIT.DOCUMENTKEY ORDER BY T_SYS_AUDIT.SYS_CREATED_ON ASC, T_SYS_AUDIT.RECORD_CHECKPOINT ASC) AS STATE_EVENT_ORDER,
        T_SYS_AUDIT.NEWVALUE,
        T_SYS_AUDIT.DOCUMENTKEY,
        T_SYS_AUDIT.FIELDNAME
    FROM ETL.T_SYS_AUDIT
    INNER JOIN DATA.v_tickets_min_Last2Years AS TICKETS ON T_SYS_AUDIT.DOCUMENTKEY = TICKETS.SYS_ID
    WHERE TABLENAME IN ('incident', 'u_request', 'problem') and FIELDNAME = 'state'
    UNION /** Add first State Entry with relevant Details **/
    SELECT NUMBER AS U_TASK_NUMBER, TICKETS.SYS_CREATED_ON AS EVENT_TIMESTAMP,  T_SYS_AUDIT.tablename,
        ROW_NUMBER() OVER (PARTITION BY T_SYS_AUDIT.DOCUMENTKEY ORDER BY T_SYS_AUDIT.SYS_CREATED_ON ASC, T_SYS_AUDIT.RECORD_CHECKPOINT ASC) -1 AS STATE_EVENT_ORDER,
        T_SYS_AUDIT.OLDVALUE AS NEWVALUE,
        T_SYS_AUDIT.DOCUMENTKEY,
        T_SYS_AUDIT.FIELDNAME
    FROM ETL.T_SYS_AUDIT
    INNER JOIN DATA.v_tickets_min_Last2Years AS TICKETS ON T_SYS_AUDIT.DOCUMENTKEY = TICKETS.SYS_ID
    WHERE T_SYS_AUDIT.TABLENAME IN ('incident', 'u_request', 'problem') AND T_SYS_AUDIT.FIELDNAME = 'state' --and U_TASK_NUMBER = 'INC8690877'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY DOCUMENTKEY ORDER BY T_SYS_AUDIT.SYS_CREATED_ON ASC, T_SYS_AUDIT.RECORD_CHECKPOINT ASC ) =1
),
EVENTS_ASSIGNMENTS AS /** SELECT RELEVANT INFORMATION FROM U_ASSIGNMENT_GROUP_HISTORY **/
(
    SELECT
    U_TASK_NUMBER,
    U_ASSIGNED_AT,
    COALESCE(U_ASSIGNMENT_REVOKED_AT, '9999-12-31 23:59:59') AS U_ASSIGNMENT_REVOKED_AT,
    U_ASSIGNMENT_GROUP_NAME,
    U_ORDER
    FROM DATA.V_EVENTS_ASSIGNMENTS
)
SELECT /** CREATE EVENT LOG FOR ALL EVENTS BESIDES FIRST **/
    T_SYS_AUDIT_STATES_CURRENT.U_TASK_NUMBER,
    U_ORDER,
    GREATEST_IGNORE_NULLS(T_SYS_AUDIT_STATES_CURRENT.EVENT_TIMESTAMP, U_ASSIGNED_AT) AS START_TIMESTAMP,
    CONCAT('State - ', TICKET_MAPPING_STATE.MATCHING) AS event,
    'state_change' AS event_level,
    LEAST_IGNORE_NULLS(T_SYS_AUDIT_STATES_NEXT_ROW.EVENT_TIMESTAMP, U_ASSIGNMENT_REVOKED_AT) AS END_TIMESTAMP,
    DATEDIFF('second',START_TIMESTAMP, END_TIMESTAMP ) /3600 AS DURATION,
    EVENTS_ASSIGNMENTS.U_ASSIGNMENT_GROUP_NAME,
    /* DEBUG*/ T_SYS_AUDIT_STATES_CURRENT.EVENT_TIMESTAMP AS STATE_START, T_SYS_AUDIT_STATES_NEXT_ROW.EVENT_TIMESTAMP AS STATE_END, U_ASSIGNED_AT, U_ASSIGNMENT_REVOKED_AT
FROM T_SYS_AUDIT_STATES AS T_SYS_AUDIT_STATES_CURRENT
INNER JOIN etl.ticket_mapping_state ON T_SYS_AUDIT_STATES_CURRENT.NEWVALUE = ticket_mapping_state.raw_data_state AND T_SYS_AUDIT_STATES_CURRENT.TABLENAME = ticket_mapping_state.sys_class_name
LEFT JOIN T_SYS_AUDIT_STATES AS T_SYS_AUDIT_STATES_NEXT_ROW  ON T_SYS_AUDIT_STATES_NEXT_ROW.DOCUMENTKEY = T_SYS_AUDIT_STATES_CURRENT.DOCUMENTKEY  AND
T_SYS_AUDIT_STATES_NEXT_ROW.STATE_EVENT_ORDER = T_SYS_AUDIT_STATES_CURRENT.STATE_EVENT_ORDER +1 /** SELF JOIN für ENDZEITSTEMPEL VON EVENTS **/
LEFT JOIN EVENTS_ASSIGNMENTS ON T_SYS_AUDIT_STATES_CURRENT.U_TASK_NUMBER = EVENTS_ASSIGNMENTS.U_TASK_NUMBER
AND
(EVENTS_ASSIGNMENTS.U_ASSIGNED_AT < T_SYS_AUDIT_STATES_NEXT_ROW.EVENT_TIMESTAMP AND EVENTS_ASSIGNMENTS.U_ASSIGNMENT_REVOKED_AT >T_SYS_AUDIT_STATES_CURRENT.EVENT_TIMESTAMP)
ORDER BY START_TIMESTAMP ASC;