create or replace view PROCESS_MINING_PRODUCTION.DATA.V_TASK_RESOLUTION_SLA(
	SLA_BUSINESS_DURATION_SECONDS,
	SLA_BUSINESS_PAUSE_DURATION_SECONDS,
	BUSINESS_PERCENTAGE,
	SLA_BUSINESS_TIME_LEFT_SECONDS,
	SLA_DURATION_SECONDS,
	HAS_BREACHED,
	SLA_PAUSE_DURATION_SECONDS,
	SLA,
	STAGE,
	TASK,
	SYS_ID,
	SYS_UPDATED_ON,
	SLA_CONTRACT_SLA_NAME,
	SLA_PLANNED_END_TIME
) as
SELECT datediff('second','1970-01-01', T_TASK_SLA.BUSINESS_DURATION ) as SLA_BUSINESS_DURATION_SECONDS,  datediff('second','1970-01-01', GREATEST(T_TASK_SLA.BUSINESS_PAUSE_DURATION,'1970-01-01')) as SLA_BUSINESS_PAUSE_DURATION_SECONDS, T_TASK_SLA.BUSINESS_PERCENTAGE,  datediff('second','1970-01-01', GREATEST(T_TASK_SLA.BUSINESS_TIME_LEFT, '1970-01-01') ) as SLA_BUSINESS_TIME_LEFT_SECONDS, datediff('second','1970-01-01', GREATEST(T_TASK_SLA.DURATION,'1970-01-01')) as SLA_DURATION_SECONDS, T_TASK_SLA.HAS_BREACHED,
datediff('second','1970-01-01',  GREATEST(T_TASK_SLA.PAUSE_DURATION, '1970-01-01') ) as SLA_PAUSE_DURATION_SECONDS, T_TASK_SLA.SLA, T_TASK_SLA.STAGE, T_TASK_SLA.TASK, T_TASK_SLA.SYS_ID, T_TASK_SLA.SYS_UPDATED_ON, T_CONTRACT_SLA.NAME AS SLA_CONTRACT_SLA_NAME, T_TASK_SLA.PLANNED_END_TIME AS SLA_PLANNED_END_TIME
FROM
ETL.T_TASK_SLA
inner JOIN ETL.T_CONTRACT_SLA ON
T_TASK_SLA.sla = T_CONTRACT_SLA.sys_id AND T_CONTRACT_SLA.NAME like '%resolution'
where stage != 'cancelled'
qualify row_number() over (partition by task order by sla_contract_sla_name not like '%Sol_Appl_Default%' desc ) =1;