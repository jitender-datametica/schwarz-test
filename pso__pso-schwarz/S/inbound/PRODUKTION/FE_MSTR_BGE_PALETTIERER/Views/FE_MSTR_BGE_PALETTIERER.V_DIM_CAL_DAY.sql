CREATE OR REPLACE VIEW FE_MSTR_BGE_PALETTIERER.V_DIM_CAL_DAY
AS
SELECT
 CORE.T_DIM_CAL_DAY.CAL_DT
,CORE.T_DIM_CAL_DAY.CY
,CORE.T_DIM_CAL_DAY.BUS_YEAR
,CORE.T_DIM_CAL_DAY.CY_MONTH
,CORE.T_DIM_CAL_DAY.MONTH_OF_YEAR
,CORE.T_DIM_CAL_DAY.MONTH_OF_BUS_YEAR
,CORE.T_DIM_CAL_DAY.MONTH_OF_YEAR_NAME
,CORE.T_DIM_CAL_DAY.DAY_OF_MONTH
,CORE.T_DIM_CAL_DAY.CY_WEEK
,CORE.T_DIM_CAL_DAY.WEEK_OF_YEAR
,CORE.T_DIM_CAL_DAY.CY_WEEK_PART                              
,CORE.T_DIM_CAL_DAY.DAY_OF_WEEK          
,CORE.T_DIM_CAL_DAY.DAY_OF_WEEK_NAME
,CORE.T_DIM_CAL_DAY.DAY_OF_CY
,CORE.T_DIM_CAL_DAY.DAY_OF_BUS_YEAR
,datediff(day, current_date(), cal_dt) AS CAL_DT_OFFSET
FROM
CORE.T_DIM_CAL_DAY
;