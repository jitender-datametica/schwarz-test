CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_FACT_BOOKING(
	BOOKING_ID
	,PLANT_RESOURCE_ITEM_SID
	,SHIFT_ID
	,ORIG_SHIFT_ID
	,MATERIAL_RESOURCE_ITEM_SID
	,WAREHOUSE_RESOURCE_ITEM_SID
	,BOOKING_DT
	,MATERIAL_UNIT
	,MATERIAL_MOVEMENT_TYPE_ID
	,MATERIAL_GROUP_RESOURCE_ITEM_GROUP_SID
	,MATERIAL_QTY
	,BOOKING_TMSP
) AS
SELECT
 BO1.BOOKING_ID AS BOOKING_ID
,PLA1.PLANT_NAME AS PLANT_RESOURCE_ITEM_SID
,BO1.SHIFT_ID AS SHIFT_ID
,BO1.ORIG_SHIFT_ID AS ORIG_SHIFT_ID
,MATR1.MATERIAL_ID AS MATERIAL_RESOURCE_ITEM_SID
,WRH1.WAREHOUSE_NAME AS WAREHOUSE_RESOURCE_ITEM_SID
,BO1.BOOKING_DT AS BOOKING_DT
,BO1.MATERIAL_UNIT AS MATERIAL_UNIT
,BO1.MATERIAL_MOVEMENT_TYPE_ID AS MATERIAL_MOVEMENT_TYPE_ID
,MATERIAL_GROUP_NR AS MATERIAL_GROUP_RESOURCE_ITEM_GROUP_SID
,BO1.MATERIAL_QTY AS MATERIAL_QTY  
,BO1.BOOKING_TMSP AS BOOKING_TMSP
FROM
CORE.T_FACT_BOOKING AS BO1
INNER JOIN CORE.T_DIM_PLANT AS PLA1
  ON PLA1.RESOURCE_ITEM_SID = BO1.PLANT_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_WAREHOUSE AS WRH1
  ON WRH1.RESOURCE_ITEM_SID = BO1.WAREHOUSE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_MATERIAL_GROUP AS MGR1
  ON MGR1.RESOURCE_ITEM_GROUP_SID = BO1.MATERIAL_GROUP_RESOURCE_ITEM_GROUP_SID
INNER JOIN CORE.T_DIM_MATERIAL AS MATR1
  ON MATR1.RESOURCE_ITEM_SID = BO1.MATERIAL_RESOURCE_ITEM_SID
;
