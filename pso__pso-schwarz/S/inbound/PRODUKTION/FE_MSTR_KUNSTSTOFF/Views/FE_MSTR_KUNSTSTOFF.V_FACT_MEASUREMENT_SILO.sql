CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_FACT_MEASUREMENT_SILO(
	PRODUCTION_LINE_RESOURCE_ITEM_SID
	,WAREHOUSE_RESOURCE_ITEM_SID
	,SILO_RESOURCE_ITEM_SID
	,MIXER_LINE_RESOURCE_ITEM_SID
	,PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
	,MATERIAL_ID
	,MEASUREMENT_DT
	,MEASUREMENT_TM
	,MEASUREMENT_TMSP
	,FILL_LEVEL_UNIT_ID
	,FILL_LEVEL_PCT
	,FILL_LEVEL_MEAS
) AS
SELECT
 prl1.PRODUCTION_LINE_ID AS PRODUCTION_LINE_RESOURCE_ITEM_SID
,wrh1.WAREHOUSE_NAME AS WAREHOUSE_RESOURCE_ITEM_SID
,sildim1.SILO_NAME AS SILO_RESOURCE_ITEM_SID
,mix1.MIXER_LINE_CD AS MIXER_LINE_RESOURCE_ITEM_SID
,CONCAT(prl1.PRODUCTION_LINE_ID,prm.PRODUCTION_LINE_PARAMETER_CD) AS PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
,matr1.MATERIAL_ID
,silfa1.MEASUREMENT_DT
,silfa1.MEASUREMENT_TM
,silfa1.MEASUREMENT_TMSP
,silfa1.FILL_LEVEL_UNIT_ID
,silfa1.FILL_LEVEL_PCT
,silfa1.FILL_LEVEL_MEAS
FROM
CORE.T_FACT_MEASUREMENT_SILO AS silfa1
INNER JOIN CORE.T_DIM_PRODUCTION_LINE prl1
  ON prl1.RESOURCE_ITEM_SID = silfa1.PRODUCTION_LINE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_WAREHOUSE AS wrh1
  ON wrh1.RESOURCE_ITEM_SID = silfa1.WAREHOUSE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_SILO AS sildim1
  ON sildim1.RESOURCE_ITEM_SID = silfa1.SILO_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_MIXER_LINE AS mix1
  ON mix1.RESOURCE_ITEM_SID = silfa1.MIXER_LINE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_PRODUCTION_LINE_PARAMETER AS prm
  ON prm.RESOURCE_ITEM_SID = silfa1.FILL_LEVEL_RES_ITEM_SID
INNER JOIN CORE.T_DIM_MATERIAL AS matr1
  ON matr1.RESOURCE_ITEM_SID = silfa1.MATERIAL_RESOURCE_ITEM_SID
;