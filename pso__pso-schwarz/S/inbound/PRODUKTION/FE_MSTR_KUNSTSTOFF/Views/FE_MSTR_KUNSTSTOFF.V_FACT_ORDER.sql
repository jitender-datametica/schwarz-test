CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_FACT_ORDER(
	ORDER_ID
	,PRODUCTION_LINE_RESOURCE_ITEM_SID
	,MATERIAL_RESOURCE_ITEM_SID
	,ORDER_START_DT
	,ORDER_END_DT
	,ORDER_NR
	,ORDER_START_TMSP
	,ORDER_END_TMSP
	,PRODUCTION_LINE_START_TMSP
	,PRODUCTION_LINE_END_TMSP
	,ORDER_AMOUNT_PLAN_QTY
	,ORDER_AMOUNT_ACTUAL_QTY
	,NOMINAL_CAPACITY_QTY
	,DWH_SRC_1_TMSP
) AS
SELECT
 ORDER_ID
,prl1.PRODUCTION_LINE_ID AS PRODUCTION_LINE_RESOURCE_ITEM_SID
,matr1.MATERIAL_ID AS MATERIAL_RESOURCE_ITEM_SID
,ORDER_START_DT
,ORDER_END_DT
,ORDER_NR
,ORDER_START_TMSP
,ORDER_END_TMSP
,PRODUCTION_LINE_START_TMSP
,PRODUCTION_LINE_END_TMSP
,ORDER_AMOUNT_PLAN_QTY
,ORDER_AMOUNT_ACTUAL_QTY
,NOMINAL_CAPACITY_QTY
,ordfa1.DWH_SRC_1_TMSP AS DWH_SRC_1_TMSP
FROM
CORE.T_FACT_ORDER ordfa1
INNER JOIN CORE.T_DIM_MATERIAL AS matr1
  ON matr1.RESOURCE_ITEM_SID = ordfa1.MATERIAL_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_PRODUCTION_LINE AS prl1
  ON prl1.RESOURCE_ITEM_SID = ordfa1.PRODUCTION_LINE_RESOURCE_ITEM_SID
;