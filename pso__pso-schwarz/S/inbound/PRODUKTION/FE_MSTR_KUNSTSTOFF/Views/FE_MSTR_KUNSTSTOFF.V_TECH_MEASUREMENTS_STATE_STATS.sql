CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_TECH_MEASUREMENTS_STATE_STATS(
	CAL_DT
	, STATE
	, MIN_TMSP
	, MAX_TMSP
	, STATE_ROW_CNT
) AS
SELECT 
   MEASUREMENT_DT AS CAL_DT
   , MEASUREMENT_DELIVERY_STATE_TXT AS STATE
   , MIN(MEASUREMENT_TMSP) AS MIN_TMSP
   , MAX(MEASUREMENT_TMSP) AS MAX_TMSP
   , COUNT(*) AS STATE_ROW_CNT
FROM CORE_REL.T_MEASUREMENT_PRODUCTION_LINE
WHERE MEASUREMENT_DT BETWEEN (CURRENT_DATE - 6) AND CURRENT_DATE
GROUP BY 
   MEASUREMENT_DT
   , MEASUREMENT_DELIVERY_STATE_TXT
;