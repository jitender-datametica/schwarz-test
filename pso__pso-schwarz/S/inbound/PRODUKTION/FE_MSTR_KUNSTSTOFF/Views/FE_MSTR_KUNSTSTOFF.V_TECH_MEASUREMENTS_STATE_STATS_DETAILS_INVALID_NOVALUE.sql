CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_TECH_MEASUREMENTS_STATE_STATS_DETAILS_INVALID_NOVALUE(
	CAL_DT
	, SAMPLE_RATE
	, FROM_TMSP
	, TO_TMSP
	, KEY
	, STATE
	, VALUE
	, UNIT
) AS
SELECT 
   TMPL.MEASUREMENT_DT AS CAL_DT
   , TMPL.MEASUREMENT_DELIVERY_SAMPLE_RATE AS SAMPLE_RATE
   , MIN(TMPL.MEASUREMENT_TMSP) AS FROM_TMSP
   , MAX(TMPL.MEASUREMENT_TMSP) AS TO_TMSP
   , TPLP.PRODUCTION_LINE_PARAMETER_CD AS KEY
   , TMPL.MEASUREMENT_DELIVERY_STATE_TXT AS STATE
   , TMPL.VALUE_QTY AS VALUE
   , TUNT.UNIT_CODE AS UNIT
FROM CORE_REL.T_MEASUREMENT_PRODUCTION_LINE AS TMPL
JOIN CORE_REL.T_PRODUCTION_LINE_PARAMETER AS TPLP
ON TMPL.PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID = TPLP.RESOURCE_ITEM_SID
JOIN CORE_REL.T_UNIT AS TUNT
ON TMPL.UNIT_ID = TUNT.UNIT_ID
WHERE UPPER(TMPL.MEASUREMENT_DELIVERY_STATE_TXT) NOT LIKE 'VALID'
AND TMPL.MEASUREMENT_DT BETWEEN (CURRENT_DATE - 6) AND CURRENT_DATE
GROUP BY 
   TMPL.MEASUREMENT_DT
   , TMPL.MEASUREMENT_DELIVERY_SAMPLE_RATE
   , TPLP.PRODUCTION_LINE_PARAMETER_CD
   , TMPL.MEASUREMENT_DELIVERY_STATE_TXT
   , TMPL.VALUE_QTY
   , TUNT.UNIT_CODE
;