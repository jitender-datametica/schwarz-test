create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_CAL_MONTH(
	CY_MONTH,
	MONTH_ID,
	MONTH_DESCR,
	MONTH_OF_YEAR,
	CY_MONTH_SEQ,
	BUSYEAR
) as (
	SELECT 
    MON.CY_MONTH
	,MON.MONTH_ID
    ,DESCR.MONTH_DESCR
    ,CONCAT(MONTH_DESCR,' ',SUBSTR(MON.CY_MONTH,0,4)) AS MONTH_OF_YEAR
	,MON.CY_MONTH_SEQ
	,MON.BUSYEAR 
    FROM DATA_SHARED_LDL.P_LEW_CORE_T_CAL_MONTH MON
    JOIN
DATA_SHARED_LDL.P_LEW_CORE_T_CAL_MONTH_DESCR DESCR
ON MON.MONTH_ID=DESCR.MONTH_ID
AND LANG_SID=9);
