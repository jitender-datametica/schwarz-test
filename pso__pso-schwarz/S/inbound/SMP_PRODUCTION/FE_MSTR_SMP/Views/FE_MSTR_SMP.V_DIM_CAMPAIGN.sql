create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_CAMPAIGN(
	COUNTRY_ID,
	DIVISION_ID,
	CAMPAIGN_ID,
	ADVERTISER_ID,
	SOURCE_SYSTEM_ID,
	ADVERTISER_ID_SMP,
	ADVERTISER_ID_PIQ,
	CAMPAIGN_NAME,
	CAMPAIGN_START_DT,
	CAMPAIGN_END_DT,
	DURATION_IN_DAYS,
	CAMPAIGN_STATUS_ID,
	CHANNEL_ID,
	ATTRIBUTION_START_DT,
	ATTRIBUTION_END_DT,
	GTIN_ASSIGNED_LIST,
	CAMPAIGN_TYPE_ID,
	CAMPAIGN_ID_EXT,
	SUPPLIER_ID_REF,
	FOOD_FG,
	ADVERTISER_BID_VAL,
	SALES_QTY,
	SALES_VAL,
	BID_AVG_VAL,
	BUDGET_VAL,
	BUDGET_SPENT_VAL,
	IMPRESSION_QTY,
	VIEW_QTY,
	CLICK_QTY,
	SHOPPER_QTY,
	CONVERSION_QTY,
	PURCHASE_FREQUENCY,
	REPURCHASE_RATE_PCT,
	LIFETIME_REVENUE_VAL,
	CAMPAIGN_LAST_MODIFIED,
	STATUS,
	CNT_CAMPAIGNS_WITHIN_GROUP,
	CNT_ACTIVE_CAMPAIGNS_WITHIN_GROUP,
	STATUS_TOTAL
) as

SELECT DISTINCT RC.COUNTRY_ID
	,RC.DIVISION_ID
	,RC.CAMPAIGN_ID
	,ADVERTISER_ID
	,RC.SOURCE_SYSTEM_ID
	,ADVERTISER_ID_SMP
	,ADVERTISER_ID_PIQ
	,RC.CAMPAIGN_NAME
	,CAMPAIGN_START_DT
	,CAMPAIGN_END_DT
	,CAMPAIGN_END_DT - CAMPAIGN_START_DT AS DURATION_IN_DAYS
	,CAMPAIGN_STATUS_ID
	,CHANNEL_ID
	,ATTRIBUTION_START_DT
	,ATTRIBUTION_END_DT
	,GTIN_ASSIGNED_LIST
	,CAMPAIGN_TYPE_ID
	,CAMPAIGN_ID_EXT
	,SUPPLIER_ID_REF
	,FOOD_FG
	,ADVERTISER_BID_VAL
	,SALES_QTY
	,SALES_VAL
	,BID_AVG_VAL
	,BUDGET_VAL
	,BUDGET_SPENT_VAL
	,IMPRESSION_QTY
	,VIEW_QTY
	,CLICK_QTY
	,SHOPPER_QTY
	,CONVERSION_QTY
	,PURCHASE_FREQUENCY
	,REPURCHASE_RATE_PCT
	,LIFETIME_REVENUE_VAL
	,CAMPAIGN_LAST_MODIFIED
	,CASE 
		WHEN CURRENT_DATE BETWEEN CAMPAIGN_START_DT
				AND CAMPAIGN_END_DT
			THEN 'RUNNING'
		WHEN CURRENT_DATE > CAMPAIGN_END_DT
			THEN 'ENDED'
		WHEN CURRENT_DATE < CAMPAIGN_START_DT
			THEN 'NOT STARTED YET'
		END AS STATUS
	,COUNT(DISTINCT REL.CAMPAIGN_ID) OVER (PARTITION BY REL.CAMPAIGN_GROUP_ID) AS CNT_CAMPAIGNS_WITHIN_GROUP
	,SUM(CASE 
			WHEN STATUS = 'RUNNING'
				THEN 1
			ELSE 0
			END) OVER (PARTITION BY REL.CAMPAIGN_GROUP_ID) AS CNT_ACTIVE_CAMPAIGNS_WITHIN_GROUP
        ,CONCAT(STATUS, '/', CNT_CAMPAIGNS_WITHIN_GROUP, ' CAMPAIGN(S) WITHIN GROUP, ', CNT_ACTIVE_CAMPAIGNS_WITHIN_GROUP, ' RUNNING') AS STATUS_TOTAL
FROM CORE.T_DIM_CAMPAIGN RC
LEFT JOIN FE_MSTR_SMP.V_CAMPAIGN_GROUP_REL REL ON RC.CAMPAIGN_ID = REL.CAMPAIGN_ID
	AND RC.COUNTRY_ID = REL.COUNTRY_ID
	AND RC.DIVISION_ID = REL.DIVISION_ID
LEFT JOIN CORE_REL.T_CAMPAIGN_GROUP RG ON REL.CAMPAIGN_GROUP_ID = RG.CAMPAIGN_GROUP_ID
	AND REL.COUNTRY_ID = RG.COUNTRY_ID
	AND REL.DIVISION_ID = RG.DIVISION_ID;
