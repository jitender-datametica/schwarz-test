create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_CAMPAIGN_AUDIENCE(
	COUNTRY_ID,
	DIVISION_ID,
	CAMPAIGN_ID,
	ADVERTISER_ID,
	SOURCE_SYSTEM_ID,
	ADVERTISER_ID_SMP,
	ADVERTISER_ID_PIQ,
	CAMPAIGN_NAME,
	CAMPAIGN_START_DT,
	CAMPAIGN_END_DT,
	DURATION_IN_DAYS,
	CAMPAIGN_STATUS_ID,
	CHANNEL_ID,
	ATTRIBUTION_START_DT,
	ATTRIBUTION_END_DT,
	GTIN_ASSIGNED_LIST,
	CAMPAIGN_TYPE_ID,
	CAMPAIGN_ID_EXT,
	SUPPLIER_ID_REF,
	FOOD_FG,
	ADVERTISER_BID_VAL,
	SALES_QTY,
	SALES_VAL,
	BID_AVG_VAL,
	BUDGET_VAL,
	BUDGET_SPENT_VAL,
	IMPRESSION_QTY,
	VIEW_QTY,
	CLICK_QTY,
	SHOPPER_QTY,
	CONVERSION_QTY,
	LIFETIME_REVENUE_VAL,
	CAMPAIGN_LAST_MODIFIED
) as

SELECT DIM.COUNTRY_ID
	,DIM.DIVISION_ID
	,DIM.CAMPAIGN_ID
	,DIM.ADVERTISER_ID
	,DIM.SOURCE_SYSTEM_ID
	,DIM.ADVERTISER_ID_SMP
	,DIM.ADVERTISER_ID_PIQ
	,DIM.CAMPAIGN_NAME
	,DIM.CAMPAIGN_START_DT
	,DIM.CAMPAIGN_END_DT
    ,DIM.CAMPAIGN_END_DT-CAMPAIGN_START_DT AS DURATION_IN_DAYS
	,DIM.CAMPAIGN_STATUS_ID
	,DIM.CHANNEL_ID
	,DIM.ATTRIBUTION_START_DT
	,DIM.ATTRIBUTION_END_DT
	,DIM.GTIN_ASSIGNED_LIST
	,DIM.CAMPAIGN_TYPE_ID
	,DIM.CAMPAIGN_ID_EXT
	,DIM.SUPPLIER_ID_REF
	,DIM.FOOD_FG
	,DIM.ADVERTISER_BID_VAL
	,DIM.SALES_QTY
	,DIM.SALES_VAL
	,DIM.BID_AVG_VAL
	,DIM.BUDGET_VAL
	,DIM.BUDGET_SPENT_VAL
	,DIM.IMPRESSION_QTY
	,DIM.VIEW_QTY
	,DIM.CLICK_QTY
	,DIM.SHOPPER_QTY
	,DIM.CONVERSION_QTY
	,DIM.LIFETIME_REVENUE_VAL
	,DIM.CAMPAIGN_LAST_MODIFIED
FROM CORE.T_DIM_CAMPAIGN DIM
WHERE COALESCE(click_qty, 0) > 0
  AND COALESCE(sales_val, 0) > 0;
