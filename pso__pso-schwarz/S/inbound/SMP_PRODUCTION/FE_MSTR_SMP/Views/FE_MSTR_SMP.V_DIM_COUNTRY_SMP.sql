create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_COUNTRY_SMP(
	DIVISION_ID,
	COUNTRY_ID,
	COUNTRY_NAME_FE,
	COUNTRY_DIVISION_ID,
	STAR_ACTIVE_FG
) as (
	SELECT DIVISION_ID
	,COUNTRY_ID
	,CASE 
		WHEN COUNTRY_NAME LIKE 'CLIENT: LIDL-LAND%'
			THEN REPLACE(COUNTRY_NAME, 'CLIENT: LIDL-LAND ', '') || ' ' || 'LDL'
		ELSE COUNTRY_NAME || ' ' || 'KL'
		END AS COUNTRY_NAME_FE
	,CONCAT (
		COUNTRY_ID
		,':'
		,DIVISION_ID
		) COUNTRY_DIVISION_ID
	,STAR_ACTIVE_FG FROM CORE_REL.T_COUNTRY WHERE STAR_ACTIVE_FG = 1
	);
