create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_ITEM(
	DIVISION_ID,
	COUNTRY_ID,
	GTIN_ID,
	GTIN_NAME,
	ARTICLE_ID,
	KL_GTIN_ID,
	MUKI_ID,
	ART_ID_REF_KL,
	TAXONOMY_ID
) as (SELECT DISTINCT 
GTIN.DIVISION_ID
	,GTIN.COUNTRY_ID
	,GTIN.GTIN_ID
	,GTIN.GTIN_NAME
	,GTIN.ARTICLE_ID_REF AS ARTICLE_ID
	,to_char(ART.GTIN_ID) AS KL_GTIN_ID
    ,to_char(art2.KL_ART_ID) as MUKI_ID
	,to_char(to_number(CASE 
		WHEN GTIN.DIVISION_ID = 'KFL'
			THEN ART.KL_ART_ID
		ELSE ARTICLE_ID_REF
		END)) AS ART_ID_REF_KL
	,TAX.TAXONOMY_ID 
    FROM CORE_REL.T_GTIN GTIN 
        JOIN CORE_REL.T_COUNTRY LAND 
        ON GTIN.DIVISION_ID = LAND.DIVISION_ID
	AND GTIN.COUNTRY_ID = LAND.COUNTRY_ID 
      left outer  JOIN DATA_SHARED_KFL.DBP_DATA_ART ART 
      ON GTIN.GTIN_ID = ART.GTIN_ID
     --   ON GTIN.ARTICLE_ID_REF = ART.KL_ART_ID
	   AND GTIN.DIVISION_ID = 'KFL'
	   AND LAND.DIVISION_COUNTRY_REF = ART.MANDANT_ID
	   AND ART.DAT_BIS = '9999-12-31' 
      left outer JOIN
  DATA_SHARED_KFL.DBP_DATA_ART ART2
  ON ART.mutter_wb_id = ART2.ART_ID
	   AND ART.MANDANT_ID = ART2.MANDANT_ID
	   AND ART.DAT_BIS = '9999-12-31' 
       AND ART.DAT_BIS = '9999-12-31'
    LEFT OUTER JOIN CORE_REL.T_TAXONOMY_GTIN TAX 
        ON GTIN.DIVISION_ID = TAX.DIVISION_ID
	   AND GTIN.COUNTRY_ID = TAX.COUNTRY_ID
	   AND GTIN.GTIN_ID = TAX.GTIN_ID);
