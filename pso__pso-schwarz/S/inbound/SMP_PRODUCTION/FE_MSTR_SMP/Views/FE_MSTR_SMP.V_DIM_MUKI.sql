create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_MUKI(
	COUNTRY_ID,
	MUKI_ID
) as
(SELECT distinct
	LAND.COUNTRY_ID
    ,art2.KL_ART_ID as MUKI_ID
    FROM
  DATA_SHARED_KFL.DBP_DATA_ART ART1
  left outer JOIN
  DATA_SHARED_KFL.DBP_DATA_ART ART2
  ON ART1.mutter_wb_id = ART2.ART_ID
	   AND ART1.MANDANT_ID = ART2.MANDANT_ID
	   AND ART1.DAT_BIS = '9999-12-31' 
       AND ART2.DAT_BIS = '9999-12-31'
JOIN CORE_REL.T_COUNTRY LAND 
ON
LAND.DIVISION_COUNTRY_REF = ART1.MANDANT_ID
);
