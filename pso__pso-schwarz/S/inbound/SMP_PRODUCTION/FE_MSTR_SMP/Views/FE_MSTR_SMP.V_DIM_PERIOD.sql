create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_PERIOD(
	PERIOD,
	PERIOD_DETAIL
) as 

WITH P AS 
(SELECT 
'TEST' AS PERIOD
UNION
SELECT 
'PRE' AS PERIOD
UNION
SELECT 
'POST' AS PERIOD
),
PP AS 
(SELECT 
'TEST' AS PERIOD_DETAIL
UNION
SELECT 
'PRE' AS PERIOD_DETAIL
UNION
SELECT 
'POST_1' AS PERIOD_DETAIL
UNION
SELECT 
'POST_2' AS PERIOD_DETAIL) 

SELECT
P.PERIOD, PP.PERIOD_DETAIL
FROM P JOIN PP
ON PERIOD_DETAIL  like '%'||PERIOD||'%'
;
