create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_STORES_RANDOM_EXCLUSION(
	COUNTRY_ID,
	DIVISION_ID,
	STORE_ID,
	STORE_NR
) as
	WITH STORES_WITH_RANK AS (
			SELECT DISTINCT DIVISION_ID
				,COUNTRY_ID
				,STORE_ID
				,STORE_NR
				,ROW_NUMBER() OVER (
					PARTITION BY COUNTRY_ID
					,DIVISION_ID ORDER BY RANDOM()
					) AS RAND
				,COUNT(*) OVER (
					PARTITION BY COUNTRY_ID
					,DIVISION_ID
					) AS CNT_STORE
			FROM FE_MSTR_SMP.V_DIM_STORE
			GROUP BY DIVISION_ID
				,COUNTRY_ID
				,STORE_ID
				,STORE_NR
			)
		,STORES_TO_EXCLUDE AS (
			SELECT DIVISION_ID
				,COUNTRY_ID
				,STORE_ID
				,STORE_NR
				,RAND
				,CNT_STORE
				,CAST(CEIL(0.3 * CNT_STORE) AS INTEGER) AS EXCLUDE_CNT
			FROM STORES_WITH_RANK
			)

SELECT COUNTRY_ID
	,DIVISION_ID
	,STORE_ID
	,STORE_NR
FROM STORES_TO_EXCLUDE
WHERE RAND > EXCLUDE_CNT;
