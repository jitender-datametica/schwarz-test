create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_CAMPAIGN_AUDIENCE_CLICKS(
	CAMPAIGN_ID,
	COUNTRY_ID,
	DIVISION_ID,
	DESCR_AUDIENCE_ID,
	CNT_CLICKS_CAMPAIGN,
	CNT_CLICK_USERS
) as
	WITH CLICKS_BY_AUDIENCE AS (
			SELECT DISTINCT TE.CAMPAIGN_ID
				,TE.COUNTRY_ID
				,TE.DIVISION_ID
				,DA.DESCR_AUDIENCE_ID
				,TE.SHOPPER_ID
			FROM CORE_REL.T_SMP_TRACK_EVENT TE
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE DA ON TE.COUNTRY_ID = DA.COUNTRY_ID
				AND TE.DIVISION_ID = DA.DIVISION_ID
				AND TE.SHOPPER_ID = DA.SHOPPER_ID
				AND TE.CAMPAIGN_ID = TE.CAMPAIGN_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
					'GEN'
					,'AGE'
					,'BUY'
					,'ZIP'
					)
				AND TE.SPECIFICITY_ID = 'CLICK'
			WHERE TE.RECORD_DT BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_CLICKS_CAMPAIGN_TOTAL AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,CAMPAIGN_ID
				,COUNT(DISTINCT SHOPPER_ID) CNT_CLICKS_CAMPAIGN
			FROM CLICKS_BY_AUDIENCE
			GROUP BY 1
				,2
				,3
			)

SELECT CBA.CAMPAIGN_ID
	,CBA.COUNTRY_ID
	,CBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_CLICKS_CAMPAIGN
	,COUNT(DISTINCT CBA.SHOPPER_ID) AS CNT_CLICK_USERS
FROM CLICKS_BY_AUDIENCE CBA
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE DA ON CBA.COUNTRY_ID = DA.COUNTRY_ID
	AND CBA.DIVISION_ID = DA.DIVISION_ID
	AND CBA.SHOPPER_ID = DA.SHOPPER_ID
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
		'GEN'
		,'AGE'
		,'BUY'
		,'ZIP'
		)
JOIN CNT_CLICKS_CAMPAIGN_TOTAL ON CBA.COUNTRY_ID = CNT_CLICKS_CAMPAIGN_TOTAL.COUNTRY_ID
	AND CBA.DIVISION_ID = CNT_CLICKS_CAMPAIGN_TOTAL.DIVISION_ID
	AND CBA.CAMPAIGN_ID = CNT_CLICKS_CAMPAIGN_TOTAL.CAMPAIGN_ID
JOIN CORE.T_DIM_CAMPAIGN DC ON CBA.COUNTRY_ID = DC.COUNTRY_ID
	AND CBA.DIVISION_ID = DC.DIVISION_ID
	AND CBA.CAMPAIGN_ID = DC.CAMPAIGN_ID
	AND COALESCE(DC.CLICK_QTY, 0) > 0
	AND COALESCE(DC.SALES_VAL, 0) > 0
GROUP BY 1
	,2
	,3
	,4
	,5;
