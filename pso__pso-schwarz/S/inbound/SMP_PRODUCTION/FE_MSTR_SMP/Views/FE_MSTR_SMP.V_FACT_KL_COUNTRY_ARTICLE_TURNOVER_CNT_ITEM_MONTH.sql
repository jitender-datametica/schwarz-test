create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_KL_COUNTRY_ARTICLE_TURNOVER_CNT_ITEM_MONTH(
	CY_MONTH,
	COUNTRY_ID,
	GTIN_ID,
	ART_ID_REF,
	ART_ID_REF_KL,
	LP_TURNOVER_GROSS,
	LP_CNT_ITEM
) as
	WITH DAYAGG AS (
			SELECT DISTINCT DAY_DT
				,FACT.COUNTRY_ID
				,FACT.GTIN_ID
				,FACT.ART_ID_REF
				,CASE 
					WHEN FACT.DIVISION_ID = 'KFL'
						THEN ART.KL_ART_ID
					ELSE ART_ID_REF
					END AS ART_ID_REF_KL
				,SUM(CASE 
						WHEN SHOPPER_ID_REF IS NOT NULL
							THEN SALES_GROSS_VAL
						ELSE 0
						END) AS LP_TURNOVER_GROSS
				,SUM(CASE 
						WHEN SHOPPER_ID_REF IS NOT NULL
							THEN SALES_PIECE_QTY
						ELSE 0
						END) AS LP_CNT_ITEM
				,SUM(SALES_GROSS_VAL) TURNOVER_GROSS
				,SUM(SALES_PIECE_QTY) CNT_ITEM
			FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY FACT
			JOIN CORE_REL.T_COUNTRY LAND ON FACT.DIVISION_ID = LAND.DIVISION_ID
				AND FACT.COUNTRY_ID = LAND.COUNTRY_ID
			JOIN DATA_SHARED_KFL.DBP_DATA_ART ART ON FACT.ART_ID_REF = ART.ART_ID
				AND FACT.DIVISION_ID = 'KFL'
				AND LAND.DIVISION_COUNTRY_REF = ART.MANDANT_ID
				AND ART.DAT_BIS = '9999-12-31'
			WHERE DAY_DT BETWEEN CURRENT_DATE - 366
					AND CURRENT_DATE
				AND FACT.DIVISION_ID = 'KFL'
				AND SALES_PIECE_QTY > 0
        --        and art_id_ref_kl='1152811'
--  and day_dt between '01-JUN-2024' and '30-JUN-2024'
			GROUP BY 1
				,2
				,3
				,4
				,5
			)

SELECT DISTINCT MON.CY_MONTH
    ,DAYAGG.COUNTRY_ID    
	,DAYAGG.GTIN_ID
    ,DAYAGG.ART_ID_REF
	,DAYAGG.ART_ID_REF_KL
	,SUM(DAYAGG.LP_TURNOVER_GROSS)
	,SUM(DAYAGG.LP_CNT_ITEM)
FROM DAYAGG
JOIN FE_MSTR_SMP.V_DIM_CALENDARDAY TAG ON (DAYAGG.DAY_DT = TAG.CAL_DT)
JOIN FE_MSTR_SMP.V_DIM_CAL_MONTH MON ON (TAG.CY_MONTH = MON.CY_MONTH)
  
GROUP BY MON.CY_MONTH
    ,DAYAGG.COUNTRY_ID    
	,DAYAGG.GTIN_ID
    ,DAYAGG.ART_ID_REF
	,DAYAGG.ART_ID_REF_KL;
