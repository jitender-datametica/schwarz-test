create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_KL_COUNTRY_GTIN_BUYER_NONBUYER(
	DAY_DT,
	COUNTRY_ID,
	ART_ID_REF,
	ART_ID_REF_KL,
	GTIN_ID,
	BUYER
) as
SELECT DAY_DT
		,FACT.COUNTRY_ID
		,ART_ID_REF
		,KL_ART_ID AS ART_ID_REF_KL
		,FACT.GTIN_ID
		,COUNT(DISTINCT SHOPPER_ID_REF) BUYER
	FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY FACT
	JOIN CORE_REL.T_COUNTRY LAND ON FACT.DIVISION_ID = LAND.DIVISION_ID
		AND FACT.COUNTRY_ID = LAND.COUNTRY_ID
	JOIN DATA_SHARED_KFL.DBP_DATA_ART ART ON FACT.ART_ID_REF = ART.ART_ID
		AND FACT.DIVISION_ID = 'KFL'
		AND LAND.DIVISION_COUNTRY_REF = ART.MANDANT_ID
		AND to_char(FACT.GTIN_ID) = to_char(ART.GTIN_ID)
		AND ART.DAT_BIS = '9999-12-31'
	WHERE DAY_DT BETWEEN CURRENT_DATE - 366
			AND CURRENT_DATE
		AND FACT.DIVISION_ID = 'KFL'
		AND SHOPPER_ID_REF IS NOT NULL
	GROUP BY DAY_DT
		,FACT.COUNTRY_ID
		,ART_ID_REF
		,ART_ID_REF_KL
		,FACT.GTIN_ID;
