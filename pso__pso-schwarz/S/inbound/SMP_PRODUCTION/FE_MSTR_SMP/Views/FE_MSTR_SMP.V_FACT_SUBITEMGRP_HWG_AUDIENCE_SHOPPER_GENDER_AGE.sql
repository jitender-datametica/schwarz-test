create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_SUBITEMGRP_HWG_AUDIENCE_SHOPPER_GENDER_AGE(
	SUBITEMGRP_HWG,
	COUNTRY_ID,
	DIVISION_ID,
	GENDER,
	AGE,
	CNT_SHOPPER_SUBITEMGRP_HWG,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_GENDER AS (
			SELECT DISTINCT a14.SUBITEMGRP_HWG
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) = 'GEN'
                join	FE_MSTR_SMP.V_DIM_ITEM	a12
				on 	(FCT.COUNTRY_ID = a12.COUNTRY_ID and 
				FCT.DIVISION_ID = a12.DIVISION_ID and 
				FCT.GTIN_ID = a12.GTIN_ID)
			join	FE_MSTR_SMP.V_REL_WG_ITEMFAMILY_OWG	a13
				on 	(a12.COUNTRY_ID = a13.COUNTRY_ID and 
				a12.DIVISION_ID = a13.DIVISION_ID and 
				a12.TAXONOMY_ID = coalesce(a13.WG, a13.FAMILYGRP_OWG, a13.WG))
			join	FE_MSTR_SMP.V_REL_ITEMGRP_WG_FAMILYGROUP_OWG	a14
				on 	(a13.COUNTRY_ID = a14.COUNTRY_ID and 
				a13.DIVISION_ID = a14.DIVISION_ID and 
				a13.FAMILYGRP_OWG = a14.FAMILYGRP_OWG)
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_SUBITEMGRP_HWG AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,SUBITEMGRP_HWG
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_SUBITEMGRP_HWG
			FROM SHOPPERS_BY_GENDER
			GROUP BY 1
				,2
				,3
			)

SELECT SBG.SUBITEMGRP_HWG
	,SBG.COUNTRY_ID
	,SBG.DIVISION_ID
	,SBG.DESCR_AUDIENCE_ID AS GENDER
	,DA.DESCR_AUDIENCE_ID AS AGE
	,CNT_SHOPPER_SUBITEMGRP_HWG
	,COUNT(SBG.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_GENDER SBG
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE DA ON SBG.COUNTRY_ID = DA.COUNTRY_ID
	AND SBG.DIVISION_ID = DA.DIVISION_ID
	AND SBG.SHOPPER_ID = DA.SHOPPER_ID
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) = 'AGE'
JOIN CNT_SUBITEMGRP_HWG ON SBG.COUNTRY_ID = CNT_SUBITEMGRP_HWG.COUNTRY_ID
	AND SBG.DIVISION_ID = CNT_SUBITEMGRP_HWG.DIVISION_ID
	AND SBG.SUBITEMGRP_HWG = CNT_SUBITEMGRP_HWG.SUBITEMGRP_HWG
GROUP BY SBG.SUBITEMGRP_HWG
	,SBG.COUNTRY_ID
	,SBG.DIVISION_ID
	,SBG.DESCR_AUDIENCE_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_SUBITEMGRP_HWG;
