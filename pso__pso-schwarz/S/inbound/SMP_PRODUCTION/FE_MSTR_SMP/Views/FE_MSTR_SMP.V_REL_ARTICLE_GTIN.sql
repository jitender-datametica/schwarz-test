create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_REL_ARTICLE_GTIN(
	COUNTRY_ID,
	GTIN_ID,
	ART_ID_REF,
	ART_ID_REF_KL
) as

SELECT COUNTRY_ID
	,GTIN_ID
	,ART_ID_REF
    ,ART_ID_REF_KL
    FROM FE_MSTR_SMP.V_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY FACT
WHERE DAY_DT BETWEEN CURRENT_DATE - 366
		AND CURRENT_DATE
	AND DIVISION_ID = 'KFL'
	AND SHOPPER_ID_REF IS NOT NULL
	AND SALES_PIECE_QTY > 0;
