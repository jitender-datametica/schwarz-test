create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_REL_PERIOD_SEQUENCE(
	DIVISION_ID,
	COUNTRY_ID,
	CAMPAIGN_ID,
	CAMPAIGN_NAME,
	PERIOD,
	CY_WEEK,
	PERIOD_WEEK_SEQ
) as
SELECT 	DIVISION_ID,
	COUNTRY_ID,
	CAMPAIGN_ID,
	CAMPAIGN_NAME,
	PERIOD,
	CY_WEEK,
    PERIOD_WEEK_SEQ
    FROM 
    (
with tab1 as
(SELECT DISTINCT

	DIVISION_ID,
	COUNTRY_ID,
	CAMPAIGN_ID,
	CAMPAIGN_NAME,
	PERIOD,
	CY_WEEK
FROM
CORE.T_AB_TEST_RESULT)

SELECT 	DIVISION_ID,
	COUNTRY_ID,
	CAMPAIGN_ID,
	CAMPAIGN_NAME,
	PERIOD,
	CY_WEEK,
    ROW_NUMBER ()  OVER (PARTITION BY PERIOD ORDER BY CY_WEEK ASC) AS PERIOD_WEEK_SEQ
    FROM tab1);
