create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_REL_WG_ITEMFAMILY_OWG(
	DIVISION_ID,
	COUNTRY_ID,
	WG,
	FAMILYGRP_OWG
) as

SELECT T1.DIVISION_ID
	,T1.COUNTRY_ID
	,T2.TAXONOMY_ID WG
	,T1.TAXONOMY_ID FAMILYGRP_OWG
FROM CORE_REL.T_TAXONOMY_HIERARCHY T1
JOIN CORE_REL.T_TAXONOMY_HIERARCHY T2 ON T1.COUNTRY_ID = T2.COUNTRY_ID
	AND T1.DIVISION_ID = T2.DIVISION_ID
	AND T1.TAXONOMY_ID = T2.TAXONOMY_PARENT_ID
WHERE T1.LEVEL IN (
		3
		,4
		)

UNION ALL

SELECT T1.DIVISION_ID
	,T1.COUNTRY_ID
	,NULL AS WG
	,T1.TAXONOMY_ID FAMILYGRP_OWG
FROM CORE_REL.T_TAXONOMY_HIERARCHY T1
WHERE T1.LEVEL IN (3)
	AND T1.DIVISION_ID = 'LDL';
