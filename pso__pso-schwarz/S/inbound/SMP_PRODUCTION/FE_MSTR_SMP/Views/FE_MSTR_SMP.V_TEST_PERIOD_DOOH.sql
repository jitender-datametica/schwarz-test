create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_TEST_PERIOD_DOOH(
	CAMPAIGN_ID,
	DOOH_CAMPAIGN_NAME,
	DATE_UPDATED,
	DATE_START,
	DATE_END,
	COUNTRY_DIVISION_ID,
	CAMPAIGN_TYPE_ID,
	TIMERANGE,
	DURATION,
	DATE_START_PRE_PERIOD,
	DATE_END_PRE_PERIOD,
	WEEK_START,
	WEEK_END,
	BASELINE_START,
	BASELINE_END,
	ANALYSIS_END,
	DATE_START_PRE_CONVERSION_PERIOD,
	DATE_END_PRE_CONVERSION_PERIOD,
	BASELINE_COUNT_DAYS,
	GTIN_LIST,
	STORE_LIST,
	BUDGET_SPENT,
	DELETE_FG
) as

SELECT
CAMP.CAMPAIGN_ID,
COALESCE(DOOH_CAMPAIGN_NAME,CAMPAIGN_NAME) AS DOOH_CAMPAIGN_NAME,
DATE_UPDATED,
COALESCE(DATE_START,CAMPAIGN_START_DT) AS DATE_START,
COALESCE(DATE_END,CAMPAIGN_END_DT) AS DATE_END,
C.COUNTRY_DIVISION_ID,
COALESCE(CAMP.CAMPAIGN_TYPE_ID, TP.CAMPAIGN_TYPE_ID) AS CAMPAIGN_TYPE_ID,
CONCAT(DATE_START,'-',DATE_END) AS TIMERANGE,
DATE_END-DATE_START+1 AS DURATION,
date_start - greatest(28, ((DATE_END-DATE_START+1) * 2)) -1 AS DATE_START_PRE_PERIOD,
date_start -1 AS DATE_END_PRE_PERIOD,
    time_slice(DATE_START, 1, 'WEEK', 'START') as week_start,
    dateadd(day, -1, time_slice(DATE_END, 1, 'WEEK', 'END')) as week_end,
    dateadd(day, -6*7, week_start) as baseline_start, 
    dateadd(day, -2*7-1, week_start) as baseline_end,
    dateadd(day, 6*7, week_end) as analysis_end,
    DATE_START_PRE_PERIOD-28 AS DATE_START_PRE_CONVERSION_PERIOD, --nur für Kampagnen aus 2023, aus 2024 -42
    DATE_START_PRE_PERIOD AS DATE_END_PRE_CONVERSION_PERIOD,
    DATE_END_PRE_CONVERSION_PERIOD - DATE_START_PRE_CONVERSION_PERIOD AS BASELINE_COUNT_DAYS,
COALESCE((REPLACE (TP.GTIN_LIST, '\n', ',')),GTIN_STORE.GTIN_LIST)  AS GTIN_LIST,
COALESCE((REPLACE (TP.STORE_LIST, '\n', ',')),GTIN_STORE.STORE_LIST) AS STORE_LIST,
BUDGET_SPENT,
DELETE_FG
FROM
FE_MSTR_TEMP.T_TEST_PERIOD_DOOH TP
FULL OUTER JOIN
FE_MSTR_SMP.V_DIM_COUNTRY_SMP C
ON TP.COUNTRY_DIVISION_ID=C.COUNTRY_DIVISION_ID
LEFT OUTER JOIN
FE_MSTR_SMP.V_DIM_CAMPAIGN CAMP
ON TP.DOOH_CAMPAIGN_NAME=CAMP.CAMPAIGN_NAME
LEFT OUTER JOIN
(SELECT COALESCE(GTIN.DIVISION_ID, STORE.DIVISION_ID) AS DIVISION_ID
	,COALESCE(GTIN.COUNTRY_ID, STORE.COUNTRY_ID) AS COUNTRY_ID
	,COALESCE(GTIN.CAMPAIGN_ID, STORE.CAMPAIGN_ID) AS CAMPAIGN_ID
	,GTIN_LIST
	,STORE_LIST
FROM (
	SELECT DIVISION_ID
		,COUNTRY_ID
		,CAMPAIGN_ID
		,LISTAGG(GTIN_ID, ',') AS GTIN_LIST
	FROM CORE_REL.T_CAMPAIGN_GTIN
	WHERE SOURCE_SYSTEM_ID = 'DOOH'
	GROUP BY DIVISION_ID
		,COUNTRY_ID
		,CAMPAIGN_ID
	) GTIN
JOIN (
	SELECT DIVISION_ID
		,COUNTRY_ID
		,CAMPAIGN_ID
		,LISTAGG(STORE_ID, ',') AS STORE_LIST
	FROM CORE_REL.T_CAMPAIGN_STORE
    WHERE SOURCE_SYSTEM_ID = 'DOOH'
	GROUP BY DIVISION_ID
		,COUNTRY_ID
		,CAMPAIGN_ID
	) STORE ON GTIN.DIVISION_ID = STORE.DIVISION_ID
	AND GTIN.COUNTRY_ID = STORE.COUNTRY_ID
	AND GTIN.CAMPAIGN_ID = STORE.CAMPAIGN_ID) GTIN_STORE
  ON CAMP.DIVISION_ID = GTIN_STORE.DIVISION_ID
	AND CAMP.COUNTRY_ID = GTIN_STORE.COUNTRY_ID
	AND CAMP.CAMPAIGN_ID = GTIN_STORE.CAMPAIGN_ID;
