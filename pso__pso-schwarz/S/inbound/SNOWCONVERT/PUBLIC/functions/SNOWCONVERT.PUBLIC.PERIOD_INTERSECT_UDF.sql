CREATE OR REPLACE FUNCTION SNOWCONVERT.PUBLIC.PERIOD_INTERSECT_UDF("PERIOD_1" VARCHAR(22), "PERIOD_2" VARCHAR(22))
RETURNS VARCHAR(16777216)
LANGUAGE SQL
AS '
 CASE WHEN LEAST(PUBLIC.PERIOD_END_UDF(PERIOD_1),PUBLIC.PERIOD_END_UDF(PERIOD_2)) < GREATEST(PUBLIC.PERIOD_BEGIN_UDF(PERIOD_1),PUBLIC.PERIOD_BEGIN_UDF(PERIOD_2))
    THEN NULL
 ELSE
    PERIOD(GREATEST(PUBLIC.PERIOD_BEGIN_UDF(PERIOD_1),PUBLIC.PERIOD_BEGIN_UDF(PERIOD_2)),LEAST(PUBLIC.PERIOD_END_UDF(PERIOD_1),PUBLIC.PERIOD_END_UDF(PERIOD_2)))
 END
';