CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_COMPUTE_RESOURCE_CLUSTER(
	COMPUTE_RESOURCE_CLUSTER_SID
	,COMPUTE_RESOURCE_CLUSTER_MOID
	,COMPUTE_RESOURCE_CLUSTER_NAME
) AS SELECT
   DT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,DT1.COMPUTE_RESOURCE_CLUSTER_MOID
  ,DT1.COMPUTE_RESOURCE_CLUSTER_NAME
FROM
  CORE.T_DIM_COMPUTE_RESOURCE_CLUSTER DT1
  JOIN
  (SELECT 
      COMPUTE_RESOURCE_CLUSTER_SID
      ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
   FROM
      CORE.T_DIM_COMPUTE_RESOURCE_CLUSTER
   GROUP BY COMPUTE_RESOURCE_CLUSTER_SID) DT2
  ON DT1.COMPUTE_RESOURCE_CLUSTER_SID = DT2.COMPUTE_RESOURCE_CLUSTER_SID
  AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;