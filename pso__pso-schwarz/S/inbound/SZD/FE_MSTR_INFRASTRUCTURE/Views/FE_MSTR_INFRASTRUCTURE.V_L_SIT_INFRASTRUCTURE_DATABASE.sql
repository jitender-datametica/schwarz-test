CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_DATABASE
AS  
SELECT
 DT1.DATABASE_SID
,DT1.DATABASE_ID
,DT1.DATABASE_NAME 
FROM 
 CORE.T_DIM_DATABASE DT1
 JOIN 
 (SELECT 
   DATABASE_SID
   ,MAX(DWH_VALID_FROM_DT)AS MAX_DATE
  FROM 
   CORE.T_DIM_DATABASE
  GROUP BY 
   DATABASE_SID) DT2
 ON DT1.DATABASE_SID = DT2.DATABASE_SID 
 AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;