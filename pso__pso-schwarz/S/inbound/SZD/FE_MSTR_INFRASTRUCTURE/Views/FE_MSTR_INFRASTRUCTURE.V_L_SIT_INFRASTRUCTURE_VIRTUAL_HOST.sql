CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_VIRTUAL_HOST
AS SELECT    
 DT1.VIRTUAL_HOST_SID
,DT1.VIRTUAL_HOST_FQDN
,DT1.VIRTUAL_HOST_NAME
FROM
 CORE.T_DIM_VIRTUAL_HOST DT1
 JOIN
 (SELECT    
   VIRTUAL_HOST_SID
   ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
  FROM 
   CORE.T_DIM_VIRTUAL_HOST
  GROUP BY 
   VIRTUAL_HOST_SID) DT2
 ON DT1.VIRTUAL_HOST_SID = DT2.VIRTUAL_HOST_SID 
 AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;