CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_VIRTUAL_MACHINE(
	VM_SID
	,VM_MOID
	,VM_NAME
	,VM_INSTANCE_UUID
) AS SELECT
   DT1.VM_SID
  ,DT1.VM_MOID
  ,DT1.VM_NAME
  ,DT1.VM_INSTANCE_UUID
FROM
  CORE.T_DIM_VIRTUAL_MACHINE DT1
  JOIN
  (SELECT 
      VM_SID
      ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
   FROM
      CORE.T_DIM_VIRTUAL_MACHINE
   GROUP BY VM_SID) DT2
  ON DT1.VM_SID = DT2.VM_SID
  AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;