CREATE OR REPLACE VIEW FE_MSTR_LIFECYCLE.MV_F_LIFECYCLE_RVM_CUSTOMER_STATISTICS_PER_DAY
(
	 RVM_SID
    ,RECEIPT_GROSS_LOCAL_VAL
	,LOCAL_CURR_CD
	,RECEIPT_GROSS_GLOBAL_VAL
	,GLOBAL_CURR_CD
	,DEPOSIT_OUTPAYMENT_TYPE_CD
	,CAL_DT
    ,RECEIPT_CNT
) AS 
SELECT 
 CORE.T_FACT_DEPOSIT_RECEIPT.RVM_SID
,CORE.T_FACT_DEPOSIT_RECEIPT.RECEIPT_GROSS_LOCAL_VAL
,CORE.T_FACT_DEPOSIT_RECEIPT.LOCAL_CURR_CD
,CORE.T_FACT_DEPOSIT_RECEIPT.RECEIPT_GROSS_GLOBAL_VAL
,CORE.T_FACT_DEPOSIT_RECEIPT.GLOBAL_CURR_CD
,CORE.T_FACT_DEPOSIT_RECEIPT.DEPOSIT_OUTPAYMENT_TYPE_CD
,CORE.T_FACT_DEPOSIT_RECEIPT.RECEIPT_DT AS CAL_DT
,COUNT(CORE.T_FACT_DEPOSIT_RECEIPT.RECEIPT_NR) AS RECEIPT_CNT
FROM 
 CORE.T_FACT_DEPOSIT_RECEIPT
GROUP BY 1,2,3,4,5,6,7
;