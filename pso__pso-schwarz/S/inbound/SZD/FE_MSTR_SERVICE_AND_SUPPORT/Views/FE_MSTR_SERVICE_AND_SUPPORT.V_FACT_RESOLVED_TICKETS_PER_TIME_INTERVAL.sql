CREATE OR REPLACE VIEW FE_MSTR_SERVICE_AND_SUPPORT.V_FACT_RESOLVED_TICKETS_PER_TIME_INTERVAL(
	CY_MONTH
	, TICKET_CREATOR_DIVISION_CD
	, TICKET_CREATOR_COUNTRY_BUSINESS_CD
	, TICKET_TYPE_ID
	, DURATION_IN_DAYS
	, TICKET_RESOLVED_CNT
) AS
SELECT 
    CY_MONTH
    , TICKET_CREATOR_DIVISION_CD
    , TICKET_CREATOR_COUNTRY_BUSINSS_CD
    , TICKET_TYPE_ID
    , DURATION_IN_DAYS
    , SUM (TOTAL) AS TICKET_RESOLVED_CNT
FROM
    (
    SELECT 
        (YEAR(TICKET_RESOLVING_DT)*100 + MONTH(TICKET_RESOLVING_DT)) AS CY_MONTH
        , TICKET_TYPE_ID
        , TICKET_NR
        , TICKET_CREATION_TMSP
        , TICKET_RESOLVING_TMSP
        , AFFECTED_DIVISION_CD AS TICKET_CREATOR_DIVISION_CD
        , AFFECTED_COUNTRY_BUSINESS_CD AS TICKET_CREATOR_COUNTRY_BUSINSS_CD
        , (DATEDIFF(SECOND,TICKET_CREATION_TMSP, TICKET_RESOLVING_TMSP))/86400 AS DURATION
        , CASE
            WHEN DURATION > 30 AND TICKET_TYPE_ID IN (1,3) THEN 'E>30 Days' 
            WHEN DURATION BETWEEN 6 AND 30 AND TICKET_TYPE_ID IN (1,3) THEN 'D 6-30 Days'
            WHEN DURATION >= 3 AND DURATION < 6 AND TICKET_TYPE_ID IN (1,3) THEN 'C 3-6 Days'
            WHEN DURATION >= 1 AND DURATION < 3 AND TICKET_TYPE_ID IN (1,3) THEN 'B 1-3 Days'
            WHEN DURATION <1 AND TICKET_TYPE_ID IN (1,3) THEN 'A Up to 1 Day'
            WHEN DURATION > 90 AND TICKET_TYPE_ID = 2 THEN 'E>90 Days' 
            WHEN DURATION BETWEEN 60 AND 90 AND TICKET_TYPE_ID = 2 THEN 'D 60-90 Days'
            WHEN DURATION >= 40 AND DURATION < 60 AND TICKET_TYPE_ID = 2 THEN 'C 40-60 Days'
            WHEN DURATION >= 20 AND DURATION < 40 AND TICKET_TYPE_ID = 2 THEN 'B 20-40 Days'
            WHEN DURATION < 20 AND TICKET_TYPE_ID = 2 THEN 'A Up to 20 Days'
            ELSE 'other'
        END AS DURATION_IN_DAYS
        , 1 AS TOTAL
    FROM CORE.T_DIM_TICKET
    WHERE CURRENT_TIMESTAMP() BETWEEN DWH_VALID_FROM_TMSP AND DWH_VALID_TO_TMSP 
    )
WHERE CY_MONTH IS NOT NULL
GROUP BY 
    CY_MONTH
    , TICKET_TYPE_ID
    , DURATION_IN_DAYS
    , TICKET_CREATOR_DIVISION_CD
    , TICKET_CREATOR_COUNTRY_BUSINSS_CD
;