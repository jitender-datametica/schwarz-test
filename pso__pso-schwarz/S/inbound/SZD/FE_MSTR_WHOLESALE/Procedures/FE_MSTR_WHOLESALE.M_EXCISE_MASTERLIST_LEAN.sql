CREATE OR REPLACE PROCEDURE FE_MSTR_WHOLESALE.M_EXCISE_MASTERLIST_LEAN("ITEM_NO_SHORT" NUMBER(38,0), "SINGLE_ARTICLE_NO" NUMBER(38,0), "DWH_VALID_TO_TMSP" DATE, "DWH_VALID_FROM_TMSP" DATE, "ITEM_SHORTDESC" VARCHAR(2000), "VOLUME__IN_L_" NUMBER(38,2), "ABV_" NUMBER(38,1), "ADJUSTED_ABV__WINE_ONLY_" NUMBER(38,1), "TAX_CODE_" VARCHAR(2000), "DUTY_PER_LPA" NUMBER(38,1), "DUTY_PER_UNIT" FLOAT)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN

    LET
      V_PREVIOUS_DWH_VALID_FROM TIMESTAMP_LTZ(9) := (SELECT
          MAX(DWH_VALID_FROM_TMSP)
        FROM
          FE_MSTR_WHOLESALE.T_CACHE_EXCISE_MASTERLIST
        WHERE
          ITEM_NO_SHORT = :ITEM_NO_SHORT
          AND DWH_VALID_TO_TMSP = :DWH_VALID_TO_TMSP
          AND SINGLE_ARTICLE_NO = :SINGLE_ARTICLE_NO);


    UPDATE
      FE_MSTR_WHOLESALE.T_CACHE_EXCISE_MASTERLIST
    SET
      VOLUME__IN_L_ = :VOLUME__IN_L_,
      ABV_ = :ABV_,
      ADJUSTED_ABV__WINE_ONLY_ = :ADJUSTED_ABV__WINE_ONLY_,
      TAX_CODE_ = :TAX_CODE_,
      DUTY_PER_LPA= :DUTY_PER_LPA,
      DUTY_PER_UNIT = :DUTY_PER_UNIT,
      DWH_VALID_FROM_TMSP = :DWH_VALID_FROM_TMSP,
      PREVIOUS_DWH_VALID_FROM = :V_PREVIOUS_DWH_VALID_FROM,
      UPDATED_AT = CURRENT_TIMESTAMP
    WHERE
      ITEM_NO_SHORT = :ITEM_NO_SHORT
      AND DWH_VALID_TO_TMSP = :DWH_VALID_TO_TMSP
      AND SINGLE_ARTICLE_NO = :SINGLE_ARTICLE_NO;
      
    
    COMMIT;
    END';
    