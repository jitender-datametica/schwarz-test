CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_CONTAINER_COUNTRY_DESTINATION_CLASSIFICATION (
	CONTAINER_RESOURCE_ITEM_SID
	,CONTAINER_DEST_COUNTRY_CLASSIFICATION
	) AS

SELECT DISTINCT FACT.CONTAINER_RESOURCE_ITEM_SID
	,CASE 
		WHEN AVG(CASE 
					WHEN EU_MEMBER_FG
						THEN 1
					ELSE 0
					END) = 1
			THEN 'Nur EU-Ware'
		WHEN AVG(CASE 
					WHEN EU_MEMBER_FG
						THEN 1
					ELSE 0
					END) > 0
			AND AVG(CASE 
					WHEN EU_MEMBER_FG
						THEN 1
					ELSE 0
					END) < 1
			THEN 'Nicht EU-Ware & EU-Ware'
		WHEN AVG(CASE 
					WHEN EU_MEMBER_FG
						THEN 1
					ELSE 0
					END) = 0
			THEN 'Nur Nicht-EU-Ware'
		ELSE NULL
		END AS CONTAINER_DEST_COUNTRY_CLASSIFICATION
FROM CORE.T_FACT_LOT_LOT_PART_CONTAINER FACT
JOIN CORE.T_DIM_COUNTRY_POLITICAL COUNTRY_POL ON CASE 
		WHEN LEN(SHIPPING_DESTINATION_CD) = 3
			AND REGEXP_INSTR(SHIPPING_DESTINATION_CD, 'K') = 1
			THEN RIGHT(SHIPPING_DESTINATION_CD, 2)
		WHEN LEN(SHIPPING_DESTINATION_CD) = 3
			AND REGEXP_INSTR(SHIPPING_DESTINATION_CD, 'K') = 0
			AND SHIPPING_DESTINATION_CD <> 'CON'
			THEN LEFT(SHIPPING_DESTINATION_CD, 2)
		WHEN LEN(SHIPPING_DESTINATION_CD) = 4
			AND REGEXP_INSTR(SHIPPING_DESTINATION_CD, 'KO') = 1
			THEN RIGHT(SHIPPING_DESTINATION_CD, 2)
		WHEN LEN(SHIPPING_DESTINATION_CD) = 4
			AND REGEXP_INSTR(SHIPPING_DESTINATION_CD, 'OS') = 1
			THEN RIGHT(SHIPPING_DESTINATION_CD, 2)
		ELSE SHIPPING_DESTINATION_CD
		END = COUNTRY_POL.ISO_COUNTRY_CD
GROUP BY 1;