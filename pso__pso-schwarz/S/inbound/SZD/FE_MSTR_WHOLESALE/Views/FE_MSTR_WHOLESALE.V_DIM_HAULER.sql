CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_HAULER (
	HAULER_PARTY_SID
	,STATUS_CD
	,HAULER_NAME
	,HAULER_CD
	,HAULER_NR
	,DWH_VALID_FROM_TMSP
	,DWH_VALID_TO_TMSP
	,DWH_VALID_FG
	) AS

SELECT PARTY_SID
	,STATUS_CD
	,HAULER_NAME
	,HAULER_CD
	,HAULER_NR
	,DWH_VALID_FROM_TMSP
	,DWH_VALID_TO_TMSP
	,DWH_VALID_FG
FROM CORE.T_DIM_HAULER
WHERE DWH_VALID_FG = 1;