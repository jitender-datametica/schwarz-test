CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_LOT_DESTINATION (
	LOT_PROD_INSTANCE_GROUP_SID
	,SHIP_DESTINATION_CD
	,DELIVERY_WEEK_START_DT
	,DWH_VALID_FG
	,SHIFTED_DELIVERY_WEEK_START_DT
	,SHIP_MARK_TXT
	,LOB_CD
	,NOM_TOT_CARTON_QTY
	,BOOKED_TOT_CARTON_QTY
	,NOM_PIECE_PER_CARTON_QTY
	,BOOKED_PIECE_PER_CARTON_QTY
	,LENGTH_M_MEAS
	,WIDTH_M_MEAS
	,HEIGHT_M_MEAS
	,NET_WEIGHT_KG_QTY
	,GROSS_WEIGHT_KG_QTY
	) AS

SELECT DISTINCT LOT_PRODUCT_INSTANCE_GROUP_SID AS LOT_PROD_INSTANCE_GROUP_SID
	,SHIPPING_DESTINATION_CD AS SHIP_DESTINATION_CD
	,DELIVERY_WEEK_START_DT
	,DWH_VALID_FG
	,SHIFTED_DELIVERY_WEEK_START_DT
	,SHIPPING_MARK_TXT AS SHIP_MARK_TXT
	,LOB_CD
	,NOMINATED_TOTAL_CARTON_QTY AS NOM_TOT_CARTON_QTY
	,BOOKED_TOTAL_CARTON_QTY AS BOOKED_TOT_CARTON_QTY
	,NOMINATED_PIECE_PER_CARTON_QTY AS NOM_PIECE_PER_CARTON_QTY
	,BOOKED_PIECE_PER_CARTON_QTY
	,LENGTH_M_MEAS
	,WIDTH_M_MEAS
	,HEIGHT_M_MEAS
	,NET_WEIGHT_KG_QTY
	,GROSS_WEIGHT_KG_QTY
FROM CORE.T_DIM_LOT_DESTINATION
WHERE DWH_VALID_FG;