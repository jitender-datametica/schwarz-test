CREATE OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_QUALITY_CHECK_INSTITUTE(
    QCI_PARTY_SID
    ,DWH_VALID_FROM_TMSP
    ,DWH_VALID_TO_TMSP
    ,DWH_VALID_FG
    ,QCI_NAME
    ,QCI_NAME_TXT
    ,STATUS_CD
) AS
    SELECT
        PARTY_SID AS QCI_PARTY_SID
        ,DWH_VALID_FROM_TMSP
        ,DWH_VALID_TO_TMSP
        ,DWH_VALID_FG
        ,QCI_NAME
        ,SOURCE_QCI_NAME_ADDRESS_CITY_TXT AS QCI_NAME_TXT
        ,STATUS_CD
    FROM
        CORE.T_DIM_QUALITY_CHECK_INSTITUTE
    WHERE
        DWH_VALID_FG = 1
;