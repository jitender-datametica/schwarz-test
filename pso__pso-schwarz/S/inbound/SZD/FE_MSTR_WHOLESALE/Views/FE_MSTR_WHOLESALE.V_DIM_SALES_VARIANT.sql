CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_SALES_VARIANT (
	PRODUCT_SID
	,SALES_VARIANT_PRODUCT_GROUP_SID
	,SALES_VARIANT_NR
	,SALES_VARIANT_NAME
	,DWH_VALID_FROM
	,DWH_VALID_TO
	,DWH_VALID_FG
	) AS

SELECT PRODUCT_SID
	,SALES_VARIANT_PRODUCT_GROUP_SID
	,SALES_VARIANT_NR
	,SALES_VARIANT_NAME
	,TO_DATE(DWH_VALID_FROM_TMSP) AS DWH_VALID_FROM
	,TO_DATE(DWH_VALID_TO_TMSP) AS DWH_VALID_TO
	,DWH_VALID_FG
FROM CORE.T_DIM_SALES_VARIANT
WHERE DWH_VALID_FG = 1;