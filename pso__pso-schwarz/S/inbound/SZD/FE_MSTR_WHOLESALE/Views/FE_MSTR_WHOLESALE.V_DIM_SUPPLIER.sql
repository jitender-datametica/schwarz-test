CREATE OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_SUPPLIER (
	  PARTY_SID
	, SUPPLIER_PARTY_SID 
	, SUPPLIER_NAME
	, SOURCE_SUPPLIER_NAME_ADDRESS_CITY_TXT
	, SUPPLIER_NR
	, SORT_TXT
	, EMAIL_TXT
	, DWH_VALID_FROM_TMSP
	, DWH_VALID_TO_TMSP
	, DWH_VALID_FG
	, STATUS_CD
	, SUPPLIER_NAME_TXT
	) 
AS
SELECT 
      PARTY_SID
	, PARTY_SID AS SUPPLIER_PARTY_SID  
	, SUPPLIER_NAME
	, SOURCE_SUPPLIER_NAME_ADDRESS_CITY_TXT
	, SUPPLIER_NR
	, SORT_TXT
	, EMAIL_TXT
	, DWH_VALID_FROM_TMSP
	, DWH_VALID_TO_TMSP
	, DWH_VALID_FG
	, STATUS_CD
	, SOURCE_SUPPLIER_NAME_ADDRESS_CITY_TXT AS SUPPLIER_NAME_TXT
FROM CORE.T_DIM_SUPPLIER
WHERE DWH_VALID_FG = 1;