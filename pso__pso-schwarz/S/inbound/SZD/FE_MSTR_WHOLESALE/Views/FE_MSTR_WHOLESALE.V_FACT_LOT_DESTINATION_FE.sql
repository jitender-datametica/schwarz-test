CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_FACT_LOT_DESTINATION_FE (
	LOT_PROD_INSTANCE_GROUP_SID
	,SHIP_DESTINATION_CD
	,DELIVERY_WEEK_START_DT
	,DWH_VALID_FG
	,SHIFTED_DELIVERY_WEEK_START_DT
	,SHIP_MARK_TXT
	,NOM_TOT_CARTON_QTY
	,BOOKED_TOT_CARTON_QTY
	,NOM_PIECE_PER_CARTON_QTY
	,BOOKED_PIECE_PER_CARTON_QTY
	,LENGTH_M_MEAS
	,WIDTH_M_MEAS
	,HEIGHT_M_MEAS
	,NET_WEIGHT_KG_QTY
	,GROSS_WEIGHT_KG_QTY
	,PIECE_PER_CARTON_QTY
	,ORDERED_CARTONS_QTY
	,BOOKED_TOT_CARTON_QTY_LOT_LEVEL
	,LOT_LAND_SHARE
	,TOTAL_SHIPPED_TEU_LAND
	) AS

SELECT DISTINCT LD.LOT_PRODUCT_INSTANCE_GROUP_SID AS LOT_PROD_INSTANCE_GROUP_SID
	,LD.SHIPPING_DESTINATION_CD AS SHIP_DESTINATION_CD
	,DELIVERY_WEEK_START_DT
	,LD.DWH_VALID_FG
	,SHIFTED_DELIVERY_WEEK_START_DT
	,SHIPPING_MARK_TXT AS SHIP_MARK_TXT
	,LD.NOMINATED_TOTAL_CARTON_QTY AS NOM_TOT_CARTON_QTY
	,LD.BOOKED_TOTAL_CARTON_QTY AS BOOKED_TOT_CARTON_QTY
	,LD.NOMINATED_PIECE_PER_CARTON_QTY AS NOM_PIECE_PER_CARTON_QTY
	,LD.BOOKED_PIECE_PER_CARTON_QTY
	,LD.LENGTH_M_MEAS
	,LD.WIDTH_M_MEAS
	,LD.HEIGHT_M_MEAS
	,LD.NET_WEIGHT_KG_QTY
	,LD.GROSS_WEIGHT_KG_QTY
	,SUM(LP.PIECE_PER_CARTON_QTY) AS PIECE_PER_CARTON_QTY
	,SUM(LP.PIECE_PER_CARTON_QTY * LD.NOMINATED_TOTAL_CARTON_QTY) AS ORDERED_CARTONS_QTY
	,SUM(LD.BOOKED_TOTAL_CARTON_QTY) OVER (PARTITION BY LD.LOT_PRODUCT_INSTANCE_GROUP_SID) AS BOOKED_TOT_CARTON_QTY_LOT_LEVEL
	,DIV0(BOOKED_TOT_CARTON_QTY, BOOKED_TOT_CARTON_QTY_LOT_LEVEL) AS LOT_LAND_SHARE
	,LO.SHIPPED_TEU_MEAS * LOT_LAND_SHARE AS TOTAL_SHIPPED_TEU_LAND
FROM CORE.T_DIM_LOT_DESTINATION LD
JOIN CORE.T_DIM_LOT_PART LP ON LD.LOT_PRODUCT_INSTANCE_GROUP_SID = LP.LOT_PRODUCT_INSTANCE_GROUP_SID
	AND LD.SHIPPING_DESTINATION_CD = (
		CASE 
			WHEN LP.SHIPPING_DESTINATION_CD = 'NA'
				THEN LD.SHIPPING_DESTINATION_CD
			ELSE LP.SHIPPING_DESTINATION_CD
			END
		)
	AND LD.DWH_VALID_FG = 1
	AND LP.DWH_VALID_FG = 1
LEFT OUTER JOIN CORE.T_DIM_LOT LO ON LD.LOT_PRODUCT_INSTANCE_GROUP_SID = LO.PRODUCT_INSTANCE_GROUP_SID
	AND LO.DWH_VALID_FG = 1
WHERE TRUE
	AND LP.LOT_PART_STATUS_CD <> 'C'
	AND LD.SHIPPING_DESTINATION_CD <> 'SpareItems'
GROUP BY LD.LOT_PRODUCT_INSTANCE_GROUP_SID
	,LD.SHIPPING_DESTINATION_CD
	,DELIVERY_WEEK_START_DT
	,LD.DWH_VALID_FG
	,SHIFTED_DELIVERY_WEEK_START_DT
	,SHIPPING_MARK_TXT
	,LD.NOMINATED_TOTAL_CARTON_QTY
	,LD.BOOKED_TOTAL_CARTON_QTY
	,LD.NOMINATED_PIECE_PER_CARTON_QTY
	,LD.BOOKED_PIECE_PER_CARTON_QTY
	,LD.LENGTH_M_MEAS
	,LD.WIDTH_M_MEAS
	,LD.HEIGHT_M_MEAS
	,LD.NET_WEIGHT_KG_QTY
	,LD.GROSS_WEIGHT_KG_QTY
	,LO.SHIPPED_TEU_MEAS
	;