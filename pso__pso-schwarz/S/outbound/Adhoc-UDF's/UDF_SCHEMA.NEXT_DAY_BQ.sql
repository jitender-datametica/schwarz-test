CREATE OR REPLACE FUNCTION UDF_SCHEMA.NEXT_DAY_BQ(input_date DATE, day_name STRING) RETURNS DATE AS (
CASE
    WHEN UPPER(day_name) IN ('SU','SUN','SUNDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(SUNDAY))
    WHEN UPPER(day_name) IN ('MO','MON','MONDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(MONDAY))
    WHEN UPPER(day_name) IN ('TU','TUE','TUESDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(TUESDAY))
    WHEN UPPER(day_name) IN ('WE','WED','WEDNESDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(WEDNESDAY))
    WHEN UPPER(day_name) IN ('TH','THU','THURSDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(THURSDAY))
    WHEN UPPER(day_name) IN ('FR','FRI','FRIDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(FRIDAY))
    WHEN UPPER(day_name) IN ('SA','SAT','SATURDAY') THEN
      DATE_TRUNC(DATE_ADD(input_date, INTERVAL 1 WEEK), WEEK(SATURDAY))
    ELSE NULL
  END
);
