CREATE OR REPLACE FUNCTION snowconvert_public.teradata_interval_to_seconds(TD_INTERVAL STRING) RETURNS NUMERIC
AS (
(
  CASE WHEN SUBSTR(TD_INTERVAL, 1, 1) != '-'
       THEN 
           CASE WHEN LENGTH(TD_INTERVAL) = 10 --Bsp. 0 10:15:15
                THEN (((CAST(SUBSTR(TD_INTERVAL,1,1) AS NUMERIC)*86400) + EXTRACT(HOUR FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*3600 + EXTRACT(MINUTE FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*60 + EXTRACT(SECOND FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))))
                WHEN LENGTH(TD_INTERVAL) = 11 --Bsp. 10 10:15:15
                THEN ((CAST(SUBSTR(TD_INTERVAL,1,2) AS NUMERIC)*86400) + EXTRACT(HOUR FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*3600 + EXTRACT(MINUTE FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*60 + EXTRACT(SECOND FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME)))
                WHEN LENGTH(TD_INTERVAL) = 12 --Bsp. 100 10:15:15
                THEN ((CAST(SUBSTR(TD_INTERVAL,1,3) AS NUMERIC)*86400) + EXTRACT(HOUR FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*3600 + EXTRACT(MINUTE FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*60 + EXTRACT(SECOND FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME)))
           END
       ELSE
           CASE WHEN LENGTH(TD_INTERVAL) = 11 --Bsp. -0 10:15:15
                THEN -1*(((CAST(SUBSTR(TD_INTERVAL,2,1) AS NUMERIC)*86400) + EXTRACT(HOUR FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*3600 + EXTRACT(MINUTE FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*60 + EXTRACT(SECOND FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))))
                WHEN LENGTH(TD_INTERVAL) = 12 --Bsp. -10 10:15:15
                THEN -1* ((CAST(SUBSTR(TD_INTERVAL,2,2) AS NUMERIC)*86400) + EXTRACT(HOUR FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*3600 + EXTRACT(MINUTE FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*60 + EXTRACT(SECOND FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME)))
                WHEN LENGTH(TD_INTERVAL) = 13 --Bsp. -100 10:15:15
                THEN -1* ((CAST(SUBSTR(TD_INTERVAL,2,3) AS NUMERIC)*86400) + EXTRACT(HOUR FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*3600 + EXTRACT(MINUTE FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME))*60 + EXTRACT(SECOND FROM CAST(SUBSTR(TD_INTERVAL,-8) AS TIME)))
           END
  END
)
);