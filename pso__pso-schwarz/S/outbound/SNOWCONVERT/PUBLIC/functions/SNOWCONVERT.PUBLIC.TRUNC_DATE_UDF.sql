CREATE OR REPLACE FUNCTION snowconvert_public.trunc_date_udf(INPUT TIMESTAMP, FMT STRING) RETURNS DATE
AS (
CASE 
    -- Century
    WHEN FMT IN ('CC','SCC') THEN 
      DATE(CAST(CONCAT(SUBSTR(CAST(EXTRACT(YEAR FROM INPUT) AS STRING), 1, 2), '00') AS INT64), 1, 1)
      
    -- Year
    WHEN FMT IN ('SYYYY','YYYY','YEAR','SYEAR','YYY','YY','Y') THEN 
      DATE(EXTRACT(YEAR FROM INPUT), 1, 1)
      
    -- ISO Year
    WHEN FMT IN ('IYYY','IYY','IY','I') THEN 
      -- BigQuery EXTRACT(DAYOFWEEK) returns 1 (Sun) to 7 (Sat). 
      -- Subtracting 1 aligns it with Snowflake's 0-6 logic.
      CASE EXTRACT(DAYOFWEEK FROM DATE(EXTRACT(YEAR FROM INPUT), 1, 1)) - 1
        WHEN 0 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 1 DAY)
        WHEN 1 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 0 DAY)
        WHEN 2 THEN DATE_SUB(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 1 DAY)
        WHEN 3 THEN DATE_SUB(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 2 DAY)
        WHEN 4 THEN DATE_SUB(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 3 DAY)
        WHEN 5 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 3 DAY)
        WHEN 6 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 2 DAY)
      END        
      
    -- Month
    WHEN FMT IN ('MONTH','MON','MM','RM') THEN 
      DATE(EXTRACT(YEAR FROM INPUT), EXTRACT(MONTH FROM INPUT), 1)
      
    -- Quarter
    WHEN FMT IN ('Q') THEN 
      DATE(EXTRACT(YEAR FROM INPUT), (EXTRACT(QUARTER FROM INPUT) - 1) * 3 + 1, 1)
      
    -- Week of Year
    WHEN FMT IN ('WW') THEN 
      DATE_SUB(DATE(INPUT), INTERVAL MOD(DATE_DIFF(DATE(INPUT), DATE(EXTRACT(YEAR FROM INPUT), 1, 1), DAY), 7) DAY)
      
    -- ISO Week
    WHEN FMT IN ('IW') THEN 
      DATE_SUB(DATE(INPUT), INTERVAL MOD(DATE_DIFF(DATE(INPUT), 
        CASE EXTRACT(DAYOFWEEK FROM DATE(EXTRACT(YEAR FROM INPUT), 1, 1)) - 1
          WHEN 0 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 1 DAY)
          WHEN 1 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 0 DAY)
          WHEN 2 THEN DATE_SUB(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 1 DAY)
          WHEN 3 THEN DATE_SUB(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 2 DAY)
          WHEN 4 THEN DATE_SUB(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 3 DAY)
          WHEN 5 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 3 DAY)
          WHEN 6 THEN DATE_ADD(DATE(EXTRACT(YEAR FROM INPUT), 1, 1), INTERVAL 2 DAY)
        END, DAY), 7) DAY)
        
    -- Week of Month
    WHEN FMT IN ('W') THEN 
      DATE_SUB(DATE(INPUT), INTERVAL MOD(DATE_DIFF(DATE(INPUT), DATE(EXTRACT(YEAR FROM INPUT), EXTRACT(MONTH FROM INPUT), 1), DAY), 7) DAY)                                                             
      
    -- Day / Julian Day
    WHEN FMT IN ('DDD', 'DD','J') THEN 
      DATE(INPUT)
      
    -- Day of Week
    WHEN FMT IN ('DAY', 'DY','D') THEN 
      DATE_SUB(DATE(INPUT), INTERVAL (EXTRACT(DAYOFWEEK FROM INPUT) - 1) DAY)
      
    -- Time formats (Since it returns a DATE, time is naturally dropped)
    WHEN FMT IN ('HH', 'HH12','HH24', 'MI') THEN 
      DATE(INPUT)
  END
);