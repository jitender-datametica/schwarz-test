CREATE TABLE IF NOT EXISTS szd_core.t_fact_deposit_cash_data (
receipt_nr STRING(16777216) NOT NULL OPTIONS(description='The unique identifier for a receipt generated by the cash'),
receipt_dt DATE NOT NULL OPTIONS(description='The date of the generation of the receipt'),
receipt_tm TIME NOT NULL OPTIONS(description='The time of the generation of the receipt'),
store_nr STRING(250) NOT NULL
OPTIONS(description='The number by which the store is known to business. This number is unique for a given client_id, but not globally unique. (The same number can be in different clients).'),
deposit_receipt_nr STRING(16777216) NOT NULL OPTIONS(description='The deposit receipt number generated by the rvm.'),
country_pol_cd STRING(3) NOT NULL OPTIONS(description='The code identifying a political country according to ISO 3166.'),
lob_cd STRING(50) NOT NULL
OPTIONS(description='The code for the line of business within the Schwarz Group, i.e.Lidl or Kaufland lob=line os business'),
local_curr_cd STRING(3) NOT NULL OPTIONS(description='The code identifying the local currency according to ISO-4217.'),
deposit_outpayment_type_cd STRING(50) NOT NULL
OPTIONS(description='The code for the way how the deposit amount can be paid back to the customer. (outpayment / donation / QR code / ...'),
store_sid BIGNUMERIC NOT NULL
OPTIONS(description='The unique identifier (surrogate key) for a main store. It is identical to the key of the store that has first been assigned to this main store.'),
deposit_local_val BIGNUMERIC(38,5) NOT NULL
OPTIONS(description='The deposit value in local currency from a deposit receipt'),
dwh_created_tmsp TIMESTAMP NOT NULL
OPTIONS(description='The point in time when this record was inserted into the table.'),
dwh_updated_tmsp TIMESTAMP NOT NULL
OPTIONS(description='The point in time when this record was last modified. (In case the record has not been modified since its creation, dwh_updated is identical to dwh_created.)'),
deposit_global_val BIGNUMERIC(38,5) OPTIONS(description='The deposit value in global currency from a deposit receipt'),
global_curr_cd STRING(3) OPTIONS(description='The global currency code-now it is set as EUR'),
PRIMARY KEY (receipt_nr, receipt_dt, receipt_tm, store_sid) NOT ENFORCED
) OPTIONS(description='Transactional facts capturing the daily cash outpayment data for deposit receipts');