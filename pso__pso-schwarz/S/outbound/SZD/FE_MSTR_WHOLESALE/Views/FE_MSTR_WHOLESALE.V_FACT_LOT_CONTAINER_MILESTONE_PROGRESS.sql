 lot_etd_in_lot_fg AS etd_in_lot_fg,
 lot_latest_official_delivery_week_start_dt AS offical_delivery_week_dt,
 lot_latest_owim_offical_delivery_week_dt AS owim_offical_delivery_week_dt
FROM szd_core.t_fact_lot_container_milestone_progress;