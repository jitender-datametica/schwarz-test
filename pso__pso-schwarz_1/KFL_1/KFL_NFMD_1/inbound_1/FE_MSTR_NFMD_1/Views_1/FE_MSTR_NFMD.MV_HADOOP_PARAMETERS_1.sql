CREATE OR REPLACE VIEW FE_MSTR_NFMD.MV_HADOOP_PARAMETERS_1 AS
SELECT
	MANDANT_ID,
	CASE
		WHEN MANDANT_ID = 5 THEN 'SK'
		ELSE 'DE'
	END AS LAND_ID ,
	DISCOUNT_STEPS,
	PRICE_ENDING_THRESHOLD ,
	DISCOUNT_COUNT,
	MIN_DISCOUNT,
	MAX_DISCOUNT,
	MIN_PRICE AS MIN_VALUE,
	NO_TOUCH_TIME,
	TIME_BTW_DISCOUNTS,
	DISCOUNT_DAYS,
	MAX_DISCOUNT_FOR_MAX_PRICE,
	MAX_PRICE_FOR_MAX_DISCOUNT AS PRICE_THRESHOLD_FOR_MAX_DISCOUNT ,
	DISCOUNT_ENDING,
	/*CASE
		WHEN MANDANT_ID IN (1, 5) THEN 8
		ELSE 8
		-- use 8 weeks as default for any countries not set
	END*/
	-- use 8 weeks as default for any countries
	8 AS PROMOTION_LIFECYCLE,
	VALID_TO_NUMBER_OF_DAYS,
	DATES_BTW_DISCOUNTS,
	CREATED_AT
FROM
    CORE.TS_HADOOP_PARAMETERS_WBS_1 

QUALIFY ROW_NUMBER() OVER(PARTITION BY MANDANT_ID ORDER BY CREATED_AT DESC) = 1;
