CREATE OR REPLACE VIEW FE_MSTR_NFMD.MV_LATEST_ARTICE_CLUSTER_WB_1 AS
SELECT YEAR_ID,
       WEEK_ID,
       MANDANT_ID,
       AKTION_ID,
       SKU_ID,
       CREATED_AT AS UPDATED_DATE,
       ARTICLE_CLUSTER_ID
FROM CORE.TS_ARTICE_CLUSTER_WBS_1
    QUALIFY RANK() OVER (PARTITION BY YEAR_ID, WEEK_ID, MANDANT_ID, AKTION_ID, SKU_ID ORDER BY CREATED_AT DESC) = 1; --Gets the latest records only;