CREATE OR REPLACE PROCEDURE DBP_MACRO.M_SSM_WUP_CLUSTER_PROZESS_ZU
(
 P_MANDANT_ID NUMBER
,P_WUP_ID NUMBER
,P_NB_ID NUMBER
,P_SSM_CLUSTER_ID NUMBER
,P_SSM_PROZESS_ID NUMBER
)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
UPDATE DBP_DATA.SSM_WUP_CLUSTER_PROZESS_ZU_1
SET	SSM_CLUSTER_ID = 	:P_SSM_CLUSTER_ID
WHERE
	MANDANT_ID		= :P_MANDANT_ID
AND WUP_ID			= :P_WUP_ID
AND NB_ID			= :P_NB_ID
AND SSM_PROZESS_ID	= :P_SSM_PROZESS_ID;
COMMIT;
RETURN 'SSM_CLUSTER_ID_is_updated';
END;
$$;