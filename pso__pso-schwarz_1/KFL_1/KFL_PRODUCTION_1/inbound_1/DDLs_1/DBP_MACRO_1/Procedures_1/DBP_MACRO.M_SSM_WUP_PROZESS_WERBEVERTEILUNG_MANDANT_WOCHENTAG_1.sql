CREATE OR REPLACE PROCEDURE DBP_MACRO.M_SSM_WUP_PROZESS_WERBEVERTEILUNG_MANDANT_WOCHENTAG
(
 P_MANDANT_ID NUMBER
,P_SSM_PROZESS_ID NUMBER
,P_WTAG NUMBER
,P_WERT NUMBER

)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
MERGE INTO DBP_DATA.SSM_WUP_PROZESS_WERBEVERTEILUNG_1 AS target
USING(
   SELECT
   werbtsr.MANDANT_ID	 		AS MANDANT_ID
  ,W.WUP_ID						AS WUP_ID
  ,W.NB_ID						AS NB_ID
  ,werbtsr.SSM_PROZESS_ID 		AS SSM_PROZESS_ID
  ,T.DAT 						AS DAT
  ,werbtsr.WERT 				AS WERT
  FROM
  (SELECT 
	 :P_MANDANT_ID 			AS MANDANT_ID
	,:P_SSM_PROZESS_ID		AS SSM_PROZESS_ID
	,:P_WERT 				AS WERT
  ) werbtsr
  JOIN DBP_DATA.WUP_1 W
  ON werbtsr.MANDANT_ID = W.MANDANT_ID
  JOIN DBP_DATA.TAG_1 T
  ON :P_WTAG = T.wtag_id
  WHERE 
  	  W.NB_ID = 0
  AND W.DAT_EROEFFNUNG < '2090-12-31'
  AND T.AKT_WO BETWEEN '5' AND '52'

  
)AS source

  ON  target.MANDANT_ID 	= source.MANDANT_ID
  AND target.WUP_ID     	= source.WUP_ID
  AND target.NB_ID     		= source.NB_ID
  AND target.SSM_PROZESS_ID	= source.SSM_PROZESS_ID
  AND target.DAT			= source.DAT
  
WHEN MATCHED THEN UPDATE SET
target.WERT = source.WERT

WHEN NOT MATCHED THEN INSERT
(
  MANDANT_ID
 ,WUP_ID
 ,NB_ID 
 ,SSM_PROZESS_ID
 ,DAT
 ,WERT
)
VALUES
(
  source.MANDANT_ID
 ,source.WUP_ID
 ,source.NB_ID
 ,source.SSM_PROZESS_ID
 ,source.DAT
 ,source.WERT
);
COMMIT;
RETURN 'UPDATE/INSERT SUCCESSFUL';
END;
$$;