CREATE OR REPLACE PROCEDURE DBP_MACRO.M_VIS_WARENVERLUST_LOESCH_EINGABE (
	P_MANDANT_ID NUMBER
    , P_INVENTUR_ID NUMBER
    , P_LOESCH_FG NUMBER
) 
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER /* OWNER does not work */ 
AS $$ 

/*
	SQL MERGE Leergut :  TS Eingabe Löschung
	2025-03-20 muellerpatri : initiale Erstellung [AP0228745]
*/ 

DECLARE
	v_ergebnis VARCHAR DEFAULT 'Leergut merged'; 

BEGIN

MERGE INTO DBP_DATA.INVENTUR_WARENVERLUST_1 trgt USING (
	SELECT 
        :P_MANDANT_ID AS MANDANT_ID
        , :P_INVENTUR_ID AS INVENTUR_ID
		, :P_LOESCH_FG AS LOESCH_FG
        
	) srce
	ON trgt.INVENTUR_ID = srce.INVENTUR_ID
    AND trgt.MANDANT_ID = srce.MANDANT_ID

WHEN MATCHED THEN UPDATE 
	SET trgt.LOESCH_FG = srce.LOESCH_FG
    , trgt.TD_UPDATE = CURRENT_TIMESTAMP()
; 

COMMIT; 

RETURN v_ergebnis; 

END;
$$;