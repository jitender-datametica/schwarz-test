CREATE OR REPLACE PROCEDURE DBP_MACRO.SP_DEL_TS_WBS_CUSTOMIZING_ZEITSLOTS( -- vorher DBP_MACRO.SP_DEL_TS_PROCESSBORD_ZEITSLOTS
    P_MANDANT_ID FLOAT, 
    --P_AUSLIEFERUNGSGRUPPE_ID VARCHAR(10), 
    P_KJWO FLOAT
   -- P_ZEITSLOT_ID FLOAT
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS  
$$
BEGIN 
-- Auf Standardwerte zuruecksetzen 
DELETE FROM DBP_MSI_DATA.TS_WBS_ZEITSLOTS_AENDERUNG_1
WHERE DAT IN (SELECT dat FROM DBP_VIEW.V_TAG_1 WHERE KJWO = :P_KJWO ) AND MANDANT_ID = :P_MANDANT_ID;

    
COMMIT;
RETURN 'Zeitslot zurueckgesetzt! ';
END;
$$;