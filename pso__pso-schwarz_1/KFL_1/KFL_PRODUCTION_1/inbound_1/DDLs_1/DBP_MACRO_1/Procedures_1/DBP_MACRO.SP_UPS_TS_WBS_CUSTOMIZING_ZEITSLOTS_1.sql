CREATE OR REPLACE PROCEDURE DBP_MACRO.SP_UPS_TS_WBS_CUSTOMIZING_ZEITSLOTS( -- vorher DBP_MACRO.SP_UPS_TS_PROCESSBORD_ZEITSLOTS
    P_MANDANT_ID FLOAT, 
    P_AUSLIEFERUNGSGRUPPE_ID VARCHAR(10), 
    P_dat VARCHAR(30),
    P_ZEITSLOT_ID FLOAT)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS  
$$
BEGIN 

    MERGE INTO DBP_MSI_DATA.TS_WBS_ZEITSLOTS_AENDERUNG_1 AS TARGET 
    USING (SELECT 
           :P_MANDANT_ID AS MANDANT_ID,
           :P_AUSLIEFERUNGSGRUPPE_ID AS AUSLIEFERUNGSGRUPPE_ID,
           :P_DAT AS DAT,
           :P_ZEITSLOT_ID AS ZEITSLOT_ID   
    ) AS SOURCE
    ON TARGET.MANDANT_ID = SOURCE.MANDANT_ID 
    AND TARGET.AUSLIEFERUNGSGRUPPE_ID = SOURCE.AUSLIEFERUNGSGRUPPE_ID
    AND TARGET.DAT = SOURCE.DAT
    WHEN MATCHED THEN 
        UPDATE SET TARGET.ZEITSLOT_ID = SOURCE.ZEITSLOT_ID
    WHEN NOT MATCHED THEN 
        INSERT (MANDANT_ID, AUSLIEFERUNGSGRUPPE_ID, DAT, ZEITSLOT_ID) 
        VALUES (SOURCE.MANDANT_ID, SOURCE.AUSLIEFERUNGSGRUPPE_ID, SOURCE.DAT, SOURCE.ZEITSLOT_ID)
    ;
COMMIT;
RETURN 'Zeitslot abgespeichert! ';
END;
$$;