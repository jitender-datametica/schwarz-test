CREATE OR REPLACE PROCEDURE DBP_MSI_VIEW2.SP_UPS_AIS_DE_PROGNOSE_AVQ_EK_SAISON(
    P_CLUSTER_ID NUMBER,
    P_DAT VARCHAR,
    P_SAISON_MENGE_ABSATZ_PROGNOSE NUMBER(38,3)
)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS OWNER
AS  
$$
BEGIN

MERGE INTO DBP_MSI_VIEW2.TS_AIS_DE_PROGNOSE_AVQ_EK_SAISON_TAG_1 AS target 
USING 
    (SELECT :P_CLUSTER_ID AS CLUSTER_ID, 
    :P_DAT AS DAT, 
    :P_SAISON_MENGE_ABSATZ_PROGNOSE AS SAISON_MENGE_ABSATZ_PROGNOSE ) AS source
ON target.ek_saison_id = source.CLUSTER_ID
AND target.DAT_PROGNOSE = source.dat 

WHEN MATCHED THEN 
UPDATE SET target.MENGE_ABSATZ_PROGNOSE = source.SAISON_MENGE_ABSATZ_PROGNOSE

WHEN NOT MATCHED THEN 
INSERT (MANDANT_ID, EK_SAISON_ID, DAT_PROGNOSE, MENGE_ABSATZ_PROGNOSE)
VALUES ( 1, source.CLUSTER_ID, source.dat, source.SAISON_MENGE_ABSATZ_PROGNOSE)

;

COMMIT; 

RETURN 'Absatzprognose geaendert';

END;

$$;