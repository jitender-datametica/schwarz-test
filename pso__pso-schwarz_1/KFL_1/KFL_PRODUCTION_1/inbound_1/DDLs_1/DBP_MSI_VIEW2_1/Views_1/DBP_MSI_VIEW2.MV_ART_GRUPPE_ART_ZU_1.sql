CREATE OR REPLACE VIEW DBP_MSI_VIEW2.MV_ART_GRUPPE_ART_ZU_1
(
MANDANT_ID,
ART_ID,
UMRECH_FAKTOR,
ART_GRUPPE_ID,
ART_GRUPPE_BEZ,
ART_GRUPPE_BEREICH,
ART_GRUPPE_BEMERKUNG,
ART_GRUPPE_KATEGORIE,
DAT_ANLAGE,
DAT_AENDERUNG
)
AS
SELECT
--Anpassung neue Logik SP0239305/SPEC0326063 sschuecke 19.08.2025
v01.mandant_id,
v01.art_id,
COALESCE(v02.UMRECH_FAKTOR,0),
COALESCE(v02.ART_GRUPPE_ID,-1),
COALESCE(v03.ART_GRUPPE_BEZ,'Nicht in Artikelgruppierung'),
COALESCE(v03.ART_GRUPPE_BEREICH,'Nicht in Artikelgruppierung'),
COALESCE(v03.ART_GRUPPE_BEMERKUNG,'Nicht in Artikelgruppierung'),
COALESCE(v03.ART_GRUPPE_KATEGORIE,'Nicht in Artikelgruppierung'),
COALESCE(v03.DAT_ANLAGE,'1900-01-01'),
COALESCE(v03.DAT_AENDERUNG,'1900-01-01')

FROM DBP_DATA.ART_1 v01
LEFT JOIN DBP_DATA.ART_GRUPPE_ART_ZU_1 v02
ON v01.mandant_id = v02.MANDANT_ID
AND v01.art_id = v02.art_id
LEFT JOIN DBP_DATA.ART_GRUPPE_1 v03
ON v02.art_gruppe_id = v03.art_gruppe_id
WHERE v01.mandant_id = 1;