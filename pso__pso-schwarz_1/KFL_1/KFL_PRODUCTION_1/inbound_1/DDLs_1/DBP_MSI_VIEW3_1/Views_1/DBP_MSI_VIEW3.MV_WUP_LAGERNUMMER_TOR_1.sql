CREATE OR REPLACE VIEW DBP_MSI_VIEW3.MV_WUP_LAGERNUMMER_TOR_1 
  (
	MANDANT_ID,
	WUP_ID,
	NB_ID,
	LAGERNUMMER_ID,
	TOR_ID,
	BSFLAECHE_ID
) AS
-- 2023-01-25, dknop, adding BSFLAECHE_ID
-- 24.04.2025, INC, NWAG2310, Filter out irrelevant systems
  SELECT DISTINCT mandant_id,
   wup_id,
   nb_id,
   lagernummer_id,
   tor_id_zugeordnet AS tor_id,
   bsflaeche_id
   FROM dbp_view.v_wup_lagernummer_bsflaeche_per_1 t01 WHERE
   CAST(datzeit_bis AS DATE) = '9999-12-31' AND EXISTS (SELECT 1 FROM  DBP_DATA.L_VZ_SAP_SYSTEM_ZU_1 SVZ
JOIN DBP_DATA.L_SYSTEM_1 S ON SVZ.MANDANT_ID=S.MANDANT_ID AND SVZ.SYSTEM_ID=S.SYSTEM_ID
WHERE S.SYSTEM_GRUPPE = 'SAP LVS' AND SVZ.MANDANT_ID=T01.MANDANT_ID AND SVZ.WUP_ID = T01.WUP_ID AND SVZ.SYSTEM_ID=T01.SYSTEM_ID);