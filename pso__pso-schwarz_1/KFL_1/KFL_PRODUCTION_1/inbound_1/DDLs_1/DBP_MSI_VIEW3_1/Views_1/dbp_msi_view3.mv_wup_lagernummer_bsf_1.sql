CREATE OR REPLACE VIEW DBP_MSI_VIEW3.MV_WUP_LAGERNUMMER_BSF_1
-- 27.10.2020, AP0070828, NWAG2310, INTIAL FROM MV_WUP_LAGERNUMMER_BSFLAECHE_PER_1+MV_WUP_LAGEREINHEIT_PER_1
-- 11.11.2020, AP0070828, NWAG2310, UMSTELLUNG AUF PERSISTENTE TAG_1-STUNDE-TABELLE (PERFORMANCE)
-- 12.11.2020, AP0070828, NWAG2310, ADDED DAT
-- 12.11.2020, AP0070828, SROM0404, ADDED STUNDE_MINUTEN
-- 16.11.2020, AP0070828, NWAG2310, IMPROVED JOIN CRITERIA T02
-- 17.11.2020, AP0070828, NWAG2310, B01/BF1 INTO COLUMNS TO AVOID DUPLICATION / REMOVE LAGERPLATZ+TYP
-- 24.04.2025, INC, NWAG2310, Filter out irrelevant systems
AS
SELECT
T01.MANDANT_ID,
T01.LAGERNUMMER_ID,
T01.WUP_ID,
T01.NB_ID,
T01.BSFLAECHE_ID,
T01.DOPPELBELEGUNG_FG,
T02.DAT_ZEIT,
T02.DAT,
T02.STUNDE_MINUTEN,
T01.WARENEMPFAENGER_ID,
T01.WARENEMPFAENGER_ORIG,
T01.STATUS_VERPLANT_FG,
T01.STATUS_FIXE_EINPLANUNG_FG,
T01.REFERENZNUMMER,
T01.MAXIMALE_KAPAZITAET,
T01.VERPLANTE_KAPAZITAET,
T01.BESTAND_BSF,
T01.BESTANDSART,
T01.ANZ_PALETTEN_BSF,
T01.WE_KAPAZITAET,
T01.TOR_ID_ZUGEORDNET,
T01.STATUS_VERPLANT_IGN_FG,
T01.ANZ_SAMMELPALETTEN_BSF,
T01.ANZ_BIGBOX_BSF,
T01.BELEGTE_STP_BSF,
T01.BSF_STATUS_ID,
T01.BSF_ZONE_ID,
T01.BSF_SPERRGRUND_ID,
T01.ERHOEHTE_KAPAZITAET,
T01.KAPA_CHECK_IGN_FG,
T01.TOR_BLOCKEN_IGN_FG,
T01.BSF_SPERRGRUND_MANUELL,
COALESCE(T03.BSF_VIRTUELL_FG, 0) AS BSF_VIRTUELL_ID,
COALESCE(LEIN_B01.ANZ_LAGEREINHEIT_B01, 0) AS ANZ_LAGEREINHEIT_B01,
COALESCE(LEIN_BF1.ANZ_LAGEREINHEIT_BF1, 0) AS ANZ_LAGEREINHEIT_BF1,
COALESCE(LEIN_B01.ANZ_SPUREN_B01, 0) AS ANZ_SPUREN_B01,
COALESCE(LEIN_BF1.ANZ_SPUREN_BF1, 0) AS ANZ_SPUREN_BF1
FROM DBP_VIEW.V_WUP_LAGERNUMMER_BSFLAECHE_PER_1 T01

JOIN DBP_VIEW.V_TAG_STUNDE_1 T02
ON T02.DAT_ZEIT >= T01.DATZEIT_VON
AND T02.DAT_ZEIT < T01.DATZEIT_BIS

/* B01 */
LEFT JOIN (SELECT
T01.MANDANT_ID,
T02.DAT_ZEIT,
T01.LAGERNUMMER_ID,
T01.WUP_ID,
T01.NB_ID,
T01.SPURNUMMER,
T01.LAGERPLATZ_ID,
COUNT(DISTINCT CASE WHEN T01.LAGERTYP_ID = 'B01' THEN T01.LAGEREINHEIT_ID END) AS ANZ_LAGEREINHEIT_B01,
COUNT(DISTINCT CASE WHEN T01.LAGERTYP_ID = 'B01' THEN T01.SPURNUMMER END) AS ANZ_SPUREN_B01
FROM DBP_VIEW.V_WUP_LAGEREINHEIT_PER_1 T01
JOIN DBP_VIEW.V_TAG_STUNDE_1 T02
ON T02.DAT_ZEIT >= T01.DATZEIT_VON
AND T02.DAT_ZEIT < T01.DATZEIT_BIS
GROUP BY T01.MANDANT_ID
      ,T02.DAT_ZEIT
      ,T01.LAGERNUMMER_ID
      ,T01.WUP_ID
      ,T01.NB_ID
      ,T01.SPURNUMMER
      ,T01.LAGERPLATZ_ID
) LEIN_B01
ON T02.DAT_ZEIT            = LEIN_B01.DAT_ZEIT
AND LEIN_B01.MANDANT_ID     = T01.MANDANT_ID
AND LEIN_B01.WUP_ID         = T01.WUP_ID
AND LEIN_B01.LAGERNUMMER_ID = T01.LAGERNUMMER_ID
AND LEIN_B01.SPURNUMMER     = T01.BSFLAECHE_ID
--FÜR B01 MUSS LAGERPLATZ IN LEIN UND ZLVBSFLAECHE IDENTISCH SEIN!
AND LEIN_B01.LAGERPLATZ_ID = T01.LAGERPLATZ_ID

/* BF1 */
LEFT JOIN (SELECT
T01.MANDANT_ID,
T02.DAT_ZEIT,
T01.LAGERNUMMER_ID,
T01.WUP_ID,
T01.NB_ID,
T01.SPURNUMMER,
COUNT(DISTINCT CASE WHEN T01.LAGERTYP_ID = 'BF1' THEN T01.LAGEREINHEIT_ID END) AS ANZ_LAGEREINHEIT_BF1,
COUNT(DISTINCT CASE WHEN T01.LAGERTYP_ID = 'BF1' THEN T01.SPURNUMMER END) AS ANZ_SPUREN_BF1
FROM DBP_VIEW.V_WUP_LAGEREINHEIT_PER_1 T01
JOIN DBP_VIEW.V_TAG_STUNDE_1 T02
ON T02.DAT_ZEIT >= T01.DATZEIT_VON
AND T02.DAT_ZEIT < T01.DATZEIT_BIS
GROUP BY T01.MANDANT_ID
      ,T02.DAT_ZEIT
      ,T01.LAGERNUMMER_ID
      ,T01.WUP_ID
      ,T01.NB_ID
      ,T01.SPURNUMMER
) LEIN_BF1
ON T02.DAT_ZEIT            = LEIN_BF1.DAT_ZEIT
AND LEIN_BF1.MANDANT_ID     = T01.MANDANT_ID
AND LEIN_BF1.WUP_ID         = T01.WUP_ID
AND LEIN_BF1.LAGERNUMMER_ID = T01.LAGERNUMMER_ID
AND LEIN_BF1.SPURNUMMER     = T01.BSFLAECHE_ID

LEFT JOIN DBP_VIEW.V_WUP_LAGERNUMMER_BSFLAECHE_VIRTUELL_PER_1 T03
ON T01.MANDANT_ID     = T03.MANDANT_ID
AND T01.WUP_ID         = T03.WUP_ID
AND T01.LAGERNUMMER_ID = T03.LAGERNUMMER_ID
AND T01.BSFLAECHE_ID   = T03.BSFLAECHE_ID
AND T02.DAT BETWEEN T03.DAT_VON AND T03.DAT_BIS

WHERE T02.DAT <= CURRENT_DATE
AND EXISTS (SELECT 1 FROM  DBP_DATA.L_VZ_SAP_SYSTEM_ZU_1 SVZ
JOIN DBP_DATA.L_SYSTEM_1 S ON SVZ.MANDANT_ID=S.MANDANT_ID AND SVZ.SYSTEM_ID=S.SYSTEM_ID
WHERE S.SYSTEM_GRUPPE = 'SAP LVS' AND SVZ.MANDANT_ID=T01.MANDANT_ID AND SVZ.WUP_ID = T01.WUP_ID AND SVZ.SYSTEM_ID=T01.SYSTEM_ID)
;