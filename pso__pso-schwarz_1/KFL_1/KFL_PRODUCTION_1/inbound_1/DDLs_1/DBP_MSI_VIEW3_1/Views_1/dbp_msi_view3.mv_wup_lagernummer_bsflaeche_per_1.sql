CREATE OR REPLACE VIEW DBP_MSI_VIEW3.MV_WUP_LAGERNUMMER_BSFLAECHE_PER_1
AS
--AP0025040, ADDING JOIN TO WUP_LAGERNUMMER_BSFLAECHE_TAG, ASZU1204, 14.12.2018
--AP0025040, ADDING JOIN ON DAT_VON / DAT_BIS, ASZU1204, 17.12.2018
-- REMOVING WG_VERKETT_ID , BARANOWSKA, 13.01.2020
-- 11.11.2020, AP0070828, NWAG2310, UMSTELLUNG AUF PERSISTENTE TAG_1-STUNDE-TABELLE (PERFORMANCE)
-- 24.04.2025, INC, NWAG2310, Filter out irrelevant systems
SELECT
T01.MANDANT_ID,
T01.LAGERNUMMER_ID,
T01.WUP_ID,
T01.NB_ID,
T01.BSFLAECHE_ID,
T01.DOPPELBELEGUNG_FG,
T02.DAT_ZEIT,
T01.WARENEMPFAENGER_ID,
T01.WARENEMPFAENGER_ORIG,
T01.STATUS_VERPLANT_FG,
T01.STATUS_FIXE_EINPLANUNG_FG,
TO_VARCHAR(t01.referenznummer) AS referenznummer,
T01.MAXIMALE_KAPAZITAET,
T01.VERPLANTE_KAPAZITAET,
T01.BESTAND_BSF,
T01.BESTANDSART,
T01.ANZ_PALETTEN_BSF,
T01.WE_KAPAZITAET,
T01.TOR_ID_ZUGEORDNET,
T01.STATUS_VERPLANT_IGN_FG,
T01.ANZ_SAMMELPALETTEN_BSF,
T01.ANZ_BIGBOX_BSF,
T01.BELEGTE_STP_BSF,
T01.BSF_STATUS_ID,
T01.BSF_ZONE_ID,
T01.BSF_SPERRGRUND_ID,
T01.ERHOEHTE_KAPAZITAET,
T01.KAPA_CHECK_IGN_FG,
T01.TOR_BLOCKEN_IGN_FG,
T01.BSF_SPERRGRUND_MANUELL,
T01.LAGERPLATZ_ID,
COALESCE(T03.BSF_VIRTUELL_FG,0) AS BSF_VIRTUELL_ID
FROM DBP_VIEW.V_WUP_LAGERNUMMER_BSFLAECHE_PER_1 T01
JOIN DBP_VIEW.V_TAG_STUNDE_1 T02
ON T02.DAT_ZEIT >= T01.DATZEIT_VON AND T02.DAT_ZEIT < T01.DATZEIT_BIS
LEFT OUTER JOIN DBP_VIEW.V_WUP_LAGERNUMMER_BSFLAECHE_VIRTUELL_PER_1 T03
ON T01.MANDANT_ID=T03.MANDANT_ID AND T01.WUP_ID=T03.WUP_ID AND T01.LAGERNUMMER_ID=T03.LAGERNUMMER_ID AND T01.BSFLAECHE_ID = T03.BSFLAECHE_ID
--ADD--
AND CAST(t02.dat_zeit AS DATE) BETWEEN T03.DAT_VON AND T03.DAT_BIS
WHERE DAT_ZEIT <= CURRENT_DATE
AND EXISTS (SELECT 1 FROM  DBP_DATA.L_VZ_SAP_SYSTEM_ZU_1 SVZ
JOIN DBP_DATA.L_SYSTEM_1 S ON SVZ.MANDANT_ID=S.MANDANT_ID AND SVZ.SYSTEM_ID=S.SYSTEM_ID
WHERE S.SYSTEM_GRUPPE = 'SAP LVS' AND SVZ.MANDANT_ID=T01.MANDANT_ID AND SVZ.WUP_ID = T01.WUP_ID AND SVZ.SYSTEM_ID=T01.SYSTEM_ID)
;