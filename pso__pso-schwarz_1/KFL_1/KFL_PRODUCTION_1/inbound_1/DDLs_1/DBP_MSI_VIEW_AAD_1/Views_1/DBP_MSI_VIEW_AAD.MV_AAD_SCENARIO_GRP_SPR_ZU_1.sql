CREATE OR REPLACE VIEW DBP_MSI_VIEW_AAD.MV_AAD_SCENARIO_GRP_SPR_ZU_1 AS
--20.06.2023 snik: SPEC0200569 AAD Scenario-Gruppe_1 Sprachtabelle
   SELECT
    v01.SCENARIO_GRP_ID
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.SCENARIO_GRP_DESCR END),'N/A') AS SCENARIO_GRP_DESCR                      
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.SCENARIO_GRP_DESCR END),'N/A') AS SCENARIO_GRP_DESCR_DE                
   ,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.SCENARIO_GRP_DESCR END), SCENARIO_GRP_DESCR_DE) AS SCENARIO_GRP_DESCR_CZ
   ,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.SCENARIO_GRP_DESCR END), SCENARIO_GRP_DESCR_DE) AS SCENARIO_GRP_DESCR_SK
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.SCENARIO_GRP_DESCR END), SCENARIO_GRP_DESCR_DE) AS SCENARIO_GRP_DESCR_HR
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.SCENARIO_GRP_DESCR END), SCENARIO_GRP_DESCR_DE) AS SCENARIO_GRP_DESCR_PL
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.SCENARIO_GRP_DESCR END), SCENARIO_GRP_DESCR_DE) AS SCENARIO_GRP_DESCR_RO
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.SCENARIO_GRP_DESCR END), SCENARIO_GRP_DESCR_DE) AS SCENARIO_GRP_DESCR_BG
FROM DBP_VIEW.V_AAD_SCENARIO_GRP_SPR_ZU_1 v01
GROUP BY v01.SCENARIO_GRP_ID;