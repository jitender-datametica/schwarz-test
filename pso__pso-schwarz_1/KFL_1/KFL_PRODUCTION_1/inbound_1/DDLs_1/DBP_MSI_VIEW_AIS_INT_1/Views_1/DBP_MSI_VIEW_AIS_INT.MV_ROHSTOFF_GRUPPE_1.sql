CREATE OR REPLACE VIEW DBP_MSI_VIEW_AIS_INT.MV_ROHSTOFF_GRUPPE_1
(
 ROHSTOFF_GRUPPE_TYP_ID
,ROHSTOFF_GRUPPE_NAME
,ROHSTOFFKATEGORIE
,ROHSTOFFSUBKATEGORIE
,ROHSTOFF_GRUPPE_KURZ_NAME
)
AS
SELECT
 ROHSTOFF_GRUPPE_TYP_ID
,ROHSTOFF_GRUPPE_NAME
,CASE WHEN ROHSTOFF_GRUPPE_TYP_ID = 2 THEN ROHSTOFF_GRUPPE_NAME END AS ROHSTOFFKATEGORIE -- Basis für TS 1 + Pflege über TS 1
,CASE WHEN ROHSTOFF_GRUPPE_TYP_ID = 3 THEN ROHSTOFF_GRUPPE_NAME END AS ROHSTOFFSUBKATEGORIE -- Pflege über TS 1
,ROHSTOFF_GRUPPE_KURZ_NAME
FROM DBP_DATA.ROHSTOFF_GRUPPE_1;