CREATE OR REPLACE VIEW DBP_MSI_VIEW_AIS_INT.MV_WUP_REGION_ZU_1(
	MANDANT_ID,
	WUP_ID,
	NB_ID,
	REGION_ID
) AS SELECT
	v01.MANDANT_ID,
	v01.WUP_ID,
	v01.NB_ID,
	COALESCE(v02.WUP_CLUSTER_ID,-1) AS REGION_ID
FROM DBP_VIEW.V_WUP_1 v01
LEFT JOIN DBP_VIEW.V_TS_SCM_WUP_CLUSTER_ZU_1 v02
	ON v01.MANDANT_ID   = v02.MANDANT_ID
	AND v01.WUP_ID      = v02.WUP_ID
	AND v01.NB_ID       = v02.NB_ID
	AND v02.WUP_CLUSTER_ID IN (101,102,103,106,107,108)
	WHERE v01.NB_ID=0

UNION ALL

SELECT
	MANDANT_ID,
	WUP_ID,
	NB_ID,
	VS_ID

FROM DBP_VIEW.V_WUP_1

WHERE MANDANT_ID <> 1 AND NB_ID = 0;