           WHEN T02.wrg_typ_id = 0 AND t02.berichtskurs_typ_id = 1
           THEN (((COALESCE(T01.BETRAG_VK_NETTO_ABGANG, CAST (0. AS DECIMAL(18, 4))) * T04.KEIN_ZEKP_FG * T04.EINSTANDSPREIS) 
