CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMS_DT.MV_L_BELASTUNGS_KZ_1
(
	BELASTUNGS_KZ
)
TARGET_LAG = '1 hour, 30 minutes' 
REFRESH_MODE = FULL 
INITIALIZE = ON_CREATE 
WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMS

AS
-- 25.08.2014 twie: Initial

   SELECT

   CASE WHEN dat = CURRENT_DATE THEN 'A'
   WHEN dat = CURRENT_DATE -1 THEN 'H'
   WHEN dat = CURRENT_DATE -2 THEN 'L'
   ELSE 'S'
   END AS belastungs_kz
   FROM dbp_view.v_tag_1
   WHERE dat BETWEEN CURRENT_DATE -3 AND CURRENT_DATE
;