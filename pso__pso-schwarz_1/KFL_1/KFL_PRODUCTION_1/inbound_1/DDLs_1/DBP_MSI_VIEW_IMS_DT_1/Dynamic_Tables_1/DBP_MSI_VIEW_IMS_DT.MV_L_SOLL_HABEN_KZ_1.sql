CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMS_DT.MV_L_SOLL_HABEN_KZ_1
(
	SOLL_HABEN_KZ
)
TARGET_LAG = '1 hour, 30 minutes' 
REFRESH_MODE = FULL 
INITIALIZE = ON_CREATE 
WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMS

AS
-- 13.06.2013 AL Init

   SELECT CASE WHEN dat= CURRENT_DATE THEN  'S'
   ELSE 'H'
   END AS soll_haben_kz
   FROM dbp_view.v_tag_1
   WHERE DAT BETWEEN CURRENT_DATE -1 AND CURRENT_DATE
;