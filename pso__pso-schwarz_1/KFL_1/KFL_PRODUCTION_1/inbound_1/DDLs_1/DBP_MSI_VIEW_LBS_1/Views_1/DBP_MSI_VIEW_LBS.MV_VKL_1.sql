CREATE OR REPLACE VIEW DBP_MSI_VIEW_LBS.MV_VKL_1(
	VKL_ID,
	GF_ID,
	VKL_NAME,
	MANDANT_ID,
	SPR_ID
) AS SELECT
    V01.VKL_ID,
    V01.GF_ID,
    TRIM(V02.MA_ANREDE || ' ' || V02.MA_VORNAME || ' ' || V02.MA_NAME) AS VKL_NAME,
    V01.MANDANT_ID,
    V02.SPR_ID

FROM dbp_view.v_vkl_1 V01

JOIN dbp_view.v_ma_spr_zu_1 V02
    ON  V01.VKL_ID = V02.MA_ID;