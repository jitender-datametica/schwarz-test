CREATE OR REPLACE VIEW DBP_MSI_VIEW_NFMD.MV_NFMD_LATEST_ARTICLE_ARTICLE_CLUSTER_REL_1 AS 
SELECT KJWO_WW,
       MANDANT_ID,
       -- AKTION_ID,
       ART_ID,
       DWH_CREATED_TMSP AS UPDATED_DATE,
       ARTICLE_CLUSTER_ID
FROM DBP_MSI_VIEW_NFMD.TS_NFMD_ARTICLE_ARTICLE_CLUSTER_REL_1
    QUALIFY RANK() OVER (PARTITION BY KJWO_WW, MANDANT_ID,  ART_ID ORDER BY DWH_CREATED_TMSP DESC) = 1;