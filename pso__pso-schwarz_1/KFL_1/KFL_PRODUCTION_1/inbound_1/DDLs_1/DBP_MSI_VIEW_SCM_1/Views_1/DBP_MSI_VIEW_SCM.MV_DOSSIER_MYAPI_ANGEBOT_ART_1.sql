    SELECT angebot_nr, wup_id, art_id, mandant_id,
           MAX(CASE WHEN menge > 0 THEN 1 ELSE 0 END) AS sales_fg,
           SUM(menge) AS menge,
           SUM(umsatz_netto) AS umsatz_netto,
           SUM(absatz_af_n_loyalty_schM_BBY) AS absatz_af_n_loyalty_schM_BBY,
