           SUM(absatz_sa_loyalty) AS absatz_sa_loyalty,       
           SUM(absatz_sa_n_loyalty_BBY) AS absatz_sa_n_loyalty_BBY, 
           SUM(absatz_sa_loyalty_BBY) AS absatz_sa_loyalty_BBY,  
           SUM(absatz_sa_loyalty_KK_BBY) AS absatz_sa_loyalty_KK_BBY,       
           SUM(absatz_sa_loyalty_KK_C_BBY) AS absatz_sa_loyalty_KK_C_BBY
    FROM ab 
    GROUP BY angebot_nr, wup_id, art_id, mandant_id
) ab_agg
    ON A_ART_WUP.mandant_id = ab_agg.mandant_id
   AND A_ART_WUP.wup_id = ab_agg.wup_id
   AND A_ART_WUP.art_id = ab_agg.art_id
   AND A_ART_WUP.angebot_nr = ab_agg.angebot_nr

JOIN DBP_VIEW.V_WERBEWOCHE_KL_1 WW
    ON A.MANDANT_ID = WW.MANDANT_ID
   AND A.DAT_ANGEBOT_GUELTIG_VON = WW.DAT

JOIN DBP_VIEW.V_TAG_1 T
    ON A.DAT_ANGEBOT_GUELTIG_VON = T.DAT

JOIN DBP_VIEW.V_ART_GP_WUP_DTS_ZU_PER_1 AGW
    ON CASE WHEN A_ART_WUP.MANDANT_ID = 4 THEN 7 ELSE A_ART_WUP.MANDANT_ID END = AGW.MANDANT_ID
   AND A_ART_WUP.ART_ID = AGW.ART_ID
   AND A_ART_WUP.WUP_ID = AGW.WUP_ID
   AND A_ART_WUP.NB_ID = COALESCE(AGW.NB_ID, 0)
   AND AGW.DAT_BIS = '9999-12-31'

LEFT JOIN DBP_VIEW.V_ART_GP_NM_ZU_PER_1 A_GP
    ON A_ART_WUP.ART_ID = A_GP.ART_ID
   AND A_ART_WUP.MANDANT_ID = A_GP.MANDANT_ID
   AND A_ART_WUP.WUP_ID = A_GP.WUP_ID
   AND A_ART_WUP.NB_ID = A_GP.NB_ID
   AND A_GP.DAT_BIS = '9999-12-31'

JOIN DBP_MSI_VIEW_SCM.MV_DT_ART_SPR_ZU_1 ART_1
ON A_ART_WUP.ART_ID = ART.ART_ID
AND A_ART_WUP.MANDANT_ID = ART.MANDANT_ID

JOIN DBP_MSI_VIEW_SCM.MV_MANDANT_1 M
ON A_ART_WUP.MANDANT_ID = M.MANDANT_ID

WHERE
    A_ART_WUP.ART_ID NOT IN (0, -1)
    AND AGW.LOESCH_FG = 0
    AND A.ANGEBOT_STATUS_ID IN (4, 6)
    AND A.TRANSFER_STATUS_ID IN (0, 3, 5, 6)
    AND A.ANGEBOT_GELOESCHT_FG = 0
    AND CASE
            WHEN A_ART_WUP.MANDANT_ID = 7
                 AND A.ANGEBOT_TYP_CD NOT IN ('ZAI', 'ZAIR', 'ZAIM') THEN 1
            WHEN A_ART_WUP.MANDANT_ID = 1
                 AND A.ANGEBOT_TYP_CD NOT IN ('ZAI', 'ZAIR', 'ZAIM') THEN 1
            WHEN A.ANGEBOT_TYP_CD NOT IN ('0009','ZAI','ZAIR','ZAIM','0010','ZB09','ZB10') THEN 1
            ELSE 0
        END = 1
    AND EXISTS (
        SELECT 1
        FROM DBP_VIEW.V_ART_LIST_WUP_ZU_PER_1 V_ART_LIST
        WHERE CURRENT_DATE - 1 BETWEEN V_ART_LIST.DAT_VON AND V_ART_LIST.DAT_BIS
          AND A_ART_WUP.MANDANT_ID = V_ART_LIST.MANDANT_ID
          AND A_ART_WUP.WUP_ID     = V_ART_LIST.WUP_ID
          AND A_ART_WUP.ART_ID     = V_ART_LIST.ART_ID
    )
    AND CURRENT_DATE BETWEEN DAT_ANGEBOT_GUELTIG_VON AND DAT_ANGEBOT_GUELTIG_BIS 
    AND t.akt_kj = 0;
