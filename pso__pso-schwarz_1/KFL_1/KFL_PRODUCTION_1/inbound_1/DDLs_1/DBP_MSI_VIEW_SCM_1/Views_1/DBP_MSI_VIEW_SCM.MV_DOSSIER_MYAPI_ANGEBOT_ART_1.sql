AND A.DAT_ANGEBOT_GUELTIG_BIS = AVQ_W.DAT_AKTION_BIS
AND A_ART_WUP.ART_ID = AVQ_W.ART_ID
AND A_ART_WUP.MANDANT_ID = AVQ_W.MANDANT_ID
AND A_ART_WUP.WUP_ID = AVQ_W.WUP_ID

