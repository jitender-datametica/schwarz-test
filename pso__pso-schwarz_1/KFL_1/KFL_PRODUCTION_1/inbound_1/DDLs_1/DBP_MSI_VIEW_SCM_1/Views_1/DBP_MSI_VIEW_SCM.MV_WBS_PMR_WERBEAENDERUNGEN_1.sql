CREATE OR REPLACE VIEW DBP_MSI_VIEW_SCM.MV_WBS_PMR_WERBEAENDERUNGEN_1(
  MANDANT_ID
 ,ART_ID
 ,OFFER_ID
 ,AKTION_ID
 ,DAT_BELADUNG
 ,DAT_AB
 ,DAT_BIS
 ,KJWO
 ,WERBETHEMA_VORTAG_BEZ
 ,TITEL_FG
 ,RUECKSEITE_FG
 ,TV_FG
 ,ANZ_TAGE_WERBUNG
 ,WERBEAENDERUNG_MARKTANZAHLERHOEHUNG_FG
 ,WERBEAENDERUNG_MARKTANZAHLREDUKTION_FG
 ,WERBEAENDERUNG_ABBILDUNGSAENDERUNG_FG
 ,RABATTAENDERUNG_FG
 ,PMR_WERBETHEMA_ID
 ,PMR_WERBETHEMA_BESCHREIBUNG
 ,PREIS_AKTION
 ,PREIS_AKTION_VORLAUF
 ,PREIS_NORMAL
 ,PREIS_NORMAL_VORLAUF
 ,BONUSKAUF_FG
 ,BONUSKAUF_GESCHAEFTSVORFALL_ID
 ,BONUSKAUF_PROMOTIONSTYP
 ,WERBEMITTEL_ART_ID
 ,WERBEMITTEL_ID
 ,WERBEFLAECHE_ABSCHNITT_NAME
 ,werbeflaeche_thema_id
 ,NORMALPREISAENDERUNG_FG
 ,AKTIONSPREISAENDERUNG_FG
 ,WERBEAENDERUNG_ARTIKELENTFERNUNG_FG
 ,WERBEAENDERUNG_ARTIKELNEUANLAGE_FG
 ,ANZAHL_ARTIKELENTFERNUNG
 ,ANZAHL_ARTIKELNEUANLAGE
 ,ANZAHL_WUP
 ,ARTIKELENTFERNUNG_ART_FG
 ,ARTIKELNEUANLAGE_ART_FG
 ,ANZAHL_MARKT_OUT
 ,ANZAHL_MARKT_IN
) AS
SELECT 
  WBS.MANDANT_ID
,WBS.ART_ID
,WBS.OFFER_ID
,WBS.AKTION_ID
,WBS.DAT_BELADUNG
,WBS.DAT_AB
,WBS.DAT_BIS
,WBS.KJWO
,MAX(WBS.WERBETHEMA_VORTAG_BEZ)
,MAX(WBS.TITEL_FG)
,MAX(WBS.RUECKSEITE_FG)
,MAX(WBS.TV_FG)
,MAX(WBS.ANZ_TAGE_WERBUNG)
,MAX(WBS.WERBEAENDERUNG_MARKTANZAHLERHOEHUNG_FG)
,MAX(WBS.WERBEAENDERUNG_MARKTANZAHLREDUKTION_FG)
,MAX(WBS.WERBEAENDERUNG_ABBILDUNGSAENDERUNG_FG)
,MAX(WBS.RABATTAENDERUNG_FG)
,MAX(PMR.PMR_WERBETHEMA_ID)
,MAX(PMR.PMR_WERBETHEMA_BESCHREIBUNG)
,WBS.PREIS_AKTION
,WBS.PREIS_AKTION_VORLAUF
,WBS.PREIS_NORMAL
,WBS.PREIS_NORMAL_VORLAUF
,MAX(PMR.BONUSKAUF_FG)
,MAX(RIGHT('00' || COALESCE(PMR.BONUSKAUF_GESCHAEFTSVORFALL_ID::VARCHAR(2),''),2)) AS BONUSKAUF_GESCHAEFTSVORFALL_ID
,MAX(PMR.BONUSKAUF_PROMOTIONSTYP)
,PMR_WM.WERBEMITTEL_ART_ID
,PMR_WM.WERBEMITTEL_ID
,PMR_WM.WERBEFLAECHE_ABSCHNITT_NAME
,PMR_WM.werbeflaeche_thema_id
,MAX(WBS.NORMALPREISAENDERUNG_FG)
,MAX(WBS.AKTIONSPREISAENDERUNG_FG)
,MAX(WERBEAENDERUNG_ARTIKELENTFERNUNG_FG)
,MAX(WERBEAENDERUNG_ARTIKELNEUANLAGE_FG)
,MAX(WBS.ANZAHL_ARTIKELENTFERNUNG)
,MAX(WBS.ANZAHL_ARTIKELNEUANLAGE)
,COUNT(DISTINCT WBS.WUP_ID)
,MAX(IFF(WBS.ANZAHL_ARTIKELENTFERNUNG = WBS.ANZAHL_WUP, 1, 0 )) AS ARTIKELENTFERNUNG_ART_FG
,MAX(IFF(WBS.ANZAHL_ARTIKELNEUANLAGE = WBS.ANZAHL_WUP, 1, 0 )) AS ARTIKELNEUANLAGE_ART_FG
,MAX(WBS.ANZAHL_MARKT_OUT)
,MAX(WBS.ANZAHL_MARKT_IN)
FROM (SELECT DISTINCT WBS_inner.MANDANT_ID_VZ
,WBS_inner.MANDANT_ID
,WBS_inner.WUP_ID
,WBS_inner.ART_ID
,WBS_inner.OFFER_ID
,WBS_inner.AKTION_ID
,WBS_inner.DAT_BELADUNG
,WBS_inner.DAT_AB
,WBS_inner.DAT_BIS
,WBS_inner.KJWO
,COALESCE(WBS_inner.WERBETHEMA_VORTAG_BEZ,' ') AS WERBETHEMA_VORTAG_BEZ
,WBS_inner.TITEL_FG
,WBS_inner.RUECKSEITE_FG
,WBS_inner.TV_FG
,WBS_inner.ANZ_TAGE_WERBUNG
,WBS_inner.WERBEAENDERUNG_MARKTANZAHLERHOEHUNG_FG
,WBS_inner.WERBEAENDERUNG_MARKTANZAHLREDUKTION_FG
,WBS_inner.WERBEAENDERUNG_ABBILDUNGSAENDERUNG_FG
,WBS_inner.RABATTAENDERUNG_FG
,WBS_inner.PREIS_AKTION
,WBS_inner.PREIS_AKTION_VORLAUF
,WBS_inner.PREIS_NORMAL
,WBS_inner.PREIS_NORMAL_VORLAUF
,CASE WHEN WBS_inner.PREIS_NORMAL <> WBS_inner.PREIS_NORMAL_VORLAUF THEN 1 ELSE 0 END AS NORMALPREISAENDERUNG_FG
,CASE WHEN WBS_inner.PREIS_AKTION <> WBS_inner.PREIS_AKTION_VORLAUF THEN 1 ELSE 0 END AS AKTIONSPREISAENDERUNG_FG
,WBS_inner.WERBEAENDERUNG_ARTIKELENTFERNUNG_FG
,WBS_inner.WERBEAENDERUNG_ARTIKELNEUANLAGE_FG
,COUNT(DISTINCT WBS_inner.WUP_ID) OVER (PARTITION BY WBS_inner.MANDANT_ID_VZ, WBS_inner.ART_ID, WBS_inner.AKTION_ID, WBS_inner.DAT_BELADUNG) AS ANZAHL_WUP
,SUM(WBS_inner.WERBEAENDERUNG_ARTIKELENTFERNUNG_FG) OVER (PARTITION BY WBS_inner.MANDANT_ID_VZ, WBS_inner.ART_ID, WBS_inner.AKTION_ID, WBS_inner.DAT_BELADUNG) AS ANZAHL_ARTIKELENTFERNUNG
,SUM(WBS_inner.WERBEAENDERUNG_ARTIKELNEUANLAGE_FG) OVER (PARTITION BY WBS_inner.MANDANT_ID_VZ, WBS_inner.ART_ID, WBS_inner.AKTION_ID, WBS_inner.DAT_BELADUNG) AS ANZAHL_ARTIKELNEUANLAGE
,SUM(WBS_inner.WERBEAENDERUNG_MARKTANZAHLREDUKTION_FG) OVER (PARTITION BY WBS_inner.MANDANT_ID_VZ, WBS_inner.ART_ID, WBS_inner.AKTION_ID, WBS_inner.DAT_BELADUNG) AS ANZAHL_MARKT_OUT
,SUM(WBS_inner.WERBEAENDERUNG_MARKTANZAHLERHOEHUNG_FG) OVER (PARTITION BY WBS_inner.MANDANT_ID_VZ, WBS_inner.ART_ID, WBS_inner.AKTION_ID, WBS_inner.DAT_BELADUNG) AS ANZAHL_MARKT_IN
FROM DBP_VIEW.V_WBS_WERBEAENDERUNGEN_1 WBS_inner
) WBS 
 
JOIN DBP_VIEW.V_PMR_ANGEBOT_ART_WUP_ZU_1 PMR 
ON WBS.MANDANT_ID=PMR.MANDANT_ID
AND WBS.WUP_ID=PMR.WUP_ID
AND WBS.ART_ID=PMR.ART_ID
AND WBS.OFFER_ID=PMR.ANGEBOT_ID
AND WBS.AKTION_ID=PMR.AKTION_ID
 
JOIN  DBP_VIEW.V_PMR_ANGEBOT_WERBEMITTEL_WERBEFLAECHE_ZU_1 PMR_WM
ON PMR_WM.MANDANT_ID=PMR.MANDANT_ID
AND PMR_WM.ANGEBOT_ID=PMR.ANGEBOT_ID

GROUP BY WBS.MANDANT_ID
,WBS.ART_ID
,WBS.OFFER_ID
,WBS.AKTION_ID
,WBS.DAT_BELADUNG
,WBS.DAT_AB
,WBS.DAT_BIS
,WBS.KJWO
,PMR_WM.WERBEMITTEL_ART_ID
,PMR_WM.WERBEMITTEL_ID
,PMR_WM.WERBEFLAECHE_ABSCHNITT_NAME
,PMR_WM.werbeflaeche_thema_id
,WBS.PREIS_AKTION
,WBS.PREIS_AKTION_VORLAUF
,WBS.PREIS_NORMAL
,WBS.PREIS_NORMAL_VORLAUF
;