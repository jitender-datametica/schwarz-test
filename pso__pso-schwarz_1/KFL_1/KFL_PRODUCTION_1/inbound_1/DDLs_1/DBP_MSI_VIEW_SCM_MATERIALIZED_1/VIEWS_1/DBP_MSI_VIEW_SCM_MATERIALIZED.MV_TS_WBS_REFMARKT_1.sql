create or replace view DBP_MSI_VIEW_SCM_MATERIALIZED.MV_TS_WBS_REFMARKT_1(
	MANDANT_ID,
	WUP_ID,
	NB_ID,
	WUP_ID_REF,
	NB_ID_REF,
	REF_FAKTOR_FALLBACK,
	MANDANT_ID_VZ_FALLBACK,
	WUP_ID_VZ_FALLBACK,
	NB_ID_VZ_FALLBACK,
	FIXAMOUNT_SHARE_ALG_500,
	FIXAMOUNT_SHARE_ALG_120,
	ESTIMATION_FG,
	ADJUSTMENT_FG
) as

SELECT  
    wup.MANDANT_ID,
	wup.WUP_ID,
	wup.NB_ID,
    ref.WUP_ID_REF,
    ref.NB_ID_REF,
    ref.REF_FAKTOR_FALLBACK,
    ref.MANDANT_ID_VZ_FALLBACK,
    ref.WUP_ID_VZ_FALLBACK,
    ref.NB_ID_VZ_FALLBACK,
    ref.FIXAMOUNT_SHARE_ALG_500,
    ref.FIXAMOUNT_SHARE_ALG_120,
    
    COALESCE(ref.ESTIMATION_FG,  1) AS ESTIMATION_FG,
    COALESCE(ref.ADJUSTMENT_ID,  1) AS ADJUSTMENT_FG
FROM DBP_VIEW.V_WUP_1 wup_1 
    

    LEFT JOIN DBP_MSI_DATA.ts_wbs_refmarkt_1 ref
        ON (ref.MANDANT_ID = wup.MANDANT_ID AND ref.WUP_ID = wup.WUP_ID AND ref.NB_ID = wup.NB_ID)
    






WHERE wup.NB_ID = 0;