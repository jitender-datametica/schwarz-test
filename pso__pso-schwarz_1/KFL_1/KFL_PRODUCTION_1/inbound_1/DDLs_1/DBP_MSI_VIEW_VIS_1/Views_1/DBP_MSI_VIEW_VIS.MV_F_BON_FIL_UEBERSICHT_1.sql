                  SELECT
                  mandant_id,
                  nb_id,
                  wup_id,
                  dat,
                  CAST(CASE WHEN anz_ec_cash<>0 THEN  anz_ec_cash*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_ec_cash,
                  CAST(anz_ec_cash AS INTEGER) AS anz_ec_cash,
                  CAST(CASE WHEN anz_mp_1<>0 THEN anz_mp_1*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_1,
                  CAST(anz_mp_1 AS INTEGER) AS anzahl_mp1,
                  CAST(anz_ec_mp_1 AS INTEGER) AS anzahl_ec_mp1,
                  CAST(CASE WHEN anz_mp_10<>0 THEN  anz_mp_10*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_10,
                  CAST(anz_mp_10 AS INTEGER) AS anzahl_mp10,
                  CAST(CASE WHEN anz_mp_13_10euro<>0 THEN  anz_mp_13_10euro*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_13_10euro,
                  CAST(anz_mp_13_10euro AS INTEGER) AS anzahl_mp13_10euro,
                  CAST(CASE WHEN anz_mp_13_50euro<>0 THEN  anz_mp_13_50euro*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_13_50euro,
                  CAST(anz_mp_13_50euro AS INTEGER) AS anzahl_mp13_50euro,
                  CAST(CASE WHEN anz_mp_14<>0 THEN  anz_mp_14*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_14,
                  CAST(anz_mp_14 AS INTEGER) AS anzahl_mp14,
                  CAST(CASE WHEN anz_mp_16<>0 THEN  anz_mp_16*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_16,
                  CAST(anz_mp_16 AS INTEGER) AS anzahl_mp16,
                  CAST(CASE WHEN anz_mp_2<>0 THEN  anz_mp_2*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_2,
                  CAST(anz_mp_2 AS INTEGER) AS anzahl_mp2,
                  CAST(anz_ec_mp_2 AS INTEGER) AS anzahl_ec_mp2,
                  CAST(CASE WHEN anz_mp_3<>0 THEN  anz_mp_3*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_3,
                  CAST(anz_mp_3 AS INTEGER) AS anzahl_mp3,
                  CAST(anz_ec_mp_3 AS INTEGER) AS anzahl_ec_mp3,
                  CAST(CASE WHEN anz_mp_5_6<>0 THEN  anz_mp_5_6*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_5_6,
                  CAST(anz_mp_5_6 AS INTEGER) AS anzahl_mp5_6,
                  CAST(CASE WHEN anz_mp_5<>0 THEN  anz_mp_5*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_5,
                  CAST(anz_mp_5 AS INTEGER) AS anzahl_mp5,
                  CAST(CASE WHEN anz_mp_6<>0 THEN  anz_mp_6*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_6,
                  CAST(anz_mp_6 AS INTEGER) AS anzahl_mp6,
                  CAST(CASE WHEN anz_mp_9<>0 THEN  anz_mp_9*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_9,
                  CAST(anz_mp_9 AS INTEGER) AS anzahl_mp9,
                  CAST(CASE WHEN anz_mp_7_8<>0 THEN  anz_mp_7_8*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_7_8,
                  CAST(anz_mp_7_8 AS INTEGER) AS anzahl_mp7_8,
                  CAST(CASE WHEN anz_mp_7<>0 THEN  anz_mp_7*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_7,
                  CAST(anz_mp_7 AS INTEGER) AS anzahl_mp7,
                  CAST(CASE WHEN anz_mp_8<>0 THEN  anz_mp_8*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_mp_8,
                  CAST(anz_mp_8 AS INTEGER) AS anzahl_mp8,
                  CAST(CASE WHEN anz_wg_1<>0 THEN  anz_wg_1*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_wg_1,
                  CAST(anz_wg_1 AS INTEGER) AS anz_wg_1,
                  CAST(CASE WHEN anz_wg_2<>0 THEN  anz_wg_2*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_wg_2,
                  CAST(anz_wg_2 AS INTEGER) AS anz_wg_2,
                  CAST(CASE WHEN anz_wg_3<>0 THEN anz_wg_3*100/anz_bons ELSE 0 END AS DECIMAL (18,4)) AS anteil_wg_3,
                  CAST(anz_wg_3 AS INTEGER) AS anz_wg_3,
                  CAST(anz_mp_1+anz_mp_2+anz_mp_3 AS INTEGER) AS anz_bon_storno,
                  CAST(anz_mp_5_6+anz_mp_7_8+anz_mp_13_10euro+anz_mp_14+anz_mp_16 AS INTEGER) AS anz_bon_freundschaft,
                  CAST(anz_mp_9+anz_mp_10 AS INTEGER) AS anz_bon_leergut,
                  CAST(anz_bons AS INTEGER) AS bons_ges,
                  CAST(anz_mp_bons AS INTEGER) AS bons_nicht_ok,
                  SUBSTR('000',1,3- LENGTH(TRIM(CAST(CAST(wg_1 AS INTEGER) AS CHAR(3)))))|| TRIM(CAST(CAST(wg_1 AS INTEGER) AS CHAR(3))) AS wg_1,
                  SUBSTR('000',1,3- LENGTH(TRIM(CAST(CAST(wg_2 AS INTEGER) AS CHAR(3)))))|| TRIM(CAST(CAST(wg_2 AS INTEGER) AS CHAR(3))) AS wg_2,
                  SUBSTR('000',1,3- LENGTH(TRIM(CAST(CAST(wg_3 AS INTEGER) AS CHAR(3)))))|| TRIM(CAST(CAST(wg_3 AS INTEGER) AS CHAR(3))) AS wg_3
                  FROM
                  ( --td1
                  SELECT
                  dt1.mandant_id,
                  dt1.nb_id,
                  dt1.wup_id,
                  CURRENT_DATE AS dat,
                  MAX(dt1.anz_bons) AS anz_bons,
                  MAX(dt1.anz_mp_bons) AS anz_mp_bons,
                  MAX(dt1.anz_ec_cash) AS anz_ec_cash,
                  MAX(dt1.anz_mp_1) AS anz_mp_1,
                  MAX(dt1.anz_ec_mp_1) AS anz_ec_mp_1,
                  MAX(dt1.anz_mp_10) AS anz_mp_10,
                  MAX(dt1.anz_mp_13_10euro) AS anz_mp_13_10euro,
                  MAX(dt1.anz_mp_13_50euro) AS anz_mp_13_50euro,
                  MAX(dt1.anz_mp_14) AS anz_mp_14,
                  MAX(dt1.anz_mp_16) AS anz_mp_16,
                  MAX(dt1.anz_mp_2) AS anz_mp_2,
                  MAX(dt1.anz_ec_mp_2) AS anz_ec_mp_2,
                  MAX(dt1.anz_mp_3) AS anz_mp_3,
                  MAX(dt1.anz_ec_mp_3) AS anz_ec_mp_3,
                  MAX(dt1.anz_mp_5_6) AS anz_mp_5_6,
                  MAX(dt1.anz_mp_5) AS anz_mp_5,
                  MAX(dt1.anz_mp_6) AS anz_mp_6,
                  MAX(dt1.anz_mp_9) AS anz_mp_9,
                  MAX(dt1.anz_mp_7_8) AS anz_mp_7_8,
                  MAX(dt1.anz_mp_7) AS anz_mp_7,
                  MAX(dt1.anz_mp_8) AS anz_mp_8,
                  MAX(dt1.wg_1) AS wg_1,
                  MAX(dt1.wg_2) AS wg_2,
                  MAX(dt1.wg_3) AS wg_3,
                  MAX(dt1.anz_wg_1) AS anz_wg_1,
                  MAX(dt1.anz_wg_2) AS anz_wg_2,
                  MAX(dt1.anz_wg_3) AS anz_wg_3
                  FROM
                  ( --dt1
                  SELECT
                  t1.mandant_id,
                  t1.nb_id,
                  t1.wup_id,
                  CAST(MAX(t1.bon_anz_ges) AS DECIMAL(18,3)) AS anz_bons,
                  CAST(SUM(CASE WHEN t1.mp_id = 131 THEN 0 ELSE t1.bon_anz_mp END) AS DECIMAL(18,3)) AS anz_mp_bons,
                  CAST(0 AS DECIMAL(18,3)) AS anz_ec_cash,
                  CAST(SUM(CASE WHEN t1.mp_id = 1   THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_1,
                  CAST(SUM(CASE WHEN t1.mp_id = 1   THEN  t1.bon_anz_ec ELSE 0 END) AS DECIMAL (18,4)) AS anz_ec_mp_1,
                  CAST(SUM(CASE WHEN t1.mp_id = 10  THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_10,
                  CAST(SUM(CASE WHEN t1.mp_id = 130 THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_13_10euro,
                  CAST(SUM(CASE WHEN t1.mp_id = 131 THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_13_50euro,
                  CAST(SUM(CASE WHEN t1.mp_id = 14  THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_14,
                  CAST(SUM(CASE WHEN t1.mp_id = 16  THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_16,
                  CAST(SUM(CASE WHEN t1.mp_id = 2   THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_2,
                  CAST(SUM(CASE WHEN t1.mp_id = 2   THEN  t1.bon_anz_ec ELSE 0 END) AS DECIMAL (18,4)) AS anz_ec_mp_2,
                  CAST(SUM(CASE WHEN t1.mp_id = 3   THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_3,
                  CAST(SUM(CASE WHEN t1.mp_id = 3   THEN  t1.bon_anz_ec ELSE 0 END) AS DECIMAL (18,4)) AS anz_ec_mp_3,
                  CAST(SUM(CASE WHEN t1.mp_id = 5 OR t1.mp_id = 6 THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_5_6,
                  CAST(SUM(CASE WHEN t1.mp_id = 5   THEN t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_5,
                  CAST(SUM(CASE WHEN t1.mp_id = 6   THEN t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_6,
                  CAST(SUM(CASE WHEN t1.mp_id = 9   THEN  t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_9,
                  CAST(SUM(CASE WHEN t1.mp_id = 7 OR t1.mp_id = 8 THEN  t1.bon_anz_mp ELSE 0 END)  AS DECIMAL (18,4)) AS anz_mp_7_8,
                  CAST(SUM(CASE WHEN t1.mp_id = 7   THEN t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_7,
                  CAST(SUM(CASE WHEN t1.mp_id = 8   THEN t1.bon_anz_mp ELSE 0 END) AS DECIMAL (18,4)) AS anz_mp_8,
                  NULL AS wg_1,
                  NULL AS wg_2,
                  NULL AS wg_3,
                  CAST(0 AS DECIMAL(18,4))  AS anz_wg_1,
                  CAST(0 AS DECIMAL(18,4))  AS anz_wg_2,
                  CAST(0 AS DECIMAL(18,4))  AS anz_wg_3
                  FROM dbp_bda_view.v_bon_wup_anz_anym t1_1
                  GROUP BY t1.mandant_id,
                  t1.nb_id,
                  t1.wup_id

                  UNION ALL

                  SELECT
                  t2.mandant_id,
                  t2.nb_id,
                  t2.wup_id,
                  0 AS anz_bons,
                  0 AS anz_mp_bons,
                  CAST(COUNT(t1.bon_id) AS DECIMAL (18,3)) AS anz_ec_cash,
                  0 AS anz_mp_1,
                  0 AS anz_ec_mp1,
                  0 AS anz_mp_10,
                  0 AS anz_mp_13_10euro,
                  0 AS anz_mp_13_50euro,
                  0 AS anz_mp_14,
                  0 AS anz_mp_16,
                  0 AS anz_mp_2,
                  0 AS anz_ec_mp2,
                  0 AS anz_mp_3,
                  0 AS anz_ec_mp3,
                  0 AS anz_mp_5_6,
                  0 AS anz_mp_5,
                  0 AS anz_mp_6,
                  0 AS anz_mp_9,
                  0 AS anz_mp_7_8,
                  0 AS anz_mp_7,
                  0 AS anz_mp_8,
                  NULL AS wg_1,
                  NULL AS wg_2,
                  NULL AS wg_3,
                  0 AS anz_wg_1,
                  0 AS anz_wg_2,
                  0 AS anz_wg_3

                  FROM dbp_bda_view.v_kasse_zahlung_anym t1_1
                  INNER JOIN dbp_bda_view.v_kasse_kopf_anym t2
                  ON t2.dat_bon = t1.dat_bon
                  AND t2.bon_id = t1.bon_id
                  WHERE blz<>0
                  GROUP BY t2.mandant_id,
                  t2.nb_id,
                  t2.wup_id

                  UNION ALL

                  SELECT
                  t1.mandant_id,
                  t1.nb_id,
                  t1.wup_id,
                  0 AS anz_bons,
                  0 AS anz_mp_bons,
                  0 AS anz_ec_cash,
                  0 AS anz_mp_1,
                  0 AS anz_ec_mp1,
                  0 AS anz_mp_10,
                  0 AS anz_mp_13_10euro,
                  0 AS anz_mp_13_50euro,
                  0 AS anz_mp_14,
                  0 AS anz_mp_16,
                  0 AS anz_mp_2,
                  0 AS anz_ec_mp2,
                  0 AS anz_mp_3,
                  0 AS anz_ec_mp3,
                  0 AS anz_mp_5_6,
                  0 AS anz_mp_5,
                  0 AS anz_mp_6,
                  0 AS anz_mp_9,
                  0 AS anz_mp_7_8,
                  0 AS anz_mp_7,
                  0 AS anz_mp_8,
                  CASE WHEN t1.ranking=1 THEN t1.wg_id ELSE NULL END AS wg_1,
                  CASE WHEN t1.ranking=2 THEN t1.wg_id ELSE NULL END AS wg_2,
                  CASE WHEN t1.ranking=3 THEN t1.wg_id ELSE NULL END AS wg_3,
                  CASE WHEN t1.ranking=1 THEN t1.anz_storno ELSE 0 END AS anz_wg_1,
                  CASE WHEN t1.ranking=2 THEN t1.anz_storno ELSE 0 END AS anz_wg_2,
                  CASE WHEN t1.ranking=3 THEN t1.anz_storno ELSE 0 END AS anz_wg_3
                  FROM
                  ( --t1_1
                  SELECT t1.mandant_id AS mandant_id,
                  t1.wup_id AS wup_id,
                  t1.nb_id AS nb_id,
                  t1.wg_id,
                  t1.anz_storno,
                  RANK () OVER (PARTITION BY t1.mandant_id, t1.nb_id, t1.wup_id ORDER BY anz_storno DESC NULLS LAST,wg_id) AS ranking
                  FROM dbp_bda_view.v_bon_wg_wup_storno_anym t1_1
                  GROUP BY t1.mandant_id,
                  t1.wup_id,
                  t1.nb_id,
                  t1.wg_id,
                  t1.anz_storno
                  ) t1_1
                  WHERE  t1.ranking <=3
                  ) dt1

                  GROUP BY dt1.mandant_id,
                  dt1.nb_id,
                  dt1.wup_id,
                  dat
                  )td1

                  WHERE anz_bons<>0;