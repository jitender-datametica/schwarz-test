CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_KMR_COMPETITOR_STORE_1(
	MANDANT_ID,
	SYSTEM_NAME,
    COMPETITOR_STORE_ID,
	COMPETITOR_STORE_NAME,
	COMPETITOR_STORE_ADDRESS,
    COMPETITOR_COMPANY_ID,
	BREITENGRAD,
	LAENGENGRAD,
	COMPETITOR_WUP_ID
) AS 
/*	KMR Google : Wettbewerber Company Store 
	2024-02-27 : Review
    2025-05-06 muellerpatri : Änderung von SID auf ID
*/
SELECT
  RST.MANDANT_ID 
	, RST.EXT_SYSTEM_NAME           AS SYSTEM_NAME
	, RST.EXT_STORE_ID              AS COMPETITOR_STORE_ID
	, RST.RETAIL_STORE_NAME         AS COMPETITOR_STORE_NAME
	, RST.RETAIL_STORE_ADDRESS      AS COMPETITOR_STORE_ADDRESS
	, RST.EXT_RETAIL_COMPANY_ID     AS COMPETITOR_COMPANY_ID
	, RST.BREITENGRAD               AS BREITENGRAD
	, RST.LAENGENGRAD               AS LAENGENGRAD
	, RST.COMPETITOR_WUP_ID         AS COMPETITOR_WUP_ID
FROM DBP_VIEW.V_RETAIL_STORE_1 RST
 
INNER JOIN DBP_VIEW.V_RETAIL_COMPANY_1 RCO 
ON RCO.EXT_RETAIL_COMPANY_ID = RST.EXT_RETAIL_COMPANY_ID AND RCO.EXT_SYSTEM_NAME = RST.EXT_SYSTEM_NAME 
 
WHERE RCO.COMPETITOR_FG = 1;