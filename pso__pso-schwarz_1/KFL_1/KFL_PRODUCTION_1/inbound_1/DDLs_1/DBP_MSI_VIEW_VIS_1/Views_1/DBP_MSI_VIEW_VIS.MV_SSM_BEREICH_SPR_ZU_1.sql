CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_SSM_BEREICH_SPR_ZU_1
AS
-- 09.04.2020 SNIK1809 AP0052955-SPEC0067085
SELECT
V01.WUP_BEREICH_ID,
MAX(CASE WHEN SPR_ID =  22 THEN WUP_BEREICH_BEZ END) AS WUP_BEREICH_BEZ                 -- STANDARD == DE
,
MAX(CASE WHEN SPR_ID =  22 THEN WUP_BEREICH_BEZ END) AS WUP_BEREICH_BEZ_DE                         -- DE
,
COALESCE(MAX(CASE WHEN SPR_ID = 124 THEN WUP_BEREICH_BEZ END), WUP_BEREICH_BEZ_DE) AS WUP_BEREICH_BEZ_CZ    -- CZ
,
COALESCE(MAX(CASE WHEN SPR_ID = 108 THEN WUP_BEREICH_BEZ END), WUP_BEREICH_BEZ_DE) AS WUP_BEREICH_BEZ_SK    -- SK
,
COALESCE(MAX(CASE WHEN SPR_ID =  65 THEN WUP_BEREICH_BEZ END), WUP_BEREICH_BEZ_DE) AS WUP_BEREICH_BEZ_HR    -- HR
,
COALESCE(MAX(CASE WHEN SPR_ID =  90 THEN WUP_BEREICH_BEZ END), WUP_BEREICH_BEZ_DE) AS WUP_BEREICH_BEZ_PL    -- PL
,
COALESCE(MAX(CASE WHEN SPR_ID =  95 THEN WUP_BEREICH_BEZ END), WUP_BEREICH_BEZ_DE) AS WUP_BEREICH_BEZ_RO    -- RO
,
COALESCE(MAX(CASE WHEN SPR_ID =  18 THEN WUP_BEREICH_BEZ END), WUP_BEREICH_BEZ_DE) AS WUP_BEREICH_BEZ_BG    -- BG

FROM DBP_VIEW.V_SSM_BEREICH_SPR_ZU_1  V01

GROUP BY    V01.WUP_BEREICH_ID;

