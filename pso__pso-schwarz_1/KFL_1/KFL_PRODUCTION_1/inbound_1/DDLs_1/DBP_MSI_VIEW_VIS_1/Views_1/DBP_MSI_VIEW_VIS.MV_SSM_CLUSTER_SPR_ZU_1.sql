CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_SSM_CLUSTER_SPR_ZU_1
AS
-- 09.04.2020 SNIK1809 AP0052955-SPEC0067085
SELECT
V01.MANDANT_ID,
V01.WUP_BEREICH_ID,
V01.WUP_ABT_ID,
V01.SSM_CLUSTER_ID,
MAX(CASE WHEN SPR_ID =  22 THEN SSM_CLUSTER_BEZ END) AS SSM_CLUSTER_BEZ                 -- STANDARD == DE
,
MAX(CASE WHEN SPR_ID =  22 THEN SSM_CLUSTER_BEZ END) AS SSM_CLUSTER_BEZ_DE                         -- DE
,
COALESCE(MAX(CASE WHEN SPR_ID = 124 THEN SSM_CLUSTER_BEZ END), SSM_CLUSTER_BEZ_DE) AS SSM_CLUSTER_BEZ_CZ    -- CZ
,
COALESCE(MAX(CASE WHEN SPR_ID = 108 THEN SSM_CLUSTER_BEZ END), SSM_CLUSTER_BEZ_DE) AS SSM_CLUSTER_BEZ_SK    -- SK
,
COALESCE(MAX(CASE WHEN SPR_ID =  65 THEN SSM_CLUSTER_BEZ END), SSM_CLUSTER_BEZ_DE) AS SSM_CLUSTER_BEZ_HR    -- HR
,
COALESCE(MAX(CASE WHEN SPR_ID =  90 THEN SSM_CLUSTER_BEZ END), SSM_CLUSTER_BEZ_DE) AS SSM_CLUSTER_BEZ_PL    -- PL
,
COALESCE(MAX(CASE WHEN SPR_ID =  95 THEN SSM_CLUSTER_BEZ END), SSM_CLUSTER_BEZ_DE) AS SSM_CLUSTER_BEZ_RO    -- RO
,
COALESCE(MAX(CASE WHEN SPR_ID =  18 THEN SSM_CLUSTER_BEZ END), SSM_CLUSTER_BEZ_DE) AS SSM_CLUSTER_BEZ_BG    -- BG

FROM DBP_VIEW.V_SSM_CLUSTER_SPR_ZU_1  V01

GROUP BY    1,2,3,4;

