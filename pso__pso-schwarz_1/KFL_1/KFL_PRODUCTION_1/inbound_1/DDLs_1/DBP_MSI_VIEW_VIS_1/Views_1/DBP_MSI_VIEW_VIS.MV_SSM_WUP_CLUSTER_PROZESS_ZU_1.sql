CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_SSM_WUP_CLUSTER_PROZESS_ZU_1(
  MANDANT_ID
 ,WUP_ID
 ,NB_ID
 ,SSM_CLUSTER_ID
 ,SSM_PROZESS_ID
 ,DAT_VON
 ,DAT_BIS
 ,WUP_BEREICH_ID
 ,WUP_ABT_ID
 ,ETAGEN_ANZ
)
AS
SELECT
	 ssmcl.MANDANT_ID
	,ssmcl.WUP_ID
	,ssmcl.NB_ID
	,ssmcl.SSM_CLUSTER_ID
	,ssmcl.SSM_PROZESS_ID
	,ssmcl.DAT_VON
	,ssmcl.DAT_BIS
	,ssmcl.WUP_BEREICH_ID
	,ssmcl.WUP_ABT_ID
	,wp.ETAGEN_ANZ
FROM DBP_VIEW.V_SSM_WUP_CLUSTER_PROZESS_ZU_1 ssmcl
INNER JOIN DBP_VIEW.V_WUP_1 wp
		 ON ssmcl.MANDANT_ID = wp.MANDANT_ID
		AND ssmcl.WUP_ID = wp.WUP_ID
;