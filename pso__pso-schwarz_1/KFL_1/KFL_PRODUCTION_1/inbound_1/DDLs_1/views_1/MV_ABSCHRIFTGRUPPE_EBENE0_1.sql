CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE0_1(
	ABSCHRIFTENART_ID,
	ABSCHRIFTGRUPPE_ID_EBENE0,
	ABSCHRIFTGRUPPE_ID_EBENE1
) AS
SELECT

       
       
       
       
        ABSCHRIFTENART_ID
       ,ABSCHRIFTGRUPPE_ID_EBENE0
       ,ABSCHRIFTGRUPPE_ID_EBENE1

       FROM (
SELECT  
       
        CAST(V01.PREIS_AEND_GRUND_ID AS STRING) AS ABSCHRIFTENART_ID
       
       
       ,V01.ABSCHRIFTGRUPPE_ID AS ABSCHRIFTGRUPPE_ID_EBENE0
       ,V02.ABSCHRIFTGRUPPE_ID_EBENE1
FROM DBP_VIEW.V_L_PREIS_AENDERUNG_1 V01
JOIN DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE1_1 V02

ON V01.ABSCHRIFTGRUPPE_ID = V02.ABSCHRIFTGRUPPE_ID_EBENE1

UNION ALL

SELECT 
       
       
       CAST(V01.ABSCHRIFTART_ID AS STRING) ABSCHRIFTENART_ID
       
       ,V01.ABSCHRIFTGRUPPE_ID AS ABSCHRIFTGRUPPE_ID_EBENE0
       ,V02.ABSCHRIFTGRUPPE_ID_EBENE1
FROM DBP_VIEW.V_L_ABSCHRIFTART_1 V01
JOIN DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE1_1 V02

ON V01.ABSCHRIFTGRUPPE_ID = V02.ABSCHRIFTGRUPPE_ID_EBENE1

UNION ALL

SELECT  
       
       
       
        CAST(V01.LAGER_BEWART_ID AS STRING) AS ABSCHRIFTENART_ID
       ,V01.ABSCHRIFTGRUPPE_ID AS ABSCHRIFTGRUPPE_ID_EBENE0
       ,V02.ABSCHRIFTGRUPPE_ID_EBENE1
FROM DBP_VIEW.V_L_LAGER_BEWART_1 V01
JOIN DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE1_1 V02

ON V01.ABSCHRIFTGRUPPE_ID = V02.ABSCHRIFTGRUPPE_ID_EBENE1
WHERE SYSTEM_ID <> 13)
GROUP BY 1,2,3;