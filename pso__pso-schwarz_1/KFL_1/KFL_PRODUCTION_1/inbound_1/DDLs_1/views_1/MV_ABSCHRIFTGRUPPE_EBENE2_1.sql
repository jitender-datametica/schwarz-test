CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE2_1(
	ABSCHRIFTGRUPPE_ID_EBENE2,
	ABSCHRIFTGRUPPE_ID_EBENE3
) AS
SELECT
V02.ABSCHRIFTGRUPPE_ID  AS ABSCHRIFTGRUPPE_ID_EBENE2

,V02.UEBERGEORDNETE_ABSCHRIFTGRUPPE_ID AS ABSCHRIFTGRUPPE_ID_EBENE3

FROM DBP_VIEW.V_ABSCHRIFTGRUPPE_1 V01
INNER JOIN DBP_VIEW.V_ABSCHRIFTGRUPPE_HIERARCHIE_ZU_1 V02
   ON V01.MANDANT_ID         = V02.MANDANT_ID 
  AND V01.ABSCHRIFTGRUPPE_ID = V02.ABSCHRIFTGRUPPE_ID  
WHERE V01.ABSCHRIFTGRUPPE_EBENE_KZ = 2
GROUP BY 1,2;