CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE4_SPR_ZU_1(
	ABSCHRIFTGRUPPE_ID_EBENE4,
	ABSCHRIFTGRUPPE_EBENE4_BEZ
) AS
SELECT


V01.ABSCHRIFTGRUPPE_ID
,COALESCE (MAX(CASE WHEN SPR_ID = 22  THEN V01.ABSCHRIFTGRUPPE_BEZ END), 'N/A') AS ABSCHRIFTGRUPPE_EBENE4_BEZ                     

FROM DBP_VIEW.V_ABSCHRIFTGRUPPE_SPR_ZU_1 V01
JOIN DBP_VIEW.V_ABSCHRIFTGRUPPE_1 V02
ON V01.MANDANT_ID = V02.MANDANT_ID
AND V01.ABSCHRIFTGRUPPE_ID = V02.ABSCHRIFTGRUPPE_ID
WHERE V02.ABSCHRIFTGRUPPE_EBENE_KZ = 4
GROUP BY
V01.ABSCHRIFTGRUPPE_ID;