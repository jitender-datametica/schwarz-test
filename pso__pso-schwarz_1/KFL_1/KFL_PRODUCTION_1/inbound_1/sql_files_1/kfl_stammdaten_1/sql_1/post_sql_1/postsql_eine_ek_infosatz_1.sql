
UPDATE DBP_DATA.EK_INFOSATZ_1
   SET EK_INFOSATZ.KONDITIONSGRUPPE_ID= a.KONDITIONSGRUPPE_ID,
       EK_INFOSATZ.TD_UPDATE          = CURRENT_TIMESTAMP
  FROM (
        SELECT MANDANT_ID,
               EK_INFOSATZ_ID,
               MAX(KONDITIONSGRUPPE_ID) KONDITIONSGRUPPE_ID
          FROM DBP_ETL.EINE_EK_INFOSATZ
          GROUP BY 1,2
     )a
 WHERE EK_INFOSATZ.MANDANT_ID           = a.MANDANT_ID
   AND EK_INFOSATZ.EK_INFOSATZ_ID       = a.EK_INFOSATZ_ID
   AND COALESCE(EK_INFOSATZ.KONDITIONSGRUPPE_ID,'-1') <> a.KONDITIONSGRUPPE_ID
;



UPDATE DBP_DATA.EK_INFOSATZ_1
   SET EK_INFOSATZ.KONDITIONSGRUPPE_ID= a.KONDITIONSGRUPPE_ID,
       EK_INFOSATZ.TD_UPDATE          = CURRENT_TIMESTAMP
  FROM (
        SELECT MANDANT_ID,
               EK_INFOSATZ_ID,
               KONDITIONSGRUPPE_ID
          FROM DBP_ETL.EINE_EK_INFOSATZ
         WHERE WUP_ID    = 0
           AND LOESCH_FG = 0
          GROUP BY 1,2,3
     )a
 WHERE EK_INFOSATZ.MANDANT_ID           = a.MANDANT_ID
   AND EK_INFOSATZ.EK_INFOSATZ_ID       = a.EK_INFOSATZ_ID
   AND COALESCE(EK_INFOSATZ.KONDITIONSGRUPPE_ID,'-1') <> a.KONDITIONSGRUPPE_ID
;
