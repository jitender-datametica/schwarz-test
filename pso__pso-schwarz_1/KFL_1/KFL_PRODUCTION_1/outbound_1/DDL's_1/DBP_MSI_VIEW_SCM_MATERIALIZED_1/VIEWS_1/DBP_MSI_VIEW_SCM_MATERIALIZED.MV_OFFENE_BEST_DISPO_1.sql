CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_scm_materialized.MV_OFFENE_BEST_DISPO_1 (MANDANT_ID, WUP_ID, NB_ID, GP_ID, ART_ID,
DAT_LIEF_NEXT_DISPO, DAT_LIEF_MAX_DISPO, MENGE_BEST_BME_OFFEN_DISPO, MENGE_BEST_KOLLI_OFFEN_DISPO, ANZ_BEST_POS_DISPO,
DIFF_TAGE_DISPO, MENGE_BEST_BME_OFFEN_NEXT_DISPO, MENGE_BEST_KOLLI_OFFEN_NEXT_DISPO) AS SELECT MANDANT_ID,
 WUP_ID,
 NB_ID,
 GP_ID,
 ART_ID,
 MAX(`_u0024_F12`) AS DAT_LIEF_NEXT_DISPO,
 MAX(`_u0024_F13`) AS DAT_LIEF_MAX_DISPO,
 SUM(MENGE_BEST_BME) AS MENGE_BEST_BME_OFFEN_DISPO,
 SUM(MENGE_BEST_KOLLI) AS MENGE_BEST_KOLLI_OFFEN_DISPO,
 SUM(ANZ_BEST_POS) AS ANZ_BEST_POS_DISPO,
 DATE_DIFF(MAX(`_u0024_F13`), MAX(`_u0024_F12`), DAY) AS DIFF_TAGE_DISPO,
 SUM(`_u0024_F14`) AS MENGE_BEST_BME_OFFEN_NEXT_DISPO,
 SUM(`_u0024_F15`) AS MENGE_BEST_KOLLI_OFFEN_NEXT_DISPO
FROM (SELECT MANDANT_ID,
   WUP_ID,
   NB_ID,
   GP_ID,
   ART_ID,
   MENGE_BEST_BME,
   MENGE_BEST_KOLLI,
   ANZ_BEST_POS,
    CASE
    WHEN (ROW_NUMBER() OVER (PARTITION BY MANDANT_ID, WUP_ID, NB_ID, GP_ID, ART_ID ORDER BY DAT_LIEF IS NULL, DAT_LIEF)
      ) = 1
    THEN DAT_LIEF
    ELSE NULL
    END AS `_u0024_F12`,
   CAST(NULL AS DATE) AS `_u0024_F13`,
    CASE
    WHEN (ROW_NUMBER() OVER (PARTITION BY MANDANT_ID, WUP_ID, NB_ID, GP_ID, ART_ID ORDER BY DAT_LIEF IS NULL, DAT_LIEF)
      ) = 1
    THEN MENGE_BEST_BME
    ELSE NULL
    END AS `_u0024_F14`,
    CASE
    WHEN (ROW_NUMBER() OVER (PARTITION BY MANDANT_ID, WUP_ID, NB_ID, GP_ID, ART_ID ORDER BY DAT_LIEF IS NULL, DAT_LIEF)
      ) = 1
    THEN MENGE_BEST_KOLLI
    ELSE NULL
    END AS `_u0024_F15`
  FROM (SELECT MANDANT_ID,
     WUP_ID,
     NB_ID,
     GP_ID,
     CAST(ROUND(CAST(ART_ID AS FLOAT64)) AS INTEGER) AS ART_ID,
     DAT_LIEF,
     SUM(CAST(MENGE_BEST_GESAMT AS NUMERIC)) AS MENGE_BEST_BME,
     SUM(CAST(MENGE_BEST_GESAMT AS NUMERIC) / UMRECH_FAKTOR_BEST_BME) AS MENGE_BEST_KOLLI,
     COUNT(*) AS ANZ_BEST_POS
    FROM kfl_production_dbp_view.v_vz_best_vor_1
    WHERE DAT_LIEF >= DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
     AND DAT_PLAN = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
    GROUP BY MANDANT_ID,
     WUP_ID,
     NB_ID,
     GP_ID,
     ART_ID,
     DAT_LIEF) AS t0) AS t2
GROUP BY MANDANT_ID,
 WUP_ID,
 NB_ID,
 GP_ID,
 ART_ID;