CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_rpw.mv_lagerbew_wbnk_1 (mandant_id, lagerbew_beleg_id,
lagerbew_beleg_pos_id, kj, lager_bewart_id, art_id, grund_id, wup_id, nb_id, auto_fg, lagerort_id, gp_id,
einkaufsorganisation_id, soll_haben_kz, wrg_id, best_beleg_id, best_beleg_pos_id, betrag_lagerbew, betrag_verkauf,
erfsngs_menge_einh_id, lagerplatz_id_id, kunde_id, menge_kolli, menge_lagerbew, menge_palette, menge_lieferschein,
menge_lief, menge_erf, empfaenger_id, dat_buch, dat_beleg, dat_erfasst, system_id, lagerbew_beleg_storno_id,
lagerbew_beleg_pos_storno_id, lagerbew_beleg_storno_kj, betrag_vk_netto, wert_auslandsfracht, wert_auslandsfracht2,
wert_zoll, wert_antidump, wert_inlandsfracht, wert_gem_rueckn, wert_duales_system, wert_gema, wert_verbrauchsst,
wert_verpackung, wert_prov, wert_hk_prov, wert_agentur_prov, wert_mto, wert_pruefkosten, wert_eu_regelung,
wert_sonst_kosten) AS SELECT DET.mandant_id,
 DET.lagerbew_beleg_id,
 DET.lagerbew_beleg_pos_id,
 DET.kj,
 DET.lager_bewart_id,
 DET.art_id,
 DET.grund_id,
 DET.wup_id,
 DET.nb_id,
 DET.auto_fg,
 DET.lagerort_id,
 DET.gp_id,
 DET.einkaufsorganisation_id,
 DET.soll_haben_kz,
 DET.wrg_id,
 DET.best_beleg_id,
 DET.best_beleg_pos_id,
 DET.betrag_lagerbew,
 COALESCE(DET.betrag_verkauf, DET.betrag_lagerbew) AS betrag_verkauf,
 DET.erfsngs_menge_einh_id,
 DET.lagerplatz_id AS lagerplatz_id_id,
 DET.kunde_id,
 DET.menge_lagerbew_kolli AS menge_kolli,
 DET.menge_lagerbew_bme AS menge_lagerbew,
 DET.menge_lagerbew_palette AS menge_palette,
 DET.menge_lieferschein,
 DET.menge_lief,
 DET.menge_erf,
 DET.empfaenger_id,
 DET.dat_buch,
 LB.dat_beleg,
 LB.dat_erfasst,
 7 AS system_id,
 DET.lagerbew_beleg_storno_id,
 DET.lagerbew_beleg_pos_storno_id,
 DET.lagerbew_beleg_storno_kj,
 DET.betrag_vk_netto,
  AGPWBZP.betrag_auslandsfracht * DET.menge_lagerbew_bme AS wert_auslandsfracht,
  AGPWBZP.betrag_auslandsfracht2 * DET.menge_lagerbew_bme AS wert_auslandsfracht2,
  AGPWBZP.betrag_zoll * DET.menge_lagerbew_bme AS wert_zoll,
  AGPWBZP.betrag_antidump * DET.menge_lagerbew_bme AS wert_antidump,
  AGPWBZP.betrag_inlandsfracht * DET.menge_lagerbew_bme AS wert_inlandsfracht,
  AGPWBZP.betrag_gem_rueckn * DET.menge_lagerbew_bme AS wert_gem_rueckn,
  AGPWBZP.betrag_duales_system * DET.menge_lagerbew_bme AS wert_duales_system,
  AGPWBZP.betrag_gema * DET.menge_lagerbew_bme AS wert_gema,
  AGPWBZP.betrag_verbrauchsst * DET.menge_lagerbew_bme AS wert_verbrauchsst,
  AGPWBZP.betrag_verpackung * DET.menge_lagerbew_bme AS wert_verpackung,
  AGPWBZP.betrag_prov * DET.menge_lagerbew_bme AS wert_prov,
  AGPWBZP.betrag_hk_prov * DET.menge_lagerbew_bme AS wert_hk_prov,
  AGPWBZP.betrag_agentur_prov * DET.menge_lagerbew_bme AS wert_agentur_prov,
  AGPWBZP.betrag_mto * DET.menge_lagerbew_bme AS wert_mto,
  AGPWBZP.betrag_pruefkosten * DET.menge_lagerbew_bme AS wert_pruefkosten,
  AGPWBZP.betrag_eu_regelung * DET.menge_lagerbew_bme AS wert_eu_regelung,
  AGPWBZP.betrag_sonst_kosten * DET.menge_lagerbew_bme AS wert_sonst_kosten
FROM kfl_production_dbp_view.v_lagerbew_det_1 AS DET
 INNER JOIN kfl_production_dbp_view.v_lagerbew_1 AS LB ON DET.lagerbew_beleg_id = LB.lagerbew_beleg_id AND DET.mandant_id
     = LB.mandant_id AND DET.kj = LB.kj AND DET.dat_buch = LB.dat_buch
 INNER JOIN kfl_production_dbp_view.v_art_gp_wup_bnk_zu_per_1 AS AGPWBZP ON DET.art_id = AGPWBZP.art_id AND DET.gp_id =
        AGPWBZP.gp_id AND DET.einkaufsorganisation_id = AGPWBZP.einkaufsorganisation_id AND DET.wup_id = AGPWBZP.wup_id
    AND DET.mandant_id = AGPWBZP.mandant_id AND DET.nb_id = AGPWBZP.nb_id AND DET.dat_buch BETWEEN AGPWBZP.dat_von AND
   AGPWBZP.dat_bis
WHERE DET.mandant_id = 1;