CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_rpw.mv_monat_1 (kjmo, kjmo_vj, gjmo, gjmo_vj, kjqu, gjqu, kj, gj,
akt_mo, akt_mo_komplett, akt_gjqu, akt_gjqu_komplett, akt_kjqu, akt_kjqu_komplett, akt_gj, akt_gj_komplett, akt_kj,
akt_kj_komplett, mo_gj, mo_kj, kjmo_dat_von, kjmo_dat_bis, system_id) AS SELECT M.kjmo,
 M.kjmo_vj,
 M.gjmo,
 M.gjmo_vj,
 M.kjqu,
 M.gjqu,
 M.kj,
 M.gj,
 M.akt_mo,
 M.akt_mo_komplett,
 M.akt_gjqu,
 M.akt_gjqu_komplett,
 M.akt_kjqu,
 M.akt_kjqu_komplett,
 M.akt_gj,
 M.akt_gj_komplett,
 M.akt_kj,
 M.akt_kj_komplett,
 M.mo_gj,
 M.mo_kj,
 MIN(T.dat) AS kjmo_dat_von,
 MAX(T.dat) AS kjmo_dat_bis,
 7 AS system_id
FROM kfl_production_dbp_view.v_monat_1 AS M
 INNER JOIN kfl_production_dbp_view.v_tag_1 AS T ON M.kjmo = T.kjmo
WHERE M.kjmo >= 200501
 AND M.kj <= EXTRACT(YEAR FROM CURRENT_DATE)
GROUP BY M.kjmo,
 M.kjmo_vj,
 M.gjmo,
 M.gjmo_vj,
 M.kjqu,
 M.gjqu,
 M.kj,
 M.gj,
 M.akt_mo,
 M.akt_mo_komplett,
 M.akt_gjqu,
 M.akt_gjqu_komplett,
 M.akt_kjqu,
 M.akt_kjqu_komplett,
 M.akt_gj,
 M.akt_gj_komplett,
 M.akt_kj,
 M.akt_kj_komplett,
 M.mo_gj,
 M.mo_kj;