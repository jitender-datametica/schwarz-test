CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_vis.mv_eigentum_spr_zu_1 AS SELECT CASE
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
  THEN 1
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
  THEN - 1
  ELSE 0
  END AS eigentum_fg,
  CASE
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
  THEN 'Eigentum'
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
  THEN ''
  ELSE 'Miete'
  END AS eigentum_bez
FROM kfl_production_dbp_view.v_tag_1
WHERE dat BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY) AND (CURRENT_DATE);