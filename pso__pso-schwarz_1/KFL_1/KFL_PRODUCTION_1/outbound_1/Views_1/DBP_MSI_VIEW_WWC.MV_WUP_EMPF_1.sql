CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_wwc.mv_wup_empf_1 (mandant_id, nb_id, land_id, wup_id, wup_standort,
vs_id, vw_id, wm_id, vkl_id, hl_id, vf_id, buchungskreis_id, dat_eroeffnung, verkaufsflaeche, uebernahme_von,
getraenkemarkt_fg, kundenfaktor, getraenke_markt_fg, preiskategorie_food, preiskategorie_nonfood, sortkategorie_food,
sortkategorie_nonfood, region_id, wup_str, wup_plz, wup_stadt, wup_typ_id, wup_name_v, wup_name_e, lead_mwst,
breakevenumsatz, systemrentabilitaet, betriebsflaeche, fleischsystem, sondermarkt, ref_wup_id, kassentyp,
dat_qbm_umstellung, qbm_id, vz_wup_id, verkaufsorganisation_id) AS SELECT V01.mandant_id,
 V01.nb_id,
 V01.land_id,
 V01.wup_id,
 V01.wup_standort,
 V01.vs_id,
 V01.vw_id,
 V01.wm_id,
 V01.vkl_id,
 V01.hl_id,
 V01.vf_id,
 V01.buchungskreis_id,
 V01.dat_eroeffnung,
 V01.verkaufsflaeche,
 V01.uebernahme_von,
 V01.getraenkemarkt_fg,
 V01.kundenfaktor,
  CASE
  WHEN V01.kundenfaktor < 1.000
  THEN 1
  ELSE 0
  END AS getraenke_markt_fg,
 V01.preiskategorie_food,
 V01.preiskategorie_nonfood,
 V01.sortkategorie_food,
 V01.sortkategorie_nonfood,
 COALESCE(V03.region_id, V01.region_id, - V01.mandant_id) AS region_id,
 COALESCE(V03.wup_str, V01.wup_str, '') AS wup_str,
 COALESCE(V03.wup_plz, V01.wup_plz) AS wup_plz,
 COALESCE(V03.wup_stadt_1, V01.wup_stadt, '') AS wup_stadt,
 V01.wup_typ_id,
 V01.wup_name_v,
 V01.wup_name_e,
 V01.lead_mwst,
 V01.breakevenumsatz,
 V01.systemrentabilitaet,
 V01.betriebsflaeche,
 V01.fleischsystem,
 V01.sondermarkt,
 V01.ref_wup_id,
 V01.kassentyp,
 V01.dat_qbm_umstellung,
 V01.qbm_id,
 V01.vz_wup_id,
 V01.verkaufsorganisation_id
FROM kfl_production_dbp_view.v_wup_1 AS V01
 LEFT JOIN kfl_production_dbp_view.v_vaus_wup_1 AS V03 ON V01.wup_id = V03.wup_id AND V01.mandant_id = V03.mandant_id
WHERE V01.nb_id IN (- 2, - 1, 0, 2, 6, 7) AND V01.dat_eroeffnung > PARSE_DATE('%F', '1900-01-01')
 OR V01.nb_id IN (- 111, 99);