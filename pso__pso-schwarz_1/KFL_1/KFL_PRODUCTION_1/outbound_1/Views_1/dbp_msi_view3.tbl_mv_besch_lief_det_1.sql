CREATE OR REPLACE VIEW kfl_production_dbp_msi_view3.tbl_mv_besch_lief_det_1(AKTIONS_POS_KZ, ANNAHMEVERWEIGERUNG_ID, ART_ID, BESCH_PALETTE_FG, BRUTTOGEW, DAT_AENDERUNG, DAT_HALTBARKEIT, DIFF_ID, LAGERORT_ID, LIEF_BELEG_ID, LIEF_BELEG_POS_ID, MANDANT_ID, MENGE_LIEF_IST_BME, MENGE_LIEF_SOLL_KOLLI, MENGE_LIEF_PALETTE, NB_ID, SYSTEM_ID, VERK_MENGE_EINH_ID, BEST_BELEG_ID, BEST_BELEG_POS_ID, WUP_ID, DAT_LIEF_SOLL, MENGE_LIEF_SOLL_BME, MENGE_LIEF_IST_KOLLI, MENGE_LIEF_IST_LME, MENGE_LIEF_FEHL_BME, MENGE_LIEF_FEHL_KOLLI, WRG_ID, MENGE_KOLLI, WRG_TYP_ID, VK_NETTO_LIEF_SOLL, VK_NETTO_LIEF_IST, VK_NETTO_LIEF_FEHL, LETZTER_WE_MARKT_LIEF, BESTELLART_ID, KJ, MANDANT_ID_KUNDE, KUNDE_ID, NB_ID_KUNDE, LIEF_PAL_TYP_ID, BETRAG_LIEF_IST, BETRAG_LIEF_SOLL, UMRECHNUNGSKURS, AUSLIEFERUNGSGRUPPE_ID, LAGERNUMMER_ID, LIEF_TYP_ID, WERBEWARE_ID, GP_ID, VERSANDSTELLE_ID, VERTR_BELEG_TYP_ID, WG_VERKETT_FG, WG_VERKETT_LIEF) AS SELECT
    -- 19.07.2017, AP0013197 SPEC0022485, srom0404, mapping best_beleg_id und vorlage_beleg_id
    -- 01.02.2018, AP0013197 SPEC0022485, srom0404, JOIN auf Kopf besch_lief_1 eingeführt.
    -- Erforderlich, da Kunde nicht auf Detail Ebene vorlag. Microstrategy dies aber vom Schema bzgl. Disporhythmus erforderte.
    -- nb_id_kunde existiert nicht in Kopf und muss hier 'erfunden' werden
    -- 13.06.2018 srom0404: NSR0211557 umwandeln nicht-numerisch auf numerisch jetzt mit TRYCAST
    -- 09.07.2018 srom0404: AP0013197 SPEC0037744, erweiterung um bestellart_id
    -- 04.12.2018 mkub1811, AP0032032, SPEC0046895, Erweiterung um lief_pal_typ_id
    -- 27.11.2019 nwag2310, AP0041558, added KJ in join (LIKP/LIPS)
    -- 13.02.2020 nwag2310, AP0041558, bugfix
    -- 30.04.2021 nwag2310, AP0078007, bugfix pal typ char
    -- 12.05.2022, AP0128635, SPEC0151986, dknop, adding aulieferungsgruppe_id
    -- 2023-12-11, dknop, adding lagernummer_id, lief_typ_id,gp_id,werbeware_id,versandstelle_id,wg_verkett_fg, wg_verkett_lief, vertr_beleg_typ_id, adding join to dbp_msi_data.ts_lagerort_ewm_dat_1 and filter on dat_lief_soll instead of hardcoded DC/Dates
    -- 2024-01-09, dknop, limit to current+last 2 years
    -- 2022-04-25, dknop, AP0128635_SPEC0151986, adding auslieferungsgruppe_id
    -- 2023-12-11, dknop, adding lagernummer_id, lief_typ_id,gp_id,  adding join to dbp_msi_data.ts_lagerort_ewm_dat_1 and filter on dat_lief_soll instead of hardcoded DC/Dates
    -- 2024-01-31, INC7963291, dknop, change kunde_id
    -- 2024-07-23,AP0204035, SPEC0254614,dknop, adding aktuell_wup_id logic
    -- 2024-09-09, dknop, change to left join with dbp_view.v_wup_1
    -- 2024-10-01, nwag, performance fix for MAT
    -- 2024-10-09, nwag, performance fix for MAT
    V01.AKTIONS_POS_KZ,
    V01.ANNAHMEVERWEIGERUNG_ID,
    V01.ART_ID,
    V01.BESCH_PALETTE_FG,
    V01.BRUTTOGEW,
    V01.DAT_AENDERUNG,
    V01.DAT_HALTBARKEIT,
    V01.DIFF_ID,
    V01.LAGERORT_ID,
    V01.LIEF_BELEG_ID,
    V01.LIEF_BELEG_POS_ID,
    V01.MANDANT_ID,
    V01.MENGE_LIEF_IST_BME,
    CASE
      WHEN V01.DAT_LIEF_SOLL < '2005-04-12' THEN NUMERIC '0'
      ELSE V01.MENGE_LIEF_SOLL_KOLLI
    END AS MENGE_LIEF_SOLL_KOLLI,
    V01.MENGE_LIEF_PALETTE,
    V01.NB_ID,
    V01.SYSTEM_ID,
    V01.VERK_MENGE_EINH_ID,
    CASE
      WHEN V01.BEST_BELEG_ID <> NUMERIC '0' THEN V01.BEST_BELEG_ID
      ELSE V01.VORLAGE_BELEG_ID
    END AS BEST_BELEG_ID,
    V01.VORLAGE_BELEG_POS_ID AS BEST_BELEG_POS_ID,
    V01.WUP_ID,
    V01.DAT_LIEF_SOLL,
    CASE
      WHEN V01.DAT_LIEF_SOLL < '2005-04-12' THEN NUMERIC '0'
      ELSE V01.MENGE_LIEF_SOLL_BME
    END AS MENGE_LIEF_SOLL_BME,
    V01.MENGE_LIEF_IST_KOLLI,
    V01.MENGE_LIEF_IST_LME,
    CASE
      WHEN V01.DAT_LIEF_SOLL < '2005-04-12' THEN NUMERIC '0'
      ELSE V01.MENGE_LIEF_SOLL_BME - V01.MENGE_LIEF_IST_BME
    END AS MENGE_LIEF_FEHL_BME,
    CASE
      WHEN V01.DAT_LIEF_SOLL < '2005-04-12' THEN NUMERIC '0'
      ELSE V01.MENGE_LIEF_SOLL_KOLLI - V01.MENGE_LIEF_IST_KOLLI
    END AS MENGE_LIEF_FEHL_KOLLI,
    V03.WRG_ID,
    V01.MENGE_KOLLI,
    V03.WRG_TYP_ID,
    CASE
      WHEN V03.WRG_TYP_ID = NUMERIC '0' THEN V01.VK_NETTO_LIEF_SOLL * V02.UMRECHNUNGSKURS
      ELSE V01.VK_NETTO_LIEF_SOLL
    END AS VK_NETTO_LIEF_SOLL,
    CASE
      WHEN V03.WRG_TYP_ID = NUMERIC '0' THEN V01.VK_NETTO_LIEF_IST * V02.UMRECHNUNGSKURS
      ELSE V01.VK_NETTO_LIEF_IST
    END AS VK_NETTO_LIEF_IST,
    CASE
      WHEN V03.WRG_TYP_ID = NUMERIC '0' THEN (V01.VK_NETTO_LIEF_SOLL - V01.VK_NETTO_LIEF_IST) * V02.UMRECHNUNGSKURS
      ELSE V01.VK_NETTO_LIEF_SOLL - V01.VK_NETTO_LIEF_IST
    END AS VK_NETTO_LIEF_FEHL,
    cast(cast(V01.DAT_HALTBARKEIT as string) as int64) - cast((V05.MHD_ZEITRAUM * V05.LAGER_PROZENT / NUMERIC '100' + NUMERIC '0.5')as int64) AS LETZTER_WE_MARKT_LIEF,
    V01.BESTELLART_ID,
    V01.KJ,
    V011.MANDANT_ID_KUNDE,
    -- ,CASE WHEN TRY_CAST(kunde_id AS INTEGER) IS NULL THEN -3 ELSE TRY_CAST(kunde_id AS INTEGER) END AS kunde_id
    CASE
      WHEN KUNDE_ID IS NULL THEN -NUMERIC '3'
      ELSE V04.AKTUELL_WUP_ID
    END AS KUNDE_ID,
    NUMERIC '0' AS NB_ID_KUNDE,
    CASE
      WHEN V011.LIEF_PAL_TYP_ID <> '6' THEN CAST( V011.LIEF_PAL_TYP_ID as STRING)
      WHEN V011.LIEF_PAL_TYP_ID = '6'
       AND V01.MANDANT_ID = NUMERIC '1'
       AND V01.LIEF_BELEG_POS_ID = NUMERIC '10'
       OR V01.MANDANT_ID <> NUMERIC '1'
       AND V01.LIEF_BELEG_POS_ID = NUMERIC '1' THEN '61'
      WHEN V011.LIEF_PAL_TYP_ID = '6'
       AND V01.MANDANT_ID = NUMERIC '1'
       AND V01.LIEF_BELEG_POS_ID <> NUMERIC '10'
       OR V01.MANDANT_ID <> NUMERIC '1'
       AND V01.LIEF_BELEG_POS_ID <> NUMERIC '1' THEN '64'
    END AS LIEF_PAL_TYP_ID,
    V01.BETRAG_LIEF_IST,
    V01.BETRAG_LIEF_SOLL,
    V02.UMRECHNUNGSKURS,
    coalesce(ART_AUSL.AUSLIEFERUNGSGRUPPE_ID, coalesce(WG_AUSL.AUSLIEFERUNGSGRUPPE_ID, '-1')) AS AUSLIEFERUNGSGRUPPE_ID,
    V011.LAGERNUMMER_ID,
    V011.LIEF_TYP_ID,
    V011.WERBEWARE_ID,
    V011.GP_ID,
    V011.VERSANDSTELLE_ID,
    V011.VERTR_BELEG_TYP_ID,
    V011.WG_VERKETT_FG,
    V011.WG_VERKETT_LIEF
  FROM
    kfl_production_dbp_view.v_besch_lief_1 AS V011
    INNER JOIN kfl_production_dbp_view.v_tag_1 AS T ON V011.DAT_LIEF_SOLL = T.DAT
     AND AKT_KJ >= -NUMERIC '2'
    INNER JOIN kfl_production_dbp_view.v_besch_lief_det_1 AS V01 ON V01.MANDANT_ID = V011.MANDANT_ID
     AND V01.LIEF_BELEG_ID = V011.LIEF_BELEG_ID
     AND V01.KJ = V011.KJ
     AND V01.DAT_LIEF_SOLL = T.DAT
    INNER JOIN kfl_production_dbp_msi_view3.mv_kurs_1 AS V02 ON V01.WRG_ID = V02.VON_WRG_ID
    INNER JOIN kfl_production_dbp_view.v_mandant_wrg_typ_zu_1 AS V03 ON V01.MANDANT_ID = V03.MANDANT_ID
    INNER JOIN kfl_production_dbp_view.v_art_1 AS V05 ON V01.ART_ID = V05.ART_ID
     AND V01.MANDANT_ID = V05.MANDANT_ID
    INNER JOIN kfl_production_dbp_view.v_art_vorschlagswert_per_1 AS MAW1_1 ON V01.MANDANT_ID = MAW1.MANDANT_ID
     AND V01.ART_ID = MAW1.ART_ID
     AND V01.DAT_LIEF_SOLL BETWEEN MAW1.DAT_VON AND MAW1.DAT_BIS
    INNER JOIN kfl_production_dbp_view.v_art_wg_zu_per_1 AS WG ON V01.MANDANT_ID = WG.MANDANT_ID
     AND V01.ART_ID = WG.ART_ID
     AND V01.DAT_LIEF_SOLL BETWEEN WG.DAT_VON AND WG.DAT_BIS
     AND WG.ARTHIERTYP_ID = NUMERIC '2'
    LEFT OUTER JOIN kfl_production_dbp_view.v_wup_1 AS V04 ON V04.MANDANT_ID = V011.MANDANT_ID_KUNDE
     AND V04.WUP_ID = CASE
      WHEN KUNDE_ID IS NULL THEN -NUMERIC '3'
      ELSE V04.AKTUELL_WUP_ID
    END
    LEFT OUTER JOIN kfl_production_dbp_view.v_art_auslieferungsgruppe_per_1 AS ART_AUSL ON V01.MANDANT_ID = ART_AUSL.MANDANT_ID
     AND V01.ART_ID = ART_AUSL.ART_ID
     AND V01.DAT_LIEF_SOLL BETWEEN ART_AUSL.DAT_VON AND ART_AUSL.DAT_BIS
    LEFT OUTER JOIN kfl_production_dbp_view.v_wg_auslieferungsgruppe_per_1 AS WG_AUSL ON V01.MANDANT_ID = WG_AUSL.MANDANT_ID
     AND WG.WG_ID = WG_AUSL.WG_ID
     AND CASE
      WHEN WG_AUSL.SORTIMENTSLISTENART_ID = '' THEN ''
      ELSE MAW1.SORTIMENTSLISTENART_ID
    END = WG_AUSL.SORTIMENTSLISTENART_ID
     AND V01.DAT_LIEF_SOLL BETWEEN WG_AUSL.DAT_VON AND WG_AUSL.DAT_BIS
    LEFT OUTER JOIN kfl_production_dbp_view.v_l_lagernummer_1 AS L_LAGN ON V011.MANDANT_ID = L_LAGN.MANDANT_ID
     AND V011.LAGERNUMMER_ID = L_LAGN.LAGERNUMMER_ID
    LEFT OUTER JOIN (
      SELECT
          TS_LAGERORT_EWM_DAT.MANDANT_ID,
          TS_LAGERORT_EWM_DAT.WUP_ID,
          TS_LAGERORT_EWM_DAT.NB_ID,
          TS_LAGERORT_EWM_DAT.LAGERNUMMER_ID,
          min(TS_LAGERORT_EWM_DAT.DAT) AS DAT
        FROM
          kfl_production_dbp_msi_data.ts_lagerort_ewm_dat_1
        GROUP BY 1, 2, 3, 4
    ) AS TS_LO_EWM ON V011.MANDANT_ID = TS_LO_EWM.MANDANT_ID
     AND L_LAGN.WUP_ID = TS_LO_EWM.WUP_ID
     AND L_LAGN.NB_ID = TS_LO_EWM.NB_ID
     AND V011.LAGERNUMMER_ID = TS_LO_EWM.LAGERNUMMER_ID
  -- EWM Lagernummern ausfiltern! - Erweiterung mit jedem Go-Live erforderlich!
  WHERE TS_LO_EWM.MANDANT_ID IS NULL
   OR NOT V011.DAT_LIEF_SOLL >= TS_LO_EWM.DAT
;
