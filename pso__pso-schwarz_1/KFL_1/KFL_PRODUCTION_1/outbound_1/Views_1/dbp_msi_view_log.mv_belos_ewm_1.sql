CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_log.mv_belos_ewm_1 (lief_beleg_id, lief_typ_id, mandant_id,
belos_vorgang_id, nb_id, dat_lief_soll, dat_leistung, sendung_id, lagerort_id, transportauftrag_id, sonderabwicklung_id
, belos_adresse_absender_num_id, belos_adresse_empfaenger_id, belos_adresse_spedition_id, adress_name, lagernummer_id,
transportation_unit_id, kj_transportation_unit, leergut_abh_fg, retouren_fg, industrie_abh_fg, anz_stellplatz,
belos_sendungsstatus_id, rundlauf_transport_fg, fleischwerk_fg, distribution_abr_fg, brtgew_sendung, brtvol_stauraum,
anz_stellplatz_belos, menge_lief_ist_kolli) AS SELECT AGG.lief_beleg_id,
 AGG.lief_typ_id,
 AGG.mandant_id,
 BELOS.belos_vorgang_id,
 BELOS.nb_id,
 AGG.dat_lief_soll,
 BELOS.dat_leistung,
 BELOS.sendung_id,
 AGG.lagerort_id,
 BELOS.transportauftrag_id,
 BELOS.sonderabwicklung_id,
 BELOS.belos_adresse_absender_num_id,
 BELOS.belos_adresse_empfaenger_id,
 BELOS.belos_adresse_spedition_id,
 BELOS_ADRESSE.adress_name,
 AGG.lagernummer_id,
 AGG.transportation_unit_id,
 EXTRACT(YEAR FROM AGG.dat_tour) AS kj_transportation_unit,
 BELOS.leergut_abh_fg,
 BELOS.retouren_fg,
 BELOS.industrie_abh_fg,
 BELOS.anz_stellplatz,
 BELOS.belos_sendungsstatus_id,
 BELOS.rundlauf_transport_fg,
 BELOS.fleischwerk_fg,
 BELOS.distribution_abr_fg,
 MAX(BELOS.brtgew_sendung) AS brtgew_sendung,
 MAX(BELOS.brtvol_stauraum) AS brtvol_stauraum,
 MAX(BELOS.anz_stellplatz_belos) AS anz_stellplatz_belos,
 SUM(AGG.menge_lief_ist_kolli) AS menge_lief_ist_kolli
FROM kfl_production_dbp_view.v_besch_lief_wa_det_1 AS AGG
 LEFT JOIN kfl_production_dbp_view.v_belos_vorgang_1 AS BELOS ON AGG.mandant_id = BELOS.mandant_id AND AGG.belos_vorgang_id
    = BELOS.belos_vorgang_id
 LEFT JOIN kfl_production_dbp_view.v_belos_adresse_1 AS BELOS_ADRESSE_1 ON BELOS.mandant_id = BELOS_ADRESSE.mandant_id AND
   BELOS.belos_adresse_spedition_id = BELOS_ADRESSE.belos_adresse_id
WHERE COALESCE(BELOS.belosart_fg, 1) = 1
 AND AGG.lief_typ_id NOT IN ('YCD1', 'EL')
GROUP BY AGG.lief_beleg_id,
 AGG.lief_typ_id,
 AGG.mandant_id,
 BELOS.belos_vorgang_id,
 BELOS.nb_id,
 BELOS.dat_leistung,
 AGG.dat_lief_soll,
 BELOS.sendung_id,
 AGG.lagerort_id,
 BELOS.transportauftrag_id,
 BELOS.sonderabwicklung_id,
 BELOS.belos_adresse_absender_num_id,
 BELOS.belos_adresse_empfaenger_id,
 BELOS.belos_adresse_spedition_id,
 BELOS_ADRESSE.adress_name,
 AGG.lagernummer_id,
 AGG.transportation_unit_id,
 kj_transportation_unit,
 BELOS.leergut_abh_fg,
 BELOS.retouren_fg,
 BELOS.industrie_abh_fg,
 BELOS.anz_stellplatz,
 BELOS.belos_sendungsstatus_id,
 BELOS.rundlauf_transport_fg,
 BELOS.fleischwerk_fg,
 BELOS.distribution_abr_fg;