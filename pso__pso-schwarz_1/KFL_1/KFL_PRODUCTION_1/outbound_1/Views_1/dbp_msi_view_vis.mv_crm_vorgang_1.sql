FROM kfl_production_dbp_view.v_crm_vorgang_1 AS V01
 INNER JOIN kfl_production_dbp_view.v_crm_l_themenbaum_lv2_1 AS V02 ON V01.crm_themenbaum_lv2_id = V02.crm_themenbaum_lv2_id
  
 INNER JOIN kfl_production_dbp_view.v_wup_1 AS WUP_1 ON V01.mandant_id = WUP.mandant_id AND V01.wup_id = WUP.wup_id;