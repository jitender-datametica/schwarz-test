CREATE OR REPLACE PROCEDURE dbp_macro.m_delete_in_lieferant_int(IN IN_LIEF_ID_INT FLOAT64, IN LIEFERANT_INT_LOESCH_FG FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;

BEGIN TRANSACTION;

SET sql_stmt  =  '''DELETE FROM dbp_data.in_lieferant_int_1 WHERE in_lief_id_int = @IN_LIEF_ID_INT AND 1 = @LIEFERANT_INT_LOESCH_FG''';

EXECUTE IMMEDIATE (sql_stmt) USING IN_LIEF_ID_INT AS IN_LIEF_ID_INT,  LIEFERANT_INT_LOESCH_FG AS LIEFERANT_INT_LOESCH_FG;

SET sql_stmt  =  '''UPDATE dbp_data.in_lieferant_1 SET  in_lief_id_int = -1 WHERE in_lief_id_int = @IN_LIEF_ID_INT AND 1 = @LIEFERANT_INT_LOESCH_FG  ''';

EXECUTE IMMEDIATE (sql_stmt) USING IN_LIEF_ID_INT AS IN_LIEF_ID_INT,  LIEFERANT_INT_LOESCH_FG AS LIEFERANT_INT_LOESCH_FG;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;