CREATE OR REPLACE PROCEDURE dbp_macro.m_delete_msi_user(IN USER_ID STRING, IN MSI_PRODUKT_BEZ STRING, IN LOESCH_FG FLOAT64)
BEGIN

DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;

BEGIN TRANSACTION;
SET sql_stmt  =  '''DELETE FROM dbp_security.user_mandant_msiprodukt_zu_1 WHERE @LOESCH_FG = 1 AND user_id = @USER_ID AND msi_produkt_bez = @MSI_PRODUKT_BEZ ''';

EXECUTE IMMEDIATE (sql_stmt) USING USER_ID AS USER_ID,  MSI_PRODUKT_BEZ AS MSI_PRODUKT_BEZ,  LOESCH_FG AS LOESCH_FG;

SET sql_stmt  =  '''DELETE FROM dbp_security.l_msi_user_1 WHERE @LOESCH_FG = 1 AND user_id = @USER_ID AND msi_produkt_bez = @MSI_PRODUKT_BEZ ''';

EXECUTE IMMEDIATE (sql_stmt) USING USER_ID AS USER_ID,  MSI_PRODUKT_BEZ AS MSI_PRODUKT_BEZ,  LOESCH_FG AS LOESCH_FG;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;
