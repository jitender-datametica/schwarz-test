CREATE OR REPLACE PROCEDURE dbp_macro.m_delete_ts_autodispo_dif(IN MANDANT_ID_KUNDE FLOAT64, IN WUP_ID_KUNDE FLOAT64, IN NB_ID_KUNDE FLOAT64, IN MANDANT_ID_VZ FLOAT64, IN WUP_ID_VZ FLOAT64, IN NB_ID_VZ FLOAT64, IN ART_ID FLOAT64, IN VS_ID FLOAT64, IN VKL_ID FLOAT64, IN WG_ID FLOAT64, IN ART_GRUPPE_ID STRING, IN DAT_VON STRING, IN DAT_BIS STRING, IN SA_AF_FG FLOAT64, IN ART_CLUSTER_ID FLOAT64, IN WUP_CLUSTER_ID FLOAT64, IN WERBEGRUPPE_FLEISCH STRING, IN DIF_FUNKTION_ID STRING, IN DIF_TYP_ID FLOAT64, IN MENGE_EINH_ID STRING, IN DIF_STATUS_ID FLOAT64, IN DELETE_FG FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;
BEGIN TRANSACTION;
SET sql_stmt  =  '''DELETE FROM dbp_data.ts_autodispo_dif_1 WHERE 1 = @DELETE_FG 
AND mandant_id_kunde = @MANDANT_ID_KUNDE 
AND wup_id_kunde = @WUP_ID_KUNDE 
AND nb_id_kunde = @NB_ID_KUNDE 
AND mandant_id_vz = @MANDANT_ID_VZ 
AND wup_id_vz = @WUP_ID_VZ
 AND nb_id_vz = @NB_ID_VZ 
 AND art_id = @ART_ID               
 AND vs_id = @VS_ID 
 AND vkl_id = @VKL_ID 
 AND wg_id = @WG_ID 
 AND art_gruppe_id = @ART_GRUPPE_ID 
 AND dat_von = @DAT_VON 
 AND dat_bis = @DAT_BIS 
 AND sa_af_fg = @SA_AF_FG 
 AND art_cluster_id = @ART_CLUSTER_ID 
 AND wup_cluster_id = @WUP_CLUSTER_ID 
 AND werbegruppe_fleisch = @WERBEGRUPPE_FLEISCH 
 AND dif_funktion_id = @DIF_FUNKTION_ID 
 AND dif_typ_id = @DIF_TYP_ID 
 AND menge_einh_id = @MENGE_EINH_ID 
 AND dif_status_id = @DIF_STATUS_ID ''';


SET sql_stmt  =  REGEXP_REPLACE(sql_stmt, 'undefined', 'NULL');

EXECUTE IMMEDIATE (sql_stmt) USING MANDANT_ID_KUNDE AS MANDANT_ID_KUNDE,  WUP_ID_KUNDE AS WUP_ID_KUNDE,  NB_ID_KUNDE AS NB_ID_KUNDE,  MANDANT_ID_VZ AS MANDANT_ID_VZ,  WUP_ID_VZ AS WUP_ID_VZ,  NB_ID_VZ AS NB_ID_VZ,  ART_ID AS ART_ID,  VS_ID AS VS_ID,  VKL_ID AS VKL_ID,  WG_ID AS WG_ID,  ART_GRUPPE_ID AS ART_GRUPPE_ID,  DAT_VON AS DAT_VON,  DAT_BIS AS DAT_BIS,  SA_AF_FG AS SA_AF_FG,  ART_CLUSTER_ID AS ART_CLUSTER_ID,  WUP_CLUSTER_ID AS WUP_CLUSTER_ID,  WERBEGRUPPE_FLEISCH AS WERBEGRUPPE_FLEISCH,  DIF_FUNKTION_ID AS DIF_FUNKTION_ID,  DIF_TYP_ID AS DIF_TYP_ID,  MENGE_EINH_ID AS MENGE_EINH_ID,  DIF_STATUS_ID AS DIF_STATUS_ID,  DELETE_FG AS DELETE_FG;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;