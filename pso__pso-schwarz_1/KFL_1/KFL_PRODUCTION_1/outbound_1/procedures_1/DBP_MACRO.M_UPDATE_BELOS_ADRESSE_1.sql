CREATE OR REPLACE PROCEDURE dbp_macro.m_update_belos_adresse(IN BELOS_STANDORT_TYP_ID FLOAT64, IN MANDANT_ID FLOAT64, IN BELOS_ADRESSE_ID STRING)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;
BEGIN TRANSACTION;
SET sql_stmt  =  '''UPDATE dbp_data.belos_adresse_1 SET  belos_standort_typ_id = CAST(@BELOS_STANDORT_TYP_ID AS INT64) WHERE mandant_id=CAST(@MANDANT_ID AS INT64)  AND belos_adresse_id =@BELOS_ADRESSE_ID ''';

EXECUTE IMMEDIATE (sql_stmt) USING BELOS_STANDORT_TYP_ID AS BELOS_STANDORT_TYP_ID,  MANDANT_ID AS MANDANT_ID,  BELOS_ADRESSE_ID AS BELOS_ADRESSE_ID;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;
