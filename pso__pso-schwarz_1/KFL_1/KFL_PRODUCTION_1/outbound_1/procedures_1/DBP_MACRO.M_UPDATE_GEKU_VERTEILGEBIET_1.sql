CREATE OR REPLACE PROCEDURE dbp_macro.m_update_geku_verteilgebiet(IN VERTEILGEBIET_UID FLOAT64, IN NILS_VERTEILGEBIET_ID FLOAT64, IN MANDANT_ID FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;
BEGIN TRANSACTION;
SET sql_stmt  =  '''UPDATE dbp_data.geku_verteilgebiet_1 SET  nils_verteilgebiet_id = CAST(@NILS_VERTEILGEBIET_ID AS INT64)  ,  mandant_id = CAST(@MANDANT_ID AS INT64) WHERE verteilgebiet_uid = CAST(@VERTEILGEBIET_UID AS INT64)''';

EXECUTE IMMEDIATE (sql_stmt) USING NILS_VERTEILGEBIET_ID AS NILS_VERTEILGEBIET_ID,  MANDANT_ID AS MANDANT_ID,  VERTEILGEBIET_UID AS VERTEILGEBIET_UID;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;
