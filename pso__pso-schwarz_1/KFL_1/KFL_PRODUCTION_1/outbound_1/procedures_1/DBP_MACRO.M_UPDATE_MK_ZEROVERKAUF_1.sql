CREATE OR REPLACE PROCEDURE dbp_macro.m_update_mk_zeroverkauf(IN WUP_ID FLOAT64, IN MANDANT_ID FLOAT64, IN ART_ID FLOAT64, IN DAT DATE, IN ZEITFENSTER_ID FLOAT64, IN ART_FEHLGRUND_BEZ STRING, IN ART_FEHLGRUND_TEXT STRING)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;
BEGIN TRANSACTION;
SET sql_stmt  =  'UPDATE dbp_data.mk_zeroverkauf_1 SET  art_fehlgrund_id = CAST(CASE    WHEN @ART_FEHLGRUND_BEZ IS NULL    THEN SUBSTR(CAST(mk_zeroverkauf.art_fehlgrund_id AS STRING), 1, 100)    ELSE SUBSTR(@ART_FEHLGRUND_BEZ_1, 1, 2)    END AS INTEGER),  art_fehlgrund_text = @ART_FEHLGRUND_TEXT,  dat_erfasst = CAST(CURRENT_TIMESTAMP() AS DATETIME) WHERE (CAST(SUBSTR(@ART_FEHLGRUND_BEZ_1_2, 1, 2) AS FLOAT64) <> 0 OR @ART_FEHLGRUND_BEZ_1_2_3 IS NULL) AND mandant_id =CAST(@MANDANT_ID AS INT64) AND wup_id =CAST(@WUP_ID AS INT64)AND dat =CAST(@DAT AS DATE) AND zeitfenster_id =CAST(@ZEITFENSTER_ID AS INT64) AND art_id=CAST(@ART_ID AS INT64)' ;
 -- bisherigen Grund beibehalten 

EXECUTE IMMEDIATE (sql_stmt) USING ART_FEHLGRUND_BEZ AS ART_FEHLGRUND_BEZ,  ART_FEHLGRUND_BEZ AS ART_FEHLGRUND_BEZ_1,  ART_FEHLGRUND_TEXT AS ART_FEHLGRUND_TEXT,  MANDANT_ID AS MANDANT_ID,  WUP_ID AS WUP_ID,  FORMAT_TIMESTAMP('%FT%H:%M:%S', DAT) AS DAT,  ZEITFENSTER_ID AS ZEITFENSTER_ID,  ART_ID AS ART_ID,  ART_FEHLGRUND_BEZ AS ART_FEHLGRUND_BEZ_1_2,  ART_FEHLGRUND_BEZ AS ART_FEHLGRUND_BEZ_1_2_3;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;
