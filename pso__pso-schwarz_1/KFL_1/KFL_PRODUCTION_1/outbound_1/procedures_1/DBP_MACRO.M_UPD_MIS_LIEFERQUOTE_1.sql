CREATE OR REPLACE PROCEDURE dbp_macro.m_upd_mis_lieferquote(IN MANDANT_ID FLOAT64, IN LIEFERQUOTE FLOAT64, IN DATENQUOTE FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;
BEGIN TRANSACTION;
SET sql_stmt  =  '''UPDATE dbp_msi_data.mis_lieferquote_1 SET  mandant_id = CAST(@MANDANT_ID AS INT64),  lieferquote =CAST(@LIEFERQUOTE AS NUMERIC) ,  datenquote = CAST(@DATENQUOTE AS NUMERIC) WHERE mandant_id = @MANDANT_ID_1 ''';

EXECUTE IMMEDIATE (sql_stmt) USING MANDANT_ID AS MANDANT_ID,  LIEFERQUOTE AS LIEFERQUOTE,  DATENQUOTE AS DATENQUOTE,  MANDANT_ID AS MANDANT_ID_1;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;
 