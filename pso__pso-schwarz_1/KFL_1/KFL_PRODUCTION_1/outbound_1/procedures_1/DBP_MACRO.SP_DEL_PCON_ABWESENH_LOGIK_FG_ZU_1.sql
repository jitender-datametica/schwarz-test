CREATE OR REPLACE PROCEDURE dbp_macro.sp_del_pcon_abwesenh_logik_fg_zu(IN P_MANDANT_ID FLOAT64, 
    IN P_ABWESENHEIT_ID STRING,
    IN P_KJMO_BIS FLOAT64,
    IN P_KJMO_VON FLOAT64,
    IN P_LOGIK_KZ STRING,
    IN P_LANGZEIT_ABWESEND_FG FLOAT64,
    IN P_PFLEGE_FG FLOAT64,
    IN P_BESCHAEFTIGUNGS_VERBOT_FG FLOAT64,
    IN P_KRANKHEIT_UNFALL_FG FLOAT64,
    IN P_SONSTIGE_ABWESENHEIT_FG FLOAT64,
    IN P_FREIGESTELLT_FG FLOAT64,
    IN P_MUTTERSCHUTZ_FG FLOAT64,
    IN P_ELTERNZEIT_FG FLOAT64,
    IN P_LOESCHEN_FG FLOAT64)

BEGIN
DECLARE sql_commit STRING;
DECLARE sql_stmt STRING;
-- Vorhandener Datensatz loeschen
BEGIN TRANSACTION;

IF P_LOESCHEN_FG = 1 THEN
    BEGIN

    SET sql_stmt  =  '''DELETE FROM dbp_data.pcon_abwesenh_logik_fg_zu_1 
                        WHERE kjmo_bis = @P_KJMO_BIS AND kjmo_von = @P_KJMO_VON AND logik_kz = @P_LOGIK_KZ 
                        AND langzeit_abwesend_fg = @P_LANGZEIT_ABWESEND_FG AND pflege_fg = @P_PFLEGE_FG 
                        AND beschaeftigungs_verbot_fg = @P_BESCHAEFTIGUNGS_VERBOT_FG AND krankheit_unfall_fg = @P_KRANKHEIT_UNFALL_FG 
                        AND sonstige_abwesenheit_fg = @P_SONSTIGE_ABWESENHEIT_FG AND freigestellt_fg = @P_FREIGESTELLT_FG 
                        AND mutterschutz_fg = @P_MUTTERSCHUTZ_FG AND elternzeit_fg = @P_ELTERNZEIT_FG 
                        AND mandant_id = @P_MANDANT_ID AND abwesenheit_id = @P_ABWESENHEIT_ID ''';

    EXECUTE IMMEDIATE (sql_stmt) USING P_KJMO_BIS AS P_KJMO_BIS,  P_KJMO_VON AS P_KJMO_VON,  P_LOGIK_KZ AS P_LOGIK_KZ,  P_LANGZEIT_ABWESEND_FG AS P_LANGZEIT_ABWESEND_FG,  P_PFLEGE_FG AS P_PFLEGE_FG,  P_BESCHAEFTIGUNGS_VERBOT_FG AS P_BESCHAEFTIGUNGS_VERBOT_FG,  P_KRANKHEIT_UNFALL_FG AS P_KRANKHEIT_UNFALL_FG,  P_SONSTIGE_ABWESENHEIT_FG AS P_SONSTIGE_ABWESENHEIT_FG,  P_FREIGESTELLT_FG AS P_FREIGESTELLT_FG,  P_MUTTERSCHUTZ_FG AS P_MUTTERSCHUTZ_FG,  P_ELTERNZEIT_FG AS P_ELTERNZEIT_FG,  P_MANDANT_ID AS P_MANDANT_ID,  P_ABWESENHEIT_ID AS P_ABWESENHEIT_ID;

    END;
END IF;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;