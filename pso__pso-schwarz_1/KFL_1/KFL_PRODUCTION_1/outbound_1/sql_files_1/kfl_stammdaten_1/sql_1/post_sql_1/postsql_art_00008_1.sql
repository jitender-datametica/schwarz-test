CREATE OR REPLACE TABLE dbp_etl.`_murks_1` AS
SELECT
    T1.mandant_id,
    T1.art_id,
    SUBSTR(T1.sustain_concat, `_track`.nr_von, 3) AS zeichen
FROM dbp_data.art_1 AS T1_1
INNER JOIN dbp_etl.`_track` ON TRUE
WHERE
    TRIM(T1.sustain_concat) <> '' AND
    SUBSTR(T1.sustain_concat, `_track`.nr_von, 3) <> '';


CREATE OR REPLACE TABLE dbp_etl.`_murks2` AS
SELECT
    mandant_id,
    art_id,
    STRING_AGG(zeichen, ',' ORDER BY zeichen IS NULL, zeichen) AS sustain_concat_neu
FROM (
    SELECT DISTINCT
        mandant_id,
        art_id,
        zeichen
    FROM dbp_etl.`_murks_1`
)
GROUP BY mandant_id, art_id;


UPDATE dbp_data.art_1 SET
    sustain_concat = b.sustain_concat_neu
FROM dbp_etl.`_murks2` AS b
WHERE art.mandant_id = b.mandant_id AND art.art_id = b.art_id;


UPDATE dbp_data.art_1 AS A SET
    sustain_concat = ''
WHERE
    sustain_concat <> ''
    AND mandant_id IN (
        SELECT DISTINCT mandant_id
        FROM ${TEMP_TABLE} AS B
    )
    AND NOT EXISTS (
        SELECT 1 FROM ${TEMP_TABLE} AS B
        WHERE
            mandant_id = A.mandant_id
            AND art_id = A.art_id
    );
