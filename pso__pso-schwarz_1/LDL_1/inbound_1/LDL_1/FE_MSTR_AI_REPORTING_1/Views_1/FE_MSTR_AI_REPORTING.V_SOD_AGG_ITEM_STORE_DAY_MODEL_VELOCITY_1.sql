CREATE OR REPLACE VIEW FE_MSTR_AI_REPORTING.V_SOD_AGG_ITEM_STORE_DAY_MODEL_VELOCITY_1(
	CLIENT_ID
	, MODEL_SID
	, MODEL_RUN_DT
	, ITEM_SID
	, LOC_SID
	, PREDICTION_DT
	, SEGMENTATION_SID
	, SEGMENT_SID
	, MODEL_AREA_CD
	, MODEL_GROUP_CD
	, DWH_LOAD_ID
	, DWH_CREATED
	, DWH_UPDATED
	, ASPECT_ID
) AS
    /* Version: 1.0
    ** Author:  Stefan Sockel
    ** Date:    2022-11-09
    ** Changes: Initial version
    */
SELECT
    SG.CLIENT_ID
	,SG.MODEL_SID
	,SG.MODEL_RUN_DT
	,SG.ITEM_SID
	,SG.LOC_SID
	,SG.PREDICTION_DT
	,SG.SEGMENTATION_SID
	,SG.SEGMENT_SID
	,SG.MODEL_AREA_CD
	,SG.MODEL_GROUP_CD
	,SG.DWH_LOAD_ID
	,SG.DWH_CREATED
	,SG.DWH_UPDATED
    ,2 
FROM 
    "P_LEW_CORE"."T_ITEM_STORE_DAY_MODEL_SEGMENT_1" AS SG
INNER JOIN
      (
      SELECT 
        ROW_NUMBER() OVER (PARTITION BY PREDICTION_DT ORDER BY MODEL_RUN_DT DESC) AS RN
        ,MODEL_RUN_DT
        ,PREDICTION_DT
      FROM 
        "P_LEW_CORE"."T_ITEM_STORE_DAY_MODEL_SEGMENT_1"
      WHERE
        SEGMENTATION_SID = 1
      GROUP BY MODEL_RUN_DT,PREDICTION_DT
        ORDER BY 3,1
      ) RW
ON 
    SG.MODEL_RUN_DT = RW.MODEL_RUN_DT AND SG.PREDICTION_DT = RW.PREDICTION_DT    
WHERE 
    SG.SEGMENTATION_SID = 1
    AND RW.RN = 1
    ;