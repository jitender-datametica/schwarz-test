CREATE OR REPLACE PROCEDURE FE_MSTR_TOOLBOX_SPIEGEL.P_KOP_TS
(
  P_INT_ORG_SID NUMBER
, P_SPACEMAN_ITEM_SID NUMBER
, P_HEAVY_SORT VARCHAR(300)
, P_CENTER_PULL VARCHAR(300)
, P_EASY_IDENT VARCHAR(300)
, P_REASON VARCHAR(300)
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
MERGE INTO FE_MSTR_TOOLBOX_SPIEGEL.T_SPACEMAN_KOP_TS_1 AS TARGET
USING
(
SELECT
  :P_INT_ORG_SID		AS INT_ORG_SID
, :P_SPACEMAN_ITEM_SID	AS SPACEMAN_ITEM_SID
, :P_HEAVY_SORT			AS HEAVY_SORT
, :P_CENTER_PULL		AS CENTER_PULL
, :P_EASY_IDENT			AS EASY_IDENT
, :P_REASON				AS REASON
) AS SOURCE
 ON TARGET.SPACEMAN_ITEM_SID = SOURCE.SPACEMAN_ITEM_SID
 AND TARGET.INT_ORG_SID = SOURCE.INT_ORG_SID

WHEN MATCHED THEN UPDATE SET
      TARGET.HEAVY_SORT		= SOURCE.HEAVY_SORT
    , TARGET.CENTER_PULL	= SOURCE.CENTER_PULL
    , TARGET.EASY_IDENT		= SOURCE.EASY_IDENT
    , TARGET.REASON			= SOURCE.REASON
	, TARGET.DWH_UPDATED	= CURRENT_TIMESTAMP

WHEN NOT MATCHED THEN INSERT
(
  INT_ORG_SID
, SPACEMAN_ITEM_SID
, HEAVY_SORT
, CENTER_PULL
, EASY_IDENT
, REASON
, DWH_CREATED
, DWH_UPDATED)
VALUES
(
  SOURCE.INT_ORG_SID
, SOURCE.SPACEMAN_ITEM_SID
, SOURCE.HEAVY_SORT
, SOURCE.CENTER_PULL
, SOURCE.EASY_IDENT
, SOURCE.REASON
, CURRENT_TIMESTAMP
, CURRENT_TIMESTAMP
);
COMMIT;
RETURN 'Data Updated';
END;
$$;