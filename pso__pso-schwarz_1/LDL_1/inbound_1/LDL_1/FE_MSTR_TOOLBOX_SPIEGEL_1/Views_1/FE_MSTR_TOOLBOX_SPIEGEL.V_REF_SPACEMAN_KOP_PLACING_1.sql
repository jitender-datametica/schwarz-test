, PBT_PLACING_DESC_ES
, PBT_PLACING_DESC_FI
, PBT_PLACING_DESC_FR
, PBT_PLACING_DESC_GB
, PBT_PLACING_DESC_GR
, PBT_PLACING_DESC_HR
, PBT_PLACING_DESC_HU
