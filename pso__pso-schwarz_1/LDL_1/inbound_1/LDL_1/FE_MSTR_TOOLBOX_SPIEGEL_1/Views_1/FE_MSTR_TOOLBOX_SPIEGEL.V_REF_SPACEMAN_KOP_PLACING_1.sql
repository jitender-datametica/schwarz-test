 , PBT_PLACING_EN	AS PBT_PLACING_DESC_SK
 , PBT_PLACING_EN	AS PBT_PLACING_DESC_CS
 , PBT_PLACING_EN	AS PBT_PLACING_DESC_MT
 , PBT_PLACING_EN	AS PBT_PLACING_DESC_US
 , PBT_PLACING_EN	AS PBT_PLACING_DESC_RS
FROM
 (
	SELECT DISTINCT
	PBT_PLACING
	,CASE
	WHEN PBT_PLACING = 'Palette - DD' THEN 'DD'
	WHEN PBT_PLACING = 'Palette - EP/GMA' THEN 'EP/GMA'
	WHEN PBT_PLACING = 'Regal - Mittel_Oberzug' THEN 'Middle/ Top Shelf'
	WHEN PBT_PLACING = 'Regal - Podest' THEN 'Plinth'
	ELSE ' '
	END AS PBT_PLACING_EN
	,CASE
	WHEN PBT_PLACING = 'Palette - DD' THEN 'DD'
	WHEN PBT_PLACING = 'Palette - EP/GMA' THEN 'EP/GMA'
	WHEN PBT_PLACING = 'Regal - Mittel_Oberzug' THEN 'Mittel-/Oberzug'
	WHEN PBT_PLACING = 'Regal - Podest' THEN 'Podest'
	ELSE ' '
	END AS PBT_PLACING_DE
	FROM
	FE_MSTR_TOOLBOX_SPIEGEL.V_AGG_SPACEMAN_KOP_1
 );