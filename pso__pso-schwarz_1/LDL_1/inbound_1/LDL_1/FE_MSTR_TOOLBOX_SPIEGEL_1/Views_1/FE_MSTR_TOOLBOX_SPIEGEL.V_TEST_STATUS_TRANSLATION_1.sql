CREATE OR REPLACE VIEW FE_MSTR_TOOLBOX_SPIEGEL.V_TEST_STATUS_TRANSLATION_1(
  TEST_STATUS
 ,TEST_STATUS_US
 ,TEST_STATUS_GB
) AS
SELECT
  TEST_STATUS
 ,TEST_STATUS_US
 ,TEST_STATUS_GB
FROM
(
SELECT 
 'abgeschlossen'	AS TEST_STATUS
,'finished'			AS TEST_STATUS_US
,'finished'			AS TEST_STATUS_GB
 
UNION
 
SELECT 
 'laufend'			AS TEST_STATUS
,'running'			AS TEST_STATUS_US
,'running'			AS TEST_STATUS_GB
) stattransl;