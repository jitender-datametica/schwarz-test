CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_DIM_COUNTRY_1 (
	COUNTRY_CD
	,COUNTRY_NAME
	) AS

SELECT DISTINCT C.MARKET_RESEARCH_COUNTRY_CD
	,C.MARKET_RESEARCH_COUNTRY_NAME
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_COUNTRY_1 C
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_DATA_DELIVERY_1 DD ON C.MARKET_RESEARCH_COUNTRY_CD = DD.MARKET_RESEARCH_COUNTRY_CD;