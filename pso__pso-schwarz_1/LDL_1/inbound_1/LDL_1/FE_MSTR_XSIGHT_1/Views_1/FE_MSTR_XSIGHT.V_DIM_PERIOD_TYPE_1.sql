CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_DIM_PERIOD_TYPE_1 (
	PERIOD_TYPE_CD
	,PERIOD_TYPE_DESCR
	) AS

SELECT DISTINCT BP.MARKET_RESEARCH_PERIOD_TYPE_CD AS PERIOD_TYPE_CD
	,PT.MARKET_RESEARCH_PERIOD_TYPE_DESCR AS PERIOD_TYPE_DESCR
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_1 BP
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION_1 PR --GET NIELSEN PERIOD
	ON BP.MARKET_RESEARCH_PERIOD_SID = PR.REL_MARKET_RESEARCH_PERIOD_SID
	AND PR.MARKET_RESEARCH_PERIOD_REL_TYPE_CD = 'src_to_bc'
JOIN P_LEW_CORE_AC.V_LOCAL_MARKET_RESEARCH_PERIOD_1 LP --GET LOCAL PERIOD BY COUNTRY_1 AND SRC_SEGMENT
	ON LP.MARKET_RESEARCH_PERIOD_SID = PR.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION_1 PYPR --GET PREVIOUS YEAR BUSINESS PERIOD
	ON BP.MARKET_RESEARCH_PERIOD_SID = PYPR.MARKET_RESEARCH_PERIOD_SID
	AND PYPR.MARKET_RESEARCH_PERIOD_REL_TYPE_CD = 'prev_year'
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_1 PYBP ON PYPR.REL_MARKET_RESEARCH_PERIOD_SID = PYBP.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION_1 PRPYLP --GET PREVIOS YEAR NIELSEN PERIOD
	ON PYPR.REL_MARKET_RESEARCH_PERIOD_SID = PRPYLP.REL_MARKET_RESEARCH_PERIOD_SID
	AND PRPYLP.MARKET_RESEARCH_PERIOD_REL_TYPE_CD = 'src_to_bc'
JOIN P_LEW_CORE_AC.V_LOCAL_MARKET_RESEARCH_PERIOD_1 PYLP --GET PREVIOS YEAR LOCAL PERIOD BY COUNTRY_1 AND SRC_SEGMENT
	ON PYLP.MARKET_RESEARCH_PERIOD_SID = PRPYLP.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_TYPE_1 PT --GET PREVIOS YEAR LOCAL PERIOD BY COUNTRY_1 AND SRC_SEGMENT
	ON BP.MARKET_RESEARCH_PERIOD_TYPE_CD = PT.MARKET_RESEARCH_PERIOD_TYPE_CD;