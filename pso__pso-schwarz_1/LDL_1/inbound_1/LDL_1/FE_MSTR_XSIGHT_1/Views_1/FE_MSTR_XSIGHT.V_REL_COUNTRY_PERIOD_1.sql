CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_REL_COUNTRY_PERIOD_1 (
	PERIOD_TYPE_CD
	,COUNTRY_CD
	) AS

SELECT DISTINCT PER2.MARKET_RESEARCH_PERIOD_TYPE_CD AS PERIOD_TYPE_CD
	,FACT.MARKET_RESEARCH_COUNTRY_CD AS COUNTRY_CD
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_METRIC_1 FACT
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_1 PERIOD ON PERIOD.MARKET_RESEARCH_PERIOD_SID = FACT.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_RELATION_1 REL ON PERIOD.MARKET_RESEARCH_PERIOD_SID = REL.MARKET_RESEARCH_PERIOD_SID
JOIN P_LEW_CORE_AC.V_MARKET_RESEARCH_PERIOD_1 PER2 ON PER2.MARKET_RESEARCH_PERIOD_SID = REL.REL_MARKET_RESEARCH_PERIOD_SID;