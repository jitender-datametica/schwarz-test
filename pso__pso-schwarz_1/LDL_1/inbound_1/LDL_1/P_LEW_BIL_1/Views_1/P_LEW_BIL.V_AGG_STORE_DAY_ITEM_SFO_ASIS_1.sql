create or replace view LDL_PRODUCTION.P_LEW_BIL.V_AGG_STORE_DAY_ITEM_SFO_ASIS_1(
	CLIENT_ID,
	LOC_SID_STORE,
	SRC_ORIG_STORE_NR,
	BOOKING_DAT,
	CY_MONTH,
	ITEM_SID,
	SFOTYPE_ID,
	PCWO_REASON_ID,
	SFO_TOTAL_QTY_ASIS,
	SFO_WRTOFF_ZERO_QTY_ASIS,
	SFO_TOTAL_RTL_RL_VAL_ASIS,
	SFO_TOTAL_RTL_RL_NET_VAL_ASIS,
	SFO_WRTOFF_ZERO_RTL_RL_VAL_ASIS,
	SFO_WRTOFF_ZERO_RTL_RL_NET_VAL_ASIS,
	PRICE_WH_SFO_ASIS,
	PRICE_WH_NET_SFO_ASIS,
	PRICE_STR_SFO_ASIS,
	PRICE_STR_NET_SFO_ASIS,
	VAL_PR_DIFF_SFO_ASIS,
	VAL_PR_DIFF_NET_SFO_ASIS,
	SFO_TOTAL_FA_QTY_ASIS,
	SFO_WRTOFF_ZERO_FA_QTY_ASIS,
	SFO_TOTAL_RTL_RL_FA_VAL_ASIS,
	SFO_TOTAL_RTL_RL_NET_FA_VAL_ASIS,
	SFO_WRTOFF_ZERO_RTL_RL_FA_VAL_ASIS,
	SFO_WRTOFF_ZERO_RTL_RL_NET_FA_VAL_ASIS,
	PRICE_WH_FA_SFO_ASIS,
	PRICE_WH_NET_FA_SFO_ASIS,
	PRICE_STR_FA_SFO_ASIS,
	PRICE_STR_NET_FA_SFO_ASIS,
	VAL_PR_DIFF_FA_SFO_ASIS,
	VAL_PR_DIFF_NET_FA_SFO_ASIS,
	CURR_CD,
	CURR_SID,
	SRC_FG
) as
   SELECT
    agg.client_id,
   agg.loc_sid_store,
   agg.src_orig_store_nr,
   agg.booking_dat,
   agg.cy_month,
   agg.item_sid,
   agg.sfotype_id,
   agg.pcwo_reason_id,
   agg.sfo_total_qty                                                                                                                     AS sfo_total_qty_asis,
   agg.sfo_wrtoff_zero_qty                                                                                                               AS sfo_wrtoff_zero_qty_asis,
   agg.sfo_total_rtl_rl_val                                                                                                              AS sfo_total_rtl_rl_val_asis,
   agg.sfo_total_rtl_rl_net_val                                                                                                          AS sfo_total_rtl_rl_net_val_asis,
   agg.sfo_wrtoff_zero_rtl_rl_val                                                                                                        AS sfo_wrtoff_zero_rtl_rl_val_asis,
   agg.sfo_wrtoff_zero_rtl_rl_net_val                                                                                                    AS sfo_wrtoff_zero_rtl_rl_net_val_asis,
   CASE WHEN agg.sfotype_id IN (131, 141) AND agg.src_fg = 1 THEN
         Cast(NULL AS NUMBER(38,5)) ELSE (Abs(Cast(agg.sfo_total_wh_val AS NUMBER(38,5)) / CASE WHEN agg.sfo_total_qty = 0 THEN null ELSE agg.sfo_total_qty END)) END                          AS price_wh_sfo_asis,
   CASE WHEN agg.sfotype_id IN (131, 141) AND agg.src_fg = 1 THEN
         Cast(NULL AS NUMBER(38,5)) ELSE (Abs(Cast(agg.sfo_total_wh_net_val AS NUMBER(38,5)) / CASE WHEN agg.sfo_total_qty = 0 THEN null ELSE agg.sfo_total_qty END)) END                      AS price_wh_net_sfo_asis,
   CASE WHEN agg.sfotype_id IN (131, 141) AND agg.src_fg = 1 THEN
         Cast(NULL AS NUMBER(38,5)) ELSE (Abs(Cast(agg.sfo_total_store_val AS NUMBER(38,5)) / CASE WHEN agg.sfo_total_qty = 0 THEN null ELSE agg.sfo_total_qty END)) END                       AS price_str_sfo_asis,
   CASE WHEN agg.sfotype_id IN (131, 141) AND agg.src_fg = 1 THEN
         Cast(NULL AS NUMBER(38,5)) ELSE (Abs(Cast(agg.sfo_total_store_net_val AS NUMBER(38,5))/ CASE WHEN agg.sfo_total_qty = 0 THEN null ELSE agg.sfo_total_qty END)) END                     AS price_str_net_sfo_asis,
   CASE WHEN agg.sfotype_id IN (131, 141) AND agg.src_fg = 1 THEN
         Cast(NULL AS DECIMAL(18,4)) ELSE agg.val_pr_diff_sfo END                                                                         AS val_pr_diff_sfo_asis,
   CASE WHEN agg.sfotype_id IN (131, 141) AND agg.src_fg = 1 THEN
         Cast(NULL AS DECIMAL(19,5)) ELSE agg.val_pr_diff_net_sfo END                                                                     AS val_pr_diff_net_sfo_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN sfo_total_qty_asis                   ELSE NULL END                                        AS sfo_total_fa_qty_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN sfo_wrtoff_zero_qty_asis             ELSE NULL END                                        AS sfo_wrtoff_zero_fa_qty_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN sfo_total_rtl_rl_val_asis            ELSE NULL END                                        AS sfo_total_rtl_rl_fa_val_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN sfo_total_rtl_rl_net_val_asis        ELSE NULL END                                        AS sfo_total_rtl_rl_net_fa_val_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN sfo_wrtoff_zero_rtl_rl_val_asis      ELSE NULL END                                        AS sfo_wrtoff_zero_rtl_rl_fa_val_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN sfo_wrtoff_zero_rtl_rl_net_val_asis  ELSE NULL END                                        AS sfo_wrtoff_zero_rtl_rl_net_fa_val_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN price_wh_sfo_asis                    ELSE NULL END                                        AS price_wh_fa_sfo_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN price_wh_net_sfo_asis                ELSE NULL END                                        AS price_wh_net_fa_sfo_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN price_str_sfo_asis                   ELSE NULL END                                        AS price_str_fa_sfo_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN price_str_net_sfo_asis               ELSE NULL END                                        AS price_str_net_fa_sfo_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN val_pr_diff_sfo_asis                 ELSE NULL END                                        AS val_pr_diff_fa_sfo_asis,
   CASE WHEN agg.foodaction_fg_asis = 1   THEN val_pr_diff_net_sfo_asis             ELSE NULL END                                        AS val_pr_diff_net_fa_sfo_asis,
   c.curr_cd,
   c.curr_sid,
   agg.src_fg
   FROM p_lew_bil.t_agg_store_day_item_sfo_1 AS agg
   INNER JOIN p_lew_core_ac.v_client_1 c
   ON c.client_id=agg.client_id
   ;
