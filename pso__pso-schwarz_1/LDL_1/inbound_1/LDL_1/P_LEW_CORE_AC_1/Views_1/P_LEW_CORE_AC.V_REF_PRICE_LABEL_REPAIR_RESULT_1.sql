   PRICE_LABEL_REPAIR_RESULT_CD
  ,PRICE_LABEL_PRODUCER_NAME
  ,PRICE_LABEL_REPAIR_RESULT_DESCR
  ,DWH_LOAD_ID
  ,DWH_CREATED
  ,DWH_UPDATED
FROM P_LEW_CORE.T_REF_PRICE_LABEL_REPAIR_RESULT_1
