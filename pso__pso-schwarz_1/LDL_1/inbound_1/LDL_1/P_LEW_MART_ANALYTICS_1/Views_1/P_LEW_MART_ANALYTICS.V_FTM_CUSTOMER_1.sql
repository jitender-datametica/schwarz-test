CREATE OR REPLACE VIEW P_LEW_MART_ANALYTICS.V_FTM_CUSTOMER_1
(
    CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
    , CNT_CUST
) 
AS
SELECT 
AGG_EJR.CLIENT_ID
,RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
,AGG_EJR.DAT_FORMDATE
,TAG.CY_WEEK
,AGG_EJR.STORE_ID
,AGG_EJR.ORIG_STORE_NR
,SUM(AGG_EJR.CNT_CUSTOMER_ASIS) AS CNT_CUST

FROM P_LEW_MART_MSI_AC.V_AGG_STR_DAY_EJR_TXJ_WW_ASIS_1 AS AGG_EJR
INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY_1 AS RCTRY
    ON AGG_EJR.CLIENT_ID = RCTRY.COUNTRY_ID
INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY_1 AS TAG_1
    ON TAG.DAT_CALENDAR = AGG_EJR.DAT_FORMDATE
WHERE AGG_EJR.CURRENCY_ISO_CD = 'EUR'
GROUP BY 1,2,3,4,5,6
;