create or replace view LDL_PRODUCTION_CLONE_GOOGLE_20260608_1030.P_LEW_MART_ANALYTICS.V_FTM_LDPL_STORE_DAY_1(
	CLIENT_ID,
	COUNTRY_CODE,
	DAT_FORMDATE,
	CY_WEEK,
	STORE_ID,
	ORIG_STORE_NR,
	CNT_CUST,
	CNT_RCPT
) as

SELECT  
      A11.CLIENT_ID
	, COUNTRY_ISO_CD AS COUNTRY_CODE
	, DAT_CALENDAR AS DAT_FORMDATE
	, CY_WEEK
	, LOC_SID AS STORE_ID
	, ORIG_STORE_NR
    , SUM(CNT_CUST) AS CNT_CUST
    , SUM(CNT_RCPT) AS CNT_RCPT
FROM  (SELECT   DWH_CAL_DT  DAT_CALENDAR
        	  , MOVE_TO_STORE_ID  MOVE_TO_STORE_ID
        	  , ASPECT_ID  ASPECT_ID
        	  , CLIENT_ID  CLIENT_ID
              , LOC_SID AS LOC_SID
			  , CY_WEEK
        	  , (CASE WHEN (COUNT(DISTINCT CUSTOMER_SID))=0 THEN NULL ELSE (COUNT(DISTINCT CUSTOMER_SID)) END)  CNT_CUST
        	  , (CASE WHEN COUNT(DISTINCT RECEIPT_CNT_UNIQ)=0 THEN NULL ELSE COUNT(DISTINCT RECEIPT_CNT_UNIQ) END)  CNT_RCPT
    FROM P_LEW_MART_LIDL_DIGITAL.V_AGG_CLIENT_STORE_RCPT_ITEM_LDPL_DAY_1
    WHERE ASPECT_ID = 2 AND LIDLPLUS_CUST_FG = 'Y'
    GROUP BY    DWH_CAL_DT
        	  , MOVE_TO_STORE_ID
        	  , ASPECT_ID
        	  , CLIENT_ID
              , LOC_SID
			  , CY_WEEK
    )A11
    JOIN P_LEW_MART_MSI.V_ORG_ALL_STORE_MERGE_1	A12
	  ON 	(A11.ASPECT_ID = A12.ASPECT_ID AND
	A11.CLIENT_ID = A12.CLIENT_ID AND 
	A11.MOVE_TO_STORE_ID = A12.MOVE_TO_STORE_ID)
GROUP BY   A11.CLIENT_ID
		 , COUNTRY_ISO_CD
         , DAT_CALENDAR
		 , CY_WEEK
		 , LOC_SID
		 , ORIG_STORE_NR
;
