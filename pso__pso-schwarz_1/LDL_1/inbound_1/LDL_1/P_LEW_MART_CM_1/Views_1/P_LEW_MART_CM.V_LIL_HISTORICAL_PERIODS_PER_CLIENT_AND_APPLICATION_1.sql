CREATE OR REPLACE VIEW P_LEW_MART_CM.V_LIL_HISTORICAL_PERIODS_PER_CLIENT_AND_APPLICATION_1(
	CLIENT_ID
	,PER_ID
	,APPLICATION_ID
	,ACTIVE_FG
	,ACTIVE_FG_PY
	,TRANSACTION_TMSP
) AS
WITH BASE AS (
    SELECT 
        T1.CLIENT_ID
        , T1.PER_ID
        , T1.APPLICATION_ID
        , T1.ACTIVE_FG
        , COALESCE(T3.ACTIVE_FG,0) AS ACTIVE_FG_PY
        , T1.TRANSACTION_TMSP
    FROM P_LEW_MART_CM.T_LIL_HISTORICAL_PERIODS_PER_CLIENT_AND_APPLICATION_1 AS T1_1
    JOIN P_LEW_MART_CM.V_LIL_PERIOD_1 AS T2
    ON (T1.PER_ID=T2.PER_ID)
    JOIN P_LEW_MART_CM.T_LIL_HISTORICAL_PERIODS_PER_CLIENT_AND_APPLICATION_1 AS T3
    ON (T2.PY_PER_ID = T3.PER_ID AND T1.CLIENT_ID = T3.CLIENT_ID AND T1.APPLICATION_ID = T3.APPLICATION_ID)
)
SELECT 
    CLIENT_ID
	,PER_ID
	,APPLICATION_ID
	,ACTIVE_FG
	,ACTIVE_FG_PY
	,TRANSACTION_TMSP
FROM BASE

UNION ALL

SELECT -- duplication for INT
    7 AS CLIENT_ID
	,PER_ID
	,APPLICATION_ID
	,ACTIVE_FG
	,ACTIVE_FG_PY
	,TRANSACTION_TMSP
FROM BASE
;