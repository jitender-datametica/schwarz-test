CREATE OR REPLACE VIEW P_LEW_MART_CM.V_LIL_RETAILER_1(
	RTL_ID
	,RTL_DESC
	,RTL_DESC_EN
	,RPT_DELTA_SYM
	,RTL_DESC_DELTA_PY_PERC
	,RTL_DESC_DELTA_PY_PERC_EN
) AS

SELECT DISTINCT
   RTL_ID
  ,CAST(REGION_RTL_DESC_DE AS VARCHAR(128)) AS REGION_RTL_DESC
  ,CAST(REGION_RTL_DESC_EN AS VARCHAR(128)) AS REGION_RTL_DESC_EN
  ,CAST('Δ' AS VARCHAR(10)) AS RPT_DELTA_SYM
  ,CAST(CONCAT(REGION_RTL_DESC_DE,' ','Δ','PY%') AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC
  ,CAST(CONCAT(REGION_RTL_DESC_EN,' ','Δ','PY%') AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC_EN
FROM P_LEW_PROCESS_MSTR_AC.V_LIL_REGION_RETAILER_1
UNION ALL
SELECT
   1010 AS RTL_ID
  ,'Hauptwettbewerber' AS RTL_DESC
  ,'Main Competitor' AS RTL_DESC_EN
  ,CAST('Δ' AS VARCHAR(10)) AS RPT_DELTA_SYM
  ,CAST('Hauptwettbewerber ΔPY%' AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC
  ,CAST('Main Competitor ΔPY%' AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC_EN
UNION ALL
SELECT
   1020 AS RTL_ID
  ,'2. Wettbewerber' AS RTL_DESC
  ,'2nd Competitor' AS RTL_DESC_EN
  ,CAST('Δ' AS VARCHAR(10)) AS RPT_DELTA_SYM
  ,CAST('2. Wettbewerber ΔPY%' AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC
  ,CAST('2nd Competitor ΔPY%' AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC_EN
UNION ALL  
SELECT
   1030 AS RTL_ID
  ,'3. Wettbewerber' AS RTL_DESC
  ,'3rd Competitor' AS RTL_DESC_EN
  ,CAST('Δ' AS VARCHAR(10)) AS RPT_DELTA_SYM
  ,CAST('3. Wettbewerber ΔPY%' AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC
  ,CAST('3rd Competitor ΔPY%' AS VARCHAR(128)) AS RTL_DESC_DELTA_PY_PERC_EN
  ORDER BY RTL_ID
;

