CREATE OR REPLACE VIEW P_LEW_MART_MSI.V_AGG_COUNRTY_GROUP_DAY_ROC_1
/*
#----------------------------------------------------------------------------
# History:
#  1.0  18.07.2022    Oliver Haus         Initial DDL deployment - RWL aggregated values for Cockpits
#  1.1  10.07.2023    Chetana Patil       Added logic for RWL_WEIGHTED_VJ  
#----------------------------------------------------------------------------
*/
(
	COUNTRY_GROUP_ID
  , CLIENT_ID
  , DAT_FORMDATE
  ,	CURRENCY_ISO_CD
  ,	QTY_PIECE_STC_WH
  ,	RWL_NOMINATOR
  ,	RWL_WEIGHTED
  , RWL_WEIGHTED_VJ
) COMMENT='Aggregated View on CounrtyGroup-Level for RWL in Cockpits'
 AS
	  WITH VORJAHRESWERTE AS(
	   SELECT 
	   WH.COUNTRY_GROUP_ID
	 , V02.CAL_DT AS DAT_FORMDATE
	 , ROC.CURRENCY_ISO_CD
	 , SUM(ROC.RWL_NOMINATOR)/SUM(ROC.QTY_PIECE_EP_WH) AS RWL_WEIGHTED_VJ
	   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC_1 ROC
	   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH
	   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
	   JOIN  P_LEW_MART_LEAD_AC.V_DIM_CAL_DAY_1 V02
	   ON ROC.DAT_FORMDATE = V02.CAL_DT_PREV_1Y
	   WHERE FLAGS_COMBINED = '0000'
	   AND WH.ASPECT_ID = 1
	   GROUP BY 
	   WH.COUNTRY_GROUP_ID
	 , V02.CAL_DT
	 , ROC.CURRENCY_ISO_CD) 
	 
	 , BASE AS(
	   SELECT 
	   WH.COUNTRY_GROUP_ID
	 , DAT_FORMDATE
	 , CURRENCY_ISO_CD
	 , SUM(QTY_PIECE_EP_WH) AS QTY_PIECE_STC_WH
	 , SUM(RWL_NOMINATOR) AS RWL_NOMINATOR
	 , SUM(RWL_NOMINATOR)/SUM(QTY_PIECE_EP_WH) AS RWL_WEIGHTED
	   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC_1 ROC
	   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH
	   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
	   WHERE FLAGS_COMBINED = '0000'
	   AND WH.ASPECT_ID = 1
	   GROUP BY 
	   WH.COUNTRY_GROUP_ID
	 , DAT_FORMDATE
	 , CURRENCY_ISO_CD) 

	 SELECT
	   COALESCE(BASE.COUNTRY_GROUP_ID, VJ.COUNTRY_GROUP_ID) AS COUNTRY_GROUP_ID 
	 , WH.CLIENT_ID
	 , COALESCE(BASE.DAT_FORMDATE, VJ.DAT_FORMDATE) AS DAT_FORMDATE
	 , COALESCE(BASE.CURRENCY_ISO_CD, VJ.CURRENCY_ISO_CD) AS CURRENCY_ISO_CD
	 , BASE.QTY_PIECE_STC_WH -- ON LEVEL LAENDERGRUPPE 
	 , BASE.RWL_NOMINATOR -- ON LEVEL LAENDERGRUPPE
	 , BASE.RWL_WEIGHTED -- ON LEVEL LAENDERGRUPPE 
	 , VJ.RWL_WEIGHTED_VJ -- ON LEVEL LAENDERGRUPPE
	FROM BASE 
	JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH 
	ON BASE.COUNTRY_GROUP_ID = WH.COUNTRY_GROUP_ID
	FULL OUTER JOIN VORJAHRESWERTE VJ
	ON  BASE.COUNTRY_GROUP_ID = VJ.COUNTRY_GROUP_ID
	AND BASE.CURRENCY_ISO_CD = VJ.CURRENCY_ISO_CD
	AND BASE.DAT_FORMDATE = VJ.DAT_FORMDATE
; 
