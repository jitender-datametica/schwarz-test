CREATE OR REPLACE VIEW P_LEW_MART_MSI.V_AGG_INT_WG_DAY_ROC_1
/*
#----------------------------------------------------------------------------
# History:
#  1.0  18.07.2022    Oliver Haus         Initial DDL deployment - RWL aggregated values for Cockpits
#  1.1  21.07.2023    Chetana Patil       Added logic for RWL_WEIGHTED_VJ  
#----------------------------------------------------------------------------
*/
(
	INT_ID
  , CLIENT_ID
  , ITEMGROUP_INT_ID
  , DAT_FORMDATE
  ,	CURRENCY_ISO_CD
  ,	QTY_PIECE_STC_WH
  ,	RWL_NOMINATOR
  ,	RWL_WEIGHTED
  , RWL_WEIGHTED_VJ
) COMMENT='Aggregated View on International-WG-Level for RWL in Cockpits'
 AS
	  WITH VORJAHRESWERTE AS(
	  SELECT 
	   WH.INT_ID
	 , SUB.ITEMGROUP_INT_ID
	 , V02.CAL_DT AS DAT_FORMDATE
	 , ROC.CURRENCY_ISO_CD
	 , SUM(ROC.RWL_NOMINATOR)/SUM(ROC.QTY_PIECE_EP_WH) AS RWL_WEIGHTED_VJ
	   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC_1 ROC
	   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH
	   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
	   JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_1 ITM 
	   ON ROC.CLIENT_ID = ITM.CLIENT_ID AND ROC.ITEM_ID = ITM.ITEM_ID
	   JOIN	P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_1	SUB
	   ON ITM.SUBITEMGROUP_ID = SUB.SUBITEMGROUP_ID
	   JOIN  P_LEW_MART_LEAD_AC.V_DIM_CAL_DAY_1 V02
	   ON ROC.DAT_FORMDATE = V02.CAL_DT_PREV_1Y 
	   WHERE FLAGS_COMBINED = '0000'
	   AND WH.ASPECT_ID = 1
	   AND SUB.ITEMGROUP_INT_ID IN (40,50,60) -- ONLY TIKO, KUEHLUNG & FOODTS
	   GROUP BY 
	   WH.INT_ID
	 , SUB.ITEMGROUP_INT_ID
	 , V02.CAL_DT
	 , ROC.CURRENCY_ISO_CD)
	 
	 , BASE AS(
	  SELECT 
	   WH.INT_ID
	 , SUB.ITEMGROUP_INT_ID
	 , DAT_FORMDATE
	 , CURRENCY_ISO_CD
	 , SUM(QTY_PIECE_EP_WH) AS QTY_PIECE_STC_WH
	 , SUM(RWL_NOMINATOR) AS RWL_NOMINATOR
	 , SUM(RWL_NOMINATOR)/SUM(QTY_PIECE_EP_WH) AS RWL_WEIGHTED
	   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC_1 ROC
	   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH
	   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
	   JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_1 ITM 
	   ON ROC.CLIENT_ID = ITM.CLIENT_ID AND ROC.ITEM_ID = ITM.ITEM_ID
	   JOIN	P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_1	SUB
	   ON ITM.SUBITEMGROUP_ID = SUB.SUBITEMGROUP_ID
	   WHERE FLAGS_COMBINED = '0000'
	   AND WH.ASPECT_ID = 1
	   AND SUB.ITEMGROUP_INT_ID IN (40,50,60) -- ONLY TIKO, KUEHLUNG & FOODTS
	   GROUP BY 
	   WH.INT_ID
	 , SUB.ITEMGROUP_INT_ID
	 , DAT_FORMDATE
	 , CURRENCY_ISO_CD)
 
	 SELECT   
	 COALESCE(BASE.INT_ID,VJ.INT_ID ) AS INT_ID
	 , WH.CLIENT_ID
	 , COALESCE(BASE.ITEMGROUP_INT_ID, VJ.ITEMGROUP_INT_ID) AS ITEMGROUP_INT_ID
	 , COALESCE(BASE.DAT_FORMDATE, VJ.DAT_FORMDATE) AS DAT_FORMDATE
	 , COALESCE(BASE.CURRENCY_ISO_CD, VJ.CURRENCY_ISO_CD) AS CURRENCY_ISO_CD
	 , BASE.QTY_PIECE_STC_WH -- ON LEVEL INT_WG
	 , BASE.RWL_NOMINATOR -- ON LEVEL INT_WG
	 , BASE.RWL_WEIGHTED -- ON LEVEL INT_WG 
	 , VJ.RWL_WEIGHTED_VJ -- ON LEVEL INT
	FROM BASE 
	FULL OUTER JOIN VORJAHRESWERTE VJ
	ON  BASE.INT_ID = VJ.INT_ID
	AND BASE.CURRENCY_ISO_CD = VJ.CURRENCY_ISO_CD
	AND BASE.DAT_FORMDATE = VJ.DAT_FORMDATE
	AND BASE.ITEMGROUP_INT_ID = VJ.ITEMGROUP_INT_ID
	JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH 
	ON BASE.INT_ID = WH.INT_ID
; 
