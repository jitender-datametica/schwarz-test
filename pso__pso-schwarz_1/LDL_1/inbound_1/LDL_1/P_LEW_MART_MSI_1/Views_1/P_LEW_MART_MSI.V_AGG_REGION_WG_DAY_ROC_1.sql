CREATE OR REPLACE VIEW P_LEW_MART_MSI.V_AGG_REGION_WG_DAY_ROC_1
/*
#----------------------------------------------------------------------------
# History:
#  1.0  18.07.2022    Oliver Haus         Initial DDL deployment - RWL aggregated values for Cockpits
#  1.1  10.07.2023    Chetana Patil       Added logic for RWL_WEIGHTED_VJ  
#----------------------------------------------------------------------------
*/
(
     CLIENT_ID
   , GL_REGION_ID
   , ITEMGROUP_INT_ID
   , DAT_FORMDATE
   , CURRENCY_ISO_CD
   , QTY_PIECE_STC_WH
   , RWL_NOMINATOR
   , RWL_WEIGHTED
   , RWL_WEIGHTED_VJ
) COMMENT='Aggregated View ON REGION_1-WG-Level for RWL in Cockpits'
 AS
 WITH MAINFACTTABLE AS 
  (
  SELECT 
   COALESCE(THISYEAR.CLIENT_ID,VJ.CLIENT_ID) AS CLIENT_ID
 , COALESCE(THISYEAR.GL_REGION_ID, VJ.GL_REGION_ID) AS GL_REGION_ID
 , COALESCE(THISYEAR.ITEMGROUP_INT_ID, VJ.ITEMGROUP_INT_ID) AS ITEMGROUP_INT_ID
 , COALESCE(THISYEAR.DAT_FORMDATE, VJ.DAT_FORMDATE) AS DAT_FORMDATE
 , COALESCE(THISYEAR.CURRENCY_ISO_CD, VJ.CURRENCY_ISO_CD) AS CURRENCY_ISO_CD
 , SUM(THISYEAR.QTY_PIECE_STC_WH) AS QTY_PIECE_STC_WH
 , SUM(THISYEAR.RWL_NOMINATOR) AS RWL_NOMINATOR
 , SUM(THISYEAR.RWL_WEIGHTED) AS RWL_WEIGHTED
 , SUM(VJ.RWL_WEIGHTED_VJ) AS RWL_WEIGHTED_VJ
  FROM 
		  ( SELECT 
		   ROC.CLIENT_ID
		 , WH.GL_REGION_ID
		 , SUB.ITEMGROUP_INT_ID
		 , ROC.DAT_FORMDATE
		 , ROC.CURRENCY_ISO_CD
		 , SUM(ROC.QTY_PIECE_EP_WH) AS QTY_PIECE_STC_WH
		 , SUM(ROC.RWL_NOMINATOR) AS RWL_NOMINATOR
		 , SUM(ROC.RWL_NOMINATOR) / SUM(ROC.QTY_PIECE_EP_WH) AS RWL_WEIGHTED
		   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC_1 ROC
		   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH
		   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
		   JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_1 ITM 
           ON ROC.CLIENT_ID = ITM.CLIENT_ID AND ROC.ITEM_ID = ITM.ITEM_ID
		   JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_1    SUB
		   ON ITM.SUBITEMGROUP_ID = SUB.SUBITEMGROUP_ID
		   WHERE FLAGS_COMBINED = '0000'
		   AND WH.ASPECT_ID = 1
		   AND SUB.ITEMGROUP_INT_ID IN (40,50,60) -- ONLY TIKO, KUEHLUNG & FOODTS
		   GROUP BY
		   ROC.CLIENT_ID  
		 , WH.GL_REGION_ID
		 , SUB.ITEMGROUP_INT_ID
		 , ROC.DAT_FORMDATE
		 , ROC.CURRENCY_ISO_CD
		  ) THISYEAR
		  
		  FULL OUTER JOIN 
 
		  ( SELECT
		   ROC.CLIENT_ID
		 , GL_REGION_ID
		 , SUB.ITEMGROUP_INT_ID
		 , WEEK_BER.CAL_DT AS DAT_FORMDATE
		 , CURRENCY_ISO_CD
		 , SUM(RWL_NOMINATOR) / SUM(QTY_PIECE_EP_WH) AS RWL_WEIGHTED_VJ
		   FROM P_LEW_MART_MSI.V_ITM_ITEM_WH_DAY_ROC_1 ROC
		   JOIN P_LEW_MART_MSI_AC.V_ORG_WH_MERGE_1 WH
		   ON ROC.CLIENT_ID = WH.CLIENT_ID AND ROC.WH_ID = WH.WH_ID
		   JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_1 ITM 
           ON ROC.CLIENT_ID = ITM.CLIENT_ID AND ROC.ITEM_ID = ITM.ITEM_ID
		   JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_1    SUB
           ON ITM.SUBITEMGROUP_ID = SUB.SUBITEMGROUP_ID
           JOIN  P_LEW_MART_LEAD_AC.V_DIM_CAL_DAY_1 WEEK_BER
		   ON ROC.DAT_FORMDATE = WEEK_BER.CAL_DT_PREV_1Y
		   WHERE FLAGS_COMBINED = '0000'
		   AND WH.ASPECT_ID = 1
		   AND SUB.ITEMGROUP_INT_ID IN (40,50,60) -- ONLY TIKO, KUEHLUNG & FOODTS
		   GROUP BY
		   ROC.CLIENT_ID
		 , GL_REGION_ID
		 , SUB.ITEMGROUP_INT_ID
		 , WEEK_BER.CAL_DT
		 , CURRENCY_ISO_CD
		  ) VJ
    ON THISYEAR.CLIENT_ID = VJ.CLIENT_ID
	AND THISYEAR.DAT_FORMDATE = VJ.DAT_FORMDATE
    AND THISYEAR.CURRENCY_ISO_CD = VJ.CURRENCY_ISO_CD
	AND THISYEAR.GL_REGION_ID = VJ.GL_REGION_ID
	AND THISYEAR.ITEMGROUP_INT_ID = VJ.ITEMGROUP_INT_ID
    
    GROUP BY 
     COALESCE(THISYEAR.CLIENT_ID, VJ.CLIENT_ID ) 
   , COALESCE(THISYEAR.GL_REGION_ID, VJ.GL_REGION_ID)
   , COALESCE(THISYEAR.ITEMGROUP_INT_ID, VJ.ITEMGROUP_INT_ID)
   , COALESCE(THISYEAR.DAT_FORMDATE, VJ.DAT_FORMDATE) 
   , COALESCE(THISYEAR.CURRENCY_ISO_CD, VJ.CURRENCY_ISO_CD) 
 )
 
 SELECT 
		 FCT.CLIENT_ID
	   , FCT.GL_REGION_ID
	   , FCT.ITEMGROUP_INT_ID
	   , FCT.DAT_FORMDATE
	   , FCT.CURRENCY_ISO_CD
	   , FCT.QTY_PIECE_STC_WH AS QTY_PIECE_STC_WH
	   , FCT.RWL_NOMINATOR AS RWL_NOMINATOR
	   , FCT.RWL_WEIGHTED AS RWL_WEIGHTED
	   , FCT.RWL_WEIGHTED_VJ AS RWL_WEIGHTED_VJ
	   FROM MAINFACTTABLE FCT
;	   
