CREATE Or REPLACE VIEW FE_MSTR_AUTODISPO.V_HIVE_FK_FORECAST_QUALITY_REDUCED_1(
	COUNTRY_1
	, TS
	, DATE
	, ITEMNO
	, ITEMDESC
	, SUBGROUPNO
	, FAMILYNO
	, STORE
	, WH
	, PROMOTION
	, HOUR_LAST_SALE
	, AMOUNT
	, V_MODEL
	, PFC
	, D_PFC
	, D_MIN
	, D_PLUS
	, PFC_BEFORE_TREND
	, PFC_MODEL
	, PFC_DAY_BEFORE
	, PFC_TWO_DAY_BEFORE
	, SPECIAL_PLACEMENT
	, IS_TREND
	, ARCHTS
	, IS_AMOUNT_ZERO
	, FORECAST_DAY
	, PFC_RARE_SALES
) AS
    /* Version: 1.1
	** Author:	Dominik Pfarr
	** Date:    2024-03-12
	** Change:  adding pfc_rare_sales for BIAS reporting
	*/
SELECT COUNTRY_1
	,TS
	,date_::DATE AS DATE
	,ITEMNO
	,ITEMDESC
	,SUBGROUPNO
	,FAMILYNO
	,STORE
	,WH
	,PROMOTION
	,TO_TIME(SALE_LAST_TIME_INT) AS hour_last_sale
	,AMOUNT
	,V_MODEL
	,PFC
	,D_PFC
	,D_MIN
	,D_PLUS
	,PFC_BEFORE_TREND
	,PFC_MODEL
	,PFC_DAY_BEFORE
	,PFC_TWO_DAY_BEFORE
	,SPECIAL_PLACEMENT
	,IS_TREND
	,ARCHTS
	,CASE WHEN AMOUNT = 0 THEN 1 ELSE 0 END AS IS_AMOUNT_ZERO
	,FORECAST_DAY
    ,PFC_RARE_SALES
FROM "CORE"."T_HIVE_V_FORECAST_QUALITY_REDUCED_1"
WHERE FORECAST_DAY = 1
;