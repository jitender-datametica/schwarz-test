CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_INTERNAL_FORECAST_RESULTS_1(
	COUNTRY_1
	, WH
	, STORE
	, ITEMNO
	, FORECAST_DATE
	, V_MODEL
	, DATE
	, FORECAST_DAY
	, PFC
	, PROMOTION
	, SOURCE_FLAG
	, SOURCE_EXTRACTION_TMSP
	, SNFLK_INSERT_TMSP
	, SNFLK_UPDATE_TMSP
) AS

/* Version: 1.0
	** Author:	Dominik Pfarr
	** Date: 	2024-02-16
	** Changes:	initial version for Internal Forecast WH Level simplification
	*/
SELECT COUNTRY_1
	,WH
	,STORE
	,ITEMNO
	,FORECAST_DATE
	,V_MODEL
	,DATE_::DATE DATE
	,CASE 
		WHEN DATE_::DATE >= CURRENT_DATE ()
			THEN CURRENT_DATE - forecast_date::DATE
		ELSE FORECAST_DAY
		END AS FORECAST_DAY
	,PFC
	,PROMOTION
	,SOURCE_FLAG
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
FROM CORE.T_INTERNAL_FORECAST_RESULTS_1;