	** Date: 	2023-05-24
	** Changes:	Initial version
	*/
SELECT DIC_AREA_ID
	,DIC_ACTIVE
	,MOD_DATE
	,DIC_AREA_NR
	,DIC_AREA_WH
	,COUNTRY_1
	,DIC_AREA_NAME
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_DIC_AREA_NEW_1

UNION ALL

SELECT da.DIC_AREA_ID
	,da.DIC_ACTIVE
	,da.MOD_DATE
	,da.DIC_AREA_NR
	,w.WARE_ID AS DIC_AREA_WH
	,da.COUNTRY_1
	,da.DIC_AREA_NAME
	,da.SOURCE_EXTRACTION_TMSP
	,da.SNFLK_INSERT_TMSP
	,da.SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_DIC_AREA_1 da
JOIN CORE.T_ORACLE_V_DIM_WAREHOUSE_1 w ON da.country_1 = w.country_1
WHERE da.country_1 NOT IN (
		SELECT DISTINCT country_1
		FROM CORE.T_ORACLE_V_DIC_AREA_NEW_1
		);