CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_FK_ADL_TREND_TRANSFORMED_1 (
	DATE
	,COUNTRY_1
	,WH
	,ITEM_PACKAGECAPACITY
	,TREND_ID
	,TREND_TYPE
	,ACTIVE_FG
	,TREND_VALUE
	,TREND_START_DATE
	,TREND_END_DATE
	,MOD_DATE
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
	,ITEM_NR
	
	) COMMENT = 'Version: 1.0 - Initial version
	 Version: 1.1 - Adjust wh column name' AS 
	(
	SELECT c.cal_dt DATE
	, t.COUNTRY_1
	, t.WH_NR AS WH
	, t.ITEM_PACKAGECAPACITY
	, t.TREND_ID
	, t.TREND_TYPE
	, t.ACTIVE_FG
	, t.TREND_VALUE
	, t.TREND_START_DATE
	, t.TREND_END_DATE
	, t.MOD_DATE
	, t.SOURCE_EXTRACTION_TMSP
	, t.SNFLK_INSERT_TMSP
	, t.SNFLK_UPDATE_TMSP
	, t.ITEM_NR
    FROM 
	CORE.T_ORACLE_V_FK_TREND_ADL_1 t 
	INNER JOIN FE_MSTR_AUTODISPO.V_DIM_CALENDAR_DATE_1 C
	ON c.cal_dt BETWEEN trend_start_date AND COALESCE(trend_end_date, CURRENT_DATE + 28) 
	WHERE t.active_fg = 1
	);