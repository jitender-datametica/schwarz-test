CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_FK_OPTIMIZATION_1(
	COUNTRY_1
	, DATE
	, OPT_STORECALCULATION_ID
	, OPT_ORDER_TYPE
	, ITEM_NR
	, STORE
	, OPT_TYPE_NAME
	, OPT_BEFORE
	, OPT_AFTER
	, OPT_UNIT_ID
	, CUTBACK
	, MOD_DATE
	, DELETED
	, SOURCE_EXTRACTION_TMSP
	, SNFLK_INSERT_TMSP
	, SNFLK_UPDATE_TMSP
) AS
    /* Version:   1.1
    ** Author:    Dominik Pfarr
    ** Date:      2022-11-10
    ** Changes:   adding Cutback, opt_unit_id And filter on deleted = 0
    */
SELECT COUNTRY_1
	,DATEADD(DAY, opt_time_id - 365.25 * (4712) - 2, '0000-01-01')::DATE DATE
	,OPT_STORECALCULATION_ID
	,OPT_ORDER_TYPE
	,OPT_ITEM_NR ITEM_NR
	,OPT_STORE_NR STORE
	,OPT_TYPE_NAME
	,OPT_BEFORE
	,OPT_AFTER
    ,OPT_UNIT_ID
	,CASE WHEN opt_type_name = 'Warehouse Stock' THEN opt_before - opt_after END Cutback
	,MOD_DATE
    ,DELETED
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
FROM CORE.T_ORACLE_V_FK_OPTIMIZATION_1
WHERE DELETED =0;