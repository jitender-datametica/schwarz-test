	COUNTRY_1
	,WH
	,STORECALCULATION_ID
	,ARGUMENTS
	,USER
	,DATE
	,AUTOMATIC_ENTRY
	,MOD_DATE
	,SOURCE_EXTRACTION_TMSP
	,SNFLK_INSERT_TMSP
	,SNFLK_UPDATE_TMSP
	) AS

    /* Version: 1.1
