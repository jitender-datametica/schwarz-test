CREATE OR REPLACE PROCEDURE FE_MSTR_BCBI.P_DELETE_WAWI_MANUAL_EXTRACTION_ENTRY
(
P_CLIENT_ID NUMBER(38,0)
,P_SYSTEM_KEY NUMBER(38,0)
,P_WH_ID NUMBER(38,0)
,P_DAYEND_DATE DATE
,P_ENTRY_FROM VARCHAR(255)
,P_REASON VARCHAR(255)
,P_CREATE_TIMESTAMP TIMESTAMP_NTZ(9)
)
RETURNS TEXT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
    DELETE FROM FE_MSTR_BCBI.TS_WAWI_MANUAL_EXTRACTION_1
    WHERE   CLIENT_ID       = :P_CLIENT_ID
    AND     SYSTEM_KEY      = :P_SYSTEM_KEY
    AND     WH_ID           = :P_WH_ID
    AND     DAYEND_DATE     = :P_DAYEND_DATE
    AND     ENTRY_FROM      = :P_ENTRY_FROM
    AND     REASON          = :P_REASON
    AND     TO_VARCHAR(create_timestamp, 'YYYY-MM_1-DD HH24:MI:SS')   = DATE_TRUNC('SECONDS', :P_CREATE_TIMESTAMP)
    ;
COMMIT;
END;
$$
;