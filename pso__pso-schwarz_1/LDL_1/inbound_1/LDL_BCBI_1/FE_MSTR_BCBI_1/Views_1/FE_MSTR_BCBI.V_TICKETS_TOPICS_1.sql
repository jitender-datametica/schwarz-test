CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_TICKETS_TOPICS_1 AS 
SELECT ID
    ,subject
    ,upload_date
    ,CASE
        WHEN subject LIKE ANY ('%DES%') THEN 'DES'
        WHEN subject LIKE ANY ('%rite off%','%bschreibung%','%bschriften%','%Write Off%') THEN 'Abschriften_1'
        WHEN subject LIKE ANY ('%Werbe%','%werbe%','%Advert%','%advert%' ) THEN 'Werbeartikel/-termine'
        WHEN subject LIKE ANY ('%ieferant%') THEN 'Lieferant'
        WHEN subject LIKE ANY ('%torelist%') THEN 'MD-Storelist'
        WHEN subject LIKE ANY ('%langsam%', '%wird abgebrochen%','%slow%') THEN 'Performance'
        WHEN subject LIKE ANY ('%utzungsgrad%') THEN 'PbV Nutzungsgrad'
        WHEN subject LIKE ANY ('%bersetzung%','%ranslation%','%prache%', '%anguage%') THEN 'Sprache/Übersetzung'
        WHEN subject LIKE ANY ('%nventur%','%nventory%','%nventories%') THEN 'Inventur_1'
        WHEN subject LIKE ANY ('%tückleistung%','%tuckleistung%') THEN 'Stückleistung'
        WHEN subject LIKE ANY ('%STD%','%rtikelbestände%', '%Bestand%', '%Bestände%','%Stock%', '%stock%','%bestände%') THEN 'STD Itemstock'
        WHEN subject LIKE ANY ('%alettenleistung%') THEN 'Palettenleistung'
        WHEN subject LIKE ANY ('%WE%','%We-Kalk%' ,'%We Kalk%', '%WE_Kalk%', '%WE-Kalk%', '%WE Kalk%', '%WE-kalk%', '%WE kalk%', '%WE_kalk%', '%We kalk%','%We-kalk%','%We Kalkulation%','%We-Kalkulation%' ) THEN 'WE-Kalkulation'
        WHEN subject LIKE ANY ('%Netto%', '%netto%') THEN 'Nettoleistung'
        WHEN subject LIKE ANY ('%Umsatz%', '%umsatz%','%msätze%','%urnover%') THEN 'Umsatz'
        WHEN subject LIKE ANY ('%Endanwender%','%freischalten%','%userid%','%erechtigung%','%uthorization%','%ccount%','%enutzerantrag%','%ammelantrag%' ,'%errechtung%','%in Mis anlegen%','%MIS User%','%MIS user%','%MIS Role%','%itabeiteraustritt%','%eurer Mitarbeiter%','%nmeldung%', '%ugriff%', '%ugangsdaten%', '%ugang%','%right%', '%login%','%Login%', '%access%','%reischaltung%', '%grant%','%asswor%','%reset%', '%Reset%','%Access%','%Grant%', '%enehmigung%', '%account_1 for%') THEN 'Zugriff/Berechtigung' 
        WHEN subject LIKE ANY ('%PZE4%', '%GPS%', '%PTM%','%rbeitszeiten%','%hours%','%Hours%','%eiterfassung%','%Ptm%','%ptm%','%Gps%','%gps%','%tunden%') THEN 'Zeiterfassung'
        WHEN subject LIKE ANY ('%utoD%', '%utod%', '%uto D%', '%uto d%' ) THEN 'AutoDispo'
        WHEN subject LIKE ANY ('%WFM%', '%wfm%') THEN 'WFM'
        WHEN subject LIKE ANY ('%mlagerung%', '%mzug%', '%mzüge%', '%ufschaltung%','%amensänderung%','%mgliederung%','%ew WH%','%ew warehouse%','%eues WH%', '%eue Gesellschaft%','%eue GES%','%oft opening%','%oftopening%','%andesaufschaltung%','%ountry initialization%','%oft Opening%') THEN 'Aufschaltungen/Filialumzüge'
        WHEN subject LIKE ANY ('%eferenzdaten%', '%Refdata%','%refdata%','%Ref data%','%ref data%','%Ref-data%','%ref-data%','%eferencedata%') THEN 'Referenzdaten'
        WHEN subject LIKE ANY ('%Rabatt%', '%discount%','%Discount%','%abverkauf%','%Abverkauf%', '%Abverkäufe%') THEN 'Rabatt'
        WHEN subject LIKE ANY ('%Rückgabe%','%ückgabe%','%Rücksende%') THEN 'Rückgabe'
        WHEN subject LIKE ANY ('%EJR%', '%Ejr%', '%ejr%','%eJournale%', '%eceipt%','%eciept%','%Bondaten%','%bondaten%','%ZKP%','%Zkp%','%zkp%') THEN 'EJR'
        WHEN subject LIKE ANY ('%Annon%','%annon%', '%ANNON%', '%Anon%') THEN 'ANNON'
        WHEN subject LIKE ANY ('%IMS%','%Immo%') THEN 'IMS'
        WHEN subject LIKE ANY ('%PEP%') THEN 'PEP'
        WHEN subject LIKE ANY ('%LISA%', '%Lisa%','%lisa%','%LiSa%','%LiSA%') THEN 'LISA'
        WHEN subject LIKE ANY ('%ockpit%', '%ocpit%') THEN 'Cockpit'
        WHEN subject LIKE ANY ('%ategory Management%') THEN 'Category Management'
        WHEN subject LIKE ANY ('%Rolle%','%role%') THEN 'Rollen'
        WHEN subject LIKE ANY ('%SIAM%','%IDM%' ) THEN 'SIAM/IDM'
        WHEN subject LIKE ANY ('%Kolli%','%Koli%','%kolli%','%koli%','%KOLLI%','%KOLI%' ) THEN 'Kolli'
        WHEN subject LIKE ANY ('%Azure%','%Devops%', '%Dev ops%', '%DevOps%','%Dev Ops%' ,'%cloud%', '%Cloud%','%CLOUD%')   THEN 'Cloud'
        WHEN subject LIKE ANY ('%AfO%', '%AFO%', '%Afo%') THEN 'AfO'
        WHEN subject LIKE ANY ('%Oracle%') THEN 'Oracle'
        WHEN subject LIKE ANY ('%irewall%', '%omain%') THEN 'Firewall/Domain'
        WHEN subject LIKE ANY ('%iPad%', '%Ipad%','%ipad%','%IPAD%') THEN 'iPad'
        WHEN subject LIKE ANY ('%idlPlus%','%Lidl Plus%','%idlplus%','%Lidl plus%', '%Lidl+%') THEN 'LidlPlus'
        WHEN subject LIKE ANY ('%LEAD%', '%Lead%', '%lead%') THEN 'MIS Lead'
        WHEN subject LIKE ANY ('%MSTR%','%MicroStrategy%', '%Microstrategy%','%Mstr%', '%MICRO%','%Cubing%') THEN 'MicroStrategy'
        WHEN subject LIKE ANY ('%GL Regio%', '%GL-Regio%') THEN 'GL-Regio'
        WHEN subject LIKE ANY ('%binitio%', '%b initio%','%binito%', '%b inito%', '%job%','%Job%','%bInitio%') THEN 'Ab Initio'
        WHEN subject LIKE ANY ('%DWH%','%snow%','%Snow%','%Teradata%','%t^_%', '%abelle%','%column%', '%table%', '%uery%','%ata export%','%ata import%','%Data Store%','%Data store%','%data store%') ESCAPE '^' THEN 'Snowflake'
        WHEN subject LIKE ANY ('%WAWI%','%Wawi%','%WaWi%','%wawi%') THEN 'WAWI'
        WHEN subject LIKE ANY ('%ilial%', '%Store%','%Stores%', '%store%') THEN 'Filiale'
        WHEN subject LIKE ANY ('%rtikel%') THEN 'Artikel_1'
        WHEN subject LIKE ANY ('%eport documentation%','%Report%','%report%','%dossier%','%Dossier%','%Bericht%','%INT-%') THEN 'Bericht'
        WHEN subject LIKE ANY ('%SAP%') THEN 'SAP'
        WHEN subject LIKE ANY ('%MIS%','%Mis%') THEN 'MIS'

        ELSE 'Sonstige'
    END AS topic
    ,CASE 
       WHEN topic IN ('Abschriften_1', 'Werbeartikel/-termine','PbV Nutzungsgrad','Inventur_1','Stückleistung','Lieferant','STD Itemstock','Palettenleistung'
                      ,'WE-Kalkulation','Nettoleistung','Umsatz','WFM','Zeiterfassung'
                      ,'Rabatt','Rückgabe','Kolli') THEN 'Kennzahlen'
       WHEN topic IN ('Rollen','Zugriff/Berechtigung','SIAM/IDM') THEN 'User Berechtigung'
       WHEN topic IN ('Ab Initio','MIS','Snowflake','MicroStrategy','Annon','WAWI','Oracle','SAP','IMS','LISA','PEP','DES') THEN 'System'
    END AS category
FROM FE_MSTR_BCBI.V_TICKETS_DAILY_1;