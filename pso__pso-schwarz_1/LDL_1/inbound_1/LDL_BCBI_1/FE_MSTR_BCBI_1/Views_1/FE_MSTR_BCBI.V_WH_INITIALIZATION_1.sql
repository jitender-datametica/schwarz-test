CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_WH_INITIALIZATION_1 AS 
SELECT
    WHIR.COUNTRY_NAME
    ,COUNTRY.CLIENT_ID
    ,COUNTRY.COUNTRY_ISO AS COUNTRY_NAME_SHORT
    ,CAL_DAY.CY AS YEAR
    ,CAL_DAY.CY_MONTH AS MONTH_ID
    ,CAL_DAY.MONTH_OF_YEAR AS MONTH
    ,CAL_DAY.MONTH_OF_YEAR_NAME AS MONTH_NAME
    ,CAL_DAY.WEEK_OF_YEAR AS WEEK
    ,CAL_WEEK.CY_WEEK_SHORT_NAME AS WEEK_NAME
    ,CAL_DAY.CY_WEEK AS WEEK_ID
    ,CAL_WEEK.CY_WEEK_NAME AS WEEK_NAME_YEAR
    ,WHIR.WH_NAME
    ,WHIR.WH_NAME_SHORT
    ,WHIR.WH_ID
    ,WHIR.OBJECT_TYPE
    ,CASE
        WHEN WHIR.OBJECT_TYPE = 'B' THEN 'BGES'
        WHEN WHIR.OBJECT_TYPE = 'V' THEN 'VGES'
        WHEN WHIR.OBJECT_TYPE = 'BV' THEN 'BGES=VGES'
        WHEN WHIR.OBJECT_TYPE = 'BnotV' THEN 'BGES!=VGES'
    END AS object_type_desc
    ,WHIR.STORES_ASSIGNED_FG
    ,CASE
        WHEN (
            WHIR.OBJECT_TYPE = 'BV'
            OR WHIR.OBJECT_TYPE = 'BnotV'
            )
            AND WHIR.STORES_ASSIGNED_FG = 1 
        THEN 'WH_Master, WH_Move, STD_Move, STD_itemstock, PTM_Master, PTM_Move/GPS, WAMAS, DISPO, TTP, MMO_Master, MMO_Move, EJR, TXJ'
        WHEN (
            WHIR.OBJECT_TYPE = 'BV'
            OR WHIR.OBJECT_TYPE = 'BnotV'
            )
            AND WHIR.STORES_ASSIGNED_FG = 0 
        THEN 'WH_Master, WH_Move, WAMAS, DISPO_Orders, TTP, (MMO_Master, MMO_Move)'
        WHEN WHIR.OBJECT_TYPE = 'B'
            AND WHIR.STORES_ASSIGNED_FG = 0 
        THEN 'WH_Master, WH_Move, evtl. STD_itemstock'
        WHEN WHIR.OBJECT_TYPE = 'V' 
        THEN 'Keine Schnittstellen'
    END AS INTERFACES
    ,WHIR.WH_TYPE
    ,CASE
        WHEN CONTAINS(WHIR.WH_TYPE, '(NF)') THEN 1
        ELSE 0
    END AS NON_FOOD
    ,CASE
        WHEN CONTAINS(WHIR.WH_TYPE, '(F)') THEN 1
        ELSE 0
    END AS FOOD
    ,CASE
        WHEN CONTAINS(WHIR.WH_TYPE, '(BP)') THEN 1
        ELSE 0
    END AS BlUMEN_PFLANZEN
    ,CASE
        WHEN CONTAINS(WHIR.WH_TYPE, '(TK)') THEN 1
        ELSE 0
    END AS TIKO
    ,CASE
        WHEN CONTAINS(WHIR.WH_TYPE, '(AL)') THEN 1
        ELSE 0
    END AS AUSSENLAGER
    ,CASE
        WHEN CONTAINS(WHIR.WH_TYPE, '(OL)') THEN 1
        ELSE 0
    END AS ONLINE_LAGER
    ,WHIR.BGES_ID
    ,WHIR.VGES_FG
    ,WHIR.VGES_ID
    ,WHIR.OPENING_DATE
    ,WHIR.GOODS_RECEIPT_DATE
    ,WHIR.FIRST_PROD_DATA_DATE
    ,WHIR.GOODS_ISSUE_DATE
    ,WHIR.STORES_ASSIGNED_DATE
    ,WHIR.STORES_RELOCATED_FROM
    ,WHIR.WORKING_HOURS_TRANSMISSION
    ,WHIR.WH_RELOCATION_FG
    ,STATUS_.STATUS_ID
    ,STATUS_.STATUS_
    ,STATUS_.Aufgabe AS STATUS_AUFGABE
    ,STATUS_.Anteil AS STATUS_ANTEIL
    ,CASE
        WHEN WHIR.object_type = 'V'
        OR WHIR.object_type = 'BnotV' THEN '1.3x Management Cockpit'
        WHEN WHIR.object_type = 'BV' THEN '1.3 Management Cockpit'
        ELSE 'Keine Cockpit-Anzeige'
    END AS COCKPIT_DISPLAY
    ,WHIR.COMMENTS
    ,WHIR.UPLOAD_DATE
FROM
    FE_MSTR_BCBI.T_WH_INITIALIZATION_1 AS WHIR
    INNER JOIN FE_MSTR_BCBI.T_DIM_CAL_DAY_1 AS CAL_DAY ON WHIR.opening_date = CAL_DAY.cal_dt
    INNER JOIN FE_MSTR_BCBI.T_DIM_CAL_WEEK_1 AS CAL_WEEK ON CAL_DAY.cy_week = CAL_WEEK.cy_week
    INNER JOIN FE_MSTR_BCBI.T_COUNTRY_1 AS COUNTRY_1 ON WHIR.country_name = country.country_name
    LEFT JOIN FE_MSTR_BCBI.T_WH_INIT_STATUS_1 AS STATUS_ ON WHIR.status_id = STATUS_.status_id;