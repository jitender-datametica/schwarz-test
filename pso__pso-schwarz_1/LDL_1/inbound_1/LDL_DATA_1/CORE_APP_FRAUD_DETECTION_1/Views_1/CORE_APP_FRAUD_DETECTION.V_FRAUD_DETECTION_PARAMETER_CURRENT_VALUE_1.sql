CREATE OR REPLACE VIEW CORE_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_PARAMETER_CURRENT_VALUE_1(
	PARAM_ID
	,SCENARIO_ID
    ,SCENARIO_TYPE_CD
	,PARAM_NAME
	,COUNTRY_ORG_CD
	,PARAM_DEFAULT_VAL_QTY
	,PARAM_COUNTRY_VAL_QTY
	,PARAM_VAL_QTY
	,PARAM_LAST_UPDATE_TMSP
	,IS_SCENARIO_ENABLED_IN_COUNTRY_FG
) AS
	SELECT 
        P.PARAM_ID
        ,S.SCENARIO_ID
        ,SCENARIO_TYPE_CD
        ,P.PARAM_NAME
        ,CTR.COUNTRY_ORG_CD
        ,P.PARAM_DEFAULT_VAL_QTY
        ,PV.PARAM_VAL_QTY                               AS PARAM_COUNTRY_VAL_QTY
        ,NVL(PV.PARAM_VAL_QTY, P.PARAM_DEFAULT_VAL_QTY) AS PARAM_VAL_QTY
		,GREATEST_IGNORE_NULLS(P.DWH_UPDATED_TMSP, PV.DWH_UPDATED_TMSP) AS PARAM_LAST_UPDATE_TMSP
		
		-- IF ALL COUNTRY_1 VALUES FOR PARAMETERS FOR GIVEN SCENARIO ARE SET THEN THE SCENARIO IS ENABLED
		-- IF AT LEAST ONE PARAMATER FOR GIVEN COUNTRY_1 AND SCENARIO HAS COUNTRY_1-SPECIFIC VALUE NULL THEN THE SCENARIO IS DISABLED
		,CASE
				-- SCENARIO HAS 0 PARAMETERS ASSOCIATED WITH IT. SO IT IS ENABLED
                WHEN P.SCENARIO_ID IS NULL THEN TRUE 

                -- SCENARIO HAS SOME PARAMS ASSCOIATED WITH IT, AND ALL OF THEM HAVE NON-NULL VALUES - THEN IT IS ENABLED
                WHEN COUNT(*) OVER (PARTITION BY P.SCENARIO_ID,CTR.COUNTRY_ORG_CD) = COUNT(PARAM_COUNTRY_VAL_QTY) OVER (PARTITION BY P.SCENARIO_ID,CTR.COUNTRY_ORG_CD) THEN TRUE
				ELSE FALSE
			END IS_SCENARIO_ENABLED_IN_COUNTRY_FG
    FROM CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 S
        JOIN CORE_REL.T_INTERNAL_ORGANIZATION_1 CTR ON 1=1 -- MULTIPLY COUNTRIES BY SCENARIOS
        
        LEFT JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_PARAMETER_1 P
                ON S.SCENARIO_ID = P.SCENARIO_ID
        
        
		LEFT JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_PARAMETER_VALUE_1 PV
            ON PV.COUNTRY_ORG_CD = CTR.COUNTRY_ORG_CD
            AND PV.PARAM_ID = P.PARAM_ID
            AND PV.PARAM_STATUS_CD = 'AP'
            AND PV.DWH_VALID_FG = TRUE
    WHERE 1=1 
        AND CTR.IS_COUNTRY_ORG_FG = TRUE
        AND CTR.DWH_VALID_FG = TRUE
;