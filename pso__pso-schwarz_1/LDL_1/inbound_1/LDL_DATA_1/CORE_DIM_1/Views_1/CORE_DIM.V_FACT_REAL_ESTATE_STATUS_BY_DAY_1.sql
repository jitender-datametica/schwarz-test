CREATE OR REPLACE VIEW CORE_DIM.V_FACT_REAL_ESTATE_STATUS_BY_DAY_1(
    REAL_ESTATE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE REAL ESTATE OBJECT.'
    ,STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR A STORE.'
    ,COUNTRY_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE RELATED COUNTRY_1 ORGANIZATION.'
    ,COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_1 FOR WHICH THIS COUNTRY_1 ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY_1 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)'
    ,REPORTING_COUNTRY_CD COMMENT 'THE CODE WHICH IDENTIFIES THE REPORTING COUNTRY_1 IN WHICH THE INTERNAL ORGANIZATION IS LOCATED.'
    ,CAL_DT COMMENT 'THE DAY REPRESENTED AS A CALENDAR_1 DATE OF THE FORM YYYY-MM_1-DD. YYYY IS THE CALENDAR_1 YEAR, MM_1 (BETWEEN 1 AND 12) THE CALENDAR_1 MONTH AND DD THE DAY OF THE CALENDAR_1 MONTH (BETWEEN 1 AND 31). '
    ,REAL_ESTATE_STATUS_CD COMMENT 'THE CODE IDENTIFYING THE LIFECYCLE STATUS_1 FOR REAL ESTATE OBJECTS. (THIS IS THE BUSINESS LIFECYCLE, SO IT MIGHT DIFFER FROM THE STATUS_1 CODE SHOWN IN THE SOURCE SYSTEM.)'
    ,OPEN_STORE_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING IS OPEN, OTHERWISE VALUE 0.'
    ,OPEN_STORE_PY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS OPEN ONE YEAR AGO, OTHERWISE VALUE 0.'
    ,OPEN_STORE_PPY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS OPEN TWO YEARS AGO, OTHERWISE VALUE 0.'
    ,CLOSED_STORE_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING IS CLOSED, OTHERWISE VALUE 0.'
    ,CLOSED_STORE_PY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS CLOSED ONE YEAR AGO, OTHERWISE VALUE 0.'
    ,CLOSED_STORE_PPY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS CLOSED TWO YEARS AGO, OTHERWISE VALUE 0.'
    ,STORE_UNDER_CONTRACT_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING IS UNDER CONTRACT, REGARDLESS IF THERE IS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,STORE_UNDER_CONTRACT_PY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS UNDER CONTRACT ONE YEAR AGO, REGARDLESS IF THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,STORE_UNDER_CONTRACT_PPY_CNT COMMENT 'VALUE 1 IF STORE/BUIDLING WAS UNDER CONTRACT TWO YEARS AGO, REGARDLESS IF THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,STORE_TO_BE_BUILT_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS UNDER CONTRACT AND THERE IS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,STORE_TO_BE_BUILT_PY_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING WAS UNDER CONTRACT ONE YEAR AGO AND THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,STORE_TO_BE_BUILT_PPY_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING WAS UNDER CONTRACT TWO YEARS AGO AND THERE WAS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,CANCEL_TERM_STORE_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS FINALLY SETTLED (TERMINATED) OR THERE IS NO INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,OWN_STORE_TO_BE_BUILT_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS UNDER CONTRACT, PRIVATELY OWNED AND THERE IS INTENTION TO COMPLETE IT, OTHERWISE VALUE 0.'
    ,OWN_OPEN_STORE_CNT COMMENT 'VALUE 1 IF THE STORE/BUIDLING IS OPEN AND PRIVATELY OWNED, OTHERWISE VALUE 0.'
    ,OWNERSHIP_TYPE_CD COMMENT 'THE CODE IDENTIFYING THE OWNERSHIP OF A REAL ESTATE OBJECT, I.E. IF IT HAS BEEN BOUGHT OR IF IT IS RENTED.'
    ,OPEN_DT COMMENT 'THE DATE WHEN THE INTERNAL ORGANIZATION HAS STARTED ITS REGULAR OPERATION. (THIS DATE MAY BE DIFFERENT FROM THE PLANNED OPENING DATE.)'
    ,CLOSE_DT COMMENT 'THE DATE WHEN THIS REAL ESTATE OBJECT WAS CLOSED.'
    ,DAYS_SINCE_OPENING COMMENT 'THE COUNT OF DAYS SINCE STORE OPENING.'
    ,DAYS_SINCE_CLOSURE COMMENT 'THE COUNT OF DAYS SINCE STORE CLOSURE.'
    ,SALES_AREA_MEAS COMMENT 'THE SPACE WHICH CAN BE USED FOR SALES_1, IN THE UNIT_1 INDICATED BY THE UNIT_1 OF MEASURE CODE (E.G. M2).'
    ,TOTAL_SUBLET_AREA_MEAS COMMENT 'THE TOTAL SPACE WHICH CAN BE SUBLET, IN THE UNIT_1 INDICATED BY THE UNIT_1 OF MEASURE CODE (E.G. M2).'
    ,RENTED_SUBLET_AREA_MEAS COMMENT 'THE SPACE WHICH IS CURRENTLY RENTED OUT, IN THE UNIT_1 INDICATED BY THE UNIT_1 OF MEASURE CODE.'
)
AS
WITH 
    ALL_STATS_ASOF_NOW AS (
        SELECT
            RE.REAL_ESTATE_SID
            , RE.DWH_VALID_FROM_TMSP
            , RE.DWH_VALID_TO_TMSP
            , CD.CAL_DT AS CAL_DT
            , RE.INT_ORG_SID AS STORE_SID
            , CNTR.COUNTRY_ORG_SID AS COUNTRY_ORG_SID
            , RE.REPORTING_COUNTRY_CD AS REPORTING_COUNTRY_CD
            , CNTR.COUNTRY_ORG_CD AS COUNTRY_ORG_CD
            , RE.REAL_ESTATE_STATUS_CD
            , DECODE(RE.REAL_ESTATE_STATUS_CD, 'OP', 1, 0) AS OPEN_STORE_CNT
            , DECODE(RE.REAL_ESTATE_STATUS_CD, 'CL', 1, 0) AS CLOSED_STORE_CNT
            , DECODE(RE.REAL_ESTATE_STATUS_CD, 'UC', 1, 'CN', 1, 0) AS STORE_UNDER_CONTRACT_CNT
            , DECODE(RE.REAL_ESTATE_STATUS_CD, 'CN', 1, 'TE', 1, 0) AS CANCEL_TERM_STORE_CNT
            , DECODE(RE.REAL_ESTATE_STATUS_CD, 'UC', 1, 0) AS STORE_TO_BE_BUILT_CNT
            , CASE 
                WHEN RE.OWNERSHIP_TYPE_CD IN ('B', 'L') AND RE.REAL_ESTATE_STATUS_CD = 'UC' THEN 1
                ELSE 0
            END AS OWN_STORE_TO_BE_BUILT_CNT
            , CASE 
                WHEN RE.OWNERSHIP_TYPE_CD IN ('B', 'L') AND RE.REAL_ESTATE_STATUS_CD = 'OP' THEN 1
                ELSE 0
            END AS OWN_OPEN_STORE_CNT
            , RE.OWNERSHIP_TYPE_CD
            , REL.OPEN_DT
            , REL.CLOSE_DT
            , CD.CAL_DT - REL.OPEN_DT AS DAYS_SINCE_OPENING
            , CD.CAL_DT - REL.CLOSE_DT AS DAYS_SINCE_CLOSURE
            , RE.SALES_AREA_MEAS
            , NVL(RE.TOTAL_SUBLET_AREA_MEAS, 0) AS TOTAL_SUBLET_AREA_MEAS
            , NVL(RE.RENTED_SUBLET_AREA_MEAS, 0) AS RENTED_SUBLET_AREA_MEAS
        FROM CORE_DIM.T_DIM_REAL_ESTATE_1 RE_1
            JOIN CORE_DIM.T_FACT_REAL_ESTATE_LIFECYCLE_1 REL
                ON REL.REAL_ESTATE_SID = RE.REAL_ESTATE_SID
             JOIN CORE_DIM.T_DIM_CALENDAR_DATE_1 CD
                ON CD.CAL_DT BETWEEN RE.DWH_VALID_FROM_TMSP AND RE.DWH_VALID_TO_TMSP
             JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 CNTR
                ON CNTR.COUNTRY_ORG_CD = SUBSTR(RE.REAL_ESTATE_NR, 1, 2)
                AND CNTR.IS_COUNTRY_ORG_FG = TRUE
                AND CD.CAL_DT BETWEEN CNTR.DWH_VALID_FROM_TMSP AND CNTR.DWH_VALID_TO_TMSP
        )

        -- RECORDS FROM YEAR X (2022 FOR EXAMPLE) ARE ASSOCIATED WITH X+1 (2023 FOR EXAMPLE) FOR THE PY COLS OF 2023
 , PREV_STATS AS
 (
    SELECT
        ASAN.REAL_ESTATE_SID
        ,PY.CAL_DT
        ,PY.BUS_YEAR_DIFF
        ,ASAN.COUNTRY_ORG_CD
        ,ASAN.REPORTING_COUNTRY_CD
        
        ,SUM(OPEN_STORE_CNT) AS OPEN_STORE_CNT
        ,SUM(CLOSED_STORE_CNT) AS CLOSED_STORE_CNT
        ,SUM(STORE_UNDER_CONTRACT_CNT) AS STORE_UNDER_CONTRACT_CNT
        ,SUM(STORE_TO_BE_BUILT_CNT) AS STORE_TO_BE_BUILT_CNT

    FROM ALL_STATS_ASOF_NOW ASAN 
        JOIN CORE_REL.T_CAL_DATE_ADJUSTED_RELATIONSHIP_1 PY 
                ON ASAN.CAL_DT = PY.REL_CAL_DT  -- 02.01.2022 FOR EXAMPLE
    WHERE 1=1
        AND PY.BUS_YEAR_DIFF IN (1,2)
        AND PY.CAL_DT_ADJUST_TYPE_CD = 'M'
        AND PY.CAL_DT < CURRENT_DATE
    GROUP BY
        ASAN.REAL_ESTATE_SID
        ,PY.CAL_DT
        ,PY.BUS_YEAR_DIFF
        ,ASAN.COUNTRY_ORG_CD
        ,ASAN.REPORTING_COUNTRY_CD
)
SELECT 
    COALESCE(ASAN.REAL_ESTATE_SID, PY.REAL_ESTATE_SID, PPY.REAL_ESTATE_SID) AS REAL_ESTATE_SID
    ,ASAN.STORE_SID                                                         AS STORE_SID
    ,ASAN.COUNTRY_ORG_SID                                                   AS COUNTRY_ORG_SID
    ,COALESCE(ASAN.COUNTRY_ORG_CD, PY.COUNTRY_ORG_CD, PPY.COUNTRY_ORG_CD)   AS COUNTRY_ORG_CD 
    ,COALESCE(ASAN.REPORTING_COUNTRY_CD, PY.REPORTING_COUNTRY_CD, PPY.REPORTING_COUNTRY_CD) AS REPORTING_COUNTRY_CD
    ,COALESCE(ASAN.CAL_DT, PY.CAL_DT, PPY.CAL_DT)                           AS CAL_DT
    ,ASAN.REAL_ESTATE_STATUS_CD

    ,NVL(ASAN.OPEN_STORE_CNT, 0)        AS OPEN_STORE_CNT
    ,NVL(PY.OPEN_STORE_CNT, 0)      AS OPEN_STORE_PY_CNT
    ,NVL(PPY.OPEN_STORE_CNT, 0)     AS OPEN_STORE_PPY_CNT
    
    ,NVL(ASAN.CLOSED_STORE_CNT, 0)      AS CLOSED_STORE_CNT
    ,NVL(PY.CLOSED_STORE_CNT, 0)        AS CLOSED_STORE_PY_CNT
    ,NVL(PPY.CLOSED_STORE_CNT, 0)       AS CLOSED_STORE_PPY_CNT
    
    ,NVL(ASAN.STORE_UNDER_CONTRACT_CNT, 0)      AS STORE_UNDER_CONTRACT_CNT
    ,NVL(PY.STORE_UNDER_CONTRACT_CNT, 0)        AS STORE_UNDER_CONTRACT_PY_CNT
    ,NVL(PPY.STORE_UNDER_CONTRACT_CNT, 0)       AS STORE_UNDER_CONTRACT_PPY_CNT
    
    ,NVL(ASAN.STORE_TO_BE_BUILT_CNT, 0)    AS STORE_TO_BE_BUILT_CNT
    ,NVL(PY.STORE_TO_BE_BUILT_CNT, 0)      AS STORE_TO_BE_BUILT_PY_CNT
    ,NVL(PPY.STORE_TO_BE_BUILT_CNT, 0)     AS STORE_TO_BE_BUILT_PPY_CNT
    
    ,ASAN.CANCEL_TERM_STORE_CNT AS CANCEL_TERM_STORE_CNT
    ,ASAN.OWN_STORE_TO_BE_BUILT_CNT AS OWN_STORE_TO_BE_BUILT_CNT
    ,ASAN.OWN_OPEN_STORE_CNT AS OWN_OPEN_STORE_CNT
    ,ASAN.OWNERSHIP_TYPE_CD
    ,ASAN.OPEN_DT
    ,ASAN.CLOSE_DT
    ,ASAN.DAYS_SINCE_OPENING
    ,ASAN.DAYS_SINCE_CLOSURE
    ,ASAN.SALES_AREA_MEAS
    ,ASAN.TOTAL_SUBLET_AREA_MEAS
    ,ASAN.RENTED_SUBLET_AREA_MEAS

FROM ALL_STATS_ASOF_NOW ASAN
            
    FULL OUTER JOIN PREV_STATS PY
            ON PY.REAL_ESTATE_SID = ASAN.REAL_ESTATE_SID
            AND PY.CAL_DT = ASAN.CAL_DT
            AND PY.BUS_YEAR_DIFF = 1
    FULL OUTER JOIN PREV_STATS PPY
            ON PPY.REAL_ESTATE_SID = NVL(ASAN.REAL_ESTATE_SID, PY.REAL_ESTATE_SID)
            AND PPY.CAL_DT = NVL(ASAN.CAL_DT, PY.CAL_DT)
            AND PPY.BUS_YEAR_DIFF = 2
;