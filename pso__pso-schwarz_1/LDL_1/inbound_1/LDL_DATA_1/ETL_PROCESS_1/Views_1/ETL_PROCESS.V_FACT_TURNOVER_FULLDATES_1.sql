CREATE OR REPLACE VIEW ETL_PROCESS.V_FACT_TURNOVER_FULLDATES_1 (
       CAL_DT
     , BUS_YEAR
     , INT_ORG_SID
     , INT_ORG_TYPE_CD
     , COUNTRY_ORG_CD
     , CURR_CD
) AS  
SELECT D.CAL_DT
     , D.BUS_YEAR
     , F.INT_ORG_SID
     , F.INT_ORG_TYPE_CD
     , F.COUNTRY_ORG_CD
     , F.CURR_CD 
  FROM CORE_DIM.T_DIM_CALENDAR_DATE_1 AS D  
  JOIN ETL_PROCESS.V_FACT_TURNOVER_DATES_1 AS F
    ON D.BUS_YEAR = F.BUS_YEAR
   AND D.CAL_DT BETWEEN BEGIN_BUS_DT AND TO_BUS_DT
;