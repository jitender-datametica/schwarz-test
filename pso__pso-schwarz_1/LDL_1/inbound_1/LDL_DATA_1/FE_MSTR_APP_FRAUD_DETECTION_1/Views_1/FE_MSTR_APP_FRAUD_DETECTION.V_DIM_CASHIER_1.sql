CREATE OR REPLACE VIEW FE_MSTR_APP_FRAUD_DETECTION.V_DIM_CASHIER_1(
	STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE STORE WHERE THE RELATED CASH REGISTER EVENT HAPPENED.',
	CASHIER_NR COMMENT 'THE NUMBER WHICH IDENTIFIES THE CASHIER. (THE NUMBER IS UNIQUE FOR A GIVEN STORE AND A DAY.)',
	CASHIER_DESC COMMENT 'THE BUSINESS KEY OF A CASHIER'
 ) COMMENT='THE DIMENSION VIEW FOR THE CASHIERS'
 AS  
WITH CASHIER_DIM (COUNTRY_ORG_CD,STORE_NR,CASHIER_NR)
AS
(  
SELECT 
DIM.COUNTRY_ORG_CD
,DIM.STORE_NR
,DIM.CASHIER_NR
FROM CORE_APP_FRAUD_DETECTION.T_CASHIER_ENCRYPTION_1 DIM
WHERE DIM.BUS_DT > '2024-12-29'
GROUP BY DIM.COUNTRY_ORG_CD,DIM.STORE_NR, DIM.CASHIER_NR
)
SELECT ORG.INT_ORG_SID AS STORE_SID, 
       MAIN.CASHIER_NR AS CASHIER_NR,
       CURR_INT_ORG_NR||'|' ||MAIN.CASHIER_NR AS CASHIER_DESC
FROM CASHIER_DIM MAIN
INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 ORG
ON ORG.CURR_INT_ORG_NR = MAIN.COUNTRY_ORG_CD || MAIN.STORE_NR
AND ORG.DWH_VALID_FG
AND ORG.INT_ORG_TYPE_CD = 'STORE';

