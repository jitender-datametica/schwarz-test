CREATE OR REPLACE VIEW FE_MSTR_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_METRIC_BY_CASHIER_HOUR_1(
	STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE STORE WHERE THE RELATED CASH REGISTER EVENT HAPPENED.',
	CASHIER_NR COMMENT 'THE NUMBER WHICH IDENTIFIES THE CASHIER. (THE NUMBER IS UNIQUE FOR A GIVEN STORE AND A DAY.)',
    BUS_DT COMMENT 'THE BUSINESS DATE ON WHICH THE RETAIL EVENT IS COUNTED.',
    HR COMMENT 'HOUR INFORMATION',
	METRIC_ID COMMENT 'THE UNIQUE IDENTIFIER OF MICROSTRATEY METRIC',
    COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_1 FOR WHICH THE RELATED COUNTRY_1 ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY_1 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	CURR_CD COMMENT 'THE CODE IDENTIFYING THE CURRENCY ACCORDING TO ISO-4217.',
	CURR_GROUP_FG COMMENT 'FLAG FOR GROUP CURRENCY',
	CURR_LOCAL_FG COMMENT 'FLAG FOR LOCAL CURRENCY',
    SCENARIO_ID COMMENT 'THE UNIQUE IDENTIFIER OF FRAUD DETECTION SCENARIO',
    CALCULATION_TYPE_CD COMMENT 'THE CALCULATION TYPE OF THE METRIC SUM,SMARTAVG..',
    METRIC_VAL_1 COMMENT 'THE FIRST VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	METRIC_VAL_2 COMMENT 'THE SECOND VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	METRIC_VAL_3 COMMENT 'THE THIRD VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	METRIC_VAL_4 COMMENT 'THE  VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC'
 ) COMMENT='THIS VIEW BRINGS THE VALUES IN A NORMALIZED FORM TO CALCULATE THE METRICS, WHICH WILL BE USED FOR DYNAMIC DASHBOARD'
 AS  
 WITH CTE_METRICS
 (METRIC_ID,CALCULATION_TYPE_CD,SCENARIO_ID,EXCHANGE_RATE_CALC_FG)
 AS
 (
 SELECT 
   M.METRIC_ID
  ,M.CALCULATION_TYPE_CD
  ,M.SCENARIO_ID
  ,CASE 
	WHEN SUBSTRING(M.FORMAT_TYPE_CD,1,3) = 'INT' 
	OR  SUBSTRING(M.FORMAT_TYPE_CD,1,3) = 'FLT' AND  M.CALCULATION_TYPE_CD = 'LEVELAVG'
	OR  M.METRIC_ID BETWEEN 3400 AND 3499 
	OR  M.METRIC_ID BETWEEN 2400 AND 2499 THEN FALSE
	ELSE TRUE
	END AS EXCHANGE_RATE_FG
FROM CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_1 M
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 S
ON S.SCENARIO_ID = M.SCENARIO_ID
 )
  SELECT
    MAIN.STORE_SID
    ,MAIN.CASHIER_NR
    ,MAIN.BUS_DT
    ,MAIN.HR
    ,M.METRIC_ID
    ,MAIN.COUNTRY_ORG_CD
    ,FER.SRC_CURR_CD AS CURR_CD
    ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
    ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
    ,M.SCENARIO_ID
    ,M.CALCULATION_TYPE_CD
    ,CASE WHEN M.EXCHANGE_RATE_CALC_FG THEN  MAIN.METRIC_VAL_1 / FER.EXCHANGE_RATE ELSE MAIN.METRIC_VAL_1  END AS METRIC_VAL_1
    ,CASE WHEN M.EXCHANGE_RATE_CALC_FG THEN  MAIN.METRIC_VAL_2 / FER.EXCHANGE_RATE ELSE MAIN.METRIC_VAL_2  END AS METRIC_VAL_2
    ,CASE WHEN M.EXCHANGE_RATE_CALC_FG THEN  MAIN.METRIC_VAL_3 / FER.EXCHANGE_RATE ELSE MAIN.METRIC_VAL_3  END AS METRIC_VAL_3
    ,CASE WHEN M.EXCHANGE_RATE_CALC_FG THEN  MAIN.METRIC_VAL_4 / FER.EXCHANGE_RATE ELSE MAIN.METRIC_VAL_4  END AS METRIC_VAL_4
FROM CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_METRIC_BY_CASHIER_HOUR_1 MAIN
  INNER JOIN CTE_METRICS M
  ON M.METRIC_ID = MAIN.METRIC_ID
  INNER JOIN CORE_DIM.T_DIM_COUNTRY_1 CT
  ON MAIN.COUNTRY_ORG_CD = CT.ISO_COUNTRY_CD
  INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 FER
    ON CT.CURR_CD = FER.TGT_CURR_CD
  WHERE EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
    AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
    AND FER.ACTIVE_FG = TRUE;