CREATE OR REPLACE VIEW FE_MSTR_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_PARAMETER_VALUE_REQ_1(
	COUNTRY_ORG_SID COMMENT 'THE CODE OF THE RELATED BUSINESS COUNTRY. (THE BUSINESS COUNTRY_1 IS NOT IDENTICAL TO A POLITICAL COUNTRY_1',
	SCENARIO_ID COMMENT 'THE IDENTIFIER OF THE SCENARIO FOR FRAUD DETECTION',
	PARAM_ID COMMENT 'THE UNIQUE IDENTIFIER OF PARAMETER (THERESHOLD) OF A SCENARIO',
	PARAM_STATUS_CD COMMENT 'THE STATUS_1 OF A PARAMETER VALUE IF IT IS APPROVED, REQUESTED OR DENIED.',
	PARAM_VAL_QTY COMMENT 'CURRENT VALUE OF A PARAMETER',
	PARAM_APPROVED_VAL_QTY COMMENT 'APPROVED PARAMATER VALUE',
	PARAM_DEFAULT_VAL_QTY COMMENT 'DEFAULT PARAMETER VALUE'
) COMMENT='THE UPDATED VALUE PARAMETERS WHICH ARE READY TO APPROVE' 
AS SELECT 
ORG.INT_ORG_SID AS COUNTRY_ORG_SID,
FDP.SCENARIO_ID AS SCENARIO_ID,
FDP.PARAM_ID  AS PARAM_ID,
DECODE(FDPV.PARAM_STATUS_CD,'RE_1','RE_1','RE_1') AS PARAM_STATUS_CD_REQ,
MAX(DECODE(FDPV.PARAM_STATUS_CD,'RE_1',FDPV.PARAM_VAL_QTY ) ) AS  PARAM_VAL_QTY,
MAX(DECODE(FDPV.PARAM_STATUS_CD,'AP',FDPV.PARAM_VAL_QTY)) AS PARAM_APPROVED_VAL_QTY,
MAX(FDP.PARAM_DEFAULT_VAL_QTY) AS PARAM_DEFAULT_VAL_QTY
FROM CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 ORG
CROSS JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 FDS
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_PARAMETER_1 FDP
ON FDS.SCENARIO_ID = FDP.SCENARIO_ID
AND ORG.DWH_VALID_FG 
AND ORG.IS_COUNTRY_ORG_FG
LEFT JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_PARAMETER_VALUE_1 FDPV
ON FDPV.PARAM_ID = FDP.PARAM_ID
AND FDPV.COUNTRY_ORG_CD = ORG.COUNTRY_ORG_CD
AND FDPV.DWH_VALID_FG
AND FDPV.PARAM_STATUS_CD IN ('RE_1','AP') 
GROUP BY  
ORG.INT_ORG_SID
,FDP.SCENARIO_ID
,FDP.PARAM_ID
,PARAM_STATUS_CD_REQ;