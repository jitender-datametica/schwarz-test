CREATE OR REPLACE VIEW CORE.V_AGG_ESTIMATED_INITIAL_PROMOTION_STOCK_1(
	WSHOP_CD
	,PROD_SID
	,PROMO_START_DT
	,PROMO_SALE_START_DT
	,PROMO_ID
	,PROD_VARIANT_SID
	,ESTIMATED_INIT_PROMO_STOCK
	,STOCK_DISTRIBUTION_PCT
) AS
---CALCULATE THE STOCK PER VARIANT, ADDING THE PROD_SID TO THE TABLE NEEDED FOR FOLLOWING CALCULATIONS
WITH PROD_STOCK AS (
    SELECT
        VAR.PROD_VARIANT_SID
        ,VAR.PROD_SID
        ,AGG.CAL_DT
        ,SUM(AGG.TOTAL_STOCK_CNT) AS TOTAL_STOCK
    FROM
        CORE.T_FACT_STOCK_WAREHOUSE_DAILY_1 AGG
    JOIN 
        CORE.T_DIM_PRODUCT_VARIANT_1 VAR
    ON 
        AGG.PROD_VARIANT_SID = VAR.PROD_VARIANT_SID
    AND VAR.DWH_VALID_FG
    WHERE AGG.ACTIVE_FG
    GROUP BY
        VAR.PROD_VARIANT_SID 
		,VAR.PROD_SID
		,AGG.CAL_DT
)
--- CALCULATE THE STOCK PER VARIANT USING THE STOCK*COUNTRY_1 PERCENTAGE TABLE AVAILABLE ONLY ON PRODUCT LEVEL
,VARIANT_STOCK AS 
(
    SELECT 
    PROD.PROD_VARIANT_SID
    ,DIS_CHANNEL.WSHOP_CD
    ,PROD.CAL_DT
    ,PROD.TOTAL_STOCK
    ,PROD.TOTAL_STOCK * STOCK.DISTRIBUTION_PCT AS VARIANT_STOCK_COUNTRY
FROM
    CORE.T_FACT_STOCK_ALLOCATION_ENTITY_DAILY_1 AS STOCK
JOIN 
    CORE.T_DIM_WAREHOUSE_ALLOCATION_ENTITY_1 AS ENT_ALLOC
ON 
    ENT_ALLOC.WH_ALLOC_ENTITY_CD = STOCK.WH_ALLOC_ENTITY_CD
JOIN 
    CORE.T_DIM_DISTRIBUTION_CHANNEL_1 AS DIS_CHANNEL
ON
    DIS_CHANNEL.DIST_CHANNEL_CD = ENT_ALLOC.DIST_CHANNEL_CD
JOIN 
    PROD_STOCK AS PROD
ON 
    STOCK.PROD_SID = PROD.PROD_SID
    AND STOCK.CAL_DT = PROD.CAL_DT
    WHERE STOCK.ACTIVE_FG
)
--- CALCULATE THE ORDERS AND RETURNS QUANTITY - SOURCE IS THE T_AGG_PROMOTION_SALES_DAILY_1 TABLE WHERE THEY ARE ALREADY AGGREGATED ON A VARIANT/WSHOP/PROMO_ID LEVEL
,ORDERS AS ( 
SELECT
    PROD_VARIANT_SID
    ,WSHOP_CD
    ,PROMO_SALE_START_DT
    ,PROMO_ID  -- NEEDED TO AVOID DUPLICATES
    ,SUM(PROD_QTY) AS ORDERS
    ,SUM(RETURN_PROD_QTY) AS RETURN_ORDERS
FROM
    CORE.T_AGG_PROMOTION_SALES_DAILY_1
   GROUP BY
    PROD_VARIANT_SID
    ,WSHOP_CD
    ,PROMO_ID
    ,PROMO_SALE_START_DT)
,ESTIMATED_STOCK AS (
--START FROM THE SALES_PROMOTION TABLE + CALCULATE THE ESTIMATED_PROMO_START_STOCK AND THE VARIANT_STOCK_COUNTRY_DISTR_PERCENTAGE FOR PRODUCTS WITH STOCK
SELECT
         PROMO.WSHOP_CD AS WSHOP_CD
        ,PROMO.PROD_SID AS PROD_SID
        ,PROMO.PROMO_START_DT AS PROMO_START_DT
        ,PROMO.PROMO_SALE_START_DT AS PROMO_SALE_START_DT
        ,PROMO.PROMO_ID AS PROMO_ID
        ,VAR.PROD_VARIANT_SID AS PROD_VARIANT_SID
        ,IFNULL(ROUND(STOCK.VARIANT_STOCK_COUNTRY,0),0) + IFNULL(ORDERS.ORDERS,0) - IFNULL(ORDERS.RETURN_ORDERS,0) AS ESTIMATED_INIT_PROMO_STOCK
        ,ROUND(DIV0((IFNULL(STOCK.VARIANT_STOCK_COUNTRY,0) + IFNULL(ORDERS.ORDERS,0) - IFNULL(ORDERS.RETURN_ORDERS,0)),SUM(IFNULL(STOCK.VARIANT_STOCK_COUNTRY,0) + IFNULL(ORDERS.ORDERS,0) - IFNULL(ORDERS.RETURN_ORDERS,0)) OVER (PARTITION BY PROMO.PROMO_ID)),9) AS STOCK_DISTRIBUTION_PCT 
FROM
        CORE.T_DIM_SALES_PROMOTION_1 PROMO  --WE HAVE IT ON PROMO_ID LEVEL SO IT IS FINE TO HAVE THE T_DIM HERE, WILL BE JOINED WITH THE V_DIM IN THE FRONT-END
LEFT JOIN 
        CORE.T_DIM_PRODUCT_VARIANT_1 VAR
        ON      PROMO.PROD_SID = VAR.PROD_SID
        AND VAR.DWH_VALID_FG = TRUE
LEFT JOIN
        VARIANT_STOCK STOCK
        ON  VAR.PROD_VARIANT_SID = STOCK.PROD_VARIANT_SID
        AND PROMO.WSHOP_CD = STOCK.WSHOP_CD
LEFT JOIN
        ORDERS
        ON VAR.PROD_VARIANT_SID = ORDERS.PROD_VARIANT_SID
        AND PROMO.WSHOP_CD = ORDERS.WSHOP_CD
        AND PROMO.PROMO_SALE_START_DT = ORDERS.PROMO_SALE_START_DT
        AND PROMO.PROMO_ID = ORDERS.PROMO_ID
WHERE   PROMO.DWH_VALID_FG
    AND PROMO.SALE_PROMO_STATUS_CD = 'ACTIVE'
)
--IDENTIFY THE PRODUCTS THAT HAVE STOCK = 0
,WITHOUT_STOCK AS
(
    SELECT
        PROD_SID
        ,PROMO_ID
        ,COUNT(DISTINCT PROD_VARIANT_SID) AS CNT
        ,SUM(ESTIMATED_INIT_PROMO_STOCK) AS STOCK
    FROM
        ESTIMATED_STOCK
    GROUP BY PROD_SID, PROMO_ID
    HAVING STOCK = '0'
)
--INTEGRATE THE DISTRIBUTION PERCENTAGE ALSO FOR PRODUCTS THAT HAVE STOCK = 0
SELECT
    EST.WSHOP_CD AS WSHOP_CD
    ,EST.PROD_SID AS PROD_SID
    ,EST.PROMO_START_DT AS PROMO_START_DT
    ,EST.PROMO_SALE_START_DT AS PROMO_SALE_START_DT
    ,EST.PROMO_ID AS PROMO_ID
    ,EST.PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,EST.ESTIMATED_INIT_PROMO_STOCK
    ,CASE WHEN EST.ESTIMATED_INIT_PROMO_STOCK > 0
                THEN EST.STOCK_DISTRIBUTION_PCT 
          WHEN EST.ESTIMATED_INIT_PROMO_STOCK = 0
          AND  EST.PROMO_ID IN (SELECT PROMO_ID FROM WITHOUT_STOCK)
                THEN DIV0(1,WITHOUT_STOCK.CNT)
                ELSE 0
     END AS STOCK_DISTRIBUTION_PCT
FROM
    ESTIMATED_STOCK AS EST
LEFT JOIN
    WITHOUT_STOCK
ON  EST.PROMO_ID = WITHOUT_STOCK.PROMO_ID
AND EST.PROD_SID = WITHOUT_STOCK.PROD_SID
;