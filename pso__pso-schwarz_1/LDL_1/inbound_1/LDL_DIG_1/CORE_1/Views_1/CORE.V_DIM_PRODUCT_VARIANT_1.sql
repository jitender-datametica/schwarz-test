FROM CORE.T_DIM_PRODUCT_VARIANT_1 PR
	LEFT JOIN CORE.T_DIM_SALES_PROMOTION_1 PROMO ON PROMO.PROD_SID = PR.PROD_SID
									AND PROMO.DWH_VALID_FG
									AND LOWER(PROMO.SALE_PROMO_STATUS_CD) <> 'canceled'
	JOIN CORE.T_DIM_CAL_DAY_1 C ON C.CY_WEEK = PROMO.TGT_PROD_RECEIVE_CY_WEEK  AND C.DAY_OF_WEEK = 5
WHERE 1=1
	AND C.CAL_DT <= CURRENT_DATE
	AND (PROMO.PROD_SID, NVL(AMC_IAN_NR, '-9999')) IN 
	(
		SELECT PROD_SID, NVL(MAX(AMC_IAN_NR), '-9999')
		FROM CORE.T_DIM_SALES_PROMOTION_1 T
			JOIN CORE.T_DIM_CAL_DAY_1 C ON C.CY_WEEK = T.TGT_PROD_RECEIVE_CY_WEEK  AND C.DAY_OF_WEEK = 5
									AND T.DWH_VALID_FG
		WHERE CAL_DT <= CURRENT_DATE
		GROUP BY PROD_SID
	)
