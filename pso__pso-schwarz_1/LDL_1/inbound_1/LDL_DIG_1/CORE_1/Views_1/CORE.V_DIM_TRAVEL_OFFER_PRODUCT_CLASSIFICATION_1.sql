CREATE OR REPLACE VIEW CORE.V_DIM_TRAVEL_OFFER_PRODUCT_CLASSIFICATION_1(
	TRAV_OFFER_PROD_CLASS_CD,
	TRAV_OFFER_PROD_CLASS_DESCR
) COMMENT='A regular view to fetch the categorization of a product.(Deluxe | Premium | Standard)'
 AS
SELECT DISTINCT TRAV_OFFER_PROD_CLASS_CD,
       NULL AS TRAV_OFFER_PROD_CLASS_DESCR
FROM CORE.T_DIM_TRAVEL_OFFER_1;