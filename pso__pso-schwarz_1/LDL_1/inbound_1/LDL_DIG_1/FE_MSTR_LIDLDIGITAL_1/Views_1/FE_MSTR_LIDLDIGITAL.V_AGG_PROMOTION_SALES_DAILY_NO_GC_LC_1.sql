CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_AGG_PROMOTION_SALES_DAILY_NO_GC_LC_1
AS
    WITH CTE_PSD AS (
    SELECT
        WSHOP_CD AS WSHOP_CD
        ,PROMO_ID AS PROMO_ID
        ,PROD_VARIANT_SID AS PROD_VARIANT_SID
        ,CUST_ORDER_DT AS CUST_ORDER_DT
        ,PROMO_START_DT AS PROMO_START_DT
        ,PROMO_SALE_START_DT AS PROMO_SALE_START_DT
        ,IS_SPECIAL_ANALYSIS_FG AS IS_SPECIAL_ANALYSIS_FG
        ,CURR_CD AS CURR_CD
        ,PROD_PRICE_NET_LOCAL_VAL AS PROD_PRICE_NET_LOCAL_VAL
        ,COGS_PRICE_NET_LOCAL_VAL AS COGS_PRICE_NET_LOCAL_VAL
        ,PROD_QTY AS PROD_QTY
        ,CANCEL_PROD_PRICE_NET_LOCAL_VAL AS CANCEL_PROD_PRICE_NET_LOCAL_VAL
        ,CANCEL_PROD_QTY AS CANCEL_PROD_QTY
        ,RETURN_PROD_PRICE_NET_LOCAL_VAL AS RETURN_PROD_PRICE_NET_LOCAL_VAL
        ,RETURN_PROD_QTY AS RETURN_PROD_QTY
        ,TOTAL_PROD_PRICE_NET_LOCAL_VAL AS TOTAL_PROD_PRICE_NET_LOCAL_VAL
        ,TOTAL_PROD_QTY AS TOTAL_PROD_QTY
        ,PROMO_SALE_CLUSTER_CD AS PROMO_SALE_CLUSTER_CD
        ,PROD_PRICE_GROSS_LOCAL_VAL AS PROD_PRICE_GROSS_LOCAL_VAL
        ,CANCEL_PROD_PRICE_GROSS_LOCAL_VAL AS CANCEL_PROD_PRICE_GROSS_LOCAL_VAL
        ,RETURN_PROD_PRICE_GROSS_LOCAL_VAL AS RETURN_PROD_PRICE_GROSS_LOCAL_VAL
        ,TOTAL_PROD_PRICE_GROSS_LOCAL_VAL AS TOTAL_PROD_PRICE_GROSS_LOCAL_VAL
        ,PROD_VARIANT_NR AS PROD_VARIANT_NR
        ,PROD_ORDERABLE_LVL_CD AS PROD_ORDERABLE_LVL_CD --new field
        ,0 AS IS_AFTER_CANCELLATION_FG
    FROM
        lec_share.v_agg_promotion_sales_daily_1

    UNION ALL

    SELECT
        WSHOP_CD AS WSHOP_CD
        ,PROMO_ID AS PROMO_ID
        ,PROD_VARIANT_SID AS PROD_VARIANT_SID
        ,CUST_ORDER_DT AS CUST_ORDER_DT
        ,PROMO_START_DT AS PROMO_START_DT
        ,PROMO_SALE_START_DT AS PROMO_SALE_START_DT
        ,IS_SPECIAL_ANALYSIS_FG AS IS_SPECIAL_ANALYSIS_FG
        ,CURR_CD AS CURR_CD
        ,PROD_PRICE_NET_LOCAL_VAL - CANCEL_PROD_PRICE_NET_LOCAL_VAL AS PROD_PRICE_NET_LOCAL_VAL
        ,COGS_PRICE_NET_LOCAL_VAL - ((COGS_PRICE_NET_LOCAL_VAL/IFF(PROD_QTY=0, NULL, PROD_QTY))*(CANCEL_PROD_QTY)) AS COGS_PRICE_NET_LOCAL_VAL
        ,PROD_QTY - CANCEL_PROD_QTY AS PROD_QTY
        ,CANCEL_PROD_PRICE_NET_LOCAL_VAL AS CANCEL_PROD_PRICE_NET_LOCAL_VAL
        ,CANCEL_PROD_QTY AS CANCEL_PROD_QTY
        ,RETURN_PROD_PRICE_NET_LOCAL_VAL AS RETURN_PROD_PRICE_NET_LOCAL_VAL
        ,RETURN_PROD_QTY AS RETURN_PROD_QTY
        ,TOTAL_PROD_PRICE_NET_LOCAL_VAL AS TOTAL_PROD_PRICE_NET_LOCAL_VAL
        ,TOTAL_PROD_QTY AS TOTAL_PROD_QTY
        ,PROMO_SALE_CLUSTER_CD AS PROMO_SALE_CLUSTER_CD
        ,PROD_PRICE_GROSS_LOCAL_VAL - CANCEL_PROD_PRICE_GROSS_LOCAL_VAL AS PROD_PRICE_GROSS_LOCAL_VAL
        ,CANCEL_PROD_PRICE_GROSS_LOCAL_VAL AS CANCEL_PROD_PRICE_GROSS_LOCAL_VAL
        ,RETURN_PROD_PRICE_GROSS_LOCAL_VAL AS RETURN_PROD_PRICE_GROSS_LOCAL_VAL
        ,TOTAL_PROD_PRICE_GROSS_LOCAL_VAL AS TOTAL_PROD_PRICE_GROSS_LOCAL_VAL
        ,PROD_VARIANT_NR AS PROD_VARIANT_NR
        ,PROD_ORDERABLE_LVL_CD AS PROD_ORDERABLE_LVL_CD --new field
        ,1 AS IS_AFTER_CANCELLATION_FG
    FROM
        lec_share.v_agg_promotion_sales_daily_1
)

,CTE_PPC AS (
    SELECT
         IFNULL(FACT_PPC.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
        ,CASE WHEN FACT_PPC.WSHOP_CD = '' THEN '-1' ELSE IFNULL(FACT_PPC.WSHOP_CD, '-1') END AS WSHOP_CD
        ,CASE WHEN FACT_PPC.PRICE_TYPE_CD = '' THEN '-1' ELSE IFNULL(FACT_PPC.PRICE_TYPE_CD, '-1') END AS PRICE_TYPE_CD
        ,CASE WHEN FACT_PPC.PRICE_GROUP_CD = '' THEN '-1' ELSE IFNULL(FACT_PPC.PRICE_GROUP_CD, '-1') END AS PRICE_GROUP_CD
        ,FACT_PPC.ACTIVE_FROM_TMSP AS ACTIVE_FROM_TMSP
        ,FACT_PPC.ACTIVE_TO_TMSP AS ACTIVE_TO_TMSP
        ,CASE WHEN FACT_PPC.CURR_CD = '' THEN '-1' ELSE IFNULL(FACT_PPC.CURR_CD, '-1') END AS CURR_CD
        ,FACT_PPC.PRICE_VAL / CER_FACT.EXCHANGE_RATE AS PRICE_EUR_VAL
        ,FACT_PPC.PRICE_VAL AS PRICE_LOCAL_VAL
        ,CASE WHEN FACT_PPC.PRICE_CHANGE_REASON_CD = '' THEN '-1' ELSE IFNULL(FACT_PPC.PRICE_CHANGE_REASON_CD, '-1') END AS PRICE_CHANGE_REASON_CD
    FROM
        lec_share.v_fact_product_pricing_condition_1 FACT_PPC
    INNER JOIN
        lec_share.v_fact_currency_exchange_rate_1 CER_FACT
        ON
            FACT_PPC.CURR_CD = CER_FACT.FROM_CURR_CD
            AND DATE(FACT_PPC.ACTIVE_FROM_TMSP) BETWEEN CER_FACT.ACTIVE_FROM_DT AND CER_FACT.ACTIVE_TO_DT 
    INNER JOIN
        lec_share.v_dim_currency_exchange_rate_type_1 CERT_DIM
        ON
            CERT_DIM.CURR_EXCHANGE_RATE_TYPE_CD = CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD
            AND CERT_DIM.IS_GENERAL_USED_FG
    WHERE
        CER_FACT.TO_CURR_CD = 'EUR'
)

,CTE_PPS AS (
    SELECT
         IFNULL(FACT_PPS.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
        ,CASE WHEN FACT_PPS.WSHOP_CD = '' THEN '-1' ELSE IFNULL(FACT_PPS.WSHOP_CD, '-1') END AS WSHOP_CD
        ,CASE WHEN FACT_PPS.PRICE_TYPE_CD = '' THEN '-1' ELSE IFNULL(FACT_PPS.PRICE_TYPE_CD, '-1') END AS PRICE_TYPE_CD
        ,CASE WHEN FACT_PPS.PRICE_GROUP_CD = '' THEN '-1' ELSE IFNULL(FACT_PPS.PRICE_GROUP_CD, '-1') END AS PRICE_GROUP_CD
        ,FACT_PPS.ACTIVE_FROM_TMSP AS ACTIVE_FROM_TMSP
        ,FACT_PPS.ACTIVE_TO_TMSP AS ACTIVE_TO_TMSP
        ,CASE WHEN WC_REL.CURR_CD = '' THEN '-1' ELSE IFNULL(WC_REL.CURR_CD, '-1') END AS CURR_CD
        ,FACT_PPS.PRICE_VAL * CER_FACT.EXCHANGE_RATE AS PRICE_LOCAL_VAL
        ,FACT_PPS.PRICE_VAL AS PRICE_EUR_VAL
    FROM
        lec_share.v_fact_product_price_supplier_1 FACT_PPS
     INNER JOIN
       lec_share.v_dim_product_variant_1 PV_DIM
        ON FACT_PPS.PROD_VARIANT_SID = PV_DIM.PROD_VARIANT_SID
        AND FACT_PPS.SUPPLIER_SID = PV_DIM.MAIN_SUPPLIER_SID
        AND PV_DIM.DWH_VALID_FG = 'TRUE'   
    INNER JOIN
        lec_share.v_rel_webshop_currency_1 WC_REL
        ON
            FACT_PPS.WSHOP_CD = WC_REL.WSHOP_CD
            AND WC_REL.DWH_VALID_FG
    INNER JOIN
        lec_share.v_fact_currency_exchange_rate_1 CER_FACT
        ON
            WC_REL.CURR_CD = CER_FACT.FROM_CURR_CD
            AND DATE(FACT_PPS.ACTIVE_FROM_TMSP) BETWEEN CER_FACT.ACTIVE_FROM_DT AND CER_FACT.ACTIVE_TO_DT 
    INNER JOIN
        lec_share.v_dim_currency_exchange_rate_type_1 CERT_DIM
        ON
            CERT_DIM.CURR_EXCHANGE_RATE_TYPE_CD = CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD
            AND CERT_DIM.IS_GENERAL_USED_FG
    WHERE
        CER_FACT.TO_CURR_CD = 'EUR'
)


SELECT
     CASE WHEN AGG_PSD.WSHOP_CD = '' THEN '-1' ELSE IFNULL(AGG_PSD.WSHOP_CD, '-1') END AS WSHOP_CD
    ,IFNULL(AGG_PSD.PROMO_ID, '-1') AS PROMO_ID
    ,IFNULL(AGG_PSD.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,AGG_PSD.CUST_ORDER_DT AS CUST_ORDER_DT
    ,AGG_PSD.PROMO_START_DT AS PROMO_START_DT
    ,AGG_PSD.PROMO_SALE_START_DT AS PROMO_SALE_START_DT
    ,AGG_PSD.IS_SPECIAL_ANALYSIS_FG AS IS_SPECIAL_ANALYSIS_FG
    ,CASE
        WHEN AGG_PSD.IS_SPECIAL_ANALYSIS_FG = TRUE THEN '1'
        WHEN AGG_PSD.IS_SPECIAL_ANALYSIS_FG = FALSE THEN '0'
        ELSE '-1' END
     AS IS_SPECIAL_ANALYSIS_CD -- the field IS_SPECIAL_ANALYSIS_FG (a boolean) currently contains many nulls, which can not be fixed quickly in ETL. we use this field in MSTR instead so that joining on this field is possible.
    ,CASE WHEN AGG_PSD.CURR_CD = '' THEN '-1' ELSE IFNULL(AGG_PSD.CURR_CD, '-1') END AS CURR_CD
    ,AGG_PSD.PROD_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS PROD_PRICE_NET_EUR_VAL
    ,AGG_PSD.PROD_PRICE_NET_LOCAL_VAL AS PROD_PRICE_NET_LOCAL_VAL
    ,AGG_PSD.COGS_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS COGS_PRICE_NET_EUR_VAL
    ,AGG_PSD.COGS_PRICE_NET_LOCAL_VAL AS COGS_PRICE_NET_LOCAL_VAL
    ,IFF(AGG_PSD.PROD_QTY = 0, NULL, AGG_PSD.PROD_QTY) AS PROD_QTY -- MSTR divides by this number, so it should not be zero
    ,AGG_PSD.CANCEL_PROD_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS CANCEL_PROD_PRICE_NET_EUR_VAL
    ,AGG_PSD.CANCEL_PROD_PRICE_NET_LOCAL_VAL AS CANCEL_PROD_PRICE_NET_LOCAL_VAL
    ,AGG_PSD.CANCEL_PROD_QTY AS CANCEL_PROD_QTY
    ,AGG_PSD.RETURN_PROD_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_PRICE_NET_EUR_VAL
    ,AGG_PSD.RETURN_PROD_PRICE_NET_LOCAL_VAL AS RETURN_PROD_PRICE_NET_LOCAL_VAL
    ,AGG_PSD.RETURN_PROD_QTY AS RETURN_PROD_QTY
    ,AGG_PSD.TOTAL_PROD_PRICE_NET_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS TOTAL_PROD_PRICE_NET_EUR_VAL
    ,AGG_PSD.TOTAL_PROD_PRICE_NET_LOCAL_VAL AS TOTAL_PROD_PRICE_NET_LOCAL_VAL
    ,AGG_PSD.TOTAL_PROD_QTY AS TOTAL_PROD_QTY
    ,AGG_PSD.PROD_PRICE_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS PROD_PRICE_GROSS_EUR_VAL
    ,AGG_PSD.PROD_PRICE_GROSS_LOCAL_VAL AS PROD_PRICE_GROSS_LOCAL_VAL
    ,AGG_PSD.CANCEL_PROD_PRICE_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS CANCEL_PROD_PRICE_GROSS_EUR_VAL
    ,AGG_PSD.CANCEL_PROD_PRICE_GROSS_LOCAL_VAL AS CANCEL_PROD_PRICE_GROSS_LOCAL_VAL
    ,AGG_PSD.RETURN_PROD_PRICE_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS RETURN_PROD_PRICE_GROSS_EUR_VAL
    ,AGG_PSD.RETURN_PROD_PRICE_GROSS_LOCAL_VAL AS RETURN_PROD_PRICE_GROSS_LOCAL_VAL
    ,AGG_PSD.TOTAL_PROD_PRICE_GROSS_LOCAL_VAL / CER_FACT.EXCHANGE_RATE AS TOTAL_PROD_PRICE_GROSS_EUR_VAL
    ,AGG_PSD.TOTAL_PROD_PRICE_GROSS_LOCAL_VAL AS TOTAL_PROD_PRICE_GROSS_LOCAL_VAL 
    ,IFNULL(AGG_PSD.PROMO_SALE_CLUSTER_CD, '-1') AS PROMO_SALE_CLUSTER_CD
    ,IFNULL(MAX(AGG_PSD.PROMO_SALE_CLUSTER_CD) OVER (PARTITION BY AGG_PSD.WSHOP_CD, AGG_PSD.PROMO_START_DT, DIM_PV.PROD_SID), '-1') AS MAX_SALES_CLUSTER_CD
    ,AGG_PSD.PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,IS_AFTER_CANCELLATION_FG AS IS_AFTER_CANCELLATION_FG

    -- if the AKP is set for this product/wshop, use the AKP. if it is not set, use the VKP.
    ,COALESCE(FACT_PPC_AKP.PRICE_TYPE_CD, FACT_PPC_VKP.PRICE_TYPE_CD) AS PRICE_TYPE_CD
    ,COALESCE(FACT_PPC_AKP.PRICE_GROUP_CD, FACT_PPC_VKP.PRICE_GROUP_CD) AS PRICE_GROUP_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', COALESCE(FACT_PPC_AKP.ACTIVE_FROM_TMSP, FACT_PPC_VKP.ACTIVE_FROM_TMSP))::TIMESTAMP_NTZ AS PPC_ACTIVE_FROM_TMSP
    ,CONVERT_TIMEZONE('Europe/Berlin', COALESCE(FACT_PPC_AKP.ACTIVE_TO_TMSP, FACT_PPC_VKP.ACTIVE_TO_TMSP))::TIMESTAMP_NTZ AS PPC_ACTIVE_TO_TMSP
    ,COALESCE(FACT_PPC_AKP.CURR_CD, FACT_PPC_VKP.CURR_CD) AS PPC_CURR_CD
    ,COALESCE(FACT_PPC_AKP.PRICE_EUR_VAL, FACT_PPC_VKP.PRICE_EUR_VAL) AS PPC_PRICE_EUR_VAL
    ,COALESCE(FACT_PPC_AKP.PRICE_LOCAL_VAL, FACT_PPC_VKP.PRICE_LOCAL_VAL) AS PPC_PRICE_LOCAL_VAL
    -- remove this section once MSTR has been remapped to use fields without AKP in the name
    ,CONVERT_TIMEZONE('Europe/Berlin', COALESCE(FACT_PPC_AKP.ACTIVE_FROM_TMSP, FACT_PPC_VKP.ACTIVE_FROM_TMSP))::TIMESTAMP_NTZ AS AKP_ACTIVE_FROM_TMSP
    ,CONVERT_TIMEZONE('Europe/Berlin', COALESCE(FACT_PPC_AKP.ACTIVE_TO_TMSP, FACT_PPC_VKP.ACTIVE_TO_TMSP))::TIMESTAMP_NTZ AS AKP_ACTIVE_TO_TMSP
    ,COALESCE(FACT_PPC_AKP.CURR_CD, FACT_PPC_VKP.CURR_CD) AS AKP_CURR_CD
    ,COALESCE(FACT_PPC_AKP.PRICE_EUR_VAL, FACT_PPC_VKP.PRICE_EUR_VAL) AS AKP_PRICE_EUR_VAL
    ,COALESCE(FACT_PPC_AKP.PRICE_LOCAL_VAL, FACT_PPC_VKP.PRICE_LOCAL_VAL) AS AKP_PRICE_LOCAL_VAL
    -- end section
    ,COALESCE(FACT_PPC_AKP.PRICE_CHANGE_REASON_CD, FACT_PPC_VKP.PRICE_CHANGE_REASON_CD) AS PRICE_CHANGE_REASON_CD

    --add EKP
    ,CONVERT_TIMEZONE('Europe/Berlin', COALESCE(FACT_PPS_EKP.ACTIVE_FROM_TMSP, FACT_PPS_EKP.ACTIVE_FROM_TMSP))::TIMESTAMP_NTZ AS EKP_ACTIVE_FROM_TMSP
    ,CONVERT_TIMEZONE('Europe/Berlin', COALESCE(FACT_PPS_EKP.ACTIVE_TO_TMSP, FACT_PPS_EKP.ACTIVE_TO_TMSP))::TIMESTAMP_NTZ AS EKP_ACTIVE_TO_TMSP
    ,COALESCE(FACT_PPS_EKP.CURR_CD, FACT_PPS_EKP.CURR_CD) AS EKP_CURR_CD
    ,COALESCE(FACT_PPS_EKP.PRICE_EUR_VAL, FACT_PPS_EKP.PRICE_EUR_VAL) AS EKP_PRICE_EUR_VAL
    ,COALESCE(FACT_PPS_EKP.PRICE_LOCAL_VAL, FACT_PPS_EKP.PRICE_LOCAL_VAL) AS EKP_PRICE_LOCAL_VAL
    --end section

    ,CASE WHEN FACT_PA.AVAIL_LVL_CD = '' THEN '-1' ELSE IFNULL(FACT_PA.AVAIL_LVL_CD, '-1') END AS AVAIL_LVL   --they could be deleted if not used from this view
	,COALESCE(MAX(FACT_PA.AVAIL_LVL_CD) OVER (PARTITION BY FACT_PA.WSHOP_CD, FACT_PA.CAL_DT, DIM_PV.PROD_SID), '-1') AS AVAIL_LVL_PRODUCT  --they could be deleted if not used from this view
    ,CASE WHEN AGG_PSD.PROD_ORDERABLE_LVL_CD = '' THEN '-1' ELSE IFNULL(AGG_PSD.PROD_ORDERABLE_LVL_CD,'-1') END AS PROD_ORDERABLE_LVL_CD --new field
    ,COALESCE(MAX(AGG_PSD.PROD_ORDERABLE_LVL_CD) OVER (PARTITION BY AGG_PSD.WSHOP_CD, AGG_PSD.CUST_ORDER_DT, DIM_PV.PROD_SID),'-1') AS PROD_ORDERABLE_LVL_CD_PRODUCT --new field
    
    ,AGG_SP.FIRST_WEEK_START_DT AS FIRST_WEEK_START_DT
    ,CASE 
        WHEN DATEDIFF(DD, AGG_PSD.PROMO_SALE_START_DT, CURRENT_DATE) <= 0 AND CURRENT_DATE < AGG_SP.FIRST_WEEK_START_DT THEN 1
        WHEN DATEDIFF(DD, AGG_PSD.PROMO_SALE_START_DT, CURRENT_DATE) <= 2 AND CURRENT_DATE < AGG_SP.FIRST_WEEK_START_DT THEN 2
        WHEN DATEDIFF(DD, AGG_PSD.PROMO_SALE_START_DT, CURRENT_DATE) <= 6 AND CURRENT_DATE < AGG_SP.FIRST_WEEK_START_DT THEN 3
		WHEN DATEDIFF(DD, AGG_PSD.PROMO_SALE_START_DT, CURRENT_DATE) <= 7 AND CURRENT_DATE < AGG_SP.FIRST_WEEK_START_DT THEN 4
		WHEN DATEDIFF(DD, AGG_PSD.PROMO_SALE_START_DT, CURRENT_DATE) <= 9 AND CURRENT_DATE < AGG_SP.FIRST_WEEK_START_DT THEN 5
		WHEN DATEDIFF(DD, AGG_PSD.PROMO_SALE_START_DT, CURRENT_DATE) <= 13 AND CURRENT_DATE < AGG_SP.FIRST_WEEK_START_DT THEN 6
        WHEN CURRENT_DATE < FIRST_WEEK_START_DT THEN  7
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 1 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 8
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 3 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 9
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 7 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 10 
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 14 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 11
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 21 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 12 
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 28 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 13
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 35 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 14
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 42 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 15 
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 49 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 16 
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 56 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 17
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 63 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 18
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 70 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 19
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 77 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 20
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 84 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 21
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 126 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 22
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 182 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 23
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 224 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 24
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 273 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 25          
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 364 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 26 
        WHEN DATEDIFF(DD, AGG_SP.FIRST_WEEK_START_DT, CURRENT_DATE) < 540 AND CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT THEN 999
        WHEN CURRENT_DATE >= AGG_SP.FIRST_WEEK_START_DT AND CURRENT_DATE <= LAST_DAY(AGG_PSD.PROMO_SALE_START_DT+730, 'year') THEN 9999
        ELSE NULL 
     END AS CURRENT_PROMO_SALE_CLUSTER_CD
FROM
    CTE_PSD AGG_PSD
INNER JOIN
    lec_share.v_fact_currency_exchange_rate_1 CER_FACT
    ON
        AGG_PSD.CURR_CD = CER_FACT.FROM_CURR_CD
        AND AGG_PSD.PROMO_START_DT BETWEEN CER_FACT.ACTIVE_FROM_DT AND CER_FACT.ACTIVE_TO_DT 
INNER JOIN
    lec_share.v_dim_currency_exchange_rate_type_1 CERT_DIM
    ON
        CERT_DIM.CURR_EXCHANGE_RATE_TYPE_CD = CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD
        AND CERT_DIM.IS_GENERAL_USED_FG
LEFT JOIN
    CTE_PPC FACT_PPC_AKP
    ON AGG_PSD.PROD_VARIANT_SID = FACT_PPC_AKP.PROD_VARIANT_SID
    AND AGG_PSD.WSHOP_CD = FACT_PPC_AKP.WSHOP_CD
    AND TO_TIMESTAMP( CONCAT(AGG_PSD.PROMO_START_DT, ' 23:59:59'),'YYYY-MM_1-DD HH24:MI:SS' ) BETWEEN FACT_PPC_AKP.ACTIVE_FROM_TMSP AND FACT_PPC_AKP.ACTIVE_TO_TMSP
    AND FACT_PPC_AKP.PRICE_TYPE_CD = 'AKP'
LEFT JOIN
    CTE_PPC FACT_PPC_VKP
    ON AGG_PSD.PROD_VARIANT_SID = FACT_PPC_VKP.PROD_VARIANT_SID
    AND AGG_PSD.WSHOP_CD = FACT_PPC_VKP.WSHOP_CD
    AND TO_TIMESTAMP( CONCAT(AGG_PSD.PROMO_START_DT, ' 23:59:59'),'YYYY-MM_1-DD HH24:MI:SS' ) BETWEEN FACT_PPC_VKP.ACTIVE_FROM_TMSP AND FACT_PPC_VKP.ACTIVE_TO_TMSP
    AND FACT_PPC_VKP.PRICE_TYPE_CD = 'VKP'
LEFT JOIN
    CTE_PPS FACT_PPS_EKP
    ON AGG_PSD.PROD_VARIANT_SID = FACT_PPS_EKP.PROD_VARIANT_SID
    AND AGG_PSD.WSHOP_CD = FACT_PPS_EKP.WSHOP_CD
    AND TO_TIMESTAMP( CONCAT(AGG_PSD.PROMO_START_DT, ' 23:59:59'),'YYYY-MM_1-DD HH24:MI:SS' ) BETWEEN FACT_PPS_EKP.ACTIVE_FROM_TMSP AND FACT_PPS_EKP.ACTIVE_TO_TMSP
