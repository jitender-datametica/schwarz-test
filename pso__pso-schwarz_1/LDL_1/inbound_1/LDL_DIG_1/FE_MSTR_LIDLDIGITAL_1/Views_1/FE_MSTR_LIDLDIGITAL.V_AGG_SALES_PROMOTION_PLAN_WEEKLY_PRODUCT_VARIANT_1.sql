CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_AGG_SALES_PROMOTION_PLAN_WEEKLY_PRODUCT_VARIANT_1  
AS SELECT
     PLAN.WSHOP_CD AS WSHOP_CD
    ,PLAN.PROD_SID AS PROD_SID
    ,PLAN.PROMO_ID AS PROMO_ID
    ,PLAN.PROMO_DUR_WEEK_CNT AS PROMO_DUR_WEEK_CNT
    ,PLAN.PROMO_START_DT AS PROMO_START_DT
    ,PLAN.PROMO_SALE_START_DT AS PROMO_SALE_START_DT
    ,PLAN.SUPPLIER_ORDER_QTY AS SUPPLIER_ORDER_QTY
    ,PLAN.TGT_PROD_SALE_QTY AS TGT_PROD_SALE_QTY
    ,PLAN.ESTIMATED_INIT_PROMO_STOCK AS ESTIMATED_INIT_PROMO_STOCK
    ,PLAN.CURRENT_PROMO_WEEK_NR AS CURRENT_PROMO_WEEK_NR
    ,PLAN.WEEK_NR AS WEEK_NR
    ,PLAN.PROMO_SALE_CLUSTER_CD AS PROMO_SALE_CLUSTER_CD
    ,PLAN.TGT_SALE_PCT AS TGT_SALE_PCT
    ,PLAN.CUM_TGT_SALE_PCT AS CUM_TGT_SALE_PCT
    ,PLAN.SALE_PROMO_PHASE_CD AS SALE_PROMO_PHASE_CD
    ,STOCK.PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,STOCK.STOCK_DISTRIBUTION_PCT AS STOCK_DISTRIBUTION_PCT
    ,PLAN.IS_CURRENT_FG AS IS_CURRENT_FG
    ,PLAN_AMC_QTY*STOCK.STOCK_DISTRIBUTION_PCT AS PLAN_AMC_QTY_VARIANT
    ,CASE WHEN PLAN.SUPPLIER_ORDER_QTY > PLAN.TGT_PROD_SALE_QTY 
            THEN PLAN.SUPPLIER_ORDER_QTY * STOCK.STOCK_DISTRIBUTION_PCT
            ELSE PLAN.TGT_PROD_SALE_QTY * STOCK.STOCK_DISTRIBUTION_PCT
            END AS PLAN_AMC_DENOMINATOR_PERC_VARIANT
    ,PLAN_AMC_QTY_CUM * STOCK.STOCK_DISTRIBUTION_PCT AS PLAN_AMC_QTY_CUM_VARIANT
    ,CASE WHEN PLAN.SUPPLIER_ORDER_QTY > PLAN.TGT_PROD_SALE_QTY 
            THEN PLAN.SUPPLIER_ORDER_QTY * STOCK.STOCK_DISTRIBUTION_PCT
            ELSE PLAN.TGT_PROD_SALE_QTY * STOCK.STOCK_DISTRIBUTION_PCT
            END AS PLAN_AMC_CUM_DENOMINATOR_PERC_VARIANT
    ,PLAN_AB_QTY * STOCK.STOCK_DISTRIBUTION_PCT AS PLAN_AB_QTY_VARIANT
    ,CASE WHEN PLAN.ESTIMATED_INIT_PROMO_STOCK > PLAN.TGT_PROD_SALE_QTY
            THEN PLAN.ESTIMATED_INIT_PROMO_STOCK * STOCK.STOCK_DISTRIBUTION_PCT
            ELSE PLAN.TGT_PROD_SALE_QTY * STOCK.STOCK_DISTRIBUTION_PCT
            END AS PLAN_AB_DENOMINATOR_PERC_VARIANT
    ,PLAN_AB_QTY_CUM * STOCK.STOCK_DISTRIBUTION_PCT AS PLAN_AB_QTY_CUM_VARIANT
    ,CASE WHEN PLAN.ESTIMATED_INIT_PROMO_STOCK > PLAN.TGT_PROD_SALE_QTY
            THEN PLAN.ESTIMATED_INIT_PROMO_STOCK * STOCK.STOCK_DISTRIBUTION_PCT
            ELSE PLAN.TGT_PROD_SALE_QTY * STOCK.STOCK_DISTRIBUTION_PCT
            END AS PLAN_AB_CUM_DENOMINATOR_PERC_VARIANT
    ,CASE WHEN WEEK_NR = MAX(PLAN.WEEK_NR) OVER (PARTITION BY PLAN.WSHOP_CD, STOCK.PROD_VARIANT_SID, PLAN.PROMO_START_DT, PLAN.PROMO_SALE_CLUSTER_CD)
            THEN 1
            ELSE 0
            END AS VALID_WEEK_NR_FOR_CLUSTERS
FROM
    lec_share.v_agg_estimated_initial_promotion_stock_core_view_1 STOCK
JOIN
    lec_share.v_agg_sales_promotion_plan_weekly_core_view_1 PLAN
    ON STOCK.PROMO_ID = PLAN.PROMO_ID
;
