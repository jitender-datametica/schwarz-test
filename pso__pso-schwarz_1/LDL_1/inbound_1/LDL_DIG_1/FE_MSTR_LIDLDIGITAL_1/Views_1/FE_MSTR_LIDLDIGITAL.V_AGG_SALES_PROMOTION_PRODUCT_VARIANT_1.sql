CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_AGG_SALES_PROMOTION_PRODUCT_VARIANT_1
AS SELECT 
     CASE WHEN B.WSHOP_CD = '' THEN '-1' ELSE IFNULL(B.WSHOP_CD, '-1') END AS WSHOP_CD
    ,IFNULL(B.PROD_SID, -1) AS PROD_SID
    ,A.PROMO_START_DT AS PROMO_START_DT
    ,FLOOR(DATEDIFF(DAY, A.PROMO_START_DT, CURRENT_DATE()) / 7) AS PASSED_SALE_WEEKS
    ,B.PROMO_SALE_START_DT AS PROMO_SALE_START_DT
    ,CASE WHEN A.SALE_PROMO_TYPE_CD = '' THEN '-1' ELSE IFNULL(A.SALE_PROMO_TYPE_CD, '-1') END AS SALE_PROMO_TYPE_CD
    ,A.IS_REPEATED_FG AS IS_REPEATED_FG
    ,A.PROMO_DUR_WEEK_CNT AS PROMO_DUR_WEEK_CNT
    ,A.FIRST_WEEK_START_DT AS FIRST_WEEK_START_DT
    ,A.ANALYSIS_START_DT AS ANALYSIS_START_DT
    ,A.ANALYSIS_END_DT AS ANALYSIS_END_DT
    ,CASE WHEN A.SALE_PROMO_STATUS_CD = '' THEN '-1' ELSE IFNULL(A.SALE_PROMO_STATUS_CD, '-1') END AS SALE_PROMO_STATUS_CD
    ,B.PROMO_ID AS PROMO_ID
    ,A.TGT_PROD_RECEIVE_CY_WEEK AS TGT_PROD_RECEIVE_CY_WEEK
    ,A.FIRST_DELIVERY_CY_WEEK AS FIRST_DELIVERY_CY_WEEK
    ,A.SUPPLIER_ORDER_QTY AS SUPPLIER_ORDER_QTY
    ,A.TGT_PROD_SALE_QTY AS TGT_PROD_SALE_QTY
    ,A.PROMO_NR AS PROMO_NR
    ,A.PROMO_DESCR AS PROMO_DESCR
    ,A.AMC_IAN_NR AS AMC_IAN_NR
    ,A.IS_TV_PROMO_FG AS IS_TV_PROMO_FG
    ,A.RETURN_COND_DESCR AS RETURN_COND_DESCR
    ,A.IS_CATALOG_PROMO_FG AS IS_CATALOG_PROMO_FG
    ,IFNULL(B.PROD_VARIANT_SID, -1) AS PROD_VARIANT_SID
    ,A.TGT_PROD_SALE_QTY * B.STOCK_DISTRIBUTION_PCT AS TGT_PROD_SALE_QTY_VARIANT
    ,A.SUPPLIER_ORDER_QTY * B.STOCK_DISTRIBUTION_PCT AS SUPPLIER_ORDER_QTY_VARIANT
    ,IFNULL(B.STOCK_DISTRIBUTION_PCT, 0) AS STOCK_DISTRIBUTION_PCT
FROM
    lec_share.v_agg_sales_promotion_core_view_1 A
INNER JOIN
    lec_share.v_agg_estimated_initial_promotion_stock_core_view_1 B
    ON      A.PROD_SID = B.PROD_SID
        AND A.PROMO_SALE_START_DT = B.PROMO_SALE_START_DT
        AND A.WSHOP_CD = B.WSHOP_CD
        AND A.PROMO_ID = B.PROMO_ID
;
