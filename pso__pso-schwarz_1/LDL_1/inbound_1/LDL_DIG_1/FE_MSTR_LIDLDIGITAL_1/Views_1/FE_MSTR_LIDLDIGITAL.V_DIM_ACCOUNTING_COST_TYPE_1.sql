CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_ACCOUNTING_COST_TYPE_1
AS SELECT
     TRIM(ACCT_COST_TYPE_CD) AS ACCT_COST_TYPE_CD -- TRIM currently required because base table has spaces in ACCT_COST_TYPE_CD
    ,ACCT_COST_TYPE_NAME_EN AS ACCT_COST_TYPE_NAME_EN
    ,ACCT_COST_TYPE_NAME_DE AS ACCT_COST_TYPE_NAME_DE
FROM 
    lec_share.v_dim_accounting_cost_type_1
UNION ALL
    SELECT '-1', '', ''
;
