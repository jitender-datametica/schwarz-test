CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CAL_BUSINESS_YEAR_1
AS SELECT
     BUS_YEAR AS BUS_YEAR
    ,BUS_YEAR_BEGIN_MONTH AS BUS_YEAR_BEGIN_MONTH
    ,BUS_YEAR_END_MONTH AS BUS_YEAR_END_MONTH
    ,BUS_YEAR_BEGIN_DT AS BUS_YEAR_BEGIN_DT
    ,BUS_YEAR_END_DT AS BUS_YEAR_END_DT
    ,BUS_YEAR_WEEK_CNT AS BUS_YEAR_WEEK_CNT
    ,BUS_YEAR_DAY_CNT AS BUS_YEAR_DAY_CNT
    ,BUS_YEAR_PREV_1Y AS BUS_YEAR_PREV_1Y
    ,BUS_YEAR_PREV_2Y AS BUS_YEAR_PREV_2Y
    ,BUS_YEAR_PREV_3Y AS BUS_YEAR_PREV_3Y
    ,BUS_YEAR_PREV_4Y AS BUS_YEAR_PREV_4Y
    ,BUS_YEAR_PREV_5Y AS BUS_YEAR_PREV_5Y
    ,BUS_YEAR_OFFSET AS BUS_YEAR_OFFSET
FROM
    lec_share.v_dim_cal_business_year_1
WHERE 
    BUS_YEAR != '-1' -- some date core tables contain a -1 dummy_1 entry, which is removed here so we can add our own dummy_1 value
UNION ALL
    SELECT
         '-1' -- BUS_YEAR
        ,'-1' -- BUS_YEAR_BEGIN_MONTH
        ,'-1' -- BUS_YEAR_END_MONTH
        ,TO_DATE('1900-01-01') -- BUS_YEAR_BEGIN_DT
        ,TO_DATE('1900-01-01') -- BUS_YEAR_END_DT
        ,'0' -- BUS_YEAR_WEEK_CNT
        ,'0' -- BUS_YEAR_DAY_CNT
        ,'-1' -- BUS_YEAR_PREV_1Y
        ,'-1' -- BUS_YEAR_PREV_2Y
        ,'-1' -- BUS_YEAR_PREV_3Y
        ,'-1' -- BUS_YEAR_PREV_4Y
        ,'-1' -- BUS_YEAR_PREV_5Y
        ,'999' -- BUS_YEAR_OFFSET
;