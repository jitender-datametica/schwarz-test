CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CAL_HOUR_1

/**************************************************************************
* CREATED MANUALLY BY SACHIT VINOD
* ON 14.07.2021
* TEMPERORY VIEW TO SERVE AS A LOOKUP TABLE FOR THE HOUR ATTRIBUTE.
* CANDIDATE TO BE CONVERTED TO A TABLE OR  MATERIALISED VIEW
* LAST UPDATE BY LK - 23.10.2023
**************************************************************************/
(
HOUR_OF_DAY
,UPTO_CURRENT_HOUR_IND
,HOUR_RANGE
) AS SELECT DISTINCT
    TM.HOUR_OF_DAY
    ,IFF((HOUR(DATEADD(HOUR,1,CURRENT_TIME()))=0),0,CASE WHEN HOUR(DATEADD(HOUR,1,CURRENT_TIME())) < TM.HOUR_OF_DAY THEN 1 ELSE 0 END) UPTO_CURRENT_HOUR_IND
    ,CONCAT(RIGHT(CONCAT('00',TM.HOUR_24),2),'-',RIGHT(CONCAT('00',TM.HOUR_OF_DAY),2)) HOUR_RANGE
FROM
    lec_share.v_dim_cal_time_1 AS TM
;
