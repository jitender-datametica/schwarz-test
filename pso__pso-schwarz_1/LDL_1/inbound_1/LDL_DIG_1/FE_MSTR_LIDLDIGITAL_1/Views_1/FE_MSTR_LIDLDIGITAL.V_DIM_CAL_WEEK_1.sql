CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CAL_WEEK_1(
	CY_WEEK
	,WEEK_OF_YEAR
	,CY_WEEK_BEGIN_WEEK_PART
	,CY_WEEK_END_WEEK_PART
	,CY_WEEK_BEGIN_DT
	,CY_WEEK_END_DT
	,CY_WEEK_WEEK_PART_CNT
	,CY_WEEK_PREV_1W
	,CY_WEEK_PREV_1Y
	,CY_WEEK_PREV_2Y
	,CY_WEEK_PREV_3Y
	,CY_WEEK_PREV_4Y
	,CY_WEEK_PREV_5Y
	,CY_WEEK_OFFSET
	,CY_WEEK_OFFSET_ARTIKELABVERKAUF
	,CY_WEEK_OFFSET_ARTIKEL_LIVE
	,CY_WEEK_OFFSET_DLZ
	,CY_WEEK_SHORT_NAME
	,CY_WEEK_NAME
) AS SELECT
     CY_WEEK AS CY_WEEK
    ,WEEK_OF_YEAR AS WEEK_OF_YEAR
    ,CY_WEEK_BEGIN_WEEK_PART AS CY_WEEK_BEGIN_WEEK_PART
    ,CY_WEEK_END_WEEK_PART AS CY_WEEK_END_WEEK_PART
    ,CY_WEEK_BEGIN_DT AS CY_WEEK_BEGIN_DT
    ,CY_WEEK_END_DT AS CY_WEEK_END_DT
    ,CY_WEEK_WEEK_PART_CNT AS CY_WEEK_WEEK_PART_CNT
    ,CY_WEEK_PREV_1W AS CY_WEEK_PREV_1W
    ,CY_WEEK_PREV_1Y AS CY_WEEK_PREV_1Y
    ,CY_WEEK_PREV_2Y AS CY_WEEK_PREV_2Y
    ,CY_WEEK_PREV_3Y AS CY_WEEK_PREV_3Y
    ,CY_WEEK_PREV_4Y AS CY_WEEK_PREV_4Y
    ,CY_WEEK_PREV_5Y AS CY_WEEK_PREV_5Y
    ,CY_WEEK_OFFSET AS CY_WEEK_OFFSET
    ,CASE WHEN (CY_WEEK_OFFSET > 8) THEN NULL::NUMBER(38,0)
          WHEN (CY_WEEK_OFFSET >= 0 AND CY_WEEK_OFFSET <= 8) THEN CY_WEEK_OFFSET - 3
          WHEN (CY_WEEK_OFFSET >=-3 AND CY_WEEK_OFFSET <= -1) THEN CY_WEEK_OFFSET + 9
          ELSE CY_WEEK_OFFSET
     END AS CY_WEEK_OFFSET_ARTIKELABVERKAUF -- special order for artikelabverkauf report
	,CASE WHEN (CY_WEEK_OFFSET >= -1 AND CY_WEEK_OFFSET <= 2) THEN CY_WEEK_OFFSET + 200
          WHEN (CY_WEEK_OFFSET > 2) THEN -1 * CY_WEEK_OFFSET + 200
          ELSE CY_WEEK_OFFSET
          END CY_WEEK_OFFSET_ARTIKEL_LIVE -- special order for artikel_1 live report
    ,CASE WHEN (CY_WEEK_OFFSET > 0) THEN -1*CY_WEEK_OFFSET - 100
          ELSE CY_WEEK_OFFSET
     END AS CY_WEEK_OFFSET_DLZ -- special order for dlz report
    ,CY_WEEK_SHORT_NAME AS CY_WEEK_SHORT_NAME
    ,CY_WEEK_NAME AS CY_WEEK_NAME
FROM
    lec_share.v_dim_cal_week_1
WHERE 
    CY_WEEK != '-1' -- some date core tables contain a -1 dummy_1 entry, which is removed here so we can add our own dummy_1 value
UNION ALL
    SELECT
         '-1' -- CY_WEEK
        ,'-1' -- WEEK_OF_YEAR
        ,'0' -- CY_WEEK_BEGIN_WEEK_PART
        ,'0' -- CY_WEEK_END_WEEK_PART
        ,TO_DATE('1900-01-01') -- CY_WEEK_BEGIN_DT
        ,TO_DATE('1900-01-01') -- CY_WEEK_END_DT
        ,'0' -- CY_WEEK_WEEK_PART_CNT
        ,'-1' -- CY_WEEK_PREV_1W
        ,'-1' -- CY_WEEK_PREV_1Y
        ,'-1' -- CY_WEEK_PREV_2Y
        ,'-1' -- CY_WEEK_PREV_3Y
        ,'-1' -- CY_WEEK_PREV_4Y
        ,'-1' -- CY_WEEK_PREV_5Y
        ,'999' -- CY_WEEK_OFFSET
        ,'999' -- CY_WEEK_OFFSET_ARTIKELABVERKAUF
        ,'999' -- CY_WEEK_OFFSET_ARTIKELABVERKAUF_2
        ,'999' -- CY_WEEK_OFFSET_ARTIKEL_LIVE
        ,'' -- CY_WEEK_SHORT_NAME
        ,'' -- CY_WEEK_NAME
;