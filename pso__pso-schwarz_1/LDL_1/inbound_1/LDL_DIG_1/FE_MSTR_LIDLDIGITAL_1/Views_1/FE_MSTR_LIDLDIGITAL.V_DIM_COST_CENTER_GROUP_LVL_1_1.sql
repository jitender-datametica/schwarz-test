CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_COST_CENTER_GROUP_LVL_1_1
AS SELECT
     CC_GROUP_LVL1_NR AS CC_GROUP_LVL1_NR
    ,CASE WHEN CTRL_AREA_CD = '' THEN '-1' ELSE IFNULL(CTRL_AREA_CD, '-1') END AS CTRL_AREA_CD
    ,CC_GROUP_LVL1_NAME_EN AS CC_GROUP_LVL1_NAME_EN
    ,CC_GROUP_LVL1_NAME_DE AS CC_GROUP_LVL1_NAME_DE
FROM 
    lec_share.v_dim_cost_center_group_lvl_1_1
UNION ALL
    SELECT '-1', '-1', '', ''
;
