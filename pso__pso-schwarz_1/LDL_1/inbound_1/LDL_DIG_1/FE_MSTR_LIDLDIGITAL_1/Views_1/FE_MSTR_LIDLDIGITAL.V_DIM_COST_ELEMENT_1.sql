CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_COST_ELEMENT_1
AS SELECT
    FA.ACCT_NR AS ACCT_NR
    ,COALESCE(CE.CTRL_AREA_CD,'-1') AS CTRL_AREA_CD
    ,COALESCE(CE.CE_VALID_FROM_DT,TO_DATE('1900-01-01')) AS CE_VALID_FROM_DT
    ,COALESCE(CE.CE_VALID_TO_DT,TO_DATE('1900-01-01')) AS CE_VALID_TO_DT
    ,COALESCE(CE.CHART_OF_ACCOUNTS_CD,'-1') AS CHART_OF_ACCOUNTS_CD
    ,COALESCE(CE.SHORT_NAME_EN, FA.SHORT_NAME_EN) AS SHORT_NAME_EN
    ,COALESCE(CE.LONG_NAME_EN, FA.LONG_NAME_EN) AS LONG_NAME_EN
    ,COALESCE(CE.SHORT_NAME_DE, FA.SHORT_NAME_DE) AS SHORT_NAME_DE
    ,COALESCE(CE.LONG_NAME_DE, FA.LONG_NAME_DE) AS LONG_NAME_DE
    ,COALESCE(CE_GROUP_LVL3_NR,'-1') AS CE_GROUP_LVL3_NR
    ,COALESCE(CE_GROUP_LVL3_NAME_EN,'') AS CE_GROUP_LVL3_NAME_EN
    ,COALESCE(CE_GROUP_LVL3_NAME_DE,'') AS CE_GROUP_LVL3_NAME_DE
    ,COALESCE(CE_GROUP_LVL2_NR,'-1') AS CE_GROUP_LVL2_NR
    ,COALESCE(CE_GROUP_LVL2_NAME_EN,'') AS CE_GROUP_LVL2_NAME_EN
    ,COALESCE(CE_GROUP_LVL2_NAME_DE,'') AS CE_GROUP_LVL2_NAME_DE
    ,COALESCE(CE_GROUP_LVL1_NR,'-1') AS CE_GROUP_LVL1_NR
    ,COALESCE(CE_GROUP_LVL1_NAME_EN,'') AS CE_GROUP_LVL1_NAME_EN
    ,COALESCE(CE_GROUP_LVL1_NAME_DE,'') AS CE_GROUP_LVL1_NAME_DE
FROM 
    (
        SELECT 
          
             ACCT_NR
            ,MAX(SHORT_NAME_EN) AS SHORT_NAME_EN
            ,MAX(LONG_NAME_EN) AS LONG_NAME_EN
            ,MAX(SHORT_NAME_DE) AS SHORT_NAME_DE
            ,MAX(LONG_NAME_DE) AS LONG_NAME_DE
        FROM lec_share.v_dim_financial_account_1
        WHERE DWH_VALID_FG = TRUE
            AND CHART_OF_ACCOUNTS_CD = 'LDI1'
          GROUP BY ACCT_NR
      
    ) FA
LEFT OUTER JOIN 
    (
        SELECT * 
        FROM lec_share.v_dim_cost_element_1 CE
        WHERE CE.CHART_OF_ACCOUNTS_CD = 'LDI1'

    ) CE
	ON FA.ACCT_NR = CE.ACCT_NR ;