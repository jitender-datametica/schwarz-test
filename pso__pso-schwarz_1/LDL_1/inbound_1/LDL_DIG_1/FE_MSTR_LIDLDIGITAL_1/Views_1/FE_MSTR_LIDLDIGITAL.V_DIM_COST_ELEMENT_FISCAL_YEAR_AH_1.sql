CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_COST_ELEMENT_FISCAL_YEAR_AH_1
AS SELECT
    IFNULL( NULLIF( ACCT_NR, '' ), '-1' ) AS ACCT_NR
	,IFNULL( NULLIF( CTRL_AREA_CD, '' ), '-1' ) AS CTRL_AREA_CD
	,IFNULL( FISCAL_YEAR, '1900' ) AS FISCAL_YEAR
	,IFNULL( NULLIF( CE_GROUP_LVL1_NR, '' ), '-1' ) AS CE_GROUP_LVL1_NR
	,CE_GROUP_LVL1_NAME_EN AS CE_GROUP_LVL1_NAME_EN
	,CE_GROUP_LVL1_NAME_DE AS CE_GROUP_LVL1_NAME_DE
    ,IFNULL( NULLIF( CE_GROUP_LVL2_NR, '' ), '-1' ) AS CE_GROUP_LVL2_NR
    ,CE_GROUP_LVL2_NAME_EN AS CE_GROUP_LVL2_NAME_EN
    ,CE_GROUP_LVL2_NAME_DE AS CE_GROUP_LVL2_NAME_DE
    ,IFNULL( NULLIF( CE_GROUP_LVL3_NR, '' ), '-1' ) AS CE_GROUP_LVL3_NR
    ,CE_GROUP_LVL3_NAME_EN AS CE_GROUP_LVL3_NAME_EN
    ,CE_GROUP_LVL3_NAME_DE AS CE_GROUP_LVL3_NAME_DE
    ,IFNULL( NULLIF( CHART_OF_ACCOUNTS_CD, '' ), '-1' ) AS CHART_OF_ACCOUNTS_CD
    ,SHORT_NAME_EN AS SHORT_NAME_EN
    ,LONG_NAME_EN AS LONG_NAME_EN
    ,SHORT_NAME_DE AS SHORT_NAME_DE
    ,LONG_NAME_DE AS LONG_NAME_DE
    ,DWH_CREATED_TMSP AS DWH_CREATED_TMSP
    ,DWH_UPDATED_TMSP AS DWH_UPDATED_TMSP
    ,DWH_SRC_FILE_NAME AS DWH_SRC_FILE_NAME
    ,SRC_FILE_TMSP AS SRC_FILE_TMSP
FROM
    lec_share.v_dim_cost_element_fiscal_year_ah_1
    
UNION ALL
    SELECT
         '-1' -- ACCT_NR
        ,'-1' -- CTRL_AREA_CD
        ,'1900' --  FISCAL_YEAR
        ,'-1' -- CE_GROUP_LVL1_NR
        ,'' -- CE_GROUP_LVL1_NAME_EN
        ,'' -- CE_GROUP_LVL1_NAME_DE
        ,'-1' -- CE_GROUP_LVL2_NR
        ,'' -- , -- CE_GROUP_LVL2_NAME_EN
        ,'' -- CE_GROUP_LVL2_NAME_DE
        ,'-1' -- CE_GROUP_LVL3_NR
        ,'' -- CE_GROUP_LVL3_NAME_EN
        ,'' -- CE_GROUP_LVL3_NAME_DE
        ,'-1' -- CHART_OF_ACCOUNTS_CD
        ,'' -- SHORT_NAME_EN
        ,'' -- LONG_NAME_EN
        ,'' -- SHORT_NAME_DE
        ,'' -- LONG_NAME_DE
        ,CAST('1900-01-01' AS TIMESTAMP_LTZ) -- DWH_CREATED_TMSP
        ,CAST('1900-01-01' AS TIMESTAMP_LTZ) -- DWH_UPDATED_TMSP
        ,'' -- DWH_SRC_FILE_NAME
        ,CAST('1900-01-01' AS TIMESTAMP_LTZ) -- SRC_FILE_TMSP
;
