CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CUSTOMER_1
AS SELECT
     IFNULL(CUST_SID, '-1') AS CUST_SID
    ,CUST_NR AS CUST_NR
    ,CUST_SALUTATION AS CUST_SALUTATION
    ,CUST_FIRST_NAME AS CUST_FIRST_NAME
    ,CUST_LAST_NAME AS CUST_LAST_NAME
    ,CUST_BIRTH_DT AS CUST_BIRTH_DT
    ,FLOOR(DATEDIFF(DAY, CUST_BIRTH_DT, CURRENT_DATE()) / 365.25) AS CUST_AGE
    ,CASE WHEN CUST_TYPE_CD = '' THEN '-1' ELSE IFNULL(CUST_TYPE_CD, '-1') END AS CUST_TYPE_CD
    ,CASE WHEN CUST_ORG_TYPE_CD = '' THEN '-1' ELSE IFNULL(CUST_ORG_TYPE_CD, '-1') END AS CUST_ORG_TYPE_CD
    ,CUST_COMPANY_NAME AS CUST_COMPANY_NAME
    ,IFNULL(CUST_BILLING_ADDR_SID, '-1') AS CUST_BILLING_ADDR_SID
    ,PHONE_NR AS PHONE_NR
    ,EMAIL AS EMAIL
    ,CASE WHEN CUST_BLOCKED_REASON_CD = '' THEN '-1' ELSE IFNULL(CUST_BLOCKED_REASON_CD, '-1') END AS CUST_BLOCKED_REASON_CD
    ,CASE WHEN CUST_LAN_CD = '' THEN '-1' ELSE IFNULL(CUST_LAN_CD, '-1') END AS CUST_LAN_CD
    ,CUST_SSO_ID AS CUST_SSO_ID
    ,CUST_CREATION_DT AS CUST_CREATION_DT
    ,CUST_REGISTRATION_DT AS CUST_REGISTRATION_DT
    ,CUST_ACCT_ID AS CUST_ACCT_ID
    ,IS_CUST_ADV_BLOCKED_FG AS IS_CUST_ADV_BLOCKED_FG
    ,EMAIL_PCU AS EMAIL_PCU
    ,CUST_SSO_ID_PCU AS CUST_SSO_ID_PCU
    ,IS_CUST_BLOCKED_PCU_FG AS IS_CUST_BLOCKED_PCU_FG
    ,IS_CUST_DELETED_PCU_FG AS IS_CUST_DELETED_PCU_FG 
FROM
    lec_share.v_dim_customer_1
WHERE
    DWH_VALID_FG = TRUE
UNION ALL
    SELECT
         '-1' -- CUST_SID
        ,'' -- CUST_NR
        ,'' -- CUST_SALUTATION
        ,'' -- CUST_FIRST_NAME
        ,'' -- CUST_LAST_NAME
        ,TO_DATE('1900-01-01') -- CUST_BIRTH_DT
        ,'0' -- CUST_AGE
        ,'-1' -- CUST_TYPE_CD
        ,'-1' -- CUST_ORG_TYPE_CD
        ,'' -- CUST_COMPANY_NAME
        ,'-1' -- CUST_BILLING_ADDR_SID
        ,'' -- PHONE_NR
        ,'' -- EMAIL
        ,'-1' -- CUST_BLOCKED_REASON_CD
        ,'-1' -- CUST_LAN_CD
        ,'-1' -- CUST_SSO_ID
        ,TO_DATE('1900-01-01') -- CUST_CREATION_DT
        ,TO_DATE('1900-01-01') -- CUST_REGISTRATION_DT
        ,'-1' -- CUST_ACCT_ID
        ,'FALSE' -- IS_CUST_ADV_BLOCKED_FG
        ,'' -- EMAIL_PCU
        ,'' -- CUST_SSO_ID_PCU
        ,'FALSE' -- IS_CUST_BLOCKED_PCU_FG
        ,'FALSE' -- IS_CUST_DELETED_PCU_FG
;
