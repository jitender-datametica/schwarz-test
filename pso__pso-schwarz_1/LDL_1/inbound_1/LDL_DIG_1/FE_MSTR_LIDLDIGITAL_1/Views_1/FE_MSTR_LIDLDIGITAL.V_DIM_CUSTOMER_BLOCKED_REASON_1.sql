CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CUSTOMER_BLOCKED_REASON_1
AS SELECT
     CASE WHEN CUST_BLOCKED_REASON_CD = '' THEN '-1' ELSE IFNULL(CUST_BLOCKED_REASON_CD, '-1') END AS CUST_BLOCKED_REASON_CD
    ,CUST_BLOCKED_REASON_DESCR AS CUST_BLOCKED_REASON_DESCR 
FROM
    lec_share.v_dim_customer_blocked_reason_1
UNION ALL
    SELECT
         '-1' -- CUST_BLOCKED_REASON_CD
        ,'' -- CUST_BLOCKED_REASON_DESCR
;
