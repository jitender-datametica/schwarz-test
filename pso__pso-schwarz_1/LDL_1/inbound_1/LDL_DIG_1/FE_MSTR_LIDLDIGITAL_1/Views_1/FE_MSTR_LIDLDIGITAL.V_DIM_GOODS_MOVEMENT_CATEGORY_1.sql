CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_GOODS_MOVEMENT_CATEGORY_1
(
     GOODS_MOV_CAT_CD
    ,GOODS_MOV_CAT_GROUP_CD
    ,GOODS_MOV_CAT_DESCR
)
AS SELECT
     GOODS_MOV_CAT_CD
    ,CASE WHEN GOODS_MOV_CAT_GROUP_CD = '' THEN '-1' ELSE IFNULL(GOODS_MOV_CAT_GROUP_CD, '-1') END
    ,GOODS_MOV_CAT_DESCR
FROM
    lec_share.v_dim_goods_movement_category_1
UNION ALL
    SELECT '-1', '-1', ''
;