CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_GROUP_OF_ACCOUNTS_1
AS SELECT
     CASE WHEN CHART_OF_ACCOUNTS_CD = '' THEN '-1' ELSE IFNULL(CHART_OF_ACCOUNTS_CD, '-1') END AS CHART_OF_ACCOUNTS_CD
    ,ACCT_NR AS GROUP_ACCT_NR
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
    ,MAX(SHORT_NAME_EN) AS SHORT_NAME_EN
    ,MAX(LONG_NAME_EN) AS LONG_NAME_EN
    ,MAX(SHORT_NAME_DE) AS SHORT_NAME_DE
    ,MAX(LONG_NAME_DE) AS LONG_NAME_DE
FROM 
    lec_share.v_dim_financial_account_1
WHERE
    DWH_VALID_FG = TRUE
    GROUP BY 
         CHART_OF_ACCOUNTS_CD
        ,ACCT_NR
        ,CURR_CD
UNION ALL
    SELECT    
         '-1'   -- CHART_OF_ACCOUNTS_CD
        ,'-1'   -- GROUP_ACCT_NR
        ,''     -- CURR_CD
        ,''     -- SHORT_NAME_EN
        ,''     -- LONG_NAME_EN
        ,''     -- SHORT_NAME_DE
        ,''     -- LONG_NAME_DE
;
