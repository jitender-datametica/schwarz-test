CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_MATERIAL_DOCUMENT_DEBIT_CREDIT_1
AS SELECT
     CASE WHEN MATERIAL_DOC_DEBIT_CREDIT_CD = '' THEN '-1' ELSE IFNULL(MATERIAL_DOC_DEBIT_CREDIT_CD, '-1') END AS MATERIAL_DOC_DEBIT_CREDIT_CD
    ,MATERIAL_DOC_DEBIT_CREDIT_DESCR AS MATERIAL_DOC_DEBIT_CREDIT_DESCR 
FROM
    lec_share.v_dim_material_document_debit_credit_1
UNION ALL
    SELECT
         '-1' -- MATERIAL_DOC_DEBIT_CREDIT_CD
        ,'' -- MATERIAL_DOC_DEBIT_CREDIT_DESCR
;
