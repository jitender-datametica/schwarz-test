CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_MATERIAL_DOCUMENT_STOCK_TYPE_1
AS SELECT
     CASE WHEN MATERIAL_DOC_STOCK_TYPE_CD = '' THEN '-1' ELSE IFNULL(MATERIAL_DOC_STOCK_TYPE_CD, '-1') END AS MATERIAL_DOC_STOCK_TYPE_CD
    ,MATERIAL_DOC_STOCK_TYPE_DESCR AS MATERIAL_DOC_STOCK_TYPE_DESCR 
FROM
    lec_share.v_dim_material_document_stock_type_1
UNION ALL
    SELECT
         '-1' -- MATERIAL_DOC_STOCK_TYPE_CD
        ,'' -- MATERIAL_DOC_STOCK_TYPE_DESCR
;
