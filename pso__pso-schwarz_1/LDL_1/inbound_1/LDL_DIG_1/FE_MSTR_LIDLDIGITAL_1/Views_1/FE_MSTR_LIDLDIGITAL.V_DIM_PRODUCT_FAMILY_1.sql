CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_FAMILY_1(
		PROD_FAMILY_CD
	,	PROD_FAMILY_DESCR
	,	PROD_GROUP_CD
	,	PROD_SUBGROUP_CD
	)
AS
SELECT 
		CASE WHEN PROD_FAMILY_CD = '' 		THEN '-1' ELSE IFNULL(PROD_FAMILY_CD, '-1') 	END
	,	CASE WHEN PROD_FAMILY_DESCR = '' 	THEN '-1' ELSE IFNULL(PROD_FAMILY_DESCR, '-1') 	END
	, 	CASE WHEN PROD_GROUP_CD = '' 		THEN '-1' ELSE IFNULL(PROD_GROUP_CD, '-1') 		END
	,	CASE WHEN PROD_SUBGROUP_CD = '' 	THEN '-1' ELSE IFNULL(PROD_SUBGROUP_CD, '-1') 	END
FROM lec_share.v_dim_product_family_1
UNION ALL
SELECT
		'-1' 	--PROD_FAMILY_CD
	,	''		--PROD_FAMILY_DESCR
	,	'-1'	--PROD_SUBGROUP_CD
	,	'-1'	--PROD_GROUP_CD
;