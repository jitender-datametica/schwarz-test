CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_PURCHASE_ORGANISATION_TYPE_1
(
     PROD_PURCH_ORG_TYPE_CD
    ,PROD_PURCH_ORG_TYPE_DESCR
)
AS SELECT
     PROD_PURCH_ORG_TYPE_CD
    ,PROD_PURCH_ORG_TYPE_DESCR
FROM lec_share.v_dim_product_purchase_organisation_type_1
UNION ALL 
SELECT '-1' AS PROD_PURCH_ORG_TYPE_CD
        , '' AS PROD_PURCH_ORG_TYPE_DESCR
        ;