CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_SIZE_HANDLE_GROUP_1
(
     PROD_SIZE_HANDLE_GROUP_CD
    ,PROD_SIZE_HANDLE_GROUP_DESCR
    ,PROD_SIZE_HANDLE_GROUP_DISPLAY_ORDER_NR
)
AS SELECT
     PROD_SIZE_HANDLE_GROUP_CD
    ,PROD_SIZE_HANDLE_GROUP_DESCR
    , CASE WHEN PROD_SIZE_HANDLE_GROUP_CD = 'P_KT' THEN 1
           WHEN PROD_SIZE_HANDLE_GROUP_CD = 'P_GT' THEN 2 
           WHEN PROD_SIZE_HANDLE_GROUP_CD = 'P_2MH' THEN 3
           WHEN PROD_SIZE_HANDLE_GROUP_CD = 'P_Sonst' THEN 4 
           ELSE '999'
           END  AS PROD_SIZE_HANDLE_GROUP_DISPLAY_ORDER_NR  --only needed for MSTR_DBR therefore coded directly here
FROM lec_share.v_dim_product_size_handle_group_1
UNION ALL
    SELECT 
        '-1' --PROD_SIZE_HANDLE_GROUP_CD
        , '' --PROD_SIZE_HANDLE_GROUP_DESCR
        , 1000 --PROD_SIZE_HANDLE_GROUP_DISPLAY_ORDER_NR
;