CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_STOCK_AGE_CLUSTER_1
AS SELECT
     PROD_STOCK_AGE_CLUSTER_CD AS PROD_STOCK_AGE_CLUSTER_CD
    ,PROD_STOCK_AGE_CLUSTER_DESCR AS PROD_STOCK_AGE_CLUSTER_DESCR
    ,CLUSTER_FIRST_DAY AS CLUSTER_FIRST_DAY
    ,CLUSTER_LAST_DAY AS CLUSTER_LAST_DAY 
FROM
    lec_share.v_dim_product_stock_age_cluster_1
UNION ALL
    SELECT
         '-1' -- PROD_STOCK_AGE_CLUSTER_CD
        ,'' -- PROD_STOCK_AGE_CLUSTER_DESCR
        ,'0' -- CLUSTER_FIRST_DAY
        ,'0' -- CLUSTER_LAST_DAY
;
