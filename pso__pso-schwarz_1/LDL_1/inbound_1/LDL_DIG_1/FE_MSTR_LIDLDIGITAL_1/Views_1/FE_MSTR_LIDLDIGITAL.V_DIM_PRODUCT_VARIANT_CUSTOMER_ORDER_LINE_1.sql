CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_VARIANT_CUSTOMER_ORDER_LINE_1
/*
    Aggregates information from T_FACT_CUSTOMER_ORDER_LINE_1 by PROD_VARIANT_SID.
    Can be extended with additional aggregations (e.g. MIN(CUST_ORDER_DT) AS MIN_CUST_ORDER_DT).
*/
AS SELECT
     PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,MAX(CUST_ORDER_DT) AS MAX_CUST_ORDER_DT
FROM
    lec_share.v_fact_customer_order_line_1
GROUP BY
    PROD_VARIANT_SID
;
