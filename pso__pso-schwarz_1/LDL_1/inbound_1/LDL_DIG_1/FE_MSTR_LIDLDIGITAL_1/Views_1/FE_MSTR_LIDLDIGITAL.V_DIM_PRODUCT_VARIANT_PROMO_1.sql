CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_VARIANT_PROMO_1
/*
    This view references lec_share.v_dim_product_variant_core_view_1, which joins CORE.T_DIM_PRODUCT_VARIANT_1 and CORE.T_DIM_SALES_PROMOTION.
    This view contains most fields from FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_VARIANT_1:
        Missing fields:
            IAN_NR
            PROD_VARIANT_HIST_NR
            PROD_VARIANT_IAN_NR
        Additional fields:
            MIN_DELIVERY_DT
            MAX_DELIVERY_DT
*/
(
  	PROD_VARIANT_SID
	,PROD_VARIANT_NR
	,PROD_VARIANT_NAME
	,PROD_VARIANT_DESCR
	,PROD_SID
	,PROD_NR
	,PROD_NAME
	--,IAN_NR
	,MAIN_EAN_NR
    --,PROD_VARIANT_HIST_NR
    --,PROD_VARIANT_IAN_NR
	,VOLUME_MEAS
	,VOLUME_UOM_CD
	,VOLUME_STR
	,VOLUME_MEAS_STANDARD
	,VOLUME_MEAS_STANDARD_UOM_CD
	,WEIGHT_MEAS
	,WEIGHT_UOM_CD
	,WEIGHT_STR
	,WEIGHT_MEAS_STANDARD
	,WEIGHT_MEAS_STANDARD_UOM_CD
	,GIRTH_EAST_MEAS
	,GIRTH_WEST_MEAS
	,GIRTH_UOM_CD
	,GIRTH_EAST_STR
	,GIRTH_EAST_MEAS_STANDARD
	,GIRTH_WEST_STR
	,GIRTH_WEST_MEAS_STANDARD
	,GIRTH_MEAS_STANDARD_UOM_CD
	,LENGTH_MEAS
	,LENGTH_UOM_CD
	,LENGTH_STR
	,LENGTH_MEAS_STANDARD
	,LENGTH_MEAS_STANDARD_UOM_CD
	,MEAN_LENGTH_MEAS
	,MEAN_LENGTH_STR
	,MEAN_LENGTH_MEAS_STANDARD
	,SHORTEST_LENGTH_MEAS
	,SHORTEST_LENGTH_STR
	,SHORTEST_LENGTH_MEAS_STANDARD
	,LONGEST_LENGTH_MEAS
	,LONGEST_LENGTH_STR
	,LONGEST_LENGTH_MEAS_STANDARD
	,WIDTH_MEAS
	,WIDTH_UOM_CD
	,WIDTH_STR
	,WIDTH_MEAS_STANDARD
	,WIDTH_MEAS_STANDARD_UOM_CD
	,HEIGHT_MEAS
	,HEIGHT_UOM_CD
	,HEIGHT_STR
	,HEIGHT_MEAS_STANDARD
	,HEIGHT_MEAS_STANDARD_UOM_CD
	,PROD_SIZE_TYPE_CD
	,IS_BULKY_ITEM_FG
	,PROD_ORIG_COUNTRY_CD
	,BRAND_SID
	,BRAND_CLASS_CD
	,PROD_ASSORTMENT_CLASS_CD
	,PROD_GLOBAL_STATUS_CD
	,PROD_FOOD_CLASS_CD
	,PALETTE_CAPACITY_CNT
	,PACKAGE_CAPACITY_CNT
	,CONTAINER_CAPACITY_CNT
	,MAIN_SUPPLIER_SID
	,SHOP_CAT_SID
	,SHOP_CAT_NAME
	,SHOP_CAT_LVL4_SID
	,SHOP_CAT_LVL4_NAME
	,SHOP_CAT_LVL3_SID
	,SHOP_CAT_LVL3_NAME
	,SHOP_CAT_LVL2_SID
	,SHOP_CAT_LVL2_NAME
	,SHOP_CAT_LVL1_SID
	,SHOP_CAT_LVL1_NAME
	,FIRST_INBOUND_DT
    ,PROD_BRICK_CD
    ,COMMODITY_FG
    ,IS_BUNDLE_HEADER_FG
    ,PROD_VARIANT_SRC_INSERT_DT
    ,PROD_VARIANT_SRC_UPDATE_DT
    ,MIN_DELIVERY_DT
    ,MAX_DELIVERY_DT
    ,PROMO_DUR_WEEK_CNT
) AS SELECT
     PROD_VARIANT_SID
    ,PROD_VARIANT_NR
    ,PROD_VARIANT_NAME
    ,PROD_VARIANT_DESCR
    ,IFNULL(PROD_SID, '-1')
    ,PROD_NR
    ,PROD_NAME
    --,CASE WHEN PROD_VARIANT_IAN_NR IS NOT NULL THEN PROD_VARIANT_IAN_NR ELSE IAN_NR END -- see NBI-4630
    ,MAIN_EAN_NR
    --,PROD_VARIANT_HIST_NR
    --,PROD_VARIANT_IAN_NR
    ,VOLUME_MEAS
    ,IFNULL(UOM_VOLUME.UOM_CD, '-1') AS VOLUME_UOM_CD
    ,LEFT(VOLUME_MEAS || ' ' || UOM_VOLUME.UOM_CD, 20)::VARCHAR(20) AS VOLUME_STR
    ,VOLUME_MEAS * UOM_VOLUME.UOM_STANDARD_MULTIPL_MEAS AS VOLUME_MEAS_STANDARD
    ,IFNULL(UOM_VOLUME.UOM_STANDARD_CD, '-1') AS VOLUME_MEAS_STANDARD_UOM_CD
    ,WEIGHT_MEAS
    ,IFNULL(UOM_WEIGHT.UOM_CD, '-1') AS WEIGHT_UOM_CD
    ,LEFT(WEIGHT_MEAS || ' ' || UOM_WEIGHT.UOM_CD, 20)::VARCHAR(20) AS WEIGHT_STR
    ,WEIGHT_MEAS * UOM_WEIGHT.UOM_STANDARD_MULTIPL_MEAS AS WEIGHT_MEAS_STANDARD
    ,IFNULL(UOM_WEIGHT.UOM_STANDARD_CD, '-1') AS WEIGHT_MEAS_STANDARD_UOM_CD
    ,GIRTH_EAST_MEAS
    ,GIRTH_WEST_MEAS
    ,IFNULL(UOM_GIRTH.UOM_CD, '-1') AS GIRTH_UOM_CD
    ,LEFT(GIRTH_EAST_MEAS || ' ' || UOM_GIRTH.UOM_CD, 20)::VARCHAR(20) AS GIRTH_EAST_STR
    ,GIRTH_EAST_MEAS * UOM_GIRTH.UOM_STANDARD_MULTIPL_MEAS AS GIRTH_EAST_MEAS_STANDARD
    ,LEFT(GIRTH_WEST_MEAS || ' ' || UOM_GIRTH.UOM_CD, 20)::VARCHAR(20) AS GIRTH_WEST_STR
    ,GIRTH_WEST_MEAS * UOM_GIRTH.UOM_STANDARD_MULTIPL_MEAS AS GIRTH_WEST_MEAS_STANDARD
    ,IFNULL(UOM_GIRTH.UOM_STANDARD_CD, '-1') AS GIRTH_MEAS_STANDARD_UOM_CD
    ,LENGTH_MEAS
    ,IFNULL(UOM_LENGTH.UOM_CD, '-1') AS LENGTH_UOM_CD
    ,LEFT(LENGTH_MEAS || ' ' || UOM_LENGTH.UOM_CD, 20)::VARCHAR(20) AS LENGTH_STR
    ,LENGTH_MEAS * UOM_LENGTH.UOM_STANDARD_MULTIPL_MEAS AS LENGTH_MEAS_STANDARD
    ,IFNULL(UOM_LENGTH.UOM_STANDARD_CD, '-1') AS LENGTH_MEAS_STANDARD_UOM_CD
    ,MEAN_LENGTH_MEAS
    ,LEFT(MEAN_LENGTH_MEAS || ' ' || UOM_LENGTH.UOM_CD, 20)::VARCHAR(20) AS MEAN_LENGTH_STR
    ,MEAN_LENGTH_MEAS * UOM_LENGTH.UOM_STANDARD_MULTIPL_MEAS AS MEAN_LENGTH_MEAS_STANDARD
    ,SHORTEST_LENGTH_MEAS
    ,LEFT(SHORTEST_LENGTH_MEAS || ' ' || UOM_LENGTH.UOM_CD, 20)::VARCHAR(20) AS SHORTEST_LENGTH_STR
    ,SHORTEST_LENGTH_MEAS * UOM_LENGTH.UOM_STANDARD_MULTIPL_MEAS AS SHORTEST_LENGTH_MEAS_STANDARD
    ,LONGEST_LENGTH_MEAS
    ,LEFT(LONGEST_LENGTH_MEAS || ' ' || UOM_LENGTH.UOM_CD, 20)::VARCHAR(20) AS LONGEST_LENGTH_STR
    ,LONGEST_LENGTH_MEAS * UOM_LENGTH.UOM_STANDARD_MULTIPL_MEAS AS LONGEST_LENGTH_MEAS_STANDARD
    ,WIDTH_MEAS
    ,IFNULL(UOM_WIDTH.UOM_CD, '-1') AS WIDTH_UOM_CD
    ,LEFT(WIDTH_MEAS || ' ' || UOM_WIDTH.UOM_CD, 20)::VARCHAR(20) AS WIDTH_STR
    ,WIDTH_MEAS * UOM_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS WIDTH_MEAS_STANDARD
    ,IFNULL(UOM_WIDTH.UOM_STANDARD_CD, '-1') AS WIDTH_MEAS_STANDARD_UOM_CD
    ,HEIGHT_MEAS
    ,IFNULL(UOM_HEIGHT.UOM_CD, '-1') AS HEIGHT_UOM_CD
    ,LEFT(HEIGHT_MEAS || ' ' || UOM_HEIGHT.UOM_CD, 20)::VARCHAR(20) AS HEIGHT_STR
    ,HEIGHT_MEAS * UOM_HEIGHT.UOM_STANDARD_MULTIPL_MEAS AS HEIGHT_MEAS_STANDARD
    ,IFNULL(UOM_HEIGHT.UOM_STANDARD_CD, '-1') AS HEIGHT_MEAS_STANDARD_UOM_CD
    ,CASE WHEN PROD_SIZE_TYPE_CD = '' THEN '-1' ELSE IFNULL(PROD_SIZE_TYPE_CD, '-1') END
    ,IS_BULKY_ITEM_FG
    ,CASE WHEN PROD_ORIG_COUNTRY_CD = '' THEN '-1' ELSE IFNULL(PROD_ORIG_COUNTRY_CD, '-1') END
    ,IFNULL(BRAND_SID, '-1')
    ,CASE WHEN BRAND_CLASS_CD = '' THEN '-1' ELSE IFNULL(BRAND_CLASS_CD, '-1') END
    ,CASE WHEN PROD_ASSORTMENT_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_CLASS_CD, '-1') END
    ,CASE WHEN PROD_GLOBAL_STATUS_CD = '' THEN '-1' ELSE IFNULL(PROD_GLOBAL_STATUS_CD, '-1') END
    ,CASE WHEN PROD_FOOD_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_FOOD_CLASS_CD, '-1') END
    ,PALETTE_CAPACITY_CNT
    ,PACKAGE_CAPACITY_CNT
    ,CONTAINER_CAPACITY_CNT
    ,IFNULL(MAIN_SUPPLIER_SID, '-1')
    ,IFNULL(SHOP_CAT_SID, '-1')
    ,SHOP_CAT_NAME
    ,IFNULL(SHOP_CAT_LVL4_SID, '-1')
    ,SHOP_CAT_LVL4_NAME
    ,IFNULL(SHOP_CAT_LVL3_SID, '-1')
    ,SHOP_CAT_LVL3_NAME
    ,IFNULL(SHOP_CAT_LVL2_SID, '-1')
    ,SHOP_CAT_LVL2_NAME
    ,IFNULL(SHOP_CAT_LVL1_SID, '-1')
    ,SHOP_CAT_LVL1_NAME
    ,NULL
    ,CASE WHEN PROD_BRICK_CD = '' THEN '-1' ELSE IFNULL(PROD_BRICK_CD, '-1') END
    ,CASE
        WHEN LEFT(PROD_VARIANT_NR::STRING, 1) = '1'
        THEN TRUE
        ELSE FALSE
     END AS COMMODITY_FG
    ,IS_BUNDLE_HEADER_FG
    ,PROD_VARIANT_SRC_INSERT_DT
    ,PROD_VARIANT_SRC_UPDATE_DT
    ,MIN_DELIVERY_DT
    ,MAX_DELIVERY_DT
    ,PROMO_DUR_WEEK_CNT
FROM
    lec_share.v_dim_product_variant_core_view_1 PV
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_VOLUME ON UOM_VOLUME.UOM_SID = IFNULL(PV.VOLUME_UOM_SID, '-1')
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_WEIGHT ON UOM_WEIGHT.UOM_SID = IFNULL(PV.WEIGHT_UOM_SID, '-1')
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_GIRTH ON UOM_GIRTH.UOM_SID = IFNULL(PV.GIRTH_UOM_SID, '-1')
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_LENGTH ON UOM_LENGTH.UOM_SID = IFNULL(PV.LENGTH_UOM_SID, '-1')
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_WIDTH ON UOM_WIDTH.UOM_SID = IFNULL(PV.WIDTH_UOM_SID, '-1')
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_HEIGHT ON UOM_HEIGHT.UOM_SID = IFNULL(PV.HEIGHT_UOM_SID, '-1')
WHERE
    DWH_VALID_FG = TRUE
UNION ALL 
    SELECT 
         '-1' -- PROD_VARIANT_SID
        ,'' -- ,PROD_VARIANT_NR
        ,'' -- ,PROD_VARIANT_NAME
        ,'' -- ,PROD_VARIANT_DESCR
        ,'-1' -- ,PROD_SID
        ,'' -- ,PROD_NR
        ,'' -- ,PROD_NAME
        --,'' -- ,IAN_NR
        ,'' -- ,MAIN_EAN_NR
        --,'' -- ,PROD_VARIANT_HIST_NR
        --,'' -- ,PROD_VARIANT_IAN_NR
        ,'0' -- ,VOLUME_MEAS
        ,'' -- ,VOLUME_UOM_CD
        ,'' -- ,VOLUME_STR
        ,'0' -- ,VOLUME_MEAS_STANDARD
        ,'' -- ,VOLUME_MEAS_STANDARD_UOM_CD
        ,'0' -- ,WEIGHT_MEAS
        ,'' -- ,WEIGHT_UOM_CD
        ,'' -- ,WEIGHT_STR
        ,'0' -- ,WEIGHT_MEAS_STANDARD
        ,'' -- ,WEIGHT_MEAS_STANDARD_UOM_CD
        ,'0' -- ,GIRTH_EAST_MEAS
        ,'0' -- ,GIRTH_WEST_MEAS
        ,'' -- ,GIRTH_UOM_CD
        ,'' -- ,GIRTH_EAST_STR
        ,'0' -- ,GIRTH_EAST_MEAS_STANDARD
        ,'' -- ,GIRTH_WEST_STR
        ,'0' -- ,GIRTH_WEST_MEAS_STANDARD
        ,'' -- ,GIRTH_MEAS_STANDARD_UOM_CD
        ,'0' -- ,LENGTH_MEAS
        ,'' -- ,LENGTH_UOM_CD
        ,'' -- ,LENGTH_STR
        ,'0' -- ,LENGTH_MEAS_STANDARD
        ,'' -- ,LENGTH_MEAS_STANDARD_UOM_CD
        ,'0' -- ,MEAN_LENGTH_MEAS
        ,'' -- ,MEAN_LENGTH_STR
        ,'0' -- ,MEAN_LENGTH_MEAS_STANDARD
        ,'0' -- ,SHORTEST_LENGTH_MEAS
        ,'' -- ,SHORTEST_LENGTH_STR
        ,'0' -- ,SHORTEST_LENGTH_MEAS_STANDARD
        ,'0' -- ,LONGEST_LENGTH_MEAS
        ,'' -- ,LONGEST_LENGTH_STR
        ,'0' -- ,LONGEST_LENGTH_MEAS_STANDARD
        ,'0' -- ,WIDTH_MEAS
        ,'' -- ,WIDTH_UOM_CD
        ,'' -- ,WIDTH_STR
        ,'0' -- ,WIDTH_MEAS_STANDARD
        ,'' -- ,WIDTH_MEAS_STANDARD_UOM_CD
        ,'0' -- ,HEIGHT_MEAS
        ,'' -- ,HEIGHT_UOM_CD
        ,'' -- ,HEIGHT_STR
        ,'0' -- ,HEIGHT_MEAS_STANDARD
        ,'' -- ,HEIGHT_MEAS_STANDARD_UOM_CD
        ,'-1' -- ,PROD_SIZE_TYPE_CD
        ,FALSE -- ,IS_BULKY_ITEM_FG
        ,'-1' -- ,PROD_ORIG_COUNTRY_CD
        ,'-1' -- ,BRAND_SID
        ,'-1' -- ,BRAND_CLASS_CD
        ,'-1' -- ,PROD_ASSORTMENT_CLASS_CD
        ,'-1' -- ,PROD_GLOBAL_STATUS_CD
        ,'-1' -- ,PROD_FOOD_CLASS_CD
        ,'0'  -- ,PALETTE_CAPACITY_CNT
        ,'0'  -- ,PACKAGE_CAPACITY_CNT
        ,'0'  -- ,CONTAINER_CAPACITY_CNT
        ,'-1' -- ,MAIN_SUPPLIER_SID
        ,'-1' -- ,SHOP_CAT_SID
        ,''   -- ,SHOP_CAT_NAME
        ,'-1' -- ,SHOP_CAT_LVL4_SID
        ,''   -- ,SHOP_CAT_LVL4_NAME
        ,'-1' -- ,SHOP_CAT_LVL3_SID
        ,''   -- ,SHOP_CAT_LVL3_NAME
        ,'-1' -- ,SHOP_CAT_LVL2_SID
        ,''   -- ,SHOP_CAT_LVL2_NAME
        ,'-1' -- ,SHOP_CAT_LVL1_SID
        ,''   -- ,SHOP_CAT_LVL1_NAME
        ,TO_DATE('1900-01-01') -- ,FIRST_INBOUND_DT
        ,'-1' -- ,PROD_BRICK_CD
        ,FALSE -- COMMODITY_FG
        ,FALSE -- IS_BUNDLE_HEADER_FG
        ,TO_DATE('1900-01-01') -- ,PROD_VARIANT_SRC_INSERT_DT
        ,TO_DATE('1900-01-01') -- ,PROD_VARIANT_SRC_UPDATE_DT
        ,TO_DATE('1900-01-01') -- ,MIN_DELIVERY_DT
        ,TO_DATE('1900-01-01') -- ,MAX_DELIVERY_DT
        ,'-1' -- ,PROMO_DUR_WEEK_CNT
    ;