CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_SHOP_CATEGORY_LVL_4_1
(
     SHOP_CAT_LVL4_SID
    ,SHOP_CAT_LVL4_CD
    ,SHOP_CAT_LVL4_NAME
    ,SHOP_CAT_LVL3_SID
    ,SHOP_CAT_LVL3_CD
    ,SHOP_CAT_LVL3_NAME
    ,SHOP_CAT_LVL2_SID
    ,SHOP_CAT_LVL2_CD
    ,SHOP_CAT_LVL2_NAME
    ,SHOP_CAT_LVL1_SID
    ,SHOP_CAT_LVL1_CD
    ,SHOP_CAT_LVL1_NAME
)
AS SELECT 
     SHOP_CAT_LVL4_SID
	,IFNULL(SHOP_CAT_LVL4_CD, '-1')
    ,SHOP_CAT_LVL4_NAME
	,IFNULL(SHOP_CAT_LVL3_SID, '-1')
	,IFNULL(SHOP_CAT_LVL3_CD, '-1')
    ,SHOP_CAT_LVL3_NAME
	,IFNULL(SHOP_CAT_LVL2_SID, '-1')
	,IFNULL(SHOP_CAT_LVL2_CD, '-1')
    ,SHOP_CAT_LVL2_NAME
	,IFNULL(SHOP_CAT_LVL1_SID, '-1')
	,IFNULL(SHOP_CAT_LVL1_CD, '-1')
    ,SHOP_CAT_LVL1_NAME
FROM lec_share.v_dim_shop_category_lvl_4_1
WHERE DWH_VALID_FG = TRUE
UNION ALL
    SELECT    
         '-1' --  SHOP_CAT_LVL4_SID
        ,'-1' -- ,SHOP_CAT_LVL4_CD
        ,''   -- ,SHOP_CAT_LVL4_NAME
        ,'-1' -- ,SHOP_CAT_LVL3_SID
        ,'-1' -- ,SHOP_CAT_LVL3_CD
        ,''   -- ,SHOP_CAT_LVL3_NAME
        ,'-1' -- ,SHOP_CAT_LVL2_SID
        ,'-1' -- ,SHOP_CAT_LVL2_CD
        ,''   -- ,SHOP_CAT_LVL2_NAME
        ,'-1' -- ,SHOP_CAT_LVL1_SID
        ,'-1' -- ,SHOP_CAT_LVL1_CD
        ,''   -- ,SHOP_CAT_LVL1_NAME
;
