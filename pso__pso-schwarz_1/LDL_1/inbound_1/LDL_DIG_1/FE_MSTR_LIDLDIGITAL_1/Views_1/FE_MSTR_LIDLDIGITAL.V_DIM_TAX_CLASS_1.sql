CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TAX_CLASS_1
(
     WSHOP_CD
    ,TAX_CLASS_CD
    ,TAX_CLASS_PCT
)
AS SELECT
     WSHOP_CD
    ,CASE WHEN TAX_CLASS_CD = '' THEN '-1' ELSE IFNULL(TAX_CLASS_CD, '-1') END
    ,TAX_CLASS_PCT
FROM lec_share.v_dim_tax_class_1
WHERE ACTIVE_FG = TRUE
UNION ALL
    SELECT '-1', '-1', 0
;