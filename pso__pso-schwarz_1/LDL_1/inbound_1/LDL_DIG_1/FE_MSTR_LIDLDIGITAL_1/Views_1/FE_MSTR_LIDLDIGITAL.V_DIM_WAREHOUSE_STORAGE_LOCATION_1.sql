CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_WAREHOUSE_STORAGE_LOCATION_1
(
     WH_SID
    ,WH_CD
    ,STORAGE_LOC_CD
    ,STORAGE_LOC_DESCR
)
AS SELECT
     WH_SID
    ,CASE WHEN WH_CD = '' THEN '-1' ELSE IFNULL(WH_CD, '-1') END
    ,CASE WHEN STORAGE_LOC_CD = '' THEN '-1' ELSE IFNULL(STORAGE_LOC_CD, '-1') END
    ,STORAGE_LOC_DESCR
FROM
    lec_share.v_dim_warehouse_storage_location_1
UNION ALL
    SELECT
        '-1', '-1', '-1', ''
;