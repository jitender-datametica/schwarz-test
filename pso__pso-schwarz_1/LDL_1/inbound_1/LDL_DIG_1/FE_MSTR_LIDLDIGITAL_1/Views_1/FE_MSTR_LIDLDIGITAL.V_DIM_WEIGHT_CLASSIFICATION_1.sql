CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_WEIGHT_CLASSIFICATION_1
AS SELECT
     CASE WHEN WEIGHT_CLASS_CD = '' THEN '-1' ELSE IFNULL(WEIGHT_CLASS_CD, '-1') END AS WEIGHT_CLASS_CD
    ,WEIGHT_CLASS_DESCR AS WEIGHT_CLASS_DESCR 
FROM
    lec_share.v_dim_weight_classification_1
UNION ALL
    SELECT
         '-1' -- WEIGHT_CLASS_CD
        ,'' -- WEIGHT_CLASS_DESCR
;
