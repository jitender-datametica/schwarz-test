CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_ACCOUNTING_DOCUMENT_LINE_1 (
	LEDGER_CD
	,INTERNAL_COMPANY_CD
	,FISCAL_YEAR
	,ACCT_DOC_NR
	,ACCT_DOC_LINE_NR
	,FIN_ACCT_SID
	,INTERNAL_COMPANY_SID
	,INTERNAL_COMPANY_PARTNER_SID
	,ACCT_NR
	,ACCT_DOC_DT
	,ACCT_DOC_TYPE_CD
	,ACCT_DOC_POSTING_DT
	,ACCT_DOC_STATUS
	,CTRL_DOC_NR
	,FISCAL_PERIOD
	,CURR_CD
	,POSTING_LOCAL_VAL
	,POSTING_GROUP_VAL
	,CTRL_AREA_CD
	,COST_CENTER_NR
	,SENDER_COST_CENTER_NR
	,POSTING_TMSP
	,REF_DOC_NR
	,ACCOUNTED_MODULE_CD
	,DEBIT_CREDIT_CD
	,GL_ACCT_TYPE
	,OFFSETTING_ACCT_NR
	,ACCT_DOCUMENT_TX
	,ACCT_TRANS_TYPE_CD
	,ACCT_COST_TYPE_CD
	,PROD_VARIANT_NR
	,PROD_VARIANT_SID
	,CHART_OF_ACCOUNTS_CD
	,GROUP_ACCT_NR
	,ACCT_CURR_CD
	,ACCT_DATA_SRC_NAME
) AS SELECT
    A1.LEDGER_CD 																							AS LEDGER_CD
    ,CASE WHEN A1.INTERNAL_COMPANY_CD = '' THEN '-1' ELSE IFNULL(A1.INTERNAL_COMPANY_CD, '-1') END 			AS INTERNAL_COMPANY_CD
    ,A1.FISCAL_YEAR 																						AS FISCAL_YEAR
    ,A1.ACCT_DOC_NR 																						AS ACCT_DOC_NR
    ,A1.ACCT_DOC_LINE_NR 																					AS ACCT_DOC_LINE_NR
    ,IFNULL(A1.FIN_ACCT_SID, '-1') 																			AS FIN_ACCT_SID
    ,IFNULL(A1.INTERNAL_COMPANY_SID, '-1') 																	AS INTERNAL_COMPANY_SID
    ,IFNULL(A1.INTERNAL_COMPANY_PARTNER_SID, '-1') 															AS INTERNAL_COMPANY_PARTNER_SID
    ,CASE WHEN A1.ACCT_NR = '' THEN '-1' ELSE IFNULL(ACCT_NR, '-1') END										AS ACCT_NR
    ,A1.ACCT_DOC_DT 																						AS ACCT_DOC_DT
    ,CASE WHEN A1.ACCT_DOC_TYPE_CD = '' THEN '-1' ELSE IFNULL(A1.ACCT_DOC_TYPE_CD, '-1') END 				AS ACCT_DOC_TYPE_CD
    ,A1.ACCT_DOC_POSTING_DT 																				AS ACCT_DOC_POSTING_DT
    ,A1.ACCT_DOC_STATUS 																					AS ACCT_DOC_STATUS
    ,A1.CTRL_DOC_NR 																						AS CTRL_DOC_NR
    ,IFNULL(A1.FISCAL_PERIOD_NR, '-1') 																		AS FISCAL_PERIOD
    ,CASE WHEN A1.CURR_CD = '' THEN '-1' ELSE IFNULL(A1.CURR_CD, '-1') END 									AS CURR_CD
    ,A1.POSTING_LOCAL_VAL 																					AS POSTING_LOCAL_VAL
    ,A1.POSTING_GROUP_VAL 																					AS POSTING_GROUP_VAL
    ,CASE WHEN A1.CTRL_AREA_CD = '' THEN '-1' ELSE IFNULL(A1.CTRL_AREA_CD, '-1') END 						AS CTRL_AREA_CD
    ,CASE WHEN A1.COST_CENTER_NR = '' THEN '-1' ELSE IFNULL(A1.COST_CENTER_NR, '-1') END 					AS COST_CENTER_NR
    ,COALESCE( NULLIF( A1.SENDER_COST_CENTER_NR, '' ), NULLIF( A1.COST_CENTER_NR, '' ), '-1'  ) 			AS SENDER_COST_CENTER_NR
    ,CONVERT_TIMEZONE('Europe/Berlin', A1.POSTING_TMSP)::TIMESTAMP_NTZ 										AS POSTING_TMSP
    ,A1.REF_DOC_NR 																							AS REF_DOC_NR
    ,CASE WHEN A1.ACCOUNTED_MODULE_CD = '' THEN '-1' ELSE IFNULL(A1.ACCOUNTED_MODULE_CD, '-1') END 			AS ACCOUNTED_MODULE_CD
    ,CASE WHEN A1.DEBIT_CREDIT_CD = '' THEN '-1' ELSE IFNULL(A1.DEBIT_CREDIT_CD, '-1') END 					AS DEBIT_CREDIT_CD
    ,A1.GL_ACCT_TYPE 																						AS GL_ACCT_TYPE
    ,CASE WHEN A1.OFFSETTING_ACCT_NR = '' THEN '-1' ELSE IFNULL(OFFSETTING_ACCT_NR, '-1') END 				AS OFFSETTING_ACCT_NR
    ,CASE WHEN A1.ACCT_DOCUMENT_TX = '' THEN '-1' ELSE IFNULL( A1.ACCT_DOCUMENT_TX, '-1') END 				AS ACCT_DOCUMENT_TX
    ,CASE WHEN A1.ACCT_TRANS_TYPE_CD = '' THEN '-1' ELSE IFNULL(A1.ACCT_TRANS_TYPE_CD, '-1') END 			AS ACCT_TRANS_TYPE_CD
    ,CASE WHEN A1.ACCT_COST_TYPE_CD = '' THEN '-1' ELSE IFNULL(A1.ACCT_COST_TYPE_CD, '-1') END 				AS ACCT_COST_TYPE_CD
    ,CASE WHEN A1.PROD_VARIANT_NR = '' THEN '-1' ELSE IFNULL(A1.PROD_VARIANT_NR, '-1') END 					AS PROD_VARIANT_NR
    ,IFNULL(A1.PROD_VARIANT_SID, '-1') 																		AS PROD_VARIANT_SID
    ,CASE WHEN A2.CHART_OF_ACCOUNTS_CD = '' THEN '-1' ELSE IFNULL(A2.CHART_OF_ACCOUNTS_CD, '-1') END 		AS CHART_OF_ACCOUNTS_CD
    ,CASE WHEN A2.GROUP_ACCT_NR = '' THEN '-1' ELSE IFNULL(A2.GROUP_ACCT_NR, '-1') END 						AS GROUP_ACCT_NR
    ,A2.CURR_CD 																							AS ACCT_CURR_CD
    ,'IST SAP' 																								AS ACCT_DATA_SRC_NAME
FROM
    lec_share.v_fact_accounting_document_line_1 AS A1
LEFT JOIN
    (
        SELECT
             FIN_ACCT_SID
            ,CHART_OF_ACCOUNTS_CD
            ,GROUP_ACCT_NR
            ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
        FROM
            lec_share.v_dim_financial_account_1
        WHERE
            DWH_VALID_FG = TRUE AND CHART_OF_ACCOUNTS_CD = 'LDI1'
    ) AS A2
    ON
        A1.FIN_ACCT_SID = A2.FIN_ACCT_SID
;