CREATE OR REPLACE VIEW  FE_MSTR_LIDLDIGITAL.V_FACT_COUPON_VALIDATION_1(
    COUPON_VALIDATION_NR
    , CUST_ORDER_SID
    , PROD_VARIANT_SID
    , COUPON_ID
    , COUPON_CD
    , COUPON_TYPE_CD
    , COUPON_PROMO_CD
    , PROFIT_LOSS_REASON_CD
    , PROFIT_LOSS_REASON_NAME
    , PROFIT_LOSS_TYPE_NAME
    , CURR_CD
    , WSHOP_CD
    , PROD_QTY
    , COUPON_VALIDATION_TMSP
    , COUPON_SHIP_GROSS_VAL
    , COUPON_ITEM_GROSS_VAL
    , COUPON_POS_GROSS_VAL
    , GC_LC_CD
    , CAL_YEAR
    , CAL_MONTH
    , BUS_YEAR
    , MONTH_OF_BUS_YEAR
) AS 
SELECT
    FC.COUPON_VALIDATION_NR AS COUPON_VALIDATION_NR
    , FC.CUST_ORDER_SID AS CUST_ORDER_SID
    , FC.PROD_VARIANT_SID AS PROD_VARIANT_SID
    , FC.COUPON_ID AS COUPON_ID
    , FC.COUPON_CD AS COUPON_CD
    , DC.COUPON_TYPE_CD AS COUPON_TYPE_CD
    , FC.COUPON_PROMO_CD AS COUPON_PROMO_CD
    , FC.PROFIT_LOSS_REASON_CD AS PROFIT_LOSS_REASON_CD
    , DPLR.PROFIT_LOSS_REASON_NAME AS PROFIT_LOSS_REASON_NAME
    , DPLR.PROFIT_LOSS_TYPE_NAME AS PROFIT_LOSS_TYPE_NAME
    , 'EUR' AS CURR_CD
    , FC.WSHOP_CD AS WSHOP_CD
    , FC.PROD_QTY AS PROD_QTY
    , FC.COUPON_VALIDATION_TMSP AS COUPON_VALIDATION_TMSP
    , FC.COUPON_SHIP_GROSS_EUR_VAL AS COUPON_SHIP_GROSS_VAL
    , FC.COUPON_ITEM_GROSS_EUR_VAL AS COUPON_ITEM_GROSS_VAL
    , FC.COUPON_POS_GROSS_EUR_VAL  AS COUPON_POS_GROSS_VAL
    , 'GC' AS GC_LC_CD
    , YEAR(FC.COUPON_VALIDATION_TMSP) AS CAL_YEAR
    , MONTH(FC.COUPON_VALIDATION_TMSP) AS CAL_MONTH
    , DIM_CAL_DAY.BUS_YEAR AS BUS_YEAR
    , DIM_CAL_DAY.MONTH_OF_BUS_YEAR AS MONTH_OF_BUS_YEAR
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_COUPON_VALIDATION_NO_GC_LC_1 FC
LEFT JOIN FE_MSTR_LIDLDIGITAL.V_DIM_COUPON_1 DC
    ON FC.COUPON_ID = DC.COUPON_ID  
LEFT JOIN FE_MSTR_LIDLDIGITAL.V_DIM_PROFIT_LOSS_REASON_1 DPLR
    ON FC.PROFIT_LOSS_REASON_CD = DPLR.PROFIT_LOSS_REASON_CD
JOIN FE_MSTR_LIDLDIGITAL.V_DIM_CAL_DAY_1 DIM_CAL_DAY
    ON TO_DATE(FC.COUPON_VALIDATION_TMSP) = DIM_CAL_DAY.CAL_DT
UNION 
SELECT
    FC.COUPON_VALIDATION_NR AS COUPON_VALIDATION_NR
    , FC.CUST_ORDER_SID AS CUST_ORDER_SID
    , FC.PROD_VARIANT_SID AS PROD_VARIANT_SID
    , FC.COUPON_ID AS COUPON_ID
    , FC.COUPON_CD AS COUPON_CD
    , DC.COUPON_TYPE_CD AS COUPON_TYPE_CD
    , FC.COUPON_PROMO_CD AS COUPON_PROMO_CD
    , FC.PROFIT_LOSS_REASON_CD AS PROFIT_LOSS_REASON_CD
    , DPLR.PROFIT_LOSS_REASON_NAME AS PROFIT_LOSS_REASON_NAME
    , DPLR.PROFIT_LOSS_TYPE_NAME AS PROFIT_LOSS_TYPE_NAME
    , FC.CURR_CD AS CURR_CD
    , FC.WSHOP_CD AS WSHOP_CD
    , FC.PROD_QTY AS PROD_QTY
    , FC.COUPON_VALIDATION_TMSP AS COUPON_VALIDATION_TMSP
    , FC.COUPON_SHIP_GROSS_LOCAL_VAL AS COUPON_SHIP_GROSS_VAL
    , FC.COUPON_ITEM_GROSS_LOCAL_VAL AS COUPON_ITEM_GROSS_VAL
    , FC.COUPON_POS_GROSS_LOCAL_VAL  AS COUPON_POS_GROSS_VAL
    , 'LC' AS GC_LC_CD
    , YEAR(FC.COUPON_VALIDATION_TMSP) AS CAL_YEAR
    , MONTH(FC.COUPON_VALIDATION_TMSP) AS CAL_MONTH
    , DIM_CAL_DAY.BUS_YEAR AS BUS_YEAR
    , DIM_CAL_DAY.MONTH_OF_BUS_YEAR AS MONTH_OF_BUS_YEAR
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_COUPON_VALIDATION_NO_GC_LC_1 FC
LEFT JOIN FE_MSTR_LIDLDIGITAL.V_DIM_COUPON_1 DC
    ON FC.COUPON_ID = DC.COUPON_ID 
LEFT JOIN FE_MSTR_LIDLDIGITAL.V_DIM_PROFIT_LOSS_REASON_1 DPLR
    ON FC.PROFIT_LOSS_REASON_CD = DPLR.PROFIT_LOSS_REASON_CD
JOIN FE_MSTR_LIDLDIGITAL.V_DIM_CAL_DAY_1 DIM_CAL_DAY
    ON TO_DATE(FC.COUPON_VALIDATION_TMSP) = DIM_CAL_DAY.CAL_DT
WHERE
    FC.CURR_CD != 'EUR'
;
