CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_ORDER_LINE_LIVE_TEST_1(
    WSHOP_CD
    ,CUST_ORDER_NR
    ,PROD_VARIANT_SID
    ,LT_RELATIVE_DT
    ,CUST_ORDER_CREATE_HOUR
    ,PROD_PRICE_NET_EUR_VAL_TODAY
    ,PROD_PRICE_NET_EUR_VAL_AVG_BY
    ,PROD_PRICE_NET_EUR_VAL_SDWLY
    ,PROD_PRICE_NET_EUR_VAL_AVG_BY_CURR_HOUR
    ,PROD_PRICE_NET_EUR_VAL_SDWLY_CURR_HOUR
) AS
SELECT
    WSHOP_CD
    ,CUST_ORDER_NR
    ,PROD_VARIANT_SID
    ,LT_RELATIVE_DT
    ,CUST_ORDER_CREATE_HOUR
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'TODAY' THEN PROD_PRICE_NET_EUR_VAL ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_TODAY
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'BY' THEN PROD_PRICE_NET_EUR_VAL/COUNT_BY_DAYS ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_AVG_BY
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'SDWLY' THEN PROD_PRICE_NET_EUR_VAL ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_SDWLY
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'BY' AND CUST_ORDER_CREATE_HOUR <= CUST_ORDER_CREATE_HOUR_MAX_TODAY THEN PROD_PRICE_NET_EUR_VAL/COUNT_BY_DAYS ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_AVG_BY_CURR_HOUR
    ,SUM(CASE WHEN LT_RELATIVE_DT = 'SDWLY' AND CUST_ORDER_CREATE_HOUR <= CUST_ORDER_CREATE_HOUR_MAX_TODAY THEN PROD_PRICE_NET_EUR_VAL ELSE NULL END) AS PROD_PRICE_NET_EUR_VAL_SDWLY_CURR_HOUR
FROM
    (SELECT
        WSHOP_CD
        ,CUST_ORDER_NR
        ,PROD_VARIANT_SID
        ,CUST_ORDER_DT
        ,VERSION_DT
        ,CASE
            WHEN CUST_ORDER_DT = VERSION_DT THEN 'TODAY'                          -- Today
            WHEN CUST_ORDER_DT = DATEADD(DAY, - 1, VERSION_DT) THEN 'BY'          -- Business year to date excluding today                
            ELSE 'SDWLY' END AS LT_RELATIVE_DT                                    -- Same day of the week last year
        ,HOUR(CUST_ORDER_CREATE_TM) AS CUST_ORDER_CREATE_HOUR
        ,PROD_PRICE_NET_EUR_VAL
        ,(SELECT
            MAX(CASE WHEN  CUST_ORDER_DT = VERSION_DT THEN HOUR(CUST_ORDER_CREATE_TM) ELSE NULL END)
        FROM FE_MSTR_LIDLDIGITAL.T_FACT_CUSTOMER_ORDER_LINE_LIVE_1
        WHERE IS_PART_OF_BUNDLE_HEADER_CNT_FG = 'TRUE' AND VERSION_DT = CURRENT_DATE()) AS CUST_ORDER_CREATE_HOUR_MAX_TODAY            -- Support column to calculate Business year to date and Same day of the week last year sales_1 up to the current hour today
        ,(SELECT COUNT(DISTINCT INCL_CAL_DT) - 1 FROM FE_MSTR_LIDLDIGITAL.V_CAL_CUM_BUSINESS_YEAR_TO_DATE_1 WHERE CAL_DT = VERSION_DT) AS COUNT_BY_DAYS        -- Support column to calculate Average sales_1 for the Business year to date
    FROM FE_MSTR_LIDLDIGITAL.T_FACT_CUSTOMER_ORDER_LINE_LIVE_1
    WHERE IS_PART_OF_BUNDLE_HEADER_CNT_FG = 'TRUE' AND VERSION_DT = CURRENT_DATE())
GROUP BY
     WSHOP_CD
    ,CUST_ORDER_NR
    ,PROD_VARIANT_SID
    ,LT_RELATIVE_DT
    ,CUST_ORDER_CREATE_HOUR
;