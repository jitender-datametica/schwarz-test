CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_DLZ_QUALITY_CHECK_1(
	PK
	,PACK_SID
	,GERMAN_CARRIER_FG
	,INTERNATIONAL_CARRIER_FG
	,HAULER_SID
	,HAULER
	,HAULER_COUNTRY_CD
	,PACK_TRACKING_NR
	,PACK_ORDER_NR
	,API_URL
	,PACK_TRACKING_URL
	,CUSTOMER_PUNCTUALITY_SHIPMENT_LEVEL
	,CUST_DELIVERY_TGT_DT
	,QUALITY_CHECK_DATE
	,FIRST_ATTEMPT_DELIVERY_TMSP
	,DELIVERY_EVENT_WAS_RECORDED_FG
	,LAST_EVENT
	,LAST_EVENT_TMSP
	,MIN_EVENT_TMSP
	,MAX_EVENT_TMSP
	,DATA_QUALITY_ISSUE_FG
	,MISSING_HUID_FG
	,MISSING_DATA_TRANSFER_FG
	,MISSING_FIRST_HUB_SCAN_FG
	,MISSING_BOTH_HUB_SCAN_FG
	,DWH_SRC_FILE_NAME
) AS
WITH
-- Select package_1 shipment data from core from the last 50 days
    nr_list AS (
        SELECT
            CONCAT_WS( '_', pack_tracking_nr, hauler_sid )      AS pk_audit        -- PK in the audit table, when aggregated at package_1 level
            ,pack_sid                                           AS pack_sid        -- PK in the core table, built on pack_order_nr = huid
            ,pack_tracking_nr                                   AS tracking_nr
            ,cust_delivery_tgt_dt
            ,first_attempt_delivery_tmsp
        FROM
            lec_share.v_fact_sales_package_shipment_1
        WHERE
                cust_delivery_tgt_dt >= TO_DATE( CURRENT_DATE() - 50 )
            AND
                LEN( TRIM( pack_tracking_nr ) ) > 0             -- Exclude records without a valid pack_tracking_nr (not relevant for carrierlayer_track_trace data quality checks)
    )
    
-- Select the data from the ETL audit table
    ,cte_etl AS (
        SELECT
             CONCAT_WS( '_'
                  ,t1.pack_tracking_nr
                  ,t1.hauler_sid
             )                          AS pk_audit     -- Primary key for the aggregated package_1 level (see below)
            ,t1.pack_sid                                  -- Based on pack_order_nr
            ,t1.pack_order_nr                             -- Internal package_1 number = HUID (SAP key, link to other tables) 
            ,t1.pack_tracking_nr                          -- External package_1 number, generated by the hauler/carrier
            ,t1.hauler_sid
            ,t2.hauler_name
            ,t2.hauler_country_cd
            ,t1.event_type_name
            ,t1.carrierlayer_event_tmsp
            ,t1.pack_tracking_url
            ,IFF( t1.pack_order_nr IS NULL, 1, 0 )                                AS null_huid_fg    
            ,IFF( t1.event_type_name = 'DATA_TRANSFERED_TO_CARRIER', 1, 0 )       AS data_transfer_fg
            ,IFF( t1.event_type_name = 'FIRST_HUB_SCAN', 1, 0 )                   AS first_hub_scan_fg
            ,IFF( t1.event_type_name LIKE '%HUB_SCAN', 1, 0 )                     AS hub_scan_events_fg
            ,CASE WHEN (
                            ( t1.event_type_name LIKE '%DELIVERY%' )
                        OR  ( ( t2.hauler_country_cd != 'DE' OR t2.hauler_name = 'DE_DPD' ) AND t1.event_type_name = 'CUSTOMER_INTERVENTION' )
                        OR  ( t2.hauler_country_cd = 'DE' AND t1.event_type_name IN ( 'PARCEL_STOPPED', 'DAMAGED_UNSUCCESSFUL' ) )
                ) THEN 1
                    ELSE 0
            END                                                                 AS delivery_event_fg
            ,FIRST_VALUE( t1.event_type_name ) OVER ( PARTITION BY t1.pack_tracking_nr, t1.hauler_sid ORDER BY t1.carrierlayer_event_tmsp DESC )   AS last_event
            ,t1.dwh_src_file_name
        FROM
            lec_share.v_fact_carrierlayer_track_trace_audit_1 AS t1_1
		INNER JOIN
			lec_share.v_dim_hauler_1 AS t2			ON t1.hauler_sid = t2.hauler_sid
        WHERE
            pk_audit IN (
                SELECT pk_audit FROM nr_list
            )
        AND NOT t1.event_type_name IN ( 'UNKNOWN', 'IGNORE' )     -- Filter out dummy_1 events
		AND t2.dwh_valid_fg
    )
    ,package_level_audit AS (
        SELECT
            pk_audit
            ,ANY_VALUE(pack_sid)                                                   AS pack_sid 
            ,ANY_VALUE(pack_order_nr)                                              AS pack_order_nr 
            ,ANY_VALUE( pack_tracking_nr )                                         AS tracking_nr
            ,ANY_VALUE( hauler_sid )                                               AS hauler_sid
            ,ANY_VALUE( hauler_name )                                              AS hauler
            ,ANY_VALUE( hauler_country_cd )                                        AS hauler_country_cd
            ,ANY_VALUE( pack_tracking_url )                                        AS tracking_url
            ,IFF( ANY_VALUE( hauler_country_cd ) = 'DE', 1, 0 )::BOOLEAN           AS german_carrier_fg
            ,NOT german_carrier_fg                                                 AS international_carrier_fg
            ,ANY_VALUE( last_event )                                               AS last_event
            ,MAX( carrierlayer_event_tmsp )                                        AS max_event_tmsp
            ,MIN( carrierlayer_event_tmsp )                                        AS min_event_tmsp
            ,IFF( SUM( null_huid_fg ) > 0, 1, 0 )                                  AS missing_huid_fg              -- Main issue (missing key huid/pack_order_nr)
            ,IFF( SUM( data_transfer_fg ) = 0, 1, 0 )                              AS missing_data_transfer_fg
            ,IFF( SUM( first_hub_scan_fg ) = 0, 1, 0 )                             AS missing_first_hub_scan_fg    -- There should always be a first hub scan 
            ,IFF( SUM( hub_scan_events_fg ) = 0, 1, 0 )                            AS missing_hub_scan_events_fg     -- If scan events are missing then records get filtered out later on     
            ,IFF( SUM( delivery_event_fg ) = 0, 1, 0 )                             AS missing_delivery_event_fg    -- Checks whether a delivery event was recorded for this package_1
            ,ANY_VALUE( dwh_src_file_name )                                        AS dwh_src_file_name
        FROM
            cte_etl
        GROUP BY        -- Aggregated at package_1 level
            pk_audit          
    )
    ,overview AS (
        SELECT
            t1.pk_audit                                                                                             AS pk
            ,t1.pack_sid                                                                                            AS pack_sid       
            ,t1.german_carrier_fg                                                                                   AS german_carrier_fg
            ,t1.international_carrier_fg                                                                            AS international_carrier_fg
            ,t1.hauler_sid                                                                                          AS hauler_sid
            ,t1.hauler                                                                                              AS hauler
            ,t1.hauler_country_cd                                                                                   AS hauler_country_cd
            ,t1.tracking_nr                                                                                         AS pack_tracking_nr
            ,t1.pack_order_nr                                                                                       AS pack_order_nr
            ,CONCAT( 'https://kep-parcel-status_1-api.prod.sit.sys.odj.cloud/api/tracking-ids/', t1.tracking_nr )     AS api_url
            ,tracking_url                                                                                           AS pack_tracking_url
            ,CASE
                WHEN DATEDIFF(DAY, t2.cust_delivery_tgt_dt, t2.first_attempt_delivery_tmsp) <= 0
                    THEN 'pünktlich'
                WHEN DATEDIFF(DAY, t2.cust_delivery_tgt_dt, t2.first_attempt_delivery_tmsp) > 0
                    THEN 'zu spät'
                ELSE 'Zustellung nicht bestätigt'
            END                                                                                                     AS customer_punctuality_shipment_level
            ,t2.cust_delivery_tgt_dt                                                                                AS cust_delivery_tgt_dt
            ,t2.cust_delivery_tgt_dt                                                                                AS quality_check_date
            ,t2.first_attempt_delivery_tmsp                                                                         AS first_attempt_delivery_tmsp        
            ,IFF( t1.missing_delivery_event_fg = 1, 0, 1 )                                                          AS delivery_event_was_recorded_fg
            ,t1.last_event                                                                                          AS last_event
            ,t1.max_event_tmsp                                                                                      AS last_event_tmsp
            ,t1.min_event_tmsp                                                                                      AS min_event_tmsp
            ,t1.max_event_tmsp                                                                                      AS max_event_tmsp
            ,IFF( missing_huid_fg + missing_hub_scan_events_fg = 0, 0, 1 )                                          AS data_quality_issue_fg    -- Summary flag for known data quality issues        
            ,t1.missing_huid_fg                                                                                     AS missing_huid_fg
            ,t1.missing_data_transfer_fg                                                                            AS missing_data_transfer_fg
            ,t1.missing_first_hub_scan_fg                                                                           AS missing_first_hub_scan_fg
            ,t1.missing_hub_scan_events_fg                                                                          AS missing_both_hub_scan_fg
            ,t1.dwh_src_file_name                                                                                   AS dwh_src_file_name
        FROM
            package_level_audit                         AS t1_1
        LEFT JOIN
            nr_list                                     AS t2       ON t1.pk_audit = t2.pk_audit
    )
SELECT
    pk
    ,pack_sid       
    ,german_carrier_fg
    ,international_carrier_fg
    ,hauler_sid
    ,hauler
    ,hauler_country_cd
    ,pack_tracking_nr
    ,pack_order_nr
    ,api_url
    ,pack_tracking_url
    ,customer_punctuality_shipment_level
    ,cust_delivery_tgt_dt
    ,quality_check_date
    ,first_attempt_delivery_tmsp        
    ,delivery_event_was_recorded_fg
    ,last_event
    ,last_event_tmsp
    ,min_event_tmsp
    ,max_event_tmsp
    ,data_quality_issue_fg
    ,missing_huid_fg
    ,missing_data_transfer_fg
    ,missing_first_hub_scan_fg
    ,missing_both_hub_scan_fg
    ,dwh_src_file_name
FROM
    overview
;