CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_GOODS_PACKAGE_SHIPMENT_1
/*
    This view is referenced in V_FACT_GOODS_MASTER_1
*/
AS SELECT
     FACT_GPS.PACK_SID AS PACK_SID
    ,FACT_GPS.PACK_ORDER_NR AS PACK_ORDER_NR
    ,FACT_GPS.PACK_TRACKING_NR AS PACK_TRACKING_NR
    ,FACT_GPS.PACK_TRACKING_URL AS PACK_TRACKING_URL
    ,FACT_GPS.EWM_PACK_NR AS EWM_PACK_NR
    ,CONVERT_TIMEZONE('Europe/Berlin', FACT_GPS.PACK_ORDER_ACTUAL_CREATE_TMSP)::TIMESTAMP_NTZ AS PACK_ORDER_ACTUAL_CREATE_TMSP
    ,FACT_GPS.PACK_MATERIAL_NR AS PACK_MATERIAL_NR
    ,IFNULL(FACT_GPS.PACK_VOLUME_UOM_SID, '-1') AS PACK_VOLUME_UOM_SID
    ,FACT_GPS.PACK_VOLUME_MEAS AS PACK_VOLUME_MEAS
    ,LEFT(FACT_GPS.PACK_VOLUME_MEAS || ' ' || UOM_PACK_VOLUME.UOM_CD, 20)::VARCHAR(20) AS PACK_VOLUME_STR
    ,FACT_GPS.PACK_VOLUME_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_VOLUME_MEAS_STANDARD
    ,IFNULL(UOM_PACK_VOLUME.UOM_STANDARD_CD, '-1') AS PACK_VOLUME_MEAS_STANDARD_UOM_CD
    ,IFNULL(FACT_GPS.PACK_HEIGHT_UOM_SID, '-1') AS PACK_HEIGHT_UOM_SID
    ,FACT_GPS.PACK_HEIGHT_MEAS AS PACK_HEIGHT_MEAS
    ,LEFT(FACT_GPS.PACK_HEIGHT_MEAS || ' ' || UOM_PACK_HEIGHT.UOM_CD, 20)::VARCHAR(20) AS PACK_HEIGHT_STR
    ,FACT_GPS.PACK_HEIGHT_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_HEIGHT_MEAS_STANDARD
    ,IFNULL(UOM_PACK_HEIGHT.UOM_STANDARD_CD, '-1') AS PACK_HEIGHT_MEAS_STANDARD_UOM_CD
    ,IFNULL(FACT_GPS.PACK_WEIGHT_UOM_SID, '-1') AS PACK_WEIGHT_UOM_SID
    ,FACT_GPS.PACK_WEIGHT_MEAS AS PACK_WEIGHT_MEAS
    ,LEFT(FACT_GPS.PACK_WEIGHT_MEAS || ' ' || UOM_PACK_WEIGHT.UOM_CD, 20)::VARCHAR(20) AS PACK_WEIGHT_STR
    ,FACT_GPS.PACK_WEIGHT_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_WEIGHT_MEAS_STANDARD
    ,IFNULL(UOM_PACK_WEIGHT.UOM_STANDARD_CD, '-1') AS PACK_WEIGHT_MEAS_STANDARD_UOM_CD
    ,IFNULL(FACT_GPS.PACK_WIDTH_UOM_SID, '-1') AS PACK_WIDTH_UOM_SID
    ,FACT_GPS.PACK_WIDTH_MEAS AS PACK_WIDTH_MEAS
    ,LEFT(FACT_GPS.PACK_WIDTH_MEAS || ' ' || UOM_PACK_WIDTH.UOM_CD, 20)::VARCHAR(20) AS PACK_WIDTH_STR
    ,FACT_GPS.PACK_WIDTH_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_WIDTH_MEAS_STANDARD
    ,IFNULL(UOM_PACK_WIDTH.UOM_STANDARD_CD, '-1') AS PACK_WIDTH_MEAS_STANDARD_UOM_CD
    ,FACT_GPS.PACK_LONGEST_LENGTH_MEAS AS PACK_LONGEST_LENGTH_MEAS
    ,FACT_GPS.PACK_SHORTEST_LENGTH_MEAS AS PACK_SHORTEST_LENGTH_MEAS
    ,FACT_GPS.PACK_MEAN_LENGTH_MEAS AS PACK_MEAN_LENGTH_MEAS
    ,IFNULL(FACT_GPS.PACK_LENGTH_UOM_SID, '-1') AS PACK_LENGTH_UOM_SID
    ,FACT_GPS.PACK_LENGTH_MEAS AS PACK_LENGTH_MEAS
    ,LEFT(FACT_GPS.PACK_MEAN_LENGTH_MEAS || ' ' || UOM_PACK_LENGTH.UOM_CD, 20)::VARCHAR(20) AS PACK_MEAN_LENGTH_STR
    ,FACT_GPS.PACK_MEAN_LENGTH_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_MEAN_LENGTH_MEAS_STANDARD
    ,LEFT(FACT_GPS.PACK_SHORTEST_LENGTH_MEAS || ' ' || UOM_PACK_LENGTH.UOM_CD, 20)::VARCHAR(20) AS PACK_SHORTEST_LENGTH_STR
    ,FACT_GPS.PACK_SHORTEST_LENGTH_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_SHORTEST_LENGTH_MEAS_STANDARD
    ,LEFT(FACT_GPS.PACK_LONGEST_LENGTH_MEAS || ' ' || UOM_PACK_LENGTH.UOM_CD, 20)::VARCHAR(20) AS PACK_LONGEST_LENGTH_STR
    ,FACT_GPS.PACK_LONGEST_LENGTH_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_LONGEST_LENGTH_MEAS_STANDARD
    ,IFNULL(UOM_PACK_LENGTH.UOM_STANDARD_CD, '-1') AS PACK_LENGTH_MEAS_STANDARD_UOM_CD
    ,IFNULL(FACT_GPS.PACK_GIRTH_UOM_SID, '-1') AS PACK_GIRTH_UOM_SID
    ,FACT_GPS.PACK_GIRTH_EAST_MEAS AS PACK_GIRTH_EAST_MEAS
    ,FACT_GPS.PACK_GIRTH_WEST_MEAS AS PACK_GIRTH_WEST_MEAS
    ,LEFT(FACT_GPS.PACK_GIRTH_WEST_MEAS || ' ' || UOM_PACK_GIRTH.UOM_CD, 20)::VARCHAR(20) AS PACK_GIRTH_WEST_STR
    ,FACT_GPS.PACK_GIRTH_WEST_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_GIRTH_WEST_MEAS_STANDARD
    ,LEFT(FACT_GPS.PACK_GIRTH_EAST_MEAS || ' ' || UOM_PACK_GIRTH.UOM_CD, 20)::VARCHAR(20) AS PACK_GIRTH_EAST_STR
    ,FACT_GPS.PACK_GIRTH_EAST_MEAS * UOM_PACK_WIDTH.UOM_STANDARD_MULTIPL_MEAS AS PACK_GIRTH_EAST_MEAS_STANDARD
    ,IFNULL(UOM_PACK_GIRTH.UOM_STANDARD_CD, '-1') AS PACK_GIRTH_MEAS_STANDARD_UOM_CD

    ,FACT_GPS.IS_PRODUCTSIZE_USED_FG AS IS_PRODUCTSIZE_USED_FG
    ,IFNULL(FACT_GPS.DELIVERY_ORDER_SID, '-1') AS DELIVERY_ORDER_SID
FROM
    lec_share.v_fact_goods_package_shipment_1 FACT_GPS
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_PACK_HEIGHT ON UOM_PACK_HEIGHT.UOM_SID = IFNULL(FACT_GPS.PACK_HEIGHT_UOM_SID, '-1') 
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_PACK_WIDTH ON UOM_PACK_WIDTH.UOM_SID = IFNULL(FACT_GPS.PACK_WIDTH_UOM_SID, '-1') 
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_PACK_LENGTH ON UOM_PACK_LENGTH.UOM_SID = IFNULL(FACT_GPS.PACK_LENGTH_UOM_SID, '-1') 
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_PACK_GIRTH ON UOM_PACK_GIRTH.UOM_SID = IFNULL(FACT_GPS.PACK_GIRTH_UOM_SID, '-1') 
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_PACK_WEIGHT ON UOM_PACK_WEIGHT.UOM_SID = IFNULL(FACT_GPS.PACK_WEIGHT_UOM_SID, '-1') 
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_1 UOM_PACK_VOLUME ON UOM_PACK_VOLUME.UOM_SID = IFNULL(FACT_GPS.PACK_VOLUME_UOM_SID, '-1')    
;
