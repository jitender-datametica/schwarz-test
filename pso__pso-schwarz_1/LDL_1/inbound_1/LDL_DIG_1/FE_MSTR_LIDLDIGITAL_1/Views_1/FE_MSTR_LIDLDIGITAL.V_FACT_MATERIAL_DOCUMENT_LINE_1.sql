CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_MATERIAL_DOCUMENT_LINE_1(
	MATERIAL_DOC_NR
	,MATERIAL_DOC_YEAR
	,MATERIAL_DOC_POS_NR
	,WH_SID
	,PROD_VARIANT_SID
	,STORAGE_LOC_CD
	,BOOKING_DT
	,BATCH_NR
	,CURR_CD
	,PROD_GROSS_VAL
	,PROD_QTY
	,MATERIAL_DOC_STOCK_TYPE_CD
	,MATERIAL_DOC_MOV_TYPE_CD
	,MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD
	,MATERIAL_DOC_MOV_REASON_CD
	,MATERIAL_DOC_CONSUM_TYPE_CD
	,MATERIAL_DOC_RECEIPT_TYPE_CD
	,MATERIAL_DOC_DEBIT_CREDIT_CD
	,DELIVERY_ORDER_SID
	,DELIVERY_ORDER_POS_NR
	,UOM_SID
	,ENTRY_PROD_QTY
	,ENTRY_UOM_SID
	,WH_CD
	,CUST_SID
	,SUPPLIER_ORDER_NR
	,SUPPLIER_ORDER_POS_NR
	,PACK_MATERIAL_NR
	,DELIVERY_SRC_TYPE_CD
    ,GC_LC_CD
) AS SELECT
     CASE WHEN MDL_FACT.MATERIAL_DOC_NR = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_NR, '-1') END AS MATERIAL_DOC_NR
    ,IFNULL(MDL_FACT.MATERIAL_DOC_YEAR, '-1') AS MATERIAL_DOC_YEAR
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_POS_NR = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_POS_NR, '-1') END AS MATERIAL_DOC_POS_NR
    ,IFNULL(MDL_FACT.WH_SID, '-1') AS WH_SID
    ,IFNULL(MDL_FACT.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,CASE WHEN MDL_FACT.STORAGE_LOC_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.STORAGE_LOC_CD, '-1') END AS STORAGE_LOC_CD
    ,MDL_FACT.BOOKING_DT AS BOOKING_DT
    ,MDL_FACT.BATCH_NR AS BATCH_NR
    ,CASE WHEN MDL_FACT.CURR_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.CURR_CD, '-1') END AS CURR_CD
    ,MDL_FACT.PROD_GROSS_LOC_VAL * IFF(MDL_FACT.MATERIAL_DOC_DEBIT_CREDIT_CD = 'H', -1, 1) AS PROD_GROSS_VAL -- multiplication with -1/1 required for Lagerbewegungen report. might be included in CORE table in the future
    ,MDL_FACT.PROD_QTY * IFF(MDL_FACT.MATERIAL_DOC_DEBIT_CREDIT_CD = 'H', -1, 1) AS PROD_QTY -- multiplication with -1/1 required for Lagerbewegungen report. might be included in CORE table in the future
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_STOCK_TYPE_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_STOCK_TYPE_CD, '-1') END AS MATERIAL_DOC_STOCK_TYPE_CD
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_MOV_TYPE_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_MOV_TYPE_CD, '-1') END AS MATERIAL_DOC_MOV_TYPE_CD
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD, '-1') END AS MATERIAL_DOC_SPECIAL_STOCK_TYPE_CD
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_MOV_REASON_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_MOV_REASON_CD, '-1') END AS MATERIAL_DOC_MOV_REASON_CD
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_CONSUM_TYPE_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_CONSUM_TYPE_CD, '-1') END AS MATERIAL_DOC_CONSUM_TYPE_CD
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_RECEIPT_TYPE_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_RECEIPT_TYPE_CD, '-1') END AS MATERIAL_DOC_RECEIPT_TYPE_CD
    ,CASE WHEN MDL_FACT.MATERIAL_DOC_DEBIT_CREDIT_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.MATERIAL_DOC_DEBIT_CREDIT_CD, '-1') END AS MATERIAL_DOC_DEBIT_CREDIT_CD
    ,IFNULL(MDL_FACT.DELIVERY_ORDER_SID, '-1') AS DELIVERY_ORDER_SID
    ,IFNULL(MDL_FACT.DELIVERY_ORDER_POS_NR, '-1') AS DELIVERY_ORDER_POS_NR
    ,IFNULL(MDL_FACT.UOM_SID, '-1') AS UOM_SID
    ,MDL_FACT.ENTRY_PROD_QTY AS ENTRY_PROD_QTY
    ,IFNULL(MDL_FACT.ENTRY_UOM_SID, '-1') AS ENTRY_UOM_SID
    ,CASE WHEN MDL_FACT.WH_CD = '' THEN '-1' ELSE IFNULL(MDL_FACT.WH_CD, '-1') END AS WH_CD
    ,IFNULL(MDL_FACT.CUST_SID, '-1') AS CUST_SID
    ,CASE WHEN MDL_FACT.SUPPLIER_ORDER_NR = '' THEN '-1' ELSE IFNULL(MDL_FACT.SUPPLIER_ORDER_NR, '-1') END AS SUPPLIER_ORDER_NR
    ,IFNULL(MDL_FACT.SUPPLIER_ORDER_POS_NR, '-1') AS SUPPLIER_ORDER_POS_NR 
    ,IFNULL(MDL_FACT.PACK_MATERIAL_NR, '-1') AS PACK_MATERIAL_NR
    ,IFNULL(MDL_FACT.DELIVERY_SRC_TYPE_CD,'-1') AS DELIVERY_SRC_TYPE_CD
    ,'GC' AS GC_LC_CD
FROM
    lec_share.v_fact_material_document_line_1 MDL_FACT
    ;