CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PACKAGING_MATERIAL_PRICE_SUPPLIER_1
AS SELECT
     CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD
    ,IFNULL(SUPPLIER_SID, '-1') AS SUPPLIER_SID
    ,IFNULL(PACK_MATERIAL_NR, '-1') AS PACK_MATERIAL_NR
    ,CASE WHEN PRICE_TYPE_CD = '' THEN '-1' ELSE IFNULL(PRICE_TYPE_CD, '-1') END AS PRICE_TYPE_CD
    ,CASE WHEN PRICE_GROUP_CD = '' THEN '-1' ELSE IFNULL(PRICE_GROUP_CD, '-1') END AS PRICE_GROUP_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', ACTIVE_FROM_TMSP)::TIMESTAMP_NTZ AS ACTIVE_FROM_TMSP
    ,CONVERT_TIMEZONE('Europe/Berlin', ACTIVE_TO_TMSP)::TIMESTAMP_NTZ AS ACTIVE_TO_TMSP
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
    ,PRICE_VAL AS PRICE_VAL
    ,PROD_QTY AS PROD_QTY
    ,'GC' AS GC_LC_CD
FROM
    lec_share.v_fact_packaging_material_price_supplier_1
WHERE
    CURR_CD = 'EUR'
    AND CURRENT_TIMESTAMP() BETWEEN ACTIVE_FROM_TMSP AND ACTIVE_TO_TMSP
UNION ALL
    SELECT
         '-1' -- WSHOP_CD
        ,'-1' -- SUPPLIER_SID
        ,'-1' -- PACK_MATERIAL_NR
        ,'-1' -- PRICE_TYPE_CD
        ,'-1' -- PRICE_GROUP_CD
        ,TO_TIMESTAMP_NTZ('1900-01-01') -- ACTIVE_FROM_TMSP
        ,TO_TIMESTAMP_NTZ('1900-01-01') -- ACTIVE_TO_TMSP
        ,'-1' -- CURR_CD
        ,'0' -- PRICE_VAL
        ,'0' -- PROD_QTY
        ,'-1' -- GC_LC_CD
;
