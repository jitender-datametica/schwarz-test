CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_SUPPLIER_1 
/*
    This view is referenced in V_FACT_ARTICLE_MASTER.
*/
AS
WITH CTE AS (
    SELECT
         PPS_FACT.SUPPLIER_SID
        ,PPS_FACT.WSHOP_CD 
        ,IFNULL(PPS_FACT.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
        ,PPS_FACT.ACTIVE_TO_TMSP
        ,PPS_FACT.ACTIVE_FROM_TMSP
        ,CASE WHEN PPS_FACT.CURR_CD = '' THEN '-1' ELSE IFNULL(PPS_FACT.CURR_CD, '-1') END AS CURR_CD
        ,CASE WHEN PPS_FACT.PRICE_TYPE_CD = 'EKP' THEN PPS_FACT.PRICE_VAL END AS EKP_PRICE_EUR_VAL
        ,CASE WHEN PPS_FACT.PRICE_TYPE_CD = 'FKZ' THEN PPS_FACT.PRICE_VAL END AS FKZ_PRICE_EUR_VAL
    FROM
        lec_share.v_fact_product_price_supplier_1 PPS_FACT
    WHERE
        PPS_FACT.CURR_CD = 'EUR' -- must filter to EUR if GC_LC_CD = 'GC'
    AND
        CURRENT_TIMESTAMP() BETWEEN PPS_FACT.ACTIVE_FROM_TMSP AND PPS_FACT.ACTIVE_TO_TMSP
)
SELECT 
     SUPPLIER_SID
    ,WSHOP_CD
    ,PROD_VARIANT_SID
    ,CURR_CD
    ,MAX(EKP_PRICE_EUR_VAL) AS EKP_PRICE_VAL
    ,MAX(FKZ_PRICE_EUR_VAL) AS FKZ_PRICE_VAL
    ,'GC' AS GC_LC_CD

-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
    ,MAX(EKP_PRICE_EUR_VAL) AS EKP_PRICE_EUR_VAL
    ,MAX(FKZ_PRICE_EUR_VAL) AS FKZ_PRICE_EUR_VAL
-- end section
FROM
    CTE
GROUP BY  
     SUPPLIER_SID
    ,WSHOP_CD
    ,PROD_VARIANT_SID
    ,CURR_CD
    ,GC_LC_CD
;
