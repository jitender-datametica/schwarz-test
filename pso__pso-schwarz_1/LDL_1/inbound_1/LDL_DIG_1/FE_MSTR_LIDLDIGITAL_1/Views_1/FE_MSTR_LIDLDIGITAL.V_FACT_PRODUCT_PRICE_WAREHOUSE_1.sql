CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_WAREHOUSE_1
AS SELECT
     WH_SID AS WH_SID
    ,PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,PRICE_TYPE_CD AS PRICE_TYPE_CD
    ,PRICE_GROUP_CD AS PRICE_GROUP_CD
    ,CURR_CD AS CURR_CD
    ,'GC' AS GC_LC_CD
    ,PRICE_EUR_VAL AS PRICE_VAL
    ,WH_CD AS WH_CD
    ,PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,IS_SUBSTITUTION_PRICE_FG AS IS_SUBSTITUTION_PRICE_FG 
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_WAREHOUSE_NO_GC_LC_1

UNION ALL

SELECT
     WH_SID AS WH_SID
    ,PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,PRICE_TYPE_CD AS PRICE_TYPE_CD
    ,PRICE_GROUP_CD AS PRICE_GROUP_CD
    ,CURR_CD AS CURR_CD
    ,'LC' AS GC_LC_CD
    ,PRICE_LOCAL_VAL AS PRICE_VAL
    ,WH_CD AS WH_CD
    ,PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,IS_SUBSTITUTION_PRICE_FG AS IS_SUBSTITUTION_PRICE_FG 
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_WAREHOUSE_NO_GC_LC_1
WHERE
    CURR_CD != 'EUR'
;