CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICE_WAREHOUSE_NO_GC_LC_1
AS SELECT
     IFNULL(FACT_PPW.WH_SID, '-1') AS WH_SID
    ,IFNULL(FACT_PPW.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,CASE WHEN FACT_PPW.PRICE_TYPE_CD = '' THEN '-1' ELSE IFNULL(FACT_PPW.PRICE_TYPE_CD, '-1') END AS PRICE_TYPE_CD
    ,CASE WHEN FACT_PPW.PRICE_GROUP_CD = '' THEN '-1' ELSE IFNULL(FACT_PPW.PRICE_GROUP_CD, '-1') END AS PRICE_GROUP_CD
    ,CASE WHEN FACT_PPW.CURR_CD = '' THEN '-1' ELSE IFNULL(FACT_PPW.CURR_CD, '-1') END AS CURR_CD
    ,FACT_PPW.PRICE_VAL / FACT_CER.EXCHANGE_RATE AS PRICE_EUR_VAL
    ,FACT_PPW.PRICE_VAL AS PRICE_LOCAL_VAL
    ,CASE WHEN FACT_PPW.WH_CD = '' THEN '-1' ELSE IFNULL(FACT_PPW.WH_CD, '-1') END AS WH_CD
    ,FACT_PPW.PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,FACT_PPW.IS_SUBSTITUTION_PRICE_FG AS IS_SUBSTITUTION_PRICE_FG 
FROM
    lec_share.v_fact_product_price_warehouse_1 FACT_PPW
INNER JOIN
    lec_share.v_fact_currency_exchange_rate_1 FACT_CER
    ON
        FACT_PPW.CURR_CD = FACT_CER.FROM_CURR_CD
    AND FACT_CER.ACTIVE_FG = TRUE
    AND FACT_CER.TO_CURR_CD = 'EUR'
INNER JOIN
    lec_share.v_dim_currency_exchange_rate_type_1 DIM_CERT
    ON
        DIM_CERT.CURR_EXCHANGE_RATE_TYPE_CD = FACT_CER.CURR_EXCHANGE_RATE_TYPE_CD
    AND DIM_CERT.IS_GENERAL_USED_FG
WHERE
    FACT_PPW.DWH_VALID_FG = TRUE
;
