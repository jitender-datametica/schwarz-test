	,NULL AS IVP_PRICE_GROSS_VAL
	,ZVP_PRICE_GROSS_LOCAL_VAL AS ZVP_PRICE_GROSS_VAL
    ,'LC' AS GC_LC_CD
-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
    ,VKP_CURR_CD AS VKP_CURR_CD
    ,VKP_PRICE_GROSS_LOCAL_VAL AS VKP_PRICE_GROSS_LOCAL_VAL
    ,VKP_PRICE_GROSS_EUR_VAL AS VKP_PRICE_GROSS_EUR_VAL
    ,VKP_PRICE_NET_LOCAL_VAL AS VKP_PRICE_NET_LOCAL_VAL
    ,VKP_PRICE_NET_EUR_VAL AS VKP_PRICE_NET_EUR_VAL
    ,AKP_CURR_CD AS AKP_CURR_CD
    ,AKP_PRICE_GROSS_LOCAL_VAL AS AKP_PRICE_GROSS_LOCAL_VAL
    ,AKP_PRICE_GROSS_EUR_VAL AS AKP_PRICE_GROSS_EUR_VAL
    ,AKP_PRICE_NET_LOCAL_VAL AS AKP_PRICE_NET_LOCAL_VAL
    ,AKP_PRICE_NET_EUR_VAL AS AKP_PRICE_NET_EUR_VAL
    ,UVP_CURR_CD AS UVP_CURR_CD
    ,UVP_PRICE_GROSS_LOCAL_VAL AS UVP_PRICE_GROSS_LOCAL_VAL
    ,UVP_PRICE_GROSS_EUR_VAL AS UVP_PRICE_GROSS_EUR_VAL
    ,STP_CURR_CD AS STP_CURR_CD
    ,STP_PRICE_GROSS_LOCAL_VAL AS STP_PRICE_GROSS_LOCAL_VAL
    ,STP_PRICE_GROSS_EUR_VAL AS STP_PRICE_GROSS_EUR_VAL
    ,VKZ1_CURR_CD AS VKZ1_CURR_CD
    ,VKZ1_PRICE_GROSS_LOCAL_VAL AS VKZ1_PRICE_GROSS_LOCAL_VAL
    ,VKZ1_PRICE_GROSS_EUR_VAL AS VKZ1_PRICE_GROSS_EUR_VAL
    ,VKZ2_CURR_CD AS VKZ2_CURR_CD
    ,VKZ2_PRICE_GROSS_LOCAL_VAL AS VKZ2_PRICE_GROSS_LOCAL_VAL
    ,VKZ2_PRICE_GROSS_EUR_VAL AS VKZ2_PRICE_GROSS_EUR_VAL
    ,IVP_CURR_CD AS IVP_CURR_CD
    ,IVP_PRICE_GROSS_LOCAL_VAL AS IVP_PRICE_GROSS_LOCAL_VAL
    ,IVP_PRICE_GROSS_EUR_VAL AS IVP_PRICE_GROSS_EUR_VAL
    ,ZVP_CURR_CD AS ZVP_CURR_CD
    ,ZVP_PRICE_GROSS_LOCAL_VAL AS ZVP_PRICE_GROSS_LOCAL_VAL
    ,ZVP_PRICE_GROSS_EUR_VAL AS ZVP_PRICE_GROSS_EUR_VAL
-- end section
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICING_CONDITION_NO_GC_LC_1
WHERE
    CURR_CD != 'EUR'
;
