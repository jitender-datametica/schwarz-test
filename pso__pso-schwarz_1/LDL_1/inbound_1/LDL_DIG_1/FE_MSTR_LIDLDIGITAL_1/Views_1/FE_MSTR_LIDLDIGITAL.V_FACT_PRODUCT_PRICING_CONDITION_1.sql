     WSHOP_CD AS WSHOP_CD
    ,PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,TAX_CLASS_PCT AS TAX_CLASS_PCT
    ,'EUR' AS CURR_CD
	,VKP_PRICE_GROSS_EUR_VAL AS VKP_PRICE_GROSS_VAL
	,VKP_PRICE_NET_EUR_VAL AS VKP_PRICE_NET_VAL
	,AKP_PRICE_GROSS_EUR_VAL AS AKP_PRICE_GROSS_VAL
	,AKP_PRICE_NET_EUR_VAL AS AKP_PRICE_NET_VAL
	,UVP_PRICE_GROSS_EUR_VAL AS UVP_PRICE_GROSS_VAL
	,STP_PRICE_GROSS_EUR_VAL AS STP_PRICE_GROSS_VAL
	,VKZ1_PRICE_GROSS_EUR_VAL AS VKZ1_PRICE_GROSS_VAL
	,VKZ2_PRICE_GROSS_EUR_VAL AS VKZ2_PRICE_GROSS_VAL
	,IVP_PRICE_GROSS_EUR_VAL AS IVP_PRICE_GROSS_VAL
	,ZVP_PRICE_GROSS_EUR_VAL AS ZVP_PRICE_GROSS_VAL
    ,'GC' AS GC_LC_CD
-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
    ,VKP_CURR_CD AS VKP_CURR_CD
    ,VKP_PRICE_GROSS_LOCAL_VAL AS VKP_PRICE_GROSS_LOCAL_VAL
    ,VKP_PRICE_GROSS_EUR_VAL AS VKP_PRICE_GROSS_EUR_VAL
