    ,VKZ2_PRICE_GROSS_LOCAL_VAL AS VKZ2_PRICE_GROSS_LOCAL_VAL
    ,VKZ2_PRICE_GROSS_EUR_VAL AS VKZ2_PRICE_GROSS_EUR_VAL
    ,IVP_CURR_CD AS IVP_CURR_CD
    ,IVP_PRICE_GROSS_LOCAL_VAL AS IVP_PRICE_GROSS_LOCAL_VAL
    ,IVP_PRICE_GROSS_EUR_VAL AS IVP_PRICE_GROSS_EUR_VAL
    ,ZVP_CURR_CD AS ZVP_CURR_CD
    ,ZVP_PRICE_GROSS_LOCAL_VAL AS ZVP_PRICE_GROSS_LOCAL_VAL
    ,ZVP_PRICE_GROSS_EUR_VAL AS ZVP_PRICE_GROSS_EUR_VAL
-- end section
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICING_CONDITION_NO_GC_LC_1
UNION ALL
 SELECT
    /*
        Assumptions for this section:
            - IVP_PRICE_GROSS_VAL is always in EUR, therefore it is never shown for LC
            - the other currencies are either NULL or all entries in a row have the same currency
    */
     WSHOP_CD AS WSHOP_CD
    ,PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,TAX_CLASS_PCT AS TAX_CLASS_PCT
    ,COALESCE(VKP_CURR_CD, AKP_CURR_CD, UVP_CURR_CD, STP_CURR_CD, VKZ1_CURR_CD, VKZ2_CURR_CD, ZVP_CURR_CD) AS CURR_CD 
	,VKP_PRICE_GROSS_LOCAL_VAL AS VKP_PRICE_GROSS_VAL
	,VKP_PRICE_NET_LOCAL_VAL AS VKP_PRICE_NET_VAL
	,AKP_PRICE_GROSS_LOCAL_VAL AS AKP_PRICE_GROSS_VAL
	,AKP_PRICE_NET_LOCAL_VAL AS AKP_PRICE_NET_VAL
	,UVP_PRICE_GROSS_LOCAL_VAL AS UVP_PRICE_GROSS_VAL
	,STP_PRICE_GROSS_LOCAL_VAL AS STP_PRICE_GROSS_VAL
	,VKZ1_PRICE_GROSS_LOCAL_VAL AS VKZ1_PRICE_GROSS_VAL
