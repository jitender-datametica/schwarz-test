CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_SUPPLIER_EVALUATION_MASTER_1(
     SUPPLIER_ORDER_NR
    ,SUPPLIER_ORDER_POS_NR
    ,SUPPLIER_ORDER_DT
    ,SUPPLIER_ORDER_TYPE_CD
    ,SUPPLIER_SID
    ,BOOKING_DT
    ,PURCHASE_PROD_QTY
    ,SUPPLIER_ORDER_CONFIRM_DT
    ,SUPPLIER_PROD_QTY
    ,TGT_PROD_DELIVERY_DT
    ,DELIVERED_PROD_QTY
    ,WH_SID
    ,STORAGE_LOC_CD
    ,PROD_VARIANT_SID
    ,PROD_VARIANT_NR
    ,PROD_PRICE_VAT_PCT
    ,PROD_PRICE_VAT_VAL
    ,PROD_PRICE_NET_LOCAL_VAL
    ,PROD_PRICE_GROSS_LOCAL_VAL
    ,CURR_CD
    ,DELIVERY_SRC_TYPE_CD
    ,IS_DELIVERY_COMPLETED_FG
    ,DELETION_IN_PURCH_DOC_FG
    ,ORDER_STATUS_FG
    ,GTIN_LIDL
    ,GTIN_MANUFACTURER
    ,GTIN_SUPPLIER
) AS SELECT
     IFNULL(FACT_SOL.SUPPLIER_ORDER_NR, '-1') AS SUPPLIER_ORDER_NR
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_POS_NR, '-1') AS SUPPLIER_ORDER_POS_NR
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_DT, DATE('9999-12-31')) AS SUPPLIER_ORDER_DT
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_TYPE_CD, '-1') AS SUPPLIER_ORDER_TYPE_CD
    ,IFNULL(FACT_SOL.SUPPLIER_SID, '-1') AS SUPPLIER_SID
    ,IFNULL(FACT_MDL.BOOKING_DT, DATE('9999-12-31')) AS BOOKING_DT
    ,FACT_MDL.PROD_QTY AS PURCHASE_PROD_QTY
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_CONFIRM_DT, DATE('9999-12-31')) AS SUPPLIER_ORDER_CONFIRM_DT
    ,FACT_SOL.PROD_QTY AS SUPPLIER_PROD_QTY
    ,IFNULL(FACT_SOL.TGT_PROD_DELIVERY_DT, DATE('9999-12-31')) AS TGT_PROD_DELIVERY_DT
    ,FACT_SOL.DELIVERED_PROD_QTY AS DELIVERED_PROD_QTY
    ,IFNULL(FACT_SOL.WH_SID, '-1') AS WH_SID
    ,IFNULL(FACT_GM.STORAGE_LOC_CD, '-1') AS STORAGE_LOC_CD
    ,IFNULL(FACT_SOL.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,IFNULL(FACT_MDL.PROD_VARIANT_NR, '-1') AS PROD_VARIANT_NR
    ,FACT_SOL.PROD_PRICE_VAT_PCT
    ,FACT_SOL.PROD_PRICE_NET_LOCAL_VAL * FACT_SOL.PROD_PRICE_VAT_PCT AS PROD_PRICE_VAT_VAL
    ,FACT_SOL.PROD_PRICE_NET_LOCAL_VAL
    ,FACT_SOL.PROD_PRICE_NET_LOCAL_VAL * (1+(FACT_SOL.PROD_PRICE_VAT_PCT)) AS PROD_PRICE_GROSS_LOCAL_VAL
    ,IFNULL(FACT_SOL.CURR_CD, '-1') AS CURR_CD
    ,IFNULL(FACT_MDL.DELIVERY_SRC_TYPE_CD, '-1') AS DELIVERY_SRC_TYPE_CD
    ,FACT_SOL.IS_DELIVERY_COMPLETED_FG AS IS_DELIVERY_COMPLETED_FG
    ,FACT_SOL.DELETION_IN_PURCH_DOC_FG AS DELETION_IN_PURCH_DOC_FG
    ,CASE 
		WHEN 
			   FACT_SOL.IS_DELIVERY_COMPLETED_FG = '1' 
			OR FACT_SOL.DELETION_IN_PURCH_DOC_FG = '1'
      	    THEN '1'
      	    ELSE '0'
  	  	END
     AS  ORDER_STATUS_FG
    ,REL_PVAN.GTIN_LIDL
    ,REL_PVAN.GTIN_MANUFACTURER
    ,REL_PVAN.GTIN_SUPPLIER
FROM
    lec_share.v_fact_supplier_order_line_1 AS FACT_SOL
LEFT OUTER JOIN
    (SELECT
        SUPPLIER_ORDER_NR
        ,SUPPLIER_ORDER_POS_NR
        ,PROD_VARIANT_NR
        ,MATERIAL_DOC_MOV_TYPE_CD
        ,DELIVERY_SRC_TYPE_CD
        ,MAX(BOOKING_DT) AS BOOKING_DT
        ,SUM(PROD_QTY) AS PROD_QTY
    FROM 
        lec_share.v_fact_material_document_line_1
    WHERE
        MATERIAL_DOC_MOV_TYPE_CD = '101'
    GROUP BY
        SUPPLIER_ORDER_NR
        ,SUPPLIER_ORDER_POS_NR
        ,PROD_VARIANT_NR
        ,MATERIAL_DOC_MOV_TYPE_CD
        ,DELIVERY_SRC_TYPE_CD) AS FACT_MDL
    ON
            FACT_MDL.SUPPLIER_ORDER_NR = FACT_SOL.SUPPLIER_ORDER_NR
        AND FACT_MDL.SUPPLIER_ORDER_POS_NR = FACT_SOL.SUPPLIER_ORDER_POS_NR
LEFT OUTER JOIN
    (SELECT
        SUPPLIER_ORDER_NR
        ,SUPPLIER_ORDER_POS_NR
        ,STORAGE_LOC_CD
     FROM 
        lec_share.v_fact_goods_movement_1
     WHERE
        GOODS_MOV_CAT_GROUP_CD = 'WE'
        AND (SUPPLIER_ORDER_NR, SUPPLIER_ORDER_POS_NR, GOODS_MOV_ACTUAL_TMSP)
            IN (SELECT
                    SUPPLIER_ORDER_NR
                    ,SUPPLIER_ORDER_POS_NR
                    ,MAX(GOODS_MOV_ACTUAL_TMSP)
                FROM 
                    lec_share.v_fact_goods_movement_1 
                WHERE 
                    GOODS_MOV_CAT_GROUP_CD = 'WE'
                GROUP BY
                   SUPPLIER_ORDER_NR
                   ,SUPPLIER_ORDER_POS_NR)
     GROUP BY
        SUPPLIER_ORDER_NR
        ,SUPPLIER_ORDER_POS_NR
        ,STORAGE_LOC_CD) AS FACT_GM
    ON 
            FACT_GM.SUPPLIER_ORDER_NR = FACT_SOL.SUPPLIER_ORDER_NR
        AND FACT_GM.SUPPLIER_ORDER_POS_NR = FACT_SOL.SUPPLIER_ORDER_POS_NR
LEFT OUTER JOIN
    (SELECT
        PROD_VARIANT_SID
        ,MAX(GTIN_LIDL) AS GTIN_LIDL
        ,MAX(GTIN_MANUFACTURER) AS GTIN_MANUFACTURER
        ,MAX(GTIN_SUPPLIER) AS GTIN_SUPPLIER
    FROM
       (SELECT
            PROD_VARIANT_SID
            ,CASE WHEN PROD_ADD_NR_TYPE_CD = 'LI' THEN MAX(PROD_ADD_NR) ELSE NULL END AS GTIN_LIDL
            ,CASE WHEN PROD_ADD_NR_TYPE_CD = 'HE' THEN MAX(PROD_ADD_NR) ELSE NULL END AS GTIN_MANUFACTURER
            ,CASE WHEN PROD_ADD_NR_TYPE_CD = 'SO' THEN MAX(PROD_ADD_NR) ELSE NULL END AS GTIN_SUPPLIER
        FROM
            lec_share.v_rel_product_variant_additional_number_1
        WHERE
            DWH_VALID_FG
        GROUP BY
            PROD_VARIANT_SID
            ,PROD_ADD_NR_TYPE_CD)
    GROUP BY
        PROD_VARIANT_SID) REL_PVAN
    ON
        REL_PVAN.PROD_VARIANT_SID = FACT_SOL.PROD_VARIANT_SID
WHERE
    FACT_SOL.DWH_VALID_FG
    AND FACT_SOL.SUPPLIER_ORDER_TYPE_CD IN ('NB_1','ZNBD','ZAKO','ZAKB','ZLDI','ZNPH','ZNPL','ZUB','ZUB2','ZUB3', 'ZUB5')
;