CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_SUPPLIER_ORDER_LINE_1
/*
    This view is referenced in V_FACT_DROPSHIPMENT_MASTER_1
*/
AS SELECT
     CASE WHEN SUPPLIER_ORDER_NR = '' THEN '-1' ELSE IFNULL(SUPPLIER_ORDER_NR, '-1') END AS SUPPLIER_ORDER_NR
    ,IFNULL(SUPPLIER_ORDER_POS_NR, '-1') AS SUPPLIER_ORDER_POS_NR
    ,CASE WHEN SUPPLIER_ORDER_TYPE_CD = '' THEN '-1' ELSE IFNULL(SUPPLIER_ORDER_TYPE_CD, '-1') END AS SUPPLIER_ORDER_TYPE_CD
    ,IFNULL(PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,SUPPLIER_ORDER_DT AS SUPPLIER_ORDER_DT
    ,IFNULL(SUPPLIER_SID, '-1') AS SUPPLIER_SID
    ,PROD_QTY AS PROD_QTY
    ,DROPSHIPMENT_ORDER_FG AS DROPSHIPMENT_ORDER_FG
    ,IFNULL(CUST_ORDER_SID, '-1') AS CUST_ORDER_SID
    ,CASE WHEN CUST_ORDER_NR = '' THEN '-1' ELSE IFNULL(CUST_ORDER_NR, '-1') END AS CUST_ORDER_NR
    ,IFNULL(CUST_ORDER_POS_NR, '-1') AS CUST_ORDER_POS_NR
    ,IFNULL(PROD_VARIANT_NR, '-1') AS PROD_VARIANT_NR
    ,IFNULL(SUPPLIER_NR, '-1') AS SUPPLIER_NR
    ,SUPPLIER_ORDER_CANCEL_DT AS SUPPLIER_ORDER_CANCEL_DT
FROM
    lec_share.v_fact_supplier_order_line_1
WHERE
    DWH_VALID_FG = TRUE
;
