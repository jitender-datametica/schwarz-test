CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_WAREHOUSE_PROCESSING_1(
	WH_ORDER_POS_NR
	,WH_ORDER_NR
	,WAVE_ID
	,TASK_ID
	,WH_PROCESS_TYPE_CD
	,WH_TASK_STATUS_CD
	,WH_TASK_CONFIRM_TMSP
	,WH_TASK_CONFIRM_HOUR
	,WH_TASK_CREATE_TMSP
	,SORT_TRACK_NAME
	,SORT_TRACK_GROUP
	,PACK_SORT_TRACK_NAME
	,PACK_SORT_TRACK_GROUP
	,DEST_STORAGE_UNIT_NR
	,PROD_QTY
	,WH_SID
	,TGT_PICK_QTY
	,MAX_WAVE_QTY
	,ACTUAL_PICK_QTY
	,WSHOP_CD
    ,DIST_CHANNEL_CD
	,WH_ORDER_PROCESS
	,OUT_INVOICE_DT
	,WH_ORDER_SHIP_TYPE_NAME
	,IS_ORDER_IN_PROGRESS_FG
	,WH_TASK_PROCESSING_STATUS_CD
	,IS_TASK_IN_PROGRESS_FG
) AS SELECT
     L.WH_ORDER_POS_NR AS WH_ORDER_POS_NR
    ,L.WH_ORDER_NR AS WH_ORDER_NR
    ,P.WAVE_ID AS WAVE_ID
    ,P.TASK_ID AS TASK_ID
    ,CASE WHEN P.WH_PROCESS_TYPE_CD = '' THEN '-1' ELSE IFNULL(P.WH_PROCESS_TYPE_CD, '-1') END AS WH_PROCESS_TYPE_CD
    ,CASE WHEN P.WH_TASK_STATUS_CD = '' THEN '-1' ELSE IFNULL(P.WH_TASK_STATUS_CD, '-1') END AS WH_TASK_STATUS_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', P.WH_TASK_CONFIRM_TMSP)::TIMESTAMP_NTZ AS WH_TASK_CONFIRM_TMSP
    ,HOUR(P.WH_TASK_CONFIRM_TMSP) AS WH_TASK_CONFIRM_HOUR
    ,CONVERT_TIMEZONE('Europe/Berlin', P.WH_TASK_CREATE_TMSP)::TIMESTAMP_NTZ AS WH_TASK_CREATE_TMSP
    ,P.SORT_TRACK_NAME AS SORT_TRACK_NAME
    ,CASE
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P0' THEN 'P0'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P1' THEN 'P1'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P2' THEN 'P2'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P3' THEN 'P3'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P4' THEN 'P4'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P5' THEN 'P5'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P6' THEN 'P6'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P7' THEN 'P7'
        WHEN LEFT(P.SORT_TRACK_NAME, 2) = 'P8' THEN 'P8'
        ELSE 'Sonstiges'
     END AS SORT_TRACK_GROUP
    ,CASE WHEN P.PACK_SORT_TRACK_NAME = '' THEN '-1' ELSE IFNULL(P.PACK_SORT_TRACK_NAME, '-1') END AS PACK_SORT_TRACK_NAME
    ,CASE
        WHEN LEFT(P.PACK_SORT_TRACK_NAME, 2) = 'SW' THEN 'Batch'
        WHEN LEFT(P.PACK_SORT_TRACK_NAME, 3) = 'EPO' THEN 'Singles'
        ELSE 'MEPO'
     END AS PACK_SORT_TRACK_GROUP
    ,CASE WHEN P.DEST_STORAGE_UNIT_NR = '' THEN '-1' ELSE IFNULL(P.DEST_STORAGE_UNIT_NR, '-1') END AS DEST_STORAGE_UNIT_NR
    ,P.PROD_QTY AS PROD_QTY
    ,P.WH_SID AS WH_SID
    ,P.TGT_PICK_QTY AS TGT_PICK_QTY
    ,P.MAX_WAVE_QTY AS MAX_WAVE_QTY
    ,P.ACTUAL_PICK_QTY AS ACTUAL_PICK_QTY
    ,CASE WHEN L.WSHOP_CD = '' THEN '-1' ELSE IFNULL(L.WSHOP_CD, '-1') END AS WSHOP_CD
    ,L.DIST_CHANNEL_CD AS DIST_CHANNEL_CD                                                                                                  --PARKSIDE
    ,CASE
        WHEN L.WH_ORDER_DOC_TYPE_CD IN ('ZPLW' , 'ZEPL') THEN 'EPO'
        WHEN L.WH_ORDER_DOC_TYPE_CD IN ('ZEPO' , 'ZEPG', 'ZEPW') THEN 'MEPO'
        WHEN L.WH_ORDER_DOC_TYPE_CD IN ('ZMPG' , 'ZMPO', 'ZEPT', 'ZMPT', 'ZMPW') THEN 'Batch'
        ELSE 'Sonstige'
     END AS WH_ORDER_PROCESS -- Attribute "Process" in LUD Dashboard
    ,L.OUT_INVOICE_DT AS OUT_INVOICE_DT
    ,L.WH_ORDER_SHIP_TYPE_NAME          AS WH_ORDER_SHIP_TYPE_NAME
    ,L.IS_ORDER_IN_PROGRESS_FG          AS IS_ORDER_IN_PROGRESS_FG
    ,P.WH_TASK_PROCESSING_STATUS_CD     AS WH_TASK_PROCESSING_STATUS_CD
	,NULL AS IS_TASK_IN_PROGRESS_FG
FROM
    lec_share.v_fact_warehouse_processing_1 P
JOIN
    lec_share.v_fact_warehouse_order_line_1 L
    ON
        L.WH_ORDER_SID = P.WH_ORDER_SID
        AND L.WH_ORDER_POS_SID = P.WH_ORDER_POS_SID
WHERE
    L.DWH_VALID_FG = TRUE
    AND     P.DWH_VALID_FG = TRUE
;