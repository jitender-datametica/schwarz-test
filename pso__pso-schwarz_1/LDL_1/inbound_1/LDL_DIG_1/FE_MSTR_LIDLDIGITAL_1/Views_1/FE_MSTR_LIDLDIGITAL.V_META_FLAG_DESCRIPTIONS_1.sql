CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_META_FLAG_DESCRIPTIONS_1
/*
    This view provides descriptions for flags in fact tables.
*/
AS SELECT
     FLAG_NAME AS FLAG_NAME
    ,FLAG_VALUE AS FLAG_VALUE
    ,FLAG_DESCR_DE AS FLAG_DESCR_DE
    ,FLAG_DESCR_EN AS FLAG_DESCR_EN
FROM
    FE_MSTR_LIDLDIGITAL.T_META_FLAG_DESCRIPTIONS_1
;
