CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_META_LOAD_TIME_FACT_CUSTOMER_ORDER_LINE_LIVE_1(
	MAX_DWH_UPDATED_TMSP
) AS
SELECT
   CONVERT_TIMEZONE('Europe/Berlin', CONCAT(MAX(CUST_ORDER_DT), ' ', MAX(CUST_ORDER_CREATE_TM)))::TIMESTAMP_NTZ AS MAX_DWH_UPDATED_TMSP
FROM FE_MSTR_LIDLDIGITAL.T_FACT_CUSTOMER_ORDER_LINE_LIVE_1
WHERE IS_PART_OF_BUNDLE_HEADER_CNT_FG = 'TRUE' AND CUST_ORDER_DT = CURRENT_DATE()
;