CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_BRICK_CODE_ATTRIBUTE_VALUE_1
(
    ATTR_CD
    ,PROD_BRICK_CD
    ,ATTR_DESCR
) AS
SELECT
     CASE WHEN ATTR_CD = '' THEN '-1' ELSE IFNULL(ATTR_CD, '-1') END AS ATTR_CD
    ,CASE WHEN PROD_BRICK_CD = '' THEN '-1' ELSE IFNULL(PROD_BRICK_CD, '-1') END AS PROD_BRICK_CD
    ,ATTR_DESCR AS ATTR_DESCR
FROM
    lec_share.v_rel_brick_code_attribute_value_1
WHERE
    DWH_VALID_FG = TRUE
;