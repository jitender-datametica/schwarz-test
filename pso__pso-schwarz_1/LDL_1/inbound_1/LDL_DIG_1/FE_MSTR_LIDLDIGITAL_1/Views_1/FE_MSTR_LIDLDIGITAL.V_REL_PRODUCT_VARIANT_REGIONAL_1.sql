CREATE OR REPLACE  VIEW FE_MSTR_LIDLDIGITAL.V_REL_PRODUCT_VARIANT_REGIONAL_1
(
WSHOP_CD
,PROD_VARIANT_SID
,PROD_VARIANT_NR
,REG_PROD_VARIANT_NAME
,REG_PROD_VARIANT_DESCR
,PROD_SID
,PROD_NR
,REG_PROD_NAME
,PROD_TGT_DELIVERY_TIME
,TAX_CLASS_CD
,MATERIAL_POS_TYPE_CD
,DELIVERY_SRC_TYPE_CD
,PROD_REG_CATALOG_UPDATE_DT
,PROD_REG_CATALOG_INSERT_DT
,SHOP_CAT_SID
,SHOP_CAT_NAME
,SHOP_CAT_LVL4_SID
,SHOP_CAT_LVL4_NAME
,SHOP_CAT_LVL3_SID
,SHOP_CAT_LVL3_NAME
,SHOP_CAT_LVL2_SID
,SHOP_CAT_LVL2_NAME
,SHOP_CAT_LVL1_SID
,SHOP_CAT_LVL1_NAME
,PROD_ONLINE_STATUS_CD
,PROD_LISTING_STATUS_CD
,FIRST_ONLINE_DT
,PACK_SIZE_HANDLE_GROUP_CD
,SHIP_SIZE_HANDLE_GROUP_CD
,PROD_SIZE_HANDLE_GROUP_CD
)
AS
SELECT
WSHOP_CD
,IFNULL(PROD_VARIANT_SID , '-1')
,PROD_VARIANT_NR
,REG_PROD_VARIANT_NAME
,REG_PROD_VARIANT_DESCR
,IFNULL(PROD_SID , '-1')
,PROD_NR
,REG_PROD_NAME
,PROD_TGT_DELIVERY_TIME
,CASE WHEN TAX_CLASS_CD = '' THEN '-1' ELSE IFNULL(TAX_CLASS_CD , '-1') END
,CASE WHEN MATERIAL_POS_TYPE_CD = '' THEN '-1' ELSE IFNULL(MATERIAL_POS_TYPE_CD , '-1') END
,CASE WHEN DELIVERY_SRC_TYPE_CD = '' THEN '-1' ELSE IFNULL(DELIVERY_SRC_TYPE_CD , '-1') END
,PROD_REG_CATALOG_UPDATE_DT
,PROD_REG_CATALOG_INSERT_DT
,IFNULL(SHOP_CAT_SID , '-1')
,SHOP_CAT_NAME
,IFNULL(SHOP_CAT_LVL4_SID , '-1')
,SHOP_CAT_LVL4_NAME
,IFNULL(SHOP_CAT_LVL3_SID , '-1')
,SHOP_CAT_LVL3_NAME
,IFNULL(SHOP_CAT_LVL2_SID , '-1')
,SHOP_CAT_LVL2_NAME
,IFNULL(SHOP_CAT_LVL1_SID , '-1')
,SHOP_CAT_LVL1_NAME
,CASE WHEN TRIM(PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_ONLINE_STATUS_CD , '-1') END -- TRIM is a temporary workaround until data in source table is fixed, see https://jira.schwarz/browse/NBI-4789
,CASE WHEN TRIM(PROD_LISTING_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_LISTING_STATUS_CD , '-1') END -- TRIM is a temporary workaround until data in source table is fixed, see https://jira.schwarz/browse/NBI-4789
,FIRST_ONLINE_DT
,IFNULL(PACK_SIZE_HANDLE_GROUP_CD, '-1')
,CASE WHEN PACK_SIZE_HANDLE_GROUP_CD = 'MF' THEN 'P_KT' --temp logic until this attribute becomes global
    WHEN PACK_SIZE_HANDLE_GROUP_CD = '2MH' THEN 'P_2MH'
    WHEN PACK_SIZE_HANDLE_GROUP_CD = 'NMF' THEN 'P_GT'
    ELSE 'P_-1'
  END AS SHIP_SIZE_HANDLE_GROUP_CD
,IFNULL(PROD_SIZE_HANDLE_GROUP_CD, '-1')
FROM
lec_share.v_rel_product_variant_regional_1
WHERE DWH_VALID_FG ='TRUE' ;