CREATE OR REPLACE VIEW FE_SHS.V_REFDATA_NEGATIVCHECK_DATUMSFORMAT2_1(
	ID,
	FIRSTNAME,
	LASTNAME,
	DATEOFBIRTH,
	COUNTRY_1,
	ZIPCODE,
	CITY,
	STREETNAME,
	STREETNUMBER,
	ADDRESSSUFFIX,
	ADRESSTYP
) AS (

	WITH REFDATA AS (

		SELECT 
			CAST(COLL.Debitor AS INT) AS ID,
			SPLIT_PART(KNA.NAME1, ' ',  1) AS firstName,
			RIGHT(KNA.NAME1, LEN(KNA.NAME1) - CHARINDEX(' ', KNA.NAME1)) AS lastName,
			BUT.BIRTHDT AS DateOfBirth,
			ADRC.COUNTRY_1 AS country_1,
			ADRC.POSTCODE1 AS zipCode,            
			ADRC.CITY1 AS city,           
			ADRC.STREET AS streetName,   
			ADRC.HOUSENUM1 AS streetNumber,      
			ADRC.STRSUPPL2 AS addressSuffix,
			'RA_1' AS Adresstyp
		FROM 
		(
			SELECT DISTINCT
				T1.GPART AS Debitor  
			FROM 
				ETL.T_DFKKCOLL_1 T1_1
				
			LEFT JOIN ETL.T_DFKKOP_1 T2
				ON T1.OPBEL = T2.OPBEL
				AND T1.INKPS = T2.INKPS
				
			WHERE
				T1.GPART != '1000940044'
				AND T1.AGDAT > CURRENT_DATE()-365
				AND T2.AUGST = ''
				
			UNION ALL

			SELECT 
				* 
			FROM 
				(
					VALUES 
						('1040004469'),
						('1040002536'),
						('1040001484'),
						('1040004769'),
						('1040005216'),
						('1040002552'),
						('1040001801'),
						('1040003136'),
						('1040004260'),
						('1040003262'),
						('1040003000'),
						('1040004766'),
						('1040005019'),
						('1040003203'),
						('1040004248'),
						('1040001980'),
						('1040003594'),
						('1040002388'),
						('1040004528'),
						('1040004595'),
						('1040003208')
				) T (Debitor)
		) AS COLL

		LEFT JOIN ETL.T_KNA1_1 AS KNA
			ON coll.Debitor = KNA.KUNNR 

		LEFT JOIN ETL.T_BUT000_1 AS BUT
			ON KNA.KUNNR = BUT.PARTNER

		LEFT JOIN ETL.T_ADRC_1 AS ADRC_1
			ON KNA.ADRNR = ADRC.ADDRNUMBER
      
        WHERE ADRC.COUNTRY_1 = 'DE'
	)

    SELECT * FROM REFDATA
);