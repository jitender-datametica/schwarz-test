CREATE OR REPLACE VIEW FE_SHS.V_REFDATA_NEGATIVCHECK_DATUMSFORMAT2_VERSION2_1(
	ID,
	FIRSTNAME,
	LASTNAME,
	DATEOFBIRTH,
	COUNTRY_1,
	ZIPCODE,
	CITY,
	STREETNAME,
	STREETNUMBER,
	ADDRESSSUFFIX,
	ADRESSTYP
) AS (

    WITH CUST_IDS AS(
        SELECT DISTINCT FOD.CUST_SID AS ID
        FROM CORE.T_FACT_CUSTOMER_FINANCIAL_ORDER_1 FO
        LEFT JOIN 
            CORE.T_FACT_CUSTOMER_FINANCIAL_ORDER_DEBT_1 FOD
            ON FOD.CUST_ORDER_INSTALL_NR = FO.CUST_ORDER_INSTALL_NR
            AND FOD.DWH_VALID_FG = TRUE
        LEFT JOIN 
            CORE.T_FACT_CUSTOMER_ORDER_INSTALLMENT_1 OI
            ON OI.CUST_ORDER_INSTALL_NR = FO.CUST_ORDER_INSTALL_NR
            AND OI.DEBT_COLLECTION_ITEM_NR = FOD.DEBT_COLLECTION_ITEM_NR
            AND OI.DWH_VALID_FG = TRUE
            
        WHERE FO.DWH_VALID_FG = TRUE
            AND FO.DEBT_COLLECTION_START_DT > CURRENT_DATE() - 365
            AND OI.IS_SETTL_FG = FALSE
    )
     SELECT 
        CUST_IDS.ID AS ID
        ,CUST.CUST_FIRST_NAME AS FIRSTNAME
        ,CUST.CUST_LAST_NAME AS LASTNAME
        ,CUST.CUST_BIRTH_DT AS DATEOFBIRTH
    
        ,ADDR.COUNTRY_NAME AS COUNTRY_1
        ,ADDR.ZIP_CD AS ZIPCODE
        ,ADDR.CITY_NAME AS CITY
        ,ADDR.STREET_NAME AS STREETNAME
        ,ADDR.HOUSE_NR AS STREETNUMBER
        ,ADDR.ADDR_SUFFIX AS ADDRESSSUFFIX
        ,'RA_1' AS ADRESSTYP
    
    FROM CUST_IDS
    LEFT JOIN
        CORE.T_DIM_CUSTOMER_1 CUST
        ON CUST.CUST_SID = CUST_IDS.ID
    LEFT JOIN
        CORE.T_DIM_ADDRESS_1 ADDR
        ON CUST.CUST_BILLING_ADDR_SID = ADDR.ADDR_SID 
        AND ADDR.DWH_VALID_FG = TRUE
    WHERE CUST.DWH_VALID_FG = TRUE
        AND ADDR.COUNTRY_NAME = 'DE'
)    
;