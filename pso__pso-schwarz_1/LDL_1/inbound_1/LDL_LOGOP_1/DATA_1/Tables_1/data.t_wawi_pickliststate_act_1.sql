CREATE DYNAMIC TABLE DATA.t_wawi_pickliststate_act_1
 TARGET_LAG = '1 hour' 
 REFRESH_MODE = INCREMENTAL
 INITIALIZE = ON_CREATE 
 WAREHOUSE = WH_LDL_LOGOP_%%environmentAbbreviation%%_DYNAMIC_TABLE_DATA
 CLUSTER BY (CLIENT_ID, WH_NR, DATE(MODDATE)) AS
SELECT 
    CLIENT_ID,
    WAWI_INSTANZ_KZL,
    WH_NR,
    PICKLISTNO,
    ORDERAREA,
    KEYCODE,
    STORENO,
    FORMDATE,
    MODDATE,
    MODUSER,
    OLDKEYCODE,
    SCN,
    DWH_CREATED,
    DWH_UPDATED
FROM 
    DATA.T_WAWI_PICKLISTSTATE_1
WHERE 
    CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
    AND DELETED_FG = 0 
    AND KEYCODE = '6'
    AND MODDATE >= '2025-03-01';