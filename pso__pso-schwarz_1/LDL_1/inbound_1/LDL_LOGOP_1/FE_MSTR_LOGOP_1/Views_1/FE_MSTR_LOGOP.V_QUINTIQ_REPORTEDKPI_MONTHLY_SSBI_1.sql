, ZEROIFNULL((COUNT_SHIFTS_STORE_DELIVERY_MO / NULLIFZERO(COUNT_TRUCKS_STORE_DELIVERY_MO)-1)*100) AS SHARE_DOUBLE_SHIFTS_STORE_DELIVERY_MO
, ZEROIFNULL((COUNT_SHIFTS_NON_STORE_DELIVERY_MO / NULLIFZERO(COUNT_TRUCKS_NON_STORE_DELIVERY_MO)-1)*100) AS SHARE_DOUBLE_SHIFTS_NON_STORE_DELIVERY_MO
, SUM(TOTALNUMPALLETSWITHISDELIVERYTOEXTERNALWAREHOUSEPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISDELIVERYTOEXTERNALWAREHOUSEPLANNEDEXCLDUMMY_MO
, SUM(TOTALNUMPALLETSWITHISDELIVERYTOINTERNALWAREHOUSEPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISDELIVERYTOINTERNALWAREHOUSEPLANNEDEXCLDUMMY_MO
, SUM(TOTALNUMPALLETSWITHISDELIVERYTONONFOODWAREHOUSEPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISDELIVERYTONONFOODWAREHOUSEPLANNEDEXCLDUMMY_MO
, SUM(TOTALNUMPALLETSWITHISSTOCKTRANSFERPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISSTOCKTRANSFERPLANNEDEXCLDUMMY_MO
, SUM(TOTALNUMPALLETSWITHISRECEIVINGCROSSDOCKINGPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISRECEIVINGCROSSDOCKINGPLANNEDEXCLDUMMY_MO
, SUM(TOTALNUMPALLETSWITHISPICKINGCROSSDOCKINGPLANNEDEXCLDUMMY) AS TOTALNUMPALLETSWITHISPICKINGCROSSDOCKINGPLANNEDEXCLDUMMY_MO
