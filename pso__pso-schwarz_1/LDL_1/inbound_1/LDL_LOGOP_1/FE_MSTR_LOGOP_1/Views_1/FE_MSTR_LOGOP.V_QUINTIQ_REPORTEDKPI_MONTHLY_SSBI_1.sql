, SUM(COUNT_TOURS_STORE_DELIVERY) AS COUNT_TOURS_STORE_DELIVERY_MO
, SUM(COUNT_TOURS_NON_STORE_DELIVERY) AS COUNT_TOURS_NON_STORE_DELIVERY_MO
