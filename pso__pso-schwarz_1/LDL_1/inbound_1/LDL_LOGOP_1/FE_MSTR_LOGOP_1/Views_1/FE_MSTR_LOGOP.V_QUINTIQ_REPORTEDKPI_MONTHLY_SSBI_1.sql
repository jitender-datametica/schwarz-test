, ZEROIFNULL(COUNT_TOURS_STORE_DELIVERY_MO / NULLIFZERO(COUNT_SHIFTS_STORE_DELIVERY_MO)) AS TOURS_PER_SHIFT_STORE_DELIVERY_MO
, ZEROIFNULL(COUNT_TOURS_NON_STORE_DELIVERY_MO / NULLIFZERO(COUNT_SHIFTS_NON_STORE_DELIVERY_MO)) AS TOURS_PER_SHIFT_NON_STORE_DELIVERY_MO
, SUM(PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY) AS PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY_MO
, SUM(PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY) AS PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY_MO
