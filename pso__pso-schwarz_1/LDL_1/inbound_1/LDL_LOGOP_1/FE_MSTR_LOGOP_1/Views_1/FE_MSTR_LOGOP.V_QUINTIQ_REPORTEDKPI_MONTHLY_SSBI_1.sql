, SUM(USE_TIME_IN_MIN_PER_SHIFT_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_SHIFT_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_HR_PER_SHIFT_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_SHIFT_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_SEC_PER_SHIFT_NON_STORE_DELIVERY) AS USE_TIME_IN_SEC_PER_SHIFT_NON_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_MIN_PER_SHIFT_NON_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_SHIFT_NON_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_HR_PER_SHIFT_NON_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_SHIFT_NON_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_SEC_PER_TRUCK) AS USE_TIME_IN_SEC_PER_TRUCK_MO
, SUM(USE_TIME_IN_MIN_PER_TRUCK) AS USE_TIME_IN_MIN_PER_TRUCK_MO
, SUM(USE_TIME_IN_HR_PER_TRUCK) AS USE_TIME_IN_HR_PER_TRUCK_MO
, SUM(USE_TIME_IN_SEC_PER_TRUCK_STORE_DELIVERY) AS USE_TIME_IN_SEC_PER_TRUCK_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_MIN_PER_TRUCK_STORE_DELIVERY) AS USE_TIME_IN_MIN_PER_TRUCK_STORE_DELIVERY_MO
, SUM(USE_TIME_IN_HR_PER_TRUCK_STORE_DELIVERY) AS USE_TIME_IN_HR_PER_TRUCK_STORE_DELIVERY_MO
