  CLIENT_ID COMMENT 'Client id - calculated based on the country_1 code'
, LIDL_COUNTRY COMMENT 'Country_1 code. Original field name bic_zmlila'
, SOURCE_SYSTEM COMMENT 'Source system'
, WH_ID COMMENT 'Warehouse ID'
, DELIVERY_DT COMMENT 'Inidcates the delivery day of the reporting line '
, PALLETS_TOTAL
, PALLET_STORES
, PALLET_NON_STORES
, COUNT_TRUCKS_TOTAL
, COUNT_TRUCKS_STORE_DELIVERY
, COUNT_TRUCKS_NON_STORE_DELIVERY
, COUNT_SHIFTS_TOTAL
, COUNT_SHIFTS_STORE_DELIVERY
, COUNT_SHIFTS_NON_STORE_DELIVERY
, USE_TIME_IN_SEC
, USE_TIME_IN_MIN
, USE_TIME_IN_HR
, USE_TIME_IN_SEC_STORE_DELIVERY
, USE_TIME_IN_MIN_STORE_DELIVERY
, USE_TIME_IN_HR_STORE_DELIVERY
, USE_TIME_IN_SEC_NON_STORE_DELIVERY
, USE_TIME_IN_MIN_NON_STORE_DELIVERY
, USE_TIME_IN_HR_NON_STORE_DELIVERY
, KILOMETER
, KILOMETER_STORE_DELIVERY
, KILOMETER_NON_STORE_DELIVERY
, DV_DIESEL_TOTAL
, DV_DIESEL_STORE_DELIVERY
, DV_DIESEL_NON_STORE_DELIVERY
, DV_LNG_TOTAL
, DV_LNG_STORE_DELIVERY
, DV_LNG_NON_STORE_DELIVERY
, DV_CNG_TOTAL
, DV_CNG_STORE_DELIVERY
, DV_CNG_NON_STORE_DELIVERY
, DV_ELEKTRO_TOTAL
, DV_ELEKTRO_STORE_DELIVERY
, DV_ELEKTRO_NON_STORE_DELIVERY
, DV_WASSERSTOFF_TOTAL
, DV_WASSERSTOFF_STORE_DELIVERY
, DV_WASSERSTOFF_NON_STORE_DELIVERY
, COUNT_TOURS_TOTAL
, COUNT_TOURS_STORE_DELIVERY
, COUNT_TOURS_NON_STORE_DELIVERY
, TOURS_PER_SHIFT_TOTAL
, TOURS_PER_SHIFT_STORE_DELIVERY
, TOURS_PER_SHIFT_NON_STORE_DELIVERY
, PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY
, PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY
, PALLETS_PER_SHIFT_TOTAL
, PALLETS_PER_SHIFT_STORE_DELIVERY
, PALLETS_PER_SHIFT_NON_STORE_DELIVERY
, TOTAL_NUM_PALLETS_PLANNED
, TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES
, TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES
, TOTAL_NUM_PALLETS_CAPACITY
, TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_STORE_DELIVERIES
, TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_NON_STORE_DELIVERIES
, UTILIZATION_PERCENT_TOTAL
, UTILIZATION_PERCENT_STORE_DELIVERY
, UTILIZATION_PERCENT_NON_STORE_DELIVERY
, KM_PER_PALLET_TOTAL
, KM_PER_PALLET_STORE_DELIVERY
, KM_PER_PALLET_NON_STORE_DELIVERY
, USE_TIME_IN_SEC_PER_SHIFT
, USE_TIME_IN_MIN_PER_SHIFT
, USE_TIME_IN_HR_PER_SHIFT
, USE_TIME_IN_SEC_PER_SHIFT_STORE_DELIVERY
, USE_TIME_IN_MIN_PER_SHIFT_STORE_DELIVERY
, USE_TIME_IN_HR_PER_SHIFT_STORE_DELIVERY
, USE_TIME_IN_SEC_PER_SHIFT_NON_STORE_DELIVERY
, USE_TIME_IN_MIN_PER_SHIFT_NON_STORE_DELIVERY
, USE_TIME_IN_HR_PER_SHIFT_NON_STORE_DELIVERY
, USE_TIME_IN_SEC_PER_TRUCK
, USE_TIME_IN_MIN_PER_TRUCK
, USE_TIME_IN_HR_PER_TRUCK
, USE_TIME_IN_SEC_PER_TRUCK_STORE_DELIVERY
, USE_TIME_IN_MIN_PER_TRUCK_STORE_DELIVERY
, USE_TIME_IN_HR_PER_TRUCK_STORE_DELIVERY
, USE_TIME_IN_SEC_PER_TRUCK_NON_STORE_DELIVERY
, USE_TIME_IN_MIN_PER_TRUCK_NON_STORE_DELIVERY
, USE_TIME_IN_HR_PER_TRUCK_NON_STORE_DELIVERY
, SHARE_DOUBLE_SHIFTS
, SHARE_DOUBLE_SHIFTS_STORE_DELIVERY
, SHARE_DOUBLE_SHIFTS_NON_STORE_DELIVERY
, TOTALNUMPALLETSWITHISDELIVERYTOEXTERNALWAREHOUSEPLANNEDEXCLDUMMY
, TOTALNUMPALLETSWITHISDELIVERYTOINTERNALWAREHOUSEPLANNEDEXCLDUMMY
, TOTALNUMPALLETSWITHISDELIVERYTONONFOODWAREHOUSEPLANNEDEXCLDUMMY
, TOTALNUMPALLETSWITHISSTOCKTRANSFERPLANNEDEXCLDUMMY
, TOTALNUMPALLETSWITHISRECEIVINGCROSSDOCKINGPLANNEDEXCLDUMMY
, TOTALNUMPALLETSWITHISPICKINGCROSSDOCKINGPLANNEDEXCLDUMMY
) AS
WITH GEO_MAP AS(
/* !!!!!!!!!!!!!! NOT ALL COUNTRIES ARE INCLUDED IN THIS LOGIC !!!!!!!!!!!!!!!!*/
SELECT DISTINCT
   CLIENT_ID
 , WH_ID
 , CASE WHEN CLIENT_ID = 33
		THEN 'CONVERT'
		ELSE 'REGULAR'
   END AS CONV_VAL
 
 , CASE WHEN CLIENT_ID IN (1,2,3,4,5,6,8,12,14,15,16,17,18,19,21,22,23,24,26,28,32,33,34)
		THEN 'STANDARD_SHIFT'
		
		WHEN CLIENT_ID IN (10,11,13,20,25,27,29,31)
		THEN 'SHIFT_INDICATOR'
		
		ELSE NULL
   END AS SHIFT_TYPE
   
FROM DATA.T_QUINTIQ_REPORTEDKPI_1
)

SELECT
   RK.CLIENT_ID
 , RK.LIDL_COUNTRY
 , RK.SOURCE_SYSTEM
 , RK.WH_ID
 , RK.DELIVERY_DT

 , CASE WHEN GM.CONV_VAL = 'CONVERT'
		THEN TOTALNUM1APALLETSPLANNEDEXCLDUMMYCONVERTED + TOTALNUM1BPALLETSPLANNEDEXCLDUMMYCONVERTED 
		ELSE TOTALNUM1BPALLETSPLANNEDEXCLDUMMY + TOTALNUM1APALLETSPLANNEDEXCLDUMMY
   END AS PALLETS_TOTAL

 , CASE WHEN GM.CONV_VAL = 'CONVERT'
		THEN TOTALNUM1APALLETSPLANNEDEXCLDUMMYCONVERTED
		ELSE TOTALNUM1APALLETSPLANNEDEXCLDUMMY
   END AS PALLET_STORES

 , CASE WHEN GM.CONV_VAL = 'CONVERT'
		THEN TOTALNUM1BPALLETSPLANNEDEXCLDUMMYCONVERTED
		ELSE TOTALNUM1BPALLETSPLANNEDEXCLDUMMY
   END AS PALLET_NON_STORES
   
 , TOTALROUTESINUSEEXCLDUMMY								AS COUNT_TRUCKS_TOTAL
 , TOTALROUTESINUSESTOREDELIVERYEXCLDUMMY					AS COUNT_TRUCKS_STORE_DELIVERY
 , TOTALROUTESINUSENONSTOREDELIVERYEXCLDUMMY				AS COUNT_TRUCKS_NON_STORE_DELIVERY

 , CASE WHEN GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN TOTALNUMSHIFTINDICATOREXCLDUMMY
		WHEN GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN TOTALNUMSHIFTSEXCLDUMMY 
		ELSE NULL 
   END AS COUNT_SHIFTS_TOTAL
   
 , CASE WHEN GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN TOTALNUMSHIFTINDICATORSTOREDELIVERYEXCLDUMMY
		WHEN GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN TOTALNUMSHIFTSSTOREDELIVERYEXCLDUMMY 
		ELSE NULL 
   END AS COUNT_SHIFTS_STORE_DELIVERY
   
 , CASE WHEN GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN TOTALNUMSHIFTINDICATORNONSTOREDELIVERYEXCLDUMMY
		WHEN GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN TOTALNUMSHIFTSNONSTOREDELIVERYEXCLDUMMY
		ELSE NULL
   END AS COUNT_SHIFTS_NON_STORE_DELIVERY

 ,(SPLIT_PART(TOTALDURATIONEXCLDUMMY,':',1)*3600
 + SPLIT_PART(TOTALDURATIONEXCLDUMMY,':',2)*60 
 + SPLIT_PART(TOTALDURATIONEXCLDUMMY,':',3))			AS USE_TIME_IN_SEC
 ,USE_TIME_IN_SEC/60 AS USE_TIME_IN_MIN
 ,USE_TIME_IN_SEC/3600 AS USE_TIME_IN_HR
 
 ,(SPLIT_PART(TOTALDURATIONSTOREDELIVERIESEXCLDUMMY,':',1)*3600
 + SPLIT_PART(TOTALDURATIONSTOREDELIVERIESEXCLDUMMY,':',2)*60 
 + SPLIT_PART(TOTALDURATIONSTOREDELIVERIESEXCLDUMMY,':',3))		AS USE_TIME_IN_SEC_STORE_DELIVERY
 ,USE_TIME_IN_SEC_STORE_DELIVERY/60 AS USE_TIME_IN_MIN_STORE_DELIVERY
 ,USE_TIME_IN_SEC_STORE_DELIVERY/3600 AS USE_TIME_IN_HR_STORE_DELIVERY
 
 ,(SPLIT_PART(TOTALDURATIONNONSTOREDELIVERIESEXCLDUMMY,':',1)*3600
 + SPLIT_PART(TOTALDURATIONNONSTOREDELIVERIESEXCLDUMMY,':',2)*60 
 + SPLIT_PART(TOTALDURATIONNONSTOREDELIVERIESEXCLDUMMY,':',3))	AS USE_TIME_IN_SEC_NON_STORE_DELIVERY
 ,USE_TIME_IN_SEC_NON_STORE_DELIVERY/60 AS USE_TIME_IN_MIN_NON_STORE_DELIVERY
 ,USE_TIME_IN_SEC_NON_STORE_DELIVERY/3600 AS USE_TIME_IN_HR_NON_STORE_DELIVERY
 
 , TOTALUSEDDISTANCEEXCLDUMMY 								AS KILOMETER
 , TOTALUSEDDISTANCESTOREDELIVERYEXCLDUMMY 					AS KILOMETER_STORE_DELIVERY
 , TOTALUSEDDISTANCENONSTOREDELIVERYEXCLDUMMY 				AS KILOMETER_NON_STORE_DELIVERY
 , TOTALUSEDDISTANCEDIESELEXCLDUMMY 						AS DV_DIESEL_TOTAL
 , TOTALUSEDDISTANCEDIESELSTOREDELIVERYEXCLDUMMY 			AS DV_DIESEL_STORE_DELIVERY
 , TOTALUSEDDISTANCEDIESELNONSTOREDELIVERYEXCLDUMMY 		AS DV_DIESEL_NON_STORE_DELIVERY
 , TOTALUSEDDISTANCELNGEXCLDUMMY                          	AS DV_LNG_TOTAL
 , TOTALUSEDDISTANCELNGSTOREDELIVERYEXCLDUMMY             	AS DV_LNG_STORE_DELIVERY
 , TOTALUSEDDISTANCELNGNONSTOREDELIVERYEXCLDUMMY          	AS DV_LNG_NON_STORE_DELIVERY
 , TOTALUSEDDISTANCECNGEXCLDUMMY                          	AS DV_CNG_TOTAL
 , TOTALUSEDDISTANCECNGSTOREDELIVERYEXCLDUMMY             	AS DV_CNG_STORE_DELIVERY
 , TOTALUSEDDISTANCECNGNONSTOREDELIVERYEXCLDUMMY          	AS DV_CNG_NON_STORE_DELIVERY
 , TOTALUSEDDISTANCEELECTRICEXCLDUMMY                     	AS DV_ELEKTRO_TOTAL
 , TOTALUSEDDISTANCEELECTRICSTOREDELIVERYEXCLDUMMY        	AS DV_ELEKTRO_STORE_DELIVERY
 , TOTALUSEDDISTANCEELECTRICNONSTOREDELIVERYEXCLDUMMY     	AS DV_ELEKTRO_NON_STORE_DELIVERY
 , TOTALUSEDDISTANCEHYDROGENEXCLDUMMY                     	AS DV_WASSERSTOFF_TOTAL
 , TOTALUSEDDISTANCEHYDROGENSTOREDELIVERYEXCLDUMMY        	AS DV_WASSERSTOFF_STORE_DELIVERY
 , TOTALUSEDDISTANCEHYDROGENNONSTOREDELIVERYEXCLDUMMY     	AS DV_WASSERSTOFF_NON_STORE_DELIVERY
 , NUMTOURSEXCLDUMMY                                      	AS COUNT_TOURS_TOTAL
 , NUMTOURSSTOREDELIVERYEXCLDUMMY                         	AS COUNT_TOURS_STORE_DELIVERY
 , NUMTOURSNONSTOREDELIVERYEXCLDUMMY                      	AS COUNT_TOURS_NON_STORE_DELIVERY

/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - COUNT_TOURS_TOTAL / COUNT_SHIFTS_TOTAL */
 , CASE WHEN GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(NUMTOURSEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTINDICATOREXCLDUMMY))
		WHEN GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(NUMTOURSEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTSEXCLDUMMY))
		ELSE NULL
   END AS TOURS_PER_SHIFT_TOTAL

/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - COUNT_TOURS_STORE_DELIVERY / COUNT_SHIFTS_STORE_DELIVERY */
 , CASE WHEN GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(NUMTOURSSTOREDELIVERYEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTINDICATORSTOREDELIVERYEXCLDUMMY))
		WHEN GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(NUMTOURSSTOREDELIVERYEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTSSTOREDELIVERYEXCLDUMMY))
		ELSE NULL
   END AS TOURS_PER_SHIFT_STORE_DELIVERY

/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - COUNT_TOURS_NON_STORE_DELIVERY / COUNT_SHIFTS_NON_STORE_DELIVERY */
 , CASE WHEN GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(NUMTOURSNONSTOREDELIVERYEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTINDICATORNONSTOREDELIVERYEXCLDUMMY))
		WHEN GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(NUMTOURSNONSTOREDELIVERYEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTSNONSTOREDELIVERYEXCLDUMMY))
		ELSE NULL
   END AS TOURS_PER_SHIFT_NON_STORE_DELIVERY

 , CASE WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTINDICATORSTOREDELIVERIESEXCLDUMMYCONVERTED
	WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTSTOREDELIVERIESEXCLDUMMYCONVERTED
	WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTINDICATORSTOREDELIVERIESEXCLDUMMY
	WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTSTOREDELIVERIESEXCLDUMMY
	ELSE NULL
	END AS PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY

 , CASE WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTINDICATORNONSTOREDELIVERIESEXCLDUMMYCONVERTED
	WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTNONSTOREDELIVERIESEXCLDUMMYCONVERTED
	WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTINDICATORNONSTOREDELIVERIESEXCLDUMMY
	WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
	THEN TOTALNUMPALLETSPLANNEDONSHIFTNONSTOREDELIVERIESEXCLDUMMY
	ELSE NULL
	END AS PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY
	
/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - PALLETS_TOTAL / COUNT_SHIFTS_TOTAL */
 , CASE WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL((TOTALNUM1APALLETSPLANNEDEXCLDUMMYCONVERTED + TOTALNUM1BPALLETSPLANNEDEXCLDUMMYCONVERTED) / NULLIFZERO(TOTALNUMSHIFTINDICATOREXCLDUMMY))
		WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL((TOTALNUM1APALLETSPLANNEDEXCLDUMMYCONVERTED + TOTALNUM1BPALLETSPLANNEDEXCLDUMMYCONVERTED) / NULLIFZERO(TOTALNUMSHIFTSEXCLDUMMY))
		WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL((TOTALNUM1BPALLETSPLANNEDEXCLDUMMY + TOTALNUM1APALLETSPLANNEDEXCLDUMMY) / NULLIFZERO(TOTALNUMSHIFTINDICATOREXCLDUMMY))	
		WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL((TOTALNUM1BPALLETSPLANNEDEXCLDUMMY + TOTALNUM1APALLETSPLANNEDEXCLDUMMY) / NULLIFZERO(TOTALNUMSHIFTSEXCLDUMMY))
   END AS PALLETS_PER_SHIFT_TOTAL

/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - PALLETS_PLANNED_ON_SHIFT_STORE_DELIVERY / COUNT_SHIFTS_STORE_DELIVERY */
 , CASE WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTINDICATORSTOREDELIVERIESEXCLDUMMYCONVERTED / NULLIFZERO(TOTALNUMSHIFTINDICATORSTOREDELIVERYEXCLDUMMY))
		WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTSTOREDELIVERIESEXCLDUMMYCONVERTED / NULLIFZERO(TOTALNUMSHIFTSSTOREDELIVERYEXCLDUMMY))
		WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTINDICATORSTOREDELIVERIESEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTINDICATORSTOREDELIVERYEXCLDUMMY))
		WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTSTOREDELIVERIESEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTSSTOREDELIVERYEXCLDUMMY))
		ELSE NULL 		
   END AS PALLETS_PER_SHIFT_STORE_DELIVERY

/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - PALLETS_PLANNED_ON_SHIFT_NON_STORE_DELIVERY / COUNT_SHIFTS_NON_STORE_DELIVERY */
 , CASE WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTINDICATORNONSTOREDELIVERIESEXCLDUMMYCONVERTED / NULLIFZERO(TOTALNUMSHIFTINDICATORNONSTOREDELIVERYEXCLDUMMY))
		WHEN GM.CONV_VAL = 'CONVERT' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTNONSTOREDELIVERIESEXCLDUMMYCONVERTED / NULLIFZERO(TOTALNUMSHIFTSNONSTOREDELIVERYEXCLDUMMY))
		WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'SHIFT_INDICATOR'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTINDICATORNONSTOREDELIVERIESEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTINDICATORNONSTOREDELIVERYEXCLDUMMY))
		WHEN GM.CONV_VAL = 'REGULAR' AND GM.SHIFT_TYPE = 'STANDARD_SHIFT'
		THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONSHIFTNONSTOREDELIVERIESEXCLDUMMY / NULLIFZERO(TOTALNUMSHIFTSNONSTOREDELIVERYEXCLDUMMY))
		ELSE NULL
   END AS PALLETS_PER_SHIFT_NON_STORE_DELIVERY

  , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED + TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED
	ELSE TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMY + TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMY
	END AS TOTAL_NUM_PALLETS_PLANNED

  , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED
	ELSE TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMY
	END AS TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES

 , CASE WHEN GM.CONV_VAL = 'CONVERT'
		THEN TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED
		ELSE TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMY
   END AS TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES
   
, CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED + TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED
	ELSE TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMY + TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMY
	END AS TOTAL_NUM_PALLETS_CAPACITY
	
 , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED
	ELSE TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMY
	END AS TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_STORE_DELIVERIES
	
 , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED
	ELSE TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMY
	END AS TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_NON_STORE_DELIVERIES

/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - TOTAL_NUM_PALLETS_PLANNED / (TOTAL_NUM_PALLETS_CAPACITY *100) */
 , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN ZEROIFNULL((TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED+TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED) / NULLIFZERO(TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED + TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED) *100)
	ELSE ZEROIFNULL((TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMY + TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMY) / NULLIFZERO(TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMY + TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMY) *100)
	END AS UTILIZATION_PERCENT_TOTAL
 
/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_STORE_DELIVERIES / (TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_STORE_DELIVERIES *100) */
 , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED / NULLIFZERO(TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMYCONVERTED) *100)
	ELSE ZEROIFNULL(TOTALNUMPALLETSPLANNEDONTOURSTOREDELIVERIESEXCLDUMMY / NULLIFZERO(TOTALNUMPALLETSCAPACITYONTOURSTOREDELIVERIESEXCLDUMMY) *100)
	END AS UTILIZATION_PERCENT_STORE_DELIVERY
 
/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - TOTAL_NUM_PALLETS_PLANNED_ON_TOUR_NON_STORE_DELIVERIES / (TOTAL_NUM_PALLETS_CAPACITY_ON_TOUR_NON_STORE_DELIVERIES *100) */
 , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
	THEN ZEROIFNULL(TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED/  NULLIFZERO(TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMYCONVERTED) *100)
	ELSE ZEROIFNULL(TOTALNUMPALLETSPLANNEDONTOURNONSTOREDELIVERIESEXCLDUMMY /  NULLIFZERO(TOTALNUMPALLETSCAPACITYONTOURNONSTOREDELIVERIESEXCLDUMMY) *100)
	END AS UTILIZATION_PERCENT_NON_STORE_DELIVERY
	
/* FOR STRATEGY SETUP, USE THIS CALCULATION FOR THE BELOW KPI - KILOMETER / TOTAL_NUM_PALLETS_PLANNED */
  , CASE
	WHEN GM.CONV_VAL = 'CONVERT'
