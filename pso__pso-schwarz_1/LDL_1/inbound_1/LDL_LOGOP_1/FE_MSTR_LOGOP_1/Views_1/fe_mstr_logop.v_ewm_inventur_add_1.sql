CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_EWM_INVENTUR_ADD_1(
    CLIENT_ID COMMENT 'Client id - calculated based on the country_1 code',
    WH_ID COMMENT 'Warehouse id',
    ARTIKELNR COMMENT 'Item_1 nr',
	FORM_NR COMMENT 'T067 Form nr',
    REPORTED_DATE COMMENT 'T067 and DA Date',
    REASON_ID COMMENT 'T067 and DA Reason id',
	REASON_DESC COMMENT 'T067 and DA Reason description',
    PIECE_QTY COMMENT 'T067 Piece quantity',
    PIECE_QTY_NEG COMMENT 'T067 Summe negierte Piece QTY auf Ebene „C067 Itemnumber“ und „C076 Formdate“ mit Filter„C067 Reason ID“ = 3',
    PIECE_QTY_POS COMMENT 'T067 Summe Piece QTY auf Ebene der „C067 Itemnumber“ und „C076 Formdate“ mit Filter „C067 Reason ID“ = 4',
	FORM_REF_FG COMMENT 'Form Ref Flag: 1 = All ; 2 = Form Nr Ref starts with 2 ; 3 = Difference Analyzer',
    DIFF_QTY COMMENT 'DA Difference QTY. (PC)',
    DIFF_VAL COMMENT 'DA Difference Val.',
    DWH_LOAD_ID COMMENT 'Load id',
    DWH_CREATED COMMENT 'Record created at',
    DWH_UPDATED COMMENT 'Record updated at',
    DWH_VALID_FROM COMMENT 'Valid from date',
    DWH_VALID_TO COMMENT 'Valid to date',
    DELETED_FG COMMENT 'Flag if record is deleted'
) AS
WITH 
-- All Stock Corrections Reference
lustock_all AS (
    SELECT
        CLIENT_ID,
        CASE 
            WHEN CLIENT_ID=13 AND WH_ID = 600 THEN 60 
            WHEN CLIENT_ID=18 AND WH_ID = 20 THEN 4 
            WHEN CLIENT_ID=21 AND WH_ID = 20 THEN 22 ELSE WH_ID
            END AS WH_ID,
        ITEM_NR AS ARTIKELNR,
		FORM_NR,
        FORM_DATE AS T067_FORM_DATE,
        REASON_ID AS T067_REASON_ID,
		REASON_DESC AS T067_REASON_DESC,
        (CASE_QTY*DECIMAL_CASE)+PIECE_QTY AS T067_PIECE_QTY,
        CASE WHEN REASON_ID IN (1,2,3) THEN T067_PIECE_QTY ELSE 0 END AS T067_PIECE_QTY_NEG,
        CASE WHEN REASON_ID = 4 THEN T067_PIECE_QTY ELSE 0 END AS T067_PIECE_QTY_POS,
		CAST(1 AS INTEGER) AS FORM_REF_FG,
        DWH_LOAD_ID,
        DWH_CREATED,
        MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED,
        DWH_VALID_FROM,
        DWH_VALID_TO,
        DELETED_FG
    FROM "DATA".T_WAWI_STOCK_CORR_1
    WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
      AND DELETED_FG = 0
	  AND T067_FORM_DATE > '2024-03-01'
      --AND SCN <> 0 
),
-- Stock Corrections - Tech Differences Reference
lustock_tech AS (
    SELECT
        CLIENT_ID,
        CASE 
            WHEN CLIENT_ID=13 AND WH_ID = 600 THEN 60 
            WHEN CLIENT_ID=18 AND WH_ID = 20 THEN 4 
            WHEN CLIENT_ID=21 AND WH_ID = 20 THEN 22 ELSE WH_ID
            END AS WH_ID,
        ITEM_NR AS ARTIKELNR,
		FORM_NR,
        FORM_DATE AS T067_FORM_DATE,
        REASON_ID AS T067_REASON_ID,
		REASON_DESC AS T067_REASON_DESC,
        (CASE_QTY*DECIMAL_CASE)+PIECE_QTY AS T067_PIECE_QTY,
        CASE WHEN REASON_ID IN (1,2,3) THEN T067_PIECE_QTY ELSE 0 END AS T067_PIECE_QTY_NEG,
        CASE WHEN REASON_ID = 4 THEN T067_PIECE_QTY ELSE 0 END AS T067_PIECE_QTY_POS,
		CAST(2 AS INTEGER) AS FORM_REF_FG,
        DWH_LOAD_ID,
        DWH_CREATED,
        MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED,
        DWH_VALID_FROM,
        DWH_VALID_TO,
        DELETED_FG
    FROM "DATA".T_WAWI_STOCK_CORR_1
    WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
      AND DELETED_FG = 0
	  AND T067_FORM_DATE > '2024-03-01'
      --AND SCN <> 0
	  AND STARTSWITH(FORM_NR_REF,'2')
),
-- Difference Analyzer Reference
ludiff AS (
    SELECT
        CLIENT_ID,
        WH_ID,
        LPAD(MATNR,11,'0') AS ARTIKELNR,
        POSTED_DATE,
        REASON AS REASON_ID,
		REASON_TEXT AS DA_REASON_DESC,
        SUM(UI_QUAN_DIFF) AS DIFF_QTY,
        SUM(VALUE) AS DIFF_VAL,
		CAST(3 AS INTEGER) AS FORM_REF_FG,
        MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED
	FROM "DATA".T_SAPEWM_DIFFERENCEANALYZER_1
    GROUP BY CLIENT_ID, WH_ID, ARTIKELNR, POSTED_DATE, REASON_ID, DA_REASON_DESC, FORM_REF_FG, DWH_UPDATED

)
SELECT
    lusa.CLIENT_ID,
    lusa.WH_ID,
    lusa.ARTIKELNR,
	lusa.FORM_NR,
    lusa.T067_FORM_DATE AS REPORTED_DATE,
    lusa.T067_REASON_ID AS REASON_ID,
	lusa.T067_REASON_DESC AS REASON_DESC,
    lusa.T067_PIECE_QTY AS PIECE_QTY,
    lusa.T067_PIECE_QTY_NEG AS PIECE_QTY_NEG,
    lusa.T067_PIECE_QTY_POS AS PIECE_QTY_POS,
	lusa.FORM_REF_FG,
    NULL AS DIFF_QTY,
    NULL AS DIFF_VAL,
    lusa.DWH_LOAD_ID,
    lusa.DWH_CREATED,
    lusa.DWH_UPDATED,
    lusa.DWH_VALID_FROM,
    lusa.DWH_VALID_TO,
    lusa.DELETED_FG
FROM lustock_all lusa
UNION
SELECT
	lust.CLIENT_ID,
    lust.WH_ID,
    lust.ARTIKELNR,
	lust.FORM_NR,
    lust.T067_FORM_DATE AS REPORTED_DATE,
    lust.T067_REASON_ID AS REASON_ID,
	lust.T067_REASON_DESC AS REASON_DESC,
    lust.T067_PIECE_QTY AS PIECE_QTY,
    lust.T067_PIECE_QTY_NEG AS PIECE_QTY_NEG,
    lust.T067_PIECE_QTY_POS AS PIECE_QTY_POS,
	lust.FORM_REF_FG,
    NULL AS DIFF_QTY,
    NULL AS DIFF_VAL,
    lust.DWH_LOAD_ID,
    lust.DWH_CREATED,
    lust.DWH_UPDATED,
    lust.DWH_VALID_FROM,
    lust.DWH_VALID_TO,
    lust.DELETED_FG
FROM lustock_tech lust
UNION
SELECT
	ludi.CLIENT_ID,
    ludi.WH_ID,
    ludi.ARTIKELNR,
	NULL AS FORM_NR,
    ludi.POSTED_DATE AS REPORTED_DATE,
    ludi.REASON_ID AS REASON_ID,
	ludi.DA_REASON_DESC AS REASON_DESC,
    NULL AS PIECE_QTY,
    NULL AS PIECE_QTY_NEG,
    NULL AS PIECE_QTY_POS,
	ludi.FORM_REF_FG,
    ludi.DIFF_QTY,
    ludi.DIFF_VAL,
    NULL AS DWH_LOAD_ID,
    NULL AS DWH_CREATED,
    ludi.DWH_UPDATED,
    NULL AS DWH_VALID_FROM,
    NULL AS DWH_VALID_TO,
    NULL AS DELETED_FG
FROM ludiff ludi
;