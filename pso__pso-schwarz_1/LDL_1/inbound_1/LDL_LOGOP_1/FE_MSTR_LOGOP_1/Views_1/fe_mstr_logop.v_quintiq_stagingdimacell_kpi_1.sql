CREATE OR REPLACE VIEW fe_mstr_logop.v_quintiq_stagingdimacell_kpi_1 (
   CLIENT_ID COMMENT 'CLIENT ID - CALCULATED BASED ON THE COUNTRY_1 CODE'
 , LIDL_COUNTRY COMMENT 'COUNTRY_1 CODE. ORIGINAL FIELD NAME BIC_ZMLILA'
 , SOURCE_SYSTEM COMMENT 'SOURCE SYSTEM'
 , WH_ID COMMENT 'WAREHOUSE ID'
 , SRC_TGT_DIST COMMENT 'DISTANCE FROM ORIGIN TO DESTINATION ADDRESS_1 (DISREGARD UOM)'
 , SRC_TGT_DUR COMMENT 'DURATION FROM ORIGIN TO DESTIONATION ADDRESS_1 (IN MINUTES) - IMPORTED'
 , SRC_ADDRESS_ID COMMENT 'IDENTIFIER OF THE ORIGIN ADDRESS_1'
 , RESOURCE_TYPE_ID COMMENT 'THE IDENTIFIER FOR RESOURCE TYPE'
 , TIME_PROFILE_ID COMMENT 'IDENTIFIER OF TIME PROFILE'
 , TGT_ADDRESS_ID COMMENT 'IDENTIFIER OF THE DESTINATION ADDRESS_1'
 , TOLL_DIST2 COMMENT 'DISTANCE FOR WHICH THE SECOND TYPE OF TOLL IS CONSIDERED'
 , TOLL_DIST COMMENT 'DISTANCE FOR WHICH FIRST TYPE OF TOLL IS CONSIDERED'
 , TOLLDISTANCE3 COMMENT 'DISTANCE FOR WHICH THE THIRD TYPE OF TOLL IS CONSIDERED IN KILOMETERS'
 , DWH_LOAD_ID COMMENT 'LOAD ID'
 , DWH_CREATED COMMENT 'RECORD CREATED AT'
 , DWH_UPDATED COMMENT 'RECORD UPDATED AT'
 , DWH_VALID_FROM COMMENT 'VALID FROM DATE'
 , DWH_VALID_TO COMMENT 'VALID TO DATE'
 , DELETED_FG COMMENT 'FLAG IF RECORD IS DELETED'
 , ACTIVE_FG COMMENT 'FLAG IF RECORD IS ACTIVE'
) COMMENT='QUINTIQ - VIEW WITH FINAL KPIS FOR FE'
 AS 
SELECT
   CLIENT_ID
 , LIDL_COUNTRY
 , SOURCE_SYSTEM
 , WH_ID
 , SRC_TGT_DIST
 , SRC_TGT_DUR
 , SRC_ADDRESS_ID
 , RESOURCE_TYPE_ID
 , TIME_PROFILE_ID
 , TGT_ADDRESS_ID
 , TOLL_DIST2
 , TOLL_DIST
 , TOLLDISTANCE3
 , DWH_LOAD_ID
 , DWH_CREATED
 , DWH_UPDATED
 , DWH_VALID_FROM
 , DWH_VALID_TO
 , DELETED_FG
 , IFF(DWH_VALID_TO = '9999-12-30', 1, 0) AS ACTIVE_FG
FROM FE_MSTR_LOGOP.V_QUINTIQ_STAGINGDIMACELL_1;