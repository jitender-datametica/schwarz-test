CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_WAWI_BESTANDARTIKEL_ACT_1 AS
	SELECT
        CLIENT_ID
        ,CASE 
            WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
            WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
            WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
            END AS WH_NR
        ,ARTIKELNR
        ,MENGE
		,RETAIL_PRICE
        ,SCN
        ,TO_DATE(DATUM) AS DATUM
        ,DWH_VALID_FROM
        ,DWH_VALID_TO
        ,MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_NR) AS DWH_UPDATED
        ,DELETED_FG
    FROM
        "DATA".T_WAWI_BESTANDARTIKEL_ACT_1
;