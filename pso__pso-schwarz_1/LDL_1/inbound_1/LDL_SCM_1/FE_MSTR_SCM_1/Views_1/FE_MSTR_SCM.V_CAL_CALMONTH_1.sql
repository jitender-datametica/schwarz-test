CREATE OR REPLACE VIEW FE_MSTR_SCM.V_CAL_CALMONTH_1(
	 CAL_MONTH
	,PREV_MONTH
	,PREV_CY_MONTH
	,PREPREV_CY_MONTH
	,PREPREVPREV_CY_MONTH
	,CY
	,BUSYEAR
	,CY_MONTH_SEQ
	,MONTH_ID
	,MONTH_NAME
) AS
SELECT
	CY_MONTH 
	,PREV_MONTH
	,PREV_CY_MONTH
	,PREPREV_CY_MONTH
	,PREPREVPREV_CY_MONTH
	,CY
	,BYR
	,CY_MONTH_SEQUENCE
	,MONTH_ID
	,Concat(MONTH_NAME,' ',LEFT(CY_MONTH,4)) AS month_name
FROM CORE_REL.V_CAL_MONTH_1
;