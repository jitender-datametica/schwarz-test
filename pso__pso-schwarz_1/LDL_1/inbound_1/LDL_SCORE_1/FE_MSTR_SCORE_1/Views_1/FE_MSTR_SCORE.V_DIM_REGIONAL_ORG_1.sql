CREATE OR REPLACE VIEW FE_MSTR_SCORE.V_DIM_REGIONAL_ORG_1 AS

SELECT
	REGIONAL_ORG_SID
	,REGIONAL_ORG_NR
	,REGIONAL_ORG_NAME
	,NATIONAL_ORG_SID
	,NATIONAL_ORG_NR
	,NATIONAL_ORG_NAME
	,REGIONAL_ORG_SHORT_NAME
	,CASE IS_ONLINESHOP_FG
    	WHEN TRUE THEN '1'
        WHEN FALSE THEN '0'
        ELSE 'unknown'
     END AS IS_ONLINESHOP_FG
	,VAT_NR
FROM CORE.T_DIM_REGIONAL_ORG_1; 