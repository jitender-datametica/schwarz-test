CREATE OR REPLACE VIEW FE_MSTR_APOLLO_KAUFLAND.V_DIM_KFL_CLIENT_ADVERTISE_WEEK_1
(
 KFL_CLIENT_ID
,KFL_ADV_WEEK
,KFL_ADV_WEEK_BEGIN_DT
,KFL_ADV_WEEK_END_DT
,KFL_ADV_WEEK_OFFSET
,KFL_COMPLETED_ADV_WEEK_OFFSET
,CAL_DT
)
AS
SELECT
 KFL_CLIENT_ID
,KFL_ADV_WEEK
,KFL_ADV_WEEK_BEGIN_DT
,KFL_ADV_WEEK_END_DT
,KFL_ADV_WEEK_OFFSET
,KFL_COMPLETED_ADV_WEEK_OFFSET
,CAL_DT
FROM CORE.T_DIM_KFL_CLIENT_ADVERTISE_WEEK_1 v01
JOIN CORE.T_DIM_KFL_CALENDAR_DATE_1 v02
ON v02.CAL_DT BETWEEN v01.KFL_ADV_WEEK_BEGIN_DT AND v01.KFL_ADV_WEEK_END_DT;