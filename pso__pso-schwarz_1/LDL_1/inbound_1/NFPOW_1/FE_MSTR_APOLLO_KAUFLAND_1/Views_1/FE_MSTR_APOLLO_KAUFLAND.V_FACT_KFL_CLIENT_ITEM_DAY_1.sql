CREATE OR REPLACE VIEW FE_MSTR_APOLLO_KAUFLAND.V_FACT_KFL_CLIENT_ITEM_DAY_1
(
 LOB_CD
,KFL_CLIENT_ID
,KFL_ITEM_NR
,CAL_DT
,CURR_CD
,KFL_ADV_WEEK
,KFL_RCV_QTY
,LDL_BUYING_RCV_NET_VAL
,LDL_RETAIL_RCV_NET_VAL
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
)
AS
SELECT
 LOB_CD
,KFL_CLIENT_ID
,CASE WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID = 1 THEN (KFL_ITEM_NR / 100)::INTEGER
      WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID > 1 THEN (KFL_ITEM_NR / 10)::INTEGER
      WHEN lob_cd = 'LDL' THEN (KFL_ITEM_NR / 100)::INTEGER ELSE NULL
      END AS KFL_ITEM_NR
,CAL_DT
,CURR_CD
,KFL_ADV_WEEK
,KFL_RCV_QTY -- vorher LDL_RCV_QTY
,LDL_BUYING_RCV_NET_VAL
,LDL_RETAIL_RCV_NET_VAL
--AP0219535/SPEC0270105 neue Spalte für Posten KZ aufgenommen / sschuecke 26.09.2024
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
FROM CORE.T_FACT_KFL_CLIENT_ITEM_DAY_1;