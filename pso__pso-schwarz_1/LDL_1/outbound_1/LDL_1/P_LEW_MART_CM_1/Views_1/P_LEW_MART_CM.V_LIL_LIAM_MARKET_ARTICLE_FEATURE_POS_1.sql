 MAFP.turnover_cum_product_pct,
   MAFP.total_market_turnover_val / 1000 * CER.rate_currency_exchange AS total_market_turnover_val,
 MAFP.total_market_promotion_share_pct,
 MAFP.total_market_extrapol_package_cnt,
   MAFP.lidl_turnover_val / 1000 * CER.rate_currency_exchange AS lidl_turnover_val,
 MAFP.lidl_promotion_share_pct,
 MAFP.lidl_extrapol_package_cnt,
   MAFP.competitor1_turnover_val / 1000 * CER.rate_currency_exchange AS competitor1_turnover_val,
 MAFP.competitor1_promotion_share_pct,
 MAFP.competitor1_extrapol_package_cnt,
   MAFP.competitor2_turnover_val / 1000 * CER.rate_currency_exchange AS competitor2_turnover_val,
 MAFP.competitor2_promotion_share_pct,
 MAFP.competitor2_extrapol_package_cnt,
 RR1.rtl_id AS retailer_comp1_id,
 RR2.rtl_id AS retailer_comp2_id
FROM ldl_p_lew_core_ac.v_market_article_feature_pos_1 AS MAFP
 INNER JOIN ldl_p_lew_process_mstr_ac.v_lil_period_1 AS PP ON MAFP.period_sid = PP.period_sid
 INNER JOIN ldl_p_lew_process_mstr_ac.v_lil_assort_region_cat_1 AS ARC ON MAFP.client_id = ARC.client_id AND MAFP.region_sid
     = ARC.region_sid AND MAFP.assort_cat_sid = ARC.assort_cat_sid
 INNER JOIN ldl_p_lew_process_mstr_ac.v_lil_region_retailer_1 AS RR1 ON MAFP.client_id = RR1.client_id AND MAFP.region_sid
     = RR1.region_sid AND MAFP.retailer_sid_comp1 = RR1.retailer_sid
 INNER JOIN ldl_p_lew_process_mstr_ac.v_lil_region_retailer_1 AS RR2 ON MAFP.client_id = RR2.client_id AND MAFP.region_sid
     = RR2.region_sid AND MAFP.retailer_sid_comp2 = RR2.retailer_sid
 INNER JOIN ldl_p_lew_mart_cm.v_lil_currency_exch_rt_1 AS CER ON MAFP.curr_cd = CER.from_currency_iso_cd;