weight_type_txt, avg_price_per_pack_val, packs_per_trip_cnt, penetrate_cum_abs_pct, penetrate_cum_rel_pct,
penetrate_diff_cum_rel_pct, penetrate_single_rel_pct, penetrate_exclusive_rel_pct, exclusive_buyer_assortment_pct,
assortment_depth_per_buyer_cnt, turnover_cum_all_pct, turnover_cum_product_pct, total_market_turnover_val,
total_market_promotion_share_pct, total_market_extrapol_package_cnt, lidl_turnover_val, lidl_promotion_share_pct,
lidl_extrapol_package_cnt, competitor1_turnover_val, competitor1_promotion_share_pct, competitor1_extrapol_package_cnt,
competitor2_turnover_val, competitor2_promotion_share_pct, competitor2_extrapol_package_cnt, retailer_comp1_id,
retailer_comp2_id) AS SELECT CASE
  WHEN MAFP.client_id = 33
  THEN 331
  ELSE MAFP.client_id
  END AS client_id,
 MAFP.region_sid,
 PP.period_id,
 SUBSTR(CAST(SUBSTR(ARC.assort_region_cat_id, 1, 13) || '00005000000000' AS STRING), 1, 27) AS liam_parnt_clnt_cat_id,
 SUBSTR(CAST(ARC.assort_region_cat_id AS STRING), 1, 27) AS liam_clnt_cat_id,
 MAFP.assort_cat_subfamily_sid,
 SUBSTR(CAST(CER.to_currency_iso_cd AS STRING), 1, 3) AS currency_iso_cd,
 MAFP.rank_pos,
 MAFP.brand_type_txt,
 MAFP.product_name,
 MAFP.manufacturer,
 MAFP.brand_1,
 MAFP.pack_size,
 MAFP.ean_1,
 MAFP.category_family,
 MAFP.category_subfamily_name,
 MAFP.feature1_content AS feature1,
 MAFP.feature2_content AS feature2,
 MAFP.feature3_content AS feature3,
 MAFP.feature4_content AS feature4,
 MAFP.feature5_content AS feature5,
 MAFP.feature6_content AS feature6,
 MAFP.feature7_content AS feature7,
 MAFP.feature8_content AS feature8,
 MAFP.feature9_content AS feature9,
 MAFP.feature10_content AS feature10,
 MAFP.feature11_content AS feature11,
 MAFP.feature12_content AS feature12,
 MAFP.feature13_content AS feature13,
 MAFP.feature14_content AS feature14,
   MAFP.turnover_val / 1000 * CER.rate_currency_exchange AS turnover_val,
   MAFP.turnover_prom_val / 1000 * CER.rate_currency_exchange AS turnover_prom_val,
 MAFP.promotion_share_pct,
 MAFP.trip_cnt,
 MAFP.buyer_cnt,
 MAFP.extrapol_package_cnt,
 MAFP.weight_type_txt,
  MAFP.avg_price_per_pack_val * CER.rate_currency_exchange AS avg_price_per_pack_val,
 MAFP.packs_per_trip_cnt,
 MAFP.penetrate_cum_abs_pct,
 MAFP.penetrate_cum_rel_pct,
 MAFP.penetrate_diff_cum_rel_pct,
 MAFP.penetrate_single_rel_pct,
 MAFP.penetrate_exclusive_rel_pct,
