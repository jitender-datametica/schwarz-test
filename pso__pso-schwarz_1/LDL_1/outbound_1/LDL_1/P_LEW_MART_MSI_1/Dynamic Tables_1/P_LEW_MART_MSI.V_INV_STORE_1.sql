   CURRENT_DATE BETWEEN ST.dwh_valid_from AND ST.dwh_valid_to
 INNER JOIN ldl_p_lew_bil_ac.v_warehouse_1 AS WH ON INVS.client_id = WH.client_id AND INVS.wh_loc_sid = WH.loc_sid_wh AND
   CURRENT_DATE BETWEEN WH.dwh_valid_from AND WH.dwh_valid_to
 INNER JOIN ldl_p_lew_mart_msi.v_report_fixed_exchange_rate_1 AS CRY ON INVS.client_id = CRY.client_id AND CURRENT_DATE
   BETWEEN CRY.active_from_dt AND CRY.active_to_dt
