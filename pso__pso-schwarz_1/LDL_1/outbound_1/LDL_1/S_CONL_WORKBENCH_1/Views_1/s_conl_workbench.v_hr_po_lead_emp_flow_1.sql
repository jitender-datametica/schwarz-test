 inflow.employee_inflow,
 outflow.employee_outflow,
 WAGE.cla_hourly_wage
FROM ldl_s_conl_workbench.v_hr_po_lead_1 AS HR_LEAD
 LEFT JOIN (SELECT cy_month,
   employee_subgroup,
   orig_store_nr,
   employee_inflow
  FROM ldl_s_conl_workbench.v_employee_inflow_1 AS INFL) AS inflow ON HR_LEAD.cy_month = inflow.cy_month AND HR_LEAD.employee_subgroup
     = inflow.employee_subgroup AND HR_LEAD.orig_store_nr = inflow.orig_store_nr
 LEFT JOIN (SELECT cy_month,
   employee_subgroup,
   orig_store_nr,
   employee_outflow
  FROM ldl_s_conl_workbench.v_employee_outflow_1 AS OUTFL) AS outflow ON HR_LEAD.cy_month = outflow.cy_month AND HR_LEAD.employee_subgroup
     = outflow.employee_subgroup AND HR_LEAD.orig_store_nr = outflow.orig_store_nr
 LEFT JOIN ldl_s_conl_workbench.v_cla_hourly_wage_1 AS WAGE ON HR_LEAD.cy_month = CAST(WAGE.cy_month AS FLOAT64) AND
   HR_LEAD.orig_store_nr = WAGE.orig_store_nr;