 INTERN.fte_vj,
 INTERN.fte_hours_month_lj,
 INTERN.fte_hours_month_vj,
 INTERN.employee_inflow_lj,
 INTERN.employee_inflow_vj,
 INTERN.employee_outflow_lj,
 INTERN.employee_outflow_vj,
 INTERN.cla_hourly_wage_lj,
 INTERN.cla_hourly_wage_vj,
 INTERN.hours_nett_lj,
 INTERN.hours_nett_vj,
 INTERN.hours_gross_lj,
 INTERN.hours_gross_vj,
 INTERN.hours_gross_hk_lj,
 INTERN.hours_gross_hk_vj,
 INTERN.hours_overtime_lj,
 INTERN.hours_overtime_vj,
 INTERN.hours_worked_hk_lj,
 INTERN.hours_worked_hk_vj,
 INTERN.hours_vacation_lj,
 INTERN.hours_vacation_vj,
 INTERN.hours_holiday_lj,
 INTERN.hours_holiday_vj,
 INTERN.hours_sick_lj,
 INTERN.hours_sick_vj,
 INTERN.hours_sick_absent_9glc_lj,
 INTERN.hours_sick_absent_9glc_vj,
 INTERN.hours_other_lj,
 INTERN.hours_other_vj,
 INTERN.hours_contract_lj,
 INTERN.hours_contract_vj,
 INTERN.hours_contract_excl_hk_lj,
 INTERN.hours_contract_excl_hk_vj,
 INTERN.hours_contract_hk_lj,
 INTERN.hours_contract_hk_vj,
 INTERN.surcharge_overtime_lj,
 INTERN.surcharge_overtime_vj,
 INTERN.surcharge_late_night_hours_lj,
 INTERN.surcharge_late_night_hours_vj,
 EXTERN.hours_external_lj,
 EXTERN.hours_external_vj,
 Ages.headcount_21min_lj,
 Ages.headcount_21plus_lj,
 Ages.headcount_21min_vj,
 Ages.headcount_21plus_vj,
 YOS.years_service2_lj,
 YOS.years_service2_vj,
 YOS.fte_parttime_factor_lj,
 YOS.fte_parttime_factor_vj
FROM (SELECT business_year,
   booking_month,
   warehouse_nr,
   cost_center,
   SUM(head_count_lj) AS head_count_lj,
   SUM(head_count_vj) AS head_count_vj,
   SUM(head_count_hk_lj) AS head_count_hk_lj,
   SUM(head_count_hk_vj) AS head_count_hk_vj,
   SUM(temporary_helper_12_hours_lj) AS temporary_helper_12_hours_lj,
   SUM(temporary_helper_12_hours_vj) AS temporary_helper_12_hours_vj,
   SUM(contract_non_permanent_ft_lj) AS contract_non_permanent_ft_lj,
   SUM(contract_non_permanent_ft_vj) AS contract_non_permanent_ft_vj,
   SUM(contract_non_permanent_pt_lj) AS contract_non_permanent_pt_lj,
   SUM(contract_non_permanent_pt_vj) AS contract_non_permanent_pt_vj,
   SUM(contract_non_permanent_hk_lj) AS contract_non_permanent_hk_lj,
   SUM(contract_non_permanent_hk_vj) AS contract_non_permanent_hk_vj,
   SUM(contract_permanent_ft_lj) AS contract_permanent_ft_lj,
   SUM(contract_permanent_ft_vj) AS contract_permanent_ft_vj,
   SUM(contract_permanent_pt_lj) AS contract_permanent_pt_lj,
   SUM(contract_permanent_pt_vj) AS contract_permanent_pt_vj,
   SUM(contract_permanent_0_hours_lj) AS contract_permanent_0_hours_lj,
   SUM(contract_permanent_0_hours_vj) AS contract_permanent_0_hours_vj,
   SUM(contract_permanent_hk_lj) AS contract_permanent_hk_lj,
   SUM(contract_permanent_hk_vj) AS contract_permanent_hk_vj,
   SUM(years_service_lj) AS years_service_lj,
   SUM(years_service_vj) AS years_service_vj,
   SUM(amount_women_diversity_lj) AS amount_women_diversity_lj,
   SUM(amount_women_diversity_vj) AS amount_women_diversity_vj,
   SUM(amount_total_diversity_lj) AS amount_total_diversity_lj,
   SUM(amount_total_diversity_vj) AS amount_total_diversity_vj,
   SUM(fte_lj) AS fte_lj,
   SUM(fte_vj) AS fte_vj,
   AVG(fte_hours_month_lj) AS fte_hours_month_lj,
   AVG(fte_hours_month_vj) AS fte_hours_month_vj,
   SUM(employee_inflow_lj) AS employee_inflow_lj,
   SUM(employee_inflow_vj) AS employee_inflow_vj,
   SUM(employee_outflow_lj) AS employee_outflow_lj,
   SUM(employee_outflow_vj) AS employee_outflow_vj,
   AVG(CASE
     WHEN cla_hourly_wage_lj > 0
     THEN cla_hourly_wage_lj
     ELSE NULL
     END) AS cla_hourly_wage_lj,
   AVG(CASE
     WHEN cla_hourly_wage_vj > 0
     THEN cla_hourly_wage_vj
     ELSE NULL
     END) AS cla_hourly_wage_vj,
   CAST(SUM(hours_nett_lj) AS BIGNUMERIC) AS hours_nett_lj,
   CAST(SUM(hours_nett_vj) AS BIGNUMERIC) AS hours_nett_vj,
   CAST(SUM(hours_gross_lj) AS BIGNUMERIC) AS hours_gross_lj,
   CAST(SUM(hours_gross_vj) AS BIGNUMERIC) AS hours_gross_vj,
   CAST(SUM(hours_gross_hk_lj) AS BIGNUMERIC) AS hours_gross_hk_lj,
   CAST(SUM(hours_gross_hk_vj) AS BIGNUMERIC) AS hours_gross_hk_vj,
   CAST(SUM(hours_overtime_lj) AS BIGNUMERIC) AS hours_overtime_lj,
   CAST(SUM(hours_overtime_vj) AS BIGNUMERIC) AS hours_overtime_vj,
   CAST(SUM(hours_worked_hk_lj) AS BIGNUMERIC) AS hours_worked_hk_lj,
   CAST(SUM(hours_worked_hk_vj) AS BIGNUMERIC) AS hours_worked_hk_vj,
   CAST(SUM(hours_vacation_lj) AS BIGNUMERIC) AS hours_vacation_lj,
   CAST(SUM(hours_vacation_vj) AS BIGNUMERIC) AS hours_vacation_vj,
   CAST(SUM(hours_holiday_lj) AS BIGNUMERIC) AS hours_holiday_lj,
   CAST(SUM(hours_holiday_vj) AS BIGNUMERIC) AS hours_holiday_vj,
   CAST(SUM(hours_sick_lj) AS BIGNUMERIC) AS hours_sick_lj,
   CAST(SUM(hours_sick_vj) AS BIGNUMERIC) AS hours_sick_vj,
   CAST(SUM(hours_sick_absent_9glc_lj) AS BIGNUMERIC) AS hours_sick_absent_9glc_lj,
   CAST(SUM(hours_sick_absent_9glc_vj) AS BIGNUMERIC) AS hours_sick_absent_9glc_vj,
   CAST(SUM(hours_other_lj) AS BIGNUMERIC) AS hours_other_lj,
   CAST(SUM(hours_other_vj) AS BIGNUMERIC) AS hours_other_vj,
   CAST(SUM(hours_contract_lj) AS BIGNUMERIC) AS hours_contract_lj,
   CAST(SUM(hours_contract_vj) AS BIGNUMERIC) AS hours_contract_vj,
   CAST(SUM(hours_contract_excl_hk_lj) AS BIGNUMERIC) AS hours_contract_excl_hk_lj,
   CAST(SUM(hours_contract_excl_hk_vj) AS BIGNUMERIC) AS hours_contract_excl_hk_vj,
   CAST(SUM(hours_contract_hk_lj) AS BIGNUMERIC) AS hours_contract_hk_lj,
   CAST(SUM(hours_contract_hk_vj) AS BIGNUMERIC) AS hours_contract_hk_vj,
   CAST(SUM(surcharge_overtime_lj) AS BIGNUMERIC) AS surcharge_overtime_lj,
   CAST(SUM(surcharge_overtime_vj) AS BIGNUMERIC) AS surcharge_overtime_vj,
   CAST(SUM(surcharge_late_night_hours_lj) AS BIGNUMERIC) AS surcharge_late_night_hours_lj,
   CAST(SUM(surcharge_late_night_hours_vj) AS BIGNUMERIC) AS surcharge_late_night_hours_vj
  FROM ldl_s_conl_workbench.v_mdf_dc_hours_hr_intern_1
  GROUP BY business_year,
   booking_month,
   warehouse_nr,
   cost_center) AS INTERN
 LEFT JOIN (SELECT business_year,
   booking_month,
   warehouse_nr,
   cost_center,
   SUM(hours_external_lj) AS hours_external_lj,
   SUM(hours_external_vj) AS hours_external_vj
  FROM ldl_s_conl_workbench.v_mdf_dc_hours_hr_extern_1
  GROUP BY business_year,
   booking_month,
   warehouse_nr,
   cost_center) AS EXTERN ON INTERN.business_year = EXTERN.business_year AND INTERN.booking_month = EXTERN.booking_month
      AND INTERN.warehouse_nr = EXTERN.warehouse_nr AND INTERN.cost_center = EXTERN.cost_center
 LEFT JOIN (SELECT business_year,
   booking_month,
   warehouse_nr,
   cost_center,
   SUM(headcount_21min_lj) AS headcount_21min_lj,
   SUM(headcount_21plus_lj) AS headcount_21plus_lj,
   SUM(headcount_21min_vj) AS headcount_21min_vj,
   SUM(headcount_21plus_vj) AS headcount_21plus_vj
  FROM ldl_s_conl_workbench.v_mdf_dc_hours_hr_ages_1
  GROUP BY business_year,
   booking_month,
   warehouse_nr,
   cost_center) AS Ages ON INTERN.business_year = Ages.business_year AND INTERN.booking_month = Ages.booking_month AND
    INTERN.warehouse_nr = Ages.warehouse_nr AND INTERN.cost_center = Ages.cost_center
 LEFT JOIN (SELECT business_year,
   booking_month,
   warehouse_nr,
   cost_center,
   SUM(years_service_lj) AS years_service2_lj,
   SUM(years_service_vj) AS years_service2_vj,
   CAST(SUM(fte_parttime_factor_lj / 100) AS BIGNUMERIC) AS fte_parttime_factor_lj,
   CAST(SUM(fte_parttime_factor_vj / 100) AS BIGNUMERIC) AS fte_parttime_factor_vj
  FROM ldl_s_conl_workbench.v_mdf_dc_hours_hr_years_services_1
  GROUP BY business_year,
   booking_month,
   warehouse_nr,
   cost_center) AS YOS ON INTERN.business_year = YOS.business_year AND INTERN.booking_month = YOS.booking_month AND
    INTERN.warehouse_nr = YOS.warehouse_nr AND INTERN.cost_center = YOS.cost_center;