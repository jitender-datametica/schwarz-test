CREATE OR REPLACE VIEW ldl_autodispo_fe_mstr_autodispo.autdi_11_1 AS WITH A AS (SELECT country_1,
    pfc,
    pfc_day_before,
    pfc_two_day_before,
    pfc_model AS forecast_no_ratio,
    pfc_before_trend,
    d_min,
    TIME(CAST(TRIM(sale_last_time_int) AS TIME)) AS hour_last_sale,
    d_plus,
    d_pfc,
    subgroupno,
    familyno,
    ROUND(CAST(store AS BIGNUMERIC), 0) AS store,
    DATE(date_) AS date,
    wh,
    promotion,
    amount,
    0 AS avg_amount,
     CASE
     WHEN amount = 0
     THEN 1
     ELSE 0
     END AS is_amount_zero,
    itemno,
    special_placement,
    v_model,
    is_trend,
    forecast_day,
    'fqr' AS tab
   FROM ldl_autodispo_core.t_hive_v_forecast_quality_reduced_1 AS DR
   WHERE forecast_day = 1
   UNION ALL
   SELECT FR.country_1,
    FR.pfc,
    0 AS pfc_day_before,
    0 AS pfc_two_day_before,
    FR.pfc_model AS forecast_no_ratio,
    FR.pfc_before_trend,
    0 AS d_min,
    CAST(NULL AS TIME) AS hour_last_sale,
    0 AS d_plus,
    0 AS d_pfc,
    FR.subgroupno,
    FR.familyno,
    FR.store,
    DATE(FR.date_) AS date,
    FR.wh,
    FR.promotion,
    CAST(NULL AS BIGNUMERIC) AS amount,
    CAST(NULL AS INTEGER) AS avg_amount,
    0 AS is_amount_zero,
    FR.itemno,
    FR.spec_placement AS special_placement,
    FR.v_model,
    CAST(NULL AS BIGNUMERIC) AS is_trend,
    FD.forecast_day,
    'frr' AS tab
   FROM ldl_autodispo_core.t_hive_final_results_reduced_1 AS FR
    INNER JOIN ldl_autodispo_core.t_hive_dim_forecast_day_1 AS FD ON FR.country_1 = FD.country_1
   WHERE DATE(FR.date_) >= CURRENT_DATE), T AS (SELECT country_1,
   date,
   store_nr,
   store_wh,
   itemno,
   EXP(SUM(LN(fst_percent / 100))) AS fst_factor
  FROM ldl_autodispo_core.t_oracle_v_fk_store_trend_transformed_1
  GROUP BY country_1,
   date,
   store_nr,
   store_wh,
   itemno) (SELECT t8.fst_factor,
    t4.pfc * COALESCE(t8.fst_factor, 1) AS forecast_trend,
   t4.country_1,
   t4.pfc,
   t4.pfc_day_before,
   t4.pfc_two_day_before,
   t4.forecast_no_ratio,
   t4.pfc_before_trend,
   t4.d_min,
   t4.hour_last_sale,
   t4.d_plus,
   t4.d_pfc,
   t4.subgroupno,
   t4.familyno,
   t4.store,
   t4.date,
   t4.wh,
   t4.promotion,
   t4.amount,
   t4.avg_amount,
   t4.is_amount_zero,
   t4.itemno,
   t4.special_placement,
   t4.v_model,
   t4.is_trend,
   t4.forecast_day,
   t4.tab
  FROM A AS t4
   LEFT JOIN T AS t8 ON t4.country_1 = t8.country_1 AND t4.date = t8.date AND t4.store = t8.store_nr AND t4.itemno = t8.itemno
     );