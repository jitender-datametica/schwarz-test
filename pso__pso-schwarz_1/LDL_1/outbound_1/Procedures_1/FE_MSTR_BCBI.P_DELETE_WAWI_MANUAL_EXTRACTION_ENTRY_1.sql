CREATE OR REPLACE PROCEDURE fe_mstr_bcbi.p_delete_wawi_manual_extraction_entry(IN P_CLIENT_ID INT64, IN P_SYSTEM_KEY INT64, IN P_WH_ID INT64, IN P_DAYEND_DATE DATE, IN P_ENTRY_FROM STRING, IN P_REASON STRING, IN P_CREATE_TIMESTAMP DATETIME)
BEGIN
BEGIN TRANSACTION;
DELETE FROM fe_mstr_bcbi.ts_wawi_manual_extraction_1
WHERE client_id = P_CLIENT_ID AND system_key = P_SYSTEM_KEY AND wh_id = P_WH_ID AND dayend_date = P_DAYEND_DATE AND entry_from = P_ENTRY_FROM AND reason = P_REASON AND CAST(FORMAT_DATETIME('%F %H:%M:%S', create_timestamp) AS DATETIME) = DATE_TRUNC(P_CREATE_TIMESTAMP, SECOND);
COMMIT TRANSACTION;
END;
