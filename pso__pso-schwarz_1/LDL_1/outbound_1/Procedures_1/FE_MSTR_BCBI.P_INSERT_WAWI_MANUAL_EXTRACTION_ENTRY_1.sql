CREATE OR REPLACE PROCEDURE fe_mstr_bcbi.p_insert_wawi_manual_extraction_entry(IN P_CLIENT_ID INT64, IN P_SYSTEM_KEY INT64, IN P_WH_ID INT64, IN P_DAYEND_DATE DATE, IN P_ENTRY_FROM STRING, IN P_REASON STRING)
BEGIN
BEGIN TRANSACTION;
IF P_DAYEND_DATE >= DATE '2022-03-01' AND EXISTS (SELECT 1
        FROM fe_mstr_bcbi.v_l_source_system_wawi_manual_extraction_1
        WHERE client_id = P_CLIENT_ID AND WH_ID = P_WH_ID AND SYSTEM_KEY = P_SYSTEM_KEY) AND NOT EXISTS (SELECT 1
    FROM fe_mstr_bcbi.ts_wawi_manual_extraction_1
    WHERE CLIENT_ID = P_CLIENT_ID AND SYSTEM_KEY = P_SYSTEM_KEY AND WH_ID = P_WH_ID AND DAYEND_DATE = P_DAYEND_DATE AND EXTRACTED_FG = 0) THEN
    INSERT INTO fe_mstr_bcbi.ts_wawi_manual_extraction_1
(SELECT P_CLIENT_ID, P_SYSTEM_KEY, P_WH_ID, P_DAYEND_DATE, P_ENTRY_FROM, P_REASON, 0, CAST(CURRENT_TIMESTAMP() AS DATETIME), CAST(NULL AS DATETIME));
END IF;

COMMIT TRANSACTION;
END;
