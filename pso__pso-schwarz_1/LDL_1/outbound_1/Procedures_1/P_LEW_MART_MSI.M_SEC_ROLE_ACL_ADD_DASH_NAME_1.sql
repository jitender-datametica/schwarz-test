CREATE OR REPLACE PROCEDURE p_lew_mart_msi.m_sec_role_acl_add_dash_name(
  DASHBOARD_DISP_NAME STRING, 
  DASHBOARD_NAME STRING
)
BEGIN
  BEGIN TRANSACTION;

  EXECUTE IMMEDIATE '''
    UPDATE p_lew_mart_msi.t_sec_role_acl_tmpl_1
    SET   dashboard_disp_name= @DASHBOARD_DISP_NAME
    WHERE   dashboard_name= @DASHBOARD_NAME
  ''' USING DASHBOARD_DISP_NAME AS DASHBOARD_DISP_NAME, DASHBOARD_NAME AS DASHBOARD_NAME;

  COMMIT TRANSACTION;
END;