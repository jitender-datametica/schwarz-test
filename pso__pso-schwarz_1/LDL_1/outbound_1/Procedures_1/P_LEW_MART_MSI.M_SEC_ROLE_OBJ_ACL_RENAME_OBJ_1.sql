CREATE OR REPLACE PROCEDURE p_lew_mart_msi.m_sec_role_obj_acl_rename_obj(
  OBJECT_NAME_OLD STRING, 
  OBJECT_NAME_NEW STRING, 
  NSTD_LFT_ID FLOAT64, 
  NSTD_RGT_ID FLOAT64
)
BEGIN
  BEGIN TRANSACTION;

  EXECUTE IMMEDIATE '''
    UPDATE p_lew_mart_msi.t_ct_sec_role_obj_acl_1
    SET  object_name = @OBJECT_NAME_NEW
    WHERE nstd_lft_id = @NSTD_LFT_ID
  ''' USING OBJECT_NAME_NEW AS OBJECT_NAME_NEW, NSTD_LFT_ID AS NSTD_LFT_ID;

  EXECUTE IMMEDIATE '''
    UPDATE p_lew_mart_msi.t_ct_sec_role_obj_acl_1
    SET object_path = REPLACE(object_path, @OBJECT_NAME_OLD, @OBJECT_NAME_NEW)
    WHERE @NSTD_LFT_ID BETWEEN @NSTD_LFT_ID AND @NSTD_RGT_ID
  ''' USING OBJECT_NAME_OLD AS OBJECT_NAME_OLD, OBJECT_NAME_NEW AS OBJECT_NAME_NEW, NSTD_LFT_ID AS NSTD_LFT_ID, NSTD_RGT_ID AS NSTD_RGT_ID;

  EXECUTE IMMEDIATE '''
    UPDATE p_lew_mart_msi.t_ref_obj_acl_parent_child_1
    SET p_object_name = @OBJECT_NAME_NEW
    WHERE p_lft_id = @NSTD_LFT_ID
  ''' USING OBJECT_NAME_NEW AS OBJECT_NAME_NEW, NSTD_LFT_ID AS NSTD_LFT_ID;

  COMMIT TRANSACTION;
END;