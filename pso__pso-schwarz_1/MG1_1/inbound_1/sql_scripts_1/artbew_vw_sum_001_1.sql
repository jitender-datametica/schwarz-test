  nb_id smallint not null,
  dat date not null
);

insert into _faecher (mandant_id,
                      vw_id,
                      wup_id,
                      nb_id,
                      dat)
select a.mandant_id,
       b.vw_id,
       b.wup_id,
       b.nb_id,
       a.dat
from (select x.mandant_id,
             y.vw_id,
             x.dat
      from dbp_data.artbew_agg_wt_1 x
      join dbp_data.wup_1 y
        on x.mandant_id = y.mandant_id and
           x.wup_id = y.wup_id and
           x.nb_id = y.nb_id
      group by 1,2,3) a
join dbp_data.wup_1 b
  on a.mandant_id = b.mandant_id and
     a.vw_id = b.vw_id
;

