CREATE TEMPORARY TABLE IF NOT EXISTS _ART_PER_TMP AS
SELECT ART_ID,
 MANDANT_ID,
 CURRENT_DATE AS DAT_VON,
 '9999-12-31' AS DAT_BIS,
 MUTTER_WB_ID,
 POSTEN_ID,
 IPN_ID,
 MWST_ID,
 OUG_ID,
 CURRENT_TIMESTAMP() AS TD_INSERT,
 CURRENT_TIMESTAMP() AS TD_UPDATE
FROM KFL_PRODUCTION_DBP_DATA.ART_1
WHERE CURRENT_DATE > (SELECT MAX(DAT_VON)
   FROM KFL_PRODUCTION_DBP_DATA.ART_PER_1)
GROUP BY ART_ID,
 MANDANT_ID,
 ART.DAT_VON,
 ART.DAT_BIS,
 MUTTER_WB_ID,
 POSTEN_ID,
 IPN_ID,
 MWST_ID,
 OUG_ID;


CREATE TEMPORARY TABLE IF NOT EXISTS _ART_PER_NEW AS
SELECT B.ART_ID,
 B.MANDANT_ID,
 B.DAT_VON,
 B.DAT_BIS,
 B.MUTTER_WB_ID,
 B.POSTEN_ID,
 B.IPN_ID,
 B.MWST_ID,
 B.OUG_ID,
 B.TD_INSERT,
 B.TD_UPDATE
FROM KFL_PRODUCTION_DBP_DATA.ART_PER_1 AS A
 INNER JOIN `_ART_PER_TMP` AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.ART_ID = B.ART_ID AND A.DAT_BIS = PARSE_DATE('%F',
    '9999-12-31')
WHERE COALESCE(A.MUTTER_WB_ID, - 999) <> COALESCE(B.MUTTER_WB_ID, - 999)
 OR A.POSTEN_ID <> B.POSTEN_ID
 OR A.OUG_ID <> B.OUG_ID
 OR A.MWST_ID <> B.MWST_ID
 OR COALESCE(A.IPN_ID, - 999) <> COALESCE(B.IPN_ID, - 999);


INSERT INTO `_ART_PER_NEW`
(SELECT *
 FROM `_ART_PER_TMP`
 WHERE (ART_ID, MANDANT_ID) NOT IN (SELECT (ART_ID, MANDANT_ID)
    FROM KFL_PRODUCTION_DBP_DATA.ART_PER_1));


INSERT INTO KFL_PRODUCTION_DBP_DATA.ART_PER_1 (ART_ID, MANDANT_ID, DAT_VON, DAT_BIS, MUTTER_WB_ID, POSTEN_ID, IPN_ID,
 TD_INSERT, TD_UPDATE, MWST_ID, OUG_ID)
(SELECT DISTINCT ART_ID,
  MANDANT_ID,
  DAT_VON,
  DAT_BIS,
  MUTTER_WB_ID,
  POSTEN_ID,
  IPN_ID,
  TD_INSERT,
  TD_UPDATE,
  MWST_ID,
  OUG_ID
 FROM (SELECT ART_ID,
    MANDANT_ID,
    DAT_VON,
    DATE(DAT_BIS) AS DAT_BIS,
    MUTTER_WB_ID,
    POSTEN_ID,
    IPN_ID,
    TD_INSERT,
    TD_UPDATE,
    MWST_ID,
    OUG_ID
   FROM `_ART_PER_NEW`) AS t
 WHERE NOT EXISTS (SELECT 1 AS `A11860`
   FROM KFL_PRODUCTION_DBP_DATA.ART_PER_1
   WHERE ART_ID = t.ART_ID
    AND MANDANT_ID = t.MANDANT_ID
    AND DAT_VON = t.DAT_VON)
 QUALIFY (ROW_NUMBER() OVER (PARTITION BY ART_ID, MANDANT_ID, DAT_VON)) = 1);


UPDATE KFL_PRODUCTION_DBP_DATA.ART_PER_1 AS ART_PER0 SET
 DAT_BIS = dt1.DAT_BIS FROM (SELECT MANDANT_ID,
   ART_ID,
   DAT_VON,
   COALESCE(LEAD(DATE_SUB(DAT_VON, INTERVAL 1 DAY)) OVER (PARTITION BY CAST(MANDANT_ID AS STRING), CAST(ART_ID AS STRING)
       ORDER BY DAT_VON IS NULL, DAT_VON), PARSE_DATE('%F', '9999-12-31')) AS DAT_BIS
  FROM KFL_PRODUCTION_DBP_DATA.ART_PER_1) AS dt1
WHERE ART_PER0.MANDANT_ID = dt1.MANDANT_ID AND ART_PER0.ART_ID = dt1.ART_ID AND ART_PER0.DAT_VON = dt1.DAT_VON AND
  ART_PER0.DAT_BIS <> dt1.DAT_BIS;