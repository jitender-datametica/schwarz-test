INSERT INTO KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1 (MANDANT_ID, VW_ID, ART_ID, DAT_VON, SM_ID, DAT_ERST_LISTUNG,
 KSM_ID)
(SELECT MANDANT_ID,
  VW_ID,
  ART_ID,
  PARSE_DATE('%Y%m%d', '19000101') AS DAT_VON,
  - 1 AS SM_ID,
  PARSE_DATE('%Y%m%d', '99991231') AS DAT_ERST_LISTUNG,
  'K0' AS KSM_ID
 FROM KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP2_1
 WHERE (MANDANT_ID, VW_ID, ART_ID) NOT IN (SELECT (MANDANT_ID, VW_ID, ART_ID)
    FROM KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1));


UPDATE KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1 SET
 SM_ID = t1.SM_ID_,
 DAT_VON = CURRENT_DATE FROM (SELECT VW_ID AS VW_ID_,
   ART_ID AS ART_ID_,
   MANDANT_ID AS MANDANT_ID_,
   SM_ID AS SM_ID_
  FROM KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP1_1) AS t1_1
WHERE ART_VW_LISTUNG_VON.MANDANT_ID = t1.MANDANT_ID_ AND ART_VW_LISTUNG_VON.VW_ID = t1.VW_ID_ AND ART_VW_LISTUNG_VON.ART_ID
    = t1.ART_ID_ AND ART_VW_LISTUNG_VON.SM_ID <> t1.SM_ID_;


UPDATE KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1 SET
 KSM_ID = t1.KSM_ID_,
 DAT_VON = CURRENT_DATE FROM (SELECT VW_ID AS VW_ID_,
   ART_ID AS ART_ID_,
   MANDANT_ID AS MANDANT_ID_,
   KSM_ID AS KSM_ID_
  FROM KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP1_1) AS t1_1
WHERE ART_VW_LISTUNG_VON.MANDANT_ID = t1.MANDANT_ID_ AND ART_VW_LISTUNG_VON.VW_ID = t1.VW_ID_ AND ART_VW_LISTUNG_VON.ART_ID
    = t1.ART_ID_ AND ART_VW_LISTUNG_VON.KSM_ID <> t1.KSM_ID_;


UPDATE KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1 SET
 SM_ID = - 1,
 DAT_VON = CURRENT_DATE
WHERE SM_ID <> - 1 AND (MANDANT_ID, VW_ID, ART_ID) NOT IN (SELECT (MANDANT_ID, VW_ID, ART_ID)
   FROM KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP1_1);


UPDATE KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1 SET
 KSM_ID = 'K0',
 DAT_VON = CURRENT_DATE
WHERE KSM_ID <> 'K0' AND (MANDANT_ID, VW_ID, ART_ID) NOT IN (SELECT (MANDANT_ID, VW_ID, ART_ID)
   FROM KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP1_1);


UPDATE KFL_PRODUCTION_DBP_DATA.ART_VW_LISTUNG_VON_1 SET
 DAT_ERST_LISTUNG = t1.DAT_ERST_LISTUNG_ FROM (SELECT VW_ID AS VW_ID_,
   ART_ID AS ART_ID_,
   MANDANT_ID AS MANDANT_ID_,
   DAT_ERST_LISTUNG AS DAT_ERST_LISTUNG_
  FROM KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP_1) AS t1_1
WHERE ART_VW_LISTUNG_VON.MANDANT_ID = t1.MANDANT_ID_ AND ART_VW_LISTUNG_VON.VW_ID = t1.VW_ID_ AND ART_VW_LISTUNG_VON.ART_ID
   = t1.ART_ID_;