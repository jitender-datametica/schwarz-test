INSERT INTO KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP_1 (MANDANT_ID, VW_ID, ART_ID, DAT_ERST_LISTUNG)
(SELECT T1.MANDANT_ID,
  COALESCE(dt2.VW_ID, 0) AS DT2_VW_ID,
  T1.ART_ID,
  MIN(T1.DAT_VON) AS DAT_ERST_LISTUNG
 FROM KFL_PRODUCTION_DBP_DATA.ART_LIST_WUP_ZU_PER_1 AS T1_1
  INNER JOIN (SELECT MANDANT_ID,
    WUP_ID,
    NB_ID,
    VW_ID
   FROM KFL_PRODUCTION_DBP_DATA.WUP_1
   WHERE NB_ID = 0) AS dt2 ON T1.MANDANT_ID = dt2.MANDANT_ID AND T1.WUP_ID = dt2.WUP_ID AND T1.NB_ID = dt2.NB_ID
 GROUP BY T1.ART_ID,
  T1.MANDANT_ID,
  dt2.VW_ID);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP1_1 (MANDANT_ID, VW_ID, ART_ID, SM_ID, KSM_ID, DURCHGAENGIG_FG)
(SELECT dt_1.MANDANT_ID,
  dt_1.VW_ID,
  dt_2.ART_ID,
  dt_1.SM_ID,
  'K0' AS KSM_ID,
   CASE
   WHEN dt_2.S_LSTG = dt_1.WUP_ANZ
   THEN 1
   ELSE 0
   END AS DURCHGAENGIG_FG
 FROM (SELECT DT1_1.MANDANT_ID,
    COUNT(DISTINCT DT1_1.WUP_ID) AS WUP_ANZ,
    DT1_1.WG_ID,
    DT1_1.SM_ID,
    DT1_2.VW_ID
   FROM KFL_PRODUCTION_DBP_DATA.SM_WUP_WG_ZU_PER_1 AS DT1_1
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_1 AS DT1_2 ON DT1_1.MANDANT_ID = DT1_2.MANDANT_ID AND DT1_1.WUP_ID = DT1_2.WUP_ID
        AND DT1_1.NB_ID = DT1_2.NB_ID
   WHERE CURRENT_DATE BETWEEN DT1_1.DAT_VON AND DT1_1.DAT_BIS
    AND CURRENT_DATE BETWEEN DT1_2.DAT_VON AND DT1_2.DAT_BIS
    AND DT1_1.NB_ID = 0
   GROUP BY DT1_1.MANDANT_ID,
    DT1_1.WG_ID,
    DT1_1.SM_ID,
    DT1_2.VW_ID) AS dt_1
  INNER JOIN (SELECT t4.MANDANT_ID,
    COUNT(t4.WUP_ID) AS C_WUP_ID,
    t4.ART_ID,
    t4.WG_ID,
    dt2_2.SM_ID,
    dt2_2.VW_ID,
    SUM(t4.LISTUNG_ID) AS S_LSTG
   FROM (SELECT DT2_1_1.MANDANT_ID,
      DT2_1_1.ART_ID,
      DT2_1_1.WUP_ID,
      DT2_1_2.WG_ID,
      DT2_1_1.LISTUNG_ID
     FROM KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_1 AS DT2_1_1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1 AS DT2_1_2 ON DT2_1_1.ART_ID = DT2_1_2.ART_ID AND DT2_1_1.MANDANT_ID
         = DT2_1_2.MANDANT_ID
     WHERE DT2_1_2.ARTHIERTYP_ID = 2
      AND CURRENT_DATE BETWEEN DT2_1_2.DAT_VON AND DT2_1_2.DAT_BIS
      AND CURRENT_DATE BETWEEN DT2_1_1.DAT_VON AND DT2_1_1.DAT_BIS
     GROUP BY DT2_1_1.MANDANT_ID,
      DT2_1_1.WUP_ID,
      DT2_1_1.ART_ID,
      DT2_1_1.LISTUNG_ID,
      DT2_1_2.WG_ID) AS t4
    INNER JOIN (SELECT DT2_2_1.MANDANT_ID,
      DT2_2_1.WUP_ID,
      DT2_2_1.WG_ID,
      DT2_2_1.SM_ID,
      DT2_2_2.VW_ID
     FROM KFL_PRODUCTION_DBP_DATA.SM_WUP_WG_ZU_PER_1 AS DT2_2_1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_1 AS DT2_2_2 ON DT2_2_1.MANDANT_ID = DT2_2_2.MANDANT_ID AND DT2_2_1.WUP_ID =
         DT2_2_2.WUP_ID AND DT2_2_1.NB_ID = DT2_2_2.NB_ID
     WHERE CURRENT_DATE BETWEEN DT2_2_1.DAT_VON AND DT2_2_1.DAT_BIS
      AND CURRENT_DATE BETWEEN DT2_2_2.DAT_VON AND DT2_2_2.DAT_BIS
      AND DT2_2_1.NB_ID = 0
     GROUP BY DT2_2_1.MANDANT_ID,
      DT2_2_1.WUP_ID,
      DT2_2_1.WG_ID,
      DT2_2_1.SM_ID,
      DT2_2_2.VW_ID) AS dt2_2 ON t4.MANDANT_ID = dt2_2.MANDANT_ID AND t4.WUP_ID = dt2_2.WUP_ID AND t4.WG_ID = dt2_2.WG_ID
      
   GROUP BY t4.MANDANT_ID,
    t4.ART_ID,
    t4.WG_ID,
    dt2_2.SM_ID,
    dt2_2.VW_ID) AS dt_2 ON dt_1.MANDANT_ID = dt_2.MANDANT_ID AND dt_1.WG_ID = dt_2.WG_ID AND dt_1.SM_ID = dt_2.SM_ID
   AND dt_1.VW_ID = dt_2.VW_ID
 WHERE dt_2.SM_ID > - 1);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ART_VW_LISTUNG_VON_TMP1_1 (MANDANT_ID, VW_ID, ART_ID, SM_ID, KSM_ID, DURCHGAENGIG_FG)
(SELECT dt_1.MANDANT_ID,
  dt_1.VW_ID,
  dt_2.ART_ID,
  - 1 AS SM_ID,
   'K' || TRIM(CAST(dt_1.KSM_ID AS STRING)) AS KSM_ID,
   CASE
   WHEN dt_2.S_LSTG = dt_1.WUP_ANZ
   THEN 1
   ELSE 0
   END AS DURCHGAENGIG_FG
 FROM (SELECT DT1_1.MANDANT_ID,
    COUNT(DISTINCT DT1_1.WUP_ID) AS WUP_ANZ,
    DT1_1.WG_ID,
     CASE
     WHEN ROUND(CAST(SUBSTR(DT1_1.KSM_ID, 2, 1) AS BIGNUMERIC), 0) > 7
     THEN 7
     ELSE ROUND(CAST(SUBSTR(DT1_1.KSM_ID, 2, 1) AS BIGNUMERIC), 0)
     END AS KSM_ID,
    DT1_2.VW_ID
   FROM KFL_PRODUCTION_DBP_DATA.SM_WUP_WG_ZU_PER_1 AS DT1_1
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_1 AS DT1_2 ON DT1_1.MANDANT_ID = DT1_2.MANDANT_ID AND DT1_1.WUP_ID = DT1_2.WUP_ID
        AND DT1_1.NB_ID = DT1_2.NB_ID
   WHERE CURRENT_DATE BETWEEN DT1_1.DAT_VON AND DT1_1.DAT_BIS
    AND CURRENT_DATE BETWEEN DT1_2.DAT_VON AND DT1_2.DAT_BIS
    AND DT1_1.NB_ID = 0
    AND LENGTH(DT1_1.KSM_ID) = 2
    AND SUBSTR(DT1_1.KSM_ID, 1, 1) = 'K'
    AND ROUND(CAST(SUBSTR(DT1_1.KSM_ID, 2, 1) AS BIGNUMERIC), 0) BETWEEN 1 AND 9
   GROUP BY DT1_1.MANDANT_ID,
    DT1_1.WG_ID,
    KSM_ID,
    DT1_2.VW_ID) AS dt_1
  INNER JOIN (SELECT t5.MANDANT_ID,
    COUNT(t5.WUP_ID) AS C_WUP_ID,
    t5.ART_ID,
    t5.WG_ID,
    dt2_2.KSM_ID,
    dt2_2.VW_ID,
    SUM(t5.LISTUNG_ID) AS S_LSTG
   FROM (SELECT DT2_1_1.MANDANT_ID,
      DT2_1_1.ART_ID,
      DT2_1_1.WUP_ID,
      DT2_1_2.WG_ID,
      DT2_1_1.LISTUNG_ID
     FROM KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_1 AS DT2_1_1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1 AS DT2_1_2 ON DT2_1_1.ART_ID = DT2_1_2.ART_ID AND DT2_1_1.MANDANT_ID
         = DT2_1_2.MANDANT_ID
     WHERE DT2_1_2.ARTHIERTYP_ID = 2
      AND CURRENT_DATE BETWEEN DT2_1_2.DAT_VON AND DT2_1_2.DAT_BIS
      AND CURRENT_DATE BETWEEN DT2_1_1.DAT_VON AND DT2_1_1.DAT_BIS
     GROUP BY DT2_1_1.MANDANT_ID,
      DT2_1_1.WUP_ID,
      DT2_1_1.ART_ID,
      DT2_1_1.LISTUNG_ID,
      DT2_1_2.WG_ID) AS t5
    INNER JOIN (SELECT DT2_2_1.MANDANT_ID,
      DT2_2_1.WUP_ID,
      DT2_2_1.WG_ID,
       CASE
       WHEN ROUND(CAST(SUBSTR(DT2_2_1.KSM_ID, 2, 1) AS BIGNUMERIC), 0) > 7
       THEN 7
       ELSE ROUND(CAST(SUBSTR(DT2_2_1.KSM_ID, 2, 1) AS BIGNUMERIC), 0)
       END AS KSM_ID,
      DT2_2_2.VW_ID
     FROM KFL_PRODUCTION_DBP_DATA.SM_WUP_WG_ZU_PER_1 AS DT2_2_1
      INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_1 AS DT2_2_2 ON DT2_2_1.MANDANT_ID = DT2_2_2.MANDANT_ID AND DT2_2_1.WUP_ID =
         DT2_2_2.WUP_ID AND DT2_2_1.NB_ID = DT2_2_2.NB_ID
     WHERE CURRENT_DATE BETWEEN DT2_2_1.DAT_VON AND DT2_2_1.DAT_BIS
      AND CURRENT_DATE BETWEEN DT2_2_2.DAT_VON AND DT2_2_2.DAT_BIS
      AND DT2_2_1.NB_ID = 0
      AND LENGTH(DT2_2_1.KSM_ID) = 2
      AND SUBSTR(DT2_2_1.KSM_ID, 1, 1) = 'K'
      AND ROUND(CAST(SUBSTR(DT2_2_1.KSM_ID, 2, 1) AS BIGNUMERIC), 0) BETWEEN 1 AND 9
     GROUP BY DT2_2_1.MANDANT_ID,
      DT2_2_1.WUP_ID,
      DT2_2_1.WG_ID,
      KSM_ID,
      DT2_2_2.VW_ID) AS dt2_2 ON t5.MANDANT_ID = dt2_2.MANDANT_ID AND t5.WUP_ID = dt2_2.WUP_ID AND t5.WG_ID = dt2_2.WG_ID
      
   GROUP BY t5.MANDANT_ID,
    t5.ART_ID,
    t5.WG_ID,
    dt2_2.KSM_ID,
    dt2_2.VW_ID) AS dt_2 ON dt_1.MANDANT_ID = dt_2.MANDANT_ID AND dt_1.WG_ID = dt_2.WG_ID AND dt_1.KSM_ID = dt_2.KSM_ID
   AND dt_1.VW_ID = dt_2.VW_ID);


