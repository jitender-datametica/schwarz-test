DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.AWP_TMP_1;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 LIKE KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_1;


CREATE TEMPORARY TABLE IF NOT EXISTS _GATHER AS
(SELECT MANDANT_ID,
  ART_ID,
  WUP_ID,
  DAT,
  NB_ID
 FROM KFL_PRODUCTION_DBP_ETL.AWP_VK_1
 WHERE VK_BRUTTO < 1000000
 GROUP BY ART_ID,
  MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT
 UNION DISTINCT
 SELECT MANDANT_ID,
  ART_ID,
  WUP_ID,
  DAT,
  NB_ID
 FROM KFL_PRODUCTION_DBP_ETL.AWP_LSTG_1
 GROUP BY ART_ID,
  MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT)
UNION DISTINCT
SELECT MANDANT_ID,
 ART_ID,
 WUP_ID,
 DAT,
 NB_ID
FROM KFL_PRODUCTION_DBP_ETL.AWP_MARC_1
GROUP BY ART_ID,
 MANDANT_ID,
 WUP_ID,
 NB_ID,
 DAT;


INSERT INTO KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 (MANDANT_ID, WUP_ID, NB_ID, DAT_VON, ART_ID, BEZUGSWEG_ID, LISTUNG_ID,
 VK_BRUTTO, DAT_BIS, KDIS, WRG_ID, TD_INSERT, TD_UPDATE)
(SELECT T1.MANDANT_ID,
  T1.WUP_ID,
  T1.NB_ID,
  T1.DAT AS DAT_VON,
  T1.ART_ID,
  COALESCE(T3.BEZUGSWEG_ID, 4) AS BEZUGSWEG_ID,
  COALESCE(T4.LISTUNG_ID, 0) AS LISTUNG_ID,
  COALESCE(t2.VK_BRUTTO, 0) AS VK_BRUTTO,
  PARSE_DATE('%F', '9999-12-31') AS DAT_BIS,
  COALESCE(T3.KDIS, 0) AS KDIS,
  COALESCE(t2.WRG_ID, X.DEFAULT_WRG) AS WRG_ID,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP()
 FROM `_GATHER` AS T1_1
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MANDANT_1 AS X ON T1.MANDANT_ID = X.MANDANT_ID
  LEFT JOIN KFL_PRODUCTION_DBP_ETL.AWP_LSTG_1 AS T4 ON T1.ART_ID = T4.ART_ID AND T1.WUP_ID = T4.WUP_ID AND T1.MANDANT_ID =
     T4.MANDANT_ID AND T1.DAT = T4.DAT
  LEFT JOIN (SELECT *
   FROM KFL_PRODUCTION_DBP_ETL.AWP_VK_1
   WHERE VK_BRUTTO < 1000000) AS t2 ON T1.ART_ID = t2.ART_ID AND T1.WUP_ID = t2.WUP_ID AND T1.MANDANT_ID = t2.MANDANT_ID
      AND T1.DAT = t2.DAT
  LEFT JOIN KFL_PRODUCTION_DBP_ETL.AWP_MARC_1 AS T3 ON T1.ART_ID = T3.ART_ID AND T1.WUP_ID = T3.WUP_ID AND T1.MANDANT_ID =
     T3.MANDANT_ID AND T1.DAT = T3.DAT);


INSERT INTO KFL_PRODUCTION_DBP_ETL.AWP_TMP_1
(SELECT *
 FROM KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_1
 WHERE DAT_BIS >= CURRENT_DATE
  AND DAT_VON < CURRENT_DATE);


DELETE FROM KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 AS T1_1
WHERE EXISTS (SELECT *
 FROM KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 AS T2
 WHERE T1.WUP_ID = WUP_ID
  AND T1.ART_ID = ART_ID
  AND T1.MANDANT_ID = MANDANT_ID
  AND DATE_SUB(T1.DAT_VON, INTERVAL 1 DAY) = DAT_VON
  AND T1.LISTUNG_ID = LISTUNG_ID
  AND T1.BEZUGSWEG_ID = BEZUGSWEG_ID
  AND T1.KDIS = KDIS
  AND T1.VK_BRUTTO = VK_BRUTTO
  AND T1.WRG_ID = WRG_ID);


DELETE FROM KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 AS T1_1
WHERE EXISTS (SELECT *
  FROM KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 AS T2
  WHERE T1.WUP_ID = WUP_ID
   AND T1.ART_ID = ART_ID
   AND T1.MANDANT_ID = MANDANT_ID
   AND T1.LISTUNG_ID = LISTUNG_ID
   AND T1.BEZUGSWEG_ID = BEZUGSWEG_ID
   AND T1.KDIS = KDIS
   AND T1.VK_BRUTTO = VK_BRUTTO
   AND T1.WRG_ID = WRG_ID
   AND DAT_VON < CURRENT_DATE) AND DAT_VON = CURRENT_DATE;


UPDATE KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 AS T
SET DAT_BIS = DT1._DAT_BIS
FROM (
    SELECT
        T1.MANDANT_ID AS _MANDANT_ID,
        T1.ART_ID     AS _ART_ID,
        T1.DAT_VON    AS _DAT_VON,
        T1.WUP_ID     AS _WUP_ID,
        T1.NB_ID      AS _NB_ID,
        DATE_SUB(
            LEAD(DAT_VON, 1, DATE '9999-01-01')
                OVER (
                    PARTITION BY T1.MANDANT_ID, T1.ART_ID, T1.WUP_ID, T1.NB_ID
                    ORDER BY DAT_VON
                ),
            INTERVAL 1 DAY
        ) AS _DAT_BIS
    FROM KFL_PRODUCTION_DBP_ETL.AWP_TMP_1 T1_1
) AS DT1
WHERE T.ART_ID     = DT1._ART_ID
  AND T.WUP_ID     = DT1._WUP_ID
  AND T.DAT_VON    = DT1._DAT_VON
  AND T.MANDANT_ID = DT1._MANDANT_ID
  AND T.DAT_BIS    <> DT1._DAT_BIS;



DELETE FROM KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_1
WHERE DAT_BIS >= CURRENT_DATE;


