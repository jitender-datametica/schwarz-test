                 IS NULL OR CAST(BONUSKAUF_ID AS FLOAT64) = 0)) AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000', '') AND
          KUNDENKARTE_ID IS NOT NULL AND AKTION_ID_OBV IS NOT NULL
        THEN 100211
        ELSE CASE
         WHEN (KUNDENKARTE_ID IS NULL AND KUNDENKARTE_TYP_ID IN (0) OR KUNDENKARTE_TYP_ID IN (3, 4)) AND
              CUSTOMER_PROMOTION_FG = 0 AND PROMOTION_ART = 'COMMON' AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000', ''
             ) AND BONUSKAUF_ID IS NOT NULL
         THEN 100220
         ELSE CASE
          WHEN KUNDENKARTE_TYP_ID IN (2) AND CUSTOMER_PROMOTION_FG = 0 AND PROMOTION_ART = 'COMMON' AND LTRIM(AKTION_ID
               ) NOT IN ('0', '0000000000', '') AND BONUSKAUF_ID IS NOT NULL AND KUNDENKARTE_ID IS NOT NULL
          THEN 100221
          ELSE CASE
           WHEN CUSTOMER_PROMOTION_FG = 1 AND PROMOTION_ART = 'CUSTOMER' AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000'
