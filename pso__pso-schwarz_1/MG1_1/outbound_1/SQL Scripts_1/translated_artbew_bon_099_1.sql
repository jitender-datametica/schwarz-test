    ART_ID,
    KL_ART_ID,
    POSTEN_ID,
    MWST_ID
   FROM KFL_PRODUCTION_DBP_DATA.ART_1
   QUALIFY (ROW_NUMBER() OVER (PARTITION BY CAST(MANDANT_ID AS STRING), CAST(KL_ART_ID AS STRING) ORDER BY ART_ID
         IS NULL DESC, ART_ID DESC)) = 1) AS t2 ON p.KL_ART_ID = t2.KL_ART_ID AND p.MANDANT_ID = t2.MANDANT_ID
  LEFT JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.DWH_WG_ERFASS_ARTIKEL_1 AS ERF ON p.MANDANT_ID = ERF.MANDANT_ID AND p.WG_ID =
     ERF.WG_ID AND ERF.ARTHIERTYP_ID = 2
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_1 AS AERF ON ERF.MANDANT_ID = AERF.MANDANT_ID AND ERF.ART_ID = AERF.ART_ID
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.MWST_PER_1 AS MW ON p.MANDANT_ID = MW.MANDANT_ID AND p.DAT BETWEEN MW.DAT_VON AND MW.DAT_BIS
       AND p.MWST_ID = MW.MWST_ID AND COALESCE(MW.MWST, 0) <> 0
