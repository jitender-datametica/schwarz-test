CREATE OR REPLACE TEMPORARY TABLE _TRACK_PERSONAL AS
SELECT A.MANDANT_ID,
 A.BON_ID,
 A.BON_ZEILE,
 A.BON_DAT,
 A.WUP_ID,
 A.PROMOTION_ART,
 MAX(b.ANZ) AS ANZ,
 COUNT(*) AS ANZ_ZEILEN,
 MAX(b.BONRABATT) AS BONRABATT
FROM KFL_PRODUCTION_DBP_ODS.ODS_PROMOTION_1 AS A
 INNER JOIN (SELECT MANDANT_ID,
   BON_ID,
   BON_ZEILE,
   BON_DAT,
   WUP_ID,
   COUNT(DISTINCT PROMOTION_ART) AS ANZ,
   MAX(CASE
     WHEN KONDITIONSART_ID IN ('ZBON', 'ZBOV')
     THEN 1
     ELSE 0
     END) AS BONRABATT
  FROM KFL_PRODUCTION_DBP_ODS.ODS_PROMOTION_1
  GROUP BY MANDANT_ID,
   BON_ID,
   BON_ZEILE,
   BON_DAT,
   WUP_ID) AS b ON A.MANDANT_ID = b.MANDANT_ID AND A.BON_ID = b.BON_ID AND A.BON_ZEILE = b.BON_ZEILE AND A.BON_DAT = b.BON_DAT
     AND A.WUP_ID = b.WUP_ID
WHERE (A.MANDANT_ID, A.BON_ID, A.BON_ZEILE, A.BON_DAT, A.WUP_ID) IN (SELECT (MANDANT_ID, BON_ID, BON_ZEILE, BON_DAT,
     WUP_ID)
   FROM KFL_PRODUCTION_DBP_ODS.ODS_PROMOTION_1
   WHERE PROMOTION_ART = 'PERSONAL'
   GROUP BY MANDANT_ID,
    BON_ID,
    BON_ZEILE,
    BON_DAT,
    WUP_ID)
 AND A.KONDITIONSART_ID NOT IN ('ZRT3', 'ZTAG', 'ZGEB')
GROUP BY A.MANDANT_ID,
 A.BON_ID,
 A.WUP_ID,
 A.BON_ZEILE,
 A.BON_DAT,
 A.PROMOTION_ART;


