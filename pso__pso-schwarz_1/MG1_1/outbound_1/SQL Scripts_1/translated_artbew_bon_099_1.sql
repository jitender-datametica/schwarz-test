     MWS.DAT_BIS AND COALESCE(t2.MWST_ID, AERF.MWST_ID) = MWS.MWST_ID
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_1 AS AW ON p.MANDANT_ID = AW.MANDANT_ID AND p.WUP_ID = AW.WUP_ID AND
     COALESCE(t2.ART_ID, ERF.ART_ID, 0) = AW.ART_ID AND p.DAT BETWEEN AW.DAT_VON AND AW.DAT_BIS
 GROUP BY p.MANDANT_ID,
  WRG_1,
  p.WUP_ID,
  W.NB_ID,
  p.DAT,
  POSTEN_ID,
  COALESCE(AW.BEZUGSWEG_ID, p.BEZUGSWEG_ID),
  1,
  EAN_KASSE,
  p.BEWART_ID,
  COALESCE(MW.MWST_ID, MWS.MWST_ID),
  p.AKTION_ID,
  p.BEWART_DET_ID,
  STANDARD_AKTION_ID
 HAVING MENGE_ <> 0 OR SUM(p.UMSATZ) - UMSATZ_MWST_BETRAG <> 0);


