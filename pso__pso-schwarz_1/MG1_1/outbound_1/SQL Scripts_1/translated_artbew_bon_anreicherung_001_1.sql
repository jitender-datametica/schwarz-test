CREATE OR REPLACE TEMPORARY TABLE _TRACK_ZBON_ZBOV_UNIQUE_PERSONAL
  AS
    SELECT
        A.MANDANT_ID,
        A.BON_ID,
        A.BON_ZEILE,
        A.BON_DAT,
        A.WUP_ID,
        A.PROMOTION_ART,
        NUMERIC '1' AS FLAG,
        max(B.ANZ) AS ANZ,
        max(B.BONRABATT) AS BONRABATT
      FROM
        KFL_PRODUCTION_DBP_ODS.ODS_PROMOTION_1 AS A
        INNER JOIN (
          SELECT
              ODS_PROMOTION.MANDANT_ID,
              ODS_PROMOTION.BON_ID,
              ODS_PROMOTION.BON_ZEILE,
              ODS_PROMOTION.BON_DAT,
              ODS_PROMOTION.WUP_ID,
              CAST(count(DISTINCT ODS_PROMOTION.PROMOTION_ART) as BIGNUMERIC) AS ANZ,
              max(CASE
                WHEN ODS_PROMOTION.KONDITIONSART_ID IN(
                  'ZBON', 'ZBOV'
                ) THEN NUMERIC '1'
                ELSE NUMERIC '0'
              END) AS BONRABATT
            FROM
              KFL_PRODUCTION_DBP_ODS.ODS_PROMOTION_1
            GROUP BY 1, 2, 3, 4, 5
        ) AS B ON A.MANDANT_ID = B.MANDANT_ID
         AND A.BON_ID = B.BON_ID
         AND A.BON_ZEILE = B.BON_ZEILE
         AND A.BON_DAT = B.BON_DAT
         AND A.WUP_ID = B.WUP_ID
      WHERE (A.MANDANT_ID, A.BON_ID, A.BON_ZEILE, A.BON_DAT, A.WUP_ID) IN(
        SELECT AS STRUCT
            B.MANDANT_ID,
            B.BON_ID,
            B.BON_ZEILE,
            B.BON_DAT,
            B.WUP_ID
          FROM
            KFL_PRODUCTION_DBP_ODS.ODS_PROMOTION_1
          WHERE A.PROMOTION_ART = 'PERSONAL'
          GROUP BY 1, 2, 3, 4, 5
      )
       AND A.KONDITIONSART_ID NOT IN(
        'ZRT3', 'ZTAG', 'ZGEB'
      )
      GROUP BY 1, 2, 3, 4, 5, 6
      HAVING count(DISTINCT PROMOTION_ART) = FLAG
       AND max(B.BONRABATT) = NUMERIC '0'
       AND max(B.ANZ) = FLAG
;


