CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_NEUE_TALONS` AS
SELECT MANDANT_ID,
 WUP_ID,
 TALON_ID,
 SUM(UMSATZ_BRUTTO) AS UMSATZ_BRUTTO_TALON
FROM KFL_PRODUCTION_DBP_ODS.ODS_TALON_DET_1
WHERE ARTBEW_FG = 0
 AND (SUBSTR(CAST(TALON_ID AS STRING), 1, 2) = '90' OR STRPOS(CAST(KL_ART_ID AS STRING), CAST(TALON_ID AS STRING)) <= 0
