 LEFT JOIN `_TRACK_ZBON_ZBOV` AS Y ON A.MANDANT_ID = Y.MANDANT_ID AND A.WUP_ID = Y.WUP_ID AND A.BON_ID = Y.BON_ID AND A
     .BON_ZEILE = Y.BON_ZEILE AND A.LFD_NR = Y.PROMOTION_LFD_NR AND A.DAT_BOOKING = Y.BON_DAT
 LEFT JOIN KFL_PRODUCTION_DBP_DATA.L_BONUSKAUF_1 AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.BONUSKAUF_ID = B.BONUSKAUF_ID
  AND A.DAT_BOOKING BETWEEN B.DAT_VON AND B.DAT_BIS
GROUP BY A.MANDANT_ID,
 A.BON_ID,
 A.DAT_BOOKING,
 A.BON_ZEILE,
 A.CUSTOMER_PROMOTION_FG,
 A.PROMOTION_ART,
 IMPORTANT,
 BBY_BEWART,
 BBY_UNIQUE;


