DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_DAT_1;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_DAT_1 (
DAT DATE NOT NULL
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_DAT_1 (DAT)
(SELECT DAT
 FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
 GROUP BY DAT);


DELETE FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
WHERE (MANDANT_ID, WG_ID, ARTHIERTYP_ID) IN (SELECT (MANDANT_ID, WG_ID, ARTHIERTYP_ID)
   FROM KFL_PRODUCTION_DBP_DATA.WG_FILTER_ZU_1
   WHERE WG_FILTER_ID = 38) AND UMSATZ_MWST_BETRAG = 0;


DELETE FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
WHERE (MANDANT_ID, WG_ID, ARTHIERTYP_ID) IN (SELECT (MANDANT_ID, WG_ID, ARTHIERTYP_ID)
  FROM KFL_PRODUCTION_DBP_DATA.WG_FILTER_ZU_1
  WHERE WG_FILTER_ID = 49);


DELETE FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
WHERE MANDANT_ID = 1 AND ART_ID IN (590006700, 590006900);


UPDATE KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1 SET
 MENGE = 0 FROM (SELECT *
  FROM KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1
  WHERE ARTHIERTYP_ID = 2
   AND DAT_BIS = DATE '9999-12-31'
   AND WG_ID = 823
   AND WUG_ID IN (2, 3, 4)) AS b
WHERE ARTBEW_MIS.MANDANT_ID = b.MANDANT_ID AND ARTBEW_MIS.ART_ID = b.ART_ID;


DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_1
WHERE (MANDANT_ID, WUP_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, DAT)
   FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1) AND DAT IN (SELECT DAT
   FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_DAT_1);


INSERT INTO KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_1 (MANDANT_ID, NB_ID, ARTHIERTYP_ID, WG_ID, DAT, WUP_ID, BEWART_ID, KJMO
 , UMSATZ_BRUTTO, UMSATZ_NETTO, UMSATZ_WRG, UMSATZ_BRUTTO_KONZ, UMSATZ_NETTO_KONZ, QUELLE, MENGE, UMRECHNUNGSKURS_HIST)
(SELECT MANDANT_ID,
  NB_ID,
  ARTHIERTYP_ID,
  WG_ID,
  DAT,
  WUP_ID,
  1001 AS BEWART_ID_,
  CAST(ROUND(CAST(FORMAT_DATE('%Y%m', DAT) AS BIGNUMERIC), 0) AS INTEGER) AS KJMO,
  SUM(UMSATZ_NETTO + UMSATZ_MWST_BETRAG) AS UMSATZ_BRUTTO,
  SUM(UMSATZ_NETTO),
  WRG_1 AS UMSATZ_WRG,
  SUM(UMSATZ_NETTO + UMSATZ_MWST_BETRAG + DIFF_UMSATZ_NETTO_KONZ + DIFF_UMSATZ_MWST_BETRAG_KONZ) AS UMSATZ_BRUTTO_KONZ,
  SUM(UMSATZ_NETTO + DIFF_UMSATZ_NETTO_KONZ) AS UMSATZ_NETTO_KONZ,
  1 AS QUELLE,
  SUM(MENGE) AS MENGE_,
  1 AS UMRECHNUNGSKURS_HIST
 FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
 WHERE WG_ID IS NOT NULL
 GROUP BY MANDANT_ID,
  WUP_ID,
  NB_ID,
  WG_ID,
  ARTHIERTYP_ID,
  BEWART_ID_,
  DAT,
  UMSATZ_WRG,
  KJMO,
  QUELLE);


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_1 SET
 DATENLIEFERUNG_ARTBEW_WG_SUM = 1,
 DAT_EXTRAKT_UMSATZ = CURRENT_DATE
WHERE (MANDANT_ID, WUP_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, DAT)
  FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
  WHERE NB_ID IN (0, 2, 7));


INSERT INTO KFL_PRODUCTION_DBP_ETL_PROCESS.ARTBEW_WG_SUM_AGG_WT_1 (MANDANT_ID, WUP_ID, NB_ID, DAT, CALC_FG, DAT_LIEF)
(SELECT MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT,
  0 AS CALC_FG,
  CURRENT_DATE AS DAT_LIEF
 FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1
 WHERE (MANDANT_ID, WUP_ID, NB_ID, DAT) NOT IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
    FROM KFL_PRODUCTION_DBP_ETL_PROCESS.ARTBEW_WG_SUM_AGG_WT_1)
 GROUP BY MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT,
  CALC_FG,
  DAT_LIEF);


TRUNCATE TABLE KFL_PRODUCTION_DBP_ETL.ARTBEW_MIS_1;