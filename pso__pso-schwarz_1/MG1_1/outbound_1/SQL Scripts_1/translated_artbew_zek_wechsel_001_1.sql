CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_TMP_1 (
MANDANT_ID INTEGER NOT NULL,
ART_ID INTEGER NOT NULL,
ALT_NEU_KZ INTEGER NOT NULL,
ZEK_ID STRING(3) NOT NULL
);


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_JOIN_1 (
MANDANT_ID INTEGER NOT NULL,
ART_ID INTEGER NOT NULL,
KJMO INTEGER NOT NULL,
ALT_NEU_KZ INTEGER NOT NULL,
ZEK_ID STRING(3) NOT NULL
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_TMP_1 (MANDANT_ID, ART_ID, ALT_NEU_KZ, ZEK_ID)
(SELECT MANDANT_ID,
  ART_ID,
  - 1,
  ZEK_ID
 FROM KFL_PRODUCTION_DBP_PROCESS.ARTBEW_ZEK_WECHSEL_1);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_TMP_1 (MANDANT_ID, ART_ID, ALT_NEU_KZ, ZEK_ID)
(SELECT MANDANT_ID,
  ART_ID,
  1,
  ZEK_ID
 FROM KFL_PRODUCTION_DBP_DATA.ART_1);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_JOIN_1 (MANDANT_ID, ART_ID, KJMO, ALT_NEU_KZ, ZEK_ID)
(SELECT W1.MANDANT_ID,
  W1.ART_ID,
  M.KJMO,
  W1.ALT_NEU_KZ,
  W1.ZEK_ID
 FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_TMP_1 AS W1
  INNER JOIN KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_TMP_1 AS W2 ON W1.MANDANT_ID = W2.MANDANT_ID AND W1.ART_ID = W2.ART_ID
      AND (W1.ALT_NEU_KZ = 1 AND W2.ALT_NEU_KZ = - 1 OR W1.ALT_NEU_KZ = - 1 AND W2.ALT_NEU_KZ = 1)
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MONAT_1 AS M ON M.AKT_MO <= 0 AND M.KJMO >= 200001
 WHERE W1.ZEK_ID <> W2.ZEK_ID);


CREATE OR REPLACE TEMPORARY TABLE _ZEK_CHANGE AS
SELECT MANDANT_ID,
 ZEK_ID
FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_ZEK_WECHSEL_JOIN_1
GROUP BY MANDANT_ID,
 ZEK_ID;


DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_ZEK_MO_SUM_1
WHERE (MANDANT_ID, ZEK_ID) IN (SELECT (MANDANT_ID, ZEK_ID)
  FROM `_ZEK_CHANGE`);


INSERT INTO KFL_PRODUCTION_DBP_DATA.ARTBEW_ZEK_MO_SUM_1 (MANDANT_ID, KJMO, BEWART_ID, WUP_ID, NB_ID, POSTEN_ID, MENGE,
 UMSATZ_NETTO, DIFF_UMSATZ_NETTO_KONZ, UMSATZ_MWST_BETRAG, DIFF_UMSATZ_MWST_BETRAG_KONZ, EK_BRUTTO, DIFF_EK_BRUTTO_KONZ
 , EK_NETTO, DIFF_EK_NETTO_KONZ, EK_NETTONETTO, DIFF_EK_NETTONETTO_KONZ, EK_KAL_BASIS, DIFF_EK_KAL_BASIS_KONZ, EK_MEP,
 DIFF_EK_MEP_KONZ, EINSTANDSPREIS, DIFF_EINSTANDSPREIS_KONZ, LOGKOSTENZUSCHLAG, DIFF_LOGKOSTENZUSCHLAG_KONZ,
 EK_NETTO_BNK, DIFF_EK_NETTO_BNK_KONZ, EK_NETTO_BNK_SACHK, DIFF_EK_NETTO_BNK_SACHK_KONZ, DIFF_EK_GLD_KONZ, EK_GLD,
 BEWART_DET_ID, PV_AKTION, PV_BBY, PV_KDN_BBY, PV_KDP_BBY, PV_AKTION_BBY, PV_AKTION_KDN_BBY, PV_AKTION_KDP_BBY,
 TD_UPDATE, TD_INSERT, EK_MEP_VOR_FWU, EK_MEP_VOR_FWU_KONZ, BONUSBASIS, BONUSBASIS_KONZ, PV_BONRABATT_BBY, ZEK_ID,
 WRG_ID, UMRECHNUNGSKURS_HIST)
(SELECT A.MANDANT_ID,
  A.KJMO,
  A.BEWART_ID,
  A.WUP_ID,
  A.NB_ID,
  A.POSTEN_ID,
  SUM(A.MENGE),
  SUM(A.UMSATZ_NETTO),
  SUM(A.DIFF_UMSATZ_NETTO_KONZ),
  SUM(A.UMSATZ_MWST_BETRAG),
  SUM(A.DIFF_UMSATZ_MWST_BETRAG_KONZ),
  SUM(A.EK_BRUTTO),
  SUM(A.DIFF_EK_BRUTTO_KONZ),
  SUM(A.EK_NETTO),
  SUM(A.DIFF_EK_NETTO_KONZ),
  SUM(A.EK_NETTONETTO),
  SUM(A.DIFF_EK_NETTONETTO_KONZ),
  SUM(A.EK_KAL_BASIS),
  SUM(A.DIFF_EK_KAL_BASIS_KONZ),
  SUM(A.EK_MEP),
  SUM(A.DIFF_EK_MEP_KONZ),
  SUM(A.EINSTANDSPREIS),
  SUM(A.DIFF_EINSTANDSPREIS_KONZ),
  SUM(A.LOGKOSTENZUSCHLAG),
  SUM(A.DIFF_LOGKOSTENZUSCHLAG_KONZ),
  SUM(A.EK_NETTO_BNK),
  SUM(A.DIFF_EK_NETTO_BNK_KONZ),
  SUM(A.EK_NETTO_BNK_SACHK),
  SUM(A.DIFF_EK_NETTO_BNK_SACHK_KONZ),
  SUM(A.DIFF_EK_GLD_KONZ),
  SUM(A.EK_GLD),
  A.BEWART_DET_ID,
  SUM(A.PV_AKTION),
  SUM(A.PV_BBY),
  SUM(A.PV_KDN_BBY),
  SUM(A.PV_KDP_BBY),
  SUM(A.PV_AKTION_BBY),
  SUM(A.PV_AKTION_KDN_BBY),
  SUM(A.PV_AKTION_KDP_BBY),
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP(),
  SUM(A.EK_MEP_VOR_FWU),
  SUM(A.EK_MEP_VOR_FWU_KONZ),
  SUM(A.BONUSBASIS),
  SUM(A.BONUSBASIS_KONZ),
  SUM(A.PV_BONRABATT_BBY),
  B.ZEK_ID,
  A.WRG_ID,
  MAX(K.UMRECHNUNGSKURS)
 FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_MO_SUM_1 AS A
  INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_1 AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.ART_ID = B.ART_ID AND CASE
     WHEN A.MANDANT_ID = 2 AND A.ART_ID = 208124500 OR A.MANDANT_ID = 3 AND A.ART_ID = 208113690 OR A.MANDANT_ID = 5 AND
           A.ART_ID = 206731500 OR A.MANDANT_ID = 6 AND A.ART_ID = 208131570 OR A.MANDANT_ID IN (4, 7) AND A.ART_ID =
         208114740 OR A.MANDANT_ID = 8 AND A.ART_ID = 208131640
     THEN 0
     ELSE 1
     END = 1
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MONAT_1 AS X ON A.KJMO = X.KJMO
  INNER JOIN KFL_PRODUCTION_DBP_DATA.KURS_1 AS K ON A.WRG_ID = K.VON_WRG_ID AND X.MIN_DAT BETWEEN K.DAT_VON AND K.DAT_BIS
    AND K.NACH_WRG_ID = 'EUR' AND K.KURSTYP_ID = 3
 WHERE (A.MANDANT_ID, B.ZEK_ID) IN (SELECT (MANDANT_ID, ZEK_ID)
    FROM `_ZEK_CHANGE`)
 GROUP BY A.MANDANT_ID,
  A.WUP_ID,
  A.NB_ID,
  A.KJMO,
  A.BEWART_ID,
  A.POSTEN_ID,
  A.BEWART_DET_ID,
  A.WRG_ID,
  B.ZEK_ID);


