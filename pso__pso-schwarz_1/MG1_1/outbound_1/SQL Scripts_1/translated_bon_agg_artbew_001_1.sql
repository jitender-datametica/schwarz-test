CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.BON_AGG_ARTBEW_TMP_1 (
WUP_ID INTEGER NOT NULL,
MANDANT_ID INTEGER NOT NULL,
BON_DAT DATE NOT NULL,
XML_NAME STRING(255)
);


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.BON_ARTBEW_TGL_DELTA_1 (
WUP_ID INTEGER NOT NULL,
MANDANT_ID INTEGER NOT NULL,
DAT DATE NOT NULL
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.BON_AGG_ARTBEW_TMP_1 (WUP_ID, MANDANT_ID, BON_DAT, XML_NAME)
(SELECT T2.WUP_ID,
  T2.MANDANT_ID,
  T2.BON_DAT,
  T1.XML_NAME
 FROM KFL_PRODUCTION_DBP_ODS.BON_LOAD_STATUS_1 AS T1_1
  INNER JOIN KFL_PRODUCTION_DBP_ODS.ODS_BON_TRANSACTION_1 AS T2 ON T1.XML_NAME = T2.DATEI_NAME
 WHERE T1.ARTBEW_FG = 0
  AND T1.PARSEBON_TIME <= CAST(TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 10 MINUTE) AS DATETIME)
  AND T2.MANDANT_ID = 1
  AND T2.BON_DAT < CURRENT_DATE
  AND T2.BON_DAT > DATE_SUB(CURRENT_DATE, INTERVAL 90 DAY));


INSERT INTO KFL_PRODUCTION_DBP_ETL.BON_ARTBEW_TGL_DELTA_1 (WUP_ID, MANDANT_ID, DAT)
(SELECT WUP_ID,
  MANDANT_ID,
  BON_DAT
 FROM KFL_PRODUCTION_DBP_ETL.BON_AGG_ARTBEW_TMP_1
 WHERE (MANDANT_ID, WUP_ID, BON_DAT) NOT IN (SELECT (MANDANT_ID, WUP_ID, DAT)
    FROM KFL_PRODUCTION_DBP_ETL.BON_ARTBEW_TGL_DELTA_1)
 GROUP BY WUP_ID,
  MANDANT_ID,
  BON_DAT);


UPDATE KFL_PRODUCTION_DBP_ODS.BON_LOAD_STATUS_1 SET
 ARTBEW_FG = 1
WHERE XML_NAME IN (SELECT XML_NAME
  FROM KFL_PRODUCTION_DBP_ETL.BON_AGG_ARTBEW_TMP_1);