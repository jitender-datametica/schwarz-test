CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.TMP_ART_WUP_TAG_GLD_1 (
ART_ID INTEGER NOT NULL,
MANDANT_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID INTEGER NOT NULL,
DAT DATE NOT NULL,
EK_GLD NUMERIC(18,4),
UMRECHNUNGSKURS FLOAT64
);


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.SNAP_ART_WUP_TAG_GLD_1 AS
SELECT MANDANT_ID,
 ART_ID,
 WUP_ID,
 NB_ID,
 DAT_BUCH,
 SUM(SUM_BETRAG) AS SUM_BETRAG,
 SUM(CAST(SUM_MENGE AS NUMERIC)) AS SUM_MENGE
FROM (SELECT L.MANDANT_ID,
    L.ART_ID,
    L.WUP_ID,
    L.NB_ID,
    L.DAT_BUCH,
    ABS(SUM(CAST(L.BETRAG_LAGERBEW AS NUMERIC))) AS SUM_BETRAG,
    ABS(SUM(L.MENGE_LAGERBEW_BME)) AS SUM_MENGE
   FROM KFL_PRODUCTION_DBP_DATA.LAGERBEW_DET_1 AS L
    INNER JOIN KFL_PRODUCTION_DBP_ETL.GLD_DAT_1 AS D ON L.DAT_BUCH = D.DAT
   WHERE L.LAGER_BEWART_ID IN ('251', '252')
    AND L.MANDANT_ID > 1
   GROUP BY L.MANDANT_ID,
    L.ART_ID,
    L.WUP_ID,
    L.NB_ID,
    L.DAT_BUCH
   UNION ALL
   SELECT L.MANDANT_ID,
    L.ART_ID,
    L.WUP_ID,
    L.NB_ID,
    L.DAT_BUCH,
    ABS(SUM(CAST(L.BETRAG_LAGERBEW AS NUMERIC))) AS SUM_BETRAG,
    ABS(SUM(L.MENGE_LAGERBEW_BME)) AS SUM_MENGE
   FROM KFL_PRODUCTION_DBP_DATA.LAGERBEW_DET_DELTA_1 AS L
    INNER JOIN KFL_PRODUCTION_DBP_ETL.GLD_DAT_1 AS D ON L.DAT_BUCH = D.DAT
   WHERE L.LAGER_BEWART_ID IN ('251', '252')
    AND L.MANDANT_ID > 1
   GROUP BY L.MANDANT_ID,
    L.ART_ID,
    L.WUP_ID,
    L.NB_ID,
    L.DAT_BUCH) AS x
GROUP BY MANDANT_ID,
 ART_ID,
 WUP_ID,
 NB_ID,
 DAT_BUCH;


INSERT INTO KFL_PRODUCTION_DBP_ETL.TMP_ART_WUP_TAG_GLD_1 (ART_ID, MANDANT_ID, WUP_ID, NB_ID, DAT, EK_GLD, UMRECHNUNGSKURS
 )
(SELECT A.ART_ID,
  A.MANDANT_ID,
  A.WUP_ID,
  A.NB_ID,
  A.DAT_BUCH,
  CAST(CASE
    WHEN A.SUM_MENGE = 0
    THEN 0
    ELSE A.SUM_BETRAG / A.SUM_MENGE
    END AS NUMERIC) AS EK_GLD,
  CAST(K.UMRECHNUNGSKURS AS FLOAT64) AS UMRECHNUNGSKURS
 FROM KFL_PRODUCTION_DBP_ETL.SNAP_ART_WUP_TAG_GLD_1 AS A
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MANDANT_1 AS M ON A.MANDANT_ID = M.MANDANT_ID
  INNER JOIN KFL_PRODUCTION_DBP_DATA.KURS_1 AS K ON M.DEFAULT_WRG = K.VON_WRG_ID AND K.KURSTYP_ID = 3 AND K.NACH_WRG_ID =
     'EUR' AND K.DAT_BIS = DATE '9999-12-31');


