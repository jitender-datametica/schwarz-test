 DIFF_EK_GLD_KONZ = ARTBEW.DIFF_EK_NETTO_KONZ FROM DBP_ETL.GLD_DAT_1, KFL_PRODUCTION_DBP_DATA.ART_1 AS A
WHERE ARTBEW.DAT = GLD_DAT.DAT AND ARTBEW.MANDANT_ID > 1 AND ARTBEW.MANDANT_ID = A.MANDANT_ID AND ARTBEW.ART_ID = A.ART_ID
     AND ARTBEW.ART_ID > - 1 AND A.WG_ART_FG = 1;


UPDATE KFL_PRODUCTION_DBP_DATA.ARTBEW_1 SET
 EK_GLD = CAST(b.EK_GLD * ARTBEW.MENGE AS NUMERIC),
 DIFF_EK_GLD_KONZ = CAST(b.EK_GLD * ARTBEW.MENGE * b.UMRECHNUNGSKURS AS NUMERIC) FROM KFL_PRODUCTION_DBP_ETL.ABWEICHENDE_ART_WUP_TAG_GLD_1
 AS b
WHERE ARTBEW.MANDANT_ID = b.MANDANT_ID AND ARTBEW.WUP_ID = b.WUP_ID AND ARTBEW.ART_ID = b.ART_ID AND ARTBEW.DAT = b.DAT
 AND ARTBEW.MANDANT_ID > 1;


