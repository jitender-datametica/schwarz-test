CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.FEHLENDE_ART_WUP_TAG_GLD_1 AS
SELECT a.MANDANT_ID,
 a.WUP_ID,
 a.ART_ID,
 a.DAT
FROM (SELECT A.MANDANT_ID,
   A.WUP_ID,
   A.ART_ID,
   A.DAT
  FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_1 AS A
   INNER JOIN KFL_PRODUCTION_DBP_ETL.GLD_DAT_1 AS C ON A.DAT = C.DAT
  WHERE A.MANDANT_ID > 1
  GROUP BY A.MANDANT_ID,
   A.WUP_ID,
   A.DAT,
   A.ART_ID) AS a
 LEFT JOIN KFL_PRODUCTION_DBP_ETL.TMP_ART_WUP_TAG_GLD_1 AS B ON a.MANDANT_ID = B.MANDANT_ID AND a.WUP_ID = B.WUP_ID AND a
    .ART_ID = B.ART_ID AND a.DAT = B.DAT
WHERE B.UMRECHNUNGSKURS IS NULL
GROUP BY a.MANDANT_ID,
 a.WUP_ID,
 a.ART_ID,
 a.DAT;


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.ABWEICHENDE_ART_WUP_TAG_GLD_1 AS
SELECT B.MANDANT_ID,
 B.DAT,
 B.WUP_ID,
 B.ART_ID,
 B.EK_GLD,
 B.UMRECHNUNGSKURS
FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_1 AS A
 INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_1 AS D ON A.MANDANT_ID = D.MANDANT_ID AND A.ART_ID = D.ART_ID
 INNER JOIN KFL_PRODUCTION_DBP_ETL.GLD_DAT_1 AS C ON A.DAT = C.DAT
 INNER JOIN KFL_PRODUCTION_DBP_ETL.TMP_ART_WUP_TAG_GLD_1 AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B.WUP_ID AND A
    .ART_ID = B.ART_ID AND A.DAT = B.DAT
WHERE A.EK_GLD <> ROUND(CAST(B.EK_GLD * A.MENGE AS NUMERIC), 4)
 AND A.ART_ID > - 1
 AND D.WG_ART_FG = 0
GROUP BY B.MANDANT_ID,
 B.DAT,
 B.WUP_ID,
 B.ART_ID,
 B.EK_GLD,
 B.UMRECHNUNGSKURS;


UPDATE KFL_PRODUCTION_DBP_DATA.ARTBEW_1 SET
 EK_GLD = 0,
 DIFF_EK_GLD_KONZ = 0 FROM KFL_PRODUCTION_DBP_ETL.FEHLENDE_ART_WUP_TAG_GLD_1 AS b
WHERE ARTBEW.MANDANT_ID = b.MANDANT_ID AND ARTBEW.WUP_ID = b.WUP_ID AND ARTBEW.ART_ID = b.ART_ID AND ARTBEW.DAT = b.DAT
