WITH arbeitstag_berechnung AS (
  SELECT 
    EXTRACT(YEAR FROM dat) * 100 + EXTRACT(MONTH FROM dat) AS jahr_monat,
    CASE 
      WHEN MIN(erste) + MIN(zweite) = 2 THEN 2
      WHEN MIN(erste) + MIN(zweite) + MIN(dritte) = 2 THEN 3
      WHEN MIN(erste) + MIN(zweite) + MIN(dritte) + MIN(vierte) = 2 THEN 4
      WHEN MIN(erste) + MIN(zweite) + MIN(dritte) + MIN(vierte) + MIN(fuenfte) = 2 THEN 5
    END AS tag_ausfuerung
  FROM (
    SELECT 
      dat,
      CASE WHEN EXTRACT(DAY FROM dat) = 1 THEN erste ELSE 1 END AS erste,
      CASE WHEN EXTRACT(DAY FROM dat) = 2 THEN zweite ELSE 1 END AS zweite,
      CASE WHEN EXTRACT(DAY FROM dat) = 3 THEN dritte ELSE 1 END AS dritte,
      CASE WHEN EXTRACT(DAY FROM dat) = 4 THEN vierte ELSE 1 END AS vierte,
      CASE WHEN EXTRACT(DAY FROM dat) = 5 THEN fuenfte ELSE 1 END AS fuenfte
    FROM (
      SELECT 
        tag.dat AS dat,    
        CASE WHEN COALESCE(EXTRACT(DAY FROM a.dat), -1) = 1 OR tag.WTAG_ID = 7 THEN 0 ELSE 1 END AS erste,
        CASE WHEN COALESCE(EXTRACT(DAY FROM a.dat), -1) = 2 OR tag.WTAG_ID = 7 THEN 0 ELSE 1 END AS zweite, 
        CASE WHEN COALESCE(EXTRACT(DAY FROM a.dat), -1) = 3 OR tag.WTAG_ID = 7 THEN 0 ELSE 1 END AS dritte,
        CASE WHEN COALESCE(EXTRACT(DAY FROM a.dat), -1) = 4 OR tag.WTAG_ID = 7 THEN 0 ELSE 1 END AS vierte,
        CASE WHEN COALESCE(EXTRACT(DAY FROM a.dat), -1) = 5 OR tag.WTAG_ID = 7 THEN 0 ELSE 1 END AS fuenfte
      FROM `KFL_PRODUCTION_DBP_DATA.TAG_1` AS tag_1
      LEFT JOIN (
        SELECT
          t1.LAND_ID AS land_id,
          t3.dat AS dat,
          SUM(CASE WHEN t4.offen = 0 THEN 1 ELSE 0 END) AS geschlossen
        FROM `KFL_PRODUCTION_DBP_DATA.WUP_1` AS t1_1
        LEFT JOIN `KFL_PRODUCTION_DBP_DATA.REGION_1` AS t2
          ON t1.region_id = t2.region_id
          AND t1.mandant_id = t2.mandant_id
          AND t1.land_id = t2.land_id
        INNER JOIN `KFL_PRODUCTION_DBP_DATA.TAG_1` AS t3
          ON t3.dat BETWEEN t1.dat_von AND t1.dat_bis
        LEFT JOIN `KFL_PRODUCTION_DBP_DATA.WUPCAL_EREIGNIS_ZU_1` AS t4
          ON t4.wup_id = t1.wup_id
          AND t4.nb_id = t1.nb_id
          AND t4.mandant_id = t1.mandant_id
          AND t4.dat = t3.dat
          AND t4.ereignistyp_id <> 2
        WHERE t1.nb_id = 0 
          AND t1.land_id = 'DE'
        GROUP BY 1, 2
      ) AS a
        ON a.dat = tag.dat   
       AND a.geschlossen > 300
      WHERE EXTRACT(DAY FROM tag.dat) BETWEEN 1 AND 5
    )
    WHERE EXTRACT(YEAR FROM dat) * 100 + EXTRACT(MONTH FROM dat) = EXTRACT(YEAR FROM CURRENT_DATE()) * 100 + EXTRACT(MONTH FROM CURRENT_DATE())
  )
  GROUP BY 1
)

