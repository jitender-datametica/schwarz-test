  CURRENT_TIMESTAMP() AS TD_INSERT,
  art.EK_MEP_VOR_FWU AS PREIS_EK_MEP_VOR_FWU
FROM `KFL_PRODUCTION_DBP_DATA.ART_GP_WUP_ZU_PER_1` AS art_1
JOIN arbeitstag_berechnung
  ON TRUE
LEFT JOIN `KFL_PRODUCTION_DBP_DATA.ART_UMSATZ_KMEP_ZU_PER_1` AS ums
  ON art.MANDANT_ID = ums.MANDANT_ID
  AND art.ART_ID = ums.ART_ID
WHERE CURRENT_DATE() BETWEEN art.dat_von AND art.dat_bis
  AND ums.ZEITRAUM_KZ = 'KM'
  AND CAST(FORMAT_DATE('%Y%m', ums.dat_von) AS INT64) >= CAST(FORMAT_DATE('%Y%m', DATE_SUB(CURRENT_DATE(), INTERVAL 1 MONTH)) AS INT64)
  AND CAST(FORMAT_DATE('%Y%m', ums.dat_bis) AS INT64) <= CAST(FORMAT_DATE('%Y%m', DATE_SUB(CURRENT_DATE(), INTERVAL 1 MONTH)) AS INT64)
  AND arbeitstag_berechnung.jahr_monat = EXTRACT(YEAR FROM CURRENT_DATE()) * 100 + EXTRACT(MONTH FROM CURRENT_DATE())
  AND arbeitstag_berechnung.tag_ausfuerung = EXTRACT(DAY FROM CURRENT_DATE());
