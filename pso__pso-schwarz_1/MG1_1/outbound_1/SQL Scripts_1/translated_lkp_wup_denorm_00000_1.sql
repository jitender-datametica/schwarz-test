SELECT D.MANDANT_ID,
 D.WUP_ID,
 D.GL_VERTRIEB_ID,
   S.MA_VORNAME || ' ' || S.MA_NAME AS GL_NAME
FROM KFL_PRODUCTION_DBP_MSI_DATA.WUP_DENORM_1 AS D
 INNER JOIN KFL_PRODUCTION_DBP_DATA.MA_SPR_ZU_1 AS S ON D.GL_VERTRIEB_ID = S.MA_ID
WHERE D.MANDANT_ID IN (3, 7)
 AND D.GL_VERTRIEB_ID > 0
GROUP BY D.MANDANT_ID,
 D.WUP_ID,
 D.GL_VERTRIEB_ID,
 GL_NAME;