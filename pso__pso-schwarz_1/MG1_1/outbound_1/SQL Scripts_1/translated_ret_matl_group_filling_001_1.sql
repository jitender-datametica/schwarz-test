  INNER JOIN KFL_PRODUCTION_DBP_ETL.RET_WGHIER_1 AS OWG0 ON OWG0.NODE_TYPE = '0CLASS_NUM' AND WG0.PARENT_ID = OWG0.ID AND
    WG0.MANDANT_ID = OWG0.MANDANT_ID
  INNER JOIN KFL_PRODUCTION_DBP_ETL.RET_WGHIER_1 AS HWG0 ON HWG0.NODE_TYPE = '0CLASS_NUM' AND OWG0.PARENT_ID = HWG0.ID AND
    OWG0.MANDANT_ID = HWG0.MANDANT_ID
  INNER JOIN KFL_PRODUCTION_DBP_ETL.RET_WGHIER_1 AS ABT0 ON ABT0.NODE_TYPE = '0CLASS_NUM' AND HWG0.PARENT_ID = ABT0.ID AND
    HWG0.MANDANT_ID = ABT0.MANDANT_ID
  INNER JOIN KFL_PRODUCTION_DBP_ETL.RET_WGHIER_1 AS BER0 ON BER0.NODE_TYPE = '0CLASS_NUM' AND ABT0.PARENT_ID = BER0.ID AND
    ABT0.MANDANT_ID = BER0.MANDANT_ID
 WHERE WG0.NODE_TYPE = '0MATL_GROUP');





