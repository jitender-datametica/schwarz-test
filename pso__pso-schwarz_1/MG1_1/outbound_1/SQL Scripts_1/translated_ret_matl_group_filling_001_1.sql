 , BER, ABT_1, HWG, OWG, WG)
(SELECT WG0.MANDANT_ID,
  BER0.NODE AS BEREICH,
  ABT0.NODE AS ABTEILUNG,
  HWG0.NODE AS HAUPTWARENGRUPPE,
  OWG0.NODE AS OBERWARENGRUPPE,
  WG0.NODE AS WARENGRUPPE,
  CAST(SUBSTR(BER0.NAME1, STRPOS(BER0.NAME1, '/B') + 2, 10) AS SMALLINT) AS BER,
  CAST(SUBSTR(ABT0.NAME1, STRPOS(ABT0.NAME1, '/A') + 2, 10) AS SMALLINT) AS ABT_1,
  CAST(SUBSTR(HWG0.NAME1, STRPOS(HWG0.NAME1, '/H') + 2, 10) AS SMALLINT) AS HWG,
  CAST(SUBSTR(OWG0.NAME1, STRPOS(OWG0.NAME1, '/O') + 2, 10) AS SMALLINT) AS OWG,
  CAST(SUBSTR(WG0.NAME1, STRPOS(WG0.NAME1, '/') + 1, 10) AS SMALLINT) AS WG
