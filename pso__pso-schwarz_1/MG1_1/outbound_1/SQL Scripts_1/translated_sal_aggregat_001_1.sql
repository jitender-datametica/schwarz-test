CREATE OR REPLACE TEMPORARY TABLE _DAILY_SAL_UPD AS
SELECT A.MANDANT_ID,
 B.MATCHING_ID,
 COALESCE(B.ANZAHL_MARKT_WOCHEN_KOMBIS_ABVERKAUF_MIT_LISTUNG, 0) AS TM_ANZ_ABVERKAUF,
 COALESCE(B.ANZAHL_MARKT_WOCHEN_KOMBIS_LISTUNG, 0) AS TM_ANZ_LISTUNG,
 SUM(A.ANZ_WUP_ABSATZ) AS SAL_ANZ_ABVERKAUF,
 SUM(A.ANZ_WUP_LISTUNG) AS SAL_ANZ_LISTUNG
FROM KFL_PRODUCTION_DBP_DATA.SAL_INT_1 AS A
 INNER JOIN (SELECT MANDANT_ID,
   ART_MATCHING_ID,
   ART_ID
  FROM KFL_PRODUCTION_DBP_ETL.ART_MATCHING_NIELSEN_PER_1
  GROUP BY MANDANT_ID,
   ART_MATCHING_ID,
   ART_ID) AS c ON A.MANDANT_ID = c.MANDANT_ID AND A.ART_ID = c.ART_ID
 INNER JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.TUPEL_MAT_ETL_1 AS B ON c.MANDANT_ID = B.MANDANT_ID AND c.ART_MATCHING_ID = B.MATCHING_ID
   
WHERE A.KJWO IN (SELECT KJWO
   FROM KFL_PRODUCTION_DBP_DATA.ART_NIELSEN_FAKTEN_KJWO_1
   WHERE MANDANT_ID = 1
   GROUP BY KJWO
   QUALIFY ((RANK() OVER (ORDER BY KJWO IS NULL DESC, KJWO DESC)) * - 1) BETWEEN - 52 AND (- 1))
 AND A.MANDANT_ID = 1
 AND B.A500_KJWO_UPDATE IN (SELECT MAX(A500_KJWO_UPDATE) AS A1581216993
   FROM KFL_PRODUCTION_DBP_ETL_PROCESS.TUPEL_MAT_ETL_1
   WHERE MANDANT_ID = 1)
GROUP BY A.MANDANT_ID,
 B.MATCHING_ID,
 TM_ANZ_ABVERKAUF,
 TM_ANZ_LISTUNG
HAVING TM_ANZ_ABVERKAUF <> SAL_ANZ_ABVERKAUF OR TM_ANZ_LISTUNG <> SAL_ANZ_LISTUNG;


UPDATE KFL_PRODUCTION_DBP_ETL_PROCESS.TUPEL_MAT_ETL_1 SET
 ANZAHL_MARKT_WOCHEN_KOMBIS_ABVERKAUF_MIT_LISTUNG = b.SAL_ANZ_ABVERKAUF,
 ANZAHL_MARKT_WOCHEN_KOMBIS_LISTUNG = b.SAL_ANZ_LISTUNG FROM `_DAILY_SAL_UPD` AS b
WHERE TUPEL_MAT_ETL.MANDANT_ID = b.MANDANT_ID AND TUPEL_MAT_ETL.MATCHING_ID = b.MATCHING_ID AND TUPEL_MAT_ETL.A500_KJWO_UPDATE
   IN (SELECT MAX(A500_KJWO_UPDATE) AS A1581216993
   FROM KFL_PRODUCTION_DBP_ETL_PROCESS.TUPEL_MAT_ETL_1
   WHERE MANDANT_ID = 1);


