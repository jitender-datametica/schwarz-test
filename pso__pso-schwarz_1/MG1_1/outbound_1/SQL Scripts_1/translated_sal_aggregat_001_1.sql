CREATE TEMPORARY TABLE IF NOT EXISTS _STEP1 AS
SELECT ART_ID,
 MANDANT_ID,
  CASE
  WHEN MIN(SM_ID) <> 0
  THEN 1
  ELSE 0
  END AS LISTUNG_MIN_1_SST_DURCHG_V1
FROM (SELECT LSL.ART_ID,
   LSL.SM_ID,
   LSL.MANDANT_ID,
   LSL.LIST_DURCHG_FG,
   LSL.ANZAHL_MARKT_SOLL,
   LS.STERNCHEN_ID
  FROM KFL_PRODUCTION_DBP_DATA.STERNCHEN_LOGIK_1 AS LSL
   INNER JOIN KFL_PRODUCTION_DBP_DATA.L_STERNCHEN_1 AS LS ON LSL.LIST_DURCHG_FG = LS.LIST_DURCHG_FG AND LSL.BEZUGSWEG1_FG
         = LS.BEZUGSWEG1_FG AND LSL.BEZUGSWEG4_FG = LS.BEZUGSWEG4_FG AND LSL.KDIS0_FG = LS.KDIS0_FG AND LSL.KDIS1_FG =
      LS.KDIS1_FG AND LSL.MANDANT_ID = LS.MANDANT_ID
  WHERE LSL.MANDANT_ID = 1) AS a11
WHERE MANDANT_ID = 1
 AND LIST_DURCHG_FG = 1
GROUP BY ART_ID,
 MANDANT_ID;


CREATE TEMPORARY TABLE IF NOT EXISTS _STEP2 AS
SELECT ART_ID,
 MANDANT_ID,
  CASE
  WHEN MAX(TYP_OST_BASIS) <> 0 OR MAX(TYP_OST_GROSS) <> 0 OR MAX(TYP_SUED_OST) <> 0 OR MAX(TYP_SUED_WEST) <> 0 OR MAX(TYP_WEST
      ) <> 0 OR MAX(TYP_NORD) <> 0
  THEN 1
  ELSE 0
  END AS LISTUNG_MIN_1_REGION_DURCHG_V1
FROM (SELECT ART_ID,
   MAX(CASE
     WHEN KREISTYP_GRUPPE_ID = 'O' AND LIST_DURCHG_FG = 1
     THEN 1
     ELSE 0
     END) AS TYP_OST_BASIS,
   MAX(CASE
     WHEN KREISTYP_GRUPPE_ID = 'Q' AND LIST_DURCHG_FG = 1
     THEN 1
     ELSE 0
     END) AS TYP_OST_GROSS,
   MAX(CASE
     WHEN KREISTYP_GRUPPE_ID = 'G' AND LIST_DURCHG_FG = 1
     THEN 1
     ELSE 0
     END) AS TYP_SUED_OST,
   MAX(CASE
     WHEN KREISTYP_GRUPPE_ID = 'M' AND LIST_DURCHG_FG = 1
     THEN 1
     ELSE 0
     END) AS TYP_SUED_WEST,
   MAX(CASE
     WHEN KREISTYP_GRUPPE_ID = 'W' AND LIST_DURCHG_FG = 1
     THEN 1
     ELSE 0
     END) AS TYP_WEST,
   MAX(CASE
     WHEN KREISTYP_GRUPPE_ID = 'N' AND LIST_DURCHG_FG = 1
     THEN 1
     ELSE 0
     END) AS TYP_NORD,
   MANDANT_ID
  FROM KFL_PRODUCTION_DBP_DATA.STERNCHEN_LOGIK_KREIS_1 AS V01
  WHERE MANDANT_ID = 1
  GROUP BY ART_ID,
   MANDANT_ID) AS t1_1
WHERE MANDANT_ID = 1
GROUP BY ART_ID,
 MANDANT_ID;


