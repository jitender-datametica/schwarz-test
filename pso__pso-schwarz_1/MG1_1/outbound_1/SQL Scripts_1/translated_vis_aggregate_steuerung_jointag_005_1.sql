INSERT INTO KFL_PRODUCTION_DBP_ETL.DAT_VJ_VERGLEICH_TMP_1 (JOIN_DAT, DAT, GJ, KJWO, KJMO, MO_KJ, AKT_GJ, AKT_MO, AKT_WO,
 AKT_TAG, WTAG_ID, AKT_GJ_FG, VJ_1_FG, VJ_2_FG, VJ_WT_1_FG, VJ_WT_2_FG)
(SELECT t1.DAT AS JOIN_DAT,
  COALESCE(t2.DAT, dt1.DAT) AS DAT,
  CAST(COALESCE(t2.GJ, dt1.GJ) AS SMALLINT) AS GJ,
  CAST(COALESCE(t2.KJWO, dt1.KJWO) AS INTEGER) AS KJWO,
  CAST(COALESCE(t2.KJMO, dt1.KJMO) AS INTEGER) AS KJMO,
  COALESCE(t2.MO_KJ, dt1.MO_KJ) AS MO_KJ,
  CAST(COALESCE(t2.AKT_GJ, dt1.AKT_GJ) AS SMALLINT) AS AKT_GJ,
  CAST(COALESCE(t2.AKT_MO, dt1.AKT_MO) AS SMALLINT) AS AKT_MO,
  CAST(COALESCE(t2.AKT_WO, dt1.AKT_WO) AS SMALLINT) AS AKT_WO,
  CAST(COALESCE(t2.AKT_TAG, dt1.AKT_TAG) AS SMALLINT) AS AKT_TAG,
  COALESCE(t2.WTAG_ID, dt1.WTAG_ID) AS WTAG_ID,
   CASE
   WHEN t1.GJ = COALESCE(t2.GJ, dt1.GJ)
   THEN 1
   ELSE 0
   END AS AKT_GJ_FG,
   CASE
   WHEN t1.GJ + 1 = COALESCE(t2.GJ, dt1.GJ)
   THEN 1
   ELSE 0
   END AS VJ_1_FG,
   CASE
   WHEN t1.GJ + 2 = COALESCE(t2.GJ, dt1.GJ)
   THEN 1
   ELSE 0
   END AS VJ_2_FG,
  0 AS VJ_WT_1_FG,
  0 AS VJ_WT_2_FG
 FROM (SELECT DAT,
    GJ
   FROM KFL_PRODUCTION_DBP_DATA.TAG_1
   WHERE AKT_GJ IN (0, - 1, - 2)
    OR AKT_GJ = 1 AND SUBSTR(CAST(KJMO AS STRING), 5, 2) IN ('03', '04', '05', '06')) AS t1_1
  FULL JOIN (SELECT DAT,
    GJ,
    KJWO,
    KJMO,
    MO_KJ,
    AKT_GJ,
    AKT_MO,
    AKT_WO,
    AKT_TAG,
    WTAG_ID
   FROM KFL_PRODUCTION_DBP_DATA.TAG_1
   WHERE AKT_GJ IN (0)
    OR AKT_GJ = 1 AND SUBSTR(CAST(KJMO AS STRING), 5, 2) IN ('03', '04', '05', '06')) AS t2 ON EXTRACT(DAY FROM t1.DAT)
    = EXTRACT(DAY FROM t2.DAT) AND EXTRACT(MONTH FROM t1.DAT) = EXTRACT(MONTH FROM t2.DAT)
  INNER JOIN (SELECT DAT,
    GJ,
    KJWO,
    KJMO,
    MO_KJ,
    AKT_GJ,
    AKT_MO,
    AKT_WO,
    AKT_TAG,
    WTAG_ID
   FROM KFL_PRODUCTION_DBP_DATA.TAG_1 AS T3
   WHERE AKT_GJ IN (0)
    AND EXTRACT(DAY FROM DAT) = 28
    AND EXTRACT(MONTH FROM DAT) = 2) AS dt1 ON TRUE);


