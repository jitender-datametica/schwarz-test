INSERT INTO KFL_PRODUCTION_DBP_ETL.WUP_MONAT_TMP_1 (MANDANT_ID, WUP_ID, NB_ID, GJ, KJMO, GJMO, AKT_GJ, AKT_MO, MO_KJ,
 UMSATZ_WRG)
(SELECT W.MANDANT_ID,
  W.WUP_ID,
  W.NB_ID,
  CAST(mo.GJ AS INTEGER) AS GJ,
  mo.KJMO,
  mo.GJMO,
  COALESCE(mo.AKT_GJ, M2.AKT_GJ) AS AKT_GJ,
  COALESCE(mo.AKT_MO, M2.AKT_MO) AS AKT_MO,
  COALESCE(mo.MO_KJ, M2.MO_KJ) AS MO_KJ,
  MA.DEFAULT_WRG AS UMSATZ_WRG
 FROM KFL_PRODUCTION_DBP_DATA.WUP_1 AS W
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MANDANT_1 AS MA ON W.MANDANT_ID = MA.MANDANT_ID
  INNER JOIN (SELECT COALESCE(AKT_GJ_MO.GJ, CAST(FLOOR(periode.KJ_KER_MO_ID / 100) AS INTEGER)) AS GJ,
    COALESCE(AKT_GJ_MO.KJMO, periode.KJ_KER_MO_ID) AS KJMO,
    COALESCE(AKT_GJ_MO.GJMO, periode.KJ_KER_MO_ID) AS GJMO,
    AKT_GJ_MO.AKT_GJ,
    AKT_GJ_MO.AKT_MO,
    AKT_GJ_MO.MO_KJ
   FROM (SELECT KJ_KER_MO_ID
     FROM KFL_PRODUCTION_DBP_DATA.KER_MO_PERIODE_ZU_1
     WHERE KRK_ID = 'DE01'
     GROUP BY KJ_KER_MO_ID) AS periode
    FULL JOIN KFL_PRODUCTION_DBP_DATA.MONAT_1 AS AKT_GJ_MO ON periode.KJ_KER_MO_ID = AKT_GJ_MO.KJMO
   WHERE COALESCE(AKT_GJ_MO.GJ, CAST(FLOOR(periode.KJ_KER_MO_ID / 100) AS INTEGER)) BETWEEN EXTRACT(YEAR FROM
       CURRENT_DATE) - 2 AND (EXTRACT(YEAR FROM CURRENT_DATE))
   GROUP BY GJ,
    KJMO,
    GJMO,
    AKT_GJ_MO.AKT_GJ,
    AKT_GJ_MO.AKT_MO,
    AKT_GJ_MO.MO_KJ) AS mo ON TRUE
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.MONAT_1 AS M2 ON M2.KJMO = mo.KJMO - 1
 WHERE W.NB_ID IN (- 2, - 1, 0, 2, 7)
  AND W.DAT_EROEFFNUNG IS NOT NULL);


