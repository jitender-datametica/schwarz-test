CREATE OR REPLACE TEMPORARY TABLE _PERF5 AS
SELECT A.MANDANT_ID,
 A.ART_ID,
 A.BEWART_ID,
 A.BEWART_DET_ID,
 A.WUP_ID,
 A.NB_ID,
 A.DAT,
 SUM(A.UMSATZ_NETTO) AS UMSATZ_NETTO_,
 SUM(A.LOGKOSTENZUSCHLAG) AS LOGKOSTENZUSCHLAG,
 SUM(A.EK_MEP_EINSTANDSPREIS) AS EK_MEP_EINSTANDSPREIS_,
 SUM(A.MENGE) AS MENGE_,
 SUM(COALESCE(B.BONUS_STK, 0)) AS BONUS_STK_,
 SUM(COALESCE(C.BONUS_STK, 0)) AS BONUS_STK_KW_,
 SUM(COALESCE(D.BONUS_STK, 0)) AS BONUS_STK_WW_,
   SUM(A.UMSATZ_NETTO) - SUM(A.EK_MEP_EINSTANDSPREIS) + SUM(A.MENGE) * SUM(COALESCE(B.BONUS_STK, 0)) AS
 EK_MEP_EINSTANDSPREIS__,
   SUM(A.UMSATZ_NETTO) - SUM(A.EK_MEP_EINSTANDSPREIS) + SUM(A.MENGE) * SUM(COALESCE(C.BONUS_STK, 0)) AS WA_KALK_KW_,
   SUM(A.UMSATZ_NETTO) - SUM(A.EK_MEP_EINSTANDSPREIS) + SUM(A.MENGE) * SUM(COALESCE(D.BONUS_STK, 0)) AS WA_KALK_WW_,
 SUM(COALESCE(B.BONUS_STK_FWU, 0)) AS BONUS_STK_FWU_,
 SUM(COALESCE(C.BONUS_STK_FWU, 0)) AS BONUS_STK_FWU_KW_,
 SUM(COALESCE(D.BONUS_STK_FWU, 0)) AS BONUS_STK_FWU_WW_,
   SUM(A.UMSATZ_NETTO) - SUM(A.EK_MEP_EINSTANDSPREIS_FWU) + SUM(A.MENGE) * SUM(COALESCE(B.BONUS_STK_FWU, 0)) AS
 EK_MEP_EINSTANDSPREIS_FWU__,
   SUM(A.UMSATZ_NETTO) - SUM(A.EK_MEP_EINSTANDSPREIS_FWU) + SUM(A.MENGE) * SUM(COALESCE(C.BONUS_STK_FWU, 0)) AS
 WA_KALK_FWU_KW_,
   SUM(A.UMSATZ_NETTO) - SUM(A.EK_MEP_EINSTANDSPREIS_FWU) + SUM(A.MENGE) * SUM(COALESCE(D.BONUS_STK_FWU, 0)) AS
 WA_KALK_FWU_WW_
FROM `_PERF1` AS A
 LEFT JOIN `_PERF2` AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.ART_ID = B.ART_ID AND A.DAT BETWEEN B.DAT_VON AND B.DAT_BIS
   
 LEFT JOIN `_PERF3` AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.ART_ID = C.ART_ID AND A.DAT BETWEEN C.DAT_VON AND C.DAT_BIS
   
 LEFT JOIN `_PERF4` AS D ON A.MANDANT_ID = D.MANDANT_ID AND A.ART_ID = D.ART_ID AND A.DAT BETWEEN D.DAT_VON AND D.DAT_BIS
   
GROUP BY A.MANDANT_ID,
 A.ART_ID,
 A.BEWART_ID,
 A.BEWART_DET_ID,
 A.WUP_ID,
 A.NB_ID,
 A.DAT;


