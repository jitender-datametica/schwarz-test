CREATE OR REPLACE TEMPORARY TABLE _ZEITRAUM AS
SELECT A.DAT,
 A.KJMO
FROM KFL_PRODUCTION_DBP_DATA.TAG_1 AS A
 INNER JOIN (SELECT KJMO
  FROM KFL_PRODUCTION_DBP_DATA.TAG_1
  WHERE AKT_MO BETWEEN (SELECT *
     FROM KFL_PRODUCTION_DBP_ETL_PROCESS.FWW_GLD_ZEITRAUM_1) AND 0
  GROUP BY KJMO) AS b ON A.KJMO = b.KJMO
WHERE A.DAT < CURRENT_DATE;


CREATE OR REPLACE TEMPORARY TABLE _PERF1 AS
SELECT T1.MANDANT_ID,
 T1.ART_ID,
 T1.BEWART_ID,
 T1.BEWART_DET_ID,
 T1.WUP_ID,
 T1.NB_ID,
 T1.DAT,
 SUM(T1.UMSATZ_NETTO) AS UMSATZ_NETTO,
 SUM(T1.LOGKOSTENZUSCHLAG) AS LOGKOSTENZUSCHLAG,
 SUM(CASE
   WHEN T1.MANDANT_ID = 1 OR T1.MANDANT_ID > 1 AND T2.WG_ID = 969 AND T2.WUG_ID BETWEEN 1 AND 4
   THEN CAST(T1.EK_MEP AS NUMERIC)
   ELSE COALESCE(T1.EK_GLD, 0)
   END) AS EK_MEP_EINSTANDSPREIS,
 SUM(CASE
   WHEN T1.MANDANT_ID = 1 OR T1.MANDANT_ID > 1 AND T2.WG_ID = 969 AND T2.WUG_ID BETWEEN 1 AND 4
   THEN CAST(T1.EK_MEP_VOR_FWU AS NUMERIC)
   ELSE COALESCE(T1.EK_GLD, 0)
   END) AS EK_MEP_EINSTANDSPREIS_FWU,
 SUM(T1.MENGE) AS MENGE
FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_1 AS T1_1
 INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1 AS T2 ON T1.MANDANT_ID = T2.MANDANT_ID AND T1.ART_ID = T2.ART_ID AND
    T2.ARTHIERTYP_ID = 2 AND T2.DAT_BIS = DATE '9999-12-31'
WHERE T1.DAT BETWEEN (SELECT MIN(DAT)
   FROM `_ZEITRAUM`) AND (SELECT MAX(DAT)
   FROM `_ZEITRAUM`)
GROUP BY T1.MANDANT_ID,
 T1.ART_ID,
 T1.BEWART_ID,
 T1.BEWART_DET_ID,
 T1.WUP_ID,
 T1.NB_ID,
 T1.DAT;


