CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.ZEITRAUM_FWW_KMO_GLD_1 AS
SELECT A.DAT,
 A.KJMO,
  CASE
  WHEN MOD(EXTRACT(YEAR FROM A.DAT), 4) = 0 AND EXTRACT(MONTH FROM A.DAT) >= 3
  THEN 366
  WHEN MOD(EXTRACT(YEAR FROM A.DAT), 4) = 1 AND EXTRACT(MONTH FROM A.DAT) <= 2
  THEN 366
  ELSE 365
  END AS DAYS_BACK,
  CASE
  WHEN EXTRACT(MONTH FROM A.DAT) = 2 AND MOD(EXTRACT(YEAR FROM A.DAT), 4) = 0 AND EXTRACT(DAY FROM A.DAT) = 29
  THEN 1
  WHEN EXTRACT(MONTH FROM A.DAT) = 2 AND MOD(EXTRACT(YEAR FROM A.DAT), 4) = 1 AND EXTRACT(DAY FROM A.DAT) = 28
  THEN - 1
  ELSE 0
  END AS SJ
FROM KFL_PRODUCTION_DBP_DATA.TAG_1 AS A
 INNER JOIN (SELECT MIN(KJMO) AS MIN_KJMO,
   MAX(KJMO) AS MAX_KJMO
  FROM (SELECT KJMO
    FROM KFL_PRODUCTION_DBP_DATA.TAG_1
    WHERE AKT_MO BETWEEN (SELECT *
       FROM KFL_PRODUCTION_DBP_ETL_PROCESS.FWW_GLD_ZEITRAUM_1) AND 0
    GROUP BY KJMO) AS x) AS b ON A.KJMO BETWEEN b.MIN_KJMO AND b.MAX_KJMO
WHERE A.DAT < CURRENT_DATE;


MERGE INTO KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ZEK_1 AS A
USING (SELECT A0.MANDANT_ID,
  A0.ART_ID,
  A0.ZEK_ID,
   CASE
   WHEN A0.ZEK_ID <> A0.ZEK_VAT_ID
   THEN 1
   ELSE 0
   END AS EIGENMARKE_FG
 FROM KFL_PRODUCTION_DBP_DATA.ART_1 AS A0
  INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1 AS B ON A0.MANDANT_ID = B.MANDANT_ID AND A0.ART_ID = B.ART_ID AND B.ARTHIERTYP_ID
      = 2 AND B.DAT_BIS = DATE '9999-12-31'
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WG_PER_1 AS C ON A0.MANDANT_ID = C.MANDANT_ID AND B.WG_ID = C.WG_ID AND C.ARTHIERTYP_ID
      = 2 AND C.DAT_BIS = DATE '9999-12-31'
 WHERE A0.DAT_BIS = DATE '9999-12-31'
  AND A0.MANDANT_ID = 1
  AND C.ABT_ID NOT IN (8)
 GROUP BY A0.MANDANT_ID,
  A0.ART_ID,
  A0.ZEK_ID,
  EIGENMARKE_FG) AS b
ON A.MANDANT_ID = b.MANDANT_ID AND A.ART_ID = b.ART_ID
WHEN MATCHED THEN UPDATE SET
 ZEK_ID = b.ZEK_ID,
 EIGENMARKE_FG = b.EIGENMARKE_FG
WHEN NOT MATCHED THEN INSERT (MANDANT_ID, ART_ID, ZEK_ID, EIGENMARKE_FG) VALUES(b.MANDANT_ID, b.ART_ID, b.ZEK_ID, b.EIGENMARKE_FG
 );


MERGE INTO KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ZEK_1 AS A
USING (SELECT A0.MANDANT_ID,
  A0.ART_ID,
  A0.ZEK_ID,
   CASE
   WHEN A0.EIGENMARKE_ID <> ''
   THEN 1
   ELSE 0
   END AS EIGENMARKE_FG
 FROM KFL_PRODUCTION_DBP_DATA.ART_1 AS A0
  INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1 AS B ON A0.MANDANT_ID = B.MANDANT_ID AND A0.ART_ID = B.ART_ID AND B.ARTHIERTYP_ID
      = 2 AND B.DAT_BIS = DATE '9999-12-31'
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WG_PER_1 AS C ON A0.MANDANT_ID = C.MANDANT_ID AND B.WG_ID = C.WG_ID AND C.ARTHIERTYP_ID
      = 2 AND C.DAT_BIS = DATE '9999-12-31'
 WHERE A0.DAT_BIS = DATE '9999-12-31'
  AND A0.MANDANT_ID = 1
  AND C.ABT_ID IN (8)
 GROUP BY A0.MANDANT_ID,
  A0.ART_ID,
  A0.ZEK_ID,
  EIGENMARKE_FG) AS b
ON A.MANDANT_ID = b.MANDANT_ID AND A.ART_ID = b.ART_ID
WHEN MATCHED THEN UPDATE SET
 ZEK_ID = b.ZEK_ID,
 EIGENMARKE_FG = b.EIGENMARKE_FG
WHEN NOT MATCHED THEN INSERT (MANDANT_ID, ART_ID, ZEK_ID, EIGENMARKE_FG) VALUES(b.MANDANT_ID, b.ART_ID, b.ZEK_ID, b.EIGENMARKE_FG
 );


MERGE INTO KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ZEK_1 AS A
USING (SELECT MANDANT_ID,
  ART_ID,
  ZEK_ID,
   CASE
   WHEN EIGENMARKE_ID <> ''
   THEN 1
   ELSE 0
   END AS EIGENMARKE_FG
 FROM KFL_PRODUCTION_DBP_DATA.ART_1 AS A
 WHERE DAT_BIS = DATE '9999-12-31'
  AND MANDANT_ID > 1
 GROUP BY MANDANT_ID,
  ART_ID,
  ZEK_ID,
  EIGENMARKE_FG) AS b
ON A.MANDANT_ID = b.MANDANT_ID AND A.ART_ID = b.ART_ID
WHEN MATCHED THEN UPDATE SET
 ZEK_ID = b.ZEK_ID,
 EIGENMARKE_FG = b.EIGENMARKE_FG
WHEN NOT MATCHED THEN INSERT (MANDANT_ID, ART_ID, ZEK_ID, EIGENMARKE_FG) VALUES(b.MANDANT_ID, b.ART_ID, b.ZEK_ID, b.EIGENMARKE_FG
 );