CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_EKC_PREIS_ABSCHRIFTEN` AS
SELECT A.MANDANT_ID,
 A.ART_ID,
 COALESCE(B.BEWART_ID, 1002) AS BEWART_ID,
 COALESCE(B.BEWART_DET_ID, 100210) AS BEWART_DET_ID,
 A.WUP_ID,
 A.NB_ID,
 A.DAT,
 A.WRG_ID,
 C.ZEK_ID,
 C.EIGENMARKE_FG,
 0 AS WUP_BEREINIGT_FG,
 ROUND(SUM(CAST(A.ABSCHRIFTBETRAG_NETTO AS FLOAT64) * COALESCE(CAST(B.ANTEIL AS FLOAT64), 1.0000)), 2) AS
 PREIS_ABSCHRIFT_NETTO
FROM KFL_PRODUCTION_DBP_DATA.MARKTABSCHRIFTEN_1 AS A
 INNER JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ZEK_1 AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.ART_ID = C.ART_ID
 LEFT JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ARTBEW_FLAGGING_1 AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B.WUP_ID
      AND A.ART_ID = B.ART_ID AND A.DAT = B.DAT
WHERE A.MANDANT_ID = 1
 AND (A.DAT BETWEEN DATE '2022-03-01' AND DATE '2024-02-29' AND A.ABSCHRIFTART_ID IN (5, 7, 26, 30) OR A.DAT BETWEEN
       DATE '2024-03-01' AND DATE '9999-12-31' AND A.ABSCHRIFTART_ID IN (5, 7, 26, 27, 30) AND NOT A.DAT BETWEEN
      DATE '2022-03-01' AND DATE '2024-02-29' OR A.ABSCHRIFTART_ID IN (5, 7, 26) AND NOT A.DAT BETWEEN DATE '2022-03-01'
      AND DATE '2024-02-29' AND NOT A.DAT BETWEEN DATE '2024-03-01' AND DATE '9999-12-31')
GROUP BY A.MANDANT_ID,
 A.ART_ID,
 BEWART_ID,
 BEWART_DET_ID,
 A.WUP_ID,
 A.NB_ID,
 A.DAT,
 A.WRG_ID,
 C.ZEK_ID,
 C.EIGENMARKE_FG,
 WUP_BEREINIGT_FG
UNION ALL
SELECT A.MANDANT_ID,
 A.ART_ID,
 COALESCE(B.BEWART_ID, 1002) AS BEWART_ID,
 COALESCE(B.BEWART_DET_ID, 100210) AS BEWART_DET_ID,
 A.WUP_ID,
 A.NB_ID,
 A.DAT_UMBEW AS DAT,
 A.WRG_ID,
 C.ZEK_ID,
 C.EIGENMARKE_FG,
 0 AS WUP_BEREINIGT_FG,
 ROUND(SUM(CASE
    WHEN A.MANDANT_ID IN (2, 5) AND A.PREIS_AEND_GRUND_ID IN (7, 10, 26) OR A.MANDANT_ID IN (6) AND A.PREIS_AEND_GRUND_ID
          IN (2, 26) OR A.MANDANT_ID IN (3) AND A.PREIS_AEND_GRUND_ID IN (11, 26) OR A.MANDANT_ID IN (4, 7, 8) AND A.PREIS_AEND_GRUND_ID
        IN (7, 26)
    THEN CAST(A.DIFF_WERT_BESTAND_NETTO AS FLOAT64) * COALESCE(CAST(B.ANTEIL AS FLOAT64), 1.0000)
    ELSE 0
    END), 2) AS PREIS_ABSCHRIFT_NETTO
FROM KFL_PRODUCTION_DBP_DATA.ART_UMBEWERTUNG_1 AS A
 INNER JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ZEK_1 AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.ART_ID = C.ART_ID
 LEFT JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.EKC_ARTBEW_FLAGGING_1 AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.WUP_ID = B.WUP_ID
      AND A.ART_ID = B.ART_ID AND A.DAT_UMBEW = B.DAT
WHERE A.MANDANT_ID > 1
GROUP BY A.MANDANT_ID,
 A.ART_ID,
 BEWART_ID,
 BEWART_DET_ID,
 A.WUP_ID,
 A.NB_ID,
 DAT,
 A.WRG_ID,
 C.ZEK_ID,
 C.EIGENMARKE_FG,
 WUP_BEREINIGT_FG;


