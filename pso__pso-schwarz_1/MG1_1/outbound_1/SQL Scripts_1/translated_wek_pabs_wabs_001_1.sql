 BEWART_DET_ID,
 WUP_ID,
 NB_ID,
 DATE_ADD(DAT, INTERVAL 364 DAY) AS DAT,
 WRG_ID,
 ZEK_ID,
 EIGENMARKE_FG,
 WUP_BEREINIGT_FG,
 WERBE_ABSCHRIFT_NETTO AS WERBE_ABSCHRIFT_NETTO_VJ
FROM DEFAULTSCHEMA.`_EKC_WERBE_ABSCHRIFTEN` AS A
WHERE DAT BETWEEN (SELECT DATE_SUB(MIN(DAT), INTERVAL 364 DAY)
   FROM KFL_PRODUCTION_DBP_ETL.ZEITRAUM_FWW_KMO_GLD_1) AND (SELECT DATE_SUB(MAX(DAT), INTERVAL 364 DAY)
   FROM KFL_PRODUCTION_DBP_ETL.ZEITRAUM_FWW_KMO_GLD_1);


CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_WABS_VJ_KM` AS
SELECT MANDANT_ID,
 ART_ID,
 BEWART_ID,
 BEWART_DET_ID,
 WUP_ID,
 NB_ID,
 DAT,
 WRG_ID,
 ZEK_ID,
 EIGENMARKE_FG,
 WUP_BEREINIGT_FG,
 SUM(WERBE_ABSCHRIFT_NETTO) AS WERBE_ABSCHRIFT_NETTO_VJ_KM
FROM (SELECT A.MANDANT_ID,
    A.ART_ID,
    A.BEWART_ID,
    A.BEWART_DET_ID,
    A.WUP_ID,
    A.NB_ID,
    DATE_ADD(A.DAT, INTERVAL CAST(ROUND(X.DAYS_BACK) AS INTEGER) DAY) AS DAT,
    A.WRG_ID,
    A.ZEK_ID,
    A.EIGENMARKE_FG,
    A.WUP_BEREINIGT_FG,
    A.WERBE_ABSCHRIFT_NETTO
   FROM DEFAULTSCHEMA.`_EKC_WERBE_ABSCHRIFTEN` AS A
    INNER JOIN KFL_PRODUCTION_DBP_ETL.ZEITRAUM_FWW_KMO_GLD_1 AS X ON A.DAT = DATE_SUB(X.DAT, INTERVAL CAST(ROUND(X.DAYS_BACK) AS INTEGER)
      DAY)
   WHERE DATE_ADD(A.DAT, INTERVAL CAST(ROUND(X.DAYS_BACK) AS INTEGER) DAY) NOT IN (SELECT DAT
      FROM KFL_PRODUCTION_DBP_ETL.ZEITRAUM_FWW_KMO_GLD_1
      WHERE SJ = 1)
   UNION ALL
   SELECT A.MANDANT_ID,
    A.ART_ID,
    A.BEWART_ID,
    A.BEWART_DET_ID,
    A.WUP_ID,
    A.NB_ID,
    DATE_SUB(DATE_ADD(A.DAT, INTERVAL CAST(ROUND(X.DAYS_BACK) AS INTEGER) DAY), INTERVAL 1 DAY) AS DAT,
    A.WRG_ID,
    A.ZEK_ID,
    A.EIGENMARKE_FG,
    A.WUP_BEREINIGT_FG,
    A.WERBE_ABSCHRIFT_NETTO
   FROM DEFAULTSCHEMA.`_EKC_WERBE_ABSCHRIFTEN` AS A
    INNER JOIN KFL_PRODUCTION_DBP_ETL.ZEITRAUM_FWW_KMO_GLD_1 AS X ON A.DAT = DATE_ADD(DATE_SUB(X.DAT, INTERVAL CAST(ROUND(X.DAYS_BACK) AS INTEGER)
        DAY), INTERVAL 1 DAY) AND X.SJ = - 1) AS x
GROUP BY MANDANT_ID,
 ART_ID,
 BEWART_ID,
 BEWART_DET_ID,
 WUP_ID,
 NB_ID,
 DAT,
 WRG_ID,
 ZEK_ID,
 EIGENMARKE_FG,
 WUP_BEREINIGT_FG;


MERGE INTO DEFAULTSCHEMA.`_WABS` AS A
USING DEFAULTSCHEMA.`_WABS_VJ` AS b
ON A.MANDANT_ID = b.MANDANT_ID AND A.WUP_ID = b.WUP_ID AND A.NB_ID = b.NB_ID AND A.ART_ID = b.ART_ID AND A.BEWART_ID = b
     .BEWART_ID AND A.BEWART_DET_ID = b.BEWART_DET_ID AND A.DAT = b.DAT AND A.WRG_ID = b.WRG_ID
WHEN MATCHED THEN UPDATE SET
 WERBE_ABSCHRIFT_NETTO_VJ = CAST(b.WERBE_ABSCHRIFT_NETTO_VJ AS NUMERIC)
WHEN NOT MATCHED THEN INSERT VALUES(b.MANDANT_ID, b.ART_ID, b.BEWART_ID, b.BEWART_DET_ID, b.WUP_ID, b.NB_ID, b.DAT, b.WRG_ID
 , b.ZEK_ID, b.EIGENMARKE_FG, 0, 0, CAST(b.WERBE_ABSCHRIFT_NETTO_VJ AS NUMERIC), 0);


MERGE INTO DEFAULTSCHEMA.`_WABS` AS A
USING DEFAULTSCHEMA.`_WABS_VJ_KM` AS b
ON A.MANDANT_ID = b.MANDANT_ID AND A.WUP_ID = b.WUP_ID AND A.NB_ID = b.NB_ID AND A.ART_ID = b.ART_ID AND A.BEWART_ID = b
     .BEWART_ID AND A.BEWART_DET_ID = b.BEWART_DET_ID AND A.DAT = b.DAT AND A.WRG_ID = b.WRG_ID
WHEN MATCHED THEN UPDATE SET
 WERBE_ABSCHRIFT_NETTO_VJ_KM = CAST(b.WERBE_ABSCHRIFT_NETTO_VJ_KM AS NUMERIC)
WHEN NOT MATCHED THEN INSERT VALUES(b.MANDANT_ID, b.ART_ID, b.BEWART_ID, b.BEWART_DET_ID, b.WUP_ID, b.NB_ID, b.DAT, b.WRG_ID
 , b.ZEK_ID, b.EIGENMARKE_FG, 0, 0, 0, CAST(b.WERBE_ABSCHRIFT_NETTO_VJ_KM AS NUMERIC));


