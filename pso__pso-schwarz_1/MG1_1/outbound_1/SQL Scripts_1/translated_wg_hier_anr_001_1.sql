INSERT INTO KFL_PRODUCTION_DBP_ETL.WG_PER_TMP_1 (MANDANT_ID, WG_ID, ARTHIERTYP_ID, DAT_VON, LEAD_MWST_ID, ABT_ID, DAT_BIS
 , OWG_ID)
(SELECT A.MANDANT_ID,
  A.WG_ID,
  2 AS ARTHIERTYP_ID,
  A.DAT_VON,
  COALESCE(l.LEAD_MWST_ID, 0) AS LEAD_MWST_ID,
  A.ABT_ID,
  A.DAT_BIS,
  A.OWG_ID
 FROM KFL_PRODUCTION_DBP_ETL.WG_PER_INIT_1 AS A
  LEFT JOIN (SELECT A0.MANDANT_ID,
    W.WG_ID,
    A0.MWST_ID AS LEAD_MWST_ID,
    COUNT(*) AS ZAEHLER_MWST,
    RANK() OVER (PARTITION BY A0.MANDANT_ID, W.WG_ID ORDER BY COUNT(*) IS NULL DESC, COUNT(*) DESC, A0.MWST_ID IS NULL
       DESC, A0.MWST_ID DESC) AS RANKING
   FROM KFL_PRODUCTION_DBP_DATA.ART_1 AS A0
    INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_1 AS W ON A0.MANDANT_ID = W.MANDANT_ID AND A0.ART_ID = W.ART_ID AND
       CURRENT_DATE BETWEEN W.DAT_VON AND W.DAT_BIS AND W.ARTHIERTYP_ID = 2
   GROUP BY A0.MANDANT_ID,
    W.WG_ID,
    LEAD_MWST_ID
   QUALIFY (RANK() OVER (PARTITION BY A0.MANDANT_ID, W.WG_ID ORDER BY COUNT(*) IS NULL DESC, COUNT(*) DESC, A0.MWST_ID
         IS NULL DESC, A0.MWST_ID DESC)) = 1) AS l ON A.MANDANT_ID = l.MANDANT_ID AND A.WG_ID = l.WG_ID);


