DELETE FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_1
WHERE (WUP_ID, MANDANT_ID, NB_ID, DAT) IN (SELECT (WC.WUP_ID, WC.MANDANT_ID, WC.NB_ID, WC.DAT)
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_1 AS WC
   INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_1 AS W ON WC.WUP_ID = W.WUP_ID AND WC.MANDANT_ID = W.MANDANT_ID AND WC.NB_ID = W
     .NB_ID
  WHERE WC.DAT < W.DAT_VON
   OR WC.DAT > COALESCE(W.DAT_BIS, PARSE_DATE('%F', '9999-12-31')));


INSERT INTO KFL_PRODUCTION_DBP_DATA.WUPCAL_1 (MANDANT_ID, WUP_ID, NB_ID, DAT, OFFEN, WERBEWOCHE,
 DATENLIEFERUNG_ARTBEW_WG_SUM, DATENLIEFERUNG_BONANZAHL, DATENLIEFERUNG_MISVIER, DATENLIEFERUNG_ARTBEW,
 DATENLIEFERUNG_QBM_STATUS, BONANZAHL, BONANZAHL_MISVIER, TD_UPDATE, TD_INSERT)
(SELECT W.MANDANT_ID,
  W.WUP_ID,
  W.NB_ID,
  T.DAT,
  1 AS OFFEN,
  0 AS WERBEWOCHE,
  0 AS DATENLIEFERUNG_ARTBEW_WG_SUM,
  0 AS DATENLIEFERUNG_BONANZAHL,
  0 AS DATENLIEFERUNG_MISVIER,
  0 AS DATENLIEFERUNG_ARTBEW,
  0 AS DATENLIEFERUNG_QBM_STATUS,
  0 AS BONANZAHL,
  0 AS BONANZAHL_MISVIER,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP()
 FROM KFL_PRODUCTION_DBP_DATA.WUP_1 AS W
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_1 AS T ON TRUE
 WHERE W.DAT_VON <= T.DAT
  AND CASE
    WHEN W.DAT_BIS = PARSE_DATE('%F', '9999-12-31')
    THEN CURRENT_DATE
    ELSE W.DAT_BIS
    END >= T.DAT
  AND T.DAT >= PARSE_DATE('%F', '1998-01-01')
  AND T.DAT <= CURRENT_DATE
  AND (W.MANDANT_ID, W.WUP_ID, W.NB_ID, T.DAT) NOT IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
    FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_1));