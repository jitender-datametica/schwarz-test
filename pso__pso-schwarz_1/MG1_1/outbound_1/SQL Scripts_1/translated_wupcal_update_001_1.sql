UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_1 SET
 OFFEN = t0.OFFEN,
 TD_UPDATE = CURRENT_TIMESTAMP() FROM (SELECT MANDANT_ID,
   WUP_ID,
   NB_ID,
   DAT,
   MAX(OFFEN) AS OFFEN
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_EREIGNIS_ZU_1 AS WEZ
  GROUP BY DAT,
   WUP_ID,
   NB_ID,
   MANDANT_ID) AS t0
WHERE t0.MANDANT_ID = WUPCAL.MANDANT_ID AND t0.WUP_ID = WUPCAL.WUP_ID AND t0.NB_ID = WUPCAL.NB_ID AND t0.DAT = WUPCAL.DAT
    AND t0.DAT = CURRENT_DATE;


