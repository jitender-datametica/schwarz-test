CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_ETL.MV_SAL_LISTUNG_MARKT_KW_1 (MANDANT_ID, WG_ID, ART_ID, WUP_ID, NB_ID,
KREISTYP_GRUPPE_ID, KJWO, ABSATZ, ABSATZ_SA, ABSATZ_AF, ANZ_WO_MIT_ABSATZ, ANZ_WO_MIT_ABSATZ_SA, ANZ_WO_MIT_ABSATZ_AF)
AS SELECT V01.MANDANT_ID,
 V01.WG_ID,
 V01.ART_ID,
 V01.WUP_ID,
 V01.NB_ID,
 V04.KREISTYP_GRUPPE_ID,
 V01.KJWO,
 IFNULL(SUM(V01.MENGE), 0) AS ABSATZ,
 IFNULL(SUM(CASE
    WHEN V01.BEWART_ID = 1002
    THEN V01.MENGE
    ELSE NULL
    END), 0) AS ABSATZ_SA,
 IFNULL(SUM(CASE
    WHEN V01.BEWART_ID = 1001
    THEN V01.MENGE
    ELSE NULL
    END), 0) AS ABSATZ_AF,
 IFNULL(CASE
   WHEN IFNULL(SUM(V01.MENGE), 0) > 0
   THEN COUNT(DISTINCT V01.KJWO)
   ELSE NULL
   END, 0) AS ANZAHL_WOCHEN_MIT_ABSATZ,
 IFNULL(CASE
   WHEN IFNULL(SUM(CASE
        WHEN V01.BEWART_ID = 1002
        THEN V01.MENGE
        ELSE NULL
        END), 0) > 0 AND IFNULL(SUM(CASE
       WHEN V01.BEWART_ID = 1002
       THEN V01.MENGE
       ELSE NULL
       END), 0) IS NOT NULL
   THEN COUNT(DISTINCT CASE
     WHEN V01.BEWART_ID = 1002
     THEN V01.KJWO
     ELSE NULL
     END)
   ELSE NULL
   END, 0) AS ANZAHL_WOCHEN_MIT_ABSATZ_SA,
 IFNULL(CASE
   WHEN IFNULL(SUM(CASE
        WHEN V01.BEWART_ID = 1001
        THEN V01.MENGE
        ELSE NULL
        END), 0) > 0 AND IFNULL(SUM(CASE
       WHEN V01.BEWART_ID = 1001
       THEN V01.MENGE
       ELSE NULL
       END), 0) IS NOT NULL
   THEN COUNT(DISTINCT CASE
     WHEN V01.BEWART_ID = 1001
     THEN V01.KJWO
     ELSE NULL
     END)
   ELSE NULL
   END, 0) AS ANZAHL_WOCHEN_MIT_ABSATZ_AF
FROM KFL_PRODUCTION_DBP_ETL.SAL_ARTBEW_WG_ART_WO_SUM_1 AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_ART_WG_ZU_PER_1 AS V03 ON V01.ART_ID = V03.ART_ID AND V01.MANDANT_ID = V03.MANDANT_ID
   
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_WUP_1 AS V04 ON V01.WUP_ID = V04.WUP_ID AND V01.NB_ID = V04.NB_ID AND V01.MANDANT_ID
    = V04.MANDANT_ID
WHERE V01.MANDANT_ID = 1
 AND V03.ARTHIERTYP_ID = 2
 AND V03.DAT_BIS = PARSE_DATE('%F', '9999-12-31')
GROUP BY V01.MANDANT_ID,
 V01.WG_ID,
 V01.ART_ID,
 V01.WUP_ID,
 V01.NB_ID,
 V04.KREISTYP_GRUPPE_ID,
 V01.KJWO;
