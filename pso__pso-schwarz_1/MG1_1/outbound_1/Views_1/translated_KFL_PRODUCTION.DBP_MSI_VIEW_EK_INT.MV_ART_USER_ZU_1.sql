CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_ART_USER_ZU_1 (MANDANT_ID, USER_ID, ART_ID) AS (SELECT U_R.MANDANT_ID
  ,
  U_R.USER_ID,
  a_vhd.ART_ID
 FROM KFL_PRODUCTION_DBP_SECURITY.USER_ROLLE_EK_INT_ZU_1 AS U_R
  INNER JOIN (SELECT A.MANDANT_ID,
    A.ART_ID,
    A.ZEK_ID,
    EKL.WBL_ID,
    GF.GF_ID
   FROM KFL_PRODUCTION_DBP_VIEW.V_ART_1 AS A
    LEFT JOIN KFL_PRODUCTION_DBP_VIEW.V_ZEK_1 AS EKL ON A.MANDANT_ID = EKL.MANDANT_ID AND A.ZEK_ID = EKL.ZEK_ID
    LEFT JOIN KFL_PRODUCTION_DBP_VIEW.V_WBL_1 AS GF_1 ON EKL.MANDANT_ID = GF.MANDANT_ID AND EKL.WBL_ID = GF.WBL_ID) AS a_vhd
  ON U_R.MANDANT_ID = a_vhd.MANDANT_ID AND COALESCE(U_R.ZEK_ID, a_vhd.ZEK_ID) = a_vhd.ZEK_ID AND COALESCE(U_R.WBL_ID,
      a_vhd.WBL_ID) = a_vhd.WBL_ID AND COALESCE(U_R.GF_ID, a_vhd.GF_ID) = a_vhd.GF_ID
 WHERE U_R.ROLLE_ID IN (1, 2, 3)
 UNION DISTINCT
 SELECT U_R.MANDANT_ID,
  U_R.USER_ID,
  a_vat.ART_ID
 FROM KFL_PRODUCTION_DBP_SECURITY.USER_ROLLE_EK_INT_ZU_1 AS U_R
  INNER JOIN (SELECT A.MANDANT_ID,
    A.ART_ID,
    A.ZEK_VAT_ID AS ZEK_ID,
    EKL.WBL_ID,
    GF.GF_ID
   FROM KFL_PRODUCTION_DBP_VIEW.V_ART_1 AS A
    LEFT JOIN KFL_PRODUCTION_DBP_VIEW.V_ZEK_1 AS EKL ON A.MANDANT_ID = EKL.MANDANT_ID AND A.ZEK_VAT_ID = EKL.ZEK_ID
    LEFT JOIN KFL_PRODUCTION_DBP_VIEW.V_WBL_1 AS GF_1 ON EKL.MANDANT_ID = GF.MANDANT_ID AND EKL.WBL_ID = GF.WBL_ID) AS a_vat
  ON U_R.MANDANT_ID = a_vat.MANDANT_ID AND COALESCE(U_R.ZEK_ID, a_vat.ZEK_ID) = a_vat.ZEK_ID AND COALESCE(U_R.WBL_ID,
      a_vat.WBL_ID) = a_vat.WBL_ID AND COALESCE(U_R.GF_ID, a_vat.GF_ID) = a_vat.GF_ID
 --ON (u_r.mandant_id = a_vat.mandant_id AND (u_r.zek_id = a_vat.zek_id OR u_r.wbl_id = a_vat.wbl_id OR u_r.gf_id = a_vat.gf_id))
 WHERE U_R.ROLLE_ID IN (1, 2, 3))
UNION DISTINCT
