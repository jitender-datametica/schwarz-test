CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_HWG_SPR_ZU_1 (HWG_ID, ARTHIERTYP_ID, HWG_BEZ, HWG_BEZ_DE,
HWG_BEZ_CZ, HWG_BEZ_SK, HWG_BEZ_HR, HWG_BEZ_PL, HWG_BEZ_RO, HWG_BEZ_BG) AS SELECT V01.HWG_ID,
 V01.ARTHIERTYP_ID,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.HWG_BEZ
    ELSE NULL
    END), 'N/A') AS HWG_BEZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.HWG_BEZ
    ELSE NULL
    END), 'N/A') AS HWG_BEZ_DE,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 124
    THEN V02.HWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.HWG_BEZ
     ELSE NULL
     END), 'N/A')) AS HWG_BEZ_CZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 108
    THEN V02.HWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.HWG_BEZ
     ELSE NULL
     END), 'N/A')) AS HWG_BEZ_SK,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 65
    THEN V02.HWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.HWG_BEZ
     ELSE NULL
     END), 'N/A')) AS HWG_BEZ_HR,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 90
    THEN V02.HWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.HWG_BEZ
     ELSE NULL
     END), 'N/A')) AS HWG_BEZ_PL,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 95
    THEN V02.HWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.HWG_BEZ
     ELSE NULL
     END), 'N/A')) AS HWG_BEZ_RO,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 18
    THEN V02.HWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.HWG_BEZ
     ELSE NULL
     END), 'N/A')) AS HWG_BEZ_BG
FROM KFL_PRODUCTION_DBP_VIEW.V_HWG_PER_1 AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_HWG_SPR_ZU_1 AS V02 ON V01.MANDANT_ID = V02.MANDANT_ID AND V01.HWG_ID = V02.HWG_ID
WHERE CURRENT_DATE BETWEEN V01.DAT_VON AND V01.DAT_BIS
GROUP BY V01.HWG_ID,
 V01.ARTHIERTYP_ID;