CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_OWG_SPR_ZU_1 (OWG_ID, MANDANT_ID, OWG_BEZ, OWG_BEZ_DE,
OWG_BEZ_CZ, OWG_BEZ_SK, OWG_BEZ_HR, OWG_BEZ_PL, OWG_BEZ_RO, OWG_BEZ_BG) AS SELECT V01.OWG_ID,
 V01.MANDANT_ID,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.OWG_BEZ
    ELSE NULL
    END), 'N/A') AS OWG_BEZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.OWG_BEZ
    ELSE NULL
    END), 'N/A') AS OWG_BEZ_DE,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 124
    THEN V02.OWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.OWG_BEZ
     ELSE NULL
     END), 'N/A')) AS OWG_BEZ_CZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 108
    THEN V02.OWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.OWG_BEZ
     ELSE NULL
     END), 'N/A')) AS OWG_BEZ_SK,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 65
    THEN V02.OWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.OWG_BEZ
     ELSE NULL
     END), 'N/A')) AS OWG_BEZ_HR,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 90
    THEN V02.OWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.OWG_BEZ
     ELSE NULL
     END), 'N/A')) AS OWG_BEZ_PL,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 95
    THEN V02.OWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.OWG_BEZ
     ELSE NULL
     END), 'N/A')) AS OWG_BEZ_RO,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 18
    THEN V02.OWG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.OWG_BEZ
     ELSE NULL
     END), 'N/A')) AS OWG_BEZ_BG
FROM KFL_PRODUCTION_DBP_VIEW.V_OWG_PER_1 AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_OWG_SPR_ZU_1 AS V02 ON V01.OWG_ID = V02.OWG_ID
WHERE CURRENT_DATE BETWEEN V01.DAT_VON AND V01.DAT_BIS
GROUP BY V01.OWG_ID,
 V01.MANDANT_ID;