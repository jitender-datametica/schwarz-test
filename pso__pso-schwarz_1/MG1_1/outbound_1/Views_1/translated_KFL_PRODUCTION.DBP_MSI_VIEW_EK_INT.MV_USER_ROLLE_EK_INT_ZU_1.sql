CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_USER_ROLLE_EK_INT_ZU_1 (MANDANT_ID, USER_ID, ROLLE_ID,
ROLLE_BEZ, ZEK_ID, WBL_ID, GF_ID) AS SELECT MANDANT_ID,
--Anpassung user_id in Kleinschreibung im Zuge automat. Useranlage / sschuecke 30.10.2023
 LOWER(USER_ID) --,user_id
 AS USER_ID,
 ROLLE_ID,
 ROLLE_BEZ,
 ZEK_ID,
 WBL_ID,
 GF_ID
FROM KFL_PRODUCTION_DBP_SECURITY.USER_ROLLE_EK_INT_ZU_1
UNION DISTINCT
SELECT DISTINCT MANDANT_ID,
 'Superuser' AS USER_ID,
 ROLLE_ID,
 ROLLE_BEZ,
 ZEK_ID,
 WBL_ID,
 GF_ID
FROM KFL_PRODUCTION_DBP_SECURITY.USER_ROLLE_EK_INT_ZU_1
WHERE ROLLE_ID = 4;