CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_WG_SPR_ZU_1 (MANDANT_ID, ARTHIERTYP_ID, WG_ID, WG_GESPERRT,
WG_BEZ, WG_BEZ_DE, WG_BEZ_CZ, WG_BEZ_SK, WG_BEZ_HR, WG_BEZ_PL, WG_BEZ_RO, WG_BEZ_BG) AS SELECT V01.MANDANT_ID,
 V01.ARTHIERTYP_ID,
 V01.WG_ID,
 MAX(COALESCE(CASE
    WHEN INSTR(UPPER(CASE
        WHEN V01.MANDANT_ID = 1
        THEN 'Gesperrt'
        WHEN V01.MANDANT_ID = 2
        THEN 'BLOKOV\u00c1NO'
        WHEN V01.MANDANT_ID = 3
        THEN 'zablokowane'
        WHEN V01.MANDANT_ID = 5
        THEN 'Blokované'
        WHEN V01.MANDANT_ID = 6
        THEN 'ZATVORENO'
        WHEN V01.MANDANT_ID = 7
        THEN '\u00ceNCHIS'
        WHEN V01.MANDANT_ID = 8
        THEN 'Блокирана'
        ELSE NULL
        END), V02.WG_BEZ) = 1
    THEN 1
    ELSE NULL
    END, 0)) AS WG_GESPERRT,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.WG_BEZ
    ELSE NULL
    END), 'N/A') AS WG_BEZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 22
    THEN V02.WG_BEZ
    ELSE NULL
    END), 'N/A') AS WG_BEZ_DE,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 124
    THEN V02.WG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WG_BEZ
     ELSE NULL
     END), 'N/A')) AS WG_BEZ_CZ,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 108
    THEN V02.WG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WG_BEZ
     ELSE NULL
     END), 'N/A')) AS WG_BEZ_SK,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 65
    THEN V02.WG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WG_BEZ
     ELSE NULL
     END), 'N/A')) AS WG_BEZ_HR,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 90
    THEN V02.WG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WG_BEZ
     ELSE NULL
     END), 'N/A')) AS WG_BEZ_PL,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 95
    THEN V02.WG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WG_BEZ
     ELSE NULL
     END), 'N/A')) AS WG_BEZ_RO,
 COALESCE(MAX(CASE
    WHEN V02.SPR_ID = 18
    THEN V02.WG_BEZ
    ELSE NULL
    END), COALESCE(MAX(CASE
     WHEN V02.SPR_ID = 22
     THEN V02.WG_BEZ
     ELSE NULL
     END), 'N/A')) AS WG_BEZ_BG
FROM KFL_PRODUCTION_DBP_VIEW.V_WG_PER_1 AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_WG_SPR_ZU_1 AS V02 ON V01.WG_ID = V02.WG_ID
WHERE V01.ARTHIERTYP_ID = 2
 AND V02.ARTHIERTYP_ID = 2
GROUP BY V01.MANDANT_ID,
 V01.ARTHIERTYP_ID,
 V01.WG_ID;