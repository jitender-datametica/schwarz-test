create or replace view TMP_OPEN_STORE_VALIDATION1_1(
	CAL_DT,
	DAY_OF_WEEK,
	INT_ORG_SID,
	STORE_OPEN_FG,
	DWH_VALID_FROM_TMSP,
	DWH_VALID_TO_TMSP,
	DWH_VALID_FG,
	CURR_INT_ORG_NR,
	INIT_INT_ORG_NR,
	INT_ORG_NAME,
	INT_ORG_STATUS_CD,
	INT_ORG_STATUS_DESCR,
	OPEN_DT,
	PLANNED_OPEN_DT,
	CLOSE_DT,
	ISO_COUNTRY_CD,
	COUNTRY_NAME,
	CITY_NAME,
	DISTRICT_NAME,
	ZIP,
	STREET_NAME,
	HOUSE_NR,
	LON,
	LAT,
	PO_BOX_NR,
	PHONE_NR,
	FAX_NR,
	EMAIL_ADDR_TXT,
	BUS_DT,
	INT_ORG_TYPE_CD,
	COUNTRY_ORG_CD,
	TURNOVER_NET_VAL,
	TURNOVER_BYTD_NET_VAL,
	TURNOVER_PY_NET_VAL,
	TURNOVER_PY_BYTD_NET_VAL,
	TURNOVER_PY_SWDAY_NET_VAL,
	TURNOVER_PY_SWDAY_BYTD_NET_VAL,
	SALES_CNT,
	SALES_QTY,
	RETURN_CNT,
	RETURN_QTY,
	EOD_TURNOVER_NET_VAL,
	BOOKED_TURNOVER_NET_VAL,
	TURNOVER_GROSS_VAL,
	TURNOVER_BYTD_GROSS_VAL,
	TURNOVER_PY_GROSS_VAL,
	TURNOVER_PY_BYTD_GROSS_VAL,
	TURNOVER_PY_SWDAY_GROSS_VAL,
	TURNOVER_PY_SWDAY_BYTD_GROSS_VAL,
	EOD_TURNOVER_GROSS_VAL,
	CURR_CD,
	RECEIPT_CNT,
	RECEIPT_BYTD_CNT,
	RECEIPT_PY_CNT,
	RECEIPT_PY_BYTD_CNT,
	RECEIPT_PY_SWDAY_CNT,
	RECEIPT_PY_SWDAY_BYTD_CNT,
	CASH_REGISTER_RECEIPT_CNT,
	EOD_RECEIPT_CNT,
	BOOKED_RECEIPT_CNT,
	FAILED_STORE_CLOSED_DELIVERED_REVENUE,
	TOTAL
) as   
SELECT dt.cal_dt,
       dt.day_of_week,
       store.int_org_sid,
       COALESCE(open_store.open_fg, FALSE) AS store_open_fg,
       store.dwh_valid_from_tmsp,
       store.dwh_valid_to_tmsp,
       store.dwh_valid_fg,
       store.curr_int_org_nr,
       store.init_int_org_nr,
       store.int_org_name,
       store.int_org_status_cd,
       store.int_org_status_descr,
       store.open_dt,
       store.planned_open_dt,
       store.close_dt,
       store.iso_country_cd,
       store.country_name,
       store.city_name,
       store.district_name,
       store.zip,
       store.street_name,
       store.house_nr,
       store.lon,
       store.lat,
       store.po_box_nr,
       store.phone_nr,
       store.fax_nr,
       store.email_addr_txt,
       rev.bus_dt,
       rev.int_org_type_cd,
       rev.country_org_cd,
       rev.turnover_net_val,
       rev.turnover_bytd_net_val,
       rev.turnover_py_net_val,
       rev.turnover_py_bytd_net_val,
       rev.turnover_py_swday_net_val,
       rev.turnover_py_swday_bytd_net_val,
       rev.sales_cnt,
       rev.sales_qty,
       rev.return_cnt,
       rev.return_qty,
       rev.eod_turnover_net_val,
       rev.booked_turnover_net_val,
       rev.turnover_gross_val,
       rev.turnover_bytd_gross_val,
       rev.turnover_py_gross_val,
       rev.turnover_py_bytd_gross_val,
       rev.turnover_py_swday_gross_val,
       rev.turnover_py_swday_bytd_gross_val,
       rev.eod_turnover_gross_val,
       rev.curr_cd,
       rev.receipt_cnt,
       rev.receipt_bytd_cnt,
       rev.receipt_py_cnt,
       rev.receipt_py_bytd_cnt,
       rev.receipt_py_swday_cnt,
       rev.receipt_py_swday_bytd_cnt,
       rev.cash_register_receipt_cnt,
       rev.eod_receipt_cnt,
       rev.booked_receipt_cnt,
       (CASE WHEN COALESCE(rev.turnover_net_val, 0) > 0
              AND store_open_fg = FALSE 
             THEN 1
			 ELSE 0
		END) AS failed_store_closed_delivered_revenue, --if store is closed and delivers revenue
       1 AS total

  FROM core_dim.t_dim_internal_organization_1 AS store
  
 INNER JOIN core_dim.t_dim_calendar_date_1 AS dt 
    ON dt.cal_dt < CURRENT_DATE()
   AND dt.bus_year_offset >= -2 --cross join to get all dates for last 2 business years
   
  LEFT OUTER JOIN core_dim.t_fact_retail_by_store_day_1 AS rev
    ON store.int_org_sid = rev.int_org_sid
   AND rev.bus_dt = dt.cal_dt --get revenue
   
  LEFT OUTER JOIN EVAL.TMP_OPEN_STORE1_1 AS open_store
    ON dt.cal_dt = open_store.cal_dt 
   AND store.int_org_sid = open_store.int_org_sid

 WHERE dt.cal_dt BETWEEN store.dwh_valid_from_tmsp AND store.dwh_valid_to_tmsp
   AND store_open_fg = FALSE
   AND store.int_org_type_cd = 'STORE';