INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        INT_ORG_KEY_TYPE_CD,
        INT_ORG_NK,
        INT_ORG_REAL_ESTATE_USG_TYPE_CD,
        REAL_ESTATE_KEY_TYPE_CD,
        REAL_ESTATE_NK,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        'STORE' AS INT_ORG_KEY_TYPE_CD,
        LOWER(SUBSTR(IGL_NUMBER, 1, 2)) ||'|'||TO_NUMBER(SUBSTR(IGL_NUMBER,3,5)) AS INT_ORG_NK,
        'USED_BY' AS INT_ORG_REAL_ESTATE_USG_TYPE_CD,
        'RE_1' AS REAL_ESTATE_KEY_TYPE_CD,
         LOWER(SUBSTR(IGL_NUMBER, 1, 2)) ||'|'||TO_NUMBER(SUBSTR(IGL_NUMBER,3,5))  AS REAL_ESTATE_NK,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
                CASE WHEN IGL_EXPECTEDOPENINGDATE > CURRENT_DATE OR IGL_NEODATE >= CURRENT_DATE THEN  SINKMODIFIEDON
                ELSE NVL(IGL_NEODATE, SINKMODIFIEDON)
        END AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' AS DWH_LOAD_ID 
FROM  etl_process.T_${SRC_INPUT_TABLE} SRC
INNER JOIN META.T_PARTY_KEY_1 STORE 
                ON STORE.PARTY_NAT_KEY_NR =  UPPER(SUBSTR(SRC.IGL_NUMBER, 1, 2)) ||'|'||TO_NUMBER(SUBSTR(SRC.IGL_NUMBER,3,5))
                AND STORE.PARTY_KEY_TYPE_CD = 'STORE'
INNER JOIN META.T_RESOURCE_ITEM_KEY_1 BUILDING
                ON BUILDING.RESOURCE_ITEM_NAT_KEY_NR = UPPER(SUBSTR(SRC.IGL_NUMBER, 1, 2)) ||'|'||TO_NUMBER(SUBSTR(SRC.IGL_NUMBER,3,5)) 
                AND BUILDING.RESOURCE_ITEM_KEY_TYPE_CD = 'RE_1'
WHERE IGL_EXPECTEDOPENINGDATE <= CURRENT_DATE OR IGL_NEODATE < CURRENT_DATE 
;
