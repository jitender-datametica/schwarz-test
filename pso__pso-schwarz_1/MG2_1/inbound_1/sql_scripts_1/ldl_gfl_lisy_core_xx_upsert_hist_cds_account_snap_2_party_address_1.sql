INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
	PARTY_KEY_TYPE_CD,
        PARTY_NATURAL_KEY,
	ADDR_KEY_TYPE_CD,
        ADDR_NATURAL_KEY,
	ADDR_USG_TYPE_CD,
        PARTY_TYPE_CD,
	ADDR_TYPE_CD,        
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        'STORE' AS PARTY_KEY_TYPE_CD,
        IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(IGL_NUMBER, 3, LENGTH(IGL_NUMBER)), '0#') AS PARTY_NATURAL_KEY,
        'STAD' AS ADDR_KEY_TYPE_CD,
        COALESCE(SRC.IGL_ISOCODE2, '') 
                || '|' || COALESCE(SRC.address1_city, '') 
                || '|' || COALESCE(SRC.igl_ortsteil, '') 
                || '|' || COALESCE(SRC.address1_postalcode, '')
                || '|' || COALESCE(SRC.address1_line1, '') 
                || '|' || COALESCE(SRC.address1_line2, '') 
                || '|' || nvl(SRC.address1_longitude, 0)
                || '|' || nvl(SRC.address1_latitude, 0) AS ADDR_NATURAL_KEY,
        'SA_MN'AS ADDR_USG_TYPE_CD,
        'INT_ORG' AS PARTY_TYPE_CD,
        'STAD' AS ADDR_TYPE_CD,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CASE
            WHEN SRC.IGL_NEODATE IS NOT NULL THEN SRC.IGL_NEODATE
            ELSE SRC.SINKMODIFIEDON
        END AS DWH_VALID_FROM_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        'T_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' AS DWH_LOAD_ID 
FROM etl_process.T_${SRC_INPUT_TABLE} SRC
WHERE IGL_ACCOUNTTYPECODE IN (285540000, 285540009)
AND IGL_NUMBER IS NOT NULL
AND (IGL_NEODATE IS NOT NULL OR IGL_CLOSINGDATE IS NOT NULL )
AND IGL_ISOCODE2 IS NOT NULL
AND DELETED != 'x'
UNION ALL
SELECT
        'STORE' AS PARTY_KEY_TYPE_CD,
        IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(IGL_NUMBER, 3, LENGTH(IGL_NUMBER)), '0#') AS PARTY_NATURAL_KEY,
        'TEL' AS ADDR_KEY_TYPE_CD,
        (SRC.IGL_ISOCODE2 || '|' || SRC.ADDRESS1_TELEPHONE2) AS ADDR_NATURAL_KEY,
        'TL_MN'AS ADDR_USG_TYPE_CD,
        'INT_ORG' AS PARTY_TYPE_CD,
        'TEL' AS ADDR_TYPE_CD,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CASE
            WHEN SRC.IGL_NEODATE IS NOT NULL THEN SRC.IGL_NEODATE
            ELSE SRC.SINKMODIFIEDON
        END AS DWH_VALID_FROM_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        'T_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' AS DWH_LOAD_ID 
FROM etl_process.T_${SRC_INPUT_TABLE} SRC
WHERE IGL_ACCOUNTTYPECODE IN (285540000, 285540009)
AND IGL_NUMBER IS NOT NULL
AND (IGL_NEODATE IS NOT NULL OR IGL_CLOSINGDATE IS NOT NULL )
AND IGL_ISOCODE2 IS NOT NULL
AND DELETED != 'x'
AND ADDRESS1_TELEPHONE2 IS NOT NULL
