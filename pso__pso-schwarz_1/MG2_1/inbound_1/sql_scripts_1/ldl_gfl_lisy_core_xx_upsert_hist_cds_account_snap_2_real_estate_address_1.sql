        'TEL' AS ADDR_KEY_TYPE_CD,
        (SRC.IGL_ISOCODE2 || '|' || SRC.ADDRESS1_TELEPHONE2) AS ADDR_NATURAL_KEY,
        'TL_MN'AS ADDR_USG_TYPE_CD,
        'TEL' AS ADDR_TYPE_CD,
        'LISY' AS SOURCE_SYSTEM,
