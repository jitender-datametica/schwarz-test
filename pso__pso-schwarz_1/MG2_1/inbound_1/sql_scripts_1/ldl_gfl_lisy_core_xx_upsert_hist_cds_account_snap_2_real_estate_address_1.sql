SELECT
        'RE_1' AS REAL_ESTATE_KEY_TYPE_CD,
        (SRC.IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(SRC.IGL_NUMBER, 3, 7), '0#')) AS REAL_ESTATE_NATURAL_KEY,
        'STAD' AS ADDR_KEY_TYPE_CD,
        COALESCE(SRC.IGL_ISOCODE2, '') || '|' || COALESCE(SRC.ADDRESS1_CITY, '') || '|' || COALESCE(SRC.IGL_ORTSTEIL, '') || '|' || COALESCE(SRC.ADDRESS1_POSTALCODE, '') || '|' || COALESCE(SRC.ADDRESS1_LINE1, '') || '|' || COALESCE(SRC.ADDRESS1_LINE2, '') || '|' || COALESCE(SRC.ADDRESS1_LONGITUDE, 0) || '|' || COALESCE(SRC.ADDRESS1_LATITUDE, 0) AS ADDR_NATURAL_KEY,
        'SA_MN'AS ADDR_USG_TYPE_CD,
        'STAD' AS ADDR_TYPE_CD,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CASE
            WHEN IGL_NEODATE IS NOT NULL THEN IGL_NEODATE
            ELSE SINKMODIFIEDON
        END AS DWH_VALID_FROM_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
