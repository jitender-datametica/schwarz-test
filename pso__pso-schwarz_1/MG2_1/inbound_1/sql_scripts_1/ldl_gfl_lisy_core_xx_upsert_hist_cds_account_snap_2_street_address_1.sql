INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        IGL_ISOCODE2,
        ADDRESS1_CITY,
        IGL_ORTSTEIL,
        ADDRESS1_POSTALCODE,
        STREET_ADDR_NK,
        STREET_ADDR_KEY_TYPE_CD,
        COUNTRY_KEY_TYPE_CD,
        ISO_COUNTRY_CD,
        COUNTRY_NAME,
        CITY_KEY_TYPE_CD,
        CITY_NAME,
        DISTRICT_NK,
        DISTRICT_KEY_TYPE_CD,
        DISTRICT_NAME,
        POSTAL_CD_AREA_KEY_TYPE_CD,
        ZIP,
        STREET_NAME,
        HOUSE_NR,
        REPORTING_COUNTRY_KEY_TYPE_CD,
        REPORTING_COUNTRY_CD,
        LON,
        LAT,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        SRC.IGL_ISOCODE2 AS IGL_ISOCODE2,
        SRC.ADDRESS1_CITY AS ADDRESS1_CITY,
        SRC.IGL_ORTSTEIL AS IGL_ORTSTEIL,
        SRC.ADDRESS1_POSTALCODE AS ADDRESS1_POSTALCODE,
        COALESCE(SRC.IGL_ISOCODE2, '') || '|' || COALESCE(SRC.ADDRESS1_CITY, '') || '|' || COALESCE(SRC.IGL_ORTSTEIL, '') || '|' || COALESCE(SRC.ADDRESS1_POSTALCODE, '') || '|' || COALESCE(SRC.ADDRESS1_LINE1, '') || '|' || COALESCE(SRC.ADDRESS1_LINE2, '') || '|' || COALESCE(SRC.ADDRESS1_LONGITUDE, 0) || '|' || COALESCE(SRC.ADDRESS1_LATITUDE, 0) AS STREET_ADDR_NK,
        'STAD' AS STREET_ADDR_KEY_TYPE_CD,
        'CTRY' AS COUNTRY_KEY_TYPE_CD,
        CASE
            WHEN IGL_ISOCODE2 = 'NI' THEN 'GB'
            ELSE IGL_ISOCODE2
        END AS ISO_COUNTRY_CD,
        CASE
            WHEN IGL_ISOCODE2 = 'NI' THEN 'Vereinigtes Königreich'
            ELSE CTRY.COUNTRY_NAME 
        END AS COUNTRY_NAME,
        'CITY' AS CITY_KEY_TYPE_CD,
        SRC.ADDRESS1_CITY AS CITY_NAME,
        CASE
            WHEN SRC.IGL_ORTSTEIL IS NOT NULL THEN COALESCE(SRC.IGL_ISOCODE2, '') || '|' || COALESCE(SRC.ADDRESS1_CITY, '') || '|' || COALESCE(SRC.IGL_ORTSTEIL, '')
            ELSE NULL
        END AS DISTRICT_NK,
        'DSTR' AS DISTRICT_KEY_TYPE_CD,
        SRC.IGL_ORTSTEIL AS DISTRICT_NAME,
         'ZIP' AS POSTAL_CD_AREA_KEY_TYPE_CD,
        SRC.ADDRESS1_POSTALCODE AS ZIP,
        SRC.ADDRESS1_LINE1 AS STREET_NAME,
        SRC.ADDRESS1_LINE2 AS HOUSE_NR,
        'REP_CTRY' AS REPORTING_COUNTRY_KEY_TYPE_CD,
        SRC.IGL_ISOCODE2 AS REPORTING_COUNTRY_CD,
        SRC.ADDRESS1_LONGITUDE AS LON,
        SRC.ADDRESS1_LATITUDE AS LAT,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CURRENT_DATE AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM etl_process.t_${SRC_INPUT_TABLE} SRC
LEFT JOIN CORE_REL.T_COUNTRY_1 CTRY
ON SRC.IGL_ISOCODE2 = CTRY.ISO_COUNTRY_CD
WHERE IGL_ISOCODE2 IS NOT NULL
AND ADDRESS1_CITY IS NOT NULL
AND DELETED <> 'x'
-- ""Grossebersdorf"" is same as ""Großebersdorf"" when converted to UPPER
-- so we eliminate such duplicates of NK by taking the longer ( ""ss"" instead of ""ß"")
QUALIFY ROW_NUMBER() OVER 
	(PARTITION BY SRC.IGL_ISOCODE2
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_CITY, ''))
				   ||'|'|| UPPER(NVL(SRC.IGL_ORTSTEIL, ''))
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_POSTALCODE, ''))
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_LINE1, ''))
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_LINE2, ''))
				   ||'|'|| NVL(SRC.ADDRESS1_LONGITUDE, 0)
				   ||'|'|| NVL(SRC.ADDRESS1_LATITUDE, 0) 
	ORDER BY LENGTH(SRC.IGL_ISOCODE2
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_CITY, ''))
				   ||'|'|| UPPER(NVL(SRC.IGL_ORTSTEIL, ''))
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_POSTALCODE, ''))
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_LINE1, ''))
				   ||'|'|| UPPER(NVL(SRC.ADDRESS1_LINE2, ''))
				   ||'|'|| NVL(SRC.ADDRESS1_LONGITUDE, 0)
				   ||'|'|| NVL(SRC.ADDRESS1_LATITUDE, 0)),
                                            SINKMODIFIEDON DESC) = 1
;
