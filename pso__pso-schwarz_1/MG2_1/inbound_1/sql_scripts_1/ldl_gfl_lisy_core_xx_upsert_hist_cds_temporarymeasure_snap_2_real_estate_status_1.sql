INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        REAL_ESTATE_KEY_TYPE_CD,
        REAL_ESTATE_NK,
        REAL_ESTATE_STATUS_CATEG_CD,
        REAL_ESTATE_STATUS_CD,
        REAL_ESTATE_STATUS_REASON_CD,
        COMMENT_TXT,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        DWH_ENDING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        'RE_1' AS REAL_ESTATE_KEY_TYPE_CD,
        IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(IGL_NUMBER, 3, 7), '0#') AS REAL_ESTATE_NK,
        'BS' AS REAL_ESTATE_STATUS_CATEG_CD,
        'TC' AS REAL_ESTATE_STATUS_CD,
        CASE
                WHEN IGL_MEASUREREASONCODE = 285540001 THEN 'BS_TC_DNC'
                WHEN IGL_MEASUREREASONCODE = 285540002 THEN 'BS_TC_REL'
                WHEN IGL_MEASUREREASONCODE = 285540003 THEN 'BS_TC_MOD'
                WHEN IGL_MEASUREREASONCODE = 285540004 THEN 'BS_TC_MEX'
                WHEN IGL_MEASUREREASONCODE = 285540005 THEN 'BS_TC_OWN'
                WHEN IGL_MEASUREREASONCODE = 285540006 THEN 'BS_TC_OTH'
                WHEN IGL_MEASUREREASONCODE = 285540007 THEN 'BS_TC_DMG'
                WHEN IGL_MEASUREREASONCODE = 285540008 THEN 'BS_TC_NAT'
                WHEN IGL_MEASUREREASONCODE = 285540009 THEN 'BS_TC_SRR'
                WHEN IGL_MEASUREREASONCODE = 285540010 THEN 'BS_TC_SMC'
                WHEN IGL_MEASUREREASONCODE = 285540011 THEN 'BS_TC_SSS'
                WHEN IGL_MEASUREREASONCODE = 285540012 THEN 'BS_TC_FMW'
                WHEN IGL_MEASUREREASONCODE = 285540013 THEN 'BS_TC_SCC'
        END AS REAL_ESTATE_STATUS_REASON_CD,
        NULL AS COMMENT_TXT,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CAST(TRY_TO_DATE(IGL_CLOSINGDATEFROM, 'YYYYMMDD') AS DATETIME) AS DWH_MAPPING_TMSP,
        CASE
                WHEN (IGL_REOPENINGDATE IS NULL OR IGL_REOPENINGDATE < IGL_CLOSINGDATEFROM) AND IGL_CLOSINGDATETO >= IGL_CLOSINGDATEFROM 
                        THEN DATEADD(d,1,(DATEADD(ns, -1, TRY_TO_DATE(IGL_CLOSINGDATETO, 'YYYYMMDD'))))
                ELSE DATEADD(d,1,(DATEADD(ns, -1, TRY_TO_DATE(IGL_REOPENINGDATE, 'YYYYMMDD'))))
        END AS DWH_ENDING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM etl_process.t_${SRC_INPUT_TABLE} SRC
WHERE
IGL_NUMBER IS NOT NULL -- (only objects with assigned object number should be kept)
AND IGL_CLOSINGDATEFROM IS NOT NULL
AND (IGL_CLOSINGDATETO IS NOT NULL OR IGL_REOPENINGDATE IS NOT NULL)
AND (IGL_CLOSINGDATETO >= IGL_CLOSINGDATEFROM
OR IGL_REOPENINGDATE >= IGL_CLOSINGDATEFROM)
AND DELETED <> 'x'
QUALIFY ROW_NUMBER() OVER (PARTITION BY IGL_NUMBER, IGL_CLOSINGDATEFROM ORDER BY EXTRACTION_TS DESC) = 1
;
