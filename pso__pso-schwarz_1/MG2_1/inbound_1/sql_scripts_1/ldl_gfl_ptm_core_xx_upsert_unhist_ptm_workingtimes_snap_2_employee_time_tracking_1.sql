INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        INT_ORG_KEY_TYPE_CD,
        INT_ORG_NATURAL_KEY,
        COUNTRY_ORG_KEY_TYPE_CD,
        COUNTRY_ORG_NATURAL_KEY,
        COUNTRY_ORG_CD,
        EMP_HASH,
        EMP_TM_TRACKING_NR,
        TM_BOOKING_TMSP,
        CANCEL_FG,
        BUS_DT,
        EMP_TM_TRACKING_TYPE_CD,
        EMP_START_TM_TRACKING_METHOD_CD,
        EMP_END_TM_TRACKING_METHOD_CD,
        EMP_START_TM_BOOKING_TYPE_CD,
        EMP_END_TM_BOOKING_TYPE_CD,
        EMP_TM_EVENT_TYPE_CD,
        TM_TRACKING_TMSP,
        EMP_TM_PERIOD_TYPE_KEY_TYPE_CD,
        EMP_TM_PERIOD_TYPE_NATURAL_KEY,
        PERIOD_START_TMSP,
        PERIOD_END_TMSP,
        HR_CNT,
        BREAK_MIN_CNT,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
WITH WH_LKP AS 
(SELECT DISTINCT 
        X.STORENO, 
        B.INT_ORG_SID AS SALES_COMPANY_SID, 
        SUBSTR(INT_ORG_NR,1,2)||'|'||SUBSTR(INT_ORG_NR,3,LENGTH(INT_ORG_NR)-2) AS WAREHOUSE_NK 
FROM ETL_PROCESS.T_TCACHE_PTM_MISSINGTIMES_SNAP X
LEFT JOIN META.T_PARTY_KEY_1 Y 
        ON Y.PARTY_NAT_KEY_NR=BIC_ZMLILA||'|'||STORENO
AND Y.PARTY_KEY_TYPE_CD='STORE'
LEFT JOIN CORE_REL.T_INTERNAL_ORGANIZATION_HIERARCHY_1 A
        ON Y.PARTY_SID=A.INT_ORG_SID AND INT_ORG_HIERARCHY_TYPE_CD='DELIVCMP_STORE' 
LEFT  JOIN CORE_REL.T_INTERNAL_ORGANIZATION_1 B 
        ON A.PARENT_INT_ORG_SID=B.INT_ORG_SID
)
SELECT
        'STORE' AS INT_ORG_KEY_TYPE_CD,
         UPPER(BIC_ZMLILA)||'|'||LTRIM (REGEXP_REPLACE(SRC.STORENO, '[^0-9]', ''), 0) AS INT_ORG_NATURAL_KEY,
         'COUNTRY_1' AS COUNTRY_ORG_KEY_TYPE_CD,
        UPPER(BIC_ZMLILA) AS COUNTRY_ORG_NATURAL_KEY,
        UPPER(BIC_ZMLILA) AS COUNTRY_ORG_CD,
        MIS_KEY AS EMP_HASH,
        LTRIM(WORKING_ID,0) AS EMP_TM_TRACKING_NR,
        CHANGE_DATE AS TM_BOOKING_TMSP,
        CASE 
                WHEN VALIDFOR IS NULL THEN 0
                ELSE 1 
        END AS CANCEL_FG,
        WORKING_DATE AS BUS_DT,
        'WT' AS EMP_TM_TRACKING_TYPE_CD,
        CASE 
             WHEN TYPE_FROM = 'T' then 'T'
             ELSE 'M'
        END AS EMP_START_TM_TRACKING_METHOD_CD, 
        CASE 
             WHEN TYPE_TO = 'T' then 'T'
             ELSE 'M'
        END AS EMP_END_TM_TRACKING_METHOD_CD,
        CASE 
             WHEN TYPE_FROM IS NULL THEN 'PTM_NULL'
             WHEN TRIM(TYPE_FROM) = '' THEN 'PTM_NULL'
             ELSE 'PTM_' || TRIM(TYPE_FROM)
        END AS EMP_START_TM_BOOKING_TYPE_CD, 
        CASE 
             WHEN TYPE_TO IS NULL THEN 'PTM_NULL'
             WHEN TRIM(TYPE_TO) = '' THEN 'PTM_NULL'
             ELSE 'PTM_' || TRIM(TYPE_TO)
        END AS EMP_END_TM_BOOKING_TYPE_CD, 
        NULL AS EMP_TM_EVENT_TYPE_CD,
        NULL AS TM_TRACKING_TMSP,
        'PTM' AS EMP_TM_PERIOD_TYPE_KEY_TYPE_CD, 
        WH_LKP.WAREHOUSE_NK || '|' || TRIM(WORKING_ID,'') AS EMP_TM_PERIOD_TYPE_NATURAL_KEY, 
        COALESCE((DATE_FROM) || ' ' || (TIME_FROM) , '9999-12-30 23:59:59') AS PERIOD_START_TMSP,
        COALESCE((DATE_FROM) || ' ' || (TIME_TO) , '9999-12-30 23:59:59') AS  PERIOD_END_TMSP,
        NULL AS HR_CNT,
        NULL AS BREAK_MIN_CNT,
        'SAP_PTM'           AS SOURCE_SYSTEM,
        CURRENT_DATE     AS EXTRACTION_DT,
        CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
        0                AS TF_ERROR_FG,
        0                AS DELETED_FG,
        0                AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'SAP_PTM' AS DWH_NODE_CD,
        '${LOAD_ID}' AS DWH_LOAD_ID 
FROM etl_process.t_${SRC_INPUT_TABLE} SRC
JOIN WH_LKP ON SRC.STORENO = WH_LKP.STORENO
;
