INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
 (
        PROD_NAT_KEY_NR,    
        PROD_KEY_TYPE_CD,  
        PROD_VARIANT_KEY_TYPE_CD,  
        PROD_VARIANT_NAT_KEY_NR,
        PROD_VARIANT_NR,
        GTIN,
        PROD_VARIANT_NAME,
        PROD_VARIANT_TYPE_CD,
        WEIGHT_BASED_FG,
        LOGISTIC_VARIANT_TYPE_CD,
        CASE_SIZE_CNT,

        SOURCE_SYSTEM, 
        EXTRACTION_DT, 
        DWH_MAPPING_TMSP,  
        TF_ERROR_FG, 
        DELETED_FG, 
        RECORD_ID, 
        FILENAME,
        DWH_NODE_CD, 
        DWH_LOAD_ID
)
SELECT
        ART.CTRCODE || '|' || LTRIM(ART.ITEMNR,'0') PROD_NAT_KEY_NR,
        'WAWI' PROD_KEY_TYPE_CD, 
        'WAW_LOG' PROD_VARIANT_KEY_TYPE_CD, 
        ART.CTRCODE || '|' || CAST (ART.ITEMNR AS STRING) PROD_VARIANT_NAT_KEY_NR,
        ART.CTRCODE || '|' || CAST (ART.ITEMNR AS STRING) PROD_VARIANT_NR,
        NULL GTIN,
        ART.DEUTSCHTEXT PROD_VARIANT_NAME,
        'LOGISTIC' PROD_VARIANT_TYPE_CD,
        CASE 
        WHEN  COALESCE(GEWICHTSARTIKEL,0) = 1 THEN TRUE 
        ELSE FALSE 
        END	WEIGHT_BASED_FG,
        NULL LOGISTIC_VARIANT_TYPE_CD,
        NULL CASE_SIZE_CNT,
        'WAWI' SOURCE_SYSTEM,
        ART.EXTRACTION_TMSP EXTRACTION_DT,
        ART.EXTRACTION_TMSP DWH_MAPPING_TMSP,
        0 TF_ERROR_FG,
        0 DELETED_FG,
        0 RECORD_ID,
        't_${SRC_INPUT_TABLE}' FILENAME,
        'WAWI_HQ' DWH_NODE_CD,
        '${LOAD_ID}' DWH_LOAD_ID 
FROM
  (  
        SELECT
            ART.CTRCODE
          , ART.ITEMNR
          , ART.CASE_SIZE
          , ART.EXTRACTION_TMSP
          , ART.DEUTSCHTEXT
          , ITMO.GEWICHTSARTIKEL  --WEIGHT_BASED_FG --
          , ART.ARTGRUPNR
        FROM
        (
            SELECT *
              , CAST(ARTNRVIER AS NUMBER) AS ITEMNR
              , CAST(RIGHT(ARTIKELNR, 4) AS NUMBER) AS CASE_SIZE
            FROM ${TEMP_DB}.T_WAWI_PRECORE_ARTIKEL_1
        ) AS ART_1

        LEFT OUTER JOIN
        (
            SELECT DISTINCT
                CTRCODE
              , CAST(SUBSTRING(C215_ITEMNR, 1, LENGTH(C215_ITEMNR)-4) AS NUMBER) AS ITEMNR
              , CAST(C215_INT_ITEMNR AS NUMBER) AS C215_INT_ITEMNR
            FROM ${TEMP_DB}.T_WAWI_PRECORE_T215_INT_ITEMNR_1
        ) AS II
                ON  ART.CTRCODE = II.CTRCODE
                AND ART.ITEMNR = II.ITEMNR
        LEFT OUTER JOIN META.T_PRODUCT_KEY_1 AS IPK
                ON  CAST(II.C215_INT_ITEMNR AS STRING) = IPK.PROD_NAT_KEY_NR
                AND IPK.PROD_KEY_TYPE_CD IN ('CBX', 'FV')
                AND IPK.DWH_VALID_FG
        LEFT OUTER JOIN
        (
            SELECT DISTINCT ITEMNO
            FROM ETL.T_WAWI_PRECORE_EKS_ITEM_WAWI_ITEM_1
        ) AS EKS
                ON  II.C215_INT_ITEMNR = EKS.ITEMNO
        LEFT OUTER JOIN ${TEMP_DB}.T_WAWI_PRECORE_T271_PACKAGETYPE_1   AS PT
                ON  ART.CTRCODE = PT.CTRCODE
                AND ART.PACKUNG = PT.C271_PACKDESCRIPT

        INNER JOIN ${TEMP_DB}.T_WAWI_PRECORE_ARTIKELBESTELL_1 AS ITMO
                ON  ART.CTRCODE = ITMO.CTRCODE
                AND ART.ARTIKELNR = ITMO.ARTIKELNR

        INNER JOIN ${TEMP_DB}.T_WAWI_PRECORE_T277_UNITFACTORS_1 AS UNIT_1
                ON  ART.CTRCODE = UNIT.CTRCODE
                AND ART.UNIT_ID = UNIT.C277_ID
        WHERE
        (
            II.ITEMNR IS NULL /* NO LINK TO INTERNATIONAL ITEM_1 NUMBER */
            OR
            (
                    IPK.PROD_SID IS NULL /* INTERNATIONAL NUMBER NOT FOUND IN INTERNATIONAL KEYS */
                AND EKS.ITEMNO IS NULL
            ))

        QUALIFY ROW_NUMBER() OVER (PARTITION BY ART.CTRCODE, 
                                                ART.ITEMNR
                                        ORDER BY ART.CASE_SIZE DESC NULLS LAST
                                      ) = 1
) AS ART_1
;
