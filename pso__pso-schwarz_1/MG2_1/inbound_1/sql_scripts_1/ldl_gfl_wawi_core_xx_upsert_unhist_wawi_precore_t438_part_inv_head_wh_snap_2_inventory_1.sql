INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        INV_KEY_TYPE_CD
       ,INV_NATURAL_KEY
       ,INV_DT
       ,INV_TYPE_CD
       ,INV_NR
       ,INT_ORG_KEY_TYPE_CD
       ,INT_ORG_NATURAL_KEY
       ,INT_ORG_TYPE_CD
       ,COUNTRY_ORG_CD
       ,COUNTRY_ORG_NATURAL_KEY
       ,COUNTRY_ORG_KEY_TYPE_CD
       ,INV_PERIOD_START_DT
       ,INV_PERIOD_END_DT
       ,INV_REASON_ID
       ,SOURCE_SYSTEM
       ,EXTRACTION_DT
       ,DWH_MAPPING_TMSP
       ,TF_ERROR_FG
       ,DELETED_FG
       ,RECORD_ID
       ,FILENAME
       ,DWH_NODE_CD
       ,DWH_LOAD_ID
)
SELECT  
       'PART' AS INV_KEY_TYPE_CD,
        CTRCODE || '|' || WH_NR || '|' || C438_INV_ID  AS INV_NATURAL_KEY,
        C438_INVENTORYDATE AS INV_DT,
        'PART' AS INV_TYPE_CD,
        C438_INV_ID AS INV_NR,
        'STORE' AS INT_ORG_KEY_TYPE_CD,
        CTRCODE || '|' || C438_STORENR AS INT_ORG_NATURAL_KEY,
        'STORE' AS INT_ORG_TYPE_CD,
        LEFT(ctrcode,2) AS COUNTRY_ORG_CD,
        LEFT(ctrcode,2) AS COUNTRY_ORG_NATURAL_KEY,
        'COUNTRY_1' AS COUNTRY_ORG_KEY_TYPE_CD,
        C438_INVENTORYDATE AS INV_PERIOD_START_DT,
        C438_INVENTORYDATE AS INV_PERIOD_END_DT,
        C438_INV_TYPE AS INV_REASON_ID,
        'WAWI_WH' AS SOURCE_SYSTEM,
        EXTRACTION_TMSP AS EXTRACTION_DT,
        CURRENT_TIMESTAMP() AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'WAWI_WH' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM ETL_PROCESS.t_${SRC_INPUT_TABLE}  SRC
INNER JOIN ${TEMP_DB}.WAWI_CONTROL_TABLE_1 ctrl
ON true
AND ctrl.SOURCE_TABLE_NAME = UPPER('${TEMP_DB}.t438_part_inv_head_wh_1')
AND ctrl.SOURCE_STATUS = 'A'
AND src.EXTRACTION_TMSP between ctrl.BEGIN_TMSP and ctrl.END_TMSP
;
