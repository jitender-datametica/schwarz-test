create or replace view LDL_DATA_PRODUCTION.ETL.V_RECORD_COUNT_1(
	BUS_DT,
	TARGET_TABLE,
	TODAY_RECCOUNT,
	PREV_RECCOUNT
) as  
 SELECT CRDAY.BUS_DT,
        COALESCE( CRDAY.TBL_NAME, PRDAY.TBL_NAME) AS TARGET_TABLE,
        COALESCE( CRDAY.TODAY_RECCOUNT, 0) AS TODAY_RECCOUNT,
        COALESCE( PRDAY.PREV_RECCOUNT, 0) AS PREV_RECCOUNT
   FROM 
(select BUS_DT,
        TBL_NAME,
        TBL_REC_CNT as TODAY_RECCOUNT
   from etl.T_REC_CNT_1 where BUS_DT = (select MAX(BUS_DT) as LAST_BUSS_DT from etl.T_REC_CNT_1)
   ) as CRDAY
-- on  mbdt.LAST_BUSS_DT = CRDAY.BUS_DT 
   FULL JOIN  
(select BUS_DT,
        TBL_NAME,
        TBL_REC_CNT as PREV_RECCOUNT
   from etl.T_REC_CNT_1 where BUS_DT = (select MAX(BUS_DT) - 1 as LAST_BUSS_DT from etl.T_REC_CNT_1)
) as PRDAY
     ON CRDAY.TBL_NAME = PRDAY.TBL_NAME
;