create or replace view LDL_DATA_PRODUCTION.FE_MSTR_APP_FRAUD_DETECTION.V_CASH_REGISTER_EVENT_CLASSIFICATION_BY_CASHIER_DAY_CUST_1(
	STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE STORE WHERE THE RELATED CASH REGISTER EVENT HAPPENED.',
	BUS_DT COMMENT 'THE BUSINESS DATE ON WHICH THE RETAIL EVENT IS COUNTED.',
	CASHIER_NR COMMENT 'THE NUMBER WHICH IDENTIFIES THE CASHIER. (THE NUMBER IS UNIQUE FOR A GIVEN STORE AND A DAY.)',
	SCENARIO_ID COMMENT 'THE UNIQUE IDENTIFIER OF FRAUD DETECTION SCENARIO',
	COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_1 FOR WHICH THE RELATED COUNTRY_1 ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY_1 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	CUST_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE CUSTOMER.',
	METRIC_ID COMMENT 'THE UNIQUE IDENTIFIER OF MICROSTRATEY METRIC',
	CALCULATION_TYPE_CD COMMENT 'THE CALCULATION TYPE OF THE METRIC SUM,SMARTAVG..',
	SCENARIO_VALUE_1 COMMENT 'THE FIRST VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	SCENARIO_VALUE_2 COMMENT 'THE SECOND VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	SCENARIO_VALUE_3 COMMENT 'THE THIRD VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	SCENARIO_VALUE_4 COMMENT 'THE  VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	CURR_CD COMMENT 'THE CODE IDENTIFYING THE CURRENCY ACCORDING TO ISO-4217.',
	CURR_GROUP_FG COMMENT 'FLAG FOR GROUP CURRENCY',
	CURR_LOCAL_FG COMMENT 'FLAG FOR LOCAL CURRENCY'
) as  
WITH CTE_CASH_REGISTER_EVENT_CLASSIFICATION
(COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,CASHIER_NR,SCENARIO_ID,CUST_SID,BUS_DT,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG,CASH_REGISTER_EVENT_CNT,CASH_REGISTER_EVENT_AFFECTED_LINE_CNT,CASH_REGISTER_EVENT_AFFECTED_NET_VAL,CUST_SID_DST_CNT)
AS 
(
  SELECT 
  MAIN.COUNTRY_ORG_CD
  ,STORE.SALES_COMPANY_SID
  ,MAIN.STORE_SID
  ,MAIN.CASHIER_NR
  ,MAIN.SCENARIO_ID
  ,MAIN.CUST_SID
  ,MAIN.BUS_DT
  ,FER.SRC_CURR_CD AS CURR_CD
  ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
  ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
  ,SUM(MAIN.CASH_REGISTER_EVENT_CNT) AS CASH_REGISTER_EVENT_CNT
  ,SUM(MAIN.CASH_REGISTER_EVENT_AFFECTED_LINE_CNT) AS CASH_REGISTER_EVENT_AFFECTED_LINE_CNT
  ,SUM(MAIN.CASH_REGISTER_EVENT_AFFECTED_NET_VAL / FER.EXCHANGE_RATE ) AS CASH_REGISTER_EVENT_AFFECTED_LINE_CNT
  ,COUNT(DISTINCT MAIN.CUST_SID) AS CUST_SID_DST_CNT
  FROM CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_CLASSIFICATION_1 MAIN
  INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 STORE
  ON STORE.INT_ORG_SID = MAIN.STORE_SID
  AND STORE.DWH_VALID_FG
  INNER JOIN CORE_DIM.T_DIM_COUNTRY_1 CT
  ON MAIN.COUNTRY_ORG_CD = CT.ISO_COUNTRY_CD
  INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 FER
    ON CT.CURR_CD = FER.TGT_CURR_CD
  WHERE FER.EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
    AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
    AND FER.ACTIVE_FG = TRUE
    AND MAIN.SCENARIO_ID IN (20,40,200100)
  GROUP BY 
  MAIN.COUNTRY_ORG_CD
  ,STORE.SALES_COMPANY_SID
  ,MAIN.STORE_SID
  ,MAIN.CASHIER_NR
  ,MAIN.SCENARIO_ID
  ,MAIN.BUS_DT
  ,FER.SRC_CURR_CD 
  ,FER.TGT_CURR_CD
  ,MAIN.CUST_SID
)
,CTE_CASHIER_SCENARIO (COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,CASHIER_NR,SCENARIO_ID,CUST_SID)
AS
(
SELECT 
    FACT.COUNTRY_ORG_CD
	,FACT.SALES_COMPANY_SID
	,FACT.STORE_SID
	,FACT.CASHIER_NR
	,FACT.SCENARIO_ID
    ,FACT.CUST_SID
	FROM CTE_CASH_REGISTER_EVENT_CLASSIFICATION FACT
	GROUP BY 
	FACT.COUNTRY_ORG_CD
	,FACT.SALES_COMPANY_SID
	,FACT.STORE_SID
	,FACT.CASHIER_NR
	,FACT.SCENARIO_ID
    ,FACT.CUST_SID
) 
,CTE_COUNTRY_IN_RV (COUNTRY_ORG_CD,ANALYSIS_PERIOD_START_DT,ANALYSIS_PERIOD_END_DT)
AS
(
  SELECT ORD.COUNTRY_ORG_CD, MIN(ORD.ANALYSIS_PERIOD_START_DT) AS ANALYSIS_PERIOD_START_DT, MAX(ORD.ANALYSIS_PERIOD_END_DT) AS ANALYSIS_PERIOD_END_DT
  FROM CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_ORDER_1 ORD
  WHERE ORD.ORDER_PARAMETER_STATUS_CD = 'RV'
  GROUP BY ORD.COUNTRY_ORG_CD
)
, CTE_STORE_ANALYSIS_PERIOD (COUNTRY_ORG_CD,STORE_SID,ANALYSIS_PERIOD_START_DT,ANALYSIS_PERIOD_END_DT) AS
(
  SELECT SAL_COMP.COUNTRY_ORG_CD , STORE.INT_ORG_SID AS STORE_SID, MIN(ORD.ANALYSIS_PERIOD_START_DT) AS ANALYSIS_PERIOD_START_DT, MAX(ORD.ANALYSIS_PERIOD_END_DT) AS ANALYSIS_PERIOD_END_DT
  FROM CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_ORDER_1 ORD
  INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 SAL_COMP
    ON ORD.INT_ORG_SID = SAL_COMP.INT_ORG_SID
  INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 STORE
   ON STORE.SALES_COMPANY_SID = SAL_COMP.SALES_COMPANY_SID
  WHERE SAL_COMP.DWH_VALID_FG 
   AND STORE.DWH_VALID_FG
   AND ORD.ORDER_PARAMETER_STATUS_CD = 'RV'
   AND STORE.INT_ORG_TYPE_CD = 'STORE'
  GROUP BY SAL_COMP.COUNTRY_ORG_CD,STORE.INT_ORG_SID
)
,CTE_STORE_CUST (COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,SCENARIO_ID,CUST_SID,ANALYSIS_PERIOD_START_DT,ANALYSIS_PERIOD_END_DT)
AS
(
SELECT 
    FACT.COUNTRY_ORG_CD
	,FACT.SALES_COMPANY_SID
	,FACT.STORE_SID
	,FACT.SCENARIO_ID
    ,FACT.CUST_SID
    ,MIN(RV.ANALYSIS_PERIOD_START_DT) AS ANALYSIS_PERIOD_START_DT
    ,MAX(RV.ANALYSIS_PERIOD_END_DT) AS ANALYSIS_PERIOD_END_DT
	FROM CTE_CASHIER_SCENARIO FACT
    INNER JOIN CTE_STORE_ANALYSIS_PERIOD RV
    ON FACT.COUNTRY_ORG_CD = RV.COUNTRY_ORG_CD
    AND FACT.STORE_SID = RV.STORE_SID
	GROUP BY 
	FACT.COUNTRY_ORG_CD
	,FACT.SALES_COMPANY_SID
	,FACT.STORE_SID
	,FACT.SCENARIO_ID
    ,FACT.CUST_SID
)
,CTE_CUSTOMER_DAY_COUNTRY (CUST_SID,BUS_DT,COUNTRY_ORG_CD,SALES_EVENT_CNT,RETURN_EVENT_CNT,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG)
AS
(
SELECT
    CUST_SID
    ,BUS_DT
    ,R.COUNTRY_ORG_CD
    ,SUM(DECODE(RETAIL_EVENT_TYPE_CD, 'S',1.0)) SALES_EVENT_CNT
    ,SUM(DECODE(RETAIL_EVENT_TYPE_CD, 'R',1.0)) RETURN_EVENT_CNT
    ,FER.SRC_CURR_CD AS CURR_CD
    ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
    ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
FROM CORE_REL.T_RETAIL_EVENT_1 R
INNER JOIN CTE_COUNTRY_IN_RV AS CNTRY_IN_RV
ON R.COUNTRY_ORG_CD = CNTRY_IN_RV.COUNTRY_ORG_CD
AND R.BUS_DT BETWEEN CNTRY_IN_RV.ANALYSIS_PERIOD_START_DT AND CNTRY_IN_RV.ANALYSIS_PERIOD_END_DT
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 FER
ON R.CURR_CD = FER.TGT_CURR_CD
WHERE 1=1
    AND CUST_SID IS NOT NULL
    AND TURNOVER_RELEVANT_FG
    AND BUS_DT > CURRENT_DATE - 180
    AND EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
    AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
    AND FER.ACTIVE_FG = TRUE
GROUP BY
    CUST_SID
    ,BUS_DT
    ,R.COUNTRY_ORG_CD
    ,FER.SRC_CURR_CD 
  ,FER.TGT_CURR_CD
)
,CTE_CUSTOMER_DAY_STORE (CUST_SID,BUS_DT,COUNTRY_ORG_CD,STORE_SID,SCENARIO_ID,SALES_EVENT_CNT,RETURN_EVENT_CNT,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG)
AS
(
SELECT
    R.CUST_SID
    ,R.BUS_DT
    ,R.COUNTRY_ORG_CD
    ,R.STORE_SID
    ,CTE_STORE_IN_RV.SCENARIO_ID
    ,SUM(DECODE(RETAIL_EVENT_TYPE_CD, 'S',1.0)) SALES_EVENT_CNT
    ,SUM(DECODE(RETAIL_EVENT_TYPE_CD, 'R',1.0)) RETURN_EVENT_CNT
    ,FER.SRC_CURR_CD AS CURR_CD
    ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
    ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
FROM CORE_REL.T_RETAIL_EVENT_1 R
INNER JOIN CTE_STORE_CUST AS CTE_STORE_IN_RV
ON R.COUNTRY_ORG_CD = CTE_STORE_IN_RV.COUNTRY_ORG_CD
AND R.STORE_SID = CTE_STORE_IN_RV.STORE_SID
AND R.CUST_SID = CTE_STORE_IN_RV.CUST_SID
AND R.BUS_DT BETWEEN CTE_STORE_IN_RV.ANALYSIS_PERIOD_START_DT AND CTE_STORE_IN_RV.ANALYSIS_PERIOD_END_DT
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 FER
ON R.CURR_CD = FER.TGT_CURR_CD
WHERE 1= 1 
    AND TURNOVER_RELEVANT_FG
    AND BUS_DT > CURRENT_DATE - 180
    AND EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
    AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
    AND FER.ACTIVE_FG = TRUE
GROUP BY
    R.CUST_SID
    ,R.BUS_DT
    ,R.COUNTRY_ORG_CD
    ,R.STORE_SID
    ,CTE_STORE_IN_RV.SCENARIO_ID
    ,FER.SRC_CURR_CD 
    ,FER.TGT_CURR_CD
),
CTE_STATISTICS_BY_STORE_DAY_CASHIER (COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,BUS_DT,CASHIER_NR,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG,SALES_NET_VAL,RETURN_NET_VAL)
AS 
( 
SELECT
 ORG.COUNTRY_ORG_CD
 ,ORG.SALES_COMPANY_SID
 ,MAIN.INT_ORG_SID AS STORE_SID
 ,MAIN.BUS_DT
 ,MAIN.CASHIER_NR
 ,FER.SRC_CURR_CD AS CURR_CD
 ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
 ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
 ,MAIN.SALES_NET_VAL AS  SALES_NET_VAL
 ,MAIN.RETURN_NET_VAL   AS RETURN_NET_VAL
FROM CORE_APP_FRAUD_DETECTION.T_STATISTICS_BY_STORE_HOUR_CASHIER_1 MAIN
INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 ORG
   ON MAIN.INT_ORG_SID = ORG.INT_ORG_SID
   AND ORG.DWH_VALID_FG
INNER JOIN CORE_DIM.T_DIM_COUNTRY_1 CT
   ON ORG.COUNTRY_ORG_CD = CT.ISO_COUNTRY_CD
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 FER
  ON CT.CURR_CD = FER.TGT_CURR_CD
WHERE FER.EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
   AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
   AND FER.ACTIVE_FG = TRUE   
)



SELECT 
 FACT.STORE_SID 
 ,FACT.BUS_DT
 ,FACT.CASHIER_NR
 ,-100 AS SCENARIO_ID
 ,FACT.COUNTRY_ORG_CD AS COUNTRY_ORG_CD
 ,CASHIER.CUST_SID AS CUST_SID 
 ,-100::NUMERIC(38,0) AS METRIC_ID
  ,'SUM' AS CALCULATION_TYPE_CD
 ,COALESCE(FACT.SALES_NET_VAL,0) - COALESCE(FACT.RETURN_NET_VAL,0) AS METRIC_VAL_1
 ,0::NUMERIC(38,5) AS METRIC_VAL_2
 ,0::NUMERIC(38,5) AS METRIC_VAL_3
 ,0::NUMERIC(38,5) AS METRIC_VAL_4
 ,FACT.CURR_CD
 ,FACT.CURR_GROUP_FG
 ,FACT.CURR_LOCAL_FG
FROM CTE_STATISTICS_BY_STORE_DAY_CASHIER FACT
INNER JOIN CTE_CASHIER_SCENARIO CASHIER
ON FACT.COUNTRY_ORG_CD = CASHIER.COUNTRY_ORG_CD
AND FACT.STORE_SID = CASHIER.STORE_SID
AND FACT.CASHIER_NR = CASHIER.CASHIER_NR
WHERE METRIC_VAL_1 <> 0   
AND CASHIER.SCENARIO_ID = 20
UNION ALL
SELECT 
    MAIN.STORE_SID
    ,CUST.BUS_DT
	,MAIN.CASHIER_NR
    ,40 AS SCENARIO_ID
    ,MAIN.COUNTRY_ORG_CD
    ,MAIN.CUST_SID
    ,4050 AS METRIC_ID
    ,'SUM' AS CALCULATION_TYPE_CD
    ,COALESCE(CUST.SALES_EVENT_CNT,0) + COALESCE(CUST.RETURN_EVENT_CNT,0)  AS SCENARIO_VALUE_1
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_2
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_3
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_4
	,CUST.CURR_CD
    ,CUST.CURR_GROUP_FG
    ,CUST.CURR_LOCAL_FG
FROM CTE_CASHIER_SCENARIO MAIN
INNER JOIN CTE_STORE_ANALYSIS_PERIOD STO
ON MAIN.COUNTRY_ORG_CD = STO.COUNTRY_ORG_CD
AND MAIN.STORE_SID = STO.STORE_SID
INNER JOIN CTE_CUSTOMER_DAY_COUNTRY CUST
ON MAIN.CUST_SID = CUST.CUST_SID
AND MAIN.COUNTRY_ORG_CD = CUST.COUNTRY_ORG_CD
AND CUST.BUS_DT BETWEEN STO.ANALYSIS_PERIOD_START_DT AND STO.ANALYSIS_PERIOD_END_DT
WHERE MAIN.SCENARIO_ID = 20
UNION ALL
SELECT 
    MAIN.STORE_SID
    ,MAIN.BUS_DT
	,MAIN.CASHIER_NR
    ,MAIN.SCENARIO_ID
    ,MAIN.COUNTRY_ORG_CD
    ,MAIN.CUST_SID
    ,DECODE(M.METRIC_ID,2010,-100,M.METRIC_ID)
    ,M.CALCULATION_TYPE_CD AS CALCULATION_TYPE_CD
    ,CASE WHEN  M.METRIC_ID IN (2010,2100,2200,3200)  THEN MAIN.CASH_REGISTER_EVENT_AFFECTED_NET_VAL 
          WHEN  M.METRIC_ID = 4005  THEN MAIN.CUST_SID_DST_CNT  
          ELSE MAIN.CASH_REGISTER_EVENT_CNT END  AS SCENARIO_VALUE_1
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_2
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_3
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_4
	,MAIN.CURR_CD
    ,MAIN.CURR_GROUP_FG
    ,MAIN.CURR_LOCAL_FG
FROM CTE_CASH_REGISTER_EVENT_CLASSIFICATION MAIN 
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 S
ON S.SCENARIO_ID = MAIN.SCENARIO_ID
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_1 M
ON S.SCENARIO_ID = M.SCENARIO_ID
WHERE  M.METRIC_ID IN (2000,200100)
UNION ALL
SELECT 
    CASHIER.STORE_SID
    ,STORE_FACT.BUS_DT
	,CASHIER.CASHIER_NR
    ,CASHIER.SCENARIO_ID
    ,CASHIER.COUNTRY_ORG_CD
    ,CASHIER.CUST_SID
    ,CASHIER.METRIC_ID
    ,CASHIER.CALCULATION_TYPE_CD AS CALCULATION_TYPE_CD
    ,CASHIER_FACT.CASH_REGISTER_EVENT_CNT AS SCENARIO_VALUE_1
    ,STORE_FACT.CASH_REGISTER_EVENT_CNT AS SCENARIO_VALUE_2
    ,1::NUMERIC(38,5) AS SCENARIO_VALUE_3
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_4
	,STORE_FACT.CURR_CD
    ,STORE_FACT.CURR_GROUP_FG
    ,STORE_FACT.CURR_LOCAL_FG
FROM 
( 
	SELECT 
	FACT.STORE_SID
	,FACT.CASHIER_NR
	,FACT.SCENARIO_ID 
	,FACT.COUNTRY_ORG_CD
    ,FACT.CUST_SID
    ,M.METRIC_ID
    ,M.CALCULATION_TYPE_CD AS CALCULATION_TYPE_CD
  	FROM CTE_CASHIER_SCENARIO FACT
    INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 S
     ON S.SCENARIO_ID = FACT.SCENARIO_ID
    INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_1 M
     ON S.SCENARIO_ID = M.SCENARIO_ID
   WHERE S.SCENARIO_TYPE_CD = 'AUTO' 
   AND M.CALCULATION_TYPE_CD = 'LEVELAVG'
 ) CASHIER
 LEFT JOIN 
(
SELECT 
    MAIN.STORE_SID
    ,MAIN.BUS_DT
    ,MAIN.SCENARIO_ID
    ,MAIN.COUNTRY_ORG_CD
    ,MAIN.CUST_SID
    ,M.METRIC_ID
    ,SUM(COALESCE(MAIN.SALES_EVENT_CNT,0) + COALESCE(MAIN.RETURN_EVENT_CNT,0)) AS CASH_REGISTER_EVENT_CNT
    ,MAIN.CURR_CD
    ,MAIN.CURR_GROUP_FG
    ,MAIN.CURR_LOCAL_FG
FROM CTE_CUSTOMER_DAY_STORE MAIN 
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 S
ON S.SCENARIO_ID = MAIN.SCENARIO_ID
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_1 M
ON S.SCENARIO_ID = M.SCENARIO_ID
WHERE S.SCENARIO_TYPE_CD = 'AUTO'
AND M.CALCULATION_TYPE_CD = 'LEVELAVG'
GROUP BY 
	MAIN.STORE_SID
    ,MAIN.BUS_DT
    ,MAIN.SCENARIO_ID
    ,MAIN.COUNTRY_ORG_CD
    ,MAIN.CUST_SID
    ,M.METRIC_ID
    ,MAIN.CURR_CD
    ,MAIN.CURR_GROUP_FG
    ,MAIN.CURR_LOCAL_FG
) STORE_FACT
ON CASHIER.STORE_SID = STORE_FACT.STORE_SID
AND CASHIER.METRIC_ID = STORE_FACT.METRIC_ID 
AND CASHIER.CUST_SID  =  STORE_FACT.CUST_SID
LEFT JOIN 
(
SELECT 
    MAIN.STORE_SID
    ,MAIN.CASHIER_NR
    ,MAIN.BUS_DT
    ,MAIN.SCENARIO_ID
    ,MAIN.COUNTRY_ORG_CD
    ,MAIN.CUST_SID
    ,M.METRIC_ID
    ,MAIN.CASH_REGISTER_EVENT_CNT AS CASH_REGISTER_EVENT_CNT
    ,MAIN.CURR_CD
    ,MAIN.CURR_GROUP_FG
    ,MAIN.CURR_LOCAL_FG
FROM CTE_CASH_REGISTER_EVENT_CLASSIFICATION MAIN 
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_1 S
ON S.SCENARIO_ID = MAIN.SCENARIO_ID
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_1 M
ON S.SCENARIO_ID = M.SCENARIO_ID
WHERE S.SCENARIO_TYPE_CD = 'AUTO'
AND M.CALCULATION_TYPE_CD = 'LEVELAVG'
) CASHIER_FACT
ON CASHIER.CASHIER_NR = CASHIER_FACT.CASHIER_NR
AND STORE_FACT.STORE_SID = CASHIER_FACT.STORE_SID
AND STORE_FACT.METRIC_ID = CASHIER_FACT.METRIC_ID
AND STORE_FACT.BUS_DT = CASHIER_FACT.BUS_DT
AND STORE_FACT.CURR_CD = CASHIER_FACT.CURR_CD 
AND STORE_FACT.CUST_SID  =  CASHIER_FACT.CUST_SID;