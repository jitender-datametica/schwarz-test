create or replace view LDL_DATA_PRODUCTION.FE_MSTR_APP_FRAUD_DETECTION.V_FRAUD_DETECTION_ORDER_BY_STORE_ACT_YEAR_1(
	STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE INTERNAL ORGANIZATION.',
	REVISION_FG_CNT COMMENT 'NUMBER OF AUDITING HAPPENED FOR THE SALES_1 COMPANY',
	ACTIVE_ANALYSIS_FG COMMENT 'CURRENTLY REQUIRED OR NOT'
) COMMENT='THE COMPLETED OR RUNNING ANALYSIS FOR THE CURRENT YEAR'
 as SELECT 
ORG.INT_ORG_SID   AS   STORE_SID, 
SUM(DECODE(ORD_PARAM.INT_ORG_SID,ORG.INT_ORG_SID,1,0))   AS   REVISION_FG_CNT, 
MAX(DECODE(ORD_PARAM.ORDER_PARAMETER_STATUS_CD,'RV',1,0))   AS   ACTIVE_ANALYSIS_FG
FROM CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1 ORG
LEFT JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_ORDER_1 ORD_PARAM
ON  ORG.INT_ORG_SID = ORD_PARAM.INT_ORG_SID
AND YEAR(ORD_PARAM.AUDIT_TMSP)= YEAR(CURRENT_DATE())
AND ORD_PARAM.ORDER_PARAMETER_STATUS_CD IN ('RV','END')
WHERE ORG.INT_ORG_TYPE_CD = 'STORE'
AND ORG.DWH_VALID_FG
GROUP BY 
ORG.INT_ORG_SID;