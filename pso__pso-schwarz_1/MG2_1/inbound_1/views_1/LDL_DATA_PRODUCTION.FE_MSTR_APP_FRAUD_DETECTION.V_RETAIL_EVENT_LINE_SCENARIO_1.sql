create or replace view LDL_DATA_PRODUCTION.FE_MSTR_APP_FRAUD_DETECTION.V_RETAIL_EVENT_LINE_SCENARIO_1(
	RETAIL_EVENT_LINE_SCENARIO_ID COMMENT 'The numeric identifier for the scenario which is represented by the retail event line.',
	LANG_CD COMMENT 'The code identifying the language.',
	RETAIL_EVENT_LINE_SCENARIO_NAME COMMENT 'The name of the business scenario which is represented by the retail event line.',
	RETAIL_EVENT_LINE_SCENARIO_SHORT_NAME COMMENT 'The short name of the business scenario which is represented by the retail event line.',
	RETAIL_EVENT_LINE_SCENARIO_DESCR COMMENT 'A textual description of the conditions which determine the business scenario.',
	DWH_CREATED_TMSP COMMENT 'The point in time when this record was created in the data warehouse.',
	DWH_UPDATED_TMSP COMMENT 'The point in time when this record was created or last updated.',
	DWH_LOAD_ID COMMENT 'The unique identifier of the batch load which has done the last update to this record. (Closing a record in history without updating any payload columns does not trigger an update of the dwh_load_id.)',
	DWH_NODE_CD COMMENT 'The code for the source system (or slice of source system) from which this record was loaded.'
) as
SELECT
MAIN.RETAIL_EVENT_LINE_SCENARIO_ID
,MAIN.LANG_CD
,MAIN.RETAIL_EVENT_LINE_SCENARIO_NAME
,MAIN.RETAIL_EVENT_LINE_SCENARIO_SHORT_NAME
,MAIN.RETAIL_EVENT_LINE_SCENARIO_DESCR
,MAIN.DWH_CREATED_TMSP
,MAIN.DWH_UPDATED_TMSP
,MAIN.DWH_LOAD_ID
,MAIN.DWH_NODE_CD
FROM CORE_REL.T_RETAIL_EVENT_LINE_SCENARIO_1 MAIN
WHERE MAIN.LANG_CD = 'DE'
AND MAIN.RETAIL_EVENT_LINE_SCENARIO_ID NOT IN ( 
		SELECT
			CRE.TECH_CASH_REGISTER_EVENT_TYPE_CD
		  FROM CORE_REL.T_TECHNICAL_CASH_REGISTER_EVENT_TYPE_1 CRE
		WHERE CRE.LANG_CD = 'DE'
		UNION ALL
		SELECT
			RES.RETAIL_EVENT_SCENARIO_ID
		FROM CORE_REL.T_RETAIL_EVENT_SCENARIO_1 RES
		WHERE RES.LANG_CD = 'DE' 
		)
UNION ALL 
SELECT
MAIN.TECH_CASH_REGISTER_EVENT_TYPE_CD
,MAIN.LANG_CD
,MAIN.TECH_CASH_REGISTER_EVENT_TYPE_DESCR
,MAIN.TECH_CASH_REGISTER_EVENT_TYPE_DESCR
,MAIN.TECH_CASH_REGISTER_EVENT_TYPE_DESCR
,MAIN.DWH_CREATED_TMSP
,MAIN.DWH_UPDATED_TMSP
,MAIN.DWH_LOAD_ID
,MAIN.DWH_NODE_CD
FROM CORE_REL.T_TECHNICAL_CASH_REGISTER_EVENT_TYPE_1 MAIN
WHERE MAIN.LANG_CD = 'DE'
UNION ALL
SELECT
MAIN.RETAIL_EVENT_SCENARIO_ID
,MAIN.LANG_CD
,MAIN.RETAIL_EVENT_SCENARIO_NAME
,MAIN.RETAIL_EVENT_SCENARIO_NAME
,MAIN.RETAIL_EVENT_SCENARIO_DESCR
,MAIN.DWH_CREATED_TMSP
,MAIN.DWH_UPDATED_TMSP
,MAIN.DWH_LOAD_ID
,MAIN.DWH_NODE_CD
FROM CORE_REL.T_RETAIL_EVENT_SCENARIO_1 MAIN
WHERE MAIN.LANG_CD = 'DE' ;