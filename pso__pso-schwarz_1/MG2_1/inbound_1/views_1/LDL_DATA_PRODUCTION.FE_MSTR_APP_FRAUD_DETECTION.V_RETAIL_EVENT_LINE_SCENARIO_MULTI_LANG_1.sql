create or replace view LDL_DATA_PRODUCTION.FE_MSTR_APP_FRAUD_DETECTION.V_RETAIL_EVENT_LINE_SCENARIO_MULTI_LANG_1(
	COUNTRY_ORG_SID COMMENT 'THE IDENTIFIER FOR THE ORGANIZATION COUNTRY_1',
	RETAIL_EVENT_LINE_SCENARIO_ID COMMENT 'THE NUMERIC IDENTIFIER FOR THE SCENARIO WHICH IS REPRESENTED BY THE RETAIL EVENT LINE.',
	LANG_CD COMMENT 'THE CODE IDENTIFYING THE LANGUAGE.',
	RETAIL_EVENT_LINE_SCENARIO_NAME COMMENT 'THE NAME OF THE BUSINESS SCENARIO WHICH IS REPRESENTED BY THE RETAIL EVENT LINE.',
	RETAIL_EVENT_LINE_SCENARIO_SHORT_NAME COMMENT 'THE NAME OF THE BUSINESS SCENARIO WHICH IS REPRESENTED BY THE RETAIL EVENT LINE.',
	RETAIL_EVENT_LINE_SCENARIO_DESCR COMMENT 'A TEXTUAL DESCRIPTION OF THE CONDITIONS WHICH DETERMINE THE BUSINESS SCENARIO.',
	DWH_CREATED_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS CREATED IN THE DATA WAREHOUSE.',
	DWH_UPDATED_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS CREATED OR LAST UPDATED.',
	DWH_LOAD_ID COMMENT 'THE UNIQUE IDENTIFIER OF THE BATCH LOAD WHICH HAS DONE THE LAST UPDATE TO THIS RECORD. (CLOSING A RECORD IN HISTORY WITHOUT UPDATING ANY PAYLOAD COLUMNS DOES NOT TRIGGER AN UPDATE OF THE DWH_LOAD_ID.)',
	DWH_NODE_CD COMMENT 'THE CODE FOR THE SOURCE SYSTEM (OR SLICE OF SOURCE SYSTEM) FROM WHICH THIS RECORD WAS LOADED.'
) as

WITH ALLSCENARIOIDS AS (
    SELECT RETAIL_EVENT_LINE_SCENARIO_ID FROM CORE_REL.T_RETAIL_EVENT_LINE_SCENARIO_1
    UNION
    SELECT TECH_CASH_REGISTER_EVENT_TYPE_CD FROM CORE_REL.T_TECHNICAL_CASH_REGISTER_EVENT_TYPE_1
    UNION
    SELECT RETAIL_EVENT_SCENARIO_ID FROM CORE_REL.T_RETAIL_EVENT_SCENARIO_1
),


TARGETCOUNTRIES AS (
    SELECT INT_ORG_SID, OFFICIAL_LANG_CD
    FROM CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_1
    WHERE IS_COUNTRY_ORG_FG AND DWH_VALID_FG
),


ALLTRANSLATIONS AS (
    SELECT
        SCENARIO_ID,
        LANG_CD,
        SCENARIO_NAME,
        SCENARIO_SHORT_NAME,
        SCENARIO_DESCR,
        DWH_CREATED_TMSP,
        DWH_UPDATED_TMSP,
        DWH_LOAD_ID,
        DWH_NODE_CD
    FROM (
        SELECT
            SCENARIO_ID, LANG_CD, SCENARIO_NAME, SCENARIO_SHORT_NAME, SCENARIO_DESCR,
            DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_LOAD_ID, DWH_NODE_CD,
            
            ROW_NUMBER() OVER(PARTITION BY SCENARIO_ID, LANG_CD ORDER BY SOURCE_PRIORITY ASC) AS RN
        FROM (
            
            SELECT
                RETAIL_EVENT_LINE_SCENARIO_ID AS SCENARIO_ID, LANG_CD, RETAIL_EVENT_LINE_SCENARIO_NAME AS SCENARIO_NAME,
                RETAIL_EVENT_LINE_SCENARIO_SHORT_NAME AS SCENARIO_SHORT_NAME, RETAIL_EVENT_LINE_SCENARIO_DESCR AS SCENARIO_DESCR,
                DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_LOAD_ID, DWH_NODE_CD, 1 AS SOURCE_PRIORITY
            FROM CORE_REL.T_RETAIL_EVENT_LINE_SCENARIO_1

            UNION ALL

            
            SELECT
                TECH_CASH_REGISTER_EVENT_TYPE_CD, LANG_CD, TECH_CASH_REGISTER_EVENT_TYPE_DESCR,
                TECH_CASH_REGISTER_EVENT_TYPE_DESCR, TECH_CASH_REGISTER_EVENT_TYPE_DESCR,
                DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_LOAD_ID, DWH_NODE_CD, 2 AS SOURCE_PRIORITY
            FROM CORE_REL.T_TECHNICAL_CASH_REGISTER_EVENT_TYPE_1

            UNION ALL

            
            SELECT
                RETAIL_EVENT_SCENARIO_ID, LANG_CD, RETAIL_EVENT_SCENARIO_NAME,
                RETAIL_EVENT_SCENARIO_NAME, RETAIL_EVENT_SCENARIO_DESCR,
                DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_LOAD_ID, DWH_NODE_CD, 3 AS SOURCE_PRIORITY
            FROM CORE_REL.T_RETAIL_EVENT_SCENARIO_1
        ) ALL_SOURCES
    ) RANKED_TRANSLATIONS
    WHERE RN = 1 
)

SELECT
    TC.INT_ORG_SID,
    S.RETAIL_EVENT_LINE_SCENARIO_ID,
    TC.OFFICIAL_LANG_CD,
    COALESCE(SPECIFIC_LANG.SCENARIO_NAME, DEFAULT_LANG.SCENARIO_NAME) AS RETAIL_EVENT_LINE_SCENARIO_NAME,
    COALESCE(SPECIFIC_LANG.SCENARIO_SHORT_NAME, DEFAULT_LANG.SCENARIO_SHORT_NAME) AS RETAIL_EVENT_LINE_SCENARIO_SHORT_NAME,
    COALESCE(SPECIFIC_LANG.SCENARIO_DESCR, DEFAULT_LANG.SCENARIO_DESCR) AS RETAIL_EVENT_LINE_SCENARIO_DESCR,
    DEFAULT_LANG.DWH_CREATED_TMSP,
    DEFAULT_LANG.DWH_UPDATED_TMSP,
    DEFAULT_LANG.DWH_LOAD_ID,
    DEFAULT_LANG.DWH_NODE_CD
FROM
    ALLSCENARIOIDS S
    CROSS JOIN TARGETCOUNTRIES TC
    LEFT JOIN ALLTRANSLATIONS SPECIFIC_LANG
        ON S.RETAIL_EVENT_LINE_SCENARIO_ID = SPECIFIC_LANG.SCENARIO_ID
        AND TC.OFFICIAL_LANG_CD = SPECIFIC_LANG.LANG_CD
    LEFT JOIN ALLTRANSLATIONS DEFAULT_LANG
        ON S.RETAIL_EVENT_LINE_SCENARIO_ID = DEFAULT_LANG.SCENARIO_ID
        AND DEFAULT_LANG.LANG_CD = 'DE';