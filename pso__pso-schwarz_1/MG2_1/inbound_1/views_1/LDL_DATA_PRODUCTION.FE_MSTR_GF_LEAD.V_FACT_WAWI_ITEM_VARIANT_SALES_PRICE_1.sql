create or replace view LDL_DATA_PRODUCTION.FE_MSTR_GF_LEAD.V_FACT_WAWI_ITEM_VARIANT_SALES_PRICE_1(
	INT_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE INTERNAL ORGANIZATION.',
	INT_ORG_TYPE_CD COMMENT 'THE CODE IDENTIFYING THE DISCRIMINATORS FOR INTERNAL ORGANIZATIONS.',
	COUNTRY_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE COUNTRY_1 ORGANIZATION.',
	COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_1 FOR WHICH THE RELATED COUNTRY_1 ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY_1 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	WAWI_ITEM_VARIANT_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) OF THE WAWI ITEM_1 VARIANT.',
	WAWI_ITEM_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) OF THE WAWI ITEM.',
	DWH_VALID_FROM_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD BECAME VALID.',
	DWH_VALID_TO_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS NO LONGER VALID.',
	DWH_VALID_FG COMMENT 'AN INDICATOR SHOWING THE CURRENT RECORD, I.E. WHERE THE CURRENT DATE IS BETWEEN DWH_VALID_FROM AND DWH_VALID_TO.',
	SALES_NET_PRICE COMMENT 'THE NET PRICE (I.E. EXCLUDING VAT) FOR WHICH PRODUCTS THAT ARE RELATED TO THE WAWI ITEM_1 VARIANT ARE SOLD IN THE GIVEN STORE OR WAREHOUSE.',
	SALES_GROSS_PRICE COMMENT 'THE GROSS PRICE (I.E. INCLUDING VAT) FOR WHICH PRODUCTS THAT ARE RELATED TO THE WAWI ITEM_1 VARIANT ARE SOLD IN THE GIVEN STORE OR WAREHOUSE.',
	DEPOSIT_VAL COMMENT 'THE DEPOSIT AMOUNT FOR THIS WAWI ITEM_1 VARIANT. E.G. 25C FOR A PLASTIC BOTTLE. (THIS ATTRIBUTE IS ONLY FILLED, IF THERE IS A DEPOSIT.)',
	TAX_PCT COMMENT 'THE ACTUAL TAX PERCENTAGE WHICH IS APPLICABLE FOR THE WAWI ITEM_1 VARIANT IN THE GIVEN STORE OR WAREHOUSE. (IN CASE SEVERAL TAXES APPLY, THIS IS THE TOTAL TAX PERCENTAGE.)',
	CURR_CD COMMENT 'THE CODE IDENTIFYING THE CURRENCY ACCORDING TO ISO-4217.',
	DWH_CREATED_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS CREATED IN THE DATA WAREHOUSE.',
	DWH_UPDATED_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS CREATED OR LAST UPDATED.',
	DWH_LOAD_ID COMMENT 'THE UNIQUE IDENTIFIER OF THE BATCH LOAD WHICH HAS DONE THE LAST UPDATE TO THIS RECORD. (CLOSING A RECORD IN HISTORY WITHOUT UPDATING ANY PAYLOAD COLUMNS DOES NOT TRIGGER AN UPDATE OF THE DWH_LOAD_ID.)',
	DWH_NODE_CD COMMENT 'THE CODE FOR THE SOURCE SYSTEM (OR SLICE OF SOURCE SYSTEM) FROM WHICH THIS RECORD WAS LOADED.'
) as SELECT 
MAIN.INT_ORG_SID
,MAIN.INT_ORG_TYPE_CD
,MAIN.COUNTRY_ORG_SID
,MAIN.COUNTRY_ORG_CD
,MAIN.WAWI_ITEM_VARIANT_SID
,MAIN.WAWI_ITEM_SID
,MAIN.DWH_VALID_FROM_TMSP
,MAIN.DWH_VALID_TO_TMSP
,MAIN.DWH_VALID_FG
,MAIN.SALES_NET_PRICE/FER.EXCHANGE_RATE AS SALES_NET_PRICE 
,MAIN.SALES_GROSS_PRICE/FER.EXCHANGE_RATE AS SALES_GROSS_PRICE
,MAIN.DEPOSIT_VAL/FER.EXCHANGE_RATE  AS DEPOSIT_VAL
,MAIN.TAX_PCT
,MAIN.CURR_CD
,MAIN.DWH_CREATED_TMSP
,MAIN.DWH_UPDATED_TMSP
,MAIN.DWH_LOAD_ID
,MAIN.DWH_NODE_CD
FROM CORE_DIM.T_FACT_WAWI_ITEM_VARIANT_SALES_PRICE_1 AS MAIN
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 FER
ON MAIN.CURR_CD = FER.TGT_CURR_CD
WHERE EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
AND FER.ACTIVE_FG = TRUE;