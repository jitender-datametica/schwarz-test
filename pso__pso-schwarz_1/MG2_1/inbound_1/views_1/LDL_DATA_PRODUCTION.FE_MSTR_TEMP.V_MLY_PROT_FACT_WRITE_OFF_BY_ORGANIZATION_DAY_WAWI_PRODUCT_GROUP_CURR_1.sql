create or replace view LDL_DATA_PRODUCTION.FE_MSTR_TEMP.V_MLY_PROT_FACT_WRITE_OFF_BY_ORGANIZATION_DAY_WAWI_PRODUCT_GROUP_CURR_1(
	CAL_DT,
	STORE_SID,
	INT_ORG_TYPE_CD,
	COUNTRY_ORG_SID,
	COUNTRY_ORG_CD,
	WAWI_VARIANT_SID,
	WAWI_PRODUCT_SID,
	WRITE_OFF_FOR_BREAKAGE_NET_VAL,
	WRITE_OFF_FOR_SELL_BY_DT_NET_VAL,
	WRITE_OFF_FOR_DELIV_QUALITY_NET_VAL,
	WRITE_OFF_FOR_DEFECTIVE_NON_FOOD_NET_VAL,
	WRITE_OFF_FOR_DONATIONS_NET_VAL,
	WRITE_OFF_FOR_TAKEN_PROD_NET_VAL,
	WRITE_OFF_FOR_DISCOUNTS_NET_VAL,
	DWH_CREATED_TMSP,
	DWH_UPDATED_TMSP,
	DWH_LOAD_ID,
	DWH_NODE_CD,
	WRITE_OFF_NET_VAL,
	WRITE_OFF_FOR_FORCE_MAJEURE_NET_VAL,
	WRITE_OFF_FOR_STOCK_CLEARANCE_NET_VAL,
	CURR_CD,
	CURR_GROUP_FG,
	LOCAL_GROUP_FG
) as 
SELECT
main.BUS_DT
,main.INT_ORG_SID
,main.INT_ORG_TYPE_CD
,main.COUNTRY_ORG_SID
,main.COUNTRY_ORG_CD
,main.WAWI_VARIANT_SID
,main.WAWI_PRODUCT_SID
,main.WRITE_OFF_FOR_BREAKAGE_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_SELL_BY_DT_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_DELIV_QUALITY_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_DEFECTIVE_NON_FOOD_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_DONATIONS_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_TAKEN_PROD_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_DISCOUNTS_NET_VAL/fer.exchange_rate
,main.DWH_CREATED_TMSP
,main.DWH_UPDATED_TMSP
,main.DWH_LOAD_ID
,main.DWH_NODE_CD
,main.WRITE_OFF_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_FORCE_MAJEURE_NET_VAL/fer.exchange_rate
,main.WRITE_OFF_FOR_STOCK_CLEARANCE_NET_VAL/fer.exchange_rate
,fer.src_curr_cd AS curr_cd
,DECODE(fer.src_curr_cd,'EUR',1,0) AS curr_group_fg
,DECODE(fer.src_curr_cd,fer.tgt_curr_cd,1,0) AS curr_local_fg
FROM  FE_MSTR_TEMP.T_MLY_PROT_FACT_WRITE_OFF_BY_ORGANIZATION_DAY_WAWI_PRODUCT_1 main
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_1 fer
ON main.curr_cd = fer.tgt_curr_cd
WHERE exchange_rate_type_cd = 'BEW_ISK'
AND (fer.src_curr_cd = 'EUR')
AND fer.active_fg = TRUE ;
;