create or replace view LDL_DATA_PRODUCTION.POLICIES.V_SEC_RAP_HIERARCHY_INT_ORG_SID_1(
	NAME,
	INT_ORG_SID
) COMMENT='SECURITY VIEW FOR THE ORGANIZATIONAL HIERARCHY_1 TABLE BASED ON THE INT_ORG_SID COLUMN'
 as
    SELECT DISTINCT 
         ROLE_NAME AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_CORE_ISO_COUNTRY_CD_1 COUNTRY_1
    LEFT JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON COUNTRY.ISO_COUNTRY_CD = HIERARCHY.ISO_COUNTRY_CD
    
    UNION ALL

    SELECT DISTINCT
         ROLE_NAME AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_CORE_SALES_COMPANY_NR_1 POS
    LEFT JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON POS.SALES_COMPANY_NR = HIERARCHY.SALES_COMPANY_NR
   
    UNION ALL
    
    SELECT DISTINCT 
         LOGIN_NAME_EMAIL AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_ACCOUNTMANAGER_1 ACCTMNGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON ACCTMNGR.ACCT_MGR_DISTRICT_SID = HIERARCHY.ACCT_MGR_DISTRICT_SID
   
    UNION ALL
    
    SELECT 
         LOGIN_NAME_EMAIL AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR
    FROM POLICIES.T_SEC_RAP_SALESMANAGER_1 SLSMNGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON SLSMNGR.SALES_MGR_DISTRICT_SID = HIERARCHY.SALES_MGR_DISTRICT_SID
    ;