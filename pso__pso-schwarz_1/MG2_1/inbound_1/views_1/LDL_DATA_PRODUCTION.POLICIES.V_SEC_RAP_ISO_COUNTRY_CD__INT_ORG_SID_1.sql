create or replace view LDL_DATA_PRODUCTION.POLICIES.V_SEC_RAP_ISO_COUNTRY_CD__INT_ORG_SID_1(
	NAME,
	ISO_COUNTRY_CD,
	INT_ORG_SID
) as

    SELECT DISTINCT
         
         COUNTRY.ROLE_NAME::VARCHAR AS NAME
        ,COUNTRY.ISO_COUNTRY_CD::VARCHAR AS ISO_COUNTRY_CD
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_CORE_ISO_COUNTRY_CD_1 COUNTRY_1
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON HIERARCHY.ISO_COUNTRY_CD = COUNTRY.ISO_COUNTRY_CD
  
    UNION ALL

    SELECT DISTINCT
         COMPANY.ROLE_NAME::VARCHAR AS NAME
        ,HIERARCHY.ISO_COUNTRY_CD::VARCHAR AS ISO_COUNTRY_CD
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_CORE_SALES_COMPANY_NR_1 COMPANY 
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON HIERARCHY.SALES_COMPANY_NR = COMPANY.SALES_COMPANY_NR

    UNION ALL

    SELECT DISTINCT 
         ACCTMGR.LOGIN_NAME_EMAIL::VARCHAR AS NAME
        ,ACCTMGR.ISO_COUNTRY_CD::VARCHAR AS ISO_COUNTRY_CD
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_ACCOUNTMANAGER_1 ACCTMGR
    LEFT OUTER JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 ON ACCTMGR.ACCT_MGR_DISTRICT_NR = HIERARCHY.ACCT_MGR_DISTRICT_NR

    UNION ALL

    SELECT DISTINCT
         SLSMGR.LOGIN_NAME_EMAIL::VARCHAR AS NAME
        ,SLSMGR.ISO_COUNTRY_CD::VARCHAR AS COUNTRY_VALUE
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_SALESMANAGER_1 SLSMGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_1 HIERARCHY_1 
        ON SLSMGR.SALES_MGR_DISTRICT_SID = HIERARCHY.SALES_MGR_DISTRICT_SID
    WHERE HIERARCHY.INT_ORG_TYPE_CD = 'STORE'
;