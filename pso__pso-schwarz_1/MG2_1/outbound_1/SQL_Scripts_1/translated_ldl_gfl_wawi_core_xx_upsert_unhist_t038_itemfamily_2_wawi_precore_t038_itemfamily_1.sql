TRUNCATE TABLE LDL_DATA_PRODUCTION.PO_PREFIX_TARGET_DB_PO_SUFFIX.PO_PREFIX_TGT_TARGET_TABLE_PO_SUFFIX;
INSERT INTO LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC2TGT_TEMP_TABLE1_PO_SUFFIX_PO_PREFIX_SRC_CONTEXT_AREA_PO_SUFFIX (CTRCODE, EXTRACTION_TMSP, FAMILY_ID, ITEMGRPNR, PRODGRPNR, FAMILY_CODE, DESC_LONG, DESC_SHORT, MOD_DATE, MOD_USER, MMO_CALCULATION_FLAG, PST_PRINT_FLAG, MMO_MODIFY_FLAG, SCN, SOURCE_SYSTEM, EXTRACTION_DT, DWH_MAPPING_TMSP, TF_ERROR_FG, DELETED_FG, RECORD_ID, FILENAME, DWH_NODE_CD, DWH_LOAD_ID)
  SELECT
      --
      left(SRC.CTRCODE, 2) AS CTRCODE,
      SRC.EXTRACTION_TMSP,
      SRC.C038_FAMILY_ID,
      SRC.C038_ITEMGRPNR,
      SRC.C038_PRODGRPNR,
      SRC.C038_FAMILY_CODE,
      SRC.C038_DESC_LONG,
      SRC.C038_DESC_SHORT,
      SRC.C038_MOD_DATE,
      SRC.C038_MOD_USER,
      SRC.C038_MMO_CALCULATION_FLAG,
      SRC.C038_PST_PRINT_FLAG,
      SRC.C038_MMO_MODIFY_FLAG,
      SRC.SCN,
      --
      'WAWI' AS SOURCE_SYSTEM,
      current_date() AS EXTRACTION_DT,
      current_timestamp() AS DWH_MAPPING_TMSP,
      NUMERIC '0' AS TF_ERROR_FG,
      NUMERIC '0' AS DELETED_FG,
      NUMERIC '0' AS RECORD_ID,
      'po_prefix_SRC_INPUT_TABLE_po_suffix' AS FILENAME,
      'WAWI' AS DWH_NODE_CD,
      'po_prefix_LOAD_ID_po_suffix' AS DWH_LOAD_ID
    FROM
      LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX AS SRC
      INNER JOIN LDL_DATA_PRODUCTION.ETL.WAWI_CONTROL_TABLE_1 AS CTRL ON CTRL.SOURCE_TABLE_NAME = upper('LDL_DATA_PRODUCTION.po_prefix_TEMP_DB_po_suffix.po_prefix_SRC_INPUT_TABLE_po_suffix')
       AND CTRL.SOURCE_STATUS = 'A'
       AND SRC.EXTRACTION_TMSP BETWEEN CTRL.BEGIN_TMSP AND CTRL.END_TMSP
      INNER JOIN (
        SELECT
            A.CTRCODE,
            rank() OVER (ORDER BY if(CASE
              WHEN A.CTRCODE = 'DE' THEN NUMERIC '1'
              WHEN A.CTRCODE NOT IN(
                'BG', 'CY', 'GR'
              ) THEN NUMERIC '2'
              WHEN A.CTRCODE = 'GR' THEN NUMERIC '3'
              WHEN A.CTRCODE IN(
                'BG', 'CY'
              ) THEN NUMERIC '4'
            END IS NULL, 0, 1) DESC, CASE
              WHEN A.CTRCODE = 'DE' THEN NUMERIC '1'
              WHEN A.CTRCODE NOT IN(
                'BG', 'CY', 'GR'
              ) THEN NUMERIC '2'
              WHEN A.CTRCODE = 'GR' THEN NUMERIC '3'
              WHEN A.CTRCODE IN(
                'BG', 'CY'
              ) THEN NUMERIC '4'
            END, if(A.CTRCODE IS NULL, 0, 1) DESC, A.CTRCODE) AS EKS_RANK
          FROM
            (
              SELECT DISTINCT
                  PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX.CTRCODE
                FROM
                  LDL_DATA_PRODUCTION.PO_PREFIX_TEMP_DB_PO_SUFFIX.PO_PREFIX_SRC_INPUT_TABLE_PO_SUFFIX
            ) AS A
      ) AS CSRC ON SRC.CTRCODE = CSRC.CTRCODE
    QUALIFY CSRC.EKS_RANK = min(CSRC.EKS_RANK) OVER (PARTITION BY CTRCODE, SRC.C038_FAMILY_ID)
     AND row_number() OVER (PARTITION BY CTRCODE, SRC.C038_FAMILY_ID ORDER BY if(SRC.EXTRACTION_TMSP IS NULL, 0, 1), SRC.EXTRACTION_TMSP DESC) = NUMERIC '1'
;
