-- Apply the changes as INSERTs or UPDATES ignoring any unchanged rows.
MERGE INTO LDL_DATA_PRODUCTION.CORE_REL.T_PRICE_REASON_1 AS TARGET USING (
  SELECT DISTINCT
      PCWO.C815_REASON_ID AS PRICE_REASON_CD,
      -- pcwo.c815_reason_desc_int,
      PCWO.C815_REASON_DESC_NAT AS PRICE_REASON_DESCR,
      -- pcwo.ctrcode,
      C.OFFICIAL_LANG_CD AS LANG_CD
    FROM
      LDL_DATA_PRODUCTION.ETL.T_WAWI_PRECORE_T201_ITEMPRICES_HQ_1 AS HQ
      INNER JOIN LDL_DATA_PRODUCTION.ETL.T_WAWI_PRECORE_T815_PCWO_REASON_1 AS PCWO ON HQ.C201_REASON_ID = PCWO.C815_REASON_ID
      INNER JOIN LDL_DATA_PRODUCTION.CORE_REL.T_COUNTRY_1 AS C ON C.ISO_COUNTRY_CD = PCWO.CTRCODE
    WHERE PCWO.CTRCODE IN(
      'DE', 'GB', 'ES', 'FI', 'GR', 'SE', 'DK', 'BG', 'CZ', 'FR', 'HR', 'HU', 'IT', 'NL', 'PL', 'PT', 'RO', 'RS_1', 'SI', 'SK'
    ) /* take countries which are using local languages for Reason codes*/
) AS SOURCE
ON TARGET.PRICE_REASON_CD = SOURCE.PRICE_REASON_CD
 AND TARGET.LANG_CD = SOURCE.LANG_CD
   WHEN MATCHED THEN UPDATE SET
    PRICE_REASON_DESCR = SOURCE.PRICE_REASON_DESCR, 
    DWH_UPDATED_TMSP = current_timestamp(), 
    DWH_LOAD_ID = ${LOAD_ID}, 
    DWH_NODE_CD = 'WAWI'
   WHEN NOT MATCHED BY TARGET THEN
    INSERT (PRICE_REASON_CD, LANG_CD, PRICE_REASON_DESCR, DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_LOAD_ID, DWH_NODE_CD)
    VALUES (SOURCE.PRICE_REASON_CD, SOURCE.LANG_CD, SOURCE.PRICE_REASON_DESCR, current_timestamp(), current_timestamp(), SOURCE.${LOAD_ID}, 'WAWI')
;
