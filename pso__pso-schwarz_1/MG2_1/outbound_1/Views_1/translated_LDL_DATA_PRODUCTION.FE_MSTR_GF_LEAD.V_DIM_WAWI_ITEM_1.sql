 country_org_cd,
 wawi_item_nr,
 wawi_item_name,
 wawi_item_descr,
 wawi_item_creation_dt,
 wawi_item_status_cd,
 wawi_item_status_descr,
 item_fam_sid,
 item_fam_nr,
 item_fam_name,
 sub_item_grp_sid,
 sub_item_grp_nr,
 sub_item_grp_name,
 food_fg,
 int_item_grp_sid,
 int_item_grp_nr,
 int_item_grp_name,
 dwh_created_tmsp,
 dwh_updated_tmsp,
 dwh_load_id,
 dwh_node_cd
FROM ldl_data_production_core_dim.t_dim_wawi_item_1 AS main
