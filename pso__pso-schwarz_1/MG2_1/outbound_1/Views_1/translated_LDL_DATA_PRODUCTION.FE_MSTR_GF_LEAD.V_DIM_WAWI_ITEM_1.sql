wawi_item_creation_dt
OPTIONS(description='THE DATE WHEN THE ITEM_1 WAS CREATED IN THE OPERATIONAL SYSTEM (WAWI) OF THE GIVEN COUNTRY_1 ORGANIZATION. THIS IS THE CREATE DATE OF THE FIRST ITEM_1 VARIANT.'),
wawi_item_status_cd OPTIONS(description='THE CODE FOR THE LIFECYCLE STATUS_1 FOR WAWI ITEMS.'), wawi_item_status_descr
OPTIONS(description='A TEXTUAL DESCRIPTION FOR THE LIFECYCLE STATUS_1 FOR WAWI ITEMS. (DESCRIPTION IN GROUP LANGUAGE, I.E. IN GERMAN)'),
item_fam_sid
