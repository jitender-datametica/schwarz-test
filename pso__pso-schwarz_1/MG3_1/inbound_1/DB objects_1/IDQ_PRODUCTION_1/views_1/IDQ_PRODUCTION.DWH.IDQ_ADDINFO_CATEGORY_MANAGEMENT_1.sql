create or replace view IDQ_PRODUCTION.DWH.IDQ_ADDINFO_CATEGORY_MANAGEMENT_1(
	IDQ_ADDINFO_CATEGORY_MANAGEMENT_ID,
	IDQ_TEST_OBJECT_ID,
	REF_TEST_OBJECT_TYPE_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID,
	IS_RELEVANT,
	LAND_1,
	DATENLIEFERANT,
	PERIODE,
	JAHR,
	MONAT_NR,
	MONAT_1,
	WARENGRUPPE,
	RETAILER_TYPE,
	HAENDLER
) as

select 
	ADDI.ID 					AS IDQ_ADDINFO_CATEGORY_MANAGEMENT_ID,
	ITO.ID 					AS 	IDQ_TEST_OBJECT_ID,
	ITO.TEST_OBJECT_TYPE_ID 	AS REF_TEST_OBJECT_TYPE_ID,
	ADDI.SOURCE_SYSTEM_PRIMARY_KEY,
	ADDI.SOURCE_SYSTEM_ID 	AS REF_SOURCE_SYSTEM_ID,
	ADDI.COUNTRY_ID 			AS REF_COUNTRY_ID,
	ADDI.BRANCH_ID 			AS REF_BRANCH_ID,
	ITO.IS_RELEVANT,
	ADDI.LAND_1,
	ADDI.DATENLIEFERANT,
	ADDI.PERIODE,
    ADDI.Jahr,
    ADDI.Monat_Nr,
    ADDI.Monat_1,
	ADDI.WARENGRUPPE,
    ADDI.RETAILER_TYPE,
	ADDI.HAENDLER

FROM IDQ_RESULTS.IDQ_ADDINFO_CATEGORY_MANAGEMENT_1 ADDI
	INNER JOIN IDQ_RESULTS.IDQ_TEST_OBJECT_1 ITO
	  ON     ADDI.SOURCE_SYSTEM_PRIMARY_KEY = ITO.SOURCE_SYSTEM_PRIMARY_KEY
		 AND ADDI.SOURCE_SYSTEM_ID = ITO.SOURCE_SYSTEM_ID
		 AND ADDI.COUNTRY_ID = ITO.COUNTRY_ID
		 AND ADDI.BRANCH_ID = ITO.BRANCH_ID
	WHERE ITO.TEST_OBJECT_TYPE_ID in (493,494)
;