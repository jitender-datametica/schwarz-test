create or replace view IDQ_PRODUCTION.DWH.IDQ_TEST_OBJECT_1(
	IDQ_TEST_OBJECT_ID,
	REF_BRANCH_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	FUNCTIONAL_ID,
	REF_SOURCE_SYSTEM_ID,
	LDO_NUM,
	REF_COUNTRY_ID,
	NAME,
	REF_TEST_OBJECT_TYPE_ID,
	SOURCE_SYSTEM_STATUS,
	IS_RELEVANT,
	LAST_UPDATE,
	FIRST_UNSUCCESSFUL_LOAD,
	REF_TIME_FIRST_UNSUCCESSFUL_LOAD_DAY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	IDQ_TEST_OBJECT_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	PENALTY,
	SCORE,
	FIELD_AMOUNT,
	IS_USABLE
) as
SELECT ITO.ID                          		AS IDQ_TEST_OBJECT_ID
      ,ITO.BRANCH_ID					 		AS REF_BRANCH_ID
      ,ITO.SOURCE_SYSTEM_PRIMARY_KEY	 		AS SOURCE_SYSTEM_PRIMARY_KEY
	  ,case  																		--NEW COLUMN
			when ITO.FUNCTIONAL_ID is null 
			then ITO.SOURCE_SYSTEM_PRIMARY_KEY 
			else ITO.FUNCTIONAL_ID end 		AS FUNCTIONAL_ID
      ,ITO.SOURCE_SYSTEM_ID			 		AS REF_SOURCE_SYSTEM_ID
      ,ITO.LDO_NUM					 		AS LDO_NUM
      ,ITO.COUNTRY_ID					 		AS REF_COUNTRY_ID
      ,ITO.NAME						 		AS NAME
      ,ITO.TEST_OBJECT_TYPE_ID		 		AS REF_TEST_OBJECT_TYPE_ID
      ,ITO.SOURCE_SYSTEM_STATUS		 		AS SOURCE_SYSTEM_STATUS
      ,ITO.IS_RELEVANT				 		AS IS_RELEVANT
	  ,ITO.LAST_UPDATE						AS LAST_UPDATE					--NEW COLUMN
	  ,ITO.FIRST_UNSUCCESSFUL_LOAD     		AS FIRST_UNSUCCESSFUL_LOAD
	  ,ITO.FIRST_UNSUCCESSFUL_LOAD_DAY_ID     AS REF_TIME_FIRST_UNSUCCESSFUL_LOAD_DAY_ID
      ,RSS.SOURCE_SYSTEM_TYPE_ID		 		AS REF_SOURCE_SYSTEM_TYPE_ID
      ,CDTO.CALCULATION_TIME			 		AS IDQ_TEST_OBJECT_CALCULATION_TIME
	  ,CDTO.CALCULATION_DAY_ID   				AS REF_TIME_CALCULATION_DAY_ID
      ,CDTO.PENALTY					 		AS PENALTY
      ,CDTO.SCORE						 		AS SCORE
      ,CDTO.FIELD_AMOUNT				 		AS FIELD_AMOUNT
      ,CDTO.IS_USABLE					 		AS IS_USABLE
FROM idq_results.IDQ_TEST_OBJECT_1 ITO
INNER JOIN idq_results.REF_SOURCE_SYSTEM_1 RSS
  ON ITO.SOURCE_SYSTEM_ID = RSS.ID
LEFT JOIN idq_results.CHECK_DQ_BY_TEST_OBJECT_CURRENT_1 CDTO
  ON     ITO.ID = CDTO.TEST_OBJECT_ID 
;