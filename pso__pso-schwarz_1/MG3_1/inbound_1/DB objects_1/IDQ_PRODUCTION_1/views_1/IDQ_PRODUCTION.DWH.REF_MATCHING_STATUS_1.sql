create or replace view IDQ_PRODUCTION.DWH.REF_MATCHING_STATUS_1(
	REF_MATCHING_STATUS_ID,
	MATCHING_STATUS_TECHNICAL_NAME,
	MATCHING_STATUS_NAME,
	MATCHING_STATUS_NAME_DE,
	MATCHING_STATUS_NAME_EN
) as
SELECT ID                  AS REF_MATCHING_STATUS_ID
      ,MATCHING_STATUS     AS MATCHING_STATUS_TECHNICAL_NAME
      ,NAME_DE	 AS MATCHING_STATUS_NAME
      ,NAME_DE	 AS MATCHING_STATUS_NAME_DE
      ,NAME_EN	 AS MATCHING_STATUS_NAME_EN
FROM idq_results.REF_MATCHING_STATUS_1
;