create or replace view IDQ_PRODUCTION.DWH.REF_SCOPE_1(
	REF_SCOPE_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID,
	REF_TEST_OBJECT_TYPE_ID,
	CONTACT_EMAIL
) as
SELECT ID                        AS REF_SCOPE_ID
      ,SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
	  ,SOURCE_SYSTEM_ID     	   AS REF_SOURCE_SYSTEM_ID
      ,COUNTRY_ID                AS REF_COUNTRY_ID
      ,BRANCH_ID                 AS REF_BRANCH_ID
      ,TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
	  ,CONTACT_EMAIL			   AS CONTACT_EMAIL

FROM idq_results.REF_SCOPE_1 
;