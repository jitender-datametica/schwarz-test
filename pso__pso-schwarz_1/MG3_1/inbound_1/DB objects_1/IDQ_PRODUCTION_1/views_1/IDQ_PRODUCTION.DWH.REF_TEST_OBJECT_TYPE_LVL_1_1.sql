create or replace view IDQ_PRODUCTION.DWH.REF_TEST_OBJECT_TYPE_LVL_1_1(
	REF_TEST_OBJECT_TYPE_LEVEL_1_ID,
	TEST_OBJECT_TYPE,
	TEST_OBJECT_TYPE_EXTENDED_NAME,
	TEST_OBJECT_TYPE_EXTENDED_NAME_DE,
	TEST_OBJECT_TYPE_EXTENDED_NAME_EN,
	TEST_OBJECT_TYPE_EXTENDED_SORTING_ORDER,
	TEST_OBJECT_TYPE_EXTENDED_CHANGE_BY,
	TEST_OBJECT_TYPE_EXTENDED_LAST_CHANGE,
	TEST_OBJECT_TYPE_EXTENDED_FROM_DATE,
	TEST_OBJECT_TYPE_EXTENDED_TO_DATE
) as
	SELECT
        TOTE.ID                               				AS REF_TEST_OBJECT_TYPE_LEVEL_1_ID
        ,TOTE.TEST_OBJECT_TYPE                 				AS TEST_OBJECT_TYPE
        ,TOTE.NAME_DE                            				AS TEST_OBJECT_TYPE_EXTENDED_NAME
        ,TOTE.NAME_DE                             			AS TEST_OBJECT_TYPE_EXTENDED_NAME_DE
        ,TOTE.NAME_EN                             			AS TEST_OBJECT_TYPE_EXTENDED_NAME_EN
		,TOTE.SORTING_ORDER									AS TEST_OBJECT_TYPE_EXTENDED_SORTING_ORDER
        ,TOTE.CHANGE_BY                        				AS TEST_OBJECT_TYPE_EXTENDED_CHANGE_BY
        ,TOTE.LAST_CHANGE                        				AS TEST_OBJECT_TYPE_EXTENDED_LAST_CHANGE
        ,TOTE.FROM_DATE                         				AS TEST_OBJECT_TYPE_EXTENDED_FROM_DATE
        ,TOTE.TO_DATE                           		 		AS TEST_OBJECT_TYPE_EXTENDED_TO_DATE
	FROM idq_results.REF_TEST_OBJECT_TYPE_EXTENDED_1 TOTE
	WHERE TOTE.ID = TOTE.LEVEL_1_ID
;