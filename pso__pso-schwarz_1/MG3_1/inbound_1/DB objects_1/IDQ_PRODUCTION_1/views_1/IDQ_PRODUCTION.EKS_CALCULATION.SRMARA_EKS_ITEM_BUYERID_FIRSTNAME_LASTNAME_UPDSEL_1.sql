create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_BUYERID_FIRSTNAME_LASTNAME_UPDSEL_1(
	ITEMID,
	BUYERID,
	BUYERIDNEW,
	BUYERFIRSTNAME,
	BUYERFIRSTNAMENEW,
	BUYERLASTNAME,
	BUYERLASTNAMENEW
) as
SELECT Distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, 
        EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID, 
        EKS.EMPLOYEE.EMPLOYEEID AS BuyerIDNew, 
        EKS_CALCULATION.STMARA_EKS_ITEM.BuyerFirstName, 
        EKS.EMPLOYEE.FIRSTNAME AS BuyerFirstNameNew, 
                  EKS_CALCULATION.STMARA_EKS_ITEM.BuyerLastName, 
                  EKS.EMPLOYEE.LASTNAME AS BuyerLastNameNew
FROM     EKS_CALCULATION.STMARA_EKS_ITEM_1 INNER JOIN
                  EKS.ITEMBUYEREL_1 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMBUYEREL.ITEMID INNER JOIN
                  EKS.EMPLOYEE_1 ON EKS.ITEMBUYEREL.EMPLOYEEID = EKS.EMPLOYEE.EMPLOYEEID
WHERE  (CURRENT_DATE() BETWEEN EKS.ITEMBUYEREL.DATEFROM AND EKS.ITEMBUYEREL.DATEUNTIL)
QUALIFY ROW_NUMBER() OVER (PARTITION BY EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID ORDER BY BuyerIDNew desc) = 1;