create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_CONSTRUCTSKFROMEA_INSSEL_1(
	ZACTIVE,
	ITEMID,
	BITFLAG,
	EMPLOYEEID,
	ITEMGROUPTYPEID,
	ITEMNO,
	SHORTDESC_INT,
	SHORTDESC_NAT,
	DESCRIPTION_INT,
	DESCRIPTION_NAT,
	IN_USE,
	ZLEGACYMANDT,
	ZLEGACYMATNR,
	ZLEGACYMATKL,
	ZMATKL,
	ZBISMT,
	ZMEINS,
	ZZEINR,
	ZISVALIDBITFLAG,
	ZISIN_USE,
	ZISFOOD,
	ZISCURRENTCONTRACT,
	ZNEGOTIATINGCOUNTRY,
	ZARTICLETYPE,
	ZITEM_BA,
	ZSOURCE,
	CONSTRUCTED,
	TARGETSYSTEM,
	TARGETCLIENT,
	ZMTART,
	ZATTYP,
	ZTRAGR,
	ZBWSCL,
	ZVABME,
	ZBEGRU,
	ZMSTAE,
	ZMSTDE,
	ZTAKLV,
	ZINHME,
	ZINHAL,
	CONSTRUCTEDFROM,
	CR_LOCATIONID,
	ZLEGACYSATNR,
	ZVPREH,
	ZSKCASESIZE
) as
SELECT stMARA.zActive,
         EKS_CALCULATION.srMARA_EKS_ITEM_zSKCaseSizeForEA.ItemPrefix
         || (REPEAT('0', 7 - length((CAST(stMARA.ITEMID as VARCHAR(255)))))  || (CAST(stMARA.ITEMID as VARCHAR(255))) )         AS ITEMID,
         4                                                                             AS BITFLAG,
         stMARA.EMPLOYEEID,
         stMARA.ITEMGROUPTYPEID,
         EKS_CALCULATION.srMARA_EKS_ITEM_zSKCaseSizeForEA.ItemPrefix
         || (REPEAT('0', 7 - length(CAST(stMARA.ITEMNO as VARCHAR(255))))  || CAST(stMARA.ITEMNO as VARCHAR(255)) )            AS ITEMNO,
         stMARA.SHORTDESC_INT,
         stMARA.SHORTDESC_NAT,
         stMARA.DESCRIPTION_INT,
         stMARA.DESCRIPTION_NAT,
         stMARA.IN_USE,
         stMARA.zLegacyMANDT,
         EKS_CALCULATION.srMARA_EKS_ITEM_zSKCaseSizeForEA.ItemPrefix
         || (REPEAT('0', 7 - length(CAST(stMARA.ITEMNO as VARCHAR(255))))  || CAST(stMARA.ITEMNO as VARCHAR(255)) )            AS zLegacyMATNR,
         stMARA.zLegacyMATKL,
         stMARA.zMATKL,
         stMARA.ITEMNO                                                    AS zBISMT,
         stMARA.zMEINS,
         stMARA.zZEINR,
         stMARA.zIsValidBITFLAG,
         stMARA.zIsIN_USE,
         stMARA.zIsFood,
         stMARA.zIsCurrentContract,
         stMARA.zNegotiatingCountry,
         'SK'                                                                          AS zArticleType,
         IFNULL(stMARA.zITEM_BA, 9990000000 || stMARA.ITEMID) AS zITEM_BA,
         stMARA.zSource,
         1                                                                             AS Constructed,
         stMARA.TargetSystem,
         stMARA.TargetClient,
         'ZSK'                                                                         AS zMTART,
         '12'                                                                          AS zATTYP,
         stMARA.zTRAGR,
         stMARA.zBWSCL,
         stMARA.zVABME,
         stMARA.zBEGRU,
         stMARA.zMSTAE,
         stMARA.zMSTDE,
         stMARA.zTAKLV,
         NULL                                                                          AS zINHME,
         NULL                                                                          AS zINHAL,
         stMARA.ITEMID                                                    AS ConstructedFrom,
         stMARA.CR_LOCATIONID,
         IFNULL(stMARA.zITEM_BA, 9990000000 || stMARA.ITEMNO) AS zLegacySATNR,
         NULL                                                                          AS zVPREH,
         EKS_CALCULATION.srMARA_EKS_ITEM_zSKCaseSizeForEA.zSKCaseSize
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1 as stMARA
         INNER JOIN EKS_CALCULATION.srMARA_EKS_ITEM_zSKCaseSizeForEA_1
                 ON stMARA.ITEMID = EKS_CALCULATION.srMARA_EKS_ITEM_zSKCaseSizeForEA.ITEMID
  WHERE  ( stMARA.BITFLAG = 0 )
         AND ( stMARA.zActive = 1 )
         AND ( stMARA.zIsCurrentContract = 1 )
          OR ( stMARA.BITFLAG = 0 )
             AND ( stMARA.zActive = 1 )
             AND ( stMARA.zIsCurrentContract = 1 );