create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCE_ZRELEVANTMDM_UPDSEL_1(
	ITEMID,
	ZRELEVANTMDM,
	ZRELEVANTMDMNEW,
	ZACTIVE
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantMDM,
         0 AS zRelevantMDMNew,
         srMARA_EKS_ITEM_WAWIRelevancy_zActive_UpdSel.zActiveNew
  FROM   EKS_CALCULATION.srMARA_EKS_ITEM_WAWIRelevancy_zActive_UpdSel_1
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_1
                 ON srMARA_EKS_ITEM_WAWIRelevancy_zActive_UpdSel.ITEMID = EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID
    where EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantMDM = 1;