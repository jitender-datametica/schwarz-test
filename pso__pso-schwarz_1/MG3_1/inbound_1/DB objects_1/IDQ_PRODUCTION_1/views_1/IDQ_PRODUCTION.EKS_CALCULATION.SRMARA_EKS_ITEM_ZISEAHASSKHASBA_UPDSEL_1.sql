create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISEAHASSKHASBA_UPDSEL_1(
	ITEMID,
	ZISEAHASSKHASBANEW,
	ZISEAHASSKHASBA
) as
SELECT distinct   t1.ITEMID, 1 AS zIsEAhasSKhasBANew, t1.zIsEAhasSKhasBA

FROM          EKS_CALCULATION.stMARA_EKS_ITEM_1 t1_1 
              INNER JOIN
              EKS.ITEMSORTING_1 t2 ON t1.ITEMID = t2.ITEMID 
              INNER JOIN
              EKS_CALCULATION.stMARA_EKS_ITEM_1 t3 ON t2.SORTITEMID = t3.ITEMID 
              INNER JOIN
              EKS.ITEMSORTING_1 t4 ON t3.ITEMID = t4.ITEMID 
              INNER JOIN
              EKS_CALCULATION.stMARA_EKS_ITEM_1 t5 ON t4.SORTITEMID = t5.ITEMID
WHERE        (t1.BITFLAG = 0) AND (t3.BITFLAG = 4) AND (t5.BITFLAG = 2) AND (t1.zIsEAhasSKhasBA IS NULL);