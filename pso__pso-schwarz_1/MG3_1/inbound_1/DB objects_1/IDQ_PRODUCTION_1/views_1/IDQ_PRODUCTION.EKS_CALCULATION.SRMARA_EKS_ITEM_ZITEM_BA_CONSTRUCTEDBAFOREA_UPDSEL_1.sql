create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZITEM_BA_CONSTRUCTEDBAFOREA_UPDSEL_1(
	ITEMID,
	ZITEM_BANEW,
	ZITEM_BA
) as
SELECT stMARA_EKS_ITEM_1.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID AS zITEM_BANew,
         stMARA_EKS_ITEM_1.zITEM_BA
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_1 AS stMARA_EKS_ITEM_1
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ConstructedFrom = stMARA_EKS_ITEM_1.ITEMID
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType = 'BA' )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed = 1 )
         AND ( stMARA_EKS_ITEM_1.zArticleType = 'EA' )  ;