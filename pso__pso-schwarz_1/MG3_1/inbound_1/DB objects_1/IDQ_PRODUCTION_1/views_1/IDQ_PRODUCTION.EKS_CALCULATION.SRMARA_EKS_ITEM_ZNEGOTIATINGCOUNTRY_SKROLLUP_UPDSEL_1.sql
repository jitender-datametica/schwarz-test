create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_SKROLLUP_UPDSEL_1(
	ITEMID,
	ZNEGOTIATINGCOUNTRY,
	ZNEGOTIATINGCOUNTRYNEW
) as
SELECT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zNegotiatingCountry,
         EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_SKROLLUP01.zNegotiatingCountry AS zNegotiatingCountryNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1
         INNER JOIN EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_SKROLLUP01_1
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_SKROLLUP01.ITEMID
                    AND EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_SKROLLUP01.BITFLAG
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 4 )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zNegotiatingCountry IS NULL ) ;