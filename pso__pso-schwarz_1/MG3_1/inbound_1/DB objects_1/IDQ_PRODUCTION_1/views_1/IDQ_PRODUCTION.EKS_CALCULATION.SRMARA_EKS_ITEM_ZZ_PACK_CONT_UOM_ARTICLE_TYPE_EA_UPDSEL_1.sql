create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZZ_PACK_CONT_UOM_ARTICLE_TYPE_EA_UPDSEL_1(
	ITEMID,
	ZLEGACYZZ_PACK_CONT_UOM,
	ZLEGACYZZ_PACK_CONT_UOMNEW
) as
SELECT Distinct EKS_CALCULATION.STMARA_EKS_ITEM.itemid,
    EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyZZ_PACK_CONT_UOM, 
EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT.DESCRIPTION AS zLegacyZZ_PACK_CONT_UOMNew
FROM     EKS_CALCULATION.STMARA_EKS_ITEM_1 INNER JOIN
                  EKS.ITEMDETAIL_1 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID INNER JOIN
                  EKS.UNIT_1 ON EKS.ITEMDETAIL.UNITID = EKS.UNIT.UNITID INNER JOIN
                  EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT_1 ON EKS.UNIT.SHORTDESCID = EKS_CALCULATION.STEKS_TRANSLATION_INT_UNIT.TRANSLATIONID
WHERE  (EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyZZ_PACK_CONT_UOM IS NULL) AND (EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = '0');