create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVBASKEA_EKS_TOTAL_CASENETWEIGHT_1(
	TOTAL_CASENETWEIGHT,
	SK_ITEMID
) as				
SELECT  SUM(TRY_CAST((stEKS_ITEMSORTING_1.QUANTITY * stEKS_ITEMDETAIL.NETWEIGHT) as NUMBER(38,5))) AS Total_CaseNetweight,
		EKS.ITEMSORTING.ITEMID AS SK_ITEMID
FROM EKS_CALCULATION.stMARA_EKS_ITEM_1 
INNER JOIN
EKS.ITEMSORTING_1 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.SORTITEMID 
INNER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM_1 AS stMARA_EKS_ITEM_1 ON EKS.ITEMSORTING.ITEMID = stMARA_EKS_ITEM_1.ITEMID 
INNER JOIN
EKS.ITEMSORTING_1 AS stEKS_ITEMSORTING_1 ON EKS.ITEMSORTING.ITEMID = stEKS_ITEMSORTING_1.SORTITEMID 
INNER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM_1 AS stMARA_EKS_ITEM_2 ON stEKS_ITEMSORTING_1.ITEMID = stMARA_EKS_ITEM_2.ITEMID 
INNER JOIN
EKS.ITEMDETAIL_1 as stEKS_ITEMDETAIL ON stEKS_ITEMDETAIL.ITEMID = stMARA_EKS_ITEM_2.ITEMID
WHERE 
(EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'BA') AND
(stMARA_EKS_ITEM_1.zArticleType = 'SK') AND
(stMARA_EKS_ITEM_2.zArticleType = 'EA') GROUP BY SK_ITEMID;