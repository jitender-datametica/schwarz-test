create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_EA_RECEIVINGCOUNTRY_1(
	ITEMID,
	RECEIVINGCOUNTRY
) as 
SELECT EA.ITEMID, EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ReceivingCountry
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS SK INNER JOIN
                  EKS.ITEMSORTING_1 ON SK.ITEMID = EKS.ITEMSORTING.SORTITEMID INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_1 AS EA ON EKS.ITEMSORTING.ITEMID = EA.ITEMID INNER JOIN
                  EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_1 ON SK.ITEMID = EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID
WHERE  (EA.BITFLAG = 0) AND (SK.BITFLAG = 4)
UNION
SELECT EA.ITEMID, EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ReceivingCountry
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS EA INNER JOIN
                  EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_1 ON EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID = EA.ITEMID
WHERE  (EA.BITFLAG = 0)
UNION
SELECT SK.ITEMID, EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ReceivingCountry
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS SK INNER JOIN
                  EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_1 ON EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID = SK.ITEMID
WHERE  (SK.BITFLAG = 4) AND constructed IS NULL;