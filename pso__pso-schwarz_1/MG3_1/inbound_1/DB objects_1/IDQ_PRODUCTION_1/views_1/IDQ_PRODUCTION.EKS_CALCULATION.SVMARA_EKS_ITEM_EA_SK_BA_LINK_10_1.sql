create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_EA_SK_BA_LINK_10_1(
	EA_ITEMID,
	EA_ITEMNO,
	EA_DESCRIPTION,
	SK_ITEMID,
	SK_ITEMNO,
	SK_DESCRIPTION,
	BA_ITEMID,
	BA_ITEMNO,
	BA_DESCRIPTION
) as
(SELECT EA.ITEMID AS EA_ITEMID, EA.ITEMNO AS EA_ITEMNO, EA.DESCRIPTION_INT AS EA_Description, SK.ITEMID AS SK_ITEMID, SK.ITEMNO AS SK_ITEMNO, SK.DESCRIPTION_INT AS SK_Description, BA.ITEMID AS BA_ITEMID, 
                  BA.ITEMNO AS BA_ITEMNO, BA.DESCRIPTION_INT AS BA_Description
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS EA INNER JOIN
                  EKS.ITEMSORTING_1 AS EASK ON EA.ITEMID = EASK.ITEMID INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_1 AS SK ON EASK.SORTITEMID = SK.ITEMID INNER JOIN
                  EKS.ITEMSORTING_1 AS SKBA ON SK.ITEMID = SKBA.ITEMID INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_1 AS BA ON SKBA.SORTITEMID = BA.ITEMID
WHERE  (EA.zArticleType = 'EA') AND (SK.zArticleType = 'SK') AND (BA.zArticleType = 'BA') AND (SK.zIsCurrentContract = 1)

);