create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL_1(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	LISTINGOVERVIEWID,
	RECEIVINGCOUNTRY,
	ZUSATZ,
	ITEMVALIDFROM,
	ITEMVALIDUNTIL,
	ZRELEVANTMDM,
	SUPPLIERCOUNTRY,
	ZSOURCE,
	ZACTIVE,
	EXECUTION_TIME
) as
SELECT DISTINCT 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID,
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description, 
                  v.INTSUPPLIERNO AS SupplierNo, v.DESCRIPTION AS SupplierDescription, eks.LISTINGOVERVIEWID, 
				  eks.ReceivingCountry, TR_VAL.DESCRIPTION AS Zusatz, EKS.CONTRACTPRICEVALIDITY.DATEFROM AS ItemValidFrom, 
                  EKS.CONTRACTPRICEVALIDITY.DATEUNTIL AS ItemValidUntil, eks.zIsWAWIRelevant AS zRelevantMDM,
				  CASE WHEN loc.shortsign = 'INT' THEN 'NT' ELSE loc.SHORTSIGN END AS SupplierCountry, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zSource, EKS_CALCULATION.stMARA_EKS_ITEM.zActive,
                  EKS_CALCULATION.GETLASTEXECUTIONTIME()
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 LEFT OUTER JOIN
                  EKS.ITEMEAN_1
				  ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMEAN.ITEMID
				  INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 AS eks ON eks.itemid = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID 
				  INNER JOIN
                  EKS.CONTRACTPRICEVALIDITY_1 ON eks.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID
				  LEFT OUTER JOIN
                  EKS.VALIDITY_1 AS val ON EKS.CONTRACTPRICEVALIDITY.VALIDITYID = val.VALIDITYID
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_1 AS TR_VAL ON TR_VAL.TRANSLATIONID = val.DESCRIPTIONID
				  LEFT OUTER JOIN
                  EKS.SUPPLIER_1 AS v ON eks.SUPPLIERNO = v.SUPPLIERNO
				  LEFT OUTER JOIN
                  EKS.SUPPLIER_LOC_USE_1 AS SU ON SU.SUPPLIERNO = v.SUPPLIERNO AND SU.CR_LOC_FLAG = 1
				  LEFT OUTER JOIN
                  EKS.LOCATION_1 AS LOC ON LOC.LOCATIONID = SU.LOCATIONID
WHERE  (EKS.ITEMEAN.EAN_1 IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND 
(EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) AND 
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'KG') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'LB') 
				  AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL <> 74) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry <> 'NT') AND 
                  (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO IN
                      (SELECT ITEMNO
                       FROM      EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1
                       WHERE   (ReceivingCountry <> 'KO'))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID NOT IN
                      (SELECT ITEMID
                       FROM      EKS.ITEMPLU_1)) OR
                  (EKS.ITEMEAN.EAN_1 IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND
				  (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'KG') AND 
				  (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'LB') AND
                   (EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL <> '74') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry <> 'NT')
				   AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO IN
                      (SELECT ITEMNO
                       FROM      EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1
                       WHERE   (ReceivingCountry <> 'KO'))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID NOT IN
                      (SELECT ITEMID
                       FROM      EKS.ITEMPLU_1)) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1) OR
                  (EKS.ITEMEAN.EAN_1 IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL)
				  AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) AND 
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'KG') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'LB') AND
				  (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry = 'NT') AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO IN
                      (SELECT ITEMNO
                       FROM      EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1
                       WHERE   (ReceivingCountry <> 'KO'))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID NOT IN
                      (SELECT ITEMID
                       FROM      EKS.ITEMPLU_1)) OR
                  (EKS.ITEMEAN.EAN_1 IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND
				  (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'KG') AND
				  (EKS_CALCULATION.stMARA_EKS_ITEM.zMEINS <> 'LB') AND
                   (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry = 'NT') AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO IN
                      (SELECT ITEMNO
                       FROM      EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1
                       WHERE   (ReceivingCountry <> 'KO'))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID NOT IN
                      (SELECT ITEMID
                       FROM      EKS.ITEMPLU_1)) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1);