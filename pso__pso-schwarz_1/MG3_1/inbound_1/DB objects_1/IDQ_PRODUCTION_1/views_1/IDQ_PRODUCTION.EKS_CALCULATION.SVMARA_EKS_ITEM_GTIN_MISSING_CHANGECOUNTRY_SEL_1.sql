	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	LISTINGOVERVIEWID,
	RECEIVINGCOUNTRY,
	ZUSATZ,
	ITEMVALIDFROM,
	ITEMVALIDUNTIL,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
SELECT DISTINCT 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.NegotiatingCountry, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.BuyerSHORTSIGN, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.BuyerFirstName, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.BuyerLastName, 
