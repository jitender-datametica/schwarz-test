FROM            EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL_1 LEFT OUTER JOIN
                         EKS_CALCULATION.EKS_ZSM_EXCLUDELIST_1 ON EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.ITEMNO = EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.ITEMNO 
