                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.ArticleFamily, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.ITEMID, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.ITEMNO, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.ArticleType, 
                         EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.Description, 
