                             EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.LISTINGOVERVIEWID = EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.LISTINGOVERVIEWID 
                             AND EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.SUPPLIERNO IS NULL OR
                             EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.SupplierNo = EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.SUPPLIERNO 
                             AND 
                             EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.LISTINGOVERVIEWID = EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.LISTINGOVERVIEWID 
                             OR
                             EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.SUPPLIERNO IS NULL 
                             AND EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.LISTINGOVERVIEWID IS NULL) 
                         AND EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.REPORTNO = '010.1'
WHERE        (EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.ITEMNO IS NULL) AND (EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.NegotiatingCountry <> EKS_CALCULATION.SVMARA_EKS_ITEM_GTIN_MISSINGSEL_ALL.SupplierCountry);