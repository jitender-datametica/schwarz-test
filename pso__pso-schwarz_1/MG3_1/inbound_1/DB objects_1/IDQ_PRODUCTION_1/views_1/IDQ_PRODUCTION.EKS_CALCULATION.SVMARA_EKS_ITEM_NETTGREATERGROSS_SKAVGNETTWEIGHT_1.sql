create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTGREATERGROSS_SKAVGNETTWEIGHT_1(
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	LISTINGOVERVIEWID,
	DECIMALCASESIZE,
	CASESIZE,
	NETWEIGHT,
	SUPPLIERNO,
	RECEIVINGCOUNTRY
) as	SELECT DISTINCT 
                  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CaseSize, 
				  AVG(EKS.ITEMDETAIL.NETWEIGHT) AS Netweight, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry
				  FROM EKS_CALCULATION.stMARA_EKS_ITEM_1 
				  INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 
				  ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID 
				  INNER JOIN
                  EKS.ITEMSORTING_1 
				  ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.SORTITEMID 
				  INNER JOIN
                  EKS.ITEMDETAIL_1
				  ON EKS.ITEMDETAIL.ITEMID = EKS.ITEMDETAIL.ITEMID
				  GROUP BY 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.Casesize,  
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry
				  HAVING (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'SK');