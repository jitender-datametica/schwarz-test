create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTWEIGHT_MISSINGSEL_1(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	BUNDLEFACT,
	VOLUME,
	UNITDESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
(WITH its AS (SELECT DISTINCT eA.ITEMID, lom.ReceivingCountry, MIN(SK.zRelevantMDM) AS SK
			FROM      EKS_CALCULATION.stMARA_EKS_ITEM_1 AS eA INNER JOIN
			EKS.ITEMSORTING_1 AS its ON its.ITEMID = eA.ITEMID AND eA.zArticleType = 'EA' INNER JOIN
			EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_1 AS lom ON lom.ITEMID = its.SORTITEMID INNER JOIN
			EKS_CALCULATION.stMARA_EKS_ITEM_1 AS SK ON SK.ITEMID = its.SORTITEMID AND SK.zArticleType = 'SK'
			GROUP BY eA.ITEMID, lom.ReceivingCountry
			UNION
			SELECT DISTINCT eA.ITEMID, lom.ReceivingCountry, 0 AS SK
			FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS eA INNER JOIN
			EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_1 AS lom ON lom.ITEMID = eA.ITEMID AND eA.zArticleType = 'EA')
SELECT DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName,EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description, EKS.ITEMDETAIL.BUNDLEFACT, EKS.ITEMDETAIL.VOLUME, TR.DESCRIPTION AS UnitDescription,CASE WHEN EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1 THEN EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM ELSE  its_2.SK END AS zRelevantMDM, EKS_CALCULATION.stMARA_EKS_ITEM.zSource, EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 LEFT OUTER JOIN
EKS.ITEMDETAIL_1 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID LEFT OUTER JOIN 
EKS.UNIT_1 AS UN ON UN.UNITID = EKS.ITEMDETAIL.UNITID LEFT OUTER JOIN
EKS.TRANSLATION_INT_1 AS TR ON TR.TRANSLATIONID = UN.SHORTDESCID LEFT OUTER JOIN
its AS its_2 ON its_2.ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID LEFT OUTER JOIN 
EKS_CALCULATION.EKS_ZSM_EXCLUDELIST_1 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO = EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.ITEMNO
AND EKS_CALCULATION.EKS_ZSM_EXCLUDELIST.REPORTNO = '020'
WHERE  (EKS.ITEMDETAIL.NETWEIGHT IS NULL OR EKS.ITEMDETAIL.NETWEIGHT = '') AND (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID IN
(SELECT DISTINCT ITEMID FROM      its AS its_1 WHERE   (ReceivingCountry NOT IN ('US', 'LX', 'EW', 'CH')))) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) AND ( EKS_CALCULATION.EKS_ZSM_ExcludeList.ITEMNO IS NULL ) 
ORDER BY EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO);