create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_ZUSATZGEWICHTSARTIKEL010_1(
	LISTINGOVERVIEWID,
	ITEMID,
	ITEMNO,
	SK_ITEMID,
	SK_ITEMNO,
	SK_DESCRIPTION_INT,
	BASICPRICEUNIT,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	BASICPRICEID,
	ZRELEVANTMDM
) as
with cte as (SELECT DISTINCT 
						EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID, 
						EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
						EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
						EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS SK_DESCRIPTION_INT, 
						EKS.TRANSLATION_INT_UNIT.DESCRIPTION AS BasicPriceUnit, 
						EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ReceivingCountry, 
						EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.SUPPLIERNO, 
						EKS.BASICPRICE.BASICPRICEID, 
						EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
						EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant
				FROM  EKS_CALCULATION.stMARA_EKS_ITEM_1 
				INNER JOIN
						EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_1 
						ON EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID AND EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1 
					INNER JOIN
							EKS.BASICPRICE_1 
							ON EKS.BASICPRICE.CASESIZECalc = EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.CaseSize 
					INNER JOIN
							EKS.UNIT_1 
							ON EKS.BASICPRICE.UNITID = EKS.UNIT.UNITID 
					INNER JOIN
							EKS.TRANSLATION_INT_UNIT_1 
							ON EKS.UNIT.SHORTDESCID = EKS.TRANSLATION_INT_UNIT.TRANSLATIONID 
					INNER JOIN
							EKS_CALCULATION.xtEKS_BASICINFO_UNION_1 
							ON EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.LISTINGOVERVIEWID 
							AND EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.CaseSize = EKS_CALCULATION.xtEKS_BASICINFO_UNION.casesize 
							AND EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid 
							AND EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ReceivingCountry = EKS_CALCULATION.xtEKS_BASICINFO_UNION.RecIEvingCountry 
AND EKS.BASICPRICE.BASICPRICEID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.BASICPRICEID INNER JOIN
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 
ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.LISTINGOVERVIEWID 
AND EKS_CALCULATION.xtEKS_BASICINFO_UNION.casesize = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize 
AND EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.SUPPLIERNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO 
AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry = EKS_CALCULATION.xtEKS_BASICINFO_UNION.RecIEvingCountry 
AND ((EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid = EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid AND EKS_CALCULATION.xtEKS_BASICINFO_UNION.zArticleType = 'EA') OR
								  (EKS_CALCULATION.xtEKS_BASICINFO_UNION.zArticleType = 'SK' AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = SK_ITEMID)) AND 
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.BASICPRICEID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.BASICPRICEID WHERE stEKS_LISTINGOVERVIEWMAX.zactive = 1) 
				SELECT cte.LISTINGOVERVIEWID, EKS.ITEM.itemid, EKS.ITEM.ITEMNO, cte.itemid AS SK_ITEMID, cte.itemno 
				AS SK_ITEMNO, cte.SK_DESCRIPTION_INT AS SK_DESCRIPTION_INT, 
				BasicPriceUnit, ReceivingCountry, SUPPLIERNO, BASICPRICEID, zIsWAWIRelevant AS zRelevantMDM
				FROM 
				cte 
				INNER JOIN
				EKS.ITEMSORTING_1 
				ON EKS.ITEMSORTING.SORTITEMID = cte.ITEMID 
				AND zArticleType = 'SK' 
				INNER JOIN
					EKS.ITEM_1 ON EKS.ITEMSORTING.itemid = EKS.ITEM.itemid AND EKS.ITEM.bitflag = 0
				UNION
			SELECT cte.LISTINGOVERVIEWID, itemid, ITEMNO, NULL AS SK_ITEMID, NULL AS SK_ITEMNO, NULL AS SK_DESCRIPTION_INT, BasicPriceUnit, ReceivingCountry, SUPPLIERNO, BASICPRICEID, 
								  zIsWAWIRelevant AS zRelevantMDM
				FROM     cte
				WHERE  zArticleType = 'EA';