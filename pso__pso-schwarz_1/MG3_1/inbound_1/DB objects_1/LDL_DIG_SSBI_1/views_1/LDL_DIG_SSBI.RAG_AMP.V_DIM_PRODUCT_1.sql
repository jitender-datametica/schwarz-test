create or replace view LDL_DIG_SSBI.RAG_AMP.V_DIM_PRODUCT_1(
	PROD_SID,
	PROD_NR,
	PROD_NAME,
	PROD_DESCR,
	IAN_NR,
	PROD_BRICK_CD,
	PROD_PACKING_TYPE_CD,
	PROD_ASSORTMENT_CLASS_CD,
	PROD_FOOD_CLASS_CD,
	BRAND_SID,
	BRAND_CLASS_CD,
	PROD_STORAGE_COND_CD,
	PROD_DANG_GOOD_CLASS_CD,
	PROD_GROUP_CD,
	IMPORT_NR,
	SEASON_NR,
	PROD_MATERIAL_TYPE_CD,
	PROD_PROMO_CLASS_CD,
	SHOP_CAT_LVL4_SID,
	SHOP_CAT_LVL4_NAME,
	SHOP_CAT_LVL3_SID,
	SHOP_CAT_LVL3_NAME,
	SHOP_CAT_LVL2_SID,
	SHOP_CAT_LVL2_NAME,
	SHOP_CAT_LVL1_SID,
	SHOP_CAT_LVL1_NAME,
	SHOP_CAT_SID,
	SHOP_CAT_NAME,
	PROD_PURCH_ORG_TYPE_CD
) as SELECT
PROD_SID
,PROD_NR
,PROD_NAME
,PROD_DESCR
,IAN_NR
,CASE WHEN PROD_BRICK_CD = '' THEN '-1' ELSE IFNULL(PROD_BRICK_CD, '-1') END
,CASE WHEN PROD_PACKING_TYPE_CD = '' THEN '-1' ELSE IFNULL(PROD_PACKING_TYPE_CD, '-1') END
,CASE WHEN PROD_ASSORTMENT_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_CLASS_CD, '-1') END
,CASE WHEN PROD_FOOD_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_FOOD_CLASS_CD, '-1') END
,IFNULL(BRAND_SID, '-1')
,CASE WHEN BRAND_CLASS_CD = '' THEN '-1' ELSE IFNULL(BRAND_CLASS_CD, '-1') END
,CASE WHEN PROD_STORAGE_COND_CD = '' THEN '-1' ELSE IFNULL(PROD_STORAGE_COND_CD, '-1') END
,CASE WHEN PROD_DANG_GOOD_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_DANG_GOOD_CLASS_CD, '-1') END
,CASE WHEN PROD_GROUP_CD = '' THEN '-1' ELSE IFNULL(PROD_GROUP_CD, '-1') END
,IMPORT_NR
,SEASON_NR
,CASE WHEN PROD_MATERIAL_TYPE_CD = '' THEN '-1' ELSE IFNULL(PROD_MATERIAL_TYPE_CD, '-1') END
,CASE WHEN PROD_PROMO_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_PROMO_CLASS_CD, '-1') END
,IFNULL(SHOP_CAT_LVL4_SID, '-1')
,SHOP_CAT_LVL4_NAME
,IFNULL(SHOP_CAT_LVL3_SID, '-1')
,SHOP_CAT_LVL3_NAME
,IFNULL(SHOP_CAT_LVL2_SID, '-1')
,SHOP_CAT_LVL2_NAME
,IFNULL(SHOP_CAT_LVL1_SID, '-1')
,SHOP_CAT_LVL1_NAME
,IFNULL(SHOP_CAT_SID, '-1')
,SHOP_CAT_NAME 
,CASE WHEN PROD_PURCH_ORG_TYPE_CD = '' THEN '-1' ELSE IFNULL(PROD_PURCH_ORG_TYPE_CD, '-1') END
FROM "SH_LDL_DIG_PRODUCTION"."CORE"."T_DIM_PRODUCT_1"
WHERE DWH_VALID_FG = TRUE
UNION
    SELECT 
         '-1' --  PROD_SID
        ,''   -- ,PROD_NR
        ,''   -- ,PROD_NAME
        ,''   -- ,PROD_DESCR
        ,''   -- ,IAN_NR
        ,'-1' -- ,PROD_BRICK_CD
        ,'-1' -- ,PROD_PACKING_TYPE_CD
        ,'-1' -- ,PROD_ASSORTMENT_CLASS_CD
        ,'-1' -- ,PROD_FOOD_CLASS_CD
        ,'-1' -- ,BRAND_SID
        ,'-1' -- ,BRAND_CLASS_CD
        ,'-1' -- ,PROD_STORAGE_COND_CD
        ,'-1' -- ,PROD_DANG_GOOD_CLASS_CD
        ,'-1' -- ,PROD_GROUP_CD
        ,''   -- ,IMPORT_NR
        ,''   -- ,SEASON_NR
        ,'-1' -- ,PROD_MATERIAL_TYPE_CD
        ,'-1' -- ,PROD_PROMO_CLASS_CD
        ,'-1' -- ,SHOP_CAT_LVL4_SID
        ,''   -- ,SHOP_CAT_LVL4_NAME
        ,'-1' -- ,SHOP_CAT_LVL3_SID
        ,''   -- ,SHOP_CAT_LVL3_NAME
        ,'-1' -- ,SHOP_CAT_LVL2_SID
        ,''   -- ,SHOP_CAT_LVL2_NAME
        ,'-1' -- ,SHOP_CAT_LVL1_SID
        ,''   -- ,SHOP_CAT_LVL1_NAME
        ,'-1' -- ,SHOP_CAT_SID
        ,''   -- ,SHOP_CAT_NAME
        , '-1' -- PROD_PURCH_ORG_TYPE_CD
;