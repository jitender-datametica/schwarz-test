CREATE OR REPLACE FUNCTION LDL_PRODUCTION.P_LEW_MART_PIT.F_GETHISTSOURCESYSTEMID(""P_SOURCESYSTEMNAME"" VARCHAR(16777216), ""P_REPDATE"" DATE)
RETURNS NUMBER(38,0)
LANGUAGE SQL
AS '
	
	SELECT
		max(
			COALESCE(sc.SOURCE_SYSTEM_ID,-1::INTEGER)
		) AS SOURCE_SYSTEM_ID
	FROM
		(
			SELECT SOURCE_SYSTEM_ID 
			FROM P_LEW_MART_PIT.T_CNTL_DIM_SOURCE_SYSTEM_1
			WHERE TRUE
				AND DELETED_FG 						= 0
				AND REJECT_FG 						= 0
				AND UPPER(TRIM(SOURCE_SYSTEM_NAME))	LIKE ''%'' || UPPER(TRIM(p_SourceSystemName)) || ''%''
				AND 
				(
					(
					p_RepDate 	IS NULL
					AND 
					CURRENT_FG 	= 1
					)
					OR
					p_RepDate BETWEEN VALID_FROM_DT AND VALID_TO_DT
				)
			QUALIFY ROW_NUMBER() OVER(PARTITION BY SOURCE_SYSTEM_ID, VALID_FROM_DT, DELETED_FG ORDER BY DWH_UPDATED_TS) = 1 
    	)sc
	WHERE TRUE	
		
    ';