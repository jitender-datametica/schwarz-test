			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''CNT_REAGG_PERIOD_IN_ADV_WEEKS''))				,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	CNT_REAGG_PERIOD_IN_ADV_WEEKS
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''CNT_REAGG_PERIOD_IN_DAYS''))					,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	CNT_REAGG_PERIOD_IN_DAYS
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_DT_REAGG''))							,TRY_TO_DATE(pa.PARAM_VALUE_CHAR,''YYYY-MM_1-DD''),NULL) )	AS	START_DT_REAGG 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''END_DT_REAGG''))								,TRY_TO_DATE(pa.PARAM_VALUE_CHAR,''YYYY-MM_1-DD''),NULL) )	AS	END_DT_REAGG 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_ADV_WEEK_REAGG''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	START_ADV_WEEK_REAGG
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''END_ADV_WEEK_REAGG''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	END_ADV_WEEK_REAGG
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''CNT_BASELINE_ADV_WEEK''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	CNT_BASELINE_ADV_WEEK
