			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_DT_PIT_DATA''))							,TRY_TO_DATE(pa.PARAM_VALUE_CHAR,''YYYY-MM_1-DD''),NULL) )	AS	START_DT_PIT_DATA 
