			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''LOC_STORE_SALES_NET_VAL_GT''))				,CAST(pa.PARAM_VALUE AS NUMBER(38,5)),NULL) )			AS	LOC_STORE_SALES_NET_VAL_GT
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''LOC_STORE_SALES_QTY_GT''))					,CAST(pa.PARAM_VALUE AS NUMBER(38,5)),NULL) )			AS	LOC_STORE_SALES_QTY_GT
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''ADP_TIME_GAP_IN_DAYS''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	ADP_TIME_GAP_IN_DAYS
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''CTR_ADV_WEEK_START_WEEKDAY_ID''))				,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	CTR_ADV_WEEK_START_WEEKDAY_ID
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''CTR_STORE_NBR''))								,CAST(pa.PARAM_VALUE AS NUMBER(38,5)),NULL) )			AS	CTR_STORE_NBR
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''CTR_EX_ELVIS_COUNTRY_FG''))					,CAST(pa.PARAM_VALUE AS SMALLINT),0::SMALLINT) )		AS	CTR_EX_ELVIS_COUNTRY_FG
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_DT_BASE_METRIC_NF_FA''))				,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	START_DT_BASE_METRIC_NF_FA 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''END_DT_BASE_METRIC_NF_FA''))					,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	END_DT_BASE_METRIC_NF_FA 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_DT_DELIV_QTY''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	START_DT_DELIV_QTY 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''END_DT_DELIV_QTY''))							,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	END_DT_DELIV_QTY 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_DT_STC_REAL_QTY''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	START_DT_STC_REAL_QTY 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''END_DT_STC_REAL_QTY''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	END_DT_STC_REAL_QTY 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_DAILY_RUN_FG''))						,CAST(pa.PARAM_VALUE AS SMALLINT),-1::SMALLINT) )		AS	EXEC_PIT_DAILY_RUN_FG
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_WEEKLY_RUN_FG''))					,CAST(pa.PARAM_VALUE AS SMALLINT),-1::SMALLINT) )		AS	EXEC_PIT_WEEKLY_RUN_FG
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_DQ_RUN_FG''))						,CAST(pa.PARAM_VALUE AS SMALLINT),-1::SMALLINT) )		AS	EXEC_PIT_DQ_RUN_FG
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_MANUAL_RUN_FG''))					,CAST(pa.PARAM_VALUE AS SMALLINT),-1::SMALLINT) )		AS	EXEC_PIT_MANUAL_RUN_FG 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_MANUAL_COUNTRY_LST''))				,pa.PARAM_VALUE_CHAR,NULL) )							AS	EXEC_PIT_MANUAL_COUNTRY_LST 
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_RUN_WEEKLY_WEEKDAY''))				,CAST(pa.PARAM_VALUE AS SMALLINT),NULL) )				AS	EXEC_PIT_RUN_WEEKLY_WEEKDAY
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_CNT_INITIAL_ADV_WEEKS''))			,CAST(pa.PARAM_VALUE AS SMALLINT),NULL) )				AS	EXEC_PIT_CNT_INITIAL_ADV_WEEKS
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_AB_PARALLEL_EXECUTION''))			,CAST(pa.PARAM_VALUE AS SMALLINT),NULL) )				AS	EXEC_PIT_AB_PARALLEL_EXECUTION			  
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''EXEC_PIT_SF_CREDIT_TIMERANGE_IN_DAYS''))		,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	EXEC_PIT_SF_CREDIT_TIMERANGE_IN_DAYS	
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''DEFAULT_PIT_MANUAL_RUN_FG''))					,CAST(pa.PARAM_VALUE AS SMALLINT),NULL) )				AS	DEFAULT_PIT_MANUAL_RUN_FG	
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''PIT_MAX_DATA_HISTORY_IN_DAYS''))				,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	PIT_MAX_DATA_HISTORY_IN_DAYS	
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''PIT_MAX_DATA_HISTORY_IN_ADV_WEEK''))			,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	PIT_MAX_DATA_HISTORY_IN_ADV_WEEK	

			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''WAWI_PRICE_CHANGE_GAP_IN_DAYS''))				,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	WAWI_PRICE_CHANGE_GAP_IN_DAYS
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''PV_PERIOD_LENGTH_MAX''))						,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	PV_PERIOD_LENGTH_MAX
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''PV_PERIOD_GAP_SPLITTING_DAYS''))				,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	PV_PERIOD_GAP_SPLITTING_DAYS
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''LP_ORIG_COUPON_TYPE_SID''))					,pa.PARAM_VALUE_CHAR,NULL) )							AS	LP_ORIG_COUPON_TYPE_SID
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''LP_COUPON_PROMO_TYPE_SID''))					,pa.PARAM_VALUE_CHAR,NULL) )							AS	LP_COUPON_PROMO_TYPE_SID
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''FA_OVERLAP_PERIOD_ACTION_TYPE_CONDITION''))	,pa.PARAM_VALUE_CHAR,NULL) )							AS	FA_OVERLAP_PERIOD_ACTION_TYPE_CONDITION
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''REJECT_PERIOD''))								,pa.PARAM_VALUE_CHAR,NULL) )							AS	REJECT_PERIOD
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''LP_SHIFT_PERIOD_START_DT''))					,CAST(pa.PARAM_VALUE AS INTEGER),NULL) )				AS	LP_SHIFT_PERIOD_START_DT
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''REJECT_WAWI_PV_LONG_PERIOD''))				,CAST(pa.PARAM_VALUE AS SMALLINT),NULL) )				AS	REJECT_WAWI_PV_LONG_PERIOD

		FROM  
			/* PARAM */
			(
				SELECT 
					  CLIENT_ID
					, PARAM_ID
					, PARAM_VALUE
					, PARAM_VALUE_CHAR 
				FROM P_LEW_MART_PIT.T_CNTL_PROCESSING_PARAM_1 
				WHERE TRUE	
					AND CURRENT_DATE() BETWEEN VALID_FROM_DT AND VALID_TO_DT
					AND DELETED_FG = 0
					AND REJECT_FG  = 0
					AND 
					(
						pClientId = -1    
						OR
						CLIENT_ID IN ( pClientId )
					) 					
				QUALIFY VERSION_NR = MAX(VERSION_NR) OVER (PARTITION BY CLIENT_ID, PARAM_ID)	
			)
			pa
		    
			/* PARAM REF */
			INNER JOIN
			(
				SELECT DISTINCT
			  		  PARAM_ID
					, PARAM_NAME
					, PARAM_DESCR
					, PARAM_COLUMN_DATATYPE
				FROM P_LEW_MART_PIT.T_CNTL_DIM_PROCESSING_PARAM_1
				WHERE TRUE
					AND DELETED_FG 	= 0
					AND REJECT_FG  	= 0
				-- Deduplication 
				QUALIFY ROW_NUMBER() OVER(PARTITION BY PARAM_ID ORDER BY DWH_UPDATED_TS DESC) = 1						
			) par
			ON TRUE
				AND pa.PARAM_ID = par.PARAM_ID
						
			GROUP BY 1	
			
		) pa
		WHERE TRUE 
			AND pa.START_DT_REAGG    IS NOT NULL
			AND pa.END_DT_REAGG      IS NOT NULL
			AND pa.NEXT_RUN_DT_REAGG IS NOT NULL 
			-- AKU 2022-10-20 Issue in preparing param, this is not needed for weekly PIT runs only Daily run
			--AND pa.NEXT_RUN_DT_REAGG <> TO_DATE(''8888-12-31'',''YYYY-MM_1-DD'')
			
			AND
				(
					-- Scheduled ReAgg - running on Weekdays 
					(
							pPitManualRunFg 				= 0::SMALLINT
						AND pa.EXEC_PIT_MANUAL_RUN_FG 		= 0::SMALLINT
						AND pa.EXEC_PIT_RUN_WEEKLY_WEEKDAY 	= date_part(''dayofweekiso'', CURRENT_DATE())						
					)
					OR
					-- Scheduled ReAgg - running on every day based on clients in param Table 
					(
							pPitManualRunFg 				= 3::SMALLINT
						AND pa.EXEC_PIT_MANUAL_RUN_FG 		= 3::SMALLINT
					)           
					OR
					-- Manual test_1 ReAgg Process - triggered by Operator 
					(
							pPitManualRunFg 				= 1::SMALLINT
						AND pa.EXEC_PIT_MANUAL_RUN_FG 		= 1::SMALLINT
						AND pa.CLIENT_ID 					IN 
								(
								SELECT 
									CTRLIST.Value AS CLIENT_ID
								FROM
									TABLE(SPLIT_TO_TABLE(pPitmanualCountryList,'',''))  CTRLIST
								WHERE TRUE
									AND CTRLIST.VALUE 				IS NOT NULL
									AND LENGTH(TRIM(CTRLIST.VALUE)) > 0
								GROUP BY 1				
								)
					)
					OR
					-- Initialize Data Process - triggered by Operator 
					(
							pPitManualRunFg 				= 2::SMALLINT
							AND 
							(
									pClientId = -1    
									OR
									pa.CLIENT_ID IN ( pClientId )
							)			
							AND 
							( 
								pClientId IS NULL 
								OR
								LEN(TRIM(pClientId)) <= 0
								OR
								pa.CLIENT_ID 	IN 
									(
									SELECT 
										CTRLIST.Value AS CLIENT_ID
									FROM
										TABLE(SPLIT_TO_TABLE(pPitmanualCountryList,'',''))  CTRLIST
									WHERE TRUE
										AND CTRLIST.VALUE 				IS NOT NULL
										AND LENGTH(TRIM(CTRLIST.VALUE)) > 0
									GROUP BY 1				
							)
						)
					)					
				)			

	';