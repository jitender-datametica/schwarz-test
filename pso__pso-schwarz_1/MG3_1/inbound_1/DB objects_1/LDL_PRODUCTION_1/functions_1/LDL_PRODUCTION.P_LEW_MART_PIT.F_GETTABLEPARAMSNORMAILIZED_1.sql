			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''START_DT_INTERMEDIATE''))						,TRY_TO_DATE(pa.PARAM_VALUE_CHAR,''YYYY-MM_1-DD''),NULL) )	AS	START_DT_INTERMEDIATE
			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''END_DT_INTERMEDIATE''))						,TRY_TO_DATE(pa.PARAM_VALUE_CHAR,''YYYY-MM_1-DD''),NULL) )	AS	END_DT_INTERMEDIATE 
