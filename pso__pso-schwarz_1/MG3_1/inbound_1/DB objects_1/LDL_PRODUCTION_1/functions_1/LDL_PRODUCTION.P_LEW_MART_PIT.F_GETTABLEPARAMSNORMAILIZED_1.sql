			, MAX( iff(UPPER(TRIM(par.PARAM_NAME))  =  UPPER(TRIM(''NEXT_RUN_DT_REAGG''))							,TRY_TO_DATE(pa.PARAM_VALUE_CHAR,''YYYY-MM_1-DD''),NULL) )	AS	NEXT_RUN_DT_REAGG 
