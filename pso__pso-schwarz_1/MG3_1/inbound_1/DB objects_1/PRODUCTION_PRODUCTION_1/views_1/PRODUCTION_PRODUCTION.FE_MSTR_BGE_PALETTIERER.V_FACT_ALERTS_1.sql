create or replace view PRODUCTION_PRODUCTION.FE_MSTR_BGE_PALETTIERER.V_FACT_ALERTS_1(
	ALERTS_PRIORITY_ID,
	ALERTS_MESSAGE_ID,
	ALERTS_TYPE_ID,
	CAL_DT,
	CAL_START_DT,
	CAL_END_DT,
	ALERTS_DAY_SHIFT_ID,
	ALERTS_LOCATION_ID,
	ALERTS_TM,
	ALERTS_START_TM,
	ALERTS_END_TM,
	ALERTS_DURATION_DIFF,
	HOUR_SORT,
	ALERTS_PRODUCTION_STOP_FG,
	ALERTS_DELETED_FG
) as
SELECT
 ALERTS_PRIORITY_ID
,ALERTS_MESSAGE_ID
,ALERTS_TYPE_ID									  
,CAL_DT
,TO_DATE(TIMEADD(SECOND, -ALERTS_DURATION_DIFF, CAL_DT||' '||ALERTS_TM)) AS CAL_START_DT
,CAL_DT AS CAL_END_DT
,ALERTS_DAY_SHIFT_ID
,ALERTS_LOCATION_ID
,ALERTS_TM
,TO_TIME(TIMEADD(SECOND, -ALERTS_DURATION_DIFF, CAL_DT||' '||ALERTS_TM)) AS ALERTS_START_TM
,ALERTS_TM AS ALERTS_END_TM
,ALERTS_DURATION_DIFF
,(EXTRACT(HOUR FROM ALERTS_TM) + 18) % 24 AS HOUR_SORT
,IFNULL(ALERTS_PRODUCTION_STOP_FG,0) AS ALERTS_PRODUCTION_STOP_FG
,ALERTS_DELETED_FG
FROM
CORE.T_FACT_ALERTS_1
WHERE ALERTS_DELETED_FG <> 1
;