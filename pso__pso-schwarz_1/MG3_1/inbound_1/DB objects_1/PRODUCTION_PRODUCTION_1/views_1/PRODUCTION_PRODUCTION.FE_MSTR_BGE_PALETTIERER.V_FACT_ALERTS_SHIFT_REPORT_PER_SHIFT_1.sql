create or replace view PRODUCTION_PRODUCTION.FE_MSTR_BGE_PALETTIERER.V_FACT_ALERTS_SHIFT_REPORT_PER_SHIFT_1(
	ALERTS_DAY_SHIFT_ID,
	ALERTS_SHIFT_REPORT_AGREEMENT_TXT,
	ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT,
	ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT,
	ALERTS_SHIFT_REPORT_SECURITY_ISSUES
) as
SELECT
 SHFT.ALERTS_DAY_SHIFT_ID                                AS ALERTS_DAY_SHIFT_ID
,COALESCE(SRPS.ALERTS_SHIFT_REPORT_AGREEMENT_TXT, '')    AS ALERTS_SHIFT_REPORT_AGREEMENT_TXT
,COALESCE(SRPS.ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT, '')   AS ALERTS_SHIFT_REPORT_NEXT_SHIFT_TXT
,COALESCE(SRPS.ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT, '') AS ALERTS_SHIFT_REPORT_OUT_OF_ORDER_TXT
,COALESCE(SRPS.ALERTS_SHIFT_REPORT_SECURITY_ISSUES, '')  AS ALERTS_SHIFT_REPORT_SECURITY_ISSUES
FROM            CORE.T_DIM_ALERTS_DAY_SHIFT_1 AS SHFT
LEFT OUTER JOIN CORE.T_FACT_ALERTS_SHIFT_REPORT_PER_SHIFT_1 AS SRPS
ON SRPS.ALERTS_DAY_SHIFT_ID = SHFT.ALERTS_DAY_SHIFT_ID
;