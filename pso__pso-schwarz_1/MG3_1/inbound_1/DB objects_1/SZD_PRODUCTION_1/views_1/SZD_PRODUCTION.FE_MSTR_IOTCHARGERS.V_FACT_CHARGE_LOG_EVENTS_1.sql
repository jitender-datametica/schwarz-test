create or replace view SZD_PRODUCTION.FE_MSTR_IOTCHARGERS.V_FACT_CHARGE_LOG_EVENTS_1(
	CHARGER_PROVIDER_SYSTEM_CD,
	CHARGE_LOG_UUID_NR,
	CHARGE_EVENT_DT,
	CY_MONTH,
	CY,
	START_TMSP,
	END_TMSP,
	CHARGER_RESOURCE_ITEM_SID,
	CHARGER_CLASSIFICATION_ID,
	CHARGER_SERIAL_NR,
	CHARGER_LABEL_NR,
	DIVISION_PARTY_SID,
	DIVISION_NAME,
	COUNTRY_LOCATION_SID,
	ISO_COUNTRY_CD,
	INTERNAL_COMPANY_NAME,
	REAL_ESTATE_RESOURCE_ITEM_SID,
	REAL_ESTATE_NR,
	REAL_ESTATE_ZIP,
	REAL_ESTATE_CITY_NAME,
	REAL_ESTATE_STREET_NAME,
	CHARGE_POINT_RESOURCE_ITEM_SID,
	CHARGE_POINT_PLUGIN_TYPE_NAME,
	CHARGER_STATION_TYPE_CD,
	CHARGE_POINT_NR,
	CHARGE_POINT_EVSE_NR,
	CHARGE_POINT_CONNECTOR_LABEL_TXT,
	ROAMING_IDENTIFICATION_DATA_TXT,
	CUSTOMER_UUID_NR,
	DURATION_SEC,
	TOTAL_CHARGING_POWER_MEAS,
	AVERAGE_CHARGING_POWER_MEAS,
	TURNOVER_VAL,
	TURNOVER_LOCAL_VAL,
	TURNOVER_LOCAL_CURR_CD
) as SELECT
 	 A.CHARGER_PROVIDER_SYSTEM_CD
	,A.CHARGE_LOG_UUID_NR
	,A.CHARGE_EVENT_DT
    ,B.CY_MONTH
    ,B.CY
    ,A.START_TMSP::TIMESTAMP(6) AS START_TMSP
    ,A.END_TMSP::TIMESTAMP(6) AS END_TMSP
	,A.CHARGER_RESOURCE_ITEM_SID
	,A.CHARGER_CLASSIFICATION_ID
	,A.CHARGER_SERIAL_NR
	,A.CHARGER_LABEL_NR
	,A.DIVISION_PARTY_SID
	,A.DIVISION_NAME
	,CASE WHEN A.COUNTRY_ISO_CD = 'AF'
          THEN -1
          ELSE A.COUNTRY_LOCATION_SID
      END AS COUNTRY_LOCATION_SID    
	,CASE WHEN A.COUNTRY_ISO_CD = 'AF'
          THEN 'Unknown'
          ELSE A.COUNTRY_ISO_CD
      END AS ISO_COUNTRY_CD
	,A.INTERNAL_COMPANY_NAME
	,A.REAL_ESTATE_RESOURCE_ITEM_SID
	,A.REAL_ESTATE_NR
	,A.REAL_ESTATE_ZIP
	,A.REAL_ESTATE_CITY_NAME
	,A.REAL_ESTATE_STREET_NAME
	,A.CHARGE_POINT_RESOURCE_ITEM_SID
    ,A.CHARGE_POINT_PLUGIN_TYPE_CD
	,A.CHARGER_STATION_TYPE_CD
	,A.CHARGE_POINT_NR
	,A.CHARGE_POINT_EVSE_NR
	,A.CHARGE_POINT_CONNECTOR_LABEL_TXT
	,A.ROAMING_IDENTIFICATION_DATA_TXT
	,A.CUSTOMER_UUID_NR
	,A.DURATION_SEC
	,A.TOTAL_CHARGING_POWER_MEAS
	,A.AVERAGE_CHARGING_POWER_MEAS
	,A.TURNOVER_VAL
	,A.TURNOVER_LOCAL_VAL
    ,A.LOCAL_CURR_CD
	FROM
	CORE.T_FACT_CHARGE_LOG_EVENTS_1 A
    JOIN FE_MSTR_IOTCHARGERS.V_DIM_CAL_DAY_1 B
    ON (A.CHARGE_EVENT_DT=B.CAL_DT)
    WHERE A.END_TMSP BETWEEN DATEADD(MONTH, -14, CURRENT_DATE) AND CURRENT_DATE
	AND A.TURNOVER_VAL BETWEEN 0.0 AND 100.0
	AND A.DURATION_SEC BETWEEN 0.0 AND 86400.0
    AND A.COUNTRY_ISO_CD IS NOT NULL
    AND A.END_TMSP IS NOT NULL
;