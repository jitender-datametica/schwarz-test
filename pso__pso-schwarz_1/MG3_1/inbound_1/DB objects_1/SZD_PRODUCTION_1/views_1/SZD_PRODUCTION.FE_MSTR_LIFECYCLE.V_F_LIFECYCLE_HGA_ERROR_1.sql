create or replace view SZD_PRODUCTION.FE_MSTR_LIFECYCLE.V_F_LIFECYCLE_HGA_ERROR_1(
	HGA_SID,
	ERROR_DATE,
	HGA_ERROR_CD,
	MANUFACTURER_SID,
	ERROR_START_TMSP,
	ERROR_END_TMSP,
	START_HOUR,
	HGA_ERROR_GRP_SID,
	OUT_OF_ORDER,
	ERROR_TIME
) as

 
WITH ARR_CTE AS 
    (
    SELECT DISTINCT
     HGA_SID
    ,ERROR_TMSP
    ,HGA_ERROR_CD
    ,HGA_ERROR_TYPE_ID
    ,ERROR_STATUS_FG
    ,IS_IN_OPERATION_FG
    ,MANUFACTURER_SID
    ,DWH_CREATED_TMSP
    ,DWH_UPDATED_TMSP
    ,ROW_NUMBER() OVER (ORDER BY HGA_SID,ERROR_TMSP,HGA_ERROR_CD,ERROR_STATUS_FG DESC
								,HGA_ERROR_TYPE_ID,IS_IN_OPERATION_FG,MANUFACTURER_SID,DWH_CREATED_TMSP,DWH_UPDATED_TMSP ASC) AS ROW_SORT
    FROM CORE.T_FACT_HGA_ERROR_1
    )
 
, ERREND_CTE AS
    (
    SELECT
      HGA_SID
    , HGA_ERROR_CD
    , MANUFACTURER_SID
    , ERROR_TMSP AS ERROR_START_TMSP
    , ROW_SORT
    , COALESCE(LEAD(ERROR_TMSP) OVER (PARTITION BY MANUFACTURER_SID, HGA_SID, HGA_ERROR_TYPE_ID, HGA_ERROR_CD ORDER BY ROW_SORT ASC), CONCAT(DATE(ERROR_TMSP), ' 23:59:59.999')::TIMESTAMP_TZ) AS ERROR_END_TMSP
    , ERROR_STATUS_FG
    , IS_IN_OPERATION_FG
    , HGA_ERROR_TYPE_ID
    FROM ARR_CTE
    	WHERE HGA_ERROR_CD NOT IN
    (
     SELECT HGA_ERROR_CD
     FROM CORE.T_DIM_HGA_ERROR_1
	   WHERE UPPER(HGA_ERROR_DESCR) LIKE 'STANDBY'
    )

   )
 
, ERR_CTE AS
    (
    SELECT 
      HGA_SID                   AS HGA_SID
    , TO_DATE(ERROR_START_TMSP) AS ERROR_DATE
    , HGA_ERROR_CD              AS HGA_ERROR_CD
    , MANUFACTURER_SID          AS MANUFACTURER_SID
    , ERROR_START_TMSP          AS ERROR_START_TMSP
    , ERROR_END_TMSP            AS ERROR_END_TMSP
    , IS_IN_OPERATION_FG 
    FROM ERREND_CTE
    WHERE ERROR_STATUS_FG = TRUE
    )
 
SELECT
  ERR_CTE.HGA_SID               AS HGA_SID
, HGD1.CAL_DT                   AS ERROR_DATE
, ERR_CTE.HGA_ERROR_CD          AS HGA_ERROR_CD
, ERR_CTE.MANUFACTURER_SID      AS MANUFACTURER_SID
, ERR_CTE.ERROR_START_TMSP      AS ERROR_START_TMSP
, ERR_CTE.ERROR_END_TMSP        AS ERROR_END_TMSP
, HOUR(ERR_CTE.ERROR_START_TMSP) AS START_HOUR
, HGL1.HGA_ERROR_GRP_SID        AS HGA_ERROR_GRP_SID
 
, CASE
   WHEN IS_IN_OPERATION_FG = FALSE THEN 'ja'
   WHEN IS_IN_OPERATION_FG = TRUE THEN 'nein'
  END AS OUT_OF_ORDER
 
, CASE 
   WHEN (DATEDIFF(DAY,ERR_CTE.ERROR_START_TMSP,ERR_CTE.ERROR_END_TMSP)+1) = 1 
     THEN ROUND(TIMESTAMPDIFF(MILLISECOND, ERR_CTE.ERROR_START_TMSP, ERR_CTE.ERROR_END_TMSP)/1000)
   WHEN ((DATEDIFF(DAY,ERR_CTE.ERROR_START_TMSP,ERR_CTE.ERROR_END_TMSP)+1) = 2 AND HGD1.CAL_DT = DATE(ERR_CTE.ERROR_START_TMSP)) 
     THEN ROUND(TIMESTAMPDIFF(MILLISECOND, ERR_CTE.ERROR_START_TMSP, CONCAT(DATE(ERR_CTE.ERROR_START_TMSP),' 23:59:59.999')::TIMESTAMP_TZ)/1000)
   WHEN ((DATEDIFF(DAY,ERR_CTE.ERROR_START_TMSP,ERR_CTE.ERROR_END_TMSP)+1) = 2 AND HGD1.CAL_DT = DATE(ERR_CTE.ERROR_END_TMSP)) 
     THEN ROUND(TIMESTAMPDIFF(MILLISECOND,CONCAT(DATE(ERR_CTE.ERROR_END_TMSP),' 00:00:00.000')::TIMESTAMP_TZ, ERR_CTE.ERROR_END_TMSP)/1000)
   WHEN ((DATEDIFF(DAY,ERR_CTE.ERROR_START_TMSP,ERR_CTE.ERROR_END_TMSP)+1) > 2 AND HGD1.CAL_DT = DATE(ERR_CTE.ERROR_START_TMSP)) 
     THEN ROUND(TIMESTAMPDIFF(MILLISECOND, ERR_CTE.ERROR_START_TMSP, CONCAT(DATE(ERR_CTE.ERROR_START_TMSP),' 23:59:59.999')::TIMESTAMP_TZ)/1000)
   WHEN ((DATEDIFF(DAY,ERR_CTE.ERROR_START_TMSP,ERR_CTE.ERROR_END_TMSP)+1) > 2 AND HGD1.CAL_DT <> DATE(ERR_CTE.ERROR_START_TMSP) AND HGD1.CAL_DT <> DATE(ERR_CTE.ERROR_END_TMSP)) 
     THEN 86400  
   WHEN ((DATEDIFF(DAY,ERR_CTE.ERROR_START_TMSP,ERR_CTE.ERROR_END_TMSP)+1) > 2 AND HGD1.CAL_DT = DATE(ERR_CTE.ERROR_END_TMSP))  
     THEN ROUND(TIMESTAMPDIFF(MILLISECOND,CONCAT(DATE(ERR_CTE.ERROR_END_TMSP),' 00:00:00.000')::TIMESTAMP_TZ, ERR_CTE.ERROR_END_TMSP)/1000)
  END AS ERROR_TIME
 
FROM ERR_CTE
 
JOIN CORE.T_DIM_CAL_DAY_1 AS HGD1
ON HGD1.CAL_DT >= DATE(ERR_CTE.ERROR_START_TMSP)
AND HGD1.CAL_DT <= DATE(ERR_CTE.ERROR_END_TMSP)
 
LEFT JOIN FE_MSTR_LIFECYCLE.V_L_LIFECYCLE_HGA_ERROR_1 HGL1
ON ERR_CTE.HGA_ERROR_CD = HGL1.HGA_ERROR_CD
AND ERR_CTE.MANUFACTURER_SID = HGL1.MANUFACTURER_SID
;