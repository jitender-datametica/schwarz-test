create or replace view SZD_PRODUCTION.FE_MSTR_LIFECYCLE.V_F_LIFECYCLE_RVM_DEPOSIT_CASH_DATA_1(
	RECEIPT_DT,
	STORE_NR,
	COUNTRY_POL_CD,
	LOB_CD,
	LOCAL_CURR_CD,
	GLOBAL_CURR_CD,
	DEPOSIT_OUTPAYMENT_TYPE_CD,
	STORE_SID,
	DEPOSIT_LOCAL_VAL,
	DEPOSIT_GLOBAL_VAL
) as
--03.05.2023 twie: INC6523697 wird in MSI nur auf Tagesebene ausgewertet, deshalb die Belege aufsummieren

SELECT
 v01.RECEIPT_DT
,v01.STORE_NR
,v01.COUNTRY_POL_CD
,v01.LOB_CD
,v01.LOCAL_CURR_CD
,v01.GLOBAL_CURR_CD
,v01.DEPOSIT_OUTPAYMENT_TYPE_CD
,v01.STORE_SID
,SUM(v01.DEPOSIT_LOCAL_VAL) AS DEPOSIT_LOCAL_VAL
,SUM(v01.DEPOSIT_GLOBAL_VAL) AS DEPOSIT_GLOBAL_VAL

FROM
CORE.T_FACT_DEPOSIT_CASH_DATA_1 v01

GROUP BY
 v01.RECEIPT_DT
,v01.STORE_NR
,v01.COUNTRY_POL_CD
,v01.LOB_CD
,v01.LOCAL_CURR_CD
,v01.GLOBAL_CURR_CD
,v01.DEPOSIT_OUTPAYMENT_TYPE_CD
,v01.STORE_SID
;