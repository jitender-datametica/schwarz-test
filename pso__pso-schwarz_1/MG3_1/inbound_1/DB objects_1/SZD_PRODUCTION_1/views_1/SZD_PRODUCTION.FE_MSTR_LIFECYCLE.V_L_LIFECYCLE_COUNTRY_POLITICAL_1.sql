create or replace view SZD_PRODUCTION.FE_MSTR_LIFECYCLE.V_L_LIFECYCLE_COUNTRY_POLITICAL_1(
	COUNTRY_POL_CD,
	COUNTRY_POL_NAME,
	COUNTRY_POL_NAME_DE,
	COUNTRY_POL_NAME_CH,
	COUNTRY_POL_NAME_EN,
	COUNTRY_POL_NAME_CZ,
	COUNTRY_POL_NAME_LT,
	COUNTRY_POL_NAME_SK,
	COUNTRY_POL_NAME_SI,
	COUNTRY_POL_NAME_RO
) as
SELECT
   ISO_COUNTRY_CD AS COUNTRY_POL_CD
 , COUNTRY_NAME_DE AS COUNTRY_POL_NAME
 , COUNTRY_NAME_DE AS COUNTRY_POL_NAME_DE
 , COUNTRY_NAME_DE AS COUNTRY_POL_NAME_CH
 , COUNTRY_NAME_EN
 , COUNTRY_NAME_EN AS COUNTRY_POL_NAME_CZ
 , COUNTRY_NAME_EN AS COUNTRY_POL_NAME_LT
 , COUNTRY_NAME_EN AS COUNTRY_POL_NAME_SK
 , COUNTRY_NAME_EN AS COUNTRY_POL_NAME_SI
 , COUNTRY_NAME_EN AS COUNTRY_POL_NAME_RO
FROM
CORE.T_DIM_COUNTRY_POLITICAL_1
WHERE
DWH_VALID_FG = TRUE
;