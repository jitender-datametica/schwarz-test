create or replace view SZD_PRODUCTION.FE_MSTR_LIFECYCLE.V_L_LIFECYCLE_HGA_OUT_OF_ORDER_1(
	OUT_OF_ORDER,
	OUT_OF_ORDER_DESC,
	OUT_OF_ORDER_DESC_DE,
	OUT_OF_ORDER_DESC_CH,
	OUT_OF_ORDER_DESC_EN,
	OUT_OF_ORDER_DESC_CZ,
	OUT_OF_ORDER_DESC_LT,
	OUT_OF_ORDER_DESC_SK,
	OUT_OF_ORDER_DESC_SI,
	OUT_OF_ORDER_DESC_RO
) as
SELECT DISTINCT
  CASE
  WHEN IS_IN_OPERATION_FG = FALSE THEN 'ja'
  WHEN IS_IN_OPERATION_FG = TRUE THEN 'nein'
  END AS OUT_OF_ORDER
   
, OUT_OF_ORDER AS OUT_OF_ORDER_DESC
, OUT_OF_ORDER AS OUT_OF_ORDER_DESC_DE
, OUT_OF_ORDER AS OUT_OF_ORDER_DESC_CH

, CASE
  WHEN IS_IN_OPERATION_FG = FALSE THEN 'yes'
  WHEN IS_IN_OPERATION_FG = TRUE THEN 'no'
  END AS OUT_OF_ORDER_DESC_EN
  
 , OUT_OF_ORDER_DESC_EN AS OUT_OF_ORDER_DESC_CZ
 , OUT_OF_ORDER_DESC_EN AS OUT_OF_ORDER_DESC_LT
 , OUT_OF_ORDER_DESC_EN AS OUT_OF_ORDER_DESC_SK
 , OUT_OF_ORDER_DESC_EN AS OUT_OF_ORDER_DESC_SI
 , OUT_OF_ORDER_DESC_EN AS OUT_OF_ORDER_DESC_RO
FROM CORE.T_FACT_HGA_ERROR_1
;