create or replace view DWH.REF_DPL_CHECK_DEFINITION_1(
	REF_DPL_CHECK_DEFINITION_ID,
	DPL_CHECK_DEFINITION_TECHNICAL_NAME,
	DPL_CHECK_DEFINITION_NAME,
	DPL_CHECK_DEFINITION_NAME_DE,
	DPL_CHECK_DEFINITION_NAME_EN,
	REF_TEST_OBJECT_TYPE_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_BRANCH_ID
) as
SELECT ID                        AS REF_DPL_CHECK_DEFINITION_ID
      ,NAME                      AS DPL_CHECK_DEFINITION_TECHNICAL_NAME
      ,NAME                      AS DPL_CHECK_DEFINITION_NAME
      ,NAME                      AS DPL_CHECK_DEFINITION_NAME_DE
      ,NAME                      AS DPL_CHECK_DEFINITION_NAME_EN
	  ,TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
	  ,SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
	  ,BRANCH_ID                 AS REF_BRANCH_ID
FROM idq_results.REF_DPL_CHECK_DEFINITION_1
