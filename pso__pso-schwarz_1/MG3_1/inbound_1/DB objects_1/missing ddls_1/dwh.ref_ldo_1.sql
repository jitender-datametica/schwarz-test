create or replace view DWH.REF_LDO_1(
	REF_LDO_ID,
	LDO_TECHNICAL_NAME,
	FUNCTIONAL_CODE,
	REF_COUNTRY_1,
	SOURCE_SYSTEM,
	PRJ_FOLDER,
	LDO_DESCRIPTION
) as
SELECT ID                   AS REF_LDO_ID
      ,NAME                 AS LDO_TECHNICAL_NAME
      ,FUNCTIONAL_CODE	  AS FUNCTIONAL_CODE
      ,REF_COUNTRY_1	      AS REF_COUNTRY_1
      ,SOURCE_SYSTEM	      AS SOURCE_SYSTEM
      ,PRJ_FOLDER	          AS PRJ_FOLDER
      ,DESCRIPTION          AS LDO_DESCRIPTION
FROM idq_results.REF_LDO_1
;