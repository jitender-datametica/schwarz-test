create or replace view DWH.REF_PARAMETER_INSERT_1(
	REF_PARAMETER_ID,
	SCOPE,
	REF_BRANCH_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	PARAMETER_TECHNICAL_NAME,
	DEFAULT_VALUE,
	PARAMETER_DESCRIPTION,
	PARAMETER_DESCRIPTION_DE,
	PARAMETER_DESCRIPTION_EN,
	REF_PARAMETER_USAGE_ID,
	REF_RULE_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID
) as

select distinct

 a.ID                     		AS REF_PARAMETER_ID
      ,a.SCOPE                  	AS SCOPE
      ,a.BRANCH_ID              	AS REF_BRANCH_ID
      ,a.SOURCE_SYSTEM_TYPE_ID  	AS REF_SOURCE_SYSTEM_TYPE_ID
      ,a.NAME                   	AS PARAMETER_TECHNICAL_NAME
      ,a.DEFAULT_VALUE          	AS DEFAULT_VALUE
      ,a.DESCRIPTION_DE         	AS PARAMETER_DESCRIPTION
      ,a.DESCRIPTION_DE         	AS PARAMETER_DESCRIPTION_DE
      ,a.DESCRIPTION_EN         	AS PARAMETER_DESCRIPTION_EN
	  ,a.REF_PARAMETER_USAGE_ID 	AS REF_PARAMETER_USAGE_ID
	  ,d.RULE_ID					AS REF_RULE_ID
	  ,e.ID							AS REF_SOURCE_SYSTEM_ID
	  ,f.COUNTRY_ID					AS REF_COUNTRY_ID

from idq_results.REF_PARAMETER_1  a
	join idq_results.REF_PARAMETER_USAGE b
		on a.REF_PARAMETER_USAGE_ID=b.id
	join idq_results.REF_REL_RULE_MAPPLET_PARAMETER_1 c
		on a.ID=c.PARAMETER_ID
	join idq_results.REF_REL_RULE_MAPPLET_1 d
		on c.REL_RULE_MAPPLET_ID=d.ID
	join idq_results.REF_SOURCE_SYSTEM_1 e
		on e.SOURCE_SYSTEM_TYPE_ID=a.SOURCE_SYSTEM_TYPE_ID
	join idq_results.IDQ_TEST_OBJECT_1 f
		on a.BRANCH_ID=f.BRANCH_ID and e.id=f.SOURCE_SYSTEM_ID
where e.PARENT_ID is null
;