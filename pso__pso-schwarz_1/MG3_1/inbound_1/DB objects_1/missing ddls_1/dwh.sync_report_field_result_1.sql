create or replace view DWH.SYNC_REPORT_FIELD_RESULT_1(
	SYNC_REPORT_FIELD_RESULT_ID,
	SYNC_REPORT_EXECUTION_ID,
	REF_SYNC_REL_FIELD_FIELD_ID,
	CHECKS_AMOUNT,
	EQUAL_AMOUNT,
	UNEQUAL_AMOUNT,
	LEADING_EMPTY_AMOUNT,
	DEPENDENT_EMPTY_AMOUNT,
	SYNC_RATIO,
	REF_SYNC_REPORT_DEFINITION_ID,
	REF_TEST_OBJECT_TYPE_ID,
	LEADING_SYSTEM_ID,
	DEPENDENT_SYSTEM_ID,
	SYNC_REPORT_FIELD_IS_CURRENT
) as
SELECT SRFR.ID                        AS SYNC_REPORT_FIELD_RESULT_ID
      ,SRFR.SYNC_REPORT_EXECUTION_ID  AS SYNC_REPORT_EXECUTION_ID
      ,SRFR.SYNC_REL_FIELD_FIELD_ID   AS REF_SYNC_REL_FIELD_FIELD_ID
      ,SRFR.CHECKS_AMOUNT			    AS CHECKS_AMOUNT
      ,SRFR.EQUAL_AMOUNT			    AS EQUAL_AMOUNT
      ,SRFR.UNEQUAL_AMOUNT			AS UNEQUAL_AMOUNT
      ,SRFR.LEADING_EMPTY_AMOUNT	    AS LEADING_EMPTY_AMOUNT
      ,SRFR.DEPENDENT_EMPTY_AMOUNT	AS DEPENDENT_EMPTY_AMOUNT
      ,SRFR.SYNC_RATIO				AS SYNC_RATIO
      ,SRE.SYNC_REPORT_DEFINITION_ID	AS REF_SYNC_REPORT_DEFINITION_ID
      ,RSRD.TEST_OBJECT_TYPE_ID           AS REF_TEST_OBJECT_TYPE_ID
      ,RSRD.LEADING_SYSTEM_ID             AS LEADING_SYSTEM_ID
      ,RSRD.DEPENDENT_SYSTEM_ID           AS DEPENDENT_SYSTEM_ID
	  ,SRE.IS_CURRENT                     AS SYNC_REPORT_FIELD_IS_CURRENT
FROM idq_results.SYNC_REPORT_FIELD_RESULT_1 SRFR
INNER JOIN idq_results.SYNC_REPORT_EXECUTION_1 SRE
  ON SRFR.SYNC_REPORT_EXECUTION_ID = SRE.ID
INNER JOIN idq_results.REF_SYNC_REPORT_DEFINITION_1 RSRD
  ON SRE.SYNC_REPORT_DEFINITION_ID = RSRD.ID
;