create or replace view DWH.SYNC_REPORT_RECORD_RESULT_1(
	SYNC_REPORT_RECORD_RESULT_ID,
	LEADING_PRIMARY_KEY,
	DEPENDENT_PRIMARY_KEY,
	REF_COUNTRY_ID,
	REF_SYNC_REPORT_EXECUTION_ID,
	REF_MATCHING_STATUS_ID,
	CHECKS_AMOUNT,
	EQUAL_AMOUNT,
	UNEQUAL_AMOUNT,
	LEADING_EMPTY_AMOUNT,
	DEPENDENT_EMPTY_AMOUNT,
	SYNC_SCORE,
	IS_USABLE,
	UNMATCHED_TABLES,
	REF_SYNC_REPORT_DEFINITION_ID,
	REF_TEST_OBJECT_TYPE_ID,
	LEADING_SYSTEM_ID,
	DEPENDENT_SYSTEM_ID
) as
SELECT SRCS.ID                            AS SYNC_REPORT_RECORD_RESULT_ID
      ,SRCS.LEADING_PRIMARY_KEY	        AS LEADING_PRIMARY_KEY
      ,SRCS.DEPENDENT_PRIMARY_KEY	        AS DEPENDENT_PRIMARY_KEY
      ,SRCS.COUNTRY_ID			        AS REF_COUNTRY_ID
      ,SRCS.SYNC_REPORT_EXECUTION_ID      AS REF_SYNC_REPORT_EXECUTION_ID
      ,SRCS.REF_MATCHING_STATUS_ID        AS REF_MATCHING_STATUS_ID
      ,SRCS.CHECKS_AMOUNT			        AS CHECKS_AMOUNT
      ,SRCS.EQUAL_AMOUNT			        AS EQUAL_AMOUNT
      ,SRCS.UNEQUAL_AMOUNT		        AS UNEQUAL_AMOUNT
      ,SRCS.LEADING_EMPTY_AMOUNT	        AS LEADING_EMPTY_AMOUNT
      ,SRCS.DEPENDENT_EMPTY_AMOUNT        AS DEPENDENT_EMPTY_AMOUNT
      ,SRCS.SYNC_SCORE			        AS SYNC_SCORE
      ,SRCS.IS_USABLE				        AS IS_USABLE
      ,SRCS.UNMATCHED_TABLES		        AS UNMATCHED_TABLES
      ,SRE.SYNC_REPORT_DEFINITION_ID	    AS REF_SYNC_REPORT_DEFINITION_ID
      ,RSRD.TEST_OBJECT_TYPE_ID           AS REF_TEST_OBJECT_TYPE_ID
      ,RSRD.LEADING_SYSTEM_ID             AS LEADING_SYSTEM_ID
      ,RSRD.DEPENDENT_SYSTEM_ID           AS DEPENDENT_SYSTEM_ID
FROM idq_results.SYNC_REPORT_RECORD_RESULT_1 SRCS
INNER JOIN idq_results.SYNC_REPORT_EXECUTION_1 SRE
  ON SRCS.SYNC_REPORT_EXECUTION_ID = SRE.ID
INNER JOIN idq_results.REF_SYNC_REPORT_DEFINITION_1 RSRD
  ON SRE.SYNC_REPORT_DEFINITION_ID = RSRD.ID
;