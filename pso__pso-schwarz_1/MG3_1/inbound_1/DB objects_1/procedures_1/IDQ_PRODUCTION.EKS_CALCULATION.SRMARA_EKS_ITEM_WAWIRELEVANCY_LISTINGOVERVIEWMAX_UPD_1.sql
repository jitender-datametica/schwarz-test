CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_WAWIRELEVANCY_LISTINGOVERVIEWMAX_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_1 
SET  LISTINGOVERVIEWID = sr.LISTINGOVERVIEWIDNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_WAWIRelevancy_LISTINGOVERVIEWMAX_UpdSel_1 AS sr
            WHERE EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = sr.LISTINGOVERVIEWID
            AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry = sr.ReceivingCountry
            AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = sr.ITEMID
            AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize = sr.CaseSize;
END;
';