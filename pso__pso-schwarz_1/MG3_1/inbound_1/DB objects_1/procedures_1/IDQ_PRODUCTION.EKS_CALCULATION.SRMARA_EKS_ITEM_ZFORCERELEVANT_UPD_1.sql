CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZFORCERELEVANT_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_1 
SET  zForceRelevant = sr.zForceRelevantNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zForceRelevant_UpdSel_1 AS sr
WHERE EKS_CALCULATION.STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';