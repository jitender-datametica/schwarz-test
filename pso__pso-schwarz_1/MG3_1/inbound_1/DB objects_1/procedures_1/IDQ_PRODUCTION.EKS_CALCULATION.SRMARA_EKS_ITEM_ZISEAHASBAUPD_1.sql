CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISEAHASBAUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
UPDATE EKS_CALCULATION.STMARA_EKS_ITEM_1
SET zIsEAhasBA = EKS_CALCULATION.SRMARA_EKS_ITEM_ZISEAHASBAUPDSEL.zIsEAhasBANew
FROM EKS_CALCULATION.SRMARA_EKS_ITEM_ZISEAHASBAUPDSEL_1
where EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.SRMARA_EKS_ITEM_ZISEAHASBAUPDSEL.ITEMID;
END;
';