CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISEAHASSKUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_1 
SET  zIsEAhasSK = sr.zIsEAhasSKNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zIsEAhasSKUpdSel_1 AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';