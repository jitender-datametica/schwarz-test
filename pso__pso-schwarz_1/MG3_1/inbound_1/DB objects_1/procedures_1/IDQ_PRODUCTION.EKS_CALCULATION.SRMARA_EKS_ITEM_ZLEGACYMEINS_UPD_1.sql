CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZLEGACYMEINS_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_1 
SET  zLegacyMEINS = sr.zLegacyMEINSNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zLegacyMEINS_UpdSel_1 AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';