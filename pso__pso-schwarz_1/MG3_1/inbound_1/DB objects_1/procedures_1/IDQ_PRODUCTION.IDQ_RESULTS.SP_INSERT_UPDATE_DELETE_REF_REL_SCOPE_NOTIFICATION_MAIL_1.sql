--SP_INSERT_UPDATE_DELETE_REF_REL_SCOPE_NOTIFICATION_MAIL( NUMBER, VARCHAR, NUMBER, VARCHAR, NUMBER, NUMBER)

CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_REL_SCOPE_NOTIFICATION_MAIL("REF_REL_SCOPE_NOTIFICATION_MAIL_ID" NUMBER(38,0), "REF_SCOPE_ID" VARCHAR(255), "REF_NOTIFICATION_ID" NUMBER(38,0), "EMAIL" VARCHAR(255), "FREQUENCY" NUMBER(38,0), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE Notification_Mail_exist number(38,0);
BEGIN
Notification_Mail_exist := (SELECT ID FROM REF_REL_SCOPE_NOTIFICATION_MAIL_1 WHERE SCOPE_ID = :REF_SCOPE_ID and NOTIFICATION_ID = :REF_NOTIFICATION_ID and EMAIL = :EMAIL and FREQUENCY = :FREQUENCY);
    IF (:DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_REL_SCOPE_NOTIFICATION_MAIL_1 WHERE ID = :REF_REL_SCOPE_NOTIFICATION_MAIL_ID;
   
    -- INSERT NEW MAIL
    elseIF (:REF_REL_SCOPE_NOTIFICATION_MAIL_ID = 0 AND :DEL = 0 and Notification_Mail_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_REL_SCOPE_NOTIFICATION_MAIL_1
        (ID,SCOPE_ID,NOTIFICATION_ID,EMAIL,FREQUENCY,INSERTED_AT) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_REL_SCOPE_NOTIFICATION_MAIL_1),:REF_SCOPE_ID, :REF_NOTIFICATION_ID, :EMAIL, :FREQUENCY, SYSDATE());
    
    -- Abort inserting existing combination mail
    --elseIF (:REF_REL_SCOPE_NOTIFICATION_MAIL_ID = 0 AND :DEL = 0 and Notification_Mail_exist is not NULL) THEN
    

    -- Update existing row with new mail
else 
    MERGE INTO IDQ_RESULTS.REF_REL_SCOPE_NOTIFICATION_MAIL_1 AS TARGET
    USING 
    (SELECT :REF_REL_SCOPE_NOTIFICATION_MAIL_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.EMAIL <> :EMAIL THEN
            UPDATE SET EMAIL = :EMAIL;

            end if;
            commit;

            return 1;
END';