CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.SCHEDULER.SP_INSERT_SCHEDULER_MSTR_CUBE("MSTR_CUBE_ID" VARCHAR(250), "MSTR_PROJECT_ID" VARCHAR(250), "MSTR_CUBE_NAME" VARCHAR(250), "SOURCE_SYSTEM_TYPE_ID" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    let entry_exist INTEGER := null;
    SELECT count(1) INTO :entry_exist
    FROM SCHEDULER.MSTR_CUBE_1
        WHERE MSTR_CUBE_ID = :MSTR_CUBE_ID
        AND MSTR_PROJECT_ID = :MSTR_PROJECT_ID
        AND MSTR_CUBE_NAME = :MSTR_CUBE_NAME
        AND SOURCE_SYSTEM_TYPE_ID = :SOURCE_SYSTEM_TYPE_ID;
    IF (entry_exist > 0) THEN
        -- Cube already exists
        RETURN 0;
    END IF;
    
    INSERT INTO SCHEDULER.MSTR_CUBE_1 (MSTR_CUBE_ID, MSTR_PROJECT_ID, MSTR_CUBE_NAME, SOURCE_SYSTEM_TYPE_ID) VALUES (:MSTR_CUBE_ID, :MSTR_PROJECT_ID, :MSTR_CUBE_NAME, :SOURCE_SYSTEM_TYPE_ID);
    
    COMMIT;
    
END';
