CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.SCHEDULER.SP_UPDATE_SCHEDULER_MSTR_CUBE("ID" NUMBER(38,0), "MSTR_CUBE_ID" VARCHAR(250), "MSTR_PROJECT_ID" VARCHAR(250), "MSTR_CUBE_NAME" VARCHAR(250), "SOURCE_SYSTEM_TYPE_ID" NUMBER(38,0), "DEL_FLAG" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    IF (:DEL_FLAG = 1) THEN
        DELETE FROM SCHEDULER.MSTR_CUBE_1 WHERE ID = :ID;
    END IF;
    UPDATE SCHEDULER.MSTR_CUBE_1 SET MSTR_CUBE_ID = :MSTR_CUBE_ID, MSTR_CUBE_NAME = :MSTR_CUBE_NAME, SOURCE_SYSTEM_TYPE_ID = :SOURCE_SYSTEM_TYPE_ID WHERE ID = :ID;
    COMMIT;
END';
