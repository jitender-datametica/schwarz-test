BEGIN TRANSACTION;

DELETE FROM CORE.${TST_PREFIX}T_DIM_CHARGE_POINT_1;

INSERT INTO CORE.${TST_PREFIX}T_DIM_CHARGE_POINT_1 (RESOURCE_ITEM_SID, DWH_VALID_FROM_TMSP, DWH_VALID_TO_TMSP, DWH_VALID_FG, CHARGER_PROVIDER_SYSTEM_CD, CHARGER_RESOURCE_ITEM_SID, CHARGE_POINT_PLUGIN_TYPE_CD, CHARGE_POINT_PLUGIN_TYPE_NAME, CHARGE_POINT_POWER_TYPE_CD, CHARGE_POINT_POWER_TYPE_NAME, CHARGE_POINT_UUID_NR, CHARGE_POINT_CONNECTOR_LABEL_TXT, CHARGE_POINT_EVSE_NR, CHARGE_POINT_OCPP_ID, DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_SRC_FILE_NAME, DWH_SRC_1_TMSP)
SELECT RESOURCE_ITEM_SID,
       DWH_VALID_FROM_TMSP,
       DWH_VALID_TO_TMSP,
       CURRENT_TIMESTAMP BETWEEN DWH_VALID_FROM_TMSP AND DWH_VALID_TO_TMSP AS DWH_VALID_FG,
       CHARGER_PROVIDER_SYSTEM_CD,
       CHARGER_RESOURCE_ITEM_SID,
       CHARGE_POINT_PLUGIN_TYPE_CD,
       CHARGE_POINT_PLUGIN_TYPE_NAME,
       CHARGE_POINT_POWER_TYPE_CD,
       CHARGE_POINT_POWER_TYPE_NAME,
       CHARGE_POINT_UUID_NR,
       CONNECTOR_LABEL_TXT,
       EVSE_NR,
       OCPP_ID,
       DWH_CREATED_TMSP AS DWH_CREATED_TMSP,
       DWH_UPDATED_TMSP AS DWH_UPDATED_TMSP,
       DWH_SRC_FILE_NAME AS DWH_SRC_FILE_NAME,
       DWH_SRC_1_TMSP AS DWH_SRC_1_TMSP
  FROM(SELECT RESOURCE_ITEM_SID,
              DWH_VALID_FROM_TMSP,
              DATEADD(MILLISECOND, -1, LEAD(DWH_VALID_FROM_TMSP, 1, '9999-12-31 23:59:59.999') OVER (PARTITION BY RESOURCE_ITEM_SID ORDER BY DWH_VALID_FROM_TMSP)) AS DWH_VALID_TO_TMSP,
              CHARGER_PROVIDER_SYSTEM_CD,
              CHARGER_RESOURCE_ITEM_SID,
              CHARGE_POINT_PLUGIN_TYPE_CD,
              CHARGE_POINT_PLUGIN_TYPE_NAME,
              CHARGE_POINT_POWER_TYPE_CD,
              CHARGE_POINT_POWER_TYPE_NAME,
              CHARGE_POINT_UUID_NR,
              CONNECTOR_LABEL_TXT,
              EVSE_NR,
              OCPP_ID,
			  DWH_CREATED_TMSP,
			  DWH_UPDATED_TMSP,
			  DWH_SRC_FILE_NAME,
			  DWH_SRC_1_TMSP
         FROM(SELECT RESOURCE_ITEM_SID,
                     DWH_VALID_FROM_TMSP,
                     CHARGER_PROVIDER_SYSTEM_CD,
                     CHARGER_RESOURCE_ITEM_SID,
                     CHARGE_POINT_PLUGIN_TYPE_CD,
                     CHARGE_POINT_PLUGIN_TYPE_NAME,
                     CHARGE_POINT_POWER_TYPE_CD,
                     CHARGE_POINT_POWER_TYPE_NAME,
                     CHARGE_POINT_UUID_NR,
                     CONNECTOR_LABEL_TXT,
                     EVSE_NR,
                     OCPP_ID,
					 DWH_CREATED_TMSP,
					 DWH_UPDATED_TMSP,
					 DWH_SRC_FILE_NAME,
					 DWH_SRC_1_TMSP,
                     LAG(HASH_NR, 1, '#') OVER (PARTITION BY RESOURCE_ITEM_SID ORDER BY DWH_VALID_FROM_TMSP) != HASH_NR AS CHANGE_FG
                FROM(SELECT CPO.RESOURCE_ITEM_SID,
                            CPO.DWH_VALID_FROM_TMSP,
                            CPO.CHARGER_PROVIDER_SYSTEM_CD,
                            CPO.CHARGER_RESOURCE_ITEM_SID,      
                            CPO.CHARGE_POINT_PLUGIN_TYPE_CD,
                            CPGT.CHARGE_POINT_PLUGIN_TYPE_NAME,
                            CPPT.CHARGE_POINT_POWER_TYPE_CD,
                            CPPT.CHARGE_POINT_POWER_TYPE_NAME,
                            CPO.CHARGE_POINT_UUID_NR,
                            CPO.CONNECTOR_LABEL_TXT,
                            CPO.EVSE_NR,
                            CPO.OCPP_ID, 
                            MD5(COALESCE(CPO.CHARGER_PROVIDER_SYSTEM_CD, '1') || '^'
                                || COALESCE(CPO.CHARGER_RESOURCE_ITEM_SID, -1) || '^'
                                || COALESCE(CPO.CHARGE_POINT_PLUGIN_TYPE_CD, '-1') || '^'
                                || COALESCE(CPGT.CHARGE_POINT_PLUGIN_TYPE_NAME, '#') || '^'
                                || COALESCE(CPPT.CHARGE_POINT_POWER_TYPE_CD, '-1') || '^'
                                || COALESCE(CPPT.CHARGE_POINT_POWER_TYPE_NAME, '#') || '^'
                                || COALESCE(CPO.CHARGE_POINT_UUID_NR, '#') || '^'
                                || COALESCE(CPO.CONNECTOR_LABEL_TXT, '#') || '^'
                                || COALESCE(CPO.EVSE_NR, '#') || '^'
                                || COALESCE(CPO.OCPP_ID, -1)) AS HASH_NR,
                            CPO.DWH_CREATED_TMSP AS DWH_CREATED_TMSP,
                            GREATEST(CPO.DWH_UPDATED_TMSP, CPCT.DWH_UPDATED_TMSP, CPPT.DWH_UPDATED_TMSP) AS DWH_UPDATED_TMSP,
                            CPO.DWH_SRC_FILE_NAME,
                            CPO.DWH_SRC_1_TMSP							
                       FROM CORE_REL.T_CHARGE_POINT_1 CPO
                       JOIN CORE_REL.T_CHARGE_POINT_CONNECTOR_TYPE_1 CPCT
                         ON CPO.CHARGE_POINT_CONNECTOR_TYPE_ID = CPCT.CHARGE_POINT_CONNECTOR_TYPE_ID
                       JOIN CORE.T_DIM_CHARGE_POINT_POWER_TYPE_1 CPPT
                         ON CPPT.CHARGE_POINT_POWER_TYPE_CD = CPCT.POWER_TYPE_CD
                       JOIN CORE.T_DIM_CHARGE_POINT_PLUGIN_TYPE_1 CPGT
                         ON CPO.CHARGE_POINT_PLUGIN_TYPE_CD = CPGT.CHARGE_POINT_PLUGIN_TYPE_CD
                     )
             )
        WHERE CHANGE_FG = TRUE     
      )
;

COMMIT;
