BEGIN TRANSACTION;

DELETE FROM CORE.${TST_PREFIX}T_DIM_CHARGER_1;

INSERT INTO CORE.${TST_PREFIX}T_DIM_CHARGER_1 (RESOURCE_ITEM_SID, DWH_VALID_FROM_TMSP, DWH_VALID_TO_TMSP, DWH_VALID_FG, CHARGER_PROVIDER_SYSTEM_CD, CHARGING_STATION_OWNER_PARTY_SID, REAL_ESTATE_RESOURCE_ITEM_SID, CHARGER_STATION_TYPE_CD, CHARGER_STATION_TYPE_NAME, CHARGER_UUID_NR, CHARGER_LABEL_NR, PUBLIC_DISPLAY_NAME, DWH_CREATED_TMSP, DWH_UPDATED_TMSP, DWH_SRC_FILE_NAME, DWH_SRC_1_TMSP)
SELECT RESOURCE_ITEM_SID,
       DWH_VALID_FROM_TMSP,
       DWH_VALID_TO_TMSP,
       CURRENT_TIMESTAMP BETWEEN DWH_VALID_FROM_TMSP AND DWH_VALID_TO_TMSP AS DWH_VALID_FG,
       CHARGER_PROVIDER_SYSTEM_CD,
       CHARGING_STATION_OWNER_PARTY_SID,
       REAL_ESTATE_RESOURCE_ITEM_SID,
       CHARGER_STATION_TYPE_CD,
       CHARGER_STATION_TYPE_NAME,
       CHARGER_UUID_NR,
       LABEL_NR,
       PUBLIC_DISPLAY_NAME,
       DWH_CREATED_TMSP AS DWH_CREATED_TMSP,
       DWH_UPDATED_TMSP AS DWH_UPDATED_TMSP,
       DWH_SRC_FILE_NAME AS DWH_SRC_FILE_NAME,
       DWH_SRC_1_TMSP AS DWH_SRC_1_TMSP
  FROM(SELECT RESOURCE_ITEM_SID,
              DWH_VALID_FROM_TMSP,
              DATEADD(MILLISECOND, -1, LEAD(DWH_VALID_FROM_TMSP, 1, '9999-12-31 23:59:59.999') OVER (PARTITION BY RESOURCE_ITEM_SID ORDER BY DWH_VALID_FROM_TMSP)) AS DWH_VALID_TO_TMSP,
              CHARGER_PROVIDER_SYSTEM_CD,
              CHARGING_STATION_OWNER_PARTY_SID,
              REAL_ESTATE_RESOURCE_ITEM_SID,
              CHARGER_STATION_TYPE_CD,
              CHARGER_STATION_TYPE_NAME,
              CHARGER_UUID_NR,
              LABEL_NR,
              PUBLIC_DISPLAY_NAME,
			  DWH_CREATED_TMSP,
			  DWH_UPDATED_TMSP,
			  DWH_SRC_FILE_NAME,
			  DWH_SRC_1_TMSP
         FROM(SELECT RESOURCE_ITEM_SID,
                     DWH_VALID_FROM_TMSP,
                     CHARGER_PROVIDER_SYSTEM_CD,
                     CHARGING_STATION_OWNER_PARTY_SID,
                     REAL_ESTATE_RESOURCE_ITEM_SID,
                     CHARGER_STATION_TYPE_CD,
                     CHARGER_STATION_TYPE_NAME,
                     CHARGER_UUID_NR,
                     LABEL_NR,
                     PUBLIC_DISPLAY_NAME,
					 DWH_CREATED_TMSP,
					 DWH_UPDATED_TMSP,
					 DWH_SRC_FILE_NAME,
					 DWH_SRC_1_TMSP,
                     LAG(HASH_NR, 1, '#') OVER (PARTITION BY RESOURCE_ITEM_SID ORDER BY DWH_VALID_FROM_TMSP) != HASH_NR AS CHANGE_FG
                FROM(SELECT C.RESOURCE_ITEM_SID,
                            C.DWH_VALID_FROM_TMSP,
                            C.CHARGER_PROVIDER_SYSTEM_CD,
                            COALESCE(C.CHARGING_STATION_OWNER_PARTY_SID, -1) AS CHARGING_STATION_OWNER_PARTY_SID,
                            COALESCE(C.REAL_ESTATE_RESOURCE_ITEM_SID, -1) AS REAL_ESTATE_RESOURCE_ITEM_SID,
                            COALESCE(CPO.POWER_TYPE_CD, '-1') AS CHARGER_STATION_TYPE_CD,
                            COALESCE(CST.CHARGER_STATION_TYPE_NAME, 'Unbekannt') AS CHARGER_STATION_TYPE_NAME,
                            C.CHARGER_UUID_NR,
                            C.LABEL_NR,
                            COALESCE(C.PUBLIC_DISPLAY_NAME, 'Unbekannt') AS PUBLIC_DISPLAY_NAME,
                            MD5(COALESCE(CHARGER_PROVIDER_SYSTEM_CD, '-1') || '^'
                                || COALESCE(REAL_ESTATE_RESOURCE_ITEM_SID, -1) || '^'
                                || COALESCE(CPO.POWER_TYPE_CD, '-1') || '^'
                                || COALESCE(CST.CHARGER_STATION_TYPE_NAME, '#') || '^'
                                || COALESCE(CHARGER_UUID_NR, '#') || '^'
                                || COALESCE(LABEL_NR, '#') || '^'
                                || COALESCE(CHARGING_STATION_OWNER_PARTY_SID, -1) || '^'
                                || COALESCE(PUBLIC_DISPLAY_NAME, '#')) AS HASH_NR,
						    C.DWH_CREATED_TMSP,
							C.DWH_UPDATED_TMSP,
							C.DWH_SRC_FILE_NAME,
							C.DWH_SRC_1_TMSP
                       FROM CORE_REL.T_CHARGER_1 C
                       LEFT
                       JOIN(SELECT CPO.CHARGER_RESOURCE_ITEM_SID,
                                   MAX(CPCT.POWER_TYPE_CD) AS POWER_TYPE_CD
                              FROM CORE_REL.T_CHARGE_POINT_1 CPO
                              JOIN CORE_REL.T_CHARGE_POINT_CONNECTOR_TYPE_1 CPCT
                                ON CPO.CHARGE_POINT_CONNECTOR_TYPE_ID = CPCT.CHARGE_POINT_CONNECTOR_TYPE_ID
                             GROUP
                                BY 1
                           ) CPO
                         ON C.RESOURCE_ITEM_SID = CPO.CHARGER_RESOURCE_ITEM_SID 
                       LEFT
                       JOIN CORE.T_DIM_CHARGER_STATION_TYPE_1 CST
                         ON CPO.POWER_TYPE_CD = CST.CHARGER_STATION_TYPE_CD 
                    )
             )
        WHERE CHANGE_FG = TRUE
      )
 ;

COMMIT;
