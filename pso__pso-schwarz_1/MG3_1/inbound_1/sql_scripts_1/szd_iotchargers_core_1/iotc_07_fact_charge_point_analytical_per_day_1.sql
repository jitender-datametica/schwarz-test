BEGIN TRANSACTION;

DELETE FROM CORE.${TST_PREFIX}T_FACT_CHARGE_POINT_ANALYTICAL_PER_DAY_1;


INSERT INTO CORE.${TST_PREFIX}T_FACT_CHARGE_POINT_ANALYTICAL_PER_DAY_1 (REPORT_DT, CHARGER_PROVIDER_SYSTEM_CD, CHARGE_POINT_RESOURCE_ITEM_SID, CHARGER_RESOURCE_ITEM_SID, CHARGING_STATION_OWNER_PARTY_SID, REAL_ESTATE_RESOURCE_ITEM_SID, COUNTRY_LOCATION_SID, DIVISION_PARTY_SID, AUTHENTICATION_METHOD_CD, CHARGE_POINT_PLUGIN_TYPE_CD, CHARGE_POINT_POWER_TYPE_CD, CHARGER_STATION_TYPE_CD, CURR_CD, LOCAL_CURR_CD, TURNOVER_LOCAL_VAL, TURNOVER_EUR_VAL, PROVIDED_POWER_MEAS, CHARGING_PROCESS_CNT, CHARGING_DURATION_SEC_MEAS, CHARGING_PERFORMANCE_MEAS, DWH_CREATED_TMSP, DWH_UPDATED_TMSP)
SELECT TO_DATE(CL.END_LOCAL_TMSP) AS REPORT_DT,
       CL.CHARGER_PROVIDER_SYSTEM_CD,
       CL.CHARGE_POINT_RESOURCE_ITEM_SID,
       CL.CHARGER_RESOURCE_ITEM_SID,       
       COALESCE(CHG.CHARGING_STATION_OWNER_PARTY_SID, -1) AS CHARGING_STATION_OWNER_PARTY_SID,
       COALESCE(CHG.REAL_ESTATE_RESOURCE_ITEM_SID, -1) AS REAL_ESTATE_RESOURCE_ITEM_SID,
       COALESCE(RES.COUNTRY_LOCATION_SID, -1) AS COUNTRY_LOCATION_SID,
       COALESCE(RES.DIVISION_PARTY_SID, -1) AS DIVISION_PARTY_SID, 
       CASE WHEN UPPER(CPT.CHARGE_POINT_TARIFF_NAME) LIKE 'LIDL%'
            THEN 'LIDL-PLUS'
            WHEN UPPER(CPT.CHARGE_POINT_TARIFF_NAME) LIKE 'KAUFLAND%'
            THEN 'KFL-APP'
            WHEN CL.ROAMING_INTERFACE_CD = 'ENERGISED'
            THEN 'ICR'
            WHEN CL.ROAMING_INTERFACE_CD = 'COMMUNITY'
            THEN CASE WHEN UPPER(EMP.EMP_NAME) = 'VIRTUAL DIRECT PAYMENT PROVIDER'
                      THEN 'ADHOC'
                      ELSE 'RCOM'
                  END
            ELSE '-1'      
        END AS AUTHENTICATION_METHOD_CD,
        COALESCE(CPO.CHARGE_POINT_PLUGIN_TYPE_CD, '-1') AS CHARGE_POINT_PLUGIN_TYPE_CD,
        COALESCE(CPO.CHARGE_POINT_POWER_TYPE_CD, '-1') AS CHARGE_POINT_POWER_TYPE_CD,
        COALESCE(CHG.CHARGER_STATION_TYPE_CD, '-1') AS CHARGER_STATION_TYPE_CD,
        'EUR' AS CURR_CD,
        COALESCE(EXR.SOURCE_CURRENCY_CD , '-1') AS LOCAL_CURR_CD,
        SUM(COALESCE(CL.TOTAL_COST_VAL, 0)) AS TURNOVER_LOCAL_VAL,
        SUM(COALESCE(CL.TOTAL_COST_VAL / EXR.exchange_rate, 0)) AS TURNOVER_EUR_VAL,
        SUM(COALESCE(CL.METER_TOTAL_MEAS / 1000, 0)) AS PROVIDED_POWER_MEAS,
        SUM(1) AS CHARGING_PROCESS_CNT,
        SUM(TIMESTAMPDIFF(SECOND, START_LOCAL_TMSP, END_LOCAL_TMSP)) AS CHARGING_DURATION_SEC_MEAS,
        SUM(COALESCE(CL.METER_TOTAL_MEAS / 1000 / TIMESTAMPDIFF(SECOND, START_LOCAL_TMSP, END_LOCAL_TMSP) * 3600, 0)) AS CHARGING_PERFORMANCE_MEAS,
        CURRENT_TIMESTAMP AS DWH_CREATED_TMSP,
        CURRENT_TIMESTAMP AS DWH_UPDATED_TMSP 
  FROM CORE_REL.T_CHARGE_LOG_1 CL
  LEFT
  JOIN CORE_REL.T_EXCHANGE_RATE_1 EXR
    ON CL.INVOICE_CURR_CD = EXR.SOURCE_CURRENCY_CD
   AND EXR.TARGET_CURRENCY_CD = 'EUR'
   AND EXR.EXCHANGE_RATE_TYPE_CD = 'IOTCHARGER'
   AND CL.END_TMSP BETWEEN EXR.DWH_VALID_FROM_TMSP AND EXR.DWH_VALID_TO_TMSP 
  LEFT 
  JOIN CORE_REL.T_CHARGE_POINT_TARIFF_1 CPT
    ON CL.CHARGE_POINT_TARIFF_ID = CPT.CHARGE_POINT_TARIFF_ID
  LEFT
  JOIN CORE_REL.T_ELECTRO_MOBILITY_PROVIDER_1 EMP
    ON CL.EMP_PARTY_SID = EMP.PARTY_SID
  LEFT
  JOIN CORE.T_DIM_CHARGE_POINT_1 CPO
    ON CL.CHARGE_POINT_RESOURCE_ITEM_SID = CPO.RESOURCE_ITEM_SID 
   AND CPO.DWH_VALID_FG = TRUE
  LEFT
  JOIN CORE.T_DIM_CHARGER_1  CHG
    ON CL.CHARGER_RESOURCE_ITEM_SID = CHG.RESOURCE_ITEM_SID 
   AND CHG.DWH_VALID_FG = TRUE
  LEFT
  JOIN CORE.T_DIM_REAL_ESTATE_1 RES
    ON CHG.REAL_ESTATE_RESOURCE_ITEM_SID = RES.RESOURCE_ITEM_SID 
   AND RES.DWH_VALID_FG = TRUE
 WHERE CL.METER_TOTAL_MEAS >= 0
   AND CL.METER_TOTAL_MEAS < 150000
   AND TIMESTAMPDIFF(SECOND, START_LOCAL_TMSP, END_LOCAL_TMSP) > 0
 GROUP
    BY ALL
;

COMMIT;
