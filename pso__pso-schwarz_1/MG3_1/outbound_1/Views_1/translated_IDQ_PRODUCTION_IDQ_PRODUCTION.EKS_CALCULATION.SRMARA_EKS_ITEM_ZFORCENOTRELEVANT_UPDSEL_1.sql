zforcenotrelevant, zforcenotrelevantnew) AS SELECT stmara_eks_item.itemno,
 stmara_eks_item.zforcenotrelevant,
 eks_zsm_articlerelevancyoverride.forcenotrelevant AS zforcenotrelevantnew
