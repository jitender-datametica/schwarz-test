create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_AAD.MV_AAD_REQUEST_TYPE_SPR_ZU_1(
	REQUEST_TYPE_ID,
	REQUEST_TYPE_DESCR,
	REQUEST_TYPE_DESCR_DE,
	REQUEST_TYPE_DESCR_CZ,
	REQUEST_TYPE_DESCR_SK,
	REQUEST_TYPE_DESCR_HR,
	REQUEST_TYPE_DESCR_PL,
	REQUEST_TYPE_DESCR_RO,
	REQUEST_TYPE_DESCR_BG
) as 
-- 30.06.2023 staeblern Erstellen Sprachtabelle AAD_REQUEST_TYPE
SELECT v01.REQUEST_TYPE_ID
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.REQUEST_TYPE_DESCR END),'N/A') AS REQUEST_TYPE_DESCR                   
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.REQUEST_TYPE_DESCR END),'N/A') AS REQUEST_TYPE_DESCR_DE           
,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.REQUEST_TYPE_DESCR END), REQUEST_TYPE_DESCR_DE) AS REQUEST_TYPE_DESCR_CZ
,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.REQUEST_TYPE_DESCR END), REQUEST_TYPE_DESCR_DE) AS REQUEST_TYPE_DESCR_SK
,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.REQUEST_TYPE_DESCR END), REQUEST_TYPE_DESCR_DE) AS REQUEST_TYPE_DESCR_HR
,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.REQUEST_TYPE_DESCR END), REQUEST_TYPE_DESCR_DE) AS REQUEST_TYPE_DESCR_PL
,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.REQUEST_TYPE_DESCR END), REQUEST_TYPE_DESCR_DE) AS REQUEST_TYPE_DESCR_RO
,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.REQUEST_TYPE_DESCR END), REQUEST_TYPE_DESCR_DE) AS REQUEST_TYPE_DESCR_BG

FROM dbp_view.v_AAD_REQUEST_TYPE_SPR_ZU_1 v01
GROUP BY v01.REQUEST_TYPE_ID
UNION 
SELECT 0 AS REQUEST_TYPE_ID
,'' AS REQUEST_TYPE_DESCR                   
,'' AS REQUEST_TYPE_DESCR_DE           
,'' AS REQUEST_TYPE_DESCR_CZ
,'' AS REQUEST_TYPE_DESCR_SK
,'' AS REQUEST_TYPE_DESCR_HR
,'' AS REQUEST_TYPE_DESCR_PL
,'' AS REQUEST_TYPE_DESCR_RO
,'' AS REQUEST_TYPE_DESCR_BG
 ;