create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_EK_KUN.MV_KOMMUNIKATIONSKANAL_SPR_ZU_1(
	MANDANT_ID,
	KOMMUNIKATIONSKANAL_ID,
	KOMMUNIKATIONSKANAL_BEZ_EN,
	KOMMUNIKATIONSKANAL_BEZ,
	KOMMUNIKATIONSKANAL_BEZ_CZ,
	KOMMUNIKATIONSKANAL_BEZ_SK,
	KOMMUNIKATIONSKANAL_BEZ_HR,
	KOMMUNIKATIONSKANAL_BEZ_PL,
	KOMMUNIKATIONSKANAL_BEZ_RO,
	KOMMUNIKATIONSKANAL_BEZ_BG
) as
SELECT
 MANDANT_ID
,KOMMUNIKATIONSKANAL_ID
, MAX(CASE WHEN spr_id =  24            THEN KOMMUNIKATIONSKANAL_BEZ END) AS KOMMUNIKATIONSKANAL_BEZ_EN      --EN
, COALESCE(MAX(CASE WHEN spr_id = 22    THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ       --DE (Standard)
, COALESCE(MAX(CASE WHEN spr_id = 124   THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ_CZ    -- CZ
, COALESCE(MAX(CASE WHEN spr_id = 108   THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ_SK    -- SK
, COALESCE(MAX(CASE WHEN spr_id = 65    THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ_HR    -- HR
, COALESCE(MAX(CASE WHEN spr_id = 90    THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ_PL    -- PL
, COALESCE(MAX(CASE WHEN spr_id = 95    THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ_RO    -- RO
, COALESCE(MAX(CASE WHEN spr_id = 18    THEN KOMMUNIKATIONSKANAL_BEZ END), KOMMUNIKATIONSKANAL_BEZ_EN) AS KOMMUNIKATIONSKANAL_BEZ_BG    -- BG

FROM DBP_VIEW.V_KOMMUNIKATIONSKANAL_SPR_ZU_1
GROUP BY
 MANDANT_ID
,KOMMUNIKATIONSKANAL_ID;