	PROJEKT_ID,
	PROJEKT_ID_LFD_NR,
	PROJEKT_NR,
	PROJEKT_NR_ENDUNG,
	TECHN_PLATZ_ID,
	TECHN_PLATZ_EBENE_ID,
	MASSNAHME_KZ,
	MASSNAHME_ID,
	CPR_KATEGORIE_ID,
	PROJEKT_ANLASS_ID,
	PROJEKTART_ID,
	CPR_PROJEKT_GRUPPE_ID,
	DAT_FREIGABE,
	CPR_SUCHFELD,
	MANDANT_ID,
	WUP_ID,
	CPR_FILIALTYP_BEZ,
	CPR_STANDORT,
	CPR_PLZ,
	CPR_STR,
	CPR_VS,
	CPR_VW,
	REGION_ID,
	LAND_ID,
	MARKT_TYP_EA,
	MARKT_TYP_VP,
	KBL_NL_BEZ,
	CPR_BETREUER_NAME,
	OBJEKT_PLANER_NAME,
	PLAN_VERANTW_KZ,
