   SELECT
   
   
   
   pr.projekt_id, 
   pr.projekt_id  AS projekt_id_lfd_nr, 
   pr.cpr_ext_id  AS projekt_nr, 
   SUBSTRING(pr.cpr_ext_id, 14, 2) AS projekt_nr_endung, 
   TRIM(pr.techn_platz_id)  AS techn_platz_id, 
   2  AS techn_platz_ebene_id, 
   CASE WHEN SUBSTR( pr.massnahme_id, 1, 5) = 'ZPPM_' THEN SUBSTR(pr.massnahme_id,6,LENGTH(pr.massnahme_id)-5) ELSE pr.massnahme_id END AS massnahme_kz, 
   pr.massnahme_id, 
   pr.cpr_kategorie_id, 
   pr.projekt_anlass_id, 
   pr.projektart_id, 
   CAST(NULL AS VARCHAR(40))  AS cpr_projekt_gruppe_id, 
   pr.dat_freigabe, 
   su.cpr_suchfeld AS cpr_suchfeld,
   pr.mandant_id, 
   
   COALESCE(v01.aktuell_wup_id,pr.wup_id) AS wup_id, 
   pr.cpr_filialtyp_bez, 
   pr.cpr_standort, 
   pr.cpr_plz, 
   pr.cpr_str, 
   pr.cpr_vs,
   pr.cpr_vw, 
