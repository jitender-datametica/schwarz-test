	CPR_SYSTEMSTATUS2_ID,
	CPR_SYSTEMSTATUS3_ID,
	BAULEITER_NAME,
	BEARBEIT_EA_SOA_NAME,
	FACH_ING_NAME,
	GES_GRUND_FLAECHE_BEZ,
