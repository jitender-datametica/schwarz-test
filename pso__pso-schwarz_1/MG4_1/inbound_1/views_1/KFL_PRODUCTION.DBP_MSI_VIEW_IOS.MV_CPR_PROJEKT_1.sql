   pr.cpr_fachpl_kaelt_name, 
   pr.cpr_fachpl_sonst_name, 
   pr.cpr_gutachter_name, 
   pr.cpr_vermesser_name, 
   pr.cpr_fachin_tga_name, 
   pr.cpr_qual_sich_bau_name, 
   pr.cpr_qual_sich_haust_name, 
   pr.cpr_gj_ber, 
   pr.cpr_eig_proj, 
   pr.cpr_gu_ausbau AS cpr_gen_unt_ausb_name, 
   pr.einbau_kkv AS einbau_kkv, 
   CAST(NULL AS DATE)  AS dat_eroeffnung, 
   CAST(NULL AS DATE)  AS dat_teil_oeffentl, 
   CASE WHEN pr.kbl_nl_bez IS NOT NULL THEN  ((TRIM(pr.land_id) || ' / Region_1  ' || TRIM(pr.kbl_nl_bez) ))
        ELSE ((TRIM(pr.land_id) || ' / Region_1  ' ) )
          END  AS land_nl


   FROM dbp_view.v_cpr_projekt_per_1 pr
   INNER JOIN dbp_view.v_cpr_projekt_spr_zu_per_1 pr_spr
   ON pr.projekt_id = pr_spr.projekt_id
   AND pr.dat_bis = pr_spr.dat_bis
   LEFT JOIN dbp_view.v_l_cpr_suchfeld_1  su
   ON pr.cpr_suchfeld_id = su.cpr_suchfeld_id
   LEFT JOIN dbp_view.v_wup_1 v01
   ON pr.wup_id = v01.wup_id AND pr.mandant_id = v01.mandant_id 

   WHERE
   pr.dat_bis = '9999-12-31';