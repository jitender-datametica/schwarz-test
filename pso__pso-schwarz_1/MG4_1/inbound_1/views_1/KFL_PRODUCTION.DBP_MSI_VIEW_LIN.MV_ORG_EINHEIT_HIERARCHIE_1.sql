) as
SELECT V01.MANDANT_ID,
    V01.HR_OBJEKT_EBENE1_ID,
    V01.HR_OBJEKT_EBENE2_ID,
    V01.HR_OBJEKT_EBENE3_ID,
    V01.HR_OBJEKT_EBENE4_ID,
