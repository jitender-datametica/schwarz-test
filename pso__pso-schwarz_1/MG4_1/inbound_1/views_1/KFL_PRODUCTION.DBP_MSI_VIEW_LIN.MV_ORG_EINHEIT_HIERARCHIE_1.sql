FROM DBP_VIEW.V_ORG_EINHEIT_HIERARCHIE_1 V01
    INNER JOIN (
        SELECT V021.USER_ID,
            V021.HR_OBJEKT_EBENE1_ID,
            V021.MANDANT_ID
        FROM DBP_SECURITY.USER_HR_OBJEKT_ID_ZU_1 V021
            INNER JOIN DBP_MSI_DATA.AKT_MSI_USER_1 V022 ON V021.USER_ID = V022.USER_ID AND V022.session_id = current_session()
    ) V03 ON V01.HR_OBJEKT_EBENE1_ID = V03.HR_OBJEKT_EBENE1_ID
    AND V01.MANDANT_ID = V03.MANDANT_ID
    AND V01.SPR_ID = 22 
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY V01.MANDANT_ID,
        HR_OBJEKT_EBENE11_ID
        ORDER BY KJMO DESC NULLS LAST
    ) = 1;