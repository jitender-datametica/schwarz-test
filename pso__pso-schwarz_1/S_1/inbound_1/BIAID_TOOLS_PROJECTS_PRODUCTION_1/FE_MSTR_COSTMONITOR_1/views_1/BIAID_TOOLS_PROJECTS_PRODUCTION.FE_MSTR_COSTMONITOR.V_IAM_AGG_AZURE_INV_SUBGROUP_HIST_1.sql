create or replace view BIAID_TOOLS_PROJECTS_PRODUCTION.FE_MSTR_COSTMONITOR.V_IAM_AGG_AZURE_INV_SUBGROUP_HIST_1(
	CONTAINER_NAME,
	DWH_VALID_FROM,
	PROJECT_ID,
	PROJECT_SHORT_NAME,
	SOLUTION_ID,
	SOLUTION_NAME,
	STORAGE_ACCOUNT,
	SYSTEM_GROUP,
	SUB_GROUP,
	STORAGE_GB,
	IS_LAST_PER_MONTH
) as
select
    "CONTAINER_NAME",
    "DWH_VALID_FROM",
    "PROJECT_ID",
    "PROJECT_SHORT_NAME",
    "SOLUTION_ID",
    "SOLUTION_NAME",
    "STORAGE_ACCOUNT",
    "SYSTEM_GROUP",
    "SUB_GROUP",
    "STORAGE_GB",
    row_number() over (
        partition by "CONTAINER_NAME",
        "PROJECT_ID",
        "SOLUTION_ID",
        "STORAGE_ACCOUNT",
        "SYSTEM_GROUP",
        "SUB_GROUP",
        date_trunc('MONTH', DWH_VALID_FROM)
        order by DWH_VALID_FROM desc
    ) = 1 as IS_LAST_PER_MONTH
from
    "DATA"."T_IAM_AGG_AZURE_INV_SUBGROUP_HIST_1"
WHERE
    dwh_valid_from >= '2022-01-01';