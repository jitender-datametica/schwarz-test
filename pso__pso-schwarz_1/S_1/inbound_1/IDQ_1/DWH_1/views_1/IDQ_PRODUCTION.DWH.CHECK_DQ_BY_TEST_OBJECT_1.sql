create or replace view IDQ_PRODUCTION.DWH.CHECK_DQ_BY_TEST_OBJECT_1(
	CHECK_DQ_BY_TEST_OBJECT_ID,
	IDQ_TEST_OBJECT_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	CHECK_DQ_BY_TEST_OBJECT_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	PENALTY,
	SCORE,
	FIELD_AMOUNT,
	IS_USABLE,
	CHECK_DQ_BY_TEST_OBJECT_IS_CURRENT,
	IS_RELEVANT,
	REF_SOURCE_SYSTEM_ID
) as
SELECT 1                            AS CHECK_DQ_BY_TEST_OBJECT_ID
      ,CDTO.TEST_OBJECT_ID        AS IDQ_TEST_OBJECT_ID
      ,CDTO.BRANCH_ID             AS REF_BRANCH_ID
      ,CDTO.COUNTRY_ID            AS REF_COUNTRY_ID
      ,CDTO.SOURCE_SYSTEM_TYPE_ID AS REF_SOURCE_SYSTEM_TYPE_ID
      ,CDTO.TEST_OBJECT_TYPE_ID   AS REF_TEST_OBJECT_TYPE_ID
      ,CDTO.CALCULATION_TIME      AS CHECK_DQ_BY_TEST_OBJECT_CALCULATION_TIME
      ,CDTO.CALCULATION_DAY_ID    AS REF_TIME_CALCULATION_DAY_ID
      ,CDTO.PENALTY               AS PENALTY
      ,CDTO.SCORE                 AS SCORE
      ,CDTO.FIELD_AMOUNT          AS FIELD_AMOUNT
      ,CDTO.IS_USABLE             AS IS_USABLE
      ,1                            AS CHECK_DQ_BY_TEST_OBJECT_IS_CURRENT
      ,ITO.IS_RELEVANT            AS IS_RELEVANT
      ,ITO.SOURCE_SYSTEM_ID       AS REF_SOURCE_SYSTEM_ID
FROM idq_results.CHECK_DQ_BY_TEST_OBJECT_CURRENT_1 CDTO
INNER JOIN idq_results.IDQ_TEST_OBJECT_1 ITO
    ON CDTO.TEST_OBJECT_ID = ITO.ID
UNION ALL
SELECT 1                            AS CHECK_DQ_BY_TEST_OBJECT_ID
      ,CDTO.TEST_OBJECT_ID        AS IDQ_TEST_OBJECT_ID
      ,CDTO.BRANCH_ID             AS REF_BRANCH_ID
      ,CDTO.COUNTRY_ID            AS REF_COUNTRY_ID
      ,CDTO.SOURCE_SYSTEM_TYPE_ID AS REF_SOURCE_SYSTEM_TYPE_ID
      ,CDTO.TEST_OBJECT_TYPE_ID   AS REF_TEST_OBJECT_TYPE_ID
      ,CDTO.CALCULATION_TIME      AS CHECK_DQ_BY_TEST_OBJECT_CALCULATION_TIME
      ,CDTO.CALCULATION_DAY_ID    AS REF_TIME_CALCULATION_DAY_ID
      ,CDTO.PENALTY               AS PENALTY
      ,CDTO.SCORE                 AS SCORE
      ,CDTO.FIELD_AMOUNT          AS FIELD_AMOUNT
      ,CDTO.IS_USABLE             AS IS_USABLE
      ,0                            AS CHECK_DQ_BY_TEST_OBJECT_IS_CURRENT
      ,ITO.IS_RELEVANT            AS IS_RELEVANT
      ,ITO.SOURCE_SYSTEM_ID       AS REF_SOURCE_SYSTEM_ID
FROM idq_results.CHECK_DQ_BY_TEST_OBJECT_HISTORICAL_1 CDTO
INNER JOIN idq_results.IDQ_TEST_OBJECT_1 ITO
    ON CDTO.TEST_OBJECT_ID = ITO.ID
;