create or replace view IDQ_PRODUCTION.DWH.CHECK_ERROR_INFO_1(
	CHECK_ERROR_INFO_ID,
	CHECK_TEST_RESULT_ID,
	IDQ_TEST_OBJECT_ID,
	REF_RULE_ID,
	INVALID_CONTENT,
	ADDITIONAL_INFO,
	ADDITIONAL_INFO_DE,
	ADDITIONAL_INFO_EN,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_FIELD_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_TEST_OBJECT_TYPE_ID,
	NAT_SUPPLIER,
	INT_SUPPLIER,
	GUELTIG_BIS,
	NEG_COUNTRY,
	SUPPLIER_1,
	WERKNR,
	PS_SAP_NR,
	STANDORT,
	EINKAEUFER,
	LUE,
	LUE_GUELTIG_BIS
) as
SELECT ROW_NUMBER() OVER (ORDER BY IDQ_TEST_OBJECT_ID) AS CHECK_ERROR_INFO_ID, *
FROM (
	SELECT 10000 * Cast(CTR.TEST_OBJECT_ID as BigInt)+ CTR.RULE_ID  AS CHECK_TEST_RESULT_ID
		  ,CER.TEST_OBJECT_ID			                                      AS IDQ_TEST_OBJECT_ID
		  ,CER.RULE_ID				                                          AS REF_RULE_ID
		  ,CER.INVALID_CONTENT		                                      AS INVALID_CONTENT
		  ,CER.ADDITIONAL_INFO_DE		                                    AS ADDITIONAL_INFO
		  ,CER.ADDITIONAL_INFO_DE		                                    AS ADDITIONAL_INFO_DE
		  ,CER.ADDITIONAL_INFO_EN		                                    AS ADDITIONAL_INFO_EN
		  ,SRS.SOURCE_SYSTEM_TYPE_ID	                                  AS REF_SOURCE_SYSTEM_TYPE_ID
		  ,ITO.SOURCE_SYSTEM_ID		                                      AS REF_SOURCE_SYSTEM_ID
		  ,RR.FIELD_ID				                                          AS REF_FIELD_ID
		  ,ITO.BRANCH_ID				                                        AS REF_BRANCH_ID
		  ,ITO.COUNTRY_ID				                                        AS REF_COUNTRY_ID
		  ,ITO.TEST_OBJECT_TYPE_ID	                                    AS REF_TEST_OBJECT_TYPE_ID
          ,SPLIT_PART(ADDITIONAL_INFO, '|',1) as NAT_SUPPLIER
          ,SPLIT_PART(ADDITIONAL_INFO, '|',2) as INT_SUPPLIER
          ,substr(SPLIT_PART(ADDITIONAL_INFO, '|',3),0,19) as GUELTIG_BIS
          ,SPLIT_PART(ADDITIONAL_INFO, '|',4) as NEG_COUNTRY
          ,SPLIT_PART(ADDITIONAL_INFO, '|',5) as SUPPLIER_1
          ,substr(ADDITIONAL_INFO,6,4) as WERKNR
          ,SPLIT_PART(ADDITIONAL_INFO,'#',1) as PS_SAP_NR
          ,SPLIT_PART(ADDITIONAL_INFO,'#',2) as STANDORT
          ,SPLIT_PART(ADDITIONAL_INFO,'#',3) as EINKAEUFER
          ,SPLIT_PART(ADDITIONAL_INFO,'#',4) as LUE
          ,SPLIT_PART(ADDITIONAL_INFO,'#',5) as LUE_GUELTIG_BIS
	FROM idq_results.CHECK_ERROR_INFO_CURRENT_1 CER
	INNER JOIN idq_results.CHECK_TEST_RESULT_CURRENT_1 CTR
	  ON CER.TEST_OBJECT_ID = CTR.TEST_OBJECT_ID  AND  CER.RULE_ID = CTR.RULE_ID
	INNER JOIN idq_results.IDQ_TEST_OBJECT_1 AS ITO
	  ON CER.TEST_OBJECT_ID = ITO.ID
	INNER JOIN idq_results.REF_SOURCE_SYSTEM_1 AS SRS
	  ON ITO.SOURCE_SYSTEM_ID = SRS.ID
	INNER JOIN idq_results.REF_RULE_1 AS RR
	  ON CER.RULE_ID =  RR.ID
) ERROR_INFO
;