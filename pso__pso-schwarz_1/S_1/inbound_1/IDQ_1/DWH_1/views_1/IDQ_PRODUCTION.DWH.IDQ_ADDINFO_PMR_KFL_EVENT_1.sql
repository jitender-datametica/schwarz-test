create or replace view IDQ_PRODUCTION.DWH.IDQ_ADDINFO_PMR_KFL_EVENT_1(
	IDQ_ADDINFO_PMR_KFL_ITEM_ID,
	IDQ_TEST_OBJECT_ID,
	REF_BRANCH_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	IS_RELEVANT,
	EXT_ID,
	WERBUNGSTYP,
	WERBEMITTELART,
	WERBEMITTEL,
	COUNTRY_CODE,
	KUERZEL,
	GILT_VON,
	GILT_BIS
) as
SELECT
	ID AS IDQ_ADDINFO_PMR_KFL_ITEM_ID,
	TEST_OBJECT_ID AS IDQ_TEST_OBJECT_ID,
	BRANCH_ID  AS REF_BRANCH_ID,
	SOURCE_SYSTEM_PRIMARY_KEY  AS SOURCE_SYSTEM_PRIMARY_KEY,
	SOURCE_SYSTEM_ID  AS REF_SOURCE_SYSTEM_ID,
	COUNTRY_ID AS REF_COUNTRY_ID,
	IS_RELEVANT AS IS_RELEVANT,
	EXT_ID AS EXT_ID,
    WERBUNGSTYP AS WERBUNGSTYP,
    CONCAT(TACTIC_TYPE,' ',TACTIC_TYPE_DESC) AS WERBEMITTELART,
    CONCAT(TACTIC,' ',TACTIC_DESC)   AS WERBEMITTEL,
    COUNTRY_CODE AS COUNTRY_CODE,
    KUERZEL AS KUERZEL,
	GILT_VON AS GILT_VON,
	GILT_BIS AS GILT_BIS
	FROM IDQ_RESULTS.IDQ_ADDINFO_PMR_KFL_EVENT_1
	;