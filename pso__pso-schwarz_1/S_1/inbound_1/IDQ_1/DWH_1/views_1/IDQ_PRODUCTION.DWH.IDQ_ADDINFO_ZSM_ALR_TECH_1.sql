create or replace view IDQ_PRODUCTION.DWH.IDQ_ADDINFO_ZSM_ALR_TECH_1(
	IDQ_ADDINFO_ZSM_ALR_ID,
	IDQ_TEST_OBJECT_ID,
	REF_TEST_OBJECT_TYPE_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID,
	IS_RELEVANT,
	LIEFERANTENNUMMER,
	LIEFERANTENNAME,
	ARTIKELNUMMER,
	ARTIKELBEZEICHNUNG,
	BERECHTIGUNGSGRUPPE,
	ARTIKELART,
	WARENGRUPPE,
	GRUNDDATEN_STATUS
) as

select
	ADDI.ID 					AS IDQ_ADDINFO_ZSM_ALR_ID,
	ITO.ID 					AS 	IDQ_TEST_OBJECT_ID,
	ITO.TEST_OBJECT_TYPE_ID 	AS REF_TEST_OBJECT_TYPE_ID,
	ADDI.SOURCE_SYSTEM_PRIMARY_KEY,
	ADDI.SOURCE_SYSTEM_ID AS REF_SOURCE_SYSTEM_ID,
	ADDI.COUNTRY_ID AS REF_COUNTRY_ID,
	ADDI.BRANCH_ID AS REF_BRANCH_ID,
	ADDI.IS_RELEVANT,
	ADDI.Lieferantennummer,
	ADDI.Lieferantenname,
	ADDI.Artikelnummer,
	ADDI.Artikelbezeichnung,
	ADDI.Berechtigungsgruppe,
	ADDI.Artikelart,
	ADDI.Warengruppe,
	ADDI.Grunddaten_Status

FROM IDQ_RESULTS.IDQ_ADDINFO_ZSM_ALR_1 ADDI
	INNER JOIN IDQ_RESULTS.IDQ_TEST_OBJECT_1 ITO
	  ON	ADDI.SOURCE_SYSTEM_PRIMARY_KEY = ITO.SOURCE_SYSTEM_PRIMARY_KEY
		 AND ADDI.SOURCE_SYSTEM_ID = ITO.SOURCE_SYSTEM_ID
		 AND ADDI.COUNTRY_ID = ITO.COUNTRY_ID
		 AND ADDI.BRANCH_ID = ITO.BRANCH_ID
	WHERE ITO.TEST_OBJECT_TYPE_ID = 111
;