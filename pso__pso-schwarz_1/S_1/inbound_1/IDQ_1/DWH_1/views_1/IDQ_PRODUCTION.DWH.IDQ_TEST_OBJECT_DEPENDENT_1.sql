create or replace view IDQ_PRODUCTION.DWH.IDQ_TEST_OBJECT_DEPENDENT_1(
	DEPENDENT_IDQ_TEST_OBJECT_ID,
	LDO_NUM,
	SOURCE_SYSTEM_STATUS,
	IS_RELEVANT,
	FIRST_UNSUCCESSFUL_LOAD,
	REF_TIME_FIRST_UNSUCCESSFUL_LOAD_DAY_ID,
	IDQ_TEST_OBJECT_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	PENALTY,
	SCORE,
	FIELD_AMOUNT,
	IS_USABLE,
	DEPENDENT_REF_BRANCH_ID,
	DEPENDENT_SOURCE_SYSTEM_PRIMARY_KEY,
	DEPENDENT_REF_SOURCE_SYSTEM_ID,
	DEPENDENT_REF_COUNTRY_ID,
	DEPENDENT_NAME,
	DEPENDENT_REF_TEST_OBJECT_TYPE_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,
	DEPENDENT_FUNCTIONAL_ID
) as
SELECT
      distinct ITO.ID                          		AS DEPENDENT_IDQ_TEST_OBJECT_ID
      ,ITO.LDO_NUM					 		AS LDO_NUM
      ,ITO.SOURCE_SYSTEM_STATUS		 		AS SOURCE_SYSTEM_STATUS
      ,ITO.IS_RELEVANT				 		AS IS_RELEVANT
	  ,ITO.FIRST_UNSUCCESSFUL_LOAD     		AS FIRST_UNSUCCESSFUL_LOAD
	  ,ITO.FIRST_UNSUCCESSFUL_LOAD_DAY_ID     AS REF_TIME_FIRST_UNSUCCESSFUL_LOAD_DAY_ID
      ,CDTO.CALCULATION_TIME			 		AS IDQ_TEST_OBJECT_CALCULATION_TIME
	  ,CDTO.CALCULATION_DAY_ID   				AS REF_TIME_CALCULATION_DAY_ID
      ,CDTO.PENALTY					 		AS PENALTY
      ,CDTO.SCORE						 		AS SCORE
      ,CDTO.FIELD_AMOUNT				 		AS FIELD_AMOUNT
      ,CDTO.IS_USABLE					 		AS IS_USABLE
	  ,ITO.BRANCH_ID					 		AS DEPENDENT_REF_BRANCH_ID
      ,ITO.SOURCE_SYSTEM_PRIMARY_KEY	 		AS DEPENDENT_SOURCE_SYSTEM_PRIMARY_KEY
      ,ITO.SOURCE_SYSTEM_ID			 		AS DEPENDENT_REF_SOURCE_SYSTEM_ID
      ,ITO.COUNTRY_ID					 		AS DEPENDENT_REF_COUNTRY_ID
      ,ITO.NAME						 		AS DEPENDENT_NAME
      ,ITO.TEST_OBJECT_TYPE_ID		 		AS DEPENDENT_REF_TEST_OBJECT_TYPE_ID
      ,RSS.SOURCE_SYSTEM_TYPE_ID		 		AS DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID
	,case
		when ITO.FUNCTIONAL_ID is null
		then ITO.SOURCE_SYSTEM_PRIMARY_KEY
		else ITO.FUNCTIONAL_ID end   AS DEPENDENT_FUNCTIONAL_ID --new column FD

FROM idq_results.IDQ_TEST_OBJECT_1 ITO
INNER JOIN idq_results.REF_SOURCE_SYSTEM_1 RSS
  ON ITO.SOURCE_SYSTEM_ID = RSS.ID
LEFT JOIN idq_results.CHECK_DQ_BY_TEST_OBJECT_CURRENT_1 CDTO
  ON     ITO.ID = CDTO.TEST_OBJECT_ID
LEFT JOIN SYSCOMP.COMP_RECORD_LIST_1  CRL
	ON ITO.ID = CRL.DEPENDENT_TEST_OBJECT_ID
LEFT JOIN SYSCOMP.COMP_FIELD_RESULT_CURRENT_1 CFR
	ON ITO.ID = CFR.DEPENDENT_TEST_OBJECT_ID
	WHERE (MATCHING_STATUS_ID > 1
	or IS_ERROR_DETECTED = 1)
;