create or replace view IDQ_PRODUCTION.DWH.REF_FIELD_DEPENDENT_1(
	DEPENDENT_REF_FIELD_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,
	DEPENDENT_SOURCE_TABLE,
	DEPENDENT_FIELD_TECHNICAL_NAME,
	DEPENDENT_FIELD_NAME,
	DEPENDENT_FIELD_NAME_DE,
	DEPENDENT_FIELD_NAME_EN
) as
SELECT ID                      AS DEPENDENT_REF_FIELD_ID
      ,SOURCE_SYSTEM_TYPE_ID	 AS DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID
      ,SOURCE_TABLE			 AS DEPENDENT_SOURCE_TABLE
      ,TECHNICAL_NAME			 AS DEPENDENT_FIELD_TECHNICAL_NAME
	  ,NAME_DE				 AS DEPENDENT_FIELD_NAME
      ,NAME_DE				 AS DEPENDENT_FIELD_NAME_DE
      ,NAME_EN				 AS DEPENDENT_FIELD_NAME_EN
FROM idq_results.REF_FIELD_1
;