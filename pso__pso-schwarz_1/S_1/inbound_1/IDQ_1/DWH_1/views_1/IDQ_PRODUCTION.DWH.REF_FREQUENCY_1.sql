create or replace view IDQ_PRODUCTION.DWH.REF_FREQUENCY_1(
	REF_FREQUENCY_ID,
	FREQUENCY_NAME,
	FREQUENCY_NAME_DE,
	FREQUENCY_NAME_EN
) as
SELECT ID										AS REF_FREQUENCY_ID
      ,NAME_DE						AS FREQUENCY_NAME
      ,NAME_DE						AS FREQUENCY_NAME_DE
      ,NAME_EN						AS FREQUENCY_NAME_EN
FROM idq_results.REF_FREQUENCY_1
;