create or replace view IDQ_PRODUCTION.DWH.REF_REL_RULE_GROUP_RULE_1(
	REF_REL_RULE_GROUP_RULE_ID,
	REF_RULE_GROUP_ID,
	REF_RULE_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_FIELD_ID
) as
SELECT RRGR.ID                     AS REF_REL_RULE_GROUP_RULE_ID
      ,RRGR.RULE_GROUP_ID          AS REF_RULE_GROUP_ID
      ,RRGR.RULE_ID    		     AS REF_RULE_ID
      ,F.SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
      ,R.FIELD_ID				     AS REF_FIELD_ID
FROM idq_results.REF_REL_RULE_GROUP_RULE_1 RRGR
INNER JOIN idq_results.REF_RULE_1 R
  ON RRGR.RULE_ID = R.ID
INNER JOIN idq_results.REF_FIELD_1 F
  ON R.FIELD_ID =  F.ID
;