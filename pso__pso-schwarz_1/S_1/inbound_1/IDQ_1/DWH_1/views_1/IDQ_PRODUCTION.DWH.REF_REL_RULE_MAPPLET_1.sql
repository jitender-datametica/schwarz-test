create or replace view IDQ_PRODUCTION.DWH.REF_REL_RULE_MAPPLET_1(
	REF_REL_RULE_MAPPLET_ID,
	REF_RULE_ID,
	REF_MAPPLET_TYPE_ID,
	MAPPLET_FUNCTIONAL_CODE,
	MAPPLET_SEQUENCE
) as
SELECT ID                      AS REF_REL_RULE_MAPPLET_ID
      ,RULE_ID                 AS REF_RULE_ID
      ,MAPPLET_TYPE_ID         AS REF_MAPPLET_TYPE_ID
      ,MAPPLET_FUNCTIONAL_CODE AS MAPPLET_FUNCTIONAL_CODE
      ,MAPPLET_SEQUENCE		 AS MAPPLET_SEQUENCE
FROM idq_results.REF_REL_RULE_MAPPLET_1
;