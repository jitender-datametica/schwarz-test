create or replace view IDQ_PRODUCTION.DWH.REF_RULE_REPORTING_1(
	REF_RULE_ID,
	REF_RULE_ID_DE,
	REF_RULE_ID_EN,
	REF_RULE_TYPE_ID,
	CATALOG_ID,
	REF_FIELD_ID,
	RULE_TECHNICAL_NAME,
	RULE_SHORT_DESCRIPTION,
	RULE_SHORT_DESCRIPTION_DE,
	RULE_SHORT_DESCRIPTION_EN,
	RULE_DESCRIPTION,
	RULE_DESCRIPTION_DE,
	RULE_DESCRIPTION_EN,
	REF_CRITICALITY_ID,
	REF_DIMENSION_ID,
	ERROR_TEXT,
	ERROR_TEXT_DE,
	ERROR_TEXT_EN,
	VERSION,
	REF_STATUS_ID,
	FIRST_IDQ_RELEASE,
	REF_SOURCE_SYSTEM_TYPE_ID,
	SDC_OBJECT_ID
) as
SELECT RR.ID                    AS REF_RULE_ID
	  ,RR.ID                    AS REF_RULE_ID_DE
	  ,RR.ID                    AS REF_RULE_ID_EN
      ,RR.RULE_TYPE_ID          AS REF_RULE_TYPE_ID
      ,RR.CATALOG_ID            AS CATALOG_ID
      ,RR.FIELD_ID              AS REF_FIELD_ID
      ,RR.NAME                  AS RULE_TECHNICAL_NAME
      ,RR.SHORT_DESCRIPTION_DE  AS RULE_SHORT_DESCRIPTION
      ,RR.SHORT_DESCRIPTION_DE  AS RULE_SHORT_DESCRIPTION_DE
      ,RR.SHORT_DESCRIPTION_EN  AS RULE_SHORT_DESCRIPTION_EN
      ,RR.DESCRIPTION_DE        AS RULE_DESCRIPTION
      ,RR.DESCRIPTION_DE        AS RULE_DESCRIPTION_DE
      ,RR.DESCRIPTION_EN        AS RULE_DESCRIPTION_EN
      ,RR.CRITICALITY_ID        AS REF_CRITICALITY_ID
      ,RR.DIMENSION_ID          AS REF_DIMENSION_ID
      ,RR.ERROR_TEXT_DE         AS ERROR_TEXT
      ,RR.ERROR_TEXT_DE         AS ERROR_TEXT_DE
      ,RR.ERROR_TEXT_EN         AS ERROR_TEXT_EN
      ,RR.VERSION               AS VERSION
      ,RR.STATUS_ID             AS REF_STATUS_ID
      ,RR.FIRST_IDQ_RELEASE     AS FIRST_IDQ_RELEASE
      ,RF.SOURCE_SYSTEM_TYPE_ID AS REF_SOURCE_SYSTEM_TYPE_ID
	  ,'https://sdc-prod.sys.schwarz/MH-SDC/dg/index.jsp#/abvdl-component?objectViewType=DETAILS&objID=' + RR.SDC_OBJECT_ID		  AS SDC_OBJECT_ID
FROM idq_results.REF_RULE_1  RR
INNER JOIN idq_results.REF_FIELD_1 RF
  ON RR.FIELD_ID = RF.ID
WHERE RR.RULE_TYPE_ID=4
;