CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZITEM_BA_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_1 
SET  zArticleType = sr.zArticleTypeNew, zITEM_BA = zITEM_BANew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_LISTINGOVERVIEWMAX_zITEM_BA_UpdSel_1 AS sr
WHERE STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = sr.LISTINGOVERVIEWID and
STEKS_LISTINGOVERVIEWMAX.RECEIVINGCOUNTRY = sr.RECEIVINGCOUNTRY and 
STEKS_LISTINGOVERVIEWMAX.ITEMID = sr.ITEMID and
STEKS_LISTINGOVERVIEWMAX.casesize = sr.casesize;
END;
';