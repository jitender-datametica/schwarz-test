create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_LOCATION_UPDSEL_1(
	LISTINGOVERVIEWID,
	LOCATION_1,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE,
	CR_LOCATIONIDNEW,
	LOCATIONNEW
) as
SELECT   EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LOCATION_1,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CR_LOCATIONID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize,
         EKS.LISTINGOVERVIEW.CR_LOCATIONID AS CR_LOCATIONIDNew,
         EKS.LOCATION.SHORTSIGN            AS LOCATIONNew
  FROM   EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_1
         INNER JOIN EKS.LISTINGOVERVIEW_1
                 ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID =EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID
         INNER JOIN EKS.LOCATION_1
                 ON EKS.LISTINGOVERVIEW.CR_LOCATIONID = EKS.LOCATION.LOCATIONID

                 ;