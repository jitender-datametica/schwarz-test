create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_BA_UPDSEL_1(
	ZLEGACYMATKL,
	ZMATKL,
	ZLEGACYMATKLNEW,
	ZMATKLNEW,
	ITEMID
) as
SELECT
EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL,
EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL,
EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_BA_010.zLegacyMATKLNew,
EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_BA_010.zMATKLNew,
EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
FROM
EKS_CALCULATION.stMARA_EKS_ITEM_1
INNER JOIN
EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_BA_010_1 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.srMARA_EKS_ITEM_MATKL_Article_Type_BA_010.SORTITEMID
WHERE     (EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.BITFLAG = '2') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL IS NULL);