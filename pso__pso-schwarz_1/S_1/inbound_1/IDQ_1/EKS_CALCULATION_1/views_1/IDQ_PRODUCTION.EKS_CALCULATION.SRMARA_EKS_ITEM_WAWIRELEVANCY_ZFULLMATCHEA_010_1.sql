create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_WAWIRELEVANCY_ZFULLMATCHEA_010_1(
	ITEMID,
	ITEMNO,
	ZFULLMATCHNEW,
	ZISVALIDCONTRACT
) as
SELECT   EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
        EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO,
         1 AS zFullMatchNew,
         xtEKS_BASICINFO_RecCountry.zIsValidContract
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1
         INNER JOIN EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_1 as xtEKS_BASICINFO_RecCountry_1
                    On EKS_CALCULATION.STMARA_EKS_ITEM.ITEMNO = xtEKS_BASICINFO_RecCountry.ITEMNO
                    AND xtEKS_BASICINFO_RecCountry.SK_ITEMID IS NULL
  WHERE  ( xtEKS_BASICINFO_RecCountry.zIsValidContract = 1 and EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantMDM = 1) ;