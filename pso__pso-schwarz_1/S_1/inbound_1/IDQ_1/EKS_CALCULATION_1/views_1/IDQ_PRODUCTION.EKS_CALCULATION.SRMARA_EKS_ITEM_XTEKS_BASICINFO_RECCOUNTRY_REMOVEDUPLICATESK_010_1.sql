create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_REMOVEDUPLICATESK_010_1(
	LISTINGOVERVIEWID,
	SK_ITEMID,
	RECEIVINGCOUNTRY,
	CASESIZE,
	MAXDATE
) as
SELECT        EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID,
                EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID,
                EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry,
                EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize,
                         MAX(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL) AS MaxDate
FROM            EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_1 INNER JOIN
                         EKS.CONTRACTPRICEVALIDITY_1 ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID INNER JOIN
                         EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_1 AS P0 ON P0.ID = 'ADSFLGCHK' INNER JOIN
                         EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_1 AS P1 ON P1.ID = 'ADSFLGON' INNER JOIN
                         EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_1 AS P2 ON P2.ID = 'VALIDITYDATE' AND EKS.CONTRACTPRICEVALIDITY.DATEUNTIL >= P2.Date
WHERE        (EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID IS NOT NULL) AND (EKS.CONTRACTPRICEVALIDITY.ADSFLG = P0.Value) OR
                         (EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID IS NOT NULL) AND (P1.Value = 0)
GROUP BY EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize
HAVING        (MIN(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL) <> MAX(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL));