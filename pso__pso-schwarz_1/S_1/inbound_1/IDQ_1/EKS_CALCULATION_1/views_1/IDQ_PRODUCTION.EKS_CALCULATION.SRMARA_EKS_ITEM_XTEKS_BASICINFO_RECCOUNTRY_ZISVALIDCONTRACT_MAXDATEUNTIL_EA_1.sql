create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_ZISVALIDCONTRACT_MAXDATEUNTIL_EA_1(
	LISTINGOVERVIEWID,
	ITEMID,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	MAXDATEUNTIL
) as
SELECT        EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO,
                         MAX(EKS.CONTRACTPRICEVALIDITY.DATEUNTIL) AS MAXDATEUNTIL
FROM            EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_1 INNER JOIN
                         EKS.CONTRACTPRICEVALIDITY_1 ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID
WHERE        (EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID IS NULL)
GROUP BY EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry, EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO;