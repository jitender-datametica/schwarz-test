create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_ZISVALIDCONTRACT_RESETZISFOODZISVALIDCONSTRUCT_UPDSEL_1(
	ITEMID,
	LISTINGOVERVIEWID,
	CASESIZE,
	ITEMNO,
	SK_ITEMID,
	SK_ITEMNO,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	ZISVALIDCONTRACT,
	ZISFOOD,
	ZISVALIDCONSTRUCT,
	ZISVALIDCONTRACTNEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ITEMNO,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMNO,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsFood,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsValidConstruct,
         0 AS zIsValidContractNew
  FROM   EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_1
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_1
                 ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid = EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID
  WHERE  ( EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract = 1 )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsFood IS NULL )
          OR ( EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract = 1 )
             AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsValidConstruct = 0 );