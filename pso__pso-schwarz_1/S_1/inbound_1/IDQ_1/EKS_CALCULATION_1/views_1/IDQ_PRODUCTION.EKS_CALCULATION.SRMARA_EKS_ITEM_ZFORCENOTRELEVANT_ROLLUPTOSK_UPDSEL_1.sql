create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZFORCENOTRELEVANT_ROLLUPTOSK_UPDSEL_1(
	ITEMID,
	ZLEGACYMATNR,
	ZFORCENOTRELEVANT,
	ZFORCENOTRELEVANTNEW
) as
SELECT distinct SK.ITEMID,
         SK.zLegacyMATNR,
         SK.zForceNotRelevant,
         1 AS zForceNotRelevantNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1 AS SK
         INNER JOIN EKS.ITEMSORTING_1
                 ON SK.ITEMID = EKS.ITEMSORTING.SORTITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_1 AS EA
                 ON EKS.ITEMSORTING.ITEMID = EA.ITEMID
  WHERE  ( SK.zArticleType = 'SK' )
         AND ( EA.zArticleType = 'EA' )
         AND ( EA.zForceNotRelevant = 1 );