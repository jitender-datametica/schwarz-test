create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZHASVALIDMAXLU_UPDSEL_1(
	ITEMID,
	ZHASVALIDMAXLU,
	ZHASVALIDMAXLUNEW,
	ZRELEVANTLUIDNEW,
	ZRELEVANTLUID
) as

SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
        EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidMaxLU,
         1                                              AS zHasValidMaxLUNew,
         max(EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID) AS zRelevantLUIDNew,
         EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantLUID
        --, EKS.LISTINGITEM.LISTINGOVERVIEWID
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1
         INNER JOIN EKS.LISTINGITEM_1
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.LISTINGITEM.ITEMID
         INNER JOIN EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_1
                 ON EKS.LISTINGITEM.LISTINGOVERVIEWID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID
                    AND EKS.LISTINGITEM.ITEMID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID
                    group by EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidMaxLU,EKS_CALCULATION.STMARA_EKS_ITEM.zRelevantLUID;