create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISVALIDCONSTRUCTUPDSEL_1(
	ITEMID,
	ZISVALIDCONSTRUCT,
	ZISVALIDCONSTRUCTNEW
) as
SELECT
EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
EKS_CALCULATION.STMARA_EKS_ITEM.zIsValidConstruct,
cast (case when zArticleType = 'EA' and ifnull(zIsEAhasSK, 0) = 0 then 1 else ifnull(zIsEAhasBA, 0) or IfNULL(zIsEAhasSKhasBA, 0) or ifnull(zIsSKhasBA, 0) end  AS NUMBER(38,0))   AS   zIsValidConstructNew

FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1
WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsValidConstruct IS NULL ) ;