create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZITEM_BA_ARTICLE_TYPE_EA_01_UPDSEL_1(
	ITEMID,
	ITEMNO,
	BITFLAG,
	ZISEAHASBA,
	EXPR1,
	EXPR2,
	ZITEM_BA,
	ZITEM_BANEW
) as
SELECT distinct stMARA_EKS_ITEM.ITEMID,
         stMARA_EKS_ITEM.ITEMNO,
         stMARA_EKS_ITEM.BITFLAG,
         stMARA_EKS_ITEM.zIsEAhasBA,
         stMARA_EKS_ITEM_1.ITEMID  AS Expr1,
         stMARA_EKS_ITEM_1.BITFLAG AS Expr2,
         stMARA_EKS_ITEM.zITEM_BA,
         stMARA_EKS_ITEM_1.ITEMID  AS zITEM_BANew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1 AS stMARA_EKS_ITEM_1
         INNER JOIN EKS.ITEMSORTING_1
                 ON stMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_1 AS stMARA_EKS_ITEM_1
                 ON EKS.ITEMSORTING.SORTITEMID = stMARA_EKS_ITEM_1.ITEMID
  WHERE  ( stMARA_EKS_ITEM.BITFLAG = 0 )
         AND ( stMARA_EKS_ITEM.zIsEAhasBA = 1 )
         AND ( stMARA_EKS_ITEM_1.BITFLAG = 2 )
    QUALIFY ROW_NUMBER() OVER (PARTITION BY stMARA_EKS_ITEM.ITEMID ORDER BY zITEM_BANew) = 1;