create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRYUPDSEL_1(
	ITEMID,
	ZNEGOTIATINGCOUNTRY,
	ZNEGOTIATINGCOUNTRYNEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zNegotiatingCountry,
         EKS.COUNTRY.COUNTRYCODE AS zNegotiatingCountryNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_1
         INNER JOIN EKS.ITEMBUYEREL_1
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMBUYEREL.ITEMID
         INNER JOIN EKS.EMPLOYEE_1
                 ON EKS.ITEMBUYEREL.EMPLOYEEID = EKS.EMPLOYEE.EMPLOYEEID
         INNER JOIN EKS.COUNTRY_1
                 ON EKS.EMPLOYEE.COUNTRYID = EKS.COUNTRY.COUNTRYID
  WHERE  ( CAST(CURRENT_DATE() as TIMESTAMP_NTZ(9)) BETWEEN EKS.ITEMBUYEREL.DATEFROM AND EKS.ITEMBUYEREL.DATEUNTIL );