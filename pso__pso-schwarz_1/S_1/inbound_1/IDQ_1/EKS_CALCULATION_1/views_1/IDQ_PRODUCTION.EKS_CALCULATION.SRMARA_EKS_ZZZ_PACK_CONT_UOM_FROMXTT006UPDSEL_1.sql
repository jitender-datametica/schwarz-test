                  EKS_CALCULATION.XTT006_EKS_EKS_MM_ZSM_1 ON EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyZZ_PACK_CONT_UOM = EKS_CALCULATION.XTT006_EKS_EKS_MM_ZSM.LegacyValue
