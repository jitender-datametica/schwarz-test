	ITEMID,
	ZZZ_PACK_CONT_UOM,
	ZZZ_PACK_CONT_UOMNEW
) as
SELECT Distinct EKS_CALCULATION.STMARA_EKS_ITEM.itemid,
EKS_CALCULATION.STMARA_EKS_ITEM.zZZ_PACK_CONT_UOM,
EKS_CALCULATION.XTT006_EKS_EKS_MM_ZSM.TargetValue1 AS zZZ_PACK_CONT_UOMnew
