create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRWRF_MATGRP_SKU_EKS_ITEM_NODE_UPDSEL_1(
	ITEMID,
	ZNODENEW,
	ZNODE,
	ZLEGACYNODE
) as
SELECT distinct EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.ITEMID,
         ZSM.WRF_MATGRP_STRCT.NODE AS zNODENew,
         EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zNODE,
         EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE
  FROM   ZSM.WRF_MATGRP_STRCT_1
         INNER JOIN EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM_1
                 ON  CAST(SUBSTRING(ZSM.WRF_MATGRP_STRCT.LTEXT, 1, CHARINDEX(' ', ZSM.WRF_MATGRP_STRCT.LTEXT) - 1) AS nvarchar) = EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE
  WHERE  ( NOT ( EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE IS NULL ) ) and  ZSM.WRF_MATGRP_STRCT.SPRAS = 'D'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.ITEMID ORDER BY zNODENew) = 1;