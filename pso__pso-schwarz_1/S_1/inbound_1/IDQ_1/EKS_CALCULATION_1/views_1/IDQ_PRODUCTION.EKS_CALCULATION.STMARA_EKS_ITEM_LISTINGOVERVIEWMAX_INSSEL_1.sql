create or replace view IDQ_PRODUCTION.EKS_CALCULATION.STMARA_EKS_ITEM_LISTINGOVERVIEWMAX_INSSEL_1(
	LISTINGOVERVIEWID,
	LOCATION_1,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE
) as
select
MAX(t1.listingoverviewid) AS LISTINGOVERVIEWID,
'' AS LOCATION_1,
t3.SUPPLIERNO,
'' AS CR_LOCATIONID,
STEKS_LOCATION_1.SHORTSIGN AS ReceivingCountry,
t7.ITEMID,
t6.casesizecalc as CaseSize
from EKS.LISTINGOVERVIEW_1 t1_1
INNER JOIN EKS.CONTRACTLINK_1  t2 ON t1.LISTINGOVERVIEWID = t2.LISTINGOVERVIEWID
INNER JOIN EKS.SUPPLIER_1 t3 ON t1.supplierno = t3.SUPPLIERNO
INNER JOIN EKS.LOCATION_1 t4 ON t1.cr_locationid = t4.locationid
INNER JOIN EKS.LOCATION_1 AS STEKS_LOCATION_1 ON t2.LOCATIONID = STEKS_LOCATION_1.locationid
INNER JOIN EKS.CONTRACTPRICEREL_1 t5 ON t2.contractlinkid = t5.contractlinkid
INNER JOIN EKS.BASICPRICE_1 t6 ON t5.basicpriceid = t6.basicpriceid
INNER JOIN EKS.LISTINGITEM_1 t7 ON t6.listingitemid = t7.listingitemid
LEFT OUTER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_1 t8 ON t8.id = 'DRDATE'

WHERE (t2.statusid in (34, 86) ) AND t1.dateuntil >= t8.date
GROUP BY t3.supplierno, stEKS_LOCATION_1.shortsign, t7.itemid, t6.casesizecalc
having t3.supplierno <> 10236
;