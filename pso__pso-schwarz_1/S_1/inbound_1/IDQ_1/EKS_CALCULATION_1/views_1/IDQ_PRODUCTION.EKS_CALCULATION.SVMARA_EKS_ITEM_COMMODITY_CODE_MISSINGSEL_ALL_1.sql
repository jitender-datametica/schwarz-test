create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_COMMODITY_CODE_MISSINGSEL_ALL_1(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION_INT,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
			SELECT DISTINCT
			EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry,
			EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN,
			EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName,
			EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName,
			EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL,
			EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily,
			EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID,
			EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO,
			EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType,
			EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT,
			EKS.SUPPLIER.INTSUPPLIERNO AS SUPPLIERNO,
			EKS.SUPPLIER.DESCRIPTION AS SupplierDescription,
			EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM,
			EKS_CALCULATION.stMARA_EKS_ITEM.zSource,
			EKS_CALCULATION.stMARA_EKS_ITEM.zActive
	FROM    EKS_CALCULATION.stMARA_EKS_ITEM_1 LEFT OUTER JOIN
			EKS.ITEMINTRASTAT_1 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMINTRASTAT.ITEMID INNER JOIN
			EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMNO = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO INNER JOIN
			EKS.SUPPLIER_1 ON EKS.SUPPLIER.SUPPLIERNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO
	WHERE  (EKS.ITEMINTRASTAT.INTRASTAT IS NULL OR
			    EKS.ITEMINTRASTAT.INTRASTAT = '') AND (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1)
				AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND
					(EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID IN
							(SELECT ITEMID
							   FROM EKS_CALCULATION.svMARA_EKS_ITEM_EA_ReceivingCountry_1
							   WHERE(ReceivingCountry NOT IN ('US', 'LX', 'EW', 'CH'))))
							   AND (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry NOT IN ('US', 'LX', 'EW', 'CH'));