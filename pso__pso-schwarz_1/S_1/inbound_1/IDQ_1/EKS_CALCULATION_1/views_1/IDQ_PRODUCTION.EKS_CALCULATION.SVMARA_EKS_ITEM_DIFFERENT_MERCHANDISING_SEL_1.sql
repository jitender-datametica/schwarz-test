create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DIFFERENT_MERCHANDISING_SEL_1(
	ZSOURCE,
	ZACTIVE,
	NEGOTIATINGCOUNTRY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	MERCHANDISING_GROUP,
	BA_ITEM_NO,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	BUYERSHORTSIGN
) as
SELECT EKS_CALCULATION.stMARA_EKS_ITEM.zSource,
EKS_CALCULATION.stMARA_EKS_ITEM.zActive,
EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry,
EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID,
EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO,
EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType,
EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description,
EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL AS Merchandising_Group,
stMARA_EKS_ITEM_1.ITEMNO AS BA_Item_No,
EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName,
EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName,
EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN
FROM EKS_CALCULATION.stMARA_EKS_ITEM_1
INNER JOIN
	EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_02_Sel_1
ON EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA = EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_02_Sel.BAItemNumber
INNER JOIN
	EKS_CALCULATION.stMARA_EKS_ITEM_1 AS stMARA_EKS_ITEM_1
ON EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA = stMARA_EKS_ITEM_1.ITEMID
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL IS NOT NULL)
AND (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1)
ORDER BY BA_Item_No;