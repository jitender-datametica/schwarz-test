create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DQ_EKS_MEASUREMENTSANDCASEGROSSWEIGHTDIFFERENCES_010_1(
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE,
	ZNEGOTIATINGCOUNTRY,
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	DESCRIPTION_INT,
	ZMATKL,
	ARTICLEFAMILY,
	BUYERID,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	BUYERSHORTSIGN,
	CASESIZE,
	DECIMALCASESIZE,
	LISTINGOVERVIEWID,
	CASEDEPTH,
	CASEWIDTH,
	CASEHEIGHT,
	LENGTHUNIT,
	CASEGROSSWEIGHT,
	WEIGHTUNIT,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	RECEIVINGCOUNTRY,
	CONC,
	CONTRACTPRICEVALIDITYID
) as
SELECT DISTINCT
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM,
				  st.zSource, st.zActive, st.zNegotiatingCountry,
				  st.ITEMID, st.ITEMNO, st.zArticleType,
				  st.DESCRIPTION_INT, st.zMATKL,
				  st.ArticleFamily,
				  st.BuyerID,
				  st.BuyerFirstName,
                  st.BuyerLastName,
				  st.BuyerSHORTSIGN,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CaseSize,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID,
				  ITD.CASEDEPTH,
                  ITD.CASEWIDTH, ITD.CASEHEIGHT,
				  tr1.DESCRIPTION AS LengthUnit, iwg.CASEGROSSWEIGHT,
				  tr2.DESCRIPTION AS WeightUnit,
				  sup.INTSUPPLIERNO AS SUPPLIERNO,
				  sup.DESCRIPTION AS SupplierDescription,
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry,
--IFNULL(ITD.CASEDEPTH, '') + IFNULL(ITD.CASEWIDTH, '') + IFNULL(ITD.CASEHEIGHT, '') + IFNULL(tr1.DESCRIPTION, '') + IFNULL(iwg.CASEGROSSWEIGHT, '')
--+ IFNULL(tr2.DESCRIPTION, '') AS conc,
CONCAT(ITD.CASEDEPTH, ITD.CASEWIDTH, ITD.CASEHEIGHT,tr1.DESCRIPTION, iwg.CASEGROSSWEIGHT,tr2.DESCRIPTION)  AS conc, ITD.CONTRACTPRICEVALIDITYID
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS st
INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 ON (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMNO = st.itemno
				  AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.sk_itemno IS NULL AND st.zArticleType = 'EA') LEFT OUTER JOIN
                  EKS.ITEMDIMENSION_1 AS ITD ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID = ITD.CONTRACTPRICEVALIDITYID
				  AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMID = ITD.ITEMID LEFT OUTER JOIN
                  EKS.UNIT_1 AS un1 ON ITD.CASEUNITID = un1.UNITID LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_UNIT_1 AS tr1 ON un1.SHORTDESCID = tr1.TRANSLATIONID
				  LEFT OUTER JOIN
                      (SELECT CONTRACTPRICEVALIDITYID, ITEMID, CASEGROSSWEIGHT, CASEUNITID
                       FROM      EKS.ITEMWEIGHT_1
                       WHERE   (CONTRACTPRICEVALIDITYID IS NOT NULL) AND (ITEMID IS NOT NULL) AND (NOT (CASEUNITID IS NULL))) AS iwg ON
                  iwg.CONTRACTPRICEVALIDITYID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID AND iwg.ITEMID = ITD.ITEMID LEFT OUTER JOIN
                  EKS.UNIT_1 AS un2 ON iwg.CASEUNITID = un2.UNITID LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_UNIT_1 AS tr2 ON un2.SHORTDESCID = tr2.TRANSLATIONID LEFT OUTER JOIN
                  EKS.SUPPLIER_1 AS sup ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO = sup.SUPPLIERNO
UNION ALL
SELECT DISTINCT
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM,
				  st.zSource,  st.zActive, st.zNegotiatingCountry,
				  st.ITEMID, st.ITEMNO, st.zArticleType,
				  st.DESCRIPTION_INT, st.zMATKL, st.ArticleFamily, st.BuyerID, st.BuyerFirstName,
                  st.BuyerLastName, st.BuyerSHORTSIGN,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CaseSize,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, ITD.CASEDEPTH,
                  ITD.CASEWIDTH, ITD.CASEHEIGHT, tr1.DESCRIPTION AS LengthUnit, iwg.CASEGROSSWEIGHT, tr2.DESCRIPTION AS WeightUnit, /*sup.SUPPLIERNO, */ sup.INTSUPPLIERNO AS SUPPLIERNO, sup.DESCRIPTION AS SupplierDescription,
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry,
				  --IFNULL(ITD.CASEDEPTH, '') + IFNULL(ITD.CASEWIDTH, '') + IFNULL(ITD.CASEHEIGHT, '') + IFNULL(tr1.DESCRIPTION, '') + IFNULL(iwg.CASEGROSSWEIGHT, '')
                  --+ IFNULL(tr2.DESCRIPTION, '') AS conc,
				  CONCAT(ITD.CASEDEPTH, ITD.CASEWIDTH, ITD.CASEHEIGHT,tr1.DESCRIPTION, iwg.CASEGROSSWEIGHT,tr2.DESCRIPTION)  AS conc,
	              ITD.CONTRACTPRICEVALIDITYID
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1 AS st INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 ON (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.sk_ITEMNO = st.itemno) LEFT OUTER JOIN
                  EKS.ITEMDIMENSION_1 AS ITD ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID = ITD.CONTRACTPRICEVALIDITYID AND (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = ITD.ITEMID) LEFT OUTER JOIN
                  EKS.UNIT_1 AS un1 ON ITD.CASEUNITID = un1.UNITID LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_UNIT_1 AS tr1 ON un1.SHORTDESCID = tr1.TRANSLATIONID LEFT OUTER JOIN
                      (SELECT CONTRACTPRICEVALIDITYID, ITEMID, CASEGROSSWEIGHT, CASEUNITID
                       FROM      EKS.ITEMWEIGHT_1
                       WHERE   (CONTRACTPRICEVALIDITYID IS NOT NULL) AND (ITEMID IS NOT NULL) AND (NOT (CASEUNITID IS NULL))) AS iwg ON
                  iwg.CONTRACTPRICEVALIDITYID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID AND iwg.ITEMID = ITD.ITEMID LEFT OUTER JOIN
                  EKS.UNIT_1 AS un2 ON iwg.CASEUNITID = un2.UNITID LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_UNIT_1 AS tr2 ON un2.SHORTDESCID = tr2.TRANSLATIONID LEFT OUTER JOIN
                  EKS.SUPPLIER_1 AS sup ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO = sup.SUPPLIERNO;