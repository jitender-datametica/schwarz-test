create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DQ_EKS_MISSINGKOLLIGTIN_010_1(
	LISTINGOVERVIEWID
) as
SELECT DISTINCT EKS_CALCULATION.xtEKS_BASICINFO_UNION.LISTINGOVERVIEWID
FROM     EKS_CALCULATION.xtEKS_BASICINFO_UNION_1 LEFT OUTER JOIN
                      (SELECT EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID, MAX(EKS.ITEM.BRANDTYPEID) AS max_brandtype
                       FROM      EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 INNER JOIN
                                         EKS.ITEM_1 ON EKS.ITEM.BRANDTYPEID = '1' AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid = EKS.ITEM.ITEMID AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID IS NOT NULL
                       GROUP BY EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID) AS brandtype_1 ON brandtype.SK_ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid LEFT OUTER JOIN
                  EKS.ITEM_1 ON EKS.ITEM.BRANDTYPEID IN ('1') AND EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid = EKS.ITEM.ITEMID INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_1 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid LEFT OUTER JOIN
                  EKS.ITEMGTIN_1 AS ITG ON ITG.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid AND (EKS_CALCULATION.xtEKS_BASICINFO_UNION.casesize = CASE WHEN trunc(itg.CASESIZE, 0) = 0 THEN 1 ELSE trunc(itg.CASESIZE, 0) END OR
                  ITG.CASESIZE IS NULL OR
                  EKS_CALCULATION.xtEKS_BASICINFO_UNION.zArticleType = 'SK')
WHERE  (EKS.ITEM.BRANDTYPEID = 1) OR
                  (brandtype.max_brandtype = 1)
GROUP BY EKS_CALCULATION.xtEKS_BASICINFO_UNION.LISTINGOVERVIEWID
HAVING (COUNT(EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO) <> COUNT(ITG.GTIN)) AND
 (SUM(CASE WHEN no_gtin IS NULL THEN 1 ELSE no_gtin END) <> COUNT(EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO));