create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DQ_EKS_MISSINGKOLLIGTIN_SEL_ALL_1(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION_INT,
	DECIMALCASESIZE,
	KOLLIGTIN,
	LISTINGOVERVIEWID,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
SELECT DISTINCT
                  EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN,
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName,
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL,
                  EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID,
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT,
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, ITG.GTIN AS KolliGTIN,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID,
				  EKS.SUPPLIER.INTSUPPLIERNO AS SUPPLIERNO,
                  EKS.SUPPLIER.DESCRIPTION AS SupplierDescription,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM,
				  EKS_CALCULATION.stMARA_EKS_ITEM.zSource,
				  EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_1
INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_UNION_1 ON EKS_CALCULATION.xtEKS_BASICINFO_UNION.itemid = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
				  INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_1 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize = EKS_CALCULATION.xtEKS_BASICINFO_UNION.casesize
				  AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA' AND
                  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid OR
                  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'SK' AND EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID)
				  INNER JOIN
                  EKS_CALCULATION.svMARA_EKS_ITEM_DQ_EKS_MissingKolliGTIN_010_1 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = EKS_CALCULATION.svMARA_EKS_ITEM_DQ_EKS_MissingKolliGTIN_010.LISTINGOVERVIEWID
				  INNER JOIN
                  EKS.ITEM_1 ON EKS.ITEM.BRANDTYPEID IN ('1') AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid = EKS.ITEM.ITEMID
				  LEFT OUTER JOIN
                  EKS.SUPPLIER_1 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO
				  LEFT OUTER JOIN
                  EKS.ITEMGTIN_1 AS ITG ON ITG.ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID AND (ITG.CASESIZE = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize OR
                  ITG.CASESIZE IS NULL)
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) AND (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) AND (EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID IS NOT NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'SK');