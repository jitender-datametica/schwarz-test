
CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_SP_MATART("REF_MAIL_SP_MATART_ID" NUMBER(38,0), "MATART" VARCHAR(255), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE MATART_exist number(38,0);
BEGIN
MATART_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_SP_MATART_1 WHERE MATART = :MATART);
    IF (:DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_MAIL_SP_MATART_1 WHERE ID = :REF_MAIL_SP_MATART_ID;
      --  RETURN 0;
   -- END IF;
   
    -- INSERT NEW MATART
    elseIF (:REF_MAIL_SP_MATART_ID = 0 AND :DEL = 0 and MATART_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_MAIL_SP_MATART_1
        (ID,MATART) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_MAIL_SP_MATART_1),:MATART);
        -- RETURN 0;
    --END IF;
else 
    MERGE INTO IDQ_RESULTS.REF_MAIL_SP_MATART_1 AS TARGET
    USING 
    (SELECT :REF_MAIL_SP_MATART_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.MATART <> :MATART THEN
            UPDATE SET MATART = :MATART;

            end if;
            commit;

            return 1;
END';
