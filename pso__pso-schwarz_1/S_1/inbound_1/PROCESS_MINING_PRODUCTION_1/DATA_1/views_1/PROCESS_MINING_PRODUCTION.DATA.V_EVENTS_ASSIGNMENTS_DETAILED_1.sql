create or replace view PROCESS_MINING_PRODUCTION.DATA.V_EVENTS_ASSIGNMENTS_DETAILED_1(
	U_TASK_NUMBER,
	U_ORDER,
	U_ASSIGNED_AT,
	U_FINAL_ASSIGNMENT,
	U_ASSIGNMENT_GROUP_NAME,
	LAST_ASSIGNMENT_FLAG,
	U_ASSIGNMENT_REVOKED_AT,
	TIME_OPEN,
	TIME_WORK_IN_PROGRESS,
	TIME_WAITING,
	TIME_WAITING_FOR_ENDUSER
) as
select ASSIGNMENTS.u_task_number, ASSIGNMENTS.u_order, u_assigned_at,
u_final_assignment, ASSIGNMENTS.U_ASSIGNMENT_GROUP_NAME, last_assignment_flag, u_assignment_revoked_at, STATE_TIMES.TIME_OPEN, STATE_TIMES.TIME_WORK_IN_PROGRESS, STATE_TIMES.TIME_WAITING, STATE_TIMES.TIME_WAITING_FOR_ENDUSER
from data.v_events_assignments_min_1 AS ASSIGNMENTS
left join data.v_events_states_times_aggregated_1 as STATE_TIMES ON ASSIGNMENTS.u_task_number = STATE_TIMES.U_TASK_NUMBER
AND  ASSIGNMENTS.U_ASSIGNMENT_GROUP_NAME = STATE_TIMES.U_ASSIGNMENT_GROUP_NAME AND ASSIGNMENTS.U_ORDER = STATE_TIMES.U_ORDER;