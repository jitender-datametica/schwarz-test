create or replace view PROCESS_MINING_PRODUCTION.DATA.V_EVENTS_STATES_TIMES_AGGREGATED_PER_TICKET_HELPER_1(
	U_TASK_NUMBER,
	U_ASSIGNMENT_GROUP_NAME,
	TIME_NEW,
	TIME_OPEN,
	TIME_WORK_IN_PROGRESS,
	TIME_WAITING_FOR_ENDUSER,
	TIME_WAITING_FOR_EXTERNAL,
	TIME_WAITING_FOR_PROBLEM,
	TIME_TOTAL
) as
SELECT U_TASK_NUMBER, U_ASSIGNMENT_GROUP_NAME,
SUM(CASE WHEN EVENT = 'State - New' THEN DURATION ELSE 0 END) AS TIME_NEW,
SUM(CASE WHEN EVENT = 'State - Open' THEN DURATION ELSE 0 END) AS TIME_OPEN,
SUM(CASE WHEN EVENT = 'State - Work in progress' THEN DURATION ELSE 0 END) AS TIME_WORK_IN_PROGRESS,
--SUM(CASE WHEN EVENT LIKE 'State - Wait%' THEN DURATION ELSE 0 END) AS TIME_WAITING,
SUM(CASE WHEN EVENT LIKE 'State - Wait for enduser%' THEN DURATION ELSE 0 END) AS TIME_WAITING_FOR_ENDUSER,
SUM(CASE WHEN EVENT LIKE 'State - Wait for external%' THEN DURATION ELSE 0 END) AS TIME_WAITING_FOR_EXTERNAL,
SUM(CASE WHEN EVENT LIKE 'State - Wait for problem%' THEN DURATION ELSE 0 END) AS TIME_WAITING_FOR_Problem,
SUM(DURATION) AS TIME_TOTAL
from data.v_events_states_times_1
 GROUP BY U_TASK_NUMBER, U_ASSIGNMENT_GROUP_NAME;