create or replace view PROCESS_MINING_PRODUCTION.DATA_SHARED_SERVICE_SUPPORT.TASK_SLA_1(
	BUSINESS_DURATION_SECONDS,
	BUSINESS_DURATION,
	BUSINESS_PAUSE_DURATION_SECONDS,
	BUSINESS_PAUSE_DURATION,
	BUSINESS_PERCENTAGE,
	BUSINESS_TIME_LEFT_SECONDS,
	BUSINESS_TIME_LEFT,
	DURATION_SECONDS,
	DURATION,
	HAS_BREACHED,
	PAUSE_DURATION_SECONDS,
	PAUSE_DURATION,
	SLA,
	STAGE,
	TASK,
	SYS_ID,
	SYS_UPDATED_ON,
	CONTRACT_SLA_NAME,
	ORIGINAL_BREACH_TIME
) as
SELECT datediff('second','1970-01-01', T_TASK_SLA.BUSINESS_DURATION ) as BUSINESS_DURATION_SECONDS,  T_TASK_SLA.BUSINESS_DURATION, datediff('second','1970-01-01', GREATEST(T_TASK_SLA.BUSINESS_PAUSE_DURATION,'1970-01-01')) as BUSINESS_PAUSE_DURATION_SECONDS,
T_TASK_SLA.BUSINESS_PAUSE_DURATION , T_TASK_SLA.BUSINESS_PERCENTAGE,  datediff('second','1970-01-01', GREATEST(T_TASK_SLA.BUSINESS_TIME_LEFT, '1970-01-01') ) as BUSINESS_TIME_LEFT_SECONDS,T_TASK_SLA.BUSINESS_TIME_LEFT,datediff('second','1970-01-01', GREATEST(T_TASK_SLA.DURATION,'1970-01-01')) as DURATION_SECONDS, T_TASK_SLA.DURATION, T_TASK_SLA.HAS_BREACHED,
datediff('second','1970-01-01',  GREATEST(T_TASK_SLA.PAUSE_DURATION, '1970-01-01') ) as PAUSE_DURATION_SECONDS, T_TASK_SLA.PAUSE_DURATION, T_TASK_SLA.SLA, T_TASK_SLA.STAGE, T_TASK_SLA.TASK, T_TASK_SLA.SYS_ID, T_TASK_SLA.SYS_UPDATED_ON, T_CONTRACT_SLA.NAME AS CONTRACT_SLA_NAME, T_TASK_SLA.ORIGINAL_BREACH_TIME
FROM ETL.T_TASK_SLA_1
LEFT JOIN ETL.T_CONTRACT_SLA_1 ON
T_TASK_SLA.sla = T_CONTRACT_SLA.sys_id;