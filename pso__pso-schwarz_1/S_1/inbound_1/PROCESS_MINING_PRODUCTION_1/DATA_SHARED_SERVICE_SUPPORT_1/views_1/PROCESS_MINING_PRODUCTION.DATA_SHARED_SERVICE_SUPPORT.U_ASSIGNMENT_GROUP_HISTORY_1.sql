create or replace view PROCESS_MINING_PRODUCTION.DATA_SHARED_SERVICE_SUPPORT.U_ASSIGNMENT_GROUP_HISTORY_1(
	SYS_CREATED_ON,
	SYS_MOD_COUNT,
	U_ASSIGNED_AT,
	U_ASSIGNMENT_GROUP,
	U_ASSIGNMENT_REVOKED_AT,
	U_FINAL_ASSIGNMENT,
	U_ORDER,
	U_SYS_CLASS_NAME,
	U_TASK,
	SYS_ID,
	SYS_UPDATED_ON
) as
SELECT convert_timezone('UTC', 'Europe/Berlin', SYS_CREATED_ON) as SYS_CREATED_ON, SYS_MOD_COUNT, convert_timezone('UTC', 'Europe/Berlin', U_ASSIGNED_AT) as U_ASSIGNED_AT, U_ASSIGNMENT_GROUP, convert_timezone('UTC', 'Europe/Berlin', U_ASSIGNMENT_REVOKED_AT) as U_ASSIGNMENT_REVOKED_AT, U_FINAL_ASSIGNMENT, U_ORDER, U_SYS_CLASS_NAME, U_TASK, SYS_ID, convert_timezone('UTC', 'Europe/Berlin', SYS_UPDATED_ON) as SYS_UPDATED_ON FROM ETL.T_U_ASSIGNMENT_GROUP_HISTORY_1;