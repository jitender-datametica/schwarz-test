CREATE OR REPLACE VIEW FE_MSTR_BGE_PALETTIERER.V_REL_CAL_START_DT_TO_CAL_END_DT_1
AS
SELECT A1.cal_dt AS CAL_START_DT, B1.cal_dt AS CAL_END_DT
FROM
(SELECT cal_dt FROM "CORE"."T_DIM_CAL_DAY_1" WHERE cal_dt >= DATEADD(year, -1, CURRENT_DATE()) AND cal_dt <= CURRENT_DATE()) A1
CROSS JOIN
(SELECT cal_dt FROM "CORE"."T_DIM_CAL_DAY_1" WHERE cal_dt >= DATEADD(year, -1, CURRENT_DATE()) AND cal_dt <= CURRENT_DATE()) B1
WHERE B1.cal_dt >= A1.cal_dt
;