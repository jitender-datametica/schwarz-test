CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_DIM_MIXER_LINE_1(
	RESOURCE_ITEM_SID
	,PRODUCTION_LINE_RESOURCE_ITEM_SID
	,MIXER_LINE_CD
	,MIXER_LINE_NAME
) AS
SELECT
 MIX1.MIXER_LINE_CD AS RESOURCE_ITEM_SID
,PRL1.PRODUCTION_LINE_ID AS PRODUCTION_LINE_RESOURCE_ITEM_SID
,MIX1.MIXER_LINE_CD AS MIXER_LINE_CD
,MIX1.MIXER_LINE_NAME AS MIXER_LINE_NAME
FROM
CORE.T_DIM_MIXER_LINE_1 AS MIX1
JOIN CORE.T_DIM_PRODUCTION_LINE_1 AS PRL1
ON MIX1.PRODUCTION_LINE_RESOURCE_ITEM_SID = PRL1.RESOURCE_ITEM_SID
;