CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_DIM_PRODUCTION_LINE_PARAMETER_1(
	RESOURCE_ITEM_SID
	,PRODUCTION_LINE_PARAMETER_CD
	,PRODUCTION_LINE_PARAMETER_NAME
) AS
SELECT DISTINCT
 CONCAT(TO_CHAR(PRL1.PRODUCTION_LINE_ID),PRM1.PRODUCTION_LINE_PARAMETER_CD) AS RESOURCE_ITEM_SID
, PRODUCTION_LINE_PARAMETER_CD
, PRODUCTION_LINE_PARAMETER_NAME
FROM
CORE.T_DIM_PRODUCTION_LINE_PARAMETER_1 PRM1
JOIN CORE.T_DIM_PRODUCTION_LINE_1 PRL1
ON PRM1.PRODUCTION_LINE_RESOURCE_ITEM_SID = PRL1.RESOURCE_ITEM_SID
;