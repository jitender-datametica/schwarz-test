CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_DIM_TIMESTAMP_1(
	MEASUREMENT_TMSP
) AS
SELECT 
TIMESTAMP_TZ_FROM_PARTS(YEAR(V4.CAL_DT),MONTH(V4.CAL_DT),DAY(V4.CAL_DT),V1.HH,V2.MI,V3.SEC) AS MEASUREMENT_TMSP
FROM
 (SELECT ROW_NUMBER() OVER (ORDER BY seq4()) - 1 AS HH
  FROM 
   TABLE(generator(rowcount => 24))) AS V1
CROSS JOIN
 (SELECT ROW_NUMBER() OVER (ORDER BY seq4()) - 1 AS MI
  FROM 
  TABLE(generator(rowcount => 60))) AS V2
CROSS JOIN
 (SELECT ROW_NUMBER() OVER (ORDER BY seq4()) - 1 AS SEC
  FROM 
  TABLE(generator(rowcount => 60))) AS V3
CROSS JOIN
 (SELECT CAL_DT
  FROM CORE.T_DIM_CAL_DAY_1
  WHERE 
   CAL_DT BETWEEN DATEADD(MONTH,-24,CURRENT_DATE()) AND CURRENT_DATE()) AS V4
;