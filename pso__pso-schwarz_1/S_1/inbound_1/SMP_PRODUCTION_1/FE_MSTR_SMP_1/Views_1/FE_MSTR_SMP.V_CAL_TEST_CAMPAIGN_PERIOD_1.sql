create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_CAL_TEST_CAMPAIGN_PERIOD_1(
	CAMPAIGN_ID,
	COUNTRY_ID,
	DIVISION_ID,
	DAY_DT,
	CAL_DT_TRANS,
	CAMPAIGN_START_DT,
	CAMPAIGN_END_DT
) as (
	SELECT DISTINCT CAM.CAMPAIGN_ID
	,COUNTRY_ID
	,DIVISION_ID
	,CAL_DT
	,CASE 
		WHEN DURATION_IN_DAYS = 7
			THEN CAMPAIGN_START_DT - 28
		WHEN DURATION_IN_DAYS > 14
			THEN dateadd(day, (- 1 * (DURATION_IN_DAYS * 2)), CAMPAIGN_START_DT)
		ELSE CAMPAIGN_START_DT - 28
		END AS CAL_DT_TRANS
    ,CAMPAIGN_START_DT
    ,CAMPAIGN_END_DT
    FROM FE_MSTR_SMP.V_DIM_CALENDARDAY_1 CAL JOIN FE_MSTR_SMP.V_DIM_CAMPAIGN_1 CAM ON CAL.CAL_DT = CAM.CAMPAIGN_START_DT
	);
