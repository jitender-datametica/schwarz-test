create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_CAMPAIGN_GROUP_REL_1(
	CAMPAIGN_GROUP_ID,
	CAMPAIGN_GROUP_NAME,
	CAMPAIGN_ID,
	CAMPAIGN_NAME,
	COUNTRY_ID,
	DIVISION_ID
) as
SELECT RC.CAMPAIGN_GROUP_ID
	,CAMPAIGN_GROUP_NAME
	,CAMPAIGN_ID
	,CAMPAIGN_NAME
    ,RC.COUNTRY_ID
	,RC.DIVISION_ID
FROM CORE_REL.T_CAMPAIGN_1 RC
LEFT JOIN CORE_REL.T_CAMPAIGN_GROUP_1 RG 
ON RC.CAMPAIGN_GROUP_ID = RG.CAMPAIGN_GROUP_ID
AND RC.COUNTRY_ID = RG.COUNTRY_ID
AND RC.DIVISION_ID = RG.DIVISION_ID;
