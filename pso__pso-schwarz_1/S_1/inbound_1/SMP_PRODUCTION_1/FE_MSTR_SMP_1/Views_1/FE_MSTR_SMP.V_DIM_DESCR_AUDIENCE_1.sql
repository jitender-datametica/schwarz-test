create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_DESCR_AUDIENCE_1(
	COUNTRY_ID,
	DIVISION_ID,
	DESCR_AUDIENCE_ID,
	DESCR_AUDIENCE_NAME,
	DESCR_AUDIENCE_VALUE,
	DESCR_AUDIENCE_DESC,
	DESCR_AUDIENCE_TYPE_ID
) as (
	SELECT DISTINCT COUNTRY_ID
	,DIVISION_ID
	,DESCR_AUDIENCE_ID
	,DESCR_AUDIENCE_NAME
	,DESCR_AUDIENCE_VALUE
	,REPLACE(DESCR_AUDIENCE_VALUE, ' ABOVE MEDIAN', '') DESCR_AUDIENCE_DESC
	,DESCR_AUDIENCE_TYPE_ID FROM CORE_REL.T_DESCR_AUDIENCE_1 WHERE LEFT(DESCR_AUDIENCE_ID, 3) NOT IN (
		'ZIP'
		,'BUY'
		,'CLI'
		,'VIE'
	--	,'AGE'
		)
	AND DESCR_AUDIENCE_TYPE_ID in ('BUYING BEHAVIOUR', 'AGE', 'GENDER')
	);
