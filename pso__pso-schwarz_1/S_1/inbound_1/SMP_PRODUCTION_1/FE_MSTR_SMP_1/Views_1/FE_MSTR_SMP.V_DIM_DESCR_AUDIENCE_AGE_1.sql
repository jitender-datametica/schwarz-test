create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_DESCR_AUDIENCE_AGE_1(
	DESCR_AUDIENCE_ID,
	DESCR_AUDIENCE_NAME,
	DESCR_AUDIENCE_VALUE,
	DESCR_AUDIENCE_DESC
) as (
	SELECT DISTINCT
    DESCR_AUDIENCE_ID
	,DESCR_AUDIENCE_NAME
	,DESCR_AUDIENCE_VALUE
	,REPLACE(DESCR_AUDIENCE_VALUE, ' ABOVE MEDIAN', '') DESCR_AUDIENCE_DESC
    FROM CORE_REL.T_DESCR_AUDIENCE_1 WHERE 
     DESCR_AUDIENCE_TYPE_ID = 'AGE'
     UNION ALL
     SELECT DISTINCT 'AGE_ALL', 'All age groups', 'n/a', 'n/a' FROM CORE_REL.T_DESCR_AUDIENCE_1);
