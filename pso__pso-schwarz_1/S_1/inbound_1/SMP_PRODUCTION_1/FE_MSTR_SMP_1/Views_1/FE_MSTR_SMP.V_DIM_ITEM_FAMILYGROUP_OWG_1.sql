create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_ITEM_FAMILYGROUP_OWG_1(
	DIVISION_ID,
	COUNTRY_ID,
	ITEMFAMILYGRP_OWG_ID,
	ITEMFAMILYGRP_OWG_DESC
) as

SELECT DISTINCT DIVISION_ID
	,COUNTRY_ID
	,TAXONOMY_ID AS ITEMFAMILYGRP_OWG_ID
	,TAXONOMY_NAME AS ITEMFAMILYGRP_OWG_DESC
FROM CORE_REL.T_TAXONOMY_HIERARCHY_1
WHERE LEVEL = 3;
