create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_DIM_SUBITEMGRP_HWG_1(
	DIVISION_ID,
	COUNTRY_ID,
	SUBITEMGRP_HWG_ID,
	SUBITEMGRP_HWG_DESC
) as
SELECT DISTINCT
DIVISION_ID,
COUNTRY_ID,
TAXONOMY_ID AS SUBITEMGRP_HWG_ID,
TAXONOMY_NAME AS SUBITEMGRP_HWG_DESC
    FROM
    CORE_REL.T_TAXONOMY_HIERARCHY_1
    where level=2;
