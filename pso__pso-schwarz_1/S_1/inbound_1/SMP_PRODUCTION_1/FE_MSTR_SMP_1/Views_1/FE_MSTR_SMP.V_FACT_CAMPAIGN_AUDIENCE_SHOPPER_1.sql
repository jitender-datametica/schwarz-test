create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_CAMPAIGN_AUDIENCE_SHOPPER_1(
	COUNTRY_ID,
	DIVISION_ID,
	CAMPAIGN_ID,
	DESCR_AUDIENCE_ID,
	CNT_SHOPPER_CAMPAIGN,
	CNT_SHOPPER
) as
	WITH GOPA1 AS (
			SELECT DISTINCT DIM.CAMPAIGN_ID
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,SHOPPER.SHOPPER_ID
			FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FCT
			JOIN CORE_REL.T_CAMPAIGN_GTIN_1 C_GTIN ON FCT.COUNTRY_ID = C_GTIN.COUNTRY_ID
				AND FCT.DIVISION_ID = C_GTIN.DIVISION_ID
				AND FCT.GTIN_ID = C_GTIN.GTIN_ID
			JOIN CORE.T_DIM_CAMPAIGN_1 DIM ON FCT.COUNTRY_ID = DIM.COUNTRY_ID
				AND FCT.DIVISION_ID = DIM.DIVISION_ID
				AND FCT.GTIN_ID = C_GTIN.GTIN_ID
				AND FCT.DAY_DT <= DIM.CAMPAIGN_END_DT
				AND FCT.DAY_DT >= DIM.CAMPAIGN_START_DT
			JOIN EVAL.TMP_SHOPPER_SPECIAL_BEHAVIOUR_1 SHOPPER_1 ON FCT.COUNTRY_ID = SHOPPER.COUNTRY_ID
				AND FCT.DIVISION_ID = SHOPPER.DIVISION_ID
				AND FCT.SHOPPER_ID_REF = SHOPPER.SHOPPER_ID_REF
			WHERE FCT.DAY_DT BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
                    AND FCT.SHOPPER_ID_REF is not null
			)
,     CNT_CAMPAIGN
AS
(SELECT COUNTRY_ID
	,DIVISION_ID
	,CAMPAIGN_ID
    ,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_CAMPAIGN
    FROM GOPA1
    GROUP BY 1,2,3)

    
SELECT GOPA1.COUNTRY_ID
	,GOPA1.DIVISION_ID
	,GOPA1.CAMPAIGN_ID
	,MSDA.DESCR_AUDIENCE_ID
 /*   ,MAX(CASE WHEN da.descr_audience_type_id = 'AGE' THEN da.descr_audience_type_id ELSE NULL END) AS age
    ,MAX(CASE WHEN da.descr_audience_type_id = 'AGE' THEN da.descr_audience_id ELSE NULL END) AS age_id
    ,MAX(CASE WHEN da.descr_audience_type_id = 'AGE' THEN da.descr_audience_name ELSE NULL END) AS age_name
    ,MAX(CASE WHEN da.descr_audience_type_id = 'GENDER' THEN da.descr_audience_type_id ELSE NULL END) AS gender
    ,MAX(CASE WHEN da.descr_audience_type_id = 'GENDER' THEN da.descr_audience_id ELSE NULL END) AS gender_id
    ,MAX(CASE WHEN da.descr_audience_type_id = 'GENDER' THEN da.descr_audience_name ELSE NULL END) AS gender_name*/
    ,CNT_SHOPPER_CAMPAIGN
	,COUNT(DISTINCT GOPA1.SHOPPER_ID) AS CNT_SHOPPER
FROM CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_1 MSDA
JOIN GOPA1 ON GOPA1.COUNTRY_ID = MSDA.COUNTRY_ID
	AND GOPA1.DIVISION_ID = MSDA.DIVISION_ID
	AND GOPA1.SHOPPER_ID = MSDA.SHOPPER_ID
JOIN CNT_CAMPAIGN ON
GOPA1.COUNTRY_ID = CNT_CAMPAIGN.COUNTRY_ID
	AND GOPA1.DIVISION_ID = CNT_CAMPAIGN.DIVISION_ID
	AND GOPA1.CAMPAIGN_ID = CNT_CAMPAIGN.CAMPAIGN_ID
JOIN  core_rel.t_descr_audience_1 da
ON DA.division_id = MSDA.division_id
  AND DA.country_id = MSDA.country_id 
  AND DA.descr_audience_id = MSDA.descr_audience_id 
  AND DA.descr_audience_type_id IN ('BUYING BEHAVIOUR', 'AGE', 'GENDER')
GROUP BY GOPA1.CAMPAIGN_ID
	,GOPA1.COUNTRY_ID
	,GOPA1.DIVISION_ID 
    ,MSDA.DESCR_AUDIENCE_ID
    ,CNT_SHOPPER_CAMPAIGN;
