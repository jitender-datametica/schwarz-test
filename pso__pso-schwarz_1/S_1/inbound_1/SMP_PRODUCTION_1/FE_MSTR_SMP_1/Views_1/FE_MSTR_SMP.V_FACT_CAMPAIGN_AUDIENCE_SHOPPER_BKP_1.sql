create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_CAMPAIGN_AUDIENCE_SHOPPER_BKP_1(
	COUNTRY_ID,
	DIVISION_ID,
	CAMPAIGN_ID,
	DESCR_AUDIENCE_ID,
	CNT_SHOPPER_CAMPAIGN,
	CNT_SHOPPER
) as
	WITH GOPA1 AS (
			SELECT DISTINCT C_GTIN.GTIN_ID
				,DIM.CAMPAIGN_ID
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,SHOPPER.SHOPPER_ID
			FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FCT
			JOIN CORE_REL.T_CAMPAIGN_GTIN_1 C_GTIN ON FCT.COUNTRY_ID = C_GTIN.COUNTRY_ID
				AND FCT.DIVISION_ID = C_GTIN.DIVISION_ID
				AND FCT.GTIN_ID = C_GTIN.GTIN_ID
			JOIN CORE.T_DIM_CAMPAIGN_1 DIM ON FCT.COUNTRY_ID = DIM.COUNTRY_ID
				AND FCT.DIVISION_ID = DIM.DIVISION_ID
				AND FCT.GTIN_ID = C_GTIN.GTIN_ID
				AND FCT.DAY_DT <= DIM.CAMPAIGN_END_DT
				AND FCT.DAY_DT >= DIM.CAMPAIGN_START_DT
			JOIN EVAL.TMP_SHOPPER_SPECIAL_BEHAVIOUR_1 SHOPPER_1 ON FCT.COUNTRY_ID = SHOPPER.COUNTRY_ID
				AND FCT.DIVISION_ID = SHOPPER.DIVISION_ID
				AND FCT.SHOPPER_ID_REF = SHOPPER.SHOPPER_ID_REF
			WHERE FCT.DAY_DT BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)

SELECT GOPA1.COUNTRY_ID
	,GOPA1.DIVISION_ID
	,GOPA1.CAMPAIGN_ID
	,DA.DESCR_AUDIENCE_ID
	,(SELECT 
       COUNT(DISTINCT GOPA1.SHOPPER_ID)
    FROM GOPA1
    WHERE 
    GOPA1.COUNTRY_ID=    GOPA1.COUNTRY_ID
    AND
	GOPA1.DIVISION_ID=	GOPA1.DIVISION_ID
    AND
	GOPA1.CAMPAIGN_ID=	GOPA1.CAMPAIGN_ID
    )
		 AS CNT_SHOPPER_CAMPAIGN
	,--ADDITIONAL CNT NOT AGGREGATED BY AUDIENCE
	COUNT(DISTINCT GOPA1.SHOPPER_ID) AS CNT_SHOPPER
FROM CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_1 DA
JOIN GOPA1 ON GOPA1.COUNTRY_ID = DA.COUNTRY_ID
	AND GOPA1.DIVISION_ID = DA.DIVISION_ID
	AND GOPA1.SHOPPER_ID = DA.SHOPPER_ID
GROUP BY GOPA1.CAMPAIGN_ID,
DA.DESCR_AUDIENCE_ID
	,GOPA1.COUNTRY_ID
	,GOPA1.DIVISION_ID;
