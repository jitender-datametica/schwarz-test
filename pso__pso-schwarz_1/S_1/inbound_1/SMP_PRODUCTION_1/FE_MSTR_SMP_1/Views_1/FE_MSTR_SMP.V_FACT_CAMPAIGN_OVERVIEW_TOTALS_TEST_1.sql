create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_CAMPAIGN_OVERVIEW_TOTALS_TEST_1(
	CAMPAIGN_ID,
	DURATION_IN_DAYS,
	CAMPAIGN_TYPE_ID,
	CAMPAIGN_START_DT,
	CAMPAIGN_END_DT,
	ATTRIBUTION_END_DT,
	CHANNEL_ID,
	COUNTRY_ID,
	DIVISION_ID,
	STATUS_1,
	ADVERTISER_ID_SMP,
	ADVERTISER_BID_VAL,
	BUDGET_SPENT_VAL,
	VIEW_QTY,
	CLICK_QTY,
	SALES_QTY,
	CONVERSION_QTY,
	SHOPPER_QTY,
	BUDGET_VAL,
	SALES_VAL,
	LIFETIME_REVENUE_VAL,
	IMPRESSION_QTY
) as
SELECT 
CAMPAIGN_ID
,DATEDIFF(DAY, CAMPAIGN_START_DT, CAMPAIGN_END_DT) + 1 AS DURATION_IN_DAYS
,CAMPAIGN_TYPE_ID
,CAMPAIGN_START_DT
,CAMPAIGN_END_DT
,ATTRIBUTION_END_DT
,CHANNEL_ID
,COUNTRY_ID
,DIVISION_ID
,CASE 
	WHEN CURRENT_DATE BETWEEN CAMPAIGN_START_DT
			AND CAMPAIGN_END_DT
		THEN 'RUNNING'
	WHEN CURRENT_DATE > CAMPAIGN_END_DT
		THEN 'ENDED'
	WHEN CURRENT_DATE < CAMPAIGN_START_DT
		THEN 'NOT STARTED YET'
	END AS STATUS_1
,ADVERTISER_ID_SMP
,ADVERTISER_BID_VAL
,BUDGET_SPENT_VAL
,VIEW_QTY
,CLICK_QTY
,SALES_QTY
,CONVERSION_QTY
,SHOPPER_QTY
,BUDGET_VAL
,SALES_VAL
,LIFETIME_REVENUE_VAL
,IMPRESSION_QTY
FROM
CORE.T_DIM_CAMPAIGN_1
WHERE CAMPAIGN_START_DT >= '2023-01-01'
	AND CAMPAIGN_NAME NOT ILIKE '%TEST_1%';
