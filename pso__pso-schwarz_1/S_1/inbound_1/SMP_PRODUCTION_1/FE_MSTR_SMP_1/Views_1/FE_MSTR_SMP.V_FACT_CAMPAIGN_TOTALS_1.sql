create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_CAMPAIGN_TOTALS_1(
	REPORT_GENERATED_DATE,
	ADVERTISER_ID_SMP,
	CAMPAIGN_GROUP_NAME,
	CAMPAIGN_NAME,
	CAMPAIGN_ID,
	TYPE,
	DURATION_IN_DAYS,
	CAMPAIGN_START_DT,
	CAMPAIGN_END_DT,
	ATTRIBUTION_END_DT,
	CHANNEL,
	COUNTRY_ID,
	DIVISION_ID,
	UNIVERSE_SIZE,
	STATUS_1,
	PLANNED_VIEWS,
	PLANNED_UNIT_SOLD,
	BID,
	E_CPM,
	E_CPC,
	E_CPA,
	BUDGET,
	BUDGET_SPENT,
	PERCENT_BUDGET_SPENT,
	TOTAL_IMPRESSIONS,
	TOTAL_VIEWS,
	TOTAL_SHOPPERS_REACHED,
	VIEWABILITY,
	VIEW_FREQUENCY,
	TOTAL_CLICKS,
	CTR,
	TOTAL_UNITS_PURCHASED,
	CONVERSION_RATE,
	TOTAL_REVENUE,
	LIFETIME_REVENUE,
	ROAS,
	BASELINE_SALES,
	SALES_UPLIFT
) as


SELECT DISTINCT CURRENT_DATE AS REPORT_GENERATED_DATE
	,C.ADVERTISER_ID_SMP
    ,RG.CAMPAIGN_GROUP_NAME
	,'TOTAL' AS CAMPAIGN_NAME_
	,RG.CAMPAIGN_GROUP_ID AS CAMPAIGN_ID_
	,MIN(C.CAMPAIGN_TYPE_ID) AS CAMPAIGN_TYPE 
	,MAX(C.CAMPAIGN_END_DT)-MIN(C.CAMPAIGN_START_DT) AS DURATION_IN_DAYS
	,MIN(C.CAMPAIGN_START_DT) AS CAMPAIGN_START_DT
	,MAX(C.CAMPAIGN_END_DT) AS CAMPAIGN_END_DT
	,NULL AS ATTRIBUTION_END_DT
	,C.CHANNEL_ID AS CHANNEL
	,C.COUNTRY_ID
	,C.DIVISION_ID
	,NULL AS UNIVERSE_SIZE
	,CASE 
		WHEN CURRENT_DATE BETWEEN C.CAMPAIGN_START_DT
				AND C.CAMPAIGN_END_DT
			THEN 'RUNNING'
		WHEN CURRENT_DATE > C.CAMPAIGN_END_DT
			THEN 'ENDED'
		WHEN CURRENT_DATE < C.CAMPAIGN_START_DT
			THEN 'NOT STARTED YET'
		END AS STATUS_1
	,SUM(CASE 
		WHEN C.CAMPAIGN_TYPE_ID = 'CPM'
			THEN DIV0(C.BUDGET_VAL, C.ADVERTISER_BID_VAL) * 1000
		ELSE NULL
		END) AS PLANNED_VIEWS
	,NULL AS PLANNED_UNIT_SOLD
	,AVG(C.ADVERTISER_BID_VAL) AS BID
	,DIV0(SUM(C.BUDGET_SPENT_VAL), SUM(C.VIEW_QTY)) * 1000 E_CPM
	,DIV0(SUM(C.BUDGET_SPENT_VAL), SUM(C.CLICK_QTY)) E_CPC
	,DIV0(SUM(C.BUDGET_SPENT_VAL), SUM(C.SALES_QTY)) E_CPA
	,SUM(C.BUDGET_VAL) AS BUDGET
	,SUM(C.BUDGET_SPENT_VAL) AS BUDGET_SPENT
	,DIV0(SUM(C.BUDGET_SPENT_VAL), SUM(C.BUDGET_VAL)) AS PERCENT_BUDGET_SPENT
	,SUM(C.IMPRESSION_QTY) AS TOTAL_IMPRESSIONS
	,SUM(C.VIEW_QTY) AS TOTAL_VIEWS
	,SUM(C.SHOPPER_QTY) AS TOTAL_SHOPPERS_REACHED
	,DIV0(SUM(C.VIEW_QTY), SUM(C.IMPRESSION_QTY)) AS VIEWABILITY
	,DIV0(SUM(C.VIEW_QTY), SUM(C.SHOPPER_QTY)) AS VIEW_FREQUENCY
	,SUM(C.CLICK_QTY) AS TOTAL_CLICKS
	,DIV0(SUM(C.CLICK_QTY), SUM(C.VIEW_QTY)) AS CTR
	,SUM(C.SALES_QTY) AS TOTAL_UNITS_PURCHASED
	,DIV0(SUM(C.CONVERSION_QTY), SUM(C.CLICK_QTY)) AS CONVERSION_RATE
	,SUM(C.SALES_VAL) AS TOTAL_REVENUE
	,SUM(C.LIFETIME_REVENUE_VAL) AS LIFETIME_REVENUE
	,DIV0(SUM(C.SALES_VAL), SUM(C.BUDGET_SPENT_VAL)) AS ROAS
	,NULL AS BASELINE_SALES
	,NULL AS SALES_UPLIFT
FROM CORE.T_DIM_CAMPAIGN_1 C
 LEFT JOIN CORE_REL.T_CAMPAIGN_1  RC
            ON RC.CAMPAIGN_ID = C.CAMPAIGN_ID
        LEFT JOIN CORE_REL.T_CAMPAIGN_GROUP_1 RG
            ON RG.CAMPAIGN_GROUP_ID = RC.CAMPAIGN_GROUP_ID
    where C.campaign_start_dt >= '2023-01-01' 
        AND C.CAMPAIGN_NAME NOT ILIKE '%TEST_1%'
        AND RG.CAMPAIGN_GROUP_NAME IS NOT NULL
GROUP BY 1
	,2
	,3
	,4
	,5
	,10
	,11
    ,12,13,14,15;
