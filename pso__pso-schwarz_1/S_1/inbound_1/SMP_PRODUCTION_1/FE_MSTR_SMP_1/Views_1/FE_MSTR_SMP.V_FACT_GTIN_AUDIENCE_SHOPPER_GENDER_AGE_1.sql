create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_GTIN_AUDIENCE_SHOPPER_GENDER_AGE_1(
	GTIN_ID,
	COUNTRY_ID,
	DIVISION_ID,
	GENDER,
	AGE,
	CNT_SHOPPER_GTIN,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_GENDER AS (
			SELECT DISTINCT FCT.GTIN_ID
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_1 FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_1 DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) = 'GEN'
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_GTIN AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,GTIN_ID
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_GTIN
			FROM SHOPPERS_BY_GENDER
			GROUP BY 1
				,2
				,3
			)

SELECT SBG.GTIN_ID
	,SBG.COUNTRY_ID
	,SBG.DIVISION_ID
	,SBG.DESCR_AUDIENCE_ID AS GENDER
	,DA.DESCR_AUDIENCE_ID AS AGE
	,CNT_SHOPPER_GTIN
	,COUNT(SBG.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_GENDER SBG
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_1 DA ON SBG.COUNTRY_ID = DA.COUNTRY_ID
	AND SBG.DIVISION_ID = DA.DIVISION_ID
	AND SBG.SHOPPER_ID = DA.SHOPPER_ID
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) = 'AGE'
JOIN CNT_GTIN ON SBG.COUNTRY_ID = CNT_GTIN.COUNTRY_ID
	AND SBG.DIVISION_ID = CNT_GTIN.DIVISION_ID
	AND SBG.GTIN_ID = CNT_GTIN.GTIN_ID
GROUP BY SBG.GTIN_ID
	,SBG.COUNTRY_ID
	,SBG.DIVISION_ID
	,SBG.DESCR_AUDIENCE_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_GTIN;
