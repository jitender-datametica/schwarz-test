create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_KL_COUNTRY_ARTICLE_BUYER_NONBUYER_NONAGG_1(
	DAY_DT,
	COUNTRY_ID,
	ART_ID_REF_KL,
	BUYER
) as

SELECT DISTINCT DAY_DT
	,COUNTRY_ID
	,KL_ART_ID AS ART_ID_REF_KL
	,SHOPPER_ID_REF AS BUYER
FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FACT
LEFT OUTER JOIN DATA_SHARED_KFL.DBP_DATA_ART_1 ART_1 ON FACT.ART_ID_REF = ART.ART_ID
	AND ART.DAT_BIS = '9999-12-31'
WHERE DAY_DT BETWEEN CURRENT_DATE - 90
		AND CURRENT_DATE
	AND DIVISION_ID = 'KFL'
	AND SHOPPER_ID_REF IS NOT NULL;
