create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_KL_COUNTRY_GTIN_PRICE_1(
	COUNTRY_ID,
	GTIN_ID,
	KL_GTIN_ID,
	ART_ID_REF,
	ART_ID_REF_KL,
	VK_BRUTTO
) as
SELECT DISTINCT
    LAND.COUNTRY_ID,
    ART.GTIN_ID,
    ART.GTIN_ID AS KL_GTIN_ID,
    ART.ART_ID AS ART_ID_REF,
    ART.KL_ART_ID AS ART_ID_REF_KL,
    MAX(BON.VK_BRUTTO_OBB) OVER (PARTITION BY LAND.COUNTRY_ID, ART.KL_ART_ID) AS VK_BRUTTO
FROM
    DATA_SHARED_KFL.DBP_ODS_ODS_BON_VERKAUF_1 BON
INNER JOIN
    DATA_SHARED_KFL.DBP_DATA_ART_1 ART_1
ON
    BON.KL_ART_ID = ART.KL_ART_ID
    AND BON.MANDANT_ID = ART.MANDANT_ID
    AND ART.DAT_BIS = '9999-12-31'
LEFT JOIN
    CORE_REL.T_COUNTRY_1 LAND_1
ON
    BON.MANDANT_ID = LAND.DIVISION_COUNTRY_REF
    AND LAND.DIVISION_ID = 'KFL'
WHERE
    BON_DAT BETWEEN CURRENT_DATE - 90 AND CURRENT_DATE
    AND BON.MANDANT_ID IN (SELECT DIVISION_COUNTRY_REF FROM CORE_REL.T_COUNTRY_1 WHERE DIVISION_ID = 'KFL')
    AND BON.MENGE > 0
GROUP BY
    1, 2, 3, 4, 5, VK_BRUTTO_OBB;
