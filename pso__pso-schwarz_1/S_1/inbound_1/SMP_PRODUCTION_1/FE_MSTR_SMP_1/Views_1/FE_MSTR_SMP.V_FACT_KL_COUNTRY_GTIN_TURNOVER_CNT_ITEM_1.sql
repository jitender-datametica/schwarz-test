create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_KL_COUNTRY_GTIN_TURNOVER_CNT_ITEM_1(
	DAY_DT,
	COUNTRY_ID,
	GTIN_ID,
	KL_GTIN_ID,
	ART_ID_REF,
	ART_ID_REF_KL,
	LP_TURNOVER_GROSS,
	LP_TURNOVER_NET,
	LP_CNT_ITEM,
	BUYER,
	TURNOVER_GROSS,
	CNT_ITEM_1,
	VK_BRUTTO
) as

SELECT DAY_DT
	,FACT.COUNTRY_ID
	,FACT.GTIN_ID
    ,to_char(ART.GTIN_ID) AS KL_GTIN_ID
	,to_char(FACT.ART_ID_REF)
	,to_char(to_number(CASE 
		WHEN FACT.DIVISION_ID = 'KFL'
			THEN ART.KL_ART_ID
		ELSE ART_ID_REF
		END)) AS ART_ID_REF_KL
	,SUM(CASE 
			WHEN SHOPPER_ID_REF IS NOT NULL
				THEN SALES_GROSS_VAL
			ELSE 0
			END) AS LP_TURNOVER_GROSS
	,SUM(CASE 
			WHEN SHOPPER_ID_REF IS NOT NULL
				THEN SALES_NET_VAL
			ELSE 0
			END) AS LP_TURNOVER_NET
	,SUM(CASE 
			WHEN SHOPPER_ID_REF IS NOT NULL
				THEN SALES_PIECE_QTY
			ELSE 0
			END) AS LP_CNT_ITEM
    ,COUNT(DISTINCT SHOPPER_ID_REF) BUYER
	,SUM(SALES_GROSS_VAL) TURNOVER_GROSS
	,SUM(SALES_PIECE_QTY) CNT_ITEM_1
    ,SUM(SALES_GROSS_VAL)/SUM(SALES_PIECE_QTY) AS VK_BRUTTO
FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FACT
LEFT OUTER JOIN CORE_REL.T_COUNTRY_1 LAND_1 ON FACT.DIVISION_ID = LAND.DIVISION_ID
	AND FACT.COUNTRY_ID = LAND.COUNTRY_ID
LEFT OUTER JOIN DATA_SHARED_KFL.DBP_DATA_ART_1 ART_1 ON FACT.ART_ID_REF = ART.ART_ID
	AND FACT.DIVISION_ID = 'KFL'
	AND LAND.DIVISION_COUNTRY_REF = ART.MANDANT_ID
   AND  to_char(FACT.GTIN_ID) = to_char(ART.GTIN_ID)
	AND ART.DAT_BIS = '9999-12-31'
WHERE DAY_DT BETWEEN CURRENT_DATE - 366
		AND CURRENT_DATE
	AND FACT.DIVISION_ID = 'KFL'
	AND SALES_PIECE_QTY > 0
GROUP BY 1
	,2
	,3
	,4
	,5
    ,6;
