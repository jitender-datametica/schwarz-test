create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_KL_COUNTRY_GTIN_TURNOVER_CNT_ITEM_BKP_1(
	DAY_DT,
	COUNTRY_ID,
	GTIN_ID,
	ART_ID_REF,
	LP_TURNOVER_GROSS,
	LP_CNT_ITEM,
	TURNOVER_GROSS,
	CNT_ITEM_1
) as

SELECT DAY_DT
	,COUNTRY_ID
	,GTIN_ID
	,ART_ID_REF
    ,SUM(CASE WHEN SHOPPER_ID_REF IS NOT NULL THEN SALES_GROSS_VAL ELSE 0 END) AS LP_TURNOVER_GROSS
    ,SUM(CASE WHEN SHOPPER_ID_REF IS NOT NULL THEN SALES_PIECE_QTY ELSE 0 END) AS  LP_CNT_ITEM
    ,SUM(SALES_GROSS_VAL) TURNOVER_GROSS
	,SUM(SALES_PIECE_QTY) CNT_ITEM_1
FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FACT
WHERE DAY_DT BETWEEN CURRENT_DATE - 90
		AND CURRENT_DATE
	AND DIVISION_ID = 'KFL'
	AND SALES_PIECE_QTY > 0
GROUP BY DAY_DT
	,COUNTRY_ID
	,GTIN_ID
	,ART_ID_REF;
