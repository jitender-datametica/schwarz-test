create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_SALES_CAMPAIGN_PG_1(
	DIVISION_ID,
	COUNTRY_ID,
	CAMPAIGN_ID,
	CAMPAIGN_TYPE_ID,
	BANNER_ID,
	GTIN_ID,
	ARTICLE_NR_EXT,
	IROAS_PCT,
	INCR_CONVERSION,
	REGULAR_UNIT_PRICE,
	ACTUAL_UNIT_PRICE,
	AMOUNT_VAL,
	UNIT_QTY,
	BILLED_CONVERSIONS,
	CAMPAIGN_GTIN_RETAIL_UNIT_PRICE,
	INCR_REVENUE,
	CAMPAIGN_SPENT,
	CPA
) as (
	SELECT TAS.DIVISION_ID
	,TAS.COUNTRY_ID
	,TAS.CAMPAIGN_ID
	,TAS.CAMPAIGN_TYPE_ID
	,TAS.BANNER_ID
	,TAS.GTIN_ID
	,TAS.ARTICLE_NR_EXT
    ,TCS.IROAS_PCT
    ,SUM(TCS.INCR_CONVERSION) AS INCR_CONVERSION
	,MAX(TAS.REGULAR_UNIT_PRICE) AS REGULAR_UNIT_PRICE
	,MAX(TAS.ACTUAL_UNIT_PRICE) AS ACTUAL_UNIT_PRICE
	,SUM(TAS.AMOUNT_VAL) AS AMOUNT_VAL
	,SUM(TAS.UNIT_QTY) AS UNIT_QTY
	,SUM(TCS.INCR_CONVERSION * TAS.UNIT_QTY) AS BILLED_CONVERSIONS
	,MAX(TGT.CAMPAIGN_GTIN_REGULAR_UNIT_PRICE) AS CAMPAIGN_GTIN_RETAIL_UNIT_PRICE
	,SUM(TCS.INCR_CONVERSION * TGT.CAMPAIGN_GTIN_REGULAR_UNIT_PRICE) AS INCR_REVENUE
	,SUM(TDC.BUDGET_SPENT_VAL) AS CAMPAIGN_SPENT
	,SUM(TDC.BUDGET_SPENT_VAL / (TCS.INCR_CONVERSION * TAS.UNIT_QTY)) AS CPA
    FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_1 TAS 
    JOIN CORE.T_AB_CAMPAIGN_SETUP_1 TCS 
        ON TAS.DIVISION_ID = TCS.DIVISION_ID
	       AND TAS.CAMPAIGN_ID = TCS.CAMPAIGN_ID
	       AND TAS.COUNTRY_ID = TCS.COUNTRY_ID 
    JOIN CORE_REL.T_CAMPAIGN_GTIN_1 TGT 
        ON TGT.COUNTRY_ID = TAS.COUNTRY_ID
	       AND TGT.DIVISION_ID = TAS.DIVISION_ID
	       AND TGT.CAMPAIGN_ID = TAS.CAMPAIGN_ID
	       AND TGT.GTIN_ID = TAS.GTIN_ID 
    JOIN CORE.T_DIM_CAMPAIGN_1 TDC
        ON TDC.COUNTRY_ID = TAS.COUNTRY_ID
	       AND TDC.DIVISION_ID = TAS.DIVISION_ID
	       AND TDC.CAMPAIGN_ID = TAS.CAMPAIGN_ID
    GROUP BY TAS.DIVISION_ID
	,TAS.COUNTRY_ID
	,TAS.CAMPAIGN_ID
	,TAS.CAMPAIGN_TYPE_ID
	,TAS.BANNER_ID
	,TAS.GTIN_ID
	,TAS.ARTICLE_NR_EXT
    ,TCS.IROAS_PCT
	);
