create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_SALES_GTIN_DAY_TEST_1(
	DIVISION_ID,
	COUNTRY_ID,
	DAY_DT,
	GTIN_ID,
	CAMPAIGN_ID,
	SALES_PIECE_QTY
) as
(
SELECT
FACT.DIVISION_ID
,FACT.COUNTRY_ID
,CAL.DAY_DT
,FACT.GTIN_ID
,CAMPAIGN_ID
,sum(FACT.SALES_PIECE_QTY) 
--,CASE WHEN FACT.DAY_DT BETWEEN CAL.CAL_DT_TRANS and CAL.DAY_DT THEN sum(FACT.SALES_PIECE_QTY)  ELSE NULL END PRE_PERIOD_QTY
--,CASE WHEN FACT.DAY_DT BETWEEN CAL.CAMPAIGN_START_DT and CAL.CAMPAIGN_END_DT THEN sum(FACT.SALES_PIECE_QTY)  ELSE NULL END TEST_PERIOD_QTY
FROM
FE_MSTR_SMP.V_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FACT
JOIN
FE_MSTR_SMP.V_REL_TEST_CAMPAIGN_PERIOD_1 CAL
ON
FACT.DAY_DT >= CAL.CAL_DT_TRANS
and
FACT.DAY_DT <= CAL.DAY_DT
AND 
FACT.DIVISION_ID = CAL.DIVISION_ID
AND 
FACT.COUNTRY_ID = CAL.COUNTRY_ID
AND 
FACT.GTIN_ID = CAL.GTIN_ID
GROUP BY
FACT.DIVISION_ID
,FACT.COUNTRY_ID
,CAL.DAY_DT
,CAMPAIGN_ID
,FACT.GTIN_ID
);
