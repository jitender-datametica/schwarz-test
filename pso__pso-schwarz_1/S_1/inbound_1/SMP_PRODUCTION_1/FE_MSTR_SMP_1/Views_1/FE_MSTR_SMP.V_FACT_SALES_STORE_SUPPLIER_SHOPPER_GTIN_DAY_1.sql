create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1(
	DIVISION_ID,
	COUNTRY_ID,
	DIVISION_COUNTRY_REF,
	DAY_DT,
	STORE_ID_REF,
	SUPPLIER_ID_REF,
	SHOPPER_ID_REF,
	GTIN_ID,
	ART_ID_REF,
	ART_ID_REF_KL,
	CY_WEEK,
	CY_MONTH,
	CY_YEAR,
	SALES_GROSS_VAL,
	SALES_NET_VAL,
	SALES_PIECE_QTY,
	DISCOUNT_PIECE_QTY
) as (
	SELECT FACT.DIVISION_ID
	,FACT.COUNTRY_ID
	,FACT.DIVISION_COUNTRY_REF
	,FACT.DAY_DT
	,FACT.STORE_ID_REF
	,FACT.SUPPLIER_ID_REF
	,FACT.SHOPPER_ID_REF
	,FACT.GTIN_ID
	,FACT.ART_ID_REF
	,CASE 
		WHEN FACT.DIVISION_ID = 'KFL'
			THEN ART.KL_ART_ID
		ELSE ART_ID_REF
		END AS ART_ID_REF_KL
	,FACT.CY_WEEK
	,FACT.CY_MONTH
	,FACT.CY_YEAR
	,FACT.SALES_GROSS_VAL
	,FACT.SALES_NET_VAL
	,FACT.SALES_PIECE_QTY
	,FACT.DISCOUNT_PIECE_QTY FROM CORE.T_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_1 FACT
	/*LEFT OUTER JOIN CORE_REL.t_country_1 LAND_1
ON
FACT.DIVISION_COUNTRY_REF = LAND.DIVISION_COUNTRY_REF
AND FACT.DIVISION_ID = LAND.DIVISION_ID
AND FACT.COUNTRY_ID = LAND.COUNTRY_ID*/
	LEFT OUTER JOIN DATA_SHARED_KFL.DBP_DATA_ART_1 ART_1 ON FACT.DIVISION_ID = 'KFL'
	AND FACT.DIVISION_COUNTRY_REF = ART.mandant_id
	AND FACT.ART_ID_REF = ART.ART_ID
	AND FACT.DAY_DT >= ART.DAT_VON
	AND FACT.DAY_DT <= ART.DAT_BIS
	);
