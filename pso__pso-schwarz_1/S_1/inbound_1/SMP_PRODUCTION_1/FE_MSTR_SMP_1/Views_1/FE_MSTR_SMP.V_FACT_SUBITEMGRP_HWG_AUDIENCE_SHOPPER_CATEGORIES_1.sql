create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_SUBITEMGRP_HWG_AUDIENCE_SHOPPER_CATEGORIES_1(
	SUBITEMGRP_HWG,
	COUNTRY_ID,
	DIVISION_ID,
	DESCR_AUDIENCE_ID,
	CNT_SHOPPER_FAMILYGRP_OWG,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_AUDIENCE AS (
			SELECT DISTINCT a14.SUBITEMGRP_HWG
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_1 FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_1 DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
					'GEN'
					,'AGE'
					,'VIE'
					,'ZIP'
					)
			join	FE_MSTR_SMP.V_DIM_ITEM_1	a12
				on 	(FCT.COUNTRY_ID = a12.COUNTRY_ID and 
				FCT.DIVISION_ID = a12.DIVISION_ID and 
				FCT.GTIN_ID = a12.GTIN_ID)
			join	FE_MSTR_SMP.V_REL_WG_ITEMFAMILY_OWG_1	a13
				on 	(a12.COUNTRY_ID = a13.COUNTRY_ID and 
				a12.DIVISION_ID = a13.DIVISION_ID and 
				a12.TAXONOMY_ID = coalesce(a13.WG, a13.FAMILYGRP_OWG, a13.WG))
			join	FE_MSTR_SMP.V_REL_ITEMGRP_WG_FAMILYGROUP_OWG_1	a14
				on 	(a13.COUNTRY_ID = a14.COUNTRY_ID and 
				a13.DIVISION_ID = a14.DIVISION_ID and 
				a13.FAMILYGRP_OWG = a14.FAMILYGRP_OWG)
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_SUBITEMGRP_HWG AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,SUBITEMGRP_HWG
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_SUBITEMGRP_HWG
			FROM SHOPPERS_BY_AUDIENCE
			GROUP BY 1
				,2
				,3
			)

SELECT SBA.SUBITEMGRP_HWG
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_SUBITEMGRP_HWG
	,COUNT(DISTINCT SBA.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_AUDIENCE SBA
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_1 DA ON SBA.COUNTRY_ID = DA.COUNTRY_ID
	AND SBA.DIVISION_ID = DA.DIVISION_ID
	AND SBA.SHOPPER_ID = DA.SHOPPER_ID
JOIN CNT_SUBITEMGRP_HWG ON SBA.COUNTRY_ID = CNT_SUBITEMGRP_HWG.COUNTRY_ID
	AND SBA.DIVISION_ID = CNT_SUBITEMGRP_HWG.DIVISION_ID
	AND SBA.SUBITEMGRP_HWG = CNT_SUBITEMGRP_HWG.SUBITEMGRP_HWG
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
		'GEN'
		,'AGE'
		,'VIE'
		,'ZIP'
		)
GROUP BY SBA.SUBITEMGRP_HWG
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_SUBITEMGRP_HWG;
