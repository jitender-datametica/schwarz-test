CREATE OR REPLACE FUNCTION SNOWCONVERT.PUBLIC.TIMESTAMP_ADD_UDF("A" TIMESTAMP_NTZ(9), "B" TIMESTAMP_NTZ(9), "OP" VARCHAR(1))
RETURNS TIMESTAMP_NTZ(9)
LANGUAGE SQL
AS '
CASE WHEN OP = ''+'' THEN
 TIMESTAMPADD(YEAR, YEAR(B), TIMESTAMPADD(MONTH, MONTH(B), TIMESTAMPADD(DAY, DAY(B), TIMESTAMPADD(SECOND, SECOND(B), TIMESTAMPADD(MINUTE, MINUTE(B), TIMESTAMPADD(HOUR, HOUR(B), A))))))
ELSE
 TIMESTAMPADD(YEAR, 0-YEAR(B), TIMESTAMPADD(MONTH, 0-MONTH(B), TIMESTAMPADD(DAY, 0-DAY(B), TIMESTAMPADD(SECOND, 0-SECOND(B), TIMESTAMPADD(MINUTE, 0-MINUTE(B), TIMESTAMPADD(HOUR, 0-HOUR(B), A))))))
END
';