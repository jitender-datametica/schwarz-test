CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_COUNTRY_POLITICAL_1(
	 COUNTRY_POL_CD
	,COUNTRY_POL_NAME
	,CURR_CD
) AS SELECT
     iso_country_cd AS COUNTRY_POL_CD
	,country_name_de AS COUNTRY_POL_NAME
	,CURR_CD
FROM
  CORE.T_DIM_COUNTRY_POLITICAL_1
WHERE
    dwh_valid_fg = TRUE  
;