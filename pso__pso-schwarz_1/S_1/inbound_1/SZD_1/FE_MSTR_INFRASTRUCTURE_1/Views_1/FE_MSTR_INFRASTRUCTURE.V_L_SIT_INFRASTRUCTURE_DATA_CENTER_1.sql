CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_DATA_CENTER_1(
	DATA_CENTER_SID
	,DATA_CENTER_MOID
	,DATA_CENTER_NAME
) AS SELECT
   DT1.DATA_CENTER_SID
  ,DT1.DATA_CENTER_MOID
  ,DT1.DATA_CENTER_NAME
FROM
  CORE.T_DIM_DATA_CENTER DT1
  JOIN
  (SELECT 
      DATA_CENTER_SID
      ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
   FROM
      CORE.T_DIM_DATA_CENTER
   GROUP BY DATA_CENTER_SID) DT2
  ON DT1.DATA_CENTER_SID = DT2.DATA_CENTER_SID
  AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;