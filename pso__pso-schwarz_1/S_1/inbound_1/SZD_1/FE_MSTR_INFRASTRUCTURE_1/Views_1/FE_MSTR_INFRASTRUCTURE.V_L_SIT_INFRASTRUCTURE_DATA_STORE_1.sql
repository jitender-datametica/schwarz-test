CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_DATA_STORE_1(
	DATA_STORE_SID
	,DATA_STORE_MOID
	,DATA_STORE_NAME
) AS SELECT
   DT1.DATA_STORE_SID
  ,DT1.DATA_STORE_MOID
  ,DT1.DATA_STORE_NAME
FROM
  CORE.T_DIM_DATA_STORE DT1
  JOIN
  (SELECT 
      DATA_STORE_SID
      ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
   FROM
      CORE.T_DIM_DATA_STORE
   GROUP BY DATA_STORE_SID) DT2
  ON DT1.DATA_STORE_SID = DT2.DATA_STORE_SID
  AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;