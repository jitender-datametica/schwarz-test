CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_FACT_COMPUTE_RESOURCE_CLUSTER_USAGE_1(
	VCENTER_SID
	,DATA_CENTER_SID
	,COMPUTE_RESOURCE_CLUSTER_SID
	,PHYSICAL_HOST_SID
	,CAL_DT
	,STAGE_CD
	,SITE_CD
	,LOB_CD
	,HW_VENDOR_NAME
	,HW_MODEL_NAME
	,SERIAL_NR
	,OPERATING_SYSTEM_NAME
	,OPERATING_SYSTEM_VERSION
	,CPU_MODEL_NAME
	,PH_HW_VENDOR_NAME
	,PH_HW_MODEL_NAME
	,PH_SERIAL_NR
	,PH_OPERATING_SYSTEM_NAME
	,PH_OPERATING_SYSTEM_VERSION
	,PH_CPU_MODEL_NAME
	,PHYSICAL_CPU_CNT
	,PHYSICAL_CPU_CORE_CNT
	,PHYSICAL_MEMORY_MB_MEAS
) AS SELECT
  FT1.VCENTER_SID
  ,FT1.DATA_CENTER_SID 
  ,FT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,FT1.PHYSICAL_HOST_SID
  ,FT1.CAL_DT
  ,LT1.STAGE_CD
  ,LT1.SITE_CD
  ,LT2.LOB_CD
  ,IFNULL(LT3.HW_VENDOR_NAME,'unknown') AS HW_VENDOR_NAME
  ,IFNULL(LT3.HW_MODEL_NAME,'unknown') AS HW_MODEL_NAME
  ,IFNULL(LT3.SERIAL_NR,'unknown') AS SERIAL_NR
  ,IFNULL(LT3.OPERATING_SYSTEM_NAME,'unknown') AS OPERATING_SYSTEM_NAME
  ,IFNULL(LT3.OPERATING_SYSTEM_VERSION, 'unknown') AS OPERATING_SYSTEM_VERSION
  ,IFNULL(LT3.CPU_MODEL_NAME, 'unknown') AS CPU_MODEL_NAME
  ,IFNULL(LT3.HW_VENDOR_NAME,'unknown') AS PH_HW_VENDOR_NAME
  ,IFNULL(LT3.HW_MODEL_NAME,'unknown') AS PH_HW_MODEL_NAME
  ,IFNULL(LT3.SERIAL_NR,'unknown') AS PH_SERIAL_NR
  ,IFNULL(LT3.OPERATING_SYSTEM_NAME,'unknown') AS PH_OPERATING_SYSTEM_NAME
  ,IFNULL(LT3.OPERATING_SYSTEM_VERSION, 'unknown') AS PH_OPERATING_SYSTEM_VERSION
  ,IFNULL(LT3.CPU_MODEL_NAME, 'unknown') AS PH_CPU_MODEL_NAME
  ,SUM(FT1.PHYSICAL_CPU_CNT) AS PHYSICAL_CPU_CNT
  ,SUM(FT1.PHYSICAL_CPU_CORE_CNT) AS PHYSICAL_CPU_CORE_CNT
  ,SUM(FT1.PHYSICAL_MEMORY_MB_MEAS) AS PHYSICAL_MEMORY_MB_MEAS
FROM
  CORE.T_FACT_COMPUTE_RESOURCE_CLUSTER_USAGE FT1
  JOIN CORE.T_DIM_COMPUTE_RESOURCE_CLUSTER LT1
  ON FT1.COMPUTE_RESOURCE_CLUSTER_SID = LT1.COMPUTE_RESOURCE_CLUSTER_SID AND FT1.CAL_DT >= LT1.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT1.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_DATA_CENTER LT2
  ON FT1.DATA_CENTER_SID = LT2.DATA_CENTER_SID AND FT1.CAL_DT >= LT2.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT2.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_PHYSICAL_HOST LT3
  ON FT1.PHYSICAL_HOST_SID = LT3.PHYSICAL_HOST_SID AND FT1.CAL_DT >= LT3.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT3.DWH_VALID_TO_DT
GROUP BY 
  FT1.VCENTER_SID
  ,FT1.DATA_CENTER_SID 
  ,FT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,FT1.PHYSICAL_HOST_SID
  ,FT1.CAL_DT
  ,LT1.STAGE_CD
  ,LT1.SITE_CD
  ,LT2.LOB_CD
  ,HW_VENDOR_NAME
  ,HW_MODEL_NAME
  ,SERIAL_NR
  ,OPERATING_SYSTEM_NAME
  ,OPERATING_SYSTEM_VERSION
  ,CPU_MODEL_NAME
  ,PH_HW_VENDOR_NAME
  ,PH_HW_MODEL_NAME
  ,PH_SERIAL_NR
  ,PH_OPERATING_SYSTEM_NAME
  ,PH_OPERATING_SYSTEM_VERSION
  ,PH_CPU_MODEL_NAME
;