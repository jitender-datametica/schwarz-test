CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_FACT_DATA_STORE_HOST_RESOURCE_CLUSTER_1(
	VCENTER_SID
	,DATA_CENTER_SID
	,COMPUTE_RESOURCE_CLUSTER_SID
	,DATA_STORE_SID
	,PHYSICAL_HOST_SID
	,CAL_DT
	,STAGE_CD
	,SITE_CD
	,LOB_CD
	,DATA_STORE_CAPACITY_MB_MEAS
	,PROVISIONED_SPACE_MB_MEAS
) AS SELECT
  FT2.VCENTER_SID
  ,FT2.DATA_CENTER_SID 
  ,FT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,FT1.DATA_STORE_SID
  ,FT1.PHYSICAL_HOST_SID
  ,FT1.CAL_DT
  ,LT1.STAGE_CD
  ,LT1.SITE_CD
  ,LT2.LOB_CD
  ,FT2.DATA_STORE_CAPACITY_MB_MEAS/FT2.HOST_MOUNT_CNT AS DATA_STORE_CAPACITY_MB_MEAS
  ,FT2.PROVISIONED_SPACE_MB_MEAS/FT2.HOST_MOUNT_CNT AS PROVISIONED_SPACE_MB_MEAS
FROM
  (SELECT DISTINCT COMPUTE_RESOURCE_CLUSTER_SID, PHYSICAL_HOST_SID, DATA_STORE_SID, CAL_DT FROM CORE.T_FACT_DATA_STORE_HOST_CLUSTER_REL) FT1
  JOIN CORE.T_FACT_DATA_STORE_USAGE FT2
  ON FT1.DATA_STORE_SID= FT2.DATA_STORE_SID AND FT1.CAL_DT = FT2.CAL_DT
  JOIN CORE.T_DIM_COMPUTE_RESOURCE_CLUSTER LT1
  ON FT1.COMPUTE_RESOURCE_CLUSTER_SID = LT1.COMPUTE_RESOURCE_CLUSTER_SID AND FT1.CAL_DT >= LT1.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT1.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_DATA_CENTER LT2
  ON FT2.DATA_CENTER_SID = LT2.DATA_CENTER_SID AND FT2.CAL_DT >= LT2.DWH_VALID_FROM_DT AND FT2.CAL_DT < LT2.DWH_VALID_TO_DT
;