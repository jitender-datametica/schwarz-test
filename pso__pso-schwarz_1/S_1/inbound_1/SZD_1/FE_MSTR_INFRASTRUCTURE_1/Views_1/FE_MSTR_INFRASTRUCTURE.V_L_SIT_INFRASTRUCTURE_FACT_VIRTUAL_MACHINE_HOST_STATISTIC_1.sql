CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_FACT_VIRTUAL_MACHINE_HOST_STATISTIC_1(
	VCENTER_SID
	,DATA_CENTER_SID
	,COMPUTE_RESOURCE_CLUSTER_SID
	,PHYSICAL_HOST_SID
	,VM_SID
	,CAL_DT
	,STAGE_CD
	,SITE_CD
	,LOB_CD
	,VM_POWER_STATUS
	,VM_OPERATING_SYSTEM_NAME
	,PH_HW_VENDOR_NAME
	,PH_HW_MODEL_NAME
	,PH_SERIAL_NR
	,PH_OPERATING_SYSTEM_NAME
	,PH_OPERATING_SYSTEM_VERSION
	,PH_CPU_MODEL_NAME
	,VIRTUAL_CPU_CNT
	,VIRTUAL_SOCKET_CORE_CNT
	,VM_USED_MEMORY_MB_MEAS
	,VM_OVERHEAD_MEMORY_MB_MEAS
	,VM_USED_STORAGE_MB_MEAS
	,VIRTUAL_DISK_CNT
) AS SELECT
  FT1.VCENTER_SID
  ,FT1.DATA_CENTER_SID 
  ,FT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,FT1.PHYSICAL_HOST_SID
  ,FT1.VM_SID
  ,FT1.CAL_DT
  ,LT1.STAGE_CD
  ,LT1.SITE_CD
  ,LT2.LOB_CD
  ,FT1.VM_POWER_STATUS
  ,LT3.VM_OPERATING_SYSTEM_NAME
  ,IFNULL(LT4.HW_VENDOR_NAME,'unknown') AS PH_HW_VENDOR_NAME
  ,IFNULL(LT4.HW_MODEL_NAME,'unknown') AS PH_HW_MODEL_NAME
  ,IFNULL(LT4.SERIAL_NR,'unknown') AS PH_SERIAL_NR
  ,IFNULL(LT4.OPERATING_SYSTEM_NAME,'unknown') AS PH_OPERATING_SYSTEM_NAME
  ,IFNULL(LT4.OPERATING_SYSTEM_VERSION, 'unknown') AS PH_OPERATING_SYSTEM_VERSION
  ,IFNULL(LT4.CPU_MODEL_NAME, 'unknown') AS PH_CPU_MODEL_NAME
  ,SUM(FT1.VIRTUAL_CPU_CNT) AS VIRTUAL_CPU_CNT
  ,SUM(FT1.VIRTUAL_SOCKET_CORE_CNT) AS VIRTUAL_SOCKET_CORE_CNT
  ,SUM(FT1.VM_USED_MEMORY_MB_MEAS) AS VM_USED_MEMORY_MB_MEAS
  ,SUM(FT1.VM_OVERHEAD_MEMORY_MB_MEAS) AS VM_OVERHEAD_MEMORY_MB_MEAS
  ,SUM(FT1.VM_USED_STORAGE_MB_MEAS) AS VM_USED_STORAGE_MB_MEAS
  ,SUM(FT1.VIRTUAL_DISK_CNT) AS VIRTUAL_DISK_CNT
FROM
  CORE.T_FACT_VIRTUAL_MACHINE_HOST_STATISTIC FT1
  JOIN CORE.T_DIM_COMPUTE_RESOURCE_CLUSTER LT1
  ON FT1.COMPUTE_RESOURCE_CLUSTER_SID = LT1.COMPUTE_RESOURCE_CLUSTER_SID AND FT1.CAL_DT >= LT1.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT1.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_DATA_CENTER LT2
  ON FT1.DATA_CENTER_SID = LT2.DATA_CENTER_SID AND FT1.CAL_DT >= LT2.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT2.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_VIRTUAL_MACHINE LT3
  ON FT1.VM_SID = LT3.VM_SID AND FT1.CAL_DT >= LT3.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT3.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_PHYSICAL_HOST LT4
  ON FT1.PHYSICAL_HOST_SID = LT4.PHYSICAL_HOST_SID AND FT1.CAL_DT >= LT4.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT4.DWH_VALID_TO_DT
GROUP BY
  FT1.VCENTER_SID
  ,FT1.DATA_CENTER_SID 
  ,FT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,FT1.PHYSICAL_HOST_SID
  ,FT1.VM_SID
  ,FT1.CAL_DT
  ,LT1.STAGE_CD
  ,LT1.SITE_CD
  ,LT2.LOB_CD
  ,FT1.VM_POWER_STATUS
  ,LT3.VM_OPERATING_SYSTEM_NAME
  ,LT4.HW_VENDOR_NAME
  ,LT4.HW_MODEL_NAME
  ,LT4.SERIAL_NR
  ,LT4.OPERATING_SYSTEM_NAME
  ,LT4.OPERATING_SYSTEM_VERSION
  ,LT4.CPU_MODEL_NAME
;