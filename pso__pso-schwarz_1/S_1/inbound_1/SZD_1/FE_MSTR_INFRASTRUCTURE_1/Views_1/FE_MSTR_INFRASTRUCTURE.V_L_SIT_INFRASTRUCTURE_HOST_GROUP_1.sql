CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_HOST_GROUP_1
AS SELECT    
 DT1.HOST_GROUP_SID
,DT1.HOST_GROUP_ID
,DT1.HOST_GROUP_NAME
,DT1.HOST_GROUP_DESCR
,DT1.LOB_CD
,DT1.STAGE_CD
FROM 
 CORE.T_DIM_HOST_GROUP DT1
 JOIN
 (SELECT    
   HOST_GROUP_SID
   ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
  FROM 
   CORE.T_DIM_HOST_GROUP
  GROUP BY 
   HOST_GROUP_SID) DT2
 ON DT1.HOST_GROUP_SID = DT2.HOST_GROUP_SID 
 AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;