CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_PHYSICAL_HOST_1(
	PHYSICAL_HOST_SID
	,PHYSICAL_HOST_ID
	,PHYSICAL_HOST_FQDN
	,PHYSICAL_HOST_NAME
	,OPERATING_SYSTEM_NAME
	,OPERATING_SYSTEM_VERSION
	,DOMAIN_NAME
	,END_OF_LIFE_DT
	,MAINTENANCE_WINDOW
	,PHYSICAL_HOST_IP_ADDR
	,SUBNET_ID
	,VLAN_ID
	,NETWORK_ZONE
	,CPU_MODEL_NAME
	,CPU_HT_ACTIVE_FG
	,HW_VENDOR_NAME
	,HW_MODEL_NAME
	,ENCLOSURE_NAME
	,RACK_NAME
	,DATA_CENTER_NAME
	,SERIAL_NR
	,BACKUP_CLASS_ID
	,BACKUP_11_Y_FG
	,MANAGED_WINDOWS_SITE
	,VMWARE_CLUSTER_ID
	,VMWARE_NAME
	,VMWARE_CLUSTER_NAME
	,VMWARE_CLUSTER_VCENTER
	,VMWARE_REPL_FG
	,VMWARE_UUID
	,VMWARE_MOID
) AS SELECT
 DT1.PHYSICAL_HOST_SID
,DT1.PHYSICAL_HOST_ID
,DT1.PHYSICAL_HOST_FQDN
,DT1.PHYSICAL_HOST_NAME
,DT1.OPERATING_SYSTEM_NAME
,DT1.OPERATING_SYSTEM_VERSION
,DT1.DOMAIN_NAME
,DT1.END_OF_LIFE_DT
,DT1.MAINTENANCE_WINDOW
,DT1.PHYSICAL_HOST_IP_ADDR
,DT1.SUBNET_ID
,DT1.VLAN_ID
,DT1.NETWORK_ZONE
,DT1.CPU_MODEL_NAME
,DT1.CPU_HT_ACTIVE_FG
,DT1.HW_VENDOR_NAME
,DT1.HW_MODEL_NAME
,DT1.ENCLOSURE_NAME
,DT1.RACK_NAME
,DT1.DATA_CENTER_NAME
,DT1.SERIAL_NR
,DT1.BACKUP_CLASS_ID
,DT1.BACKUP_11_Y_FG
,DT1.MANAGED_WINDOWS_SITE
,DT1.VMWARE_CLUSTER_ID
,DT1.VMWARE_NAME
,DT1.VMWARE_CLUSTER_NAME
,DT1.VMWARE_CLUSTER_VCENTER
,DT1.VMWARE_REPL_FG
,DT1.VMWARE_UUID
,DT1.VMWARE_MOID
FROM 
 CORE.T_DIM_PHYSICAL_HOST DT1
 JOIN
 (SELECT    
   PHYSICAL_HOST_SID
   ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
  FROM 
   CORE.T_DIM_PHYSICAL_HOST
  GROUP BY 
   PHYSICAL_HOST_SID) DT2
 ON DT1.PHYSICAL_HOST_SID = DT2.PHYSICAL_HOST_SID 
 AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;