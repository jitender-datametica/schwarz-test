CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_SOLUTION_1
AS SELECT
 DT1.SOLUTION_SID
,DT1.SOLUTION_SIT_ID_CD
,DT1.SOLUTION_UCMDB_ID
,DT1.SOLUTION_PSP_ELEMENT_CD
,DT1.SOLUTION_NAME
,DT1.SOLUTION_CLASS
,DT1.DWH_VALID_TO_DT
FROM
 CORE.T_DIM_SOLUTION DT1
 JOIN
 (SELECT    
   SOLUTION_SID
   ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
  FROM 
   CORE.T_DIM_SOLUTION
  GROUP BY 
   SOLUTION_SID) DT2
 ON DT1.SOLUTION_SID = DT2.SOLUTION_SID 
 AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;