CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_VIRTUAL_DISK_1(
	VIRTUAL_DISK_SID
	,VIRTUAL_DISK_ID
	,VIRTUAL_DISK_NAME
) AS SELECT
   DT1.VIRTUAL_DISK_SID
  ,DT1.VIRTUAL_DISK_ID
  ,DT1.VIRTUAL_DISK_NAME
FROM
  CORE.T_DIM_VIRTUAL_DISK DT1
  JOIN
  (SELECT 
      VIRTUAL_DISK_SID
      ,MAX(DWH_VALID_FROM_DT) AS MAX_DATE
   FROM
      CORE.T_DIM_VIRTUAL_DISK
   GROUP BY VIRTUAL_DISK_SID) DT2
  ON DT1.VIRTUAL_DISK_SID = DT2.VIRTUAL_DISK_SID
  AND DT1.DWH_VALID_FROM_DT = DT2.MAX_DATE
;