CREATE OR REPLACE VIEW FE_MSTR_IOTCHARGERS.V_FACT_CHARGE_POINT_ANALYTICAL_PER_DAY_1
(     
      REPORT_DT
    , CHARGER_PROVIDER_SYSTEM_CD
    , CHARGE_POINT_UUID_NR
    , CHARGER_UUID_NR
    , CHARGING_STATION_OWNER_NAME
    , REAL_ESTATE_NR
    , ISO_COUNTRY_CD
    , EU_MEMBER_FG
    , DIVISION_CD
    , AUTHENTICATION_METHOD_CD
    , CHARGE_POINT_PLUGIN_TYPE_CD
    , CHARGE_POINT_POWER_TYPE_CD
    , CHARGER_STATION_TYPE_CD
    , CHARGER_CLASSIFICATION_ID
    , TURNOVER_LOCAL_CURR_CD
    , TURNOVER_LOCAL_VAL
    , TURNOVER_EUR_VAL
    , PROVIDED_POWER_MEAS
    , CHARGING_PROCESS_CNT
    , CHARGING_DURATION_SEC_MEAS
    , CHARGING_PERFORMANCE_MEAS
) AS
SELECT 
	  TF1.REPORT_DT
    , TF1.CHARGER_PROVIDER_SYSTEM_CD
    , TD1.CHARGE_POINT_UUID_NR
    , TD2.CHARGER_UUID_NR
    , TD3.CHARGING_STATION_OWNER_NAME
    , TD4.REAL_ESTATE_NR
    , TD5.ISO_COUNTRY_CD
    , TD5.EU_MEMBER_FG
    , TD6.DIVISION_CD
    , TF1.AUTHENTICATION_METHOD_CD
    , TF1.CHARGE_POINT_PLUGIN_TYPE_CD
    , TF1.CHARGE_POINT_POWER_TYPE_CD
    , TF1.CHARGER_STATION_TYPE_CD
    , TF1.CHARGER_CLASSIFICATION_ID
    , TF1.LOCAL_CURR_CD
    , TF1.TURNOVER_LOCAL_VAL
    , TF1.TURNOVER_EUR_VAL
    , TF1.PROVIDED_POWER_MEAS
    , TF1.CHARGING_PROCESS_CNT
    , TF1.CHARGING_DURATION_SEC_MEAS
    , TF1.CHARGING_PERFORMANCE_MEAS
FROM CORE.T_FACT_CHARGE_POINT_ANALYTICAL_PER_DAY_1 TF1
JOIN CORE.T_DIM_CHARGE_POINT_1 TD1
ON TF1.CHARGE_POINT_RESOURCE_ITEM_SID = TD1.RESOURCE_ITEM_SID AND TD1.DWH_VALID_FG = TRUE
JOIN CORE.T_DIM_CHARGER_1 TD2
ON TF1.CHARGER_RESOURCE_ITEM_SID = TD2.RESOURCE_ITEM_SID AND TD2.DWH_VALID_FG = TRUE
JOIN CORE.T_DIM_CHARGING_STATION_OWNER_1 TD3
ON TF1.CHARGING_STATION_OWNER_PARTY_SID = TD3.PARTY_SID AND TD3.DWH_VALID_FG = TRUE 
JOIN CORE.T_DIM_REAL_ESTATE_1 TD4
ON TF1.REAL_ESTATE_RESOURCE_ITEM_SID = TD4.RESOURCE_ITEM_SID AND TD4.DWH_VALID_FG = TRUE 
JOIN CORE.T_DIM_COUNTRY_POLITICAL_1 TD5
ON TF1.COUNTRY_LOCATION_SID = TD5.LOCATION_SID AND TD5.DWH_VALID_FG = TRUE 
JOIN CORE.T_DIM_DIVISION_1 TD6
ON TF1.DIVISION_PARTY_SID = TD6.PARTY_SID AND TD6.DWH_VALID_TO_TMSP >= '9999-12-31'
WHERE TF1.RELEVANCE_FG = TRUE
;