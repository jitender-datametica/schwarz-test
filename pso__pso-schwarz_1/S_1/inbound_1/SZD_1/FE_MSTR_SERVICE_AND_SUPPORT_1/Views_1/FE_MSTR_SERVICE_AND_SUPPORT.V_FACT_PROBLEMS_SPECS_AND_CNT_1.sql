CREATE OR REPLACE VIEW FE_MSTR_SERVICE_AND_SUPPORT.V_FACT_PROBLEMS_SPECS_AND_CNT_1(
	CY_MONTH
    , TICKET_CREATOR_DIVISION_CD
    , TICKET_CREATOR_COUNTRY_BUSINESS_CD
    , TICKET_NR
    , TICKET_PRIORITY_ID
    , TICKET_PRIORITY_CD
    , TICKET_PRIORITY_DESCR
    , TICKET_CREATION_DT
    , TICKET_RESOLVING_DT
    , TICKET_CLOSING_REASON_ID
    , TICKET_CLOSING_REASON_CD
    , TICKET_CLOSING_REASON_NAME
    , TICKET_CLOSING_REASON_NAME_EN
    , PROBLEM_CNT
) AS
SELECT 
    (YEAR(TD1.TICKET_RESOLVING_DT)*100 + MONTH(TD1.TICKET_RESOLVING_DT)) AS CY_MONTH
    , TD1.AFFECTED_DIVISION_CD AS TICKET_CREATOR_DIVISION_CD
    , TD1.AFFECTED_COUNTRY_BUSINESS_CD AS TICKET_CREATOR_COUNTRY_BUSINSS_CD
    , TD1.TICKET_NR
    , TD1.TICKET_PRIORITY_ID
    , TD3.TICKET_PRIORITY_CD
    , TD3.TICKET_PRIORITY_DESCR
    , TD1.TICKET_CREATION_DT
    , TD1.TICKET_RESOLVING_DT
    , TD1.TICKET_CLOSING_REASON_ID
    , TD2.TICKET_CLOSING_REASON_CD
    , TD2.TICKET_CLOSING_REASON_NAME
    , TD2.TICKET_CLOSING_REASON_NAME_EN
    , 1 AS PROBLEM_CNT
FROM CORE.T_DIM_TICKET_1 AS TD1
JOIN CORE.T_DIM_TICKET_CLOSING_REASON_1 AS TD2
ON TD1.TICKET_CLOSING_REASON_ID=TD2.TICKET_CLOSING_REASON_ID AND TD1.TICKET_TYPE_ID=TD2.TICKET_TYPE_ID
JOIN CORE.T_DIM_TICKET_PRIORITY_1 TD3
ON TD1.TICKET_PRIORITY_ID=TD3.TICKET_PRIORITY_ID
WHERE TD1.TICKET_TYPE_ID = 2 
    AND CURRENT_TIMESTAMP() BETWEEN DWH_VALID_FROM_TMSP AND DWH_VALID_TO_TMSP 
    AND CY_MONTH IS NOT NULL
;