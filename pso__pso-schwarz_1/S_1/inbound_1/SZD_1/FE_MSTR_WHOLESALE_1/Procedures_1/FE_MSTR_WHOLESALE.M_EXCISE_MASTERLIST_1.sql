CREATE
	OR REPLACE PROCEDURE FE_MSTR_WHOLESALE.M_EXCISE_MASTERLIST (
	"ITEM_NO_SHORT" NUMBER(38, 0)
	,"SINGLE_ARTICLE_NO" NUMBER(38, 0)
	,"DWH_VALID_TO" DATE
	,"DWH_VALID_FROM" DATE
	,"ITEM_SHORTDESC" VARCHAR(2000)
	,"WG" VARCHAR(2000)
	,"VOLUME__IN_L_" NUMBER(38, 2)
	,"ABV_" NUMBER(38, 1)
	,"ADJUSTED_ABV__WINE_ONLY_" NUMBER(38, 1)
	,"UNIT_OF_MEASURE__FORMULA_" FLOAT
	,"TAX_CODE_" VARCHAR(2000)
	,"DUTY_PER_LPA" NUMBER(38, 1)
	,"DUTY_PER_UNIT" FLOAT
	)
RETURNS VARCHAR(16777216) LANGUAGE SQL

EXECUTE AS OWNER AS 
	'BEGIN

    LET
      V_PREVIOUS_DWH_VALID_FROM DATE := (SELECT
          MAX(DWH_VALID_FROM)
        FROM
          FE_MSTR_WHOLESALE.T_CACHE_EXCISE_MASTERLIST_1
        WHERE
          ITEM_NO_SHORT = :ITEM_NO_SHORT
          AND DWH_VALID_TO = :DWH_VALID_TO
          AND SINGLE_ARTICLE_NO = :SINGLE_ARTICLE_NO);


    UPDATE
      FE_MSTR_WHOLESALE.T_CACHE_EXCISE_MASTERLIST_1
    SET
      WG= :WG,
      VOLUME__IN_L_ = :VOLUME__IN_L_,
      ABV_ = :ABV_,
      ADJUSTED_ABV__WINE_ONLY_ = :ADJUSTED_ABV__WINE_ONLY_,
      UNIT_OF_MEASURE__FORMULA_= :UNIT_OF_MEASURE__FORMULA_,
      TAX_CODE_ = :TAX_CODE_,
      DUTY_PER_LPA= :DUTY_PER_LPA,
      DUTY_PER_UNIT = :DUTY_PER_UNIT,
      DWH_VALID_FROM = :DWH_VALID_FROM,
      PREVIOUS_DWH_VALID_FROM = :V_PREVIOUS_DWH_VALID_FROM,
      UPDATED_AT = CURRENT_TIMESTAMP
    WHERE
      ITEM_NO_SHORT = :ITEM_NO_SHORT
      AND DWH_VALID_TO = :DWH_VALID_TO
      AND SINGLE_ARTICLE_NO = :SINGLE_ARTICLE_NO;
      
    
    COMMIT;
    END';
    