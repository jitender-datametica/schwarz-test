CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_CONSIGNOR_STREAM_PARENT_1 (
	CONSIGNOR_STREAM_CD
	,CONSIGNOR_STREAM_NAME
	,CONSIGNOR_STREAM_CD_PARENT
	,CONSIGNOR_STREAM_NAME_PARENT
	) AS

SELECT CONSIGNOR_STREAM_CD
	,CONSIGNOR_STREAM_NAME
	,CASE 
		WHEN CONSIGNOR_STREAM_CD = '-1'
			THEN 'EXTERNAL'
		ELSE CONSIGNOR_STREAM_CD
		END AS CONSIGNOR_STREAM_CD_PARENT
	,CASE 
		WHEN CONSIGNOR_STREAM_NAME = 'Unknown'
			THEN 'External Company'
		ELSE CONSIGNOR_STREAM_NAME
		END AS CONSIGNOR_STREAM_NAME_PARENT
FROM CORE.T_DIM_CONSIGNOR_STREAM_1
ORDER BY CONSIGNOR_STREAM_CD ASC;