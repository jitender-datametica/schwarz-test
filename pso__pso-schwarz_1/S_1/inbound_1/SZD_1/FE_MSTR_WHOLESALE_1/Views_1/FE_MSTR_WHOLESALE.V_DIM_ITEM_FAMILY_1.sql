CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_ITEM_FAMILY_1 (
	PRODUCT_GROUP_SID
	,DWH_VALID_FROM_TMSP
	,DWH_VALID_TO_TMSP
	,DWH_VALID_FG
	,ITEM_FAMILY_NR
	,ITEM_FAMILY_NAME
	,ITEM_FAMILY_NAME_DE
	,ITEM_FAMILY_NAME_EN
	,SUB_ITEM_GROUP_NR
	,SUB_ITEM_GROUP_NAME
	,SUB_ITEM_GROUP_NAME_DE
	,SUB_ITEM_GROUP_NAME_EN
	) AS

SELECT PRODUCT_GROUP_SID
	,DWH_VALID_FROM_TMSP
	,DWH_VALID_TO_TMSP
	,DWH_VALID_FG
	,REPLACE(ITEM_FAMILY_NR,CONCAT(SUB_ITEM_GROUP_NR,'.')) AS ITEM_FAMILY_NR
	,ITEM_FAMILY_NAME
	,ITEM_FAMILY_NAME_DE
	,ITEM_FAMILY_NAME_EN
	,SUB_ITEM_GROUP_NR
	,SUB_ITEM_GROUP_NAME
	,SUB_ITEM_GROUP_NAME_DE
	,SUB_ITEM_GROUP_NAME_EN
FROM CORE.T_DIM_ITEM_FAMILY_1;