CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_LOT_PART_1 (
	LOT_PART_PROD_INSTANCE_GROUP_SID
	,DWH_VALID_FROM_TMSP
	,DWH_VALID_TO_TMSP
	,DWH_VALID_FG
	,LOT_PART_STATUS_CD
	,LOT_PROD_INSTANCE_GROUP_SID
	,SHIP_DESTINATION_CD
	,GTIN_NR
	,IS_SPARE_UNIT_FG
	,SHIPPED_CARTON_QTY
	,PIECE_PER_CARTON_QTY
	,PIECE_PER_CARTON_QTY_AGG
	,LENGTH_M_MEAS
	,WIDTH_M_MEAS
	,HEIGHT_M_MEAS
	,NET_WEIGHT_KG_QTY
	,GROSS_WEIGHT_KG_QTY
	) AS

SELECT PRODUCT_INSTANCE_GROUP_SID AS LOT_PART_PROD_INSTANCE_GROUP_SID
	,DWH_VALID_FROM_TMSP
	,DWH_VALID_TO_TMSP
	,DWH_VALID_FG
	,LOT_PART_STATUS_CD
	,LOT_PRODUCT_INSTANCE_GROUP_SID AS LOT_PROD_INSTANCE_GROUP_SID
	,SHIPPING_DESTINATION_CD AS SHIP_DESTINATION_CD
	,GTIN_NR
	,SPARE_UNIT_FG AS IS_SPARE_UNIT_FG
	,SHIPPED_CARTON_QTY
	,PIECE_PER_CARTON_QTY
	,SUM(DISTINCT PIECE_PER_CARTON_QTY) OVER (PARTITION BY LOT_PRODUCT_INSTANCE_GROUP_SID) AS PIECE_PER_CARTON_QTY_AGG
	,LENGTH_M_MEAS
	,WIDTH_M_MEAS
	,HEIGHT_M_MEAS
	,NET_WEIGHT_KG_QTY
	,GROSS_WEIGHT_KG_QTY
FROM CORE.T_DIM_LOT_PART_1
WHERE DWH_VALID_FG = 1
	AND LOT_PART_STATUS_CD <> 'C';