CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_FACT_LOT_PART_CONTAINER_1 (
	LOT_PART_PROD_INSTANCE_GROUP_SID
	,LOT_NR
	,CONTAINER_RESOURCE_SID
	,LOT_PROD_INSTANCE_GROUP_SID
	,GTIN_NR
	,SHIP_DESTINATION_CD
	,TOTAL_SHIP_PROD_QTY
	,SHIPPED_PRODUCT_QTY
	,OTHER_LOTS_IN_CONTAINER_CNT
	,OTHER_LOTS_IN_CONTAINER_TXT
	,TOTAL_SHIP_CONT_PROD_QTY
	,CONTAINER_SHARE_PCT
	,PRODUCED_PCS_CNT
	,TEU_SHARE
	,CARTON_VOLUME
	,EU_MEMBER_FLAG
    ,CONTAINER_DEST_COUNTRY_CLASSIFICATION
	,CARTON_VOLUME_LOT
	,CONTAINER_SHARE_VOLUME
	) AS

SELECT DISTINCT LPC.LOT_PART_PRODUCT_INSTANCE_GROUP_SID AS LOT_PART_PROD_INSTANCE_GROUP_SID
	,LPC.LOT_NR
	,LPC.CONTAINER_RESOURCE_ITEM_SID AS CONTAINER_RESOURCE_SID
	,LPC.LOT_PRODUCT_INSTANCE_GROUP_SID AS LOT_PROD_INSTANCE_GROUP_SID
	,LPC.GTIN_NR
	,LPC.SHIPPING_DESTINATION_CD AS SHIP_DESTINATION_CD
	,LPC.TOTAL_SHIPPED_PRODUCT_QTY AS TOTAL_SHIP_PROD_QTY
	,LPC.SHIPPED_PRODUCT_QTY
	,LPC.OTHER_LOTS_IN_CONTAINER_CNT
	,LPC.OTHER_LOTS_IN_CONTAINER_TXT
	,LPC.TOTAL_SHIPPED_CONTAINER_PRODUCT_QTY AS TOTAL_SHIP_CONT_PROD_QTY
	,LPC.CONTAINER_SHARE_PCT
	,LP.PIECE_PER_CARTON_QTY * LPC.SHIPPED_PRODUCT_QTY AS PRODUCED_PCS_CNT
	,LPC.CONTAINER_SHARE_PCT * C.TEU_QTY AS TEU_SHARE
	,LP.LENGTH_M_MEAS * LP.WIDTH_M_MEAS * LP.HEIGHT_M_MEAS * LPC.SHIPPED_PRODUCT_QTY AS CARTON_VOLUME
	,CASE 
		WHEN COUNTRY_POL.EU_MEMBER_FG
			THEN 1
		ELSE 0
		END AS EU_MEMBER_FLAG
	,CASE 
		WHEN AVG(EU_MEMBER_FLAG) OVER (PARTITION BY LPC.CONTAINER_RESOURCE_ITEM_SID) = 1
			THEN 'Nur EU-Ware'
		WHEN AVG(EU_MEMBER_FLAG) OVER (PARTITION BY LPC.CONTAINER_RESOURCE_ITEM_SID) > 0
			AND AVG(EU_MEMBER_FLAG) OVER (PARTITION BY LPC.CONTAINER_RESOURCE_ITEM_SID) < 1
			THEN 'Nicht EU-Ware & EU-Ware'
		WHEN AVG(EU_MEMBER_FLAG) OVER (PARTITION BY LPC.CONTAINER_RESOURCE_ITEM_SID) = 0
			THEN 'Nur Nicht-EU-Ware'
		ELSE NULL
		END AS CONTAINER_DEST_COUNTRY_CLASSIFICATION
	,SUM(LP.LENGTH_M_MEAS * LP.WIDTH_M_MEAS * LP.HEIGHT_M_MEAS * LPC.SHIPPED_PRODUCT_QTY) OVER (PARTITION BY LPC.CONTAINER_RESOURCE_ITEM_SID) AS CARTON_VOLUME_LOT
	,DIV0(CARTON_VOLUME, CARTON_VOLUME_LOT) AS CONTAINER_SHARE_VOLUME
FROM CORE.T_FACT_LOT_LOT_PART_CONTAINER_1 LPC
LEFT OUTER JOIN CORE.T_DIM_LOT_PART_1 LP ON LPC.LOT_PART_PRODUCT_INSTANCE_GROUP_SID = LP.PRODUCT_INSTANCE_GROUP_SID
	AND LPC.LOT_PRODUCT_INSTANCE_GROUP_SID = LP.LOT_PRODUCT_INSTANCE_GROUP_SID
	AND LPC.SHIPPING_DESTINATION_CD = LP.SHIPPING_DESTINATION_CD
LEFT OUTER JOIN CORE.T_DIM_CONTAINER_1 C ON LPC.CONTAINER_RESOURCE_ITEM_SID = C.RESOURCE_ITEM_SID
JOIN CORE.T_DIM_COUNTRY_POLITICAL_1 COUNTRY_POL ON CASE
        WHEN LPC.SHIPPING_DESTINATION_CD IN ('SpareItems', 'CON')
		    THEN '-1'
		WHEN LEN(LPC.SHIPPING_DESTINATION_CD) = 3
			AND REGEXP_INSTR(LPC.SHIPPING_DESTINATION_CD, 'K') = 1
			THEN RIGHT(LPC.SHIPPING_DESTINATION_CD, 2)
		WHEN LEN(LPC.SHIPPING_DESTINATION_CD) = 3
			AND REGEXP_INSTR(LPC.SHIPPING_DESTINATION_CD, 'K') = 0
			AND LPC.SHIPPING_DESTINATION_CD <> 'CON'
			THEN LEFT(LPC.SHIPPING_DESTINATION_CD, 2)
		WHEN LEN(LPC.SHIPPING_DESTINATION_CD) = 4
			AND REGEXP_INSTR(LPC.SHIPPING_DESTINATION_CD, 'KO') = 1
			THEN RIGHT(LPC.SHIPPING_DESTINATION_CD, 2)
		WHEN LEN(LPC.SHIPPING_DESTINATION_CD) = 4
			AND REGEXP_INSTR(LPC.SHIPPING_DESTINATION_CD, 'OS') = 1
			THEN RIGHT(LPC.SHIPPING_DESTINATION_CD, 2)
		ELSE LPC.SHIPPING_DESTINATION_CD
		END = COUNTRY_POL.ISO_COUNTRY_CD
WHERE LPC.DWH_VALID_FG = 1
	AND LP.DWH_VALID_FG = 1
	AND C.DWH_VALID_FG = 1
	AND COUNTRY_POL.DWH_VALID_FG = 1
	AND C.CONTAINER_STATUS_CD = 'A'
	AND LP.LOT_PART_STATUS_CD = 'A';