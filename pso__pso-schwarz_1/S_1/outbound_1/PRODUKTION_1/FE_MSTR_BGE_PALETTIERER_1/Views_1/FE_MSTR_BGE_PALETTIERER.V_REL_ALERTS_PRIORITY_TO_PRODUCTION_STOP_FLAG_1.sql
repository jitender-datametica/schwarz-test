CREATE OR REPLACE VIEW produktion_fe_mstr_bge_palettierer.v_rel_alerts_priority_to_production_stop_flag_1 AS SELECT
 v_dim_alerts_priority.alerts_priority_id,
 v_dim_production_stop_flag.alerts_production_stop_fg
FROM produktion_fe_mstr_bge_palettierer.v_dim_alerts_priority_1
 INNER JOIN produktion_fe_mstr_bge_palettierer.v_dim_production_stop_flag_1 ON TRUE
