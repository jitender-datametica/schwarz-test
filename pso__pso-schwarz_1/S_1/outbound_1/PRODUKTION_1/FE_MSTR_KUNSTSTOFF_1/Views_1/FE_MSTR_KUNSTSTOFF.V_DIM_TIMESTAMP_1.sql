CREATE OR REPLACE VIEW produktion_fe_mstr_kunststoff.v_dim_timestamp_1 (measurement_tmsp) AS SELECT TIMESTAMP(DATETIME(EXTRACT(YEAR
    FROM V4.cal_dt), EXTRACT(MONTH FROM V4.cal_dt), EXTRACT(DAY FROM V4.cal_dt), V1.hh, V2.mi, V3.sec)) AS
 measurement_tmsp
FROM (SELECT (ROW_NUMBER() OVER (ORDER BY SEQ IS NULL, SEQ)) - 1 AS hh
  FROM UNNEST(GENERATE_ARRAY(0, 23)) AS SEQ) AS V1
 INNER JOIN (SELECT (ROW_NUMBER() OVER (ORDER BY SEQ IS NULL, SEQ)) - 1 AS mi
  FROM UNNEST(GENERATE_ARRAY(0, 59)) AS SEQ) AS V2 ON TRUE
 INNER JOIN (SELECT (ROW_NUMBER() OVER (ORDER BY SEQ IS NULL, SEQ)) - 1 AS sec
  FROM UNNEST(GENERATE_ARRAY(0, 59)) AS SEQ) AS V3 ON TRUE
 INNER JOIN (SELECT cal_dt
  FROM produktion_core.t_dim_cal_day_1
  WHERE cal_dt BETWEEN DATE_ADD(CURRENT_DATE, INTERVAL - 24 MONTH) AND (CURRENT_DATE)) AS V4 ON TRUE;