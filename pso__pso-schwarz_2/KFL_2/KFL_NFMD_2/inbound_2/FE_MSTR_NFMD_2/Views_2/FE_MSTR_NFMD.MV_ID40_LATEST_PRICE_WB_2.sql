CREATE OR REPLACE VIEW FE_MSTR_NFMD.MV_ID40_LATEST_PRICE_WB_2 AS
SELECT YEAR_ID,
       WEEK_ID,
       MANDANT_ID,
       AKTION_ID,
       SKU_ID,
       WUP_ID,
       NULL       AS INITAL_DECISON_DATE,   -- Deprecated, will be removed
       CREATED_AT AS UPDATED_DATE,
       MANUAL_MARKDOWN_PRICE
FROM CORE.TS_ID40_PRICE_WBS_2
    QUALIFY RANK() OVER (PARTITION BY YEAR_ID, WEEK_ID, MANDANT_ID, AKTION_ID, SKU_ID, WUP_ID ORDER BY CREATED_AT DESC) =  1;