CREATE OR REPLACE PROCEDURE DBP_MACRO.M_UPS_TS_WBS_WARENGRUPPE (
    P_MANDANT_ID NUMBER,
   -- P_AUSLIEFERUNGSGRUPPE_ID VARCHAR(10),
    P_WG_ID NUMBER,
    P_KJWO NUMBER,
    P_ESTIMATION_FG NUMBER,
    P_ADJUSTMENT_FG NUMBER,
    P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG NUMBER,
    P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG NUMBER,
    P_BONUSKAUF_PROMOTIONSTYP VARCHAR(10)
   -- P_WG_CLUSTER_ID NUMBER
)
RETURNS VARCHAR
LANGUAGE SQL
AS 
$$
BEGIN
-- Wenn Eintrag vorhanden loeschen 
DELETE FROM DBP_MSI_DATA.TS_WBS_WARENGRUPPE_2 
    WHERE MANDANT_ID = :P_MANDANT_ID 
      --  AND AUSLIEFERUNGSGRUPPE_ID = :P_AUSLIEFERUNGSGRUPPE_ID
        AND WG_ID = :P_WG_ID
        AND KJWO = :P_KJWO;

-- Eintrag einfügen 
INSERT INTO DBP_MSI_DATA.TS_WBS_WARENGRUPPE_2 (MANDANT_ID,/*AUSLIEFERUNGSGRUPPE_ID,*/WG_ID,KJWO, ESTIMATION_FG,ADJUSTMENT_ID,AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG,AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG , /*WG_CLUSTER_ID,*/BONUSKAUF_PROMOTIONSTYP, TD_UPDATE, TD_INSERT
	)
VALUES (:P_MANDANT_ID,/*:P_AUSLIEFERUNGSGRUPPE_ID,*/:P_WG_ID,:P_KJWO,:P_ESTIMATION_FG,:P_ADJUSTMENT_FG,:P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG,:P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG,/*:P_WG_CLUSTER_ID,*/ CASE WHEN:P_BONUSKAUF_PROMOTIONSTYP = 'Standard' THEN '-1' ELSE :P_BONUSKAUF_PROMOTIONSTYP END, CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);




COMMIT;
RETURN 'Warengruppe gespeichert';
END;
$$;