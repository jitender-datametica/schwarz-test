CREATE OR REPLACE PROCEDURE DBP_MACRO.M_UPS_TS_WBS_WARENGRUPPE_STANDARD (
    P_MANDANT_ID NUMBER,
    --P_AUSLIEFERUNGSGRUPPE_ID VARCHAR(10),
    P_WG_ID NUMBER,
    P_ESTIMATION_FG NUMBER,
    P_ADJUSTMENT_FG NUMBER,
    P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG NUMBER,
    P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG NUMBER,
    P_BONUSKAUF_PROMOTIONSTYP VARCHAR(10),
    P_BONUSKAUF_PROMOTIONSTYP_PREV VARCHAR(10),
    P_DELETE_FG NUMBER
   
)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS OWNER
AS 
$$
BEGIN

MERGE INTO DBP_MSI_DATA.TS_WBS_WARENGRUPPE_STANDARD_2 AS target
    USING (
    SELECT
	:P_MANDANT_ID AS MANDANT_ID,
--:P_AUSLIEFERUNGSGRUPPE_ID AS AUSLIEFERUNGSGRUPPE_ID,
:P_WG_ID AS WG_ID,
:P_ESTIMATION_FG AS ESTIMATION_FG,
:P_ADJUSTMENT_FG AS ADJUSTMENT_FG,
:P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG AS AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG,
:P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG AS AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG,
:P_BONUSKAUF_PROMOTIONSTYP AS BONUSKAUF_PROMOTIONSTYP,
:P_BONUSKAUF_PROMOTIONSTYP_PREV AS BONUSKAUF_PROMOTIONSTYP_PREV

   ) AS source
    ON target.MANDANT_ID = source.MANDANT_ID
        --AND target.AUSLIEFERUNGSGRUPPE_ID = source.AUSLIEFERUNGSGRUPPE_ID
        AND target.WG_ID = source.WG_ID
		AND target.BONUSKAUF_PROMOTIONSTYP = source.BONUSKAUF_PROMOTIONSTYP_PREV
        
        

WHEN MATCHED AND :P_DELETE_FG =0 THEN 
    UPDATE SET ESTIMATION_FG = source.ESTIMATION_FG ,
    ADJUSTMENT_ID =  source.ADJUSTMENT_FG,
    AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG = source.AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG,
    AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG =  source.AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG,
    BONUSKAUF_PROMOTIONSTYP = CASE WHEN source.BONUSKAUF_PROMOTIONSTYP = 'STANDARD' THEN '-1' ELSE source.BONUSKAUF_PROMOTIONSTYP END,
	TD_UPDATE = CURRENT_TIMESTAMP

WHEN MATCHED AND :P_DELETE_FG=1 
AND :P_ESTIMATION_FG = source.ESTIMATION_FG
        AND :P_ADJUSTMENT_FG = source.ADJUSTMENT_FG
        AND :P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG=source.AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG
		AND :P_AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG = source.AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG
        THEN
    DELETE  
        
WHEN NOT MATCHED THEN
    INSERT 
    (MANDANT_ID,
    --AUSLIEFERUNGSGRUPPE_ID,
    WG_ID,
    ESTIMATION_FG,
    ADJUSTMENT_ID,
    AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG,
    AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG,
    BONUSKAUF_PROMOTIONSTYP,
    TD_UPDATE,
    TD_INSERT)
 
VALUES (source.MANDANT_ID,
--source.AUSLIEFERUNGSGRUPPE_ID,
source.WG_ID,
source.ESTIMATION_FG,
source.ADJUSTMENT_FG,
source.AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_I_FG,
source.AUTO_BESTELLMENGE_MIT_BESTAND_PHASE_SWITCH_III_FG,
CASE WHEN source.BONUSKAUF_PROMOTIONSTYP = 'STANDARD' THEN '-1' ELSE source.BONUSKAUF_PROMOTIONSTYP END,
CURRENT_TIMESTAMP,
CURRENT_TIMESTAMP);

COMMIT;
RETURN 'Freeze Writeback angepasst';
END;

$$;