CREATE OR REPLACE PROCEDURE DBP_MACRO.M_VIS_KOMMENTAR_KENNZAHLEN(
	P_MANDANT_ID             NUMBER,
	P_KJMO                   NUMBER,
	P_KOMMENTAR_EBENE_ID     NUMBER,
	P_KOMMENTAR_ID           NUMBER,
	P_KOMMENTAR_NR           NUMBER,
	P_KOMMENTAR_THEMA        VARCHAR(16777216),
	P_KOMMENTAR_FESTSTELLUNG VARCHAR(16777216),
	P_KOMMENTAR_MASSNAHME    VARCHAR(16777216),
	P_KOMMENTAR_TITEL        VARCHAR(16777216),
	P_KOMMENTAR_DAT          VARCHAR
)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER /* OWNER does not work */ 
AS $$ 

/*
	SQL MERGE : Kennzahlen Kommentierung (PUK DE) - Transaction
	2026-06-17 ssch0611 : initial [STRY0084061]
*/ 

DECLARE
	v_ergebnis VARCHAR DEFAULT 'Kommentare Kennzahlen aktualisiert'; 

BEGIN

	MERGE INTO DBP_MSI_VIEW_VIS.TS_VIS_KOMMENTAR_KENNZAHLEN_2 trgt 
	USING (
		SELECT :P_MANDANT_ID            AS MANDANT_ID
			, :P_KJMO                   AS KJMO
			, :P_KOMMENTAR_EBENE_ID     AS KOMMENTAR_EBENE_ID 
			, :P_KOMMENTAR_ID           AS KOMMENTAR_ID 
			, :P_KOMMENTAR_NR           AS KOMMENTAR_NR 
			, :P_KOMMENTAR_THEMA        AS KOMMENTAR_THEMA 
			, :P_KOMMENTAR_FESTSTELLUNG AS KOMMENTAR_FESTSTELLUNG
			, :P_KOMMENTAR_MASSNAHME    AS KOMMENTAR_MASSNAHME
			, :P_KOMMENTAR_TITEL        AS KOMMENTAR_TITEL
			, :P_KOMMENTAR_DAT          AS KOMMENTAR_DAT
	) srce
		ON  srce.MANDANT_ID = trgt.MANDANT_ID
		AND srce.KJMO = trgt.KJMO 
		AND srce.KOMMENTAR_EBENE_ID = trgt.KOMMENTAR_EBENE_ID
		AND srce.KOMMENTAR_ID = trgt.KOMMENTAR_ID
		AND srce.KOMMENTAR_NR = trgt.KOMMENTAR_NR 

	WHEN MATCHED THEN UPDATE 
		SET trgt.KOMMENTAR_THEMA = srce.KOMMENTAR_THEMA
			, trgt.KOMMENTAR_FESTSTELLUNG = srce.KOMMENTAR_FESTSTELLUNG
			, trgt.KOMMENTAR_MASSNAHME = srce.KOMMENTAR_MASSNAHME
			, trgt.KOMMENTAR_TITEL = srce.KOMMENTAR_TITEL
			, trgt.KOMMENTAR_DAT = srce.KOMMENTAR_DAT
			, trgt.KOMMENTAR_TS = CURRENT_TIMESTAMP() 

	WHEN NOT MATCHED THEN INSERT (
		  trgt.MANDANT_ID 
		, trgt.KJMO 
		, trgt.KOMMENTAR_EBENE_ID 
		, trgt.KOMMENTAR_ID 
		, trgt.KOMMENTAR_NR 
		, trgt.KOMMENTAR_THEMA 
		, trgt.KOMMENTAR_FESTSTELLUNG 
		, trgt.KOMMENTAR_MASSNAHME 
		, trgt.KOMMENTAR_TITEL 
		, trgt.KOMMENTAR_DAT 
		, trgt.KOMMENTAR_TS 
	)
	VALUES (
		  srce.MANDANT_ID 
		, srce.KJMO 
		, srce.KOMMENTAR_EBENE_ID 
		, srce.KOMMENTAR_ID 
		, srce.KOMMENTAR_NR 
		, srce.KOMMENTAR_THEMA 
		, srce.KOMMENTAR_FESTSTELLUNG 
		, srce.KOMMENTAR_MASSNAHME 
		, srce.KOMMENTAR_TITEL 
		, srce.KOMMENTAR_DAT 
		, CURRENT_TIMESTAMP()
	); 

	COMMIT; 
	RETURN v_ergebnis; 

END;
$$;