CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW2.MV_ART_SPR_ZU_2
(
	SPR_ID,
	ART_ID,
	MANDANT_ID,
	ART_BEZ,
	ART_ID_BEZ
) TARGET_LAG = '1 HOUR, 30 MINUTES' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_AIS_DE
AS
SELECT
SPR_ID,
ART_ID,
MANDANT_ID,
CASE WHEN SUBSTR(ART_BEZ, 1, 11) = 'Wertartikel' AND ART_ID < 0 THEN 'Sachkonto WG ' || TRIM(ART_ID/-1000) ELSE ART_BEZ END ART_BEZ,
CAST(CAST(ART_ID AS CHAR(10)) || '   ' || ART_BEZ AS CHAR(100)) AS ART_ID_BEZ
FROM DBP_VIEW.V_ART_SPR_ZU_2
WHERE SPR_ID = 22
AND MANDANT_ID = 1;