CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW2.MV_TS_ARTIKEL_CLUSTER_ZU_2
(
	MANDANT_ID,
	ART_ID,
	EK_SAISON_ID,
	DAT_VON,
	DAT_BIS,
	ABFOLGE,
	DAT_VON_AKT,
	DAT_BIS_AKT,
	DAT,
	KL_ART_ID_LISTE_TXT
) TARGET_LAG = '1 HOUR, 30 MINUTES' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_AIS_DE
AS 
WITH t_rank AS 
(SELECT DISTINCT
    ek_saison_id,
    DAT_GUELTIG_VON,
    DAT_GUELTIG_BIS,
    DENSE_RANK() OVER (PARTITION BY ek_saison_id ORDER BY DAT_GUELTIG_VON DESC) AS abfolge
    FROM DBP_MSI_VIEW2.TS_AIS_DE_EK_SAISON_ART_ZU_2)
, t_akt_zeitraum AS (
SELECT ek_saison_id,
    DAT_GUELTIG_VON,
    DAT_GUELTIG_BIS
FROM t_rank
WHERE abfolge = 1
)
SELECT 
    v01.MANDANT_ID,
    v01.ART_ID,
    v01.ek_saison_id,
    v01.DAT_GUELTIG_VON AS DAT_VON,
    v01.DAT_GUELTIG_BIS AS DAT_BIS,
    v02.abfolge ,
    v03.DAT_GUELTIG_VON AS dat_von_akt,
    v03.DAT_GUELTIG_BIS AS dat_bis_akt,
    v04.dat,
    v01.KL_ART_ID_LISTE_TXT 
FROM DBP_MSI_VIEW2.TS_AIS_DE_EK_SAISON_ART_ZU_2 v01
JOIN t_rank v02
ON v01.ek_saison_id = v02.ek_saison_id
AND v01.DAT_GUELTIG_VON = v02.DAT_GUELTIG_VON
AND v01.DAT_GUELTIG_BIS = v02.DAT_GUELTIG_BIS
JOIN t_akt_zeitraum v03
ON v01.ek_saison_id = v03.ek_saison_id
JOIN dbp_view.v_tag_2 v04
ON dat BETWEEN v03.DAT_GUELTIG_VON AND v03.DAT_GUELTIG_BIS

WHERE v01.MANDANT_ID = 1
;