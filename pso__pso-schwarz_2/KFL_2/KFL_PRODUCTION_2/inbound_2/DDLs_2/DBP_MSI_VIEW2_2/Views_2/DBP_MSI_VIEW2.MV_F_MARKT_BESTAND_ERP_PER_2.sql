CAST(v01.BETRAG_EK_EINSTANDSPREIS_LGBEST_ERP_QUAL AS NUMBER(38,5)) AS ds_markt_bestand_klep_qual,
CAST(v01.menge_lgbest_erp_gesp_bme * v01.EK_EINSTANDSPREIS AS NUMBER(38,5)) AS ds_markt_bestand_klep_gesperrt,
CAST(v01.BETRAG_EK_EINSTANDSPREIS_LGBEST_ERP_FREI + v01.BETRAG_EK_EINSTANDSPREIS_LGBEST_ERP_QUAL + ds_markt_bestand_klep_gesperrt AS NUMBER(38,5)) AS ds_markt_bestand_klep_ges,
