CAST(v01.BETRAG_VK_NETTO_LGBEST_ERP_QUAL AS NUMBER(38,5)) AS ds_markt_bestand_vkn_qual,
CAST(v01.menge_lgbest_erp_gesp_bme * v01.vk_netto AS NUMBER(38,5)) AS ds_markt_bestand_vkn_gesperrt,
CAST(v01.BETRAG_VK_NETTO_LGBEST_ERP_FREI + v01.BETRAG_VK_NETTO_LGBEST_ERP_QUAL + ds_markt_bestand_vkn_gesperrt AS NUMBER(38,5)) AS ds_markt_bestand_vkn_ges
FROM DBP_MSI_DATA.MARKTBESTAND_ERP_TAG_SUM_2 v01
WHERE v01.mandant_id =1 AND v01.nb_id = 0 AND v01.dat < CURRENT_DATE();