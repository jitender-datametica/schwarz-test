CREATE OR REPLACE VIEW DBP_MSI_VIEW2.MV_TS_EK_DASHBOARD_KOMMENTAR_2 AS 

SELECT v01.EK_DASHBOARD_ID, 
       v02.td_insert AS dwh_timestamp,
       COALESCE(v02.kommentar_txt,'') AS kommentar_txt
FROM DBP_MSI_VIEW2.MV_L_EK_DASHBOARD_SPR_ZU_2 v01
LEFT JOIN dbp_msi_view2.TS_EK_DASHBOARD_KOMMENTAR_2 v02
ON v01.EK_DASHBOARD_ID = v02.EK_DASHBOARD_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY v01.EK_DASHBOARD_ID ORDER BY v02.td_insert DESC ) = 1
;