create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_AIS_INT.MV_ABSCHRIFTGRUPPE_EBENE1_2(
	ABSCHRIFTGRUPPE_ID_EBENE1,
	ABSCHRIFTGRUPPE_ID_EBENE2
) as
SELECT
v02.ABSCHRIFTGRUPPE_ID AS ABSCHRIFTGRUPPE_ID_EBENE1

,v02.UEBERGEORDNETE_ABSCHRIFTGRUPPE_ID AS ABSCHRIFTGRUPPE_ID_EBENE2

FROM DBP_VIEW.V_ABSCHRIFTGRUPPE_2 v01
INNER JOIN DBP_VIEW.V_ABSCHRIFTGRUPPE_HIERARCHIE_ZU_2 v02
   ON v01.MANDANT_ID         = v02.MANDANT_ID 
  AND v01.ABSCHRIFTGRUPPE_ID = v02.ABSCHRIFTGRUPPE_ID  
WHERE  v01.ABSCHRIFTGRUPPE_EBENE_KZ = 1
GROUP BY 1,2;
