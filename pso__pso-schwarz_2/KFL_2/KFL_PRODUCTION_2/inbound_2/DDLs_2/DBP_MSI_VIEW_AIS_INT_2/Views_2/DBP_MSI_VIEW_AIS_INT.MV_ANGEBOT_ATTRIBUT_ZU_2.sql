CREATE OR REPLACE VIEW DBP_MSI_VIEW_AIS_INT.MV_ANGEBOT_ATTRIBUT_ZU_2
(
 MANDANT_ID
,ANGEBOT_NR
--,ANGEBOT_ATTRIBUT_ID
,MASTERBONUS_FG
,MOOD_FG
,GONDELKOPF_FG
,AM_FAKTOR_FG
,MASTERBONUS_FG_TXT
,MOOD_FG_TXT
--,ANGEBOT_ATTRIBUT_TXT
,GONDELKOPF_FG_TXT
,AM_FAKTOR_FG_TXT
,MENGE_ALLER_FILIALEN
--,ANGEBOT_ATTRIBUT_BEZ
,MASTERBONUS_FG_BEZ
,MOOD_FG_BEZ
,GONDELKOPF_FG_BEZ
,AM_FAKTOR_FG_BEZ
)
AS
SELECT
 v01.MANDANT_ID
,v01.ANGEBOT_NR
--,v01.ANGEBOT_ATTRIBUT_ID
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 41 THEN 'X' ELSE '' END) AS MASTERBONUS_FG
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 47 THEN 'X' ELSE '' END) AS MOOD_FG
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 49 THEN 'X' ELSE '' END) AS GONDELKOPF_FG
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 52 THEN 'X' ELSE '' END) AS AM_FAKTOR_FG
--,ANGEBOT_ATTRIBUT_TXT
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 41 THEN v01.ANGEBOT_ATTRIBUT_TXT ELSE '' END) AS MASTERBONUS_FG_TXT
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 47 THEN v01.ANGEBOT_ATTRIBUT_TXT ELSE '' END) AS MOOD_FG_TXT
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 49 THEN v01.ANGEBOT_ATTRIBUT_TXT ELSE '' END) AS GONDELKOPF_FG_TXT
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 52 THEN v01.ANGEBOT_ATTRIBUT_TXT ELSE '' END) AS AM_FAKTOR_FG_TXT
,SUM(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 44 THEN 1 ELSE 0 END) AS MENGE_ALLER_FILIALEN
--,v02.ANGEBOT_ATTRIBUT_BEZ
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 41 THEN v02.ANGEBOT_ATTRIBUT_BEZ ELSE '' END) AS MASTERBONUS_FG_BEZ
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 47 THEN v02.ANGEBOT_ATTRIBUT_BEZ ELSE '' END) AS MOOD_FG_BEZ
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 49 THEN v02.ANGEBOT_ATTRIBUT_BEZ ELSE '' END) AS GONDELKOPF_FG_BEZ
,MAX(CASE WHEN v01.ANGEBOT_ATTRIBUT_ID = 52 THEN v02.ANGEBOT_ATTRIBUT_BEZ ELSE '' END) AS AM_FAKTOR_FG_BEZ
FROM DBP_DATA.ANGEBOT_ATTRIBUT_ZU_2 v01
JOIN DBP_DATA.ANGEBOT_ATTRIBUT_SPR_ZU_2 v02
ON v01.MANDANT_ID = v02.MANDANT_ID
AND v01.ANGEBOT_ATTRIBUT_ID = v02.ANGEBOT_ATTRIBUT_ID
AND v02.SPR_ID = 22
GROUP BY
 v01.MANDANT_ID
,v01.ANGEBOT_NR
--,v01.ANGEBOT_ATTRIBUT_ID
--,v01.ANGEBOT_ATTRIBUT_TXT
--,v02.ANGEBOT_ATTRIBUT_BEZ
;