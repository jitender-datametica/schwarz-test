CREATE OR REPLACE VIEW DBP_MSI_VIEW_AIS_INT.MV_ROHSTOFF_GRUPPE_NACHRICHT_2
(
 	ROHSTOFFKATEGORIE,
	NACHRICHT_TYP_ID,
	SPR_ID,
    SPRACHE,
	NACHRICHT_TITEL_TXT,
	NACHRICHT_INHALT_TXT,
	TREND_TYP_ID,
	DAT_TREND_VON,
	PROGNOSE_HALBJAHR_TYP_ID,
	NACHRICHT_LINK_TXT,
	PREIS_REDUZIERENDE_FAKTOREN_TXT,
	PREIS_STEIGERNDE_FAKTOREN_TXT,
	FORECAST_TXT,
	DAT_GUELTIG_VON,
	DAT_GUELTIG_BIS
) 
AS
SELECT
-- v01.ROHSTOFF_GRUPPE_TYP_ID
--,v01.ROHSTOFF_GRUPPE_NAME
 v01.ROHSTOFF_KATEGORIE_KFL_NAME AS ROHSTOFFKATEGORIE
--,v01.ROHSTOFF_SUBKATEGORIE_KFL_NAME AS ROHSTOFFSUBKATEGORIE -- ausgeblendet, da hier keine Eingabe über TS erfolgt, kann im FE dazugejoint werden
,v01.NACHRICHT_TYP_ID
,v01.SPR_ID
,CASE WHEN v01.SPR_ID = 22 THEN 'Deutsch'
      WHEN v01.SPR_ID = 24 THEN 'Englisch' END AS SPRACHE
-- Rohstoffmonitoring ist per Anforderung nur in Englisch und Deutsch verfügbar, daher keine reguläre_2 Sprachtabelle
,v01.NACHRICHT_TITEL_TXT
,v01.NACHRICHT_INHALT_TXT
,v01.TREND_TYP_ID
,v01.DAT_TREND_VON
,v01.PROGNOSE_HALBJAHR_TYP_ID
,v01.NACHRICHT_LINK_TXT
,v01.PREIS_REDUZIERENDE_FAKTOREN_TXT
,v01.PREIS_STEIGERNDE_FAKTOREN_TXT
,v01.FORECAST_TXT
,v01.DAT_GUELTIG_VON
,v01.DAT_GUELTIG_BIS
FROM DBP_MSI_DATA.TS_ROHSTOFF_MONITORING_NACHRICHT_2 v01
WHERE CURRENT_DATE BETWEEN v01.DAT_GUELTIG_VON AND v01.DAT_GUELTIG_BIS;