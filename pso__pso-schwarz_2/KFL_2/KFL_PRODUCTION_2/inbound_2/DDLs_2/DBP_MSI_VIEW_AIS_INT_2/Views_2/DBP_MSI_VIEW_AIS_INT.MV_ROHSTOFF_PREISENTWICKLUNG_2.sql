CREATE OR REPLACE VIEW DBP_MSI_VIEW_AIS_INT.MV_ROHSTOFF_PREISENTWICKLUNG_2
(
 ROHSTOFF_NR
,DAT_ROHSTOFF_PREIS
,MAX_DAT_ROHSTOFF_PREIS
,MAX_DAT_ROHSTOFF_PREIS_VJ
,MAX_DAT_ROHSTOFF_PREIS_VHJ
,MAX_DAT_ROHSTOFF_PREIS_VQ
,MAX_DAT_ROHSTOFF_PREIS_VM
,KJWO
,WRG_ID
,ROHSTOFF_EINH_NAME
,ROHSTOFF_EINH_NAME_ABBR
,PREIS_ROHSTOFF_MAX
,PREIS_ROHSTOFF_MIN
,PREIS_ROHSTOFF_AVG
,PREIS_GEFUELLT_FG
)
AS
SELECT
    ROHSTOFF_NR,
    DAT_ROHSTOFF_PREIS,
    -- Das maximale Datum wird einmal berechnet
    MAX(DAT_ROHSTOFF_PREIS) OVER (PARTITION BY ROHSTOFF_NR, ROHSTOFF_EINH_NAME) AS MAX_DAT_ROHSTOFF_PREIS,
    -- Berechnung der anderen Datumversionen erfolgen immer direkt vom Max-Datum
    DATEADD(WEEK, -52, MAX_DAT_ROHSTOFF_PREIS) AS MAX_DAT_ROHSTOFF_PREIS_VJ,
    DATEADD(WEEK, -26, MAX_DAT_ROHSTOFF_PREIS) AS MAX_DAT_ROHSTOFF_PREIS_VHJ,
    DATEADD(WEEK, -13, MAX_DAT_ROHSTOFF_PREIS) AS MAX_DAT_ROHSTOFF_PREIS_VQ,
    DATEADD(WEEK, -4, MAX_DAT_ROHSTOFF_PREIS) AS MAX_DAT_ROHSTOFF_PREIS_VM,
    KJWO,
    WRG_ID,
    ROHSTOFF_EINH_NAME,
    CASE ROHSTOFF_EINH_NAME
        WHEN 'kilogram' THEN 'kg'
        WHEN 'liter' THEN 'l'
        WHEN 'megawatt hour' THEN 'mwh'
        WHEN 'tonne (metric ton)' THEN 'to'
    END AS ROHSTOFF_EINH_NAME_ABBR,
    PREIS_ROHSTOFF_MAX,
    PREIS_ROHSTOFF_MIN,
    PREIS_ROHSTOFF_AVG,
    PREIS_GEFUELLT_FG
FROM
    DBP_DATA.ROHSTOFF_PREISENTWICKLUNG_2
WHERE
    ROHSTOFF_EINH_NAME IN ('kilogram', 'liter', 'megawatt hour', 'tonne (metric ton)')
    AND WRG_ID = 'EUR';