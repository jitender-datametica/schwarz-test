CREATE OR REPLACE VIEW DBP_MSI_VIEW_EK_KUN.MV_F_ODS_BON_KOPF_2
-- MCIE1607, 09/12/2019, ADDED FILTER ON MANDANT_ID=2
-- MANDANTFILTERUNG ZUR REDUZIERUNG DATEN / PERFORMANCEGRÜNDEN
-- MCIE1607, SPEC0070977, 04/03/2020, ADDED FILTER ON MANDANT_ID=4
-- 06.08.2020 TWIE: SPEC0082685 MANDANT_ID 6 FÜR HR ERGÄNZEN
-- 19.10.2020 STANISZEWSKP: SPEC0085484, AP0071310 -INCLUDED SK (5) IN THE MANDANT_2
-- 12.05.2021 twie: SPEC0105240 mandant_id 1 und 8 für DE und BG ergänzen
-- 21.09.2022 lsvi: SPEC0169775

(
 BON_ID
,BON_DAT
,WUP_ID
,NB_ID
,MANDANT_ID
,TURNOVER_FG
,WRG_ID
,KUNDENKARTE_ID
,KUNDENKARTE_TYP_ID
)
AS
SELECT
K.BON_ID,
K.BON_DAT,
K.WUP_ID,
W.NB_ID,
K.MANDANT_ID,
K.TURNOVER_FG,
K.WRG_ID,
CASE 
WHEN K.MANDANT_ID = 3 AND K.KUNDENKARTE_TYP_ID = 2 THEN K.KUNDENKARTE_ID 
WHEN K.MANDANT_ID <> 3 THEN K.KUNDENKARTE_ID 
ELSE NULL END AS KUNDENKARTE_ID,
CASE 
WHEN K.MANDANT_ID = 3 AND K.KUNDENKARTE_TYP_ID = 2 THEN K.KUNDENKARTE_TYP_ID
WHEN K.MANDANT_ID <> 3 THEN K.KUNDENKARTE_TYP_ID
ELSE NULL END AS KUNDENKARTE_TYP_ID

FROM DBP_V_ODS.V_ODS_BON_KOPF_2 K

INNER JOIN DBP_VIEW.V_WUP_2 W
ON W.MANDANT_ID = K.MANDANT_ID
AND W.WUP_ID     = K.WUP_ID

WHERE ( K.BON_ID
    ,K.WUP_ID
    ,K.MANDANT_ID) NOT IN (SELECT
STO.BON_ID,
STO.WUP_ID,
STO.MANDANT_ID
FROM DBP_V_ODS.V_ODS_BON_STORNO_2 STO
)
--AND KAR.CRM_KUNDENKARTE_ART_ID <> 2

AND K.TURNOVER_FG = 1
;