CREATE OR REPLACE VIEW DBP_MSI_VIEW_EK_KUN.MV_KAMPAGNE_2
(
 MANDANT_ID
,KAMPAGNE_ID
,KAMPAGNE_NAME
,DAT_KAMPAGNE_VON
,DAT_KAMPAGNE_BIS
,KAMPAGNE_RHYTHMUS_TYP_ID
,KAMPAGNE_VERSION_NR
,ANZAHL_LOYALTY_KUNDEN
)
AS
SELECT
 v01.MANDANT_ID
,v01.KAMPAGNE_ID
,v01.KAMPAGNE_NAME
,v01.DAT_KAMPAGNE_VON
,v01.DAT_KAMPAGNE_BIS
,v01.KAMPAGNE_RHYTHMUS_TYP_ID
,v01.KAMPAGNE_VERSION_NR
,COUNT (DISTINCT v02.CRM_KUNDE_ID) AS ANZAHL_LOYALTY_KUNDEN
FROM DBP_VIEW.V_KAMPAGNE_2 v01
JOIN DBP_VIEW.V_CRM_L_KUNDE_2 v02
ON v01.MANDANT_ID = v02.KUNDE_MANDANT_ID
WHERE TO_DATE(v02.ZEIT_REGISTRIERUNG) <= v01.DAT_KAMPAGNE_VON
GROUP BY ALL
;