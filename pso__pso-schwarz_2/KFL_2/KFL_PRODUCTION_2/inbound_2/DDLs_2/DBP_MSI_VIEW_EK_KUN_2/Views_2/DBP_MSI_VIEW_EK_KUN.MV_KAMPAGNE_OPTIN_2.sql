CREATE OR REPLACE VIEW DBP_MSI_VIEW_EK_KUN.MV_KAMPAGNE_OPTIN_2
(
 MANDANT_ID
,KAMPAGNE_ID
,KAMPAGNE_NAME
,DAT_KAMPAGNE_VON
,DAT_KAMPAGNE_BIS
,KAMPAGNE_RHYTHMUS_TYP_ID
,KAMPAGNE_VERSION_NR
,CRM_OPTIN_KANAL_ID
,ANZAHL_OPTIN_ANTWORTEN
)
AS
SELECT
 v04.MANDANT_ID
,v04.KAMPAGNE_ID
,v04.KAMPAGNE_NAME
,v04.DAT_KAMPAGNE_VON
,v04.DAT_KAMPAGNE_BIS
,v04.KAMPAGNE_RHYTHMUS_TYP_ID
,v04.KAMPAGNE_VERSION_NR
,v01.CRM_OPTIN_KANAL_CD AS CRM_OPTIN_KANAL_ID
,COUNT (DISTINCT v02.CRM_OPTIN_ID) AS ANZAHL_OPTIN_ANTWORTEN

FROM	DBP_VIEW.V_CRM_L_OPTIN_2 v01
JOIN	DBP_VIEW.V_CRM_KUNDE_OPTIN_ZU_2 v02
	ON 	V01.CRM_OPTIN_ID = v02.CRM_OPTIN_ID
JOIN	DBP_VIEW.V_CRM_L_KUNDE_2 v03
	ON 	v02.CRM_KUNDE_ID = v03.CRM_KUNDE_ID
JOIN	DBP_VIEW.V_KAMPAGNE_2	v04
ON v03.REGISTRIERUNGSFILIALE_MANDANT_ID = v04.MANDANT_ID
AND TO_DATE(v03.ZEIT_REGISTRIERUNG) <= v04.DAT_KAMPAGNE_VON
WHERE v01.CRM_OPTIN_KANAL_CD IN ('emailLoyalty', 'smsLoyalty')
GROUP BY ALL
;