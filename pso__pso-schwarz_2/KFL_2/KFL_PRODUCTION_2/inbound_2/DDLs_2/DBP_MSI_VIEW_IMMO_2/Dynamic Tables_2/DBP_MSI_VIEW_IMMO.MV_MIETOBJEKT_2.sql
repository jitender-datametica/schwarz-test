CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMMO.MV_MIETOBJEKT_2(
	MANDANT_ID,
	MO_INTRENO,
	MO_SMENR,
	MO_OBJEKT_NR,
	MO_BRANCHE_ID,
	MO_TYP_ID,
	MO_ART_KZ,
	MO_NUTZUNG_ID,
	WE_INTRENO,
	DAT_MO_GUELTIG_VON,
	DAT_MO_GUELTIG_BIS,
	MO_STATUS_ID,
	MO_AKT_GUELTIG_FG,
	DAT_LETZTE_UEBERGABE,
	LEERSTAND_SEIT,
	LEERSTAND_SEIT_2101,
	BEMESSUNG_ART,
	BEMESSUNG_ART_ID,
	GEBAUDE_NR,
	FLAECHENKATEGORIE_ID,
	FLAECHENKATEGORIE_BEZ,
	FLAECHEART_LEERSTAND_ID,
	FLAECHEART_LEERSTAND_BEZ
) TARGET_LAG = '1 hour, 30 minutes' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMMO
 AS
   SELECT V0.MANDANT_ID ,
       V0.MO_INTRENO ,
       V0.MO_SMENR ,
       V0.MO_OBJEKT_NR ,
       V0.BRANCHE_ID AS MO_BRANCHE_ID ,
       V0.MO_TYP_ID ,
       V0.MO_ART_KZ ,
       V0.MO_NUTZUNG_ID ,
       V0.WE_INTRENO ,
       CASE
           WHEN V0.DAT_MO_GUELTIG_VON IS NULL
                OR V0.DAT_MO_GUELTIG_VON=TO_DATE('1900-01-01','YYYY-MM_2-DD') THEN V7.DAT_WE_GUELTIG_VON
           ELSE V0.DAT_MO_GUELTIG_VON
       END AS DAT_MO_GUELTIG_VON ,
       V0.DAT_MO_GUELTIG_BIS ,
       V5.MO_STATUS_ID ,
       CASE
           WHEN CURRENT_DATE BETWEEN V0.DAT_MO_GUELTIG_VON AND V0.DAT_MO_GUELTIG_BIS THEN 1
           ELSE 0
       END AS MO_AKT_GUELTIG_FG ,
       V1.DAT_LETZTE_UEBERGABE ,
       COALESCE(V4.DAT_LEERSTAND_SEIT +1, (CASE
                                               WHEN V6.MAX_DAT_STATUS_VON = TO_DATE('1900-01-01','YYYY-MM_2-DD') THEN V0.DAT_MO_GUELTIG_VON
                                               ELSE V6.MAX_DAT_STATUS_VON
                                           END)) AS LEERSTAND_SEIT ,
       COALESCE(V4.DAT_LEERSTAND_SEIT +1, (CASE
                                               WHEN V0.DAT_MO_GUELTIG_VON=TO_DATE('1900-01-01','YYYY-MM_2-DD') THEN V7.DAT_WE_GUELTIG_VON
                                               ELSE V0.DAT_MO_GUELTIG_VON
                                           END)) AS LEERSTAND_SEIT_2101 ,
       V2.BEMESSUNG_ART_ID ,
       V2.BEMESSUNG_ART_ID AS BEMESSUNG_ART_ID2 ,
       SUBSTR(V0.MO_SMENR, 1, 2) AS GEBAEUDE_NR ,
       CASE
           WHEN V0.GEBAEUDE_NR=0 THEN 6
           WHEN V0.MO_TYP_ID=30 THEN 5
           WHEN V2.BEMESSUNG_ART_ID='0310' THEN 1
           WHEN V2.BEMESSUNG_ART_ID='0300'
                AND V2.GROESSE < 200 THEN 2
           WHEN V2.BEMESSUNG_ART_ID='0300'
                AND V2.GROESSE >= 200 THEN 3
           WHEN V2.BEMESSUNG_ART_ID='0320' THEN 4
           ELSE 0
       END AS FLACHENKATEGORIE ,
       CASE
           WHEN V0.GEBAEUDE_NR=0 THEN 'Freiflächen'
           WHEN V0.MO_TYP_ID=30 THEN 'SB-Warenhaus'
           WHEN V2.BEMESSUNG_ART_ID='0310' THEN 'Gewerbeflächen'
           WHEN V2.BEMESSUNG_ART_ID='0300'
                AND V2.GROESSE < 200 THEN 'Handelsflächen < 200m²'
           WHEN V2.BEMESSUNG_ART_ID='0300'
                AND V2.GROESSE >= 200 THEN 'Handelsflächen >= 200m²'
           WHEN V2.BEMESSUNG_ART_ID='0320' THEN 'Wohnungen'
           ELSE 'n.v.'
       END AS FLACHENKATEGORIE_BEZ ,
       CASE
           WHEN V0.MO_ART_KZ IN ('I') THEN 4
           WHEN V0.MO_ART_KZ IN ('V') THEN 5
           WHEN V0.MO_ART_KZ IN ('T') THEN 7
           WHEN V0.MO_ART_KZ IN ('U') THEN 8
           WHEN V0.MO_ART_KZ IN ('A') THEN 9
           WHEN V2.BEMESSUNG_ART_ID='0300' THEN 1
           WHEN V2.BEMESSUNG_ART_ID='0310' THEN 2
           WHEN V2.BEMESSUNG_ART_ID='0320' THEN 3
           ELSE 0
       END FLAECHEART_LEERSTAND_ID ,
       CASE
           WHEN V0.MO_ART_KZ IN ('I') THEN 'nicht wirtschaftlicher Invest / hoher Invest'
           WHEN V0.MO_ART_KZ IN ('V') THEN 'Vermietungsflächen an Vertrieb'
           WHEN V0.MO_ART_KZ IN ('T') THEN 'Vetriebsflächen an Vermietung'
           WHEN V0.MO_ART_KZ IN ('U') THEN 'Umbauflächen'
           WHEN V0.MO_ART_KZ IN ('A') THEN 'zu vermietende Allgemeinflächen'
           WHEN V2.BEMESSUNG_ART_ID='0300' THEN 'Handelsflächen'
           WHEN V2.BEMESSUNG_ART_ID='0310' THEN 'Sonderflächen'
           WHEN V2.BEMESSUNG_ART_ID='0320' THEN 'Wohnungen'
           ELSE 'nicht definiert'
       END FLAECHEART_LEERSTAND_BEZ
FROM DBP_VIEW.V_IMMO_MIETOBJEKT_2 V0
INNER JOIN
  (SELECT MANDANT_ID ,
          MO_INTRENO ,
          MAX(MO_STATUS_ID) AS MO_STATUS_ID
   FROM DBP_VIEW.V_IMMO_MO_STATUS_PER_2
   WHERE CURRENT_DATE BETWEEN DAT_STATUS_VON AND DAT_STATUS_BIS
   GROUP BY 1 ,
            2) V5 ON V5.MANDANT_ID = V0.MANDANT_ID
AND V5.MO_INTRENO = V0.MO_INTRENO
LEFT OUTER JOIN
  (SELECT MANDANT_ID ,
          MO_INTRENO ,
          MAX(DAT_BIS) AS DAT_LEERSTAND_SEIT
   FROM DBP_VIEW.V_IMMO_MIETVERTRAG_MO_ZU_PER_2
   WHERE CURRENT_DATE > DAT_BIS
   GROUP BY 1 ,
            2) V4 ON V0.MANDANT_ID = V4.MANDANT_ID
AND V0.MO_INTRENO = V4.MO_INTRENO
AND V5.MO_STATUS_ID IN (0 ,
                        2 ,
                        3)
LEFT JOIN
  (SELECT MANDANT_ID ,
          MO_INTRENO ,
          MAX(DAT_STATUS_VON) AS MAX_DAT_STATUS_VON
   FROM DBP_VIEW.V_IMMO_MO_STATUS_PER_2
   WHERE CURRENT_DATE BETWEEN DAT_STATUS_VON AND DAT_STATUS_BIS
   GROUP BY 1 ,
            2) V6 ON V0.MANDANT_ID = V6.MANDANT_ID
AND V0.MO_INTRENO = V6.MO_INTRENO
LEFT JOIN DBP_MSI_VIEW_IMMO.MV_IMMO_MIETOBJEKT_MESSUNG_2 V2 ON (V2.MO_INTRENO = V0.MO_INTRENO)
AND (V2.MANDANT_ID = V0.MANDANT_ID)
LEFT JOIN
    (SELECT MANDANT_ID ,
          MO_STATUS_ID ,
          MO_INTRENO ,
          MAX(DAT_STATUS_VON) AS DAT_LETZTE_UEBERGABE
   FROM DBP_VIEW.V_IMMO_MO_STATUS_PER_2
   WHERE MO_STATUS_ID = 4
     AND CURRENT_DATE BETWEEN DAT_STATUS_VON AND DAT_STATUS_BIS
   GROUP BY 1 ,
            2 ,
            3) V1 ON V0.MANDANT_ID = V1.MANDANT_ID
AND V0.MO_INTRENO = V1.MO_INTRENO
LEFT JOIN DBP_VIEW.V_IMMO_WIRTSCHAFTSEINHEIT_2 AS V7 ON V0.MANDANT_ID=V7.MANDANT_ID
AND V0.WE_INTRENO=V7.WE_INTRENO;