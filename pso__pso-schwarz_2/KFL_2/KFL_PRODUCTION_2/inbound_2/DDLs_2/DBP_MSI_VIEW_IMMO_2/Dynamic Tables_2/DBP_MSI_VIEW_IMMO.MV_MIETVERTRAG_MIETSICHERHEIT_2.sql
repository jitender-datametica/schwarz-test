CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMMO.MV_MIETVERTRAG_MIETSICHERHEIT_2(
	MANDANT_ID,
	MV_INTRENO,
	WE_INTRENO,
	WIRTSCHAFTSEINHEIT_ID,
	PARTNER_ID,
	BUCHUNGSKREIS_ID,
	SICHERHEIT_LFD_NR,
	KURS_IST,
	BETRAG_SICHERHEIT_IST,
	KURS_SOLL,
	BETRAG_SICHERHEIT_SOLL,
	DAT_EINGANG,
	DAT_EINLOESUNG,
	DAT_RUECKGABE,
	DAT_UEBERGABE,
	DAT_AUSSTELLUNG,
	DAT_BIS,
	BUERGSCHAFT_TYP_ID,
	BUERGSCHAFT_ID,
	BUERGSCHAFT_GRUND,
	RUECKGABE_VORAUSSETZUNG,
	BANK_ID,
	KAUTION_BEZ,
	WRG_ID,
	WRG_TYP_ID,
	BUERGSCHAFT_NR
) TARGET_LAG = '1 hour, 30 minutes' REFRESH_MODE = FULL INITIALIZE = ON_CREATE WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMMO
 AS 
-- 20191021 cbru1709: Vereinfachung und Ausbau einiger Subselect und Left joins bezüglich distinct Zugriff auf WE_MO_MV
 -- 20191030 cbru1709: Entfernen der felder miet_fg1 und miet_fg (wird über zusätzliche Tabelle geregelt)
 -- 20191108 cbru1709: Datumsfelder ersetzen von 31.12.9999 durch Null TEST1294768
 -- 20200129 cbru1709: Hinzufügen von fi.sachkonto_id = 197200 Filter
 -- 20200204 cbru1709: Neuer Join mit ivs_mietvertrag_sicher_2 wegen buchungskreis
 -- 20220331 richternic: INC3325029 TRUNC bei KURS_2 (CASE 2) rausnehmen 
  -- 20221205 richternic: SPEC0178553 -> WRG_ID fuer SOLL und IST Betrag kann unterschiedlich sein, daher getrennte Umrechnung 
SELECT MVS.MANDANT_ID ,
       MVS.MV_INTRENO ,
       W.WE_INTRENO ,
       W.WIRTSCHAFTSEINHEIT_ID ,
       NULL AS PARTNER_ID, -- ausbauen nach Bereinigung FE- deshalb null!
 CAST(IVS.BUCHUNGSKREIS_ID AS VARCHAR(20)) AS BUCHUNGSKREIS_ID,
 MVS.SICHERHEIT_LFD_NR,
 CASE
     WHEN WRG_TYP_ID = 0
          AND MVS.IST_WRG_ID <> MWT.WRG_ID THEN LW.UMRECHNUNGSKURS
     WHEN WRG_TYP_ID = 1
          AND MVS.IST_WRG_ID <> MWT.WRG_ID THEN (1/LW.UMRECHNUNGSKURS)
     ELSE 1.0000000
 END AS KURS_IST,
 CASE
     WHEN MVS.BETRAG_IST = 0 THEN COALESCE(FIDET.BETRAG_SICHERHEIT_IST*KURS_IST, 0)
     ELSE MVS.BETRAG_IST * KURS_IST
 END AS BETRAG_SICHERHEIT_IST,
 
 CASE
     WHEN WRG_TYP_ID = 0
          AND MVS.SOLL_WRG_ID <> MWT.WRG_ID THEN LW.UMRECHNUNGSKURS
     WHEN WRG_TYP_ID = 1
          AND MVS.SOLL_WRG_ID <> MWT.WRG_ID THEN (1/LW.UMRECHNUNGSKURS)
     ELSE 1.0000000
 END AS KURS_SOLL,
 MVS.BETRAG_SOLL * KURS_SOLL AS BETRAG_SICHERHEIT_SOLL,
 
 MVS.DAT_EINGANG_AM AS DAT_EINGANG,
 CASE
     WHEN MVS.DAT_EINGELOEST_AM = TO_DATE('9999-12-31','YYYY-MM_2-DD') THEN NULL
     ELSE MVS.DAT_EINGELOEST_AM
 END AS DAT_EINLOESUNG,
 MVS.DAT_RUECKGABE_AM AS DAT_RUECKGABE,
 CASE
     WHEN MVS.DAT_UEBERGABE_AM = TO_DATE('9999-12-31','YYYY-MM_2-DD') THEN NULL
     ELSE MVS.DAT_UEBERGABE_AM
 END AS DAT_UEBERGABE,
 CASE
     WHEN MVS.DAT_AUSSTELLUNG_AM = TO_DATE('9999-12-31','YYYY-MM_2-DD') THEN NULL
     ELSE MVS.DAT_AUSSTELLUNG_AM
 END AS DAT_AUSSTELLUNG,
 MVS.DAT_BIS,
 MVS.SICHERHEIT_TYP AS BUERGSCHAFT_TYP_ID,
 COALESCE(MVS.BUERGSCHAFT_NR, '') AS BUERGSCHAFT_ID,
 MVS.BUERGSCHAFT_GRUND,
 MVS.RUECKGABE_VORAUSSETZUNG,
 COALESCE(MVS.BANK_ID, '') AS BANK_ID,
 COALESCE(MVS.KAUTION_BEZ, '') AS KAUTION_BEZ,
 MWT.WRG_ID,
 MWT.WRG_TYP_ID,
 MVS.BUERGSCHAFT_NR
FROM DBP_VIEW.V_IMMO_MIETVERTRAG_SICHERHEIT_2 MVS
LEFT JOIN DBP_VIEW.V_IVS_MIETVERTRAG_SICHER_2 IVS ON MVS.MANDANT_ID = IVS.MANDANT_ID
AND MVS.MV_INTRENO = IVS.MIETVERTRAG_ID
AND MVS.SICHERHEIT_LFD_NR = IVS.SICHERHEIT_LFD_NR
JOIN DBP_VIEW.V_MANDANT_WRG_TYP_ZU_2 MWT ON MWT.MANDANT_ID = MVS.MANDANT_ID
JOIN DBP_VIEW.V_MANDANT_2 M ON M.MANDANT_ID = MVS.MANDANT_ID
JOIN DBP_VIEW.V_KURS_2 LW ON LW.VON_WRG_ID = M.DEFAULT_WRG
AND LW.NACH_WRG_ID = 'EUR'
AND LW.KURSTYP_ID = 3
AND LW.DAT_BIS = TO_DATE('9999-12-31','YYYY-MM_2-DD')
--AND COALESCE(MVS.DAT_AUSSTELLUNG_AM, CURRENT_DATE) BETWEEN CAST(101 AS DATE) AND CAST(80991231 AS DATE)
AND COALESCE(MVS.DAT_AUSSTELLUNG_AM, CURRENT_DATE) BETWEEN TO_DATE('1900-01-01','YYYY-MM_2-DD') AND TO_DATE('9999-12-31','YYYY-MM_2-DD')
LEFT JOIN
  (SELECT DISTINCT MANDANT_ID ,
                   WE_INTRENO ,
                   MV_INTRENO
   FROM
     (SELECT V2.MANDANT_ID ,
             V2.WE_INTRENO ,
             V1.MV_INTRENO
      FROM DBP_VIEW.V_IMMO_MO_STATUS_PER_2 V1 -- dat_von, dat_bis der Beziehung

      JOIN DBP_VIEW.V_IMMO_MIETOBJEKT_2 V2 ON V1.MO_INTRENO = V2.MO_INTRENO
      WHERE CURRENT_DATE BETWEEN DAT_STATUS_VON AND DAT_STATUS_BIS
      UNION ALL SELECT V2.MANDANT_ID ,
                       V2.WE_INTRENO ,
                       V1.MV_INTRENO
      FROM DBP_VIEW.V_IMMO_MIETVERTRAG_MO_ZU_PER_2 V1 -- dat_von, dat_bis der Beziehung

      JOIN DBP_VIEW.V_IMMO_MIETOBJEKT_2 V2 ON V1.MO_INTRENO = V2.MO_INTRENO
      WHERE (V1.MV_INTRENO) NOT IN
          (SELECT MV_INTRENO
           FROM DBP_VIEW.V_IMMO_MO_STATUS_PER_2
           WHERE CURRENT_DATE BETWEEN DAT_STATUS_VON AND DAT_STATUS_BIS )
      UNION ALL SELECT V1.MANDANT_ID ,
                       V1.WE_INTRENO ,
                       V1.MV_INTRENO
      FROM DBP_VIEW.V_IMMO_MIETVERTRAG_WE_ZU_PER_2 V1 -- dat_von, dat_bis der Beziehung

      WHERE CURRENT_DATE BETWEEN V1.DAT_VON AND V1.DAT_BIS ) TMP) H ON MVS.MANDANT_ID = H.MANDANT_ID
AND MVS.MV_INTRENO = H.MV_INTRENO
LEFT JOIN DBP_VIEW.V_IMMO_WIRTSCHAFTSEINHEIT_2 W ON H.MANDANT_ID = W.MANDANT_ID
AND H.WE_INTRENO = W.WE_INTRENO
AND CURRENT_DATE BETWEEN W.DAT_WE_GUELTIG_VON AND W.DAT_WE_GUELTIG_BIS
LEFT JOIN
  (SELECT FI.MANDANT_ID ,
          FI.DAT_BUCH ,
          FI.IN_FI_BELEG_ID ,
          FI.GESCHAEFTSBEREICH_ID ,
          FI.AUSGLEICH_BELEG_ID ,
          FI.RECH_KONTOART_ID ,
          S.BUERGSCHAFT_NR ,
          S.SICHERHEIT_LFD_NR ,
          S.MV_INTRENO ,
          SUM(FI.BETRAG_FI_BELEG * CASE
                                       WHEN FI.SOLL_HABEN_KZ = 'H' THEN (1)
                                       ELSE -1
                                   END) AS BETRAG_SICHERHEIT_IST
   FROM DBP_VIEW.V_IMMO_MIETVERTRAG_SICHERHEIT_2 S
   JOIN DBP_VIEW.V_IN_FI_BELEG_DET_2 FI ON S.MANDANT_ID = FI.MANDANT_ID
   AND S.DAT_EINGANG_AM = FI.DAT_BUCH
   AND CAST(S.BUERGSCHAFT_NR AS DECIMAL(18, 0)) = FI.IN_FI_BELEG_ID
   AND TRIM(LENGTH(S.BUERGSCHAFT_NR)) < 19 --AND (Translate_Chk(s.buergschaft_nr USING Unicode_To_Latin) = 0)

   WHERE FI.AUSGLEICH_BELEG_ID IS NULL
     AND FI.RECH_KONTOART_ID = 'D'
     AND S.BETRAG_IST = 0.0000
     AND try_to_numeric(S.BUERGSCHAFT_NR) IS NOT NULL
     AND FI.SACHKONTO_ID =197200
   GROUP BY FI.MANDANT_ID ,
            FI.DAT_BUCH ,
            FI.IN_FI_BELEG_ID ,
            FI.GESCHAEFTSBEREICH_ID ,
            FI.AUSGLEICH_BELEG_ID ,
            FI.RECH_KONTOART_ID ,
            S.BUERGSCHAFT_NR ,
            S.SICHERHEIT_LFD_NR ,
            S.MV_INTRENO) FIDET ON MVS.MANDANT_ID = FIDET.MANDANT_ID
AND MVS.DAT_EINGANG_AM = FIDET.DAT_BUCH
AND MVS.MV_INTRENO = FIDET.MV_INTRENO
AND ((FIDET.GESCHAEFTSBEREICH_ID IS NOT NULL
      AND FIDET.GESCHAEFTSBEREICH_ID = W.WIRTSCHAFTSEINHEIT_ID)
     OR (FIDET.GESCHAEFTSBEREICH_ID IS NULL))
AND MVS.BUERGSCHAFT_NR = FIDET.BUERGSCHAFT_NR
AND MVS.SICHERHEIT_LFD_NR = FIDET.SICHERHEIT_LFD_NR;