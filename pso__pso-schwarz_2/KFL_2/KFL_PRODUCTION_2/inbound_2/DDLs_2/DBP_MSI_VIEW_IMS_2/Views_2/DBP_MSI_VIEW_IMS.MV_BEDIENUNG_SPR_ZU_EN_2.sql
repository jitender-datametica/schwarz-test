CREATE OR REPLACE VIEW DBP_MSI_VIEW_IMS.MV_BEDIENUNG_SPR_ZU_EN_2 AS
-- 17.06.2013 twie: Kopie aus VIS

   SELECT
   CASE WHEN dat = CURRENT_DATE -1 THEN 1
   WHEN dat = CURRENT_DATE -2 THEN -1
   ELSE 0 END bed_fg,
   CASE WHEN dat = CURRENT_DATE -1 THEN 'Yes'
   WHEN dat = CURRENT_DATE -2 THEN ''
   ELSE 'No' END bed_bez,
   CASE WHEN dat = CURRENT_DATE -1 THEN 'Y'
   ELSE '' END bed_kbez

   FROM dbp_view.v_tag_2
   WHERE dat BETWEEN CURRENT_DATE -2 AND CURRENT_DATE;