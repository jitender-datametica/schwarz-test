CREATE OR REPLACE VIEW DBP_MSI_VIEW_IMS.MV_L_BELASTUNGS_KZ_2 AS
-- 25.08.2014 twie: Initial

   SELECT

   CASE WHEN dat = CURRENT_DATE THEN 'A'
   WHEN dat = CURRENT_DATE -1 THEN 'H'
   WHEN dat = CURRENT_DATE -2 THEN 'L'
   ELSE 'S'
   END AS belastungs_kz
   FROM dbp_view.v_tag_2
   WHERE dat BETWEEN CURRENT_DATE -3 AND CURRENT_DATE
;