CREATE OR REPLACE DYNAMIC TABLE DBP_MSI_VIEW_IMS_DT.MV_BEDIENUNG_SPR_ZU_BG_2
(
	BED_FG,
	BED_BEZ,
	BED_KBEZ
)
TARGET_LAG = '1 hour, 30 minutes' 
REFRESH_MODE = FULL 
INITIALIZE = ON_CREATE 
WAREHOUSE = WH_KFL_%%environmentAbbreviation%%_DYNAMIC_TABLE_IMS

AS
-- 17.06.2013 twie: Kopie aus VIS

   SELECT
   CASE WHEN dat = CURRENT_DATE -1 THEN 1
   WHEN dat = CURRENT_DATE -2 THEN -1
   ELSE 0 END bed_fg,
   CASE WHEN dat = CURRENT_DATE -1 THEN 'Ja'
   WHEN dat = CURRENT_DATE -2 THEN ''
   ELSE 'Nein' END bed_bez,
   CASE WHEN dat = CURRENT_DATE -1 THEN 'J'
   ELSE '' END bed_kbez

   FROM dbp_view.v_tag_2
   WHERE dat BETWEEN CURRENT_DATE -2 AND CURRENT_DATE
   ;