--22.09.2021, AP0103346,SPEC0124027, dknop, initial
--18.10.2021, dknop, formatting adjustments
AS
SELECT
 WUP_ID AS EMPFAENGER_ID
,NB_ID
,MANDANT_ID AS MANDANT_ID_EMPFAENGER
,DAT_VON
,CASE WHEN NB_ID = -1 THEN '---' ELSE WUP_STANDORT END AS EMPFAENGER_BEZ
,DAT_BIS
,BUCHUNGSKREIS_ID
,VERKAUFSORGANISATION_ID
,WUP_TYP_ID
,BREITENGRAD
,LAENGENGRAD
,VKL_ID
,VS_ID
FROM DBP_VIEW.V_WUP_2
WHERE (NB_ID IN (2, 0, -111) AND WUP_ID > 0)
   OR (NB_ID = -1 AND WUP_ID = 0);