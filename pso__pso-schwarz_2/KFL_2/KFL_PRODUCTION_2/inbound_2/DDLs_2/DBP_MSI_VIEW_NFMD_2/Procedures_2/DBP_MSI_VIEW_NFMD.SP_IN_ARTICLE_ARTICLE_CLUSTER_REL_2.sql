CREATE OR REPLACE PROCEDURE DBP_MSI_VIEW_NFMD.SP_IN_ARTICLE_ARTICLE_CLUSTER_REL(
    "P_KJWO_WW" NUMBER, 
    "P_MANDANT_ID" NUMBER, 
    "P_AKTION_ID" VARCHAR(255), 
    "P_ART_ID" NUMBER, 
    "P_USER_ID" VARCHAR(255))
RETURNS STRING
LANGUAGE SQL
COMMENT='Set selected Article Cluster for Article'
EXECUTE AS OWNER
AS $$ 
BEGIN 

INSERT INTO DBP_MSI_VIEW_NFMD.TS_NFMD_ARTICLE_ARTICLE_CLUSTER_REL_2 
    (MANDANT_ID, 
    AKTION_ID, 
    ART_ID, 
    ARTICLE_CLUSTER_ID,
    KJWO_WW,
    DWH_CREATED_TMSP,
    USER_ID
    )
SELECT :P_MANDANT_ID, 
        :P_AKTION_ID, 
        :P_ART_ID, 
        ARTICLE_CLUSTER_ID, 
        :P_KJWO_WW, 
        CURRENT_TIMESTAMP::TIMESTAMP_NTZ, 
        :P_USER_ID
FROM DBP_MSI_VIEW_NFMD.MV_NFMD_LATEST_SELECTED_ARTICLE_CLUSTER_2 
WHERE MANDANT_ID = :P_MANDANT_ID;

COMMIT;
RETURN 'Artikel_2 wurde einem Cluster hinzugefuegt';
END;
$$;