CREATE OR REPLACE PROCEDURE DBP_MSI_VIEW_NFMD.SP_IN_NFMD_ART_SECOND_DISCOUNT_Checkbox(
    "P_KJWO_WW" NUMBER(38,0),
    "P_MANDANT_ID" NUMBER(38,0),
    "P_AKTION_ID" VARCHAR(255),
    "P_ART_ID" NUMBER(38,0),
    "P_USER_ID" VARCHAR(255),
    "P_WRG_ID" VARCHAR(20),
    "P_DISCOUNT_TYPE_NAME" VARCHAR(50),
    "P_CHECKBOX_HELPER" NUMBER(1,0)
)
RETURNS STRING
LANGUAGE SQL
COMMENT='Insert data into TS_NFMD_ARTICLE_STORE_PRICE_2 based on the second discount percentage and retrieve article-WUP_2 price combinations from MV_NFMD_ARTICLE_STORE_SCORECARD_2'
EXECUTE AS OWNER
AS 
$$
DECLARE
    var_currentDate_add3Months DATE;
    var_next_saptransfer_date DATE;
BEGIN
        
    CASE  :P_CHECKBOX_HELPER 
        WHEN 1 THEN
        

        INSERT INTO DBP_MSI_VIEW_NFMD.TS_NFMD_ARTICLE_STORE_PRICE_2 (
            KJWO_WW, MANDANT_ID, AKTION_ID, ART_ID, WUP_ID,
            DWH_CREATED_TMSP, USER_ID, WRG_ID, MANUAL_PROMO_PRICE_GROSS_LOCAL_VAL, DISCOUNT_TYPE_NAME
        )
        SELECT
            :P_KJWO_WW, :P_MANDANT_ID, :P_AKTION_ID, :P_ART_ID, WUP_ID,
            CURRENT_TIMESTAMP::TIMESTAMP_NTZ, :P_USER_ID, :P_WRG_ID, MODEL_PRICE_GROSS_LOCAL_VAL, :P_DISCOUNT_TYPE_NAME
        FROM DBP_DATA.NFMD_ARTICLE_STORE_SCORECARD_2
        WHERE DISCOUNT_TYPE_NAME = :P_DISCOUNT_TYPE_NAME
          AND MANDANT_ID = :P_MANDANT_ID
          AND KJWO_WW = :P_KJWO_WW
          AND ART_ID = :P_ART_ID;
          
        WHEN 0 THEN 
        DELETE FROM DBP_MSI_VIEW_NFMD.TS_NFMD_ARTICLE_STORE_PRICE_2 WHERE
         MANDANT_ID = :P_MANDANT_ID 
         AND KJWO_WW = :P_KJWO_WW 
         AND DWH_CREATED_TMSP < DATEADD(minute, -30 ,GETDATE()) -- warum ?!  
         AND ART_ID = :P_ART_ID 
         AND ART_ID NOT IN 
         (SELECT ART_ID FROM DBP_MSI_VIEW_NFMD.TS_NFMD_MANUAL_PRICE_RELEASE_2 
            WHERE discount_type_name = :P_DISCOUNT_TYPE_NAME 
            AND ART_ID = :P_ART_ID 
            AND MANDANT_ID = :P_MANDANT_ID 
            AND KJWO_WW = :P_KJWO_WW);
    END;

    COMMIT;
    return 'Anpassung ZR erfolgreich';
END;
$$;