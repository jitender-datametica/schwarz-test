CREATE OR REPLACE VIEW DBP_MSI_VIEW_NFMD.MV_NFMD_LATEST_ART_PRICE_DAT_2 AS
SELECT KJWO_WW,
       MANDANT_ID,
       --AKTION_ID,
       ART_ID,
       --NULL       AS INITAL_DECISON_DATE, -- Deprecated, will be removed
       DWH_CREATED_TMSP AS UPDATED_DATE,
       MANUAL_PROMO_PRICE_DT AS MANUAL_PRICE_ART_DAT
FROM DBP_MSI_VIEW_NFMD.TS_NFMD_ARTICLE_PRICE_DATE_2
    QUALIFY RANK() OVER (PARTITION BY KJWO_WW, MANDANT_ID,  ART_ID ORDER BY DWH_CREATED_TMSP DESC) = 1;    