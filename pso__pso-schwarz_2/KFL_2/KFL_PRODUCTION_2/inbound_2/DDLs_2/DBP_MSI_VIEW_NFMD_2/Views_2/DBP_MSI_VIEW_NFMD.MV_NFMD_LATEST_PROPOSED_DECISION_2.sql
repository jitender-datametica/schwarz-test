CREATE OR REPLACE VIEW DBP_MSI_VIEW_NFMD.MV_NFMD_LATEST_PROPOSED_DECISION_2 AS 
SELECT KJWO_WW,
       MANDANT_ID,
       --AKTION_ID,
       ART_ID,
       --NULL       AS INITAL_DECISON_DATE,  -- Deprecated, will be removed
       DWH_CREATED_TMSP AS UPDATED_DATE,
       MARKDOWN_DECISION_ID
FROM DBP_MSI_VIEW_NFMD.TS_NFMD_PROPOSED_DECISION_2
    QUALIFY RANK() OVER (PARTITION BY KJWO_WW, MANDANT_ID,  ART_ID ORDER BY DWH_CREATED_TMSP DESC) = 1;