CREATE OR REPLACE VIEW DBP_MSI_VIEW_NFMD.MV_NFMD_PARAMETERS_2(
	MANDANT_ID,
	WRG_ID,
	DISCOUNT_STEPS,
	PRICE_ENDING_THRESHOLD,
	MAX_DISCOUNT_CNT,
	MIN_DISCOUNT_PCT,
	MAX_DISCOUNT_PCT,
	MIN_VALUE,
	NO_TOUCH_DAYS_CNT,
	MIN_DAYS_BTW_DISCOUNTS_CNT,
	DISCOUNT_DAY_OF_WEEK,
	NEXT_DISCOUNT_DATE,
	MAX_DISCOUNT_FOR_MAX_PRICE_PCT,
	PRICE_THRESHOLD_FOR_MAX_DISCOUNT,
	DISCOUNT_TYPE_FG,
	PROMOTION_LIFECYCLE,
	PROMO_LIFECYCLE_WEEKS_CNT,
	VALIDITY_DAYS_CNT,
	MAX_DAYS_BTW_DISCOUNTS_CNT,
	DWH_CREATED_TMSP,
	EXPERIMENT_COHORTS_CNT,
	EXPERIMENTS_FOR_MANUAL_EVALUATION_CNT,
	SUCCESS_WRITE_OFF_THRESHOLD,
	SUCCESS_COHORTS_THRESHOLD,
	EXPORT_DAY_OF_WEEK,
	NEXT_EXPORT_DATE,
	SECOND_DISCOUNT_PCT,
	SECOND_DISCOUNT_VALIDITY_WKS_CNT
) AS
SELECT
	MANDANT_ID,
    WRG_ID,
	DISCOUNT_STEPS,
	PRICE_ENDING_THRESHOLD ,
	NULL AS MAX_DISCOUNT_CNT, 
	MIN_DISCOUNT_PCT,
	MAX_DISCOUNT_PCT,
	MIN_PRICE_GROSS_LOCAL_VAL AS MIN_VALUE,
	NO_TOUCH_DAYS_CNT,
	MIN_DAYS_BTW_DISCOUNTS_CNT,
	DISCOUNT_DAY_OF_WEEK,
	NEXT_DAY(CURRENT_DATE,DISCOUNT_DAY_OF_WEEK) AS NEXT_DISCOUNT_DATE,   
	MAX_DISCOUNT_FOR_MAX_PRICE_PCT,
	MAX_PRICE_FOR_MAX_DISCOUNT AS PRICE_THRESHOLD_FOR_MAX_DISCOUNT ,
	DISCOUNT_TYPE_FG,
	PROMO_LIFECYCLE_WEEKS_CNT AS PROMOTION_LIFECYCLE,
	PROMO_LIFECYCLE_WEEKS_CNT,    
	VALIDITY_DAYS_CNT,
	MAX_DAYS_BTW_DISCOUNTS_CNT,
	DWH_CREATED_TMSP,
    EXPERIMENT_COHORTS_CNT,
	EXPERIMENTS_FOR_MANUAL_EVALUATION_CNT,
    SUCCESS_WRITE_OFF_THRESHOLD,
    SUCCESS_COHORTS_THRESHOLD,
    EXPORT_DAY_OF_WEEK, -- SAP Transfer Tag_2 
    CASE WHEN DAYOFWEEK(CURRENT_DATE) = 5 -- Wenn heute Freitag ist 
		THEN CURRENT_DATE
		ELSE NEXT_DAY(CURRENT_DATE,EXPORT_DAY_OF_WEEK)
	END AS NEXT_EXPORT_DATE,
    SECOND_DISCOUNT_PCT,
    SECOND_DISCOUNT_VALIDITY_WKS_CNT
FROM
    DBP_VIEW.V_NFMD_PARAMETER_2;