CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_ART_PER_HIST_2(
	MANDANT_ID,
	ART_ID,
	DAT,
	MUTTER_WB_ID,
	POSTEN_ID,
	IPN_ID,
	MWST_ID,
	OUG_ID
) AS
 SELECT
  ARP.MANDANT_ID
 ,ARP.ART_ID
 ,TG.DAT
 ,ARP.MUTTER_WB_ID
 ,ARP.POSTEN_ID
 ,ARP.IPN_ID
 ,ARP.MWST_ID
 ,ARP.OUG_ID	
	
 FROM DBP_VIEW.V_ART_PER_2 ARP
 INNER JOIN DBP_VIEW.V_TAG_2 TG
	ON  TG.DAT >= ARP.DAT_VON
	AND TG.DAT <= ARP.DAT_BIS
 WHERE
     TG.AKT_GJ BETWEEN -3 AND 0
 AND TG.DAT <= CURRENT_DATE
;