CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_ERL_KZ_SPR_ZU_2(
  ERL_KZ
 ,ERL_KZ_BEZ_DE
 ,ERL_KZ_BEZ
 ,ERL_KZ_BEZ_CZ
 ,ERL_KZ_BEZ_SK
 ,ERL_KZ_BEZ_HR
 ,ERL_KZ_BEZ_PL
 ,ERL_KZ_BEZ_RO
 ,ERL_KZ_BEZ_BG
)
AS
SELECT
 ERL_KZ
 ,MAX(CASE WHEN spr_id =  22 THEN ERL_KZ_BEZ ELSE TRIM(ERL_KZ) END) 		AS ERL_KZ_BEZ_de
 ,ERL_KZ_BEZ_de		                                                        AS ERL_KZ_BEZ       
 ,COALESCE(MAX(CASE WHEN spr_id = 124 THEN ERL_KZ_BEZ END), ERL_KZ_BEZ_de) 	AS ERL_KZ_BEZ_cz    
 ,COALESCE(MAX(CASE WHEN spr_id = 108 THEN ERL_KZ_BEZ END), ERL_KZ_BEZ_de) 	AS ERL_KZ_BEZ_sk    
 ,COALESCE(MAX(CASE WHEN spr_id =  65 THEN ERL_KZ_BEZ END), ERL_KZ_BEZ_de) 	AS ERL_KZ_BEZ_hr    
 ,COALESCE(MAX(CASE WHEN spr_id =  90 THEN ERL_KZ_BEZ END), ERL_KZ_BEZ_de) 	AS ERL_KZ_BEZ_pl    
 ,COALESCE(MAX(CASE WHEN spr_id =  95 THEN ERL_KZ_BEZ END), ERL_KZ_BEZ_de) 	AS ERL_KZ_BEZ_ro    
 ,COALESCE(MAX(CASE WHEN spr_id =  18 THEN ERL_KZ_BEZ END), ERL_KZ_BEZ_de) 	AS ERL_KZ_BEZ_bg   
FROM DBP_VIEW.V_ERL_KZ_SPR_ZU_2
GROUP BY
 ERL_KZ
;