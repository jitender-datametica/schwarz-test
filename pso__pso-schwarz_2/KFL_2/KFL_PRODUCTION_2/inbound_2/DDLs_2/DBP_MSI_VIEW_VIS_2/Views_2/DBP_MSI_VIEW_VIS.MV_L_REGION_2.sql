CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_L_REGION_2(
	MANDANT_ID,
	REGION_ID,
	VS_ID_ALT,
	REGION_KBEZ,
	REGION_BEZ
) AS
--2025-06- 24 | dknop | initial
--2025-07-03 | dknop | add -1
SELECT 
MANDANT_ID, WUP_CLUSTER_ID AS REGION_ID, WUP_CLUSTER_ID - 100 AS VS_ID_ALT, WUP_CLUSTER_BEZ AS REGION_KBEZ, WUP_CLUSTER_DESCR AS REGION_BEZ
FROM DBP_VIEW.V_TS_SCM_L_WUP_CLUSTER_2 LWC
WHERE WUP_CLUSTER_ID   IN (101,102,103,106,107,108)
UNION
SELECT
MANDANT_ID,
-1 AS REGION_ID,
-1 AS VS_ID_ALT,
'-/-' REGION_KBEZ,
'Keine Zuordnung' REGION_BEZ
FROM DBP_VIEW.V_MANDANT_2;