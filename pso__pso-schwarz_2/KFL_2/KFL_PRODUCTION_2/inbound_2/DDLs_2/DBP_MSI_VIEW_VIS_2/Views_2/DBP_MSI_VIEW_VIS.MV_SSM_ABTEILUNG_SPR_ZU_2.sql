CREATE OR REPLACE VIEW DBP_MSI_VIEW_VIS.MV_SSM_ABTEILUNG_SPR_ZU_2
AS
-- 09.04.2020 SNIK1809 AP0052955-SPEC0067085
SELECT
V01.WUP_ABT_ID,
MAX(CASE WHEN SPR_ID =  22 THEN WUP_ABT_BEZ END) AS WUP_ABT_BEZ                 -- STANDARD == DE
,
MAX(CASE WHEN SPR_ID =  22 THEN WUP_ABT_BEZ END) AS WUP_ABT_BEZ_DE                         -- DE
,
COALESCE(MAX(CASE WHEN SPR_ID = 124 THEN WUP_ABT_BEZ END), WUP_ABT_BEZ_DE) AS WUP_ABT_BEZ_CZ    -- CZ
,
COALESCE(MAX(CASE WHEN SPR_ID = 108 THEN WUP_ABT_BEZ END), WUP_ABT_BEZ_DE) AS WUP_ABT_BEZ_SK    -- SK
,
COALESCE(MAX(CASE WHEN SPR_ID =  65 THEN WUP_ABT_BEZ END), WUP_ABT_BEZ_DE) AS WUP_ABT_BEZ_HR    -- HR
,
COALESCE(MAX(CASE WHEN SPR_ID =  90 THEN WUP_ABT_BEZ END), WUP_ABT_BEZ_DE) AS WUP_ABT_BEZ_PL    -- PL
,
COALESCE(MAX(CASE WHEN SPR_ID =  95 THEN WUP_ABT_BEZ END), WUP_ABT_BEZ_DE) AS WUP_ABT_BEZ_RO    -- RO
,
COALESCE(MAX(CASE WHEN SPR_ID =  18 THEN WUP_ABT_BEZ END), WUP_ABT_BEZ_DE) AS WUP_ABT_BEZ_BG    -- BG

FROM DBP_VIEW.V_SSM_ABTEILUNG_SPR_ZU_2  V01

GROUP BY  V01.WUP_ABT_ID;

