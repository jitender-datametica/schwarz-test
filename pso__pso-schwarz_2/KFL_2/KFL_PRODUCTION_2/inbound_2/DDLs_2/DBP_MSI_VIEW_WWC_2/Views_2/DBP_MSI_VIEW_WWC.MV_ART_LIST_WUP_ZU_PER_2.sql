CREATE OR REPLACE VIEW DBP_MSI_VIEW_WWC.MV_ART_LIST_WUP_ZU_PER_2
(
art_id
,mandant_id
, wup_id
, nb_id
, dat_erstlistung
, dat_von
, dat_bis
,listungs_kz
,list_quelle_id
)
AS
   SELECT V01.ART_ID ,
       V01.MANDANT_ID ,
       V02.WUP_ID ,
       V02.NB_ID ,
       COALESCE(MIN(V03.DAT_VON) OVER (PARTITION BY V01.ART_ID, V01.MANDANT_ID, V02.WUP_ID
                                       ORDER BY 1 ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING), CAST(NULL AS DATE)) ,
       COALESCE(V03.DAT_VON, CAST(NULL AS DATE)) ,
       COALESCE(V03.DAT_BIS, CAST(NULL AS DATE)) ,
       CASE
           WHEN current_date BETWEEN V03.DAT_VON AND V03.DAT_BIS THEN 1
           WHEN V03.DAT_BIS > current_date THEN 2
           WHEN V03.DAT_BIS < current_date THEN 3
           ELSE 4
       END LISTUNGS_KZ ,
       COALESCE(V03.LIST_QUELLE_ID, '') AS LIST_QUELLE_ID
FROM DBP_VIEW.V_ART_2 V01
INNER JOIN DBP_VIEW.V_WUP_2 V02 ON V01.MANDANT_ID= V02.MANDANT_ID
LEFT  JOIN DBP_VIEW.V_ART_LIST_WUP_ZU_PER_2 V03 ON V01.ART_ID=V03.ART_ID
AND V02.WUP_ID=V03.WUP_ID
AND V01.MANDANT_ID=V03.MANDANT_ID
WHERE V01.MANDANT_ID <> 1;