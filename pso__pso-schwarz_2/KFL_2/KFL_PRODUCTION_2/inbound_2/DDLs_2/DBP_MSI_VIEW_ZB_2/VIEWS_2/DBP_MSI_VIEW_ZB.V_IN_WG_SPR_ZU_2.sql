	MANDANT_ID,
	IN_WG_ID,
	IN_WG_BEZ,
	IN_WG_BEZ_DE,
	IN_WG_BEZ_CZ,
	IN_WG_BEZ_SK,
	IN_WG_BEZ_HR,
	IN_WG_BEZ_PL,
	IN_WG_BEZ_RO,
	IN_WG_BEZ_BG
