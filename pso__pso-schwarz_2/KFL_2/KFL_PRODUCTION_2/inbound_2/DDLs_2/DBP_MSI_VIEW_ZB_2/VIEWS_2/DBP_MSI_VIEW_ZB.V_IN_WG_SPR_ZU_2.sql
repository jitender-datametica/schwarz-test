,COALESCE(MAX(CASE WHEN spr_id =  95  THEN IN_WG_BEZ END), IN_WG_BEZ_DE ) AS IN_WG_BEZ_RO   
,COALESCE(MAX(CASE WHEN spr_id =  18  THEN IN_WG_BEZ END), IN_WG_BEZ_DE ) AS IN_WG_BEZ_BG    
FROM 
DBP_DATA.IN_WG_SPR_ZU_2
GROUP BY 1,2
;
