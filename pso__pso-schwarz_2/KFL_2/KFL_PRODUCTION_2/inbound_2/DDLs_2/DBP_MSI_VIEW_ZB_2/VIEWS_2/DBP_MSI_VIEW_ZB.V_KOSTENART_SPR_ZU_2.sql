create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_ZB.V_KOSTENART_SPR_ZU_2(
	MANDANT_ID,
	KOSTENART_ID,
	KRK_ID,
	KOSTENART_BEZ,
	KOSTENART_BEZ_DE,
	KOSTENART_BEZ_CZ,
	KOSTENART_BEZ_SK,
	KOSTENART_BEZ_HR,
	KOSTENART_BEZ_PL,
	KOSTENART_BEZ_RO,
	KOSTENART_BEZ_BG
) as 
SELECT 
MANDANT_ID
,RIGHT(KOSTENART_ID,6) AS KOSTENART_ID
,KRK_ID
,COALESCE(MAX(CASE WHEN spr_id =  22  THEN KOSTENART_BEZ END),'N/A') AS KOSTENART_BEZ                       
,COALESCE(MAX(CASE WHEN spr_id =  22  THEN KOSTENART_BEZ END),'N/A') AS KOSTENART_BEZ_DE                
,COALESCE(MAX(CASE WHEN spr_id = 124 THEN KOSTENART_BEZ END), KOSTENART_BEZ_DE ) AS KOSTENART_BEZ_CZ    
,COALESCE(MAX(CASE WHEN spr_id = 108 THEN KOSTENART_BEZ END), KOSTENART_BEZ_DE ) AS KOSTENART_BEZ_SK   
,COALESCE(MAX(CASE WHEN spr_id =  65  THEN KOSTENART_BEZ END), KOSTENART_BEZ_DE ) AS KOSTENART_BEZ_HR     
,COALESCE(MAX(CASE WHEN spr_id =  90  THEN KOSTENART_BEZ END), KOSTENART_BEZ_DE ) AS KOSTENART_BEZ_PL     
,COALESCE(MAX(CASE WHEN spr_id =  95  THEN KOSTENART_BEZ END), KOSTENART_BEZ_DE ) AS KOSTENART_BEZ_RO   
,COALESCE(MAX(CASE WHEN spr_id =  18  THEN KOSTENART_BEZ END), KOSTENART_BEZ_DE ) AS KOSTENART_BEZ_BG    
FROM 
DBP_DATA.KOSTENART_SPR_ZU_2
GROUP BY 1,2,3
 ;
