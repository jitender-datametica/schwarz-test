create or replace view KFL_PRODUCTION_CLONE_GCP_MIGRATION_20260608_0800.DBP_MSI_VIEW_ZB.V_WG_SPR_ZU_2(
	MANDANT_ID,
	WG_ID,
	WARENGRUPPE_BEZ,
	WARENGRUPPE_BEZ_DE,
	WARENGRUPPE_BEZ_CZ,
	WARENGRUPPE_BEZ_SK,
	WARENGRUPPE_BEZ_HR,
	WARENGRUPPE_BEZ_PL,
	WARENGRUPPE_BEZ_RO,
	WARENGRUPPE_BEZ_BG
) as 
SELECT 
MANDANT_ID
,WG_ID
,COALESCE(MAX(CASE WHEN spr_id =  22  THEN WG_BEZ END),'N/A') AS WARENGRUPPE_BEZ                       
,COALESCE(MAX(CASE WHEN spr_id =  22  THEN WG_BEZ END),'N/A') AS WARENGRUPPE_BEZ_DE                
,COALESCE(MAX(CASE WHEN spr_id = 124 THEN WG_BEZ END), WARENGRUPPE_BEZ_DE ) AS WARENGRUPPE_BEZ_CZ    
,COALESCE(MAX(CASE WHEN spr_id = 108 THEN WG_BEZ END), WARENGRUPPE_BEZ_DE ) AS WARENGRUPPE_BEZ_SK   
,COALESCE(MAX(CASE WHEN spr_id =  65  THEN WG_BEZ END), WARENGRUPPE_BEZ_DE ) AS WARENGRUPPE_BEZ_HR     
,COALESCE(MAX(CASE WHEN spr_id =  90  THEN WG_BEZ END), WARENGRUPPE_BEZ_DE ) AS WARENGRUPPE_BEZ_PL     
,COALESCE(MAX(CASE WHEN spr_id =  95  THEN WG_BEZ END), WARENGRUPPE_BEZ_DE ) AS WARENGRUPPE_BEZ_RO   
,COALESCE(MAX(CASE WHEN spr_id =  18  THEN WG_BEZ END), WARENGRUPPE_BEZ_DE ) AS WARENGRUPPE_BEZ_BG    
FROM 
DBP_DATA.WG_SPR_ZU_2
GROUP BY 1,2
;
