CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW3.MV_TRANSPORTAUFTRAG_2(
	DAT_ERSTELLUNG,
	ZEIT_ERSTELLUNG,
	ERSTELLUNG_DT,
	DAT_QUITTIERUNG,
	DAT_LIEF_SOLL,
	DAT_BEREITSTELLUNG,
	DATZEIT_BEREITSTELLUNG,
	DATZEIT_START_TA,
	DATZEIT_END_TA,
	LAGERNUMMER_ID,
	MANDANT_ID,
	TRANSPORT_BELEG_ID,
	TRANSPORTART_ID,
	LVS_BEWART_ID,
	LIEF_BELEG_ID,
	TA_PRIO,
	DAT_PRIO_UPD,
	ZEIT_PRIO_UPD,
	NB_ID,
	WUP_ID,
	KJ_LIEF_BELEG,
	WERBEWARE_ID,
	LIEF_PAL_TYP_ID,
	REFERENZNUMMER,
	WG_VERKETT_ID
) AS

SELECT
    DAT_ERSTELLUNG,
    ZEIT_ERSTELLUNG,
    TIMESTAMP_FROM_PARTS(DAT_ERSTELLUNG,COALESCE(ZEIT_ERSTELLUNG,'00:00:00')) AS ERSTELLUNG_DT,
    DAT_QUITTIERUNG,
    DAT_LIEF_SOLL,
    DAT_BEREITSTELLUNG,
    DATZEIT_BEREITSTELLUNG,
    DATZEIT_START_TA,
    DATZEIT_END_TA,
    LAGERNUMMER_ID,
    MANDANT_ID,
    TRANSPORT_BELEG_ID,
    TRANSPORTART_ID,
    LVS_BEWART_ID,
    LIEF_BELEG_ID,
    TA_PRIO,
    DAT_PRIO_UPD,
    ZEIT_PRIO_UPD,
    NB_ID,
    WUP_ID,
    KJ_LIEF_BELEG,
    WERBEWARE_ID,
    LIEF_PAL_TYP_ID,
    REFERENZNUMMER,
    WG_VERKETT_ID
	
FROM
    DBP_VIEW.V_TRANSPORTAUFTRAG_2
     WHERE EXTRACT(YEAR FROM DAT_ERSTELLUNG) >= YEAR(CURRENT_TIMESTAMP) - 2;