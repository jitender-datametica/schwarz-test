CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW_VIS.MV_VIS_MONAT_FILIALWETTBEWERB_BACKSHOP_2(
	MANDANT_ID,
	NB_ID,
	VS_ID,
	WUP_ID,
	WRG_ID,
	GJ,
	KJMO,
	BSM_OFFEN,
	BSM_UMS_NETTO_IST,
	BSM_UMS_NETTO_KVJ,
	BSM_UMS_NETTO,
	BSM_UMS_NETTO_RANK,
	BSM_UMS_NETTO_DENSE,
	BSM_UMS_NETTO_FIL_IST,
	BSM_UMS_NETTO_FIL_KVJ,
	BSM_UMSATZANTEIL_NETTO_IST,
	BSM_UMSATZANTEIL_NETTO_KVJ,
	BSM_UMSATZANTEIL_NETTO,
	BSM_UMSATZANTEIL_NETTO_RANK,
	BSM_UMSATZANTEIL_NETTO_DENSE,
	BSM_ABS_OP_IST,
	BSM_ABS_OWG_PLAN,
	BSM_UMS_OWG_PLAN,
	BSM_ABSCHRIFT_OP_IST,
	BSM_ABSCHRIFT_OP_PLAN,
	BSM_ABSCHRIFT_OP,
	BSM_ABSCHRIFT_OP_RANK,
	BSM_ABSCHRIFT_OP_DENSE,
	BSM_ANZAHL_KUNDEN_IST,
	BSM_ANZAHL_KUNDEN_KVJ,
	BSM_ANZAHL_KUNDEN,
	BSM_ANZAHL_KUNDEN_RANK,
	BSM_ANZAHL_KUNDEN_DENSE,
	BSM_ANZAHL_KUNDEN_FIL_IST,
	BSM_ANZAHL_KUNDEN_FIL_KVJ,
	BSM_KUNDENANTEIL_IST,
	BSM_KUNDENANTEIL_KVJ,
	BSM_KUNDENANTEIL,
	BSM_KUNDENANTEIL_RANK,
	BSM_KUNDENANTEIL_DENSE,
	BSM_KMR_KC_BS_ERGEBNIS_NOK,
	BSM_KMR_KC_BS_ERGEBNIS_ANZ,
	BSM_KMR_KC_BS_PRUEFUNG_ANZ,
	BSM_KMR_KC_BS_NOK,
	BSM_KMR_KC_BS_NOK_RANK,
	BSM_KMR_KC_BS_NOK_DENSE,
	BSM_INVENTUR_WERT_NETTO,
	BSM_INVENTUR_UMS_NETTO,
	BSM_INVENTUR,
	BSM_INVENTUR_RANK,
	BSM_INVENTUR_DENSE,
	BSM_MENGE_IST,
	BSM_MENGE_KVJ,
	BSM_MENGE,
	BSM_MENGE_RANK,
	BSM_MENGE_DENSE,
	BSM_UEQ_BEST_VOR,
	BSM_UEQ_BEST_MAN,
	BSM_UEQ_BEST_KOR,
	BSM_UEQ,
	BSM_UEQ_RANK,
	BSM_UEQ_DENSE
) AS 










WITH 

 WUP_2 AS ( 
	SELECT WUP.MANDANT_ID
		, WUP.NB_ID
		, WUP.VS_ID
		, WUP.AKTUELL_WUP_ID
		, WUP.WUP_ID
		, COALESCE(WUP.DAT_EROEFFNUNG_ALT, WUP.DAT_EROEFFNUNG) AS NEO_DAT  
		, IFF(WUP_AENDERUNG_GRUND_ID = 3, '9999-12-31', NULL)  AS DAT_UMGL 
		, COALESCE(DAT_UMGL, WUP.DAT_BIS)                      AS STL_DAT  
		, EXTRACT(YEAR FROM NEO_DAT) - IFF(EXTRACT(MONTH FROM NEO_DAT) < 3, 1, 0) AS NEO_GJ 
		, EXTRACT(YEAR FROM STL_DAT) - IFF(EXTRACT(MONTH FROM STL_DAT) < 3, 1, 0) AS STL_GJ 
		
		, CASE 
			WHEN WUP.MANDANT_ID = 1 AND WUP.WUP_ID IN (1263, 1273, 3166, 6623, 8120, 8563, 8940, 5876) THEN 1 
			WHEN WUP.MANDANT_ID = 3 AND WUP.WUP_ID IN (1010)                                           THEN 1 
			WHEN WUP.MANDANT_ID = 7 AND WUP.WUP_ID IN (1110, 1410, 6210, 6310, 6410)                   THEN 1 
			
			
			WHEN WUP.MANDANT_ID = 1 AND WUP.WUP_ID IN (2380)                                           THEN 1 
			
			WHEN WUP.MANDANT_ID = 2 AND WUP.WUP_ID IN (1700, 6800)                                     THEN 2 
			ELSE 0 END AS AUS_FG
	FROM DBP_DATA.WUP_2 WUP_2
	WHERE WUP.NB_ID = 0 AND WUP.DAT_EROEFFNUNG < '2090-12-31' 
	)


, ZEIT_2 AS(
	SELECT ZEIT.GJ 
		, ZEIT.AKT_GJ 
		, ZEIT.AKT_GJ + IFF(EXTRACT(MONTH FROM CURRENT_DATE - 1) = 3, 1, 0) AS AKT_GJ_MO 
		, ZEIT.KJMO 
		, ZEIT.KJMO_VJ 
		, ZEIT.AKT_MO 
		, ZEIT.MIN_DAT 
		, ZEIT.MAX_DAT 
	FROM DBP_DATA.MONAT_2 ZEIT_2
	WHERE AKT_GJ_MO = 0 AND ZEIT.AKT_MO < 0 
	)



SELECT VIS.MANDANT_ID
	, VIS.NB_ID
	, VIS.VS_ID
	, VIS.WUP_ID
	, VIS.WRG_ID
	, VIS.GJ
	, VIS.KJMO
	, VIS.OFFEN_IST AS BSM_OFFEN
	
	, VISHWG.UMS_NETTO_IST AS BSM_UMS_NETTO_IST
	, VISHWG.UMS_NETTO_KVJ AS BSM_UMS_NETTO_KVJ
	, BSM_UMS_NETTO_IST / NULLIFZERO(BSM_UMS_NETTO_KVJ) AS BSM_UMS_NETTO
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_UMS_NETTO DESC NULLS LAST) AS BSM_UMS_NETTO_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_UMS_NETTO DESC NULLS LAST) AS BSM_UMS_NETTO_DENSE
	
	, VIS.UMS_NETTO_FIL_IST AS BSM_UMS_NETTO_FIL_IST
	, VIS.UMS_NETTO_FIL_KVJ AS BSM_UMS_NETTO_FIL_KVJ
	, BSM_UMS_NETTO_IST / NULLIFZERO(BSM_UMS_NETTO_FIL_IST) AS BSM_UMSATZANTEIL_NETTO_IST
	, BSM_UMS_NETTO_KVJ / NULLIFZERO(BSM_UMS_NETTO_FIL_KVJ) AS BSM_UMSATZANTEIL_NETTO_KVJ
	, BSM_UMSATZANTEIL_NETTO_IST - NULLIFZERO(BSM_UMSATZANTEIL_NETTO_KVJ) AS BSM_UMSATZANTEIL_NETTO
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_UMSATZANTEIL_NETTO DESC NULLS LAST) AS BSM_UMSATZANTEIL_NETTO_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_UMSATZANTEIL_NETTO DESC NULLS LAST) AS BSM_UMSATZANTEIL_NETTO_DENSE
	
	, VISABS.ABS_OP_IST    AS BSM_ABS_OP_IST
	, PLANOWG.ABS_OWG_PLAN AS BSM_ABS_OWG_PLAN
	, PLANOWG.UMS_OWG_PLAN AS BSM_UMS_OWG_PLAN
	, BSM_ABS_OP_IST   / NULLIFZERO(BSM_UMS_NETTO_IST) AS BSM_ABSCHRIFT_OP_IST
	, BSM_ABS_OWG_PLAN / NULLIFZERO(BSM_UMS_OWG_PLAN)  AS BSM_ABSCHRIFT_OP_PLAN
	, BSM_ABSCHRIFT_OP_IST - NULLIFZERO(BSM_ABSCHRIFT_OP_PLAN) AS BSM_ABSCHRIFT_OP
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_ABSCHRIFT_OP DESC NULLS LAST) AS BSM_ABSCHRIFT_OP_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_ABSCHRIFT_OP DESC NULLS LAST) AS BSM_ABSCHRIFT_OP_DENSE
	
	, KUNDE_HWG.ANZAHL_KUNDEN_IST AS BSM_ANZAHL_KUNDEN_IST
	, KUNDE_HWG.ANZAHL_KUNDEN_KVJ AS BSM_ANZAHL_KUNDEN_KVJ
	, BSM_ANZAHL_KUNDEN_IST / NULLIFZERO(BSM_ANZAHL_KUNDEN_KVJ) AS BSM_ANZAHL_KUNDEN
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_ANZAHL_KUNDEN DESC NULLS LAST) AS BSM_ANZAHL_KUNDEN_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_ANZAHL_KUNDEN DESC NULLS LAST) AS BSM_ANZAHL_KUNDEN_DENSE
	
	, VIS.ANZ_KUNDEN_FIL_IST AS BSM_ANZAHL_KUNDEN_FIL_IST
	, VIS.ANZ_KUNDEN_FIL_KVJ  AS BSM_ANZAHL_KUNDEN_FIL_KVJ
	, BSM_ANZAHL_KUNDEN_IST / NULLIFZERO(BSM_ANZAHL_KUNDEN_FIL_IST) AS BSM_KUNDENANTEIL_IST
	, BSM_ANZAHL_KUNDEN_KVJ / NULLIFZERO(BSM_ANZAHL_KUNDEN_FIL_KVJ) AS BSM_KUNDENANTEIL_KVJ
	, BSM_KUNDENANTEIL_IST - NULLIFZERO(BSM_KUNDENANTEIL_KVJ)       AS BSM_KUNDENANTEIL
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_KUNDENANTEIL DESC NULLS LAST) AS BSM_KUNDENANTIEL_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_KUNDENANTEIL DESC NULLS LAST) AS BSM_KUNDENANTEIL_DENSE
	
	, KMR.KMR_ERGEBNIS_NOK AS BSM_KMR_KC_BS_ERGEBNIS_NOK
	, KMR.KMR_ERGEBNIS_ANZ AS BSM_KMR_KC_BS_ERGEBNIS_ANZ
	, KMR.KMR_PRUEFUNG_ANZ AS BSM_KMR_KC_BS_PRUEFUNG_ANZ
	, BSM_KMR_KC_BS_ERGEBNIS_NOK / NULLIFZERO(BSM_KMR_KC_BS_ERGEBNIS_ANZ) AS BSM_KMR_KC_BS_NOK
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_KMR_KC_BS_NOK DESC NULLS LAST) AS BSM_KMR_KC_BS_NOK_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_KMR_KC_BS_NOK DESC NULLS LAST) AS BSM_KMR_KC_BS_NOK_DENSE
	
	, INV.INVENTUR_WERT_NETTO AS BSM_INVENTUR_WERT_NETTO
	, INV.INVENTUR_UMS_NETTO  AS BSM_INVENTUR_UMS_NETTO
	, BSM_INVENTUR_WERT_NETTO / NULLIFZERO(BSM_INVENTUR_UMS_NETTO) AS BSM_INVENTUR
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_INVENTUR DESC NULLS LAST) AS BSM_INVENTUR_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_INVENTUR DESC NULLS LAST) AS BSM_INVENTUR_DENSE
	
	, VISHWG.MENGE_IST AS BSM_MENGE_IST
	, VISHWG.MENGE_KVJ AS BSM_MENGE_KVJ
	, BSM_MENGE_IST / NULLIFZERO(BSM_MENGE_KVJ) AS BSM_MENGE
	, RANK ()       OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_MENGE DESC NULLS LAST) AS BSM_MENGE_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_MENGE DESC NULLS LAST) AS BSM_MENGE_DENSE
	
	, UEQ.BEST_VOR AS BSM_UEQ_BEST_VOR
	, UEQ.BEST_MAN AS BSM_UEQ_BEST_MAN
	, UEQ.BEST_KOR AS BSM_UEQ_BEST_KOR
	, (BSM_UEQ_BEST_VOR - BSM_UEQ_BEST_KOR) / (BSM_UEQ_BEST_VOR + BSM_UEQ_BEST_MAN) AS BSM_UEQ
	, RANK       () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_UEQ DESC NULLS LAST) AS BSM_UEQ_RANK
	, DENSE_RANK () OVER (PARTITION BY VIS.MANDANT_ID, VIS.VS_ID, VIS.WRG_ID, VIS.KJMO ORDER BY BSM_UEQ DESC NULLS LAST) AS BSM_UEQ_DENSE


FROM ( 
	SELECT VIS0.MANDANT_ID, VIS0.NB_ID, WUP.VS_ID, VIS0.WRG_ID
		, WUP.AKTUELL_WUP_ID AS WUP_ID
		, VIS0.GJ, VIS0.KJMO
		, SUM(VIS0.ANZ_OFFEN)     AS OFFEN_IST
		, SUM(VIS0.UMS_NETTO)     AS UMS_NETTO_FIL_IST
		, SUM(VIS0.UMS_NETTO_KVJ) AS UMS_NETTO_FIL_KVJ
		, SUM(VIS0.ANZ_KUNDE)     AS ANZ_KUNDEN_FIL_IST
		, SUM(VIS0.ANZ_KUNDE_KVJ) AS ANZ_KUNDEN_FIL_KVJ
	FROM DBP_MSI_DATA.VIS_MONAT_UMS_KUNDE_PERS_WUP_2 VIS0
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = VIS0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
	GROUP BY ALL
) VIS 


LEFT OUTER JOIN ( 
	SELECT VIS0.MANDANT_ID, WUP.AKTUELL_WUP_ID AS WUP_ID, VIS0.WRG_ID, VIS0.KJMO
		, SUM(VIS0.UMS_NETTO)     AS UMS_NETTO_IST
		, SUM(VIS0.UMS_NETTO_KVJ) AS UMS_NETTO_KVJ
		, SUM(VIS0.MENGE)     AS MENGE_IST
		, SUM(VIS0.MENGE_KVJ) AS MENGE_KVJ
	FROM DBP_MSI_VIEW_VIS.MV_VIS_MONAT_FAKT_WG_2 VIS0
	JOIN DBP_MSI_VIEW_VIS.MV_WG_INT_2	WG
		ON VIS0.WG_ID = WG.WG_ID
	JOIN DBP_MSI_VIEW_VIS.MV_OWG_INT_2 OWG
		ON WG.OWG_ID = OWG.OWG_ID
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = VIS0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND OWG.HWG_ID = 62 
	GROUP BY ALL
) VISHWG
ON VISHWG.WUP_ID = VIS.WUP_ID AND VISHWG.MANDANT_ID = VIS.MANDANT_ID
AND VISHWG.WRG_ID = VIS.WRG_ID AND VISHWG.KJMO = VIS.KJMO


LEFT OUTER JOIN ( 
	SELECT VIS0.MANDANT_ID, VIS0.WRG_ID
		, WUP.AKTUELL_WUP_ID AS WUP_ID
		, VIS0.KJMO
		, SUM(CASE 
			WHEN VIS0.MANDANT_ID IN (6) AND VIS0.ABSCHRIFTART_ID=2 THEN 1 
			WHEN VIS0.MANDANT_ID IN (3) AND VIS0.ABSCHRIFTART_ID=11 THEN 1 
			WHEN VIS0.MANDANT_ID IN (2,4,5,7,8) AND VIS0.ABSCHRIFTART_ID=7 THEN 1 
			WHEN VIS0.MANDANT_ID IN (2,5) AND VIS0.ABSCHRIFTART_ID=10 THEN 1 
			WHEN VIS0.MANDANT_ID NOT IN (1) AND VIS0.ABSCHRIFTART_ID=20 THEN 1 
			ELSE -1 END * VIS0.ABSCHRIFT_NETTO) AS ABS_OP_IST
		, SUM(CASE 
			WHEN VIS0.MANDANT_ID IN (6) AND VIS0.ABSCHRIFTART_ID=2 THEN 1 
			WHEN VIS0.MANDANT_ID IN (3) AND VIS0.ABSCHRIFTART_ID=11 THEN 1 
			WHEN VIS0.MANDANT_ID IN (2,4,5,7,8) AND VIS0.ABSCHRIFTART_ID=7 THEN 1 
			WHEN VIS0.MANDANT_ID IN (2,5) AND VIS0.ABSCHRIFTART_ID=10 THEN 1 
			WHEN VIS0.MANDANT_ID NOT IN (1) AND VIS0.ABSCHRIFTART_ID=20 THEN 1 
			ELSE -1 END * VIS0.ABSCHRIFT_NETTO_KVJ) AS ABS_OP_VJ
	FROM DBP_MSI_VIEW_VIS.MV_VIS_TAG_ABSCHRIFTEN_WG_2	VIS0
	JOIN DBP_MSI_VIEW_VIS.MV_ABSCHRIFTART_INT_ZU_2 ABS_ART
		ON ABS_ART.ABSCHRIFTART_ID = VIS0.ABSCHRIFTART_ID AND ABS_ART.MANDANT_ID = VIS0.MANDANT_ID 
	JOIN DBP_MSI_VIEW_VIS.MV_ABSCHRIFTART_INT_THEMA_ZU_2 ABS_THEMA
		ON ABS_THEMA.ABSCHRIFTART_INT_ID = ABS_ART.ABSCHRIFTART_INT_ID
	JOIN DBP_MSI_VIEW_VIS.MV_WG_INT_2 WG
		ON VIS0.WG_ID = WG.WG_ID
	JOIN DBP_MSI_VIEW_VIS.MV_OWG_INT_2 OWG
		ON WG.OWG_ID = OWG.OWG_ID
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = VIS0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID 
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND ABS_THEMA.ABSCHRIFTART_THEMA_INT_ID IN (1, 4)  
		AND OWG.HWG_ID = 62 
	GROUP BY ALL
) VISABS
ON VISABS.WUP_ID = VIS.WUP_ID AND VISABS.MANDANT_ID = VIS.MANDANT_ID
AND VISABS.WRG_ID = VIS.WRG_ID AND VISABS.KJMO = VIS.KJMO


LEFT OUTER JOIN ( 
	SELECT VIS0.MANDANT_ID, VIS0.NB_ID, VIS0.WRG_ID
	, WUP.AKTUELL_WUP_ID AS WUP_ID
	, VIS0.KJMO
	, SUM(VIS0.ABSCHRIFTEN_NETTO_OPERATIV_PLAN) AS ABS_OWG_PLAN
	, SUM(VIS0.UMSATZ_NETTO_PLAN) AS UMS_OWG_PLAN
	FROM DBP_MSI_VIEW_VIS.MV_WUP_PLAN_KJMO_OWG_2 VIS0
	JOIN DBP_MSI_VIEW_VIS.MV_OWG_INT_2 OWG
		ON VIS0.OWG_ID = OWG.OWG_ID
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = VIS0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID 
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND OWG.HWG_ID = 62 
	GROUP BY ALL
) PLANOWG
ON PLANOWG.WUP_ID = VIS.WUP_ID AND PLANOWG.MANDANT_ID = VIS.MANDANT_ID
AND PLANOWG.WRG_ID = VIS.WRG_ID AND PLANOWG.KJMO = VIS.KJMO


LEFT OUTER JOIN ( 
	SELECT VIS0.MANDANT_ID
	, WUP.AKTUELL_WUP_ID AS WUP_ID
	, ZEIT.KJMO
	, SUM(VIS0.ANZ_KUNDE_HWG)     AS ANZAHL_KUNDEN_IST
	, SUM(VIS0.ANZ_KUNDE_HWG_KVJ) AS ANZAHL_KUNDEN_KVJ
	FROM DBP_MSI_VIEW_VIS.MV_VIS_TAG_KUNDE_HWG_2 VIS0
	INNER JOIN DBP_MSI_VIEW_VIS.MV_TAG_2 ZEIT0
		ON ZEIT0.DAT = VIS0.DAT
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = ZEIT0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID 
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND VIS0.HWG_ID = 62 
	GROUP BY ALL
) KUNDE_HWG
ON KUNDE_HWG.MANDANT_ID = VIS.MANDANT_ID AND KUNDE_HWG.WUP_ID = VIS.WUP_ID 
AND KUNDE_HWG.KJMO = VIS.KJMO


LEFT OUTER JOIN ( 
	SELECT VIS0.MANDANT_ID, VIS0.WRG_ID
		, WUP.AKTUELL_WUP_ID AS WUP_ID
		, ZEIT.KJMO
		, SUM(VIS0.INVENTUR_WERT_NETTO) AS INVENTUR_WERT_NETTO
		, SUM(VIS0.INVENTUR_UMS_NETTO)  AS INVENTUR_UMS_NETTO
	FROM DBP_MSI_VIEW_VIS.MV_VIS_MONAT_HFM_INVENTUR_2 VIS0
	JOIN DBP_MSI_VIEW_VIS.MV_OWG_INT_2 OWG
		ON VIS0.OWG_ID = OWG.OWG_ID
	JOIN DBP_MSI_VIEW_VIS.MV_TAG_2 ZEIT0
		ON ZEIT0.DAT = VIS0.DAT_PLAN_ZAEHLUNG
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = ZEIT0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID 
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND OWG.HWG_ID = 62 
	GROUP BY ALL 
) INV
ON INV.MANDANT_ID = VIS.MANDANT_ID AND INV.WUP_ID = VIS.WUP_ID
AND INV.WRG_ID = VIS.WRG_ID AND INV.KJMO = VIS.KJMO


LEFT OUTER JOIN ( 
	SELECT VIS0.MANDANT_ID
		, WUP.AKTUELL_WUP_ID AS WUP_ID
		, ZEIT.KJMO
		, SUM(CASE WHEN VIS0.STATUS_2 NOT IN ('0B','0N')  THEN 1 ELSE 0 END) AS BEST_VOR 
		, SUM(CASE WHEN VIS0.STATUS_2 IN ('0B')           THEN 1 ELSE 0 END) AS BEST_MAN 
		, SUM(CASE WHEN VIS0.STATUS_2 IN ('V0','V-','V+') THEN 1 ELSE 0 END) AS BEST_KOR 
	FROM DBP_MSI_VIEW_VIS.MV_BSCH_BESTVOR_DET_2 VIS0
	JOIN DBP_MSI_VIEW_VIS.MV_ART_WG_ZU_2 ART_2
		ON VIS0.ART_ID = ART.ART_ID AND VIS0.MANDANT_ID = ART.MANDANT_ID
	JOIN DBP_MSI_VIEW_VIS.MV_WG_INT_2 WG
		ON ART.WG_ID = WG.WG_ID
	JOIN DBP_MSI_VIEW_VIS.MV_OWG_INT_2 OWG
		ON WG.OWG_ID = OWG.OWG_ID
	JOIN DBP_MSI_VIEW_VIS.MV_TAG_2 ZEIT0
		ON ZEIT0.DAT = VIS0.DAT_PLAN
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = ZEIT0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = VIS0.WUP_ID AND WUP.MANDANT_ID = VIS0.MANDANT_ID 
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND OWG.HWG_ID = 62 
		AND VIS0.STATUS_2 NOT IN ('0N')
	GROUP BY ALL 
) UEQ
ON UEQ.MANDANT_ID = VIS.MANDANT_ID AND UEQ.WUP_ID = VIS.WUP_ID 
AND UEQ.KJMO = VIS.KJMO


LEFT OUTER JOIN (  
	SELECT WUP.MANDANT_ID
		, WUP.AKTUELL_WUP_ID AS WUP_ID
		, ZEIT.KJMO 
		, SUM(CASE WHEN WUP.MANDANT_ID <> 1 AND KMR_FRG.ERGEBNIS_NUM =  1 THEN 1 ELSE 0 END) AS KMR_ERGEBNIS_NOK 
		, SUM(CASE WHEN WUP.MANDANT_ID <> 1 AND KMR_FRG.ERGEBNIS_NUM >= 0 THEN 1 ELSE 0 END) AS KMR_ERGEBNIS_ANZ 
		, COUNT(DISTINCT CASE WHEN WUP.MANDANT_ID <> 1 THEN KMR_KAP.PRUEFUNG_ID ELSE 0 END) AS KMR_PRUEFUNG_ANZ 
	FROM DBP_VIEW.V_KMR_FRAGE_2 KMR_FRG
	INNER JOIN DBP_VIEW.V_KMR_PRUEFPROGRAMM_KAPITEL_2 KMR_KAP
		ON KMR_KAP.KAPITEL_ID = KMR_FRG.KAPITEL_ID AND KMR_KAP.AMX_SYSTEM_ID = KMR_FRG.AMX_SYSTEM_ID
	INNER JOIN DBP_VIEW.V_KMR_PRUEFUNG_2 KMR_PRF
		ON KMR_PRF.PRUEFUNG_ID = KMR_KAP.PRUEFUNG_ID AND KMR_PRF.AMX_SYSTEM_ID = KMR_KAP.AMX_SYSTEM_ID
	INNER JOIN DBP_VIEW.V_KMR_L_ORGANISATIONSEINHEIT_2 KMR_LOE
		ON KMR_LOE.ORGA_EINHEIT_ID = KMR_PRF.GEPR_OE_ID AND KMR_LOE.AMX_SYSTEM_ID = KMR_PRF.AMX_SYSTEM_ID
	INNER JOIN DBP_DATA.TAG_2 ZEIT0
		ON ZEIT0.DAT = KMR_PRF.DAT_PRUEF_ZEITRAUM_BIS
	INNER JOIN ZEIT_2 
		ON ZEIT.KJMO = ZEIT0.KJMO 
	INNER JOIN WUP_2 
		ON WUP.WUP_ID = KMR_LOE.WUP_ID AND WUP.MANDANT_ID = KMR_LOE.MANDANT_ID 
	WHERE WUP.NEO_GJ < (ZEIT.GJ - 1)   
		AND WUP.STL_DAT > ZEIT.MAX_DAT 
		AND WUP.AUS_FG <> 1            
		AND NOT (WUP.AUS_FG = 2 AND ZEIT.KJMO BETWEEN 202409 AND 202602) 
		AND KMR_FRG.AMX_SYSTEM_ID = 1                    
		AND KMR_PRF.PRUEFUNG_KLASSE_ID IN (100003)         
		AND KMR_PRF.PRUEFUNG_STATUS_ID IN (100005, 100041) 
		AND TRY_TO_NUMBER(SUBSTR(KMR_FRG.SORT_NR, 14, 2)) IN (15) 
	GROUP BY ALL
) KMR
ON KMR.MANDANT_ID = VIS.MANDANT_ID AND KMR.WUP_ID = VIS.WUP_ID 
AND KMR.KJMO = VIS.KJMO
