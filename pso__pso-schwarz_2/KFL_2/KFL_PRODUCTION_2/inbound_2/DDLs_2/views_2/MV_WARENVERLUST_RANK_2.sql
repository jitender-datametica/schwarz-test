	MANDANT_ID COMMENT 'MANDANT_2 IM DWH',
	VS_ID COMMENT 'ID DER VERTRIEBSSCHIENE',
	WUP_ID COMMENT 'DER \"WUP_2\" BEINHALTET MÄRKTE UND LAGER. WUP_2 = WARENUMSCHLAGSPLATZ. MUTTER WUP_2 ID WIRD VERWENDET FÜR BEZIEHUNG LAGER ZU VERTEILZENTRUM.',
	ART_ID COMMENT 'ARTIKELNUMMER IM DWH. INPUT: ARTIKEL_2-ID EINSCHLIESSLICH DER GENERATIONEN-ID (9-STELLIG); OUTPUT: 7-STELLIGE L&S-ID + COUNTER = 8-STELLIGE ARTIKEL_2-ID. WWNNNNPC (WARENGRUPPE, NUMMER, PRÜFZIFFER, COUNTER) REGEL: NEUER ARTIKEL_2 -> COUNTER +1.',
	WG_HIST_ID COMMENT 'ID DER WARENGRUPPE',
	OWG_HIST_ID COMMENT 'ID DER OBERWARENGRUPPE',
	HWG_HIST_ID COMMENT 'ID DER HAUPTWARENGRUPPE',
	ABT_HIST_ID COMMENT 'ABTEILUNGS-ID, NEGATIVE WERTE: IM DWH GENERIERTE IDS; POSITIVE WERTE: AUS STAMMDATENSYSTEM ÜBERNOMMEN.',
	WRG_ID COMMENT 'KURZBEZEICHNUNG DER WÄHRUNG, Z.B. CZK, EUR',
	INVENTURART_ID COMMENT 'INVENTURARTEN AUS SAP. UNTERSCHEIDUNG, OB BSP. JAHRES-, FRISCHE- ODER SONDERINVENTUR. SIEHE INVENTURART_SPR_ZU.',
	DAT_INVENTUR_VON COMMENT 'START DES BETRACHTETEN INVENTURZEITRAUMS. DIESER ZEITRAUM UNTERLIEGT KEINER FESTEN ZEITLICHEN GRÖSSE UND KANN SICH JE LAND_2 UNTERSCHEIDEN.',
	DAT_INVENTUR_BIS COMMENT 'ENDE DES BETRACHTETEN INVENTURZEITRAUMS. DIESER ZEITRAUM UNTERLIEGT KEINER FESTEN ZEITLICHEN GRÖSSE UND KANN SICH JE LAND_2 UNTERSCHEIDEN.',
	GJ COMMENT 'GESCHÄFTSJAHR, DEM INVENTURZEITRAUM ZUGEORDNET WERDEN SOLL. 28.02.2024 KANN BEISPIELSWEISE IN DER BETRACHTUNG ZUM INVENTURZEITRAUM DES GJ 2024 STATT 2023 GEHÖREN.',
	INVENTUR_ID COMMENT 'EINDEUTIGE HOCHGEZÄHLTE NUMMER ÜBER ALLE FELDER DES EXCEL-UPLOADS',
	WV_UMSATZ_NETTO_WUP COMMENT 'UMSATZ DER BETROFFENEN INVENTUR_2-ARTIKEL_2 IM DEFINIERTEN INVENTUR_2-ZEITRAUM JE BETRIEB',
	WV_INVENTUR_NETTO_WUP COMMENT 'SALDIERTE INVENTUR_2-DIFFERENZ-WERTE JE ARTIKEL_2 UND BETRIEB IM DEFINIERTEN INVENTUR_2-ZEITRAUM',
	WV_MENGE_INVENTUR_WUP COMMENT 'SALDIERTE INVENTUR_2-DIFFERENZ-MENGEN JE ARTIKEL_2 UND BETRIEB IM DEFINIERTEN INVENTUR_2-ZEITRAUM',
	WV_UMSATZ_NETTO_AUFG_WUP COMMENT 'AUFGELAUFENER UMSATZ DER BETROFFENEN INVENTUR_2-ARTIKEL_2 IM DEFINIERTEN INVENTUR_2-ZEITRAUM JE BETRIEB',
	WV_INVENTUR_NETTO_AUFG_WUP COMMENT 'AUFGELAUFENE SALDIERTE INVENTUR_2-DIFFERENZ-WERTE JE ARTIKEL_2 UND BETRIEB IM DEFINIERTEN INVENTUR_2-ZEITRAUM',
	WV_MENGE_INVENTUR_AUFG_WUP COMMENT 'AUFGELAUFENE SALDIERTE INVENTUR_2-DIFFERENZ-MENGEN JE ARTIKEL_2 UND BETRIEB IM DEFINIERTEN INVENTUR_2-ZEITRAUM',
	ART_WUP_FG COMMENT 'FLAG FOR FIRST APPEARANCE OF AN ARTICLE FOR ONE STORE AND ONE BUSINESS YEAR',
	ART_VS_FG COMMENT 'FLAG FOR FIRST APPEARANCE OF AN ARTICLE FOR ONE REGION_2 AND ONE BUSINESS YEAR',
	ART_MDT_FG COMMENT 'FLAG FOR FIRST APPEARANCE OF AN ARTICLE FOR ONE COUNTRY_2 AND ONE BUSINESS YEAR',
	WV_INVENTUR_NETTO_QUOTE COMMENT 'ANTEIL VON INVENTURDIFFERENZ ZU UMSATZ (AUF FILIALEBENE)',
	WV_INVENTUR_NETTO_AUFG_QUOTE COMMENT 'ANTEIL VON AUFGELAUFENER INVENTURDIFFERENZ ZU AUFGELAUFENEM UMSATZ (AUF FILIALEBENE)',
	WV_INVENTUR_NETTO_VS COMMENT 'INVENTURDIFFERENZ AGGREGIERT AUF REGIONSEBENE (NUR EINMAL PRO REGION_2 UND NICHT FÜR ALLE ZEILEN BERECHNET)',
	WV_UMSATZ_NETTO_VS COMMENT 'UMSATZ AGGREGIERT AUF REGIONSEBENE (NUR EINMAL PRO REGION_2 UND NICHT FÜR ALLE ZEILEN BERECHNET)',
	WV_INVENTUR_NETTO_MDT COMMENT 'INVENTURDIFFERENZ AGGREGIERT AUF LANDESEBENE (NUR EINMAL PRO LAND_2 UND NICHT FÜR ALLE ZEILEN BERECHNET)',
	WV_UMSATZ_NETTO_MDT COMMENT 'UMSATZ AGGREGIERT AUF LANDESEBENE (NUR EINMAL PRO LAND_2 UND NICHT FÜR ALLE ZEILEN BERECHNET)',
	WV_INVENTUR_NETTO_RANK COMMENT 'RANKING NACH INVENTURDIFFERENZ',
	WV_INVENTUR_NETTO_RANK_AUFG COMMENT 'RANKING NACH AUFGELAUFENER INVENTURDIFFERENZ',
	WV_INVENTUR_NETTO_RANK_VS COMMENT 'RANKING NACH INVENTURDIFFERENZ PRO REGION_2',
	WV_INVENTUR_NETTO_RANK_MDT COMMENT 'RANKING NACH INVENTURDIFFERENZ PRO LAND_2'
) AS




WITH 

FACTS_INVENTUR_WARENVERLUST AS (
	SELECT I.MANDANT_ID
		, W.VS_ID 
		, I.WUP_ID
		, I.ART_ID
		, I.WG_HIST_ID
		, I.OWG_HIST_ID
		, I.HWG_HIST_ID
		, I.ABT_HIST_ID
		, I.WRG_ID
		, I.INVENTURART_ID
		, I.DAT_INVENTUR_VON
		, I.DAT_INVENTUR_BIS
		, I.GJ
		, I.INVENTUR_ID
		, I.WV_UMSATZ_NETTO
		
		
		, I.WV_INVENTUR_NETTO
		, I.WV_MENGE_INVENTUR
		
		, I.WV_UMSATZ_NETTO_AUFG
		
		
		, I.WV_INVENTUR_NETTO_AUFG
		, I.WV_MENGE_INVENTUR_AUFG
		
	FROM DBP_MSI_VIEW_VIS.MV_WARENVERLUST_2 I 
	LEFT OUTER JOIN DBP_MSI_VIEW_VIS.MV_WUP_2 W 
		USING (MANDANT_ID, WUP_ID)
	WHERE I.INVENTURART_ID = 3 
	
	),

FACTS_FLAGGED AS (
	SELECT MANDANT_ID
		, VS_ID
		, WUP_ID
		, ART_ID
		, WG_HIST_ID
		, OWG_HIST_ID
		, HWG_HIST_ID
		, ABT_HIST_ID
		, WRG_ID
		, INVENTURART_ID
		, DAT_INVENTUR_VON
		, DAT_INVENTUR_BIS
		, GJ
		, INVENTUR_ID
		, WV_UMSATZ_NETTO
		, WV_INVENTUR_NETTO
		, WV_MENGE_INVENTUR
		, WV_UMSATZ_NETTO_AUFG
		, WV_INVENTUR_NETTO_AUFG
		, WV_MENGE_INVENTUR_AUFG
		, ROW_NUMBER() OVER (
			PARTITION BY MANDANT_ID, VS_ID, WUP_ID, WRG_ID, ART_ID, GJ 
			ORDER BY MANDANT_ID, VS_ID, WUP_ID, WRG_ID, ART_ID, GJ, DAT_INVENTUR_BIS DESC
			) AS ART_WUP_NR
		, IFF(ART_WUP_NR = 1, ART_WUP_NR, 0) AS ART_WUP_FG 
		, ROW_NUMBER() OVER (
			PARTITION BY MANDANT_ID, VS_ID, WRG_ID, ART_ID, GJ 
			ORDER BY MANDANT_ID, VS_ID, WUP_ID, WRG_ID, ART_ID, GJ, DAT_INVENTUR_BIS DESC
			) AS ART_VS_NR
		, IFF(ART_VS_NR = 1, ART_VS_NR, 0) AS ART_VS_FG 
		, ROW_NUMBER() OVER (
			PARTITION BY MANDANT_ID, WRG_ID, ART_ID, GJ 
			ORDER BY MANDANT_ID, VS_ID, WUP_ID, WRG_ID, ART_ID, GJ, DAT_INVENTUR_BIS DESC
			) AS ART_MANDANT_NR
		, IFF(ART_MANDANT_NR = 1, ART_MANDANT_NR, 0) AS ART_MDT_FG 
	FROM FACTS_INVENTUR_WARENVERLUST 
	),

FACTS_AGGREGATED AS (
	SELECT MANDANT_ID
		, VS_ID
		, WUP_ID
		, ART_ID
		, WG_HIST_ID
		, OWG_HIST_ID
		, HWG_HIST_ID
		, ABT_HIST_ID
		, WRG_ID
		, INVENTURART_ID
		, DAT_INVENTUR_VON
		, DAT_INVENTUR_BIS
		, GJ
		, INVENTUR_ID
		, WV_UMSATZ_NETTO 
		, WV_INVENTUR_NETTO	
		, WV_MENGE_INVENTUR
		, WV_UMSATZ_NETTO_AUFG 
		, WV_INVENTUR_NETTO_AUFG 
		, WV_MENGE_INVENTUR_AUFG
		, ART_WUP_FG 
		, ART_VS_FG 
		, ART_MDT_FG 
		
		, DIV0(WV_INVENTUR_NETTO, WV_UMSATZ_NETTO) AS WV_INVENTUR_NETTO_QUOTE
		, DIV0(WV_INVENTUR_NETTO_AUFG, WV_UMSATZ_NETTO_AUFG) AS WV_INVENTUR_NETTO_AUFG_QUOTE
		 
		, IFF(ART_VS_FG = 1, 
			SUM(WV_INVENTUR_NETTO) OVER (PARTITION BY MANDANT_ID, VS_ID, WRG_ID, ART_ID, GJ), 
			NULL) AS WV_INVENTUR_NETTO_VS
		, IFF(ART_VS_FG = 1
			, SUM(WV_UMSATZ_NETTO) OVER (PARTITION BY MANDANT_ID, VS_ID, WRG_ID, ART_ID, GJ), 
			NULL) AS WV_UMSATZ_NETTO_VS
		
		
		, IFF(ART_MDT_FG = 1, 
			SUM(WV_INVENTUR_NETTO) OVER (PARTITION BY MANDANT_ID, WRG_ID, ART_ID, GJ), 
			NULL) AS WV_INVENTUR_NETTO_MDT
		, IFF(ART_MDT_FG = 1, 
			SUM(WV_UMSATZ_NETTO) OVER (PARTITION BY MANDANT_ID, WRG_ID, ART_ID, GJ), 
			NULL) AS WV_UMSATZ_NETTO_MDT
		
	FROM FACTS_FLAGGED
	),
RANKINGS AS (
	SELECT MANDANT_ID
		, VS_ID
		, WUP_ID
		, ART_ID
		, WG_HIST_ID
		, OWG_HIST_ID
		, HWG_HIST_ID
		, ABT_HIST_ID
		, WRG_ID
		, INVENTURART_ID
		, DAT_INVENTUR_VON
		, DAT_INVENTUR_BIS
		, GJ
		, INVENTUR_ID
		, WV_UMSATZ_NETTO
		, WV_INVENTUR_NETTO
		, WV_MENGE_INVENTUR
		, WV_UMSATZ_NETTO_AUFG
		, WV_INVENTUR_NETTO_AUFG
		, WV_MENGE_INVENTUR_AUFG
		, ART_WUP_FG 
		, ART_VS_FG 
		, ART_MDT_FG
		, WV_INVENTUR_NETTO_QUOTE
		, WV_INVENTUR_NETTO_AUFG_QUOTE
		, WV_INVENTUR_NETTO_VS
		, WV_UMSATZ_NETTO_VS
		, WV_INVENTUR_NETTO_MDT
		, WV_UMSATZ_NETTO_MDT
		
		
		
		, IFF(WV_INVENTUR_NETTO IS NOT NULL, 
			DENSE_RANK() OVER ( 
				PARTITION BY MANDANT_ID, VS_ID, WUP_ID, WRG_ID, GJ
				ORDER BY WV_INVENTUR_NETTO DESC NULLS LAST 
				),
			NULL) AS WV_INVENTUR_NETTO_RANK
		, IFF(WV_INVENTUR_NETTO_AUFG IS NOT NULL, 
			DENSE_RANK() OVER ( 
				PARTITION BY MANDANT_ID, VS_ID, WUP_ID, WRG_ID, GJ 
				ORDER BY WV_INVENTUR_NETTO_AUFG DESC NULLS LAST  
				),
			NULL) AS WV_INVENTUR_NETTO_RANK_AUFG
		 
		, IFF(WV_INVENTUR_NETTO_VS IS NOT NULL, 
			DENSE_RANK() OVER ( 
				PARTITION BY MANDANT_ID, VS_ID, WRG_ID, GJ 
				ORDER BY WV_INVENTUR_NETTO_VS DESC NULLS LAST 
				),
			NULL) AS WV_INVENTUR_NETTO_RANK_VS
		
		, IFF(WV_INVENTUR_NETTO_MDT IS NOT NULL, 
			DENSE_RANK() OVER ( 
				PARTITION BY MANDANT_ID, WRG_ID, GJ 
				ORDER BY WV_INVENTUR_NETTO_MDT DESC NULLS LAST 
				),
			NULL) AS WV_INVENTUR_NETTO_RANK_MDT
	FROM FACTS_AGGREGATED
	WHERE WV_UMSATZ_NETTO IS NOT NULL 
		OR (WV_UMSATZ_NETTO_AUFG IS NOT NULL 
			AND WV_UMSATZ_NETTO_AUFG <> 0) 
		OR WV_INVENTUR_NETTO IS NOT NULL 
		OR (WV_INVENTUR_NETTO_AUFG IS NOT NULL 
			AND WV_INVENTUR_NETTO_AUFG <> 0) 
		OR WV_MENGE_INVENTUR IS NOT NULL 
		OR (WV_MENGE_INVENTUR_AUFG IS NOT NULL 
			AND WV_MENGE_INVENTUR_AUFG <> 0) 
	)
SELECT MANDANT_ID
	, VS_ID
	, WUP_ID
	, ART_ID
	, WG_HIST_ID
	, OWG_HIST_ID
	, HWG_HIST_ID
	, ABT_HIST_ID
	, WRG_ID
	, INVENTURART_ID
	, DAT_INVENTUR_VON
	, DAT_INVENTUR_BIS
	, GJ
	, INVENTUR_ID
	, WV_UMSATZ_NETTO			AS WV_UMSATZ_NETTO_WUP
	, WV_INVENTUR_NETTO			AS WV_INVENTUR_NETTO_WUP
	, WV_MENGE_INVENTUR			AS WV_MENGE_INVENTUR_WUP
	, WV_UMSATZ_NETTO_AUFG		AS WV_UMSATZ_NETTO_AUFG_WUP
	, WV_INVENTUR_NETTO_AUFG	AS WV_INVENTUR_NETTO_AUFG_WUP
	, WV_MENGE_INVENTUR_AUFG	AS WV_MENGE_INVENTUR_AUFG_WUP
	, ART_WUP_FG 
	, ART_VS_FG 
	, ART_MDT_FG
	, WV_INVENTUR_NETTO_QUOTE
	, WV_INVENTUR_NETTO_AUFG_QUOTE
	, WV_INVENTUR_NETTO_VS
	, WV_UMSATZ_NETTO_VS
	, WV_INVENTUR_NETTO_MDT
	, WV_UMSATZ_NETTO_MDT
	
	
	, WV_INVENTUR_NETTO_RANK
	, WV_INVENTUR_NETTO_RANK_AUFG
	, WV_INVENTUR_NETTO_RANK_VS
	, WV_INVENTUR_NETTO_RANK_MDT
FROM RANKINGS	

;