CREATE OR REPLACE VIEW KFL_PRODUCTION.DBP_MSI_VIEW_AIS_INT.MV_WERBEREGION_2(
	MANDANT_ID,
	WREG_ID,
	WREG_BEZ
) AS
   
   SELECT
 MANDANT_ID

   







,CASE WHEN V01.WUP_CLUSTER_ID IN (102, 107) THEN 1
      WHEN V01.WUP_CLUSTER_ID IN (101, 103) THEN 2
      WHEN V01.WUP_CLUSTER_ID IN (106, 108) THEN 3
      END AS WREG_ID  
      
  







,CASE WHEN V01.WUP_CLUSTER_ID IN (102, 107) THEN 'SÜD'
      WHEN V01.WUP_CLUSTER_ID IN (101, 103) THEN 'OST'
      WHEN V01.WUP_CLUSTER_ID IN (106, 108) THEN 'WEST'
      END AS WREG_BEZ


FROM DBP_DATA.TS_SCM_WUP_CLUSTER_ZU_2 V01
WHERE V01.MANDANT_ID = 1
AND V01.NB_ID = 0

GROUP BY 1,2,3;