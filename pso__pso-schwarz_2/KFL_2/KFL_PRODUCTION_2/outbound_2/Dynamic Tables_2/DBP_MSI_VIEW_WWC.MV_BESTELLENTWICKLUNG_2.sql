CREATE OR REPLACE MATERIALIZED VIEW kfl_production_dbp_msi_view_wwc.mv_bestellentwicklung_2
OPTIONS (
  ENABLE_REFRESH=TRUE,
  REFRESH_INTERVAL_MINUTES=90
) AS
SELECT
  ekbe_mandant_id AS mandant_id,
  ekbe_wup_id AS ekbe_werks,
  ekbe_nb_id AS nb_id,
  mseg_beleg_id AS ekbe_belnr,
  mseg_beleg_pos_id AS ekbe_buzei,
  TRIM(CAST(mseg_beleg_id AS STRING FORMAT '0000000000')) || ' ' || TRIM(CAST(mseg_beleg_pos_id AS STRING FORMAT '0000')) AS ekbe_belnr_zeile,
  ref_gj AS ekbe_lfgja,
  mseg_kj AS ekbe_gjahr,
  mkpf_dat_buch AS mkpf_budat,
  mkpf_dat_beleg AS mkpf_bldat,
  ekbe_best_beleg_id AS ekbe_ebeln,
  ekbe_best_beleg_pos_id AS ekbe_ebelp,
  TRIM(CAST(ekbe_best_beleg_id AS STRING FORMAT '0000000000')) || ' ' || TRIM(CAST(ekbe_best_beleg_pos_id AS STRING FORMAT '0000')) AS ekbe_ebeln_zeile,
  ref_beleg_id AS ekbe_lfbnr,
  ref_beleg_pos_id AS ekbe_lfbpos,
  TRIM(CAST(ref_beleg_id AS STRING FORMAT '0000000000')) || ' ' || TRIM(CAST(ref_beleg_pos_id AS STRING FORMAT '0000')) AS ekbe_lfbnr_zeile,
  ekbe_soll_haben_kz AS ekbe_shkz,
  ekbe_best_entw_typ_id_we AS ekbe_bewtp,
  rbkp_belegart_id AS rbkp_blart,
  rbkp_dat_beleg AS rbkp_bldat,
  rseg_gj AS rseg_gjahr,
  rseg_beleg_id AS rseg_belnr,
  rseg_beleg_pos_id AS rseg_buzei,
  TRIM(CAST(rseg_beleg_id AS STRING FORMAT '0000000000')) || ' ' || TRIM(CAST(rseg_beleg_pos_id AS STRING FORMAT '0000')) AS rseg_belnr_zeile,
  rseg_soll_haben_kz AS rseg_shkzg,
  rseg_wert_bestand AS rseg_salk3,
  rseg_menge_bestand_bme AS rseg_lbkum,
  rseg_wert_bestand_vp AS rseg_vmsal,
  rseg_menge_bestand_bme_rbp AS rseg_vrkum,
  rseg_wert_bestand_buchung AS rseg_stock_posting,
  rseg_wert_bestand_buchung_vp AS rseg_stock_posting_pp,
  rseg_rueck_buchung_fg AS xrueb,
  ekbe_best_entw_typ_id_we AS ekbe_bewtp_we,
  mkpf_dat_buch AS ekbe_budat_we,
  mkpf_dat_erfasst AS mkpf_cpudt,
  CAST(TRIM(SUBSTR(CAST(mkpf_zeit_erfasst AS STRING), 1, 8)) AS TIME) AS mkpf_cputm,
  CAST(REPLACE(
    SUBSTR(CAST(mkpf_dat_erfasst AS STRING), 1, 11) || ' ' || COALESCE(SUBSTR(CAST(mkpf_zeit_erfasst AS STRING), 1, 8), '00:00:00'),
    ',',
    ':'
  ) AS DATETIME) AS mkpf_cpudt_cputm,
  ekbe_menge_basis * CASE WHEN ekbe_soll_haben_kz = 'H' THEN -1 ELSE 1 END AS ekbe_menge,
  ekbe_betrag * CASE WHEN ekbe_soll_haben_kz = 'H' THEN -1 ELSE 1 END AS ekbe_dmbtr_we,
  ekbe_menge_best AS ekbe_bpmng_we,
  ekbe_betrag_wrbtr * CASE WHEN ekbe_soll_haben_kz = 'H' THEN -1 ELSE 1 END AS ekbe_wrbtr_we,
  mseg_wrg_id AS ekbe_waers_we,
  CASE WHEN ekbe_best_entw_typ_id_we = 'E' THEN 1 ELSE NULL END AS counter_we,
  ekbe_best_entw_typ_id_rech AS ekbe_bewtp_re,
  ekbe_dat_buch_rech AS ekbe_budat_re,
  rbkp_dat_erfasst AS rbkp_cpudt,
  CAST(TRIM(SUBSTR(CAST(rbkp_zeit_erfasst AS STRING), 1, 8)) AS TIME) AS rbkp_cputm,
  CAST(REPLACE(
    SUBSTR(CAST(rbkp_dat_erfasst AS STRING), 1, 11) || ' ' || COALESCE(SUBSTR(CAST(rbkp_zeit_erfasst AS STRING), 1, 8), '00:00:00'),
    ',',
    ':'
  ) AS DATETIME) AS rbkp_cpudt_cputm,
  ekbe_betrag_rech * CASE WHEN rseg_soll_haben_kz = 'H' THEN -1 ELSE 1 END AS ekbe_dmbtr_re,
  CASE WHEN ekbe_best_entw_typ_id_rech = 'N' THEN 0 ELSE ekbe_menge_best_rech END AS ekbe_bpmng_re,
  ekbe_betrag_wrbtr_rech * CASE WHEN rseg_soll_haben_kz = 'H' THEN -1 ELSE 1 END AS ekbe_wrbtr_re,
  rseg_wrg_id AS ekbe_waers_re,
  CASE WHEN ekbe_best_entw_typ_id_rech IN ('Q', 'N', 'K') THEN 1 ELSE NULL END AS counter_re,
  ekko_dat_best_beleg,
  ekpo_art_id AS ekpo_matnr,
  mseg_menge_bestand_bme AS mseg_lbkum,
  mseg_wert_bestand AS mseg_salk3,
  mseg_gp_id AS mseg_lifnr,
  mseg_lager_bewart_id AS mseg_bwart
FROM kfl_production_dbp_view.v_wewa_wwc_2 AS wewa_wwc_2;