     22
   LEFT JOIN kfl_production_dbp_view.v_mandant_spr_zu_2 AS V06 ON V04.mandant_id = V06.mandant_id
   LEFT JOIN kfl_production_dbp_view.v_cpr_projekt_spr_zu_per_2 AS V03 ON V02.projekt_id = V03.projekt_id AND V06.spr_id =
      V03.spr_id AND V03.spr_id <> 22
  WHERE (V02.dat_bis IS NULL OR V02.dat_bis = DATE '9999-12-31')
   AND (V03.dat_bis IS NULL OR V03.dat_bis = DATE '9999-12-31')
   AND V04.dat_bis = DATE '9999-12-31') AS pr ON INPR.projekt_ext_id = pr.cpr_ext_id
 LEFT JOIN kfl_production_dbp_view.v_techn_platz_ebene_2_per_2 AS TP2 ON pr.techn_platz_id = TP2.techn_platz_id AND TP2.dat_bis
    = DATE '9999-12-31';