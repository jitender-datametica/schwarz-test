CREATE OR REPLACE TABLE `kfl_production_dbp_msi_view_scm.mv_dt_uebernahmequote_vz2`
AS
WITH ART_GP_TAG AS (
  SELECT MANDANT_ID, DAT_PLAN, ART_ID 
  FROM `kfl_production_dbp_view.v_art_gp_dispo_tag_2` A 
  JOIN `kfl_production_dbp_view.v_tag_2` T 
    ON T.DAT = A.DAT_PLAN 
    AND T.AKT_KJ BETWEEN -2 AND 0 
  WHERE DAT_PLAN >= '2025-02-01' 
  GROUP BY 1,2,3
),
EKPO_PRE_CALC AS (
  -- First pass: Define the base columns and compute KOLLIFAKTOR
  SELECT 
    BBD.MANDANT_ID, BBD.BEST_BELEG_ID, BBD.BEST_BELEG_POS_ID, BBD.WUP_ID, BBD.NB_ID, BBD.ART_ID, 
    BBD.MENGE_BEST_KOLLI, BB.GP_ID, BBD.LAGERORT_ID, BBD.BEST_MENGE_EINH_ID, 
    LET.DAT_LIEF_WUNSCH, BBD.GP_TEILSORTIMENT_ID, BB.BESTELLART_ID, MARC.DISPONENT_ID,
    BB.DAT_BEST_BELEG,
    CASE 
      WHEN (BBD.MENGE_BEST_BME / CASE WHEN COALESCE(BBD.MENGE_BEST_KOLLI, 1) = 0 THEN 1 ELSE BBD.MENGE_BEST_KOLLI END) = 0 THEN 1
      ELSE (BBD.MENGE_BEST_BME / CASE WHEN COALESCE(BBD.MENGE_BEST_KOLLI, 1) = 0 THEN 1 ELSE BBD.MENGE_BEST_KOLLI END) 
    END AS KOLLIFAKTOR
  FROM `kfl_production_dbp_view.v_besch_best_det_2` BBD 
  JOIN `kfl_production_dbp_view.v_art_wup_status_per_2` MARC_2 
    ON MARC.MANDANT_ID = BBD.MANDANT_ID AND MARC.ART_ID = BBD.ART_ID AND MARC.WUP_ID = BBD.WUP_ID 
    AND BBD.DAT_BEST_BELEG BETWEEN MARC.DAT_VON AND MARC.DAT_BIS
  JOIN `kfl_production_dbp_view.v_lief_einteilung_2` LET 
    ON LET.MANDANT_ID = BBD.MANDANT_ID AND LET.BEST_BELEG_ID = BBD.BEST_BELEG_ID AND LET.BEST_BELEG_POS_ID = BBD.BEST_BELEG_POS_ID
  JOIN `kfl_production_dbp_view.v_besch_best_2` BB 
    ON BB.MANDANT_ID = BBD.MANDANT_ID AND BB.BEST_BELEG_ID = BBD.BEST_BELEG_ID
  WHERE ((BB.MANDANT_ID = 1 AND BB.BESTELLART_ID = 'ZLLF') OR (BB.MANDANT_ID <> 1 AND BB.BESTELLART_ID IN ('ZBCZ', 'ZBPL', 'ZBSK','ZBHR','ZBRO', 'ZBBG')) OR BB.BESTELLART_ID IN ('ZNL','ZNLP','ZNLS','ZNLW')) 
    AND BB.DAT_BEST_BELEG >= '2025-02-01'
),
EKPO_2 AS (
  -- Second pass: Use KOLLIFAKTOR to compute the block quantities
  SELECT 
    EPC.*,
    CASE WHEN EPC.BEST_MENGE_EINH_ID <> 'KG' THEN BLOCK.MENGE_BLOCK / NULLIF(EPC.KOLLIFAKTOR, 0) ELSE BLOCK.MENGE_BLOCK END AS MENGE_BLOCK_WERBUNG, 
    CASE WHEN EPC.BEST_MENGE_EINH_ID <> 'KG' THEN IWT.MENGE_BLOCK / NULLIF(EPC.KOLLIFAKTOR, 0) ELSE IWT.MENGE_BLOCK END AS MENGE_BLOCK_IWT
  FROM EKPO_PRE_CALC EPC
  LEFT JOIN `kfl_production_dbp_view.v_best_blockbestand_2` BLOCK 
    ON BLOCK.MANDANT_ID = EPC.MANDANT_ID AND BLOCK.BEST_BELEG_ID = EPC.BEST_BELEG_ID AND BLOCK.BEST_BELEG_POS_ID = EPC.BEST_BELEG_POS_ID AND BLOCK.PROZESS_ID = 1
  LEFT JOIN `kfl_production_dbp_view.v_best_blockbestand_2` IWT 
    ON IWT.MANDANT_ID = EPC.MANDANT_ID AND IWT.BEST_BELEG_ID = EPC.BEST_BELEG_ID AND IWT.BEST_BELEG_POS_ID = EPC.BEST_BELEG_POS_ID AND IWT.PROZESS_ID = 2
  WHERE EXISTS (SELECT 1 FROM ART_GP_TAG TAG_2 WHERE TAG.MANDANT_ID = EPC.MANDANT_ID AND TAG.ART_ID = EPC.ART_ID AND TAG.DAT_PLAN = EPC.DAT_BEST_BELEG)
    AND NOT EXISTS (SELECT 1 FROM `kfl_production_dbp_view.v_art_wg_zu_per_2` WG WHERE WG.MANDANT_ID = EPC.MANDANT_ID AND WG.ART_ID = EPC.ART_ID AND WG.DAT_BIS = '9999-12-31' AND WG.WG_ID BETWEEN 980 AND 989)
),
CALCULATED_BASE AS (
  -- Third pass: Core Join Logic
  SELECT
    COALESCE(ART_GP_TAG.ART_ID, EKPO.ART_ID) AS RAW_ART_ID,
    ART_GP_TAG1.VZ_DISPO_ARTIKELSTATUS_ID AS RAW_VZ_DISPO_ARTIKELSTATUS_ID,
    COALESCE(ART_GP_TAG1.MENGE_EINH_ID, EKPO.BEST_MENGE_EINH_ID) AS RAW_MENGE_EINH_ID,
    COALESCE(GP_VZ_TAG.WUP_ID, EKPO.WUP_ID) AS RAW_WUP_ID,
    COALESCE(GP_VZ_TAG.NB_ID, EKPO.NB_ID) AS RAW_NB_ID,
    COALESCE(EKPO.GP_ID, GP_VZ_TAG.GP_ID) AS RAW_GP_ID,
    COALESCE(ART_GP_TAG.MANDANT_ID, EKPO.MANDANT_ID) AS RAW_MANDANT_ID,
    COALESCE(EKPO.GP_TEILSORTIMENT_ID, GP_VZ_TAG.GP_TEILSORTIMENT_ID) AS RAW_GP_TEILSORTIMENT_ID,
    COALESCE(GP_VZ_TAG.LAGERORT_ID, EKPO.LAGERORT_ID) AS RAW_LAGERORT_ID,
    COALESCE(EKPO.DISPONENT_ID, GP_VZ_TAG.DISPONENT_ID) AS RAW_DISPONENT_ID,
    GP_VZ_TAG.VZ_DISPO_STATUS_ID AS RAW_VZ_DISPO_STATUS_ID,
    GP_VZ_TAG.AUTODISPO_FG AS RAW_AUTODISPO_FG,
    COALESCE(ART_GP_TAG.DAT_PLAN, EKPO.DAT_BEST_BELEG) AS RAW_DAT_PLAN,
    COALESCE(V_B_VOR.DAT_BEST, EKPO.DAT_BEST_BELEG) AS RAW_DAT_BEST,
    COALESCE(EKET_LDAT.DAT_LIEF_WUNSCH, V_B_VOR.DAT_LIEF, EKPO.DAT_LIEF_WUNSCH) AS RAW_DAT_LIEF,
    CASE WHEN FG_ = 'M' THEN NULL ELSE COALESCE(V_B_SPLIT.BEST_VOR_DISPO_ID, V_B_VOR.BEST_VOR_DISPO_ID) END AS RAW_BEST_VOR_DISPO_ID,
    V_B_VOR.BEDARF_NETTO AS RAW_BEDARF_NETTO,
    V_B_VOR.BEDARF_NACH_MBM_ART AS RAW_BEDARF_NACH_MBM_ART,
    V_B_VOR.BEDARF_NACH_RUNDUNG AS RAW_BEDARF_NACH_RUNDUNG,
    V_B_VOR.BEDARF_NACH_DYN_RUNDUNG AS RAW_BEDARF_NACH_DYN_RUNDUNG,
    V_B_VOR.BEDARF_NACH_MBM_LIEFERANT AS RAW_BEDARF_NACH_MBM_LIEFERANT,
    CASE WHEN FG_ = 'M' THEN 0 ELSE COALESCE(V_B_VOR.BV_QUELLE_ID, 0) END AS RAW_BV_QUELLE_ID,
    CASE 
      WHEN FG_ = 'M' THEN EKPO.BEST_BELEG_ID 
      WHEN V_B_SPLIT.MENGE_GESAMT IS NOT NULL THEN V_B_SPLIT.BEST_BELEG_ID 
      ELSE COALESCE(EKPO.BEST_BELEG_ID, -1) 
    END AS RAW_BEST_BELEG_ID,
    CASE 
      WHEN FG_ = 'M' THEN EKPO.BEST_BELEG_POS_ID 
      WHEN V_B_SPLIT.MENGE_GESAMT IS NOT NULL THEN V_B_SPLIT.BEST_BELEG_POS_ID  
      ELSE COALESCE(EKPO.BEST_BELEG_POS_ID, -1) 
    END AS RAW_BEST_BELEG_POS_ID,
    EKPO.BESTELLART_ID AS RAW_BESTELLART_ID,
    V_B_VOR.MENGE_BEST_GESAMT AS RAW_MENGE_BEST_GESAMT_VOR,
    V_B_VOR.MENGE_BEST_NORMAL AS RAW_MENGE_BEST_NORMAL_VOR,
    V_B_VOR.MENGE_BEST_BEVORRATUNG AS RAW_MENGE_BEST_BEVORRATUNG_VOR,
    V_B_VOR.MENGE_BEST_IWT AS RAW_MENGE_BEST_IWT_VOR,
    V_B_VOR.MENGE_BEST_WERBUNG AS RAW_MENGE_BEST_WERBUNG_VOR,
    V_B_VOR.dat_verfuegbarkeit AS RAW_DAT_VERFUEGBAREIT,
    V_B_VOR.DAT_BESDARFSPERIODE_ENDE AS RAW_DAT_BEDARFSPERIODE_ENDE,
    V_B_VOR.DAT_BESTANDSPERIODE_ENDE AS RAW_DAT_BESTANDSPERIODE_ENDE,
    EKPO.MENGE_BEST_KOLLI AS RAW_EKPO_MENGE_BEST_KOLLI,
    EKPO.MENGE_BLOCK_WERBUNG AS RAW_EKPO_MENGE_WERBUNG,
    EKPO.MENGE_BLOCK_IWT AS RAW_EKPO_MENGE_IWT,
    V_B_SPLIT.MENGE_GESAMT AS RAW_SPLIT_GESAMT,
    V_B_SPLIT.MENGE_IWT_GESAMT AS RAW_SPLIT_IWT,
    V_B_SPLIT.MENGE_WERBUNG_GESAMT AS RAW_SPLIT_WERBUNG,
    FG_,
    V_B_VOR.BEST_VOR_DISPO_ID AS VOR_DISPO_ID_ORIG
  FROM ART_GP_TAG
  CROSS JOIN (SELECT 'M' AS FG_ UNION ALL SELECT 'BV' AS FG_) AS M_BV_FG
  LEFT JOIN `kfl_production_dbp_view.v_vz_best_vor_2` V_B_VOR
    ON ART_GP_TAG.MANDANT_ID = V_B_VOR.MANDANT_ID
    AND ART_GP_TAG.DAT_PLAN = V_B_VOR.DAT_PLAN
    AND V_B_VOR.DAT_BEST = ART_GP_TAG.DAT_PLAN 
    AND V_B_VOR.ART_ID = cast(ART_GP_TAG.ART_ID as string) 
    AND V_B_VOR.BEST_VOR_DISPO_ID > 0
  LEFT JOIN `kfl_production_dbp_view.v_art_gp_dispo_tag_2` ART_GP_TAG1
    ON ART_GP_TAG1.MANDANT_ID = V_B_VOR.MANDANT_ID
    AND ART_GP_TAG1.DAT_PLAN = V_B_VOR.DAT_PLAN
    AND ART_GP_TAG1.GP_DISPO_ID = V_B_VOR.GP_DISPO_ID
    AND ART_GP_TAG1.ART_DISPO_ID = V_B_VOR.ART_DISPO_ID
  LEFT JOIN `kfl_production_dbp_view.v_gp_dispo_vz_tag_2` GP_VZ_TAG
    ON ART_GP_TAG1.MANDANT_ID = GP_VZ_TAG.MANDANT_ID
    AND ART_GP_TAG1.GP_DISPO_ID = GP_VZ_TAG.GP_DISPO_ID
    AND ART_GP_TAG1.DAT_PLAN = GP_VZ_TAG.DAT_PLAN
  LEFT JOIN `kfl_production_dbp_view.v_vz_best_split_2` V_B_SPLIT
    ON ART_GP_TAG1.MANDANT_ID = V_B_SPLIT.MANDANT_ID
    AND ART_GP_TAG1.ART_DISPO_ID = V_B_SPLIT.ART_DISPO_ID
    AND ART_GP_TAG1.GP_DISPO_ID = V_B_SPLIT.GP_DISPO_ID
    AND V_B_VOR.BEST_VOR_DISPO_ID = CASE WHEN V_B_SPLIT.BEST_VOR_DISPO_ID > 0 THEN V_B_SPLIT.BEST_VOR_DISPO_ID ELSE V_B_VOR.BEST_VOR_DISPO_ID END
  LEFT JOIN `kfl_production_dbp_view.v_lief_einteilung_2` EKET_LDAT
    ON EKET_LDAT.MANDANT_ID = V_B_SPLIT.MANDANT_ID
    AND EKET_LDAT.BEST_BELEG_ID = V_B_SPLIT.BEST_BELEG_ID
    AND EKET_LDAT.BEST_BELEG_POS_ID = V_B_SPLIT.BEST_BELEG_POS_ID
  LEFT JOIN EKPO_2
    ON ART_GP_TAG.MANDANT_ID = EKPO.MANDANT_ID AND ART_GP_TAG.ART_ID = EKPO.ART_ID AND ART_GP_TAG.DAT_PLAN = EKPO.DAT_BEST_BELEG AND GP_VZ_TAG.WUP_ID = EKPO.WUP_ID
    AND EKPO.BEST_BELEG_ID = CASE WHEN FG_ = 'M' THEN EKPO.BEST_BELEG_ID ELSE V_B_SPLIT.BEST_BELEG_ID END
    AND EKPO.BEST_BELEG_POS_ID = CASE WHEN FG_ = 'M' THEN EKPO.BEST_BELEG_POS_ID ELSE V_B_SPLIT.BEST_BELEG_POS_ID END 
    AND EKPO.DAT_LIEF_WUNSCH = COALESCE(EKET_LDAT.DAT_LIEF_WUNSCH, V_B_VOR.DAT_LIEF, ART_GP_TAG1.DAT_LIEF, EKPO.DAT_LIEF_WUNSCH) 
    AND EKPO.GP_ID = COALESCE(V_B_SPLIT.GP_ID, GP_VZ_TAG.GP_ID, EKPO.GP_ID)
  WHERE (ART_GP_TAG.MANDANT_ID IS NULL OR ((ART_GP_TAG.MANDANT_ID = 1 AND VZ_DISPO_ARTIKELSTATUS_ID NOT IN (0, 50)) OR (ART_GP_TAG.MANDANT_ID <> 1 AND VZ_DISPO_ARTIKELSTATUS_ID <> 50) AND ART_GP_TAG.DAT_PLAN >= '2025-02-01')
    AND ((FG_ = 'M' AND EKPO.MENGE_BEST_KOLLI IS NOT NULL AND COALESCE(V_B_SPLIT.BEST_VOR_DISPO_ID, 0) = 0 AND NOT EXISTS (SELECT 1 FROM `kfl_production_dbp_view.v_vz_best_split_2` D2020 WHERE D2020.BEST_VOR_DISPO_ID > 0 AND D2020.MANDANT_ID = EKPO.MANDANT_ID AND D2020.BEST_BELEG_ID = EKPO.BEST_BELEG_ID AND D2020.BEST_BELEG_POS_ID = EKPO.BEST_BELEG_POS_ID))
    OR (FG_ = 'BV' AND COALESCE(V_B_VOR.BEST_VOR_DISPO_ID, 0) > 0 AND COALESCE(V_B_SPLIT.BEST_VOR_DISPO_ID, V_B_VOR.BEST_VOR_DISPO_ID) = V_B_VOR.BEST_VOR_DISPO_ID)))
    AND NOT (EKPO.MANDANT_ID IS NULL AND V_B_VOR.MANDANT_ID IS NULL)
),
FINAL_PROCESSING AS (
  -- Outer level logic using aliases from CALCULATED_BASE
  SELECT
    RAW_ART_ID AS ART_ID,
    RAW_VZ_DISPO_ARTIKELSTATUS_ID AS VZ_DISPO_ARTIKELSTATUS_ID,
    RAW_MENGE_EINH_ID AS MENGE_EINH_ID,
    RAW_WUP_ID AS WUP_ID,
    RAW_NB_ID AS NB_ID,
    RAW_GP_ID AS GP_ID,
    RAW_MANDANT_ID AS MANDANT_ID,
    RAW_GP_TEILSORTIMENT_ID AS GP_TEILSORTIMENT_ID,
    RAW_LAGERORT_ID AS LAGERORT_ID,
    RAW_DISPONENT_ID AS DISPONENT_ID,
    RAW_VZ_DISPO_STATUS_ID AS VZ_DISPO_STATUS_ID,
    RAW_AUTODISPO_FG AS AUTODISPO_FG,
    RAW_DAT_PLAN AS DAT_PLAN,
    RAW_DAT_BEST AS DAT_BEST,
    RAW_DAT_LIEF AS DAT_LIEF,
    RAW_BEST_VOR_DISPO_ID AS BEST_VOR_DISPO_ID,
    RAW_BEDARF_NETTO AS BEDARF_NETTO,
    RAW_BEDARF_NACH_MBM_ART AS BEDARF_NACH_MBM_ART,
    RAW_BEDARF_NACH_RUNDUNG AS BEDARF_NACH_RUNDUNG,
    RAW_BEDARF_NACH_DYN_RUNDUNG AS BEDARF_NACH_DYN_RUNDUNG,
    RAW_BEDARF_NACH_MBM_LIEFERANT AS BEDARF_NACH_MBM_LIEFERANT,
    RAW_BV_QUELLE_ID AS BV_QUELLE_ID,
    CASE 
      WHEN RAW_BV_QUELLE_ID = 1 THEN 'OP-Prepare (Standard)' 
      WHEN RAW_BV_QUELLE_ID = 2 THEN 'Promotion Monitoring (Werbung)' 
      ELSE 'Kein BV' 
    END AS BV_QUELLE_BEZ,
    RAW_BEST_BELEG_ID AS BEST_BELEG_ID,
    RAW_BEST_BELEG_POS_ID AS BEST_BELEG_POS_ID,
    CASE WHEN FG_ = 'M' THEN COALESCE(RAW_BESTELLART_ID, '-1') WHEN RAW_BEST_BELEG_ID = -1 THEN '-1' ELSE COALESCE(RAW_BESTELLART_ID, '-1') END AS BESTELLART_ID,
    CASE 
      WHEN COALESCE(RAW_EKPO_MENGE_WERBUNG, 0) > 0 AND COALESCE(FG_, 'M') = 'M' OR COALESCE(RAW_MENGE_BEST_WERBUNG_VOR, 0) > 0 THEN 'W'
      WHEN COALESCE(RAW_MENGE_BEST_BEVORRATUNG_VOR, 0) > 0 THEN 'B'
      WHEN COALESCE(RAW_EKPO_MENGE_IWT, 0) > 0 AND COALESCE(FG_, 'M') = 'M' OR COALESCE(RAW_MENGE_BEST_IWT_VOR, 0) > 0 THEN 'I' 
      ELSE 'S'
    END AS BESTELLSTATUS_TYP_ID,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_MENGE_BEST_GESAMT_VOR END AS MENGE_BV_GESAMT,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_MENGE_BEST_NORMAL_VOR END AS MENGE_BV_STANDARD,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_MENGE_BEST_BEVORRATUNG_VOR END AS MENGE_BV_BEVORRATUNG,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_MENGE_BEST_IWT_VOR END AS MENGE_BV_IWT,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_MENGE_BEST_WERBUNG_VOR END AS MENGE_BV_WERBUNG,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_DAT_VERFUEGBAREIT END AS DAT_VERFUEGBARKEIT,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_DAT_BEDARFSPERIODE_ENDE END AS DAT_BEDARFSPERIODE_ENDE,
    CASE WHEN FG_ = 'M' THEN NULL ELSE RAW_DAT_BESTANDSPERIODE_ENDE END AS DAT_BESTANDSPERIODE_ENDE,
    CASE WHEN RAW_SPLIT_GESAMT IS NULL AND FG_ = 'BV' THEN NULL ELSE RAW_EKPO_MENGE_BEST_KOLLI END AS MENGE_BEST_GESAMT,
    CASE WHEN RAW_SPLIT_GESAMT IS NULL AND FG_ = 'BV' THEN NULL ELSE RAW_EKPO_MENGE_WERBUNG END AS MENGE_BEST_WERBUNG,
    CASE WHEN RAW_SPLIT_GESAMT IS NULL AND FG_ = 'BV' THEN NULL ELSE RAW_EKPO_MENGE_IWT END AS MENGE_BEST_IWT,
    RAW_SPLIT_GESAMT AS MENGE_SPLIT_GESAMT,
    RAW_SPLIT_IWT AS MENGE_SPLIT_IWT,
    RAW_SPLIT_WERBUNG AS MENGE_SPLIT_WERBUNG,
    CASE 
      WHEN FG_ = 'M' AND RAW_EKPO_MENGE_BEST_KOLLI IS NOT NULL AND (RAW_SPLIT_GESAMT IS NULL OR RAW_BEST_VOR_DISPO_ID = 0) THEN 5
      WHEN RAW_SPLIT_GESAMT = RAW_MENGE_BEST_GESAMT_VOR AND RAW_BEST_VOR_DISPO_ID <> 0 THEN 1
      WHEN COALESCE(RAW_SPLIT_GESAMT, 0) = 0 AND RAW_MENGE_BEST_GESAMT_VOR > 0 AND RAW_BEST_VOR_DISPO_ID <> 0 THEN 2
      WHEN RAW_SPLIT_GESAMT < RAW_MENGE_BEST_GESAMT_VOR AND RAW_BEST_VOR_DISPO_ID <> 0 THEN 3
      WHEN RAW_SPLIT_GESAMT > RAW_MENGE_BEST_GESAMT_VOR AND RAW_BEST_VOR_DISPO_ID <> 0 THEN 4
      ELSE 5 
    END AS BESTELLSTATUS_VZ_ID,
    FG_ AS FG,
    RAW_MANDANT_ID, RAW_ART_ID, RAW_WUP_ID, RAW_DAT_PLAN, RAW_BEST_VOR_DISPO_ID, RAW_BEST_BELEG_ID, RAW_BEST_BELEG_POS_ID
  FROM CALCULATED_BASE
)
SELECT 
  ART_ID, VZ_DISPO_ARTIKELSTATUS_ID, MENGE_EINH_ID, WUP_ID, NB_ID, GP_ID, MANDANT_ID, GP_TEILSORTIMENT_ID, LAGERORT_ID, DISPONENT_ID, VZ_DISPO_STATUS_ID, AUTODISPO_FG, DAT_PLAN, DAT_BEST, DAT_LIEF, BEST_VOR_DISPO_ID, BEDARF_NETTO, BEDARF_NACH_MBM_ART, BEDARF_NACH_RUNDUNG, BEDARF_NACH_DYN_RUNDUNG, BEDARF_NACH_MBM_LIEFERANT, BV_QUELLE_ID, BV_QUELLE_BEZ, BEST_BELEG_ID, BEST_BELEG_POS_ID, BESTELLART_ID, BESTELLSTATUS_TYP_ID, MENGE_BV_GESAMT, MENGE_BV_STANDARD, MENGE_BV_BEVORRATUNG, MENGE_BV_IWT, MENGE_BV_WERBUNG, DAT_VERFUEGBARKEIT, DAT_BEDARFSPERIODE_ENDE, DAT_BESTANDSPERIODE_ENDE, MENGE_BEST_GESAMT, MENGE_BEST_WERBUNG, MENGE_BEST_IWT, MENGE_SPLIT_GESAMT, MENGE_SPLIT_IWT, MENGE_SPLIT_WERBUNG, BESTELLSTATUS_VZ_ID,
  CASE 
    WHEN BESTELLSTATUS_VZ_ID = 5 THEN '0M'
    WHEN BESTELLSTATUS_VZ_ID = 1 THEN 'VB'
    WHEN BESTELLSTATUS_VZ_ID = 2 THEN 'V0'
    WHEN BESTELLSTATUS_VZ_ID = 3 THEN 'V-'
    WHEN BESTELLSTATUS_VZ_ID = 4 THEN 'V+'
    ELSE 'n/a' 
  END AS BESTELLSTATUS_VZ_SHORT_DESC,
  CASE 
    WHEN BESTELLSTATUS_VZ_ID = 5 THEN 'Manuell'
    WHEN BESTELLSTATUS_VZ_ID = 1 THEN 'Übernommen'
    WHEN BESTELLSTATUS_VZ_ID = 2 THEN 'Verworfen'
    WHEN BESTELLSTATUS_VZ_ID = 3 THEN 'Reduziert'
    WHEN BESTELLSTATUS_VZ_ID = 4 THEN 'Erhöht'
    ELSE 'n/a' 
  END AS BESTELLSTATUS_VZ_DESC,
  FG,
  CASE 
    WHEN BEST_VOR_DISPO_ID IS NULL THEN 1
    WHEN ROW_NUMBER() OVER (PARTITION BY RAW_MANDANT_ID, RAW_ART_ID, RAW_WUP_ID, RAW_DAT_PLAN, RAW_BEST_VOR_DISPO_ID ORDER BY RAW_BEST_BELEG_ID DESC) = 1 THEN 1 
    ELSE 0 
  END AS BEST_VOR_DISPO_1ST_FG
FROM FINAL_PROCESSING
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY RAW_MANDANT_ID, RAW_ART_ID, RAW_WUP_ID, RAW_DAT_PLAN, RAW_BEST_VOR_DISPO_ID, RAW_BEST_BELEG_ID, RAW_BEST_BELEG_POS_ID 
  ORDER BY MENGE_SPLIT_GESAMT DESC NULLS LAST
) = 1;