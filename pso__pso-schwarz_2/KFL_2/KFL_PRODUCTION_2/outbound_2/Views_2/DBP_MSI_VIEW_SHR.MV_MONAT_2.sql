CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_shr.mv_monat_2 (kjmo, kjmo_vj, gjmo, gjmo_vj, kjqu, gjqu, kj, gj,
akt_mo, akt_mo_komplett, akt_gjqu, akt_gjqu_komplett, akt_kjqu, akt_kjqu_komplett, akt_gj, akt_gj_komplett, akt_kj,
akt_kj_komplett, mo_gj, mo_kj, kjmo_vm, kjmo_vm6) AS SELECT kjmo,
 kjmo_vj,
 gjmo,
 gjmo_vj,
 kjqu,
 gjqu,
 kj,
 gj,
 akt_mo,
 akt_mo_komplett,
 akt_gjqu,
 akt_gjqu_komplett,
 akt_kjqu,
 akt_kjqu_komplett,
 akt_gj,
 akt_gj_komplett,
 akt_kj,
 akt_kj_komplett,
 mo_gj,
 mo_kj,
 ROUND(CAST(FORMAT_DATE('%Y%m', IF(PARSE_DATE('%Y%m', SAFE_CAST(kjmo as STRING)) = LAST_DAY(PARSE_DATE('%Y%m', SAFE_CAST(kjmo as STRING))), LAST_DAY(DATE_ADD(PARSE_DATE('%Y%m', SAFE_CAST(kjmo as STRING)), INTERVAL - 1 MONTH)), DATE_ADD(PARSE_DATE('%Y%m', SAFE_CAST(kjmo as STRING)), INTERVAL - 1
      MONTH))) AS BIGNUMERIC), 0) AS kjmo_vm,
 MIN(kjmo) OVER (ORDER BY kjmo IS NULL, kjmo ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS kjmo_vm6
FROM kfl_production_dbp_view.v_monat_2 AS V01;