CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_vis.mv_bedienung_spr_zu_2 AS SELECT CASE
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
  THEN 1
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
  THEN - 1
  ELSE 0
  END AS bed_fg,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN 'Ja'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE 'Nein'
   END AS STRING) AS bed_bez,
  CASE
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
  THEN 'Ja'
  WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
  THEN ''
  ELSE 'Nein'
  END AS bed_bez_de,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN 'Ano'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE 'ne'
   END AS STRING) AS bed_bez_cz,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN 'Tak'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE 'Nie'
   END AS STRING) AS bed_bez_pl,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN 'áno'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE 'nie'
   END AS STRING) AS bed_bez_sk,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN 'Yes'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE 'No'
   END AS STRING) AS bed_bez_hr,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN 'Da'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE 'Nu'
   END AS STRING) AS bed_bez_ro,
 CAST(CASE
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
   THEN '\\u0434\\u0430'
   WHEN dat = DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY)
   THEN ''
   ELSE '\\u041D\\u0435'
   END AS STRING) AS bed_bez_bg
FROM kfl_production_dbp_view.v_tag_2
WHERE dat BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY) AND (CURRENT_DATE);