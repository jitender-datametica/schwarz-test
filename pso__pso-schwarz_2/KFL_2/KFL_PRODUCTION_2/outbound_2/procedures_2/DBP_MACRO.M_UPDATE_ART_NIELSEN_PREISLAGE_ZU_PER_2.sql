CREATE OR REPLACE PROCEDURE dbp_macro.m_update_art_nielsen_preislage_zu_per(IN MANDANT_ID FLOAT64, IN ART_MATCHING_ID FLOAT64, IN KJMO FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;

BEGIN TRANSACTION;
SET sql_stmt  =  '''UPDATE dbp_data.art_nielsen_preislage_zu_per_2 SET  art_matching_id = CAST(@ART_MATCHING_ID AS INT64) WHERE art_matching_id = CAST(@ART_MATCHING_ID_1 AS INT64) AND mandant_id = @MANDANT_ID ''';

EXECUTE IMMEDIATE (sql_stmt) USING ART_MATCHING_ID AS ART_MATCHING_ID,  MANDANT_ID AS MANDANT_ID, ART_MATCHING_ID AS ART_MATCHING_ID_1;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;