CREATE OR REPLACE PROCEDURE dbp_macro.m_update_l_aktion_thema(IN AKTION_THEMA_ID STRING, IN MANDANT_ID FLOAT64, IN AKTION_THEMA_GRUPPE_ID FLOAT64)
BEGIN
DECLARE sql_stmt STRING;
DECLARE sql_commit STRING;

BEGIN TRANSACTION;
SET sql_stmt  =  '''UPDATE dbp_data.l_aktion_thema_2 
                    SET  aktion_thema_gruppe_id = CAST(CASE WHEN @AKTION_THEMA_GRUPPE_ID = -1 THEN NULL 
                    ELSE @AKTION_THEMA_GRUPPE_ID_1 END AS INTEGER)            
                    WHERE aktion_thema_id = @AKTION_THEMA_ID AND mandant_id = @MANDANT_ID ''';

EXECUTE IMMEDIATE (sql_stmt) USING AKTION_THEMA_GRUPPE_ID AS AKTION_THEMA_GRUPPE_ID,  AKTION_THEMA_GRUPPE_ID AS AKTION_THEMA_GRUPPE_ID_1,  AKTION_THEMA_ID AS AKTION_THEMA_ID,  MANDANT_ID AS MANDANT_ID;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;