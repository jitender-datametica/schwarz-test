CREATE OR REPLACE PROCEDURE dbp_macro.m_ups_ts_artikel_vz_share(IN MANDANT_ID FLOAT64, IN ART_ID FLOAT64, IN AKTION_ID STRING, IN ANGEBOT_ID FLOAT64, IN KJWO FLOAT64, IN AUSLIEFERGRUPPE_ID STRING, IN GP_ID FLOAT64, IN WUP_ID_VZ FLOAT64, IN NB_ID_VZ FLOAT64, IN MANDANT_ID_VZ FLOAT64, IN RANK_SHARE FLOAT64, IN SHARE_WERT FLOAT64)
BEGIN
DECLARE sql_stmt1 STRING;
DECLARE sql_stmt2 STRING;
DECLARE sql_commit STRING;

BEGIN TRANSACTION;
SET sql_stmt1  =  '''MERGE INTO dbp_data.ts_wbs_artikel_vz_share_2 AS TARGET 
USING (SELECT @MANDANT_ID AS mandant_id,
   @ART_ID AS art_id,
   @AKTION_ID AS aktion_id,
   @ANGEBOT_ID AS angebot_id,
   @KJWO AS kjwo,
   @AUSLIEFERGRUPPE_ID AS ausliefergruppe_id,
   COALESCE(COALESCE(@GP_ID, -9), -9) AS gp_id,
   @WUP_ID_VZ AS wup_id_vz,
   @NB_ID_VZ AS nb_id_vz,
   @MANDANT_ID AS mandant_id_vz,
   @RANK_SHARE AS rank_share,
   @SHARE_WERT AS share_wert) AS source 
   ON TARGET.mandant_id = source.mandant_id 
   AND TARGET.art_id = source.art_id 
   AND TARGET.aktion_id = source.aktion_id 
   AND TARGET.angebot_id = source.angebot_id 
   AND TARGET.kjwo = source.kjwo 
   AND TARGET.ausliefergruppe_id = source.ausliefergruppe_id         
   AND TARGET.gp_id = source.gp_id 
   AND TARGET.wup_id_vz = source.wup_id_vz 
   AND TARGET.nb_id_vz = source.nb_id_vz   
   AND TARGET.mandant_id_vz = source.mandant_id_vz 
   AND TARGET.rank_share = source.rank_share 

   WHEN MATCHED THEN 
         UPDATE SET  share_wert = CAST(source.share_wert AS INTEGER) 
   WHEN NOT MATCHED THEN 
        INSERT (mandant_id, art_id, aktion_id, angebot_id, kjwo, ausliefergruppe_id, gp_id, wup_id_vz,  nb_id_vz, mandant_id_vz, rank_share, share_wert) VALUES(CAST(source.mandant_id AS INTEGER), CAST(source.art_id AS INTEGER)  , source.aktion_id, CAST(source.angebot_id AS INTEGER), CAST(source.kjwo AS INTEGER), source.ausliefergruppe_id, CAST(source.gp_id AS INTEGER)  , CAST(source.wup_id_vz AS INTEGER), CAST(source.nb_id_vz AS INTEGER), CAST(source.mandant_id_vz AS INTEGER), CAST(source.rank_share AS INTEGER)  , CAST(source.share_wert AS INTEGER)) ''';

EXECUTE IMMEDIATE (sql_stmt1) USING IF(MANDANT_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), MANDANT_ID) AS MANDANT_ID,  IF(ART_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), ART_ID) AS ART_ID,  IF(AKTION_ID = CAST(NULL AS STRING), CAST(NULL AS STRING), AKTION_ID) AS AKTION_ID,  IF(ANGEBOT_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), ANGEBOT_ID) AS ANGEBOT_ID,  IF(KJWO = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), KJWO) AS KJWO,  IF(AUSLIEFERGRUPPE_ID = CAST(NULL AS STRING), CAST(NULL AS STRING), AUSLIEFERGRUPPE_ID) AS AUSLIEFERGRUPPE_ID,  IF(GP_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), GP_ID) AS GP_ID,  IF(WUP_ID_VZ = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), WUP_ID_VZ) AS WUP_ID_VZ,  IF(NB_ID_VZ = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), NB_ID_VZ) AS NB_ID_VZ,  IF(MANDANT_ID_VZ = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), MANDANT_ID_VZ) AS MANDANT_ID_VZ,  IF(RANK_SHARE = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), RANK_SHARE) AS RANK_SHARE,  IF(SHARE_WERT = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), SHARE_WERT) AS SHARE_WERT;

SET sql_stmt2  =  '''DELETE FROM dbp_data.ts_wbs_artikel_vz_share_2 
            WHERE mandant_id_vz = mandant_id 
            AND share_wert IS NULL 
            AND art_id IS NOT NULL 
            AND aktion_id IS NOT NULL 
            AND angebot_id IS NOT NULL 
            AND kjwo IS NOT NULL 
            AND ausliefergruppe_id IS NOT NULL 
            AND gp_id IS NOT NULL 
            AND wup_id_vz IS NOT NULL 
            AND nb_id_vz IS NOT NULL 
            AND rank_share IS NOT NULL ''';

EXECUTE IMMEDIATE (sql_stmt2) USING IF(MANDANT_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), MANDANT_ID) AS MANDANT_ID,  IF(ART_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), ART_ID) AS ART_ID,  IF(AKTION_ID = CAST(NULL AS STRING), CAST(NULL AS STRING), AKTION_ID) AS AKTION_ID,  IF(ANGEBOT_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), ANGEBOT_ID) AS ANGEBOT_ID,  IF(KJWO = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), KJWO) AS KJWO,  IF(AUSLIEFERGRUPPE_ID = CAST(NULL AS STRING), CAST(NULL AS STRING), AUSLIEFERGRUPPE_ID) AS AUSLIEFERGRUPPE_ID,  IF(GP_ID = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), GP_ID) AS GP_ID,  IF(WUP_ID_VZ = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), WUP_ID_VZ) AS WUP_ID_VZ,  IF(NB_ID_VZ = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), NB_ID_VZ) AS NB_ID_VZ,  IF(MANDANT_ID_VZ = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), MANDANT_ID_VZ) AS MANDANT_ID_VZ,  IF(RANK_SHARE = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), RANK_SHARE) AS RANK_SHARE,  IF(SHARE_WERT = CAST(NULL AS FLOAT64), CAST(NULL AS FLOAT64), SHARE_WERT) AS SHARE_WERT;

SET sql_commit  =  'COMMIT TRANSACTION';

EXECUTE IMMEDIATE (sql_commit);
END;