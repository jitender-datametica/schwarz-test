CREATE OR REPLACE PROCEDURE `dbp_macro.m_ups_wup_stunden_tag_fil` (
    MANDANT_ID FLOAT64,
    WUP_ID FLOAT64,
    NB_ID FLOAT64,
    DAT STRING,
    UMS_NETTO_PLAN_MAN FLOAT64,
    STUNDEN_MARKT FLOAT64,
    STUNDEN_SONSTIGE FLOAT64,
    STUNDEN_VERSETZUNG FLOAT64,
    STUNDEN_PLAN FLOAT64,
    STUNDEN_SONSTIGE_PLAN FLOAT64,
    SPERRE_WOCHE_SO FLOAT64,
    SPERRE_MONAT_7 FLOAT64,
    SPERRE_MONAT_15 FLOAT64,
    SPERRE_LAND FLOAT64
)
BEGIN
    -- BigQuery requires static CALL statements, so we route them via a CASE block
    CASE CAST(MANDANT_ID AS INT64)
        WHEN 1 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_de`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 2 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_cz`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 3 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_pl`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 4 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_md`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 5 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_sk`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 6 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_hr`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 7 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_ro`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        WHEN 8 THEN 
            CALL `dbp_macro.m_ups_wup_stunden_tag_fil_bg`(MANDANT_ID, WUP_ID, NB_ID, DAT, UMS_NETTO_PLAN_MAN, STUNDEN_MARKT, STUNDEN_SONSTIGE, STUNDEN_VERSETZUNG, STUNDEN_PLAN, STUNDEN_SONSTIGE_PLAN, SPERRE_WOCHE_SO, SPERRE_MONAT_7, SPERRE_MONAT_15, SPERRE_LAND);
        ELSE 
            RAISE USING MESSAGE = CONCAT('Unsupported MANDANT_ID provided: ', COALESCE(CAST(MANDANT_ID AS STRING), 'NULL'));
    END CASE;
END;
