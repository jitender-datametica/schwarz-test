CREATE OR REPLACE VIEW FE_MSTR_AI_REPORTING.V_SOD_DIM_ITEM_VELOCITY_2(
	SEGMENT_SID
	, SEGMENTATION_SID
	, SRC_SEGMENT_NR
	, SEGMENT_NAME_US
	, SEGMENT_DESCR
	, MODEL_SID
	, MODEL_AREA_CD
	, MODEL_GROUP_CD
	, DWH_LOAD_ID
	, DWH_CREATED
	, DWH_UPDATED
	, LOWER_BOUND_MEAS
	, UPPER_BOUND_MEAS
	, SEGMENT_NAME
) AS
    /* Version: 1.1
    ** Author:  Stefan Sockel
    ** Date:    2023-01-10
    ** Changes: Added SEGMENT_NAME_DE
    */
SELECT 
	SEG.SEGMENT_SID
	,SEG.SEGMENTATION_SID
	,SEG.SRC_SEGMENT_NR
	,SEG.SEGMENT_NAME
	,SEG.SEGMENT_DESCR
	,SEG.MODEL_SID
	,SEG.MODEL_AREA_CD
	,SEG.MODEL_GROUP_CD
	,SEG.DWH_LOAD_ID
	,SEG.DWH_CREATED
	,SEG.DWH_UPDATED
    ,SEG_H.LOWER_BOUND_MEAS
    ,SEG_H.UPPER_BOUND_MEAS  
	,CAST(CASE
            WHEN SEGMENT_NAME LIKE 'ult%a_slow' THEN 'sehr langsam'
            WHEN SEGMENT_NAME = 'slow' THEN 'langsam'
            WHEN SEGMENT_NAME = 'medium' THEN 'mittel'
            WHEN SEGMENT_NAME = 'fast' THEN 'schnell'
            ELSE 'nicht definiert'
        END AS VARCHAR(100))
FROM "P_LEW_CORE"."T_REF_SEGMENT_2" SEG
JOIN "P_LEW_CORE"."T_REF_SEGMENT_HIST_2" SEG_H
ON (SEG.SEGMENT_SID = SEG_H.SEGMENT_SID)
WHERE SEG.MODEL_SID = 1
AND SEG.SEGMENTATION_SID = 1
AND SEG_H.DELETED_FG = 0
AND CURRENT_DATE BETWEEN SEG_H.DWH_VALID_FROM AND SEG_H.DWH_VALID_TO;