CREATE OR REPLACE VIEW FE_MSTR_TOOLBOX_SPIEGEL.V_MAT_AGG_SPACEMAN_KOP_2
  AS
    WITH SEC_ITM_HGHT AS /* GETTING ACT_HEIGHT on ITEM_2/SECTION/ORIENTATION/MERCH_METHOD/PLACING/METRIC_ID LEVEL */
(
 SELECT DISTINCT 
   SEC.SPACEMAN_SECTION_SID
 , SEC.INT_ORG_SID
 , POSHIST.ITEM_MERCHANDISING_TYPE_CD
 , POSHIST.CASE_ORIENTATION_CD
 , OM.METRIC_SYSTEM_ID
 , SPIT.SPACEMAN_ITEM_SID
 /* PBT PLACING LOGIC IMPLEMENTATION: */
 , CASE
 	WHEN (shelfhist.shelf_width_meas, shelfhist.shelf_depth_meas) IN ((60, 80), (80, 60))
 	THEN 'Palette - DD'
 	
 	WHEN (sec.int_org_sid <> 85 AND (shelfhist.shelf_width_meas, shelfhist.shelf_depth_meas) IN ((120, 80), (shelfhist.shelf_width_meas, 120))) 
 	OR (sec.int_org_sid = 85 AND (shelfhist.shelf_width_meas, shelfhist.shelf_depth_meas) IN ((46, 48)))
 	THEN 'Palette - EP/GMA'
 	
 	WHEN (SEC.INT_ORG_SID <> 85 AND SHELFHIST.SHELF_DEPTH_MEAS <= 62) 
 	OR (SEC.INT_ORG_SID = 85 AND SHELFHIST.SHELF_DEPTH_MEAS <= 24.40945)
 	THEN 'Regal - Mittel_Oberzug'
 	
 	WHEN (SEC.INT_ORG_SID <> 85 AND SHELFHIST.SHELF_DEPTH_MEAS > 62) 
 	OR (SEC.INT_ORG_SID = 85 AND SHELFHIST.SHELF_DEPTH_MEAS > 24.40945)
 	THEN 'Regal - Podest'
 	
 	ELSE '0'
 	END AS PBT_PLACING
 
  /* METRIC KOLLI-HÖHE IN CM (IST), DURCHSCHNITTLICHE KOLLI-HÖHE*/
 , CASE
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 	THEN SPITHIST.CASE_HIGH_MEAS * OM.FACTOR
 	
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand'
 	THEN SPITHIST.ITEM_HIGHT_MEAS * OM.FACTOR
 	
 	ELSE 0
 	END AS ACT_HEIGHT

 FROM P_LEW_CORE_AC.V_SPACEMAN_SECTION_2 SEC
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SECTION_HIST_2 SECHIST
 	ON SEC.SPACEMAN_SECTION_SID = SECHIST.SPACEMAN_SECTION_SID
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SECTION_SHELF_2 SHELF
 	ON SEC.SPACEMAN_SECTION_SID = SHELF.SPACEMAN_SECTION_SID
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SECTION_SHELF_HIST_2 SHELFHIST		
 	ON SHELF.SHELF_SID = SHELFHIST.SHELF_SID
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SHELF_POSITION_2 POS 
 	ON SHELF.SHELF_SID = POS.SHELF_SID
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SHELF_POSITION_HIST_2 POSHIST 
 	ON POS.SHELF_POSITION_SID = POSHIST.SHELF_POSITION_SID
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_ITEM_2 SPIT 
 	ON POSHIST.SPACEMAN_ITEM_SID = SPIT.SPACEMAN_ITEM_SID
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_ITEM_HIST_2 SPITHIST 
 	ON SPIT.SPACEMAN_ITEM_SID = SPITHIST.SPACEMAN_ITEM_SID
 
 INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_SPACEMAN_INT_ORG_MEASUREMENT_2 OM 
 	ON SEC.INT_ORG_SID = OM.INT_ORG_SID
 
 WHERE 
 		CURRENT_DATE BETWEEN SECHIST.DWH_VALID_FROM AND SECHIST.DWH_VALID_TO
 	AND SECHIST.DELETED_FG = 0 
 	AND CURRENT_DATE BETWEEN SHELFHIST.DWH_VALID_FROM AND SHELFHIST.DWH_VALID_TO
 	AND SHELFHIST.DELETED_FG = 0 
 	AND CURRENT_DATE BETWEEN POSHIST.DWH_VALID_FROM AND POSHIST.DWH_VALID_TO
 	AND POSHIST.DELETED_FG = 0 
 	AND CURRENT_DATE BETWEEN SPITHIST.DWH_VALID_FROM AND SPITHIST.DWH_VALID_TO
 	AND SPITHIST.DELETED_FG = 0 
 	AND CURRENT_DATE BETWEEN SPIT.ACTIVE_FROM_DT AND SPIT.ACTIVE_TO_DT
 	AND LOWER(POSHIST.ITEM_MERCHANDISING_TYPE_CD) IN ('case', 'hand')
 )
 
,SEC_ITM_HGHT_AGG AS /* AGGREGATING THE HEIGHT AND ITEM_2 COUNT ON SECTION/ORIENTATION/MERCH_METHOD/PLACING/METRIC_ID LEVEL*/
(
SELECT
   SPACEMAN_SECTION_SID
 , SPACEMAN_ITEM_SID
 , ITEM_MERCHANDISING_TYPE_CD
 , CASE_ORIENTATION_CD
 , PBT_PLACING
 , METRIC_SYSTEM_ID
 , SUM(ACT_HEIGHT) OVER (PARTITION BY SPACEMAN_SECTION_SID, ITEM_MERCHANDISING_TYPE_CD, CASE_ORIENTATION_CD, PBT_PLACING,METRIC_SYSTEM_ID) AS SUM_HEIGHT_LVL
 , COUNT(SPACEMAN_ITEM_SID) OVER (PARTITION BY SPACEMAN_SECTION_SID,ITEM_MERCHANDISING_TYPE_CD, CASE_ORIENTATION_CD, PBT_PLACING,METRIC_SYSTEM_ID) AS CNT_ITEMS_LVL
 
 FROM SEC_ITM_HGHT
)

,ITM_HGHT_AGG AS /* AGGREGATING THE AGGREGATED HEIGHT AND ITEM_2 COUNT ON ITEM_2/ORIENTATION/MERCH_METHOD/PLACING/METRIC_ID LEVEL */
(
 SELECT DISTINCT
   SPACEMAN_ITEM_SID
 , ITEM_MERCHANDISING_TYPE_CD
 , CASE_ORIENTATION_CD
 , PBT_PLACING
 , METRIC_SYSTEM_ID
 , SUM(SUM_HEIGHT_LVL) AS ITM_AGG_HEIGHT
 , SUM(CNT_ITEMS_LVL) AS ITM_AGG_CNT
 , ITM_AGG_HEIGHT/ITM_AGG_CNT AS AVG_HEIGHT

 FROM SEC_ITM_HGHT_AGG

 GROUP BY 
   SPACEMAN_ITEM_SID
 , ITEM_MERCHANDISING_TYPE_CD
 , CASE_ORIENTATION_CD
 , PBT_PLACING
 , METRIC_SYSTEM_ID
)

, MAIN AS
(
 SELECT DISTINCT
   SEC.INT_ORG_SID
 , STORE.CLIENT_ID
 , ITEM.SUBITEMGROUP_ID
 , SPIT.SPACEMAN_ITEM_SID
 , POSHIST.ITEM_MERCHANDISING_TYPE_CD
 , OM.METRIC_SYSTEM_ID
 , SPITHIST.SRC_CASE_SIZE
 , POSHIST.CASE_ORIENTATION_CD
 , TO_NUMBER('0.05',3,2) AS KOLLI_DEVIATION_PERCENT /*DEVIATION PERCENTAGE FOR TARGET_KOLLI_BREITE AND TARGET_KOLLI_TIEFE = 5%*/
 
   /* PBT PLACING LOGIC: */
 , CASE
   WHEN (shelfhist.shelf_width_meas, shelfhist.shelf_depth_meas) IN ((60, 80), (80, 60))
   THEN 'Palette - DD'
   
   WHEN (sec.int_org_sid <> 85 AND (shelfhist.shelf_width_meas, shelfhist.shelf_depth_meas) IN ((120, 80), (133, 80), (shelfhist.shelf_width_meas, 120))) 
     OR (sec.int_org_sid = 85 AND (shelfhist.shelf_width_meas, shelfhist.shelf_depth_meas) IN ((46, 48)))
   THEN 'Palette - EP/GMA'
 
   WHEN (SEC.INT_ORG_SID <> 85 AND SHELFHIST.SHELF_DEPTH_MEAS <= 62) 
 	OR (SEC.INT_ORG_SID = 85 AND SHELFHIST.SHELF_DEPTH_MEAS <= 24.40945)
   THEN 'Regal - Mittel_Oberzug'
   
   WHEN (SEC.INT_ORG_SID <> 85 AND SHELFHIST.SHELF_DEPTH_MEAS > 62) 
 	OR (SEC.INT_ORG_SID = 85 AND SHELFHIST.SHELF_DEPTH_MEAS > 24.40945)
   THEN 'Regal - Podest'
   
   ELSE '0'
   END AS PBT_PLACING
   
   /*COUNT STORES*/
 , COUNT(DISTINCT(STORE.MOVE_TO_STORE_ID)) 
   OVER (PARTITION BY SEC.INT_ORG_SID, STORE.CLIENT_ID, ITEM.SUBITEMGROUP_ID, SPIT.SPACEMAN_ITEM_SID, POSHIST.ITEM_MERCHANDISING_TYPE_CD, OM.METRIC_SYSTEM_ID, SPITHIST.SRC_CASE_SIZE, POSHIST.CASE_ORIENTATION_CD,PBT_PLACING)
   AS CNT_STORE
   
   /*METRIC KOLLI_BREITE IN CM (IST)*/
 , CASE 
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('front end','end front') 	THEN SPITHIST.CASE_WIDTH_MEAS * OM.FACTOR
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('side end','end side') 		THEN SPITHIST.CASE_DEPTH_MEAS * OM.FACTOR
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('front end','end front') 	THEN SPITHIST.ITEM_WIDTH_MEAS * OM.FACTOR 
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('side end','end side') 		THEN SPITHIST.ITEM_DEPTH_MEAS * OM.FACTOR 
 	ELSE 0
 	END AS KOLLI_BREITE
 
   /*METRIC KOLLI_BREITE IN CM (SOLL) BZW. ABWEICHUNG*/
 , CASE 
   WHEN(
 	    (SEC.INT_ORG_SID <> 85 
 		 AND POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 	     AND (KOLLI_BREITE BETWEEN 10-10*KOLLI_DEVIATION_PERCENT AND 10+10*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 15-15*KOLLI_DEVIATION_PERCENT AND 15+15*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 20-20*KOLLI_DEVIATION_PERCENT AND 20+20*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 30-30*KOLLI_DEVIATION_PERCENT AND 30+30*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 40-40*KOLLI_DEVIATION_PERCENT AND 40+40*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 60-60*KOLLI_DEVIATION_PERCENT AND 60+60*KOLLI_DEVIATION_PERCENT
 			 )
 	    )
 	    OR
 	    (SEC.INT_ORG_SID = 85
 		 AND POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 	     AND (KOLLI_BREITE BETWEEN 3.93701-3.93701*KOLLI_DEVIATION_PERCENT AND 3.93701+3.93701*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 5.90551-5.90551*KOLLI_DEVIATION_PERCENT AND 5.90551+5.90551*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 7.87402-7.87402*KOLLI_DEVIATION_PERCENT AND 7.87402+7.87402*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 11.811-11.811*KOLLI_DEVIATION_PERCENT AND 11.811+11.811*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 15.748-15.748*KOLLI_DEVIATION_PERCENT AND 15.748+15.748*KOLLI_DEVIATION_PERCENT
 			  OR
 			  KOLLI_BREITE BETWEEN 23.622-23.622*KOLLI_DEVIATION_PERCENT AND 23.622+23.622*KOLLI_DEVIATION_PERCENT
 			 )
 	    )
 	  )
 	  OR 
 	   (POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand')
   THEN 1
   ELSE 0
   END AS TARGET_KOLLI_BREITE
 
 	
   /*METRIC KOLLI_TIEFE IN CM (IST)*/
 , CASE 
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('front end','end front') 	THEN SPITHIST.CASE_DEPTH_MEAS * OM.FACTOR
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('side end','end side') 		THEN SPITHIST.CASE_WIDTH_MEAS * OM.FACTOR
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('front end','end front') 	THEN SPITHIST.ITEM_DEPTH_MEAS * OM.FACTOR
 	WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand' AND LOWER(POSHIST.CASE_ORIENTATION_CD) IN ('side end','end side') 		THEN SPITHIST.ITEM_WIDTH_MEAS * OM.FACTOR 
 	ELSE 0
 	END AS KOLLI_TIEFE
 
 
   /*METRIC KOLLI_TIEFE IN CM (SOLL) BZW. ABWEICHUNG*/
 , CASE 
   WHEN 
 	  (    (SEC.INT_ORG_SID <> 85 
 			AND POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 			AND PBT_PLACING = 'Regal - Mittel_Oberzug' 
 			AND (KOLLI_TIEFE BETWEEN 20-20*KOLLI_DEVIATION_PERCENT AND 20
 				 OR
 				 KOLLI_TIEFE BETWEEN 30-30*KOLLI_DEVIATION_PERCENT AND 30)
 		   )
 		   OR
 	       (SEC.INT_ORG_SID = 85
 			AND POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 			AND PBT_PLACING = 'Regal - Mittel_Oberzug' 
 			AND (KOLLI_TIEFE BETWEEN 7.87402-7.87402*KOLLI_DEVIATION_PERCENT AND 7.87402
 				 OR
 				 KOLLI_TIEFE BETWEEN 11.811-11.811*KOLLI_DEVIATION_PERCENT AND 11.811)
 		   )
 	  )
 	OR
 	  (    (SEC.INT_ORG_SID <> 85
 			AND POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 			AND PBT_PLACING = 'Regal - Podest' 
 			AND KOLLI_TIEFE BETWEEN 40-40*KOLLI_DEVIATION_PERCENT AND 40
 			)
 		   OR
 	       (SEC.INT_ORG_SID = 85
 			AND POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
 			AND PBT_PLACING = 'Regal - Podest'
 			AND KOLLI_TIEFE BETWEEN 15.748-15.748*KOLLI_DEVIATION_PERCENT AND 15.748
 		   )
 	  )
 	OR
 	  (POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand')
   THEN 1
   ELSE 0
   END AS TARGET_KOLLI_TIEFE
 
     /* METRIC KOLLI-HÖHE IN CM (IST), DURCHSCHNITTLICHE KOLLI-HÖHE*/
   , CASE
     WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Case'
     THEN SPITHIST.CASE_HIGH_MEAS * OM.FACTOR
     
     WHEN POSHIST.ITEM_MERCHANDISING_TYPE_CD = 'Hand'
     THEN SPITHIST.ITEM_HIGHT_MEAS * OM.FACTOR
     
     ELSE NULL
     END AS ACT_HEIGHT
 
   /* METRIC KOLLI-GEWICHT */
 , SPITHIST.CASE_WEIGHT_KG_QTY * OM.FACTOR_WEIGHT AS CASE_WEIGHT_KG_QTY
 
   /* HOW CAN THE ARTICLE BE PLACED (SIDE END VS. FRONT END) */
 , SPITHIST.CASE_ORIENTATION_FRONT_END_FG
 , SPITHIST.CASE_ORIENTATION_SIDE_END_FG
 
   /* METRIC PRODUKTANSICHT AKTUELL*/
 , SPITHIST.CASE_ITEM_ORIENTATION_TXT
 
  /* METRIC Show the ID of shelves on which the article is placed and has CASES = 1*/
 , CASE WHEN POSHIST.TOTAL_CASE_QTY = 1
 	THEN LISTAGG(DISTINCT SHELF.SRC_SECTION_NR, ', ') OVER (PARTITION BY SPIT.SPACEMAN_ITEM_SID,POSHIST.TOTAL_CASE_QTY)
 	ELSE NULL
 	END AS SHELF_ID_QTY
 
   /* METRIC amount shelves on which the article is placed and has CASES = 1*/
 , CASE WHEN POSHIST.TOTAL_CASE_QTY = 1
 	THEN COUNT(DISTINCT(SHELF.SRC_SECTION_NR)) OVER (PARTITION BY SPIT.SPACEMAN_ITEM_SID,POSHIST.TOTAL_CASE_QTY)
 	ELSE NULL
 	END AS SHELF_ID_AMNT
 
 FROM P_LEW_CORE_AC.V_SPACEMAN_SECTION_2 SEC
 
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SECTION_HIST_2 SECHIST
 ON SEC.SPACEMAN_SECTION_SID = SECHIST.SPACEMAN_SECTION_SID
 	
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SECTION_SHELF_2 SHELF
 	ON SEC.SPACEMAN_SECTION_SID = SHELF.SPACEMAN_SECTION_SID
 	
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SECTION_SHELF_HIST_2 SHELFHIST		
 	ON SHELF.SHELF_SID = SHELFHIST.SHELF_SID
 	
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SHELF_POSITION_2 POS 
 	ON SHELF.SHELF_SID = POS.SHELF_SID
 	
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_SHELF_POSITION_HIST_2 POSHIST 
 	ON POS.SHELF_POSITION_SID = POSHIST.SHELF_POSITION_SID
 	
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_ITEM_2 SPIT 
 	ON POSHIST.SPACEMAN_ITEM_SID = SPIT.SPACEMAN_ITEM_SID
 
 INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_ITEM_SPACEMAN_ITEM_2 ISI
     ON ISI.SPACEMAN_ITEM_SID = SPIT.SPACEMAN_ITEM_SID
     
 INNER JOIN P_LEW_MART_LEAD_AC.V_ITM_ITEM_2 ITEM_2
     ON ISI.CLIENT_ID = ITEM.CLIENT_ID
 	AND ISI.ITEM_SID = ITEM.ITEM_ID
 	
 INNER JOIN P_LEW_CORE_AC.V_SPACEMAN_ITEM_HIST_2 SPITHIST 
 	ON SPIT.SPACEMAN_ITEM_SID = SPITHIST.SPACEMAN_ITEM_SID
 
 /* CLIENT_ID/STORE */    
 INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_SPACEMAN_SECTION_STORE_2 SECSTORE
    ON SEC.SPACEMAN_SECTION_SID = SECSTORE.SPACEMAN_SECTION_SID
    
 INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_ORG_STORE_MERGE_VGES_2 STORE
    ON SECSTORE.LOC_SID_STORE = STORE.STORE_ID
    
 INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_SPACEMAN_SECTION_STORE_AISLE_2 SSA
    ON SECSTORE.SPACEMAN_SECTION_SID = SSA.SPACEMAN_SECTION_SID 
    AND STORE.MOVE_TO_STORE_ID = SSA.MOVE_TO_STORE_ID
    
 /* CM/IN */
 INNER JOIN FE_MSTR_TOOLBOX_SPIEGEL.V_SPACEMAN_INT_ORG_MEASUREMENT_2 OM 
 	ON SEC.INT_ORG_SID = OM.INT_ORG_SID
     
 WHERE 
 	 CURRENT_DATE BETWEEN SECHIST.DWH_VALID_FROM AND SECHIST.DWH_VALID_TO
  AND SECHIST.DELETED_FG = 0 
  AND CURRENT_DATE BETWEEN SHELFHIST.DWH_VALID_FROM AND SHELFHIST.DWH_VALID_TO
  AND SHELFHIST.DELETED_FG = 0 
  AND CURRENT_DATE BETWEEN POSHIST.DWH_VALID_FROM AND POSHIST.DWH_VALID_TO
  AND POSHIST.DELETED_FG = 0 
  AND CURRENT_DATE BETWEEN SPITHIST.DWH_VALID_FROM AND SPITHIST.DWH_VALID_TO
  AND SPITHIST.DELETED_FG = 0 
  AND CURRENT_DATE BETWEEN SPIT.ACTIVE_FROM_DT AND SPIT.ACTIVE_TO_DT
  AND LOWER(POSHIST.ITEM_MERCHANDISING_TYPE_CD) IN ('case', 'hand')

)

SELECT
   M.INT_ORG_SID
 , M.CLIENT_ID
 , M.SUBITEMGROUP_ID
 , M.SPACEMAN_ITEM_SID
 , M.ITEM_MERCHANDISING_TYPE_CD
 , M.METRIC_SYSTEM_ID
 , M.SRC_CASE_SIZE
 , M.CASE_ORIENTATION_CD
 , M.KOLLI_DEVIATION_PERCENT
 , M.PBT_PLACING
 , M.CNT_STORE
 , M.KOLLI_BREITE
 , M.TARGET_KOLLI_BREITE
 , M.KOLLI_TIEFE
 , M.TARGET_KOLLI_TIEFE
 , M.ACT_HEIGHT
 , IHA.ITM_AGG_HEIGHT
 , IHA.ITM_AGG_CNT
 , IHA.AVG_HEIGHT
 , M.CASE_WEIGHT_KG_QTY
 , M.CASE_ORIENTATION_FRONT_END_FG
 , M.CASE_ORIENTATION_SIDE_END_FG
 , M.CASE_ITEM_ORIENTATION_TXT
 , M.SHELF_ID_QTY
 , M.SHELF_ID_AMNT

 FROM MAIN M
 
 INNER JOIN ITM_HGHT_AGG IHA
 ON  M.SPACEMAN_ITEM_SID           = IHA.SPACEMAN_ITEM_SID
 AND M.ITEM_MERCHANDISING_TYPE_CD  = IHA.ITEM_MERCHANDISING_TYPE_CD
 AND M.CASE_ORIENTATION_CD         = IHA.CASE_ORIENTATION_CD 
 AND M.PBT_PLACING                 = IHA.PBT_PLACING
 AND M.METRIC_SYSTEM_ID            = IHA.METRIC_SYSTEM_ID;
