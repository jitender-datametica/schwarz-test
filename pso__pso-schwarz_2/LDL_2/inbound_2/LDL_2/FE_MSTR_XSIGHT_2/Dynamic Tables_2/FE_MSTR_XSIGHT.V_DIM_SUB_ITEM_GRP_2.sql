CREATE
	OR REPLACE DYNAMIC TABLE FE_MSTR_XSIGHT.V_DIM_SUB_ITEM_GRP_2 (
	SUB_ITEM_GRP_CD
    ,SUB_ITEM_GRP_NAME
    ,SUB_ITEM_GRP_NAME_EN
	,SUB_ITEM_GRP_NAME2
	,SUB_ITEM_GRP_NAME2_EN
	) TARGET_LAG = '90 MINUTES' REFRESH_MODE = AUTO INITIALIZE = ON_CREATE WAREHOUSE = WH_LDL_%%environmentAbbreviation%%_DYNAMIC_TABLE_XSIGHT CLUSTER BY (
	SUB_ITEM_GRP_CD
	) AS


SELECT DISTINCT COALESCE(SUB_ITEM_GRP_CD,'-1') AS SUB_ITEM_GRP_CD
    ,MAX(SUB_ITEM_GRP_NAME_DE) AS SUB_ITEM_GRP_NAME
    ,MAX(SUB_ITEM_GRP_NAME_EN) AS SUB_ITEM_GRP_NAME_EN
	,MAX((SUB_ITEM_GRP_CD ||' '|| SUB_ITEM_GRP_NAME_DE)) AS SUB_ITEM_GRP_NAME2
    ,MAX((SUB_ITEM_GRP_CD ||' '||SUB_ITEM_GRP_NAME_EN)) AS SUB_ITEM_GRP_NAME2_EN
FROM P_LEW_CORE_AC.V_MARKET_RESEARCH_PRODUCT_2
GROUP BY
SUB_ITEM_GRP_CD;