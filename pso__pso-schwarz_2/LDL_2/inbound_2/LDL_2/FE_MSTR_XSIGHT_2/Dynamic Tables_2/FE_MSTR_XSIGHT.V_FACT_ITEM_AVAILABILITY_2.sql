CREATE
	OR REPLACE DYNAMIC TABLE FE_MSTR_XSIGHT.V_FACT_ITEM_AVAILABILITY_2 (
	BRAND_NAME
	,HIERARCHY_LVL_1
	,HIERARCHY_LVL_2
	,HIERARCHY_LVL_3
	,HIERARCHY_LVL_4
	,HIERARCHY_LVL_5
	,MANUFACTURER_NAME
	,ITEM_FAM_GRP_CD
	,ITEM_GRP_INT_CD
	,SUB_BRAND_NAME
	,SUB_ITEM_GRP_CD
	,PERIOD_SID
	,PERIOD_NAME
	,PERIOD_TYPE_CD
	,DATA_SRC_SEGMENT_NAME
	,DATA_SRC_SEGMENT_DESCR
	,COUNTRY_CD
	,COUNTRY_NAME
	) TARGET_LAG = '90 MINUTES' REFRESH_MODE = AUTO INITIALIZE = ON_CREATE WAREHOUSE = WH_LDL_%%environmentAbbreviation%%_DYNAMIC_TABLE_XSIGHT CLUSTER BY (
	DATA_SRC_SEGMENT_NAME
	,HIERARCHY_LVL_1
	,PERIOD_SID
	) AS

SELECT DISTINCT COALESCE(A12.BRAND_NAME, 'N/A') AS BRAND_NAME
	,COALESCE(A12.HIERARCHY_LVL_1, 'N/A') AS HIERARCHY_LVL_1
	,COALESCE(A12.HIERARCHY_LVL_2, 'N/A') AS HIERARCHY_LVL_2
	,COALESCE(A12.HIERARCHY_LVL_3, 'N/A') AS HIERARCHY_LVL_3
	,COALESCE(A12.HIERARCHY_LVL_4, 'N/A') AS HIERARCHY_LVL_4
	,COALESCE(A12.HIERARCHY_LVL_5, 'N/A') AS HIERARCHY_LVL_5
	,COALESCE(A12.MANUFACTURER_NAME, 'N/A') AS MANUFACTURER_NAME
	,COALESCE(A12.ITEM_FAM_GRP_CD, '-1') AS ITEM_FAM_GRP_CD
	,COALESCE(A12.ITEM_GRP_INT_CD, '-1') AS ITEM_GRP_INT_CD
	,COALESCE(A12.SUB_BRAND_NAME, 'N/A') AS SUB_BRAND_NAME
	,COALESCE(A12.SUB_ITEM_GRP_CD, '-1') AS SUB_ITEM_GRP_CD
	,A13.PERIOD_SID
	,A13.PERIOD_NAME
	,A13.PERIOD_TYPE_CD
	,A12.DATA_SRC_SEGMENT_NAME
	,A14.DATA_SRC_SEGMENT_DESCR
	,A12.COUNTRY_CD
	,A15.COUNTRY_NAME
FROM FE_MSTR_XSIGHT.T_FACT_RESEARCH_METRIC_2 A11
JOIN FE_MSTR_XSIGHT.V_DIM_PRODUCT_2 A12 ON (A11.PROD_SID = A12.PROD_SID)
JOIN FE_MSTR_XSIGHT.V_DIM_PERIOD_2 A13 ON (A11.CY_BUSINESS_PERIOD_SID = A13.PERIOD_SID)
JOIN FE_MSTR_XSIGHT.V_DIM_DATA_SOURCE_SEGMENT_2 A14 ON (A12.DATA_SRC_SEGMENT_NAME = A14.DATA_SRC_SEGMENT_NAME
	AND A12.COUNTRY_CD = A14.COUNTRY_CD
	AND A12.DATA_SRC_NAME = A14.DATA_SRC_NAME
	AND A12.DATA_PROVIDER_NAME = A14.DATA_PROVIDER_NAME)
JOIN FE_MSTR_XSIGHT.V_DIM_COUNTRY_2 A15 ON (A12.COUNTRY_CD = A15.COUNTRY_CD)
/*JOIN FE_MSTR_XSIGHT.V_DIM_BENCHMARK_CHANNEL_2 A16 ON (A11.COUNTRY_CD = A16.COUNTRY_CD 
 	AND A11.CHANNEL_SID = A16.CHANNEL_SID 
 	AND A11.DATA_SRC_SEGMENT_NAME = A16.DATA_SRC_SEGMENT_NAME)*/
WHERE HIERARCHY_LVL_1 IS NOT NULL
	AND HIERARCHY_LEVEL_0 = 'ITEM_2 CODE';