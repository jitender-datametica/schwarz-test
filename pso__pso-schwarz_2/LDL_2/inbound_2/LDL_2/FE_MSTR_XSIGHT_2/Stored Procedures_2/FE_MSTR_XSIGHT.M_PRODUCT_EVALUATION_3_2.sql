CREATE OR REPLACE PROCEDURE FE_MSTR_XSIGHT.M_PRODUCT_EVALUATION_3("MARKET_RESEARCH_PROD_SID" NUMBER(38,0), "IM_SORTIMENT_MARKE" NUMBER(38,0), "IM_SORTIMENT_EM" NUMBER(38,0), "REGIONAL_SAISONAL" NUMBER(38,0), "ANDERE_VERPACKUNGSGR_M_EM" NUMBER(38,0), "AKTIONSARTIKEL_IN_OUT" NUMBER(38,0), "VORSCHLAG_NIS_MARKE" NUMBER(38,0), "VORSCHLAG_NIS_EIGENMARKE" NUMBER(38,0), "VORSCHLAG_NIS_AKTION_IN_OUT" NUMBER(38,0), "VORSCHLAG_NIS_AKTION_PV" NUMBER(38,0), "NICHT_ERHAELTLICH" NUMBER(38,0))
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN

IF  (NOT EXISTS (
			SELECT *
			FROM FE_MSTR_XSIGHT.T_FACT_PRODUCT_EVALUATION_2
			WHERE MARKET_RESEARCH_PROD_SID = :MARKET_RESEARCH_PROD_SID
			)
		) THEN
BEGIN
    INSERT INTO FE_MSTR_XSIGHT.T_FACT_PRODUCT_EVALUATION_2
        (SELECT
		:MARKET_RESEARCH_PROD_SID,
        :IM_SORTIMENT_MARKE,
        :IM_SORTIMENT_EM,
        :REGIONAL_SAISONAL,
        :ANDERE_VERPACKUNGSGR_M_EM,
        :AKTIONSARTIKEL_IN_OUT,
        :VORSCHLAG_NIS_MARKE,
        :VORSCHLAG_NIS_EIGENMARKE,
        :VORSCHLAG_NIS_AKTION_IN_OUT,
        :VORSCHLAG_NIS_AKTION_PV,
        :NICHT_ERHAELTLICH);
       END;
ELSE 
        BEGIN
        UPDATE FE_MSTR_XSIGHT.T_FACT_PRODUCT_EVALUATION_2
        SET
        AKTIONSARTIKEL_IN_OUT=:AKTIONSARTIKEL_IN_OUT,
        ANDERE_VERPACKUNGSGR_M_EM=:ANDERE_VERPACKUNGSGR_M_EM,
        IM_SORTIMENT_EM=:IM_SORTIMENT_EM,
        IM_SORTIMENT_MARKE=:IM_SORTIMENT_MARKE ,
        NICHT_ERHAELTLICH=:NICHT_ERHAELTLICH ,
        REGIONAL_SAISONAL=:REGIONAL_SAISONAL,
        VORSCHLAG_NIS_AKTION_IN_OUT=:VORSCHLAG_NIS_AKTION_IN_OUT,
        VORSCHLAG_NIS_AKTION_PV=:VORSCHLAG_NIS_AKTION_PV,
        VORSCHLAG_NIS_MARKE=:VORSCHLAG_NIS_MARKE ,
        VORSCHLAG_NIS_EIGENMARKE=:VORSCHLAG_NIS_EIGENMARKE		
		WHERE 
        MARKET_RESEARCH_PROD_SID=:MARKET_RESEARCH_PROD_SID;
        END;
    END
IF ;
	COMMIT;
	END';