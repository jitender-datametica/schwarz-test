CREATE
	OR REPLACE VIEW FE_MSTR_XSIGHT.V_TECH_STEERING_KPI_RANKING_2 (
	DASHBOARD
	,GROUP_ID
	,GROUP_NAME
	,KPI_RANK_ID
	,KPI_RANK_NAME
	,KPI_RANK_NAME_EN
	,TECH_DESC1
	,TECH_DESC2
	,KPI_DESC
	,TECH_DESC1_EN
	,KPI_DESC_EN
	) AS

SELECT DISTINCT DASHBOARD
	,GROUP_ID
	,GROUP_NAME
	,KPI_ID
	,KPI_NAME
	,KPI_NAME_EN
	,SUBSTR(KPI_NAME, 7, LEN(KPI_NAME) - 3) AS TECH_DESC1
	,SUBSTR(TECH_DESC1, 1, LEN(TECH_DESC1) - 1) TECH_DESC2
	,COALESCE(KPI_DESC, TECH_DESC2) AS KPI_DESC
	,SUBSTR(KPI_NAME_EN, 7, LEN(KPI_NAME_EN) - 3) AS TECH_DESC1_EN
	,SUBSTR(TECH_DESC1_EN, 1, LEN(TECH_DESC1_EN) - 1) AS KPI_DESC_EN
FROM FE_MSTR_XSIGHT.T_TECH_STEERING_KPI_2
WHERE DASHBOARD IN (
		'Item_2 Ranking - Ranking'
		,'Feature Analysis - Rank');