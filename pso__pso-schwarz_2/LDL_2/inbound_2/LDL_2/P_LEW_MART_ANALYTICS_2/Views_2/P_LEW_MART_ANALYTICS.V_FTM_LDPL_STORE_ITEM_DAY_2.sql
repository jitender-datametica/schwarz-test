create or replace view LDL_PRODUCTION_CLONE_GOOGLE_20260608_1030.P_LEW_MART_ANALYTICS.V_FTM_LDPL_STORE_ITEM_DAY_2(
	CLIENT_ID,
	COUNTRY_CODE,
	DAT_FORMDATE,
	CY_WEEK,
	STORE_ID,
	ORIG_STORE_NR,
	ITEM_ID,
	ORIG_ITEM_NR,
	ITEMGROUP_INT_ID,
	SUBITEMGROUP_ID,
	ITEM_TYPE,
	TOTAL_NET_VAL
) as

SELECT    A12.CLIENT_ID AS CLIENT_ID
        , A12.COUNTRY_ISO_CD AS COUNTRY_CODE
        , A11.DWH_CAL_DT AS DAT_FORMDATE
        , A11.CY_WEEK
        , A11.LOC_SID AS STORE_ID
		, A12.ORIG_STORE_NR
		, A13.ITEM_ID
		, A13.ORIG_ITEM_NR
		, A14.ITEMGROUP_INT_ID
		, A13.SUBITEMGROUP_ID
		, CASE WHEN A13.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
		, SUM(A11.TOTAL_NET_VAL) TOTAL_NET_VAL
FROM P_LEW_MART_LIDL_DIGITAL.V_AGG_CLIENT_STORE_ITEM_LDPL_DAY_2	A11
   JOIN	P_LEW_MART_MSI.V_ORG_ALL_STORE_MERGE_2	A12
	  ON (A11.ASPECT_ID = A12.ASPECT_ID 
      AND A11.CLIENT_ID = A12.CLIENT_ID 
      AND A11.MOVE_TO_STORE_ID = A12.MOVE_TO_STORE_ID)
   JOIN	P_LEW_MART_LEAD.V_ITM_ITEM_2	A13
	  ON (A11.CLIENT_ID = A13.CLIENT_ID 
      AND A11.ITEM_SID = A13.ITEM_ID 
      AND A12.CLIENT_ID = A13.CLIENT_ID)
    JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_2 AS A14
        ON A14.SUBITEMGROUP_ID = A13.SUBITEMGROUP_ID 
WHERE A11.LIDLPLUS_CUST_FG = 'Y' 
 AND (A11.CURR_TOT_ID = 0 AND A11.CURRENCY_ISO_CD = 'EUR') 
 AND A12.ASPECT_ID IN (2)
 GROUP BY   A12.CLIENT_ID
          , A12.COUNTRY_ISO_CD
          , A11.DWH_CAL_DT
          , A11.CY_WEEK
          , A11.LOC_SID
		  , A12.ORIG_STORE_NR
		  , A13.ITEM_ID
		  , A13.ORIG_ITEM_NR
		  , A14.ITEMGROUP_INT_ID
		  , A13.SUBITEMGROUP_ID
		  , CASE WHEN A13.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END
;
