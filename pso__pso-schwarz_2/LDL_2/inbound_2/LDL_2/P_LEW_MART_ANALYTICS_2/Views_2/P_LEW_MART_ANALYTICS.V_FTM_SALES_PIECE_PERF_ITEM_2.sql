create or replace view LDL_PRODUCTION_CLONE_GOOGLE_20260608_1030.P_LEW_MART_ANALYTICS.V_FTM_SALES_PIECE_PERF_ITEM_2(
	CLIENT_ID,
	COUNTRY_CODE,
	DAT_FORMDATE,
	CY_WEEK,
	STORE_ID,
	ORIG_STORE_NR,
	ITEM_ID,
	ORIG_ITEM_NR,
	ITEMGROUP_INT_ID,
	SUBITEMGROUP_ID,
	ITEM_TYPE,
	SALES_PIECES,
	SALES_PIECES_TOTAL
) as
SELECT 
    SDPP.CLIENT_ID
    , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
    , SDPP.dwh_cal_dt DAT_FORMDATE
    , TAG.CY_WEEK AS CY_WEEK
    , SDPP.loc_sid_store AS STORE_ID
    , SDPP.src_orig_store_nr AS ORIG_STORE_NR
    , ITmp.item_sid_map AS ITEM_ID
    , ART_INFO.ORIG_ITEM_NR
    , UWG_INFO.ITEMGROUP_INT_ID
    , ART_INFO.SUBITEMGROUP_ID
    , CASE WHEN ART_INFO.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
    , SDPP.SALES_PIECES
    , SDPP.SALES_PIECES_TOTAL
FROM P_LEW_BIL_AC.V_AGG_STORE_DAY_PIECE_PERF_ITEM_2 AS SDPP

INNER JOIN p_lew_core_ac.v_item_map_key_2 AS ITmp
 ON  ITmp.client_id = SDPP.client_id
 AND ITmp.item_sid  = SDPP.item_sid

INNER JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_2 AS ART_INFO
    ON ART_INFO.CLIENT_ID = ITmp.CLIENT_ID
    AND ART_INFO.ITEM_ID = ITmp.item_sid_map
    
INNER JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_2 AS UWG_INFO
    ON UWG_INFO.SUBITEMGROUP_ID = ART_INFO.SUBITEMGROUP_ID 
    
INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY_2 AS TAG_2
    ON TAG.DAT_CALENDAR = SDPP.dwh_cal_dt

INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY_2 AS RCTRY
    ON SDPP.CLIENT_ID = RCTRY.COUNTRY_ID
   
WHERE SDPP.currency_iso_cd = 'EUR'
;
