CREATE OR REPLACE VIEW P_LEW_MART_ANALYTICS.V_MAT_FTM_TURNOVER_WEEKLY_2(
	CLIENT_ID
	, COUNTRY_CODE
	, DAT_FORMDATE
	, CY_WEEK
	, STORE_ID
	, ORIG_STORE_NR
	, ITEM_ID
	, ORIG_ITEM_NR
	, ITEMGROUP_INT_ID
	, SUBITEMGROUP_ID
	, ITEM_TYPE
	, SALES_NET_VAL
	, SALES_PIECES_EJR
	, BUYING_VAL
	, SALES_BASED_MARGIN
	, SALES_BASED_MARGIN_PCT
) AS
/*
#----------------------------------------------------------------------------
# 22-08-2024 SNIK1809 - NEW setup
# 09-01-2025 SNIK1809 - Updated Buying with LDL_PRODUCTION.P_LEW_MART_LEAD.T_ITM_ORIG_ITEM_2
# 07-02-2025 SNIK1809 - Separate weekly from normal view
#----------------------------------------------------------------------------
*/

WITH A_SALES AS(
    SELECT
      A.CLIENT_ID
    , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
    , A.DAT_FORMDATE
    , TAG.CY_WEEK
    , A.STORE_ID
    , A.ORIG_STORE_NR
    , A.ITEM_ID
    , ART_INFO.ORIG_ITEM_NR
    , UWG_INFO.ITEMGROUP_INT_ID
    , ART_INFO.SUBITEMGROUP_ID
    , CASE WHEN ART_INFO.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
    , A.VAL_RTL_NET_EJR_ASIS + A.VAL_RETURN_NET_EJR_ASIS AS SALES_NET_VAL
    , A.QTY_PIECE_EJR_ASIS + A.QTY_WEIGHT_EJR_ASIS + A.QTY_RETURN_EJR_ASIS AS SALES_PIECES_EJR
    , '0' AS BUYING_VAL
    , '0' AS SALES_BASED_MARGIN
    , '0' AS SALES_BASED_MARGIN_PCT

    FROM P_LEW_MART_LEAD.V_AGG_STORE_DAY_ITEM_EJR_ASIS_2 A
    
    INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY_2 AS RCTRY
        ON A.CLIENT_ID = RCTRY.COUNTRY_ID
    
    INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY_2 AS TAG_2
        ON TAG.DAT_CALENDAR = A.DAT_FORMDATE
    	
    INNER JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_2 AS ART_INFO
        ON ART_INFO.CLIENT_ID = A.CLIENT_ID
        AND ART_INFO.ITEM_ID = A.ITEM_ID
        AND ART_INFO.DAT_VALID_FROM <= A.DAT_FORMDATE
        
    INNER JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_2 AS UWG_INFO
        ON UWG_INFO.SUBITEMGROUP_ID = ART_INFO.SUBITEMGROUP_ID 

        INNER JOIN P_LEW_MART_MSI_AC.V_ORG_STORE_SKEY_2 AS FIL
        ON FIL.CLIENT_ID = A.CLIENT_ID
        AND FIL.STORE_ID = A.STORE_ID
        
    WHERE A.CURRENCY_ISO_CD = 'EUR' AND (A.DAT_FORMDATE >= TO_CHAR((DATE_TRUNC('WEEK', CURRENT_DATE)-70),'YYYY-MM_2-DD'))
)

, B_BUYING AS (
    SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN/ SALES_NET_VAL_B AS SALES_BASED_MARGIN_PCT
    
    FROM (
        SELECT
          A.CLIENT_ID
        , RCTRY.COUNTRY_ISO_CD AS COUNTRY_CODE
        , A.DWH_CAL_DT AS DAT_FORMDATE
        , TAG.CY_WEEK
        , ST_LOC_SID AS STORE_ID
        , FIL.ORIG_STORE_NR
	    , ART_INFO2.ITEM_ID
        , A.ORIG_ITEM_NR
        , UWG_INFO.ITEMGROUP_INT_ID
        , ART_INFO.SUBITEMGROUP_ID
        , CASE WHEN ART_INFO2.BUYING_LIST_TYPE_ID IN (7,8) THEN 'AKTIONSARTIKEL' ELSE 'SORTIMENT' END AS ITEM_TYPE
        , FIL.WH_ID
        , '0' AS SALES_NET_VAl
        , '0' AS SALES_PIECES_EJR 
        , COUNT(ART_INFO2.ITEM_ID) OVER (PARTITION BY A.CLIENT_ID,A.ORIG_ITEM_NR,A.DWH_CAL_DT,A.ST_LOC_SID) AS CNT_ITM
        , A.SALES_BUYING_DIFF AS BUYING_VAL
       , A.SALES_NET_VAL/CNT_ITM AS SALES_NET_VAL_B
       , A.SALES_BUYING_DIFF/CNT_ITM AS SALES_BASED_MARGIN
       , A.SALES_BUYING_DIFF*CNT_ITM/A.SALES_NET_VAL AS SALES_BASED_MARGIN_PCT

        FROM P_LEW_MART_LEAD.V_AGG_AVG_BUY_PRICE_STR_DAY_ITM_2 A
        
        INNER JOIN P_LEW_MART_MSI_AC.V_REF_COUNTRY_2 AS RCTRY
            ON A.CLIENT_ID = RCTRY.COUNTRY_ID
        
        INNER JOIN P_LEW_MART_MSI_AC.V_CAL_CALENDARDAY_2 AS TAG_2
            ON TAG.DAT_CALENDAR = A.DWH_CAL_DT
        
        INNER JOIN P_LEW_MART_MSI_AC.V_ORG_STORE_SKEY_2 AS FIL
            ON FIL.CLIENT_ID = A.CLIENT_ID
            AND FIL.STORE_ID = A.ST_LOC_SID
            
        INNER JOIN P_LEW_MART_LEAD.T_ITM_ORIG_ITEM_2 AS ART_INFO
            ON ART_INFO.CLIENT_ID = A.CLIENT_ID
            AND ART_INFO.ORIG_ITEM_NR = A.ORIG_ITEM_NR
            AND ART_INFO.DAT_VALID_FROM = A.DAT_VALID_FROM
            
        INNER JOIN P_LEW_MART_MSI_AC.V_ITM_ITEM_2 AS ART_INFO2
            ON ART_INFO.CLIENT_ID = ART_INFO2.CLIENT_ID
            AND ART_INFO.ORIG_ITEM_NR  = ART_INFO2.ORIG_ITEM_NR            
           
        INNER JOIN P_LEW_MART_MSI_AC.V_ITM_SUBITEMGROUP_2 AS UWG_INFO
            ON UWG_INFO.SUBITEMGROUP_ID = ART_INFO.SUBITEMGROUP_ID 
        WHERE A.CURRENCY_ISO_CD = 'EUR' AND  (A.DWH_CAL_DT >= TO_CHAR((DATE_TRUNC('WEEK', CURRENT_DATE)-70),'YYYY-MM_2-DD'))

        )
)
SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN_PCT
FROM(
    SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN_PCT
    FROM A_SALES

    UNION ALL
    
    SELECT
      CLIENT_ID
    , COUNTRY_CODE
    , DAT_FORMDATE
    , CY_WEEK
    , STORE_ID
    , ORIG_STORE_NR
	, ITEM_ID
    , ORIG_ITEM_NR
    , ITEMGROUP_INT_ID
    , SUBITEMGROUP_ID
    , ITEM_TYPE
    , SALES_NET_VAL
    , SALES_PIECES_EJR
    , BUYING_VAL
    , SALES_BASED_MARGIN
    , SALES_BASED_MARGIN_PCT
    FROM B_BUYING
)
;