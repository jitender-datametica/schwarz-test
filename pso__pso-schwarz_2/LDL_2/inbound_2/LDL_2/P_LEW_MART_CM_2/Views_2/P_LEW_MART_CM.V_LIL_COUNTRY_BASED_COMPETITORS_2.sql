CREATE OR REPLACE VIEW P_LEW_MART_CM.V_LIL_COUNTRY_BASED_COMPETITORS_2(
	 CLIENT_ID
	,COMPETITOR_RANK_ID
	,COMPETITOR_RANK_NAME
    ,RTL_ID
) AS
SELECT
    CLIENT_ID
    , COMPETITOR_RANK_ID
    , COMPETITOR_RANK_NAME
    , RETAILER_ID AS RTL_ID 
