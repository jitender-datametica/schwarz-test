CREATE OR REPLACE VIEW P_LEW_MART_PIT_ONPREM.V_PIT_SCOPE_COUNTRY_PARAM_2

AS
SELECT DISTINCT
    pa.CLIENT_ID
,    pa.PARAM_ID
,    pa.DWH_VALID_FROM
,    pa.DWH_VALID_TO
,    pa.VERSION_NR
,    dpa.PARAM_NAME
,    pa.PARAM_VALUE
,    dpa.PARAM_DESCR
,    dpa.PARAM_COLUMN_DATATYPE
,    pa.PARAM_VALUE_CHAR
,    pa.DELETED_FG
,    pa.CURRENT_FG
,    pa.DWH_CREATED
,    pa.DWH_UPDATED
FROM 
(
		SELECT * FROM P_LEW_MART_PIT_ONPREM.T_PIT_SCOPE_COUNTRY_PARAM_2 
		WHERE TRUE	
			AND CURRENT_DATE() BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
			AND DELETED_FG = 0
		QUALIFY VERSION_NR = MAX(VERSION_NR) OVER (PARTITION BY CLIENT_ID, PARAM_ID)	
	)
	pa

	INNER JOIN P_LEW_MART_PIT_ONPREM.T_PIT_SCOPE_COUNTRY_PARAM_REF_2 dpa
	ON pa.PARAM_ID = dpa.PARAM_ID
;