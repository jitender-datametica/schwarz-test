CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_DIM_AREA_NEW_2(
	DIC_AREA_ID
	, DIC_ACTIVE
	, MOD_DATE
	, DIC_AREA_NR
	, DIC_AREA_WH
	, COUNTRY_2
	, DIC_AREA_NAME
	, SOURCE_EXTRACTION_TMSP
	, SNFLK_INSERT_TMSP
	, SNFLK_UPDATE_TMSP
) AS

/* Version: 1.0
