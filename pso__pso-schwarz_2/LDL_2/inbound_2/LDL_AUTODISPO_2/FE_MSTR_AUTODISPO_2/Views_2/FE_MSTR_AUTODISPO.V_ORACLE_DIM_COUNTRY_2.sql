CREATE OR REPLACE VIEW FE_MSTR_AUTODISPO.V_ORACLE_DIM_COUNTRY_2(
	  COUNTRY_2
	, SOURCE_FLAG
	, ADL_ACTIVE_FLAG
) AS

    /* Version:   1.1
    ** Author:    Dominik Pfarr
    ** Date:      2023-03-22
    ** Changes:   adding flags
    */
SELECT COUNTRY_2
	,MAX(SOURCE_FLAG) AS SOURCE_FLAG
	,MAX(ADL_ACTIVE_FLAG) AS ADL_ACTIVE_FLAG
FROM FE_MSTR_AUTODISPO.V_ORACLE_DIM_WAREHOUSE_2
GROUP BY COUNTRY_2;