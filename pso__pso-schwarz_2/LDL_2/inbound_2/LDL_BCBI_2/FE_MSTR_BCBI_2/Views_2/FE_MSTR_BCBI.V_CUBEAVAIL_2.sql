CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_CUBEAVAIL_2 AS
SELECT
CASE WHEN EXTRACT(HOUR FROM starttime)<10 OR (EXTRACT(HOUR FROM starttime)=10 AND EXTRACT(MINUTE FROM starttime)<20) THEN 'EU' ELSE 'US' END AS ZONE
,RT_IS_REP_JOB_ID AS JOB_ID
,RT_IS_PROJ_ID AS PROJECT_ID
,RT_IS_PROJ_NAME AS PROJECT_NAME
,RT_IS_REP_ID AS REPORT_ID
,RT_IS_REP_NAME AS REPORT_NAME
,IS_REP_LOC AS REPORT_LOCATION
,cubereportguid
,cubeactionid
,servermachine
,RT_IS_REP_REQ_TS AS REQUEST_TIME_TS
,starttime
,finishtime
,RT_IS_ERROR_IND_ID AS ERROR_ID
,RT_ERRORMESSAGE AS ERROR_DESC
,RT_JOB_DURATION AS JOB_DURATION_MS
,ROUND(CAST(RT_JOB_DURATION AS INTEGER) / 1000 / 60,2) AS JOB_DURATION_MIN
,RT_RESULTROWS AS RESULT_ROWS
,RT_SQLPASSES AS SQL_PASSES
,TIMESTAMP_LOAD_BCBI
FROM
(
SELECT * FROM FE_MSTR_BCBI.T_CUBESTATISTICS_2
WHERE USER_FLAG=1
UNION ALL
SELECT * FROM FE_MSTR_BCBI.T_CUBESTATISTICS_2 T1_2
WHERE T1.USER_FLAG=0
AND EXISTS
(
SELECT 1 FROM FE_MSTR_BCBI.T_CUBESTATISTICS_2 T2
WHERE T2.USER_FLAG=1
AND T1.cubereportguid=T2.cubereportguid
 )
) AS U;