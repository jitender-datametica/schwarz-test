CREATE OR REPLACE VIEW FE_MSTR_BCBI.V_CUBEAVAIL_EXPECTED_2 AS
SELECT 
     DATES.CAL_DT AS DAY 
    ,DATES.MONTH_OF_YEAR AS MONTH_OF_YEAR
    ,DATES.MONTH_OF_YEAR_NAME AS MONTH_OF_YEAR_NAME
    ,DATES.CY_MONTH AS CY_MONTH
    ,DATES.CY AS CY
    ,DATES.BUS_YEAR AS BUS_YEAR
    ,DATES.CY_WEEK AS CY_WEEK
    ,EXP.ZONE 
	,EXP.PROJECT_ID 
	,EXP.PROJECT_NAME 
	,EXP.CUBE_ID 
	,EXP.CUBE_NAME 
	,EXP.SUBCUBE_ID 
	,EXP.SUBCUBE_NAME
    ,sol.FIRST_RESP_SOLUTION_ID AS FIRST_SOLUTION_ID
    ,sol.FIRST_RESP_SOLUTION_NAME AS FIRST_SOLUTION_NAME
    ,sol.SEC_RESP_SOLUTION_ID AS SEC_SOLUTION_ID
    ,sol.SEC_RESP_SOLUTION_NAME AS SEC_SOLUTION_NAME
    ,serv.ISERVER_ID
    ,serv.ISERVER_NAME
	,EXP.DAT_REC_START 
	,EXP.DAT_REC_END 
	,EXP.SLA_VTA 
	,EXP.SLA_VVTA 
	,EXP.SLA_NVTA
    ,EXP.TIMESTAMP_LOAD_BCBI
   FROM FE_MSTR_BCBI.T_CUBEAVAIL_EXPECTED_LIST_2 EXP
   INNER JOIN FE_MSTR_BCBI.T_CUBEAVAIL_SOLUTIONS_2 sol
   ON EXP.subcube_id = sol.subcube_id
   INNER JOIN FE_MSTR_BCBI.T_CUBEAVAIL_SERVER_2 serv
   ON EXP.ZONE = serv.ZONE
   INNER JOIN 
        (SELECT  CAL_DT
         ,MONTH_OF_YEAR
         ,MONTH_OF_YEAR_NAME
         ,CY_MONTH
         ,CY
         ,BUS_YEAR
         ,CY_WEEK
         FROM
         FE_MSTR_BCBI.T_DIM_CAL_DAY_2  --since wh_expected_lISt doesn't contain dat_dayEND, each record in wh_expected_lISt IS duplicated by each calENDarday respectivly
         WHERE
            CAL_DT BETWEEN '2023-06-20'
            AND CURRENT_DATE
            ) DATES ON DATES.CAL_DT BETWEEN EXP.DAT_REC_START
            AND EXP.DAT_REC_END;