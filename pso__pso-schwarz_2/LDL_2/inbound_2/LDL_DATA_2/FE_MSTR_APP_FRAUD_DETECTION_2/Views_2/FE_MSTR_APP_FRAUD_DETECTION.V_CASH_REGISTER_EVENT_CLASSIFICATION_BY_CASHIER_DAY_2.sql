CREATE OR REPLACE VIEW FE_MSTR_APP_FRAUD_DETECTION.V_CASH_REGISTER_EVENT_CLASSIFICATION_BY_CASHIER_DAY_2(
	STORE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE STORE WHERE THE RELATED CASH REGISTER EVENT HAPPENED.',
	BUS_DT COMMENT 'THE BUSINESS DATE ON WHICH THE RETAIL EVENT IS COUNTED.',
    HR COMMENT 'HOUR INFORMATION',
	CASHIER_NR COMMENT 'THE NUMBER WHICH IDENTIFIES THE CASHIER. (THE NUMBER IS UNIQUE FOR A GIVEN STORE AND A DAY.)',
	SCENARIO_ID COMMENT 'THE UNIQUE IDENTIFIER OF FRAUD DETECTION SCENARIO',
	COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_2 FOR WHICH THE RELATED COUNTRY_2 ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY_2 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	METRIC_ID COMMENT 'THE UNIQUE IDENTIFIER OF MICROSTRATEY METRIC',
	CALCULATION_TYPE_CD COMMENT 'THE CALCULATION TYPE OF THE METRIC SUM,SMARTAVG..',
	SCENARIO_VALUE_1 COMMENT 'THE FIRST VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	SCENARIO_VALUE_2 COMMENT 'THE SECOND VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	SCENARIO_VALUE_3 COMMENT 'THE THIRD VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
	SCENARIO_VALUE_4 COMMENT 'THE  VALUE TO CALCULATE DEFINED MICROSTRATEGY METRIC',
    CURR_CD COMMENT 'THE CODE IDENTIFYING THE CURRENCY ACCORDING TO ISO-4217.',
	CURR_GROUP_FG COMMENT 'FLAG FOR GROUP CURRENCY',
	CURR_LOCAL_FG COMMENT 'FLAG FOR LOCAL CURRENCY'
 ) COMMENT='THIS VIEW BRINGS THE VALUES IN A NORMALIZED FORM TO CALCULATE THE METRICS, WHICH WILL BE USED FOR DYNAMIC DASHBOARD'
 AS 
WITH CTE_CASH_REGISTER_EVENT_CLASSIFICATION
(COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,CASHIER_NR,SCENARIO_ID,BUS_DT,EVENT_END_HR,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG,CASH_REGISTER_EVENT_CNT,CASH_REGISTER_EVENT_AFFECTED_LINE_CNT,CASH_REGISTER_EVENT_AFFECTED_NET_VAL,CUST_SID_DST_CNT)
AS 
(
  SELECT 
  MAIN.COUNTRY_ORG_CD
  ,STORE.SALES_COMPANY_SID
  ,MAIN.STORE_SID
  ,MAIN.CASHIER_NR
  ,MAIN.SCENARIO_ID
  ,MAIN.BUS_DT
  ,MAIN.EVENT_END_HR
  ,FER.SRC_CURR_CD AS CURR_CD
  ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
  ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
  ,SUM(MAIN.CASH_REGISTER_EVENT_CNT) AS CASH_REGISTER_EVENT_CNT
  ,SUM(MAIN.CASH_REGISTER_EVENT_AFFECTED_LINE_CNT) AS CASH_REGISTER_EVENT_AFFECTED_LINE_CNT
  ,SUM(MAIN.CASH_REGISTER_EVENT_AFFECTED_NET_VAL / FER.EXCHANGE_RATE ) AS CASH_REGISTER_EVENT_AFFECTED_LINE_CNT
  ,COUNT(DISTINCT MAIN.CUST_SID) AS CUST_SID_DST_CNT
  FROM CORE_APP_FRAUD_DETECTION.T_CASH_REGISTER_EVENT_CLASSIFICATION_2 MAIN
  INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_2 STORE
  ON STORE.INT_ORG_SID = MAIN.STORE_SID
  AND STORE.DWH_VALID_FG
  INNER JOIN CORE_DIM.T_DIM_COUNTRY_2 CT
  ON MAIN.COUNTRY_ORG_CD = CT.ISO_COUNTRY_CD
  INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_2 FER
    ON CT.CURR_CD = FER.TGT_CURR_CD
  WHERE EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
    AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
    AND FER.ACTIVE_FG = TRUE
  GROUP BY 
  MAIN.COUNTRY_ORG_CD
  ,STORE.SALES_COMPANY_SID
  ,MAIN.STORE_SID
  ,MAIN.CASHIER_NR
  ,MAIN.SCENARIO_ID
  ,MAIN.BUS_DT
  ,MAIN.EVENT_END_HR
  ,FER.SRC_CURR_CD 
  ,FER.TGT_CURR_CD
  )
,  CTE_STATISTICS_BY_STORE_DAY_CASHIER (COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,BUS_DT,EVENT_END_HR,CASHIER_NR,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG,SALES_NET_VAL,RETURN_NET_VAL,EVENT_CNT,EVENT_LINE_CNT,RETURN_CNT
,CANCELLED_LINE_CNT,CANCELLED_NET_VAL,DISCOUNT_LINE_CNT,DISCOUNT_NET_VAL,ABORT_CNT,ABORT_NET_VAL,SUSPENDED_UNRESOLVED_CNT,SUSPENDED_UNRESOLVED_NET_VAL,PRICE_INFO_CNT
,RETURN_WITHOUT_RECEIPT_CNT,RETURN_WITHOUT_RECEIPT_NET_VAL,DEPOSIT_SALES_NET_VAL,DEPOSIT_RETURN_NET_VAL,DEPOSIT_RETURN_MANUAL_INPUT_NET_VAL
,DEPOSIT_RETURN_MANUAL_INPUT_GROSS_VAL,DEPOSIT_ONLY_RETURN_NET_VAL,SMALL_SALES_CNT,LOGIN_CNT,LOGOFF_CNT)
AS 
( 
SELECT
ORG.COUNTRY_ORG_CD
,ORG.SALES_COMPANY_SID
,MAIN.INT_ORG_SID AS STORE_SID
,MAIN.BUS_DT
,MAIN.EVENT_END_HR
,MAIN.CASHIER_NR
,FER.SRC_CURR_CD AS CURR_CD
,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
,MAIN.SALES_NET_VAL / FER.EXCHANGE_RATE AS  SALES_NET_VAL
,MAIN.RETURN_NET_VAL  / FER.EXCHANGE_RATE AS RETURN_NET_VAL
,MAIN.EVENT_CNT 
,MAIN.EVENT_LINE_CNT
,MAIN.RETURN_CNT
,MAIN.CANCELLED_LINE_CNT
,MAIN.CANCELLED_NET_VAL  / FER.EXCHANGE_RATE AS CANCELLED_NET_VAL
,MAIN.DISCOUNT_LINE_CNT
,MAIN.DISCOUNT_NET_VAL  / FER.EXCHANGE_RATE AS DISCOUNT_NET_VAL
,MAIN.ABORT_CNT
,MAIN.ABORT_NET_VAL  / FER.EXCHANGE_RATE AS ABORT_NET_VAL
,MAIN.SUSPENDED_UNRESOLVED_CNT
,MAIN.SUSPENDED_UNRESOLVED_NET_VAL  / FER.EXCHANGE_RATE AS SUSPENDED_UNRESOLVED_NET_VAL
,MAIN.PRICE_INFO_CNT
,MAIN.RETURN_WITHOUT_RECEIPT_CNT
,MAIN.RETURN_WITHOUT_RECEIPT_NET_VAL  / FER.EXCHANGE_RATE AS RETURN_WITHOUT_RECEIPT_NET_VAL
,MAIN.DEPOSIT_SALES_NET_VAL  / FER.EXCHANGE_RATE AS DEPOSIT_SALES_NET_VAL
,MAIN.DEPOSIT_RETURN_NET_VAL  / FER.EXCHANGE_RATE AS DEPOSIT_RETURN_NET_VAL
,MAIN.DEPOSIT_RETURN_MANUAL_INPUT_NET_VAL  / FER.EXCHANGE_RATE AS DEPOSIT_RETURN_MANUAL_INPUT_NET_VAL
,MAIN.DEPOSIT_RETURN_MANUAL_INPUT_GROSS_VAL  / FER.EXCHANGE_RATE AS DEPOSIT_RETURN_MANUAL_INPUT_GROSS_VAL
,MAIN.DEPOSIT_ONLY_RETURN_NET_VAL  / FER.EXCHANGE_RATE AS DEPOSIT_ONLY_RETURN_NET_VAL
,MAIN.SMALL_SALES_CNT
,MAIN.LOGIN_CNT
,MAIN.LOGOFF_CNT
FROM CORE_APP_FRAUD_DETECTION.T_STATISTICS_BY_STORE_HOUR_CASHIER_2 MAIN
INNER JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_2 ORG
   ON MAIN.INT_ORG_SID = ORG.INT_ORG_SID
   AND ORG.DWH_VALID_FG
INNER JOIN CORE_DIM.T_DIM_COUNTRY_2 CT
   ON ORG.COUNTRY_ORG_CD = CT.ISO_COUNTRY_CD
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_2 FER
   ON CT.CURR_CD = FER.TGT_CURR_CD
WHERE EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
   AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
   AND FER.ACTIVE_FG = TRUE
)
,CTE_CASHIER_SCENARIO (COUNTRY_ORG_CD,SALES_COMPANY_SID,STORE_SID,CASHIER_NR,SCENARIO_ID)
AS
(
SELECT 
    FACT.COUNTRY_ORG_CD
	,FACT.SALES_COMPANY_SID
	,FACT.STORE_SID
	,FACT.CASHIER_NR
	,FACT.SCENARIO_ID 
	FROM CTE_CASH_REGISTER_EVENT_CLASSIFICATION FACT
	GROUP BY 
	FACT.COUNTRY_ORG_CD
	,FACT.SALES_COMPANY_SID
	,FACT.STORE_SID
	,FACT.CASHIER_NR
	,FACT.SCENARIO_ID	
)
,CTE_STORES_IN_RV (COUNTRY_ORG_CD,STORE_SID, FROM_BUS_DT, UNTIL_BUS_DT)
AS 
(
SELECT ORG.COUNTRY_ORG_CD ,ORG.INT_ORG_SID , ORD.ANALYSIS_PERIOD_START_DT, ORD.ANALYSIS_PERIOD_END_DT
FROM CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_2 ORG
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_ORDER_2 ORD
ON ORD.INT_ORG_SID = ORG.INT_ORG_SID
OR ORD.INT_ORG_SID = ORG.SALES_COMPANY_SID
WHERE ORG.DWH_VALID_FG
)
, CTE_STORES_AGG_VALUES (BUS_DT,EVENT_END_HR,COUNTRY_ORG_CD,STORE_SID,CURR_CD,CURR_GROUP_FG,CURR_LOCAL_FG,SCENARIO_ID,CASH_REGISTER_EVENT_CNT)
AS
( 
SELECT 
		UNPIVOTED_VAL.BUS_DT
        ,HOUR(UNPIVOTED_VAL.EVENT_START_TMSP)
		,STORES.COUNTRY_ORG_CD
        ,STORES.STORE_SID
        ,FER.SRC_CURR_CD AS CURR_CD
        ,DECODE(FER.SRC_CURR_CD,'EUR',1,0) AS CURR_GROUP_FG
        ,DECODE(FER.SRC_CURR_CD,FER.TGT_CURR_CD,1,0) AS CURR_LOCAL_FG
		,CASE
			  WHEN FLAG_NAME = 'DEPOSIT_AND_ONE_PROD_FG'                 THEN 1
			  WHEN FLAG_NAME = 'DEPOSIT_SAME_EAN_FG'                     THEN 2
			  WHEN FLAG_NAME = 'DEPOSIT_ONLY_MANUAL_INPUT_FG'            THEN 4
			  WHEN FLAG_NAME = 'PRICE_INFO_MULT_FG'                      THEN 5
			  WHEN FLAG_NAME = 'PRICE_INFO_AND_SMALL_SALE_FG' 
				OR FLAG_NAME = 'PRICE_INFO_AND_LOGOFF_FG'                THEN 6
			  WHEN FLAG_NAME = 'RETURN_WITHOUT_AUTH_FG'                  THEN 7
			  WHEN FLAG_NAME = 'RETURN_SAME_RECEIPT_FG'                  THEN 8
			  WHEN FLAG_NAME = 'RETURN_SAME_PROD_FG'                     THEN 9
			  WHEN FLAG_NAME = 'RETURN_NOT_ON_RECEIPT_FG'               
				OR FLAG_NAME = 'RETURN_QTY_INVALID_FG'                   THEN 10
			  WHEN FLAG_NAME = 'RETURN_AT_HIGHER_THAN_SALES_PRICE_FG'
				OR FLAG_NAME = 'RETURN_AT_HIGHER_THAN_OFFICIAL_PRICE_FG' THEN 11
			  WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_FG'          THEN 12
			  WHEN FLAG_NAME = 'RETURN_WITHOUT_RECEIPT_KE_INPUT_FG'      THEN 13
			  WHEN FLAG_NAME = 'RETURN_MULT_PROD_FG'                     THEN 14
			  WHEN FLAG_NAME = 'SUSPEND_AND_ABORT_FG'
				OR FLAG_NAME = 'SUSPEND_AND_LINE_CANCEL_FG'
				OR FLAG_NAME = 'SUSPEND_AND_EXTEND_FG'                   THEN 15
			  WHEN FLAG_NAME = 'SUSPEND_UNRESOLVED_AND_LOGOFF_FG'
				OR FLAG_NAME = 'SUSPEND_UNRESOLVED_AND_SALE_FG'          THEN 16
			  --WHEN FLAG_NAME = 'ABORT_AND_SALE_FG'
			  --	OR FLAG_NAME = 'ABORT_AND_LOGOFF_FG'                     THEN 17
			  WHEN FLAG_NAME = 'CANCEL_LAST_POS_FG'                      THEN 18
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_FG'                     THEN 19
			  WHEN FLAG_NAME = 'PRICE_INFO_AND_SMALL_SALE_FG'                     THEN  60100
			  WHEN FLAG_NAME = 'PRICE_INFO_AND_LOGOFF_FG'                         THEN  60200
			  WHEN FLAG_NAME = 'RETURN_NOT_ON_RECEIPT_FG'                         THEN 100100
              WHEN FLAG_NAME = 'RETURN_QTY_INVALID_FG'                            THEN 100200
              WHEN FLAG_NAME = 'RETURN_AT_HIGHER_THAN_SALES_PRICE_FG'             THEN 110100
              WHEN FLAG_NAME = 'RETURN_AT_HIGHER_THAN_OFFICIAL_PRICE_FG'          THEN 110200
              WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_MANUAL_FG'            THEN 120100 
              WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_WITHOUT_AUTH_FG'      THEN 120200 
              WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_CASH_PAYM_FG'         THEN 120300 
              WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_CARD_PAYM_FG'         THEN 120400 
              WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_DIFF_DAY_FG'                  THEN 120600 
              WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_DISPLAY_SEL_FG'       THEN 120700 
              --WHEN FLAG_NAME = 'RETURN_SAME_CASHIER_AND_DAY_FG'                   THEN 120800 
              -- TO BE CHECKED: PROBABLY NOT NEEDED BECAUSE IT IS USED FOR THE MAIN SCENARIO (12)
              WHEN FLAG_NAME = 'RETURN_WITHOUT_RECEIPT_DV_INPUT_FG'               THEN 130100
              WHEN FLAG_NAME = 'RETURN_WITHOUT_RECEIPT_FG'                        THEN 130200
              WHEN FLAG_NAME = 'RETURN_MULT_PROD_FULL_QTY_FG'                     THEN 140100 
              WHEN FLAG_NAME = 'SUSPEND_AND_ABORT_FG'                             THEN 150100
			  WHEN FLAG_NAME = 'SUSPEND_AND_EXTEND_FG'                            THEN 150200
			  WHEN FLAG_NAME = 'SUSPEND_AND_LINE_CANCEL_FG'                       THEN 150300
			  WHEN FLAG_NAME = 'SUSPEND_UNRESOLVED_AND_SALE_FG'                   THEN 160100
			  WHEN FLAG_NAME = 'SUSPEND_UNRESOLVED_AND_LOGOFF_FG'                 THEN 160200
              WHEN FLAG_NAME = 'ABORT_AND_SALE_FG'                                THEN 170100
              WHEN FLAG_NAME = 'ABORT_AND_LOGOFF_FG'                              THEN 170200
			  WHEN FLAG_NAME = 'CANCEL_LAST_POS_EXACT_PAYM_FG'                    THEN 180100
			  WHEN FLAG_NAME = 'CANCEL_LAST_POS_AFTER_SUBTOTAL_FG'                THEN 180200
			  WHEN FLAG_NAME = 'CANCEL_LAST_POS_ALCOHOL_TOBACCO_FG'               THEN 180300
			  WHEN FLAG_NAME = 'CANCEL_LAST_POS_HIGHEST_POS_FG'                   THEN 180400
			  WHEN FLAG_NAME = 'CANCEL_LAST_POS_OUTSIDE_OPENING_HR_FG'            THEN 180500
			  WHEN FLAG_NAME = 'CANCEL_LAST_AND_OTHER_POS_FG'                     THEN 180600
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_EXACT_PAYM_FG'                   THEN 190100
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_AFTER_SUBTOTAL_FG'               THEN 190200
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_WITHOUT_AUTH_FG'                 THEN 190300
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_ALCOHOL_TOBACCO_FG'              THEN 190400
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_OUTSIDE_OPENING_HR_FG'           THEN 190600
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_MANUAL_DISCOUNT_FG'              THEN 190700
			  WHEN FLAG_NAME = 'CANCEL_IN_FAVOUR_LIDL_PLUS_FG'                    THEN 190800
			  ELSE -1 END AS SCENARIO_ID,
              SUM(1) AS CASH_REGISTER_EVENT_CNT
	FROM  CORE_DIM.T_FACT_FRAUD_DETECTION_BY_CASH_REGISTER_EVENT_2 FACT
    -- THIS WILL CREATE SEPARATE ROWS FOR RECEIPT AND ACTIVE FLAG
	UNPIVOT (
		FLAG_VALUE FOR FLAG_NAME IN (DEPOSIT_AND_ONE_PROD_FG, DEPOSIT_SAME_EAN_FG, DEPOSIT_ONLY_MANUAL_INPUT_FG, 
					   PRICE_INFO_MULT_FG, PRICE_INFO_AND_SMALL_SALE_FG, PRICE_INFO_AND_LOGOFF_FG, 
					   RETURN_WITHOUT_AUTH_FG, RETURN_SAME_RECEIPT_FG, RETURN_SAME_PROD_FG, RETURN_NOT_ON_RECEIPT_FG, RETURN_QTY_INVALID_FG, RETURN_AT_HIGHER_THAN_SALES_PRICE_FG, RETURN_AT_HIGHER_THAN_OFFICIAL_PRICE_FG, RETURN_SAME_CASHIER_AND_DAY_FG, RETURN_WITHOUT_RECEIPT_KE_INPUT_FG, RETURN_MULT_PROD_FG, 
					   SUSPEND_AND_ABORT_FG, SUSPEND_AND_LINE_CANCEL_FG, SUSPEND_AND_EXTEND_FG, SUSPEND_UNRESOLVED_AND_LOGOFF_FG, SUSPEND_UNRESOLVED_AND_SALE_FG,
					   ABORT_AND_SALE_FG, ABORT_AND_LOGOFF_FG, CANCEL_LAST_POS_FG, CANCEL_IN_FAVOUR_FG,
					   PRICE_INFO_AND_SMALL_SALE_FG, PRICE_INFO_AND_LOGOFF_FG,
					   RETURN_NOT_ON_RECEIPT_FG, RETURN_QTY_INVALID_FG,
					   RETURN_AT_HIGHER_THAN_SALES_PRICE_FG, RETURN_AT_HIGHER_THAN_OFFICIAL_PRICE_FG,
					   RETURN_SAME_CASHIER_AND_DAY_MANUAL_FG,RETURN_SAME_CASHIER_AND_DAY_WITHOUT_AUTH_FG,RETURN_SAME_CASHIER_AND_DAY_CASH_PAYM_FG,RETURN_SAME_CASHIER_AND_DAY_CARD_PAYM_FG,RETURN_SAME_CASHIER_DIFF_DAY_FG,RETURN_SAME_CASHIER_AND_DAY_DISPLAY_SEL_FG,RETURN_SAME_CASHIER_AND_DAY_FG,
					   RETURN_WITHOUT_RECEIPT_DV_INPUT_FG,RETURN_WITHOUT_RECEIPT_FG,
					   RETURN_MULT_PROD_FULL_QTY_FG,SUSPEND_AND_ABORT_FG, SUSPEND_AND_EXTEND_FG, SUSPEND_AND_LINE_CANCEL_FG,SUSPEND_UNRESOLVED_AND_SALE_FG, SUSPEND_UNRESOLVED_AND_LOGOFF_FG,
					   CANCEL_LAST_POS_EXACT_PAYM_FG, CANCEL_LAST_POS_AFTER_SUBTOTAL_FG, CANCEL_LAST_POS_ALCOHOL_TOBACCO_FG, CANCEL_LAST_POS_HIGHEST_POS_FG, CANCEL_LAST_POS_OUTSIDE_OPENING_HR_FG, CANCEL_LAST_AND_OTHER_POS_FG,
					   CANCEL_IN_FAVOUR_EXACT_PAYM_FG, CANCEL_IN_FAVOUR_AFTER_SUBTOTAL_FG, CANCEL_IN_FAVOUR_MANUAL_DISCOUNT_FG, CANCEL_IN_FAVOUR_WITHOUT_AUTH_FG, CANCEL_IN_FAVOUR_ALCOHOL_TOBACCO_FG, CANCEL_IN_FAVOUR_OUTSIDE_OPENING_HR_FG, CANCEL_IN_FAVOUR_LIDL_PLUS_FG
			)
	) AS UNPIVOTED_VAL
    INNER JOIN CTE_STORES_IN_RV STORES
    ON UNPIVOTED_VAL.BUS_DT BETWEEN STORES.FROM_BUS_DT AND STORES.UNTIL_BUS_DT
    AND UNPIVOTED_VAL.STORE_SID = STORES.STORE_SID 
    INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_2 FER
    ON UNPIVOTED_VAL.CURR_CD = FER.TGT_CURR_CD
    WHERE EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
    AND (FER.SRC_CURR_CD = 'EUR' OR FER.SRC_CURR_CD = FER.TGT_CURR_CD)
    AND FER.ACTIVE_FG = TRUE
	AND FLAG_VALUE = 1 
    GROUP BY UNPIVOTED_VAL.BUS_DT
    ,HOUR(UNPIVOTED_VAL.EVENT_START_TMSP)
    ,STORES.COUNTRY_ORG_CD
    ,STORES.STORE_SID
    ,FER.SRC_CURR_CD
    ,SCENARIO_ID
    ,CURR_GROUP_FG
    ,CURR_LOCAL_FG
)
--
-- Main
--
 SELECT 
    MAIN.STORE_SID
    ,MAIN.BUS_DT
    ,MAIN.EVENT_END_HR
	,MAIN.CASHIER_NR
    ,MAIN.SCENARIO_ID
    ,MAIN.COUNTRY_ORG_CD
    ,M.METRIC_ID
    ,M.CALCULATION_TYPE_CD AS CALCULATION_TYPE_CD
    ,MAIN.CASH_REGISTER_EVENT_AFFECTED_NET_VAL AS SCENARIO_VALUE_1
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_2
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_3
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_4
	,MAIN.CURR_CD
    ,MAIN.CURR_GROUP_FG
    ,MAIN.CURR_LOCAL_FG
FROM CTE_CASH_REGISTER_EVENT_CLASSIFICATION MAIN 
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_2 S
ON S.SCENARIO_ID = MAIN.SCENARIO_ID
INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_2 M
ON S.SCENARIO_ID = M.SCENARIO_ID
WHERE  S.SCENARIO_TYPE_CD = 'AUTO' 
AND M.CALCULATION_TYPE_CD = 'SUM'
AND MOD(M.METRIC_ID,100) = 10  
UNION ALL 
 SELECT 
 FACT.STORE_SID 
 ,FACT.BUS_DT
 ,FACT.EVENT_END_HR
 ,FACT.CASHIER_NR
 ,-1::NUMERIC(38,0) AS SCENARIO_ID
 ,FACT.COUNTRY_ORG_CD AS COUNTRY_ORG_CD
 ,-100::NUMERIC(38,0) AS METRIC_ID
 ,'SUM' AS CALCULATION_TYPE_CD
 ,FACT.SALES_NET_VAL - FACT.RETURN_NET_VAL AS SCENARIO_VALUE_1
 ,0::NUMERIC(38,5) AS SCENARIO_VALUE_2
 ,0::NUMERIC(38,5) AS SCENARIO_VALUE_3
 ,0::NUMERIC(38,5) AS SCENARIO_VALUE_4
 ,FACT.CURR_CD
 ,FACT.CURR_GROUP_FG
 ,FACT.CURR_LOCAL_FG
FROM CTE_STATISTICS_BY_STORE_DAY_CASHIER FACT
WHERE SCENARIO_VALUE_1 <> 0  
UNION ALL
SELECT 
    CASHIER.STORE_SID
    ,STORE_FACT.BUS_DT
    ,STORE_FACT.EVENT_END_HR
	,CASHIER.CASHIER_NR
    ,CASHIER.SCENARIO_ID
    ,CASHIER.COUNTRY_ORG_CD
    ,CASHIER.METRIC_ID
    ,CASHIER.CALCULATION_TYPE_CD AS CALCULATION_TYPE_CD
    ,CASHIER_FACT.CASH_REGISTER_EVENT_CNT AS SCENARIO_VALUE_1
    ,STORE_FACT.CASH_REGISTER_EVENT_CNT AS SCENARIO_VALUE_2
    ,1::NUMERIC(38,5) AS SCENARIO_VALUE_3
    ,0::NUMERIC(38,5) AS SCENARIO_VALUE_4
	,STORE_FACT.CURR_CD
    ,STORE_FACT.CURR_GROUP_FG
    ,STORE_FACT.CURR_LOCAL_FG
FROM 
( 
	SELECT 
	FACT.STORE_SID
	,FACT.CASHIER_NR
	,FACT.SCENARIO_ID 
	,FACT.COUNTRY_ORG_CD
    ,M.METRIC_ID
    ,M.CALCULATION_TYPE_CD AS CALCULATION_TYPE_CD
  	FROM CTE_CASHIER_SCENARIO FACT
    INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_SCENARIO_2 S
     ON S.SCENARIO_ID = FACT.SCENARIO_ID
    INNER JOIN CORE_APP_FRAUD_DETECTION.T_FRAUD_DETECTION_MSTR_METRIC_2 M
     ON S.SCENARIO_ID = M.SCENARIO_ID
   WHERE S.SCENARIO_TYPE_CD = 'AUTO' 
   AND M.CALCULATION_TYPE_CD = 'LEVELAVG'
 ) CASHIER
 LEFT JOIN 
(
SELECT 
    MAIN.STORE_SID
    ,MAIN.BUS_DT
    ,MAIN.SCENARIO_ID
    ,MAIN.EVENT_END_HR
    ,MAIN.COUNTRY_ORG_CD
    ,M.METRIC_ID
    ,SUM(MAIN.CASH_REGISTER_EVENT_CNT) AS CASH_REGISTER_EVENT_CNT
    ,MAIN.CURR_CD
    ,MAIN.CURR_GROUP_FG
    ,MAIN.CURR_LOCAL_FG
FROM CTE_STORES_AGG_VALUES MAIN 
