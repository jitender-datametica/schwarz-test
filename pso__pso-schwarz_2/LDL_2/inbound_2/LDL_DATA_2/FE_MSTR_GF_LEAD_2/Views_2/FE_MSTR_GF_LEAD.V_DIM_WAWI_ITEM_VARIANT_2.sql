CREATE OR REPLACE VIEW FE_MSTR_GF_LEAD.V_DIM_WAWI_ITEM_VARIANT_2(
	WAWI_ITEM_VARIANT_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) OF THE WAWI ITEM_2 VARIANT.'  
	,DWH_VALID_FROM_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD BECAME VALID.'  
	,DWH_VALID_TO_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS NO LONGER VALID.'  
	,DWH_VALID_FG COMMENT 'AN INDICATOR SHOWING THE CURRENT RECORD, I.E. WHERE THE CURRENT DATE IS BETWEEN DWH_VALID_FROM AND DWH_VALID_TO.'  
	,WAWI_ITEM_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) OF THE WAWI ITEM_2 ON WHICH THE VARIANT IS BASED.'  
	,COUNTRY_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE COUNTRY_2 ORGANIZATION WHICH HAS CREATED THE WAWI ITEM_2 VARIANT. (THIS COLUMN IS DENORMALIZED FROM T_WAWI_ITEM.)'  
	,COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_2 FOR WHICH CREATED THIS WAWI ITEM. (THE BUSINESS COUNTRY_2 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)'  
	,WAWI_ITEM_VARIANT_NR COMMENT 'THE NUMBER WHICH IDENTIFIES THE WAWI ITEM_2 VARIANT WITHIN THE GIVEN COUNTRY_2 ORGANIZATION. NOTE THAT THE NUMBER IS UNIQUE FOR A CERTAIN POINT IN TIME, BUT MAY BE RE_2-USED LATER ON. IT IS ALSO KNOWN AS THE LONG WAWI NUMBER.'  
	,WAWI_ITEM_VARIANT_NAME COMMENT 'THE NAME BY WHICH THE WAWI ITEM_2 VARIANT IS KNOWN WITHIN THE GIVEN COUNTRY_2 ORGANIZATION.'  
	,WAWI_ITEM_VARIANT_DESCR COMMENT 'A MORE DETAILED (FREE TEXT) DESCRIPTION FOR THE WAWI ITEM_2 VARIANT - WHICH APPLIES TO THE GIVEN COUNTRY_2 ORGANIZATION.'  
	,WAWI_ITEM_VARIANT_CREATION_DT COMMENT 'THE DATE WHEN THE ITEM_2 VARIANT WAS CREATED IN THE OPERATIONAL SYSTEM (WAWI) OF THE GIVEN COUNTRY_2 ORGANIZATION.'  
	,WAWI_COUNTRY_STATUS_ID COMMENT 'THE IDENTIFIER FOR THE COUNTRY_2-LEVEL LIFECYCLE STATUS_2 FOR WAWI ITEM_2 VARIANTS. (HQ STATUS_2)'  
	,WAWI_COUNTRY_STATUS_DESCR COMMENT 'A TEXTUAL DESCRIPTION FOR THE COUNTRY_2-LEVEL LIFECYCLE STATUS_2 FOR WAWI ITEM_2 VARIANTS. (DESCRIPTION IN GROUP LANGUAGE, I.E. IN GERMAN)'  
	,WAWI_WH_STATUS_ID COMMENT 'THE IDENTIFIER FOR THE WAREHOUSE-LEVEL LIFECYCLE STATUS_2 FOR WAWI ITEM_2 VARIANTS.'  
	,WAWI_WH_STATUS_DESCR COMMENT 'A TEXTUAL DESCRIPTION FOR THE WAREHOUSE-LEVEL LIFECYCLE STATUS_2 FOR WAWI ITEM_2 VARIANTS. (DESCRIPTION IN GROUP LANGUAGE, I.E. IN GERMAN)'  
	,CASE_SIZE_CNT COMMENT 'THE NUMBER OF INDIVIDUAL ITEMS THAT ARE CONTAINED IN THE WAWI ITEM_2 VARIANT. (NOTE THAT THE INDIVIDUAL ITEM_2 REPRESENTS THE SMALLEST SELLABLE UNIT. E.G. IF A PACKED TRY OF MEAT CONTAINS TWO SLICES, THE ENTIRE TRAY IS CONSIDERED ONE SELLABLE UNIT.) IN CASE OF WEIGHT-BASED ITEMS THIS IS THE INTEGER PART OF THE EXPECTED NET WEIGHT OF THE PACKAGE.'  
	,WEIGHT_BASED_FG COMMENT 'AN INDICATOR SHOWING, IF THE WAWI ITEM_2 VARIANT IS SOLD BY WEIGHT INSTEAD OF COUNT.'  
	,ITEM_FAM_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE ITEM_2 FAMILY TO WHICH THIS PRODUCT BELONGS.'  
	,ITEM_FAM_NR COMMENT 'THE NUMBER BY WHICH THE RELATED ITEM_2 FAMILY IS KNOWN TO BUSINESS.'  
	,ITEM_FAM_NAME COMMENT 'THE NAME OF THE ITEM_2 FAMILY. (NAME IN GROUP LANGUAGE, I.E. IN GERMAN)'  
	,SUB_ITEM_GRP_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR A SUB ITEM_2 GROUP TO WHICH THIS PRODUCT BELONGS.'  
	,SUB_ITEM_GRP_NR COMMENT 'THE NUMBER BY WHICH THE RELATED SUB ITEM_2 GROUP IS KNOWN TO BUSINESS.'  
	,SUB_ITEM_GRP_NAME COMMENT 'THE NAME OF THE SUB ITEM_2 GROUP. (NAME IN GROUP LANGUAGE, I.E. IN GERMAN)'  
	,FOOD_FG COMMENT 'AN INDICATOR DISTINGUISHING FOOD FROM NON-FOOD ITEMS.'  
	,INT_ITEM_GRP_SID COMMENT 'THE UNIQUE IDENTIFIER [SURROGATE KEY] FOR AN INTERNATIONAL ITEM_2 GROUP TO WHICH THIS PRODUCT BELONGS'  
	,INT_ITEM_GRP_NR COMMENT 'THE NUMBER BY WHICH THE RELATED INTERNATIONAL ITEM_2 GROUP IS KNOWN TO BUSINESS.'  
	,INT_ITEM_GRP_NAME COMMENT 'THE NAME OF THE INTERNATIONAL ITEM_2 GROUP. (NAME IN GROUP LANGUAGE, I.E. IN GERMAN)'  
	,DWH_CREATED_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS CREATED IN THE DATA WAREHOUSE.'  
	,DWH_UPDATED_TMSP COMMENT 'THE POINT IN TIME WHEN THIS RECORD WAS CREATED OR LAST UPDATED.'  
	,DWH_LOAD_ID COMMENT 'THE UNIQUE IDENTIFIER OF THE BATCH LOAD WHICH HAS DONE THE LAST UPDATE TO THIS RECORD. (CLOSING A RECORD IN HISTORY WITHOUT UPDATING ANY PAYLOAD COLUMNS DOES NOT TRIGGER AN UPDATE OF THE DWH_LOAD_ID.)'  
	,DWH_NODE_CD COMMENT 'THE CODE FOR THE SOURCE SYSTEM (OR SLICE OF SOURCE SYSTEM) FROM WHICH THIS RECORD WAS LOADED.'
) AS SELECT 
MAIN.WAWI_ITEM_VARIANT_SID
,MAIN.DWH_VALID_FROM_TMSP
,MAIN.DWH_VALID_TO_TMSP
,MAIN.DWH_VALID_FG
,MAIN.WAWI_ITEM_SID
,MAIN.COUNTRY_ORG_SID
,MAIN.COUNTRY_ORG_CD
,MAIN.WAWI_ITEM_VARIANT_NR
,MAIN.WAWI_ITEM_VARIANT_NAME
,MAIN.WAWI_ITEM_VARIANT_DESCR
,MAIN.WAWI_ITEM_VARIANT_CREATION_DT
,MAIN.WAWI_COUNTRY_STATUS_ID
,MAIN.WAWI_COUNTRY_STATUS_DESCR
,MAIN.WAWI_WH_STATUS_ID
,MAIN.WAWI_WH_STATUS_DESCR
,MAIN.CASE_SIZE_CNT
,MAIN.WEIGHT_BASED_FG
,MAIN.ITEM_FAM_SID
,MAIN.ITEM_FAM_NR
,MAIN.ITEM_FAM_NAME
,MAIN.SUB_ITEM_GRP_SID
,MAIN.SUB_ITEM_GRP_NR
,MAIN.SUB_ITEM_GRP_NAME
,MAIN.FOOD_FG
,MAIN.INT_ITEM_GRP_SID
,MAIN.INT_ITEM_GRP_NR
,MAIN.INT_ITEM_GRP_NAME
,MAIN.DWH_CREATED_TMSP
,MAIN.DWH_UPDATED_TMSP
,MAIN.DWH_LOAD_ID
,MAIN.DWH_NODE_CD
FROM CORE_DIM.T_DIM_WAWI_ITEM_VARIANT_2 AS MAIN
 WHERE MAIN.DWH_VALID_FG;