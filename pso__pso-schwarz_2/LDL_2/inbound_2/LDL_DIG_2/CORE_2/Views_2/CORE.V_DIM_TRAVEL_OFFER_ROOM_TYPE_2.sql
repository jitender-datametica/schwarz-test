CREATE OR REPLACE VIEW CORE.V_DIM_TRAVEL_OFFER_ROOM_TYPE_2(
	TRAV_OFFER_ROOM_TYPE_CD,
	TRAV_OFFER_ROOM_TYPE_DESCR
) COMMENT='A regular view to fetch the categorization of room type for travel offer  (Single | double |..)'
 AS
SELECT DISTINCT TRAV_OFFER_ROOM_TYPE_CD,
       NULL AS TRAV_OFFER_ROOM_TYPE_DESCR
FROM CORE.T_DIM_TRAVEL_OFFER_2;