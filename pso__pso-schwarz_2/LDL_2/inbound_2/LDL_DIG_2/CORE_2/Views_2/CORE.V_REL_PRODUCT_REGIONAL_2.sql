CREATE OR REPLACE VIEW CORE.V_REL_PRODUCT_REGIONAL_2
AS
SELECT
   PREG.WSHOP_CD            
   ,PREG.PROD_SID            
   ,DWH_VALID_FROM_TMSP 
   ,DWH_VALID_TO_TMSP   
   ,DWH_VALID_FG        
   ,PROD_NR             
   ,REG_PROD_NAME       
   ,REG_PROD_DESCR      
   ,DELIVERY_SRC_TYPE_CD
   ,MATERIAL_POS_TYPE_CD
   ,SHOP_CAT_SID        
   ,SHOP_CAT_NAME       
   ,SHOP_CAT_LVL4_SID   
   ,SHOP_CAT_LVL4_NAME  
   ,SHOP_CAT_LVL3_SID   
   ,SHOP_CAT_LVL3_NAME  
   ,SHOP_CAT_LVL2_SID   
   ,SHOP_CAT_LVL2_NAME  
   ,SHOP_CAT_LVL1_SID   
   ,SHOP_CAT_LVL1_NAME
   ,PROMO.MAX_PROMO_START_DT
FROM CORE.T_REL_PRODUCT_REGIONAL_2 PREG
    LEFT JOIN
    (
		SELECT P.PROD_SID, P.WSHOP_CD, MAX(PROMO_START_DT) MAX_PROMO_START_DT
		FROM CORE.T_DIM_SALES_PROMOTION_2 P
        GROUP BY P.PROD_SID, P.WSHOP_CD
    ) PROMO ON PROMO.PROD_SID = PREG.PROD_SID
        AND PROMO.WSHOP_CD = PREG.WSHOP_CD;