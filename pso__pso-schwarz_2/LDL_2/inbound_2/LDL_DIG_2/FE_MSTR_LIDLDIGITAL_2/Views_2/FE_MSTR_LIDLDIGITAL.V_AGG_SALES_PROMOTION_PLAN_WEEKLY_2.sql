CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_AGG_SALES_PROMOTION_PLAN_WEEKLY_2
AS SELECT
     CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD
    ,IFNULL(PROD_SID, '-1') AS PROD_SID
    ,IFNULL(PROMO_ID, '-1') AS PROMO_ID
    ,PROMO_DUR_WEEK_CNT AS PROMO_DUR_WEEK_CNT
    ,PROMO_START_DT AS PROMO_START_DT
    ,PROMO_SALE_START_DT AS PROMO_SALE_START_DT
    ,SUPPLIER_ORDER_QTY AS SUPPLIER_ORDER_QTY
    ,TGT_PROD_SALE_QTY AS TGT_PROD_SALE_QTY
    ,ESTIMATED_INIT_PROMO_STOCK AS ESTIMATED_INIT_PROMO_STOCK
    ,CURRENT_PROMO_WEEK_NR AS CURRENT_PROMO_WEEK_NR
    ,WEEK_NR AS WEEK_NR
    ,IFNULL(PROMO_SALE_CLUSTER_CD, '-1') AS PROMO_SALE_CLUSTER_CD
    ,TGT_SALE_PCT AS TGT_SALE_PCT
    ,CUM_TGT_SALE_PCT AS CUM_TGT_SALE_PCT
    ,CASE WHEN SALE_PROMO_PHASE_CD = '' THEN '-1' ELSE IFNULL(SALE_PROMO_PHASE_CD, '-1') END AS SALE_PROMO_PHASE_CD
    ,PLAN_AMC_QTY AS PLAN_AMC_QTY
    ,PLAN_AMC_PERC AS PLAN_AMC_PERC
    ,CASE WHEN SUPPLIER_ORDER_QTY > TGT_PROD_SALE_QTY 
        THEN SUPPLIER_ORDER_QTY
        ELSE TGT_PROD_SALE_QTY
        END AS PLAN_AMC_DENOMINATOR_PERC
    ,PLAN_AMC_QTY_CUM AS PLAN_AMC_QTY_CUM
    ,PLAN_AMC_CUM_PERC AS PLAN_AMC_CUM_PERC
    ,CASE WHEN SUPPLIER_ORDER_QTY > TGT_PROD_SALE_QTY 
        THEN SUPPLIER_ORDER_QTY
        ELSE TGT_PROD_SALE_QTY
        END AS PLAN_AMC_CUM_DENOMINATOR_PERC
    ,PLAN_AB_QTY AS PLAN_AB_QTY
    ,PLAN_AB_PERC AS PLAN_AB_PERC
    ,CASE WHEN ESTIMATED_INIT_PROMO_STOCK > TGT_PROD_SALE_QTY
        THEN ESTIMATED_INIT_PROMO_STOCK
        ELSE TGT_PROD_SALE_QTY
        END AS PLAN_AB_DENOMINATOR_PERC
    ,PLAN_AB_QTY_CUM AS PLAN_AB_QTY_CUM
    ,PLAN_AB_CUM_PERC AS PLAN_AB_CUM_PERC 
    ,CASE WHEN ESTIMATED_INIT_PROMO_STOCK > TGT_PROD_SALE_QTY
        THEN ESTIMATED_INIT_PROMO_STOCK
        ELSE TGT_PROD_SALE_QTY
        END AS PLAN_AB_CUM_DENOMINATOR_PERC
FROM
    lec_share.v_agg_sales_promotion_plan_weekly_core_view_2
;
