CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_COUPON_MARGIN_CONTRIBUTION_2 (
    COUPON_VALIDATION_NR
    , CUST_ORDER_SID
    , PROD_VARIANT_SID
    , COUPON_ID
    , COUPON_CD
    , COUPON_TYPE_CD
    , COUPON_PROMO_CD
    , PROFIT_LOSS_REASON_CD
    , PROFIT_LOSS_REASON_NAME
    , PROFIT_LOSS_TYPE_NAME
    , CURR_CD
    , WSHOP_CD
    , PROD_QTY
    , COUPON_VALIDATION_TMSP
    , COUPON_POS_GROSS_VAL
    , GC_LC_CD
    , CAL_YEAR
    , CAL_MONTH
    , BUS_YEAR
    , MONTH_OF_BUS_YEAR
    , REVENUE_NET_EUR_VAL
    , PROD_QTY_NEW
    , COGS_NET_EUR_VAL
    , COUPON_CHANGE_LOSS_NET_EUR_VAL
    , COUPON_WRITE_OFF_LOSS_NET_EUR_VAL
    , RETURN_COUPON_CHANGE_NET_EUR_VAL
    , RETURN_COUPON_WRITE_OFF_NET_EUR_VAL
    , RETURN_PROD_NET_EUR_VAL
    , DELIVERY_COST_NET_EUR_VAL
    , COGS_RETURN_NET_EUR_VAL
    , PROD_SID
    , IS_WINE_SPIRITS_FG
    , PACK_SIZE_HANDLE_GROUP_CD
    , PROD_SIZE_TYPE_GROUP_CD
    , PROD_SIZE_HANDLE_GROUP_CD
    , SHIP_SIZE_HANDLE_GROUP_CD
    , DELIVERY_SRC_TYPE_CD
    , PROD_FOOD_CLASS_CD
    , BRAND_CLASS_CD
    , PROD_ORG_LVL_NAME
    , PROD_PROMO_CLASS_CD
    , PROD_VARIANT_NR
    , RN
) AS
WITH 
    ORDERS AS (
        SELECT 
            YEAR(MCOL.CUST_ORDER_PERFORM_DT) AS CAL_YEAR
            , MONTH(MCOL.CUST_ORDER_PERFORM_DT) AS CAL_MONTH
            , MCOL.CUST_ORDER_PERFORM_DT
            , MCOL.CUST_ORDER_SID
            , MCOL.REVENUE_NET_EUR_VAL
            , MCOL.PROD_QTY
            , MCOL.COGS_NET_EUR_VAL
            , MCOL.COUPON_CHANGE_LOSS_NET_EUR_VAL
            , MCOL.COUPON_WRITE_OFF_LOSS_NET_EUR_VAL
            , MCOL.DELIVERY_COST_NET_EUR_VAL
            , MCOL.PROD_VARIANT_SID
            , MCOL.PROD_SID
            , MCOL.IS_WINE_SPIRITS_FG
            , MCOL.PACK_SIZE_HANDLE_GROUP_CD
            , MCOL.PROD_SIZE_TYPE_GROUP_CD
            , MCOL.PROD_SIZE_HANDLE_GROUP_CD
            , MCOL.SHIP_SIZE_HANDLE_GROUP_CD
            , MCOL.DELIVERY_SRC_TYPE_CD
            , MCOL.PROD_FOOD_CLASS_CD
            , MCOL.BRAND_CLASS_CD
            , MCOL.PROD_ORG_LVL_NAME
            , MCOL.PROD_PROMO_CLASS_CD
            , MCOL.PROD_VARIANT_NR
        FROM lec_share.v_fact_margin_contribution_order_line_2 AS MCOL
        WHERE MCOL.IS_BUNDLE_HEADER_FG = 1 OR MCOL.BUNDLE_HEADER_POS_NR = 0
    )
    , RETURNS AS ( 
        SELECT
            YEAR(MCOL.CUST_ORDER_RETURN_DT) AS CAL_YEAR
            , MONTH(MCOL.CUST_ORDER_RETURN_DT) AS CAL_MONTH
            , MCOL.CUST_ORDER_RETURN_DT
            , MCOL.CUST_ORDER_SID
            , MCOL.REVENUE_NET_EUR_VAL
            , MCOL.RETURN_PROD_QTY
            , MCOL.RETURN_COUPON_CHANGE_NET_EUR_VAL
            , MCOL.RETURN_COUPON_WRITE_OFF_NET_EUR_VAL
            , MCOL.RETURN_PROD_NET_EUR_VAL
            , MCOL.COGS_RETURN_NET_EUR_VAL
            , MCOL.PROD_VARIANT_SID
        FROM lec_share.v_fact_margin_contribution_order_line_2 AS MCOL
        WHERE (MCOL.IS_BUNDLE_HEADER_FG = 1 OR MCOL.BUNDLE_HEADER_POS_NR = 0)
        AND MCOL.CUST_ORDER_RETURN_DT IS NOT NULL 
    )
    , TYPE_COUPON AS (
        SELECT DC.COUPON_ID
            , DC.COUPON_TYPE_CD
        FROM lec_share.v_dim_coupon_2 AS DC
    )
    , PROFIT_LOSS AS (
        SELECT DPLR.PROFIT_LOSS_REASON_CD
            , DPLR.PROFIT_LOSS_REASON_NAME AS PROFIT_LOSS_REASON_NAME
            , DPLR.PROFIT_LOSS_TYPE_NAME AS PROFIT_LOSS_TYPE_NAME
        FROM lec_share.v_dim_profit_loss_reason_2 AS DPLR
    )
    , AGGR AS (
        SELECT
            FC.COUPON_VALIDATION_NR
            , FC.CUST_ORDER_SID
            , FC.PROD_VARIANT_SID
            , FC.COUPON_ID
            , FC.COUPON_CD
            , TYPE_COUPON.COUPON_TYPE_CD
            , FC.COUPON_PROMO_CD
            , FC.PROFIT_LOSS_REASON_CD
            , PROFIT_LOSS.PROFIT_LOSS_REASON_NAME
            , PROFIT_LOSS.PROFIT_LOSS_TYPE_NAME
            , 'EUR' AS CURR_CD
            , FC.WSHOP_CD
            , FC.PROD_QTY
            , FC.COUPON_VALIDATION_TMSP
            , FC.COUPON_POS_GROSS_LOCAL_VAL AS COUPON_POS_GROSS_VAL
            , 'GC' AS GC_LC_CD
            , COALESCE(ORDERS.CAL_YEAR, RETURNS.CAL_YEAR) AS CAL_YEAR
            , COALESCE(ORDERS.CAL_MONTH, RETURNS.CAL_MONTH) AS CAL_MONTH
            , DIM_CAL_DAY.BUS_YEAR
            , DIM_CAL_DAY.MONTH_OF_BUS_YEAR
            , ORDERS.REVENUE_NET_EUR_VAL
            , ORDERS.PROD_QTY AS PROD_QTY_NEW
            , ORDERS.COGS_NET_EUR_VAL
            , ORDERS.COUPON_CHANGE_LOSS_NET_EUR_VAL
            , ORDERS.COUPON_WRITE_OFF_LOSS_NET_EUR_VAL
            , RETURNS.RETURN_COUPON_CHANGE_NET_EUR_VAL
            , RETURNS.RETURN_COUPON_WRITE_OFF_NET_EUR_VAL
            , RETURNS.RETURN_PROD_NET_EUR_VAL
            , ORDERS.DELIVERY_COST_NET_EUR_VAL
            , RETURNS.COGS_RETURN_NET_EUR_VAL
            , ORDERS.PROD_SID
            , ORDERS.IS_WINE_SPIRITS_FG
            , ORDERS.PACK_SIZE_HANDLE_GROUP_CD
            , ORDERS.PROD_SIZE_TYPE_GROUP_CD
            , ORDERS.PROD_SIZE_HANDLE_GROUP_CD
            , ORDERS.SHIP_SIZE_HANDLE_GROUP_CD
            , ORDERS.DELIVERY_SRC_TYPE_CD
            , ORDERS.PROD_FOOD_CLASS_CD
            , ORDERS.BRAND_CLASS_CD
            , ORDERS.PROD_ORG_LVL_NAME
            , ORDERS.PROD_PROMO_CLASS_CD
            , ORDERS.PROD_VARIANT_NR
            , ROW_NUMBER() OVER (PARTITION BY FC.CUST_ORDER_SID, FC.PROD_VARIANT_SID ORDER BY FC.COUPON_POS_GROSS_LOCAL_VAL DESC) AS RN
        FROM
            lec_share.v_fact_coupon_validation_2 AS FC
        JOIN ORDERS ON ORDERS.CUST_ORDER_SID = FC.CUST_ORDER_SID
            AND ORDERS.PROD_VARIANT_SID = FC.PROD_VARIANT_SID
        LEFT JOIN RETURNS ON RETURNS.CUST_ORDER_SID = FC.CUST_ORDER_SID
            AND RETURNS.PROD_VARIANT_SID = FC.PROD_VARIANT_SID
        JOIN lec_share.v_dim_cal_day_2 AS DIM_CAL_DAY ON COALESCE(ORDERS.CUST_ORDER_PERFORM_DT, RETURNS.CUST_ORDER_RETURN_DT) = DIM_CAL_DAY.CAL_DT
        LEFT JOIN TYPE_COUPON ON FC.COUPON_ID = TYPE_COUPON.COUPON_ID
        LEFT JOIN PROFIT_LOSS ON FC.PROFIT_LOSS_REASON_CD = PROFIT_LOSS.PROFIT_LOSS_REASON_CD
        WHERE FC.CURR_CD = 'EUR'
            AND FC.COUPON_POS_GROSS_LOCAL_VAL != 0
    )
SELECT 
     COUPON_VALIDATION_NR
    , CUST_ORDER_SID
    , PROD_VARIANT_SID
    , COUPON_ID
    , COUPON_CD
    , COUPON_TYPE_CD
    , COUPON_PROMO_CD
    , PROFIT_LOSS_REASON_CD
    , PROFIT_LOSS_REASON_NAME
    , PROFIT_LOSS_TYPE_NAME
    , CURR_CD
    , WSHOP_CD
    , PROD_QTY
    , COUPON_VALIDATION_TMSP
    , COUPON_POS_GROSS_VAL
    , GC_LC_CD
    , CAL_YEAR
    , CAL_MONTH
    , BUS_YEAR
    , MONTH_OF_BUS_YEAR
    , REVENUE_NET_EUR_VAL
    , PROD_QTY_NEW
    , COGS_NET_EUR_VAL
    , COUPON_CHANGE_LOSS_NET_EUR_VAL
    , COUPON_WRITE_OFF_LOSS_NET_EUR_VAL
    , RETURN_COUPON_CHANGE_NET_EUR_VAL
    , RETURN_COUPON_WRITE_OFF_NET_EUR_VAL
    , RETURN_PROD_NET_EUR_VAL
    , DELIVERY_COST_NET_EUR_VAL
    , COGS_RETURN_NET_EUR_VAL
    , PROD_SID
    , IS_WINE_SPIRITS_FG
    , PACK_SIZE_HANDLE_GROUP_CD
    , PROD_SIZE_TYPE_GROUP_CD
    , PROD_SIZE_HANDLE_GROUP_CD
    , SHIP_SIZE_HANDLE_GROUP_CD
    , DELIVERY_SRC_TYPE_CD
    , PROD_FOOD_CLASS_CD
    , BRAND_CLASS_CD
    , PROD_ORG_LVL_NAME
    , PROD_PROMO_CLASS_CD
    , PROD_VARIANT_NR
    , RN
FROM AGGR
WHERE RN = 1;