CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_BUSINESS_EVENT_TYPE_2
AS SELECT
     CASE WHEN BUSINESS_EVENT_TYPE_CD = '' THEN '-1' ELSE IFNULL(BUSINESS_EVENT_TYPE_CD, '-1') END AS BUSINESS_EVENT_TYPE_CD
    ,BUSINESS_EVENT_TYPE_DESCR AS BUSINESS_EVENT_TYPE_DESCR 
FROM
    lec_share.v_dim_business_event_type_2
UNION ALL
    SELECT
         '-1' -- BUSINESS_EVENT_TYPE_CD
        ,'' -- BUSINESS_EVENT_TYPE_DESCR
;
