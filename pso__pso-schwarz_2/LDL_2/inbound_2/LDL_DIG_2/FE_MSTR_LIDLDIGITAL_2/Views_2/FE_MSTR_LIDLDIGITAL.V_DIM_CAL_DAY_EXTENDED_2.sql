CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CAL_DAY_EXTENDED_2
AS SELECT
    D.CAL_DT
    ,W.CY_WEEK_BEGIN_DT
    ,W.CY_WEEK_END_DT
    ,M.CY_MONTH_BEGIN_DT
    ,M.CY_MONTH_END_DT
    ,Y.CY_BEGIN_DT
    ,Y.CY_END_DT
    ,B.BUS_YEAR_BEGIN_DT
    ,B.BUS_YEAR_END_DT
    ,D.CY AS CY
    ,D.BUS_YEAR AS BUS_YEAR
    ,D.CY_MONTH AS CY_MONTH
    ,D.MONTH_OF_YEAR AS MONTH_OF_YEAR
    ,D.MONTH_OF_BUS_YEAR AS MONTH_OF_BUS_YEAR
    ,D.MONTH_OF_YEAR_SHORT_NAME AS MONTH_OF_YEAR_SHORT_NAME
    ,D.MONTH_OF_YEAR_SHORT_NAME_DE AS MONTH_OF_YEAR_SHORT_NAME_DE
    ,D.MONTH_OF_YEAR_SHORT_NAME_EN AS MONTH_OF_YEAR_SHORT_NAME_EN
    ,D.MONTH_OF_YEAR_NAME AS MONTH_OF_YEAR_NAME
    ,D.MONTH_OF_YEAR_NAME_DE AS MONTH_OF_YEAR_NAME_DE
    ,D.MONTH_OF_YEAR_NAME_EN AS MONTH_OF_YEAR_NAME_EN
    ,D.DAY_OF_MONTH AS DAY_OF_MONTH
    ,D.CY_WEEK AS CY_WEEK
    ,D.WEEK_OF_YEAR AS WEEK_OF_YEAR
    ,D.DAY_OF_WEEK AS DAY_OF_WEEK
    ,D.DAY_OF_WEEK_SHORT_NAME AS DAY_OF_WEEK_SHORT_NAME
    ,D.DAY_OF_WEEK_SHORT_NAME_DE AS DAY_OF_WEEK_SHORT_NAME_DE
    ,D.DAY_OF_WEEK_SHORT_NAME_EN AS DAY_OF_WEEK_SHORT_NAME_EN
    ,D.DAY_OF_WEEK_NAME AS DAY_OF_WEEK_NAME
    ,D.DAY_OF_WEEK_NAME_DE AS DAY_OF_WEEK_NAME_DE
    ,D.DAY_OF_WEEK_NAME_EN AS DAY_OF_WEEK_NAME_EN
    ,D.DAY_OF_CY AS DAY_OF_CY
    ,D.DAY_OF_BUS_YEAR AS DAY_OF_BUS_YEAR
    ,D.CAL_DT_PREV_1D AS CAL_DT_PREV_1D
    ,D.CAL_DT_PREV_1W AS CAL_DT_PREV_1W
    ,D.CAL_DT_PREV_1M AS CAL_DT_PREV_1M
    ,D.CAL_DT_PREV_1Y AS CAL_DT_PREV_1Y
    ,D.CAL_DT_PREV_2Y AS CAL_DT_PREV_2Y
    ,D.CAL_DT_PREV_3Y AS CAL_DT_PREV_3Y
    ,D.CAL_DT_PREV_4Y AS CAL_DT_PREV_4Y
    ,D.CAL_DT_PREV_5Y AS CAL_DT_PREV_5Y
    ,D.CAL_DT_SWDAY_PREV_1M AS CAL_DT_SWDAY_PREV_1M
    ,D.CAL_DT_SWDAY_PREV_1Y AS CAL_DT_SWDAY_PREV_1Y
    ,D.CAL_DT_SWDAY_PREV_2Y AS CAL_DT_SWDAY_PREV_2Y
    ,D.CAL_DT_SWDAY_PREV_3Y AS CAL_DT_SWDAY_PREV_3Y
    ,D.CAL_DT_SWDAY_PREV_4Y AS CAL_DT_SWDAY_PREV_4Y
    ,D.CAL_DT_SWDAY_PREV_5Y AS CAL_DT_SWDAY_PREV_5Y
    ,D.FIRST_DAY_OF_WEEK_FG AS FIRST_DAY_OF_WEEK_FG
    ,D.LAST_DAY_OF_WEEK_FG AS LAST_DAY_OF_WEEK_FG
    ,D.FIRST_DAY_OF_MONTH_FG AS FIRST_DAY_OF_MONTH_FG
    ,D.LAST_DAY_OF_MONTH_FG AS LAST_DAY_OF_MONTH_FG
    ,D.FIRST_DAY_OF_CY_FG AS FIRST_DAY_OF_CY_FG
    ,D.LAST_DAY_OF_CY_FG AS LAST_DAY_OF_CY_FG
    ,D.FIRST_DAY_OF_BUS_YEAR_FG AS FIRST_DAY_OF_BUS_YEAR_FG
    ,D.LAST_DAY_OF_BUS_YEAR_FG AS LAST_DAY_OF_BUS_YEAR_FG
    ,D.CAL_DT_OFFSET AS CAL_DT_OFFSET
    ,D.CY_WEEK_OFFSET AS CY_WEEK_OFFSET
    ,D.CY_MONTH_OFFSET AS CY_MONTH_OFFSET
    ,D.CY_OFFSET AS CY_OFFSET
    ,D.BUS_YEAR_OFFSET AS BUS_YEAR_OFFSET
    ,D.CY_QUARTER AS CY_QUARTER
FROM
    FE_MSTR_LIDLDIGITAL.V_DIM_CAL_DAY_2 D
JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_CAL_WEEK_2 W
    ON W.CY_WEEK = D.CY_WEEK
JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_CAL_MONTH_2 M
    ON M.CY_MONTH = D.CY_MONTH
JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_CAL_CALENDAR_YEAR_2 Y
    ON Y.CY = D.CY
JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_CAL_BUSINESS_YEAR_2 B
    ON B.BUS_YEAR = D.BUS_YEAR
;
