CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_CUSTOMER_TOUCHPOINT_LEVEL2_2
(
     CUST_TOUCHPOINT_LVL2_ID
    ,CUST_TOUCHPOINT_LVL1_ID
    ,CUST_TOUCHPOINT_LVL2_NAME
)
AS SELECT
     CUST_TOUCHPOINT_LVL2_ID
    ,IFNULL(CUST_TOUCHPOINT_LVL1_ID, '-1')
    ,CUST_TOUCHPOINT_LVL2_NAME
FROM lec_share.v_dim_customer_touchpoint_level2_2
UNION ALL
    SELECT '-1', '-1', ''
;