CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_FINANCIAL_ACCOUNT_2
AS SELECT
     IFNULL(FIN_ACCT_SID, '-1') AS FIN_ACCT_SID
    ,CASE WHEN CHART_OF_ACCOUNTS_CD = '' THEN '-1' ELSE IFNULL(CHART_OF_ACCOUNTS_CD, '-1') END AS CHART_OF_ACCOUNTS_CD
	,CASE WHEN ACCT_NR = '' THEN '-1' ELSE IFNULL(ACCT_NR, '-1') END AS ACCT_NR
	,CASE WHEN GROUP_ACCT_NR = '' THEN '-1' ELSE IFNULL(GROUP_ACCT_NR, '-1') END AS GROUP_ACCT_NR
    ,BALANCE_SHEET_ACCT_FG AS BALANCE_SHEET_ACCT_FG
    ,PL_STATEMENT_ACCT_FG AS PL_STATEMENT_ACCT_FG
    ,RECONCILIATION_ACCT_FG AS RECONCILIATION_ACCT_FG
    ,CASH_ACCT_FG AS CASH_ACCT_FG
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
    ,SHORT_NAME_EN AS SHORT_NAME_EN
    ,LONG_NAME_EN AS LONG_NAME_EN
    ,SHORT_NAME_DE AS SHORT_NAME_DE
    ,LONG_NAME_DE AS LONG_NAME_DE
    ,IFNULL(INTERNAL_COMPANY_SID, '-1') AS INTERNAL_COMPANY_SID
FROM
    lec_share.v_dim_financial_account_2
WHERE
    DWH_VALID_FG = TRUE
UNION ALL
    SELECT
         '-1' -- FIN_ACCT_SID
        ,'-1' -- CHART_OF_ACCOUNTS_CD
        ,'-1' -- ACCT_NR
        ,'-1' -- GROUP_ACCT_NR
        ,FALSE -- BALANCE_SHEET_ACCT_FG
        ,FALSE -- PL_STATEMENT_ACCT_FG
        ,FALSE -- RECONCILIATION_ACCT_FG
        ,FALSE -- CASH_ACCT_FG
        ,'-1' -- CURR_CD
        ,'' -- SHORT_NAME_EN
        ,'' -- LONG_NAME_EN
        ,'' -- SHORT_NAME_DE
        ,'' -- LONG_NAME_DE
        ,'-1' -- INTERNAL_COMPANY_SID
;