CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_HAULER_2
(
     HAULER_SID
    ,HAULER_NAME
    ,HAULER_COUNTRY_CD
)
AS SELECT
     HAULER_SID
    ,HAULER_NAME
    ,CASE WHEN HAULER_COUNTRY_CD = '' THEN '-1' ELSE IFNULL(HAULER_COUNTRY_CD, '-1') END
FROM
    lec_share.v_dim_hauler_2
WHERE
    DWH_VALID_FG = TRUE
UNION ALL 
    SELECT '-1', '', '-1'
;