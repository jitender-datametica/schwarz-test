CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRICE_TYPE_2
(
     PRICE_TYPE_CD
    ,PRICE_TYPE_DESCR
    ,PRICE_GROUP_CD
    ,PRICE_TYPE_DESCR_DE
)
AS SELECT
     PRICE_TYPE_CD
    ,PRICE_TYPE_DESCR
    ,CASE WHEN PRICE_GROUP_CD = '' THEN '-1' ELSE IFNULL(PRICE_GROUP_CD, '-1') END
    ,PRICE_TYPE_DESCR_DE 
FROM lec_share.v_dim_price_type_2
UNION ALL
    SELECT '-1', '', '-1', ''
;