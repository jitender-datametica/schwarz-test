	, CASE WHEN PROD_PURCH_ORG_TYPE_CD = '' THEN '-1' ELSE IFNULL(PROD_PURCH_ORG_TYPE_CD, '-1') END
	, IS_BUNDLE_HEADER_FG
	, CASE WHEN PROD_FAMILY_CD = '' THEN '-1' ELSE IFNULL(PROD_FAMILY_CD, '-1') END
