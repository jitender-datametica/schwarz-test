CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_ASSORTMENT_LIFECYCLE_2
AS SELECT
     CASE WHEN PROD_ASSORTMENT_LIFECYCLE_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_LIFECYCLE_CD, '-1') END AS PROD_ASSORTMENT_LIFECYCLE_CD
    ,PROD_ASSORTMENT_LIFECYCLE_DESCR AS PROD_ASSORTMENT_LIFECYCLE_DESCR 
FROM
    lec_share.v_dim_product_assortment_lifecycle_2
UNION ALL
    SELECT
         '-1' -- PROD_ASSORTMENT_LIFECYCLE_CD
        ,'' -- PROD_ASSORTMENT_LIFECYCLE_DESCR
;
