CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PRODUCT_SUBGROUP_2(
		PROD_SUBGROUP_CD
	,	PROD_SUBGROUP_DESCR
	,	PROD_GROUP_CD
	)
AS
SELECT 
		CASE WHEN PROD_SUBGROUP_CD = '' 		THEN '-1' ELSE IFNULL(PROD_SUBGROUP_CD, '-1') 	    END
	,	CASE WHEN PROD_SUBGROUP_DESCR = '' 	    THEN '-1' ELSE IFNULL(PROD_SUBGROUP_DESCR, '-1') 	END
	, 	CASE WHEN PROD_GROUP_CD = '' 		    THEN '-1' ELSE IFNULL(PROD_GROUP_CD, '-1') 		    END
FROM lec_share.v_dim_product_subgroup_2
UNION ALL
SELECT
		'-1' 	--PROD_SUBGROUP_CD
	,	''		--PROD_SUBGROUP_DESCR
	,	'-1'	--PROD_GROUP_CD

;