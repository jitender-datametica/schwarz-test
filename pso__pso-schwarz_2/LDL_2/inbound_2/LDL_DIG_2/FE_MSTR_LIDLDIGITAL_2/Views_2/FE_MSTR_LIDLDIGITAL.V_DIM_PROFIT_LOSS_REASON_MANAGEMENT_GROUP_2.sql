CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PROFIT_LOSS_REASON_MANAGEMENT_GROUP_2
AS SELECT
     CASE WHEN PROFIT_LOSS_REASON_MGMT_GROUP_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_MGMT_GROUP_CD, '-1') END AS PROFIT_LOSS_REASON_MGMT_GROUP_CD
    ,PROFIT_LOSS_REASON_MGMT_GROUP_DESCR AS PROFIT_LOSS_REASON_MGMT_GROUP_DESCR 
FROM
    lec_share.v_dim_profit_loss_reason_management_group_core_view_2
UNION ALL
    SELECT
         '-1' -- PROFIT_LOSS_REASON_MGMT_GROUP_CD
        ,'' -- PROFIT_LOSS_REASON_MGMT_GROUP_DESCR
;