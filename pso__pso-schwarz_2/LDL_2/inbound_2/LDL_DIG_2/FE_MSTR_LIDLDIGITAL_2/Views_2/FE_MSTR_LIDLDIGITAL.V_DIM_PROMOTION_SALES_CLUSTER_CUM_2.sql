CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_PROMOTION_SALES_CLUSTER_CUM_2
AS SELECT
    A.PROMO_SALE_CLUSTER_CD AS PROMO_SALE_CLUSTER_CD
    ,A.PROMO_SALE_CLUSTER_DESCR AS PROMO_SALE_CLUSTER_DESC
    ,A.LAST_WEEK_NR AS LAST_WEEK_NR
    ,B.PROMO_SALE_CLUSTER_CD AS CUM_PROMO_SALE_CLUSTER_CD
    ,B.PROMO_SALE_CLUSTER_DESCR AS CUM_PROMO_SALE_CLUSTER_DESC
    ,B.LAST_WEEK_NR AS CUM_LAST_WEEK_NR
FROM
    FE_MSTR_LIDLDIGITAL.V_DIM_PROMOTION_SALES_CLUSTER_2 A
CROSS JOIN
    FE_MSTR_LIDLDIGITAL.V_DIM_PROMOTION_SALES_CLUSTER_2 B
WHERE
    A.PROMO_SALE_CLUSTER_CD>=B.PROMO_SALE_CLUSTER_CD AND B.PROMO_SALE_CLUSTER_CD<>-1
;
