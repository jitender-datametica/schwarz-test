CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_SALES_PROMOTION_TYPE_2
AS SELECT
     CASE WHEN SALE_PROMO_TYPE_CD = '' THEN '-1' ELSE IFNULL(SALE_PROMO_TYPE_CD, '-1') END AS SALE_PROMO_TYPE_CD
    ,SALE_PROMO_TYPE_NAME AS SALE_PROMO_TYPE_NAME
    ,SALE_PROMO_TYPE_DESCR AS SALE_PROMO_TYPE_DESCR
    ,CASE WHEN SALE_PROMO_TYPE_CD = '' THEN '-1' ELSE IFNULL(SALE_PROMO_TYPE_CD, '-1') END AS SALE_PROMO_TYPE_CD_TECHNICAL
FROM
    lec_share.v_dim_sales_promotion_type_2
UNION ALL
    SELECT
         '-1' -- SALE_PROMO_TYPE_CD
        ,'' -- SALE_PROMO_TYPE_NAME
        ,'' -- SALE_PROMO_TYPE_DESCR
        ,'' -- SALE_PROMO_TYPE_CD_TECHNICAL
;
