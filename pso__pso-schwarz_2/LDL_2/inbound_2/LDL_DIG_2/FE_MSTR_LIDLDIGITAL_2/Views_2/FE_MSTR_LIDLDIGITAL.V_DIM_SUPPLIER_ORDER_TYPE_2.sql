CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_SUPPLIER_ORDER_TYPE_2
AS SELECT
     CASE WHEN SUPPLIER_ORDER_TYPE_CD = '' THEN '-1' ELSE IFNULL(SUPPLIER_ORDER_TYPE_CD, '-1') END AS SUPPLIER_ORDER_TYPE_CD
    ,SUPPLIER_ORDER_TYPE_DESCR AS SUPPLIER_ORDER_TYPE_DESCR 
FROM
    lec_share.v_dim_supplier_order_type_2
UNION
    SELECT
         '-1' -- SUPPLIER_ORDER_TYPE_CD
        ,'' -- SUPPLIER_ORDER_TYPE_DESCR
;
