CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_TRAVEL_SOURCE_MARKET_2
(
     TRAV_SOURCE_MARKET_CD
    ,TRAV_SOURCE_MARKET_NAME
    ,COUNTRY_CD
)
AS SELECT
     TRAV_SOURCE_MARKET_CD
    ,TRAV_SOURCE_MARKET_NAME
    ,CASE WHEN COUNTRY_CD = '' THEN '-1' ELSE IFNULL(COUNTRY_CD, '-1') END
FROM lec_share.v_dim_travel_source_market_2
UNION ALL
    SELECT '-1', '', '-1'
;