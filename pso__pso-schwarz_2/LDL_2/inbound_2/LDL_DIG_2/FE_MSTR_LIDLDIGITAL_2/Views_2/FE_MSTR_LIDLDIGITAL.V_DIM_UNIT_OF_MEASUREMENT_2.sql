CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_DIM_UNIT_OF_MEASUREMENT_2
(
     UOM_SID
    ,UOM_CD
    ,UOM_DESCR
    ,UOM_STANDARD_SID
    ,UOM_STANDARD_CD
    ,UOM_STANDARD_MULTIPL_MEAS
)
AS SELECT
     UOM_SID
    ,CASE WHEN UOM_CD = '' THEN '-1' ELSE IFNULL(UOM_CD, '-1') END
    ,UOM_DESCR
    ,IFNULL(UOM_STANDARD_SID, '-1') END
    ,CASE WHEN UOM_STANDARD_CD = '' THEN '-1' ELSE IFNULL(UOM_STANDARD_CD, '-1') END
    ,UOM_STANDARD_MULTIPL_MEAS
FROM lec_share.v_dim_unit_of_measurement_2
UNION ALL
    SELECT 
     '-1'  -- UOM_SID
    ,''  -- UOM_CD
    ,''    -- UOM_DESCR
    ,'-1'  -- UOM_STANDARD_SID
    ,''  -- UOM_STANDARD_CD
    ,'1'   -- UOM_STANDARD_MULTIPL_MEAS
;