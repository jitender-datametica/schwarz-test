CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CURRENCY_EXCHANGE_RATE_2
(
FROM_CURR_CD
,TO_CURR_CD
,CURR_EXCHANGE_RATE_TYPE_CD
,EXCHANGE_RATE
)
AS SELECT
FROM_CURR_CD
,CASE WHEN TO_CURR_CD = '' THEN '-1' ELSE IFNULL(TO_CURR_CD , '-1') END
,CASE WHEN CURR_EXCHANGE_RATE_TYPE_CD = '' THEN '-1' ELSE IFNULL(CURR_EXCHANGE_RATE_TYPE_CD , '-1') END
,EXCHANGE_RATE
FROM lec_share.v_fact_currency_exchange_rate_2
WHERE ACTIVE_FG  = 'TRUE';