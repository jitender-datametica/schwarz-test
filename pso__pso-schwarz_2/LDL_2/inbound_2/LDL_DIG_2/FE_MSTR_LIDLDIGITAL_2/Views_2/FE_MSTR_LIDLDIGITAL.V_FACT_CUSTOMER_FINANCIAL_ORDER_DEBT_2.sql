CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_FINANCIAL_ORDER_DEBT_2
AS SELECT
     CUST_ORDER_INSTALL_NR AS CUST_ORDER_INSTALL_NR
    ,DEBT_COLLECTION_ITEM_NR AS DEBT_COLLECTION_ITEM_NR
    ,IFNULL(CUST_SID, '-1') AS CUST_SID
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
    ,CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD
    ,DEBT_COLLECTION_REQUEST_LOCAL_VAL AS DEBT_COLLECTION_REQUEST_LOCAL_VAL
    ,DEBT_COLLECTION_PAID_LOCAL_VAL AS DEBT_COLLECTION_PAID_LOCAL_VAL
FROM
    lec_share.v_fact_customer_financial_order_debt_2
WHERE
    DWH_VALID_FG = TRUE
;
