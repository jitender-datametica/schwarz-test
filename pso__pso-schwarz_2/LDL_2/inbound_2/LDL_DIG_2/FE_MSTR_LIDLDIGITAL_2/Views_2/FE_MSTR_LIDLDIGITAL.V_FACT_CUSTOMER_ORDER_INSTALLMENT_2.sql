CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_ORDER_INSTALLMENT_2
AS SELECT
     CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD
    ,CASE WHEN CUST_ORDER_INSTALL_NR = '' THEN '-1' ELSE IFNULL(CUST_ORDER_INSTALL_NR, '-1') END AS CUST_ORDER_INSTALL_NR
    ,CASE WHEN CUST_ORDER_INSTALL_POS_NR = '' THEN '-1' ELSE IFNULL(CUST_ORDER_INSTALL_POS_NR, '-1') END AS CUST_ORDER_INSTALL_POS_NR
    ,CASE WHEN CUST_ORDER_INSTALL_PART_POS_NR = '' THEN '-1' ELSE IFNULL(CUST_ORDER_INSTALL_PART_POS_NR, '-1') END AS CUST_ORDER_INSTALL_PART_POS_NR
    ,CASE WHEN CUST_ORDER_INSTALL_PART_REP_POS_NR = '' THEN '-1' ELSE IFNULL(CUST_ORDER_INSTALL_PART_REP_POS_NR, '-1') END AS CUST_ORDER_INSTALL_PART_REP_POS_NR
    ,FIN_ORDER_CREATE_DT AS FIN_ORDER_CREATE_DT
    ,IFNULL(CUST_ORDER_SID, '-1') AS CUST_ORDER_SID
    ,IFNULL(CUST_SID, '-1') AS CUST_SID
    ,CASE WHEN INSTALL_TYPE_CD = '' THEN '-1' ELSE IFNULL(INSTALL_TYPE_CD, '-1') END AS INSTALL_TYPE_CD
    ,INSTALL_PART_POS_DUE_DT AS INSTALL_PART_POS_DUE_DT
    ,AMT_PAID_LOCAL_VAL AS AMT_PAID_LOCAL_VAL
    ,CASE WHEN CUST_PAYM_METHOD_CD = '' THEN '-1' ELSE IFNULL(CUST_PAYM_METHOD_CD, '-1') END AS CUST_PAYM_METHOD_CD
    ,IS_SETTL_FG AS IS_SETTL_FG
    ,CASE WHEN PAYM_SETTL_TYPE_CD = '' THEN '-1' ELSE IFNULL(PAYM_SETTL_TYPE_CD, '-1') END AS PAYM_SETTL_TYPE_CD
    ,DEBT_COLLECTION_START_DT AS DEBT_COLLECTION_START_DT
    ,IFNULL(INSTALL_WARN_STATUS_CD, '-1') AS INSTALL_WARN_STATUS_CD
    ,CUST_ORDER_NR AS CUST_ORDER_NR
    ,PAYM_REQUEST_DT AS PAYM_REQUEST_DT
    ,AMT_DUNNED_LOCAL_VAL AS AMT_DUNNED_LOCAL_VAL
    ,IS_DUN_NOTICE_REVERSED_FG AS IS_DUN_NOTICE_REVERSED_FG
    ,IFNULL(DEBT_COLLECTION_ITEM_NR, '-1') AS DEBT_COLLECTION_ITEM_NR
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD, '-1') END AS CURR_CD
FROM
    lec_share.v_fact_customer_order_installment_2
WHERE
    DWH_VALID_FG = TRUE
;
