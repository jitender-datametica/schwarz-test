CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_DROPSHIPMENT_MASTER_2
AS
WITH CTE AS (
    SELECT
        *
    FROM
        FE_MSTR_LIDLDIGITAL.V_FACT_GOODS_MOVEMENT_2
    WHERE (WH_LEAVE_ACTUAL_TMSP, CUST_ORDER_SID, CUST_ORDER_POS_NR) IN (
        SELECT
            MAX(WH_LEAVE_ACTUAL_TMSP), CUST_ORDER_SID, CUST_ORDER_POS_NR
        FROM
            FE_MSTR_LIDLDIGITAL.V_FACT_GOODS_MOVEMENT_2
        GROUP BY
            CUST_ORDER_SID, CUST_ORDER_POS_NR
    )
)
SELECT
     FACT_SOL.SUPPLIER_ORDER_NR AS SUPPLIER_ORDER_NR
    ,FACT_SOL.SUPPLIER_ORDER_POS_NR AS SUPPLIER_ORDER_POS_NR
    ,FACT_SOL.SUPPLIER_ORDER_TYPE_CD AS SUPPLIER_ORDER_TYPE_CD
    ,FACT_SOL.PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,FACT_COL.PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,FACT_SOL.SUPPLIER_ORDER_DT AS SUPPLIER_ORDER_DT
    ,FACT_SOL.SUPPLIER_SID AS SUPPLIER_SID
    ,FACT_SOL.CUST_ORDER_SID AS CUST_ORDER_SID
    ,FACT_SOL.CUST_ORDER_NR AS CUST_ORDER_NR
    ,FACT_SOL.CUST_ORDER_POS_NR AS CUST_ORDER_POS_NR
    ,FACT_SOL.PROD_QTY AS PROD_QTY
    ,FACT_SOL.SUPPLIER_ORDER_CANCEL_DT AS SUPPLIER_ORDER_CANCEL_DT

    ,FACT_COL.WSHOP_CD AS WSHOP_CD
    ,FACT_COL.CUST_ORDER_CREATE_TMSP AS CUST_ORDER_CREATE_TMSP
    ,FACT_COL.CUST_ORDER_DT AS CUST_ORDER_DT
    ,FACT_COL.CUST_ORDER_TM AS CUST_ORDER_TM
    ,FACT_COL.CUST_ORDER_CREATE_TIME AS CUST_ORDER_CREATE_TIME
    ,FACT_COL.CUST_ORDER_CREATE_DATE AS CUST_ORDER_CREATE_DATE
    ,FACT_COL.PROD_SID AS PROD_SID
    ,FACT_COL.ARTICLE_SET AS ARTICLE_SET
    ,FACT_COL.PROD_SALE_TYPE_CD AS PROD_SALE_TYPE_CD
    ,FACT_COL.CUST_SID AS CUST_SID
    ,FACT_COL.IS_BUNDLE_HEADER_FG AS IS_BUNDLE_HEADER_FG
    ,FACT_COL.BUNDLE_HEADER_POS_NR AS BUNDLE_HEADER_POS_NR
    ,FACT_COL.DELIVERY_ADDR_SID AS DELIVERY_ADDR_SID
    ,FACT_COL.DELIVERY_CUST_SID AS DELIVERY_CUST_SID
    ,FACT_COL.IS_BLOCKED_DELIVERY_FG AS IS_BLOCKED_DELIVERY_FG
    ,FACT_COL.DELIVERY_BLOCKED_REASON_CD AS DELIVERY_BLOCKED_REASON_CD
    ,FACT_COL.IS_ORDER_CANCEL_FG AS IS_ORDER_CANCEL_FG
    ,FACT_COL.CUST_PAYM_METHOD_CD AS CUST_PAYM_METHOD_CD
    ,FACT_COL.SALES_CHANNEL_TYPE_CD AS SALES_CHANNEL_TYPE_CD
    ,FACT_COL.ORDER_CANCEL_REASON_CD AS ORDER_CANCEL_REASON_CD
    ,FACT_COL.CUST_ORDER_TYPE_CD AS CUST_ORDER_TYPE_CD
    ,FACT_COL.CUST_ORDER_PERFORM_DT AS CUST_ORDER_PERFORM_DT
    ,FACT_COL.CUST_DELIVERY_TGT_DT AS CUST_DELIVERY_TGT_DT
    ,FACT_COL.WH_SID AS WH_SID
    ,FACT_COL.WH_CD AS WH_CD
    ,FACT_COL.PRODUCT_ASSORTIMENT_TYPE_CD AS PRODUCT_ASSORTIMENT_TYPE_CD
    ,FACT_COL.DROPSHIPMENT_ORDER_FG AS DROPSHIPMENT_ORDER_FG
    ,FACT_COL.IS_PART_OF_BUNDLE_HEADER_CNT_FG AS IS_PART_OF_BUNDLE_HEADER_CNT_FG
    ,FACT_COL.IS_PART_OF_BUNDLE_POS_CNT_FG AS IS_PART_OF_BUNDLE_POS_CNT_FG

    ,FACT_GM.DELIVERY_ORDER_SID AS DELIVERY_ORDER_SID
    ,FACT_GM.DELIVERY_ORDER_NR AS DELIVERY_ORDER_NR
    ,FACT_GM.DELIVERY_ORDER_POS_NR AS DELIVERY_ORDER_POS_NR
    ,FACT_GM.GOODS_MOV_CAT_CD AS GOODS_MOV_CAT_CD
    ,FACT_GM.GOODS_MOV_CAT_GROUP_CD AS GOODS_MOV_CAT_GROUP_CD
    ,FACT_GM.GOODS_MOV_ACTUAL_TMSP AS GOODS_MOV_ACTUAL_TMSP
    ,FACT_GM.DELIVERY_PROD_QTY AS DELIVERY_PROD_QTY
    ,FACT_GM.DELIVERY_TYPE_CD AS DELIVERY_TYPE_CD
    ,FACT_GM.DELIVERY_ROUTE_CD AS DELIVERY_ROUTE_CD
    ,FACT_GM.RECIPIENT_COUNTRY_CD AS RECIPIENT_COUNTRY_CD
    ,FACT_GM.STOCK_PLACEMENT_CD AS STOCK_PLACEMENT_CD
    ,FACT_GM.STOCK_REMOVAL_CD AS STOCK_REMOVAL_CD
    ,FACT_GM.STORAGE_LOC_CD AS STORAGE_LOC_CD
    ,FACT_GM.WH_LEAVE_ACTUAL_TMSP AS WH_LEAVE_ACTUAL_TMSP
    ,FACT_GM.WH_LEAVE_ACTUAL_DT AS WH_LEAVE_ACTUAL_DT
    ,FACT_GM.WH_LEAVE_TGT_TMSP AS WH_LEAVE_TGT_TMSP
    ,FACT_GM.WH_LEAVE_TGT_DT AS WH_LEAVE_TGT_DT
    ,FACT_GM.ORDER_ITEM_CATEGORY_CD AS ORDER_ITEM_CATEGORY_CD
    ,FACT_GM.WH_ARRIVE_ACTUAL_DT AS WH_ARRIVE_ACTUAL_DT
    ,FACT_GM.SALE_DOC_TYPE_CD AS SALE_DOC_TYPE_CD
    ,FACT_GM.DELIVERY_TGT_DT AS DELIVERY_TGT_DT

    ,FE_MSTR_LIDLDIGITAL.F_COUNT_WORKING_DAYS(FACT_SOL.SUPPLIER_ORDER_DT, FACT_GM.WH_LEAVE_ACTUAL_DT) AS SUPPLIER_ORDER_TO_WH_LEAVE_IN_DAYS
    ,FE_MSTR_LIDLDIGITAL.F_COUNT_WORKING_DAYS(FACT_COL.CUST_DELIVERY_TGT_DT, FACT_GM.WH_LEAVE_ACTUAL_DT) - 1 AS CUST_DELIVERY_TG_TO_WH_LEAVE_IN_DAYS
    ,FE_MSTR_LIDLDIGITAL.F_COUNT_WORKING_DAYS(FACT_GM.DELIVERY_TGT_DT, FACT_GM.WH_LEAVE_ACTUAL_DT) AS DELIVERY_TG_TO_WH_LEAVE_IN_DAYS
FROM
    FE_MSTR_LIDLDIGITAL.V_FACT_SUPPLIER_ORDER_LINE_2 FACT_SOL
LEFT JOIN
    FE_MSTR_LIDLDIGITAL.V_FACT_CUSTOMER_ORDER_LINE_2 FACT_COL
    ON
        FACT_COL.CUST_ORDER_SID = FACT_SOL.CUST_ORDER_SID
        AND FACT_COL.CUST_ORDER_POS_NR = FACT_SOL.CUST_ORDER_POS_NR
        AND FACT_COL.GC_LC_CD = 'GC'
LEFT JOIN
    CTE FACT_GM
    ON
        FACT_GM.SUPPLIER_ORDER_NR = FACT_SOL.SUPPLIER_ORDER_NR
        AND FACT_GM.SUPPLIER_ORDER_POS_NR = FACT_SOL.SUPPLIER_ORDER_POS_NR
;
