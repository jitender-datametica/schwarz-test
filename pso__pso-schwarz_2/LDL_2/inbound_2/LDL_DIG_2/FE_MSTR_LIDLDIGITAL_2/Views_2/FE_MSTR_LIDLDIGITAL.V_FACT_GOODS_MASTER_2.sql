    FE_MSTR_LIDLDIGITAL.V_FACT_GOODS_MOVEMENT_2 AS FACT_GM
LEFT OUTER JOIN
    FE_MSTR_LIDLDIGITAL.V_REL_ORDER_PACKAGING_2 AS REL_OP
    ON
        FACT_GM.DELIVERY_ORDER_POS_NR = REL_OP.DELIVERY_ORDER_POS_NR
        AND FACT_GM.DELIVERY_ORDER_NR = REL_OP.DELIVERY_ORDER_NR

LEFT OUTER JOIN
    FE_MSTR_LIDLDIGITAL.V_FACT_GOODS_PACKAGE_SHIPMENT_2 AS FACT_GPS
    ON
        FACT_GPS.PACK_SID = REL_OP.PACK_SID

