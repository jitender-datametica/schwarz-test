CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_GOODS_MOVEMENT_2(
	WSHOP_CD
    ,DIST_CHANNEL_CD
	,DELIVERY_ORDER_SID
	,DELIVERY_ORDER_NR
	,DELIVERY_ORDER_POS_NR
	,GOODS_MOV_CAT_CD
	,GOODS_MOV_CAT_GROUP_CD
	,GOODS_MOV_ACTUAL_TMSP
	,PROD_VARIANT_SID
	,DELIVERY_PROD_QTY
	,DELIVERY_TYPE_CD
	,DELIVERY_ROUTE_CD
	,RECIPIENT_COUNTRY_CD
	,STOCK_PLACEMENT_CD
	,STOCK_REMOVAL_CD
	,CUST_ORDER_SID
	,CUST_ORDER_POS_NR
	,CUST_SID
    ,IC_ORDER_SID
    ,IC_ORDER_POS_NR
    ,IC_ORDER_NR
	,DELIVERY_ADDR_SID
	,WH_SID
	,WH_CD
	,STORAGE_LOC_CD
	,WH_LEAVE_ACTUAL_TMSP
	,WH_LEAVE_ACTUAL_DT
	,WH_LEAVE_TGT_TMSP
	,WH_LEAVE_TGT_DT
	,ORDER_ITEM_CATEGORY_CD
	,SUPPLIER_ORDER_NR
	,SUPPLIER_ORDER_POS_NR
	,DROPSHIPMENT_ORDER_FG
	,WH_ARRIVE_ACTUAL_DT
	,SALE_DOC_TYPE_CD
	,DELIVERY_TGT_DT
	,PROD_VARIANT_NR
	,CUST_ORDER_NR
) AS SELECT
     IFNULL(WSHOP_CD, '-1') AS WSHOP_CD
    ,IFNULL(DIST_CHANNEL_CD,'-1') AS DIST_CHANNEL_CD                                                                                              --PARKSIDE
    ,IFNULL(DELIVERY_ORDER_SID, '-1') AS DELIVERY_ORDER_SID
    ,DELIVERY_ORDER_NR AS DELIVERY_ORDER_NR
    ,DELIVERY_ORDER_POS_NR AS DELIVERY_ORDER_POS_NR
    ,CASE WHEN GOODS_MOV_CAT_CD = '' THEN '-1' ELSE IFNULL(GOODS_MOV_CAT_CD, '-1') END AS GOODS_MOV_CAT_CD
    ,CASE WHEN GOODS_MOV_CAT_GROUP_CD = '' THEN '-1' ELSE IFNULL(GOODS_MOV_CAT_GROUP_CD, '-1') END AS GOODS_MOV_CAT_GROUP_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', GOODS_MOV_ACTUAL_TMSP)::TIMESTAMP_NTZ AS GOODS_MOV_ACTUAL_TMSP
    ,IFNULL(PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,DELIVERY_PROD_QTY AS DELIVERY_PROD_QTY
    ,CASE WHEN DELIVERY_TYPE_CD = '' THEN '-1' ELSE IFNULL(DELIVERY_TYPE_CD, '-1') END AS DELIVERY_TYPE_CD
    ,CASE WHEN DELIVERY_ROUTE_CD = '' THEN '-1' ELSE IFNULL(DELIVERY_ROUTE_CD, '-1') END AS DELIVERY_ROUTE_CD
    ,CASE WHEN RECIPIENT_COUNTRY_CD = '' THEN '-1' ELSE IFNULL(RECIPIENT_COUNTRY_CD, '-1') END AS RECIPIENT_COUNTRY_CD
    ,CASE WHEN STOCK_PLACEMENT_CD = '' THEN '-1' ELSE IFNULL(STOCK_PLACEMENT_CD, '-1') END AS STOCK_PLACEMENT_CD
    ,CASE WHEN STOCK_REMOVAL_CD = '' THEN '-1' ELSE IFNULL(STOCK_REMOVAL_CD, '-1') END AS STOCK_REMOVAL_CD
    ,IFNULL(CUST_ORDER_SID, '-1') AS CUST_ORDER_SID
    ,CUST_ORDER_POS_NR AS CUST_ORDER_POS_NR
    ,IFNULL(CUST_SID, '-1') AS CUST_SID
    ,IFNULL(IC_ORDER_SID,'-1') AS IC_ORDER_SID                                                                                                    --PARKSIDE
    ,IFNULL(IC_ORDER_POS_NR,'-1') AS IC_ORDER_POS_NR                                                                                              --PARKSIDE
    ,IFNULL(IC_ORDER_NR,'-1') AS IC_ORDER_NR                                                                                                      --PARKSIDE
    ,IFNULL(DELIVERY_ADDR_SID, '-1') AS DELIVERY_ADDR_SID
    ,IFNULL(WH_SID, '-1') AS WH_SID
    ,CASE WHEN WH_CD = '' THEN '-1' ELSE IFNULL(WH_CD, '-1') END AS WH_CD
    ,CASE WHEN STORAGE_LOC_CD = '' THEN '-1' ELSE IFNULL(STORAGE_LOC_CD, '-1') END AS STORAGE_LOC_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', WH_LEAVE_ACTUAL_TMSP)::TIMESTAMP_NTZ AS WH_LEAVE_ACTUAL_TMSP
    ,DATE(WH_LEAVE_ACTUAL_TMSP) AS WH_LEAVE_ACTUAL_DT
    ,CONVERT_TIMEZONE('Europe/Berlin', WH_LEAVE_TGT_TMSP)::TIMESTAMP_NTZ AS WH_LEAVE_TGT_TMSP
    ,DATE(WH_LEAVE_TGT_TMSP) AS WH_LEAVE_TGT_DT
    ,CASE WHEN ORDER_ITEM_CATEGORY_CD = '' THEN '-1' ELSE IFNULL(ORDER_ITEM_CATEGORY_CD, '-1') END AS ORDER_ITEM_CATEGORY_CD
    ,CASE WHEN SUPPLIER_ORDER_NR = '' THEN '-1' ELSE IFNULL(SUPPLIER_ORDER_NR, '-1') END AS SUPPLIER_ORDER_NR
    ,IFNULL(SUPPLIER_ORDER_POS_NR, '-1') AS SUPPLIER_ORDER_POS_NR
    ,DROPSHIPMENT_ORDER_FG AS DROPSHIPMENT_ORDER_FG
    ,WH_ARRIVE_ACTUAL_DT AS WH_ARRIVE_ACTUAL_DT
    ,CASE WHEN SALE_DOC_TYPE_CD = '' THEN '-1' ELSE IFNULL(SALE_DOC_TYPE_CD, '-1') END AS SALE_DOC_TYPE_CD
    ,DELIVERY_TGT_DT  AS DELIVERY_TGT_DT
    ,PROD_VARIANT_NR AS PROD_VARIANT_NR
    ,CUST_ORDER_NR AS CUST_ORDER_NR
FROM
    lec_share.v_fact_goods_movement_2
;