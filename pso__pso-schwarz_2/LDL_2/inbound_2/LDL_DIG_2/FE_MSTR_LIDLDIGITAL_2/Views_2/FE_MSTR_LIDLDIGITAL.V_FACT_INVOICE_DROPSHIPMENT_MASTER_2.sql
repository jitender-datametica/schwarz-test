CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_INVOICE_DROPSHIPMENT_MASTER_2(
    SUPPLIER_ORDER_NR
    ,SUPPLIER_ORDER_POS_NR
    ,SUPPLIER_ORDER_DT
    ,SUPPLIER_ORDER_TYPE_CD
    ,PROD_PRICE_VAT_PCT
    ,PROD_PRICE_VAT_VAL
    ,PROD_PRICE_GROSS_LOCAL_VAL
    ,SUPPLIER_SID
    ,SUPPLIER_NR
    ,BOOKING_DT
    ,PROD_VARIANT_SID
    ,PROD_VARIANT_NR
    ,CUST_ORDER_NR
    ,DELIVERY_SRC_TYPE_CD
    ,MATERIAL_DOC_MOV_TYPE_CD
    ,WH_LEAVE_ACTUAL_DT
    ,PURCH_INVOICE_NR
    ,PURCH_INVOICE_POS_NR
    ,PURCH_AMT_NET_LOCAL_VAL
    ,INVOICE_PROD_QTY
    ,PROD_VARIANT_DESCR
    ,PRICE_VAL
    ,PRICE_VAL_TOTAL
    ,GC_LC_CD
) AS SELECT
     IFNULL(FACT_SOL.SUPPLIER_ORDER_NR, '-1') AS SUPPLIER_ORDER_NR
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_POS_NR, '-1') AS SUPPLIER_ORDER_POS_NR
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_DT, '-1') AS SUPPLIER_ORDER_DT
    ,IFNULL(FACT_SOL.SUPPLIER_ORDER_TYPE_CD, '-1') AS SUPPLIER_ORDER_TYPE_CD
    ,FACT_SOL.PROD_PRICE_VAT_PCT
    ,FACT_PIL.PURCH_AMT_NET_LOCAL_VAL * FACT_SOL.PROD_PRICE_VAT_PCT AS PROD_PRICE_VAT_VAL --> Tax Value
    ,FACT_PIL.PURCH_AMT_NET_LOCAL_VAL * (1+(FACT_SOL.PROD_PRICE_VAT_PCT)) AS PROD_PRICE_GROSS_LOCAL_VAL --> Gross Local Value
    ,IFNULL(FACT_SOL.SUPPLIER_SID, '-1') AS SUPPLIER_SID
    ,IFNULL(FACT_SOL.SUPPLIER_NR, '-1') AS SUPPLIER_NR
    ,IFNULL(FACT_MDL.BOOKING_DT, '-1') AS BOOKING_DT
    ,IFNULL(FACT_MDL.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,IFNULL(FACT_MDL.PROD_VARIANT_NR, '-1') AS PROD_VARIANT_NR
    ,IFNULL(FACT_MDL.CUST_ORDER_NR, '-1') AS CUST_ORDER_NR
    ,IFNULL(FACT_MDL.DELIVERY_SRC_TYPE_CD, '-1') AS DELIVERY_SRC_TYPE_CD
    ,IFNULL(FACT_MDL.MATERIAL_DOC_MOV_TYPE_CD, '-1') AS MATERIAL_DOC_MOV_TYPE_CD
    ,IFNULL(DATE(FACT_GM.WH_LEAVE_ACTUAL_TMSP), '-1') AS WH_LEAVE_ACTUAL_DT
    ,IFNULL(FACT_PIL.PURCH_INVOICE_NR, '-1') AS PURCH_INVOICE_NR
    ,IFNULL(FACT_PIL.PURCH_INVOICE_POS_NR, '-1') AS PURCH_INVOICE_POS_NR
    ,FACT_PIL.PURCH_AMT_NET_LOCAL_VAL
    ,FACT_PIL.PROD_QTY AS INVOICE_PROD_QTY
    ,IFNULL(DIM_PV.PROD_VARIANT_DESCR, '-1') AS PROD_VARIANT_DESCR
    ,FACT_PPS.PRICE_VAL
    ,INVOICE_PROD_QTY * FACT_PPS.PRICE_VAL AS PRICE_VAL_TOTAL --> Total Freight Costs 
    ,'GC' AS GC_LC_CD
FROM 
    lec_share.v_fact_material_document_line_2 AS FACT_MDL
LEFT OUTER JOIN
    lec_share.v_fact_supplier_order_line_2 AS FACT_SOL
    ON
            FACT_SOL.SUPPLIER_ORDER_NR = FACT_MDL.SUPPLIER_ORDER_NR
        AND FACT_SOL.SUPPLIER_ORDER_POS_NR = FACT_MDL.SUPPLIER_ORDER_POS_NR
LEFT OUTER JOIN
    lec_share.v_fact_purchase_invoice_line_2 AS FACT_PIL
    ON
        FACT_MDL.REF_DOC_NR= FACT_PIL.REF_DOC_NR
        AND FACT_MDL.REF_DOC_POS_NR = FACT_PIL.REF_DOC_POS_NR
LEFT OUTER JOIN
    (SELECT
        T2.WSHOP_CD
        ,SUPPLIER_ORDER_NR
        ,MAX(WH_LEAVE_ACTUAL_TMSP) AS WH_LEAVE_ACTUAL_TMSP
    FROM
        lec_share.v_fact_goods_movement_2 AS T1_2
        LEFT OUTER JOIN
            lec_share.v_fact_customer_order_line_2 AS T2
        ON
            T1.CUST_ORDER_SID = T2.CUST_ORDER_SID
        AND T1.CUST_ORDER_POS_NR = T2.CUST_ORDER_POS_NR
    GROUP BY
        SUPPLIER_ORDER_NR
        ,T2.WSHOP_CD
    ) AS FACT_GM
    ON
        FACT_GM.SUPPLIER_ORDER_NR = FACT_MDL.SUPPLIER_ORDER_NR
LEFT OUTER JOIN
    lec_share.v_dim_product_variant_2 AS DIM_PV
    ON
        DIM_PV.PROD_VARIANT_SID = FACT_MDL.PROD_VARIANT_SID
LEFT OUTER JOIN
    lec_share.v_fact_product_price_supplier_2 AS FACT_PPS
    ON
            FACT_PPS.WSHOP_CD = FACT_GM.WSHOP_CD
        AND FACT_PPS.PROD_VARIANT_SID = FACT_MDL.PROD_VARIANT_SID
        AND FACT_PPS.SUPPLIER_SID = DIM_PV.MAIN_SUPPLIER_SID 
        AND FACT_MDL.BOOKING_DT BETWEEN FACT_PPS.ACTIVE_FROM_TMSP AND FACT_PPS.ACTIVE_TO_TMSP
WHERE
        FACT_PPS.PRICE_TYPE_CD = 'FKZ'
    AND FACT_MDL.MATERIAL_DOC_MOV_TYPE_CD = '101'
    AND DIM_PV.DWH_VALID_FG
    AND FACT_SOL.DWH_VALID_FG
    AND FACT_MDL.REF_DOC_NR IS NOT NULL
;