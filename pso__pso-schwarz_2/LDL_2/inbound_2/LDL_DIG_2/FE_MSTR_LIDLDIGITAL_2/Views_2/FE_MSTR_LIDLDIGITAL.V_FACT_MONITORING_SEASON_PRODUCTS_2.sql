CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_MONITORING_SEASON_PRODUCTS_2(
	 PROD_SID
    ,PROD_NR
    ,PROD_NAME
    ,WH_SID
    ,WH_CD
    ,CORRECT_UTILISATION
    ,UTIL_ACTION_CD
    ,TOTAL_STOCK_CNT
    ,TOTAL_STOCK_VAL
    ,BLOCKED_STOCK_CNT
    ,BLOCKED_STOCK_VAL
    ,UNRESTRICTED_STOCK_CNT
    ,UNRESTRICTED_STOCK_VAL
    ,BE_PROD_QTY_LAST_WEEK
    ,BE_PROD_QTY_LAST_2_WEEKS
    ,BE_PROD_QTY_LAST_6_WEEKS
    ,BE_LAST_SALES_DATE
    ,CZ_PROD_QTY_LAST_WEEK
    ,CZ_PROD_QTY_LAST_2_WEEKS
    ,CZ_PROD_QTY_LAST_6_WEEKS
    ,CZ_LAST_SALES_DATE
    ,DE_PROD_QTY_LAST_WEEK
    ,DE_PROD_QTY_LAST_2_WEEKS
    ,DE_PROD_QTY_LAST_6_WEEKS
    ,DE_LAST_SALES_DATE
    ,FR_PROD_QTY_LAST_WEEK
    ,FR_PROD_QTY_LAST_2_WEEKS
    ,FR_PROD_QTY_LAST_6_WEEKS
    ,FR_LAST_SALES_DATE
    ,NL_PROD_QTY_LAST_WEEK
    ,NL_PROD_QTY_LAST_2_WEEKS
    ,NL_PROD_QTY_LAST_6_WEEKS
    ,NL_LAST_SALES_DATE
    ,PL_PROD_QTY_LAST_WEEK
    ,PL_PROD_QTY_LAST_2_WEEKS
    ,PL_PROD_QTY_LAST_6_WEEKS
    ,PL_LAST_SALES_DATE
    ,SK_PROD_QTY_LAST_WEEK
    ,SK_PROD_QTY_LAST_2_WEEKS
    ,SK_PROD_QTY_LAST_6_WEEKS
    ,SK_LAST_SALES_DATE
    ,PROD_QTY_LAST_WEEK
    ,PROD_QTY_LAST_WEEK_LESS_7_FG
    ,LAST_SALES_DATE
    ,BE_PROD_ONLINE_STATUS_CD
    ,CZ_PROD_ONLINE_STATUS_CD
    ,DE_PROD_ONLINE_STATUS_CD
    ,FR_PROD_ONLINE_STATUS_CD
    ,NL_PROD_ONLINE_STATUS_CD
    ,PL_PROD_ONLINE_STATUS_CD
    ,SK_PROD_ONLINE_STATUS_CD
    ,PALETTE_CAPACITY_CNT
    ,PROD_MANAGER_NAME
    ,BE_NEXT_PROMOTION_START_DATE
    ,CZ_NEXT_PROMOTION_START_DATE
    ,DE_NEXT_PROMOTION_START_DATE
    ,FR_NEXT_PROMOTION_START_DATE
    ,NL_NEXT_PROMOTION_START_DATE
    ,PL_NEXT_PROMOTION_START_DATE
    ,SK_NEXT_PROMOTION_START_DATE
    ,NEXT_PROMOTION_START_DATE
    ,NEXT_PROMOTION_START_DATE_OUTSIDE_NEXT_4_WEEKS_FG
    ,BE_TGT_PROD_SALE_QTY
    ,CZ_TGT_PROD_SALE_QTY
    ,DE_TGT_PROD_SALE_QTY
    ,FR_TGT_PROD_SALE_QTY
    ,NL_TGT_PROD_SALE_QTY
    ,PL_TGT_PROD_SALE_QTY
    ,SK_TGT_PROD_SALE_QTY
    ,PROMO_SEASON_CD
    ,NEXT_DELIVERY_CY_WEEK
    ,NO_UPCOMING_DELIVERY_FG
    ,LAST_DELIVERY_CY_WEEK
    ,LAST_DELIVERY_MORE_THAN_8_WEEKS_AGO_FG
) AS
WITH 
    STOCK AS(
        SELECT	
        	 PROD.PROD_SID AS PROD_SID
            ,PROD.PROD_NR AS PROD_NR
            ,MAX(PROD.PROD_NAME) AS PROD_NAME
        	,SWD.WH_SID AS WH_SID
            ,SWD.WH_CD AS WH_CD
        	,MIN(PROD_UT_DT.CORRECT_UTILISATION) AS CORRECT_UTILISATION
        	,MIN(PROD_UT.UTIL_ACTION_CD) AS UTIL_ACTION_CD
        	,SUM(SWD.TOTAL_STOCK_CNT) AS TOTAL_STOCK_CNT
            ,SUM(SWD.TOTAL_STOCK_CNT * FACT_PPS.PRICE_VAL) AS TOTAL_STOCK_VAL
            ,SUM(SWD.BLOCKED_STOCK_CNT) AS BLOCKED_STOCK_CNT
            ,SUM(SWD.BLOCKED_STOCK_CNT * FACT_PPS.PRICE_VAL) AS BLOCKED_STOCK_VAL
            ,SUM(SWD.UNRESTRICTED_STOCK_CNT) AS UNRESTRICTED_STOCK_CNT
            ,SUM(SWD.UNRESTRICTED_STOCK_CNT * FACT_PPS.PRICE_VAL) AS UNRESTRICTED_STOCK_VAL
        FROM lec_share.v_fact_stock_warehouse_daily_2 AS SWD
        LEFT JOIN lec_share.v_dim_product_variant_2 AS PROD_VAR
            ON SWD.PROD_VARIANT_SID = PROD_VAR.PROD_VARIANT_SID
            AND PROD_VAR.DWH_VALID_FG
            AND SWD.ACTIVE_FG
        INNER JOIN
            (SELECT	
                 TEMP_SWD.ACTIVE_FG AS ACTIVE_FG
                ,TEMP_PROD_VAR.PROD_SID AS PROD_SID
                ,TEMP_SWD.WH_SID AS WH_SID
            FROM lec_share.v_fact_stock_warehouse_daily_2 AS TEMP_SWD
            LEFT JOIN lec_share.v_dim_product_variant_2 AS TEMP_PROD_VAR
        	    ON TEMP_SWD.PROD_VARIANT_SID = TEMP_PROD_VAR.PROD_VARIANT_SID
                WHERE TEMP_PROD_VAR.DWH_VALID_FG
                AND TEMP_SWD.ACTIVE_FG
                GROUP BY
                     TEMP_SWD.ACTIVE_FG
                    ,TEMP_PROD_VAR.PROD_SID
                    ,TEMP_SWD.WH_SID
                HAVING SUM(TEMP_SWD.TOTAL_STOCK_CNT) > 0.0 OR SUM(TEMP_SWD.TOTAL_STOCK_CNT) < 0.0) AS FILTER
            ON (SWD.WH_SID = FILTER.WH_SID 
        	AND PROD_VAR.PROD_SID = FILTER.PROD_SID)
        LEFT JOIN lec_share.v_dim_product_2 AS PROD
        	ON PROD_VAR.PROD_SID = PROD.PROD_SID
            AND PROD.DWH_VALID_FG
        LEFT JOIN lec_share.v_dim_product_utilisation_date_core_view_2 AS PROD_UT_DT
        	ON PROD_VAR.PROD_SID = PROD_UT_DT.PROD_SID
        LEFT JOIN lec_share.v_fact_product_utilisation_2 AS PROD_UT
        	ON PROD_VAR.PROD_SID = PROD_UT.PROD_SID
            AND PROD_UT.DWH_VALID_FG
        LEFT JOIN
            lec_share.v_fact_product_price_supplier_2 AS FACT_PPS
            ON
                FACT_PPS.SUPPLIER_SID = PROD_VAR.MAIN_SUPPLIER_SID
                AND FACT_PPS.PROD_VARIANT_SID = PROD_VAR.PROD_VARIANT_SID
                AND SWD.CAL_DT BETWEEN FACT_PPS.ACTIVE_FROM_TMSP AND FACT_PPS.ACTIVE_TO_TMSP
                AND FACT_PPS.WSHOP_CD = 'DE' -- DE BUYS ALL ARTICLES
                AND FACT_PPS.PRICE_TYPE_CD = 'EKP'
                AND FACT_PPS.CURR_CD = 'EUR'
        WHERE SWD.ACTIVE_FG
        GROUP BY
        	 PROD.PROD_SID
            ,PROD.PROD_NR
            ,SWD.WH_SID
            ,SWD.WH_CD
    )
    ,SALES_2 AS(
        SELECT
             PROD_REG.PROD_SID AS PROD_SID
            ,CUST_ORD.WH_SID AS WH_SID
        	,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'BE' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS BE_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'BE' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS BE_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'BE' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS BE_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'BE' THEN CAL_D.CAL_DT ELSE NULL END) AS BE_LAST_SALES_DATE
            
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'CZ' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS CZ_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'CZ' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS CZ_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'CZ' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS CZ_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'CZ' THEN CAL_D.CAL_DT ELSE NULL END) AS CZ_LAST_SALES_DATE
            
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'DE' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS DE_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'DE' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS DE_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'DE' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS DE_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'DE' THEN CAL_D.CAL_DT ELSE NULL END) AS DE_LAST_SALES_DATE
            
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'FR' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS FR_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'FR' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS FR_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'FR' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS FR_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'FR' THEN CAL_D.CAL_DT ELSE NULL END) AS FR_LAST_SALES_DATE
            
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'NL' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS NL_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'NL' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS NL_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'NL' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS NL_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'NL' THEN CAL_D.CAL_DT ELSE NULL END) AS NL_LAST_SALES_DATE
            
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'PL' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS PL_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'PL' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS PL_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'PL' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS PL_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'PL' THEN CAL_D.CAL_DT ELSE NULL END) AS PL_LAST_SALES_DATE
            
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 AND CUST_ORD.WSHOP_CD = 'SK' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS SK_PROD_QTY_LAST_WEEK
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -14 AND -1 AND CUST_ORD.WSHOP_CD = 'SK' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS SK_PROD_QTY_LAST_2_WEEKS
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1 AND CUST_ORD.WSHOP_CD = 'SK' THEN CUST_ORD.PROD_QTY ELSE NULL END) AS SK_PROD_QTY_LAST_6_WEEKS
            ,MAX(CASE WHEN CUST_ORD.WSHOP_CD = 'SK' THEN CAL_D.CAL_DT ELSE NULL END) AS SK_LAST_SALES_DATE
        
            ,SUM(CASE WHEN CAL_D.CAL_DT_OFFSET BETWEEN -7 AND -1 THEN CUST_ORD.PROD_QTY ELSE NULL END) AS PROD_QTY_LAST_WEEK
            ,CASE WHEN PROD_QTY_LAST_WEEK <= 7 THEN 1 ELSE 0 END AS PROD_QTY_LAST_WEEK_LESS_7_FG
            ,MAX(CAL_D.CAL_DT) AS LAST_SALES_DATE
        FROM lec_share.v_fact_customer_order_line_2 AS CUST_ORD
        	LEFT JOIN lec_share.v_rel_product_variant_regional_2 AS PROD_VAR_REG
        	  ON (CUST_ORD.PROD_VARIANT_SID = PROD_VAR_REG.PROD_VARIANT_SID
        	      AND CUST_ORD.WSHOP_CD = PROD_VAR_REG.WSHOP_CD)
                  AND PROD_VAR_REG.DWH_VALID_FG
        	LEFT JOIN lec_share.v_rel_product_regional_2 AS PROD_REG
        	  ON (PROD_VAR_REG.PROD_SID = PROD_REG.PROD_SID
        	      AND PROD_VAR_REG.WSHOP_CD = PROD_REG.WSHOP_CD)
                  AND PROD_REG.DWH_VALID_FG
        	LEFT JOIN lec_share.v_dim_cal_day_2 AS CAL_D
        	  ON (CUST_ORD.CUST_ORDER_DT = CAL_D.CAL_DT)
        WHERE (CAL_D.CAL_DT_OFFSET BETWEEN -42 AND -1
               AND CUST_ORD.IS_ORDER_CANCEL_FG IN (0)
               AND IS_PART_OF_BUNDLE_HEADER_CNT_FG)
        GROUP BY
             PROD_REG.PROD_SID
            ,CUST_ORD.WH_SID 
    )
    ,PRODUCT AS (
        SELECT
            PROD.PROD_SID AS PROD_SID
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'BE' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS BE_PROD_ONLINE_STATUS_CD
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'CZ' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS CZ_PROD_ONLINE_STATUS_CD
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'DE' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS DE_PROD_ONLINE_STATUS_CD
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'FR' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS FR_PROD_ONLINE_STATUS_CD
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'NL' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS NL_PROD_ONLINE_STATUS_CD
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'PL' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS PL_PROD_ONLINE_STATUS_CD
            ,TO_NUMBER(MIN(CASE WHEN PROD_REG.WSHOP_CD = 'SK' THEN CASE WHEN TRIM(PROD_VAR_REG.PROD_ONLINE_STATUS_CD) = '' THEN '-1' ELSE IFNULL(PROD_VAR_REG.PROD_ONLINE_STATUS_CD , '-1') END ELSE NULL END)) AS SK_PROD_ONLINE_STATUS_CD
            ,MAX(PROD_VAR.PALETTE_CAPACITY_CNT) AS PALETTE_CAPACITY_CNT
            ,MAX(PROD_MNGR.PROD_MANAGER_NAME) AS PROD_MANAGER_NAME
        FROM lec_share.v_dim_product_2 AS PROD
        	LEFT JOIN lec_share.v_rel_product_regional_2 AS PROD_REG
        	  ON (PROD.PROD_SID = PROD_REG.PROD_SID)
              AND PROD_REG.DWH_VALID_FG
        	LEFT JOIN lec_share.v_rel_product_variant_regional_2 AS PROD_VAR_REG
        	  ON (PROD.PROD_SID = PROD_VAR_REG.PROD_SID 
        	      AND PROD_REG.WSHOP_CD = PROD_VAR_REG.WSHOP_CD)
              AND PROD_VAR_REG.DWH_VALID_FG
        	LEFT JOIN lec_share.v_dim_product_variant_2 AS PROD_VAR
        	  ON (PROD_VAR_REG.PROD_VARIANT_SID = PROD_VAR.PROD_VARIANT_SID)
              AND PROD_VAR.DWH_VALID_FG
            LEFT JOIN lec_share.v_dim_product_manager_2 AS PROD_MNGR
              ON (PROD.PROD_MANAGER_CD = PROD_MNGR.PROD_MANAGER_CD)
        WHERE PROD.DWH_VALID_FG
        GROUP BY PROD.PROD_SID
    )
    ,AMC AS (
        WITH PROMO_START AS
            (SELECT
                 PROD_SID
                ,WSHOP_CD
                ,MIN(CASE WHEN WSHOP_CD = 'BE' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS BE_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN WSHOP_CD = 'CZ' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS CZ_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN WSHOP_CD = 'DE' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS DE_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN WSHOP_CD = 'FR' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS FR_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN WSHOP_CD = 'NL' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS NL_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN WSHOP_CD = 'PL' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS PL_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN WSHOP_CD = 'SK' AND PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS SK_NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN PROMO_START_DT - CURRENT_DATE() > 0 THEN PROMO_START_DT ELSE NULL END) AS NEXT_PROMOTION_START_DATE
                ,MIN(CASE WHEN PROMO_START_DT - CURRENT_DATE() BETWEEN 0 AND 28 THEN 0 ELSE 1 END) AS NEXT_PROMOTION_START_DATE_OUTSIDE_NEXT_4_WEEKS_FG
                ,MAX(PROMO_SEASON_CD) AS PROMO_SEASON_CD
            FROM lec_share.v_dim_sales_promotion_2
            WHERE DWH_VALID_FG
            GROUP BY 
                PROD_SID
                ,WSHOP_CD)        
            ,DELIVERY AS
            (SELECT
                 PROD_SID
                ,MIN(CASE WHEN CAL_WEEK.CY_WEEK_OFFSET > 0 THEN SALES_PROMO.FIRST_DELIVERY_CY_WEEK ELSE NULL END) AS NEXT_DELIVERY_CY_WEEK
                ,MIN(CASE WHEN CAL_WEEK.CY_WEEK_OFFSET > 0 THEN CAL_WEEK.CY_WEEK_OFFSET ELSE NULL END) AS NEXT_DELIVERY_CY_WEEK_OFFSET
                ,CASE WHEN NEXT_DELIVERY_CY_WEEK IS NULL THEN 1 ELSE 0 END AS NO_UPCOMING_DELIVERY_FG
                ,MAX(CASE WHEN CAL_WEEK.CY_WEEK_OFFSET < 0 THEN SALES_PROMO.FIRST_DELIVERY_CY_WEEK ELSE NULL END) AS LAST_DELIVERY_CY_WEEK
                ,MAX(CASE WHEN CAL_WEEK.CY_WEEK_OFFSET < 0 THEN CAL_WEEK.CY_WEEK_OFFSET ELSE NULL END) AS LAST_DELIVERY_CY_WEEK_OFFSET
                ,CASE WHEN LAST_DELIVERY_CY_WEEK_OFFSET < -8 THEN 1 ELSE 0 END AS LAST_DELIVERY_MORE_THAN_8_WEEKS_AGO_FG
            FROM lec_share.v_dim_sales_promotion_2 AS SALES_PROMO
            LEFT JOIN lec_share.v_dim_cal_week_2 AS CAL_WEEK
                ON SALES_PROMO.FIRST_DELIVERY_CY_WEEK = CAL_WEEK.CY_WEEK
            WHERE DWH_VALID_FG
            GROUP BY PROD_SID)
        
        SELECT
             PROMO_START.PROD_SID
            ,MIN(PROMO_START.BE_NEXT_PROMOTION_START_DATE) AS BE_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.CZ_NEXT_PROMOTION_START_DATE) AS CZ_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.DE_NEXT_PROMOTION_START_DATE) AS DE_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.FR_NEXT_PROMOTION_START_DATE) AS FR_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.NL_NEXT_PROMOTION_START_DATE) AS NL_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.PL_NEXT_PROMOTION_START_DATE) AS PL_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.SK_NEXT_PROMOTION_START_DATE) AS SK_NEXT_PROMOTION_START_DATE
            ,MIN(PROMO_START.NEXT_PROMOTION_START_DATE) AS NEXT_PROMOTION_START_DATE
            ,MIN(NEXT_PROMOTION_START_DATE_OUTSIDE_NEXT_4_WEEKS_FG) AS NEXT_PROMOTION_START_DATE_OUTSIDE_NEXT_4_WEEKS_FG
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'BE' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS BE_TGT_PROD_SALE_QTY
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'CZ' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS CZ_TGT_PROD_SALE_QTY
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'DE' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS DE_TGT_PROD_SALE_QTY
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'FR' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS FR_TGT_PROD_SALE_QTY
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'NL' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS NL_TGT_PROD_SALE_QTY
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'PL' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS PL_TGT_PROD_SALE_QTY
            ,SUM(CASE WHEN PROMO_START.WSHOP_CD = 'SK' THEN SALES_PROMO.TGT_PROD_SALE_QTY ELSE NULL END) AS SK_TGT_PROD_SALE_QTY
            ,MAX(PROMO_START.PROMO_SEASON_CD) AS PROMO_SEASON_CD
            ,MAX(DELIVERY.NEXT_DELIVERY_CY_WEEK) AS NEXT_DELIVERY_CY_WEEK
            ,MAX(DELIVERY.NO_UPCOMING_DELIVERY_FG) AS NO_UPCOMING_DELIVERY_FG
            ,MAX(DELIVERY.LAST_DELIVERY_CY_WEEK) AS LAST_DELIVERY_CY_WEEK
            ,MAX(DELIVERY.LAST_DELIVERY_MORE_THAN_8_WEEKS_AGO_FG) AS LAST_DELIVERY_MORE_THAN_8_WEEKS_AGO_FG
        FROM PROMO_START
        LEFT JOIN DELIVERY
            ON PROMO_START.PROD_SID = DELIVERY.PROD_SID
        LEFT JOIN lec_share.v_dim_sales_promotion_2 AS SALES_PROMO
            ON (
                PROMO_START.PROD_SID = SALES_PROMO.PROD_SID AND
                PROMO_START.WSHOP_CD = SALES_PROMO.WSHOP_CD AND
                    (PROMO_START.BE_NEXT_PROMOTION_START_DATE = SALES_PROMO.PROMO_START_DT OR
                    PROMO_START.CZ_NEXT_PROMOTION_START_DATE = SALES_PROMO.PROMO_START_DT OR
                    PROMO_START.DE_NEXT_PROMOTION_START_DATE = SALES_PROMO.PROMO_START_DT OR
                    PROMO_START.FR_NEXT_PROMOTION_START_DATE = SALES_PROMO.PROMO_START_DT OR
                    PROMO_START.NL_NEXT_PROMOTION_START_DATE = SALES_PROMO.PROMO_START_DT OR
                    PROMO_START.PL_NEXT_PROMOTION_START_DATE = SALES_PROMO.PROMO_START_DT OR
