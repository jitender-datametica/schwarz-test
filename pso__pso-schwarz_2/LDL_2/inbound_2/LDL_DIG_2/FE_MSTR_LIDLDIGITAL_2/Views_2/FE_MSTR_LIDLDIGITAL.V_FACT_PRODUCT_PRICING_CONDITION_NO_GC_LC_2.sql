CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_PRICING_CONDITION_NO_GC_LC_2
/*
    This view is referenced in V_FACT_ARTICLE_MASTER.
*/
AS
WITH CTE AS (
    SELECT
         PPC_FACT.WSHOP_CD AS WSHOP_CD
        ,IFNULL(PPC_FACT.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
        ,TAX_DIM.TAX_CLASS_PCT AS TAX_CLASS_PCT

        ,CASE WHEN PRICE_TYPE_CD = 'VKP' THEN PPC_FACT.CURR_CD END AS VKP_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'VKP' THEN PPC_FACT.PRICE_VAL END AS VKP_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'VKP' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS VKP_PRICE_GROSS_EUR_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'VKP' THEN VKP_PRICE_GROSS_LOCAL_VAL / (1+TAX_DIM.TAX_CLASS_PCT) END AS VKP_PRICE_NET_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'VKP' THEN VKP_PRICE_GROSS_EUR_VAL / (1+TAX_DIM.TAX_CLASS_PCT) END AS VKP_PRICE_NET_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'AKP' THEN PPC_FACT.CURR_CD END AS AKP_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'AKP' THEN PPC_FACT.PRICE_VAL END AS AKP_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'AKP' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS AKP_PRICE_GROSS_EUR_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'AKP' THEN AKP_PRICE_GROSS_LOCAL_VAL / (1+TAX_DIM.TAX_CLASS_PCT) END AS AKP_PRICE_NET_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'AKP' THEN AKP_PRICE_GROSS_EUR_VAL / (1+TAX_DIM.TAX_CLASS_PCT) END AS AKP_PRICE_NET_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'UVP' THEN PPC_FACT.CURR_CD END AS UVP_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'UVP' THEN PPC_FACT.PRICE_VAL END AS UVP_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'UVP' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS UVP_PRICE_GROSS_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'STP' THEN PPC_FACT.CURR_CD END AS STP_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'STP' THEN PPC_FACT.PRICE_VAL END AS STP_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'STP' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS STP_PRICE_GROSS_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'VKZ1' THEN PPC_FACT.CURR_CD END AS VKZ1_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'VKZ1' THEN PPC_FACT.PRICE_VAL END AS VKZ1_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'VKZ1' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS VKZ1_PRICE_GROSS_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'VKZ2' THEN PPC_FACT.CURR_CD END AS VKZ2_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'VKZ2' THEN PPC_FACT.PRICE_VAL END AS VKZ2_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'VKZ2' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS VKZ2_PRICE_GROSS_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'IVP' THEN PPC_FACT.CURR_CD END AS IVP_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'IVP' THEN PPC_FACT.PRICE_VAL END AS IVP_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'IVP' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS IVP_PRICE_GROSS_EUR_VAL

        ,CASE WHEN PRICE_TYPE_CD = 'ZVP' THEN PPC_FACT.CURR_CD END AS ZVP_CURR_CD
        ,CASE WHEN PRICE_TYPE_CD = 'ZVP' THEN PPC_FACT.PRICE_VAL END AS ZVP_PRICE_GROSS_LOCAL_VAL
        ,CASE WHEN PRICE_TYPE_CD = 'ZVP' THEN PPC_FACT.PRICE_VAL / CER_FACT.EXCHANGE_RATE END AS ZVP_PRICE_GROSS_EUR_VAL
    FROM
        lec_share.v_fact_product_pricing_condition_2 PPC_FACT
    INNER JOIN
        lec_share.v_fact_currency_exchange_rate_2 CER_FACT
        ON
            PPC_FACT.CURR_CD = CER_FACT.FROM_CURR_CD
        AND
            CER_FACT.TO_CURR_CD = 'EUR'
        AND
            CER_FACT.ACTIVE_FG = TRUE
    INNER JOIN
        lec_share.v_dim_currency_exchange_rate_type_2 CERT
        ON
            CERT.CURR_EXCHANGE_RATE_TYPE_CD = CER_FACT.CURR_EXCHANGE_RATE_TYPE_CD
        AND
            CERT.IS_GENERAL_USED_FG
    INNER JOIN
        lec_share.v_rel_product_variant_regional_2 PVR_REL
        ON
            PPC_FACT.WSHOP_CD = PVR_REL.WSHOP_CD
        AND
            PPC_FACT.PROD_VARIANT_SID = PVR_REL.PROD_VARIANT_SID
        AND
            DWH_VALID_FG = TRUE
    INNER JOIN
        lec_share.v_dim_tax_class_2 TAX_DIM
        ON
            PVR_REL.TAX_CLASS_CD = TAX_DIM.TAX_CLASS_CD
        AND
            PPC_FACT.WSHOP_CD = TAX_DIM.WSHOP_CD
        AND
            TAX_DIM.ACTIVE_FG = TRUE
    WHERE
        CURRENT_TIMESTAMP() BETWEEN PPC_FACT.ACTIVE_FROM_TMSP AND PPC_FACT.ACTIVE_TO_TMSP
)
SELECT
     CTE.WSHOP_CD AS WSHOP_CD
    ,CTE.PROD_VARIANT_SID AS PROD_VARIANT_SID
    ,MAX(CTE.TAX_CLASS_PCT) AS TAX_CLASS_PCT

    ,NULLIF(LISTAGG(CTE.VKP_CURR_CD, ''), '')::VARCHAR(5) AS VKP_CURR_CD
    ,MAX(CTE.VKP_PRICE_GROSS_LOCAL_VAL) AS VKP_PRICE_GROSS_LOCAL_VAL
    ,MAX(CTE.VKP_PRICE_GROSS_EUR_VAL) AS VKP_PRICE_GROSS_EUR_VAL
    ,MAX(CTE.VKP_PRICE_NET_LOCAL_VAL) AS VKP_PRICE_NET_LOCAL_VAL
    ,MAX(CTE.VKP_PRICE_NET_EUR_VAL) AS VKP_PRICE_NET_EUR_VAL

    ,NULLIF(LISTAGG(AKP_CURR_CD, ''), '')::VARCHAR(5) AS AKP_CURR_CD
    ,MAX(AKP_PRICE_GROSS_LOCAL_VAL) AS AKP_PRICE_GROSS_LOCAL_VAL
    ,MAX(AKP_PRICE_GROSS_EUR_VAL) AS AKP_PRICE_GROSS_EUR_VAL
    ,MAX(AKP_PRICE_NET_LOCAL_VAL) AS AKP_PRICE_NET_LOCAL_VAL
    ,MAX(AKP_PRICE_NET_EUR_VAL) AS AKP_PRICE_NET_EUR_VAL

    ,NULLIF(LISTAGG(UVP_CURR_CD, ''), '')::VARCHAR(5) AS UVP_CURR_CD
    ,MAX(UVP_PRICE_GROSS_LOCAL_VAL) AS UVP_PRICE_GROSS_LOCAL_VAL
    ,MAX(UVP_PRICE_GROSS_EUR_VAL) AS UVP_PRICE_GROSS_EUR_VAL

    ,NULLIF(LISTAGG(STP_CURR_CD, ''), '')::VARCHAR(5) AS STP_CURR_CD
    ,MAX(STP_PRICE_GROSS_LOCAL_VAL) AS STP_PRICE_GROSS_LOCAL_VAL
    ,MAX(STP_PRICE_GROSS_EUR_VAL) AS STP_PRICE_GROSS_EUR_VAL

    ,NULLIF(LISTAGG(VKZ1_CURR_CD, ''), '')::VARCHAR(5) AS VKZ1_CURR_CD
    ,MAX(VKZ1_PRICE_GROSS_LOCAL_VAL) AS VKZ1_PRICE_GROSS_LOCAL_VAL
    ,MAX(VKZ1_PRICE_GROSS_EUR_VAL) AS VKZ1_PRICE_GROSS_EUR_VAL

    ,NULLIF(LISTAGG(VKZ2_CURR_CD, ''), '')::VARCHAR(5) AS VKZ2_CURR_CD
    ,MAX(VKZ2_PRICE_GROSS_LOCAL_VAL) AS VKZ2_PRICE_GROSS_LOCAL_VAL
    ,MAX(VKZ2_PRICE_GROSS_EUR_VAL) AS VKZ2_PRICE_GROSS_EUR_VAL

    ,NULLIF(LISTAGG(IVP_CURR_CD, ''), '')::VARCHAR(5) AS IVP_CURR_CD
    ,MAX(IVP_PRICE_GROSS_LOCAL_VAL) AS IVP_PRICE_GROSS_LOCAL_VAL
    ,MAX(IVP_PRICE_GROSS_EUR_VAL) AS IVP_PRICE_GROSS_EUR_VAL

    ,NULLIF(LISTAGG(ZVP_CURR_CD, ''), '')::VARCHAR(5) AS ZVP_CURR_CD
    ,MAX(ZVP_PRICE_GROSS_LOCAL_VAL) AS ZVP_PRICE_GROSS_LOCAL_VAL
    ,MAX(ZVP_PRICE_GROSS_EUR_VAL) AS ZVP_PRICE_GROSS_EUR_VAL
FROM
    CTE
GROUP BY
     WSHOP_CD
    ,PROD_VARIANT_SID
;
