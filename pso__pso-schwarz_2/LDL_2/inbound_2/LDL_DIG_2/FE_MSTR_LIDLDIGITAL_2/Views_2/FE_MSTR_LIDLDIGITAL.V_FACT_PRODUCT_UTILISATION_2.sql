CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_PRODUCT_UTILISATION_2
AS SELECT
     PROD_SID AS PROD_SID
    ,CASE WHEN UTIL_ACTION_CD = '' THEN '-1' ELSE IFNULL(UTIL_ACTION_CD, '-1') END AS UTIL_ACTION_CD
    ,EXCEPTION_UTIL_DT AS EXCEPTION_UTIL_DT
