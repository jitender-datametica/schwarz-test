CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_SALES_RETURN_PACKAGE_SHIPMENT_2(
    RETURN_PACK_SID
    ,PROD_VARIANT_SID
    ,RETURN_REQUEST_NR
    ,RETURN_PACK_TRACKING_NR
    ,RETURN_PACK_TRACKING_URL
    ,SALE_ORDER_SID
    ,SALE_ORDER_NR
    ,SALE_ORDER_POS_NR
    ,HAULER_SID
    ,ORIGIN_COUNTRY_CD
    ,RETURN_WH_SID
    ,RETURN_OPTION_CD
    ,RETURN_REQUEST_TMSP
    ,RETURN_REQUEST_DT
    ,HANDOVER_TO_CARRIER_TMSP
    ,HANDOVER_TO_CARRIER_DT
    ,FIRST_INTAKE_SCAN_HUB_TMSP
    ,FIRST_INTAKE_SCAN_HUB_DT
    ,RETURN_HUB_TMSP
    ,RETURN_HUB_DT
    ,PROD_QTY
    ,REQUEST_TO_CARRIER_DUR_DAY
    ,REQUEST_TO_CARRIER_DUR_HR
    ,CARRIER_TO_HUB_DUR_DAY
    ,CARRIER_TO_HUB_DUR_HR
    ,HUB_TO_WH_DUR_DAY
    ,HUB_TO_WH_DUR_HR
    ,RETURN_SHIP_COST_NET_EUR_VAL
    ,DIST_CHANNEL_CD
    ,RETURN_WH_TMSP
    ,RETURN_WH_DT
	,RETURN_PAYM_TO_CUST_TMSP
	,RETURN_WH_TO_PAYM_DUR_HR
	,RETURN_WH_TO_PAYM_DUR_DAY
	,CARRIER_TO_WH_DUR_HR
	,CARRIER_TO_WH_DUR_DAY
	,CARRIER_TO_PAYM_DUR_HR
	,CARRIER_TO_PAYM_DUR_DAY
	,REQUEST_TO_PAYM_DUR_HR
	,REQUEST_TO_PAYM_DUR_DAY
) AS

WITH RET_ODR AS
(
    SELECT
        CUST_ORDER_SID
        ,CUST_ORDER_POS_NR
        ,WSHOP_CD
        ,MIN(CUST_ORDER_RETURN_CREATE_TMSP)      AS  RETURN_WH_TMSP
        ,MAX(RETURN_PAYM_TO_CUST_TMSP)           AS  RETURN_PAYM_TO_CUST_TMSP
    FROM lec_share.v_fact_customer_return_line_2
    GROUP BY 
        CUST_ORDER_SID
        ,CUST_ORDER_POS_NR
        ,WSHOP_CD
        
)
SELECT
    IFNULL(RETURN_PACK_SID, '-1') AS RETURN_PACK_SID
    ,IFNULL(PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,IFNULL(RETURN_REQUEST_NR, '-1') AS RETURN_REQUEST_NR
    ,IFNULL(RETURN_PACK_TRACKING_NR, '-1') AS RETURN_PACK_TRACKING_NR
    ,IFNULL(RETURN_PACK_TRACKING_URL, '-1') AS RETURN_PACK_TRACKING_URL
    ,IFNULL(SALE_ORDER_SID, '-1') AS SALE_ORDER_SID
    ,IFNULL(SALE_ORDER_NR, '-1') AS SALE_ORDER_NR
    ,IFNULL(SALE_ORDER_POS_NR, '-1') AS SALE_ORDER_POS_NR
    ,IFNULL(HAULER_SID, '-1') AS HAULER_SID
    ,IFNULL(ORIGIN_COUNTRY_CD, '-1') AS ORIGIN_COUNTRY_CD
    ,IFNULL(RETURN_WH_SID, '-1') AS RETURN_WH_SID
    ,IFNULL(RETURN_OPTION_CD, '-1') AS RETURN_OPTION_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', RETURN_REQUEST_TMSP)::TIMESTAMP_NTZ RETURN_REQUEST_TMSP
    ,RETURN_REQUEST_DT
    ,CONVERT_TIMEZONE('Europe/Berlin', HANDOVER_TO_CARRIER_TMSP)::TIMESTAMP_NTZ HANDOVER_TO_CARRIER_TMSP
    ,HANDOVER_TO_CARRIER_DT
    ,CONVERT_TIMEZONE('Europe/Berlin', FIRST_INTAKE_SCAN_HUB_TMSP)::TIMESTAMP_NTZ FIRST_INTAKE_SCAN_HUB_TMSP
    ,FIRST_INTAKE_SCAN_HUB_DT
    ,CONVERT_TIMEZONE('Europe/Berlin', RETURN_HUB_TMSP)::TIMESTAMP_NTZ RETURN_HUB_TMSP
    ,RETURN_HUB_DT
    ,PROD_QTY
    ,REQUEST_TO_CARRIER_DUR_DAY
    ,REQUEST_TO_CARRIER_DUR_HR
    ,CARRIER_TO_HUB_DUR_DAY
    ,CARRIER_TO_HUB_DUR_HR
    ,HUB_TO_WH_DUR_DAY
    ,HUB_TO_WH_DUR_HR
    ,RETURN_SHIP_COST_NET_EUR_VAL
    ,IFNULL(DIST_CHANNEL_CD, '-1') AS DIST_CHANNEL_CD
    ,CONVERT_TIMEZONE('Europe/Berlin', RET_ODR.RETURN_WH_TMSP)::TIMESTAMP_NTZ RETURN_WH_TMSP
    ,DATE(RET_ODR.RETURN_WH_TMSP)  AS RETURN_WH_DT
	,CONVERT_TIMEZONE('Europe/Berlin', RET_ODR.RETURN_PAYM_TO_CUST_TMSP)::TIMESTAMP_NTZ RETURN_PAYM_TO_CUST_TMSP
    ,FLOOR((
	    DATEDIFF(SECOND, RET_ODR.RETURN_WH_TMSP, RET_ODR.RETURN_PAYM_TO_CUST_TMSP ) 
	    - 
	    FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (WSHOP_CD
            , RET_ODR.RETURN_WH_TMSP
			, RET_ODR.RETURN_PAYM_TO_CUST_TMSP
            )*86400 
        )/3600
    ) AS RETURN_WH_TO_PAYM_DUR_HR
    ,FLOOR(((
	    DATEDIFF(SECOND, RET_ODR.RETURN_WH_TMSP, RET_ODR.RETURN_PAYM_TO_CUST_TMSP ) 
	    - 
	    FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (WSHOP_CD
            , RET_ODR.RETURN_WH_TMSP
			, RET_ODR.RETURN_PAYM_TO_CUST_TMSP
            )*86400 
        )/3600
    )/24) AS RETURN_WH_TO_PAYM_DUR_DAY
    ,FLOOR((
		DATEDIFF(SECOND, HANDOVER_TO_CARRIER_TMSP, RET_ODR.RETURN_WH_TMSP) 
        - 
        FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (ORIGIN_COUNTRY_CD
            , HANDOVER_TO_CARRIER_TMSP
            , RET_ODR.RETURN_WH_TMSP
            )*86400 
        )/3600
	) AS CARRIER_TO_WH_DUR_HR
    ,CASE   
    WHEN DATE(HANDOVER_TO_CARRIER_TMSP) = DATE(RET_ODR.RETURN_WH_TMSP)                      
    THEN 0
    ELSE 
        FLOOR(((
			DATEDIFF(SECOND, HANDOVER_TO_CARRIER_TMSP, RET_ODR.RETURN_WH_TMSP) 
            - 
            FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
                (ORIGIN_COUNTRY_CD
                , HANDOVER_TO_CARRIER_TMSP
                , RET_ODR.RETURN_WH_TMSP
                )*86400
			)/3600
		)/24) END AS CARRIER_TO_WH_DUR_DAY
   ,FLOOR((
	    DATEDIFF(SECOND, HANDOVER_TO_CARRIER_TMSP, RET_ODR.RETURN_PAYM_TO_CUST_TMSP ) 
	    - 
	    FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (WSHOP_CD
            , HANDOVER_TO_CARRIER_TMSP
			, RET_ODR.RETURN_PAYM_TO_CUST_TMSP
            )*86400 
        )/3600
    ) AS CARRIER_TO_PAYM_DUR_HR
   ,FLOOR(((
	    DATEDIFF(SECOND, HANDOVER_TO_CARRIER_TMSP, RET_ODR.RETURN_PAYM_TO_CUST_TMSP ) 
	    - 
	    FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (WSHOP_CD
            , HANDOVER_TO_CARRIER_TMSP
			, RET_ODR.RETURN_PAYM_TO_CUST_TMSP
            )*86400 
        )/3600
    )/24) AS CARRIER_TO_PAYM_DUR_DAY
	,FLOOR((
	    DATEDIFF(SECOND, RETURN_REQUEST_TMSP, RET_ODR.RETURN_PAYM_TO_CUST_TMSP ) 
	    - 
	    FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (WSHOP_CD
            , RETURN_REQUEST_TMSP
			, RET_ODR.RETURN_PAYM_TO_CUST_TMSP
            )*86400 
        )/3600
    ) AS REQUEST_TO_PAYM_DUR_HR
   ,FLOOR(((
	    DATEDIFF(SECOND, RETURN_REQUEST_TMSP, RET_ODR.RETURN_PAYM_TO_CUST_TMSP ) 
	    - 
	    FE_MSTR_LIDLDIGITAL.F_COUNT_HOLIDAYS_AND_SUNDAYS_AND_SATURDAYS
            (WSHOP_CD
            , RETURN_REQUEST_TMSP
			, RET_ODR.RETURN_PAYM_TO_CUST_TMSP
            )*86400 
        )/3600
    )/24) AS REQUEST_TO_PAYM_DUR_DAY
   
FROM
    lec_share.v_fact_sales_return_package_shipment_2 PCK_SHP
LEFT JOIN RET_ODR 
    ON  PCK_SHP.SALE_ORDER_SID = RET_ODR.CUST_ORDER_SID
    AND PCK_SHP.SALE_ORDER_POS_NR = RET_ODR.CUST_ORDER_POS_NR;    
