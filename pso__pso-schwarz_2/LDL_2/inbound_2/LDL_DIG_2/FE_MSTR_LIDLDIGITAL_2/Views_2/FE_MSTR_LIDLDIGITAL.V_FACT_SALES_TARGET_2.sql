CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_SALES_TARGET_2(
	WSHOP_CD
	,TARGET_SALE_DT
	,DELIVERY_SRC_TYPE_CD
	,PROD_ASSORTMENT_CLASS_CD
	,PROD_FOOD_CLASS_CD
	,BRAND_CLASS_CD
	,SHOP_CAT_LVL1_SID
	,SHOP_CAT_LVL1_NAME
	,TGT_REVENUE_NET_VAL
	,TGT_MARGIN_VAL
	,CURR_CD
	,PROD_ORG_LVL_NAME
	,GC_LC_CD
	,TGT_REVENUE_NET_EUR_VAL
	,TGT_MARGIN_EUR_VAL
	,TGT_PROD_SALE_QTY
    ,TGT_COGS_NET_EUR_VAL
) AS SELECT
     WSHOP_CD AS WSHOP_CD
    ,TARGET_SALE_DT AS TARGET_SALE_DT
    ,CASE WHEN DELIVERY_SRC_TYPE_CD = '' THEN '-1' ELSE IFNULL(DELIVERY_SRC_TYPE_CD , '-1') END AS DELIVERY_SRC_TYPE_CD
    ,CASE WHEN PROD_ASSORTMENT_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_CLASS_CD , '-1') END AS PROD_ASSORTMENT_CLASS_CD
    ,CASE WHEN PROD_FOOD_CLASS_CD = '' THEN '-1' ELSE IFNULL(PROD_FOOD_CLASS_CD , '-1') END AS PROD_FOOD_CLASS_CD
    ,CASE WHEN BRAND_CLASS_CD = '' THEN '-1' ELSE IFNULL(BRAND_CLASS_CD , '-1') END AS BRAND_CLASS_CD
    ,IFNULL(SHOP_CAT_LVL1_SID , -1) AS SHOP_CAT_LVL1_SID
    ,SHOP_CAT_LVL1_NAME AS SHOP_CAT_LVL1_NAME
    ,TGT_REVENUE_NET_EUR_VAL AS TGT_REVENUE_NET_VAL
    ,TGT_MARGIN_EUR_VAL AS TGT_MARGIN_VAL
    ,CASE WHEN CURR_CD = '' THEN '-1' ELSE IFNULL(CURR_CD , '-1') END AS CURR_CD
    ,CASE WHEN PROD_ORG_LVL_NAME = '' THEN '-1' ELSE IFNULL(PROD_ORG_LVL_NAME, '-1') END AS PROD_ORG_LVL_NAME
    ,'GC' AS GC_LC_CD
-- this section is kept for a transition period. it can be removed once the MSTR reports referencing this view have switched to using the new columns
    ,TGT_REVENUE_NET_EUR_VAL AS TGT_REVENUE_NET_EUR_VAL
    ,TGT_MARGIN_EUR_VAL AS TGT_MARGIN_EUR_VAL
-- end section
    ,TGT_PROD_SALE_QTY AS TGT_PROD_SALE_QTY
    ,TGT_REVENUE_NET_EUR_VAL - TGT_MARGIN_EUR_VAL AS TGT_COGS_NET_EUR_VAL
FROM
    lec_share.v_fact_sales_target_2 TARG_FACT
INNER JOIN
    lec_share.v_dim_cal_day_2 CAL_DIM
    ON CAL_DIM.CAL_DT = TARG_FACT.TARGET_SALE_DT
WHERE
	CURR_CD = 'EUR' -- must filter to EUR if GC_LC_CD = 'GC'
;