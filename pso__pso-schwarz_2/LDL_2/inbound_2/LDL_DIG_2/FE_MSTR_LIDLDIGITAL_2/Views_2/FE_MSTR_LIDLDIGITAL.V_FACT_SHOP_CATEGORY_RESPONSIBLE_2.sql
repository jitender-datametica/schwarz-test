CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_FACT_SHOP_CATEGORY_RESPONSIBLE_2
AS SELECT
     CASE WHEN PROD_BRICK_CD = '' THEN '-1' ELSE IFNULL(PROD_BRICK_CD, '-1') END AS PROD_BRICK_CD
    ,RESP_TEAM_NAME AS RESP_TEAM_NAME
    ,CAT_MANAGER_NAME AS CAT_MANAGER_NAME
FROM
    lec_share.v_fact_shop_category_responsible_2
WHERE
    DWH_VALID_FG = TRUE
;
