CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_PRODUCT_ADDITIONAL_NUMBER_2
(
     PROD_SID
    ,PROD_ADD_NR_TYPE_CD
    ,PROD_ADD_NR
    ,IS_MAIN_FG
)
AS SELECT
     PROD_SID
    ,CASE WHEN PROD_ADD_NR_TYPE_CD = '' THEN '-1' ELSE IFNULL(PROD_ADD_NR_TYPE_CD, '-1') END
    ,PROD_ADD_NR
    ,IS_MAIN_FG
FROM lec_share.v_rel_product_additional_number_2
WHERE DWH_VALID_FG = TRUE
;
