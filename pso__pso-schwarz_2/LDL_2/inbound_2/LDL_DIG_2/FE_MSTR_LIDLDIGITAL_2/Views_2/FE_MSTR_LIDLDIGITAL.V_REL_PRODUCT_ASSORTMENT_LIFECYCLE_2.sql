CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_PRODUCT_ASSORTMENT_LIFECYCLE_2
AS SELECT
     CASE WHEN PROD_ASSORTMENT_LIFECYCLE_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_LIFECYCLE_CD, '-1') END AS PROD_ASSORTMENT_LIFECYCLE_CD
    ,CASE WHEN PROD_ASSORTMENT_LIFECYCLE_CAT_CD = '' THEN '-1' ELSE IFNULL(PROD_ASSORTMENT_LIFECYCLE_CAT_CD, '-1') END AS PROD_ASSORTMENT_LIFECYCLE_CAT_CD
    ,IFNULL(PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD 
FROM
    lec_share.v_rel_product_assortment_lifecycle_2
WHERE
    DWH_VALID_FG = TRUE
;