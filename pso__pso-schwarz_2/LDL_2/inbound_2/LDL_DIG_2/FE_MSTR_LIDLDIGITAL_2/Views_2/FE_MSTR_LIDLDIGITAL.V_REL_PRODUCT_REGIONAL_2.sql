CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_PRODUCT_REGIONAL_2(
	PROD_SID
	, WSHOP_CD
	, PROD_NR
	, REG_PROD_NAME
	, REG_PROD_DESCR
	, DELIVERY_SRC_TYPE_CD
	, SHOP_CAT_LVL4_SID
	, SHOP_CAT_LVL4_NAME
	, SHOP_CAT_LVL3_SID
	, SHOP_CAT_LVL3_NAME
	, SHOP_CAT_LVL2_SID
	, SHOP_CAT_LVL2_NAME
	, SHOP_CAT_LVL1_SID
	, SHOP_CAT_LVL1_NAME
	, SHOP_CAT_SID
	, SHOP_CAT_NAME
	, MATERIAL_POS_TYPE_CD
	, MAX_PROMO_START_DT
    , TAX_CLASS_CD
    , REG_PROD_MANAGER_CD
) AS SELECT
     PREG.PROD_SID AS PROD_SID
    , CASE WHEN PREG.WSHOP_CD = '' THEN '-1' ELSE IFNULL(PREG.WSHOP_CD , '-1') END AS WSHOP_CD
    , PROD_NR AS PROD_NR
    , REG_PROD_NAME AS REG_PROD_NAME
    , REG_PROD_DESCR AS REG_PROD_DESCR
    , CASE WHEN DELIVERY_SRC_TYPE_CD = '' THEN '-1' ELSE IFNULL(DELIVERY_SRC_TYPE_CD , '-1') END AS DELIVERY_SRC_TYPE_CD
    , IFNULL(SHOP_CAT_LVL4_SID , '-1') AS SHOP_CAT_LVL4_SID
    , SHOP_CAT_LVL4_NAME AS SHOP_CAT_LVL4_NAME
    , IFNULL(SHOP_CAT_LVL3_SID , '-1') AS SHOP_CAT_LVL3_SID
    , SHOP_CAT_LVL3_NAME AS SHOP_CAT_LVL3_NAME
    , IFNULL(SHOP_CAT_LVL2_SID , '-1') AS SHOP_CAT_LVL2_SID
    , SHOP_CAT_LVL2_NAME AS SHOP_CAT_LVL2_NAME
    , IFNULL(SHOP_CAT_LVL1_SID , '-1') AS SHOP_CAT_LVL1_SID
    , SHOP_CAT_LVL1_NAME AS SHOP_CAT_LVL1_NAME
    , IFNULL(SHOP_CAT_SID , '-1') AS SHOP_CAT_SID
    , SHOP_CAT_NAME AS SHOP_CAT_NAME
    , CASE WHEN MATERIAL_POS_TYPE_CD = '' THEN '-1' ELSE IFNULL(MATERIAL_POS_TYPE_CD , '-1') END AS MATERIAL_POS_TYPE_CD
    , MAX_PROMO_START_DT AS MAX_PROMO_START_DT
    , TAX_CLASS_CD
    , REG_PROD_MANAGER_CD
FROM
    lec_share.v_rel_product_regional_2 AS PREG
LEFT JOIN
(
	SELECT P.PROD_SID, P.WSHOP_CD, MAX(PROMO_START_DT) MAX_PROMO_START_DT
	FROM lec_share.v_dim_sales_promotion_2 P
    GROUP BY P.PROD_SID, P.WSHOP_CD
) AS PROMO ON PROMO.PROD_SID = PREG.PROD_SID
    AND PROMO.WSHOP_CD = PREG.WSHOP_CD
    WHERE DWH_VALID_FG = TRUE
;