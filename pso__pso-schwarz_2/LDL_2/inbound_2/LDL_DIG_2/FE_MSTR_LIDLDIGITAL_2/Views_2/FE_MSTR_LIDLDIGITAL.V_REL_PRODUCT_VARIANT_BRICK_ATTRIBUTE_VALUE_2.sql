CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_PRODUCT_VARIANT_BRICK_ATTRIBUTE_VALUE_2
AS SELECT
     IFNULL(DIM_PV.PROD_VARIANT_SID, '-1') AS PROD_VARIANT_SID
    ,CASE WHEN DIM_PBA.ATTR_CD = '' THEN '-1' ELSE IFNULL(DIM_PBA.ATTR_CD, '-1') END AS ATTR_CD
    ,DIM_PBA.ATTR_DESCR AS ATTR_DESCR
    ,CASE WHEN REL_PROD_BRICK.VALUE_CD = '' THEN '-1' ELSE IFNULL(REL_PROD_BRICK.VALUE_CD, '-1') END AS VALUE_CD
    ,REL_PROD_BRICK.VALUE_DESCR AS VALUE_DESCR
FROM
    lec_share.v_dim_product_variant_2 DIM_PV 
LEFT JOIN
    lec_share.v_rel_brick_code_attribute_2 DIM_PBA 
    ON DIM_PV.PROD_BRICK_CD = DIM_PBA.PROD_BRICK_CD
LEFT JOIN
    lec_share.v_rel_product_variant_brick_attribute_value_2 REL_PROD_BRICK
    ON DIM_PBA.PROD_BRICK_CD = REL_PROD_BRICK.PROD_BRICK_CD
        AND DIM_PBA.ATTR_CD = REL_PROD_BRICK.ATTR_CD
        AND DIM_PV.PROD_VARIANT_SID = REL_PROD_BRICK.PROD_VARIANT_SID
        AND REL_PROD_BRICK.DWH_VALID_FG = TRUE
WHERE
    DIM_PV.DWH_VALID_FG = TRUE
;
