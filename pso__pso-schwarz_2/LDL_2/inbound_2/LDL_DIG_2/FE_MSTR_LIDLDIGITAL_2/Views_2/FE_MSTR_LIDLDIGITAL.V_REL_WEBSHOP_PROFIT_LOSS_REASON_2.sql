CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL.V_REL_WEBSHOP_PROFIT_LOSS_REASON_2
AS SELECT
     CASE WHEN WSHOP_CD = '' THEN '-1' ELSE IFNULL(WSHOP_CD, '-1') END AS WSHOP_CD
    ,CASE WHEN PROFIT_LOSS_REASON_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_CD, '-1') END AS PROFIT_LOSS_REASON_CD
    ,IFNULL(FIN_ACCT_SID, '-1') AS FIN_ACCT_SID
    ,IFNULL(RECONCIL_FIN_ACCT_SID, '-1') AS RECONCIL_FIN_ACCT_SID
    ,IFNULL(CORRECTION_FIN_ACCT_SID, '-1') AS CORRECTION_FIN_ACCT_SID
    ,DEPART_NAME AS DEPART_NAME
    ,CASE WHEN PROFIT_LOSS_REASON_POS_GROUP_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_POS_GROUP_CD, '-1') END AS PROFIT_LOSS_REASON_POS_GROUP_CD
    ,CASE WHEN PROFIT_LOSS_REASON_MGMT_GROUP_CD = '' THEN '-1' ELSE IFNULL(PROFIT_LOSS_REASON_MGMT_GROUP_CD, '-1') END AS PROFIT_LOSS_REASON_MGMT_GROUP_CD
FROM
    lec_share.v_rel_webshop_profit_loss_reason_2
WHERE
    DWH_VALID_FG = TRUE
UNION ALL
    SELECT
         '-1' -- WSHOP_CD
        ,'-1' -- PROFIT_LOSS_REASON_CD
        ,'-1' -- FIN_ACCT_SID
        ,'-1' -- RECONCIL_FIN_ACCT_SID
        ,'-1' -- CORRECTION_FIN_ACCT_SID
        ,'' -- DEPART_NAME
        ,'-1' -- PROFIT_LOSS_REASON_POS_GROUP_CD
        ,'-1' -- PROFIT_LOSS_REASON_MGMT_GROUP_CD
;