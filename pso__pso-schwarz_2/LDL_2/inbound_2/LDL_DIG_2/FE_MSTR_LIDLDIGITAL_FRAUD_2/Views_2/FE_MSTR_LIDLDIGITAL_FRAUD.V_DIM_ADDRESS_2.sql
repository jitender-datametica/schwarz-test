CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL_FRAUD.V_DIM_ADDRESS_2
AS SELECT
     ADDR_SID AS ADDR_SID
    ,ADDR_NR AS ADDR_NR
    ,ZIP_CD AS ZIP_CD
    ,COUNTRY_NAME AS COUNTRY_NAME
    ,CITY_NAME AS CITY_NAME
    ,STREET_NAME AS STREET_NAME
    ,HOUSE_NR AS HOUSE_NR
    ,DISTRICT_NAME AS DISTRICT_NAME
    ,POST_BOX_NR AS POST_BOX_NR
    ,ADDR_SUFFIX AS ADDR_SUFFIX
    ,COMPANY_NAME AS COMPANY_NAME
    ,ADDR_LON AS ADDR_LON
    ,ADDR_LAT AS ADDR_LAT
    ,ADDR_TYPE_CD AS ADDR_TYPE_CD
    ,CONCAT(STREET_NAME, ' ', HOUSE_NR, ' ', ZIP_CD, ' ', CITY_NAME) AS ADDR_STRING
    ,ADDR_STRING ILIKE '%PACKSTATION%' AS IS_PACKSTATION_FG
FROM
    FE_MSTR_LIDLDIGITAL.V_DIM_ADDRESS_2
;
