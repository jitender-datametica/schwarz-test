CREATE OR REPLACE VIEW FE_MSTR_LIDLDIGITAL_FRAUD.V_DIM_CUSTOMER_2
AS
WITH CTE_COL AS (
    SELECT
         CUST_SID
        ,MAX(CUST_ORDER_DT) >= DATEADD(DAY, -14, CURRENT_DATE()) AS PLACED_ORDER_IN_LAST_TWO_WEEKS_FG
    FROM
        FE_MSTR_LIDLDIGITAL_FRAUD.V_FACT_CUSTOMER_ORDER_LINE_2
    GROUP BY
        CUST_SID
)
,CTE_MATCH_ADDRESSES_TO_CUSTOMERS AS (
    SELECT
         COL.CUST_SID
        ,ADDR.ADDR_STRING AS ADDR_STRING
    FROM
        lec_share.v_fact_customer_order_line_2 COL
    INNER JOIN
        FE_MSTR_LIDLDIGITAL_FRAUD.V_DIM_ADDRESS_2 ADDR ON COL.BILLING_ADDR_SID = ADDR.ADDR_SID
    INNER JOIN
        lec_share.v_dim_customer_2 CUST ON COL.CUST_SID = CUST.CUST_SID AND CUST.DWH_VALID_FG
    GROUP BY
        COL.CUST_SID, ADDR_STRING
)
,CTE_CUSTOMERS_SHARING_ADDRESSES_WITH_MORE_THAN_2_OTHERS AS (
    SELECT
        DISTINCT A.CUST_SID
    FROM
        CTE_MATCH_ADDRESSES_TO_CUSTOMERS A
    INNER JOIN (
        SELECT
             ADDR_STRING
            ,COUNT(DISTINCT CUST_SID) COUNT_CUST_SID
        FROM
            CTE_MATCH_ADDRESSES_TO_CUSTOMERS
        GROUP BY
            ADDR_STRING
        HAVING
            COUNT_CUST_SID > 2
    ) B ON A.ADDR_STRING = B.ADDR_STRING
)

SELECT
     DIM_CUST.CUST_SID AS CUST_SID
    ,DIM_CUST.CUST_NR AS CUST_NR
    ,DIM_CUST.CUST_SALUTATION AS CUST_SALUTATION
    ,DIM_CUST.CUST_FIRST_NAME AS CUST_FIRST_NAME
    ,DIM_CUST.CUST_LAST_NAME AS CUST_LAST_NAME
    ,DIM_CUST.CUST_BIRTH_DT AS CUST_BIRTH_DT
    ,DIM_CUST.CUST_AGE AS CUST_AGE
    ,DIM_CUST.CUST_TYPE_CD AS CUST_TYPE_CD
    ,DIM_CUST.CUST_ORG_TYPE_CD AS CUST_ORG_TYPE_CD
    ,DIM_CUST.CUST_COMPANY_NAME AS CUST_COMPANY_NAME
    ,DIM_CUST.CUST_BILLING_ADDR_SID AS CUST_BILLING_ADDR_SID
    ,DIM_CUST.PHONE_NR AS PHONE_NR
    ,DIM_CUST.EMAIL AS EMAIL
    ,DIM_CUST.CUST_BLOCKED_REASON_CD AS CUST_BLOCKED_REASON_CD
    ,DIM_CUST.CUST_LAN_CD AS CUST_LAN_CD
    ,DIM_CUST.CUST_SSO_ID AS CUST_SSO_ID
    ,DIM_CUST.CUST_CREATION_DT AS CUST_CREATION_DT
    ,DIM_CUST.CUST_REGISTRATION_DT AS CUST_REGISTRATION_DT
    ,DIM_CUST.CUST_ACCT_ID AS CUST_ACCT_ID
    ,DIM_CUST.IS_CUST_ADV_BLOCKED_FG AS IS_CUST_ADV_BLOCKED_FG
    ,DIM_CUST.EMAIL_PCU AS EMAIL_PCU
    ,DIM_CUST.CUST_SSO_ID_PCU AS CUST_SSO_ID_PCU
    ,DIM_CUST.IS_CUST_BLOCKED_PCU_FG AS IS_CUST_BLOCKED_PCU_FG
    ,DIM_CUST.IS_CUST_DELETED_PCU_FG AS IS_CUST_DELETED_PCU_FG 
    ,DIM_CUST.CUST_CREATION_DT >= DATEADD(DAY, -90, CURRENT_DATE()) AS CREATED_IN_LAST_THREE_MONTHS_FG
    ,IFNULL(CTE_COL.PLACED_ORDER_IN_LAST_TWO_WEEKS_FG, FALSE) AS PLACED_ORDER_IN_LAST_TWO_WEEKS_FG
    ,IFF(CTE_SHARED.CUST_SID IS NULL, FALSE, TRUE) AS SHARES_ADDRESS_FG -- if the cust_sid appears in CTE_SHARED, it uses the same address_2 as at least 2 other customers
FROM
    FE_MSTR_LIDLDIGITAL.V_DIM_CUSTOMER_2 AS DIM_CUST
LEFT JOIN
    CTE_COL AS CTE_COL
    ON
        CTE_COL.CUST_SID = DIM_CUST.CUST_SID
LEFT JOIN
    CTE_CUSTOMERS_SHARING_ADDRESSES_WITH_MORE_THAN_2_OTHERS AS CTE_SHARED
    ON
        CTE_SHARED.CUST_SID = DIM_CUST.CUST_SID
;
