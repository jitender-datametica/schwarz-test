CREATE OR REPLACE VIEW FE_SHS.V_REFDATA_BESTANDSKUNDEN_DATUMSFORMAT2_VERSION2_2(
	DEBITOR_ORG_MANDANT,
	SALUTATION,
	FIRSTNAME,
	LASTNAME,
	COMPANYNAME,
	DATEOFBIRTH,
	PHONE,
	EMAIL,
	FLAG_NUR_LIEFERADRESSE,
	STREETNAME,
	STREETNUMBER,
	ADDRESSSUFFIX,
	ZIPCODE,
	CITY,
	COUNTRY_2,
	SPERRMERKMAL,
	MAHNSTUFE,
	DATUM_ERSTE_BESTELLUNG,
	DATUM_LETZTE_BESTELLUNG,
	GP_ANZAHL_BEST_SZA_12M,
	GP_ANZAHL_BEST_NSZA_12M,
	BELEGDATUMLETZTELASTSCHRIFT,
	GP_VOLUMEN_BEST_SZA_12M,
	GP_VOLUMEN_BEST_NSZA_12M,
	GP_RETOUREN_QUOTE_PRZ_12M,
	GP_OP_FAKTURIERT_SZA,
	GP_OP_FAKTURIERT,
	GP_OP_NICHTFAKTURIERT_SZA,
	GP_OP_NICHTFAKTURIERT,
	FL_STORNOAUFTRAG_HIST,
	FL_ZAHLWEG_RATEN_HIST,
	FL_ZAHLWEG_RECHNUNG_HIST,
	FL_ZAHLWEG_SICHERE_ZA_HIST,
	FL_GESUNDHEIT_WARENKORB_HIST,
	FL_HAUSHALT_WARENKORB_HIST,
	FL_HOBBY_WARENKORB_HIST,
	FL_KINDERWELT_WARENKORB_HIST,
	FL_MODE_WARENKORB_HIST,
	FL_MULTIMEDIA_WARENKORB_HIST,
	FL_SPORT_WARENKORB_HIST,
	FL_WEINWELT_WARENKORB_HIST,
	FL_BAUMARKT_WARENKORB_HIST,
	FL_WOHNEN_WARENKORB_HIST,
	FL_KANAL_WEB_HIST,
	FL_KANAL_CIC_HIST,
	FL_KANAL_IPHONE_HIST,
	FL_KANAL_ANDROID_HIST,
	FL_ABWEICHENDE_LIEFERADRESSE_HIST,
	AKTUELL_HOECHSTE_MAHNSTUFE,
	KL_LETZTKAUF
) AS (

    WITH INSTALLMENT_INFO AS( -- R_SHS_BASIS_KENNZAHLEN
    --'FOR EVERY CUSTOMER ORDER THERE IS AN INTERNAL FINANCIAL ORDER CREATED BY LIDL. IT IS ALSO KEEP TRACKING OF PAYMENT STATUS_2 OF INSTALLEMENT IF THE ORDER WAS NOT PAID IN FULL. IS USED IN RISK LEVEL CALCULATION FOR A CUSTOMER.'
        SELECT 
            DISTINCT
            COI.CUST_SID 						AS CUST_SID --AS GESCHPARTNER_MANDANT, 
            ,COI.CUST_ORDER_SID 					AS CUST_ORDER_SID --AS VERKAUFSBELEG_MANDANT,
            ,COI.INSTALL_TYPE_CD 				AS INSTALL_TYPE_CD --TEXT_BLART,,
            ,COI.AMT_PAID_LOCAL_VAL 				AS AMT_PAID_LOCAL_VAL --AS HAUSW_BETRH, -- 'AMOUNT PAID '
            ,CPM.IS_SECURE_FG 					AS IS_SECURE_FG --AS ZAHLART_ZZSECPAYMENT, -- 'INDICATES IF THE PAYMENT METHOD IS CONSIDERED SECURE'
            ,COI.IS_SETTL_FG  					AS IS_SETTL_FG --AS FLAG_AUFTRAG_BEZAHLT -- 'WAS THE PARTIAL INSTALLMENT SETTLED ( PAID IN ANY WAY )'
            ,CUST_ORDER_INSTALL_NR
            ,CUST_ORDER_INSTALL_POS_NR
            ,CUST_ORDER_INSTALL_PART_POS_NR
        FROM 
            CORE.T_FACT_CUSTOMER_ORDER_INSTALLMENT_2 COI
            
    --    THE FOLLOWING INNER JOIN IS NEEDED TO EXCLUDE THE LIDL PLUS PAYMENTS
        INNER JOIN CORE.T_FACT_CUSTOMER_ORDER_LINE_2 COL
            ON COL.CUST_ORDER_SID = COI.CUST_ORDER_SID
            
        -- N:1
        LEFT JOIN CORE.T_DIM_CUSTOMER_PAYMENT_METHOD_2 CPM
            ON COI.CUST_PAYM_METHOD_CD = CPM.CUST_PAYM_METHOD_CD
    
        WHERE 
            COI.FIN_ORDER_CREATE_DT > CURRENT_DATE() - 365
            AND COI.INSTALL_TYPE_CD IN ('RE_2', 'RL') --'TYPE OF FINANCIAL ORDER (INVOICE AND RET. DEB./CHARGEBACK) --!!!!!!!!!!!!!!!!!!!!!!!!
            AND COI.CUST_ORDER_SID IS NOT NULL      
            AND COI.CUST_SID IS NOT NULL       
            AND COI.CUST_ORDER_INSTALL_NR IS NOT NULL   
            AND COI.DWH_VALID_FG	
    )
    ,
    INVOCED_PAYM_INFO AS( -- R_SHS_KENNZAHLEN_FAKTURA_FINAL  
        SELECT 
            CUST_SID
            ,COUNT(DISTINCT  CASE 
                            WHEN IS_SECURE_FG AND IS_SETTL_FG
                                THEN CUST_ORDER_SID
                            ELSE NULL 
                            END) 								AS GP_ANZAHL_BEST_SZA_12M
            ,COUNT(DISTINCT  CASE 
                            WHEN NOT IS_SECURE_FG AND IS_SETTL_FG
                                THEN CUST_ORDER_SID 
                            ELSE NULL 
                            END) 								AS GP_ANZAHL_BEST_NSZA_12M
            ,SUM(CASE 
                WHEN IS_SECURE_FG AND IS_SETTL_FG 
                    THEN AMT_PAID_LOCAL_VAL 
                ELSE 0 
                END) 											AS GP_VOLUMEN_BEST_SZA_12M
            ,SUM(CASE 
                WHEN NOT IS_SECURE_FG AND IS_SETTL_FG 
                    THEN AMT_PAID_LOCAL_VAL 
                ELSE 0 
                END) 											AS GP_VOLUMEN_BEST_NSZA_12M
            ,SUM(CASE 
                WHEN IS_SECURE_FG AND NOT IS_SETTL_FG 
                    THEN AMT_PAID_LOCAL_VAL 
                ELSE 0 
                END) 											AS GP_OP_FAKTURIERT_SZA
            ,SUM(CASE 
                WHEN NOT IS_SECURE_FG AND NOT IS_SETTL_FG 
                    THEN AMT_PAID_LOCAL_VAL 
                ELSE 0 
                END) 											AS GP_OP_FAKTURIERT
                
        FROM 
            INSTALLMENT_INFO --R_SHS_BASIS_KENNZAHLEN 
            
        GROUP BY
            CUST_SID
    ),
    
    NOT_INVOCED_PAYM_INFO AS( -- NOTHING NOT 0
        SELECT 
            COL.CUST_SID AS CUST_SID--GESCHPARTNER_MANDANT,
            ,COALESCE(
                SUM(CASE 
                    WHEN COL.IS_SECURE_FG = TRUE 
                        THEN IFNULL(COL.PROD_PRICE_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_PAUSHAL_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_COST_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_COUPON_GROSS_LOCAL_VAL, 0) + IFNULL(COL.PROD_COUPON_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL, 0)- IFNULL(COI.AMT_PAID_LOCAL_VAL, 0) 
                    ELSE 0 
                    END
                    )
                ,0) 											AS GP_OP_NICHTFAKTURIERT_SZA    
            ,COALESCE(
                SUM(CASE 
                    WHEN COL.IS_SECURE_FG = FALSE 
                        THEN IFNULL(COL.PROD_PRICE_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_PAUSHAL_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_COST_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_COUPON_GROSS_LOCAL_VAL, 0) + IFNULL(COL.PROD_COUPON_GROSS_LOCAL_VAL, 0) + IFNULL(COL.DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL, 0) - IFNULL(COI.AMT_PAID_LOCAL_VAL, 0)  
                    ELSE 0 
                    END
                    )
                ,0) 											AS GP_OP_NICHTFAKTURIERT     
                
        FROM ( 
            SELECT 
                CUST_SID
                ,CUST_ORDER_SID
                ,CPM.IS_SECURE_FG                                AS IS_SECURE_FG
                ,SUM(PROD_PRICE_GROSS_LOCAL_VAL) 				 AS PROD_PRICE_GROSS_LOCAL_VAL
                ,SUM(DELIVERY_PAUSHAL_GROSS_LOCAL_VAL)           AS DELIVERY_PAUSHAL_GROSS_LOCAL_VAL
                ,SUM(DELIVERY_COST_GROSS_LOCAL_VAL)              AS DELIVERY_COST_GROSS_LOCAL_VAL
                ,SUM(DELIVERY_COUPON_GROSS_LOCAL_VAL)            AS DELIVERY_COUPON_GROSS_LOCAL_VAL
                ,SUM(PROD_COUPON_GROSS_LOCAL_VAL)                AS PROD_COUPON_GROSS_LOCAL_VAL
    			,SUM(DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL)    AS DELIVERY_PAUSHAL_COUPON_GROSS_LOCAL_VAL
                
            FROM 
                CORE.T_FACT_CUSTOMER_ORDER_LINE_2  COL
            LEFT JOIN 
                CORE.T_DIM_CUSTOMER_PAYMENT_METHOD_2 CPM
                ON COL.CUST_PAYM_METHOD_CD = CPM.CUST_PAYM_METHOD_CD
                
            WHERE 
                CUST_ORDER_DT > CURRENT_DATE()-365 
    			AND IS_PART_OF_BUNDLE_POS_CNT_FG
                
            GROUP BY 
                CUST_SID
                ,CUST_ORDER_SID
                ,IS_SECURE_FG
    
        ) AS COL 
    
        LEFT JOIN (
            SELECT 
                CUST_SID
                ,CUST_ORDER_SID
                ,SUM(AMT_PAID_LOCAL_VAL) AS AMT_PAID_LOCAL_VAL
            FROM CORE.T_FACT_CUSTOMER_ORDER_INSTALLMENT_2 
            WHERE 
                DWH_VALID_FG 
                AND INSTALL_TYPE_CD = 'RE_2'
            GROUP BY 
                CUST_SID
                ,CUST_ORDER_SID
        ) AS COI
            ON COL.CUST_ORDER_SID = COI.CUST_ORDER_SID
    
        GROUP BY 
            COL.CUST_SID
    ),
    INVOCED_ONLY_PAYM_INFO AS(
        SELECT 
            CUST_SID
            ,SUM(AMT_PAID_LOCAL_VAL)	 AS AMT_PAID_LOCAL_VAL
            
        FROM 
            INSTALLMENT_INFO
            
        WHERE
            IS_SETTL_FG
            AND INSTALL_TYPE_CD = 'RE_2'
            
        GROUP BY     
            CUST_SID
    ),
    
    RETURN_AMOUNT_INFO AS (
        SELECT 
            CUST_SID 									AS CUST_SID --GESCHPARTNER_MANDANT,
            ,SUM(PROD_PRICE_GROSS_LOCAL_VAL) 			AS PROD_PRICE_GROSS_LOCAL_VAL --RETOURENWERT
            
        FROM 
            CORE.T_FACT_CUSTOMER_RETURN_LINE_2
        
        WHERE 
            CUST_ORDER_RETURN_DT > CURRENT_DATE()-365
        GROUP BY     
            CUST_SID 
    
    ),
    CUST_INFO AS( --H_HAUPTKUNDENLISTE
        SELECT 
            -- CUSTOMER FIELDS FROM T_DIM_CUSTOMER_2  A
            CUST.CUST_SID AS CUST_SID
        	,CUST.CUST_SALUTATION AS SALUTATION
        	,CUST.CUST_FIRST_NAME AS FIRSTNAME
        	,CUST.CUST_LAST_NAME AS LASTNAME
        	,CUST.CUST_COMPANY_NAME AS COMPANYNAME
        	,CUST.CUST_BIRTH_DT AS DATEOFBIRTH
        	,CUST.PHONE_NR AS PHONE
        	,CUST.EMAIL AS EMAIL
        
         -- CUSTOMER ADDRESS_2 FIELDS FROM T_DIM_ADDRESS_2  B
        	,'N' AS FLAG_NUR_LIEFERADRESSE
        	,ADDR.STREET_NAME AS STREETNAME
        	,ADDR.HOUSE_NR AS STREETNUMBER
        	,ADDR.ADDR_SUFFIX AS ADDRESSSUFFIX
        	,ADDR.ZIP_CD AS ZIPCODE
        	,ADDR.CITY_NAME AS CITY
        	,ADDR.COUNTRY_NAME AS COUNTRY_2
            
            -- SPERRMERKMAL = CUSTOMER BLOCKED STATUS_2 FROM T_DIM_CUSTOMER_2  A
        
            ,CASE WHEN CUST.CUST_BLOCKED_REASON_CD != '' THEN '1' ELSE '' END AS BLOCKED --SPERRMERKMAL,
          
        	-- MAHNSTUFE = MAXIMUM WARNING STATUS_2 LEVEL CODE FOR CUSTOMER FROM T_FACT_CUSTOMER_ORDER_INSTALLMENT_2
        	,INST.MAX_CUST_WARN_STATUS AS MAX_CUST_WARN_STATUS
            ,INST.ACTUAL_MAX_CUST_WARN_STATUS AS ACTUAL_MAX_CUST_WARN_STATUS
            ,INST.LASTSCHRIFT_FIN_ORDER_CREATE_DT AS LASTSCHRIFT_FIN_ORDER_CREATE_DT
        
            -- CUSTOMER'S FIRST AND LAST ORDER DATE FROM T_FACT_CUSTOMER_ORDER_LINE_2  D
            ,ORD.CUSTOMER_FIRST_ORDER_DATE AS CUSTOMER_FIRST_ORDER_DATE
            ,ORD.CUSTOMER_LAST_ORDER_DATE AS CUSTOMER_LAST_ORDER_DATE
        
            ,ORD.FL_CHANNEL_WEB_HIST AS FL_CHANNEL_WEB_HIST
            ,ORD.FL_CHANNEL_IOS_HIST AS FL_CHANNEL_IOS_HIST
            ,ORD.FL_CHANNEL_ANDROID_HIST AS FL_CHANNEL_ANDROID_HIST
            ,ORD.FL_DIFFERENT_DELIVERY_ADDRESS_HIST AS FL_DIFFERENT_DELIVERY_ADDRESS_HIST
            ,ORD.FL_CANCEL_ORDER_HIST AS FL_CANCEL_ORDER_HIST
            ,ORD.FL_INVOCE_PAYMENT_HIST AS FL_INVOCE_PAYMENT_HIST
            ,ORD.FL_SECURE_PAYMENT_HIST AS FL_SECURE_PAYMENT_HIST
        
        FROM
            CORE.T_DIM_CUSTOMER_2 CUST
        
        INNER JOIN 
        (
            SELECT
                CUST_SID
                ,MIN(CUST_ORDER_DT) AS CUSTOMER_FIRST_ORDER_DATE
                ,MAX(CUST_ORDER_DT) AS CUSTOMER_LAST_ORDER_DATE
                ,MAX(CASE WHEN SALES_CHANNEL_TYPE_DESCR = 'Web' AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_CHANNEL_WEB_HIST
                ,MAX(CASE WHEN SALES_CHANNEL_TYPE_DESCR = 'iOS' AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_CHANNEL_IOS_HIST
                ,MAX(CASE WHEN SALES_CHANNEL_TYPE_DESCR = 'Android' AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_CHANNEL_ANDROID_HIST
                ,MAX(CASE WHEN BILLING_ADDR_SID != DELIVERY_ADDR_SID AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_DIFFERENT_DELIVERY_ADDRESS_HIST
                ,MAX(CASE WHEN IS_ORDER_CANCEL_FG AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_CANCEL_ORDER_HIST
                ,MAX(CASE WHEN CPM.CUST_PAYM_METHOD_CD IN (9008, 9004) AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_INVOCE_PAYMENT_HIST
                ,MAX(CASE WHEN CPM.IS_SECURE_FG AND PROD_PRICE_GROSS_LOCAL_VAL > 0 AND CUST_ORDER_DT > CURRENT_DATE()-365 THEN 1 ELSE 0 END ) AS FL_SECURE_PAYMENT_HIST    
            FROM
                CORE.T_FACT_CUSTOMER_ORDER_LINE_2 OL	
            LEFT JOIN 
                CORE.T_DIM_SALES_CHANNEL_TYPE_2 SCHNL
                ON OL.SALES_CHANNEL_TYPE_CD  = SCHNL.SALES_CHANNEL_TYPE_CD    
            LEFT JOIN
                CORE.T_DIM_CUSTOMER_PAYMENT_METHOD_2 CPM
                ON CPM.CUST_PAYM_METHOD_CD = OL.CUST_PAYM_METHOD_CD
            GROUP BY
                CUST_SID
    
              
        ) AS ORD
        ON CUST.CUST_SID = ORD.CUST_SID
            
        LEFT JOIN
            CORE.T_DIM_ADDRESS_2 ADDR
            ON CUST.CUST_BILLING_ADDR_SID = ADDR.ADDR_SID 
            AND ADDR.DWH_VALID_FG
            
        LEFT JOIN 
        (
            SELECT
                CUST_SID
                ,MAX(CASE WHEN FIN_ORDER_CREATE_DT > CURRENT_DATE()-365  THEN INSTALL_WARN_STATUS_CD ELSE NULL END) AS MAX_CUST_WARN_STATUS
                ,MAX(CASE WHEN NOT IS_SETTL_FG AND FIN_ORDER_CREATE_DT > CURRENT_DATE()-365 THEN INSTALL_WARN_STATUS_CD  ELSE NULL END) AS ACTUAL_MAX_CUST_WARN_STATUS
                ,DATE(MAX(CASE WHEN CUST_PAYM_METHOD_CD IN (9008, 9017, 9016) THEN FIN_ORDER_CREATE_DT ELSE NULL END)) AS LASTSCHRIFT_FIN_ORDER_CREATE_DT -- LIDL PAY, SOFORT ZAHLBAR PER BANKEINZUG (LASTSCHRIFTEINZUG) OR BNP (BNP FINANZIERUNG)
            FROM
                CORE.T_FACT_CUSTOMER_ORDER_INSTALLMENT_2
            WHERE
                DWH_VALID_FG = TRUE	
            GROUP BY
                CUST_SID
    
        ) AS INST
        ON CUST.CUST_SID = INST.CUST_SID
            
        WHERE CUST.DWH_VALID_FG = TRUE
        AND ADDR.COUNTRY_NAME IN (
								SELECT PARAMETER_VALUE_CHAR
                                FROM META.T_REPORT_PARAMETER_2
                                WHERE REPORT ='FE_SHS'
                                AND PARAMETER_NAME='wshop_cd'
    	                        )
    )
    SELECT 
        C.CUST_SID AS DEBITOR_ORG_MANDANT
    	,C.SALUTATION 
    	,C.FIRSTNAME 
    	,C.LASTNAME
    	,C.COMPANYNAME
    	,C.DATEOFBIRTH
    	,C.PHONE
    	,C.EMAIL
    	,'N' AS FLAG_NUR_LIEFERADRESSE
    	,C.STREETNAME
    	,C.STREETNUMBER
    	,C.ADDRESSSUFFIX
    	,C.ZIPCODE
    	,C.CITY
    	,C.COUNTRY_2
    	,C.BLOCKED AS SPERRMERKMAL
    	,C.MAX_CUST_WARN_STATUS AS MAHNSTUFE
    	,DATE(C.CUSTOMER_FIRST_ORDER_DATE,'YYYY-MM_2-DD') AS DATUM_ERSTE_BESTELLUNG
    	,DATE(C.CUSTOMER_LAST_ORDER_DATE,'YYYY-MM_2-DD') AS DATUM_LETZTE_BESTELLUNG
    	,IPI.GP_ANZAHL_BEST_SZA_12M
    	,IPI.GP_ANZAHL_BEST_NSZA_12M
    	,DATE(C.LASTSCHRIFT_FIN_ORDER_CREATE_DT,'YYYY-MM_2-DD') AS BELEGDATUMLETZTELASTSCHRIFT
    	,IPI.GP_VOLUMEN_BEST_SZA_12M
    	,IPI.GP_VOLUMEN_BEST_NSZA_12M
    	,CEIL(DIV0(RAI.PROD_PRICE_GROSS_LOCAL_VAL, AMT_PAID_LOCAL_VAL)*100) AS GP_RETOUREN_QUOTE_PRZ_12M--AS RETURNS_RATE
    	,IPI.GP_OP_FAKTURIERT_SZA
    	,IPI.GP_OP_FAKTURIERT
    	,NIPM.GP_OP_NICHTFAKTURIERT_SZA 
    	,NIPM.GP_OP_NICHTFAKTURIERT  
        ,C.FL_CANCEL_ORDER_HIST AS FL_STORNOAUFTRAG_HIST
        ,NULL AS FL_ZAHLWEG_RATEN_HIST -- DON'T HAVE IT
        ,C.FL_INVOCE_PAYMENT_HIST AS FL_ZAHLWEG_RECHNUNG_HIST
        ,C.FL_SECURE_PAYMENT_HIST AS FL_ZAHLWEG_SICHERE_ZA_HIST
    	,NULL AS FL_GESUNDHEIT_WARENKORB_HIST
    	,NULL AS FL_HAUSHALT_WARENKORB_HIST
    	,NULL AS FL_HOBBY_WARENKORB_HIST
    	,NULL AS FL_KINDERWELT_WARENKORB_HIST
    	,NULL AS FL_MODE_WARENKORB_HIST
    	,NULL AS FL_MULTIMEDIA_WARENKORB_HIST
    	,NULL AS FL_SPORT_WARENKORB_HIST
    	,NULL AS FL_WEINWELT_WARENKORB_HIST
    	,NULL AS FL_BAUMARKT_WARENKORB_HIST
    	,NULL AS FL_WOHNEN_WARENKORB_HIST
    	,C.FL_CHANNEL_WEB_HIST AS FL_KANAL_WEB_HIST
    	,NULL AS FL_KANAL_CIC_HIST --AS FL_CHANNEL_CIC_HIST
    	,C.FL_CHANNEL_IOS_HIST AS FL_KANAL_IPHONE_HIST --FL_KANAL_IOS_HIST
    	,C.FL_CHANNEL_ANDROID_HIST AS FL_KANAL_ANDROID_HIST
    	,C.FL_DIFFERENT_DELIVERY_ADDRESS_HIST AS FL_ABWEICHENDE_LIEFERADRESSE_HIST
    	,C.ACTUAL_MAX_CUST_WARN_STATUS AS AKTUELL_HOECHSTE_MAHNSTUFE
    	,CASE WHEN C.CUSTOMER_LAST_ORDER_DATE > CURRENT_DATE() - 30 THEN 'selber_monat'
                      WHEN C.CUSTOMER_LAST_ORDER_DATE > CURRENT_DATE() - 60 THEN 'letzter_monat'
                      WHEN C.CUSTOMER_LAST_ORDER_DATE > CURRENT_DATE() - 120 THEN 'zwei_bis_drei_monate'
                      WHEN C.CUSTOMER_LAST_ORDER_DATE > CURRENT_DATE() - 99999 THEN 'mehr_als_drei_monate' 
                      ELSE 'kein_kauf' END AS KL_LETZTKAUF
    FROM
        CUST_INFO C
    LEFT JOIN 
        INVOCED_PAYM_INFO IPI
        ON IPI.CUST_SID = C.CUST_SID
    LEFT JOIN 
        RETURN_AMOUNT_INFO RAI
        ON RAI.CUST_SID = C.CUST_SID
    LEFT JOIN
        INVOCED_ONLY_PAYM_INFO IOPI
        ON IOPI.CUST_SID = C.CUST_SID 
    LEFT JOIN
        NOT_INVOCED_PAYM_INFO NIPM
        ON NIPM.CUST_SID = C.CUST_SID 
        
    WHERE
    	(AKTUELL_HOECHSTE_MAHNSTUFE > 0 
    	OR C.CUSTOMER_LAST_ORDER_DATE > CURRENT_DATE() - 365)
)
;