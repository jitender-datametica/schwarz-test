CREATE OR REPLACE VIEW TRANSFER.V_EXP_MIS_BUAC_2 AS (

	WITH 
		ST 
	AS 
	(
		SELECT    
			WSHOP_CD,
			TARGET_SALE_DT,
			CURR_CD,
			SUM(TGT_REVENUE_NET_EUR_VAL) AS TGT_REVENUE_NET_EUR_VAL
		FROM 
			CORE.T_FACT_SALES_TARGET_2
		GROUP BY  
			WSHOP_CD,
			TARGET_SALE_DT,
			CURR_CD
	),
		COL 
	AS 
	(
		SELECT    
			WSHOP_CD,
			CUST_ORDER_DT,
			CURR_CD,
			SUM(PROD_PRICE_NET_LOCAL_VAL) 			AS PROD_PRICE_NET_LOCAL_VAL,
			COUNT(DISTINCT CUST_ORDER_NR) 			AS DISTINCT_CUST_ORDER_NR,
			SUM(PROD_QTY)::INTEGER 				  	AS PROD_QTY
		FROM 
			CORE.T_FACT_CUSTOMER_ORDER_LINE_2 
		WHERE 
				(   
						( WSHOP_CD  = 'DE' AND IS_PART_OF_BUNDLE_HEADER_CNT_FG )
					OR  ( WSHOP_CD != 'DE' AND IS_PART_OF_BUNDLE_POS_CNT_FG ) 
				)
			AND IS_ORDER_CANCEL_FG = 0
		GROUP BY
			WSHOP_CD,
			CUST_ORDER_DT,
			CURR_CD 
	)

	SELECT
		ST.WSHOP_CD 																					            AS OSLAND,
		ST.TARGET_SALE_DT																    			            AS BESTELLDATUM,
		ST.CURR_CD 																						            AS WAEHRUNG_KONZERN,
		ROUND(COL.PROD_PRICE_NET_LOCAL_VAL / CER.EXCHANGE_RATE, 2)      											AS BESTELLUMSATZ_NACH_STORNO_NACH_PHY_RETOURE,
		COL.DISTINCT_CUST_ORDER_NR 																		            AS ANZAHL_BESTELLUNGEN_NACH_STORNO,
		ROUND(COL.PROD_PRICE_NET_LOCAL_VAL, 2) 						    											AS BESTELLUMSATZ_NACH_STORNO_NACH_PHY_RETOURE_LW,
		COL.CURR_CD 										            											AS WAEHRUNG_LAND,
		COL.PROD_QTY													 	    									AS BESTELLMENGE_NACH_STORNO_NACH_RETOURE,
		ROUND(ST.TGT_REVENUE_NET_EUR_VAL, 2) 													 	    			AS PLAN_BESTELLUMSATZ,
		ST.CURR_CD 																						            AS WAEHRUNG_PLAN_BESTELLUMSATZ

	FROM 
		ST 
	-- 1:1
	LEFT JOIN COL
		ON ST.WSHOP_CD = COL.WSHOP_CD 
		AND ST.TARGET_SALE_DT = COL.CUST_ORDER_DT  
	-- 1:1
	LEFT JOIN CORE.T_FACT_CURRENCY_EXCHANGE_RATE_2 CER 
		ON COL.CURR_CD = CER.FROM_CURR_CD
		AND COL.CUST_ORDER_DT BETWEEN CER.ACTIVE_FROM_DT AND CER.ACTIVE_TO_DT
		AND CER.CURR_EXCHANGE_RATE_TYPE_CD = 'F'
		AND CER.TO_CURR_CD = 'EUR'
)
;