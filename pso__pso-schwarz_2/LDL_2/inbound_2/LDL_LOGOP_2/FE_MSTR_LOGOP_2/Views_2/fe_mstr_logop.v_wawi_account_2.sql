CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_WAWI_ACCOUNT_2(
	CLIENT_ID COMMENT 'Client id - calculated based on the country_2 code',
	WH_ID COMMENT 'Warehouse id',
	TURNOVER COMMENT 'Turnover calculated on a warehouse level as per Fachkonzept definition: (-1)*NVL(SUM(NVL(DEBIT,0) - NVL(CREDIT,0)),0))',
	END_DT COMMENT 'Day end-date - tracking warehouse turnover',
	DWH_VALID_FROM COMMENT 'Valid from date',
	DWH_VALID_TO COMMENT 'Valid to date',
	TURNOVER_CUMULATIVE COMMENT 'Cumulative Turnover based on TURNOVER column'
) AS 
WITH Turnover_Calc AS (
SELECT 
    CLIENT_ID,
    CASE 
        WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
        WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
        WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 
        ELSE WH_NR
    END AS WH_ID,
    (-1) * NVL(SUM(NVL(DEBIT, 0) - NVL(CREDIT, 0)), 0) AS TURNOVER,
    DATE(DAY_END_DT) AS END_DT,
    DWH_VALID_FROM,
    DWH_VALID_TO
FROM 
    "DATA".T_WAWI_WHACCOUNT_2
WHERE 
    CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
    AND DELETED_FG = 'FALSE'
    AND FORM_TYPE IN (10, 11, 12, 40, 41, 44, 45, 46, 54, 55, 65, 80, 81, 130, 131, 135, 138, 140, 141, 145, 148, 150, 151, 160, 161)
    AND END_DT BETWEEN '2024-03-01' AND CURRENT_DATE
GROUP BY 
    CLIENT_ID, WH_NR, END_DT, DWH_VALID_FROM, DWH_VALID_TO
)
SELECT 
    CLIENT_ID,
    WH_ID,
    TURNOVER,
    END_DT,
    DWH_VALID_FROM,
    DWH_VALID_TO,
    SUM(TURNOVER) OVER (
        PARTITION BY CLIENT_ID, WH_ID, YEAR(END_DT) - CAST(MONTH(END_DT) < 3 AS INTEGER)
        ORDER BY END_DT
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS TURNOVER_CUMULATIVE
FROM 
    Turnover_Calc
ORDER BY 
    CLIENT_ID, WH_ID, END_DT
;