CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_WAWI_INVENTORYDET_2(
	CLIENT_ID COMMENT 'Client id - calculated based on the country_2 code',
	WH_ID COMMENT 'Warehouse id',
	ARTIKELNR COMMENT 'Item_2 nr',
	FORM_NR COMMENT 'Item_2 row id',
	INVENTORYNUM COMMENT 'Inventory nr',
	INVENTORYTYPE COMMENT 'Inventory type',
	T072_DATE COMMENT 'Modification date',
	T073_EXP_QTY COMMENT 'INV Expected Qty. (PC)',
	T073_GES_QTY COMMENT 'INV Counted Qty. (PC)',
	T073_DIFF_QTY COMMENT 'INV Difference Qty.',
	DWH_LOAD_ID COMMENT 'Load id',
	DWH_CREATED COMMENT 'Record created at',
	DWH_UPDATED COMMENT 'Record updated at',
	DWH_VALID_FROM COMMENT 'Valid from date',
	DWH_VALID_TO COMMENT 'Valid to date',
	DELETED_FG COMMENT 'Flag if record is deleted'
) COMMENT='Artikel_2 - view based on T_WAWI_INVENTORYDET_2'
AS 
WITH t73_inventorydet_2 AS (
SELECT
	CLIENT_ID
	,CASE 
            WHEN CLIENT_ID=13 AND WH_ID = 600 THEN 60
            WHEN CLIENT_ID=18 AND WH_ID = 20 THEN 4
            WHEN CLIENT_ID=21 AND WH_ID = 20 THEN 22 ELSE WH_ID
            END AS WH_ID
	,CONCAT(ITEMNUMBER,CASESIZE) AS ARTIKELNR
	,ID AS FORM_NR
	,INVENTORYNUM 
	,EXPECTED AS T073_EXP_QTY 
	,TOTALQTY AS T073_GES_QTY
	,DIFFERENCE AS T073_DIFF_QTY
	,DWH_LOAD_ID
	,DWH_CREATED
	,MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED
	,DWH_VALID_FROM
	,DWH_VALID_TO
	,DELETED_FG
FROM "DATA".T_WAWI_INVENTORYDET_2
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
--AND SCN <> 0
),
t72_inventory_2 AS (
SELECT
	CLIENT_ID
	,CASE 
            WHEN CLIENT_ID=13 AND WH_NR = 600 THEN 60
            WHEN CLIENT_ID=18 AND WH_NR = 20 THEN 4
            WHEN CLIENT_ID=21 AND WH_NR = 20 THEN 22 ELSE WH_NR
            END AS WH_ID
	,INVENTORYNUM 
	,DATE(DAYENDDATE) AS T072_DATE
	,C72_TYPE AS INVENTORYTYPE
	,DWH_LOAD_ID
	,DWH_CREATED
	,MAX(DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED
	,DWH_VALID_FROM
	,DWH_VALID_TO
	,DELETED_FG
FROM "DATA".T_WAWI_INVENTORY_2
WHERE CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
AND DELETED_FG = 'FALSE'
--AND SCN <> 0
AND T072_DATE > '2024-03-01'
)
SELECT
	a.CLIENT_ID
	,a.WH_ID
	,a.ARTIKELNR
	,a.FORM_NR
	,a.INVENTORYNUM
	,b.INVENTORYTYPE
	,b.T072_DATE
	,a.T073_EXP_QTY
	,a.T073_GES_QTY 
	,a.T073_DIFF_QTY
	,a.DWH_LOAD_ID
	,a.DWH_CREATED
	,a.DWH_UPDATED
	,a.DWH_VALID_FROM
	,a.DWH_VALID_TO
	,a.DELETED_FG
FROM
    t73_inventorydet_2 a
JOIN
    t72_inventory_2 b
ON
    a.CLIENT_ID = b.CLIENT_ID
    AND a.WH_ID = b.WH_ID
    AND a.INVENTORYNUM = b.INVENTORYNUM
;