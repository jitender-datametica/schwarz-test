CREATE OR REPLACE VIEW FE_MSTR_LOGOP.V_ZFM_DASHBOARD_2 (
	CLIENT_ID COMMENT 'Client id - calculated based on the country_2 code',
	WH_ID COMMENT 'Warehouse ID. Subset of Warehouse Number (lagernummer)',
	HAULIER COMMENT 'Haulier description',
	BOOKING_ID COMMENT 'Identification of booking',
	BOOKING_DATE COMMENT 'Date of booking',
	SUPPLIER_2 COMMENT 'Supplier_2 Name',
	SUPPLIER_LIST COMMENT 'Supplier_2 list label indicating if the supplier_2 is OWIM or SCHWARZ',
	SUPPLIER_LABEL COMMENT 'Supplier_2 label - \"Cross Dock\", \"Import/Grosshandel\" and \"Frei-Haus\"',
	ORDER_NUMBER COMMENT 'Order number - used to differentiate between \"Cross Dock\", \"Import/Grosshandel\" and \"Frei-Haus\" suppliers',
	COUNT_ORDER_PER_BOOKING COMMENT 'counting of orders per booking - support parameter to dedup the calculation',
	TYPE_OF_GOODS COMMENT 'Type of goods description',
	MAIN_TYPE_OF_GOODS COMMENT 'Main type of goods ID',
	BOOKING_DATETIME COMMENT 'Timestamp of booking',
	COMPLETED COMMENT 'Completed',
	REFERENCE_NUMBER COMMENT 'Reference Number - Join column',
	TIMESTAMP_SIGNED_IN COMMENT 'Timestamp signed in',
	TIMESTAMP_AT_GATE COMMENT 'Timestamp at gate',
	TIMESTAMP_SIGNED_OUT COMMENT 'Timestamp signed out',
	TIMESTAMP_NOT_ARRIVED COMMENT 'Timestamp not arrived',
	WAITING_TIME COMMENT 'Waiting time',
	LDL_WAITING_TIME COMMENT 'LIDL Waiting time',
	UNLOADING_TIME COMMENT 'Unloading time',
	PROCESSING_TIME_DCT COMMENT 'Processing time DCT chapter',
	PROCESSING_TIME COMMENT 'Processing time Main',
	PROCESSING_TIME_LBL COMMENT 'Processing time label depending on duration',
	PUNCTUALITY COMMENT 'Punctuality',
	PUNCTUALITY_LABEL COMMENT 'Punctuality label',
	TOO_LATE COMMENT 'Too late value if applicable',
	TOO_EARLY COMMENT 'Too early value if applicable',
	NOT_ARRIVED COMMENT 'Not arrived Flag',
	TIME_LATE COMMENT 'Time Late',
	DELETED COMMENT 'Deleted Flag',
	DSCI COMMENT 'DSCI',
	COUNT_NOT_ARRIVED COMMENT 'Flag for not arrived',
	COUNT_SIGNED_OUT COMMENT 'Flag for signed out',
	DWH_VALID_FROM COMMENT 'Valid from date',
	DWH_VALID_TO COMMENT 'Valid to date',
	DELETED_FG COMMENT 'Flag if record is deleted',
	DWH_UPDATED COMMENT 'Last update time'
) AS
WITH BOOKINGS
AS
(
SELECT 
	b.client_id
   ,b.wh_id
   ,b.warehouse_id
   ,b.WAREHOUSE
   ,b.warehouse_number
   ,b.haulier
   ,b.booking_id
   ,b.booking_date
   ,COALESCE(b.supplier_2,bo.supplier_name) AS supplier_2
   ,COALESCE (b.order_number,bo.order_number) AS order_number
   ,b.type_of_goods
   ,b.type_of_goods_id
   ,b.booking_datetime
   ,b.reference_number
   ,b.timestamp_signed_in
   ,b.timestamp_at_gate
   ,b.timestamp_signed_out
   ,b.timestamp_not_arrived
   ,b.not_arrived
   ,b.deleted
   ,b.dwh_valid_from
   ,b.dwh_valid_to
   ,b.deleted_fg
   ,b.dwh_updated
   ,ROW_NUMBER()OVER(PARTITION BY b.client_id,b.wh_id, b.booking_id ORDER BY b.booking_id) AS count_order_per_booking
FROM "DATA".T_ZFM_BOOKINGS_2 b
LEFT JOIN "DATA".T_ZFM_BOOKINGORDERS_2 bo
ON b.client_id = bo.client_id
AND b.booking_id = bo.booking_id
AND bo.deleted_fg = FALSE 
AND CURRENT_DATE BETWEEN bo.dwh_valid_from AND bo.dwh_valid_to
WHERE b.deleted_fg = FALSE 
AND CURRENT_DATE BETWEEN b.dwh_valid_from AND b.dwh_valid_to
),
WHS
AS 
(
SELECT
	WH_TOG.MAIN_TYPE_OF_GOODS
   ,WH_TOG.TYPE_OF_GOODS_ID
   ,WH.WAREHOUSE_ID
   ,WH.WAREHOUSE_NUMBER
   ,WH.DELETED_FG
   ,WH.DWH_VALID_FROM
   ,WH.DWH_VALID_TO 
FROM "DATA".T_ZFM_WAREHOUSES_2 WH
LEFT JOIN "DATA".T_ZFM_WAREHOUSES_TOG_2 WH_TOG
ON WH.WAREHOUSE_ID = WH_TOG.WAREHOUSE_ID 
AND WH.DELETED_FG = FALSE
AND CURRENT_DATE BETWEEN WH.DWH_VALID_FROM AND WH.DWH_VALID_TO
WHERE WH_TOG.DELETED_FG = FALSE 
AND CURRENT_DATE BETWEEN WH_TOG.DWH_VALID_FROM AND WH_TOG.DWH_VALID_TO
),
REGISTRATION_WAREHOUSES AS
(
SELECT DISTINCT WAREHOUSE
  FROM DATA.T_ZFM_REGISTRATIONS_2
  WHERE DELETED_FG = FALSE 
AND CURRENT_DATE BETWEEN DWH_VALID_FROM AND DWH_VALID_TO
)
SELECT 
	B.CLIENT_ID
   ,B.WH_ID
   ,B.HAULIER
   ,b.booking_id
   ,B.BOOKING_DATE
   ,B.SUPPLIER_2
   ,IFF(B.SUPPLIER_2 ILIKE '%OWIM%', 'OWIM', IFF(B.SUPPLIER_2 ILIKE '%SCHWARZ%', 'SCHWARZ', NULL)) AS SUPPLIER_LIST
   ,IFF(B.ORDER_NUMBER RLIKE '^[A-Za-z]{2}[0-9]{3,}', 'Import / /Grosshandel'
   ,IFF(B.ORDER_NUMBER RLIKE '(KL|KT|TL|TK|UF)[A-Za-z]{3}', 'Cross Dock', 'Frei-Haus')) AS SUPPLIER_LABEL
   ,B.ORDER_NUMBER
   ,b.count_order_per_booking
   ,B.TYPE_OF_GOODS
   ,WH.MAIN_TYPE_OF_GOODS
   ,B.BOOKING_DATETIME
   ,IFF(TIMESTAMP_SIGNED_OUT IS NOT NULL AND TIMESTAMP_SIGNED_IN IS NOT NULL, 1,0) AS COMPLETED
   ,B.REFERENCE_NUMBER
   ,B.TIMESTAMP_SIGNED_IN
   ,B.TIMESTAMP_AT_GATE
   ,B.TIMESTAMP_SIGNED_OUT
   ,B.TIMESTAMP_NOT_ARRIVED
   ,CEIL(TIMESTAMPDIFF(MILLISECONDS, B.TIMESTAMP_SIGNED_IN, B.TIMESTAMP_AT_GATE)/1000) AS WAITING_TIME
   ,IFF(B.TIMESTAMP_SIGNED_IN < B.BOOKING_DATETIME AND B.TIMESTAMP_AT_GATE < B.BOOKING_DATETIME, TIMESTAMPDIFF(SECOND, B.TIMESTAMP_SIGNED_IN, B.TIMESTAMP_AT_GATE)
   ,IFF(B.TIMESTAMP_SIGNED_IN < B.BOOKING_DATETIME AND B.TIMESTAMP_AT_GATE > B.BOOKING_DATETIME, TIMESTAMPDIFF(SECOND, B.BOOKING_DATETIME, B.TIMESTAMP_AT_GATE)
   ,IFF(TIMESTAMP_SIGNED_IN > BOOKING_DATETIME, TIMESTAMPDIFF(SECOND, B.TIMESTAMP_SIGNED_IN, B.TIMESTAMP_AT_GATE), NULL))) AS LDL_WAITING_TIME
   ,IFF(TIMESTAMPDIFF(SECOND, B.TIMESTAMP_AT_GATE  , B.TIMESTAMP_SIGNED_OUT) < 0, NULL,TIMESTAMPDIFF(SECOND, B.TIMESTAMP_AT_GATE  , B.TIMESTAMP_SIGNED_OUT)) AS UNLOADING_TIME
   ,IFF(WAITING_TIME IS NULL,0,WAITING_TIME) + IFF(UNLOADING_TIME IS NULL,0,UNLOADING_TIME) AS PROCESSING_TIME_DCT
   ,TIMESTAMPDIFF(SECOND, B.TIMESTAMP_SIGNED_IN, B.TIMESTAMP_SIGNED_OUT) AS PROCESSING_TIME
   ,IFF(PROCESSING_TIME > 10800, 'More than 3 hours', IFF(PROCESSING_TIME < 900, 'Less than 15 min', 'Between 15 min and 3 hours')) AS PROCESSING_TIME_LBL
   ,IFF(DELETED = 0 AND NOT_ARRIVED = FALSE,TIMESTAMPDIFF(MINUTE, B.BOOKING_DATETIME, B.TIMESTAMP_SIGNED_IN), NULL) AS PUNCTUALITY
   ,IFF(PUNCTUALITY < -15, 'Too Early', IFF(PUNCTUALITY BETWEEN -15 AND 15, 'On Time', IFF(PUNCTUALITY > 15, 'Too Late', NULL))) AS PUNCTUALITY_LABEL
   ,IFF(DELETED = 0 AND NOT_ARRIVED = FALSE AND B.TIMESTAMP_SIGNED_IN > B.BOOKING_DATETIME ,ABS(TIMESTAMPDIFF(SECOND, B.TIMESTAMP_SIGNED_IN, B.BOOKING_DATETIME)), NULL) AS TOO_LATE
   ,IFF(DELETED = 0 AND NOT_ARRIVED = FALSE AND B.TIMESTAMP_SIGNED_IN < B.BOOKING_DATETIME ,ABS(TIMESTAMPDIFF(SECOND, B.BOOKING_DATETIME, B.TIMESTAMP_SIGNED_IN)), NULL) AS TOO_EARL
   ,B.NOT_ARRIVED
   ,CEIL(TIMESTAMPDIFF(MILLISECONDS, B.TIMESTAMP_SIGNED_IN, B.TIMESTAMP_AT_GATE)/1000) AS TIME_LATE
   ,IFF(B.DELETED = TRUE,1,0) AS DELETED
   ,IFF(RWH.WAREHOUSE IS NOT NULL,1,0) AS DSCI
   ,IFF(B.TIMESTAMP_NOT_ARRIVED IS NOT NULL, 1,0) AS COUNT_NOT_ARRIVED
   ,IFF(B.TIMESTAMP_SIGNED_OUT  IS NOT NULL, 1,0) AS COUNT_SIGNED_OUT
   ,B.DWH_VALID_FROM
   ,B.DWH_VALID_TO
   ,B.DELETED_FG
   ,MAX(B.DWH_UPDATED) OVER (PARTITION BY CLIENT_ID, WH_ID) AS DWH_UPDATED
FROM BOOKINGS B
LEFT JOIN WHS WH
ON B.WAREHOUSE_ID  = WH.WAREHOUSE_ID
AND B.TYPE_OF_GOODS_ID = WH.TYPE_OF_GOODS_ID
LEFT JOIN REGISTRATION_WAREHOUSES AS RWH ON RWH.WAREHOUSE = B.WAREHOUSE;