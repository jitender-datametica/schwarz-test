CREATE OR REPLACE VIEW FE_MSTR_SCORE.V_DIM_NATIONAL_ORG_2 AS

SELECT
	NATIONAL_ORG_SID
	,NATIONAL_ORG_NR
	,NATIONAL_ORG_NAME
	,NATIONAL_ORG_SHORT_NAME
	,CASE IS_ONLINESHOP_FG
    	WHEN TRUE THEN '1'
        WHEN FALSE THEN '0'
        ELSE 'unknown'
     END AS IS_ONLINESHOP_FG
	,VAT_NR
FROM CORE.T_DIM_NATIONAL_ORG_2; 