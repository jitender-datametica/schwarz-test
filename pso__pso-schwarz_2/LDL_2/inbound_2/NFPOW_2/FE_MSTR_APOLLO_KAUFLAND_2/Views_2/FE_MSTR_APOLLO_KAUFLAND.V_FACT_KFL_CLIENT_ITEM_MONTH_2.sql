CREATE OR REPLACE VIEW FE_MSTR_APOLLO_KAUFLAND.V_FACT_KFL_CLIENT_ITEM_MONTH_2
(
 LOB_CD
,KFL_CLIENT_ID
,KFL_ITEM_NR
,CAL_MONTH
,CURR_CD
,KFL_ADJUST_SALES_GROSS_VAL
,KFL_ADJUST_SALES_NET_VAL
,KFL_ADJUST_SALES_NET_VAL_KALK
,KFL_ADJUST_ADV_SALES_NET_VAL
,KFL_RETURN_GROSS_VAL
,KFL_RETURN_NET_VAL
,KFL_ADJUST_SALES_QTY
,KFL_ADJUST_ADV_SALES_QTY
,KFL_ADJUST_AF_SALES_QTY
,KFL_RETURN_QTY
,KFL_RCV_QTY
,KFL_BUYING_SALES_NET_VAL
,LDL_BUYING_RCV_NET_VAL
,LDL_RETAIL_RCV_NET_VAL
,KFL_TOTAL_WRITEOFF_NET_VAL
,KFL_PART_WRITEOFF_NET_VAL
,LDL_WRITEOFF_NET_VAL
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
,POSTEN_KZ_AS_WAS_PLUS_SONDERAKTION
)
AS
SELECT
 LOB_CD
,KFL_CLIENT_ID
,CASE WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID = 1 THEN (KFL_ITEM_NR / 100)::INTEGER
      WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID > 1 THEN (KFL_ITEM_NR / 10)::INTEGER
      WHEN lob_cd = 'LDL' THEN (KFL_ITEM_NR / 100)::INTEGER ELSE NULL
      END AS KFL_ITEM_NR
,CAL_MONTH
,CURR_CD
,KFL_ADJUST_SALES_GROSS_VAL 
,KFL_ADJUST_SALES_NET_VAL
-- nur Umsatz KFL für Berechnung WA KALK, da WA KALK nur für KFL verfügbar und im normalen Umsatz LDL enthalten ist
,CASE WHEN LOB_CD = 'KFL' THEN KFL_ADJUST_SALES_NET_VAL ELSE 0 END AS KFL_ADJUST_SALES_NET_VAL_KALK
,KFL_ADJUST_ADV_SALES_NET_VAL
,KFL_RETURN_GROSS_VAL
,KFL_RETURN_NET_VAL
,KFL_ADJUST_SALES_QTY -- Gesamt (AF + SA)
,KFL_ADJUST_ADV_SALES_QTY -- Sonderaktion
,KFL_ADJUST_SALES_QTY - KFL_ADJUST_ADV_SALES_QTY AS KFL_ADJUST_AF_SALES_QTY -- Aktionsfrei
,KFL_RETURN_QTY
,KFL_RCV_QTY
,KFL_BUYING_SALES_NET_VAL
,LDL_BUYING_RCV_NET_VAL
,LDL_RETAIL_RCV_NET_VAL
,KFL_TOTAL_WRITEOFF_NET_VAL
,KFL_PART_WRITEOFF_NET_VAL
,LDL_WRITEOFF_NET_VAL
--AP0219535/SPEC0270105 neue Spalte für Posten KZ aufgenommen / sschuecke 26.09.2024
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
,CASE WHEN LOB_CD = 'KFL' AND KFL_ADJUST_AF_SALES_QTY <> 0 AND KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD = 'PN' THEN 'Postenart./Sortimentsart. SA' -- PO hat immer AF Absatz
      WHEN LOB_CD = 'KFL' AND KFL_ADJUST_AF_SALES_QTY <> 0 AND KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD = 'SO' THEN 'Sortimentsartikel AF' -- SO hat immer AF Absatz
      WHEN LOB_CD = 'KFL' AND (KFL_ADJUST_AF_SALES_QTY =  0 OR KFL_ADJUST_AF_SALES_QTY IS NULL) AND KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD = 'SO' THEN 'Postenart./Sortimentsart. SA' -- SO hat keinen AF Absatz
      ELSE '' END AS POSTEN_KZ_AS_WAS_PLUS_SONDERAKTION
      
FROM CORE.T_FACT_KFL_CLIENT_ITEM_MONTH_2
WHERE 
(
KFL_ADJUST_SALES_GROSS_VAL <> 0 OR
KFL_ADJUST_SALES_NET_VAL <> 0 OR
KFL_ADJUST_SALES_NET_VAL_KALK <> 0 OR
KFL_ADJUST_ADV_SALES_NET_VAL <> 0 OR
KFL_RETURN_GROSS_VAL <> 0 OR
KFL_RETURN_NET_VAL <> 0 OR
KFL_ADJUST_SALES_QTY <> 0 OR
KFL_ADJUST_ADV_SALES_QTY <> 0 OR
KFL_RETURN_QTY <> 0 OR
KFL_RCV_QTY <> 0 OR
KFL_BUYING_SALES_NET_VAL <> 0 OR
LDL_BUYING_RCV_NET_VAL <> 0 OR
LDL_RETAIL_RCV_NET_VAL <> 0 OR
KFL_TOTAL_WRITEOFF_NET_VAL <> 0 OR
KFL_PART_WRITEOFF_NET_VAL <> 0 
--,LDL_WRITEOFF_NET_VAL <> 0 OR
--,LDL_PREV_1Y_WRITEOFF_NET_VAL <> 0
AND lob_cd = 'KFL');
