CREATE OR REPLACE VIEW FE_MSTR_APOLLO_KAUFLAND.V_FACT_KFL_GTP_ITEM_GTIN_DAY_2
(
 LOB_CD
,KFL_CLIENT_ID
,KFL_GTP_NR
,KFL_GTP_SUBSIDIARY_TYPE_ID
,KFL_ITEM_NR
,GTIN_NR
,CAL_DT
,CURR_CD
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
,KFL_ADV_WEEK
,KFL_ADJUST_SALES_GROSS_VAL
,KFL_ADJUST_SALES_NET_VAL
,KFL_RETURN_GROSS_VAL
,KFL_RETURN_NET_VAL
,KFL_ADJUST_SALES_QTY
,KFL_RETURN_QTY
)
AS
SELECT
 LOB_CD
,KFL_CLIENT_ID
,KFL_GTP_NR
,KFL_GTP_SUBSIDIARY_TYPE_ID
,CASE WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID = 1 THEN (KFL_ITEM_NR / 100)::INTEGER
      WHEN lob_cd = 'KFL' AND KFL_CLIENT_ID > 1 THEN (KFL_ITEM_NR / 10)::INTEGER
      WHEN lob_cd = 'LDL' THEN (KFL_ITEM_NR / 100)::INTEGER ELSE NULL
      END AS KFL_ITEM_NR
,GTIN_NR
,CAL_DT
,CURR_CD
,KFL_CONSOLIDATED_PROMO_ITEM_TYPE_CD
,KFL_ADV_WEEK
,KFL_ADJUST_SALES_GROSS_VAL
,KFL_ADJUST_SALES_NET_VAL
,KFL_RETURN_GROSS_VAL
,KFL_RETURN_NET_VAL
,KFL_ADJUST_SALES_QTY
,KFL_RETURN_QTY
FROM CORE.T_FACT_KFL_GTP_ITEM_GTIN_DAY_2;
