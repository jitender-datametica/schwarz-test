 IFNULL(NULLIF(PV.prod_brick_cd, ''), '-1') AS prod_brick_cd,
 IF(LEFT(SAFE_CAST(PV.prod_variant_nr as STRING), 1) = '1', TRUE, FALSE) AS commodity_fg,
 PV.is_bundle_header_fg,
 PV.prod_variant_import_nr,
 IF(PV.shop_cat_lvl1_name = 'Spirituosen' OR PV.shop_cat_lvl1_name = 'Weinwelt' AND PV.shop_cat_lvl2_name <>
     'Rund um den Wein', 'Wein', PV.prod_size_type_cd) AS einlager_kz,
 IFNULL(NULLIF(PR.prod_org_lvl_name, ''), '-1') AS prod_org_lvl_name,
  CASE
  WHEN PV.prod_variant_packing_type_cd = ''
  THEN '-1'
  ELSE IFNULL(PV.prod_variant_packing_type_cd, '-1')
  END AS prod_variant_packing_type_cd
FROM ldl_dig_lec_share.v_dim_product_variant_2 AS PV
 LEFT JOIN ldl_dig_lec_share.v_dim_product_2 AS PR ON PV.prod_sid = PR.prod_sid AND PR.dwh_valid_fg
 LEFT JOIN ldl_dig_lec_share.v_dim_unit_of_measurement_2 AS UOM_VOLUME ON PV.volume_uom_sid = UOM_VOLUME.uom_sid
 LEFT JOIN ldl_dig_lec_share.v_dim_unit_of_measurement_2 AS UOM_WEIGHT ON PV.weight_uom_sid = UOM_WEIGHT.uom_sid
 LEFT JOIN ldl_dig_lec_share.v_dim_unit_of_measurement_2 AS UOM_GIRTH ON PV.girth_uom_sid = UOM_GIRTH.uom_sid
 LEFT JOIN ldl_dig_lec_share.v_dim_unit_of_measurement_2 AS UOM_LENGTH ON PV.length_uom_sid = UOM_LENGTH.uom_sid
 LEFT JOIN ldl_dig_lec_share.v_dim_unit_of_measurement_2 AS UOM_WIDTH ON PV.width_uom_sid = UOM_WIDTH.uom_sid
 LEFT JOIN ldl_dig_lec_share.v_dim_unit_of_measurement_2 AS UOM_HEIGHT ON PV.height_uom_sid = UOM_HEIGHT.uom_sid
WHERE PV.dwh_valid_fg
