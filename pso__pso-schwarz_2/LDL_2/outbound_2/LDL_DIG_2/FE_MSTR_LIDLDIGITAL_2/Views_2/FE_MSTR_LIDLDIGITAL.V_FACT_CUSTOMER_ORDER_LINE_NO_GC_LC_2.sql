   IFNULL(COL_FACT.prod_sid, - 1) AS prod_sid,
   CAST(CASE
     WHEN COL_FACT.bundle_header_pos_nr > 0
     THEN 'Group Component'
     WHEN COL_FACT.is_bundle_header_fg
     THEN 'Group Header'
     ELSE 'Single Item_2'
     END AS STRING) AS article_set,
   IFNULL(COL_FACT.cust_sid, - 1) AS cust_sid,
   COL_FACT.cust_order_nr,
   COL_FACT.cust_order_pos_nr,
