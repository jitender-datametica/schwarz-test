   COUNT(DISTINCT cust_order_pos_nr) AS cnt_distinct_order_pos_per_cust_order,
   SUM(prod_qty) AS sum_prod_qty_per_cust_order,
     COUNT(DISTINCT cust_order_pos_nr) = 1 AND SUM(prod_qty) = 1 AS is_single_position
