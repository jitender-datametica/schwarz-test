   COL_FACT.prod_variant_nr,
   COL_FACT.prod_nr,
   COL_FACT.ekp_unit_price_net_eur_val,
   COL_FACT.gross_margin_net_eur_val,
   epo.is_single_position,
    COL_FACT.add_services_net_local_val / CER_FACT.exchange_rate AS add_services_net_eur_val,
   COL_FACT.add_services_net_local_val,
    COL_FACT.add_services_gross_local_val / CER_FACT.exchange_rate AS add_services_gross_eur_val,
   COL_FACT.add_services_gross_local_val,
    COL_FACT.add_services_vat_local_val / CER_FACT.exchange_rate AS add_services_vat_eur_val,
   COL_FACT.add_services_vat_local_val,
   COL_FACT.is_replacement_order_fg,
   COL_FACT.ref_cust_order_sid,
   COL_FACT.ref_cust_order_nr,
   COL_FACT.ref_cust_order_pos_nr,
   COL_FACT.dist_channel_cd,
   COL_FACT.dist_country_cd,
   COL_FACT.dist_channel_type_cd
  FROM ldl_dig_lec_share.v_fact_customer_order_line_2 AS COL_FACT
   INNER JOIN EPO_IS_SINGLE_POSITION AS epo ON COL_FACT.cust_order_sid = epo.cust_order_sid
   INNER JOIN ldl_dig_lec_share.v_fact_currency_exchange_rate_2 AS CER_FACT ON COL_FACT.curr_cd = CER_FACT.from_curr_cd
     AND COL_FACT.cust_order_dt BETWEEN CER_FACT.active_from_dt AND CER_FACT.active_to_dt AND CER_FACT.to_curr_cd =
     'EUR'
   INNER JOIN ldl_dig_lec_share.v_dim_currency_exchange_rate_type_2 AS CERT ON CER_FACT.curr_exchange_rate_type_cd = CERT
     .curr_exchange_rate_type_cd AND CERT.is_general_used_fg
   INNER JOIN ldl_dig_lec_share.v_dim_cal_day_2 AS CAL_DIM ON COL_FACT.cust_order_dt = CAL_DIM.cal_dt AND CAL_DIM.bus_year
      >= 2020);