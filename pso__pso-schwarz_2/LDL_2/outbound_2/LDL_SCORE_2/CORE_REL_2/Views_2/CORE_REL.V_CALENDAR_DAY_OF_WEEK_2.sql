CREATE OR REPLACE VIEW ldl_score_core_rel.v_calendar_day_of_week_2 AS SELECT ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1) AS
 day_of_week,
  CASE
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 1
  THEN 'Montag'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 2
  THEN 'Dienstag'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 3
  THEN 'Mittwoch'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 4
  THEN 'Donnerstag'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 5
  THEN 'Freitag'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 6
  THEN 'Samstag'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 7
  THEN 'Sonntag'
  ELSE NULL
  END AS day_of_week_descr,
  CASE
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 1
  THEN 'Mo'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 2
  THEN 'Di'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 3
  THEN 'Mi'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 4
  THEN 'Do'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 5
  THEN 'Fr'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 6
  THEN 'Sa'
  WHEN (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) = 7
  THEN 'So'
  ELSE NULL
  END AS day_of_week_descr_short
FROM UNNEST(GENERATE_ARRAY(0, 6)) AS SEQ;