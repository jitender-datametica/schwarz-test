CREATE OR REPLACE VIEW ldl_score_core_rel.v_calendar_year_2 AS SELECT EXTRACT(YEAR FROM CURRENT_DATE) - 10 + (ROW_NUMBER()
   OVER (ORDER BY 1 IS NULL, 1)) AS cy,

 DATE_DIFF(PARSE_DATE('%Y',CAST(EXTRACT(YEAR FROM CURRENT_DATE) - 10 + (ROW_NUMBER() OVER (ORDER BY 1 IS NULL, 1)) AS STRING)),
  CURRENT_DATE, YEAR) AS cy_seq
FROM UNNEST(GENERATE_ARRAY(0, 11)) AS SEQ;