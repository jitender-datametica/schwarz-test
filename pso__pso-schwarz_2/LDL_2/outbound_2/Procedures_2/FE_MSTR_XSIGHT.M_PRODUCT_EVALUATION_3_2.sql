CREATE OR REPLACE PROCEDURE fe_mstr_xsight.m_product_evaluation_3(IN MARKET_RESEARCH_PROD_SID INT64, IN IM_SORTIMENT_MARKE INT64, IN IM_SORTIMENT_EM INT64, IN REGIONAL_SAISONAL INT64, IN ANDERE_VERPACKUNGSGR_M_EM INT64, IN AKTIONSARTIKEL_IN_OUT INT64, IN VORSCHLAG_NIS_MARKE INT64, IN VORSCHLAG_NIS_EIGENMARKE INT64, IN VORSCHLAG_NIS_AKTION_IN_OUT INT64, IN VORSCHLAG_NIS_AKTION_PV INT64, IN NICHT_ERHAELTLICH INT64)
BEGIN
BEGIN TRANSACTION;
IF NOT EXISTS (SELECT *
FROM fe_mstr_xsight.t_fact_product_evaluation_2
WHERE MARKET_RESEARCH_PROD_SID = MARKET_RESEARCH_PROD_SID) THEN
    BEGIN
    INSERT INTO fe_mstr_xsight.t_fact_product_evaluation_2
(SELECT MARKET_RESEARCH_PROD_SID, IM_SORTIMENT_MARKE, IM_SORTIMENT_EM, REGIONAL_SAISONAL, ANDERE_VERPACKUNGSGR_M_EM, AKTIONSARTIKEL_IN_OUT, VORSCHLAG_NIS_MARKE, VORSCHLAG_NIS_EIGENMARKE, VORSCHLAG_NIS_AKTION_IN_OUT, VORSCHLAG_NIS_AKTION_PV, NICHT_ERHAELTLICH);
    END;
ELSE
    BEGIN
    UPDATE fe_mstr_xsight.t_fact_product_evaluation_2 SET
    aktionsartikel_in_out = AKTIONSARTIKEL_IN_OUT,
    andere_verpackungsgr_m_em = ANDERE_VERPACKUNGSGR_M_EM,
    im_sortiment_em = IM_SORTIMENT_EM,
    im_sortiment_marke = IM_SORTIMENT_MARKE,
    nicht_erhaeltlich = NICHT_ERHAELTLICH,
    regional_saisonal = REGIONAL_SAISONAL,
    vorschlag_nis_aktion_in_out = VORSCHLAG_NIS_AKTION_IN_OUT,
    vorschlag_nis_aktion_pv = VORSCHLAG_NIS_AKTION_PV,
    vorschlag_nis_marke = VORSCHLAG_NIS_MARKE,
    vorschlag_nis_eigenmarke = VORSCHLAG_NIS_EIGENMARKE
WHERE market_research_prod_sid = MARKET_RESEARCH_PROD_SID;
    END;
END IF;

COMMIT TRANSACTION;
END;
