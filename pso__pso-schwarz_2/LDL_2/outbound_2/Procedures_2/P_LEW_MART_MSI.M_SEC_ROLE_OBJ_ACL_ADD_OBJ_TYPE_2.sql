CREATE OR REPLACE PROCEDURE p_lew_mart_msi.m_sec_role_obj_acl_add_obj_type(
  OBJECT_TYPE_ID FLOAT64, 
  OBJECT_TYPE_NAME STRING
)
BEGIN
  BEGIN TRANSACTION;

  EXECUTE IMMEDIATE '''
    INSERT INTO p_lew_mart_msi.t_ref_obj_type_acl_2 VALUES (CAST(@OBJECT_TYPE_ID AS INT64), @OBJECT_TYPE_NAME)
  ''' USING OBJECT_TYPE_ID AS OBJECT_TYPE_ID, OBJECT_TYPE_NAME AS OBJECT_TYPE_NAME;

  COMMIT TRANSACTION;
END;