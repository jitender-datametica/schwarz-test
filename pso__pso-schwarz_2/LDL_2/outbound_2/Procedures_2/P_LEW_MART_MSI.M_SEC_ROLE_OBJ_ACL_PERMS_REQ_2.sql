CREATE OR REPLACE PROCEDURE p_lew_mart_msi.m_sec_role_obj_acl_perms_req(
  SECURITY_ROLE_ID FLOAT64, 
  SECURITY_ROLE_DESC STRING, 
  PERMISSION_TYPE STRING, 
  AUTHORIZED FLOAT64, 
  ENTRY_USER STRING
)
BEGIN
  BEGIN TRANSACTION;

  -- ** MSC-WARNING - MSCEWI1022 - ONE OR MORE IDENTIFIERS IN THIS STATEMENT WERE CONSIDERED PARAMETERS BY DEFAULT. REFERENCED TABLE NOT FOUND. **
  EXECUTE IMMEDIATE '''
    -- Set the last active request to inactive, because the new request is requested   
    UPDATE p_lew_mart_msi.t_ct_sec_role_obj_acl_perms_2
    SET active_fg = 0
    WHERE security_role_id = CAST(@SECURITY_ROLE_ID AS INT64)
    AND permission_type = @PERMISSION_TYPE
    AND approved = 0
    AND active_fg = 1
  ''' USING SECURITY_ROLE_ID AS SECURITY_ROLE_ID, PERMISSION_TYPE AS PERMISSION_TYPE;

  EXECUTE IMMEDIATE '''
    -- Insert the new request
    INSERT INTO p_lew_mart_msi.t_ct_sec_role_obj_acl_perms_2 VALUES (CAST(@SECURITY_ROLE_ID AS INT64)
    , @SECURITY_ROLE_DESC
    , @PERMISSION_TYPE
    , CAST(@AUTHORIZED AS INT64)
    , @ENTRY_USER
    , CAST(CURRENT_TIMESTAMP() AS DATETIME)
    , NULL
    , NULL
    , 0
    , 1
    , 0)
  ''' USING SECURITY_ROLE_ID AS SECURITY_ROLE_ID, SECURITY_ROLE_DESC AS SECURITY_ROLE_DESC, PERMISSION_TYPE AS PERMISSION_TYPE, AUTHORIZED AS AUTHORIZED, ENTRY_USER AS ENTRY_USER;

  COMMIT TRANSACTION;
END;