CREATE OR REPLACE PROCEDURE KFL_PRODUCTION_DBP_MACRO.M_VIS_WUP(IN P_MANDANT_ID BIGNUMERIC, IN P_WUP_ID BIGNUMERIC, IN P_DAT_VON STRING, IN P_DAT_EROEFFNUNG STRING, IN P_DAT_BIS STRING, IN P_UEBERNAHME_VON STRING, IN P_KUNDENFAKTOR BIGNUMERIC, IN P_UMSATZ_EA_EUR BIGNUMERIC, IN P_UMSATZ_EA_LAND BIGNUMERIC, IN P_UMSATZ_ERWARTUNG_EUR BIGNUMERIC, IN P_DAT_WIEDEREROEFFNUNG STRING, IN P_EINWOHNER_ANZAHL BIGNUMERIC, OUT OUT_PARAM STRING)
BEGIN
DECLARE var_currentDate DATE;
DECLARE var_datvon DATE;
DECLARE var_dateroe DATE;
DECLARE var_datbis DATE;


BEGIN
SET var_currentDate  =  (SELECT DATE_SUB(CURRENT_DATE, INTERVAL 5 DAY));
SET var_datvon  =  (SELECT DAT_VON
FROM KFL_PRODUCTION_DBP_DATA.WUP_2
WHERE MANDANT_ID = P_MANDANT_ID AND WUP_ID = P_WUP_ID);
SET var_dateroe  =  (SELECT DAT_EROEFFNUNG
FROM KFL_PRODUCTION_DBP_DATA.WUP_2
WHERE MANDANT_ID = P_MANDANT_ID AND WUP_ID = P_WUP_ID);
SET var_datbis  =  (SELECT DAT_BIS
FROM KFL_PRODUCTION_DBP_DATA.WUP_2
WHERE MANDANT_ID = P_MANDANT_ID AND WUP_ID = P_WUP_ID);

IF (DATE(P_DAT_VON) = DATE(var_datvon)
 OR DATE(P_DAT_VON) <> DATE(var_datvon)
 AND DATE(P_DAT_VON) BETWEEN DATE(var_currentdate) AND CAST('2090-12-31' as DATE))
 AND (DATE(P_DAT_EROEFFNUNG) = DATE(var_dateroe)
 OR DATE(P_DAT_EROEFFNUNG) <> DATE(var_dateroe)
 AND DATE(P_DAT_EROEFFNUNG) BETWEEN DATE(var_currentdate) AND CAST('2090-12-31' as DATE))
 AND (DATE(P_DAT_BIS) = DATE(var_datbis)
 OR DATE(P_DAT_BIS) <> DATE(var_datbis)
 AND DATE(P_DAT_BIS) BETWEEN DATE(var_currentdate) AND CAST('9999-12-31' as DATE))
THEN
    BEGIN
    BEGIN TRANSACTION;
    UPDATE KFL_PRODUCTION_DBP_DATA.WUP_2 SET
    DAT_VON = CAST(P_DAT_VON AS DATE),
    DAT_EROEFFNUNG = CAST(P_DAT_EROEFFNUNG AS DATE),
    DAT_BIS = CAST(P_DAT_BIS AS DATE),
    UEBERNAHME_VON = P_UEBERNAHME_VON,
    KUNDENFAKTOR = P_KUNDENFAKTOR,
    UMSATZ_EA_EUR = CAST(P_UMSATZ_EA_EUR AS NUMERIC),
    UMSATZ_EA_LAND = CAST(P_UMSATZ_EA_LAND AS NUMERIC),
    UMSATZ_ERWARTUNG_EUR = CAST(P_UMSATZ_ERWARTUNG_EUR AS NUMERIC),
    DAT_WIEDEREROEFFNUNG = CAST(P_DAT_WIEDEREROEFFNUNG AS DATE),
    EINWOHNER_ANZAHL = P_EINWOHNER_ANZAHL
WHERE MANDANT_ID = P_MANDANT_ID AND WUP_ID = P_WUP_ID;
    COMMIT TRANSACTION;
    SET out_param  =  'WUP_is_updated';
    SELECT out_param;
    RETURN;
    END;
ELSE
    BEGIN
    RAISE USING MESSAGE = 'SERV_NOT_UPDATED';
    SET out_param  =  'WUP_not_updated';
    SELECT out_param;
    RETURN;
    END;
END IF;

END;
END;
