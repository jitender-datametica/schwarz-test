CREATE OR REPLACE PROCEDURE KFL_PRODUCTION_DBP_MACRO.SP_UPD_AIS_INT_SECURITY(IN P_FUNC STRING, IN P_GRUPPEID BIGNUMERIC, IN P_GRUPPEBEZ STRING, IN P_GRUPPEBEZNEU STRING, IN P_LOESCHFLAG BIGNUMERIC, IN P_GRUPPEPARENTID BIGNUMERIC, IN P_PFLEGEFLAG BIGNUMERIC, IN P_ZEKID STRING, IN P_MANDANTID BIGNUMERIC, IN P_USERID STRING, IN P_DAT_GUELTIG_BIS DATE, OUT out_param STRING)
BEGIN
DECLARE v_temp_check_gruppe BIGNUMERIC;
DECLARE v_temp_check_gruppe_user_zu BIGNUMERIC;
DECLARE v_temp_check_gruppe_gruppe_zu BIGNUMERIC;
DECLARE v_temp_check_gruppe_zek_zu BIGNUMERIC;
DECLARE v_temp_anzahl_zeilen BIGNUMERIC;
BEGIN
BEGIN TRANSACTION;
IF P_FUNC = 'Gruppe_2' THEN

/* ---- FUNC = GRUPPE_2 START ------------------*/

        -- // Pruefen ob eine_2 Gruppe_2 mit dem Namen bereits exisitiert

        BEGIN
SET v_temp_check_gruppe  =  (SELECT COUNT(GRUPPE_BEZ)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_2
WHERE UPPER(TRIM(GRUPPE_BEZ)) = UPPER(COALESCE(TRIM(P_GRUPPEBEZNEU), TRIM(P_GRUPPEBEZ))));

        -- // Wenn diese noch kein Eintrag exisitert 
IF v_temp_check_gruppe = 0 THEN
        MERGE INTO KFL_PRODUCTION_DBP_SECURITY.GRUPPE_2 AS SECGRP
USING (SELECT COALESCE((SELECT GRUPPE_ID
                FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_2
                WHERE GRUPPE_ID = P_GRUPPEID), MAX(GRUPPE_ID) + 1) AS GRUPPE_ID
    FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_2) AS usigrp
ON SECGRP.GRUPPE_ID = usigrp.GRUPPE_ID
WHEN MATCHED THEN UPDATE SET
    GRUPPE_BEZ = TRIM(P_GRUPPEBEZNEU)
WHEN NOT MATCHED THEN INSERT (GRUPPE_ID, GRUPPE_BEZ) VALUES(usigrp.GRUPPE_ID, TRIM(P_GRUPPEBEZ));
    ELSE
        SET out_param  =  'Gruppe_2 vorhanden!';
        SELECT out_param;
        RETURN;
    END IF;
    END;
ELSEIF P_FUNC = 'Gruppe_2 loeschen' THEN
    BEGIN
    SET v_temp_check_gruppe_user_zu  =  (SELECT COUNT(GRUPPE_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID);
    SET v_temp_check_gruppe_gruppe_zu  =  (SELECT COUNT(GRUPPE_PARENT_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2
WHERE GRUPPE_PARENT_ID = P_GRUPPEID);
    SET v_temp_check_gruppe_zek_zu  =  (SELECT COUNT(GRUPPE_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID);

    IF v_temp_check_gruppe_user_zu = 0 AND v_temp_check_gruppe_gruppe_zu = 0 AND v_temp_check_gruppe_zek_zu = 0 THEN
        DELETE FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_2
WHERE GRUPPE_ID = P_GRUPPEID AND P_LOESCHFLAG = 1;
    ELSE
        SET out_param  =  'Abhaengigkeiten vorhanden!';
        SELECT out_param;
        RETURN;
    END IF;

    END;
ELSEIF P_FUNC = 'Gruppe_2 zu Gruppe_2' THEN
    BEGIN

    IF P_PFLEGEFLAG = 1 THEN
        BEGIN
        SET v_temp_check_gruppe_zek_zu  =  (SELECT COUNT(GRUPPE_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE GRUPPE_ID = P_GRUPPEPARENTID);

        IF v_temp_check_gruppe_zek_zu = 0 THEN
            BEGIN
            SET v_temp_anzahl_zeilen  =  (SELECT COUNT(GRUPPE_PARENT_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2
WHERE GRUPPE_PARENT_ID = P_GRUPPEPARENTID AND GRUPPE_ID = P_GRUPPEID);

            IF v_temp_anzahl_zeilen = 0 THEN
                INSERT INTO KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2 (GRUPPE_PARENT_ID, GRUPPE_ID)
(SELECT P_GRUPPEPARENTID AS GRUPPE_PARENT_ID, P_GRUPPEID AS GRUPPE_ID);
            END IF;

            END;
        ELSE
            SET out_param  =  'Gruppe_2 nicht geaendert!';
            SELECT out_param;
            RETURN;
        END IF;

        END;
    ELSEIF P_PFLEGEFLAG = 0 THEN
        BEGIN
        DELETE FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND GRUPPE_PARENT_ID = P_GRUPPEPARENTID;
        END;
    END IF;

    END;
ELSEIF P_FUNC = 'ZEK_2 zuordnen' THEN
    BEGIN

    IF P_PFLEGEFLAG = 1 THEN
        BEGIN
        SET v_temp_check_gruppe_gruppe_zu  =  (SELECT COUNT(GRUPPE_PARENT_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2
WHERE GRUPPE_PARENT_ID = P_GRUPPEID);

        IF v_temp_check_gruppe_gruppe_zu = 0 AND P_ZEKID = '-1' THEN
            MERGE INTO KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 AS SECGRPZEK
USING (SELECT ZEK_ID
    FROM KFL_PRODUCTION_DBP_VIEW.V_ZEK_2
    WHERE MANDANT_ID = P_MANDANTID AND WBL_ID > 0) AS usizek
ON SECGRPZEK.GRUPPE_ID = P_GRUPPEID AND SECGRPZEK.ZEK_ID = usizek.ZEK_ID AND SECGRPZEK.MANDANT_ID = P_MANDANTID
WHEN MATCHED THEN UPDATE SET
    ALLE_ZEK_FG = 1
WHEN NOT MATCHED THEN INSERT (GRUPPE_ID, ZEK_ID, MANDANT_ID, ALLE_ZEK_FG) VALUES(P_GRUPPEID, usizek.ZEK_ID, P_MANDANTID, 1);
        ELSEIF v_temp_check_gruppe_gruppe_zu = 0 AND P_ZEKID <> '-1' THEN
            BEGIN
            SET v_temp_anzahl_zeilen  =  (SELECT COUNT(GRUPPE_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE MANDANT_ID = P_MANDANTID AND GRUPPE_ID = P_GRUPPEID AND ZEK_ID = P_ZEKID);

            IF v_temp_anzahl_zeilen = 0 THEN
                INSERT INTO KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 (GRUPPE_ID, ZEK_ID, MANDANT_ID, ALLE_ZEK_FG)
(SELECT P_GRUPPEID AS GRUPPE_ID, P_ZEKID AS ZEK_ID, P_MANDANTID AS MANDANT_ID, 0 AS ALLE_ZEK_FG);
            END IF;

            END;
        ELSE
            SET out_param  =  'Gruppe_2 eine_2 Blatt Gruppe_2 NICHT geaendert!';
            SELECT out_param;
            RETURN;
        END IF;

        END;
    ELSEIF P_PFLEGEFLAG = 0 THEN
        BEGIN

        IF P_ZEKID = '-1' THEN
            DELETE FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND MANDANT_ID = P_MANDANTID;
        ELSE
            BEGIN
            DELETE FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND ZEK_ID = P_ZEKID AND MANDANT_ID = P_MANDANTID;
            SET v_temp_check_gruppe_zek_zu  =  (SELECT COUNT(GRUPPE_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND ZEK_ID = '-1' AND MANDANT_ID = P_MANDANTID);

            IF v_temp_check_gruppe_zek_zu > 0 THEN
                BEGIN
                DELETE FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND MANDANT_ID = P_MANDANTID AND ZEK_ID = '-1';
                UPDATE KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 SET
    ALLE_ZEK_FG = 0
WHERE GRUPPE_ID = P_GRUPPEID AND MANDANT_ID = P_MANDANTID;
                END;
            END IF;

            END;
        END IF;

        END;
    END IF;

    END;
ELSEIF P_FUNC = 'User Gruppe_2 zuordnen' THEN
    BEGIN
    SET v_temp_anzahl_zeilen  =  (SELECT COUNT(GRUPPE_ID)
FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND USER_ID = P_USERID);

    IF v_temp_anzahl_zeilen = 0 AND P_DAT_GUELTIG_BIS >= CURRENT_DATE THEN
        INSERT INTO KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2 (GRUPPE_ID, USER_ID, DAT_GUELTIG_BIS, TD_UPDATE)
(SELECT P_GRUPPEID AS GRUPPE_ID, P_USERID AS USER_ID, P_DAT_GUELTIG_BIS AS DAT_GUELTIG_BIS, CAST(CURRENT_DATE AS TIMESTAMP) AS TD_UPDATE);
    END IF;

    END;
ELSEIF P_FUNC = 'User Gruppe_2 ändern' THEN
    BEGIN

    IF P_LOESCHFLAG = 1 THEN
        DELETE FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2
WHERE GRUPPE_ID = P_GRUPPEID AND USER_ID = P_USERID AND P_LOESCHFLAG = 1;
    ELSEIF P_DAT_GUELTIG_BIS >= CURRENT_DATE THEN
        UPDATE KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2 SET
    DAT_GUELTIG_BIS = P_DAT_GUELTIG_BIS,
    TD_UPDATE = CAST(CURRENT_DATE AS TIMESTAMP)
WHERE GRUPPE_ID = P_GRUPPEID AND USER_ID = P_USERID;
    END IF;

    END;
END IF;

MERGE INTO KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 AS SECGRPZEK
USING (SELECT G.GRUPPE_ID, Z.ZEK_ID, G.MANDANT_ID
        FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 AS G
            INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_ZEK_2 AS Z ON G.MANDANT_ID = Z.MANDANT_ID
        WHERE Z.WBL_ID > 0 AND G.ZEK_ID = '-1' AND Z.ZEK_ID <> '-1'
        EXCEPT DISTINCT
        SELECT GRUPPE_ID, ZEK_ID, MANDANT_ID
        FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2
        WHERE ALLE_ZEK_FG = 1 AND ZEK_ID <> '-1') AS t3
ON SECGRPZEK.GRUPPE_ID = t3.GRUPPE_ID AND SECGRPZEK.ZEK_ID = t3.ZEK_ID AND SECGRPZEK.MANDANT_ID = t3.MANDANT_ID
WHEN NOT MATCHED THEN INSERT (GRUPPE_ID, ZEK_ID, MANDANT_ID, ALLE_ZEK_FG) VALUES(t3.GRUPPE_ID, t3.ZEK_ID, t3.MANDANT_ID, 1);
INSERT INTO KFL_PRODUCTION_DBP_SECURITY.USER_ZEK_ZU_2 (USER_ID, ZEK_ID, MANDANT_ID)
(SELECT USER_ID, ZEK_ID, MANDANT_ID
    FROM (SELECT USER_ID, ZEK_ID, MANDANT_ID
            FROM ((SELECT Z.MANDANT_ID, Z.ZEK_ID, U.USER_ID
                            FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2 AS U
                                INNER JOIN KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 AS Z ON U.GRUPPE_ID = Z.GRUPPE_ID AND U.DAT_GUELTIG_BIS >= CURRENT_DATE
                            UNION DISTINCT
                            SELECT Z.MANDANT_ID, Z.ZEK_ID, U.USER_ID
                            FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2 AS G
                                INNER JOIN KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2 AS U ON G.GRUPPE_ID = U.GRUPPE_ID AND U.DAT_GUELTIG_BIS >= CURRENT_DATE OR G.GRUPPE_PARENT_ID = U.GRUPPE_ID AND U.DAT_GUELTIG_BIS >= CURRENT_DATE
                                INNER JOIN KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 AS Z ON G.GRUPPE_ID = Z.GRUPPE_ID)
                        UNION DISTINCT
                        SELECT Z.MANDANT_ID, Z.ZEK_ID, U.USER_ID
                        FROM KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2 AS G
                            INNER JOIN KFL_PRODUCTION_DBP_SECURITY.GRUPPE_GRUPPE_ZU_2 AS GG ON G.GRUPPE_ID = GG.GRUPPE_PARENT_ID
                            INNER JOIN KFL_PRODUCTION_DBP_SECURITY.GRUPPE_USER_ZU_2 AS U ON G.GRUPPE_ID = U.GRUPPE_ID AND U.DAT_GUELTIG_BIS >= CURRENT_DATE OR G.GRUPPE_PARENT_ID = U.GRUPPE_ID AND U.DAT_GUELTIG_BIS >= CURRENT_DATE OR GG.GRUPPE_ID = U.GRUPPE_ID AND U.DAT_GUELTIG_BIS >= CURRENT_DATE
                            INNER JOIN KFL_PRODUCTION_DBP_SECURITY.GRUPPE_ZEK_ZU_2 AS Z ON GG.GRUPPE_ID = Z.GRUPPE_ID) AS a) AS t3
    WHERE NOT EXISTS (SELECT 1 AS `A12180`
            FROM KFL_PRODUCTION_DBP_SECURITY.USER_ZEK_ZU_2
            WHERE ZEK_ID = t3.ZEK_ID AND MANDANT_ID = t3.MANDANT_ID)
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY ZEK_ID, MANDANT_ID)) = 1);
COMMIT TRANSACTION;
SET out_param  =  'Erfolgreich';
SELECT out_param;
RETURN;
END;
END;
