CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2 (
MANDANT_ID INTEGER NOT NULL,
LAGERBEW_BELEG_ID INTEGER NOT NULL,
LAGERBEW_BELEG_POS_ID INTEGER NOT NULL,
KJ INTEGER NOT NULL,
ART_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID INTEGER NOT NULL,
DAT_BUCH DATE NOT NULL,
ANZ_EK_INFOSATZ INTEGER,
ANZ_EK_ORDERBUCH INTEGER,
BQ_GP_ID INTEGER,
BQ_EKORG INTEGER,
BQ_FINDUNG_ID INTEGER,
REGEL_GP_ID INTEGER,
REGEL_EKORG INTEGER
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2 (MANDANT_ID, LAGERBEW_BELEG_ID, LAGERBEW_BELEG_POS_ID, KJ,
 ART_ID, WUP_ID, NB_ID, DAT_BUCH, ANZ_EK_INFOSATZ, ANZ_EK_ORDERBUCH, BQ_GP_ID, BQ_EKORG, BQ_FINDUNG_ID, REGEL_GP_ID,
 REGEL_EKORG)
(SELECT A.MANDANT_ID,
  A.LAGERBEW_BELEG_ID,
  A.LAGERBEW_BELEG_POS_ID,
  A.KJ,
  A.ART_ID,
   CASE
   WHEN A.NB_ID = - 111
   THEN A.WUP_ID
   ELSE W.WUP_ID
   END AS WUP_ID_,
  - 111 AS NB_ID_,
  A.DAT_BUCH,
  0 AS ANZ_EK_INFOSATZ,
  0 AS ANZ_EK_ORDERBUCH,
  0 AS BQ_GP_ID,
  0 AS BQ_EKORG,
  0 AS BQ_FINDUNG_ID,
  0 AS REGEL_GP_ID,
  0 AS REGEL_EKORG
 FROM KFL_PRODUCTION_DBP_DATA.LAGERBEW_DET_DELTA_2 AS A
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS W ON A.MANDANT_ID = W.MANDANT_ID AND A.EMPFAENGER_ID = W.WUP_ID
 WHERE (A.NB_ID = - 111 OR W.NB_ID = - 111)
  AND A.MANDANT_ID > 1
  AND A.LAGER_BEWART_ID IN ('301', '302', '311', '312', '641', '642', '647', '648')
  AND (A.MANDANT_ID, A.LAGERBEW_BELEG_ID, A.LAGERBEW_BELEG_POS_ID, A.KJ) NOT IN (SELECT (MANDANT_ID, LAGERBEW_BELEG_ID,
      LAGERBEW_BELEG_POS_ID, KJ)
    FROM KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2));


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_2 (
DAT_BUCH DATE
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_2 (DAT_BUCH)
(SELECT DAT_BUCH
 FROM KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2
 GROUP BY DAT_BUCH);


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_MIN_2 (
DAT_BUCH DATE
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_MIN_2 (DAT_BUCH)
(SELECT MIN(DAT_BUCH) AS DAT_BUCH
 FROM KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2);


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_ANR_2 (
MANDANT_ID INTEGER NOT NULL,
LAGERBEW_BELEG_ID INTEGER NOT NULL,
LAGERBEW_BELEG_POS_ID INTEGER NOT NULL,
KJ INTEGER NOT NULL,
DAT_BUCH DATE NOT NULL,
GP_ID_ZL INTEGER NOT NULL,
EINKAUFSORGANISATION_ID INTEGER,
BQ_FINDUNG_ID INTEGER NOT NULL,
BETRAG_EINSTANDSPREIS NUMERIC(18,4)
);


CREATE OR REPLACE TABLE DEFAULTSCHEMA.`_VOL_ART_GP_WUP_ZU_PER` (
MANDANT_ID INTEGER NOT NULL,
ART_ID INTEGER NOT NULL,
GP_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID INTEGER,
EINKAUFSORGANISATION_ID INTEGER NOT NULL,
DAT DATE NOT NULL,
EINSTANDSPREIS NUMERIC(18,4)
);


INSERT INTO DEFAULTSCHEMA.`_VOL_ART_GP_WUP_ZU_PER` (MANDANT_ID, ART_ID, GP_ID, WUP_ID, NB_ID, EINKAUFSORGANISATION_ID,
 DAT, EINSTANDSPREIS)
(SELECT a.MANDANT_ID,
  a.ART_ID,
  a.GP_ID,
  a.WUP_ID,
  a.NB_ID,
  a.EINKAUFSORGANISATION_ID,
  D.DAT_BUCH,
  a.EINSTANDSPREIS
 FROM (SELECT A.MANDANT_ID,
    A.WUP_ID,
    A.NB_ID,
    A.ART_ID,
    A.GP_ID,
    A.EINKAUFSORGANISATION_ID,
    A.DAT_VON,
    A.DAT_BIS,
    A.WRG_ID,
    CAST(A.EINSTANDSPREIS AS NUMERIC) AS EINSTANDSPREIS
   FROM KFL_PRODUCTION_DBP_DATA.ART_GP_WUP_ZU_PER_2 AS A
    INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_MIN_2 AS M ON A.DAT_BIS >= M.DAT_BUCH
   WHERE A.MANDANT_ID > 1
    AND (A.MANDANT_ID, A.ART_ID) IN (SELECT (MANDANT_ID, ART_ID)
      FROM KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2)) AS a
  INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_2 AS D ON D.DAT_BUCH BETWEEN a.DAT_VON AND a.DAT_BIS);


INSERT INTO KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_ANR_2 (MANDANT_ID, LAGERBEW_BELEG_ID, LAGERBEW_BELEG_POS_ID, KJ, DAT_BUCH
 , GP_ID_ZL, EINKAUFSORGANISATION_ID, BQ_FINDUNG_ID, BETRAG_EINSTANDSPREIS)
(SELECT MANDANT_ID,
  LAGERBEW_BELEG_ID,
  LAGERBEW_BELEG_POS_ID,
  KJ,
  DAT_BUCH,
  GP_ID_ZL,
  EINKAUFSORGANISATION_ID,
  BQ_FINDUNG_ID_,
  CAST(EINSTANDSPREIS_ AS NUMERIC) AS EINSTANDSPREIS_
 FROM (SELECT A.MANDANT_ID,
    A.LAGERBEW_BELEG_ID,
    A.LAGERBEW_BELEG_POS_ID,
    A.KJ,
    X.EINKAUFSORGANISATION_ID,
    A.DAT_BUCH,
     CASE
     WHEN X.BQ_FINDUNG_ID = 25
     THEN 0
     ELSE ROUND(CAST(A.MENGE_LAGERBEW_BME * COALESCE(AGW.EINSTANDSPREIS, AGWW.EINSTANDSPREIS) AS NUMERIC), 4)
     END AS EINSTANDSPREIS_,
    X.GP_ID AS GP_ID_ZL,
     X.BQ_FINDUNG_ID + CASE
      WHEN X.BEZUGSWEG_ID = 1 AND X.BQ_FINDUNG_ID NOT IN (25, 26, 27)
      THEN 12
      ELSE 0
      END AS BQ_FINDUNG_ID_
   FROM KFL_PRODUCTION_DBP_DATA.LAGERBEW_DET_DELTA_2 AS A
    INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_2 AS D ON A.DAT_BUCH = D.DAT_BUCH
    INNER JOIN KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2 AS Z ON A.MANDANT_ID = Z.MANDANT_ID AND A.LAGERBEW_BELEG_ID
          = Z.LAGERBEW_BELEG_ID AND A.LAGERBEW_BELEG_POS_ID = Z.LAGERBEW_BELEG_POS_ID AND A.KJ = Z.KJ AND A.DAT_BUCH = Z
      .DAT_BUCH
    INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_GP_NM_ZU_PER_2 AS X ON A.MANDANT_ID = X.MANDANT_ID AND A.ART_ID = X.ART_ID AND
       A.WUP_ID = X.WUP_ID AND A.DAT_BUCH BETWEEN X.DAT_VON AND X.DAT_BIS
    LEFT JOIN DEFAULTSCHEMA.`_VOL_ART_GP_WUP_ZU_PER` AS AGW ON A.MANDANT_ID = AGW.MANDANT_ID AND Z.WUP_ID = AGW.WUP_ID
         AND Z.NB_ID = AGW.NB_ID AND A.ART_ID = AGW.ART_ID AND X.GP_ID = AGW.GP_ID AND X.EINKAUFSORGANISATION_ID = AGW.EINKAUFSORGANISATION_ID
        AND A.DAT_BUCH = AGW.DAT
    LEFT JOIN DEFAULTSCHEMA.`_VOL_ART_GP_WUP_ZU_PER` AS AGWW ON A.MANDANT_ID = AGWW.MANDANT_ID AND AGWW.WUP_ID = - 1 AND
         A.ART_ID = AGWW.ART_ID AND X.GP_ID = AGWW.GP_ID AND X.EINKAUFSORGANISATION_ID = AGWW.EINKAUFSORGANISATION_ID
     AND A.DAT_BUCH = AGWW.DAT
   GROUP BY A.MANDANT_ID,
    A.LAGERBEW_BELEG_ID,
    A.LAGERBEW_BELEG_POS_ID,
    A.KJ,
    X.EINKAUFSORGANISATION_ID,
    A.DAT_BUCH,
    EINSTANDSPREIS_,
    GP_ID_ZL,
    BQ_FINDUNG_ID_) AS a);


UPDATE KFL_PRODUCTION_DBP_DATA.LAGERBEW_DET_DELTA_2 SET
 GP_ID_ZL = A.GP_ID_ZL,
 EINKAUFSORGANISATION_ID = A.EINKAUFSORGANISATION_ID,
 BQ_FINDUNG_ID = A.BQ_FINDUNG_ID,
 BETRAG_EINSTANDSPREIS = COALESCE(A.BETRAG_EINSTANDSPREIS, LAGERBEW_DET_DELTA.BETRAG_LAGERBEW) FROM
 KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_ANR_2 AS A
WHERE LAGERBEW_DET_DELTA.MANDANT_ID = A.MANDANT_ID AND LAGERBEW_DET_DELTA.LAGERBEW_BELEG_ID = A.LAGERBEW_BELEG_ID AND
    LAGERBEW_DET_DELTA.LAGERBEW_BELEG_POS_ID = A.LAGERBEW_BELEG_POS_ID AND LAGERBEW_DET_DELTA.KJ = A.KJ AND
  LAGERBEW_DET_DELTA.DAT_BUCH = A.DAT_BUCH;


DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_2;


DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_DAT_MIN_2;


DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.KMO_MKPFMSEG_ANR_2;


TRUNCATE TABLE KFL_PRODUCTION_DBP_ETL.KMO_MSEG_ART_GP_WUP_ZU_2;