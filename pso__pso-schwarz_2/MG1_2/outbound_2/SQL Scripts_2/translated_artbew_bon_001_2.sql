INSERT INTO `_ARTBEW_TMP` (ART_ID, WUP_ID, MANDANT_ID, BEWART_ID, NB_ID, DAT, AKTION_ID, EAN_KASSE, MWST_ID, MENGE, WRG_2
 , UMSATZ_NETTO, UMSATZ_MWST_BETRAG, BEZUGSWEG_ID, POSTEN_ID, BEWART_DET_ID)
(SELECT CAST(COALESCE(t1.ART_ID, ERF.ART_ID, 0) AS INTEGER),
  CAST(p.WUP_ID AS INTEGER) AS WUP_ID,
  p.MANDANT_ID,
  p.BEWART_ID,
  CAST(W.NB_ID AS SMALLINT) AS NB_ID,
  p.DAT,
  p.AKTION_ID,
  COALESCE(p.EAN_KASSE, 0) AS EAN_KASSE,
  COALESCE(MW.MWST_ID, MWS.MWST_ID),
  SUM(p.MENGE) AS MENGE_,
  'EUR' AS WRG_2,
   CAST(SUM(p.UMSATZ)AS NUMERIC) - SUM(CAST(p.UMSATZ / (1 + COALESCE(MW.MWST, MWS.MWST) / 100) * (COALESCE(MW.MWST, MWS.MWST) / 100)AS NUMERIC)) AS
  UMSATZ_NETTO,
  SUM(CAST(p.UMSATZ / (1 + COALESCE(MW.MWST, MWS.MWST) / 100) * (COALESCE(MW.MWST, MWS.MWST) / 100)AS NUMERIC)) AS UMSATZ_MWST_BETRAG,
  COALESCE(AW.BEZUGSWEG_ID, p.BEZUGSWEG_ID),
  COALESCE(t1.POSTEN_ID, '') AS POSTEN_ID,
  p.BEWART_DET_ID
 FROM (SELECT MANDANT_ID,
    WUP_ID,
    DAT,
    KL_ART_ID,
    EAN_KASSE,
    WG_ID,
    CAST(UMSATZ_BRUTTO AS FLOAT64) AS UMSATZ,
    MWST_ID,
    MENGE,
     CASE
     WHEN LTRIM(AKTION_ID) IN ('0', '0000000000', '')
     THEN 1001
     ELSE 1002
     END AS BEWART_ID,
     CASE
     WHEN LTRIM(AKTION_ID) IN ('0', '0000000000', '')
     THEN ''
     ELSE AKTION_ID
     END AS AKTION_ID,
    4 AS BEZUGSWEG_ID,
     CASE
     WHEN LTRIM(AKTION_ID) IN ('0', '0000000000', '') AND KUNDENKARTE_ID IS NULL AND KUNDENKARTE_TYP_ID = 0
     THEN 100110
     ELSE CASE
      WHEN LTRIM(AKTION_ID) IN ('0', '0000000000', '') AND KUNDENKARTE_TYP_ID IN (2) AND KUNDENKARTE_ID IS NOT NULL
      THEN 100111
      ELSE CASE
       WHEN KUNDENKARTE_ID IS NULL AND KUNDENKARTE_TYP_ID = 0 AND (BONUSKAUF_ID IS NULL OR CAST(BONUSKAUF_ID AS FLOAT64)
             = 0) AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000', '') AND AKTION_ID_OBV IS NOT NULL
       THEN 100210
       ELSE CASE
        WHEN KUNDENKARTE_TYP_ID IN (2) AND (BONUSKAUF_ID IS NULL OR CAST(BONUSKAUF_ID AS FLOAT64) = 0) AND LTRIM(AKTION_ID
             ) NOT IN ('0', '0000000000', '') AND KUNDENKARTE_ID IS NOT NULL AND AKTION_ID_OBV IS NOT NULL
        THEN 100211
        ELSE CASE
         WHEN KUNDENKARTE_ID IS NULL AND KUNDENKARTE_TYP_ID = 0 AND CUSTOMER_PROMOTION_FG = 0 AND PROMOTION_ART =
             'COMMON' AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000', '') AND BONUSKAUF_ID IS NOT NULL
         THEN 100220
         ELSE CASE
          WHEN KUNDENKARTE_TYP_ID IN (2) AND CUSTOMER_PROMOTION_FG = 0 AND PROMOTION_ART = 'COMMON' AND LTRIM(AKTION_ID
               ) NOT IN ('0', '0000000000', '') AND BONUSKAUF_ID IS NOT NULL AND KUNDENKARTE_ID IS NOT NULL
          THEN 100221
          ELSE CASE
           WHEN CUSTOMER_PROMOTION_FG = 1 AND PROMOTION_ART = 'CUSTOMER' AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000'
               , '') AND BONUSKAUF_ID IS NOT NULL
           THEN 100231
           ELSE CASE
            WHEN CUSTOMER_PROMOTION_FG = 1 AND PROMOTION_ART = 'PERSONAL' AND LTRIM(AKTION_ID) NOT IN ('0', '0000000000'
                , '') AND BONUSKAUF_ID IS NOT NULL
            THEN 100241
            ELSE 9999
            END
           END
          END
         END
        END
       END
      END
     END AS BEWART_DET_ID
   FROM KFL_PRODUCTION_DBP_ETL.BON_ARTBEW_TMP_TALON_2) AS p
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS W ON p.MANDANT_ID = W.MANDANT_ID AND p.WUP_ID = W.WUP_ID
  LEFT JOIN (SELECT MANDANT_ID,
    ART_ID,
    KL_ART_ID,
    POSTEN_ID,
    MWST_ID
   FROM KFL_PRODUCTION_DBP_DATA.ART_2
   QUALIFY (ROW_NUMBER() OVER (PARTITION BY CAST(MANDANT_ID AS STRING), CAST(KL_ART_ID AS STRING) ORDER BY ART_ID
         IS NULL DESC, ART_ID DESC)) = 1) AS t1_2 ON p.KL_ART_ID = t1.KL_ART_ID AND p.MANDANT_ID = t1.MANDANT_ID
  LEFT JOIN KFL_PRODUCTION_DBP_ETL_PROCESS.DWH_WG_ERFASS_ARTIKEL_2 AS ERF ON p.MANDANT_ID = ERF.MANDANT_ID AND p.WG_ID =
     ERF.WG_ID AND ERF.ARTHIERTYP_ID = 2
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_2 AS AERF ON ERF.MANDANT_ID = AERF.MANDANT_ID AND ERF.ART_ID = AERF.ART_ID
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.MWST_PER_2 AS MW ON p.MANDANT_ID = MW.MANDANT_ID AND p.DAT BETWEEN MW.DAT_VON AND MW.DAT_BIS
       AND p.MWST_ID = MW.MWST_ID AND COALESCE(MW.MWST, 0) <> 0
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.MWST_PER_2 AS MWS ON p.MANDANT_ID = MWS.MANDANT_ID AND p.DAT BETWEEN MWS.DAT_VON AND
     MWS.DAT_BIS AND COALESCE(t1.MWST_ID, AERF.MWST_ID) = MWS.MWST_ID
  LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_WUP_ZU_PER_2 AS AW ON p.MANDANT_ID = AW.MANDANT_ID AND p.WUP_ID = AW.WUP_ID AND
     COALESCE(t1.ART_ID, ERF.ART_ID, 0) = AW.ART_ID AND p.DAT BETWEEN AW.DAT_VON AND AW.DAT_BIS
 GROUP BY p.MANDANT_ID,
  WRG_2,
  p.WUP_ID,
  W.NB_ID,
  p.DAT,
  POSTEN_ID,
  COALESCE(AW.BEZUGSWEG_ID, p.BEZUGSWEG_ID),
  1,
  EAN_KASSE,
  p.BEWART_ID,
  COALESCE(MW.MWST_ID, MWS.MWST_ID),
  p.AKTION_ID,
  p.BEWART_DET_ID
 HAVING MENGE_ <> 0 OR SUM(p.UMSATZ) - UMSATZ_MWST_BETRAG <> 0);


