UPDATE _ARTBEW_TMP_ANR 
SET HERST_ID = CAST(DT1._HERST_ID AS INT64), 
    GP_ID = CAST(DT1._GP_ID AS INT64), 
    EINKAUFSORGANISATION_ID = CAST(coalesce(DT1._EINKAUFSORGANISATION_ID, 1000) AS INT64), 
EK_BRUTTO = CASE
  WHEN DT1._EK_BRUTTO IS NOT NULL THEN CAST( DT1._EK_BRUTTO as NUMERIC)
END, EK_NETTO = CASE
  WHEN DT1._EK_NETTO IS NOT NULL THEN CAST( DT1._EK_NETTO as NUMERIC)
END, EK_NETTONETTO = CASE
  WHEN DT1._EK_NETTONETTO IS NOT NULL THEN CAST( DT1._EK_NETTONETTO as NUMERIC)
END, EK_KAL_BASIS = CASE
  WHEN DT1._EK_KAL_BASIS IS NOT NULL THEN CAST( DT1._EK_KAL_BASIS as NUMERIC)
END, EK_MEP = CASE
  WHEN DT1._EK_MEP IS NOT NULL THEN CAST( DT1._EK_MEP as NUMERIC)
END, EINSTANDSPREIS = CASE
  WHEN DT1._EINSTANDSPREIS IS NOT NULL THEN CAST( DT1._EINSTANDSPREIS as NUMERIC)
END, LOGKOSTENZUSCHLAG = CASE
  WHEN DT1._LOGKOSTENZUSCHLAG IS NOT NULL THEN DT1._LOGKOSTENZUSCHLAG
END, EK_NETTO_BNK = CASE
  WHEN DT1._EK_NETTO_BNK IS NOT NULL THEN CAST( DT1._EK_NETTO_BNK as NUMERIC)
END, EK_NETTO_BNK_SACHK = CASE
  WHEN DT1._EK_NETTO_BNK_SACHK IS NOT NULL THEN CAST( DT1._EK_NETTO_BNK_SACHK as NUMERIC)
END FROM (
  SELECT
      T1.MANDANT_ID AS _MANDANT_ID,
      T1.ART_ID AS _ART_ID,
      T1.BEZUGSWEG_ID AS _BEZUGSWEG_ID,
      T1.DAT AS _DAT,
      coalesce(T4.HERST_ID, T2.GP_ID, -1) AS _HERST_ID,
      coalesce(T2.GP_ID, -1) AS _GP_ID,
      T2.EINKAUFSORGANISATION_ID AS _EINKAUFSORGANISATION_ID,
      T2.EK_BRUTTO AS _EK_BRUTTO,
      T2.EK_NETTO AS _EK_NETTO,
      T2.EK_NETTONETTO AS _EK_NETTONETTO,
      T2.EK_KAL_BASIS AS _EK_KAL_BASIS,
      T2.EK_MEP AS _EK_MEP,
      T2.EINSTANDSPREIS AS _EINSTANDSPREIS,
      T2.LOGISTIKKOSTENZUSCHLAG AS _LOGKOSTENZUSCHLAG,
      T2.EK_NETTO_BNK AS _EK_NETTO_BNK,
      T2.EK_NETTO_BNK_SACHK AS _EK_NETTO_BNK_SACHK
    FROM
      _ARTBEW_TMP_ANR AS T1_2
      -- Ermittelung potentieller ZEKP_2-Sätze für EK und GP_2
      LEFT OUTER JOIN _XXX AS T2 ON T1.MANDANT_ID = T2.MANDANT_ID
       AND T1.ART_ID = T2.ART_ID
       AND T1.DAT BETWEEN T2.DAT_VON AND T2.DAT_BIS
      -- Ermittelung der Hersteller_id
      LEFT OUTER JOIN KFL_PRODUCTION_DBP_DATA.ART_GP_ZU_PER_2 AS T4 ON T1.MANDANT_ID = T4.MANDANT_ID
       AND T1.ART_ID = T4.ART_ID
       AND T1.DAT BETWEEN T4.DAT_VON AND T4.DAT_BIS
    WHERE T1.MANDANT_ID = 1
    QUALIFY row_number() OVER (PARTITION BY _MANDANT_ID, _ART_ID, _BEZUGSWEG_ID, _DAT ORDER BY if(CASE
      WHEN _BEZUGSWEG_ID = 1
       AND T2.WUP_ID = -1
       OR _BEZUGSWEG_ID = 4
       AND T2.WUP_ID <> -1 THEN 1
      ELSE 0
    END IS NULL, 0, 1) /*Richtiger Bezugsweg*/, CASE
      WHEN _BEZUGSWEG_ID = 1
       AND T2.WUP_ID = -1
       OR _BEZUGSWEG_ID = 4
       AND T2.WUP_ID <> -1 THEN 1
      ELSE 0
    END DESC, if(T2.DAT_VON IS NULL, 0, 1) /* jüngster Satz*/, T2.DAT_VON DESC, if(_EK_BRUTTO IS NULL, 0, 1) /* kleinster ek_brutto*/, CAST( _EK_BRUTTO as NUMERIC) DESC, if(T2.GP_ID IS NULL, 0, 1) DESC, T2.GP_ID) = 1
) AS DT1 -- höchte Lieferantennummer
WHERE MANDANT_ID = DT1._MANDANT_ID
 AND ART_ID = DT1._ART_ID
 AND BEZUGSWEG_ID = DT1._BEZUGSWEG_ID
 AND DAT = DT1._DAT;

UPDATE _ARTBEW_TMP_ANR 
SET FAKTOR_FG = 1, 
    EK_BRUTTO = DT1.ZWGE, 
    EK_NETTO = DT1.ZWGE, 
    EK_NETTONETTO = DT1.ZWGM, 
    EK_KAL_BASIS = DT1.ZWGM, 
    EK_MEP = DT1.ZWGM, 
    EINSTANDSPREIS = DT1.ZWGS, 
    LOGKOSTENZUSCHLAG = 0, 
    EK_NETTO_BNK = DT1.ZWGE, 
    EK_NETTO_BNK_SACHK = DT1.ZWGM 
FROM (
  SELECT
      T0.MANDANT_ID AS _MANDANT_ID,
      T0.ART_ID AS _ART_ID,
      T0.DAT AS _DAT,
      max(T1.EK_FAKTOR) AS ZWGS,
      max(coalesce(T2.EK_FAKTOR, T1.EK_FAKTOR)) AS ZWGM,
      max(coalesce(T3.EK_FAKTOR, T2.EK_FAKTOR, T1.EK_FAKTOR)) AS ZWGE
    FROM
      _ARTBEW_TMP_ANR AS T0
      INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_MAN_SPANNE_PER_2 AS T1_2 ON T0.MANDANT_ID = T1.MANDANT_ID
       AND T0.ART_ID = T1.ART_ID
       AND T0.DAT BETWEEN T1.DAT_VON AND T1.DAT_BIS
       AND T1.KONDITIONSART_ID = 'ZWGS'
       AND T1.LOESCH_FG = 0
      LEFT OUTER JOIN KFL_PRODUCTION_DBP_DATA.ART_MAN_SPANNE_PER_2 AS T2 ON T0.MANDANT_ID = T2.MANDANT_ID
       AND T0.ART_ID = T2.ART_ID
       AND T0.DAT BETWEEN T2.DAT_VON AND T2.DAT_BIS
       AND T2.KONDITIONSART_ID = 'ZWGM'
       AND T2.LOESCH_FG = 0
      LEFT OUTER JOIN KFL_PRODUCTION_DBP_DATA.ART_MAN_SPANNE_PER_2 AS T3 ON T0.MANDANT_ID = T3.MANDANT_ID
       AND T0.ART_ID = T3.ART_ID
       AND T0.DAT BETWEEN T3.DAT_VON AND T3.DAT_BIS
       AND T3.KONDITIONSART_ID = 'ZWGE'
       AND T3.LOESCH_FG = 0
    GROUP BY 1, 2, 3
) AS DT1 WHERE MANDANT_ID = DT1._MANDANT_ID
