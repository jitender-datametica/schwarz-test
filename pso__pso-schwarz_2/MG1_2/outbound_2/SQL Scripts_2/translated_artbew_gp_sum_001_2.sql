DELETE FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_GP_SUM_2
WHERE DAT = DATE '1900-01-01' OR DAT IN (SELECT DAT
   FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_AGG_WT_2
   WHERE MANDANT_ID = 1
   GROUP BY DAT);


INSERT INTO KFL_PRODUCTION_DBP_DATA.ARTBEW_GP_SUM_2 (MANDANT_ID, DAT, GP_ID, VW_ID, WRG_2, UMSATZ_NETTO, EK_MEP,
 UMRECHNUNGSKURS_HIST)
(SELECT T1.MANDANT_ID,
  T1.DAT,
  T1.GP_ID,
  T2.VW_ID,
  T1.WRG_2,
  SUM(T1.UMSATZ_NETTO) AS UMSATZ_NETTO,
  SUM(CAST(T1.EK_MEP AS NUMERIC)) AS EK_MEP,
  T1.UMRECHNUNGSKURS_HIST
 FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_2 AS T1_2
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS T2 ON T1.WUP_ID = T2.WUP_ID AND T1.MANDANT_ID = T2.MANDANT_ID
 WHERE T1.MANDANT_ID = 1
  AND (T1.DAT = DATE '1900-01-01' OR T1.DAT IN (SELECT DAT
      FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_AGG_WT_2
      WHERE MANDANT_ID = 1
      GROUP BY DAT))
 GROUP BY T1.MANDANT_ID,
  T1.GP_ID,
  T2.VW_ID,
  T1.DAT,
  T1.WRG_2,
  T1.UMRECHNUNGSKURS_HIST);