DAT DATE NOT NULL
);


INSERT INTO `_FAECHER` (MANDANT_ID, VW_ID, WUP_ID, NB_ID, DAT)
(SELECT t0.MANDANT_ID,
  B.VW_ID,
  B.WUP_ID,
  B.NB_ID,
  t0.DAT
 FROM (SELECT X.MANDANT_ID,
    Y.VW_ID,
    X.DAT
   FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_AGG_WT_2 AS X
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS Y ON X.MANDANT_ID = Y.MANDANT_ID AND X.WUP_ID = Y.WUP_ID AND X.NB_ID = Y.NB_ID
      
   GROUP BY X.MANDANT_ID,
    X.DAT,
    Y.VW_ID) AS t0
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS B ON t0.MANDANT_ID = B.MANDANT_ID AND t0.VW_ID = B.VW_ID);


