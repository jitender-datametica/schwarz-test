DELETE FROM KFL_PRODUCTION_DBP_MSI_DATA.CHECK_BLACKBERRY_2
WHERE DAT IN (SELECT DAT
  FROM KFL_PRODUCTION_DBP_DATA.TAG_2
  WHERE AKT_TAG = 0);


INSERT INTO KFL_PRODUCTION_DBP_MSI_DATA.CHECK_BLACKBERRY_2 (DAT, MANDANT_ID, LIEFERQUOTE_REAL, LIEFERQUOTE_DEF,
 DATENQUOTE_REAL, DATENQUOTE_DEF, BB_FG, CHECK_FG, UMSATZ_IST, UMSATZ_VJ, UMSATZ_PLAN, UMSATZ_VORTAG, UMSATZ_VORWOCHE,
 KUNDEN_IST, KUNDEN_VJ, TD_INSERT, TD_UPDATE)
(SELECT COALESCE(t05.DAT, DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)) AS DAT,
  T06.MANDANT_ID,
  COALESCE(t05.FLAG_LIEFERUNG, - 1) AS LIEFERQUOTE_REAL,
  T06.LIEFERQUOTE AS LIEFERQUOTE_DEF,
  COALESCE(t05.FLAG_INHALT, - 1) AS DATENQUOTE_REAL,
  T06.DATENQUOTE AS DATENQUOTE_DEF,
   CASE
   WHEN t05.FLAG_LIEFERUNG IS NULL OR COALESCE(t05.FLAG_LIEFERUNG, - 1) > T06.LIEFERQUOTE AND COALESCE(t05.FLAG_INHALT,
       - 1) > T06.DATENQUOTE
   THEN 1
   ELSE 0
   END AS BB_FG,
   CASE
   WHEN t05.FLAG_LIEFERUNG IS NULL OR COALESCE(t05.FLAG_LIEFERUNG, - 1) > T06.LIEFERQUOTE AND COALESCE(t05.FLAG_INHALT,
       - 1) > T06.DATENQUOTE
   THEN 1
   ELSE 0
   END AS CHECK_FG,
  CAST(COALESCE(t07.UMSATZ_IST, 0) AS NUMERIC) AS UMSATZ_IST,
  CAST(COALESCE(t07.UMSATZ_VJ, 0) AS NUMERIC) AS UMSATZ_VJ,
  CAST(COALESCE(t07.UMSATZ_PLAN, 0) AS NUMERIC) AS UMSATZ_PLAN,
  CAST(COALESCE(t07.UMSATZ_VORTAG, 0) AS NUMERIC) AS UMSATZ_VORTAG,
  CAST(COALESCE(t07.UMSATZ_VORWOCHE, 0) AS NUMERIC) AS UMSATZ_VORWOCHE,
  COALESCE(t07.KUNDEN_IST, 0) AS KUNDEN_IST,
  COALESCE(t07.KUNDEN_VJ, 0) AS KUNDEN_VJ,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP()
 FROM (SELECT DISTINCT t01.MANDANT_ID,
    COALESCE(t01.DAT, t5.DAT, t8.DAT) AS DAT,
    ROUND(CAST(CAST(IFNULL(t01.COUNT_WUP, 0) - IFNULL(t5.COUNT_WUP_BER, 0) AS FLOAT64) / t01.COUNT_WUP * 100 AS NUMERIC
      ), 2) AS FLAG_LIEFERUNG,
    ROUND(CAST(CAST(IFNULL(t01.COUNT_WUP, 0) - IFNULL(t8.COUNT_WUP_PLAUSI, 0) AS FLOAT64) / t01.COUNT_WUP * 100 AS
      NUMERIC), 2) AS FLAG_INHALT
   FROM (SELECT T01.DAT,
      T01.MANDANT_ID,
      IFNULL(COUNT(T01.WUP_ID), 0) AS COUNT_WUP
     FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS T01
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T02 ON T01.DAT = T02.DAT AND TRIM(SUBSTR(CAST(EXTRACT(DAY FROM DATE_SUB(T01.DAT, INTERVAL 364 DAY)) AS STRING)
            , 1, 19)) || '.' || TRIM(SUBSTR(CAST(EXTRACT(MONTH FROM DATE_SUB(T01.DAT, INTERVAL 364 DAY)) AS STRING), 1,
           19)) = TRIM(SUBSTR(CAST(EXTRACT(DAY FROM DATE_SUB(T02.DAT, INTERVAL 364 DAY)) AS STRING), 1, 19)) || '.' ||
         TRIM(SUBSTR(CAST(EXTRACT(MONTH FROM DATE_SUB(T02.DAT, INTERVAL 364 DAY)) AS STRING), 1, 19))
     WHERE T02.AKT_TAG = 0
      AND T01.OFFEN = 1
      AND T01.NB_ID IN (0)
     GROUP BY T01.MANDANT_ID,
      T01.DAT) AS t01
    FULL JOIN (SELECT T010.DAT,
      T010.MANDANT_ID,
      COUNT(T010.WUP_ID) AS COUNT_WUP_BER
     FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS T010
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T020 ON T010.DAT = T020.DAT AND TRIM(SUBSTR(CAST(EXTRACT(DAY FROM DATE_SUB(T010.DAT, INTERVAL 364 DAY)) AS STRING)
            , 1, 19)) || '.' || TRIM(SUBSTR(CAST(EXTRACT(MONTH FROM DATE_SUB(T010.DAT, INTERVAL 364 DAY)) AS STRING), 1
           , 19)) = TRIM(SUBSTR(CAST(EXTRACT(DAY FROM DATE_SUB(T020.DAT, INTERVAL 364 DAY)) AS STRING), 1, 19)) || '.'
         || TRIM(SUBSTR(CAST(EXTRACT(MONTH FROM DATE_SUB(T020.DAT, INTERVAL 364 DAY)) AS STRING), 1, 19))
     WHERE T020.AKT_TAG = 0
      AND T010.OFFEN = 1
      AND T010.NB_ID IN (0)
      AND T010.DATENLIEFERUNG_ARTBEW_WG_SUM IN (0, 2)
     GROUP BY T010.MANDANT_ID,
      T010.DAT) AS t5 ON t01.DAT = t5.DAT AND t01.MANDANT_ID = t5.MANDANT_ID
    FULL JOIN (SELECT T011.DAT,
      T011.MANDANT_ID,
      COUNT(T011.WUP_ID) AS COUNT_WUP_PLAUSI
     FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS T011
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T021 ON T011.DAT = T021.DAT AND TRIM(SUBSTR(CAST(EXTRACT(DAY FROM DATE_SUB(T011.DAT, INTERVAL 364 DAY)) AS STRING)
            , 1, 19)) || '.' || TRIM(SUBSTR(CAST(EXTRACT(MONTH FROM DATE_SUB(T011.DAT, INTERVAL 364 DAY)) AS STRING), 1
           , 19)) = TRIM(SUBSTR(CAST(EXTRACT(DAY FROM DATE_SUB(T021.DAT, INTERVAL 364 DAY)) AS STRING), 1, 19)) || '.'
         || TRIM(SUBSTR(CAST(EXTRACT(MONTH FROM DATE_SUB(T021.DAT, INTERVAL 364 DAY)) AS STRING), 1, 19))
     WHERE T021.AKT_TAG = 0
      AND T011.OFFEN = 1
      AND T011.NB_ID IN (0)
      AND T011.PRUEF_STATUS_ID_UMSATZ <= 0
     GROUP BY T011.MANDANT_ID,
      T011.DAT) AS t8 ON t01.DAT = t8.DAT AND t01.MANDANT_ID = t8.MANDANT_ID) AS t05
  FULL JOIN KFL_PRODUCTION_DBP_MSI_DATA.MIS_LIEFERQUOTE_2 AS T06 ON t05.MANDANT_ID = T06.MANDANT_ID
  INNER JOIN (SELECT MANDANT_ID,
    MAX(UMSATZ_IST) AS UMSATZ_IST,
    MAX(UMSATZ_VJ) AS UMSATZ_VJ,
    MAX(UMSATZ_PLAN) AS UMSATZ_PLAN,
    MAX(UMSATZ_VORTAG) AS UMSATZ_VORTAG,
    MAX(UMSATZ_VORWOCHE) AS UMSATZ_VORWOCHE,
    MAX(KUNDEN_IST) AS KUNDEN_IST,
    MAX(KUNDEN_VJ) AS KUNDEN_VJ
   FROM (SELECT T012.MANDANT_ID,
       CASE
       WHEN T022.AKT_TAG = 0
       THEN SUM(T012.UMS_NETTO)
       ELSE NULL
       END AS UMSATZ_IST,
       CASE
       WHEN T022.AKT_TAG = 0
       THEN SUM(T012.UMS_NETTO_WVJ)
       ELSE NULL
       END AS UMSATZ_VJ,
       CASE
       WHEN T022.AKT_TAG = 0
       THEN SUM(T012.UMS_NETTO_PLAN)
       ELSE NULL
       END AS UMSATZ_PLAN,
       CASE
       WHEN T022.AKT_TAG = - 1
       THEN SUM(T012.UMS_NETTO)
       ELSE NULL
       END AS UMSATZ_VORTAG,
       CASE
       WHEN T022.AKT_TAG = - 7
       THEN SUM(T012.UMS_NETTO)
       ELSE NULL
       END AS UMSATZ_VORWOCHE,
       CASE
       WHEN T022.AKT_TAG = 0
       THEN SUM(T012.ANZ_KUNDE)
       ELSE NULL
       END AS KUNDEN_IST,
       CASE
       WHEN T022.AKT_TAG = 0
       THEN SUM(T012.ANZ_KUNDE_WVJ)
       ELSE NULL
       END AS KUNDEN_VJ
     FROM KFL_PRODUCTION_DBP_MSI_DATA.VIS_TAG_UMSATZ_KUNDE_WUP_2 AS T012
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T022 ON T012.DAT = T022.DAT
     WHERE T022.AKT_TAG IN (0, - 1, - 7)
      AND T012.NB_ID = 0
      AND T012.WRG_ID = 'EUR'
     GROUP BY T012.MANDANT_ID,
      T022.AKT_TAG) AS t01
   GROUP BY MANDANT_ID) AS t07 ON T06.MANDANT_ID = t07.MANDANT_ID);