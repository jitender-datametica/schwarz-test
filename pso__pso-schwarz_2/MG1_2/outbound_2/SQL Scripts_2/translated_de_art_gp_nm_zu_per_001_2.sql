UPDATE `_ART_GP_NM_ZU_PER_TMP2` AS T
SET DAT_BIS = DT1.DAT_BIS_
FROM (
  SELECT
    T0.MANDANT_ID,
    T0.WUP_ID,
    T0.ART_ID,
    T0.DAT_VON,
    CASE
      WHEN (
           SUM(
             EXTRACT(YEAR  FROM T0.DAT_VON)*10000
             + EXTRACT(MONTH FROM T0.DAT_VON)*100
             + EXTRACT(DAY   FROM T0.DAT_VON)
           ) 
           OVER (
             PARTITION BY T0.MANDANT_ID, T0.WUP_ID, T0.ART_ID
             ORDER BY T0.DAT_VON DESC
             ROWS BETWEEN 1 PRECEDING AND CURRENT ROW
           )
           - (
             EXTRACT(YEAR  FROM T0.DAT_VON)*10000
             + EXTRACT(MONTH FROM T0.DAT_VON)*100
             + EXTRACT(DAY   FROM T0.DAT_VON)
           )
         ) = 0
      THEN DATE(9999,12,31)
      ELSE
        DATE_SUB(
          DATE(
            EXTRACT(YEAR  FROM T0.DAT_VON),
            EXTRACT(MONTH FROM T0.DAT_VON),
            EXTRACT(DAY   FROM T0.DAT_VON)
          ),
          INTERVAL 1 DAY
        )
    END AS DAT_BIS_
  FROM `_ART_GP_NM_ZU_PER_TMP2` AS T0
  GROUP BY
    T0.MANDANT_ID,
    T0.WUP_ID,
    T0.ART_ID,
    T0.DAT_VON
) AS DT1
WHERE T.MANDANT_ID = DT1.MANDANT_ID
  AND T.WUP_ID     = DT1.WUP_ID
  AND T.ART_ID     = DT1.ART_ID
  AND T.DAT_VON    = DT1.DAT_VON
  AND T.DAT_BIS    <> DT1.DAT_BIS_;




