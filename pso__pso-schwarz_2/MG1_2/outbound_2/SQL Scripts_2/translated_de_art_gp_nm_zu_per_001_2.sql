MERGE INTO `_ZWISCHEN_TABELLE` AS A
USING (
  SELECT
    A0.MANDANT_ID,
    A0.ART_ID,
    A0.WUP_ID,
    D.DAT_RELEVANT AS DAT,
    MIN(CAST(A0.BEZUGSQUELLE_KZ AS INT64)) AS BEZUGSWEG_ID_
  FROM KFL_PRODUCTION_DBP_DATA.ART_WUP_ORDERSATZ_2 AS A0
  JOIN KFL_PRODUCTION_DBP_ETL.ART_GP_NM_ZU_PER_DAT_RELEVANT_2 AS D
    ON D.DAT_RELEVANT BETWEEN A0.DAT_VON AND A0.DAT_BIS
  JOIN `_ZWISCHEN_TABELLE` AS Z
    ON A0.MANDANT_ID = Z.MANDANT_ID
       AND A0.WUP_ID = Z.WUP_ID
       AND A0.ART_ID = Z.ART_ID
  WHERE Z.BEZUGSWEG_ID NOT IN (1, 4)
    AND A0.MANDANT_ID = 1
    AND A0.BEZUGSQUELLE_KZ IN ('1', '4')
  GROUP BY A0.MANDANT_ID, A0.ART_ID, A0.WUP_ID, D.DAT_RELEVANT
) AS B
ON A.MANDANT_ID = B.MANDANT_ID
   AND A.ART_ID = B.ART_ID
   AND A.WUP_ID = B.WUP_ID
   AND A.DAT = B.DAT
WHEN MATCHED THEN
  UPDATE SET BEZUGSWEG_ID = B.BEZUGSWEG_ID_;





MERGE INTO _ZWISCHEN_TABELLE AS A USING (
  SELECT
      Y.MANDANT_ID,
      Y.ART_ID,
      Y.DAT,
      CAST(Y.BEZUGSWEG_ID AS INT64) AS BEZUGSWEG_ID_
    FROM
      (
        SELECT
            AWS.MANDANT_ID,
            AWS.ART_ID,
            X.DAT_RELEVANT AS DAT,
            CAST(AWS.BEZUGSWEG_ID AS INT64) AS BEZUGSWEG_ID,
            CAST(count(*) as INT64) AS ANZAHL
          FROM
            (
              SELECT
                  MANDANT_ID,
                  ART_ID,
                  DAT_VON,
                  DAT_BIS,
                  BEZUGSWEG_ID
                FROM
                  KFL_PRODUCTION_DBP_DATA.ART_WUP_STATUS_PER_2 AS A_0
                  INNER JOIN KFL_PRODUCTION_DBP_ETL.ART_GP_NM_ZU_PER_DAT_RELEVANT_2 AS D ON 1 = 1
                WHERE A_0.ART_ID IN(
                  SELECT
                      ART_ID
                    FROM
                      _ZWISCHEN_TABELLE
                    WHERE BEZUGSWEG_ID NOT IN(
                      1, 4
                    )
                )
                 AND A_0.MANDANT_ID = 1
                 AND A_0.BEZUGSWEG_ID IN(
                  1, 4
                )
                 AND A_0.DAT_BIS >= D.DAT_RELEVANT
            ) AS AWS
            INNER JOIN KFL_PRODUCTION_DBP_ETL.ART_GP_NM_ZU_PER_DAT_RELEVANT_2 AS X ON 1 = 1
          WHERE X.DAT_RELEVANT BETWEEN AWS.DAT_VON AND AWS.DAT_BIS
          GROUP BY 1, 2, 3, 4
      ) AS Y
    QUALIFY row_number() OVER (PARTITION BY Y.MANDANT_ID, Y.ART_ID, Y.DAT, Y.DAT ORDER BY if(Y.ANZAHL IS NULL, 0, 1), Y.ANZAHL DESC) = 1
) AS B
ON A.MANDANT_ID = B.MANDANT_ID
 AND A.ART_ID = B.ART_ID
 AND A.DAT = B.DAT
 AND A.BEZUGSWEG_ID NOT IN(
  1, 4
)
   WHEN MATCHED THEN UPDATE SET
    BEZUGSWEG_ID = B.BEZUGSWEG_ID_
;




