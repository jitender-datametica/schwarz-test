    K.UMRECHNUNGSKURS AS UMRECHNUNGSKURS_HIST,
    1 AS UMRECH_FAKTOR,
    NULL AS MENGE_KOMPONENTE_IN_VK_SET
   FROM (SELECT MANDANT_ID,
      WUP_ID,
      NB_ID,
      KOPF_ART_ID,
      DAT,
      ART_ID,
      STUECKLISTE_ID,
      WRG_2,
      SUM(UMSATZ_NETTO) AS UMSATZ_NETTO,
      SUM(UMSATZ_MWST) AS UMSATZ_MWST,
      SUM(KOMPONENTENMENGEN_FAKTOR) AS KOMPONENTENMENGEN_FAKTOR,
      SUM(EK_BRUTTO) AS EK_BRUTTO,
      SUM(EK_NETTO) AS EK_NETTO,
      SUM(EK_NETTONETTO) AS EK_NETTONETTO,
      SUM(EK_KAL_BASIS) AS EK_KAL_BASIS,
      SUM(EK_MEP) AS EK_MEP,
      SUM(EINSTANDSPREIS) AS EINSTANDSPREIS,
      SUM(LOGISTIKKOSTENZUSCHLAG) AS LOGISTIKKOSTENZUSCHLAG,
      SUM(EK_NETTO_BNK) AS EK_NETTO_BNK,
      SUM(EK_NETTO_BNK_SACHK) AS EK_NETTO_BNK_SACHK,
      BQ_FINDUNG_ID,
      MAX(UMRECHNUNGSKURS) AS UMRECHNUNGSKURS,
      SUM(EK_MEP_VOR_FWU) AS EK_MEP_VOR_FWU,
      SUM(BONUSBASIS) AS BONUSBASIS
     FROM `_STEP03_2`
     WHERE KOPF_ART_ID <> - 100
     GROUP BY MANDANT_ID,
      WUP_ID,
      NB_ID,
      ART_ID,
      DAT,
      WRG_2,
      KOPF_ART_ID,
      STUECKLISTE_ID,
      BQ_FINDUNG_ID) AS x
    LEFT JOIN KFL_PRODUCTION_DBP_DATA.KURS_2 AS K ON x.WRG_2 = K.VON_WRG_ID AND x.DAT BETWEEN K.DAT_VON AND K.DAT_BIS AND K
       .NACH_WRG_ID = 'EUR' AND K.KURSTYP_ID = 3) AS t3
 WHERE NOT EXISTS (SELECT 1 AS `A11860`
   FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_STUECKLISTE_ZU_2
   WHERE ART_ID = t3.ART_ID
    AND MANDANT_ID = t3.MANDANT_ID
    AND WUP_ID = t3.WUP_ID
    AND NB_ID = t3.NB_ID
    AND DAT = t3.DAT
    AND KOMPONENTE_ART_ID = t3.KOMPONENTE_ART_ID)
 QUALIFY (ROW_NUMBER() OVER (PARTITION BY ART_ID, MANDANT_ID, WUP_ID, NB_ID, DAT, KOMPONENTE_ART_ID)) = 1);


UPDATE KFL_PRODUCTION_DBP_DATA.ARTBEW_STUECKLISTE_ZU_2 SET
 UMRECH_FAKTOR = b.UMRECH_FAKTOR,
 MENGE_KOMPONENTE_IN_VK_SET = CAST(b.UMRECH_FAKTOR * b.MENGE_KOMPONENTE_IN_VK_SET AS NUMERIC) FROM (SELECT A.MANDANT_ID
   ,
   A.ART_ID,
   A.KOMPONENTE_ART_ID,
   A.WUP_ID,
   A.DAT,
   A.STUECKLISTE_ID,
   MAX(COALESCE(C.UMRECH_FAKTOR, 1.00000)) AS UMRECH_FAKTOR,
   MAX(b.KOMPONENTENMENGE) AS MENGE_KOMPONENTE_IN_VK_SET
  FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_STUECKLISTE_ZU_2 AS A
   INNER JOIN (SELECT *
    FROM KFL_PRODUCTION_DBP_DATA.STUECKLISTE_DET_2
    WHERE STUECKLISTE_TYP_ID = 'M') AS b ON A.MANDANT_ID = b.MANDANT_ID AND A.STUECKLISTE_ID = b.STUECKLISTE_ID AND A.KOMPONENTE_ART_ID
       = b.ART_ID AND A.DAT BETWEEN b.DAT_VON AND b.DAT_BIS
   LEFT JOIN KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER_2 AS C ON b.MANDANT_ID = C.MANDANT_ID AND b.ART_ID = C.ART_ID
        AND b.KOMPONENTENMENGE_EINH_ID = C.ALTNV_MENGE_EINH_ID AND A.DAT BETWEEN C.DAT_VON AND C.DAT_BIS
  WHERE A.DAT >= (SELECT MIN(DAT)
     FROM KFL_PRODUCTION_DBP_DATA.TAG_2
     WHERE AKT_KJ = - 2)
   AND A.MANDANT_ID = 1
  GROUP BY A.MANDANT_ID,
   A.ART_ID,
   A.KOMPONENTE_ART_ID,
   A.WUP_ID,
   A.DAT,
   A.STUECKLISTE_ID) AS b
WHERE ARTBEW_STUECKLISTE_ZU.MANDANT_ID = b.MANDANT_ID AND ARTBEW_STUECKLISTE_ZU.ART_ID = b.ART_ID AND
     ARTBEW_STUECKLISTE_ZU.KOMPONENTE_ART_ID = b.KOMPONENTE_ART_ID AND ARTBEW_STUECKLISTE_ZU.WUP_ID = b.WUP_ID AND
   ARTBEW_STUECKLISTE_ZU.DAT = b.DAT AND ARTBEW_STUECKLISTE_ZU.STUECKLISTE_ID = b.STUECKLISTE_ID;