            , 2), 2), 0)) IS NULL, ABS(COALESCE(ROUND(ROUND(CAST(MENGE_LAGERBEW_BME * CAST(VK_NETTO AS FLOAT64) AS
             NUMERIC), 2), 2), 0)))) = 1) AS t0
