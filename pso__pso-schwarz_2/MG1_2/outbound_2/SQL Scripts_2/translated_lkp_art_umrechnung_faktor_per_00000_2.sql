SELECT MANDANT_ID,
 ART_ID,
 UPPER(TRIM(ALTNV_MENGE_EINH_ID)) AS ALTNV_MENGE_EINH_ID_UPPER,
 ALTNV_MENGE_EINH_ID,
 DAT_VON,
 DAT_BIS,
 UMRECH_FAKTOR
FROM KFL_PRODUCTION_DBP_DATA.ART_UMRECHNUNG_FAKTOR_PER_2
QUALIFY (ROW_NUMBER() OVER (PARTITION BY MANDANT_ID, ART_ID, UPPER(TRIM(ALTNV_MENGE_EINH_ID)) ORDER BY DAT_BIS IS NULL
      DESC, DAT_BIS DESC)) = 1
ORDER BY 1 NULLS LAST,
 2 NULLS LAST,
 3 NULLS LAST,
 4 NULLS LAST;