CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.BB_CHECK_WUPCAL_UPDATE_2 (
MANDANT_ID BIGNUMERIC NOT NULL,
DAT DATE NOT NULL,
WUP_ID INTEGER NOT NULL,
OFFEN SMALLINT,
BONANZAHL_SUG BIGNUMERIC(38,0),
NB_ID SMALLINT NOT NULL,
UMSATZ_BRUTTO_ODS_VERKAUF NUMERIC(18,4),
UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS NUMERIC(18,4),
DIFF_WERT NUMERIC(18,4),
DIFF_PROZ NUMERIC(18,4),
PRUEF_STATUS_ID_UMSATZ BIGNUMERIC(38,0),
PRUEF_GRUND_ID_UMSATZ STRING(3)
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.BB_CHECK_WUPCAL_UPDATE_2
(SELECT MANDANT_ID,
  DAT,
  CAST(WUP_ID AS INTEGER) AS WUP_ID,
  CAST(OFFEN AS SMALLINT) AS OFFEN,
  BONANZAHL_SUG,
  CAST(NB_ID AS SMALLINT) AS NB_ID,
  UMSATZ_BRUTTO_ODS_VERKAUF,
  UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS,
   UMSATZ_BRUTTO_ODS_VERKAUF - UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS AS DIFF_WERT,
     (UMSATZ_BRUTTO_ODS_VERKAUF - UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS) / IF(UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS = 0, NULL,
     UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS) * 100 AS DIFF_PROZ,
   CASE
   WHEN CAST(((UMSATZ_BRUTTO_ODS_VERKAUF - UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS) / IF(UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS = 0, NULL, UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS)) * 100 AS FLOAT64)
    NOT BETWEEN - CAST(${limit} AS FLOAT64) AND (CAST(${limit} AS FLOAT64))
   THEN - 1
   ELSE 1
   END AS PRUEF_STATUS_ID_UMSATZ,
  PRUEF_GRUND_ID_UMSATZ
 FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2
 WHERE DAT = DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY)
  AND OFFEN = 1
  AND NB_ID = 0
  AND UMSATZ_BRUTTO_ODS_KASSENABSCHLUSS <> 0);


