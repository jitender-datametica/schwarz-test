);


INSERT INTO KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_NEG_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, UMSATZ_NETTO)
(SELECT MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT,
  UMSATZ_NETTO
