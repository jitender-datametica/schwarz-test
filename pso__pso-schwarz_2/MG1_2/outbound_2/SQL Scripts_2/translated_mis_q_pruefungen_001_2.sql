UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_2 SET
 PRUEF_GRUND_ID_UMSATZ = dt1.PRUEF_GRUND_ID_UMSATZ_,
 PRUEF_STATUS_ID_UMSATZ = CASE
  WHEN WUPCAL.PRUEF_STATUS_ID_UMSATZ IS NULL
  THEN dt1.PRUEF_STATUS_ID_UMSATZ_
  ELSE dt1.PRUEF_STATUS_ID_UMSATZ_RELOAD_
  END FROM (SELECT t1.MANDANT_ID AS MANDANT_ID_,
   t1.WUP_ID AS WUP_ID_,
   t1.NB_ID AS NB_ID_,
   t1.DAT AS DAT_,
      CASE
      WHEN T2.WUP_ID IS NULL
      THEN ' '
      ELSE 'D'
      END || CASE
      WHEN T3.WUP_ID IS NULL
      THEN ' '
      ELSE 'G'
      END || CASE
     WHEN T4.WUP_ID IS NULL
     THEN ' '
     ELSE 'N'
     END AS PRUEF_GRUND_ID_UMSATZ_,
    CASE
    WHEN CASE
        WHEN T2.WUP_ID IS NULL
        THEN ' '
        ELSE 'D'
        END || CASE
        WHEN T3.WUP_ID IS NULL
        THEN ' '
        ELSE 'G'
        END || CASE
       WHEN T4.WUP_ID IS NULL
       THEN ' '
       ELSE 'N'
       END = '   '
    THEN 1
    ELSE 0
    END AS PRUEF_STATUS_ID_UMSATZ_,
    CASE
    WHEN CASE
        WHEN T2.WUP_ID IS NULL
        THEN ' '
        ELSE 'D'
        END || CASE
        WHEN T3.WUP_ID IS NULL
        THEN ' '
        ELSE 'G'
        END || CASE
       WHEN T4.WUP_ID IS NULL
       THEN ' '
       ELSE 'N'
       END = '   '
    THEN 2
    ELSE - 1
    END AS PRUEF_STATUS_ID_UMSATZ_RELOAD_,
   MAX(t1.DAT_LIEF) AS DAT_LIEF_
  FROM (SELECT *
    FROM KFL_PRODUCTION_DBP_ETL_PROCESS.ARTBEW_WG_SUM_AGG_WT_2
    WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 365 DAY) AND (CURRENT_DATE)) AS t1_2
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_ABW_AVG_2 AS T2 ON t1.DAT = T2.DAT AND t1.MANDANT_ID = T2.MANDANT_ID AND
      t1.WUP_ID = T2.WUP_ID AND t1.NB_ID = T2.NB_ID
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_GLEICH_2 AS T3 ON t1.DAT = T3.DAT AND t1.MANDANT_ID = T3.MANDANT_ID AND
      t1.WUP_ID = T3.WUP_ID AND t1.NB_ID = T3.NB_ID
   LEFT JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_NEG_2 AS T4 ON t1.DAT = T4.DAT AND t1.MANDANT_ID = T4.MANDANT_ID AND t1.WUP_ID
       = T4.WUP_ID AND t1.NB_ID = T4.NB_ID
  WHERE t1.CALC_FG = 0
  GROUP BY MANDANT_ID_,
   WUP_ID_,
   NB_ID_,
   DAT_,
   PRUEF_GRUND_ID_UMSATZ_,
   PRUEF_STATUS_ID_UMSATZ_,
   PRUEF_STATUS_ID_UMSATZ_RELOAD_) AS dt1
WHERE WUPCAL.MANDANT_ID = dt1.MANDANT_ID_ AND WUPCAL.WUP_ID = dt1.WUP_ID_ AND WUPCAL.NB_ID = dt1.NB_ID_ AND WUPCAL.DAT =
  dt1.DAT_;


