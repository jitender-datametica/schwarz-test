DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_JOIN_TAG_2;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_JOIN_TAG_2 (
MANDANT_ID BIGNUMERIC NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID SMALLINT NOT NULL,
DAT DATE NOT NULL,
DAT_VGL DATE NOT NULL,
UMSATZGLEICH_FG BIGNUMERIC NOT NULL,
UMSATZAVG_FG BIGNUMERIC NOT NULL,
UMSATZ_FG BIGNUMERIC NOT NULL
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_JOIN_TAG_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, DAT_VGL, UMSATZGLEICH_FG,
 UMSATZAVG_FG, UMSATZ_FG)
(SELECT MANDANT_ID,
  CAST(WUP_ID AS INTEGER) AS WUP_ID,
  CAST(NB_ID AS SMALLINT) AS NB_ID,
  DAT,
  DAT_VGL,
  SUM(UMSATZGLEICH_FG),
  SUM(UMSATZAVG_FG),
  SUM(UMSATZ_FG)
 FROM (SELECT t3.MANDANT_ID,
     t3.WUP_ID,
     t3.NB_ID,
     T1.DAT,
     T2.DAT AS DAT_VGL,
      CASE
      WHEN T1.DAT = T2.DAT
      THEN 1
      ELSE 0
      END AS UMSATZ_FG,
      CASE
      WHEN T1.DAT = T2.DAT
      THEN 0
      ELSE 1
      END AS UMSATZAVG_FG,
     0 AS UMSATZGLEICH_FG
    FROM KFL_PRODUCTION_DBP_DATA.TAG_2 AS T1_2
     INNER JOIN (SELECT *
      FROM KFL_PRODUCTION_DBP_ETL_PROCESS.ARTBEW_WG_SUM_AGG_WT_2
      WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 365 DAY) AND (CURRENT_DATE)) AS t3 ON T1.DAT = t3.DAT
     INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T2 ON T2.DAT BETWEEN DATE_SUB(T1.DAT, INTERVAL 30 DAY) AND T1.DAT AND T1_2
       .WTAG_ID = T2.WTAG_ID
    WHERE t3.CALC_FG = 0
    UNION DISTINCT
    SELECT t4.MANDANT_ID,
     t4.WUP_ID,
     t4.NB_ID,
     t4.DAT,
     T5.DAT AS DAT_VGL,
     0 AS UMSATZ_FG,
     0 AS UMSATZAVG_FG,
     1 AS UMSATZGLEICH_FG
    FROM (SELECT *
      FROM KFL_PRODUCTION_DBP_ETL_PROCESS.ARTBEW_WG_SUM_AGG_WT_2
      WHERE DAT BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 365 DAY) AND (CURRENT_DATE)) AS t4
     INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T5 ON T5.DAT BETWEEN DATE_SUB(t4.DAT, INTERVAL 3 DAY) AND (DATE_SUB(t4.DAT
        ,INTERVAL 1 DAY))
    WHERE t4.CALC_FG = 0
    GROUP BY t4.MANDANT_ID,
     t4.WUP_ID,
     t4.NB_ID,
     t4.DAT,
     DAT_VGL,
     UMSATZ_FG,
     UMSATZAVG_FG) AS dt1
 WHERE EXISTS (SELECT *
   FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS T6
   WHERE DAT = dt1.DAT_VGL
    AND WUP_ID = dt1.WUP_ID
    AND NB_ID = dt1.NB_ID
    AND MANDANT_ID = dt1.MANDANT_ID
    AND DATENLIEFERUNG_ARTBEW_WG_SUM = 1
    AND OFFEN = 1)
  AND EXISTS (SELECT *
   FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS T7
   WHERE DAT = dt1.DAT
    AND WUP_ID = dt1.WUP_ID
    AND NB_ID = dt1.NB_ID
    AND MANDANT_ID = dt1.MANDANT_ID
    AND DATENLIEFERUNG_ARTBEW_WG_SUM = 1
    AND OFFEN = 1)
 GROUP BY MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT,
  DAT_VGL);


DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_2;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_2 (
MANDANT_ID BIGNUMERIC NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID SMALLINT NOT NULL,
DAT DATE NOT NULL,
DAT_VGL DATE NOT NULL,
UMSATZ_NETTO NUMERIC(18,2),
UMSATZGLEICH_FG BIGNUMERIC NOT NULL,
UMSATZAVG_FG BIGNUMERIC NOT NULL,
UMSATZ_FG BIGNUMERIC NOT NULL
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, DAT_VGL, UMSATZ_NETTO, UMSATZGLEICH_FG
 , UMSATZAVG_FG, UMSATZ_FG)
(SELECT T1.MANDANT_ID,
  CAST(T1.WUP_ID AS INTEGER) AS WUP_ID,
  CAST(T1.NB_ID AS SMALLINT) AS NB_ID,
  T2.DAT,
  T2.DAT_VGL,
  SUM(T1.UMSATZ_NETTO_KONZ),
  T2.UMSATZGLEICH_FG,
  T2.UMSATZAVG_FG,
  T2.UMSATZ_FG
 FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_2 AS T1_2
  INNER JOIN KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_JOIN_TAG_2 AS T2 ON T1.MANDANT_ID = T2.MANDANT_ID AND T1.WUP_ID = T2.WUP_ID
       AND T1.NB_ID = T2.NB_ID AND T1.DAT = T2.DAT_VGL
 WHERE T1.WG_ID > - 10
 GROUP BY T1.MANDANT_ID,
  T1.NB_ID,
  T1.WUP_ID,
  T2.DAT,
  T2.DAT_VGL,
  T2.UMSATZGLEICH_FG,
  T2.UMSATZAVG_FG,
  T2.UMSATZ_FG);


DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_ABW_AVG_2;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_ABW_AVG_2 (
MANDANT_ID BIGNUMERIC NOT NULL,
WUP_ID INTEGER NOT NULL,
NB_ID SMALLINT NOT NULL,
DAT DATE NOT NULL,
UMSATZ_NETTO NUMERIC(18,2),
UMSATZ_NETTO_AVG NUMERIC(18,2),
UMSATZABWEICHUNG_PRZ NUMERIC(12,2)
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_ABW_AVG_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, UMSATZ_NETTO, UMSATZ_NETTO_AVG
 , UMSATZABWEICHUNG_PRZ)
(SELECT MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT,
  CAST(SUM(UMSATZ_NETTO * UMSATZ_FG) AS NUMERIC) AS UMSATZ_NETTO,
  CAST(CASE
    WHEN SUM(UMSATZ_NETTO * UMSATZAVG_FG) = 0
    THEN NULL
    ELSE SUM(UMSATZ_NETTO * UMSATZAVG_FG) / SUM(UMSATZAVG_FG)
    END AS NUMERIC) AS UMSATZ_NETTO_AVG,
  CAST(CASE
    WHEN CASE
     WHEN SUM(UMSATZ_NETTO * UMSATZAVG_FG) = 0
     THEN NULL
     ELSE SUM(UMSATZ_NETTO * UMSATZAVG_FG) / SUM(UMSATZAVG_FG)
     END IS NULL
    THEN NULL
    ELSE (SUM(UMSATZ_NETTO * UMSATZ_FG) - CASE
        WHEN SUM(UMSATZ_NETTO * UMSATZAVG_FG) = 0
        THEN NULL
        ELSE SUM(UMSATZ_NETTO * UMSATZAVG_FG) / SUM(UMSATZAVG_FG)
        END) / CASE
      WHEN SUM(UMSATZ_NETTO * UMSATZAVG_FG) = 0
      THEN NULL
      ELSE SUM(UMSATZ_NETTO * UMSATZAVG_FG) / SUM(UMSATZAVG_FG)
      END
    END AS NUMERIC) AS UMSATZABWEICHUNG_PRZ
 FROM KFL_PRODUCTION_DBP_ETL.MIS_Q_UMSATZ_2
 GROUP BY MANDANT_ID,
  WUP_ID,
  NB_ID,
  DAT
 HAVING CASE
   WHEN CASE
    WHEN UMSATZ_NETTO_AVG_SUM = 0
    THEN NULL
    ELSE UMSATZ_NETTO_AVG_SUM / UMSATZAVG_FG_SUM
    END IS NULL
   THEN NULL
   ELSE (UMSATZ_NETTO - CASE
       WHEN UMSATZ_NETTO_AVG_SUM = 0
       THEN NULL
       ELSE UMSATZ_NETTO_AVG_SUM / UMSATZAVG_FG_SUM
       END) / CASE
     WHEN UMSATZ_NETTO_AVG_SUM = 0
     THEN NULL
     ELSE UMSATZ_NETTO_AVG_SUM / UMSATZAVG_FG_SUM
     END
   END NOT BETWEEN - 0.5 AND 0.5);


