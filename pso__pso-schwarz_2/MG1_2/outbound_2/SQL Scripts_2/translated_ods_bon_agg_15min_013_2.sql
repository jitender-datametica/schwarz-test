INSERT INTO KFL_PRODUCTION_DBP_ETL.BON_AGG_KASSIERZEITEN_2
(
  MANDANT_ID,
  WUP_ID,
  KASSENSYSTEM_NAME,
  KASSE_NR,
  KASSE_TYP_ID,
  BON_DAT,
  BON_BEGINN,
  BON_ENDE,
  SCAN_ENDE
)
SELECT
  K.MANDANT_ID,
  K.WUP_ID,
  T.KASSENSYSTEM_NAME,
  K.KASSE_NR,
  K.KASSE_TYP_ID,
  K.BON_DAT,
  K.BON_BEGINN AS BON_BEGINN,
  K.BON_ENDE AS BON_ENDE,
  MAX(
    COALESCE(
      V.START_BON_ZEILE,
      R.START_BON_ZEILE,
      F.START_BON_ZEILE,
      K.BON_BEGINN
    )
  ) AS SCAN_ENDE
FROM KFL_PRODUCTION_DBP_ODS.ODS_BON_KOPF_2 AS K
LEFT JOIN KFL_PRODUCTION_DBP_ODS.ODS_BON_TRANSACTION_2 AS T
  ON T.BON_ID = K.BON_ID
  AND T.WUP_ID = K.WUP_ID
  AND T.MANDANT_ID = K.MANDANT_ID
LEFT JOIN KFL_PRODUCTION_DBP_ODS.ODS_BON_VERKAUF_2 AS V
  ON V.BON_ID = K.BON_ID
  AND V.WUP_ID = K.WUP_ID
  AND V.MANDANT_ID = K.MANDANT_ID
LEFT JOIN KFL_PRODUCTION_DBP_ODS.ODS_BON_RETOURE_2 AS R
  ON R.BON_ID = K.BON_ID
  AND R.WUP_ID = K.WUP_ID
  AND R.MANDANT_ID = K.MANDANT_ID
LEFT JOIN KFL_PRODUCTION_DBP_ODS.ODS_BON_FINANCIAL_2 AS F
  ON F.BON_ID = K.BON_ID
  AND F.WUP_ID = K.WUP_ID
  AND F.MANDANT_ID = K.MANDANT_ID
INNER JOIN KFL_PRODUCTION_DBP_ETL.BON_AGG_KASSENBERICHTE_2 AS B
  ON B.MANDANT_ID = K.MANDANT_ID
  AND B.WUP_ID = K.WUP_ID
  AND B.KASSENSYSTEM_NAME = T.KASSENSYSTEM_NAME
  AND B.KASSE_NR = K.KASSE_NR
  AND B.BON_DAT = K.BON_DAT
WHERE K.REACTIVATED_FG = 0
  AND K.BON_DAT BETWEEN DATE_SUB(CURRENT_DATE(), INTERVAL 15 DAY) AND DATE_SUB(CURRENT_DATE(), INTERVAL 1 DAY)
  AND V.BON_DAT BETWEEN DATE_SUB(CURRENT_DATE(), INTERVAL 15 DAY) AND DATE_SUB(CURRENT_DATE(), INTERVAL 1 DAY)
  AND T.BON_DAT BETWEEN DATE_SUB(CURRENT_DATE(), INTERVAL 15 DAY) AND DATE_SUB(CURRENT_DATE(), INTERVAL 1 DAY)
GROUP BY
  K.MANDANT_ID,
  K.WUP_ID,
  T.KASSENSYSTEM_NAME,
  K.KASSE_NR,
  K.KASSE_TYP_ID,
  K.BON_DAT,
  BON_BEGINN,
  BON_ENDE;



