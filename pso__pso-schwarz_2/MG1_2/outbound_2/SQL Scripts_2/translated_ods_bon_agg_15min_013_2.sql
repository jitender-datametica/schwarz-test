CREATE OR REPLACE TABLE DEFAULTSCHEMA._zeit_$_2{TRANSIENT_TABLE_SUFFIX} AS
SELECT ZEIT_STUNDE,
 ZEIT_MINUTE,
     CASE
     WHEN ZEIT_STUNDE < 10
     THEN '0' || TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
     ELSE TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
     END || ':' || CASE
    WHEN ZEIT_MINUTE < 10
    THEN '0' || TRIM(SUBSTR(CAST(ZEIT_MINUTE AS STRING), 1, 39))
    ELSE TRIM(SUBSTR(CAST(ZEIT_MINUTE AS STRING), 1, 39))
    END || ':00' AS START_TIME,
    CASE
    WHEN ZEIT_STUNDE < 10
    THEN '0' || TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
    ELSE TRIM(SUBSTR(CAST(ZEIT_STUNDE AS STRING), 1, 39))
    END || ':' || CASE
   WHEN ZEIT_MINUTE = 0
   THEN '14:59'
   WHEN ZEIT_MINUTE = 15
   THEN '29:59'
   WHEN ZEIT_MINUTE = 30
   THEN '44:59'
   WHEN ZEIT_MINUTE = 45
   THEN '59:59'
   ELSE NULL
   END AS END_TIME
FROM KFL_PRODUCTION_DBP_DATA.ZEIT_2;
