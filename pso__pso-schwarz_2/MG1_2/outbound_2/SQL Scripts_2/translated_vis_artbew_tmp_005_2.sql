 SUM(A.UMSATZ_NETTO + A.UMSATZ_MWST_BETRAG) AS UMSATZ_BRUTTO,
 SUM(CASE
   WHEN d.ARTHIERTYP_ID IS NOT NULL
   THEN 0
   ELSE A.MENGE
   END) AS MENGE
FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_2 AS A
 INNER JOIN KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_2 AS C ON A.MANDANT_ID = C.MANDANT_ID AND A.ART_ID = C.ART_ID AND C.ARTHIERTYP_ID
     = 2 AND C.DAT_BIS = DATE '9999-12-31'
 LEFT JOIN (SELECT MANDANT_ID,
   ART_ID,
   ARTHIERTYP_ID
  FROM KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_2
  WHERE ARTHIERTYP_ID = 2
   AND DAT_BIS = DATE '9999-12-31'
   AND WG_ID = 823
   AND WUG_ID IN (2, 3, 4)
  GROUP BY MANDANT_ID,
   ART_ID,
   ARTHIERTYP_ID) AS d ON A.MANDANT_ID = d.MANDANT_ID AND A.ART_ID = d.ART_ID
WHERE A.DAT BETWEEN (SELECT MIN(JOIN_DAT)
   FROM KFL_PRODUCTION_DBP_ETL.DAT_VJ_VERGLEICH_2) AND (SELECT MAX(JOIN_DAT)
   FROM KFL_PRODUCTION_DBP_ETL.DAT_VJ_VERGLEICH_2)
 AND A.BEWART_ID <> 1010
 AND (A.MANDANT_ID <> 6 OR A.ART_ID NOT IN (98001300, 98001310, 98001320))
 AND (A.MANDANT_ID <> 1 OR A.ART_ID NOT IN (590006700, 590006900))
 AND (A.MANDANT_ID <> 2 OR A.ART_ID NOT IN (818410, 202685400, 1485930, 207699370))
 AND (A.MANDANT_ID, A.ART_ID) NOT IN (SELECT (MANDANT_ID, ART_ID)
   FROM KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_2
   WHERE MANDANT_ID = 1
    AND ARTHIERTYP_ID = 2
    AND DAT_BIS = DATE '9999-12-31'
    AND WG_ID = 969)
 AND (A.MANDANT_ID, A.ART_ID) NOT IN (SELECT (MANDANT_ID, ART_ID)
   FROM KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_2
   WHERE MANDANT_ID = 7
    AND ARTHIERTYP_ID = 2
    AND DAT_BIS = DATE '9999-12-31'
    AND WG_ID = 969
    AND WUG_ID = 6)
 AND (A.MANDANT_ID, A.ART_ID) NOT IN (SELECT (MANDANT_ID, ART_ID)
   FROM KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_2
   WHERE MANDANT_ID = 7
    AND ARTHIERTYP_ID = 2
    AND DAT_BIS = DATE '9999-12-31'
    AND WG_ID = 980)
 AND (A.MANDANT_ID, C.WG_ID) NOT IN (SELECT (MANDANT_ID, WG_ID)
   FROM KFL_PRODUCTION_DBP_DATA.WG_FILTER_ZU_2
   WHERE WG_FILTER_ID = 49)
 AND (A.MANDANT_ID, A.ART_ID) NOT IN (SELECT (MANDANT_ID, ART_ID)
   FROM KFL_PRODUCTION_DBP_DATA.ART_WG_ZU_PER_2
   WHERE MANDANT_ID IN (2, 5, 6)
    AND ARTHIERTYP_ID = 2
    AND DAT_BIS = DATE '9999-12-31'
    AND WG_ID = 969
    AND WUG_ID BETWEEN 1 AND 4)
GROUP BY A.MANDANT_ID,
