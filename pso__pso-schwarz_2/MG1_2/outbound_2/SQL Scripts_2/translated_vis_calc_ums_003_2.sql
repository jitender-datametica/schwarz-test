DELETE FROM KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2
WHERE DAT_VON = LAST_DAY(DAT_VON, MONTH);

INSERT INTO KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 (MANDANT_ID, WUP_ID, NB_ID, WTAG_ID, UMSATZ_PRZ, DAT_VON, DAT_BIS)
(SELECT dt1.MANDANT_ID,
  dt1.WUP_ID,
  dt1.NB_ID,
  dt1.WTAG_ID,
  CAST(CASE
    WHEN dt2.AVG_UMSATZ_BRUTTO = 0
    THEN 0
    ELSE dt1.AVG_UMSATZ_BRUTTO * 100.000 / dt2.AVG_UMSATZ_BRUTTO
    END AS NUMERIC),
  LAST_DAY(CURRENT_DATE, MONTH),
  PARSE_DATE('%Y%m%d', '99991231')/* = 31.12.9999 */
 FROM (SELECT AWS.WUP_ID,
    AWS.NB_ID,
    AWS.MANDANT_ID,
    T.WTAG_ID,
     SUM(AWS.UMSATZ_BRUTTO) / COUNT(AWS.DAT) AS AVG_UMSATZ_BRUTTO
   FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_2 AS AWS
    INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T ON AWS.DAT = T.DAT AND T.DAT > DATE_SUB(CURRENT_DATE, INTERVAL 365 DAY)
      AND AWS.BEWART_ID NOT IN (1005, 1010) AND AWS.NB_ID NOT IN (2, 7)
   GROUP BY AWS.MANDANT_ID,
    AWS.NB_ID,
    AWS.WUP_ID,
    T.WTAG_ID) AS dt1
  INNER JOIN (SELECT WUP_ID,
    NB_ID,
    MANDANT_ID,
    SUM(AVG_UMSATZ_BRUTTO) AS AVG_UMSATZ_BRUTTO
   FROM (SELECT AWS0.WUP_ID,
      AWS0.NB_ID,
      AWS0.MANDANT_ID,
       SUM(AWS0.UMSATZ_BRUTTO) / COUNT(AWS0.DAT) AS AVG_UMSATZ_BRUTTO
     FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_2 AS AWS0
      INNER JOIN KFL_PRODUCTION_DBP_ETL.VIS_MANDANT_2 AS VM ON AWS0.MANDANT_ID = VM.MANDANT_ID
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T0 ON AWS0.DAT = T0.DAT AND T0.DAT > DATE_SUB(CURRENT_DATE, INTERVAL 365
           DAY) AND AWS0.BEWART_ID NOT IN (1005, 1010) AND AWS0.NB_ID NOT IN (2, 7)
     GROUP BY AWS0.MANDANT_ID,
      AWS0.NB_ID,
      AWS0.WUP_ID,
      T0.WTAG_ID) AS dt3
   GROUP BY WUP_ID,
    NB_ID,
    MANDANT_ID) AS dt2 ON dt1.MANDANT_ID = dt2.MANDANT_ID AND dt1.WUP_ID = dt2.WUP_ID AND dt1.NB_ID = dt2.NB_ID);



UPDATE KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 SET DAT_BIS = DT1.DAT_BIS FROM (
  SELECT
      T.MANDANT_ID,
      T.WUP_ID,
      T.NB_ID,
      T.WTAG_ID,
      T.DAT_VON,
      T.DAT_BIS
    FROM
      (
        SELECT
            WP.MANDANT_ID,
            WP.WUP_ID,
            WP.NB_ID,
            WP.WTAG_ID,
            WP.DAT_VON,
            CASE
              WHEN sum(CAST(FORMAT_DATE( '%Y%m%d',WP.DAT_VON) as BIGNUMERIC)) OVER (PARTITION BY WP.MANDANT_ID, WP.WUP_ID, WP.NB_ID, WP.WTAG_ID ORDER BY WP.MANDANT_ID NULLS LAST, WP.WUP_ID NULLS LAST, WP.NB_ID NULLS LAST, WP.WTAG_ID NULLS LAST, WP.DAT_VON DESC NULLS FIRST ROWS 1 PRECEDING) - CAST(FORMAT_DATE('%Y%m%d', WP.DAT_VON) as BIGNUMERIC) <> NUMERIC '0' THEN date_sub(parse_date('%Y%m%d', CAST(sum(CAST(FORMAT_DATE('%Y%m%d', WP.DAT_VON) as BIGNUMERIC)) OVER (PARTITION BY WP.MANDANT_ID, WP.WUP_ID, WP.NB_ID, WP.WTAG_ID ORDER BY WP.MANDANT_ID NULLS LAST, WP.WUP_ID NULLS LAST, WP.NB_ID NULLS LAST, WP.WTAG_ID NULLS LAST, WP.DAT_VON DESC NULLS FIRST ROWS 1 PRECEDING) - CAST(format_date('%Y%m%d', WP.DAT_VON) as BIGNUMERIC) as STRING)), interval 1 DAY)
              ELSE parse_date('%Y%m%d', '99991231')
            END AS DAT_BIS
          FROM
            KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 AS WP
      ) AS T
    GROUP BY 1, 2, 3, 4, 5, 6
) AS DT1 WHERE WUP_WOTAG_ZU_PER.MANDANT_ID = DT1.MANDANT_ID
 AND WUP_WOTAG_ZU_PER.WUP_ID = DT1.WUP_ID
 AND WUP_WOTAG_ZU_PER.NB_ID = DT1.NB_ID
 AND WUP_WOTAG_ZU_PER.WTAG_ID = DT1.WTAG_ID
 AND WUP_WOTAG_ZU_PER.DAT_VON = DT1.DAT_VON;
