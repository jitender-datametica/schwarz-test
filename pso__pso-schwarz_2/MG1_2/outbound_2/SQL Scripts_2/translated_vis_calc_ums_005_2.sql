DROP TABLE IF EXISTS KFL_PRODUCTION_DBP_ETL.ARTBEW_WG_SUM_TMP_2;


CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.ARTBEW_WG_SUM_TMP_2 AS
(SELECT *
FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_2
LIMIT 0);


INSERT INTO KFL_PRODUCTION_DBP_ETL.ARTBEW_WG_SUM_TMP_2 (MANDANT_ID, NB_ID, ARTHIERTYP_ID, WG_ID, DAT, WUP_ID, BEWART_ID,
 KJMO, UMSATZ_BRUTTO, UMSATZ_NETTO, UMSATZ_WRG, UMSATZ_BRUTTO_KONZ, UMSATZ_NETTO_KONZ, QUELLE, MENGE)
(SELECT dt1.MANDANT_ID,
  dt1.NB_ID,
  AWS.ARTHIERTYP_ID,
  AWS.WG_ID,
  dt1.DAT_MISSING,
  dt1.WUP_ID,
  AWS.BEWART_ID,
  CAST(LEFT(FORMAT_DATE('%Y%m%d', dt1.DAT_MISSING), 6) AS INTEGER) AS DT1_DAT_MISSING,
  CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0
     THEN 0
     ELSE AWS.UMSATZ_BRUTTO / WWZP0.UMSATZ_PRZ
     END * dt1.UMSATZ_PRZ AS NUMERIC) AS UMSATZ_BRUTTO,
  CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0.00
     THEN 0
     ELSE AWS.UMSATZ_NETTO / WWZP0.UMSATZ_PRZ
     END * dt1.UMSATZ_PRZ AS NUMERIC) AS UMSATZ_NETTO,
  AWS.UMSATZ_WRG,
  CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0.00
     THEN 0
     ELSE AWS.UMSATZ_BRUTTO_KONZ / WWZP0.UMSATZ_PRZ
     END * dt1.UMSATZ_PRZ AS NUMERIC) AS UMSATZ_BRUTTO_KONZ,
  CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0.00
     THEN 0
     ELSE AWS.UMSATZ_NETTO_KONZ / WWZP0.UMSATZ_PRZ
     END * dt1.UMSATZ_PRZ AS NUMERIC) AS UMSATZ_NETTO_KONZ,
  CAST('2' AS INTEGER),
  CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0.00
     THEN 0
     ELSE AWS.MENGE / WWZP0.UMSATZ_PRZ
     END * dt1.UMSATZ_PRZ AS NUMERIC) AS MENGE
 FROM (SELECT W1.MANDANT_ID,
    W1.WUP_ID,
    W1.NB_ID,
    W1.DAT AS DAT_MISSING,
    WWZP.UMSATZ_PRZ,
    MAX(W2.DAT) AS DAT_SOURCE
   FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS W1
    INNER JOIN KFL_PRODUCTION_DBP_ETL.VIS_MANDANT_2 AS VM ON W1.MANDANT_ID = VM.MANDANT_ID
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS W2 ON W1.MANDANT_ID = W2.MANDANT_ID AND W1.WUP_ID = W2.WUP_ID AND W1.NB_ID
       = W2.NB_ID
    INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T1_2 ON W1.DAT = T1.DAT AND T1.DAT < CURRENT_DATE AND T1.DAT >
      DATE '2003-11-23'
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 AS WWZP ON W1.MANDANT_ID = WWZP.MANDANT_ID AND W1.WUP_ID = WWZP
        .WUP_ID AND W1.NB_ID = WWZP.NB_ID AND T1.WTAG_ID = WWZP.WTAG_ID
   WHERE W2.DATENLIEFERUNG_ARTBEW_WG_SUM = 1
    AND W2.DAT < W1.DAT
    AND W1.DATENLIEFERUNG_ARTBEW_WG_SUM = 0
    AND W1.OFFEN = 1
    AND W1.NB_ID IN (0)
    AND WWZP.DAT_BIS = PARSE_DATE('%Y%m%d', '99991231')
   GROUP BY W1.MANDANT_ID,
    W1.WUP_ID,
    W1.NB_ID,
    DAT_MISSING,
    WWZP.UMSATZ_PRZ) AS dt1
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T2 ON dt1.DAT_SOURCE = T2.DAT AND T2.DAT < CURRENT_DATE
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 AS WWZP0 ON dt1.MANDANT_ID = WWZP0.MANDANT_ID AND dt1.WUP_ID =
       WWZP0.WUP_ID AND dt1.NB_ID = WWZP0.NB_ID AND T2.WTAG_ID = WWZP0.WTAG_ID AND WWZP0.DAT_BIS = PARSE_DATE('%Y%m%d',
     '99991231')
  INNER JOIN KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_2 AS AWS ON dt1.MANDANT_ID = AWS.MANDANT_ID AND dt1.WUP_ID = AWS.WUP_ID
         AND dt1.NB_ID = AWS.NB_ID AND dt1.DAT_SOURCE = AWS.DAT AND AWS.BEWART_ID NOT IN (1005, 1010) AND AWS.NB_ID
    NOT IN (2, 7));


DELETE FROM KFL_PRODUCTION_DBP_ETL.ARTBEW_WG_SUM_TMP_2
WHERE (MANDANT_ID, WUP_ID, NB_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
  FROM KFL_PRODUCTION_DBP_DATA.ARTBEW_WG_SUM_2
  WHERE BEWART_ID NOT IN (1005, 1010)
   AND NB_ID NOT IN (2, 7));


