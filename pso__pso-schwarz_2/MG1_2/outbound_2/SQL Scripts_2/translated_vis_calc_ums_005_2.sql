CREATE TABLE IF NOT EXISTS KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP_2 AS
(SELECT *
FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2
LIMIT 0);


INSERT INTO KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, OFFEN, WERBEWOCHE,
 DATENLIEFERUNG_ARTBEW_WG_SUM, DATENLIEFERUNG_BONANZAHL, DATENLIEFERUNG_MISVIER, DATENLIEFERUNG_ARTBEW,
 DATENLIEFERUNG_QBM_STATUS, BONANZAHL, BONANZAHL_MISVIER)
(SELECT dt1.MANDANT_ID AS `_MANDANT_ID`,
  dt1.WUP_ID AS `_WUP_ID`,
  dt1.NB_ID AS `_NB_ID`,
  dt1.DAT_MISSING AS `_DAT`,
  1 AS `_OFFEN`,
  0 AS `_WERBEWOCHE`,
  0 AS `_DATENLIEFERUNG_ARTBEW_WG_SUM`,
  0 AS `_DATENLIEFERUNG_BONANZAHL`,
  0 AS `_DATENLIEFERUNG_MISVIER`,
  0 AS `_DATENLIEFERUNG_ARTBEW`,
  0 AS `_DATENLIEFERUNG_QBM_STATUS`,
  CAST(CAST(CASE
     WHEN WWZP0.UMSATZ_PRZ = 0
     THEN 0
     ELSE dt1.SOURCE_BONANZAHL / WWZP0.UMSATZ_PRZ * dt1.UMSATZ_PRZ
     END AS BIGNUMERIC) AS INTEGER) AS `_BONANZAHL`,
  0 AS `_BONANZAHL_MISVIER`
 FROM (SELECT W1.MANDANT_ID,
    W1.WUP_ID,
    W1.NB_ID,
    W1.DAT AS DAT_MISSING,
    W1.BONANZAHL AS MISSING_BONANZAHL,
    W2.BONANZAHL AS SOURCE_BONANZAHL,
    WWZP.UMSATZ_PRZ,
    W2.DAT AS DAT_SOURCE
   FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS W1
    INNER JOIN KFL_PRODUCTION_DBP_ETL.VIS_MANDANT_2 AS VM ON W1.MANDANT_ID = VM.MANDANT_ID
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUPCAL_2 AS W2 ON W1.MANDANT_ID = W2.MANDANT_ID AND W1.WUP_ID = W2.WUP_ID AND W1.NB_ID = W2.NB_ID
    INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T1_2 ON W1.DAT = T1.DAT AND T1.DAT < CURRENT_DATE AND T1.DAT > DATE '2003-11-23'
    INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 AS WWZP ON W1.MANDANT_ID = WWZP.MANDANT_ID AND W1.WUP_ID = WWZP.WUP_ID AND W1.NB_ID = WWZP.NB_ID AND T1.WTAG_ID = WWZP.WTAG_ID
   WHERE W2.BONANZAHL <> 0
    AND W2.DAT < W1.DAT
    AND W1.DATENLIEFERUNG_BONANZAHL IN (0, 2)
    AND W1.OFFEN = 1
    AND W1.NB_ID IN (0)
    AND WWZP.DAT_BIS = PARSE_DATE('%Y%m%d', '99991231')
   QUALIFY (ROW_NUMBER() OVER (PARTITION BY W1.MANDANT_ID, W1.WUP_ID, W1.NB_ID, DAT_MISSING ORDER BY W2.DAT IS NULL DESC, W2.DAT DESC)) = 1) AS dt1
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T2 ON dt1.DAT_SOURCE = T2.DAT AND T2.DAT < CURRENT_DATE
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_WOTAG_ZU_PER_2 AS WWZP0 ON dt1.MANDANT_ID = WWZP0.MANDANT_ID AND dt1.WUP_ID = WWZP0.WUP_ID AND dt1.NB_ID = WWZP0.NB_ID AND T2.WTAG_ID = WWZP0.WTAG_ID AND WWZP0.DAT_BIS = PARSE_DATE('%Y%m%d', '99991231'));


DELETE FROM KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP_2
WHERE (MANDANT_ID, WUP_ID, NB_ID, DAT) IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
  FROM KFL_PRODUCTION_DBP_DATA.WUPCAL_2
  WHERE DATENLIEFERUNG_BONANZAHL = 1
   AND BONANZAHL <> 0);


UPDATE KFL_PRODUCTION_DBP_DATA.WUPCAL_2 SET
 BONANZAHL = ums_dt.`_BONANZAHL`,
 DATENLIEFERUNG_BONANZAHL = 2,
 TD_UPDATE = CURRENT_TIMESTAMP() FROM (SELECT MANDANT_ID AS `_MANDANT_ID`,
   WUP_ID AS `_WUP_ID`,
   NB_ID AS `_NB_ID`,
   DAT AS `_DAT`,
   BONANZAHL AS `_BONANZAHL`
  FROM KFL_PRODUCTION_DBP_ETL.WUPCAL_BONANZAHL_TMP_2 AS K) AS ums_dt
WHERE WUPCAL.MANDANT_ID = ums_dt.`_MANDANT_ID` AND WUPCAL.WUP_ID = ums_dt.`_WUP_ID` AND WUPCAL.NB_ID = ums_dt.`_NB_ID`
  AND WUPCAL.DAT = ums_dt.`_DAT` AND WUPCAL.DATENLIEFERUNG_BONANZAHL IN (0, 2);


