INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_MONAT_UMS_ABT_TMP_2 (MANDANT_ID, WUP_ID, NB_ID, WRG_ID, KJMO, ABT_ID, ARTHIERTYP_ID
 , GJ, AKT_GJ, AKT_MO, MO_KJ, UMS_NETTO, UMS_NETTO_KVJ, UMS_NETTO_KVVJ, UMS_NETTO_PLAN)
(SELECT MANDANT_ID,
  WUP_ID,
  NB_ID,
  WRG_ID,
  KJMO,
  ABT_ID,
  ARTHIERTYP_ID,
  GJ,
  AKT_GJ,
  AKT_MO,
  MO_KJ,
  UMS_NETTO,
  UMS_NETTO_KVJ,
  UMS_NETTO_KVVJ,
  0 AS UMS_NETTO_PLAN
 FROM (SELECT A.MANDANT_ID,
    A.NB_ID,
    A.WUP_ID,
    A.WRG_ID,
    A.ABT_ID,
    A.ARTHIERTYP_ID,
    A.GJ,
    A.AKT_GJ,
    A.KJMO,
    COALESCE(M.GJMO, A.KJMO) AS GJMO,
    A.AKT_MO,
    A.MO_KJ,
    SUM(A.UMS_NETTO) AS UMS_NETTO,
    SUM(A.UMS_NETTO_KVJ) AS UMS_NETTO_KVJ,
    SUM(A.UMS_NETTO_KVVJ) AS UMS_NETTO_KVVJ
   FROM KFL_PRODUCTION_DBP_ETL.VIS_ARTBEW_TMP_2 AS A
    LEFT JOIN KFL_PRODUCTION_DBP_DATA.MONAT_2 AS M ON A.KJMO = M.KJMO
   GROUP BY A.MANDANT_ID,
    A.NB_ID,
    A.WUP_ID,
    A.WRG_ID,
    A.ABT_ID,
    A.ARTHIERTYP_ID,
    A.GJ,
    A.AKT_GJ,
    A.KJMO,
    GJMO,
    A.AKT_MO,
    A.MO_KJ) AS dt1);


