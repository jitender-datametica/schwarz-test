INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_MONAT_UMS_ABT_TMP_2 (MANDANT_ID, WUP_ID, NB_ID, WRG_ID, KJMO, ABT_ID, ARTHIERTYP_ID
 , GJ, AKT_GJ, AKT_MO, MO_KJ, UMS_NETTO, UMS_NETTO_KVJ, UMS_NETTO_KVVJ, UMS_NETTO_PLAN)
(SELECT T1.MANDANT_ID,
  T1.WUP_ID,
  T1.NB_ID,
  T2.NACH_WRG_ID AS WGR_ID,
  T1.KJMO,
  T1.ABT_ID,
  T1.ARTHIERTYP_ID,
  T1.GJ,
  T1.AKT_GJ,
  T1.AKT_MO,
  T1.MO_KJ,
  CAST(T1.UMS_NETTO * T2.UMRECHNUNGSKURS AS NUMERIC),
  CAST(T1.UMS_NETTO_KVJ * T2.UMRECHNUNGSKURS AS NUMERIC),
  CAST(T1.UMS_NETTO_KVVJ * T2.UMRECHNUNGSKURS AS NUMERIC),
  CAST(T1.UMS_NETTO_PLAN * T2.UMRECHNUNGSKURS AS NUMERIC)
 FROM KFL_PRODUCTION_DBP_ETL.VIS_MONAT_UMS_ABT_TMP_2 AS T1_2
  INNER JOIN KFL_PRODUCTION_DBP_DATA.KURS_2 AS T2 ON T1.WRG_ID = T2.VON_WRG_ID AND T2.DAT_BIS = DATE '9999-12-31' AND T2.NACH_WRG_ID
      = 'EUR' AND T2.KURSTYP_ID = 3
 WHERE T1.WRG_ID <> 'EUR');


