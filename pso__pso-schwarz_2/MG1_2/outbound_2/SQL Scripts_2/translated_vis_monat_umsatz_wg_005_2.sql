INSERT INTO KFL_PRODUCTION_DBP_DATA.COI_UMP_HWG_SUM_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, HWG_ID, WRG_ID, UMSATZ_NETTO)
(SELECT VIS.MANDANT_ID,
  VIS.WUP_ID,
  VIS.NB_ID,
  VIS.DAT,
  V05.HWG_ID,
  VIS.WRG_ID,
  SUM(VIS.UMS_NETTO) AS UMSATZ_NETTO
 FROM KFL_PRODUCTION_DBP_MSI_DATA.VIS_TAG_UMSATZ_WG_2 AS VIS
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WG_PER_2 AS V04 ON VIS.MANDANT_ID = V04.MANDANT_ID AND VIS.WG_ID = V04.WG_ID AND VIS
     .ARTHIERTYP_ID = V04.ARTHIERTYP_ID AND V04.DAT_BIS = DATE '9999-12-31'
  INNER JOIN KFL_PRODUCTION_DBP_DATA.OWG_PER_2 AS V05 ON V04.MANDANT_ID = V05.MANDANT_ID AND V04.OWG_ID = V05.OWG_ID AND
     V04.ARTHIERTYP_ID = V05.ARTHIERTYP_ID AND V05.DAT_BIS = DATE '9999-12-31'
 WHERE VIS.MANDANT_ID = 1
 GROUP BY VIS.MANDANT_ID,
  VIS.DAT,
  VIS.NB_ID,
  VIS.WUP_ID,
  VIS.WRG_ID,
  V05.HWG_ID);


INSERT INTO KFL_PRODUCTION_DBP_DATA.COI_UMP_HWG_SUM_2 (MANDANT_ID, WUP_ID, NB_ID, DAT, HWG_ID, WRG_ID, UMSATZ_NETTO)
(SELECT VIS.MANDANT_ID,
  VIS.WUP_ID,
  VIS.NB_ID,
  T.DAT_VJ AS DAT,
  V05.HWG_ID,
  VIS.WRG_ID,
  SUM(VIS.UMS_NETTO_WVJ) AS UMSATZ_NETTO
 FROM KFL_PRODUCTION_DBP_MSI_DATA.VIS_TAG_UMSATZ_WG_2 AS VIS
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS T ON VIS.DAT = T.DAT
  INNER JOIN KFL_PRODUCTION_DBP_DATA.WG_PER_2 AS V04 ON VIS.MANDANT_ID = V04.MANDANT_ID AND VIS.WG_ID = V04.WG_ID AND VIS
     .ARTHIERTYP_ID = V04.ARTHIERTYP_ID AND V04.DAT_BIS = DATE '9999-12-31'
  INNER JOIN KFL_PRODUCTION_DBP_DATA.OWG_PER_2 AS V05 ON V04.MANDANT_ID = V05.MANDANT_ID AND V04.OWG_ID = V05.OWG_ID AND
     V04.ARTHIERTYP_ID = V05.ARTHIERTYP_ID AND V05.DAT_BIS = DATE '9999-12-31'
 WHERE T.DAT_VJ < (SELECT MIN(DAT)
    FROM KFL_PRODUCTION_DBP_MSI_DATA.VIS_TAG_UMSATZ_WG_2)
  AND VIS.MANDANT_ID = 1
  AND (VIS.MANDANT_ID, VIS.WUP_ID, VIS.NB_ID, T.DAT_VJ) NOT IN (SELECT (MANDANT_ID, WUP_ID, NB_ID, DAT)
    FROM KFL_PRODUCTION_DBP_DATA.COI_UMP_HWG_SUM_2
    WHERE MANDANT_ID = 1)
 GROUP BY VIS.MANDANT_ID,
  VIS.WUP_ID,
  VIS.NB_ID,
  DAT,
  V05.HWG_ID,
  VIS.WRG_ID);