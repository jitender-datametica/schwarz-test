UPDATE KFL_PRODUCTION_DBP_ETL.VIS_PERSONAL_WUP_TMP_2 SET
 WUP_ID = x1.WUP_ID_ FROM (SELECT T1.MANDANT_ID AS MANDANT_ID_,
   T1.NB_ID AS NB_ID_,
   T2.WUP_ID AS WUP_ID_,
   T1.WUP_ID AS WUP_ID_ALT_
  FROM KFL_PRODUCTION_DBP_DATA.WUP_2 AS T1_2
   INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS T2 ON T1.WUP_ID = T2.WUP_ID_ALT AND T1.NB_ID = T2.NB_ID AND T1.MANDANT_ID =
      T2.MANDANT_ID AND T2.DAT_VON <= CURRENT_DATE) AS x1
WHERE VIS_PERSONAL_WUP_TMP.MANDANT_ID = x1.MANDANT_ID_ AND VIS_PERSONAL_WUP_TMP.NB_ID = x1.NB_ID_ AND
  VIS_PERSONAL_WUP_TMP.WUP_ID = x1.WUP_ID_ALT_;


