CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2 (
MANDANT_ID INTEGER NOT NULL,
NB_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
GJ INTEGER NOT NULL,
KJMO INTEGER NOT NULL,
KJWO INTEGER NOT NULL,
MO_KJ INTEGER NOT NULL,
AKT_GJ INTEGER NOT NULL,
AKT_MO INTEGER NOT NULL,
AKT_WO INTEGER NOT NULL,
AKT_TAG INTEGER NOT NULL,
WTAG_ID INTEGER NOT NULL,
DAT DATE NOT NULL,
WRG_ID STRING NOT NULL,
PLAN_TAG_FG INTEGER,
UMS_NETTO_PLAN NUMERIC(18,2),
UMS_NETTO_PLAN_EXTERN NUMERIC(18,2)
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2 (MANDANT_ID, NB_ID, WUP_ID, GJ, KJMO, KJWO, MO_KJ, AKT_GJ,
 AKT_MO, AKT_WO, AKT_TAG, WTAG_ID, DAT, WRG_ID, PLAN_TAG_FG, UMS_NETTO_PLAN, UMS_NETTO_PLAN_EXTERN)
(SELECT T1.MANDANT_ID,
  T1.NB_ID,
  T2.WUP_ID,
  T1.GJ,
  T1.KJMO,
  T1.KJWO,
  T1.MO_KJ,
  T1.AKT_GJ,
  T1.AKT_MO,
  T1.AKT_WO,
  T1.AKT_TAG,
  T1.WTAG_ID,
  T1.JOIN_DAT,
  T2.WRG_ID,
  T2.PLAN_TAG_FG,
  T2.UMSATZ_NETTO_PLAN AS UMS_NETTO_PLAN,
  COALESCE(T2.UMSATZ_NETTO_PLAN_EXTERN, 0) AS UMS_NETTO_PLAN_EXTERN
 FROM KFL_PRODUCTION_DBP_DATA.WUP_PLAN_TAG_2 AS T2
  INNER JOIN KFL_PRODUCTION_DBP_ETL.DAT_VJ_VERGLEICH_2 AS T1_2 ON T2.MANDANT_ID = T1.MANDANT_ID AND T2.WUP_ID = T1.WUP_ID
    AND T2.DAT = T1.JOIN_DAT AND T1.AKT_GJ_FG = 1);


INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2 (MANDANT_ID, NB_ID, WUP_ID, GJ, KJMO, KJWO, MO_KJ, AKT_GJ,
 AKT_MO, AKT_WO, AKT_TAG, WTAG_ID, DAT, WRG_ID, PLAN_TAG_FG, UMS_NETTO_PLAN, UMS_NETTO_PLAN_EXTERN)
(SELECT COALESCE(T2.MANDANT_ID, dt2.MANDANT_ID) AS MANDANT_ID,
  COALESCE(T2.NB_ID, dt2.NB_ID) AS NB_ID,
  COALESCE(T2.WUP_ID, dt2.WUP_ID) AS WUP_ID,
  dt2.GJ,
  dt2.KJMO,
  dt2.KJWO,
  dt2.MO_KJ,
  dt2.AKT_GJ,
  dt2.AKT_MO,
  dt2.AKT_WO,
  dt2.AKT_TAG,
  dt2.WTAG_ID,
  dt2.DAT,
  COALESCE(T2.WRG_ID, dt2.WRG_ID) AS WRG_ID,
  COALESCE(T2.PLAN_TAG_FG, dt2.PLAN_TAG_FG) AS PLAN_TAG_FG,
  0 AS UMS_NETTO_PLAN,
  0 AS UMS_NETTO_PLAN_EXTERN
 FROM (SELECT T1.GJ,
    T1.KJMO,
    T1.KJWO,
    T1.MO_KJ,
    T1.DAT,
    T1.AKT_GJ,
    T1.AKT_MO,
    T1.AKT_WO,
    T1.AKT_TAG,
    T1.WTAG_ID,
    t0.MANDANT_ID,
    t0.WUP_ID,
    t0.NB_ID,
    t0.PLAN_TAG_FG,
    t0.WRG_ID
   FROM KFL_PRODUCTION_DBP_DATA.TAG_2 AS T1_2
    INNER JOIN (SELECT MANDANT_ID,
      WUP_ID,
      NB_ID,
      PLAN_TAG_FG,
      WRG_ID,
      MIN(DAT) AS DAT_MIN,
      MAX(DAT) AS DAT_MAX
     FROM KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2
     GROUP BY MANDANT_ID,
      NB_ID,
      WUP_ID,
      WRG_ID,
      PLAN_TAG_FG) AS t0 ON T1.DAT BETWEEN t0.DAT_MIN AND t0.DAT_MAX) AS dt2
  LEFT JOIN KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2 AS T2 ON dt2.DAT > T2.DAT AND dt2.GJ = T2.GJ AND dt2.WUP_ID = T2
        .WUP_ID AND dt2.NB_ID = T2.NB_ID AND dt2.PLAN_TAG_FG = T2.PLAN_TAG_FG AND dt2.MANDANT_ID = T2.MANDANT_ID AND dt2
    .WRG_ID = T2.WRG_ID
 WHERE (dt2.MANDANT_ID, dt2.WUP_ID, dt2.DAT) NOT IN (SELECT (MANDANT_ID, WUP_ID, DAT)
    FROM KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2)
 GROUP BY dt2.GJ,
  dt2.KJMO,
  dt2.KJWO,
  dt2.MO_KJ,
  dt2.DAT,
  dt2.AKT_GJ,
  dt2.AKT_MO,
  dt2.AKT_WO,
  dt2.AKT_TAG,
  dt2.WTAG_ID,
  MANDANT_ID,
  WUP_ID,
  NB_ID,
  PLAN_TAG_FG,
  WRG_ID);


UPDATE KFL_PRODUCTION_DBP_ETL.VIS_PLAN_TAG_WUP_TMP_2 SET
 WUP_ID = x1.WUP_ID_ FROM (SELECT T1.MANDANT_ID AS MANDANT_ID_,
   T1.NB_ID AS NB_ID_,
   T2.WUP_ID AS WUP_ID_,
   T1.WUP_ID AS WUP_ID_ALT_
  FROM KFL_PRODUCTION_DBP_DATA.WUP_2 AS T1_2
   INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS T2 ON T1.WUP_ID = T2.WUP_ID_ALT AND T1.NB_ID = T2.NB_ID AND T1.MANDANT_ID =
      T2.MANDANT_ID AND T2.DAT_VON <= CURRENT_DATE) AS x1
WHERE VIS_PLAN_TAG_WUP_TMP.MANDANT_ID = x1.MANDANT_ID_ AND VIS_PLAN_TAG_WUP_TMP.NB_ID = x1.NB_ID_ AND
  VIS_PLAN_TAG_WUP_TMP.WUP_ID = x1.WUP_ID_ALT_;


CREATE OR REPLACE TABLE KFL_PRODUCTION_DBP_ETL.VIS_PLAN_MONAT_ABT_TMP_2 (
MANDANT_ID INTEGER NOT NULL,
NB_ID INTEGER NOT NULL,
WUP_ID INTEGER NOT NULL,
ABT_ID INTEGER NOT NULL,
ARTHIERTYP_ID INTEGER NOT NULL,
GJ INTEGER NOT NULL,
KJMO INTEGER NOT NULL,
AKT_GJ INTEGER NOT NULL,
AKT_MO INTEGER NOT NULL,
MO_KJ INTEGER NOT NULL,
WRG_ID STRING NOT NULL,
UMS_NETTO_PLAN NUMERIC(18,2) NOT NULL
);


INSERT INTO KFL_PRODUCTION_DBP_ETL.VIS_PLAN_MONAT_ABT_TMP_2 (MANDANT_ID, NB_ID, WUP_ID, ABT_ID, ARTHIERTYP_ID, GJ, KJMO,
 AKT_GJ, AKT_MO, MO_KJ, WRG_ID, UMS_NETTO_PLAN)
(SELECT T1.MANDANT_ID,
  T1.NB_ID,
  T1.WUP_ID,
  T1.ABT_ID,
  CAST('2' AS INTEGER),
  T3.GJ,
  T3.KJMO,
  T3.AKT_GJ,
  T3.AKT_MO,
  T3.MO_KJ,
  T1.UMSATZ_NETTO_PLAN_WRG,
  SUM(T1.UMSATZ_NETTO_PLAN) AS UMS_NETTO_PLAN
 FROM KFL_PRODUCTION_DBP_DATA.WUP_ABT_PER_2 AS T1_2
  INNER JOIN KFL_PRODUCTION_DBP_ETL.VIS_MANDANT_2 AS VM ON T1.MANDANT_ID = VM.MANDANT_ID
  INNER JOIN KFL_PRODUCTION_DBP_DATA.MONAT_2 AS T3 ON T1.GJMO = T3.GJMO AND T3.AKT_GJ = 0
 WHERE EXISTS (SELECT *
   FROM KFL_PRODUCTION_DBP_ETL.DAT_VJ_VERGLEICH_2 AS TD1
   WHERE GJ = T3.GJ
    AND KJMO = T3.KJMO
    AND MANDANT_ID = T1.MANDANT_ID
    AND WUP_ID = T1.WUP_ID
    AND NB_ID = T1.NB_ID)
 GROUP BY T1.MANDANT_ID,
  T1.NB_ID,
  T1.WUP_ID,
  T1.ABT_ID,
  5,
  T3.GJ,
  T3.KJMO,
  T3.AKT_GJ,
  T3.AKT_MO,
  T3.MO_KJ,
  T1.UMSATZ_NETTO_PLAN_WRG);


UPDATE KFL_PRODUCTION_DBP_ETL.VIS_PLAN_MONAT_ABT_TMP_2 SET
 WUP_ID = x1.WUP_ID_ FROM (SELECT T1.MANDANT_ID AS MANDANT_ID_,
   T1.NB_ID AS NB_ID_,
   T2.WUP_ID AS WUP_ID_,
   T1.WUP_ID AS WUP_ID_ALT_
  FROM KFL_PRODUCTION_DBP_DATA.WUP_2 AS T1_2
   INNER JOIN KFL_PRODUCTION_DBP_DATA.WUP_2 AS T2 ON T1.WUP_ID = T2.WUP_ID_ALT AND T1.NB_ID = T2.NB_ID AND T1.MANDANT_ID =
      T2.MANDANT_ID AND T2.DAT_VON <= CURRENT_DATE) AS x1
WHERE VIS_PLAN_MONAT_ABT_TMP.MANDANT_ID = x1.MANDANT_ID_ AND VIS_PLAN_MONAT_ABT_TMP.NB_ID = x1.NB_ID_ AND
  VIS_PLAN_MONAT_ABT_TMP.WUP_ID = x1.WUP_ID_ALT_;