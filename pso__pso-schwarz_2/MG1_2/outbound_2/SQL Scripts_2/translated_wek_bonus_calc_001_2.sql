CREATE OR REPLACE TEMPORARY TABLE _MSEG_SNAP4 AS
SELECT A.MANDANT_ID,
 A.ZEITRAUM_KZ,
 A.ZEIT_2,
 A.DAT_BUCH,
 A.ART_ID,
 A.GP_ID,
 A.MENGE_LAGERBEW_BME,
 A.ZEILE,
 A.ACCUM,
 A.EK_NETTONETTO,
 A.EK_MEP,
 A.EK_MEP_VOR_FWU,
  CASE
  WHEN B.MENGE IS NULL
  THEN A.MENGE_LAGERBEW_BME
  ELSE A.MENGE_LAGERBEW_BME - (A.ACCUM - B.MENGE)
  END AS NEUE_MENGE,
  A.EK_NETTONETTO - A.EK_MEP AS EK_DIFF,
  A.EK_NETTONETTO - A.EK_MEP_VOR_FWU AS EK_DIFF_FWU,
   (A.EK_NETTONETTO - A.EK_MEP) * CASE
   WHEN B.MENGE IS NULL
   THEN A.MENGE_LAGERBEW_BME
   ELSE A.MENGE_LAGERBEW_BME - (A.ACCUM - B.MENGE)
   END AS BONI,
   (A.EK_NETTONETTO - A.EK_MEP_VOR_FWU) * CASE
   WHEN B.MENGE IS NULL
   THEN A.MENGE_LAGERBEW_BME
   ELSE A.MENGE_LAGERBEW_BME - (A.ACCUM - B.MENGE)
   END AS BONI_FWU,
 X.MIN_DAT AS DAT_VON,
 X.MAX_DAT AS DAT_BIS
FROM `_MSEG_SNAP3` AS A
 INNER JOIN `_ZEITRAEUME` AS X ON A.MANDANT_ID = X.MANDANT_ID AND A.ZEITRAUM_KZ = X.ZEITRAUM_KZ AND A.ZEIT_2 = X.ZEIT_2
 LEFT JOIN `_MSEG_ROW_COUNTER` AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.ART_ID = B.ART_ID AND A.ZEITRAUM_KZ = B.ZEITRAUM_KZ
      AND A.ZEIT_2 = B.ZEIT_2 AND A.ZEILE = B.ZEILE;


