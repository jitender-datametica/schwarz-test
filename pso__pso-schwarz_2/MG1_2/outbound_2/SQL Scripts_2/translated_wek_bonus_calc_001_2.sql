FROM `_MSEG_SNAP1` AS X
 INNER JOIN (SELECT MANDANT_ID,
   ZEITRAUM_KZ,
   ZEIT_2,
   ART_ID,
   SUM(MENGE) AS MENGE
  FROM `_ARTBEW_SNAP`
  WHERE GP_ID <> - 1
  GROUP BY MANDANT_ID,
   ZEITRAUM_KZ,
   ZEIT_2,
   ART_ID) AS b ON X.MANDANT_ID = b.MANDANT_ID AND X.ART_ID = b.ART_ID AND X.ZEITRAUM_KZ = b.ZEITRAUM_KZ AND X.ZEIT_2 = b
   .ZEIT_2
WHERE X.ACCUM - b.MENGE >= 0
GROUP BY X.MANDANT_ID,
 X.ZEITRAUM_KZ,
 X.ZEIT_2,
 X.ART_ID;


