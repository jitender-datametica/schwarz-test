CREATE OR REPLACE TEMPORARY TABLE _MSEG_SNAP1 AS
SELECT MANDANT_ID,
 ZEITRAUM_KZ,
 ZEIT_2,
 DAT_BUCH,
 ART_ID,
 GP_ID,
 MENGE_LAGERBEW_BME,
 ZEILE,
 SUM(MENGE_LAGERBEW_BME) OVER (PARTITION BY CAST(MANDANT_ID AS STRING), CAST(ART_ID AS STRING), ZEITRAUM_KZ, CAST(ZEIT_2 AS STRING)
    ORDER BY ZEILE IS NULL, ZEILE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ACCUM
FROM (SELECT A.MANDANT_ID,
   B.ZEITRAUM_KZ,
   B.ZEIT_2,
   A.DAT_BUCH,
   A.ART_ID,
   A.GP_ID,
   A.MENGE_LAGERBEW_BME,
   ROW_NUMBER() OVER (PARTITION BY CAST(A.MANDANT_ID AS STRING), CAST(A.ART_ID AS STRING), B.ZEITRAUM_KZ, CAST(B.ZEIT_2 AS STRING)
      ORDER BY A.DAT_BUCH IS NULL DESC, A.DAT_BUCH DESC, A.GP_ID IS NULL DESC, A.GP_ID DESC, A.MENGE_LAGERBEW_BME
      IS NULL DESC, A.MENGE_LAGERBEW_BME DESC) AS ZEILE
  FROM KFL_PRODUCTION_DBP_DATA.LAGERBEW_DET_2 AS A
   INNER JOIN `_ZEITRAEUME` AS B ON A.MANDANT_ID = B.MANDANT_ID AND A.DAT_BUCH BETWEEN B.MSEG_MIN_DAT AND B.MAX_DAT
  WHERE (A.MANDANT_ID, A.ART_ID, B.ZEITRAUM_KZ, B.ZEIT_2) IN (SELECT (MANDANT_ID, ART_ID, ZEITRAUM_KZ, ZEIT_2)
     FROM `_ARTBEW_SNAP`)
   AND A.GP_ID <> - 1
   AND CASE
     WHEN A.MANDANT_ID = 4 AND A.GP_ID = 6100 OR A.GP_ID >= 10000
     THEN 1
     ELSE 0
     END = 1
   AND A.LAGER_BEWART_ID IN ('101', '102', '901', '902', '161', '162')
   AND A.MENGE_LAGERBEW_BME > 0) AS xxx_2;


CREATE OR REPLACE TEMPORARY TABLE _MSEG_ROW_COUNTER AS
SELECT X.MANDANT_ID,
 X.ZEITRAUM_KZ,
 X.ZEIT_2,
 X.ART_ID,
 MIN(X.GP_ID) AS GP_ID,
 MIN(X.ZEILE) AS ZEILE,
