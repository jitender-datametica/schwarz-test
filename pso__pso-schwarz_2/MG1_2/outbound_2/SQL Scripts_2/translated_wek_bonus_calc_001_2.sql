

CREATE OR REPLACE TEMPORARY TABLE _ZEITRAEUME AS
(
  -- KM
  ((SELECT A.MANDANT_ID,
    'KM' AS ZEITRAUM_KZ,
    B.KJMO AS ZEIT_2,
    MIN(B.DAT) AS MIN_DAT,
    MAX(B.DAT) AS MAX_DAT,
    MIN(B.DAT) AS FAKE_MIN_DAT,
    DATE_SUB(MIN(B.DAT), INTERVAL 730 DAY) AS MSEG_MIN_DAT
   FROM KFL_PRODUCTION_DBP_DATA.MANDANT_2 AS A
    INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS B ON TRUE
   WHERE B.AKT_MO_KOMPLETT = 0
    AND A.MANDANT_ID IN (2, 3, 4, 5, 6, 7, 8)
    AND 1 = (SELECT 1
      FROM (SELECT MIN(DAT) AS DAT
        FROM KFL_PRODUCTION_DBP_DATA.TAG_2
        WHERE AKT_MO = 1) AS a
       INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS B0 ON a.DAT = B0.DAT
      WHERE B0.DAT = CURRENT_DATE)
   GROUP BY A.MANDANT_ID,
    ZEITRAUM_KZ,
    ZEIT_2
   UNION DISTINCT
   SELECT x.MANDANT_ID,
    x.ZEITRAUM_KZ,
    x.ZEIT_2,
    x.MIN_DAT,
    x.MAX_DAT,
    Y.DAT AS FAKE_MIN_DAT,
    x.MSEG_MIN_DAT
   FROM (SELECT A.MANDANT_ID,
      'KM' AS ZEITRAUM_KZ,
      B.KJMO AS ZEIT_2,
      MIN(B.DAT) AS MIN_DAT,
      MAX(B.DAT) AS MAX_DAT,
      DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY) AS ABSTAND,
       CASE
       WHEN DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY) <= 0
       THEN 7
       WHEN DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY) <= 7
       THEN 7 - DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY)
       ELSE 0
       END AS DIFF,
      DATE_SUB(MIN(B.DAT), INTERVAL 730 DAY) AS MSEG_MIN_DAT
     FROM KFL_PRODUCTION_DBP_DATA.MANDANT_2 AS A
      INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS B ON TRUE
     WHERE B.AKT_MO_KOMPLETT = 1
      AND A.MANDANT_ID IN (2, 3, 4, 5, 6, 7, 8)
     GROUP BY A.MANDANT_ID,
      ZEITRAUM_KZ,
      ZEIT_2) AS x
    INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS Y ON DATE_SUB(x.MIN_DAT, INTERVAL x.DIFF DAY) = Y.DAT)
  UNION DISTINCT
  --KW
  SELECT A.MANDANT_ID,
   'KW' AS ZEITRAUM_KZ,
   B.KJWO AS ZEIT_2,
   MIN(B.DAT) AS MIN_DAT,
   MAX(B.DAT) AS MAX_DAT,
   MIN(B.DAT) AS FAKE_MIN_DAT,
   DATE_SUB(MIN(B.DAT), INTERVAL 730 DAY) AS MSEG_MIN_DAT
  FROM KFL_PRODUCTION_DBP_DATA.MANDANT_2 AS A
   INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS B ON TRUE
  WHERE B.AKT_WO_KOMPLETT = 0
   AND A.MANDANT_ID IN (2, 3, 4, 5, 6, 7, 8)
  GROUP BY A.MANDANT_ID,
   ZEITRAUM_KZ,
   ZEIT_2)
 UNION DISTINCT
 --WW
 SELECT x.MANDANT_ID,
  'KW' AS ZEITRAUM_KZ,
  x.KJWO AS ZEIT_2,
  x.MIN_DAT,
  x.MAX_DAT,
  Y.DAT AS FAKE_MIN_DAT,
  x.MSEG_MIN_DAT
 FROM (SELECT A.MANDANT_ID,
    B.KJWO,
    MIN(B.DAT) AS MIN_DAT,
    MAX(B.DAT) AS MAX_DAT,
    DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY) AS ABSTAND,
     CASE
     WHEN DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY) <= 0
     THEN 7
     WHEN DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY) <= 7
     THEN 7 - DATE_DIFF(CURRENT_DATE, MIN(B.DAT), DAY)
     ELSE 0
     END AS DIFF,
    DATE_SUB(MIN(B.DAT), INTERVAL 730 DAY) AS MSEG_MIN_DAT
   FROM KFL_PRODUCTION_DBP_DATA.MANDANT_2 AS A
    INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS B ON TRUE
   WHERE B.AKT_WO_KOMPLETT = 1
    AND A.MANDANT_ID IN (2, 3, 4, 5, 6, 7, 8)
   GROUP BY A.MANDANT_ID,
    B.KJWO) AS x
  INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS Y ON DATE_SUB(x.MIN_DAT, INTERVAL x.DIFF DAY) = Y.DAT)
UNION DISTINCT
SELECT x.MANDANT_ID,
 'WW' AS ZEITRAUM_KZ,
 x.KJWO AS ZEIT_2,
 x.MIN_DAT,
 x.MAX_DAT,
 Y.DAT AS FAKE_MIN_DAT,
 x.MSEG_MIN_DAT
FROM (SELECT A.MANDANT_ID,
   B.KJWO,
    CASE
    WHEN A.MANDANT_ID = 8
    THEN DATE_ADD(MIN(B.DAT), INTERVAL 7 DAY)
    WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
    THEN DATE_ADD(MIN(B.DAT), INTERVAL 2 DAY)
    ELSE DATE_ADD(MIN(B.DAT), INTERVAL 3 DAY)
    END AS MIN_DAT,
    CASE
    WHEN A.MANDANT_ID = 8
    THEN DATE_ADD(MAX(B.DAT), INTERVAL 7 DAY)
    WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
    THEN DATE_ADD(MAX(B.DAT), INTERVAL 2 DAY)
    ELSE DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY)
    END AS MAX_DAT,
   DATE_DIFF(CURRENT_DATE, CASE
     WHEN A.MANDANT_ID = 8
     THEN DATE_ADD(MIN(B.DAT), INTERVAL 7 DAY)
     WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
     THEN DATE_ADD(MIN(B.DAT), INTERVAL 2 DAY)
     ELSE DATE_ADD(MIN(B.DAT), INTERVAL 3 DAY)
     END, DAY) AS ABSTAND,
    CASE
    WHEN DATE_DIFF(CURRENT_DATE, CASE
       WHEN A.MANDANT_ID = 8
       THEN DATE_ADD(MIN(B.DAT), INTERVAL 7 DAY)
       WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
       THEN DATE_ADD(MIN(B.DAT), INTERVAL 2 DAY)
       ELSE DATE_ADD(MIN(B.DAT), INTERVAL 3 DAY)
       END, DAY) <= 0
    THEN 7
    WHEN DATE_DIFF(CURRENT_DATE, CASE
       WHEN A.MANDANT_ID = 8
       THEN DATE_ADD(MIN(B.DAT), INTERVAL 7 DAY)
       WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
       THEN DATE_ADD(MIN(B.DAT), INTERVAL 2 DAY)
       ELSE DATE_ADD(MIN(B.DAT), INTERVAL 3 DAY)
       END, DAY) <= 7
    THEN 7 - DATE_DIFF(CURRENT_DATE, CASE
       WHEN A.MANDANT_ID = 8
       THEN DATE_ADD(MIN(B.DAT), INTERVAL 7 DAY)
       WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
       THEN DATE_ADD(MIN(B.DAT), INTERVAL 2 DAY)
       ELSE DATE_ADD(MIN(B.DAT), INTERVAL 3 DAY)
       END, DAY)
    ELSE 0
    END AS DIFF,
   DATE_SUB(CASE
     WHEN A.MANDANT_ID = 8
     THEN DATE_ADD(MIN(B.DAT), INTERVAL 7 DAY)
     WHEN A.MANDANT_ID = 2 AND DATE_ADD(MAX(B.DAT), INTERVAL 3 DAY) >= DATE '2019-02-27' OR A.MANDANT_ID = 7
     THEN DATE_ADD(MIN(B.DAT), INTERVAL 2 DAY)
     ELSE DATE_ADD(MIN(B.DAT), INTERVAL 3 DAY)
     END, INTERVAL 730 DAY) AS MSEG_MIN_DAT
  FROM KFL_PRODUCTION_DBP_DATA.MANDANT_2 AS A
   INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS B ON TRUE
  WHERE B.AKT_WO_KOMPLETT BETWEEN 0 AND 1
   AND A.MANDANT_ID IN (2, 3, 4, 5, 6, 7)
  GROUP BY A.MANDANT_ID,
   B.KJWO) AS x
 INNER JOIN KFL_PRODUCTION_DBP_DATA.TAG_2 AS Y ON DATE_SUB(x.MIN_DAT, INTERVAL x.DIFF DAY) = Y.DAT;


