(SELECT x.MANDANT_ID,
  x.DAT,
  x.AKT_WO_ AS AKT_KJWO_WW,
  x.AKT_WO_KOMPLETT AS AKT_KJWO_WW_KOMPLETT,
  Y.KJWO AS KJWO_WW
 FROM (SELECT B.MANDANT_ID,
    A.DAT,
     CASE
