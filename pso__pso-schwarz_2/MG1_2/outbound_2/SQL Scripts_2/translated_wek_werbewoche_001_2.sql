     THEN A.AKT_WO
     WHEN B.MANDANT_ID IN (2) AND A.WTAG_ID BETWEEN 1 AND 2 AND A.KJWO >= 201909 OR B.MANDANT_ID IN (2) AND A.WTAG_ID
                BETWEEN 1 AND 3 AND A.KJWO <= 201908 OR B.MANDANT_ID IN (6) AND A.WTAG_ID BETWEEN 1 AND 3 AND A.KJWO <=
              202204 OR B.MANDANT_ID IN (6) AND A.WTAG_ID BETWEEN 1 AND 2 AND A.KJWO >= 202205 OR B.MANDANT_ID IN (4)
            AND A.WTAG_ID BETWEEN 1 AND 2 AND A.KJWO <= 202330 OR B.MANDANT_ID IN (4) AND A.WTAG_ID BETWEEN 1 AND 3 AND
           A.KJWO = 202331 OR B.MANDANT_ID IN (4) AND A.WTAG_ID BETWEEN 1 AND 3 AND A.KJWO >= 202332 OR B.MANDANT_ID IN
          (7) AND A.WTAG_ID BETWEEN 1 AND 2 OR B.MANDANT_ID IN (1, 3, 5) AND A.WTAG_ID BETWEEN 1 AND 3
