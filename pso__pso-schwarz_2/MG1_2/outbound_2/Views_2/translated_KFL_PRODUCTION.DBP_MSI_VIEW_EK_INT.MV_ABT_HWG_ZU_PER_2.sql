CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_ABT_HWG_ZU_PER_2 (ABT_ID, HWG_ID, MANDANT_ID, DAT_VON,
DAT_BIS, ARTHIERTYP_ID) AS SELECT V01.ABT_ID,
 V02.HWG_ID,
 V01.MANDANT_ID,
 V02.DAT_VON,
 V02.DAT_BIS,
 V01.ARTHIERTYP_ID
 --abt_id
FROM KFL_PRODUCTION_DBP_VIEW.V_ABT_2 AS V01
 INNER JOIN KFL_PRODUCTION_DBP_VIEW.V_HWG_PER_2 AS V02 ON V01.MANDANT_ID = V02.MANDANT_ID AND V01.ABT_ID = V02.ABT_ID AND
   CURRENT_DATE BETWEEN V02.DAT_VON AND V02.DAT_BIS;