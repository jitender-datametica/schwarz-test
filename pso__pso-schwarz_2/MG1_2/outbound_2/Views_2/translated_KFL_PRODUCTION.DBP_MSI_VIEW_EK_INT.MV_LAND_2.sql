CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_LAND_2 (LAND_SORT_ID, LAND_ID, LAND_BEZ, WRG_ID_LAND) AS
SELECT CAST(CASE
   WHEN MANDANT_ID = 1
   THEN 2
   WHEN MANDANT_ID = 2
   THEN 4
   WHEN MANDANT_ID = 5
   THEN 5
   WHEN MANDANT_ID = 6
   THEN 6
   WHEN MANDANT_ID = 3
   THEN 7
   WHEN MANDANT_ID = 7
   THEN 8
   WHEN MANDANT_ID = 8
   THEN 9
   WHEN MANDANT_ID = 4
   THEN 10
   ELSE NULL
   END AS BIGNUMERIC) AS LAND_SORT_ID,
 MANDANT_ID AS LAND_ID,
 MANDANT_BEZ AS LAND_BEZ,
 DEFAULT_WRG AS WRG_ID_LAND
FROM KFL_PRODUCTION_DBP_VIEW.V_MANDANT_2
UNION ALL
SELECT 1 AS LAND_SORT_ID,
 - 1 AS LAND_ID,
 'INT' AS LAND_BEZ,
 'EUR' AS WRG_ID_LAND
UNION ALL
SELECT 3 AS LAND_SORT_ID,
 - 2 AS LAND_ID,
 'Ausland' AS LAND_BEZ,
 'EUR' AS WRG_ID_LAND;