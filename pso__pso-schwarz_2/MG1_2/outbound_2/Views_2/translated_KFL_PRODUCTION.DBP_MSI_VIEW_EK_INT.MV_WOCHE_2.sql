CREATE OR REPLACE VIEW KFL_PRODUCTION_DBP_MSI_VIEW_EK_INT.MV_WOCHE_2 (KJWO, KJ, WO_KJ, AKT_WO, AKT_WO_KOMPLETT, WO_DAT_VON
, WO_DAT_BIS, KJWO_VJ, KJ_VJ, WO_VJ, WO_VON_BIS, WO_VON, WO_DAT_MO, KW_IST_VJ) AS SELECT KJWO,
  KJWO / 100 AS KJ,
 MOD(CAST(KJWO AS BIGNUMERIC), 100) AS WO_KJ,
 AKT_WO,
 AKT_WO_KOMPLETT,
 WO_DAT_VON,
 WO_DAT_BIS,
 KJWO_VJ,
  KJWO_VJ / 100 AS KJ_VJ,
 MOD(CAST(KJWO_VJ AS BIGNUMERIC), 100) AS WO_VJ,
      LPAD(CAST(MOD(CAST(KJWO AS BIGNUMERIC), 100) AS STRING), 2, '0') || ' (' || FORMAT_DATE('%d.%m', WO_DAT_VON) ||
    '-' || FORMAT_DATE('%d.%m', WO_DAT_BIS) || ')' AS WO_VON_BIS,
    LPAD(CAST(MOD(CAST(KJWO AS BIGNUMERIC), 100) AS STRING), 2, '0') || ' (' || FORMAT_DATE('%d.%m', WO_DAT_VON) || ')'
 AS WO_VON,
 CAST(SUBSTR(CAST(WO_DAT_VON AS STRING), 1, 8) || '01' AS STRING) AS WO_DAT_MO,
   LPAD(CAST(MOD(CAST(KJWO AS BIGNUMERIC), 100) AS STRING), 2, '0') || ' | ' || LPAD(CAST(MOD(CAST(KJWO_VJ AS BIGNUMERIC)
     , 100) AS STRING), 2, '0') AS KW_IST_VJ
/* SPEC0249727 Umstellung auf VTA (vorher mv_woche_vvt_2) / sschuecke 23.05.2024 */    
FROM KFL_PRODUCTION_DBP_VIEW.V_WOCHE_2
  
