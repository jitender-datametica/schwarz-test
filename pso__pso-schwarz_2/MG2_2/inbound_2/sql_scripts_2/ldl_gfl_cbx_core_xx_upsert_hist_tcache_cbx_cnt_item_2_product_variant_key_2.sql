INSERT INTO ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA} (
	PROD_VARIANT_SID,
	PROD_VARIANT_KEY_TYPE_CD,
	PROD_VARIANT_NAT_KEY_NR,

	SOURCE_SYSTEM,
	EXTRACTION_DT,
	DWH_MAPPING_TMSP,
	TF_ERROR_FG,
	DELETED_FG,
	RECORD_ID,
	FILENAME,
	DWH_NODE_CD,
	DWH_LOAD_ID
    )
	
SELECT
    DISTINCT VKEY.PROD_VARIANT_SID AS PROD_VARIANT_SID,
    'SLS_GTIN' AS PROD_VARIANT_KEY_TYPE_CD,
    UPPER(SRC.ITEM_NO || '|' || EAN.LDL_EAN) AS PROD_VARIANT_NAT_KEY_NR,
	
    'CBX' AS SOURCE_SYSTEM,
    CURRENT_DATE AS EXTRACTION_DT,
    CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
    0 AS TF_ERROR_FG,
    0 AS DELETED_FG,
    0 AS RECORD_ID,
    't_${SRC_INPUT_TABLE}' AS FILENAME,
    'CBX' AS DWH_NODE_CD,
    '${LOAD_ID}' AS DWH_LOAD_ID
FROM ${TEMP_DB}.T_${SRC_INPUT_TABLE} AS SRC
INNER JOIN ETL.T_TCACHE_CBX_LDL_ITEM_ARTICLE_EAN_2 AS EAN_2 
        ON EAN.ITEM_ID = SRC.ID
INNER JOIN META.T_PRODUCT_VARIANT_KEY_2 VKEY
        /* KEY MUST ALREADY EXIST AFTER THE T_PRODUCT_VARIANT_2 (CBX_SLS) JOB. */
        ON VKEY.PROD_VARIANT_NAT_KEY_NR = UPPER(SRC.ITEM_NO || '|' || EAN.LDL_EAN)
        AND VKEY.PROD_VARIANT_KEY_TYPE_CD = 'CBX_SLS'
WHERE EAN.LDL_EAN IS NOT NULL 
QUALIFY ROW_NUMBER() OVER (
	PARTITION BY 
		SRC.ITEM_NO,
		EAN.LDL_EAN
	ORDER BY
		SRC.UPDATED_ON DESC
    ) = 1
	
UNION ALL

SELECT
    DISTINCT VKEY.PROD_VARIANT_SID AS PROD_VARIANT_SID,
    'SLS_UNK' AS PROD_VARIANT_KEY_TYPE_CD,
    UPPER(SRC.CTRCODE || '|' || SRC.WAWI_ITEM_NO) AS PROD_VARIANT_NAT_KEY_NR,
	
    'CBX' AS SOURCE_SYSTEM,
    CURRENT_DATE AS EXTRACTION_DT,
    CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
    0 AS TF_ERROR_FG,
    0 AS DELETED_FG,
    0 AS RECORD_ID,
    't_${SRC_INPUT_TABLE}' AS FILENAME,
    'CBX' AS DWH_NODE_CD,
    '${LOAD_ID}' AS DWH_LOAD_ID
FROM
    (
	SELECT
		IIT.CTRCODE,
		TRY_CAST(CBX.ITEM_NO AS NUMBER) AS ITEM_NO,
		CAST(
			SUBSTRING(IIT.C215_ITEMNR, 1, LENGTH(IIT.C215_ITEMNR) -4) AS NUMBER
		) AS WAWI_ITEM_NO,
		MIN(IIT.C215_MODDATE) AS MODDATE
	FROM ${TEMP_DB}.T_${SRC_INPUT_TABLE} AS CBX
		INNER JOIN ETL.T_WAWI_PRECORE_T215_INT_ITEMNR_2 AS IIT 
			ON CAST(IIT.C215_INT_ITEMNR AS NUMBER) = TRY_CAST(CBX.ITEM_NO AS NUMBER)
	WHERE
		TRY_CAST(CBX.ITEM_NO AS NUMBER) IS NOT NULL
	GROUP BY
		IIT.CTRCODE,
		CBX.ITEM_NO,
		WAWI_ITEM_NO
    ) AS SRC
INNER JOIN META.T_PRODUCT_VARIANT_KEY_2 VKEY
/* KEY MUST ALREADY EXIST AFTER THE T_PRODUCT_VARIANT_2 (CBX_SLS) JOB. */
        ON VKEY.PROD_VARIANT_NAT_KEY_NR = CAST(SRC.ITEM_NO AS VARCHAR(250))
        AND VKEY.PROD_VARIANT_KEY_TYPE_CD = 'CBX_SLS_UNK' 
QUALIFY ROW_NUMBER() OVER (
        PARTITION BY 
                SRC.ITEM_NO, SRC.CTRCODE
        ORDER BY 
                SRC.MODDATE DESC
) = 1

UNION ALL

SELECT
    VKEY.PROD_VARIANT_SID AS PROD_VARIANT_SID,
    'LOG' AS PROD_VARIANT_KEY_TYPE_CD,
    ALL_SRC.PROD_VARIANT_NAT_KEY_NR,
	
    'CBX' AS SOURCE_SYSTEM,
    CURRENT_DATE AS EXTRACTION_DT,
    CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
    0 AS TF_ERROR_FG,
    0 AS DELETED_FG,
    0 AS RECORD_ID,
    't_${SRC_INPUT_TABLE}' AS FILENAME,
    'CBX' AS DWH_NODE_CD,
    '${LOAD_ID}' AS DWH_LOAD_ID
FROM
(
        SELECT
            SRC.ITEM_NO || '|' || SRC.LDL_CODE AS JOIN_PROD_VARIANT_NAT_KEY_NR,
            UPPER(WINT.CTRCODE || '|' || WINT.WAWI_ITEMNR) AS PROD_VARIANT_NAT_KEY_NR,
            WINT.MODDATE
        FROM
            (
                SELECT
                        DISTINCT TRY_CAST(ITM.ITEM_NO AS NUMBER) AS ITEM_NO,
                        IPM.LDL_CODE,
                        IPM.LDL_TOTAL_PACK_RATIO,
                        IPM.LDL_CTRCODE
                FROM
                        (
                                SELECT
                                        ID,
                                        ITEM_NO
                                FROM
                                        ETL.T_TCACHE_CBX_CNT_ITEM_2
                                WHERE
                                        TRY_CAST(ITEM_NO AS NUMBER) != 0 QUALIFY ROW_NUMBER() OVER (
                                                PARTITION BY ITEM_NO
                                                ORDER BY
                                                        VERSION DESC NULLS LAST,
                                                        REVISION DESC NULLS LAST
                                        ) = 1
                        ) AS ITM
                INNER JOIN (
                        SELECT
                                IPM.ITEM_ID,
                                IPM.LDL_CODE,
                                IPM.LDL_TOTAL_PACK_RATIO,
                                SPLIT(IPMC.VALUE, '-') [0]::STRING AS LDL_CTR_BLOCK,
                                SPLIT(IPMC.VALUE, '-') [1]::STRING AS LDL_CTRCODE
                        FROM    ETL.T_TCACHE_CBX_LDL_ITEM_PACKING_METHOD_2 AS IPM,
                                LATERAL SPLIT_TO_TABLE(IPM.LDL_COUNTRY_CODES, ',') AS IPMC
                           ) AS IPM ON ITM.ID = IPM.ITEM_ID
		) AS SRC
        INNER JOIN (
                SELECT
                        CTRCODE,
                        TRY_CAST(C215_INT_ITEMNR AS NUMBER) AS INT_ITEMNR,
                        TRY_CAST(
                                SUBSTRING(C215_ITEMNR, 1, LENGTH(C215_ITEMNR) -4) AS NUMBER
                        ) AS WAWI_ITEMNR,
                        TRY_CAST(RIGHT(C215_ITEMNR, 4) AS NUMBER) AS WAWI_CASESIZE,
                        C215_MODDATE AS MODDATE
                FROM ETL.T_WAWI_PRECORE_T215_INT_ITEMNR_2
        ) AS WINT 
                ON SRC.LDL_CTRCODE = WINT.CTRCODE
                AND SRC.ITEM_NO = WINT.INT_ITEMNR QUALIFY ROW_NUMBER() OVER (
        PARTITION BY 
                WINT.CTRCODE,
                WINT.WAWI_ITEMNR
        ORDER BY
                ABS(SRC.LDL_TOTAL_PACK_RATIO - WINT.WAWI_CASESIZE),
                SRC.LDL_TOTAL_PACK_RATIO - WINT.WAWI_CASESIZE,
                WINT.WAWI_CASESIZE DESC NULLS LAST,
                SRC.LDL_CODE
        ) = 1
) AS ALL_SRC
INNER JOIN META.T_PRODUCT_VARIANT_KEY_2 VKEY
/* KEY MUST ALREADY EXIST AFTER THE T_PRODUCT_VARIANT_2 (CBX_SLS) JOB. */
	ON VKEY.PROD_VARIANT_NAT_KEY_NR = ALL_SRC.JOIN_PROD_VARIANT_NAT_KEY_NR
	AND VKEY.PROD_VARIANT_KEY_TYPE_CD = 'CBX_LOG' 
	QUALIFY ROW_NUMBER() OVER (
		PARTITION BY 
			ALL_SRC.PROD_VARIANT_NAT_KEY_NR
		ORDER BY
			ALL_SRC.MODDATE DESC
	) = 1;
