MERGE INTO POLICIES.T_SEC_RAP_CORE_SALES_COMPANY_NR_2 as tgt
USING ( 
select 'SNOW-XX-LDL-RLS-COMPANY-'||SUBSTR(SALES_COMPANY_NR, 1,2)||'-WH'||SUBSTR(SALES_COMPANY_NR, 3) as ROLE_NAME
     , SALES_COMPANY_NR
  from CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_2
 where DWH_VALID_FG = TRUE 
   and IS_SALES_COMPANY_FG = TRUE) as src
    on tgt.SALES_COMPANY_NR = src.SALES_COMPANY_NR
  /* WHEN NOT MATCHED AND tgt.SALES_COMPANY_NR IS NOT NULL THEN DELETE */
  WHEN NOT MATCHED THEN INSERT ( ROLE_NAME, SALES_COMPANY_NR)
                        VALUES ( SRC.ROLE_NAME, SRC.SALES_COMPANY_NR)
;
