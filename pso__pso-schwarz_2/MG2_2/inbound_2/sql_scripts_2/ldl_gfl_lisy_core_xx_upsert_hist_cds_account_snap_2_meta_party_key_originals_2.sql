BEGIN TRANSACTION; 

        DELETE FROM META.T_PARTY_KEY_2 -- PREVENT ANY CONCURRENT ACCESS TO THIS KEYSPACE
        WHERE 1=2;
  
        -- CREATE NEW SK ENTRIES FOR EVERY NEW NK/TYPE/VALID_FROM_TMSP COMBINATION
        
       INSERT INTO META.T_PARTY_KEY_2 
       (
                PARTY_SID,
                PARTY_KEY_TYPE_CD,
                PARTY_NAT_KEY_NR,
                DWH_CREATED_TMSP,
                DWH_UPDATED_TMSP,
                DWH_VALID_FROM_TMSP,
                DWH_VALID_TO_TMSP,
                DWH_VALID_FG,
                DWH_NODE_CD,
                DWH_LOAD_ID
       )
       (
        SELECT  
                MAX_SEQ + ROW_NUMBER() OVER(ORDER BY 1) AS PARTY_SID,
                'STORE' AS INT_ORG_KEY_TYPE_CD,
                INT_ORG_NATURAL_KEY AS NATURAL_KEY,
                CURRENT_TIMESTAMP,
                CURRENT_TIMESTAMP,
                SINKMODIFIEDON,
                '9999-12-31 23:59:59',
                TRUE,
                UPPER(T1.DWH_NODE_CD),
                ${LOAD_ID}
        
        FROM (SELECT T1.DWH_NODE_CD, INT_ORG_KEY_TYPE_CD, INT_ORG_NATURAL_KEY, SINKMODIFIEDON
                FROM (SELECT  LOWER(T1.DWH_NODE_CD) AS DWH_NODE_CD, 
                                'STORE' AS INT_ORG_KEY_TYPE_CD, 
                                UPPER(SUBSTR(IGL_NUMBER, 1, 2)) ||'|'||TO_NUMBER(SUBSTR(IGL_NUMBER,3,5)) AS INT_ORG_NATURAL_KEY,
                                SINKMODIFIEDON
                        FROM ETL_PROCESS.T_TCACHE_LISY_CDS_ACCOUNT_SNAP_2 T1_2
                        WHERE T1.IGL_ACCOUNTTYPECODE IN (285540000, 285540009) -- REAL ESTATE ASSOCIATED WITH STORES AND SPECIAL SALE STORES
                        AND T1.IGL_NUMBER IS NOT NULL -- ONLY OBJECTS WITH ASSIGNED OBJECT NUMBER SHOULD BE KEPT
                        AND (T1.IGL_NEODATE IS NOT NULL OR T1.IGL_CLOSINGDATE IS NOT NULL ) -- IF A BUILDING SHOULD BE COUNTED AS A STORE, IT MUST HAVE AT LEAST ONE OF THESE DATES
                        AND IGL_SUBSTITUTEFORID IS NULL
                        AND T1.ACCOUNTID NOT IN 
                                (SELECT IGL_REPLACEMENTID 
                                  FROM ETL_PROCESS.T_TCACHE_LISY_CDS_ACCOUNT_SNAP_2 
                                  WHERE IGL_REPLACEMENTID IS NOT NULL) -- "ROOT"( "INIT") STORES ONLY - THESE STORES ARE NOT DESCENDANTS OF ANY OTHER STORE.
                 ) T1_2
                GROUP BY T1.DWH_NODE_CD, INT_ORG_KEY_TYPE_CD, INT_ORG_NATURAL_KEY, SINKMODIFIEDON) T1_2
                
        CROSS JOIN (SELECT COALESCE(MAX(PARTY_SID),0) AS MAX_SEQ FROM META.T_PARTY_KEY_2) AS MAX_SEQ
        

        WHERE 
        NATURAL_KEY IS NOT NULL AND 
        NOT EXISTS
                (
                 SELECT 1 FROM META.T_PARTY_KEY_2 T2 
                 WHERE
                 UPPER(T2.PARTY_KEY_TYPE_CD) = UPPER(T1.INT_ORG_KEY_TYPE_CD) AND
                 CURRENT_TIMESTAMP BETWEEN T2.DWH_VALID_FROM_TMSP AND T2.DWH_VALID_TO_TMSP AND -- ACCOMODATES HISTORIZED SID ASSOCIATION (FULL CAPABILITY NOT IMPLEMENTED IN INITIAL RELEASE)
                 T2.PARTY_NAT_KEY_NR = UPPER(T1.INT_ORG_NATURAL_KEY)
                ) 
        );

COMMIT;
                
