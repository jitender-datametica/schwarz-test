
BEGIN TRANSACTION;

INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        REAL_ESTATE_KEY_TYPE_CD,
        REAL_ESTATE_NK,
        REPLACEMENT_REAL_ESTATE_KEY_TYPE_CD,
        REPLACEMENT_REAL_ESTATE_NK,
	REAL_ESTATE_REPLACEMENT_TYPE_CD,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)

/* Create a lookup table for the replacement accounts */

WITH REPL AS (
        SELECT DRV.ACCOUNTID AS ACCOUNTID, 
               DRV.IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(DRV.IGL_NUMBER, 3, 7), '0#') AS REAL_ESTATE_REPLACEMENT_NK,
               DRV.IGL_EXPECTEDOPENINGDATE,
               DRV.IGL_NEODATE
        FROM etl_process.t_${SRC_INPUT_TABLE} DRV
        WHERE DRV.ACCOUNTID IN
            (SELECT SUB.IGL_REPLACEMENTID 
             FROM etl_process.t_${SRC_INPUT_TABLE} SUB
             WHERE SUB.IGL_REPLACEMENTID IS NOT NULL
               AND SUB.IGL_NUMBER IS NOT NULL
               AND IGL_ACCOUNTTYPECODE = 285540000
               AND SUB.DELETED <> 'x'
               AND (SUB.IGL_NEODATE IS NOT NULL OR SUB.IGL_EXPECTEDOPENINGDATE IS NOT NULL))
)
SELECT
        'RE_2' AS REAL_ESTATE_KEY_TYPE_CD,
        IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(IGL_NUMBER, 3, 7), '0#') AS REAL_ESTATE_NK,
        CASE
                WHEN REPL.REAL_ESTATE_REPLACEMENT_NK IS NULL THEN 'DUMMY_2'
                ELSE 'RE_2' 
        END AS REPLACEMENT_REAL_ESTATE_KEY_TYPE_CD,
        CASE
                WHEN REPL.REAL_ESTATE_REPLACEMENT_NK IS NULL THEN 'DUMMY_2|DUMMY_2'
                ELSE REPL.REAL_ESTATE_REPLACEMENT_NK 
        END AS REPLACEMENT_REAL_ESTATE_NK,
        CASE
                WHEN IGL_PROJECTTYPECODE = 285540001 THEN 'RECON'
                ELSE 'RELOC'
        END AS REAL_ESTATE_REPLACEMENT_TYPE_CD,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CASE 
                WHEN REPL.IGL_NEODATE IS NOT NULL THEN REPL.IGL_NEODATE 
                WHEN REPL.IGL_EXPECTEDOPENINGDATE > CURRENT_DATE AND REPL.IGL_NEODATE IS NULL THEN REPL.IGL_EXPECTEDOPENINGDATE
                ELSE SINKMODIFIEDON
        END AS DWH_VALID_FROM_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM etl_process.t_${SRC_INPUT_TABLE} SRC
LEFT JOIN REPL
ON IGL_REPLACEMENTID = REPL.ACCOUNTID
WHERE IGL_ACCOUNTTYPECODE = 285540000   // only real estate associated with stores have replacements
AND IGL_NUMBER IS NOT NULL              // (only objects with assigned object number should be kept)
AND IGL_REPLACEMENTID IS NOT NULL
AND REPL.REAL_ESTATE_REPLACEMENT_NK IS NOT NULL -- e.g. Records with NULL accountid's, or NULL IGL_NUMBERs
AND SRC.DELETED <> 'x'
;

COMMIT;
