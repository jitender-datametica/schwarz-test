INSERT INTO  ETL.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        REAL_ESTATE_KEY_TYPE_CD,
        REAL_ESTATE_NK,
        CLOSED_FROM_DT,
	CLOSED_UNTIL_DT,
	CLOSED_BUS_DAYS_CNT ,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        'RE_2' AS REAL_ESTATE_KEY_TYPE_CD,
        IGL_ISOCODE2 || '|' || LTRIM(SUBSTR(IGL_NUMBER, 3, 7), '0#') AS REAL_ESTATE_NK,
        TRY_TO_DATE(IGL_CLOSINGDATEFROM, 'YYYYMMDD') AS CLOSED_FROM_DT,
        CASE
                WHEN IGL_CLOSINGDATETO IS NOT NULL THEN TRY_TO_DATE(IGL_CLOSINGDATETO, 'YYYYMMDD')
                WHEN IGL_CLOSINGDATETO IS NULL AND IGL_REOPENINGDATE IS NOT NULL THEN TRY_TO_DATE(IGL_REOPENINGDATE, 'YYYYMMDD') - 1
        END AS CLOSED_UNTIL_DT,
        CASE
                WHEN IGL_CLOSINGDATETO IS NOT NULL THEN (TRY_TO_DATE(IGL_CLOSINGDATETO, 'YYYYMMDD') - TRY_TO_DATE(IGL_CLOSINGDATEFROM, 'YYYYMMDD'))
                WHEN IGL_CLOSINGDATETO IS NULL AND IGL_REOPENINGDATE IS NOT NULL THEN ( (TRY_TO_DATE(IGL_REOPENINGDATE, 'YYYYMMDD') - 1) - TRY_TO_DATE(IGL_CLOSINGDATEFROM, 'YYYYMMDD'))
        END AS CLOSED_BUS_DAYS_CNT,
        'LISY' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        CURRENT_TIMESTAMP AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'LISY' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM etl_process.t_${SRC_INPUT_TABLE} SRC
WHERE
IGL_ACCOUNTTYPECODE IN (285540000, 285540009) -- real estate associated with stores and special sale stores,
AND IGL_NUMBER IS NOT NULL -- (only objects with assigned object number should be kept)
AND IGL_CLOSINGDATEFROM IS NOT NULL
AND (IGL_CLOSINGDATETO IS NOT NULL OR (IGL_REOPENINGDATE IS NOT NULL AND IGL_REOPENINGDATE > IGL_CLOSINGDATEFROM ) )
QUALIFY ROW_NUMBER() OVER (PARTITION BY IGL_CLOSINGDATEFROM ORDER BY EXTRACTION_TS DESC) = 1 -- we are interested in all closing times of stores regardless of the concrete measure.
;
