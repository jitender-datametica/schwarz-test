(
        REAL_ESTATE_SID,
        ADDR_SID,
        ADDR_USG_TYPE_CD,
        ADDR_TYPE_CD,  
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
