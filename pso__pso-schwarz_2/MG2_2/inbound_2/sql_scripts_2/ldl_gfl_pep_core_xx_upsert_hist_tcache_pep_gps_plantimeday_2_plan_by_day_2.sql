INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
   (
        INT_ORG_SID,
        INT_ORG_TYPE_CD ,
        REAL_ESTATE_SID ,
        CAL_DT,
        PLANNED_VAL_TYPE_NATURAL_KEY,
        PLANNED_VAL_TYPE_KEY_TYPE_CD,
        PLAN_POS_NR,
        PLANNED_KPI_MEAS,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
  )
WITH PRE_CALC AS (
SELECT
        INT_ORG_SID,
        CAL_DT,
        STORE,
        DATE(EXTRACTION_TMSP) AS EXTRACTION_DT,
        CAST(TURNOVER AS NUMBER(18,5)) AS SALES_PIECE,
        CAST(TOTALHOURS AS NUMBER(18,5)) AS TOTAL_HOURS,
        CAST(TOTALHOURS - (TRAININGHOURS + MISCHOURS + INVENTORYHOURS) AS NUMBER(18,5)) AS WORKING_HOURS,
        CAST(TRAININGHOURS AS NUMBER(18,5)) AS TRAINING_HOURS,
        CAST(INVENTORYHOURS AS NUMBER(18,5)) AS INVENTORY_HOURS,
        CAST(MISCHOURS AS NUMBER(18,5)) AS MISC_HOURS
    FROM ETL.T_TCACHE_PEP_GPS_PLANTIMEDAY_2
),
ROW_EXPL AS (
SELECT
        *
    FROM PRE_CALC
UNPIVOT (KPI_MEAS FOR KPI_TYPE IN (SALES_PIECE, TOTAL_HOURS, WORKING_HOURS, TRAINING_HOURS, INVENTORY_HOURS, MISC_HOURS))
)
SELECT 
    INT_ORG_SID,
    'STORE' AS INT_ORG_TYPE_CD,
    -1 AS REAL_ESTATE_SID,
    CAL_DT,
    KPI_TYPE AS PLANNED_VALUE_TYPE_NATURAL_KEY,
    'PEP2' AS PLANNED_VALUE_TYE_KEY_TYPE_CD,
    STORE AS PLAN_POS_NR,
    KPI_MEAS AS PLANNED_KPI_MEAS,
    EXTRACTION_DT,        
    CURRENT_TIMESTAMP              AS  DWH_MAPPING_TMSP,
    0                              AS  TF_ERROR_FG,
    0                              AS  DELETED_FG,
    0                              AS  RECORD_ID,
    'T_${SRC_INPUT_TABLE}'         AS  FILENAME,
    'PEP 2.0'                      AS  DWH_NODE_CD,
    '${LOAD_ID}'                   AS DWH_LOAD_ID 
FROM ROW_EXPL
WHERE KPI_MEAS <> 0;
