INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        PRICE_INFO_EVENT_SID,
        CASH_REGISTER_EVENT_NR,
        EVENT_TMSP,
        BUS_DT,
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        CASH_REGISTER_SID,
        CASH_REGISTER_TYPE_CD,
        CASH_REGISTER_USG_TYPE_CD,
        CASHIER_HASH,
        OFFLINE_FG,
        CANCEL_FG,
        SUSPEND_FG,
        TRAINING_FG,
        PROD_VARIANT_KEY_TYPE_CD,
        PROD_VARIANT_NATURAL_KEY,
        WAWI_ITEM_KEY_TYPE_CD,
        WAWI_ITEM_NAT_KEY_NR,
        PROD_PRICE,
        CURR_CD,
        PROD_BOUGHT_FG,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        ((((CAST(TO_CHAR(RECEIPT_BUSINESS_DATE, 'YYYYMMDD') AS NUMBER) * 100
        + ASCII(SUBSTRING(CONTEXT_COUNTRY, 1, 1))) * 100
        + ASCII(SUBSTRING(CONTEXT_COUNTRY, 2, 1))) * 100000000
        + ORIG_STORE_NR) * 10000
        + POS_TERMINAL_ID) * 10000000000
        + ORIG_RECEIPT_NR
        AS PRICE_INFO_EVENT_SID,
        ORIG_RECEIPT_NR AS CASH_REGISTER_EVENT_NR,
        RECEIPT_TIMESTAMP_BEGIN AS EVENT_TMSP,
        RECEIPT_BUSINESS_DATE AS BUS_DT,
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        CASH_REGISTER_SID,
        POS_TYPE AS CASH_REGISTER_TYPE_CD,
        NULL AS CASH_REGISTER_USG_TYPE_CD,
        checker_hash AS cashier_hash,             
        CASE WHEN OFFLINE_FG = '1'
                THEN True
                ELSE False
        END AS OFFLINE_FG,
        False AS CANCEL_FG,
        False AS SUSPEND_FG,
        CASE WHEN TRAINING_FG = '1'
                THEN True
                ELSE False
        END AS TRAINING_FG,
        'SLS_UNK' AS PROD_VARIANT_KEY_TYPE_CD,        
        CONTEXT_COUNTRY || '|' || ORIG_ITEM_NR AS PROD_VARIANT_NATURAL_KEY,
        'WAWI' AS WAWI_ITEM_KEY_TYPE_CD,
        UPPER(CASE WHEN CONTEXT_COUNTRY ='CS' THEN 'ES' ELSE CONTEXT_COUNTRY END)  || '|' || ORIG_ITEM_NR AS WAWI_ITEM_NAT_KEY_NR,
        VAL_RETAIL AS PROD_PRICE,
        CURR_CD,
        -1 AS PROD_BOUGHT_FG, -- Awaiting populated field from source,
        'EJR' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        current_timestamp AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        'V_${SRC_INPUT_TABLE}' AS FILENAME,
        'EJR' AS DWH_NODE_CD,
        '${LOAD_ID}' AS DWH_LOAD_ID 
FROM ETL.V_${SRC_INPUT_TABLE} SRC
WHERE RECEIPT_TRANSACTIONTYPE_ID = '480'
QUALIFY ROW_NUMBER() OVER ( PARTITION BY
        CONTEXT_COUNTRY
      , ORIG_STORE_NR
      , POS_TERMINAL_ID
      , ORIG_RECEIPT_NR
      , RECEIPT_BUSINESS_DATE
      , RECEIPT_TRANSACTIONTYPE_ID
      , RECEIPT_TIMESTAMP_BEGIN
      ORDER BY RECEIPT_TIMESTAMP_END DESC
) = 1;
