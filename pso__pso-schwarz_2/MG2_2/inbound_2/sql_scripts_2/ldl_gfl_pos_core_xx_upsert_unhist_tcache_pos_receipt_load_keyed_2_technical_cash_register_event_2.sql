INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        TECH_CASH_REGISTER_EVENT_SID,
        CASH_REGISTER_EVENT_NR,
        EVENT_TMSP,
        BUS_DT,
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        CASH_REGISTER_SID,
        CASH_REGISTER_TYPE_CD,
        CASH_REGISTER_USG_TYPE_CD,
        CASHIER_HASH,
        TECH_CASH_REGISTER_EVENT_TYPE_CD,
        OFFLINE_FG,
        CANCEL_FG,
        SUSPEND_FG,
        TRAINING_FG,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT
        ((((CAST(TO_CHAR(RECEIPT_BUSINESS_DATE, 'YYYYMMDD') AS NUMBER) * 100
        + ASCII(SUBSTRING(BIC_ZMLILA, 1, 1))) * 100
        + ASCII(SUBSTRING(BIC_ZMLILA, 2, 1))) * 100000000
        + ORIG_STORE_NR) * 10000
        + POS_TERMINAL_ID) * 10000000000
        + ORIG_RECEIPT_NR
        AS TECH_CASH_REGISTER_EVENT_SID,
        ORIG_RECEIPT_NR AS CASH_REGISTER_EVENT_NR,
        RECEIPT_TIMESTAMP_BEGIN AS EVENT_TMSP,
        RECEIPT_BUSINESS_DATE AS BUS_DT,
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        CASH_REGISTER_SID,
        POS_TYPE AS CASH_REGISTER_TYPE_CD,
        NULL AS CASH_REGISTER_USG_TYPE_CD,
        COALESCE(checker_hash,'Unknown') AS cashier_hash,                
        RECEIPT_TRANSACTIONTYPE_ID AS TECH_CASH_REGISTER_EVENT_TYPE_CD,
        CASE WHEN OFFLINE_FG = '1'
                THEN True
                ELSE False
        END AS OFFLINE_FG,
        False AS CANCEL_FG,
        False AS SUSPEND_FG,
        CASE WHEN TRAINING_FG = '1'
                THEN True
                ELSE False
        END AS TRAINING_FG,
         'EJR' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        current_timestamp AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        'V_${SRC_INPUT_TABLE}' AS FILENAME,
        'EJR' AS DWH_NODE_CD,
        '${LOAD_ID}' AS DWH_LOAD_ID 
FROM ETL.V_${SRC_INPUT_TABLE} SRC
WHERE RECEIPT_TRANSACTIONTYPE_ID BETWEEN '400' AND '475'
/* "Technical" Transactions only, like LogOn, LogOff, Lock, Unlock, ... */
QUALIFY ROW_NUMBER() OVER ( PARTITION BY
        CONTEXT_COUNTRY
      , ORIG_STORE_NR
      , POS_TERMINAL_ID
      , ORIG_RECEIPT_NR
      , RECEIPT_BUSINESS_DATE
      , RECEIPT_TRANSACTIONTYPE_ID
      , RECEIPT_TIMESTAMP_BEGIN
      ORDER BY RECEIPT_TIMESTAMP_END DESC
) = 1;
