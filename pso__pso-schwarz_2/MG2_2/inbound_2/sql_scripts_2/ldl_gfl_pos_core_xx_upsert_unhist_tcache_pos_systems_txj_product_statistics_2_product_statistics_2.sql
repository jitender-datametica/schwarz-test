-- Enrich with currency code and country_org_cd from int org and aggregate

INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        STORE_SID,
        COUNTRY_ORG_SID,
        COUNTRY_ORG_CD,
        REAL_ESTATE_SID,
        STAT_DT,
        BUS_DT,
        CURR_STAT_FG,
        SALES_VARIANT_SID,
        SOLD_CNT,
        RETURNED_CNT,
        CANCEL_CNT,
        SOLD_QTY,
        RETURNED_QTY,
        CANCEL_QTY,
        UOM_CD,
        TURNOVER_GROSS_VAL,
        RETURNED_GROSS_VAL,
        CANCEL_GROSS_VAL,
        CURR_CD,
        LAST_SALE_TMSP,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
        )
SELECT
        STORE_SID, --key1
        MIN(COUNTRY_ORG_SID) AS COUNTRY_ORG_SID,
        MIN(ORG.COUNTRY_ORG_CD) AS COUNTRY_ORG_CD,
        REAL_ESTATE_SID, --key2
        MIN(STAT_DT) AS STAT_DT,
        BUS_DT, --key3
        MIN(CURR_STAT_FG) AS CURR_STAT_FG,
        SALES_VARIANT_SID, --key4
        MIN(SOLD_CNT) AS SOLD_CNT,
        MIN(RETURNED_CNT) AS RETURNED_CNT,
        MIN(CANCEL_CNT) AS CANCEL_CNT,
        MIN(SOLD_QTY) AS SOLD_QTY,
        MIN(RETURNED_QTY) AS RETURNED_QTY,
        MIN(CANCEL_QTY) AS CANCEL_QTY,
        MIN(UOM_CD) AS UOM_CD,
        SUM(TURNOVER_GROSS_VAL) AS TURNOVER_GROSS_VAL,
        SUM(RETURNED_GROSS_VAL) AS RETURNED_GROSS_VAL,
        SUM(CANCEL_GROSS_VAL) AS RETURNED_GROSS_VAL,
        MIN(ORG.CURR_CD) AS CURR_CD,
        MAX(LAST_SALE_TMSP) AS LAST_SALE_TMSP,
        MIN('TXJ') AS SOURCE_SYSTEM,
        MIN(CURRENT_DATE) AS EXTRACTION_DT,
        MIN(current_timestamp) AS DWH_MAPPING_TMSP,
        MIN(0) AS TF_ERROR_FG,
        MIN(0) AS DELETED_FG,
        MIN(0) AS RECORD_ID,
        MIN('t_${SRC_INPUT_TABLE}') AS FILENAME,
        MIN('TXJ') AS DWH_NODE_CD,
        MIN('${LOAD_ID}') as DWH_LOAD_ID 
FROM ${TEMP_DB}.t_${SRC_INPUT_TABLE} SRC
LEFT OUTER JOIN CORE_REL.T_INTERNAL_ORGANIZATION_2 ORG
ON  SRC.COUNTRY_ORG_SID = ORG.INT_ORG_SID
AND SRC.BUS_DT BETWEEN ORG.DWH_VALID_FROM_TMSP AND ORG.DWH_VALID_TO_TMSP
GROUP BY STORE_SID, REAL_ESTATE_SID, BUS_DT, SALES_VARIANT_SID

;
