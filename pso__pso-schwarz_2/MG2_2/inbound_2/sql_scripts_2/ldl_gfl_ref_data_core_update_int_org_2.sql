-- Enrich Region_2 data with country_2 organisation name from t_country_2

MERGE INTO CORE_REL.T_INTERNAL_ORGANIZATION_2 TRG
USING
(
    SELECT 
    	INT_ORG.*,
    	CASE     
            WHEN SUBSTR(INT_ORG.INT_ORG_NR, 1,2) = 'NI' THEN 'Nordirland'
            ELSE CNTRY.COUNTRY_NAME
        END AS NEW_COUNTRY_NAME
    FROM CORE_REL.T_INTERNAL_ORGANIZATION_2  AS INT_ORG
    	LEFT JOIN CORE_REL.T_COUNTRY_2 CNTRY
    		ON CNTRY.ISO_COUNTRY_CD = SUBSTR(INT_ORG.INT_ORG_NR, 1,2)
            AND CNTRY.DWH_VALID_FG = TRUE
    WHERE 1=1
        AND INT_ORG.INT_ORG_TYPE_CD = 'REGION_2'
    	AND INT_ORG.DWH_VALID_FG = TRUE
) SRC
ON TRG.INT_ORG_SID  = SRC.INT_ORG_SID
    AND TRG.DWH_VALID_FROM_TMSP = SRC.DWH_VALID_FROM_TMSP
WHEN MATCHED 
    AND NOT EQUAL_NULL(TRG.COUNTRY_ORG_NAME, SRC.NEW_COUNTRY_NAME) 
THEN UPDATE
    SET TRG.COUNTRY_ORG_NAME = SRC.NEW_COUNTRY_NAME
;

