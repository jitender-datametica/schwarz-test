INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
        PARTY_SID,
	PARTY_KEY_TYPE_CD,
        PARTY_NAT_KEY_NR,
        SOURCE_SYSTEM,
        EXTRACTION_DT,
        DWH_MAPPING_TMSP,
        TF_ERROR_FG,
        DELETED_FG,
        RECORD_ID,
        FILENAME,
        DWH_NODE_CD,
        DWH_LOAD_ID
)
SELECT PARTY_SID,
        'COMPANY' AS PARTY_KEY_TYPE_CD, 
        CONCAT(WH.LAND_2,'|',WH.SHORT_NAME) AS PARTY_NAT_KEY_NR,
        'EXTERNAL_CSV' AS SOURCE_SYSTEM,
        CURRENT_DATE AS EXTRACTION_DT,
        DWH_VALID_FROM_TMSP AS DWH_MAPPING_TMSP,
        0 AS TF_ERROR_FG,
        0 AS DELETED_FG,
        0 AS RECORD_ID,
        't_${SRC_INPUT_TABLE}' AS FILENAME,
        'EXTERNAL_CSV' AS DWH_NODE_CD,
        '${LOAD_ID}' as DWH_LOAD_ID 
FROM META.T_PARTY_KEY_2 PK
INNER JOIN ETL.T_TCACHE_BIZREF_WH_CODE_SAP_WAWI_MAP WH
ON REPLACE(PK.PARTY_NAT_KEY_NR,'|','')= WH.CODE
AND PARTY_KEY_TYPE_CD='COMPANY';
