INSERT INTO  ${TEMP_DB}.${SRC2TGT_TEMP_TABLE1}_${SRC_CONTEXT_AREA}
(
    STORE_KEY_TYPE_CD,
    STORE_NK,
    COUNTRY_ORG_KEY_TYPE_CD,
    COUNTRY_ORG_NK,
    REAL_ESTATE_KEY_TYPE_CD,
    REAL_ESTATE_NK,
    STAT_DT,
    BUS_DT,
    CURR_STAT_FG,
    CORRECTION_SEQ,
    RECEIPT_NR,
    RECEIPT_LINE_NR,
    STAT_SRC_CD,
    REVENUE_STAT_TYPE_ID,
    RECEIPT_CNT,
    TURNOVER_NET_VAL,
    TURNOVER_GROSS_VAL,
    SOURCE_SYSTEM,
    EXTRACTION_DT,
    DWH_MAPPING_TMSP,
    TF_ERROR_FG,
    DELETED_FG,
    RECORD_ID,
    FILENAME,
    DWH_NODE_CD,
    DWH_LOAD_ID
)
SELECT
    'STORE' AS STORE_TYPE_KEY_CD,
    (LEFT(CTRCODE,2) || '|' || C89_STORENO) AS STORE_NK,
    'COUNTRY_2' AS COUNTRY_ORG_KEY_TYPE_CD,
    (LEFT(CTRCODE,2)) AS COUNTRY_ORG_NK,
    'RE_2' AS REAL_ESTATE_KEY_TYPE_CD,
    (LEFT(CTRCODE,2) || '|' || C89_STORENO) AS REAL_ESTATE_NK,
    Coalesce(C89_TGDATE, C89_MODDATE)::DATE AS STAT_DT,
    C89_FORMDATE AS BUS_DT,
    TRUE AS CURR_STATE_FG,
    C89_CORRECT_FLAG AS CORRECTION_SEQ,
    C89_FORMCOUNT AS RECEIPT_NR,
    C89_ROW AS RECIEPT_LINE_NR,
    'WAWI' AS STAT_SRC_CD,
    CASE C89_FORMTYPE
    WHEN 136 THEN 1 /*Base*/
    WHEN 146 THEN 2 /*Correction*/
    END AS REVENUE_STAT_TYPE_ID,
    C89_ACTPRICEGROUP AS RECEIPT_CNT,
    NULL AS TURNOVER_NET_VAL,
    C89_VALUE AS TURONOVER_GROSS_VAL,
    'WAWI_WH' AS SOURCE_SYSTEM,
    CURRENT_DATE AS EXTRACTION_DT,
    current_timestamp AS DWH_MAPPING_TMSP,
    0 AS TF_ERROR_FG,
    0 AS DELETED_FG,
    0 AS RECORD_ID,
    't_${SRC_INPUT_TABLE}' AS FILENAME,
    'WAWI_WH' AS DWH_NODE_CD,
    '${LOAD_ID}' as DWH_LOAD_ID 
FROM ${TEMP_DB}.t_${SRC_INPUT_TABLE} SRC
WHERE C89_FORMTYPE IN (136, 146)
