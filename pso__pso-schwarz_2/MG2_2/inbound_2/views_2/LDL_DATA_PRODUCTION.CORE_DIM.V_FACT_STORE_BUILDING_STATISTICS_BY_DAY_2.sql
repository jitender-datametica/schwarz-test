create or replace view LDL_DATA_PRODUCTION.CORE_DIM.V_FACT_STORE_BUILDING_STATISTICS_BY_DAY_2(
	REAL_ESTATE_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE REAL ESTATE OBJECT.',
	COUNTRY_ORG_SID COMMENT 'THE UNIQUE IDENTIFIER (SURROGATE KEY) FOR THE RELATED COUNTRY_2 ORGANIZATION.',
	COUNTRY_ORG_CD COMMENT 'THE CODE OF THE BUSINESS COUNTRY_2 FOR WHICH THIS COUNTRY_2 ORGANIZATION IS RESPONSIBLE. (THE BUSINESS COUNTRY_2 IS NOT IDENTICAL TO A POLITICAL COUNTRY.)',
	REPORTING_COUNTRY_CD COMMENT 'THE CODE WHICH IDENTIFIES THE REPORTING COUNTRY_2 IN WHICH THE INTERNAL ORGANIZATION IS LOCATED.',
	CAL_DT COMMENT 'THE DAY REPRESENTED AS A CALENDAR_2 DATE OF THE FORM YYYY-MM_2-DD. YYYY IS THE CALENDAR_2 YEAR, MM_2 (BETWEEN 1 AND 12) THE CALENDAR_2 MONTH AND DD THE DAY OF THE CALENDAR_2 MONTH (BETWEEN 1 AND 31). ',
	OPENED_STORE_BLD_CNT COMMENT 'THE OPEN STORES COUNT ON THE GIVEN DAY (KPI 1202501)',
	OPENED_STORE_BLD_PY_CNT COMMENT 'THE OPEN STORES COUNT ON THE SAME CALENDAR_2 DATE ONE YEAR AGO (KPI 1202501)',
	OPENED_STORE_BLD_PPY_CNT COMMENT 'THE OPEN STORES COUNT ON THE SAME CALENDAR_2 DATE TWO YEARS AGO (KPI 1202501)',
	RELOC_STORE_BLD_CNT COMMENT 'THE RELOCATED STORES COUNT ON THE GIVEN DAY (KPI 1202502)',
	RELOC_STORE_BLD_PY_CNT COMMENT 'THE RELOCATED STORES COUNT ON THE SAME CALENDAR_2 DATE ONE YEAR AGO (KPI 1202502)',
	RELOC_STORE_BLD_PPY_CNT COMMENT 'THE RELOCATED STORES COUNT ON THE SAME CALENDAR_2 DATE TWO YEARS AGO (KPI 1202502)',
	REPLACED_STORE_BLD_CNT COMMENT 'THE REPLACED STORES COUNT ON THE GIVEN DAY (KPI 1202512)',
	REPLACED_STORE_BLD_PY_CNT COMMENT 'THE REPLACED STORES COUNT ON THE SAME CALENDAR_2 DATE ONE YEAR AGO (KPI 1202512)',
	REPLACED_STORE_BLD_PPY_CNT COMMENT 'THE REPLACED STORES COUNT ON THE SAME CALENDAR_2 DATE TWO YEARS AGO (KPI 1202512)',
	CLOSED_STORE_BLD_CNT COMMENT 'THE CLOSED STORES COUNT ON THE GIVEN DAY (KPI 1204501)',
	CLOSED_STORE_BLD_PY_CNT COMMENT 'THE CLOSED STORES COUNT ON THE SAME CALENDAR_2 DATE ONE YEAR AGO (KPI 1204501)',
	CLOSED_STORE_BLD_PPY_CNT COMMENT 'THE CLOSED STORES COUNT ON THE SAME CALENDAR_2 DATE TWO YEARS AGO (KPI 1204501)',
	BLD_CONTRACT_CNT COMMENT 'THE COUNT OF BUILDING CONTRACTS SIGNED ON THE GIVEN DAY (KPI 1201503)',
	BLD_CONTRACT_PY_CNT COMMENT 'THE COUNT OF BUILDING CONTRACTS SIGNED ON THE SAME CALENDAR_2 DATE ONE YEAR AGO (KPI 1201503)',
	BLD_CONTRACT_PPY_CNT COMMENT 'THE COUNT OF BUILDING CONTRACTS SIGNED ON THE SAME CALENDAR_2 DATE TWO YEARS AGO (KPI 1201503)'
) as
WITH
ALL_STATS_ASOF_NOW AS
(
	SELECT 
		REE.REAL_ESTATE_SID
		,REE.BUS_DT AS CAL_DT
		,REE.COUNTRY_ORG_CD
		,REE.REPORTING_COUNTRY_CD
		
		,DECODE(REAL_ESTATE_EVENT_TYPE_CD, 'OP', 1, 0) 				AS OPENED_STORE_BLD_CNT --1202501  NEUERÖFFNUNG - FILIALE (ANZ.), ALL OPEN EVENTS, REGARDLESS OF THE REASON 
		,DECODE(REE.REAL_ESTATE_EVENT_REASON_CD, 'BS_OP_REL', 1, 0) AS RELOC_STORE_BLD_CNT  --1202502  UMZUG-FILIALE (ANZ.), BUIDLING OPENED ONLY BECASUE OF RELOCATION
		,DECODE(REE.REAL_ESTATE_EVENT_REASON_CD,
			'BS_OP_REL', 1, 
			'BS_OP_RCN', 1, 
			'BS_OP_MRG', 1,
			0) 														AS REPLACED_STORE_BLD_CNT --1202512  ERSATZ - FILIALE (ANZ.), ANY OPENING OF A NEW BUILDING THAT REPLACES PREV BUILDING (RELOCATION, RECONSTRUCTION, MERGE).

		,DECODE(REAL_ESTATE_EVENT_TYPE_CD, 'CL', 1, 0) 				AS CLOSED_STORE_BLD_CNT  -- 1204501	SCHLIEßUNGEN FILIALE (ANZ.) 
		,DECODE(REAL_ESTATE_EVENT_TYPE_CD, 'CS', 1, 0) 				AS BLD_CONTRACT_CNT      -- 1201503  VERTRAGSABSCHLÜSSE (ANZ.) 			
	FROM CORE_DIM.T_FACT_REAL_ESTATE_EVENT_2 REE
	WHERE REAL_ESTATE_EVENT_TYPE_CD IN ('OP', 'CL', 'CS')
		
)
-- RECORDS FROM YEAR X (2022 FOR EXAMPLE) ARE ASSOCIATED WITH X+1 (2023 FOR EXAMPLE) FOR THE PY COLS OF 2023
,PREV_STATS AS
(
    SELECT
        ASAN.REAL_ESTATE_SID
        ,PY.CAL_DT
		,PY.BUS_YEAR_DIFF
        ,ASAN.COUNTRY_ORG_CD
        ,ASAN.REPORTING_COUNTRY_CD
        
        ,SUM(OPENED_STORE_BLD_CNT) AS OPENED_STORE_BLD_CNT
        ,SUM(RELOC_STORE_BLD_CNT) AS RELOC_STORE_BLD_CNT
        ,SUM(REPLACED_STORE_BLD_CNT) AS REPLACED_STORE_BLD_CNT
		
		,SUM(CLOSED_STORE_BLD_CNT) AS CLOSED_STORE_BLD_CNT
		,SUM(BLD_CONTRACT_CNT) AS BLD_CONTRACT_CNT

    FROM ALL_STATS_ASOF_NOW ASAN 
        JOIN CORE_REL.T_CAL_DATE_ADJUSTED_RELATIONSHIP_2 PY 
                ON ASAN.CAL_DT = PY.REL_CAL_DT  -- 02.01.2022 FOR EXAMPLE
    WHERE 1=1
        AND PY.BUS_YEAR_DIFF IN (1,2)
        AND PY.CAL_DT_ADJUST_TYPE_CD = 'M'
        AND PY.CAL_DT < CURRENT_DATE
    GROUP BY
        ASAN.REAL_ESTATE_SID
        ,PY.CAL_DT
		,PY.BUS_YEAR_DIFF
        ,ASAN.COUNTRY_ORG_CD
        ,ASAN.REPORTING_COUNTRY_CD
)
SELECT 
    COALESCE(ASAN.REAL_ESTATE_SID, PY.REAL_ESTATE_SID, PPY.REAL_ESTATE_SID) AS REAL_ESTATE_SID
    ,IO_CTR.INT_ORG_SID                 									AS COUNTRY_ORG_SID
    ,COALESCE(ASAN.COUNTRY_ORG_CD, PY.COUNTRY_ORG_CD, PPY.COUNTRY_ORG_CD)   AS COUNTRY_ORG_CD 
    ,COALESCE(ASAN.REPORTING_COUNTRY_CD, PY.REPORTING_COUNTRY_CD, PPY.REPORTING_COUNTRY_CD) AS REPORTING_COUNTRY_CD
    ,COALESCE(ASAN.CAL_DT, PY.CAL_DT, PPY.CAL_DT) 							AS CAL_DT
	
	,NVL(ASAN.OPENED_STORE_BLD_CNT, 0)		AS OPENED_STORE_BLD_CNT
	,NVL(PY.OPENED_STORE_BLD_CNT, 0)		AS OPENED_STORE_BLD_PY_CNT
	,NVL(PPY.OPENED_STORE_BLD_CNT, 0)		AS OPENED_STORE_BLD_PPY_CNT
	
	,NVL(ASAN.RELOC_STORE_BLD_CNT, 0)		AS RELOC_STORE_BLD_CNT
	,NVL(PY.RELOC_STORE_BLD_CNT, 0)			AS RELOC_STORE_BLD_PY_CNT
	,NVL(PPY.RELOC_STORE_BLD_CNT, 0)		AS RELOC_STORE_BLD_PPY_CNT
	
	,NVL(ASAN.REPLACED_STORE_BLD_CNT, 0)	AS REPLACED_STORE_BLD_CNT
	,NVL(PY.REPLACED_STORE_BLD_CNT, 0) 		AS REPLACED_STORE_BLD_PY_CNT
	,NVL(PPY.REPLACED_STORE_BLD_CNT, 0)		AS REPLACED_STORE_BLD_PPY_CNT
	
	,NVL(ASAN.CLOSED_STORE_BLD_CNT, 0) 		AS CLOSED_STORE_BLD_CNT
	,NVL(PY.CLOSED_STORE_BLD_CNT, 0)		AS CLOSED_STORE_BLD_PY_CNT
	,NVL(PPY.CLOSED_STORE_BLD_CNT, 0)		AS CLOSED_STORE_BLD_PPY_CNT
	
	,NVL(ASAN.BLD_CONTRACT_CNT, 0)			AS BLD_CONTRACT_CNT
	,NVL(PY.BLD_CONTRACT_CNT, 0) 			AS BLD_CONTRACT_PY_CNT
	,NVL(PPY.BLD_CONTRACT_CNT, 0)			AS BLD_CONTRACT_PPY_CNT

FROM ALL_STATS_ASOF_NOW ASAN
			
    FULL OUTER JOIN PREV_STATS PY
            ON PY.REAL_ESTATE_SID = ASAN.REAL_ESTATE_SID
            AND PY.CAL_DT = ASAN.CAL_DT
			AND PY.BUS_YEAR_DIFF = 1
    FULL OUTER JOIN PREV_STATS PPY
            ON PPY.REAL_ESTATE_SID = NVL(ASAN.REAL_ESTATE_SID, PY.REAL_ESTATE_SID)
            AND PPY.CAL_DT = NVL(ASAN.CAL_DT, PY.CAL_DT)
			AND PPY.BUS_YEAR_DIFF = 2

    JOIN CORE_DIM.T_DIM_INTERNAL_ORGANIZATION_2 IO_CTR
			ON ASAN.COUNTRY_ORG_CD = IO_CTR.COUNTRY_ORG_CD
            AND IO_CTR.INT_ORG_TYPE_CD = 'COMPANY'
			AND IO_CTR.IS_COUNTRY_ORG_FG = TRUE
			AND IO_CTR.DWH_VALID_FG = TRUE
;