create or replace view LDL_DATA_PRODUCTION.ETL.V_FACT_TURNOVER_BY_STORE_DAY_PRODUCT_2(
	BUS_DT,
	STORE_SID,
	PROD_SID,
	SALES_VARIANT_SID,
	COUNTRY_ORG_SID,
	COUNTRY_ORG_CD,
	SALES_VARIANT_CNT,
	SALES_VARIANT_QTY,
	SALES_VARIANT_SALES_CNT,
	SALES_VARIANT_SALES_QTY,
	SALES_VARIANT_RETURN_CNT,
	SALES_VARIANT_RETURN_QTY,
	SALES_VARIANT_PERF_TOTAL_CNT,
	SALES_VARIANT_PERF_TOTAL_QTY,
	UOM_CD,
	TURNOVER_NET_VAL,
	TURNOVER_GROSS_VAL,
	SALES_NET_VAL,
	RETURN_NET_VAL,
	CURR_CD,
	DWH_CREATED_TMSP,
	DWH_UPDATED_TMSP,
	DWH_LOAD_ID,
	DWH_NODE_CD
) as
SELECT
      AGG.BUS_DT
    , AGG.STORE_SID
    , Coalesce(PRDVAR.PROD_SID, -1) AS PROD_SID
    , AGG.SALES_VARIANT_SID
    , AGG.COUNTRY_ORG_SID
    , AGG.COUNTRY_ORG_CD
    , AGG.SALES_VARIANT_CNT
    , AGG.SALES_VARIANT_QTY
    , AGG.SALES_VARIANT_SALES_CNT
    , AGG.SALES_VARIANT_SALES_QTY
    , AGG.SALES_VARIANT_RETURN_CNT
    , AGG.SALES_VARIANT_RETURN_QTY
    , CASE WHEN EXC.PROD_SID IS NULL THEN AGG.SALES_VARIANT_PERF_TOTAL_CNT  END SALES_VARIANT_PERF_TOTAL_CNT
    , CASE WHEN EXC.PROD_SID IS NULL THEN AGG.SALES_VARIANT_PERF_TOTAL_QTY  END SALES_VARIANT_PERF_TOTAL_QTY
    , AGG.UOM_CD
    , AGG.TURNOVER_NET_VAL
    , AGG.TURNOVER_GROSS_VAL
    , AGG.SALES_NET_VAL
    , AGG.RETURN_NET_VAL
    , AGG.CURR_CD
    , CURRENT_TIMESTAMP               AS DWH_CREATED_TMSP
    , CURRENT_TIMESTAMP               AS DWH_UPDATED_TMSP
    , 1                               AS DWH_LOAD_ID
    , 'CORE_REL'                      AS DWH_NODE_CD
FROM
(
    SELECT
          SRC.BUS_DT                      AS BUS_DT
        , SRC.STORE_SID                   AS STORE_SID
        , SRC.PROD_VARIANT_SID            AS SALES_VARIANT_SID
        , Any_Value(SRC.COUNTRY_ORG_SID)  AS COUNTRY_ORG_SID
        , Any_Value(SRC.COUNTRY_ORG_CD)   AS COUNTRY_ORG_CD
        , SUM(SRC.PROD_VARIANT_CNT)       AS SALES_VARIANT_CNT
        , SUM(SRC.PROD_VARIANT_QTY)       AS SALES_VARIANT_QTY
        , SUM(CASE WHEN PROD_RETAIL_LINE_TYPE_CD IN ('S', 'SD', 'D', 'RD') THEN PROD_VARIANT_CNT END) AS SALES_VARIANT_SALES_CNT
        , SUM(CASE WHEN PROD_RETAIL_LINE_TYPE_CD IN ('S', 'SD', 'D', 'RD') THEN PROD_VARIANT_QTY END) AS SALES_VARIANT_SALES_QTY
        , SUM(CASE WHEN PROD_RETAIL_LINE_TYPE_CD IN ('R')                  THEN PROD_VARIANT_CNT END) AS SALES_VARIANT_RETURN_CNT
        , SUM(CASE WHEN PROD_RETAIL_LINE_TYPE_CD IN ('R')                  THEN PROD_VARIANT_QTY END) AS SALES_VARIANT_RETURN_QTY
        , Any_Value(COALESCE(SRC.UOM_CD, '@')) AS UOM_CD
        , SUM(SRC.RETAIL_LINE_NET_VAL)    AS TURNOVER_NET_VAL
        , SUM(SRC.RETAIL_LINE_GROSS_VAL)  AS TURNOVER_GROSS_VAL
        , SUM(CASE WHEN PROD_RETAIL_LINE_TYPE_CD IN ('S', 'SD', 'D', 'RD') THEN RETAIL_LINE_NET_VAL END) AS SALES_NET_VAL
        , SUM(CASE WHEN PROD_RETAIL_LINE_TYPE_CD IN ('R')                  THEN RETAIL_LINE_NET_VAL END) AS RETURN_NET_VAL
        , Any_Value(COALESCE(SRC.CURR_CD, '@')) AS CURR_CD
        , SUM(CASE WHEN (ABS(SRC.UNIT_PRICE) / ((100 + SRC.TAX_PCT) / 100)) / ER.EXCHANGE_RATE NOT BETWEEN 0.0001 AND 0.0315
                        THEN SRC.PROD_VARIANT_CNT
                        ELSE 0
              END) AS SALES_VARIANT_PERF_TOTAL_CNT
        , SUM(CASE WHEN (ABS(SRC.UNIT_PRICE) / ((100 + SRC.TAX_PCT) / 100)) / ER.EXCHANGE_RATE NOT BETWEEN 0.0001 AND 0.0315
                        THEN SRC.PROD_VARIANT_QTY
                        ELSE 0
              END) AS SALES_VARIANT_PERF_TOTAL_QTY
    FROM CORE_REL.T_PRODUCT_RETAIL_LINE_2 AS SRC
    INNER JOIN
    (
        SELECT TGT_CURR_CD, EXCHANGE_RATE
        FROM CORE_REL.T_EXCHANGE_RATE_2
        WHERE EXCHANGE_RATE_TYPE_CD = 'BEW_ISK'
          AND SRC_CURR_CD = 'EUR'
          AND DWH_VALID_FG = TRUE
    ) AS ER
    ON  SRC.CURR_CD = ER.TGT_CURR_CD
    WHERE SRC.TURNOVER_RELEVANT_FG = TRUE
      AND SRC.BUS_DT BETWEEN $min_dwh_cal_dt AND $max_dwh_cal_dt
    GROUP BY
          SRC.BUS_DT
        , SRC.STORE_SID
        , SRC.PROD_VARIANT_SID
) AS AGG
LEFT OUTER JOIN CORE_REL.T_PRODUCT_VARIANT_2 AS PRDVAR
  ON  PRDVAR.PROD_VARIANT_SID = AGG.SALES_VARIANT_SID
  AND PRDVAR.DWH_VALID_FG = TRUE
LEFT OUTER JOIN
(
    SELECT DISTINCT PPG.PROD_SID
    FROM CORE_REL.T_PRODUCT_TO_PRODUCT_GROUP_2 AS PPG
    INNER JOIN CORE_REL.T_PRODUCT_GROUP_HIERARCHY_2 AS PGH1
    ON  PPG.DWH_VALID_FG = TRUE
    AND PPG.PROD_GRP_TYPE_CD = 'IFG'
    AND PPG.PROD_GRP_SID = PGH1.PROD_GRP_SID
    AND PGH1.PROD_GRP_HIERARCHY_TYPE_CD = 'IGH'
    AND PGH1.DWH_VALID_FG = TRUE
    INNER JOIN CORE_REL.T_PRODUCT_GROUP_2 AS SIG
    ON  PGH1.PARENT_PROD_GRP_SID = SIG.PROD_GRP_SID
    AND SIG.DWH_VALID_FG = TRUE
    LEFT OUTER JOIN CORE_REL.T_PRODUCT_GROUP_HIERARCHY_2 AS PGH2
    ON  PGH1.PARENT_PROD_GRP_SID = PGH2.PROD_GRP_SID
    AND PGH2.PROD_GRP_HIERARCHY_TYPE_CD = 'IGH'
    AND PGH2.DWH_VALID_FG = TRUE
    LEFT OUTER JOIN CORE_REL.T_PRODUCT_GROUP_2 AS IGI
    ON  PGH2.PARENT_PROD_GRP_SID = IGI.PROD_GRP_SID
    AND IGI.DWH_VALID_FG = TRUE
    WHERE IGI.PROD_GRP_SID IS NULL
      AND Try_Cast(SIG.PROD_GRP_NR AS Number) <> 991 /* Ignore all except commissions from the ""Admin"" group */
) AS EXC
ON  PRDVAR.PROD_SID = EXC.PROD_SID
;