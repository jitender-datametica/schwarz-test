create or replace view LDL_DATA_PRODUCTION.FE_MSTR_TEMP.V_DIM_CASHIER_VIEW_2(
	STORE_SID,
	CASHIER_NR,
	CASHIER_DESC
) as 
WITH CASHIER_DIM (COUNTRY_ORG_CD,STORE_NR,CASHIER_NR)
AS
(  
SELECT 
DIM.COUNTRY_ORG_CD
,DIM.STORE_NR
,DIM.CASHIER_NR
FROM CORE_APP_FRAUD_DETECTION.T_CASHIER_ENCRYPTION_2 DIM
WHERE DIM.BUS_DT > '2024-12-29'
GROUP BY DIM.COUNTRY_ORG_CD,DIM.STORE_NR, DIM.CASHIER_NR
)
SELECT ORG.STORE_SID AS STORE_SID, 
       MAIN.CASHIER_NR AS CASHIER_NR,
       CURR_STORE_NR||'|' ||MAIN.CASHIER_NR AS CASHIER_DESC
FROM CASHIER_DIM MAIN
INNER JOIN FE_MSTR_APP_FRAUD_DETECTION.V_DIM_STORE_2 ORG
ON ORG.CURR_STORE_NR = MAIN.COUNTRY_ORG_CD || MAIN.STORE_NR
AND ORG.DWH_VALID_FG
AND ORG.INT_ORG_TYPE_CD = 'STORE';