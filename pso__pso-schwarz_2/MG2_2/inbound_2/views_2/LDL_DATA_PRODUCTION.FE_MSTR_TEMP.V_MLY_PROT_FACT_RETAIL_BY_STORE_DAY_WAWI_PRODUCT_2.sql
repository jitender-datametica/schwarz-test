create or replace view LDL_DATA_PRODUCTION.FE_MSTR_TEMP.V_MLY_PROT_FACT_RETAIL_BY_STORE_DAY_WAWI_PRODUCT_2(
	CAL_DT,
	STORE_SID,
	COUNTRY_ORG_SID,
	COUNTRY_ORG_CD,
	WAWI_VARIANT_SID,
	WAWI_PRODUCT_SID,
	SALES_CNT,
	SALES_QTY,
	RETURN_CNT,
	RETURN_QTY,
	PERF_ADJ_SALES_CNT,
	PERF_ADJ_SALES_QTY,
	PERF_ADJ_RETURN_CNT,
	PERF_ADJ_RETURN_QTY,
	UOM_CD,
	CASH_REGISTER_SALES_NET_VAL,
	CASH_REGISTER_SALES_GROSS_VAL,
	CASH_REGISTER_RETURN_NET_VAL,
	CASH_REGISTER_RETURN_GROSS_VAL,
	DWH_CREATED_TMSP,
	DWH_UPDATED_TMSP,
	DWH_LOAD_ID,
	DWH_NODE_CD,
	PERF_ADJ_SALES_NET_VAL,
	PERF_ADJ_RETURN_NET_VAL,
	CURR_CD,
	CURR_GROUP_FG,
	LOCAL_GROUP_FG
) as  SELECT 
main.BUS_DT
,main.STORE_SID
,main.COUNTRY_ORG_SID
,main.COUNTRY_ORG_CD
,main.WAWI_VARIANT_SID
,main.WAWI_PRODUCT_SID
,main.SALES_CNT
,main.SALES_QTY
,main.RETURN_CNT
,main.RETURN_QTY
,main.PERF_ADJ_SALES_CNT
,main.PERF_ADJ_SALES_QTY
,main.PERF_ADJ_RETURN_CNT
,main.PERF_ADJ_RETURN_QTY
,main.UOM_CD
,main.CASH_REGISTER_SALES_NET_VAL/fer.exchange_rate
,main.CASH_REGISTER_SALES_GROSS_VAL/fer.exchange_rate
,main.CASH_REGISTER_RETURN_NET_VAL/fer.exchange_rate
,main.CASH_REGISTER_RETURN_GROSS_VAL/fer.exchange_rate
,main.DWH_CREATED_TMSP
,main.DWH_UPDATED_TMSP
,main.DWH_LOAD_ID
,main.DWH_NODE_CD
,main.PERF_ADJ_SALES_NET_VAL/fer.exchange_rate
,main.PERF_ADJ_RETURN_NET_VAL/fer.exchange_rate
,fer.src_curr_cd AS curr_cd
,DECODE(fer.src_curr_cd,'EUR',1,0) AS curr_group_fg
,DECODE(fer.src_curr_cd,fer.tgt_curr_cd,1,0) AS curr_local_fg
FROM  FE_MSTR_TEMP.T_MLY_PROT_FACT_RETAIL_BY_STORE_DAY_WAWI_PRODUCT_2 main
INNER JOIN  CORE_DIM.T_FACT_EXCHANGE_RATE_2 fer
ON main.curr_cd = fer.tgt_curr_cd
WHERE exchange_rate_type_cd = 'BEW_ISK'
AND (fer.src_curr_cd = 'EUR' OR fer.src_curr_cd = fer.tgt_curr_cd)
AND fer.active_fg = TRUE;