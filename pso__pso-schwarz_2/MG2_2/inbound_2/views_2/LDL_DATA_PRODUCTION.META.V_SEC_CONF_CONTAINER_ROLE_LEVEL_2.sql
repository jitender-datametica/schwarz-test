create or replace view LDL_DATA_PRODUCTION.META.V_SEC_CONF_CONTAINER_ROLE_LEVEL_2(
	ORG_UNIT_LEVEL_NAME,
	RESSORT_NAME,
	BUSINESS_ROLE_NAME,
	IDP_CONTAINER_TYPE_CD,
	CONTAINER_NAME,
	TECHNICAL_ROLE_TYPE_CD,
	IDP_ROLE_FULL_NAME,
	TECHNICAL_ROLE_NAME,
	WORKFORCE_ID,
	ROLE_LABEL_DESCRIPTION
) as
SELECT
     cont_role.ORG_UNIT_LEVEL_NAME
    ,cont_role.RESSORT_NAME
    ,cont_role.BUSINESS_ROLE_NAME
    ,cont.IDP_CONTAINER_TYPE_CD
    ,cont.CONTAINER_NAME
    ,cont_role.TECHNICAL_ROLE_TYPE_CD
    ,CONCAT(
             cont.CONTAINER_NAME 
            ,cont.CONTAINER_NAME_SEPARATOR      
            ,cont_role.TECHNICAL_ROLE_NAME
    ) AS IDP_ROLE_FULL_NAME
    ,cont_role.TECHNICAL_ROLE_NAME
    ,idp_workf.WORKFORCE_ID
    ,cont_role.ROLE_DESCR AS ROLE_LABEL_DESCRIPTION
FROM            META.T_SEC_CONF_COMPONENTS_CONTAINER_ROLE_2 cont_role
LEFT OUTER JOIN META.T_SEC_CONF_CONTAINER_2 cont
            ON  cont.TECHNICAL_ROLE_TYPE_CD = cont_role.TECHNICAL_ROLE_TYPE_CD
LEFT OUTER JOIN META.T_SEC_CONF_IDP_ROLE_WORKFORCEID_2 idp_workf
            ON  idp_workf.IDP_FULL_ROLE_NAME = CONCAT(cont.CONTAINER_NAME, cont.CONTAINER_NAME_SEPARATOR, cont_role.TECHNICAL_ROLE_NAME)
WHERE  cont.TECHNICAL_ROLE_TYPE_CD IN ('container data', 'container func')
;