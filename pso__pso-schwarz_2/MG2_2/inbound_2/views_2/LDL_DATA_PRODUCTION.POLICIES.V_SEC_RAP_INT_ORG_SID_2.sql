create or replace view LDL_DATA_PRODUCTION.POLICIES.V_SEC_RAP_INT_ORG_SID_2(
	NAME,
	INT_ORG_SID
) as

    SELECT DISTINCT
         
         COUNTRY.ROLE_NAME::VARCHAR AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_CORE_ISO_COUNTRY_CD_2 COUNTRY_2
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_2 HIERARCHY_2 ON HIERARCHY.ISO_COUNTRY_CD = COUNTRY.ISO_COUNTRY_CD

    UNION ALL

    SELECT DISTINCT
         
         COMPANY.ROLE_NAME::VARCHAR AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_CORE_SALES_COMPANY_NR_2 COMPANY 
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_2 HIERARCHY_2 ON HIERARCHY.SALES_COMPANY_NR = COMPANY.SALES_COMPANY_NR

    UNION ALL

    SELECT DISTINCT 
         ACCTMGR.LOGIN_NAME_EMAIL::VARCHAR AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_ACCOUNTMANAGER_2 ACCTMGR
    LEFT OUTER JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_2 HIERARCHY_2 ON ACCTMGR.ACCT_MGR_DISTRICT_SID = HIERARCHY.ACCT_MGR_DISTRICT_SID

    UNION ALL

    SELECT DISTINCT
         SLSMGR.LOGIN_NAME_EMAIL::VARCHAR AS NAME
        ,HIERARCHY.INT_ORG_SID::VARCHAR AS INT_ORG_SID
    FROM POLICIES.T_SEC_RAP_SALESMANAGER_2 SLSMGR
    JOIN POLICIES.T_SEC_RAP_ORG_HIERARCHY_2 HIERARCHY_2 
        ON SLSMGR.SALES_MGR_DISTRICT_SID = HIERARCHY.SALES_MGR_DISTRICT_SID
    WHERE HIERARCHY.INT_ORG_TYPE_CD = 'STORE'
;