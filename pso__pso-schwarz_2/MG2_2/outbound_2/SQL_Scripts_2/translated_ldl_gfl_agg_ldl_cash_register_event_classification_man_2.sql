         AND RE.STORE_SID = S.STORE_SID
         AND RE.BUS_DT = S.BUS_DT
        INNER JOIN LDL_DATA_PRODUCTION.CORE_APP_FRAUD_DETECTION.T_CASHIER_ENCRYPTION_2 AS CE ON RE.CASHIER_HASH = CE.CASHIER_HASH
         AND RE.BUS_DT = CE.BUS_DT
        INNER JOIN LDL_DATA_PRODUCTION.CORE_REL.T_CASH_REGISTER_2 AS CR ON CR.CASH_REGISTER_SID = RE.CASH_REGISTER_SID
         AND CR.DWH_VALID_FG = true
