        RE.RETAIL_EVENT_SID AS CASH_REGISTER_EVENT_SID,
        RE.CASH_REGISTER_EVENT_NR,
        RE.COUNTRY_ORG_CD,
        RE.STORE_SID,
        RE.BUS_DT,
