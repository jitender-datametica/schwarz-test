       AND RE.TURNOVER_RELEVANT_FG = true /* this eliminates cancelled (aborted) and suspended receipts too*/
       AND PRL.TURNOVER_RELEVANT_FG = true
      GROUP BY 1
      HAVING RETURNED_DEPOSIT_LINE_CNT + SOLD_DEPOSIT_LINE_CNT > NUMERIC '0'
