-- 1.1 Make temp tables will all relavant RetailEvents (T_RETAIL_EVENT_2) and all relevant line (T_PRODUCT_RETAIL_LINE_2)
-- 	these temp tables will be used 8-9 later so we save a lot of time that could be wasted querying these big tables
