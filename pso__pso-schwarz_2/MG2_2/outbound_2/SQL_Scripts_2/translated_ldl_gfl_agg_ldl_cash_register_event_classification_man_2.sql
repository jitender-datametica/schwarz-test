        sum(CASE
           PRL.PROD_RETAIL_LINE_TYPE_CD
          WHEN 'SD' THEN PRL.RETAIL_LINE_GROSS_VAL - PRL.RETAIL_LINE_VAT_VAL
          ELSE NUMERIC '0'
        END) AS DEPOSIT_SALES_NET_VAL,
        abs(sum(CASE
           PRL.PROD_RETAIL_LINE_TYPE_CD
          WHEN 'D' THEN PRL.RETAIL_LINE_GROSS_VAL - PRL.RETAIL_LINE_VAT_VAL
          ELSE NUMERIC '0'
