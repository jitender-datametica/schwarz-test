  AS
    SELECT
        -- enriched with these five additional cols
        RE.RETAIL_EVENT_SID,
        RE.CASH_REGISTER_EVENT_NR,
        RE.EVENT_END_TMSP,
        RE.BUS_DT,
        RE.STORE_SID,
        RE.COUNTRY_ORG_CD,
        RE.CASH_REGISTER_SID,
        RE.CASH_REGISTER_TYPE_CD,
        RE.CASHIER_HASH,
        RE.CUST_SID,
        RE.CUST_IDENT_TYPE_CD,
        RE.RETAIL_EVENT_TYPE_CD,
