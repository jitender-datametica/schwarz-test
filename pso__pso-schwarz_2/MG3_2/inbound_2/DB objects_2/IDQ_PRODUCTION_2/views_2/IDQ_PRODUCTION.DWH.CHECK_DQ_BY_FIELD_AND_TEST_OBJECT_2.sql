create or replace view IDQ_PRODUCTION.DWH.CHECK_DQ_BY_FIELD_AND_TEST_OBJECT_2(
	CHECK_DQ_BY_FIELD_AND_TEST_OBJECT_ID,
	IDQ_TEST_OBJECT_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	REF_FIELD_ID,
	CHECK_DQ_BY_FIELD_AND_TEST_OBJECT_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	PENALTY,
	SCORE,
	IS_USABLE,
	IS_RELEVANT,
	REF_SOURCE_SYSTEM_ID
) as
SELECT 1                              AS CHECK_DQ_BY_FIELD_AND_TEST_OBJECT_ID
      ,CDFTO.TEST_OBJECT_ID         AS IDQ_TEST_OBJECT_ID
      ,CDFTO.BRANCH_ID              AS REF_BRANCH_ID
      ,CDFTO.COUNTRY_ID             AS REF_COUNTRY_ID
      ,CDFTO.SOURCE_SYSTEM_TYPE_ID  AS REF_SOURCE_SYSTEM_TYPE_ID
      ,CDFTO.TEST_OBJECT_TYPE_ID    AS REF_TEST_OBJECT_TYPE_ID
      ,CDFTO.FIELD_ID               AS REF_FIELD_ID
      ,CDFTO.CALCULATION_TIME       AS CHECK_DQ_BY_FIELD_AND_TEST_OBJECT_CALCULATION_TIME
      ,CDFTO.CALCULATION_DAY_ID     AS REF_TIME_CALCULATION_DAY_ID
      ,CDFTO.PENALTY                AS PENALTY
      ,CDFTO.SCORE                  AS SCORE
      ,CDFTO.IS_USABLE              AS IS_USABLE
      ,ITO.IS_RELEVANT              AS IS_RELEVANT
      ,ITO.SOURCE_SYSTEM_ID         AS REF_SOURCE_SYSTEM_ID
FROM idq_results.CHECK_DQ_BY_FIELD_AND_TEST_OBJECT_CURRENT_2 CDFTO
INNER JOIN idq_results.IDQ_TEST_OBJECT_2 ITO
    ON CDFTO.TEST_OBJECT_ID = ITO.ID
;