create or replace view IDQ_PRODUCTION.DWH.IDQ_ADDINFO_WAWI_ART_2(
	IDQ_ADDINFO_WAWI_ART_ID,
	IDQ_TEST_OBJECT_ID,
	REF_BRANCH_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	ARTNRVIER,
	ARTIKELNR,
	C215_INT_ITEMNR,
	BEZ_LANG,
	DEUTSCHTEXT,
	ARTGRUPNR_BESCHREIBUNG,
	ARTIKEL_FAMILIE,
	C270_LISTDESCRIPT,
	C0603_REASON_FOR_RELEVANCE,
	IS_RELEVANT,
	ARTGRUPNR_DERIVED
) as
SELECT ID                         AS IDQ_ADDINFO_WAWI_ART_ID
      ,TEST_OBJECT_ID				AS IDQ_TEST_OBJECT_ID
      ,BRANCH_ID					AS REF_BRANCH_ID
      ,SOURCE_SYSTEM_PRIMARY_KEY	AS SOURCE_SYSTEM_PRIMARY_KEY
      ,SOURCE_SYSTEM_ID			AS SOURCE_SYSTEM_ID
      ,COUNTRY_ID					AS REF_COUNTRY_ID
      ,ARTNRVIER					AS ARTNRVIER
      ,ARTIKELNR					AS ARTIKELNR
      ,C215_INT_ITEMNR			AS C215_INT_ITEMNR
      ,BEZ_LANG					AS BEZ_LANG
      ,DEUTSCHTEXT				AS DEUTSCHTEXT
      ,ARTGRUPNR_BESCHREIBUNG		AS ARTGRUPNR_BESCHREIBUNG
      ,ARTIKEL_FAMILIE			AS ARTIKEL_FAMILIE
      ,C270_LISTDESCRIPT			AS C270_LISTDESCRIPT
      ,C0603_REASON_FOR_RELEVANCE	AS C0603_REASON_FOR_RELEVANCE
      ,IS_RELEVANT				AS IS_RELEVANT
	  --Extracting the ARTGRUPNR from ARTIKEL_FAMILIE:
	  ,CASE WHEN 
			CHARINDEX('.', ARTIKEL_FAMILIE) > 0 then LEFT(ARTIKEL_FAMILIE, CHARINDEX('.', ARTIKEL_FAMILIE)-1) 
			ELSE ARTIKEL_FAMILIE END 							
			AS ARTGRUPNR_DERIVED
FROM idq_results.IDQ_ADDINFO_WAWI_ART_2
 ;