create or replace view IDQ_PRODUCTION.DWH.REF_EXCLUDE_2(
	REF_EXCLUDE_ID,
	REF_RULE_ID,
	REF_BRANCH_ID,
	SOURCE_SYSTEM_PRIMARY_KEY,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_TEST_OBJECT_TYPE_ID,
	INSERTED_BY,
	EXCLUDE_REASON,
	EXCLUDE_FLAG,
	INSERTED_AT,
	IDQ_TEST_OBJECT_ID,
	UNDONE_AT
) as
SELECT REX.ID                         AS REF_EXCLUDE_ID
      ,REX.RULE_ID                    AS REF_RULE_ID
      ,REX.BRANCH_ID                  AS REF_BRANCH_ID
      ,REX.SOURCE_SYSTEM_PRIMARY_KEY  AS SOURCE_SYSTEM_PRIMARY_KEY
      ,REX.SOURCE_SYSTEM_ID           AS REF_SOURCE_SYSTEM_ID
      ,REX.COUNTRY_ID                 AS REF_COUNTRY_ID
      ,REX.TEST_OBJECT_TYPE_ID        AS REF_TEST_OBJECT_TYPE_ID
      ,REX.INSERTED_BY                AS INSERTED_BY
      ,REX.EXCLUDE_REASON             AS EXCLUDE_REASON
      ,REX.EXCLUDE_FLAG               AS EXCLUDE_FLAG
      ,REX.INSERTED_AT                AS INSERTED_AT
	  ,REX.TEST_OBJECT_ID				AS IDQ_TEST_OBJECT_ID
	  ,REX.UNDONE_AT                  AS UNDONE_AT	   
FROM  idq_results.REF_EXCLUDE_2 REX
;