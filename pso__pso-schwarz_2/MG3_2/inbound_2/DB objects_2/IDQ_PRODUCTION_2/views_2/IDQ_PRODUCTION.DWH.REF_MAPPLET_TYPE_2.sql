create or replace view IDQ_PRODUCTION.DWH.REF_MAPPLET_TYPE_2(
	REF_MAPPLET_TYPE_ID,
	MAPPLET_TYPE_TECHNICAL_NAME,
	TYPE_PREFIX,
	MAPPLET_TYPE_NAME,
	MAPPLET_TYPE_NAME_DE,
	MAPPLET_TYPE_NAME_EN
) as
SELECT ID                   AS REF_MAPPLET_TYPE_ID
      ,NAME                 AS MAPPLET_TYPE_TECHNICAL_NAME
      ,TYPE_PREFIX          AS TYPE_PREFIX
      ,NAME	              AS MAPPLET_TYPE_NAME
      ,NAME	              AS MAPPLET_TYPE_NAME_DE
      ,NAME	              AS MAPPLET_TYPE_NAME_EN
FROM idq_results.REF_MAPPLET_TYPE_2
;