create or replace view IDQ_PRODUCTION.DWH.REF_NOTIFICATION_2(
	REF_NOTIFICATION_ID,
	TECHNICAL_NAME,
	NAME,
	NAME_DE,
	NAME_EN,
	DESCRIPTION,
	DESCRIPTION_DE,
	DESCRIPTION_EN
) as
SELECT 	ID 				AS REF_NOTIFICATION_ID
		,TECHNICAL_NAME 	AS TECHNICAL_NAME
		,NAME_DE 			AS NAME
		,NAME_DE			AS NAME_DE
		,NAME_EN			AS NAME_EN
		,DESCRIPTION_DE	AS DESCRIPTION
		,DESCRIPTION_DE	AS DESCRIPTION_DE
		,DESCRIPTION_EN 	AS DESCRIPTION_EN
FROM idq_results.REF_NOTIFICATION_2;