create or replace view IDQ_PRODUCTION.DWH.REF_RELEVANCE_DEFINITION_2(
	REF_RELEVANCE_DEFINITION_ID,
	RELEVANCE_DEFINITION_TECHNICAL_NAME,
	REF_BRANCH_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	RELEVANCE_DEFINITION_NAME,
	RELEVANCE_DEFINITION_NAME_DE,
	RELEVANCE_DEFINITION_NAME_EN
) as
SELECT ID                      AS REF_RELEVANCE_DEFINITION_ID
      ,NAME                    AS RELEVANCE_DEFINITION_TECHNICAL_NAME
      ,BRANCH_ID    		     AS REF_BRANCH_ID
	  ,SOURCE_SYSTEM_TYPE_ID   AS REF_SOURCE_SYSTEM_TYPE_ID
	  ,TEST_OBJECT_TYPE_ID     AS REF_TEST_OBJECT_TYPE_ID
      ,NAME       			 AS RELEVANCE_DEFINITION_NAME
      ,NAME    				 AS RELEVANCE_DEFINITION_NAME_DE
      ,NAME   				 AS RELEVANCE_DEFINITION_NAME_EN
FROM idq_results.REF_RELEVANCE_DEFINITION_2 
;