create or replace view IDQ_PRODUCTION.DWH.REPORTING_FIELD_INFO_2(
	REPORTING_FIELD_INFO_ID,
	REPORTING_TEST_RESULT_ID,
	IDQ_TEST_OBJECT_ID,
	REF_RULE_ID,
	ADDITIONAL_INFO,
	ADDITIONAL_INFO_DE,
	ADDITIONAL_INFO_EN,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_TEST_OBJECT_TYPE_ID,
	REF_DIMENSION_ID,
	REF_SOURCE_SYSTEM_ID
) as
SELECT 
	10000 * Cast(RFI.TEST_OBJECT_ID as BigInt)+ RFI.RULE_ID AS REPORTING_FIELD_INFO_ID
      ,RTR.REPORTING_TEST_RESULT_ID AS REPORTING_TEST_RESULT_ID
      ,RFI.TEST_OBJECT_ID           AS IDQ_TEST_OBJECT_ID
      ,RFI.RULE_ID                  AS REF_RULE_ID
      ,RFI.ADDITIONAL_INFO_DE       AS ADDITIONAL_INFO
      ,RFI.ADDITIONAL_INFO_DE       AS ADDITIONAL_INFO_DE
      ,RFI.ADDITIONAL_INFO_EN       AS ADDITIONAL_INFO_EN
      ,RSS.SOURCE_SYSTEM_TYPE_ID    AS REF_SOURCE_SYSTEM_TYPE_ID
      ,ITO.BRANCH_ID                AS REF_BRANCH_ID
      ,ITO.COUNTRY_ID               AS REF_COUNTRY_ID
      ,ITO.TEST_OBJECT_TYPE_ID      AS REF_TEST_OBJECT_TYPE_ID
	  ,RR.DIMENSION_ID              AS REF_DIMENSION_ID
      ,ITO.SOURCE_SYSTEM_ID         AS REF_SOURCE_SYSTEM_ID
FROM idq_results.REPORTING_DQ_BY_FIELD_CURRENT_2 RFI
INNER JOIN DWH.REPORTING_TEST_RESULT_2 RTR
  ON RFI.TEST_OBJECT_ID = RTR.IDQ_TEST_OBJECT_ID AND RFI.RULE_ID = RTR.REF_RULE_ID
INNER JOIN idq_results.IDQ_TEST_OBJECT_2 ITO
  ON RFI.TEST_OBJECT_ID = ITO.ID
INNER JOIN idq_results.REF_SOURCE_SYSTEM_2 RSS
  ON ITO.SOURCE_SYSTEM_ID = RSS.ID
INNER JOIN idq_results.REF_RULE_2 RR 
  ON RFI.RULE_ID = RR.ID
 ;