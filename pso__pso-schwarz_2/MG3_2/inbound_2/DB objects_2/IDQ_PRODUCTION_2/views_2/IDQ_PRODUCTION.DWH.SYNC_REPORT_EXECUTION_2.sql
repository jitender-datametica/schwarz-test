create or replace view IDQ_PRODUCTION.DWH.SYNC_REPORT_EXECUTION_2(
	SYNC_REPORT_EXECUTION_ID,
	REF_SYNC_REPORT_DEFINITION_ID,
	REF_COUNTRY_ID,
	SYNC_REPORT_EXECUTION_CALCULATION_TIME,
	LEADING_AMOUNT,
	DEPENDENT_AMOUNT,
	MATCHES_AMOUNT,
	AMBIGUOUS_AMOUNT,
	MISSING_AMOUNT,
	OVERFLOW_AMOUNT,
	UNCOMPLETELY_MATCHED_AMOUNT,
	AVG_SCORE_MATCHES,
	SYNC_REPORT_EXECUTION_IS_CURRENT,
	REF_TEST_OBJECT_TYPE_ID,
	LEADING_SYSTEM_ID,
	DEPENDENT_SYSTEM_ID
) as
SELECT SRE.ID                          AS SYNC_REPORT_EXECUTION_ID
      ,SRE.SYNC_REPORT_DEFINITION_ID   AS REF_SYNC_REPORT_DEFINITION_ID
      ,SRE.COUNTRY_ID                  AS REF_COUNTRY_ID
      ,SRE.TEST_TIME                   AS SYNC_REPORT_EXECUTION_CALCULATION_TIME
      ,SRE.LEADING_AMOUNT              AS LEADING_AMOUNT
      ,SRE.DEPENDENT_AMOUNT            AS DEPENDENT_AMOUNT
      ,SRE.MATCHES_AMOUNT              AS MATCHES_AMOUNT
      ,SRE.AMBIGUOUS_AMOUNT            AS AMBIGUOUS_AMOUNT
      ,SRE.MISSING_AMOUNT              AS MISSING_AMOUNT
      ,SRE.OVERFLOW_AMOUNT             AS OVERFLOW_AMOUNT
      ,SRE.UNCOMPLETELY_MATCHED_AMOUNT AS UNCOMPLETELY_MATCHED_AMOUNT
      ,SRE.AVG_SCORE_MATCHES           AS AVG_SCORE_MATCHES
      ,SRE.IS_CURRENT                  AS SYNC_REPORT_EXECUTION_IS_CURRENT
      ,RSRD.TEST_OBJECT_TYPE_ID        AS REF_TEST_OBJECT_TYPE_ID
      ,RSRD.LEADING_SYSTEM_ID          AS LEADING_SYSTEM_ID
      ,RSRD.DEPENDENT_SYSTEM_ID        AS DEPENDENT_SYSTEM_ID
FROM idq_results.SYNC_REPORT_EXECUTION_2 SRE
INNER JOIN idq_results.REF_SYNC_REPORT_DEFINITION_2 RSRD
 ON SRE.SYNC_REPORT_DEFINITION_ID = RSRD.ID
;