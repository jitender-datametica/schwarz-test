create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_BUYERSHORTSIGN_UPDSEL_2(
	ITEMID,
	BUYERID,
	BUYERSHORTSIGN,
	BUYERSHORTSIGNNEW
) as
SELECT DISTINCT EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, 
EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID, 
EKS_CALCULATION.STMARA_EKS_ITEM.BuyerSHORTSIGN, 
EKS.EMPLOYEE.SHORTSIGN AS BuyerSHORTSIGNNew
FROM     EKS_CALCULATION.STMARA_EKS_ITEM_2 INNER JOIN
                  EKS.EMPLOYEE_2 ON EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID = EKS.EMPLOYEE.EMPLOYEEID;