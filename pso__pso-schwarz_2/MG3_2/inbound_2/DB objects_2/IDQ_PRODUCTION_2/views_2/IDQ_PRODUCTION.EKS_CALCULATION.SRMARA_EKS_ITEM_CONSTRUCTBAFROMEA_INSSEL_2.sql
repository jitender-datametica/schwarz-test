create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_CONSTRUCTBAFROMEA_INSSEL_2(
	ZACTIVE,
	ITEMID,
	BITFLAG,
	EMPLOYEEID,
	ITEMGROUPTYPEID,
	ITEMNO,
	SHORTDESC_INT,
	SHORTDESC_NAT,
	DESCRIPTION_INT,
	DESCRIPTION_NAT,
	IN_USE,
	ZLEGACYMANDT,
	ZLEGACYMATNR,
	ZLEGACYMATKL,
	ZMATKL,
	ZBFLME,
	ZBISMT,
	ZMEINS,
	ZZEINR,
	ZISVALIDBITFLAG,
	ZISIN_USE,
	ZISFOOD,
	ZISCURRENTCONTRACT,
	ZNEGOTIATINGCOUNTRY,
	ZARTICLETYPE,
	ZITEM_BA,
	ZSOURCE,
	CONSTRUCTED,
	TARGETSYSTEM,
	TARGETCLIENT,
	ZMTART,
	ZATTYP,
	ZTRAGR,
	ZBWSCL,
	ZVABME,
	ZBEGRU,
	ZMSTAE,
	ZMSTDE,
	ZTAKLV,
	ZVPREH,
	ZSPART,
	ZNTGEW,
	ZAENAM,
	ZERNAM,
	CONSTRUCTEDFROM,
	CR_LOCATIONID,
	ZLEGACYSATNR,
	ZLEGACYPMATA,
	ZINHME,
	ZINHAL,
	ZLEGACYMEINS
) as
SELECT stMARA.zActive,
         '9990000000' || stMARA.ITEMID                                       AS ITEMID,
         2                                                                             AS BITFLAG,
         stMARA.EMPLOYEEID,
         stMARA.ITEMGROUPTYPEID,
         '9990000000' || stMARA.ITEMNO                                       AS ITEMNO,
         stMARA.SHORTDESC_INT,
         stMARA.SHORTDESC_NAT,
         stMARA.DESCRIPTION_INT,
         stMARA.DESCRIPTION_NAT,
         stMARA.IN_USE,
         stMARA.zLegacyMANDT,
         '9990000000' || stMARA.ITEMNO                                       AS zLegacyMATNR,
         stMARA.zLegacyMATKL,
         stMARA.zMATKL,
         '1'                                                                           AS zBFLME,
         stMARA.zBISMT,
         stMARA.zMEINS,
         stMARA.zZEINR,
         stMARA.zIsValidBITFLAG,
         stMARA.zIsIN_USE,
         stMARA.zIsFood,
         stMARA.zIsCurrentContract,
         stMARA.zNegotiatingCountry,
         'BA'                                                                          AS zArticleType,
         '9990000000' || stMARA.ITEMID                                       AS zITEM_BA,
         stMARA.zSource,
         1                                                                             AS Constructed,
         stMARA.TargetSystem,
         stMARA.TargetClient,
         'ZBA'                                                                         AS zMTART,
         '01'                                                                          AS zATTYP,
         stMARA.zTRAGR,
         stMARA.zBWSCL,
         stMARA.zVABME,
         stMARA.zBEGRU,
         stMARA.zMSTAE,
         stMARA.zMSTDE,
         stMARA.zTAKLV,
         NULL                                                                          AS zVPREH,
         '10'                                                                          AS zSPART,
         EKS.ITEMDETAIL.NETWEIGHT                                                AS zNTGEW,
         'FF_MG_01'                                                                    AS zAENAM,
         'FF_MG_01'                                                                    AS zERNAM,
         stMARA.ITEMID                                                    AS ConstructedFrom,
         stMARA.CR_LOCATIONID,
         IFNULL(stMARA.zITEM_BA, '9990000000' || stMARA.ITEMNO) AS zLegacySATNR,
         IFNULL(stMARA.zITEM_BA, '9990000000' || stMARA.ITEMNO) AS zLegacyPMATA,
         NULL                                                                          AS zINHME,
         NULL                                                                          AS zINHAL,
         stMARA.zLegacyMEINS
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_2 as stMARA
         INNER JOIN EKS.ITEMDETAIL_2
                 ON stMARA.ITEMID = EKS.ITEMDETAIL.ITEMID
  WHERE  ( stMARA.BITFLAG = 0 )
         AND ( stMARA.zActive = 1 )
         AND ( stMARA.zIsEAhasSK IS NULL
                OR stMARA.zIsEAhasSK = 0 )
         AND ( stMARA.zIsEAhasBA IS NULL
                OR stMARA.zIsEAhasBA = 0 );