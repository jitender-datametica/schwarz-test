create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_010_2(
	LISTINGOVERVIEWID,
	SUPPLIERNO,
	RECEIVINGCOUNTRY,
	ITEMID
) as
SELECT     distinct   MAX(t1.LISTINGOVERVIEWID) AS LISTINGOVERVIEWID, t3.SUPPLIERNO, stEKS_LOCATION_1.SHORTSIGN AS RECEIVINGCOUNTRY, t7.ITEMID
                           
FROM                     EKS.LISTINGOVERVIEW_2 t1_2 
                         INNER JOIN
                         EKS.CONTRACTLINK_2 t2 ON t1.LISTINGOVERVIEWID = t2.LISTINGOVERVIEWID 
                         INNER JOIN
                         EKS.SUPPLIER_2 t3 ON t1.SUPPLIERNO = t3.SUPPLIERNO 
                         INNER JOIN
                         EKS.LOCATION_2 t4 ON t1.CR_LOCATIONID = t4.LOCATIONID 
                         INNER JOIN
                         EKS.LOCATION_2 AS stEKS_LOCATION_1 ON t2.LOCATIONID = stEKS_LOCATION_1.LOCATIONID 
                         INNER JOIN
                         EKS.CONTRACTPRICEREL_2 t5 ON t2.CONTRACTLINKID = t5.CONTRACTLINKID 
                         INNER JOIN
                         EKS.BASICPRICE_2 t6 ON t5.BASICPRICEID = t6.BASICPRICEID 
                         INNER JOIN
                         EKS.LISTINGITEM_2 t7 ON t6.LISTINGITEMID = t7.LISTINGITEMID 
                         LEFT OUTER JOIN
                         EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 t8 ON t8.ID = 'DRDATE'
WHERE        
(t2.STATUSID IN (34, 86)) AND (t1.DATEUNTIL >= t8.DATE)
GROUP BY t3.SUPPLIERNO, stEKS_LOCATION_1.SHORTSIGN, t7.ITEMID;