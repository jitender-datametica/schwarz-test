create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_MATKL_ARTICLE_TYPE_SK_010_2(
	ZLEGACYMATNR,
	ZLEGACYMATKL,
	ZMATKL,
	ZLEGACYMATKLNEW,
	ZMATKLNEW
) as
SELECT     
EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATNR, 
EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL, 
EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, 
MIN(stMARA_EKS_ITEM_1.zMATKL) AS zLegacyMATKLNew, 
MIN(stMARA_EKS_ITEM_1.zMATKL) AS zMATKLNew
FROM        EKS_CALCULATION.stMARA_EKS_ITEM_2 INNER JOIN
                  EKS.ITEMSORTING_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.SORTITEMID 
                  INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_2 AS stMARA_EKS_ITEM_1 ON EKS.ITEMSORTING.ITEMID = stMARA_EKS_ITEM_1.ITEMID
WHERE     
(EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.BITFLAG = '4') AND 
(stMARA_EKS_ITEM_1.BITFLAG = '0') AND (NOT (stMARA_EKS_ITEM_1.zMATKL IS NULL))
GROUP BY EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATNR, EKS_CALCULATION.stMARA_EKS_ITEM.zLegacyMATKL, EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL;