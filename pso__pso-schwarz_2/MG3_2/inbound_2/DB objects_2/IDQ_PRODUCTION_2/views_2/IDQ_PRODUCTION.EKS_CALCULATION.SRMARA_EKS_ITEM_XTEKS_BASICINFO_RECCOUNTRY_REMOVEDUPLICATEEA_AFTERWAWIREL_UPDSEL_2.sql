create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_REMOVEDUPLICATEEA_AFTERWAWIREL_UPDSEL_2(
	LISTINGOVERVIEWID,
	CASESIZE,
	ITEMID,
	RECEIVINGCOUNTRY,
	SUPPLIERNO,
	BASICPRICEID,
	CONTRACTPRICEVALIDITYID,
	ZISVALIDCONTRACT,
	ZISVALIDCONTRACTNEW,
	SK_ITEMID
) as
SELECT EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO,
         MAX(EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.BASICPRICEID),
         MAX(EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID),
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract,
         0 AS zIsVAlidContractNew,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID
  FROM   EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_2
         INNER JOIN EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_010_2
                 ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_010.LISTINGOVERVIEWID
                    AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_010.itemid
                    AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_010.ReceivingCountry
                    AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_010.casesize
         INNER JOIN EKS.CONTRACTPRICEVALIDITY_2
                 ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID = EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID
                    AND EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_010.MaxDate <> EKS.CONTRACTPRICEVALIDITY.DATEUNTIL
  WHERE  ( EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID IS NULL )
         AND ( EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract = 1 )
    group by EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID;