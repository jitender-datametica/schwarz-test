create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_ZISVALIDCONTRACT_EA_UPDSEL_2(
	LISTINGOVERVIEWID,
	ITEMID,
	CASESIZE,
	SK_ITEMID,
	SUPPLIERNO,
	CONTRACTPRICEVALIDITYID,
	ZISVALIDCONTRACT,
	ZISVALIDCONTRACTNEW,
	DATEUNTIL,
	ADSFLG,
	VALUE,
	DATE
) as
SELECT EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SK_ITEMID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID,
         EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.zIsValidContract,
         1 AS zIsValidContractNew,
         EKS.CONTRACTPRICEVALIDITY.DATEUNTIL,
         EKS.CONTRACTPRICEVALIDITY.ADSFLG,
         P0.Value,
         P2.Date
  FROM   EKS.CONTRACTPRICEVALIDITY_2
         INNER JOIN EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_2
                 ON EKS.CONTRACTPRICEVALIDITY.CONTRACTPRICEVALIDITYID = EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 AS P0
                 ON P0.ID = 'ADSFLGCHK'
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 AS P1
                 ON P1.ID = 'ADSFLGON'
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 AS P2
                 ON P2.ID = 'VALIDITYDATE'
                    AND EKS.CONTRACTPRICEVALIDITY.DATEUNTIL >= P2.Date
         INNER JOIN EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_MAXDATEUNTIL_EA_2
                 ON EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_MAXDATEUNTIL_EA.LISTINGOVERVIEWID
                    AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_MAXDATEUNTIL_EA.itemid
                    AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_MAXDATEUNTIL_EA.ReceivingCountry
                    AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_MAXDATEUNTIL_EA.SUPPLIERNO
                    AND EKS.CONTRACTPRICEVALIDITY.DATEUNTIL = EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_MAXDATEUNTIL_EA.MAXDATEUNTIL
  WHERE  ( EKS.CONTRACTPRICEVALIDITY.ADSFLG = P0.Value )
          OR ( P1.Value = 0 );