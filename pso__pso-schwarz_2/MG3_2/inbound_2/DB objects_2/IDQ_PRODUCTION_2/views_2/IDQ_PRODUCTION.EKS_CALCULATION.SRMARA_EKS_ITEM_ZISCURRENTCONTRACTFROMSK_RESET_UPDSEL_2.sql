create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISCURRENTCONTRACTFROMSK_RESET_UPDSEL_2(
	ITEMID,
	ZLEGACYMATNR,
	ZISCURRENTCONTRACTFROMSK,
	ZISCURRENTCONTRACTFROMSKNEW
) as
SELECT EA.ITEMID,
         EA.zLegacyMATNR,
         EA.zIsCurrentContractFromSK,
         NULL AS zIsCurrentContractFromSKNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_2 AS EA
         INNER JOIN EKS_CALCULATION.SRMARA_EKS_ITEM_ZISCURRENTCONTRACTFROMSK_RESET_01_2 AS SK
                 ON EA.ITEMID = SK.ITEMID
  WHERE  ( EA.zArticleType = 'EA' )
         AND ( EA.zIsCurrentContractFromSK = 1 )
         AND ( EA.zIsCurrentContract IS NULL ) ;