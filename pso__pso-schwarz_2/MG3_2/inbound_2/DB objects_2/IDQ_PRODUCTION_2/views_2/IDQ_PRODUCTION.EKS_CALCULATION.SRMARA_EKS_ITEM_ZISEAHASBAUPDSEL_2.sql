create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISEAHASBAUPDSEL_2(
	ITEMID,
	ZISEAHASBA,
	ZISEAHASBANEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasBA,
         '1' AS zIsEAhasBANew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_2
         INNER JOIN EKS.ITEMSORTING_2
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS.ITEM_2 as Item_parent
                 ON EKS.ITEMSORTING.SORTITEMID = Item_parent.ITEMID
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zIsEAhasBA IS NULL )
         AND EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0
         and Item_parent.BITFLAG = 2;