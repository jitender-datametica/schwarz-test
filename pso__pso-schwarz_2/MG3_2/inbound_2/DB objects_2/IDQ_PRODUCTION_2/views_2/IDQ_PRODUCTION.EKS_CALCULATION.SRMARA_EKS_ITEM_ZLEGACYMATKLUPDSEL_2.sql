create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZLEGACYMATKLUPDSEL_2(
	ITEMID,
	ZLEGACYMATKL,
	ZLEGACYMATKLNEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyMATKL,
         stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC AS zLegacyMATKLNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_2
         INNER JOIN EKS.ITEMGROUPITEMREL_2
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMGROUPITEMREL.ITEMID
         INNER JOIN EKS.ITEMGRPTIMELINE_2
                 ON EKS.ITEMGROUPITEMREL.ITEMGROUPID = EKS.ITEMGRPTIMELINE.ITEMGROUPID
         INNER JOIN EKS.ITEMGRPTIMELINE_2 as stEKS_ITEMGRPTIMELINE_PARENT
                 ON EKS.ITEMGRPTIMELINE.PARENTID = stEKS_ITEMGRPTIMELINE_PARENT.ITEMGROUPID
         INNER JOIN (SELECT ITEMID, max(MODDATE) as MAX_MODDATE from EKS.ITEMGROUPITEMREL_2 group by  ITEMID) ITEMGROUPITEMREL_MAXMODDATE
                 ON EKS.ITEMGROUPITEMREL.ITEMID = ITEMGROUPITEMREL_MAXMODDATE.ITEMID
                    and
                    EKS.ITEMGROUPITEMREL.MODDATE = ITEMGROUPITEMREL_MAXMODDATE.MAX_MODDATE
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyMATKL IS NULL )
         AND ( CAST(CURRENT_DATE() as TIMESTAMP_NTZ(9)) BETWEEN EKS.ITEMGROUPITEMREL.DATEFROM AND EKS.ITEMGROUPITEMREL.DATEUNTIL )
         AND ( CAST(CURRENT_DATE() as TIMESTAMP_NTZ(9))BETWEEN EKS.ITEMGRPTIMELINE.DATEFROM AND EKS.ITEMGRPTIMELINE.DATEUNTIL )
         AND ( CAST(CURRENT_DATE() as TIMESTAMP_NTZ(9)) BETWEEN stEKS_ITEMGRPTIMELINE_PARENT.DATEFROM AND stEKS_ITEMGRPTIMELINE_PARENT.DATEUNTIL )
         ;