create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZNEGOTIATINGCOUNTRY_BAROLLUP01_2(
	ITEMID,
	ZNEGOTIATINGCOUNTRY,
	BITFLAG
) as
SELECT        stMARA_EKS_ITEM_1.ITEMID, MIN(EKS_CALCULATION.STMARA_EKS_ITEM.zNegotiatingCountry) AS zNegotiatingCountry, stMARA_EKS_ITEM_1.BITFLAG
FROM            EKS_CALCULATION.STMARA_EKS_ITEM_2 INNER JOIN
                         EKS.ITEMSORTING_2 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID INNER JOIN
                         EKS_CALCULATION.STMARA_EKS_ITEM_2 AS stMARA_EKS_ITEM_1 ON EKS.ITEMSORTING.SORTITEMID = stMARA_EKS_ITEM_1.ITEMID
WHERE        (EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 4)
GROUP BY stMARA_EKS_ITEM_1.ITEMID, stMARA_EKS_ITEM_1.BITFLAG
HAVING        (NOT (MIN(EKS_CALCULATION.STMARA_EKS_ITEM.zNegotiatingCountry) IS NULL));