create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DIFFERENT_BUYER_SEL_ALL_2(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	BA_ITEMNO,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
SELECT DISTINCT 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, 
				  EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_010.BA_ITEMNO, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description, 
                  CASE WHEN stMARA_EKS_ITEM.zIsCurrentContract = 1 THEN 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM ELSE sk.zRelevantMDM END AS zRelevantMDM, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zSource, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM     EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_020_2 
INNER JOIN
EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_010_2 ON EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_010.struc = EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_020.struc 
INNER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO = EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_010.ea_itemno 
LEFT OUTER JOIN
    (SELECT EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid, MIN(EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM) AS zRelevantMDM
     FROM  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_2 
	 INNER JOIN
        EKS_CALCULATION.stMARA_EKS_ITEM_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
        GROUP BY EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid) AS SK ON SK.itemid = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID
WHERE  (EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_010.BA_ITEMNO IS NOT NULL) OR
                  (EKS_CALCULATION.svMARA_EKS_ITEM_Different_Buyer_010.SK_ITEMNO IS NOT NULL);