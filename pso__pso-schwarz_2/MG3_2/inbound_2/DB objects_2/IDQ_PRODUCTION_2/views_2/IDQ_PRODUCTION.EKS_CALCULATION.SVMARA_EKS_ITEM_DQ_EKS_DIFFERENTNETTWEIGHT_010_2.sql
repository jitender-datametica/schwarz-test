create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DQ_EKS_DIFFERENTNETTWEIGHT_010_2(
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE,
	ZNEGOTIATINGCOUNTRY,
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	DESCRIPTION_INT,
	ZMATKL,
	ARTICLEFAMILY,
	BUYERID,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	BUYERSHORTSIGN,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	RECEIVINGCOUNTRY,
	GEBINDE_ANZAHL,
	GEBINDE_INHALT,
	GEBINDE_EINHEIT,
	GEBINDE_VERPAKUNG,
	NETWEIGHT,
	ZUSATZ_GEW_ART_INT,
	ZUSATZ_GEW_ART_NAT
) as
SELECT DISTINCT 
                  CASE WHEN EKS_CALCULATION.stMARA_EKS_ITEM.itemid IS NULL THEN 
				  stMARA_EKS_ITEM_1.zRelevantMDM 
				  ELSE EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM 
				  END
				  AS zRelevantMDM, 
				  stMARA_EKS_ITEM_1.zSource, stMARA_EKS_ITEM_1.zActive, 
                  stMARA_EKS_ITEM_1.zNegotiatingCountry, 
				  stMARA_EKS_ITEM_1.ITEMID, 
				  stMARA_EKS_ITEM_1.ITEMNO, 
				  stMARA_EKS_ITEM_1.zArticleType, 
				  stMARA_EKS_ITEM_1.DESCRIPTION_INT, 
				  stMARA_EKS_ITEM_1.zMATKL, 
                  stMARA_EKS_ITEM_1.ArticleFamily, 
				  stMARA_EKS_ITEM_1.BuyerID, 
				  stMARA_EKS_ITEM_1.BuyerFirstName, 
				  stMARA_EKS_ITEM_1.BuyerLastName, 
				  stMARA_EKS_ITEM_1.BuyerSHORTSIGN, 
				  IFNULL(EKS.SUPPLIER.SUPPLIERNO, stEKS_SUPPLIER_1.SUPPLIERNO) AS SUPPLIERNO, 
				  IFNULL(EKS.SUPPLIER.DESCRIPTION, stEKS_SUPPLIER_1.DESCRIPTION) AS SupplierDescription, 
				  IFNULL(EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ReceivingCountry, stEKS_LISTINGOVERVIEWMAX_1.ReceivingCountry) AS ReceivingCountry, 
				  EKS.ITEMDETAIL.BUNDLEFACT AS GEBINDE_ANZAHL, 
				  EKS.ITEMDETAIL.VOLUME AS GEBINDE_INHALT, 
                  ITEM_UNIT.DESCRIPTION AS GEBINDE_EINHEIT, 
				  PACKAGE_TYPE.DESCRIPTION AS GEBINDE_VERPAKUNG, 
				  EKS.ITEMDETAIL.NETWEIGHT, EKS.ITEMDETAIL.TEXT_INT AS ZUSATZ_GEW_ART_INT, 
                  EKS.ITEMDETAIL.TEXT_NAT AS ZUSATZ_GEW_ART_NAT

FROM     EKS_CALCULATION.stMARA_EKS_ITEM_2 AS stMARA_EKS_ITEM_1 
INNER JOIN
                  EKS.ITEMDETAIL_2 ON stMARA_EKS_ITEM_1.ITEMID = EKS.ITEMDETAIL.ITEMID 
LEFT OUTER JOIN
                  EKS.ITEMSORTING_2 
INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_2 ON EKS.ITEMSORTING.SORTITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID AND
				  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'SK' AND 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1 
				  ON 
                  stMARA_EKS_ITEM_1.ITEMID = EKS.ITEMSORTING.ITEMID 
LEFT OUTER JOIN
                  EKS.SUPPLIER_2 AS stEKS_SUPPLIER_1 
INNER JOIN
                  EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_2 AS stEKS_LISTINGOVERVIEWMAX_1 
				  ON 
				  stEKS_SUPPLIER_1.SUPPLIERNO = stEKS_LISTINGOVERVIEWMAX_1.SUPPLIERNO 
				  ON 
                  EKS.ITEMSORTING.SORTITEMID = stEKS_LISTINGOVERVIEWMAX_1.ITEMID 
LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_UNIT_2 AS ITEM_UNIT 
INNER JOIN
                  EKS.UNIT_2 ON ITEM_UNIT.TRANSLATIONID = EKS.UNIT.SHORTDESCID 
				  ON 
				  EKS.ITEMDETAIL.UNITID = EKS.UNIT.UNITID 
LEFT OUTER JOIN
                  EKS.PACKAGE_2 
INNER JOIN
                  EKS.TRANSLATION_INT_2 AS PACKAGE_TYPE ON EKS.PACKAGE.SHORTDESCID = PACKAGE_TYPE.TRANSLATIONID 
				  ON 
				  EKS.ITEMDETAIL.PACKAGEID = EKS.PACKAGE.PACKAGEID 
LEFT OUTER JOIN
                  EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_2
				  ON 
				  stMARA_EKS_ITEM_1.ITEMID = EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID 
LEFT OUTER JOIN
                  EKS.SUPPLIER_2 
				  ON 
				  EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO
WHERE  (stMARA_EKS_ITEM_1.zArticleType = 'EA') AND (stMARA_EKS_ITEM_1.zIsCurrentContract = 1) AND (stMARA_EKS_ITEM_1.zActive = 1) OR
       (stMARA_EKS_ITEM_1.zArticleType = 'EA') AND (stMARA_EKS_ITEM_1.zActive = 1) AND (stMARA_EKS_ITEM_1.zIsCurrentContractFromSK = 1);