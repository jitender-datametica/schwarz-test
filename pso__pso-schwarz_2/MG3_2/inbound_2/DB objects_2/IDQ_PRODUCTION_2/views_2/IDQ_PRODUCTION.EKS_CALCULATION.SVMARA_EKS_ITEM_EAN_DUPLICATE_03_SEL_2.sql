create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_EAN_DUPLICATE_03_SEL_2(
	EAN_2,
	ITEM_COUNT,
	MAX_ZMATKL,
	MIN_ZMATKL,
	COUNT_ZMATKL,
	COUNT_NEGCOUNTRY,
	BRANDTYPEID,
	ZISWAWIRELEVANT
) as
(SELECT distinct EKS.ITEMEAN.EAN_2, COUNT(DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO) AS item_count, MAX(EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL) AS max_zmatkl, MIN(EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL) AS min_zmatkl, 
                  COUNT(DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL) AS Count_zMATKL, COUNT(DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry) AS Count_NegCountry, EKS.ITEM.BRANDTYPEID, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_2 INNER JOIN
                  EKS.ITEMEAN_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMEAN.ITEMID INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid LEFT OUTER JOIN
                  EKS.ITEMDETAIL_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID INNER JOIN
                  EKS.ITEM_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEM.ITEMID
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS.ITEM.BRANDTYPEID IN (1, 4)) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) AND (EKS.ITEMDETAIL.TEXT_INT IS NULL) AND 
                  (EKS.ITEMDETAIL.TEXT_NAT IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry NOT IN ('CH', 'DE', 'AT')) OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS.ITEM.BRANDTYPEID IN (1, 4)) AND (EKS.ITEMDETAIL.TEXT_INT IS NULL) AND (EKS.ITEMDETAIL.TEXT_NAT IS NULL) AND 
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry NOT IN ('CH', 'DE', 'AT')) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1) OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS.ITEM.BRANDTYPEID IN (1, 4)) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) AND (EKS.ITEMDETAIL.TEXT_INT IS NULL) AND 
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry IN ('CH', 'DE', 'AT')) OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS.ITEM.BRANDTYPEID IN (1, 4)) AND (EKS.ITEMDETAIL.TEXT_INT IS NULL) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry IN ('CH', 'DE', 'AT')) AND 
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK = 1)
GROUP BY EKS.ITEMEAN.EAN_2, EKS.ITEM.BRANDTYPEID, EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant
HAVING (COUNT(DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO) > 1)
);