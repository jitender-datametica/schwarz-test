create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_EA_SK_BA_LINK_20_2(
	EA_ITEMID,
	EA_ITEMNO,
	EA_DESCRIPTION,
	SK_ITEMID,
	SK_ITEMNO,
	SK_DESCRIPTION,
	BA_ITEMID,
	BA_ITEMNO,
	BA_DESCRIPTION
) as
(SELECT EA.ITEMID AS EA_ITEMID, EA.ITEMNO AS EA_ITEMNO, EA.DESCRIPTION_INT AS EA_Description, NULL AS SK_ITEMID, NULL AS SK_ITEMNO,  NULL AS SK_Description, BA.ITEMID AS BA_ITEMID, 
                  BA.ITEMNO AS BA_ITEMNO, BA.DESCRIPTION_INT AS BA_Description
