                  EKS_CALCULATION.stMARA_EKS_ITEM_2 AS BA ON EABA.SORTITEMID = BA.ITEMID INNER JOIN
                  EKS_CALCULATION.stMARA_EKS_ITEM_2 AS EA ON EABA.ITEMID = EA.ITEMID
