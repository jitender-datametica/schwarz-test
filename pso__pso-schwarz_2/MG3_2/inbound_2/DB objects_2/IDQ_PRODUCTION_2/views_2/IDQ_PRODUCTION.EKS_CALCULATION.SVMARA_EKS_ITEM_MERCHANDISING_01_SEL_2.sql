create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_MERCHANDISING_01_SEL_2(
	MERCHANDISINGGROUP,
	BAITEMNUMBER
) as
SELECT zLegacyMATKL AS MerchandisingGroup, zITEM_BA AS BAItemNumber
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_2
WHERE  (zActive = 1)
GROUP BY zLegacyMATKL, zITEM_BA
HAVING (zLegacyMATKL IS NOT NULL)
ORDER BY MerchandisingGroup;