create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_MERCHANDISING_02_SEL_2(
	BAITEMNUMBER,
	MERCHANDISINGGROUP
) as
SELECT 
EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_01_Sel.BAItemNumber, 
COUNT(DISTINCT EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_01_Sel.MerchandisingGroup) AS MerchandisingGroup
FROM     
EKS_CALCULATION.stMARA_EKS_ITEM_2 
INNER JOIN
         EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_01_Sel_2 
         ON EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA = EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_01_Sel.BAItemNumber
GROUP BY EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_01_Sel.BAItemNumber
HAVING (COUNT(DISTINCT EKS_CALCULATION.svMARA_EKS_ITEM_Merchandising_01_Sel.MerchandisingGroup) > 1);