create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTGREATERGROSS_010_2(
	CONTRACT_TYPE,
	LU_HEADING,
	ZSOURCE,
	ZACTIVE,
	ZNEGOTIATINGCOUNTRY,
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	DESCRIPTION_INT,
	ZMATKL,
	ARTICLEFAMILY,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	BUYERSHORTSIGN,
	LISTINGOVERVIEWID,
	INTSUPPLIERNO,
	SUPPLIERDESCRIPTION,
	RECEIVINGCOUNTRY,
	CASESIZE,
	DECIMALCASESIZE,
	CASEGROSSWEIGHT,
	NETWEIGHT,
	SUBCASES,
	SUBCASESIZE,
	CASENETWEIGHT,
	ZISCURRENTCONTRACT,
	ZISCURRENTCONTRACTFROMSK,
	ZRELEVANTMDM
) as	SELECT DISTINCT 
                  trans_loc.DESCRIPTION AS contract_type, 
				  trans_loh.DESCRIPTION AS lu_heading, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zSource, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zActive, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
				  EKS.SUPPLIER.INTSUPPLIERNO, 
                  EKS.SUPPLIER.DESCRIPTION AS SupplierDescription, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry, 
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize,
				  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.DecimalCaseSize, 
                  EKS.ITEMWEIGHT.CASEGROSSWEIGHT, 
				  EKS.ITEMDETAIL.NETWEIGHT, 
				  EKS.BASICPRICE.SUBCASES, EKS.BASICPRICE.SUBCASESIZE,(EKS.BASICPRICE.SUBCASES
                  * EKS.BASICPRICE.SUBCASESIZE * EKS.ITEMDETAIL.NETWEIGHT) AS CaseNetweight, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract, 
				  EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContractFromSK, 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM
			FROM     EKS_CALCULATION.stMARA_EKS_ITEM_2 
			INNER JOIN
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMNO = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO 
			INNER JOIN
                  EKS.LISTINGITEM_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = EKS.LISTINGITEM.LISTINGOVERVIEWID AND EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.LISTINGITEM.ITEMID 
				  INNER JOIN
                  EKS.BASICPRICE_2 ON EKS.BASICPRICE.BASICPRICEID = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.BASICPRICEID AND EKS.BASICPRICE.LISTINGITEMID = EKS.LISTINGITEM.LISTINGITEMID 
				  INNER JOIN
                  EKS.SUPPLIER_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO 
				  INNER JOIN
                  EKS.ITEMDETAIL_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID 
				  LEFT OUTER JOIN
                  EKS.ITEMWEIGHT_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.itemid = EKS.ITEMWEIGHT.ITEMID AND 
                  EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID = EKS.ITEMWEIGHT.CONTRACTPRICEVALIDITYID 
				  LEFT OUTER JOIN
                  EKS.LISTINGOVERVIEW_2 AS list ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = list.LISTINGOVERVIEWID 
				  LEFT OUTER JOIN
                  EKS.LOHEADING_2 AS loh ON list.LOHEADINGID = loh.LOHEADINGID 
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_2 AS trans_loh ON loh.DESCRIPTIONID = trans_loh.TRANSLATIONID 
				  LEFT OUTER JOIN
                  EKS.LOCATEGORY_2 AS loc ON list.LOCATEGORYID = loc.LOCATEGORYID 
				  LEFT OUTER JOIN
                  EKS.TRANSLATION_INT_2 AS trans_loc ON loc.DESCRIPTIONID = trans_loc.TRANSLATIONID
			WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1) AND 
			(EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND 
			(LOWER(IFNULL(trans_loc.DESCRIPTION, '')) NOT LIKE '%filialbelieferung%') AND (LOWER(IFNULL(trans_loh.DESCRIPTION, '')) 
                  NOT LIKE '%dezentral%');