create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTGREATERGROSS_SKCASEGROSSWEIGHT_2(
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	LISTINGOVERVIEWID,
	CASEGROSSWEIGHT,
	CASESIZE,
	SUPPLIERNO,
	RECEIVINGCOUNTRY,
	BASICPRICEID,
	LISTINGITEMID
) as
SELECT DISTINCT 
                EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
				EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
				EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
				EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID, 
				EKS.ITEMWEIGHT.CASEGROSSWEIGHT,
				EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.casesize, 
				EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO, 
				EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ReceivingCountry, 
				EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.BASICPRICEID, 
                EKS.LISTINGITEM.LISTINGITEMID
				FROM EKS_CALCULATION.stMARA_EKS_ITEM_2 
				INNER JOIN
                EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID 
				INNER JOIN
                EKS.LISTINGITEM_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = EKS.LISTINGITEM.LISTINGOVERVIEWID AND 
                EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SK_ITEMID = EKS.LISTINGITEM.ITEMID 
				LEFT OUTER JOIN
                EKS.ITEMWEIGHT_2 ON EKS.LISTINGITEM.ITEMID = EKS.ITEMWEIGHT.ITEMID AND EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.CONTRACTPRICEVALIDITYID = EKS.ITEMWEIGHT.CONTRACTPRICEVALIDITYID
				WHERE 
				(EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'SK') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zIsCurrentContract = 1);