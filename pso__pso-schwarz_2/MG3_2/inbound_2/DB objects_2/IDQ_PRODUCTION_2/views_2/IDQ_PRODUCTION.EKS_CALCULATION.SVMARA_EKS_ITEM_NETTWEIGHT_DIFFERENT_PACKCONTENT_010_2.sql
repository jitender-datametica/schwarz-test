create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTWEIGHT_DIFFERENT_PACKCONTENT_010_2(
	ZNEGOTIATINGCOUNTRY,
	ITEMID,
	ITEMNO,
	ZARTICLETYPE,
	ZITEM_BA,
	BITFLAG,
	DESCRIPTION_INT,
	NETWEIGHT,
	ZZZ_PACK_CONT_UOM,
	ZZZ_QUANT_PACK_CONT,
	ZZZ_PACK_CONTENT,
	ZZZ_PACK_CONTENT_CONV,
	PACKAGEPACKAGING
) as
SELECT EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry, 
EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, 
EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, 
EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, 
EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA, 
EKS_CALCULATION.stMARA_EKS_ITEM.BITFLAG, 
EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT, 
EKS.ITEMDETAIL.NETWEIGHT, 
EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONT_UOM, 
EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT,
EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONTENT, 
CAST((CASE WHEN zZZ_PACK_CONT_UOM = 'KG' THEN (EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT * EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONTENT * 1000) 
ELSE EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT * EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONTENT END) AS decimal(15, 0)) AS zZZ_PACK_CONTENT_CONV, TR1.DESCRIPTION AS PackagePackaging
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_2 INNER JOIN
EKS.ITEMDETAIL_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID LEFT OUTER JOIN
EKS.PACKAGE_2 AS PKG ON PKG.PACKAGEID = EKS.ITEMDETAIL.PACKAGEID LEFT OUTER JOIN
EKS.TRANSLATION_INT_2 AS TR1 ON TR1.TRANSLATIONID = PKG.SHORTDESCID
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL) OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.Constructed IS NULL)
GROUP BY EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType, EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT, EKS.ITEMDETAIL.NETWEIGHT, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.BITFLAG, EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONT_UOM, EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONTENT, 
                  EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_QUANT_PACK_CONT, TR1.DESCRIPTION
HAVING (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONT_UOM = 'G') OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONT_UOM = 'KG') OR
                  (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zZZ_PACK_CONT_UOM = 'LB');