create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_NETTWEIGHT_DIFFERENT_PACKCONTENT_020_2(
	ZNEGOTIATINGCOUNTRY,
	ZITEM_BA,
	ITEMNO,
	ZARTICLETYPE,
	ITEMID,
	NETTWEIGHT_CALC,
	EKS_NETTWEIGHT,
	NETWEIGHT_UNITID,
	ZZZ_PACK_CONT_UOM
) as
SELECT EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.zNegotiatingCountry, 
EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.zITEM_BA, 
                  EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.ITEMNO, 
				  EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.zArticleType, 
				  EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.ITEMID, 
                  CAST(EKS.ITEMDETAIL.NETWEIGHT AS NUMBER(15, 3)) * 1000 AS NETTWEIGHT_CALC, 
				  EKS.ITEMDETAIL.NETWEIGHT AS EKS_NETTWEIGHT, EKS.ITEMDETAIL.NETWEIGHT_UNITID, 
                  EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.zZZ_PACK_CONT_UOM
FROM     EKS.ITEMDETAIL_2 
INNER JOIN
                  EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010_2 
				  ON 
				  EKS.ITEMDETAIL.ITEMID = EKS_CALCULATION.svMARA_EKS_ITEM_NettWeight_Different_PackContent_010.ITEMID;