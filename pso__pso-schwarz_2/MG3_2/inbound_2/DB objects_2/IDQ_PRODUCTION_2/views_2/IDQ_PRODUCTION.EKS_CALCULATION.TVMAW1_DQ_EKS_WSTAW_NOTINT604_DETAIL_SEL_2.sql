create or replace view IDQ_PRODUCTION.EKS_CALCULATION.TVMAW1_DQ_EKS_WSTAW_NOTINT604_DETAIL_SEL_2(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	WSTAW,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
(SELECT DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS Description,   instrastat.COMMODITYCODE AS WSTAW, EKS.SUPPLIER.INTSUPPLIERNO AS SupplierNo, EKS.SUPPLIER.DESCRIPTION AS SupplierDescription, EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.zIsWAWIRelevant AS zRelevantMDM, EKS_CALCULATION.stMARA_EKS_ITEM.zSource, EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM     (SELECT ITEMID, CASE WHEN len(INTRASTAT) = 10 AND RIGHT(INTRASTAT, 2) = '00' THEN LEFT(INTRASTAT, 8) ELSE INTRASTAT END AS COMMODITYCODE, MODDATE
FROM     EKS.ITEMINTRASTAT_2
WHERE  (INTRASTAT IS NOT NULL)) as instrastat  INNER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = instrastat.ITEMID LEFT OUTER JOIN
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMNO = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO LEFT OUTER JOIN
EKS.SUPPLIER_2 ON EKS.SUPPLIER.SUPPLIERNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO LEFT OUTER JOIN
ZSM.T604_2 ON instrastat.COMMODITYCODE = ZSM.T604.STAWN LEFT OUTER JOIN 
EKS_CALCULATION.EKS_ZSM_ExcludeList_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO = EKS_CALCULATION.EKS_ZSM_ExcludeList.ITEMNO AND ( ( EKS.SUPPLIER.INTSUPPLIERNO = EKS_CALCULATION.EKS_ZSM_ExcludeList.SUPPLIERNO ) OR ( EKS_CALCULATION.EKS_ZSM_ExcludeList.SupplierNo IS NULL ) ) AND EKS_CALCULATION.EKS_ZSM_ExcludeList.REPORTNO = '036'
WHERE  ((ZSM.T604.STAWN IS NULL) AND (instrastat.COMMODITYCODE IS NOT NULL) AND (instrastat.COMMODITYCODE <> '') AND (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1)) and  ( EKS_CALCULATION.EKS_ZSM_ExcludeList.ITEMNO IS NULL ) 

);