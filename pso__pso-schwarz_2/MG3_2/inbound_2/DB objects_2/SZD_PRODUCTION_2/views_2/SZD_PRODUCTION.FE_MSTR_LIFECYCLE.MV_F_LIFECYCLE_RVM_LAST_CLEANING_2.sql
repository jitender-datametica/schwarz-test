create or replace view SZD_PRODUCTION.FE_MSTR_LIFECYCLE.MV_F_LIFECYCLE_RVM_LAST_CLEANING_2(
	RVM_SID,
	LAST_BEGIN_OF_CLEANING_DT
) as 
SELECT 
 CORE.T_FACT_RVM_CLEANING.RVM_SID
,MAX(CORE.T_FACT_RVM_CLEANING.BEGIN_OF_CLEANING_DT) AS LAST_BEGIN_OF_CLEANING_DT
FROM 
CORE.T_FACT_RVM_CLEANING_2
GROUP BY 
CORE.T_FACT_RVM_CLEANING.RVM_SID
;