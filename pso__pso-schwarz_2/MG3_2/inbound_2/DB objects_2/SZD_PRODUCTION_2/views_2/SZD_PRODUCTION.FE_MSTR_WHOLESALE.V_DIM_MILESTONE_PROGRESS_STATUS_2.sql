create or replace view SZD_PRODUCTION.FE_MSTR_WHOLESALE.V_DIM_MILESTONE_PROGRESS_STATUS_2(
	CONTAINER_STATUS_NR_SID,
	CONTAINER_STATUS_NR_PARENT_ID,
	CONTAINER_STATUS_DESC,
	CONTAINER_STATUS_2_DESC
) as
    SELECT 
        MILESTONE_PROGRESS_DETAIL_CD AS CONTAINER_STATUS_NR_SID
        ,MILESTONE_PROGRESS_OVERALL_CD AS CONTAINER_STATUS_NR_PARENT_ID
        ,MILESTONE_PROGRESS_DETAIL_DESCR AS CONTAINER_STATUS_DESC
        ,MILESTONE_PROGRESS_OVERALL_DESCR AS CONTAINER_STATUS_2_DESC
    FROM 
        CORE.T_DIM_MILESTONE_PROGRESS_STATUS_2
;