create or replace view SZD_PRODUCTION.FE_MSTR_WHOLESALE.V_DIM_WAREHOUSE_2(
	WH_SITE_SID,
	DWH_VALID_FROM_TMSP,
	DWH_VALID_TO_TMSP,
	DWH_VALID_FG,
	WH_NAME,
	WH_SHORT_NAME,
	COUNTRY_POL_CD,
	CITY_NAME
) as 
    SELECT 
        RESOURCE_ITEM_SID AS WH_SITE_SID
        ,DWH_VALID_FROM_TMSP
        ,DWH_VALID_TO_TMSP
        ,DWH_VALID_FG
        ,WAREHOUSE_NAME AS WH_NAME
        ,WAREHOUSE_SHORT_NAME AS WH_SHORT_NAME
        ,COUNTRY_POL_CD
        ,CITY_NAME
    FROM
        CORE.T_DIM_EXTERNAL_WAREHOUSE_2
    WHERE
        DWH_VALID_FG = 1
;