create or replace view SZD_PRODUCTION.FE_MSTR_WHOLESALE.V_FACT_LOT_CONTAINER_MILESTONE_DT_CHANGED_2(
	LOT_MILESTONE_DT_CHANGED,
	CONTAINER_MILESTONE_DT_CHANGED
) as
WITH LOT_LAST_CREATED_UPDATED AS (
			SELECT MAX(MILESTONE_DT) MAX_MILESTONE_DT_NOW
				,MAX(DONE_DT) MAX_DONE_DT_NOW
				,COUNT(*) TOTAL_COUNT_NOW
			FROM CORE_REL.T_LOT_SHIPMENT_MILESTONE_2 AT(TIMESTAMP => TO_TIMESTAMP(TO_CHAR(CURRENT_DATE, 'YYYY-MM_2-DD') || ' ' || (
							SELECT CASE 
									WHEN CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP)::TIME < '10:00:00'
										THEN '04:00:00'
									ELSE '10:00:00'
									END THE_TIME
							)))
			WHERE LOT_MILESTONE_CD IN (
					'eta_in_lot'
					,'etd_in_lot'
					,'trans_ata'
					,'trans_atd'
					)
			)
		,LOT_LAST_MILESTONE_DONE_BEFORE AS (
			SELECT MAX(MILESTONE_DT) MAX_MILESTONE_DT_BEFORE
				,MAX(DONE_DT) MAX_DONE_DT_BEFORE
				,COUNT(*) TOTAL_COUNT_BEFORE
			FROM CORE_REL.T_LOT_SHIPMENT_MILESTONE_2 AT(TIMESTAMP => TO_TIMESTAMP( TO_CHAR(CURRENT_DATE -1, 'YYYY-MM_2-DD') || ' ' || '12:00:00'))
            WHERE LOT_MILESTONE_CD IN (
					'eta_in_lot'
					,'etd_in_lot'
					,'trans_ata'
					,'trans_atd'
					)
			)
		,CONTAINER_LAST_CREATED_UPDATED AS (
			SELECT MAX(MILESTONE_DT) MAX_MILESTONE_DT_NOW
				,MAX(DONE_DT) MAX_DONE_DT_NOW
				,COUNT(*) TOTAL_COUNT_NOW
			FROM CORE_REL.T_CONTAINER_SHIPMENT_MILESTONE_2 AT(TIMESTAMP => TO_TIMESTAMP(TO_CHAR(CURRENT_DATE, 'YYYY-MM_2-DD') || ' ' || (
							SELECT CASE 
									WHEN CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP)::TIME < '10:00:00'
										THEN '04:00:00'
									ELSE '10:00:00'
									END THE_TIME
							)))
			WHERE CONTAINER_MILESTONE_CD IN (
					'eu_container_pickup_pod'
					,'eu_container_arrival_domestic_terminal'
					,'eu_container_goods_in_warehouse'
					,'eu_container_return_depot'
					)
			)
		,CONTAINER_LAST_MILESTONE_DONE_BEFORE AS (
			SELECT MAX(MILESTONE_DT) MAX_MILESTONE_DT_BEFORE
				,MAX(DONE_DT) MAX_DONE_DT_BEFORE
				,COUNT(*) TOTAL_COUNT_BEFORE
			FROM CORE_REL.T_CONTAINER_SHIPMENT_MILESTONE_2 AT(TIMESTAMP => TO_TIMESTAMP(TO_CHAR(CURRENT_DATE - 1, 'YYYY-MM_2-DD') || ' ' || '12:00:00'))
			WHERE CONTAINER_MILESTONE_CD IN (
					'eu_container_pickup_pod'
					,'eu_container_arrival_domestic_terminal'
					,'eu_container_goods_in_warehouse'
					,'eu_container_return_depot'
					)
			)
		,LOT_INFO AS (
			SELECT *
			FROM LOT_LAST_CREATED_UPDATED A
				,LATERAL(SELECT * FROM LOT_LAST_MILESTONE_DONE_BEFORE)
			)
		,CONTAINER_INFO AS (
			SELECT *
			FROM CONTAINER_LAST_CREATED_UPDATED A
				,LATERAL(SELECT * FROM CONTAINER_LAST_MILESTONE_DONE_BEFORE)
			)
		,LOT_CONCLUSION AS (
			SELECT CASE 
					WHEN MAX_MILESTONE_DT_NOW > MAX_MILESTONE_DT_BEFORE
						THEN 'later then before'
					WHEN MAX_MILESTONE_DT_NOW = MAX_MILESTONE_DT_BEFORE
						THEN 'same as before'
					ELSE 'earlier than before'
					END MILESTONE_DT_CHANGED_CD
				,CASE 
					WHEN MAX_MILESTONE_DT_NOW > MAX_MILESTONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE, 'YYYY-MM_2-DD')
					WHEN MAX_MILESTONE_DT_NOW = MAX_MILESTONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE - 1, 'YYYY-MM_2-DD')
					ELSE NULL
					END NEWEST_MILESTONE_DT
				,CASE 
					WHEN MAX_DONE_DT_NOW > MAX_DONE_DT_BEFORE
						THEN 'later than before'
					WHEN MAX_DONE_DT_NOW = MAX_DONE_DT_BEFORE
						THEN 'same as before'
					ELSE 'earlier than before'
					END DONE_DT_CHANGED_CD
				,CASE 
					WHEN MAX_DONE_DT_NOW > MAX_DONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE, 'YYYY-MM_2-DD')
					WHEN MAX_DONE_DT_NOW = MAX_DONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE - 1, 'YYYY-MM_2-DD')
					ELSE NULL
					END DONE_DT_CHANGED
				,CASE 
					WHEN TOTAL_COUNT_NOW > TOTAL_COUNT_BEFORE
						THEN (TOTAL_COUNT_NOW - TOTAL_COUNT_BEFORE)
					WHEN TOTAL_COUNT_NOW = TOTAL_COUNT_BEFORE
						THEN TOTAL_COUNT_NOW
					ELSE (TOTAL_COUNT_NOW - TOTAL_COUNT_BEFORE)
					END TOTAL_COUNT_CHANGED
			FROM LOT_INFO
			)
		,CONTAINER_CONCLUSION AS (
			SELECT CASE 
					WHEN MAX_MILESTONE_DT_NOW > MAX_MILESTONE_DT_BEFORE
						THEN 'later than before'
					WHEN MAX_MILESTONE_DT_NOW = MAX_MILESTONE_DT_BEFORE
						THEN 'same as before'
					ELSE 'earlier than before'
					END MILESTONE_DT_CD
				,CASE 
					WHEN MAX_MILESTONE_DT_NOW > MAX_MILESTONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE, 'YYYY-MM_2-DD')
					WHEN MAX_MILESTONE_DT_NOW = MAX_MILESTONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE - 1, 'YYYY-MM_2-DD')
					ELSE NULL
					END MILESTONE_DT_CHANGED
				,CASE 
					WHEN MAX_DONE_DT_NOW > MAX_DONE_DT_BEFORE
						THEN 'later than before'
					WHEN MAX_DONE_DT_NOW = MAX_DONE_DT_BEFORE
						THEN 'same as before'
					ELSE 'earlier than before'
					END DONE_DT_CHANGED_CD
				,CASE 
					WHEN MAX_DONE_DT_NOW > MAX_DONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE, 'YYYY-MM_2-DD')
					WHEN MAX_DONE_DT_NOW = MAX_DONE_DT_BEFORE
						THEN TO_CHAR(CURRENT_DATE - 1, 'YYYY-MM_2-DD')
					ELSE NULL
					END DONE_DT_CHANGED
				,CASE 
					WHEN TOTAL_COUNT_NOW > TOTAL_COUNT_BEFORE
						THEN (TOTAL_COUNT_NOW - TOTAL_COUNT_BEFORE)
					WHEN TOTAL_COUNT_NOW = TOTAL_COUNT_BEFORE
						THEN TOTAL_COUNT_NOW
					ELSE (TOTAL_COUNT_NOW - TOTAL_COUNT_BEFORE)
					END TOTAL_COUNT_CHANGED
			FROM CONTAINER_INFO
			)

SELECT MAX(CASE 
			WHEN MILESTONE_SRC = 'lot'
				THEN MILESTONE_DT_CHANGED
			ELSE MILESTONE_DT_CHANGED
			END) AS LOT_MILESTONE_DT_CHANGED
	,MAX(CASE 
			WHEN MILESTONE_SRC = 'container'
				THEN MILESTONE_DT_CHANGED
			ELSE MILESTONE_DT_CHANGED
			END) AS CONTAINER_MILESTONE_DT_CHANGED
FROM (
	SELECT 'container' MILESTONE_SRC
		,CURRENT_DATE CHECKED_DT
		,(
			SELECT CASE 
					WHEN CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP)::TIME < '10:00:00'
						THEN '04:00:00'
					ELSE '10:00:00'
					END THE_TIME
			) CHECKED_TIME
		,CURRENT_DATE - 1 CHECKED_AGAINST_DT
		,'12:00:00' CHECKED_AGAINST_TIME
		,*
	FROM CONTAINER_CONCLUSION
	
	UNION ALL
	
	SELECT 'lot' MILESTONE_SRC
		,CURRENT_DATE CHECKED_DT
		,(
			SELECT CASE 
					WHEN CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP)::TIME < '10:00:00'
						THEN '04:00:00'
					ELSE '10:00:00'
					END THE_TIME
			) CHECKED_TIME
		,CURRENT_DATE - 1 CHECKED_AGAINST_DT
		,'12:00:00' CHECKED_AGAINST_TIME
		,*
	FROM LOT_CONCLUSION
	);