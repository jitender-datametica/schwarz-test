create or replace view IDQ_PRODUCTION.DWH.COMP_SCOPE_TABLE_EXECUTION_2(
	COMP_SCOPE_TABLE_EXECUTION_ID,
	COMP_SCOPE_TABLE_EXECUTION_EXECUTION_DATE,
	REF_TIME_EXECUTION_DAY_ID,
	COMP_SCOPE_EXECUTION_ID,
	REF_COMP_DEFINITION_SCOPE_TABLE_ID,
	REF_COMP_DEFINITION_SCOPE_ID,
	TABLE_LEADING,
	TABLE_DEPENDENT,
	REF_COMP_DEFINITION_ID,
	LEADING_COMP_SCOPE_ID,
	DEPENDENT_COMP_SCOPE_ID,
	LEADING_REF_SOURCE_SYSTEM_TYPE_ID,
	LEADING_REF_SOURCE_SYSTEM_ID,
	LEADING_REF_COUNTRY_ID,
	LEADING_REF_BRANCH_ID,
	LEADING_REF_TEST_OBJECT_TYPE_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,
	DEPENDENT_REF_SOURCE_SYSTEM_ID,
	DEPENDENT_REF_COUNTRY_ID,
	DEPENDENT_REF_BRANCH_ID,
	DEPENDENT_REF_TEST_OBJECT_TYPE_ID,
	LEADING_AMOUNT,
	DEPENDENT_AMOUNT,
	MATCH_AMOUNT,
	MISSING_AMOUNT,
	OVERFLOW_AMOUNT,
	AMBIGUOUS_AMOUNT,
	COMP_SCOPE_TABLE_EXECUTION_IS_CURRENT
) as

SELECT  CSTE.ID								AS COMP_SCOPE_TABLE_EXECUTION_ID,
		CSTE.EXECUTION_DATE					AS COMP_SCOPE_TABLE_EXECUTION_EXECUTION_DATE,
		CSTE.EXECUTION_DAY_ID					AS REF_TIME_EXECUTION_DAY_ID,
		CSTE.COMP_SCOPE_EXECUTION_ID			AS COMP_SCOPE_EXECUTION_ID,
		CSTE.COMP_DEFINITION_SCOPE_TABLE_ID	AS REF_COMP_DEFINITION_SCOPE_TABLE_ID,
		RCDST.COMP_DEFINITION_SCOPE_ID		AS REF_COMP_DEFINITION_SCOPE_ID,			
		RCDST.TABLE_LEADING					AS TABLE_LEADING,							
		RCDST.TABLE_DEPENDENT					AS TABLE_DEPENDENT,						
		RCDS.COMP_DEFINITION_ID				AS REF_COMP_DEFINITION_ID,				
		--REMOVED RCDS.LEADING_COMP_SCOPE_ID			AS LEADING_SCOPE_ID,
		RCDS.LEADING_COMP_SCOPE_ID			AS LEADING_COMP_SCOPE_ID,		--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		--REMOVED RCDS.DEPENDENT_COMP_SCOPE_ID			AS DEPENDENT_SCOPE_ID, 
		RCDS.DEPENDENT_COMP_SCOPE_ID			AS DEPENDENT_COMP_SCOPE_ID,	--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		RSL.SOURCE_SYSTEM_TYPE_ID				AS LEADING_REF_SOURCE_SYSTEM_TYPE_ID,		
		RSL.SOURCE_SYSTEM_ID					AS LEADING_REF_SOURCE_SYSTEM_ID,			
		RSL.COUNTRY_ID						AS LEADING_REF_COUNTRY_ID,				
		RSL.BRANCH_ID							AS LEADING_REF_BRANCH_ID,					
		RSL.TEST_OBJECT_TYPE_ID				AS LEADING_REF_TEST_OBJECT_TYPE_ID,		
		RSD.SOURCE_SYSTEM_TYPE_ID				AS DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,	
		RSD.SOURCE_SYSTEM_ID					AS DEPENDENT_REF_SOURCE_SYSTEM_ID,		
		RSD.COUNTRY_ID						AS DEPENDENT_REF_COUNTRY_ID,				
		RSD.BRANCH_ID							AS DEPENDENT_REF_BRANCH_ID,				
		RSD.TEST_OBJECT_TYPE_ID				AS DEPENDENT_REF_TEST_OBJECT_TYPE_ID,		
		CSTE.LEADING_AMOUNT					AS LEADING_AMOUNT,
		CSTE.DEPENDENT_AMOUNT					AS DEPENDENT_AMOUNT,
		CSTE.MATCH_AMOUNT						AS MATCH_AMOUNT,
		CSTE.MISSING_AMOUNT					AS MISSING_AMOUNT,
		CSTE.OVERFLOW_AMOUNT					AS OVERFLOW_AMOUNT,
		CSTE.AMBIGUOUS_AMOUNT					AS AMBIGUOUS_AMOUNT,
		1										AS COMP_SCOPE_TABLE_EXECUTION_IS_CURRENT
	FROM SYSCOMP.COMP_SCOPE_TABLE_EXECUTION_CURRENT_2 CSTE
	INNER JOIN idq_results.REF_COMP_DEFINITION_SCOPE_TABLE_2 RCDST
	   ON CSTE.COMP_DEFINITION_SCOPE_TABLE_ID = RCDST.ID
	INNER JOIN idq_results.REF_COMP_DEFINITION_SCOPE_2 RCDS
	   ON RCDST.COMP_DEFINITION_SCOPE_ID = RCDS.ID 
	INNER JOIN idq_results.REF_COMP_SCOPE_2 RSL
	   ON RCDS.LEADING_COMP_SCOPE_ID = RSL.ID
	INNER JOIN idq_results.REF_COMP_SCOPE_2 RSD
	   ON RCDS.DEPENDENT_COMP_SCOPE_ID = RSD.ID
UNION
SELECT  CSTE.ID								AS COMP_SCOPE_TABLE_EXECUTION_ID,
		CSTE.EXECUTION_DATE					AS COMP_SCOPE_TABLE_EXECUTION_EXECUTION_DATE,
		CSTE.EXECUTION_DAY_ID					AS REF_TIME_EXECUTION_DAY_ID,
		CSTE.COMP_SCOPE_EXECUTION_ID			AS COMP_SCOPE_EXECUTION_ID,
		CSTE.COMP_DEFINITION_SCOPE_TABLE_ID	AS REF_COMP_DEFINITION_SCOPE_TABLE_ID,
		RCDST.COMP_DEFINITION_SCOPE_ID		AS REF_COMP_DEFINITION_SCOPE_ID,			
		RCDST.TABLE_LEADING					AS TABLE_LEADING,							
		RCDST.TABLE_DEPENDENT					AS TABLE_DEPENDENT,						
		RCDS.COMP_DEFINITION_ID				AS REF_COMP_DEFINITION_ID,				
		--REMOVED RCDS.LEADING_COMP_SCOPE_ID			AS LEADING_SCOPE_ID, 
		RCDS.LEADING_COMP_SCOPE_ID			AS LEADING_COMP_SCOPE_ID,		--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		--REMOVED RCDS.DEPENDENT_COMP_SCOPE_ID			AS DEPENDENT_SCOPE_ID, 
		RCDS.DEPENDENT_COMP_SCOPE_ID			AS DEPENDENT_COMP_SCOPE_ID,	--new COLUMN because of name change -- renaming tbd with Sergey & KD	
		RSL.SOURCE_SYSTEM_TYPE_ID				AS LEADING_REF_SOURCE_SYSTEM_TYPE_ID,		
		RSL.SOURCE_SYSTEM_ID					AS LEADING_REF_SOURCE_SYSTEM_ID,			
		RSL.COUNTRY_ID						AS LEADING_REF_COUNTRY_ID,				
		RSL.BRANCH_ID							AS LEADING_REF_BRANCH_ID,					
		RSL.TEST_OBJECT_TYPE_ID				AS LEADING_REF_TEST_OBJECT_TYPE_ID,		
		RSD.SOURCE_SYSTEM_TYPE_ID				AS DEPENDENT_REF_SOURCE_SYSTEM_TYPE_ID,	
		RSD.SOURCE_SYSTEM_ID					AS DEPENDENT_REF_SOURCE_SYSTEM_ID,		
		RSD.COUNTRY_ID						AS DEPENDENT_REF_COUNTRY_ID,				
		RSD.BRANCH_ID							AS DEPENDENT_REF_BRANCH_ID,				
		RSD.TEST_OBJECT_TYPE_ID				AS DEPENDENT_REF_TEST_OBJECT_TYPE_ID,		
		CSTE.LEADING_AMOUNT					AS LEADING_AMOUNT,
		CSTE.DEPENDENT_AMOUNT					AS DEPENDENT_AMOUNT,
		CSTE.MATCH_AMOUNT						AS MATCH_AMOUNT,
		CSTE.MISSING_AMOUNT					AS MISSING_AMOUNT,
		CSTE.OVERFLOW_AMOUNT					AS OVERFLOW_AMOUNT,
		CSTE.AMBIGUOUS_AMOUNT					AS AMBIGUOUS_AMOUNT,
		0										AS COMP_SCOPE_TABLE_EXECUTION_IS_CURRENT
	FROM SYSCOMP.COMP_SCOPE_TABLE_EXECUTION_HISTORICAL_2 CSTE
	INNER JOIN idq_results.REF_COMP_DEFINITION_SCOPE_TABLE_2 RCDST
	   ON CSTE.COMP_DEFINITION_SCOPE_TABLE_ID = RCDST.ID
	INNER JOIN idq_results.REF_COMP_DEFINITION_SCOPE_2 RCDS
	   ON RCDST.COMP_DEFINITION_SCOPE_ID = RCDS.ID 
	INNER JOIN idq_results.REF_COMP_SCOPE_2 RSL
	   ON RCDS.LEADING_COMP_SCOPE_ID = RSL.ID
	INNER JOIN idq_results.REF_COMP_SCOPE_2 RSD
	   ON RCDS.DEPENDENT_COMP_SCOPE_ID = RSD.ID
;

