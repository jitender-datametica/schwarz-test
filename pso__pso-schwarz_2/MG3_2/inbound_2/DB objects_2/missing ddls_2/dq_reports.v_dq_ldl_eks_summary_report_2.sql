    LEFT JOIN DQ_REPORTS.EKS_EXCLUDE_2 AS t2
        ON t1.DQ = t2.RULE_ID
        AND t1.REF_COUNTRY_ID = t2.COUNTRY_ID
        AND t1.ITEMID = t2.ITEMID
        AND IFNULL(t1.LU_NUMBER, -1) = IFNULL(t2.LISTINGOVERVIEWID, -1) -- Handle NULLs consistently
    WHERE t2.RULE_ID IS NULL -- This means there was no match in EKS_EXCLUDE_2
),
GroupedDQ AS (
    -- Group the filtered data and aggregate DQ values
    SELECT
        REF_COUNTRY_ID,
        REF_SOURCE_SYSTEM_TYPE_ID,
        MAX(NEGOTIATINGCOUNTRY) AS NEGOTIATINGCOUNTRY,
        MAX(BUYERSHORTSIGN) AS BUYERSHORTSIGN,
        MAX(ARTICLEFAMILY) AS ARTICLEFAMILY,
        SUPPLIERNO,
        MAX(SUPPLIERDESCRIPTION) AS SUPPLIERDESCRIPTION,
        LU_NUMBER,
        MAX(DESCRIPTION) AS DESCRIPTION,
        ITEMNO,
        MAX(ARTICLETYPE) AS ARTICLETYPE,
        CONCAT('|', LISTAGG(DISTINCT DQ, '|') WITHIN GROUP (ORDER BY DQ), '|') AS DQ_Aggregated
    FROM FilteredDQ
    GROUP BY
        REF_COUNTRY_ID,
        REF_SOURCE_SYSTEM_TYPE_ID,
        SUPPLIERNO,
        LU_NUMBER,
        ITEMNO
