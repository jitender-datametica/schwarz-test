create or replace view DWH.REF_MAPPLET_2(
	REF_MAPPLET_ID,
	REF_MAPPLET_TYPE_ID,
	FUNCTIONAL_CODE,
	MAPPLET_TECHNICAL_NAME,
	MAPPLET_DESCRIPTION,
	MAPPLET_DESCRIPTION_DE,
	MAPPLET_DESCRIPTION_EN,
	VERSION,
	TEST_LOGIC
) as
SELECT ID                       AS REF_MAPPLET_ID
      ,MAPPLET_TYPE_ID          AS REF_MAPPLET_TYPE_ID
      ,FUNCTIONAL_CODE          AS FUNCTIONAL_CODE
      ,NAME                     AS MAPPLET_TECHNICAL_NAME
      ,DESCRIPTION_DE	          AS MAPPLET_DESCRIPTION
      ,DESCRIPTION_DE	          AS MAPPLET_DESCRIPTION_DE
      ,DESCRIPTION_EN	          AS MAPPLET_DESCRIPTION_EN
      ,VERSION	              AS VERSION
      ,TEST_LOGIC	              AS TEST_LOGIC
FROM idq_results.REF_MAPPLET_2
;