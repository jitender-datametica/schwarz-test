CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_REMOVEDUPLICATEEA_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_2 
SET  zIsValidContract = sr.zIsVAlidContractNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_RemoveDuplicateEA_UpdSel_2 AS sr
            WHERE EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID = sr.LISTINGOVERVIEWID
            AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.itemid = sr.itemid
            AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.ReceivingCountry = sr.ReceivingCountry
            AND EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY.casesize = sr.casesize;
END;
';