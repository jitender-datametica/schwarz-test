CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_XTEKS_BASICINFO_RECCOUNTRY_ZISVALIDCONTRACT_SK_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_2 
SET  zIsValidContract = sr.zIsValidContractNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_xtEKS_BASICINFO_RecCountry_zIsValidContract_SK_UpdSel_2 AS sr
WHERE XTEKS_BASICINFO_RECCOUNTRY.LISTINGOVERVIEWID = sr.LISTINGOVERVIEWID
and XTEKS_BASICINFO_RECCOUNTRY.casesize = sr.casesize
and XTEKS_BASICINFO_RECCOUNTRY.sk_itemid = sr.sk_itemid
and XTEKS_BASICINFO_RECCOUNTRY.itemid = sr.itemid
and XTEKS_BASICINFO_RECCOUNTRY.CONTRACTPRICEVALIDITYID = sr.CONTRACTPRICEVALIDITYID
and XTEKS_BASICINFO_RECCOUNTRY.SUPPLIERNO = sr.SUPPLIERNO;
END;
';