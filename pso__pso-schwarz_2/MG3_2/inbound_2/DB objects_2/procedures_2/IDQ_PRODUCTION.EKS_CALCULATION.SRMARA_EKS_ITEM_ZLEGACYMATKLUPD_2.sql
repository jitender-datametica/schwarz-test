CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZLEGACYMATKLUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_2 
SET  zLegacyMATKL = sr.zLegacyMATKLNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zLegacyMATKLUpdSel_2 AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID
;
END;
';