CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_KFL_EKNR("REF_MAIL_KFL_EKNR_ID" NUMBER(38,0), "EK_NR" VARCHAR(255), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE EKNR_exist number(38,0);
BEGIN
EKNR_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_KFL_EKNR_2 WHERE EK_NR = :EK_NR);
    IF (DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_MAIL_KFL_EKNR_2 WHERE ID = :REF_MAIL_KFL_EKNR_ID;
      --  RETURN 0;
   -- END IF;
   
    -- INSERT NEW EKNR
    elseIF (:REF_MAIL_KFL_EKNR_ID = 0 AND :DEL = 0 and EKNR_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_MAIL_KFL_EKNR_2
        (ID,EK_NR) VALUES ((select max(ID)+1 from IDQ_RESULTS.ref_mail_kfl_eknr_2),:EK_NR);
     --   RETURN 0;
    --END IF;
else 
    MERGE INTO IDQ_RESULTS.REF_MAIL_KFL_EKNR_2 AS TARGET
    USING 
    (SELECT :REF_MAIL_KFL_EKNR_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.EK_NR <> :EK_NR THEN
            UPDATE SET EK_NR = :EK_NR;

            end if;
            commit;

            return 1;
END';