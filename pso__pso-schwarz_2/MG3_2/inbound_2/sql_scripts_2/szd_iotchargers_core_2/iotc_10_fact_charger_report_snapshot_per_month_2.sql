BEGIN TRANSACTION;

DELETE FROM CORE.${TST_PREFIX}T_FACT_CHARGER_REPORT_SNAPSHOT_PER_MONTH_2;

INSERT INTO CORE.${TST_PREFIX}T_FACT_CHARGER_REPORT_SNAPSHOT_PER_MONTH_2 (REPORT_MONTH, CHARGER_PROVIDER_SYSTEM_CD, CHARGING_STATION_OWNER_PARTY_SID, REAL_ESTATE_RESOURCE_ITEM_SID, COUNTRY_LOCATION_SID, DIVISION_PARTY_SID, CHARGER_STATION_TYPE_CD, AVAILABLE_CHARGER_CNT, DWH_CREATED_TMSP, DWH_UPDATED_TMSP)
SELECT MNT.CY_MONTH,
       CHG.CHARGER_PROVIDER_SYSTEM_CD,
       COALESCE(CHG.CHARGING_STATION_OWNER_PARTY_SID, -1) AS CHARGING_STATION_OWNER_PARTY_SID,
       COALESCE(RES.RESOURCE_ITEM_SID, -1) AS REAL_ESTATE_RESOURCE_ITEM_SID,
       COALESCE(RES.COUNTRY_LOCATION_SID, -1) AS COUNTRY_LOCATION_SID,
       COALESCE(RES.DIVISION_PARTY_SID, -1) AS DIVISION_PARTY_SID,
       COALESCE(PWT.CHARGING_STATION_TYPE_CD, '-1') AS CHARGING_STATION_TYPE_CD,
       COUNT(DISTINCT CHG.RESOURCE_ITEM_SID) AS AVAILABLE_CHARGER_CNT,
       CURRENT_TIMESTAMP,
       CURRENT_TIMESTAMP
  FROM CORE_REL.T_CHARGER_2 CHG
  JOIN CORE.T_DIM_CAL_MONTH_2 MNT
    ON MNT.CY_MONTH_END_DT BETWEEN CHG.DWH_VALID_FROM_TMSP AND CHG.DWH_VALID_TO_TMSP 
  LEFT  
  JOIN CORE_REL.T_REAL_ESTATE_2 RES
    ON CHG.REAL_ESTATE_RESOURCE_ITEM_SID = RES.RESOURCE_ITEM_SID 
   AND RES.DWH_VALID_FG = TRUE
  LEFT
  JOIN(SELECT CPO.CHARGER_RESOURCE_ITEM_SID,
              MAX(PCT.POWER_TYPE_CD) AS CHARGING_STATION_TYPE_CD
         FROM CORE_REL.T_CHARGE_POINT_2 CPO
         JOIN CORE_REL.T_CHARGE_POINT_CONNECTOR_TYPE_2 PCT
           ON CPO.CHARGE_POINT_CONNECTOR_TYPE_ID = PCT.CHARGE_POINT_CONNECTOR_TYPE_ID 
        WHERE CPO.CHARGER_RESOURCE_ITEM_SID != -1  
        GROUP
           BY 1
      ) PWT
    ON CHG.RESOURCE_ITEM_SID = PWT.CHARGER_RESOURCE_ITEM_SID
 WHERE CHG.RESOURCE_ITEM_SID != -1  
   AND CURRENT_DATE > MNT.CY_MONTH_END_DT 
 GROUP
    BY 1, 2, 3, 4, 5, 6, 7
;

COMMIT;
