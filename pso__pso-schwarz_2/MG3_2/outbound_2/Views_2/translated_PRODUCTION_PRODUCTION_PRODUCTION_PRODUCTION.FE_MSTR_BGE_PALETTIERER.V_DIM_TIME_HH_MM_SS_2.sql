CREATE OR REPLACE VIEW production_production_fe_mstr_bge_palettierer.v_dim_time_hh_mm_ss_2 (tm_hh_mm_ss) AS SELECT TIME(CAST(CONCAT(SUBSTR(SUBSTR(CAST(V1.hh + 100 AS STRING), 1, 10), 2, 2), ':', SUBSTR(SUBSTR(CAST(V2.mm_2 + 100 AS STRING), 1, 10), 2, 2), ':', SUBSTR(SUBSTR(CAST(V3.sek + 100 AS STRING),
      1, 10), 2, 2)) AS DATETIME)) AS tm_hh_mm_ss
FROM (SELECT SEQ AS hh
  FROM UNNEST(GENERATE_ARRAY(0, 23)) AS SEQ) AS V1
 INNER JOIN (SELECT SEQ AS mm_2
  FROM UNNEST(GENERATE_ARRAY(0, 59)) AS SEQ) AS V2 ON TRUE
 INNER JOIN (SELECT SEQ AS sek
  FROM UNNEST(GENERATE_ARRAY(0, 59)) AS SEQ) AS V3 ON TRUE;