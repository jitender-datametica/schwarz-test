create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_AAD.MV_AAD_PAYM_TYPE_SPR_ZU_2(
	MANDANT_ID,
	KPOS_ZAHLUNG_TYP_ID,
	PAYM_TYPE_NAME,
	KPOS_ZAHLUNG_TYP_BEZ,
	KPOS_ZAHLUNG_TYP_BEZ_DE,
	KPOS_ZAHLUNG_TYP_BEZ_CZ,
	KPOS_ZAHLUNG_TYP_BEZ_SK,
	KPOS_ZAHLUNG_TYP_BEZ_HR,
	KPOS_ZAHLUNG_TYP_BEZ_PL,
	KPOS_ZAHLUNG_TYP_BEZ_RO,
	KPOS_ZAHLUNG_TYP_BEZ_BG
) as
--21.07.2023 snik: SPEC0202038 KPOS_ZAHLUNG_TYP
   SELECT
     v01.MANDANT_ID
   , v01.KPOS_ZAHLUNG_TYP_ID
   , v01.PAYM_TYPE_NAME
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END),'N/A') 					AS KPOS_ZAHLUNG_TYP_BEZ                      
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END),'N/A') 					AS KPOS_ZAHLUNG_TYP_BEZ_DE                
   ,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END), KPOS_ZAHLUNG_TYP_BEZ_DE) AS KPOS_ZAHLUNG_TYP_BEZ_CZ
   ,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END), KPOS_ZAHLUNG_TYP_BEZ_DE) AS KPOS_ZAHLUNG_TYP_BEZ_SK
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END), KPOS_ZAHLUNG_TYP_BEZ_DE) AS KPOS_ZAHLUNG_TYP_BEZ_HR
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END), KPOS_ZAHLUNG_TYP_BEZ_DE) AS KPOS_ZAHLUNG_TYP_BEZ_PL
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END), KPOS_ZAHLUNG_TYP_BEZ_DE) AS KPOS_ZAHLUNG_TYP_BEZ_RO
   ,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.KPOS_ZAHLUNG_TYP_BEZ END), KPOS_ZAHLUNG_TYP_BEZ_DE) AS KPOS_ZAHLUNG_TYP_BEZ_BG
   FROM DBP_VIEW.V_AAD_PAYM_TYPE_SPR_ZU_2 v01
   GROUP BY v01.MANDANT_ID
   , v01.KPOS_ZAHLUNG_TYP_ID
   , v01.PAYM_TYPE_NAME
;