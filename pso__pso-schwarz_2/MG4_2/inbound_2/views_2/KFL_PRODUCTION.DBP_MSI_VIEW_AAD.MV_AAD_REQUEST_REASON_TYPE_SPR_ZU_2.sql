create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_AAD.MV_AAD_REQUEST_REASON_TYPE_SPR_ZU_2(
	REQUEST_REASON_TYPE_ID,
	REQUEST_REASON_TYPE_DESCR,
	REQUEST_REASON_TYPE_DESCR_DE,
	REQUEST_REASON_TYPE_DESCR_CZ,
	REQUEST_REASON_TYPE_DESCR_SK,
	REQUEST_REASON_TYPE_DESCR_HR,
	REQUEST_REASON_TYPE_DESCR_PL,
	REQUEST_REASON_TYPE_DESCR_RO,
	REQUEST_REASON_TYPE_DESCR_BG
) as 
-- 30.06.2023 staeblern Erstellen Sprachtabelle aad_request_reason_type_spr_zu_2
SELECT 
v01.REQUEST_REASON_TYPE_ID
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.REQUEST_REASON_TYPE_DESCR END),'N/A') AS REQUEST_REASON_TYPE_DESCR                      
,COALESCE(MAX(CASE WHEN v01.spr_id =  22  THEN v01.REQUEST_REASON_TYPE_DESCR END),'N/A') AS REQUEST_REASON_TYPE_DESCR_DE                
,COALESCE(MAX(CASE WHEN v01.spr_id = 124  THEN v01.REQUEST_REASON_TYPE_DESCR END), REQUEST_REASON_TYPE_DESCR_DE) AS REQUEST_REASON_TYPE_DESCR_CZ
,COALESCE(MAX(CASE WHEN v01.spr_id = 108  THEN v01.REQUEST_REASON_TYPE_DESCR END), REQUEST_REASON_TYPE_DESCR_DE) AS REQUEST_REASON_TYPE_DESCR_SK
,COALESCE(MAX(CASE WHEN v01.spr_id =  65  THEN v01.REQUEST_REASON_TYPE_DESCR END), REQUEST_REASON_TYPE_DESCR_DE) AS REQUEST_REASON_TYPE_DESCR_HR
,COALESCE(MAX(CASE WHEN v01.spr_id =  90  THEN v01.REQUEST_REASON_TYPE_DESCR END), REQUEST_REASON_TYPE_DESCR_DE) AS REQUEST_REASON_TYPE_DESCR_PL
,COALESCE(MAX(CASE WHEN v01.spr_id =  95  THEN v01.REQUEST_REASON_TYPE_DESCR END), REQUEST_REASON_TYPE_DESCR_DE) AS REQUEST_REASON_TYPE_DESCR_RO
,COALESCE(MAX(CASE WHEN v01.spr_id =  18  THEN v01.REQUEST_REASON_TYPE_DESCR END), REQUEST_REASON_TYPE_DESCR_DE) AS REQUEST_REASON_TYPE_DESCR_BG

FROM dbp_view.v_aad_request_reason_type_spr_zu_2 v01
GROUP BY 
v01.REQUEST_REASON_TYPE_ID
UNION 
SELECT 0 AS REQUEST_REASON_TYPE_ID
,'' AS REQUEST_REASON_TYPE_DESCR                      
,'' AS REQUEST_REASON_TYPE_DESCR_DE                
,'' AS REQUEST_REASON_TYPE_DESCR_CZ
,'' AS REQUEST_REASON_TYPE_DESCR_SK
,'' AS REQUEST_REASON_TYPE_DESCR_HR
,'' AS REQUEST_REASON_TYPE_DESCR_PL
,'' AS REQUEST_REASON_TYPE_DESCR_RO
,'' AS REQUEST_REASON_TYPE_DESCR_BG
 ;