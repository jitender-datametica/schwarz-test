create or replace view KFL_PRODUCTION.DBP_MSI_VIEW_AAD.MV_KASSE_TYP_SPR_ZU_2(
	KASSE_TYP_ID,
	KASSE_TYP_BEZ_DE,
	KASSE_TYP_BEZ,
	KASSE_TYP_BEZ_CZ,
	KASSE_TYP_BEZ_SK,
	KASSE_TYP_BEZ_HR,
	KASSE_TYP_BEZ_PL,
	KASSE_TYP_BEZ_RO,
	KASSE_TYP_BEZ_BG
) as
SELECT
	 v01.KASSE_TYP_ID
	,MAX(CASE WHEN v01.spr_id =  22 THEN v01.KASSE_TYP_BEZ ELSE TRIM(KASSE_TYP_ID) END) 	AS KASSE_TYP_BEZ_de
	,KASSE_TYP_BEZ_de                                                         		AS KASSE_TYP_BEZ       
	,COALESCE(MAX(CASE WHEN v01.spr_id = 124 THEN KASSE_TYP_BEZ END), KASSE_TYP_BEZ_de) AS KASSE_TYP_BEZ_cz    
	,COALESCE(MAX(CASE WHEN v01.spr_id = 108 THEN KASSE_TYP_BEZ END), KASSE_TYP_BEZ_de) AS KASSE_TYP_BEZ_sk    
	,COALESCE(MAX(CASE WHEN v01.spr_id =  65 THEN KASSE_TYP_BEZ END), KASSE_TYP_BEZ_de) AS KASSE_TYP_BEZ_hr    
	,COALESCE(MAX(CASE WHEN v01.spr_id =  90 THEN KASSE_TYP_BEZ END), KASSE_TYP_BEZ_de) AS KASSE_TYP_BEZ_pl    
	,COALESCE(MAX(CASE WHEN v01.spr_id =  95 THEN KASSE_TYP_BEZ END), KASSE_TYP_BEZ_de) AS KASSE_TYP_BEZ_ro    
	,COALESCE(MAX(CASE WHEN v01.spr_id =  18 THEN KASSE_TYP_BEZ END), KASSE_TYP_BEZ_de) AS KASSE_TYP_BEZ_bg    

FROM DBP_V_ODS.V_KASSE_TYP_SPR_ZU_2 v01
GROUP BY v01.KASSE_TYP_ID
;