CREATE OR REPLACE VIEW kfl_production_dbp_msi_view_ios.mv_cpr_projekt_2 (projekt_id, projekt_id_lfd_nr, projekt_nr,
projekt_nr_endung, techn_platz_id, techn_platz_ebene_id, massnahme_kz, massnahme_id, cpr_kategorie_id, projekt_anlass_id
, projektart_id, cpr_projekt_gruppe_id, dat_freigabe, cpr_suchfeld, mandant_id, wup_id, cpr_filialtyp_bez, cpr_standort
, cpr_plz, cpr_str, cpr_vs, cpr_vw, region_id, land_id, markt_typ_ea, markt_typ_vp, kbl_nl_bez, cpr_betreuer_name,
objekt_planer_name, plan_verantw_kz, cpr_general_planer, cpr_projekt_steurer, cpr_projekt_langtext, pl_be_name,
pl_vertrieb_name, pl_elektro, pl_hls, gj, betrag_proj_kosten, expansion_merkmal, expansion_auftrag_id,
cpr_auftraggeber_name, investor_eigenobj, investor_name, cpr_generalunternehmer_name, leiter_eroeff_abn_name,
leiter_rohger_abn_name, cpr_systemstatus1_id, cpr_systemstatus2_id, cpr_systemstatus3_id, bauleiter_name,
bearbeit_ea_soa_name, fach_ing_name, ges_grund_flaeche_bez, gu_ladenbau_name, kaelte_lief_name, log_massn,
pl_einrichtung_name, statiker_name, plan_verantwortl_name, cpr_bl_projekt_bau_einr_name, cpr_gen_ueb_name,
cpr_gen_unt_haust_name, cpr_arch_ph_14_name, cpr_arch_phase_58_name, cpr_fachpl_name, cpr_fachpl_kaelt_name,
cpr_fachpl_sonst_name, cpr_gutachter_name, cpr_vermesser_name, cpr_fachin_tga_name, cpr_qual_sich_bau_name,
cpr_qual_sich_haust_name, cpr_gj_ber, cpr_eig_proj, cpr_gen_unt_ausb_name, einbau_kkv, dat_eroeffnung, dat_teil_oeffentl
, land_nl) AS SELECT pr.projekt_id,
 pr.projekt_id AS projekt_id_lfd_nr,
 pr.cpr_ext_id AS projekt_nr,
 SUBSTR(pr.cpr_ext_id, 14, 2) AS projekt_nr_endung,
 TRIM(pr.techn_platz_id) AS techn_platz_id,
 2 AS techn_platz_ebene_id,
  CASE
  WHEN SUBSTR(pr.massnahme_id, 1, 5) = 'ZPPM_'
  THEN SUBSTR(pr.massnahme_id, 6, LENGTH(pr.massnahme_id) - 5)
  ELSE pr.massnahme_id
  END AS massnahme_kz,
 pr.massnahme_id,
 pr.cpr_kategorie_id,
 pr.projekt_anlass_id,
 pr.projektart_id,
 CAST(NULL AS STRING) AS cpr_projekt_gruppe_id,
 pr.dat_freigabe,
 su.cpr_suchfeld,
 pr.mandant_id,
 COALESCE(v01.aktuell_wup_id, pr.wup_id) AS wup_id,
 pr.cpr_filialtyp_bez,
 pr.cpr_standort,
 pr.cpr_plz,
 pr.cpr_str,
 pr.cpr_vs,
 pr.cpr_vw,
 pr.region_id,
 pr.land_id,
 pr.markt_typ_ea,
 pr.markt_typ_vp,
 COALESCE(pr.kbl_nl_bez, pr.land_id) AS kbl_nl_bez,
 pr.cpr_betreuer_name,
 pr.objekt_planer_name,
 pr.plan_verantw_kz,
 pr.cpr_general_planer,
 pr.cpr_objekt_steurer AS cpr_projekt_steurer,
 pr_spr.cpr_projekt_langtext,
 pr.pl_be_name,
 pr.pl_vertrieb_name,
 pr.pl_elektro,
 pr.pl_hls,
 COALESCE(pr.gj, 0) AS gj,
 pr.betrag_proj_kosten,
 COALESCE(pr.expansion_merkmal, '') AS expansion_merkmal,
 pr.expansion_auftrag_id,
 pr.cpr_auftraggeber_name,
 COALESCE(pr.investor_eigenobj, ' ') AS investor_eigenobj,
 pr.investor_name,
 pr.cpr_generalunternehmer_name,
 pr.leiter_eroeff_abn_name,
 pr.leiter_rohger_abn_name,
 pr.cpr_systemstatus1_id,
 pr.cpr_systemstatus2_id,
 pr.cpr_systemstatus3_id,
 pr.bauleiter_name,
 pr.bearbeit_ea_soa_name,
 pr.fach_ing_name,
 pr.ges_grund_flaeche_bez,
 pr.gu_ladenbau_name,
 pr.kaelte_lief_name,
 pr.log_massn,
 pr.pl_einrichtung_name,
 pr.statiker_name,
 pr.plan_verantwortl_name,
 pr.cpr_bl_projekt_bau_einr_name,
 pr.cpr_gen_ueb_name,
 pr.cpr_gen_unt_haust_name,
 pr.cpr_arch_ph_14_name,
 pr.cpr_arch_phase_58_name,
 pr.cpr_fachpl_name,
 pr.cpr_fachpl_kaelt_name,
 pr.cpr_fachpl_sonst_name,
 pr.cpr_gutachter_name,
 pr.cpr_vermesser_name,
 pr.cpr_fachin_tga_name,
 pr.cpr_qual_sich_bau_name,
 pr.cpr_qual_sich_haust_name,
 pr.cpr_gj_ber,
 pr.cpr_eig_proj,
 pr.cpr_gu_ausbau AS cpr_gen_unt_ausb_name,
 pr.einbau_kkv,
 DATE(NULL) AS dat_eroeffnung,
 DATE(NULL) AS dat_teil_oeffentl,
  CASE
  WHEN pr.kbl_nl_bez IS NOT NULL
  THEN TRIM(pr.land_id) || ' / Region_2  ' || TRIM(pr.kbl_nl_bez)
  ELSE TRIM(pr.land_id) || ' / Region_2  '
  END AS land_nl
FROM kfl_production_dbp_view.v_cpr_projekt_per_2 AS pr
 INNER JOIN kfl_production_dbp_view.v_cpr_projekt_spr_zu_per_2 AS pr_spr ON pr.projekt_id = pr_spr.projekt_id AND pr.dat_bis
    = pr_spr.dat_bis
 LEFT JOIN kfl_production_dbp_view.v_l_cpr_suchfeld_2 AS su ON pr.cpr_suchfeld_id = su.cpr_suchfeld_id
 LEFT JOIN kfl_production_dbp_view.v_wup_2 AS v01 ON pr.wup_id = v01.wup_id AND pr.mandant_id = v01.mandant_id
WHERE pr.dat_bis = DATE '9999-12-31';