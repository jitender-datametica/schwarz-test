create or replace view IDQ_PRODUCTION.CROSS_PLATFORM_COMS.V_IS_INFOR_KFL_PMR_2(
	TIMEADDED_IS_INFOR_VIEW
) as
SELECT MIN(MIN_INSERT) as TimeAdded FROM
(
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_2
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_EXP_STS_2
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_EXT_XR_2
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_OFR_TRM_PRD_2
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_PROD_2
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_PROD_EXT_XR_2
  UNION ALL
  SELECT MIN(TD_INSERT) as MIN_INSERT FROM KFL_PMR.DMF_PRODT_2
);