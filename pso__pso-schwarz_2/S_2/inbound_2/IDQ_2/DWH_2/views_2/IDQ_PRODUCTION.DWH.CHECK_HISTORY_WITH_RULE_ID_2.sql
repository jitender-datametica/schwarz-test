create or replace view IDQ_PRODUCTION.DWH.CHECK_HISTORY_WITH_RULE_ID_2(
	REF_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_BRANCH_ID,
	REF_COUNTRY_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	REF_RULE_ID,
	TEST_OBJECT_AMOUNT,
	ERROR_AMOUNT,
	CHECK_HISTORY_IS_CURRENT
) as
SELECT
      CALCULATION_TIME          AS CALCULATION_TIME
      ,CALCULATION_DAY_ID        AS REF_TIME_CALCULATION_DAY_ID
      ,SOURCE_SYSTEM_ID          AS REF_SOURCE_SYSTEM_ID
      ,BRANCH_ID                 AS REF_BRANCH_ID
      ,COUNTRY_ID                AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
	  ,RULE_ID 					 AS REF_RULE_ID
      ,TEST_RESULT_AMOUNT        AS TEST_OBJECT_AMOUNT
      ,ERROR_AMOUNT             AS ERROR_AMOUNT
      ,1                           AS CHECK_HISTORY_IS_CURRENT
FROM idq_results.CHECK_RULE_BY_SCOPE_CURRENT_2
UNION ALL
SELECT
      CALCULATION_TIME          AS CHECK_HISTORY_CALCULATION_TIME
      ,CALCULATION_DAY_ID        AS REF_TIME_CALCULATION_DAY_ID
      ,SOURCE_SYSTEM_ID          AS REF_SOURCE_SYSTEM_ID
      ,BRANCH_ID                 AS REF_BRANCH_ID
      ,COUNTRY_ID                AS REF_COUNTRY_ID
      ,SOURCE_SYSTEM_TYPE_ID     AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID       AS REF_TEST_OBJECT_TYPE_ID
	  ,RULE_ID 					 AS REF_RULE_ID
      ,TEST_RESULT_AMOUNT        AS TEST_OBJECT_AMOUNT
      ,ERROR_AMOUNT             AS ERROR_AMOUNT
      ,0                           AS CHECK_HISTORY_IS_CURRENT
FROM idq_results.CHECK_RULE_BY_SCOPE_HISTORICAL_2
where
--CALCULATION_DAY_ID >= '20250301'
     CALCULATION_TIME >= DATEADD(DAY, -7, concat(substr(to_char(sysdate()), 0, 10),' 18:00:00')::DATETIME)
;