create or replace view IDQ_PRODUCTION.DWH.DPL_CHECK_HISTORY_2(
	DPL_CHECK_HISTORY_ID,
	REF_DPL_CHECK_DEFINITION_ID,
	DPL_CHECK_EXECUTION_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	DPL_CHECK_HISTORY_CALCULATION_TIME,
	REF_TIME_CALCULATION_DAY_ID,
	TOTAL_AMOUNT,
	CLUSTER_AMOUNT,
	DUPLICATE_AMOUNT,
	DPL_CHECK_HISTORY_IS_CURRENT
) as
SELECT ID                       AS DPL_CHECK_HISTORY_ID
      ,DPL_CHECK_DEFINITION_ID  AS REF_DPL_CHECK_DEFINITION_ID
      ,DPL_CHECK_EXECUTION_ID	  AS DPL_CHECK_EXECUTION_ID
      ,SOURCE_SYSTEM_ID		  AS REF_SOURCE_SYSTEM_ID
      ,COUNTRY_ID				  AS REF_COUNTRY_ID
      ,BRANCH_ID				  AS REF_BRANCH_ID
      ,SOURCE_SYSTEM_TYPE_ID	  AS REF_SOURCE_SYSTEM_TYPE_ID
      ,TEST_OBJECT_TYPE_ID	  AS REF_TEST_OBJECT_TYPE_ID
      ,TEST_TIME				  AS DPL_CHECK_HISTORY_CALCULATION_TIME
      ,TEST_DAY_ID			  AS REF_TIME_CALCULATION_DAY_ID
      ,TOTAL_AMOUNT			  AS TOTAL_AMOUNT
      ,CLUSTER_AMOUNT			  AS CLUSTER_AMOUNT
      ,DUPLICATE_AMOUNT		  AS DUPLICATE_AMOUNT
      ,IS_CURRENT				  AS DPL_CHECK_HISTORY_IS_CURRENT
FROM idq_results.DPL_CHECK_HISTORY_2
;