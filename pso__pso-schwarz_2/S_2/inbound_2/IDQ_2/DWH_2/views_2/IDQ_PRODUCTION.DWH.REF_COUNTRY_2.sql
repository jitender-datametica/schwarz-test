create or replace view IDQ_PRODUCTION.DWH.REF_COUNTRY_2(
	REF_COUNTRY_ID,
	COUNTRY_2,
	COUNTRY_NAME,
	COUNTRY_NAME_DE,
	COUNTRY_NAME_EN,
	CAPITAL,
	CAPITAL_DE,
	CAPITAL_EN,
	HQ_CITY,
	HQ_CITY_DE,
	HQ_CITY_EN,
	COUNTRY_MIDDLE_LONGITUDE,
	COUNTRY_MIDDLE_LATITUDE,
	HQ_CITY_LONGITUDE,
	HQ_CITY_LATITUDE
) as
SELECT ID						AS REF_COUNTRY_ID
	,COUNTRY_2					AS COUNTRY_2
	,NAME_DE					AS COUNTRY_NAME
	,NAME_DE					AS COUNTRY_NAME_DE
	,NAME_EN					AS COUNTRY_NAME_EN
	,CAPITAL_DE				AS CAPITAL
	,CAPITAL_DE				AS CAPITAL_DE
	,CAPITAL_EN				AS CAPITAL_EN
	,HQ_CITY_DE				AS HQ_CITY
	,HQ_CITY_DE				AS HQ_CITY_DE
	,HQ_CITY_EN				AS HQ_CITY_EN
	,COUNTRY_MIDDLE_LONGITUDE	AS COUNTRY_MIDDLE_LONGITUDE
	,COUNTRY_MIDDLE_LATITUDE	AS COUNTRY_MIDDLE_LATITUDE
	,HQ_CITY_LONGITUDE		AS HQ_CITY_LONGITUDE
	,HQ_CITY_LATITUDE			AS HQ_CITY_LATITUDE
  FROM idq_results.REF_COUNTRY_2
;