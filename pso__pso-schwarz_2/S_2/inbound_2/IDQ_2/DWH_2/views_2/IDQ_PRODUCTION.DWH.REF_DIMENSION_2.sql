create or replace view IDQ_PRODUCTION.DWH.REF_DIMENSION_2(
	REF_DIMENSION_ID,
	DIMENSION_TECHNICAL_NAME,
	DIMENSION_NAME,
	DIMENSION_NAME_DE,
	DIMENSION_NAME_EN
) as
SELECT ID                       AS REF_DIMENSION_ID
      ,DIMENSION                AS DIMENSION_TECHNICAL_NAME
      ,NAME_DE	              AS DIMENSION_NAME
      ,NAME_DE	              AS DIMENSION_NAME_DE
      ,NAME_EN	              AS DIMENSION_NAME_EN
FROM idq_results.REF_DIMENSION_2
;