create or replace view IDQ_PRODUCTION.DWH.REF_PARAMETER_CONTEXT_2(
	REF_PARAMETER_CONTEXT_ID,
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_PARAMETER_ID,
	VALUE,
	PARAMETER_CONTEXT_DESCRIPTION,
	PARAMETER_CONTEXT_DESCRIPTION_DE,
	PARAMETER_CONTEXT_DESCRIPTION_EN
) as
SELECT ID                     AS REF_PARAMETER_CONTEXT_ID
      ,SOURCE_SYSTEM_ID       AS REF_SOURCE_SYSTEM_ID
      ,COUNTRY_ID             AS REF_COUNTRY_ID
      ,PARAMETER_ID           AS REF_PARAMETER_ID
      ,VALUE                  AS VALUE
      ,DESCRIPTION_DE         AS PARAMETER_CONTEXT_DESCRIPTION
      ,DESCRIPTION_DE         AS PARAMETER_CONTEXT_DESCRIPTION_DE
      ,DESCRIPTION_EN         AS PARAMETER_CONTEXT_DESCRIPTION_EN
FROM idq_results.REF_PARAMETER_CONTEXT_2
;