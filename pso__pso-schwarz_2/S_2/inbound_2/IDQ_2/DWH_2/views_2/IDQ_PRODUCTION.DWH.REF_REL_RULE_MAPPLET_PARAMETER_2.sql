create or replace view IDQ_PRODUCTION.DWH.REF_REL_RULE_MAPPLET_PARAMETER_2(
	REF_REL_RULE_MAPPLET_PARAMETER_ID,
	REF_REL_RULE_MAPPLET_ID,
	PARAMETER_ORDER,
	REF_PARAMETER_ID,
	REF_RULE_ID
) as
SELECT RRMP.ID                     AS REF_REL_RULE_MAPPLET_PARAMETER_ID
      ,RRMP.REL_RULE_MAPPLET_ID    AS REF_REL_RULE_MAPPLET_ID
      ,RRMP.PARAMETER_ORDER        AS PARAMETER_ORDER
      ,RRMP.PARAMETER_ID           AS REF_PARAMETER_ID
      ,RRM.RULE_ID                 AS REF_RULE_ID
FROM idq_results.REF_REL_RULE_MAPPLET_PARAMETER_2 RRMP
INNER JOIN idq_results.REF_REL_RULE_MAPPLET_2 RRM
  ON RRMP.REL_RULE_MAPPLET_ID = RRM.ID
;