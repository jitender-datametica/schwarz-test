create or replace view IDQ_PRODUCTION.DWH.REF_RULE_TYPE_2(
	REF_RULE_TYPE_ID,
	RULE_TYPE_TECHNICAL_NAME,
	RULE_TYPE_NAME,
	RULE_TYPE_NAME_DE,
	RULE_TYPE_NAME_EN
) as
SELECT ID                      AS REF_RULE_TYPE_ID
      ,RULE_TYPE	             AS RULE_TYPE_TECHNICAL_NAME
      ,NAME_DE  				 AS  RULE_TYPE_NAME
      ,NAME_DE				 AS  RULE_TYPE_NAME_DE
      ,NAME_EN				 AS  RULE_TYPE_NAME_EN
FROM idq_results.REF_RULE_TYPE_2
;