create or replace view IDQ_PRODUCTION.DWH.RELEVANCE_TEST_LIST_2(
	RELEVANCE_TEST_LIST_ID,
	REF_TEST_OBJECT_ID,
	RELEVANCE_EXECUTION_ID,
	REF_RULE_ID,
	RULE_RESULT,
	REF_RELEVANCE_DEFINITION_ID,
	REF_SOURCE_SYSTEM_TYPE_ID,
	REF_COUNTRY_ID,
	REF_BRANCH_ID
) as
SELECT RTL.ID                      AS RELEVANCE_TEST_LIST_ID
      ,RTL.TEST_OBJECT_ID          AS REF_TEST_OBJECT_ID
      ,RTL.RELEVANCE_EXECUTION_ID  AS RELEVANCE_EXECUTION_ID
      ,RTL.RULE_ID                 AS REF_RULE_ID
      ,RTL.RULE_RESULT             AS RULE_RESULT
	  ,RE.RELEVANCE_DEFINITION_ID  AS REF_RELEVANCE_DEFINITION_ID
	  ,RD.SOURCE_SYSTEM_TYPE_ID    AS REF_SOURCE_SYSTEM_TYPE_ID
	  ,RE.COUNTRY_ID               AS REF_COUNTRY_ID
	  ,RD.BRANCH_ID                AS REF_BRANCH_ID
FROM idq_results.RELEVANCE_TEST_LIST_2  RTL
INNER JOIN idq_results.RELEVANCE_EXECUTION_2 RE_2
  ON RTL.RELEVANCE_EXECUTION_ID = RE.ID
INNER JOIN idq_results.REF_RELEVANCE_DEFINITION_2 RD
  ON RE.RELEVANCE_DEFINITION_ID = RD.ID
;