CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_BUYERSHORTSIGN_UPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_2 
SET  BuyerSHORTSIGN = sr.BuyerSHORTSIGNNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_BuyerSHORTSIGN_UpdSel_2 AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';