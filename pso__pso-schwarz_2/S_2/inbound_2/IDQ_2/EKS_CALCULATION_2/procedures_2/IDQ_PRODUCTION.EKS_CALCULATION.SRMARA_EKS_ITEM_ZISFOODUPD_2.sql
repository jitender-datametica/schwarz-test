CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISFOODUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_2 
SET  zIsFood = sr.zIsFoodNew
FROM EKS_CALCULATION.srMARA_EKS_ITEM_zIsFoodUpdSel_2 AS sr
WHERE STMARA_EKS_ITEM.itemid = sr.ITEMID;
END;
';