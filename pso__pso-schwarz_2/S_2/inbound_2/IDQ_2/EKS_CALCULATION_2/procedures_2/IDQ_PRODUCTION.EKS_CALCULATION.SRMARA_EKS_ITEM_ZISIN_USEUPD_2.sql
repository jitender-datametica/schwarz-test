CREATE OR REPLACE PROCEDURE "SRMARA_EKS_ITEM_ZISIN_USEUPD"()
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
Update EKS_CALCULATION.STMARA_EKS_ITEM_2 
SET  zISin_USE = EKS_CALCULATION.SRMARA_EKS_ITEM_ZISIN_USEUPDSEL.zISIN_USENEW
FROM EKS_CALCULATION.SRMARA_EKS_ITEM_ZISIN_USEUPDSEL_2
WHERE EKS_CALCULATION.STMARA_EKS_ITEM.itemid = EKS_CALCULATION.SRMARA_EKS_ITEM_ZISIN_USEUPDSEL.itemid;
END;
';