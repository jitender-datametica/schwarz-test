create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ARTICLEFAMILY_010_2(
	ZITEM_BA,
	ARTICLEFAMILY
) as
SELECT        EKS_CALCULATION.STMARA_EKS_ITEM.zITEM_BA, MAX(IFNULL(stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC || '.' || EKS.ITEMGRPTIMELINE.SHORTDESC, '')) AS ArticleFamily
FROM            EKS.ITEMGRPTIMELINE_2
                    INNER JOIN
                         EKS.ITEMGROUPITEMREL_2 ON EKS.ITEMGRPTIMELINE.ITEMGROUPID = EKS.ITEMGROUPITEMREL.ITEMGROUPID
                         INNER JOIN
                         EKS.ITEMGRPTIMELINE_2 as stEKS_ITEMGRPTIMELINE_PARENT ON EKS.ITEMGRPTIMELINE.PARENTID = stEKS_ITEMGRPTIMELINE_PARENT.ITEMGROUPID
                         AND current_date() BETWEEN EKS.ITEMGROUPITEMREL.DATEFROM AND EKS.ITEMGROUPITEMREL.DATEUNTIL
                         AND current_date() BETWEEN EKS.ITEMGRPTIMELINE.DATEFROM AND EKS.ITEMGRPTIMELINE.DATEUNTIL
                         AND current_date() BETWEEN stEKS_ITEMGRPTIMELINE_PARENT.DATEFROM AND stEKS_ITEMGRPTIMELINE_PARENT.DATEUNTIL
                         INNER JOIN
                         EKS_CALCULATION.STMARA_EKS_ITEM_2 ON EKS.ITEMGROUPITEMREL.ITEMID = EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID
WHERE        (EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0) AND (EKS_CALCULATION.STMARA_EKS_ITEM.zActive = 1)
GROUP BY EKS_CALCULATION.STMARA_EKS_ITEM.zITEM_BA
HAVING        (COUNT(DISTINCT IFNULL(stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC || '.' || (REPEAT('0', 3-LENGTH(EKS.ITEMGRPTIMELINE.SHORTDESC)) || EKS.ITEMGRPTIMELINE.SHORTDESC), '')) = 1);