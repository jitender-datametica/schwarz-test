create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ARTICLEFAMILY_BASK_UPDSEL_2(
	ITEMID,
	ARTICLEFAMILY,
	ARTICLEFAMILYNEW
) as
SELECT Distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.ArticleFamily,
         IFNULL(EKS_CALCULATION.srMARA_EKS_ITEM_ArticleFamily_010.ArticleFamily, '') AS ArticleFamilyNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_2
         INNER JOIN EKS_CALCULATION.srMARA_EKS_ITEM_ArticleFamily_010_2
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.zITEM_BA = EKS_CALCULATION.srMARA_EKS_ITEM_ArticleFamily_010.zITEM_BA
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.ArticleFamily IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG IN ( 2, 4 ) );