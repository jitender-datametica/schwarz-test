create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_BUYERID_FIRSTNAME_LASTNAME_SKROLLUP01_2(
	ITEMID,
	BUYERID,
	BITFLAG
) as
SELECT stMARA_EKS_ITEM_1.ITEMID,
MIN(EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID) AS BuyerID,
stMARA_EKS_ITEM_1.BITFLAG
FROM     EKS_CALCULATION.STMARA_EKS_ITEM_2 INNER JOIN
                  EKS.ITEMSORTING_2 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID INNER JOIN
                  EKS_CALCULATION.STMARA_EKS_ITEM_2 AS stMARA_EKS_ITEM_1 ON EKS.ITEMSORTING.SORTITEMID = stMARA_EKS_ITEM_1.ITEMID
WHERE  (EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0)
GROUP BY stMARA_EKS_ITEM_1.ITEMID, stMARA_EKS_ITEM_1.BITFLAG
HAVING (NOT (MIN(EKS_CALCULATION.STMARA_EKS_ITEM.BuyerID) IS NULL));