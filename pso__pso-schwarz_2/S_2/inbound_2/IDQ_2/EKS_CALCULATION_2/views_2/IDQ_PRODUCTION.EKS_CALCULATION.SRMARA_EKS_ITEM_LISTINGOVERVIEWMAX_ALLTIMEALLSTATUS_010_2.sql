create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ALLTIMEALLSTATUS_010_2(
	LISTINGOVERVIEWID,
	LOCATION_2,
	INTSUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	CASESIZE
) as
With svMARA_EKS_ITEM_LISTINGOVERVIEWMAX_AllTimeAllStatus_Sel as (
    SELECT        MAX(EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID) AS LISTINGOVERVIEWID, EKS.LOCATION.SHORTSIGN AS LOCATION_2, EKS.SUPPLIER.INTSUPPLIERNO, EKS.LISTINGOVERVIEW.CR_LOCATIONID,
                             CAST(stEKS_LOCATION_1.SHORTSIGN as VARCHAR(2)) AS ReceivingCountry, EKS.LISTINGITEM.ITEMID, CAST(EKS.BASICPRICE.CASESIZECalc as DECIMAL(6, 0)) AS CaseSize
    FROM            EKS.LISTINGOVERVIEW_2 INNER JOIN
                             EKS.CONTRACTLINK_2 ON EKS.LISTINGOVERVIEW.LISTINGOVERVIEWID = EKS.CONTRACTLINK.LISTINGOVERVIEWID INNER JOIN
                             EKS.SUPPLIER_2 ON EKS.LISTINGOVERVIEW.SUPPLIERNO = EKS.SUPPLIER.SUPPLIERNO INNER JOIN
                             EKS.LOCATION_2 ON EKS.LISTINGOVERVIEW.CR_LOCATIONID = EKS.LOCATION.LOCATIONID INNER JOIN
                             EKS.LOCATION_2 AS stEKS_LOCATION_1 ON EKS.CONTRACTLINK.LOCATIONID = stEKS_LOCATION_1.LOCATIONID INNER JOIN
                             EKS.CONTRACTPRICEREL_2 ON EKS.CONTRACTLINK.CONTRACTLINKID = EKS.CONTRACTPRICEREL.CONTRACTLINKID INNER JOIN
                             EKS.BASICPRICE_2 ON EKS.CONTRACTPRICEREL.BASICPRICEID = EKS.BASICPRICE.BASICPRICEID INNER JOIN
                             EKS.LISTINGITEM_2 ON EKS.BASICPRICE.LISTINGITEMID = EKS.LISTINGITEM.LISTINGITEMID
    WHERE        (IFNULL(EKS.LISTINGOVERVIEW.STATUSID, 0) <> 0)
    GROUP BY EKS.SUPPLIER.INTSUPPLIERNO, EKS.LISTINGOVERVIEW.CR_LOCATIONID, EKS.LOCATION.SHORTSIGN, stEKS_LOCATION_1.SHORTSIGN, EKS.LISTINGITEM.ITEMID,
                             EKS.BASICPRICE.CASESIZECalc
)
SELECT DISTINCT LISTINGOVERVIEWID,
                  LOCATION_2,
                  INTSUPPLIERNO,
                  CR_LOCATIONID,
                  ReceivingCountry,
                  ITEMID,
                  Round(CaseSize, 0) AS CaseSize
  FROM   svMARA_EKS_ITEM_LISTINGOVERVIEWMAX_AllTimeAllStatus_Sel
  WHERE  ( INTSUPPLIERNO <> 10236 );