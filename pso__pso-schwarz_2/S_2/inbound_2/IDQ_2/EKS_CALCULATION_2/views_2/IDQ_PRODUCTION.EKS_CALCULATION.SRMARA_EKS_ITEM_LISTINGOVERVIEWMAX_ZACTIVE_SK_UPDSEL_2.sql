create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_SK_UPDSEL_2(
	LISTINGOVERVIEWID,
	LOCATION_2,
	SUPPLIERNO,
	CR_LOCATIONID,
	RECEIVINGCOUNTRY,
	ITEMID,
	ZACTIVE,
	ZACTIVENEW
) as
SELECT EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LOCATION_2,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CR_LOCATIONID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID,
         EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zActive,
         1 AS zActiveNew
  FROM   EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_2
         INNER JOIN EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_020_2
                 ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_020.LISTINGOVERVIEWID
                    AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_020.SUPPLIERNO
                    AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_020.ReceivingCountry
                    AND EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zITEM_BA = EKS_CALCULATION.SRMARA_EKS_ITEM_LISTINGOVERVIEWMAX_ZACTIVE_020.zITEM_BA
  WHERE  ( EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.zArticleType = 'SK' )
    QUALIFY ROW_NUMBER() OVER (PARTITION BY STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID, STEKS_LISTINGOVERVIEWMAX.ReceivingCountry, STEKS_LISTINGOVERVIEWMAX.ITEMID ORDER BY zActiveNew) = 1
;