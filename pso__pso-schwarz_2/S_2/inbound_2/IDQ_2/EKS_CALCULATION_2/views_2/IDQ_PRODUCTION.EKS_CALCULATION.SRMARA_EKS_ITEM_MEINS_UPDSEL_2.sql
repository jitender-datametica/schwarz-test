create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_MEINS_UPDSEL_2(
	ZMEINS,
	ZMEINSNEW,
	ITEMID,
	ZLEGACYMEINS,
	DESCRIPTION
) as
SELECT        EKS_CALCULATION.STMARA_EKS_ITEM.zMEINS, CASE IFNULL(EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyMEINS, '')
                         WHEN '' THEN 'ST' ELSE CASE EKS.TRANSLATION_INT.description WHEN 'KG' THEN 'KG' WHEN 'g' THEN 'KG' WHEN 'LB' THEN 'LB' WHEN 'oz' THEN 'LB' ELSE 'KG' END END AS zMEINSNew,
                         EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
                         EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyMEINS, EKS.TRANSLATION_INT.DESCRIPTION
FROM            EKS_CALCULATION.STMARA_EKS_ITEM_2 LEFT OUTER JOIN
                         EKS.ITEMDETAIL_2 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID INNER JOIN
                         EKS.UNIT_2 ON EKS.ITEMDETAIL.UNITID = EKS.UNIT.UNITID INNER JOIN
                         EKS.TRANSLATION_INT_2 ON EKS.UNIT.SHORTDESCID = EKS.TRANSLATION_INT.TRANSLATIONID
WHERE        (EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = 0);