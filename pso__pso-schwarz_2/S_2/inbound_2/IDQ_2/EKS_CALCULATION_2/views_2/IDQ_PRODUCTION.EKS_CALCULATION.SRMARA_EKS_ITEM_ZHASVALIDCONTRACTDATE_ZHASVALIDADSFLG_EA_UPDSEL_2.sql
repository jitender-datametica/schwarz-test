create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZHASVALIDCONTRACTDATE_ZHASVALIDADSFLG_EA_UPDSEL_2(
	ITEMID,
	ZHASVALIDADSFLG,
	ZHASVALIDADSFLGNEW,
	ADSFLG,
	VALUE,
	ZHASVALIDCONTRACTDATE,
	ZHASVALIDCONTRACTDATENEW,
	ITEM_DATEUNTIL,
	DATE,
	ZARTICLETYPE
) as
SELECT Distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidADSFLG,
         1                    AS zHasValidADSFLGNew,
         EAValidity.ADSFLG,
         P0.Value,
         EKS_CALCULATION.STMARA_EKS_ITEM.zHasValidContractDate,
         1                    AS zHasValidContractDateNew,
         max(EAValidity.DATEUNTIL) AS ITEM_DATEUNTIL,
         P2.Date,
         EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType
  FROM   EKS.CONTRACTPRICEVALIDITY_2 AS EAValidity
         RIGHT OUTER JOIN EKS_CALCULATION.XTEKS_BASICINFO_RECCOUNTRY_2 AS EALink
                       ON EAValidity.CONTRACTPRICEVALIDITYID = EALink.CONTRACTPRICEVALIDITYID
         RIGHT OUTER JOIN EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX_2
                       ON EALink.LISTINGOVERVIEWID = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID
                          AND EALink.casesize = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.CaseSize
                          AND EALink.itemid = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID
                          AND EALink.ReceivingCountry = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ReceivingCountry
                          AND EALink.SUPPLIERNO = EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.SUPPLIERNO
                          AND EALink.SK_ITEMID IS NULL
         RIGHT OUTER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_2
                       ON EKS_CALCULATION.STEKS_LISTINGOVERVIEWMAX.ITEMID = EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 AS P0
                 ON P0.ID = 'ADSFLGCHK'
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 AS P1
                 ON P1.ID = 'ADSFLGON'
         INNER JOIN EKS_CALCULATION.EKS_ZSM_ARTICLEPARAMETER_2 AS P2
                 ON P2.ID = 'VALIDITYDATE'
                    AND EAValidity.DATEUNTIL >= P2.Date
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
         AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType = 'EA' )
         AND ( EAValidity.ADSFLG = P0.Value )
          OR ( EKS_CALCULATION.STMARA_EKS_ITEM.Constructed IS NULL )
             AND ( EKS_CALCULATION.STMARA_EKS_ITEM.zArticleType = 'EA' )
             AND ( P1.Value = 0 )
    group by STMARA_EKS_ITEM.ITEMID, STMARA_EKS_ITEM.zHasValidADSFLG, zHasValidADSFLGNew, EAValidity.ADSFLG, P0.Value, STMARA_EKS_ITEM.zHasValidContractDate, zHasValidContractDateNew, P2.Date, STMARA_EKS_ITEM.zArticleType;