create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZISCURRENTCONTRACTFROMSK_UPDSEL_2(
	ITEMID,
	ZISCURRENTCONTRACTFROMSK,
	ZISCURRENTCONTRACTFROMSKNEW
) as
SELECT distinct EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
         EKS_CALCULATION.STMARA_EKS_ITEM.zIsCurrentContractFromSK,
         1 AS zIsCurrentContractFromSKNew
  FROM   EKS_CALCULATION.STMARA_EKS_ITEM_2
         INNER JOIN EKS.ITEMSORTING_2
                 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMSORTING.ITEMID
         INNER JOIN EKS_CALCULATION.STMARA_EKS_ITEM_2 AS stMARA_EKS_ITEM_1
                 ON EKS.ITEMSORTING.SORTITEMID = stMARA_EKS_ITEM_1.ITEMID
  WHERE  ( EKS_CALCULATION.STMARA_EKS_ITEM.BITFLAG = '0' )
         AND ( stMARA_EKS_ITEM_1.BITFLAG = '4' )
         AND ( stMARA_EKS_ITEM_1.zIsCurrentContract = 1 );