create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZLEGACYMEINS_UPDSEL_2(
	ZLEGACYMEINS,
	ITEMID,
	ZLEGACYMEINSNEW
) as
SELECT        EKS_CALCULATION.STMARA_EKS_ITEM.zLegacyMEINS, EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID,
                         CASE znegotiatingcountry WHEN 'DE' THEN TEXT_INT WHEN 'AT' THEN TEXT_INT WHEN 'CH' THEN TEXT_INT ELSE IFNULL(EKS.ITEMDETAIL.TEXT_INT, EKS.ITEMDETAIL.TEXT_NAT)
                         END AS zLegacyMEINSNew
FROM            EKS_CALCULATION.STMARA_EKS_ITEM_2 INNER JOIN
                         EKS.ITEMDETAIL_2 ON EKS_CALCULATION.STMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID;