create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRMARA_EKS_ITEM_ZZ_PACK_TYPE_ARTICLE_TYPE_EAUPDSEL_2(
	ITEMID,
	ZLEGACYZZ_PACK_TYPE,
	ZLEGACYZZ_PACK_TYPENEW
) as
SELECT        STMARA_EKS_ITEM.itemid, STMARA_EKS_ITEM.zLegacyZZ_PACK_TYPE, stEKS_TRANSLATION_PACKAGE.DESCRIPTION AS zLegacyZZ_PACK_TYPENew
FROM            EKS_CALCULATION.STMARA_EKS_ITEM_2 INNER JOIN
                         EKS.ITEMDETAIL_2 ON STMARA_EKS_ITEM.ITEMID = EKS.ITEMDETAIL.ITEMID INNER JOIN
                         EKS.PACKAGE_2 ON EKS.ITEMDETAIL.PACKAGEID = EKS.PACKAGE.PACKAGEID INNER JOIN
                         EKS_CALCULATION.stEKS_TRANSLATION_PACKAGE_2 ON EKS.PACKAGE.SHORTDESCID = stEKS_TRANSLATION_PACKAGE.TRANSLATIONID
WHERE        (STMARA_EKS_ITEM.zLegacyZZ_PACK_TYPE IS NULL) AND (STMARA_EKS_ITEM.BITFLAG = '0');