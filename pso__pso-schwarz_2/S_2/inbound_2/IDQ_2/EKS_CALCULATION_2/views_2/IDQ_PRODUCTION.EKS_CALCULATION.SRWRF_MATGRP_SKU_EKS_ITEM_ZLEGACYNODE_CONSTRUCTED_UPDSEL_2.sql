create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRWRF_MATGRP_SKU_EKS_ITEM_ZLEGACYNODE_CONSTRUCTED_UPDSEL_2(
	ITEMID,
	ZLEGACYNODE,
	ZLEGACYNODENEW
) as
SELECT distinct EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.ITEMID,
         EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE,
         EA.zLegacyNODE AS zLegacyNODENew
  FROM   EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM_2
         INNER JOIN EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM_2 AS EA
                 ON EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.ConstructedFrom = EA.ITEMID
  WHERE  ( EKS_CALCULATION.stWRF_MATGRP_SKU_EKS_ITEM.Constructed = 1 );