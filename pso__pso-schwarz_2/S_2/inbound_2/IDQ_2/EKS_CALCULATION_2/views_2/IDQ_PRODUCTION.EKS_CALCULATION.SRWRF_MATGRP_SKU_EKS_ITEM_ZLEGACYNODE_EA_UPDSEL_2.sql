create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SRWRF_MATGRP_SKU_EKS_ITEM_ZLEGACYNODE_EA_UPDSEL_2(
	ITEMID,
	LEVEL_1,
	LEVEL_2,
	ZLEGACYNODE,
	ZLEGACYNODENEW
) as
 SELECT distinct EKS_CALCULATION.STWRF_MATGRP_SKU_EKS_ITEM.ITEMID,
         EKS.ITEMGRPTIMELINE.SHORTDESC                                   AS Level_1,
         stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC                            AS Level_2,
         EKS_CALCULATION.STWRF_MATGRP_SKU_EKS_ITEM.zLegacyNODE,
         IFNULL(stEKS_ITEMGRPTIMELINE_PARENT.SHORTDESC
                || '.'
                || (REPEAT(0, 3 - length(EKS.ITEMGRPTIMELINE.SHORTDESC)) || EKS.ITEMGRPTIMELINE.SHORTDESC), '') AS zLegacyNODENew
  FROM   EKS.ITEMGRPTIMELINE_2
         INNER JOIN EKS.ITEMGROUPITEMREL_2
                 ON EKS.ITEMGRPTIMELINE.ITEMGROUPID = EKS.ITEMGROUPITEMREL.ITEMGROUPID
         INNER JOIN EKS.ITEMGRPTIMELINE_2 as stEKS_ITEMGRPTIMELINE_PARENT
                 ON EKS.ITEMGRPTIMELINE.PARENTID = stEKS_ITEMGRPTIMELINE_PARENT.ITEMGROUPID
         RIGHT OUTER JOIN EKS_CALCULATION.STWRF_MATGRP_SKU_EKS_ITEM_2
                       ON EKS.ITEMGROUPITEMREL.ITEMID = EKS_CALCULATION.STWRF_MATGRP_SKU_EKS_ITEM.ITEMID
                          AND getdate() BETWEEN EKS.ITEMGROUPITEMREL.DATEFROM AND EKS.ITEMGROUPITEMREL.DATEUNTIL
                          AND getdate() BETWEEN EKS.ITEMGRPTIMELINE.DATEFROM AND EKS.ITEMGRPTIMELINE.DATEUNTIL
                          AND getdate() BETWEEN stEKS_ITEMGRPTIMELINE_PARENT.DATEFROM AND stEKS_ITEMGRPTIMELINE_PARENT.DATEUNTIL
  WHERE  ( EKS_CALCULATION.STWRF_MATGRP_SKU_EKS_ITEM.Constructed IS NULL )
         AND ( EKS_CALCULATION.STWRF_MATGRP_SKU_EKS_ITEM.BITFLAG = 0 )
         QUALIFY ROW_NUMBER() OVER (PARTITION BY STWRF_MATGRP_SKU_EKS_ITEM.ITEMID ORDER BY zLegacyNODENew) = 1;