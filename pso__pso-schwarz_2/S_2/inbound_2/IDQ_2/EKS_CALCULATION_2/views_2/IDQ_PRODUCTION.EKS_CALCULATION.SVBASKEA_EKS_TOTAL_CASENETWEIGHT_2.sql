create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVBASKEA_EKS_TOTAL_CASENETWEIGHT_2(
	TOTAL_CASENETWEIGHT,
	SK_ITEMID
) as
SELECT    SUM(TRY_CAST(t_ea_sort.QUANTITY * t_ea_detail.NETWEIGHT AS NUMBER(38,5))) AS Total_CaseNetweight, t_sk.ITEMID AS SK_ITEMID
FROM EKS_CALCULATION.stMARA_EKS_ITEM_2 AS t_ba
INNER JOIN EKS.ITEMSORTING_2 AS t_ba_sk_link ON t_ba.ITEMID = t_ba_sk_link.SORTITEMID
INNER JOIN EKS_CALCULATION.stMARA_EKS_ITEM_2 AS t_sk ON t_ba_sk_link.ITEMID = t_sk.ITEMID
INNER JOIN EKS.ITEMSORTING_2 AS t_ea_sort ON t_sk.ITEMID = t_ea_sort.SORTITEMID
INNER JOIN EKS_CALCULATION.stMARA_EKS_ITEM_2 AS t_ea ON t_ea_sort.ITEMID = t_ea.ITEMID
INNER JOIN EKS.ITEMDETAIL_2 AS t_ea_detail ON t_ea.ITEMID = t_ea_detail.ITEMID
WHERE   t_ba.zArticleType = 'BA'
AND     t_sk.zArticleType = 'SK'
AND     t_ea.zArticleType = 'EA'
GROUP BY t_sk.ITEMID;