create or replace view IDQ_PRODUCTION.EKS_CALCULATION.SVMARA_EKS_ITEM_DQ_EKS_INCONSISTENTBRANDACROSSCONSTRUCT_SEL_2(
	NEGOTIATINGCOUNTRY,
	BUYERSHORTSIGN,
	BUYERFIRSTNAME,
	BUYERLASTNAME,
	ZMATKL,
	ARTICLEFAMILY,
	BA_ITEMNO,
	BA_DESCRIPTION,
	SK_ITEMNO,
	SK_DESCRIPTION,
	ITEMID,
	ITEMNO,
	ARTICLETYPE,
	DESCRIPTION,
	MARKENART,
	SUPPLIERNO,
	SUPPLIERDESCRIPTION,
	ZRELEVANTMDM,
	ZSOURCE,
	ZACTIVE
) as
(SELECT DISTINCT EKS_CALCULATION.stMARA_EKS_ITEM.zNegotiatingCountry AS NegotiatingCountry, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerSHORTSIGN, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerFirstName, EKS_CALCULATION.stMARA_EKS_ITEM.BuyerLastName, EKS_CALCULATION.stMARA_EKS_ITEM.zMATKL, EKS_CALCULATION.stMARA_EKS_ITEM.ArticleFamily, EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link.BA_ITEMNO, EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link.BA_Description, EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link.SK_ITEMNO, EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link.SK_Description, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID, EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO, EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType AS ArticleType, EKS_CALCULATION.stMARA_EKS_ITEM.DESCRIPTION_INT AS description, EKS.BRANDTYPE.DESCRIPTION AS MARKENART, IfNULL(EKS.SUPPLIER.INTSUPPLIERNO, steks_supplier_1.INTSUPPLIERNO) AS SUPPLIERNO, IfNULL(EKS.SUPPLIER.DESCRIPTION, steks_supplier_1.DESCRIPTION) AS SupplierDescription, CASE WHEN ziswawirelevant IS NULL THEN EKS_CALCULATION.stMARA_EKS_ITEM.zRelevantMDM ELSE ziswawirelevant END AS zRelevantMDM, EKS_CALCULATION.stMARA_EKS_ITEM.zSource, EKS_CALCULATION.stMARA_EKS_ITEM.zActive
FROM     EKS.SUPPLIER_2 RIGHT OUTER JOIN
EKS.SUPPLIER_2 AS steks_supplier_1 INNER JOIN
EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_2 AS steks_listingoverviewmax_1 ON steks_supplier_1.SUPPLIERNO = steks_listingoverviewmax_1.SUPPLIERNO RIGHT OUTER JOIN
EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link_2 ON steks_listingoverviewmax_1.ITEMID = EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link.SK_ITEMID RIGHT OUTER JOIN
EKS_CALCULATION.stMARA_EKS_ITEM_2 INNER JOIN
(SELECT zITEM_BA
FROM     EKS_CALCULATION.stMARA_EKS_ITEM_2
WHERE  (zArticleType = 'EA') AND (zActive = 1)
GROUP BY zITEM_BA
HAVING (COUNT(DISTINCT BRANDTYPEID) > 1)) as ITEMBA ON EKS_CALCULATION.stMARA_EKS_ITEM.zITEM_BA = ITEMBA.zITEM_BA INNER JOIN
EKS.BRANDTYPE_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.BRANDTYPEID = EKS.BRANDTYPE.BRANDTYPEID ON EKS_CALCULATION.svMARA_EKS_ITEM_EA_SK_BA_Link.EA_ITEMID = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID LEFT OUTER JOIN
EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMID = EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.ITEMID ON EKS.SUPPLIER.SUPPLIERNO = EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.SUPPLIERNO LEFT OUTER JOIN
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry_2 ON EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.ITEMNO = EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO AND
EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.LISTINGOVERVIEWID = EKS_CALCULATION.stEKS_LISTINGOVERVIEWMAX.LISTINGOVERVIEWID AND EKS.SUPPLIER.SUPPLIERNO = EKS_CALCULATION.xtEKS_BASICINFO_RecCountry.SUPPLIERNO LEFT OUTER JOIN
EKS_CALCULATION.EKS_ZSM_ExcludeList_2 ON EKS_CALCULATION.stMARA_EKS_ITEM.ITEMNO = EKS_CALCULATION.EKS_ZSM_ExcludeList.ITEMNO AND ( ( IfNULL(EKS.SUPPLIER.INTSUPPLIERNO, steks_supplier_1.INTSUPPLIERNO) = EKS_CALCULATION.EKS_ZSM_ExcludeList.SUPPLIERNO ) OR ( EKS_CALCULATION.EKS_ZSM_ExcludeList.SupplierNo IS NULL ) ) AND EKS_CALCULATION.EKS_ZSM_ExcludeList.REPORTNO = '054'
WHERE  (EKS_CALCULATION.stMARA_EKS_ITEM.zActive = 1) AND (EKS_CALCULATION.stMARA_EKS_ITEM.zArticleType = 'EA') AND ( EKS_CALCULATION.EKS_ZSM_ExcludeList.ITEMNO IS NULL )

);