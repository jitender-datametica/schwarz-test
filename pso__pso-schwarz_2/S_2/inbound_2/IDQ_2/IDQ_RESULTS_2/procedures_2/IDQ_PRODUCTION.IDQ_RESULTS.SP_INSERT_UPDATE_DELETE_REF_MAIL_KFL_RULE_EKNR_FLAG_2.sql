CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_KFL_RULE_EKNR_FLAG("REF_MAIL_KFL_RULE_EKNR_FLAG_ID" NUMBER(38,0), "RULE_ID" NUMBER(38,0), "COUNTRY_ID" NUMBER(38,0), "EK_NR_FLAG" NUMBER(38,0), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE EKNR_COUNTRY_Comb_exist number(38,0);
BEGIN
EKNR_COUNTRY_Comb_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_KFL_RULE_EKNR_FLAG_2 WHERE RULE_ID = :RULE_ID and COUNTRY_ID = :COUNTRY_ID and EK_NR_FLAG = :EK_NR_FLAG);
   -- Delete from contact_2 table for @REF_MAIL_KFL_EKNR_MAIL_ID if @DELETE equals 1
    IF (DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_MAIL_KFL_RULE_EKNR_FLAG_2 WHERE ID = :REF_MAIL_KFL_RULE_EKNR_FLAG_ID;
    --    RETURN 0;
   -- END IF;

    -- INSERT NEW EKNR
    elseIF (DEL = 0 and REF_MAIL_KFL_RULE_EKNR_FLAG_ID = 0 and EKNR_COUNTRY_Comb_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_MAIL_KFL_RULE_EKNR_FLAG_2
        (RULE_ID, COUNTRY_ID, EK_NR_FLAG) VALUES (:RULE_ID, :COUNTRY_ID, :EK_NR_FLAG);
       -- RETURN 0;
        
  --  END IF;
    --	Merge into REF_MAIL_KFL_RULE_EKNR_MAIL_2
    else
    MERGE INTO IDQ_RESULTS.REF_MAIL_KFL_RULE_EKNR_FLAG_2 AS TARGET
    USING 
    (SELECT :REF_MAIL_KFL_RULE_EKNR_FLAG_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.EK_NR_FLAG <> :EK_NR_FLAG THEN
            UPDATE SET EK_NR_FLAG = :EK_NR_FLAG;
            end if;
            commit;
            return 1;
END';