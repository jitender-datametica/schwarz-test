CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_SP_WERK("REF_MAIL_SP_WERK_ID" NUMBER(38,0), "WERK" VARCHAR(255), "DEL" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE WERK_exist number(38,0);
BEGIN
WERK_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_SP_WERK_2 WHERE WERK = :WERK);
    IF (:DEL = 1) THEN
        DELETE from IDQ_RESULTS.REF_MAIL_SP_WERK_2 WHERE ID = :REF_MAIL_SP_WERK_ID;
      --  RETURN 0;
   -- END IF;
   
    -- INSERT NEW WERK
    elseIF (:REF_MAIL_SP_WERK_ID = 0 AND :DEL = 0 and WERK_exist is NULL) THEN
        INSERT INTO IDQ_RESULTS.REF_MAIL_SP_WERK_2
        (ID,WERK) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_MAIL_SP_WERK_2),:WERK);
        -- RETURN 0;
    --END IF;
else 
    MERGE INTO IDQ_RESULTS.REF_MAIL_SP_WERK_2 AS TARGET
    USING 
    (SELECT :REF_MAIL_SP_WERK_ID AS ID) AS SOURCE(ID)
        ON Target.ID = SOURCE.ID
        WHEN MATCHED AND TARGET.WERK <> :WERK THEN
            UPDATE SET WERK = :WERK;

            end if;
            commit;

            return 1;
END';