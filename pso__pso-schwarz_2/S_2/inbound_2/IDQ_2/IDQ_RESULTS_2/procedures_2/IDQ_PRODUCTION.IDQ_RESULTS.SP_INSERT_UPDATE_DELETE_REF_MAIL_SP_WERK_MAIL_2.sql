CREATE OR REPLACE PROCEDURE IDQ_PRODUCTION.IDQ_RESULTS.SP_INSERT_UPDATE_DELETE_REF_MAIL_SP_WERK_MAIL("REF_MAIL_SP_WERK_MAIL_ID" NUMBER(38,0), "MAIL" VARCHAR, "DEL" NUMBER(38,0), "RULE_ID" NUMBER(38,0), "WERK_ID" NUMBER(38,0), "WG_ID" NUMBER(38,0), "MATART_ID" NUMBER(38,0))
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE mail2_exist number(38,0);
BEGIN
 mail2_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_SP_MAIL_2 WHERE MAIL = :MAIL);
-- Delete rule mail combinations from REF_MAIL_KFL_RULE_EKNR_MAIL_2
  IF (1 = :DEL) THEN
  DELETE from IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_MAIL_2 WHERE ID = :REF_MAIL_SP_WERK_MAIL_ID;
-- Insert new mail and rule mail combination
   elseif (0 = :DEL and 0 = :REF_MAIL_SP_WERK_MAIL_ID and mail2_exist is NULL) THEN
 INSERT INTO IDQ_RESULTS.REF_MAIL_SP_MAIL_2(MAIL) VALUES (:MAIL);
    mail2_exist := (SELECT ID FROM IDQ_RESULTS.REF_MAIL_SP_MAIL_2 WHERE MAIL = :MAIL);
                INSERT INTO IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_MAIL_2 (ID, RULE_ID, REF_MAIL_SP_WERK_ID, REF_MAIL_SP_WG_ID, REF_MAIL_SP_MATART_ID, MAIL_ID) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_MAIL_2),:RULE_ID, :WERK_ID, :WG_ID, :MATART_ID, :mail2_exist);
-- Insert rule mail combination with existing mail
  elseif (0 = :DEL and 0 = :REF_MAIL_SP_WERK_MAIL_ID  and mail2_exist is not NULL) THEN
 INSERT INTO IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_MAIL_2 (ID, RULE_ID, MAIL_ID, REF_MAIL_SP_WERK_ID, REF_MAIL_SP_WG_ID, REF_MAIL_SP_MATART_ID) VALUES ((select max(ID)+1 from IDQ_RESULTS.REF_MAIL_SP_RULE_WERK_MAIL_2),:RULE_ID, :mail2_exist,:WERK_ID, :WG_ID, :MATART_ID);

  END IF;
  commit;
  return 1;
END';