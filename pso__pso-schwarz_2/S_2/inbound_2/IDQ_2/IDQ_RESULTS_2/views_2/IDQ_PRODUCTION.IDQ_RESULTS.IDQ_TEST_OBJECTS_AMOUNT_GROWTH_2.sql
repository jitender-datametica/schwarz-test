create or replace VIEW IDQ_PRODUCTION.IDQ_RESULTS.IDQ_TEST_OBJECTS_AMOUNT_GROWTH_2(
	REF_SOURCE_SYSTEM_ID,
	REF_COUNTRY_ID,
	REF_RULE_ID,
	REF_TEST_OBJECT_TYPE_ID,
	TEST_RESULT_AMOUNT,
	PREVIOUS_VALUE,
	GROWTH_PERCENTAGE
) as
WITH daily_growth AS (
    SELECT
        REF_SOURCE_SYSTEM_ID,
        REF_COUNTRY_ID,
        REF_RULE_ID,
        REF_TEST_OBJECT_TYPE_ID,
        TEST_RESULT_AMOUNT AS TEST_RESULT_AMOUNT,
        LAG(TEST_RESULT_AMOUNT) OVER (PARTITION BY  REF_SOURCE_SYSTEM_ID,
        REF_COUNTRY_ID,
        REF_RULE_ID,
        REF_TEST_OBJECT_TYPE_ID ORDER BY CHECK_RULE_BY_COUNTRY_CALCULATION_TIME) AS previous_value
    FROM
        DWH.CHECK_RULE_BY_COUNTRY_SUMMARY_2
    WHERE  
        CHECK_RULE_BY_COUNTRY_CALCULATION_TIME > DATEADD(DAY, -15, sysdate()) and CHECK_RULE_BY_COUNTRY_CALCULATION_TIME < DATEADD(DAY, -1, sysdate())
    GROUP BY CHECK_RULE_BY_COUNTRY_CALCULATION_TIME, TEST_RESULT_AMOUNT,
        REF_SOURCE_SYSTEM_ID,
        REF_COUNTRY_ID,
        REF_RULE_ID,
        REF_TEST_OBJECT_TYPE_ID
)
 SELECT
    REF_SOURCE_SYSTEM_ID,
    REF_COUNTRY_ID,
    REF_RULE_ID,
    REF_TEST_OBJECT_TYPE_ID,
    AVG(TEST_RESULT_AMOUNT) TEST_RESULT_AMOUNT,
    AVG(previous_value) PREVIOUS_VALUE,
    (AVG(TEST_RESULT_AMOUNT) - AVG(previous_value)) / AVG(previous_value) * 100 AS growth_percentage
FROM
    daily_growth 
WHERE
    previous_value > 0
GROUP BY
    REF_SOURCE_SYSTEM_ID,
    REF_COUNTRY_ID,
    REF_RULE_ID,
    REF_TEST_OBJECT_TYPE_ID;