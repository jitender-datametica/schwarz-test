create or replace VIEW IDQ_PRODUCTION.IDQ_RESULTS.IDQ_WAWI_ZSM_SST_SUPPLIER_OLD_2(
	REGEL_ID,
	CATALOG_ID,
	REGELKURZBESCHREIBUNG,
	FEHLERMELDUNG,
	REGELGRUPPENAME,
	KRITIKALITAET,
	SCORE,
	OBJEKT_ID,
	LIEFNR,
	LIEFERANT,
	STATUSLIEFERANT,
	KONTENGRUPPE,
	EKSNUMMER,
	LAND_2,
	M,
	NF,
	EM,
	O_G,
	B_P,
	IMP,
	VERHANDELNDESLAND,
	UMSATZSTEUERIDNR,
	WEITEREUSTID,
	PRUEFFELD,
	GEPRUEFTERINHALT,
	ZUSAETZLINFO,
	EKORG,
	FEHLERHAFTSEIT,
	FAEHLIGKEITSDATUM,
	REF_CALCULATION_TIME
) as 
SELECT 
REGEL_ID,
CATALOG_ID,
REGELKURZBESCHREIBUNG,
FEHLERMELDUNG,
REGELGRUPPENAME,
KRITIKALITAET,
SCORE,
OBJEKT_ID,
LIEFNR,	
LIEFERANT,
STATUSLIEFERANT,
KONTENGRUPPE,	
EKSNUMMER,
LAND_2,
M,
NF,
EM,
O_G,
B_P,
IMP,
VERHANDELNDESLAND,
UMSATZSTEUERIDNR,
WEITEREUSTID,
PRUEFFELD,
GEPRUEFTERINHALT,
ZUSAETZLINFO,
EKORG, 
MAX(FEHLERHAFTSEIT) as FEHLERHAFTSEIT, 
MAX(FAEHLIGKEITSDATUM) as FAEHLIGKEITSDATUM,
MAX(REF_CALCULATION_TIME) as REF_CALCULATION_TIME
FROM
(select DISTINCT
CTR.REF_RULE_ID AS Regel_ID,
rrl.CATALOG_ID AS CATALOG_ID,
rrl.SHORT_DESCRIPTION_DE AS RegelKurzbeschreibung,
rrl.ERROR_TEXT_DE AS Fehlermeldung,
rrg.NAME_DE AS RegelgruppeName,
rcr.NAME_DE AS Kritikalitaet,
ito.SCORE,
CTR.IDQ_TEST_OBJECT_ID AS Objekt_ID,
ITO.SOURCE_SYSTEM_PRIMARY_KEY AS LiefNr,
ITO.NAME AS Lieferant,
ADI.StatusLieferant AS StatusLieferant,
ADI.Kontengruppe AS Kontengruppe,
ADI.EKS_NUMMER AS EKSNummer,
ADI.Land_2 AS Land_2,
ADI.M AS M,
ADI.NF AS NF,
ADI.EM AS EM,
ADI.O_G AS O_G,
ADI.B_P AS B_P,
ADI.IMP AS IMP,
ADI.VerhandelndesLand AS VerhandelndesLand,
ADI.UMSATZSTEUER_IDNR AS UmsatzsteuerIdNr,
ADI.WeitereUstID AS WeitereUstID,
rf.NAME_DE AS Prueffeld,
cei.INVALID_CONTENT AS GepruefterInhalt,
cei.ADDITIONAL_INFO_DE ZusaetzlInfo,
SUBSTRING(cei.ADDITIONAL_INFO_DE, 8, 4) AS EKORG,
CTR.FIRST_NEGATIVE_TEST AS Fehlerhaftseit,
CTR.DUE_DATE AS Faehligkeitsdatum,
crbcs.check_rule_by_country_calculation_time as REF_CALCULATION_TIME
FROM dwh.CHECK_TEST_RESULT_2 ctr
  join DWH.IDQ_TEST_OBJECT_2 ito
	on ito.IDQ_TEST_OBJECT_ID = ctr.IDQ_TEST_OBJECT_ID
  join idq_results.IDQ_ADDINFO_ZSM_SUPPLIER_SST_2 adi
	on ito.IDQ_TEST_OBJECT_ID = adi.TEST_OBJECT_ID
  join idq_results.REF_RULE_2 rrl
    on CTR.REF_RULE_ID = rrl.ID
	join idq_results.REF_REL_RULE_GROUP_RULE_2 rgr
	on rrl.ID = rgr.RULE_ID
  join idq_results.REF_RULE_GROUP_2 rrg
	on rgr.RULE_GROUP_ID = rrg.ID
  join idq_results.REF_CRITICALITY_2 rcr
    on rcr.ID = rrl.CRITICALITY_ID
  join idq_results.REF_FIELD_2 rf
    on rf.ID = rrl.FIELD_ID
  join idq_results.CHECK_ERROR_INFO_CURRENT_2 cei
    on cei.TEST_OBJECT_ID = ito.IDQ_TEST_OBJECT_ID AND cei.RULE_ID = rrl.ID
  join dwh.CHECK_RULE_BY_COUNTRY_SUMMARY_2 crbcs
    on ctr.REF_RULE_ID = crbcs.ref_rule_id
  where ctr.REF_RULE_ID = 383 and IS_ERROR_DETECTED =1)
GROUP BY (REGEL_ID,CATALOG_ID,REGELKURZBESCHREIBUNG,FEHLERMELDUNG,REGELGRUPPENAME,KRITIKALITAET,SCORE,OBJEKT_ID,LIEFNR,	LIEFERANT,STATUSLIEFERANT,KONTENGRUPPE,	EKSNUMMER,LAND_2,M,NF,EM,O_G,B_P,IMP,VERHANDELNDESLAND,UMSATZSTEUERIDNR,WEITEREUSTID,PRUEFFELD,GEPRUEFTERINHALT,ZUSAETZLINFO,EKORG);