 CORE.T_DIM_ALERTS_LOCATION.ALERTS_LOCATION_ID
,CORE.T_DIM_ALERTS_LOCATION.ALERTS_LOCATION_CLASSIFICATION_ID
,CORE.T_DIM_ALERTS_LOCATION.ALERTS_LOCATION_PARENT_ID
,CORE.T_DIM_ALERTS_LOCATION.ALERTS_LOCATION_HIERARCHY_LEVEL_ID
,CORE.T_DIM_ALERTS_LOCATION.ALERTS_LOCATION_DESC
