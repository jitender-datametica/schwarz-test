CREATE OR REPLACE VIEW FE_MSTR_BGE_PALETTIERER.V_REL_ALERTS_PRIORITY_TO_PRODUCTION_STOP_FLAG_2
AS
SELECT ALERTS_PRIORITY_ID, ALERTS_PRODUCTION_STOP_FG
FROM FE_MSTR_BGE_PALETTIERER.V_DIM_ALERTS_PRIORITY_2
cross join
FE_MSTR_BGE_PALETTIERER.V_DIM_PRODUCTION_STOP_FLAG_2
WHERE (ALERTS_PRIORITY_ID <> 5 OR ALERTS_PRODUCTION_STOP_FG = FALSE)
;