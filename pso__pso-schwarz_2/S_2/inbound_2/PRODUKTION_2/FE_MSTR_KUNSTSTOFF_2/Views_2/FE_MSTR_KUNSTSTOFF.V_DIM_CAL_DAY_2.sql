CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_DIM_CAL_DAY_2(
	CAL_DT
	,CY
	,BUS_YEAR
	,CY_MONTH
	,MONTH_OF_YEAR
	,MONTH_OF_BUS_YEAR
	,MONTH_OF_YEAR_NAME
	,DAY_OF_MONTH
	,CY_WEEK
	,WEEK_OF_YEAR
	,CY_WEEK_PART
	,DAY_OF_WEEK
	,DAY_OF_WEEK_NAME
	,DAY_OF_CY
	,DAY_OF_BUS_YEAR
	,CAL_DT_OFFSET
) AS
SELECT
 CAL_DT
,CY
,BUS_YEAR
,CY_MONTH
,MONTH_OF_YEAR
,MONTH_OF_BUS_YEAR
,MONTH_OF_YEAR_NAME
,DAY_OF_MONTH
,CY_WEEK
,WEEK_OF_YEAR
,CY_WEEK_PART                              
,DAY_OF_WEEK          
,DAY_OF_WEEK_NAME
,DAY_OF_CY
,DAY_OF_BUS_YEAR
,DATEDIFF(DAY, CURRENT_DATE(), CAL_DT) AS CAL_DT_OFFSET
FROM
CORE.T_DIM_CAL_DAY_2
;