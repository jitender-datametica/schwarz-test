CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_DIM_PRODUCTION_LINE_2(
	RESOURCE_ITEM_SID
	,PLANT_RESOURCE_ITEM_SID
	,PRODUCTION_LINE_NAME
	,PLANT_NAME
) AS
SELECT
 PRL1.PRODUCTION_LINE_ID AS RESOURCE_ITEM_SID
,PLA1.PLANT_NAME AS PLANT_RESOURCE_ITEM_SID
,PRL1.PRODUCTION_LINE_NAME
,PLA1.PLANT_NAME
FROM
CORE.T_DIM_PRODUCTION_LINE_2 AS PRL1
JOIN CORE.T_DIM_PLANT_2 AS PLA1
ON PRL1.PLANT_RESOURCE_ITEM_SID = PLA1.RESOURCE_ITEM_SID
;