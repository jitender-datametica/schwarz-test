CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_DIM_WAREHOUSE_2(
	RESOURCE_ITEM_SID
	,PLANT_RESOURCE_ITEM_SID
	,WAREHOUSE_NAME
	,PLANT_NAME
	,WAREHOUSE_TYPE_NAME
) AS
SELECT
 WRH1.WAREHOUSE_NAME AS RESOURCE_ITEM_SID
,PLA1.PLANT_NAME AS PLANT_RESOURCE_ITEM_SID
,WRH1.WAREHOUSE_NAME AS WAREHOUSE_NAME
,PLA1.PLANT_NAME AS PLANT_NAME
,WRH1.WAREHOUSE_TYPE_NAME AS WAREHOUSE_TYPE_NAME
FROM
CORE.T_DIM_WAREHOUSE_2 AS WRH1
JOIN CORE.T_DIM_PLANT_2 AS PLA1
ON WRH1.PLANT_RESOURCE_ITEM_SID = PLA1.RESOURCE_ITEM_SID
;