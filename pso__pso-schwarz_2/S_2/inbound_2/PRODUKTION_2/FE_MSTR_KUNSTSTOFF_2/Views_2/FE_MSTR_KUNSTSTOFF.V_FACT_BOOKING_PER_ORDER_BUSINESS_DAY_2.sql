CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_FACT_BOOKING_PER_ORDER_BUSINESS_DAY_2(
	 ORDER_ID
	,ORDER_NR
	,PRODUCTION_LINE_RESOURCE_ITEM_SID
	,MATERIAL_RESOURCE_ITEM_SID
	,BOOKING_BUSINESS_DT
	,MOVEMENT_TYPE_ID
	,MATERIAL_GROUP_RESOURCE_ITEM_GROUP_SID
	,ORDER_START_DT
	,ORDER_END_DT
	,ORDER_START_TMSP
	,ORDER_END_TMSP
	,PRODUCTION_LINE_START_TMSP
	,PRODUCTION_LINE_END_TMSP
	,CONSUMED_MATERIAL_QTY
	,PRODUCED_MATERIAL_QTY
	,DWH_SRC_1_TMSP
   ,MAX_BOOKING_TMSP
) AS
SELECT
    ORDER_ID
   ,ORDER_NR 
   ,TD1.PRODUCTION_LINE_ID AS PRODUCTION_LINE_RESOURCE_ITEM_SID
   ,TD2.MATERIAL_ID AS MATERIAL_RESOURCE_ITEM_SID
   ,BOOKING_BUSINESS_DT
   ,MOVEMENT_TYPE_ID
   ,TD3.MATERIAL_GROUP_NR AS MATERIAL_GROUP_RESOURCE_ITEM_GROUP_SID
   ,ORDER_START_DT
   ,ORDER_END_DT
   ,ORDER_START_TMSP
   ,ORDER_END_TMSP
   ,PRODUCTION_LINE_START_TMSP
   ,PRODUCTION_LINE_END_TMSP
   ,CONSUMED_MATERIAL_QTY
   ,PRODUCED_MATERIAL_QTY
   ,TF1.DWH_SRC_1_TMSP AS DWH_SRC_1_TMSP
   ,TF1.MAX_BOOKING_TMSP
FROM
   CORE.T_FACT_BOOKING_PER_ORDER_BUSINESS_DAY_2 TF1
   JOIN CORE.T_DIM_PRODUCTION_LINE_2 TD1
   ON TF1.PRODUCTION_LINE_RESOURCE_ITEM_SID = TD1.RESOURCE_ITEM_SID
   JOIN CORE.T_DIM_MATERIAL_2 TD2
   ON TF1.MATERIAL_RESOURCE_ITEM_SID = TD2.RESOURCE_ITEM_SID
   JOIN CORE.T_DIM_MATERIAL_GROUP_2 TD3
   ON TF1.MATERIAL_GROUP_RESOURCE_ITEM_GROUP_SID = TD3.RESOURCE_ITEM_GROUP_SID
;