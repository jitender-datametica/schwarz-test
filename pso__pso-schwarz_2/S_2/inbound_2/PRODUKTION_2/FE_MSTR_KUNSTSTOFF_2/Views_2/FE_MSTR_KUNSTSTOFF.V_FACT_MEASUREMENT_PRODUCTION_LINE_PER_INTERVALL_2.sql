) AS 
SELECT
  prl1.PRODUCTION_LINE_ID AS PRODUCTION_LINE_RESOURCE_ITEM_SID
, matr1.MATERIAL_ID AS MATERIAL_RESOURCE_ITEM_SID
, mpl.MEASUREMENT_DT AS MEASUREMENT_DT
, mpl.MEASUREMENT_TM AS MEASUREMENT_TM
, mpl.MEASUREMENT_TMSP AS MEASUREMENT_TMSP
, CONCAT(TO_CHAR(prl1.PRODUCTION_LINE_ID),prm.PRODUCTION_LINE_PARAMETER_CD) AS PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
, prm.UNIT_ID AS UNIT_ID
, prm.GRANULARITY_TYPE AS GRANULARITY_TYPE
, CASE
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_2_MAG01_0202'
    ) THEN mpl.AVG_FEEDER_SPEED_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_2_MAG01_0198','MVA_L2_2_MAG01_0172'
    ) THEN mpl.AVG_FEEDER_SPEED_PCT
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_3_MAG01_170'
    ) THEN mpl.AVG_BULK_MATERIAL_BALANCE_BUFFERSILO_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_4_MAG01_770','MVA_L2_4_MAG01_376','MVA_L3_4_MAG01_0376'
    ) THEN mpl.AVG_EXTRUDER_OUTPUT_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_4_MAG02_210','MVA_L2_4_MAG02_0384','MVA_L3_4_MAG02_0384'
    ) THEN mpl.AVG_FILL_LEVEL_REACTOR_VESSEL_PCT
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'Throughput_Preform'
    ) THEN mpl.AVG_THROUGHPUT_PREFORM_QTY
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_3_MAG01_296'
    ) THEN mpl.AVG_BULK_MATERIAL_BALANCE_BUFFERSILO_OUT_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L2_2_MAG01_0504'
    ) THEN mpl.AVG_BALE_WEIGHT_QTY
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'Bulk_material_balance_Washing'
    ) THEN mpl.AVG_BULK_MATERIAL_BALANCE_WASHING_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_7_MAG01_0674'
    ) THEN mpl.AVG_FEEDER_UTILIZATION_MILL_UNIT_OUTPUT_SILO_PCT
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_7_MAG01_0682'
    ) THEN mpl.AVG_FEEDER_UTILIZATION_MILL_UNIT_PCT
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_3_MAG01_190','MVA_L2_3_MAG01_0308'
    ) THEN mpl.AVG_WASHER_TANK_TEMPERATURE_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_3_MAG01_250','MVA_L2_3_MAG01_0364'
    ) THEN mpl.AVG_REWASHER_TANK_TEMPERATURE_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_4_MAG01_786','MVA_L2_4_MAG01_960','MVA_L3_4_MAG01_0960'
    ) THEN mpl.AVG_INLINE_IV_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_4_MAG02_208','MVA_L2_4_MAG02_0536','MVA_L3_4_MAG02_0536'
    ) THEN mpl.AVG_REGRANULATION_VACUUM_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
    'MVA_L1_1_MAG01_200','MVA_L1_1_MAG01_464','MVA_L2_1_MAG01_200','MVA_L4_1_MAG01_200','MVA_L5_1_MAG01_200','MVA_L6_1_MAG01_200'
    ,'MVA_L7_1_MAG02_188','MVA_L8_1_MAG01_200','MVA_L9_1_MAG01_200','MVA_L10_1_MAG01_200','MVA_L11_1_MAG01_200','MVA_L12_1_MAG01_200'
    ,'MVA_L13_1_MAG01_200','MVA_L13_1_MAG01_464'
    ) THEN mpl.AVG_HEATING_BOX_TEMPERATURE_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
    'MVA_L1_1_MAG01_222','MVA_L2_1_MAG01_222','MVA_L4_1_MAG01_222','MVA_L5_1_MAG01_222','MVA_L6_1_MAG01_222'
    ,'MVA_L7_1_MAG02_784','MVA_L8_1_MAG01_222','MVA_L9_1_MAG01_222','MVA_L10_1_MAG01_222','MVA_L11_1_MAG01_222'
    ,'MVA_L12_1_MAG01_222','MVA_L13_1_MAG01_222'
    ) THEN mpl.AVG_BOOSTER_TEMPERATURE_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
    'MVA_L1_1_MAG01_172','MVA_L2_1_MAG01_172','MVA_L4_1_MAG01_172','MVA_L5_1_MAG01_172','MVA_L6_1_MAG01_172'
    ,'MVA_L7_1_MAG02_228','MVA_L8_1_MAG01_172','MVA_L9_1_MAG01_172','MVA_L10_1_MAG01_172','MVA_L11_1_MAG01_172'
    ,'MVA_L12_1_MAG01_172','MVA_L13_1_MAG01_172'
    ) THEN mpl.AVG_DRYER_DEW_POINT_MEAS
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
    'MVA_L1_1_MAG01_178','MVA_L2_1_MAG01_178','MVA_L4_1_MAG01_178','MVA_L5_1_MAG01_178','MVA_L6_1_MAG01_178'
    ,'MVA_L8_1_MAG01_178','MVA_L9_1_MAG01_178','MVA_L10_1_MAG01_178','MVA_L11_1_MAG01_178','MVA_L12_1_MAG01_178'
    ,'MVA_L13_1_MAG01_178'
    ) THEN mpl.AVG_ETA_BOX_TEMPERATURE_MEAS
  END AS PARAMETER_PER_INTERVALL_VALUE
, COALESCE(tppmr.MIN_VAL, tppmr2.MIN_VAL) AS MIN_PARAMETER_PER_INTERVALL_VAL
, COALESCE(tppmr.MAX_VAL, tppmr2.MAX_VAL) AS MAX_PARAMETER_PER_INTERVALL_VAL
, COALESCE(tppmr.TARGET_VAL, tppmr2.TARGET_VAL) AS TARGET_PARAMETER_PER_INTERVALL_VAL
, COALESCE(tppmr.LOWER_WARNING_LIMIT_VAL, tppmr2.LOWER_WARNING_LIMIT_VAL) AS LOWER_WARNING_LIMIT_PARAMETER_PER_INTERVALL_VAL
, COALESCE(tppmr.UPPER_WARNING_LIMIT_VAL, tppmr2.UPPER_WARNING_LIMIT_VAL) AS UPPER_WARNING_LIMIT_PARAMETER_PER_INTERVALL_VAL
, mpl.INTERVAL_FIVE_MIN_HR AS INTERVAL_FIVE_MIN_HR
FROM CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_2 AS mpl
INNER JOIN CORE.T_DIM_PRODUCTION_LINE_PARAMETER_2 AS prm
  ON prm.PRODUCTION_LINE_RESOURCE_ITEM_SID = mpl.PRODUCTION_LINE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_MATERIAL_2 AS matr1
  ON matr1.RESOURCE_ITEM_SID = mpl.MATERIAL_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_PRODUCTION_LINE_2 prl1
  ON prl1.RESOURCE_ITEM_SID = mpl.PRODUCTION_LINE_RESOURCE_ITEM_SID
LEFT OUTER JOIN CORE.T_FACT_THRESHOLD_PARAMETER_PER_MATERIAL_REL_2 AS tppmr
  ON prm.RESOURCE_ITEM_SID = tppmr.PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
  AND mpl.MATERIAL_RESOURCE_ITEM_SID = tppmr.MATERIAL_RESOURCE_ITEM_SID
INNER JOIN CORE.T_FACT_THRESHOLD_PARAMETER_PER_MATERIAL_REL_2 AS tppmr2
  ON prm.RESOURCE_ITEM_SID = tppmr2.PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
  AND -1 = tppmr2.MATERIAL_RESOURCE_ITEM_SID  
WHERE prm.PRODUCTION_LINE_PARAMETER_CD IN (
  'MVA_L1_2_MAG01_0198','MVA_L2_2_MAG01_0172','MVA_L1_2_MAG01_0202','MVA_L1_3_MAG01_170','MVA_L1_4_MAG01_770','MVA_L2_4_MAG01_376','MVA_L3_4_MAG01_0376','MVA_L1_4_MAG02_210'
  ,'MVA_L2_4_MAG02_0384','MVA_L3_4_MAG02_0384','Throughput_Preform'
  ,'MVA_L1_3_MAG01_296','MVA_L2_2_MAG01_0504','Bulk_material_balance_Washing','MVA_L1_7_MAG01_0674','MVA_L1_7_MAG01_0682','MVA_L1_3_MAG01_190','MVA_L2_3_MAG01_0308'
  ,'MVA_L1_3_MAG01_250','MVA_L2_3_MAG01_0364','MVA_L1_4_MAG01_786','MVA_L2_4_MAG01_960','MVA_L3_4_MAG01_0960','MVA_L1_4_MAG02_208','MVA_L2_4_MAG02_0536','MVA_L3_4_MAG02_0536'
  ,'MVA_L1_1_MAG01_200','MVA_L1_1_MAG01_464','MVA_L2_1_MAG01_200','MVA_L4_1_MAG01_200','MVA_L5_1_MAG01_200','MVA_L6_1_MAG01_200','MVA_L7_1_MAG02_188','MVA_L8_1_MAG01_200'
  ,'MVA_L9_1_MAG01_200','MVA_L10_1_MAG01_200','MVA_L11_1_MAG01_200','MVA_L12_1_MAG01_200','MVA_L13_1_MAG01_200','MVA_L13_1_MAG01_464'
  ,'MVA_L1_1_MAG01_222','MVA_L2_1_MAG01_222','MVA_L4_1_MAG01_222','MVA_L5_1_MAG01_222','MVA_L6_1_MAG01_222','MVA_L7_1_MAG02_784','MVA_L8_1_MAG01_222','MVA_L9_1_MAG01_222'
  ,'MVA_L10_1_MAG01_222','MVA_L11_1_MAG01_222','MVA_L12_1_MAG01_222','MVA_L13_1_MAG01_222'
  ,'MVA_L1_1_MAG01_172','MVA_L2_1_MAG01_172','MVA_L4_1_MAG01_172','MVA_L5_1_MAG01_172','MVA_L6_1_MAG01_172','MVA_L7_1_MAG02_228','MVA_L8_1_MAG01_172'
  ,'MVA_L9_1_MAG01_172','MVA_L10_1_MAG01_172','MVA_L11_1_MAG01_172','MVA_L12_1_MAG01_172','MVA_L13_1_MAG01_172'
  ,'MVA_L1_1_MAG01_178','MVA_L2_1_MAG01_178','MVA_L4_1_MAG01_178','MVA_L5_1_MAG01_178','MVA_L6_1_MAG01_178','MVA_L8_1_MAG01_178','MVA_L9_1_MAG01_178','MVA_L10_1_MAG01_178'
  ,'MVA_L11_1_MAG01_178','MVA_L12_1_MAG01_178','MVA_L13_1_MAG01_178'
  )
