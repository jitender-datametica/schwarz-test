CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_MOVING_2(
	PRODUCTION_LINE_RESOURCE_ITEM_SID
	,SHIFT_ID
	,MEASUREMENT_DT
	,MEASUREMENT_TM
	,MEASUREMENT_TMSP
	,PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
	,UNIT_ID
	,GRANULARITY_TYPE
	,PARAMETER_PER_INTERVALL_MOVING_VALUE
	,MIN_PARAMETER_PER_INTERVALL_MOVING_VAL
	,MAX_PARAMETER_PER_INTERVALL_MOVING_VAL
	,TARGET_PARAMETER_PER_INTERVALL_MOVING_VAL
	,LOWER_WARNING_LIMIT_PARAMETER_PER_INTERVALL_MOVING_VAL
	,UPPER_WARNING_LIMIT_PARAMETER_PER_INTERVALL_MOVING_VAL
	,INTERVAL_FIVE_MIN_HR
) AS 
SELECT
  prl1.PRODUCTION_LINE_ID AS PRODUCTION_LINE_RESOURCE_ITEM_SID
, mpl.SHIFT_ID AS SHIFT_ID
, mpl.MEASUREMENT_DT AS MEASUREMENT_DT
, mpl.MEASUREMENT_TM AS MEASUREMENT_TM
, mpl.MEASUREMENT_TMSP AS MEASUREMENT_TMSP
, CONCAT(TO_CHAR(prl1.PRODUCTION_LINE_ID),prm.PRODUCTION_LINE_PARAMETER_CD) AS PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
, prm.UNIT_ID AS UNIT_ID
, prm.GRANULARITY_TYPE AS GRANULARITY_TYPE
, CASE
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_3_MAG01_340'
    ) THEN mpl.NAOH_DOSAGE_QTY
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'MVA_L1_3_MAG01_342'
    ) THEN mpl.ADDED_ADDITIVE_QTY
    WHEN prm.PRODUCTION_LINE_PARAMETER_CD IN (
	'Detergent_dosage_rate'
    ) THEN mpl.DETERGENT_DOSAGE_RATE
  END AS PARAMETER_PER_INTERVALL_MOVING_VALUE
, tppmr.MIN_VAL AS MIN_PARAMETER_PER_INTERVALL_MOVING_VAL
, tppmr.MAX_VAL AS MAX_PARAMETER_PER_INTERVALL_MOVING_VAL
, tppmr.TARGET_VAL AS TARGET_PARAMETER_PER_INTERVALL_MOVING_VAL
, tppmr.LOWER_WARNING_LIMIT_VAL AS LOWER_WARNING_LIMIT_PARAMETER_PER_INTERVALL_MOVING_VAL
, tppmr.UPPER_WARNING_LIMIT_VAL AS UPPER_WARNING_LIMIT_PARAMETER_PER_INTERVALL_MOVING_VAL
, mpl.INTERVAL_FIVE_MIN_HR AS INTERVAL_FIVE_MIN_HR
FROM CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_MOVING_2 AS mpl
INNER JOIN CORE.T_DIM_PRODUCTION_LINE_PARAMETER_2 AS prm
  ON prm.PRODUCTION_LINE_RESOURCE_ITEM_SID = mpl.PRODUCTION_LINE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_DIM_PRODUCTION_LINE_2 prl1
  ON prl1.RESOURCE_ITEM_SID = mpl.PRODUCTION_LINE_RESOURCE_ITEM_SID
INNER JOIN CORE.T_FACT_THRESHOLD_PARAMETER_PER_MATERIAL_REL_2 AS tppmr
  ON prm.RESOURCE_ITEM_SID = tppmr.PRODUCTION_LINE_PARAMETER_RESOURCE_ITEM_SID
WHERE prm.PRODUCTION_LINE_PARAMETER_CD IN (
   'MVA_L1_3_MAG01_340','MVA_L1_3_MAG01_342','Detergent_dosage_rate'
  )
;