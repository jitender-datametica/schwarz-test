CREATE OR REPLACE VIEW FE_MSTR_KUNSTSTOFF.V_TECH_TABLE_LOADS_TMSP_2(
	SORTING_ORDER
	, FACT_TABLE
	, MAX_TMSP
	, MAX_DATA_TMSP
	, CURRENT_TMSP
) AS
SELECT 
   1 AS SORTING_ORDER
   , 'CORE.T_FACT_BOOKING_PER_ORDER_BUSINESS_DAY_2' AS FACT_TABLE
   , MAX(DWH_SRC_1_TMSP)::TIMESTAMP_TZ AS MAX_TMSP
   , MAX(MAX_BOOKING_TMSP)::TIMESTAMP_TZ AS MAX_DATA_TMSP
   , CURRENT_TIMESTAMP() AS CURRENT_TMSP
FROM 
   CORE.T_FACT_BOOKING_PER_ORDER_BUSINESS_DAY_2
WHERE MAX_BOOKING_TMSP < TO_TIMESTAMP('9999-12-31 23:59:59','YYYY-MM_2-DD HH24:MI:SS')::TIMESTAMP_TZ
UNION
SELECT 
   2
   , 'CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_2'
   , MAX(DWH_SRC_1_TMSP)
   , MAX(Measurement_TMSP)
   , CURRENT_TIMESTAMP() 
FROM 
   CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_2
UNION
SELECT 
   3
   , 'CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_2'
   , MAX(DWH_SRC_1_TMSP)
   , MAX(Measurement_TMSP)
   , CURRENT_TIMESTAMP() 
FROM 
   CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_2
UNION
SELECT 
   4
   , 'CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_MOVING_2'
   , MAX(DWH_SRC_1_TMSP)
   , MAX(Measurement_TMSP)
   , CURRENT_TIMESTAMP() 
FROM 
   CORE.T_FACT_MEASUREMENT_PRODUCTION_LINE_PER_INTERVALL_MOVING_2
UNION
SELECT 
   5
   , 'CORE.T_FACT_MEASUREMENT_SILO_2'
   , MAX(DWH_SRC_1_TMSP)
   , MAX(Measurement_TMSP)
   , CURRENT_TIMESTAMP() 
FROM 
   CORE.T_FACT_MEASUREMENT_SILO_2
UNION
SELECT 
   6
   , 'CORE.T_FACT_ORDER_2'
   , MAX(DWH_SRC_1_TMSP)
   , MAX(DWH_SRC_1_TMSP)
   , CURRENT_TIMESTAMP() 
FROM 
   CORE.T_FACT_ORDER_2
UNION
SELECT 
   7
   , 'CORE.T_FACT_THRESHOLD_PARAMETER_PER_MATERIAL_REL_2'
   , MAX(DWH_SRC_1_TMSP)
   , MAX(DWH_SRC_1_TMSP)
   , CURRENT_TIMESTAMP() 
FROM 
   CORE.T_FACT_THRESHOLD_PARAMETER_PER_MATERIAL_REL_2
;