create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_CAMPAIGN_AUDIENCE_SHOPPER_CATEGORIES_2(
	CAMPAIGN_ID,
	COUNTRY_ID,
	DIVISION_ID,
	DESCR_AUDIENCE_ID,
	CNT_SHOPPER_CAMPAIGN,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_AUDIENCE AS (
			SELECT DISTINCT FCT.CAMPAIGN_ID
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_2 FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
					'GEN'
					,'AGE'
					,'VIE'
					,'ZIP'
					)
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_CAMPAIGN AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,CAMPAIGN_ID
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_CAMPAIGN
			FROM SHOPPERS_BY_AUDIENCE
			GROUP BY 1
				,2
				,3
			)

SELECT SBA.CAMPAIGN_ID
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_CAMPAIGN
	,COUNT(DISTINCT SBA.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_AUDIENCE SBA
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON SBA.COUNTRY_ID = DA.COUNTRY_ID
	AND SBA.DIVISION_ID = DA.DIVISION_ID
	AND SBA.SHOPPER_ID = DA.SHOPPER_ID
JOIN CNT_CAMPAIGN ON SBA.COUNTRY_ID = CNT_CAMPAIGN.COUNTRY_ID
	AND SBA.DIVISION_ID = CNT_CAMPAIGN.DIVISION_ID
	AND SBA.CAMPAIGN_ID = CNT_CAMPAIGN.CAMPAIGN_ID
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
		'GEN'
		,'AGE'
		,'VIE'
		,'ZIP'
		)
JOIN CORE.T_DIM_CAMPAIGN_2 DC ON SBA.COUNTRY_ID = DC.COUNTRY_ID
	AND SBA.DIVISION_ID = DC.DIVISION_ID
	AND SBA.CAMPAIGN_ID = DC.CAMPAIGN_ID
	AND COALESCE(DC.CLICK_QTY, 0) > 0
	AND COALESCE(DC.SALES_VAL, 0) > 0
GROUP BY SBA.CAMPAIGN_ID
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_CAMPAIGN;
