create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_FAMILYGRP_OWG_AUDIENCE_SHOPPER_GENDER_AGE_2(
	FAMILYGRP_OWG,
	COUNTRY_ID,
	DIVISION_ID,
	GENDER,
	AGE,
	CNT_SHOPPER_FAMILYGRP_OWG,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_GENDER AS (
			SELECT DISTINCT A14.FAMILYGRP_OWG
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_2 FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) = 'GEN'
                JOIN	FE_MSTR_SMP.V_DIM_ITEM_2	A12
				ON 	(FCT.COUNTRY_ID = A12.COUNTRY_ID AND 
				FCT.DIVISION_ID = A12.DIVISION_ID AND 
				FCT.GTIN_ID = A12.GTIN_ID)
			JOIN	FE_MSTR_SMP.V_REL_WG_ITEMFAMILY_OWG_2	A13
				ON 	(A12.COUNTRY_ID = A13.COUNTRY_ID AND 
				A12.DIVISION_ID = A13.DIVISION_ID AND 
				A12.TAXONOMY_ID = COALESCE(A13.WG, A13.FAMILYGRP_OWG, A13.WG))
			JOIN	FE_MSTR_SMP.V_REL_ITEMGRP_WG_FAMILYGROUP_OWG_2	A14
				ON 	(A13.COUNTRY_ID = A14.COUNTRY_ID AND 
				A13.DIVISION_ID = A14.DIVISION_ID AND 
				A13.FAMILYGRP_OWG = A14.FAMILYGRP_OWG)
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_FAMILYGRP_OWG AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,FAMILYGRP_OWG
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_FAMILYGRP_OWG
			FROM SHOPPERS_BY_GENDER
			GROUP BY 1
				,2
				,3
			)

SELECT SBG.FAMILYGRP_OWG
	,SBG.COUNTRY_ID
	,SBG.DIVISION_ID
	,SBG.DESCR_AUDIENCE_ID AS GENDER
	,DA.DESCR_AUDIENCE_ID AS AGE
	,CNT_SHOPPER_FAMILYGRP_OWG
	,COUNT(SBG.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_GENDER SBG
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON SBG.COUNTRY_ID = DA.COUNTRY_ID
	AND SBG.DIVISION_ID = DA.DIVISION_ID
	AND SBG.SHOPPER_ID = DA.SHOPPER_ID
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) = 'AGE'
JOIN CNT_FAMILYGRP_OWG ON SBG.COUNTRY_ID = CNT_FAMILYGRP_OWG.COUNTRY_ID
	AND SBG.DIVISION_ID = CNT_FAMILYGRP_OWG.DIVISION_ID
	AND SBG.FAMILYGRP_OWG = CNT_FAMILYGRP_OWG.FAMILYGRP_OWG
GROUP BY SBG.FAMILYGRP_OWG
	,SBG.COUNTRY_ID
	,SBG.DIVISION_ID
	,SBG.DESCR_AUDIENCE_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_FAMILYGRP_OWG;
