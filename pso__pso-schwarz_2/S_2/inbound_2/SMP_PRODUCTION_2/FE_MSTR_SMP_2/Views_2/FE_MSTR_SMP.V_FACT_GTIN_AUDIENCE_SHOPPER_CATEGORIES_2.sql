create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_GTIN_AUDIENCE_SHOPPER_CATEGORIES_2(
	GTIN_ID,
	COUNTRY_ID,
	DIVISION_ID,
	DESCR_AUDIENCE_ID,
	CNT_SHOPPER_GTIN,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_AUDIENCE AS (
			SELECT DISTINCT FCT.GTIN_ID
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_2 FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
					'GEN'
					,'AGE'
					,'VIE'
					,'ZIP'
					)
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_GTIN AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,GTIN_ID
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_GTIN
			FROM SHOPPERS_BY_AUDIENCE
			GROUP BY 1
				,2
				,3
			)

SELECT SBA.GTIN_ID
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_GTIN
	,COUNT(DISTINCT SBA.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_AUDIENCE SBA
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON SBA.COUNTRY_ID = DA.COUNTRY_ID
	AND SBA.DIVISION_ID = DA.DIVISION_ID
	AND SBA.SHOPPER_ID = DA.SHOPPER_ID
JOIN CNT_GTIN ON SBA.COUNTRY_ID = CNT_GTIN.COUNTRY_ID
	AND SBA.DIVISION_ID = CNT_GTIN.DIVISION_ID
	AND SBA.GTIN_ID = CNT_GTIN.GTIN_ID
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
		'GEN'
		,'AGE'
		,'VIE'
		,'ZIP'
		)
GROUP BY SBA.GTIN_ID
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_GTIN;
