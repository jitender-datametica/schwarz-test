create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_ITEMGRP_ABT_AUDIENCE_SHOPPER_CATEGORIES_2(
	ITEMGRP_ABT_ID,
	COUNTRY_ID,
	DIVISION_ID,
	DESCR_AUDIENCE_ID,
	CNT_SHOPPER_ITEMGRP_ABT,
	CNT_SHOPPER
) as
	WITH SHOPPERS_BY_AUDIENCE AS (
			SELECT DISTINCT a15.ITEMGRP_ABT
				,FCT.COUNTRY_ID
				,FCT.DIVISION_ID
				,FCT.SHOPPER_ID
				,DA.DESCR_AUDIENCE_ID
			FROM CORE_REL.T_SMP_ATTRIBUTED_SALES_2 FCT
			JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON FCT.COUNTRY_ID = DA.COUNTRY_ID
				AND FCT.DIVISION_ID = DA.DIVISION_ID
				AND FCT.SHOPPER_ID = DA.SHOPPER_ID
				AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
					'GEN'
					,'AGE'
					,'VIE'
					,'ZIP'
					)
			join	FE_MSTR_SMP.V_DIM_ITEM_2	a12
				on 	(FCT.COUNTRY_ID = a12.COUNTRY_ID and 
				FCT.DIVISION_ID = a12.DIVISION_ID and 
				FCT.GTIN_ID = a12.GTIN_ID)
			join	FE_MSTR_SMP.V_REL_WG_ITEMFAMILY_OWG_2	a13
				on 	(a12.COUNTRY_ID = a13.COUNTRY_ID and 
				a12.DIVISION_ID = a13.DIVISION_ID and 
				a12.TAXONOMY_ID = coalesce(a13.WG, a13.FAMILYGRP_OWG, a13.WG))
			join	FE_MSTR_SMP.V_REL_ITEMGRP_WG_FAMILYGROUP_OWG_2	a14
				on 	(a13.COUNTRY_ID = a14.COUNTRY_ID and 
				a13.DIVISION_ID = a14.DIVISION_ID and 
				a13.FAMILYGRP_OWG = a14.FAMILYGRP_OWG)
			join	FE_MSTR_SMP.V_REL_ITEMGRP_ABT_SUBITEMGRP_HWG_2	a15
				on 	(a14.COUNTRY_ID = a15.COUNTRY_ID and 
				a14.DIVISION_ID = a15.DIVISION_ID and 
				a14.SUBITEMGRP_HWG = a15.SUBITEMGRP_HWG)
			WHERE FCT.EVENT_TMSP BETWEEN CURRENT_DATE - 90
					AND CURRENT_DATE
			)
		,CNT_ITEMGRP_ABT AS (
			SELECT COUNTRY_ID
				,DIVISION_ID
				,ITEMGRP_ABT
				,COUNT(DISTINCT SHOPPER_ID) CNT_SHOPPER_ITEMGRP_ABT
			FROM SHOPPERS_BY_AUDIENCE
			GROUP BY 1
				,2
				,3
			)

SELECT SBA.ITEMGRP_ABT
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_ITEMGRP_ABT
	,COUNT(DISTINCT SBA.SHOPPER_ID) CNT_SHOPPER
FROM SHOPPERS_BY_AUDIENCE SBA
JOIN CORE_REL.T_MAP_SHOPPER_DESCR_AUDIENCE_2 DA ON SBA.COUNTRY_ID = DA.COUNTRY_ID
	AND SBA.DIVISION_ID = DA.DIVISION_ID
	AND SBA.SHOPPER_ID = DA.SHOPPER_ID
JOIN CNT_ITEMGRP_ABT ON SBA.COUNTRY_ID = CNT_ITEMGRP_ABT.COUNTRY_ID
	AND SBA.DIVISION_ID = CNT_ITEMGRP_ABT.DIVISION_ID
	AND SBA.ITEMGRP_ABT = CNT_ITEMGRP_ABT.ITEMGRP_ABT
	AND LEFT(DA.DESCR_AUDIENCE_ID, 3) NOT IN (
		'GEN'
		,'AGE'
		,'VIE'
		,'ZIP'
		)
GROUP BY SBA.ITEMGRP_ABT
	,SBA.COUNTRY_ID
	,SBA.DIVISION_ID
	,DA.DESCR_AUDIENCE_ID
	,CNT_SHOPPER_ITEMGRP_ABT;
