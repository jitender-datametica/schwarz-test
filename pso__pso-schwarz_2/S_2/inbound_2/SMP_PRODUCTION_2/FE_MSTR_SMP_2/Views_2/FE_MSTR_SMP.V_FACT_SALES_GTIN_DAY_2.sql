create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_FACT_SALES_GTIN_DAY_2(
	DIVISION_ID,
	COUNTRY_ID,
	DAY_DT,
	GTIN_ID,
	CAMPAIGN_ID,
	CAL_DT_TRANS,
	SALES_PIECE_QTY
) as
(SELECT
	FACT.DIVISION_ID
,FACT.COUNTRY_ID
,FACT.DAY_DT
,FACT.GTIN_ID
,CAL.CAMPAIGN_ID
,CAL.CAL_DT_TRANS
,sum(FACT.SALES_PIECE_QTY)
FROM
FE_MSTR_SMP.V_FACT_SALES_STORE_SUPPLIER_SHOPPER_GTIN_DAY_2 FACT
LEFT JOIN
FE_MSTR_SMP.V_CAL_TEST_CAMPAIGN_PERIOD_2 CAL
ON
FACT.DAY_DT = CAL.DAY_DT
AND 
FACT.DIVISION_ID = CAL.DIVISION_ID
AND 
FACT.COUNTRY_ID = CAL.COUNTRY_ID
WHERE FACT.DAY_DT BETWEEN CURRENT_DATE-50 and CURRENT_DATE
GROUP BY
FACT.DIVISION_ID
,FACT.COUNTRY_ID
,FACT.DAY_DT
,FACT.GTIN_ID
,CAL.CAMPAIGN_ID
,CAL.CAL_DT_TRANS
);
