create or replace view SMP_PRODUCTION.FE_MSTR_SMP.V_REL_ITEMGRP_WG_FAMILYGROUP_OWG_2(
	DIVISION_ID,
	COUNTRY_ID,
	SUBITEMGRP_HWG,
	FAMILYGRP_OWG
) as

SELECT T1.DIVISION_ID
	,T1.COUNTRY_ID
	,T1.TAXONOMY_ID SUBITEMGRP_HWG
	,T2.TAXONOMY_ID FAMILYGRP_OWG
FROM CORE_REL.T_TAXONOMY_HIERARCHY_2 T1_2
JOIN CORE_REL.T_TAXONOMY_HIERARCHY_2 T2 ON T1.COUNTRY_ID = T2.COUNTRY_ID
	AND T1.DIVISION_ID = T2.DIVISION_ID
	AND T1.TAXONOMY_ID = T2.TAXONOMY_PARENT_ID
WHERE T1.LEVEL = 2
	AND T2.LEVEL = 3;
