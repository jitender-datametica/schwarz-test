CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_FACT_DB_ORGANIZ_UNIT_PER_DAY_HIST_2
AS SELECT 
 FACT_T1.CAL_DT
,FACT_T1.CY_MONTH
,LOOKUP_T1.DATABASE_SID 
,LOOKUP_T1.STAGE_CD
,LOOKUP_T1.DB_DOMAIN_ID
,LOOKUP_T1.DB_DELIVERY_STATE_ID
,LOOKUP_T1.BACKUP_CLASS_ID
,LOOKUP_T1.DB_TYPE_ID
,LOOKUP_T1.LOB_CD
,FACT_T1.SOLUTION_SID
,FACT_T1.APPLICATION_SID
,FACT_T1.APPL_ORG_UNIT_ID
,FACT_T1.SOL_ORG_UNIT_ID
,SUM(DATABASE_CNT) AS DATABASE_CNT
FROM
 CORE.T_DIM_DATABASE AS LOOKUP_T1
JOIN
 CORE.T_FACT_DB_ORGANIZATIONAL_UNIT_PER_DAY AS FACT_T1
ON
 (LOOKUP_T1.DATABASE_SID = FACT_T1.DATABASE_SID)
 AND (FACT_T1.CAL_DT >= LOOKUP_T1.DWH_VALID_FROM_DT AND FACT_T1.CAL_DT < LOOKUP_T1.DWH_VALID_TO_DT)
GROUP BY 
 FACT_T1.CAL_DT
,FACT_T1.CY_MONTH
,LOOKUP_T1.DATABASE_SID 
,LOOKUP_T1.STAGE_CD
,LOOKUP_T1.DB_DOMAIN_ID
,LOOKUP_T1.DB_DELIVERY_STATE_ID
,LOOKUP_T1.BACKUP_CLASS_ID
,LOOKUP_T1.DB_TYPE_ID
,LOOKUP_T1.LOB_CD
,LOOKUP_T1.DATABASE_ID
,LOOKUP_T1.DATABASE_NAME
,FACT_T1.SOLUTION_SID
,FACT_T1.APPLICATION_SID
,FACT_T1.SOL_ORG_UNIT_ID
,FACT_T1.APPL_ORG_UNIT_ID
;