CREATE OR REPLACE VIEW FE_MSTR_INFRASTRUCTURE.V_L_SIT_INFRASTRUCTURE_FACT_VIRTUAL_DISK_PROVISION_2(
	VCENTER_SID
	,DATA_CENTER_SID
	,COMPUTE_RESOURCE_CLUSTER_SID
	,VM_SID
	,VIRTUAL_DISK_SID
	,CAL_DT
	,STAGE_CD
	,SITE_CD
	,LOB_CD
	,PROVISIONED_CAPACITY_MB_MEAS
	,TOTAL_DISK_CAPACITY_MB_MEAS
) AS SELECT
  FT1.VCENTER_SID
  ,FT1.DATA_CENTER_SID 
  ,FT1.COMPUTE_RESOURCE_CLUSTER_SID
  ,FT1.VM_SID
  ,FT1.VIRTUAL_DISK_SID
  ,FT1.CAL_DT
  ,LT1.STAGE_CD
  ,LT1.SITE_CD
  ,LT2.LOB_CD
  ,FT1.PROVISIONED_CAPACITY_MB_MEAS
  ,LT3.TOTAL_DISK_CAPACITY_MB_MEAS
FROM
  CORE.T_FACT_VIRTUAL_DISK_PROVISION FT1
  JOIN CORE.T_DIM_COMPUTE_RESOURCE_CLUSTER LT1
  ON FT1.COMPUTE_RESOURCE_CLUSTER_SID = LT1.COMPUTE_RESOURCE_CLUSTER_SID AND FT1.CAL_DT >= LT1.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT1.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_DATA_CENTER LT2
  ON FT1.DATA_CENTER_SID = LT2.DATA_CENTER_SID AND FT1.CAL_DT >= LT2.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT2.DWH_VALID_TO_DT
  JOIN CORE.T_DIM_VIRTUAL_DISK LT3
  ON FT1.VIRTUAL_DISK_SID = LT3.VIRTUAL_DISK_SID AND FT1.CAL_DT >= LT3.DWH_VALID_FROM_DT AND FT1.CAL_DT < LT3.DWH_VALID_TO_DT
;