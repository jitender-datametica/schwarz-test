CREATE OR REPLACE VIEW FE_MSTR_SERVICE_AND_SUPPORT.V_FACT_TICKET_STATUS_TRACKING_RESOLVING_PER_MONTH_TICKET_TYPE_2(
	TICKET_TYPE_ID
	, TICKET_TYPE_NAME
	, CY_MONTH
	, TICKET_CREATOR_COUNTRY_BUSINESS_CD
	, TICKET_CREATOR_COUNTRY_BUSINESS_NAME
	, TICKET_CREATOR_DIVISION_CD
	, TICKET_SOLVER_COUNTRY_BUSINESS_CD
	, TICKET_SOLVER_COUNTRY_BUSINESS_NAME
	, TICKET_SOLVER_DIVISION_CD
	, TICKET_RESOLVED_CNT
) AS
SELECT 
	TF1.TICKET_TYPE_ID
    , TF1.TICKET_TYPE_NAME
	, TF1.CY_MONTH
    , TD1.COUNTRY_BUSINESS_CD
    , TF1.TICKET_CREATOR_COUNTRY_BUSINESS_NAME
    , TD2.DIVISION_CD
    , TD3.COUNTRY_BUSINESS_CD
    , TF1.TICKET_SOLVER_COUNTRY_BUSINESS_NAME
    , TD4.DIVISION_CD
    , TF1.TICKET_RESOLVED_CNT
FROM CORE.T_FACT_TICKET_STATUS_TRACKING_RESOLVING_PER_MONTH_TICKET_TYPE_2 TF1
JOIN CORE.T_DIM_COUNTRY_BUSINESS_2 TD1
ON TF1.TICKET_CREATOR_COUNTRY_BUSINESS_LOCATION_SID=TD1.LOCATION_SID AND TD1.DWH_VALID_TO_TMSP >= '9999-12-31'
JOIN CORE.T_DIM_COUNTRY_BUSINESS_2 TD3
ON TF1.TICKET_SOLVER_COUNTRY_BUSINESS_LOCATION_SID=TD3.LOCATION_SID AND TD3.DWH_VALID_TO_TMSP >= '9999-12-31'
JOIN CORE.T_DIM_DIVISION_2 TD2
ON TF1.TICKET_CREATOR_DIVISION_PARTY_SID=TD2.PARTY_SID AND TD2.DWH_VALID_TO_TMSP >= '9999-12-31'
JOIN CORE.T_DIM_DIVISION_2 TD4
ON TF1.TICKET_SOLVER_DIVISION_PARTY_SID=TD4.PARTY_SID AND TD4.DWH_VALID_TO_TMSP >= '9999-12-31'
;