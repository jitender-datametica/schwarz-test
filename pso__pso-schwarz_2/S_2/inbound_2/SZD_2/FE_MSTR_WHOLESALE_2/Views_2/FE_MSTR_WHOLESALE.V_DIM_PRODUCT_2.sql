CREATE OR REPLACE VIEW FE_MSTR_WHOLESALE.V_DIM_PRODUCT_2(
    PROD_SID
    ,DWH_VALID_FROM_TMSP
    ,DWH_VALID_TO_TMSP
    ,DWH_VALID_FG
    ,IAN_NR
    ,PROD_NAME
    ,PRODUCT_NAME_TXT
    ,PROD_DIVISION_TYPE_CD
    ,INCOTERM_NAME
    ,PRODUCT_STATUS_CD
) AS 
    SELECT
        PRODUCT_SID AS PROD_SID
        ,DWH_VALID_FROM_TMSP
        ,DWH_VALID_TO_TMSP
        ,DWH_VALID_FG
        ,IAN_NR
        ,PRODUCT_NAME AS PROD_NAME
        ,PRODUCT_NAME_TXT
        ,PRODUCT_DIVISION_TYPE_CD AS PROD_DIVISION_TYPE_CD
        ,INCOTERM_NAME
        ,PRODUCT_STATUS_CD
    FROM 
        CORE.T_DIM_PRODUCT_2
    WHERE
        DWH_VALID_FG = 1
;