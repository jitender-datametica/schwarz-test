CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_FACT_CONTAINER_MILESTONE_DATES_2 (
	CONTAINER_RESOURCE_SID
	,PICKUP_POD_DT
	,PICKUP_POD_RESULT_NAME
	,PICKUP_POD_FG
	,ARRIVAL_DOMESTIC_TERMINAL_DT
	,ARRIVAL_DOMESTIC_TERMINAL_RESULT_NAME
	,ARRIVAL_DOMESTIC_TERMINAL_FG
	,GAS_MSMT_DT
	,GAS_MSMT_RESULT_NAME
	,GAS_MSMT_RESULT_EVAL_TXT
	,GAS_MSMT_RESULT_FG
	,DEST_CUSTOMS_CLEARANCE_DT
	,DEST_CUSTOMS_CLEARANCE_RESULT_NAME
	,DEST_CUSTOMS_CLEARANCE_FG
	,GOODS_IN_WH_DT
	,GOODS_IN_WH_YEAR
	,GOODS_IN_WH_MONTH
	,GOODS_IN_WH_WEEK
	,GOODS_IN_WAREHOUSE_YEAR_WEEK
	,GOODS_IN_WH_RESULT_NAME
	,GOODS_IN_WH_RESULT_FG
	,RETURN_DEPOT_DT
	,RETURN_DEPOT_RESULT_NAME
	,RETURN_DEPOT_FG
	) AS

SELECT DISTINCT CONTAINER_RESOURCE_ITEM_SID AS CONTAINER_RESOURCE_SID
	,CONTAINER_LPOD_PICKUP_DT AS PICKUP_POD_DT
	,CONTAINER_LPOD_PICKUP_RESULT_CD AS PICKUP_POD_RESULT_NAME
	,CONTAINER_LPOD_PICKUP_FG PICKUP_POD_FG
	,CONTAINER_DOMESTIC_TERMINAL_ARRIVAL_DT AS ARRIVAL_DOMESTIC_TERMINAL_DT
	,CONTAINER_DOMESTIC_TERMINAL_ARRIVAL_RESULT_CD AS ARRIVAL_DOMESTIC_TERMINAL_RESULT_NAME
	,CONTAINER_DOMESTIC_TERMINAL_ARRIVAL_FG AS ARRIVAL_DOMESTIC_TERMINAL_FG
	,CONTAINER_GAS_MEASUREMENT_DT AS GAS_MSMT_DT
	,CONTAINER_GAS_MEASUREMENT_RESULT_CD AS GAS_MSMT_RESULT_NAME
	,CONTAINER_GAS_MEASUREMENT_RESULT_EVALUATION_TXT GAS_MSMT_RESULT_EVAL_TXT
	,CONTAINER_GAS_MEASUREMENT_FG GAS_MSMT_RESULT_FG
	,CONTAINER_DESTINATION_CUSTOMS_CLEARANCE_DT AS DEST_CUSTOMS_CLEARANCE_DT
	,CONTAINER_DESTINATION_CUSTOMS_CLEARANCE_RESULT_CD AS DEST_CUSTOMS_CLEARANCE_RESULT_NAME
	,CONTAINER_DESTINATION_CUSTOMS_CLEARANCE_FG AS DEST_CUSTOMS_CLEARANCE_FG
	,CONTAINER_GOODS_IN_WAREHOUSE_DT AS GOODS_IN_WH_DT
	,YEAR(CONTAINER_GOODS_IN_WAREHOUSE_DT) AS GOODS_IN_WH_YEAR
	,MONTH(CONTAINER_GOODS_IN_WAREHOUSE_DT) AS GOODS_IN_WH_MONTH
	,LPAD(WEEK(CONTAINER_GOODS_IN_WAREHOUSE_DT), 2, '0') AS GOODS_IN_WH_WEEK
	,YEAR(CONTAINER_GOODS_IN_WAREHOUSE_DT) || LPAD(WEEK(CONTAINER_GOODS_IN_WAREHOUSE_DT), 2, '0') AS GOODS_IN_WAREHOUSE_YEAR_WEEK
	,CONTAINER_GOODS_IN_WAREHOUSE_RESULT_CD AS GOODS_IN_WH_RESULT_NAME
	,CONTAINER_GOODS_IN_WAREHOUSE_FG AS GOODS_IN_WH_RESULT_FG
	,CONTAINER_RETURN_DEPOT_RESULT_DT AS RETURN_DEPOT_DT
	,CONTAINER_RETURN_DEPOT_RESULT_CD AS RETURN_DEPOT_RESULT_NAME
	,CONTAINER_RETURN_DEPOT_FG AS RETURN_DEPOT_FG
FROM CORE.T_FACT_LOT_CONTAINER_MILESTONE_PROGRESS_2;