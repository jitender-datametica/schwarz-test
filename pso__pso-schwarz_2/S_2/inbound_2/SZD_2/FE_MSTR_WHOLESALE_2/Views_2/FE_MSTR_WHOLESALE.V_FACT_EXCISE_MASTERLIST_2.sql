CREATE
	OR REPLACE VIEW FE_MSTR_WHOLESALE.V_FACT_EXCISE_MASTERLIST_2 (
	ROWNUM
	,ITEM_NO_SHORT
	,SINGLE_ARTICLE_NO
	,DWH_VALID_FROM
	,DWH_VALID_TO
	,DWH_VALID_FG
	,ITEM_SHORTDESC
	,WG
