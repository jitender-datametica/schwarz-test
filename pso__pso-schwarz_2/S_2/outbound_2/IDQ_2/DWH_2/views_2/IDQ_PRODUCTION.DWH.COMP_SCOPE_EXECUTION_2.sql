CREATE OR REPLACE VIEW idq_production_dwh.comp_scope_execution_2 (comp_scope_execution_id,
comp_scope_execution_execution_date, ref_time_execution_day_id, ref_comp_definition_scope_id, ref_comp_definition_id,
leading_comp_scope_id, dependent_comp_scope_id, leading_ref_source_system_type_id, leading_ref_source_system_id,
leading_ref_country_id, leading_ref_branch_id, leading_ref_test_object_type_id, dependent_ref_source_system_type_id,
dependent_ref_source_system_id, dependent_ref_country_id, dependent_ref_branch_id, dependent_ref_test_object_type_id,
leading_amount, dependent_amount, match_amount, missing_amount, overflow_amount, ambiguous_amount, incomplete_amount,
comp_scope_execution_is_current) AS SELECT CSE.id AS comp_scope_execution_id,
 CSE.execution_date AS comp_scope_execution_execution_date,
 CSE.execution_day_id AS ref_time_execution_day_id,
 CSE.comp_definition_scope_id AS ref_comp_definition_scope_id,
 RCDS.comp_definition_id AS ref_comp_definition_id,
 RCDS.leading_comp_scope_id,
 RCDS.dependent_comp_scope_id,
 RSL.source_system_type_id AS leading_ref_source_system_type_id,
 RSL.source_system_id AS leading_ref_source_system_id,
 RSL.country_id AS leading_ref_country_id,
 RSL.branch_id AS leading_ref_branch_id,
 RSL.test_object_type_id AS leading_ref_test_object_type_id,
 RSD.source_system_type_id AS dependent_ref_source_system_type_id,
 RSD.source_system_id AS dependent_ref_source_system_id,
 RSD.country_id AS dependent_ref_country_id,
 RSD.branch_id AS dependent_ref_branch_id,
 RSD.test_object_type_id AS dependent_ref_test_object_type_id,
 CSE.leading_amount,
 CSE.dependent_amount,
 CSE.match_amount,
 CSE.missing_amount,
 CSE.overflow_amount,
 CSE.ambiguous_amount,
 CSE.incomplete_amount,
 1 AS comp_scope_execution_is_current
FROM idq_production_syscomp.comp_scope_execution_current_2 AS CSE
 INNER JOIN idq_production_idq_results.ref_comp_definition_scope_2 AS RCDS ON CSE.comp_definition_scope_id = RCDS.id
 INNER JOIN idq_production_idq_results.ref_comp_scope_2 AS RSL ON RCDS.leading_comp_scope_id = RSL.id
 INNER JOIN idq_production_idq_results.ref_comp_scope_2 AS RSD ON RCDS.dependent_comp_scope_id = RSD.id
UNION DISTINCT
SELECT CSE.id AS comp_scope_execution_id,
 CSE.execution_date AS comp_scope_execution_execution_date,
 CSE.execution_day_id AS ref_time_execution_day_id,
 CSE.comp_definition_scope_id AS ref_comp_definition_scope_id,
 RCDS.comp_definition_id AS ref_comp_definition_id,
 RCDS.leading_comp_scope_id,
 RCDS.dependent_comp_scope_id,
 RSL.source_system_type_id AS leading_ref_source_system_type_id,
 RSL.source_system_id AS leading_ref_source_system_id,
 RSL.country_id AS leading_ref_country_id,
 RSL.branch_id AS leading_ref_branch_id,
 RSL.test_object_type_id AS leading_ref_test_object_type_id,
 RSD.source_system_type_id AS dependent_ref_source_system_type_id,
 RSD.source_system_id AS dependent_ref_source_system_id,
 RSD.country_id AS dependent_ref_country_id,
 RSD.branch_id AS dependent_ref_branch_id,
 RSD.test_object_type_id AS dependent_ref_test_object_type_id,
 CSE.leading_amount,
 CSE.dependent_amount,
 CSE.match_amount,
 CSE.missing_amount,
 CSE.overflow_amount,
 CSE.ambiguous_amount,
 CSE.incomplete_amount,
 0 AS comp_scope_execution_is_current
FROM idq_production_syscomp.comp_scope_execution_historical_2 AS CSE
 INNER JOIN idq_production_idq_results.ref_comp_definition_scope_2 AS RCDS ON CSE.comp_definition_scope_id = RCDS.id
 INNER JOIN idq_production_idq_results.ref_comp_scope_2 AS RSL ON RCDS.leading_comp_scope_id = RSL.id
 INNER JOIN idq_production_idq_results.ref_comp_scope_2 AS RSD ON RCDS.dependent_comp_scope_id = RSD.id;