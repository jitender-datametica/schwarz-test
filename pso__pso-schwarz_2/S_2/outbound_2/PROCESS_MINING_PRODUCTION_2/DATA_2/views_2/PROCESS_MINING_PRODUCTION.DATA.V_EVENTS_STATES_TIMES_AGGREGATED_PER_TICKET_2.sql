CREATE OR REPLACE VIEW process_mining_production_data.v_events_states_times_aggregated_per_ticket_2 (u_task_number,
u_task_sys_class_name, z_solved_at, z_close_code, u_task_u_region_u_code, u_assignment_group_name, time_new, time_open,
time_work_in_progress, time_waiting_for_enduser, time_waiting_for_external, time_waiting_for_problem, time_total) AS
SELECT v_tickets_last2years.u_task_number,
 v_tickets_last2years.u_task_sys_class_name,
 v_tickets_last2years.z_solved_at,
 v_tickets_last2years.z_close_code,
 v_tickets_last2years.u_task_u_region_u_code,
 v_events_states_times_aggregated_per_ticket_helper.u_assignment_group_name,
 v_events_states_times_aggregated_per_ticket_helper.time_new,
 v_events_states_times_aggregated_per_ticket_helper.time_open,
 v_events_states_times_aggregated_per_ticket_helper.time_work_in_progress,
 v_events_states_times_aggregated_per_ticket_helper.time_waiting_for_enduser,
 v_events_states_times_aggregated_per_ticket_helper.time_waiting_for_external,
 v_events_states_times_aggregated_per_ticket_helper.time_waiting_for_problem,
 v_events_states_times_aggregated_per_ticket_helper.time_total
FROM process_mining_production_data.v_events_states_times_aggregated_per_ticket_helper_2
 LEFT JOIN process_mining_production_data.v_tickets_last2years_2 ON v_events_states_times_aggregated_per_ticket_helper.u_task_number
   = v_tickets_last2years.u_task_number
WHERE v_tickets_last2years.u_task_sys_class_name <> 'problem';
