CREATE OR REPLACE FUNCTION snowconvert_public.timestamp_add_udf(A TIMESTAMP, B TIMESTAMP, OP STRING) RETURNS TIMESTAMP
AS (
CASE
    WHEN OP = '+' THEN
      TIMESTAMP(DATETIME_ADD(DATETIME(A),INTERVAL EXTRACT(YEAR FROM B) YEAR)+ INTERVAL EXTRACT(MONTH FROM B) MONTH+ INTERVAL EXTRACT(DAY FROM B) DAY+ INTERVAL EXTRACT(HOUR FROM B) HOUR+ INTERVAL EXTRACT(MINUTE FROM B) MINUTE+ INTERVAL EXTRACT(SECOND FROM B) SECOND)
    ELSE
      TIMESTAMP(DATETIME_SUB(DATETIME(A),INTERVAL EXTRACT(YEAR FROM B) YEAR) - INTERVAL EXTRACT(MONTH FROM B) MONTH - INTERVAL EXTRACT(DAY FROM B) DAY - INTERVAL EXTRACT(HOUR FROM B) HOUR - INTERVAL EXTRACT(MINUTE FROM B) MINUTE - INTERVAL EXTRACT(SECOND FROM B) SECOND)
  END
);