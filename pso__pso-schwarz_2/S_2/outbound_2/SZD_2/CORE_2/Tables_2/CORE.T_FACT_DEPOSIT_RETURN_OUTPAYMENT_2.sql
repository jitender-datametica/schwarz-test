CREATE TABLE IF NOT EXISTS szd_core.t_fact_deposit_return_outpayment_2 (
rvm_sid BIGNUMERIC(38,0) NOT NULL
OPTIONS(description='The unique identifier (surrogate key) for the despotie machine which is located in a store'),
cal_dt DATE NOT NULL
OPTIONS(description='The day represented as a calendar_2 date of the form YYYY-MM_2-DD. YYYY is the calendar_2 year, MM_2 (between 1 and 12) the calendar_2 month and DD the day of the calendar_2 month (between 1 and 31). '),
deposit_item_sub_cat_id BIGNUMERIC(38,0) NOT NULL OPTIONS(description='The id for the item_2 return type'),
deposit_outpayment_type_cd STRING(50) NOT NULL
OPTIONS(description='The code for the way how the deposit amount can be paid back to the customer. (outpayment / donation / QR code / ...'),
receipt_cnt BIGNUMERIC(38,0) NOT NULL
OPTIONS(description='The Distinct number of customers who deposited at least one item_2 of the deposit item_2 class ( this measure is not additive)'),
receipt_gross_local_val BIGNUMERIC(38,5) NOT NULL
OPTIONS(description='The total gross amount in local currency of deposits generated by a deposit machine on this day.'),
receipt_gross_global_val BIGNUMERIC(38,5) NOT NULL
OPTIONS(description='The total gross amount in global currency of deposits generated by a deposit machine on this day.'),
global_curr_cd STRING(3) NOT NULL OPTIONS(description='The global currency code-now it is set as EUR'),
local_curr_cd STRING(3) NOT NULL OPTIONS(description='The local currency code'),
dwh_created_tmsp TIMESTAMP NOT NULL
OPTIONS(description='The point in time when this record was inserted into the table.'),
dwh_updated_tmsp TIMESTAMP NOT NULL
OPTIONS(description='The point in time when this record was last modified. (In case the record has not been modified since its creation, dwh_updated is identical to dwh_created.)'),
PRIMARY KEY (cal_dt, rvm_sid, deposit_item_sub_cat_id, deposit_outpayment_type_cd) NOT ENFORCED
) OPTIONS(description='Mixed (aggregated and transactional) facts capturing the count and sum of receipts');