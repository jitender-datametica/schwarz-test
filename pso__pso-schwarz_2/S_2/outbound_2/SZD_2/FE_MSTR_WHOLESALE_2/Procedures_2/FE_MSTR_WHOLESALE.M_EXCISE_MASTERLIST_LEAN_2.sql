CREATE OR REPLACE PROCEDURE fe_mstr_wholesale.m_excise_masterlist_lean(ITEM_NO_SHORT INT64, SINGLE_ARTICLE_NO INT64, DWH_VALID_TO_TMSP1 DATE, DWH_VALID_FROM_TMSP DATE, ITEM_SHORTDESC STRING, VOLUME__IN_L_ BIGNUMERIC, ABV_ BIGNUMERIC, ADJUSTED_ABV__WINE_ONLY_ BIGNUMERIC, TAX_CODE_ STRING, DUTY_PER_LPA BIGNUMERIC, DUTY_PER_UNIT FLOAT64)
  BEGIN
    DECLARE V_PREVIOUS_DWH_VALID_FROM DATE ;
    SET V_PREVIOUS_DWH_VALID_FROM = (
      SELECT
          max(CAST(DWH_VALID_FROM_TMSP AS DATE))
        FROM
          fe_mstr_wholesale.t_cache_excise_masterlist_2
        WHERE ITEM_NO_SHORT = ITEM_NO_SHORT
         AND DWH_VALID_TO_TMSP = DWH_VALID_TO_TMSP1
         AND SINGLE_ARTICLE_NO = SINGLE_ARTICLE_NO1
    );
    UPDATE fe_mstr_wholesale.t_cache_excise_masterlist_2 SET VOLUME__IN_L_ = VOLUME__IN_L_, ABV_ = ABV_, ADJUSTED_ABV__WINE_ONLY_ = ADJUSTED_ABV__WINE_ONLY_, TAX_CODE_ = TAX_CODE_, DUTY_PER_LPA = DUTY_PER_LPA, DUTY_PER_UNIT = DUTY_PER_UNIT, DWH_VALID_FROM_TMSP = DWH_VALID_FROM_TMSP, PREVIOUS_DWH_VALID_FROM = V_PREVIOUS_DWH_VALID_FROM, UPDATED_AT = CAST(current_timestamp() AS DATETIME) WHERE ITEM_NO_SHORT = ITEM_NO_SHORT
     AND DWH_VALID_TO_TMSP = DWH_VALID_TO_TMSP1
     AND SINGLE_ARTICLE_NO = SINGLE_ARTICLE_NO1;
  END;
